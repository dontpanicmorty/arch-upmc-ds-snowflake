CREATE VIEW logdata.ADF_TPA_SHARED_PIPELINE_LOGGING_VW AS
SELECT
METADATA$FILENAME AS FILENAME,
$1 AS DATAFACTORY_NAME,
$2 AS PIPELINE_NAME,
$3 AS RUN_ID,
$4 AS TRIGGER_TYPE,
$5 AS TRIGGER_ID,
$6 AS TRIGGER_NAME,
$7 AS TRIGGER_TIME,
$8 AS TARGET_LOCATION,
$9 AS DATA_COPIED,
$10 AS DATA_READ,
$11 AS ERRORS,
$12 AS EFFECTIVE_INTEGRATION_RUNTIME,
$13 AS SOURCE_TYPE,
$14 AS SINK_TYPE,
$15 AS EXECUTION_STATUS,
$16 AS COPY_ACTIVITY_START_TIME,
$17 AS COPY_ACTIVITY_END_TIME,
$18 AS COPY_ACTIVITY_QUEUING_DURATION_SECONDS,
$19 AS COPY_ACTIVITY_TRANSFER_DURATION_SECONDS
FROM @UTIL.TPADATALAKE_TPASHARED/logdata/adf/
(file_format => 'logdata.ADF_LOGGING_FILE_FORMAT')
WHERE SPLIT_PART(FILENAME, '/', 4) >= TO_CHAR(CURRENT_DATE() -7, 'YYYYMMDD')

!set variable_substitution=false;