CREATE OR REPLACE VIEW LOGDATA.ADF_DB_EXTRACT_IDW_LAKE_PIPELINE_LOGGING_VW (
    FILENAME,
    DATAFACTORY_NAME,
    PIPELINE_NAME,
    RUN_ID,
    TRIGGER_TYPE,
    TRIGGER_ID,
    TRIGGER_NAME,
    TRIGGER_TIME,
    TARGET_LOCATION,
    DATA_COPIED,
    DATA_READ,
    NO_PARALLEL_COPIES,
    COPY_DURATION_SECONDS,
    EFFECTIVE_INTEGRATION_RUNTIME,
    SOURCE_TYPE,
    SINK_TYPE,
    EXECUTION_STATUS,
    COPY_ACTIVITY_START_TIME,
    COPY_ACTIVITY_END_TIME,
    COPY_ACTIVITY_QUEUING_DURATION_SECONDS,
    COPY_ACTIVITY_TIME_TO_FIRST_BYTE_SECONDS,
    COPY_ACTIVITY_TRANSFER_DURATION_SECONDS,
    ADF_COPY_CONTROL_KEY,
    SOURCE_SCHEMA_NAME,
    SOURCE_TABLE_NAME,
    SOURCE_ROW_COUNT,
    SOURCE_WATERMARK,
    TARGET_SCHEMA_NAME,
    TARGET_TABLE_NAME,
    TARGET_ROW_COUNT,
    TARGET_WATERMARK
) AS (
SELECT
METADATA$FILENAME AS FILENAME,
$1 AS DATAFACTORY_NAME,
$2 AS PIPELINE_NAME,
$3 AS RUN_ID,
$4 AS TRIGGER_TYPE,
$5 AS TRIGGER_ID,
$6 AS TRIGGER_NAME,
$7 AS TRIGGER_TIME,
$8 AS TARGET_LOCATION,
$9 AS ROWS_COPIED,
$10 AS ROWS_READ,
$11 AS NO_PARALLEL_COPIES,
$12 AS COPY_DURATION_SECONDS,
$13 AS EFFECTIVE_INTEGRATION_RUNTIME,
$14 AS SOURCE_TYPE,
$15 AS SINK_TYPE,
$16 AS EXECUTION_STATUS,
$17 AS COPY_ACTIVITY_START_TIME,
$18 AS COPY_ACTIVITY_END_TIME,
$19 AS COPY_ACTIVITY_QUEUING_DURATION_SECONDS,
$20 AS COPY_ACTIVITY_TIME_TO_FIRST_BYTE_SECONDS,
$21 AS COPY_ACTIVITY_TRANSFER_DURATION_SECONDS,
$22 AS ADF_COPY_CONTROL_KEY,
$23 AS SOURCE_SCHEMA_NAME,
$24 AS SOURCE_TABLE_NAME,
$25 AS SOURCE_ROW_COUNT,
$26 AS SOURCE_WATERMARK,
$27 AS TARGET_SCHEMA_NAME,
$28 AS TARGET_TABLE_NAME,
$29 AS TARGET_ROW_COUNT,
$30 AS TARGET_WATERMARK
FROM @UTIL.HPDSDATALAKE_DBEXTRACT_IDW_LAKE/logdata/adf/idw/
(file_format => 'LOGDATA.IDW_LAKE_ADF_LOGGING_FILE_FORMAT')
WHERE SPLIT_PART(FILENAME, '/', 4) >= TO_CHAR(CURRENT_DATE() -35, 'YYYYMMDD')
)
;
!set variable_substitution=false;