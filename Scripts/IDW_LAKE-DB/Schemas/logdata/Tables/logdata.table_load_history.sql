create or replace TABLE LOGDATA.TABLE_LOAD_HISTORY (
	TABLE_LOAD_HISTORY_KEY NUMBER(38,0) NOT NULL autoincrement start 1 increment 1 order,
	NAME VARCHAR NOT NULL,
	TYPE VARCHAR NOT NULL,
	START_TIME TIMESTAMP_NTZ(9) NOT NULL,
	END_TIME TIMESTAMP_NTZ(9),
	INSERT_COUNT NUMBER(38,0),
	UPDATE_COUNT NUMBER(38,0),
	DELETE_COUNT NUMBER(38,0),
	RESULT_TEXT VARCHAR,
	SQL_STATEMENT VARCHAR NOT NULL,
	ERROR_CODE VARCHAR,
	ERROR_STATE VARCHAR,
	ERROR_MESSAGE VARCHAR,
	ERROR_STACK_TRACE_TEXT VARCHAR,
	constraint UK_TABLE_LOAD_HISTORY unique (NAME, TYPE, START_TIME),
	constraint PK_TABLE_LOAD_HISTORY primary key (TABLE_LOAD_HISTORY_KEY)
);