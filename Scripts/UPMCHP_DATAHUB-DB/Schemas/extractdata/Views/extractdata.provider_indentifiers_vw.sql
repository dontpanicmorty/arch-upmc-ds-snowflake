CREATE OR REPLACE VIEW EXTRACTDATA.PROVIDER_IDENTIFIERS_VW
AS
--This will probably need reworked as we add more identifiers
SELECT
HUB_PROVIDER.HUB_PROVIDER_HKEY AS HKEY
,HUB_PROVIDER.TPA_CLIENT_ID
,HUB_PROVIDER.TPA_ID
,HUB_PROVIDER.TPA_DIV_ID
,HUB_PROVIDER.DATA_SOURCE_NAME
,HUB_PROVIDER.PROVIDER_ID
,SAT_PROVIDER_DETAIL.PROVIDER_TYPE_NAME
,SAT_PROVIDER_DETAIL.NATIONAL_PROVIDER_ID
FROM HUBDATA.HUB_PROVIDER
    JOIN HUBDATA.EFF_SAT_PROVIDER
        ON(EFF_SAT_PROVIDER.HUB_PROVIDER_HKEY = HUB_PROVIDER.HUB_PROVIDER_HKEY
        AND EFF_SAT_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_PROVIDER.DELETED_DATETIME > CURRENT_TIMESTAMP())
    JOIN HUBDATA.SAT_PROVIDER_DETAIL
        ON (SAT_PROVIDER_DETAIL.HUB_PROVIDER_HKEY = HUB_PROVIDER.HUB_PROVIDER_HKEY
        AND SAT_PROVIDER_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
WHERE SAT_PROVIDER_DETAIL.NATIONAL_PROVIDER_ID IS NOT NULL
AND HUB_PROVIDER.DATA_SOURCE_NAME NOT IN ('ESI', 'Cactus') --exclude pharmacy and Cactus records

UNION ALL

SELECT
HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY AS HKEY
,HUB_MEDICAL_GROUP.TPA_CLIENT_ID
,HUB_MEDICAL_GROUP.TPA_ID
,HUB_MEDICAL_GROUP.TPA_DIV_ID
,HUB_MEDICAL_GROUP.DATA_SOURCE_NAME
,HUB_MEDICAL_GROUP.MEDICAL_GROUP_ID AS PROVIDER_ID
,'Medical Group' AS PROVIDER_TYPE_NAME
,SAT_MEDICAL_GROUP_DETAIL.NPI_NBR AS NATIONAL_PROVIDER_ID
FROM HUBDATA.HUB_MEDICAL_GROUP
    JOIN HUBDATA.EFF_SAT_MEDICAL_GROUP
        ON(EFF_SAT_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY = HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY
        AND EFF_SAT_MEDICAL_GROUP.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_MEDICAL_GROUP.DELETED_DATETIME > CURRENT_TIMESTAMP())
    JOIN HUBDATA.SAT_MEDICAL_GROUP_DETAIL
        ON (SAT_MEDICAL_GROUP_DETAIL.HUB_MEDICAL_GROUP_HKEY = HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY
        AND SAT_MEDICAL_GROUP_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
WHERE SAT_MEDICAL_GROUP_DETAIL.NPI_NBR IS NOT NULL
AND HUB_MEDICAL_GROUP.DATA_SOURCE_NAME NOT IN ('ESI', 'Cactus')  --exclude pharmacy and Cactus records
;