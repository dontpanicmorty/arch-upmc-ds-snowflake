CREATE OR REPLACE VIEW EXTRACTDATA.CLAIM_AUTHORIZATION_DETAIL_BASE_VW
COMMENT = 'LEFT OUTER JOINs core tables from hubdata data vault model for common authorization consumption'
AS
SELECT HUB_CLAIM_AUTHORIZATION_DETAIL.HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY,
HUB_CLAIM_AUTHORIZATION.TPA_CLIENT_ID,
HUB_CLAIM_AUTHORIZATION.TPA_ID,
HUB_CLAIM_AUTHORIZATION.TPA_DIV_ID,
HUB_CLAIM_AUTHORIZATION.HUB_CLAIM_AUTHORIZATION_HKEY,
HUB_CLAIM_AUTHORIZATION_DETAIL.DATA_SOURCE_NAME,
HUB_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR,
HUB_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_LINE_NBR,
RENDERING_PROVIDER.PROVIDER_ID AS RENDERING_PROVIDER_ID,
SAT_CLAIM_AUTHORIZATION_DETAIL.PROCEDURE_CODE,
REF_CLAIM_PROCEDURE.CODE_DESC AS PROCEDURE_CODE_DESC,
SAT_CLAIM_AUTHORIZATION_DETAIL.DETERMINATION_STATUS_DESC AS AUTHORIZATION_LINE_DETERMINATION_STATUS_DESC,
SAT_CLAIM_AUTHORIZATION_DETAIL.DETERMINATION_DATE AS AUTHORIZATION_LINE_DETERMINATION_DATE,
SAT_CLAIM_AUTHORIZATION_DETAIL.SERVICE_BEGIN_DATE,
SAT_CLAIM_AUTHORIZATION_DETAIL.SERVICE_END_DATE,
SAT_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZED_QTY,
SAT_CLAIM_AUTHORIZATION_DETAIL.CONSUMED_QTY,
SAT_CLAIM_AUTHORIZATION_DETAIL.DENIED_QTY,
SAT_CLAIM_AUTHORIZATION_DETAIL.REQUESTED_QTY,
SAT_CLAIM_AUTHORIZATION_DETAIL_AMOUNT.ALLOWED_AMT,
SAT_CLAIM_AUTHORIZATION_DETAIL_AMOUNT.AUTHORIZED_AMT,
SAT_CLAIM_AUTHORIZATION_DETAIL_AMOUNT.AUTHORIZED_PER_UNIT_AMT,
SAT_CLAIM_AUTHORIZATION_DETAIL_AMOUNT.BALANCE_DUE_AMT,
SAT_CLAIM_AUTHORIZATION_DETAIL_AMOUNT.BILLED_AMT,
SAT_CLAIM_AUTHORIZATION_DETAIL_AMOUNT.COINSURANCE_AMT,
SAT_CLAIM_AUTHORIZATION_DETAIL_AMOUNT.COPAY_AMT,
SAT_CLAIM_AUTHORIZATION_DETAIL_AMOUNT.DEDUCTIBLE_APPLIED_AMT,
SAT_CLAIM_AUTHORIZATION_DETAIL_AMOUNT.PAID_AMT,
SAT_CLAIM_AUTHORIZATION_DETAIL_AMOUNT.PATIENT_PAY_APPLIED_AMT,
SAT_CLAIM_AUTHORIZATION_DETAIL_AMOUNT.PAYABLE_AMT,
SAT_CLAIM_AUTHORIZATION_DETAIL_AMOUNT.USUAL_AND_CUSTOMARY_AMT,
SAT_CLAIM_AUTHORIZATION_DETAIL.TOOTH_ID,
SAT_CLAIM_AUTHORIZATION_DETAIL.TOOTH_ARCH,
SAT_CLAIM_AUTHORIZATION_DETAIL.TOOTH_QUADRANT
FROM HUBDATA.HUB_CLAIM_AUTHORIZATION_DETAIL

    JOIN HUBDATA.EFF_SAT_CLAIM_AUTHORIZATION_DETAIL
        ON(EFF_SAT_CLAIM_AUTHORIZATION_DETAIL.HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY = HUB_CLAIM_AUTHORIZATION_DETAIL.HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY
        AND EFF_SAT_CLAIM_AUTHORIZATION_DETAIL.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_CLAIM_AUTHORIZATION_DETAIL.DELETED_DATETIME > CURRENT_TIMESTAMP())    

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_AUTHORIZATION_DETAIL
                    JOIN HUBDATA.EFF_SAT_CLAIM_AUTHORIZATION
                        ON(EFF_SAT_CLAIM_AUTHORIZATION.HUB_CLAIM_AUTHORIZATION_HKEY = LNK_CLAIM_AUTHORIZATION_DETAIL.HUB_CLAIM_AUTHORIZATION_HKEY
                        AND EFF_SAT_CLAIM_AUTHORIZATION.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_CLAIM_AUTHORIZATION.DELETED_DATETIME > CURRENT_TIMESTAMP())
                    )
        ON (LNK_CLAIM_AUTHORIZATION_DETAIL.HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY = HUB_CLAIM_AUTHORIZATION_DETAIL.HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY
        AND LNK_CLAIM_AUTHORIZATION_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
        
    JOIN HUBDATA.HUB_CLAIM_AUTHORIZATION
        ON (HUB_CLAIM_AUTHORIZATION.HUB_CLAIM_AUTHORIZATION_HKEY = LNK_CLAIM_AUTHORIZATION_DETAIL.HUB_CLAIM_AUTHORIZATION_HKEY
        AND LNK_CLAIM_AUTHORIZATION_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_AUTHORIZATION_DETAIL_RENDERING_PROVIDER
                    JOIN HUBDATA.EFF_SAT_PROVIDER
                        ON(EFF_SAT_PROVIDER.HUB_PROVIDER_HKEY = LNK_CLAIM_AUTHORIZATION_DETAIL_RENDERING_PROVIDER.HUB_PROVIDER_HKEY
                        AND EFF_SAT_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_PROVIDER.DELETED_DATETIME > CURRENT_TIMESTAMP())
                    )
        ON (LNK_CLAIM_AUTHORIZATION_DETAIL_RENDERING_PROVIDER.HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY = HUB_CLAIM_AUTHORIZATION_DETAIL.HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY
        AND LNK_CLAIM_AUTHORIZATION_DETAIL_RENDERING_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.HUB_PROVIDER RENDERING_PROVIDER
        ON (RENDERING_PROVIDER.HUB_PROVIDER_HKEY = LNK_CLAIM_AUTHORIZATION_DETAIL_RENDERING_PROVIDER.HUB_PROVIDER_HKEY
        AND LNK_CLAIM_AUTHORIZATION_DETAIL_RENDERING_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_CLAIM_AUTHORIZATION_DETAIL
        ON (HUB_CLAIM_AUTHORIZATION_DETAIL.HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY = SAT_CLAIM_AUTHORIZATION_DETAIL.HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY
        AND SAT_CLAIM_AUTHORIZATION_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_CLAIM_AUTHORIZATION_DETAIL_AMOUNT
        ON (HUB_CLAIM_AUTHORIZATION_DETAIL.HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY = SAT_CLAIM_AUTHORIZATION_DETAIL_AMOUNT.HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY
        AND SAT_CLAIM_AUTHORIZATION_DETAIL_AMOUNT.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN REFDATA.CLAIM_PROCEDURE REF_CLAIM_PROCEDURE --will need to refactor later as other non-dental types of authorizations are added to the datahub, to account for the distinction between procedure and hcpcs codes
        ON (REF_CLAIM_PROCEDURE.TPA_CLIENT_ID = HUB_CLAIM_AUTHORIZATION_DETAIL.TPA_CLIENT_ID
        AND REF_CLAIM_PROCEDURE.TPA_ID = HUB_CLAIM_AUTHORIZATION_DETAIL.TPA_ID
        AND REF_CLAIM_PROCEDURE.TPA_DIV_ID = HUB_CLAIM_AUTHORIZATION_DETAIL.TPA_DIV_ID
        AND REF_CLAIM_PROCEDURE.DATA_SOURCE_NAME = HUB_CLAIM_AUTHORIZATION_DETAIL.DATA_SOURCE_NAME
        AND REF_CLAIM_PROCEDURE.CODE = SAT_CLAIM_AUTHORIZATION_DETAIL.PROCEDURE_CODE)
;