CREATE OR REPLACE VIEW EXTRACTDATA.CLAIM_AUTHORIZATION_BASE_VW
COMMENT = 'LEFT OUTER JOINs core tables from hubdata data vault model for common authorization consumption'
AS
SELECT HUB_CLAIM_AUTHORIZATION.HUB_CLAIM_AUTHORIZATION_HKEY,
HUB_CLAIM_AUTHORIZATION.TPA_CLIENT_ID,
HUB_CLAIM_AUTHORIZATION.TPA_ID,
HUB_CLAIM_AUTHORIZATION.TPA_DIV_ID,
HUB_CLAIM_AUTHORIZATION.DATA_SOURCE_NAME,
HUB_CLAIM_AUTHORIZATION.AUTHORIZATION_NBR,
HUB_MEMBER.MEMBER_NBR,
SAT_MEMBER_DETAIL.FIRST_NAME AS MEMBER_FIRST_NAME,
SAT_MEMBER_DETAIL.LAST_NAME AS MEMBER_LAST_NAME,
SAT_MEMBER_DETAIL.BIRTH_DATE AS MEMBER_DOB,
SUBMITTING_PROVIDER.MEDICAL_GROUP_ID AS SUBMITTING_PROVIDER_ID,
SAT_MEDICAL_GROUP_DETAIL.MEDICAL_GROUP_NAME,
SAT_OFFICE_ADDRESS.ADDRESS_LINE_1 AS MEDICAL_GROUP_ADDRESS_LINE_1,
SAT_OFFICE_ADDRESS.ADDRESS_LINE_2 AS MEDICAL_GROUP_ADDRESS_LINE_2,
SAT_OFFICE_ADDRESS.CITY_NAME AS MEDICAL_GROUP_CITY,
SAT_OFFICE_ADDRESS.STATE_ABBREV_NAME AS MEDICAL_GROUP_STATE_ABBREV_NAME,
SAT_OFFICE_ADDRESS.ZIP_CODE AS MEDICAL_GROUP_ZIP_CODE,
SAT_OFFICE_DETAIL.PRIMARY_PHONE_NBR AS MEDICAL_GROUP_PRIMARY_PHONE_NBR,
SAT_CLAIM_AUTHORIZATION.CARE_TYPE_NAME,
SAT_CLAIM_AUTHORIZATION.STATUS_DESC AS AUTHORIZATION_STATUS_DESC,
SAT_CLAIM_AUTHORIZATION.DETERMINATION_STATUS_DESC AS AUTHORIZATION_DETERMINATION_STATUS_DESC,
SAT_CLAIM_AUTHORIZATION.DETERMINATION_DATE AS AUTHORIZATION_DETERMINATION_DATE,
SAT_CLAIM_AUTHORIZATION.PLAN_CODE,
SAT_CLAIM_AUTHORIZATION.PLAN_TYPE_CODE,
SAT_CLAIM_AUTHORIZATION.LINE_OF_BUSINESS_CODE
FROM HUBDATA.HUB_CLAIM_AUTHORIZATION

    JOIN HUBDATA.EFF_SAT_CLAIM_AUTHORIZATION
        ON(EFF_SAT_CLAIM_AUTHORIZATION.HUB_CLAIM_AUTHORIZATION_HKEY = HUB_CLAIM_AUTHORIZATION.HUB_CLAIM_AUTHORIZATION_HKEY
        AND EFF_SAT_CLAIM_AUTHORIZATION.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_CLAIM_AUTHORIZATION.DELETED_DATETIME > CURRENT_TIMESTAMP())

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_AUTHORIZATION_SUBMITTING_PROVIDER
                    JOIN HUBDATA.EFF_SAT_MEDICAL_GROUP
                        ON(EFF_SAT_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY = LNK_CLAIM_AUTHORIZATION_SUBMITTING_PROVIDER.HUB_MEDICAL_GROUP_HKEY
                        AND EFF_SAT_MEDICAL_GROUP.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_MEDICAL_GROUP.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_AUTHORIZATION_SUBMITTING_PROVIDER.HUB_CLAIM_AUTHORIZATION_HKEY = HUB_CLAIM_AUTHORIZATION.HUB_CLAIM_AUTHORIZATION_HKEY
        AND LNK_CLAIM_AUTHORIZATION_SUBMITTING_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.HUB_MEDICAL_GROUP SUBMITTING_PROVIDER
        ON (SUBMITTING_PROVIDER.HUB_MEDICAL_GROUP_HKEY = LNK_CLAIM_AUTHORIZATION_SUBMITTING_PROVIDER.HUB_MEDICAL_GROUP_HKEY
        AND LNK_CLAIM_AUTHORIZATION_SUBMITTING_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE)

     LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_AUTHORIZATION_MEMBER
                    JOIN HUBDATA.EFF_SAT_MEMBER
                        ON(EFF_SAT_MEMBER.HUB_MEMBER_HKEY = LNK_CLAIM_AUTHORIZATION_MEMBER.HUB_MEMBER_HKEY
                        AND EFF_SAT_MEMBER.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_MEMBER.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_AUTHORIZATION_MEMBER.HUB_CLAIM_AUTHORIZATION_HKEY = HUB_CLAIM_AUTHORIZATION.HUB_CLAIM_AUTHORIZATION_HKEY
        AND LNK_CLAIM_AUTHORIZATION_MEMBER.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.HUB_MEMBER
        ON (HUB_MEMBER.HUB_MEMBER_HKEY = LNK_CLAIM_AUTHORIZATION_MEMBER.HUB_MEMBER_HKEY
        AND LNK_CLAIM_AUTHORIZATION_MEMBER.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_MEMBER_DETAIL
        ON (HUB_MEMBER.HUB_MEMBER_HKEY = SAT_MEMBER_DETAIL.HUB_MEMBER_HKEY
        AND SAT_MEMBER_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_CLAIM_AUTHORIZATION
        ON (HUB_CLAIM_AUTHORIZATION.HUB_CLAIM_AUTHORIZATION_HKEY = SAT_CLAIM_AUTHORIZATION.HUB_CLAIM_AUTHORIZATION_HKEY
        AND SAT_CLAIM_AUTHORIZATION.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_MEDICAL_GROUP_DETAIL
        ON (SUBMITTING_PROVIDER.HUB_MEDICAL_GROUP_HKEY = SAT_MEDICAL_GROUP_DETAIL.HUB_MEDICAL_GROUP_HKEY
        AND SAT_MEDICAL_GROUP_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

     LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_AUTHORIZATION_OFFICE
                    JOIN HUBDATA.EFF_SAT_OFFICE
                        ON(EFF_SAT_OFFICE.HUB_OFFICE_HKEY = LNK_CLAIM_AUTHORIZATION_OFFICE.HUB_OFFICE_HKEY
                        AND EFF_SAT_OFFICE.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_OFFICE.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_AUTHORIZATION_OFFICE.HUB_CLAIM_AUTHORIZATION_HKEY = HUB_CLAIM_AUTHORIZATION.HUB_CLAIM_AUTHORIZATION_HKEY
        AND LNK_CLAIM_AUTHORIZATION_OFFICE.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.HUB_OFFICE
        ON (HUB_OFFICE.HUB_OFFICE_HKEY = LNK_CLAIM_AUTHORIZATION_OFFICE.HUB_OFFICE_HKEY
        AND LNK_CLAIM_AUTHORIZATION_OFFICE.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_OFFICE_ADDRESS
        ON (HUB_OFFICE.HUB_OFFICE_HKEY = SAT_OFFICE_ADDRESS.HUB_OFFICE_HKEY
        AND SAT_OFFICE_ADDRESS.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_OFFICE_DETAIL
        ON (HUB_OFFICE.HUB_OFFICE_HKEY = SAT_OFFICE_DETAIL.HUB_OFFICE_HKEY
        AND SAT_OFFICE_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
;