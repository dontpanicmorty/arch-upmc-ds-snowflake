CREATE OR REPLACE VIEW EXTRACTDATA.PROVIDER_IDENTIFIERS_VW
COMMENT = 'Base view of all provider identifiers'
AS
SELECT
    HKEY,
    TPA_CLIENT_ID,
    TPA_ID,
    TPA_DIV_ID,
    DATA_SOURCE_NAME,
    PROVIDER_ID,
    PROVIDER_TYPE_NAME,
    IDENTIFIER_NAME,
    IDENTIFIER_SUBTYPE,
    IDENTIFIER_NBR
FROM EXTRACTDATA.PROVIDER_IDENTIFIERS_BASE
;