CREATE OR REPLACE VIEW EXTRACTDATA.CLAIM_HEADER_ICD_PROCEDURE_CODES_VW
AS
SELECT
HUB_CLAIM.HUB_CLAIM_HKEY
,HUB_CLAIM.TPA_CLIENT_ID
,HUB_CLAIM.TPA_ID
,HUB_CLAIM.TPA_DIV_ID
,HUB_CLAIM.DATA_SOURCE_NAME
,HUB_CLAIM.CLAIM_NBR
,ICD_PROCEDURE_CODES.ICD_PROCEDURE_CODE_POSITION AS CODE_POSITION_NBR
,ICD_PROCEDURE_CODES.ICD_PROCEDURE_CODE_VALUE AS CODE_VALUE
,IFF(REF_CLAIM_ICD_PROCEDURE.CLAIM_ICD_PROCEDURE_HKEY IS NULL, 'Description Not Found', REF_CLAIM_ICD_PROCEDURE.CODE_DESC) AS CODE_DESC
,IFF(REF_CLAIM_ICD_PROCEDURE.CLAIM_ICD_PROCEDURE_HKEY IS NULL, 'Description Not Found', IFNULL(REF_CLAIM_ICD_PROCEDURE.CODE_DESC_LONG, 'Undefined')) AS CODE_DESC_LONG
,IFF(REF_CLAIM_ICD_PROCEDURE.CLAIM_ICD_PROCEDURE_HKEY IS NULL, 'Description Not Found', IFNULL(REF_CLAIM_ICD_PROCEDURE.CODE_SPANISH_DESC, 'Undefined')) AS CODE_SPANISH_DESC
,ICD_PROCEDURE_CODES.ICD_PROCEDURE_CODE_VERSION AS CODE_VERSION
,ICD_PROCEDURE_CODES.ICD_PROCEDURE_CODE_QUALIFIER AS CODE_QUALIFIER
,REF_CLAIM_ICD_PROCEDURE.GROUP_CODE
,IFF(REF_CLAIM_ICD_PROCEDURE.CLAIM_ICD_PROCEDURE_HKEY IS NULL, 'Description Not Found', IFNULL(REF_CLAIM_ICD_PROCEDURE.GROUP_DESC, 'Undefined')) AS GROUP_DESC
,IFF(REF_CLAIM_ICD_PROCEDURE.ICD_PROCEDURE_CATEGORIES = [], NULL ,REF_CLAIM_ICD_PROCEDURE.ICD_PROCEDURE_CATEGORIES) AS ICD_PROCEDURE_CATEGORIES

FROM HUBDATA.HUB_CLAIM

    JOIN HUBDATA.EFF_SAT_CLAIM_HEADER
        ON(EFF_SAT_CLAIM_HEADER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND EFF_SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_CLAIM_HEADER.DELETED_DATETIME > CURRENT_TIMESTAMP())

    LEFT OUTER JOIN HUBDATA.SAT_CLAIM_HEADER
        ON (HUB_CLAIM.HUB_CLAIM_HKEY = SAT_CLAIM_HEADER.HUB_CLAIM_HKEY
        AND SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE)
        
    JOIN (SELECT
            SAT_CLAIM_ICD_PROCEDURE.HUB_CLAIM_HKEY
            ,DIAGNOSIS_CODES.VALUE:"icdProcedureCodePosition"::number AS ICD_PROCEDURE_CODE_POSITION
            ,DIAGNOSIS_CODES.VALUE:"icdProcedureCodeQualifier"::varchar AS ICD_PROCEDURE_CODE_QUALIFIER
            ,DIAGNOSIS_CODES.VALUE:"icdProcedureCodeValue"::varchar AS ICD_PROCEDURE_CODE_VALUE
            ,DIAGNOSIS_CODES.VALUE:"icdProcedureCodeVersion"::varchar AS ICD_PROCEDURE_CODE_VERSION
            FROM HUBDATA.SAT_CLAIM_ICD_PROCEDURE
                ,TABLE(FLATTEN(input => SAT_CLAIM_ICD_PROCEDURE.ICD_PROCEDURE_CODES)) DIAGNOSIS_CODES
            WHERE SAT_CLAIM_ICD_PROCEDURE.IS_CURRENT_ROW_FLAG = TRUE
        ) ICD_PROCEDURE_CODES
        ON (ICD_PROCEDURE_CODES.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY)

    LEFT OUTER JOIN REFDATA.CLAIM_ICD_PROCEDURE REF_CLAIM_ICD_PROCEDURE
        ON (REF_CLAIM_ICD_PROCEDURE.TPA_CLIENT_ID = HUB_CLAIM.TPA_CLIENT_ID
        AND REF_CLAIM_ICD_PROCEDURE.TPA_ID = HUB_CLAIM.TPA_ID
        AND REF_CLAIM_ICD_PROCEDURE.TPA_DIV_ID = HUB_CLAIM.TPA_DIV_ID
        AND REF_CLAIM_ICD_PROCEDURE.DATA_SOURCE_NAME = HUB_CLAIM.DATA_SOURCE_NAME
        AND REF_CLAIM_ICD_PROCEDURE.CODE_VERSION = ICD_PROCEDURE_CODES.ICD_PROCEDURE_CODE_VERSION
        AND REF_CLAIM_ICD_PROCEDURE.CODE = ICD_PROCEDURE_CODES.ICD_PROCEDURE_CODE_VALUE)

WHERE SAT_CLAIM_HEADER.CARE_TYPE_NAME <> 'pharmacy'
;