CREATE OR REPLACE VIEW EXTRACTDATA.PHARMACY_CLAIM_DETAIL_BASE_VW
COMMENT = 'LEFT OUTER JOINs core tables from hubdata data vault model for common pharmacy claim detail consumption'
AS
SELECT
    HUB_CLAIM.HUB_CLAIM_HKEY,
    HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY,
    HUB_CLAIM_DETAIL.TPA_CLIENT_ID,
    HUB_CLAIM_DETAIL.TPA_ID,
    HUB_CLAIM_DETAIL.TPA_DIV_ID,
    HUB_CLAIM_DETAIL.DATA_SOURCE_NAME,
    HUB_CLAIM_DETAIL.CLAIM_NBR,
    HUB_CLAIM_DETAIL.CLAIM_LINE_NBR,
    HUB_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR,
    HUB_CLAIM_DETAIL.CLAIM_LINE_PROCEDURE_ADJ_CODE,
    SAT_CLAIM_LINE_PHARMACY.ASSIGNED_CLAIM_ID,
    SAT_CLAIM_LINE_PHARMACY.TRANSACTION_TYPE_CODE,
    IFF(SAT_CLAIM_LINE_PHARMACY.TRANSACTION_TYPE_CODE IS NULL, NULL, IFNULL(REF_CLAIM_TRANSACTION_TYPE_CODE.CODE_DESC, 'Description Not Found')) AS TRANSACTION_TYPE_DESC,
    SAT_CLAIM_LINE_PHARMACY.TRANSACTION_ADJUSTMENT_TYPE_CODE,
    IFF(SAT_CLAIM_LINE_PHARMACY.TRANSACTION_ADJUSTMENT_TYPE_CODE IS NULL, NULL, IFNULL(REF_CLAIM_TRANSACTION_ADJUSTMENT_TYPE_CODE.CODE_DESC, 'Description Not Found')) AS TRANSACTION_ADJUSTMENT_TYPE_DESC,
    SAT_CLAIM_LINE_PHARMACY.BATCH_CODE,
    SAT_CLAIM_LINE_PHARMACY.COPAY_TIER_LEVEL_NUMBER AS COPAY_TIER_LEVEL_NBR,
    SAT_CLAIM_LINE_PHARMACY.ADJUDICATION_PHARMACY_CLASS_CODE,
    IFF(SAT_CLAIM_LINE_PHARMACY.ADJUDICATION_PHARMACY_CLASS_CODE IS NULL, NULL, IFNULL(REF_CLAIM_ADJUDICATION_PHARMACY_CLASS_CODE.CODE_DESC, 'Description Not Found')) AS ADJUDICATION_PHARMACY_CLASS_DESC,
    IFNULL(SAT_CLAIM_LINE_PHARMACY.CLAIM_COB_CODE, 'N/A') AS CLAIM_COB_CODE,
    IFF(SAT_CLAIM_LINE_PHARMACY.CLAIM_COB_CODE IS NULL, 'Not Applicable', IFNULL(REF_CLAIM_COB_CODE.CODE_DESC,'Description Not Found')) AS CLAIM_COB_DESC,
    SAT_CLAIM_LINE_PHARMACY.ADJUSTMENT_TYPE_CODE,
    IFF(SAT_CLAIM_LINE_PHARMACY.ADJUSTMENT_TYPE_CODE IS NULL, NULL, IFNULL(REF_CLAIM_ADJUSTMENT_TYPE_CODE.CODE_DESC,'Description Not Found')) AS ADJUSTMENT_TYPE_DESC,
    SAT_CLAIM_LINE_PHARMACY.FILLED_DATE,
    SAT_CLAIM_LINE_PHARMACY.PAYMENT_DATE,
    SAT_CLAIM_LINE_PHARMACY.RECEIVED_DATE,
    SAT_CLAIM_LINE_PHARMACY.ADJUDICATION_DATE,
    SAT_CLAIM_LINE_PHARMACY.PRESCRIPTION_WRITTEN_DATE,
    SAT_CLAIM_LINE_PHARMACY.PHARMACY_CLAIM_CNT,
    SAT_CLAIM_LINE_PHARMACY.CHARGE_AMT,
    SAT_CLAIM_LINE_PHARMACY.COPAY_AMT,
    SAT_CLAIM_LINE_PHARMACY.DEDUCTIBLE_AMT,
    SAT_CLAIM_LINE_PHARMACY.COINSURANCE_AMT,
    SAT_CLAIM_LINE_PHARMACY.DAY_SUPPLY_CNT,
    SAT_CLAIM_LINE_PHARMACY.INGREDIENT_COST_AMT,
    SAT_CLAIM_LINE_PHARMACY.SALES_TAX_AMT,
    SAT_CLAIM_LINE_PHARMACY.DISPENSING_FEE_AMT,
    SAT_CLAIM_LINE_PHARMACY.NET_CHECK_DUE_AMT,
    SAT_CLAIM_LINE_PHARMACY.DRUG_METRIC_QTY,
    SAT_CLAIM_LINE_PHARMACY.PRODUCT_SELECTION_AMT,
    SAT_CLAIM_LINE_PHARMACY.BENEFIT_EXCEED_AMT,
    SAT_CLAIM_LINE_PHARMACY.AWP_UNIT_AMT,
    SAT_CLAIM_LINE_PHARMACY.UNIT_PRICE_ALLOWED_MAX_AMT,
    SAT_CLAIM_LINE_PHARMACY.USUAL_CUSTOMARY_AMT,
    SAT_CLAIM_LINE_PHARMACY.ADMINISTRATIVE_FEE_AMT,
    SAT_CLAIM_LINE_PHARMACY.AWP_TOTAL_AMT,
    SAT_CLAIM_LINE_PHARMACY.HRA_APPLIED_AMT,
    SAT_CLAIM_LINE_PHARMACY.PRE_COB_CLAIM_AMT,
    SAT_CLAIM_LINE_PHARMACY.COB_RECOVERY_AMT,
    SAT_CLAIM_LINE_PHARMACY.DRUG_CALCULATED_DISCOUNT_AMT,
    SAT_CLAIM_LINE_PHARMACY.DRUG_DISCOUNT_ELIGIBLE_AMT,
    IFNULL(SAT_CLAIM_LINE_PHARMACY.UPDATED_HRA_SPENDING_AMT, SAT_CLAIM_LINE_PHARMACY.ORIGINAL_HRA_SPENDING_AMT) AS HRA_SPENDING_AMT,
    SAT_CLAIM_LINE_PHARMACY.HRA_SPENDING_AMT_UPDATE_DATE,
    IFNULL(SAT_CLAIM_LINE_PHARMACY.UPDATED_HIA_SPENDING_AMT, SAT_CLAIM_LINE_PHARMACY.ORIGINAL_HIA_SPENDING_AMT) AS HIA_SPENDING_AMT,
    SAT_CLAIM_LINE_PHARMACY.HIA_SPENDING_AMT_UPDATE_DATE,
    SAT_CLAIM_LINE_PHARMACY.TOTAL_SPENDING_AMT,
    SAT_CLAIM_LINE_PHARMACY.OTHER_PAYOR_AMT,
    SAT_CLAIM_LINE_PHARMACY.TROOP_APPLIED_AMT,
    SAT_CLAIM_LINE_PHARMACY.MEMBER_PAID_AMT,
    SAT_CLAIM_LINE_PHARMACY.REPORT_EFFECTIVE_DATE,
    SAT_CLAIM_LINE_PHARMACY.TRANSITION_FILL_IND
    
FROM HUBDATA.HUB_CLAIM

    JOIN HUBDATA.EFF_SAT_CLAIM_HEADER
        ON(EFF_SAT_CLAIM_HEADER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND EFF_SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_CLAIM_HEADER.DELETED_DATETIME > CURRENT_TIMESTAMP())

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_DETAIL
                    JOIN HUBDATA.EFF_SAT_CLAIM_LINE
                        ON(EFF_SAT_CLAIM_LINE.HUB_CLAIM_DETAIL_HKEY = LNK_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
                        AND EFF_SAT_CLAIM_LINE.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_CLAIM_LINE.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_DETAIL.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.HUB_CLAIM_DETAIL
        ON (HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = LNK_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
        AND LNK_CLAIM_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
        
    LEFT OUTER JOIN HUBDATA.SAT_CLAIM_HEADER
    ON (HUB_CLAIM.HUB_CLAIM_HKEY = SAT_CLAIM_HEADER.HUB_CLAIM_HKEY
    AND SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE)
    
    LEFT OUTER JOIN HUBDATA.SAT_CLAIM_LINE
    ON (HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = SAT_CLAIM_LINE.HUB_CLAIM_DETAIL_HKEY
    AND SAT_CLAIM_LINE.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_CLAIM_LINE_PHARMACY
        ON (HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = SAT_CLAIM_LINE_PHARMACY.HUB_CLAIM_DETAIL_HKEY
        AND SAT_CLAIM_LINE_PHARMACY.IS_CURRENT_ROW_FLAG = TRUE)
    
    LEFT OUTER JOIN REFDATA.CLAIM_TRANSACTION_TYPE_CODE REF_CLAIM_TRANSACTION_TYPE_CODE
        ON (HUB_CLAIM_DETAIL.TPA_CLIENT_ID = REF_CLAIM_TRANSACTION_TYPE_CODE.TPA_CLIENT_ID
        AND HUB_CLAIM_DETAIL.TPA_ID = REF_CLAIM_TRANSACTION_TYPE_CODE.TPA_ID
        AND HUB_CLAIM_DETAIL.TPA_DIV_ID = REF_CLAIM_TRANSACTION_TYPE_CODE.TPA_DIV_ID
        AND HUB_CLAIM_DETAIL.DATA_SOURCE_NAME = REF_CLAIM_TRANSACTION_TYPE_CODE.DATA_SOURCE_NAME
        AND SAT_CLAIM_LINE_PHARMACY.TRANSACTION_TYPE_CODE = REF_CLAIM_TRANSACTION_TYPE_CODE.CODE)

    LEFT OUTER JOIN REFDATA.CLAIM_TRANSACTION_ADJUSTMENT_TYPE_CODE REF_CLAIM_TRANSACTION_ADJUSTMENT_TYPE_CODE
        ON (HUB_CLAIM_DETAIL.TPA_CLIENT_ID = REF_CLAIM_TRANSACTION_ADJUSTMENT_TYPE_CODE.TPA_CLIENT_ID
        AND HUB_CLAIM_DETAIL.TPA_ID = REF_CLAIM_TRANSACTION_ADJUSTMENT_TYPE_CODE.TPA_ID
        AND HUB_CLAIM_DETAIL.TPA_DIV_ID = REF_CLAIM_TRANSACTION_ADJUSTMENT_TYPE_CODE.TPA_DIV_ID
        AND HUB_CLAIM_DETAIL.DATA_SOURCE_NAME = REF_CLAIM_TRANSACTION_ADJUSTMENT_TYPE_CODE.DATA_SOURCE_NAME
        AND SAT_CLAIM_LINE_PHARMACY.TRANSACTION_ADJUSTMENT_TYPE_CODE = REF_CLAIM_TRANSACTION_ADJUSTMENT_TYPE_CODE.CODE)

    LEFT OUTER JOIN REFDATA.CLAIM_ADJUSTMENT_TYPE_CODE REF_CLAIM_ADJUSTMENT_TYPE_CODE
        ON (HUB_CLAIM_DETAIL.TPA_CLIENT_ID = REF_CLAIM_ADJUSTMENT_TYPE_CODE.TPA_CLIENT_ID
        AND HUB_CLAIM_DETAIL.TPA_ID = REF_CLAIM_ADJUSTMENT_TYPE_CODE.TPA_ID
        AND HUB_CLAIM_DETAIL.TPA_DIV_ID = REF_CLAIM_ADJUSTMENT_TYPE_CODE.TPA_DIV_ID
        AND HUB_CLAIM_DETAIL.DATA_SOURCE_NAME = REF_CLAIM_ADJUSTMENT_TYPE_CODE.DATA_SOURCE_NAME
        AND SAT_CLAIM_LINE_PHARMACY.ADJUSTMENT_TYPE_CODE = REF_CLAIM_ADJUSTMENT_TYPE_CODE.CODE)

    LEFT OUTER JOIN REFDATA.CLAIM_ADJUDICATION_PHARMACY_CLASS_CODE REF_CLAIM_ADJUDICATION_PHARMACY_CLASS_CODE
        ON (HUB_CLAIM_DETAIL.TPA_CLIENT_ID = REF_CLAIM_ADJUDICATION_PHARMACY_CLASS_CODE.TPA_CLIENT_ID
        AND HUB_CLAIM_DETAIL.TPA_ID = REF_CLAIM_ADJUDICATION_PHARMACY_CLASS_CODE.TPA_ID
        AND HUB_CLAIM_DETAIL.TPA_DIV_ID = REF_CLAIM_ADJUDICATION_PHARMACY_CLASS_CODE.TPA_DIV_ID
        AND HUB_CLAIM_DETAIL.DATA_SOURCE_NAME = REF_CLAIM_ADJUDICATION_PHARMACY_CLASS_CODE.DATA_SOURCE_NAME
        AND SAT_CLAIM_LINE_PHARMACY.ADJUDICATION_PHARMACY_CLASS_CODE = REF_CLAIM_ADJUDICATION_PHARMACY_CLASS_CODE.CODE)

    LEFT OUTER JOIN REFDATA.CLAIM_COB_CODE REF_CLAIM_COB_CODE
        ON (HUB_CLAIM_DETAIL.TPA_CLIENT_ID = REF_CLAIM_COB_CODE.TPA_CLIENT_ID
        AND HUB_CLAIM_DETAIL.TPA_ID = REF_CLAIM_COB_CODE.TPA_ID
        AND HUB_CLAIM_DETAIL.TPA_DIV_ID = REF_CLAIM_COB_CODE.TPA_DIV_ID
        AND HUB_CLAIM_DETAIL.DATA_SOURCE_NAME = REF_CLAIM_COB_CODE.DATA_SOURCE_NAME
        AND SAT_CLAIM_LINE_PHARMACY.CLAIM_COB_CODE = REF_CLAIM_COB_CODE.CODE)

WHERE SAT_CLAIM_HEADER.CARE_TYPE_NAME = 'pharmacy'
;