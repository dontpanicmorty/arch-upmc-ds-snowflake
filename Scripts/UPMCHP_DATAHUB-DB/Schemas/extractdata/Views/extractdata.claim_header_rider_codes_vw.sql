CREATE OR REPLACE VIEW EXTRACTDATA.CLAIM_HEADER_RIDER_CODES_VW
AS
SELECT
HUB_CLAIM.HUB_CLAIM_HKEY
,HUB_RIDER.HUB_RIDER_HKEY
,HUB_MEMBERSHIP_GROUP.HUB_MEMBERSHIP_GROUP_HKEY
,HUB_CLAIM.CLAIM_NBR
,HUB_CLAIM.TPA_ID
,HUB_CLAIM.TPA_DIV_ID
,HUB_CLAIM.TPA_CLIENT_ID
,HUB_CLAIM.DATA_SOURCE_NAME
,HUB_MEMBERSHIP_GROUP.GROUP_NBR
,HUB_MEMBERSHIP_GROUP.SUB_GROUP_NBR
,SAT_CLAIM_HEADER.ADMITTED_DATE
,HUB_RIDER.RIDER_CODE

FROM HUBDATA.HUB_CLAIM
JOIN HUBDATA.EFF_SAT_CLAIM_HEADER
    ON (HUB_CLAIM.HUB_CLAIM_HKEY = EFF_SAT_CLAIM_HEADER.HUB_CLAIM_HKEY
    AND EFF_SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE
    AND EFF_SAT_CLAIM_HEADER.DELETED_DATETIME > CURRENT_TIMESTAMP())
LEFT JOIN HUBDATA.SAT_CLAIM_HEADER
    ON (HUB_CLAIM.HUB_CLAIM_HKEY = SAT_CLAIM_HEADER.HUB_CLAIM_HKEY
    AND SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE)
LEFT JOIN HUBDATA.LNK_CLAIM_RIDER
    ON (HUB_CLAIM.HUB_CLAIM_HKEY = LNK_CLAIM_RIDER.HUB_CLAIM_HKEY
    AND LNK_CLAIM_RIDER.IS_CURRENT_ROW_FLAG = TRUE)
LEFT JOIN HUBDATA.HUB_RIDER
    ON (HUB_RIDER.HUB_RIDER_HKEY = LNK_CLAIM_RIDER.HUB_RIDER_HKEY
    AND LNK_CLAIM_RIDER.IS_CURRENT_ROW_FLAG = TRUE)
LEFT JOIN HUBDATA.LNK_CLAIM_MEMBERSHIP_GROUP
    ON (HUB_CLAIM.HUB_CLAIM_HKEY = LNK_CLAIM_MEMBERSHIP_GROUP.HUB_CLAIM_HKEY
    AND LNK_CLAIM_MEMBERSHIP_GROUP.IS_CURRENT_ROW_FLAG = TRUE)
LEFT JOIN HUBDATA.HUB_MEMBERSHIP_GROUP
    ON (HUB_MEMBERSHIP_GROUP.HUB_MEMBERSHIP_GROUP_HKEY = LNK_CLAIM_MEMBERSHIP_GROUP.HUB_MEMBERSHIP_GROUP_HKEY
    AND LNK_CLAIM_MEMBERSHIP_GROUP.IS_CURRENT_ROW_FLAG = TRUE)
WHERE SAT_CLAIM_HEADER.CARE_TYPE_NAME <> 'pharmacy'
;