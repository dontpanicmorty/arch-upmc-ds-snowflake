CREATE OR REPLACE VIEW EXTRACTDATA.REFDATA_SKYGEN_NOT_COVERED_REASONS_VW
COMMENT = 'Reference data for Skygen NC Reasons, including MEMBER_PAY. Raw, not Processed through the hub'
AS
SELECT
CLAIM_NOT_COVERED_REASON.CLAIM_NOT_COVERED_REASON_HKEY
,CLAIM_NOT_COVERED_REASON.INSERT_DATETIME
,CLAIM_NOT_COVERED_REASON.LAST_UPDATED_DATETIME
,CLAIM_NOT_COVERED_REASON.TPA_CLIENT_ID
,CLAIM_NOT_COVERED_REASON.TPA_ID
,CLAIM_NOT_COVERED_REASON.TPA_DIV_ID
,CLAIM_NOT_COVERED_REASON.DATA_SOURCE_NAME
,CLAIM_NOT_COVERED_REASON.LINE_OF_BUSINESS_CODE
,CLAIM_NOT_COVERED_REASON.NOT_COVERED_REASON_TYPE
,CLAIM_NOT_COVERED_REASON.CODE
,CLAIM_NOT_COVERED_REASON.CODE_DESC
,CLAIM_NOT_COVERED_REASON.CODE_DESC_LONG
,CLAIM_NOT_COVERED_REASON.CODE_SPANISH_DESC
,CLAIM_NOT_COVERED_REASON.MEMBER_PAY_FLAG
FROM REFDATA.CLAIM_NOT_COVERED_REASON
WHERE CLAIM_NOT_COVERED_REASON.DATA_SOURCE_NAME = 'Skygen'
;
