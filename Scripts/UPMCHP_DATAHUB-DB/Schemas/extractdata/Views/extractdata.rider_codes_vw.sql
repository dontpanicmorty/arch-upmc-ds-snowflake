CREATE OR REPLACE VIEW EXTRACTDATA.RIDER_CODES_VW
AS
SELECT
HUB_RIDER.HUB_RIDER_HKEY
,HUB_RIDER.TPA_CLIENT_ID
,HUB_RIDER.TPA_ID
,HUB_RIDER.TPA_DIV_ID
,HUB_RIDER.DATA_SOURCE_NAME
,HUB_RIDER.RIDER_CODE
,SAT_RIDER_DETAIL.RIDER_EFFECTIVE_DATE
,SAT_RIDER_DETAIL.RIDER_DESC
,SAT_RIDER_DETAIL.RIDER_TERMINATION_DATE
,SAT_RIDER_DETAIL.TIER_METHOD_CODE
,SAT_RIDER_DETAIL.RIDER_AMT_1
,SAT_RIDER_DETAIL.RIDER_AMT_2
,SAT_RIDER_DETAIL.RIDER_AMT_3
,SAT_RIDER_DETAIL.RIDER_AMT_4
,SAT_RIDER_DETAIL.RIDER_AMT_5
,SAT_RIDER_DETAIL.RIDER_AMT_6
,SAT_RIDER_DETAIL.RIDER_AMT_7
,SAT_RIDER_DETAIL.RIDER_AMT_8
,SAT_RIDER_DETAIL.RIDER_AMT_9
,SAT_RIDER_DETAIL.RIDER_AMT_10
,SAT_RIDER_DETAIL.RIDER_TYPE_CODE
,REF_RIDER_TYPE.CODE_DESC AS RIDER_TYPE_DESC
,SAT_RIDER_DETAIL.AR_CASH_GL_DISTRIBUTION_CODE
,SAT_RIDER_DETAIL.COMPANY_CODE
,SAT_RIDER_DETAIL.ELIGIBILITY_RULE_CODE
,SAT_RIDER_DETAIL.GL_DISTRIBUTION_CODE
,SAT_RIDER_DETAIL.GROUP_NBR
,SAT_RIDER_DETAIL.SUB_GROUP_NBR
,SAT_RIDER_DETAIL.FORMULARY_CODE
,REF_RIDER_FORMULARY_CODE.CODE_DESC AS FORMULARY_CODE_DESC

FROM HUBDATA.HUB_RIDER
JOIN HUBDATA.EFF_SAT_RIDER
        ON(EFF_SAT_RIDER.HUB_RIDER_HKEY = HUB_RIDER.HUB_RIDER_HKEY
        AND EFF_SAT_RIDER.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_RIDER.DELETED_DATETIME > CURRENT_TIMESTAMP())
    LEFT JOIN HUBDATA.SAT_RIDER_DETAIL
        ON (HUB_RIDER.HUB_RIDER_HKEY = SAT_RIDER_DETAIL.HUB_RIDER_HKEY
        AND SAT_RIDER_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
    LEFT JOIN REFDATA.RIDER_TYPE REF_RIDER_TYPE
        ON (SAT_RIDER_DETAIL.RIDER_TYPE_CODE = REF_RIDER_TYPE.CODE
        AND SAT_RIDER_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
    LEFT JOIN REFDATA.RIDER_FORMULARY_CODE REF_RIDER_FORMULARY_CODE
        ON (SAT_RIDER_DETAIL.FORMULARY_CODE = REF_RIDER_FORMULARY_CODE.CODE
        AND SAT_RIDER_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
;