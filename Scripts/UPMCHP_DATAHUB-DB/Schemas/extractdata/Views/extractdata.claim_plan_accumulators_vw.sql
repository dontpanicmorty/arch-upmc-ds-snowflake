CREATE OR REPLACE VIEW EXTRACTDATA.CLAIM_PLAN_ACCUMULATORS_VW
COMMENT = 'EXTRACTDATA view of plan accumulators data'
AS
SELECT 
GREATEST(HUB_MEMBER.INSERT_DATETIME,
    HUB_PLAN_ACCUMULATOR.INSERT_DATETIME,
    HUB_PLAN.INSERT_DATETIME,
    HUB_MEMBERSHIP_GROUP.INSERT_DATETIME,
    HUB_ACCUMULATOR_CODESET.INSERT_DATETIME,
    SAT_PLAN_ACCUMULATOR.ROW_EFFECTIVE_DATETIME,
    SAT_PLAN_ACCUMULATOR_MEMBER.ROW_EFFECTIVE_DATETIME,
    SAT_PLAN_ACCUMULATOR_THRESHOLD.ROW_EFFECTIVE_DATETIME,
    SAT_ACCUMULATOR_CODESET.ROW_EFFECTIVE_DATETIME,
    SAT_PLAN_DETAIL.ROW_EFFECTIVE_DATETIME,
    SAT_MEMBERSHIP_GROUP_DETAIL.ROW_EFFECTIVE_DATETIME
) AS LAST_UPDATED_DATETIME,
HUB_MEMBER.MEMBER_NBR,
HUB_PLAN_ACCUMULATOR.TPA_CLIENT_ID,
HUB_PLAN_ACCUMULATOR.TPA_ID,
HUB_PLAN_ACCUMULATOR.TPA_DIV_ID,
HUB_PLAN_ACCUMULATOR.DATA_SOURCE_NAME,
HUB_PLAN_ACCUMULATOR.CARE_TYPE_NAME,
HUB_PLAN.PLAN_CODE,
HUB_MEMBERSHIP_GROUP.GROUP_NBR,
HUB_MEMBERSHIP_GROUP.SUB_GROUP_NBR,
HUB_PLAN_ACCUMULATOR.ACCUMULATOR_TYPE_CODE,
HUB_PLAN_ACCUMULATOR.ACCUMULATOR_PERIOD_BENEFIT_LEVEL_CODE,
HUB_ACCUMULATOR_CODESET.CODESET_CODE,
HUB_PLAN_ACCUMULATOR.IN_NETWORK_FLAG,
SAT_PLAN_ACCUMULATOR.ACCUMULATOR_PERIOD_TYPE_DESC,
SAT_PLAN_ACCUMULATOR.ACCUMULATOR_TYPE_DESC,
SAT_PLAN_ACCUMULATOR.SUBSCRIBER_TYPE_DESC,
SAT_PLAN_ACCUMULATOR_MEMBER.ACCUMULATOR_EFFECTIVE_START_DATE,
SAT_PLAN_ACCUMULATOR_MEMBER.ACCUMULATOR_EFFECTIVE_END_DATE,
SAT_PLAN_ACCUMULATOR_THRESHOLD.THRESHOLD_AMT,
SAT_PLAN_ACCUMULATOR_THRESHOLD.COINSURANCE_FORMULA,
SAT_PLAN_ACCUMULATOR_THRESHOLD.DEDUCTIBLE_FORMULA,
SAT_PLAN_ACCUMULATOR_THRESHOLD.BENEFIT_MAX_FORMULA,
SAT_PLAN_ACCUMULATOR_THRESHOLD.OUT_OF_POCKET_FORMULA,
SAT_ACCUMULATOR_CODESET.CODESET_DESC AS BENEFIT_CODESET_NAME,
SAT_ACCUMULATOR_CODESET.CODESET_CLASSIFICATION_DESC,
SAT_ACCUMULATOR_CODESET.CODESET_CATEGORY_DESC,
SAT_PLAN_DETAIL.PLAN_DESC,
SAT_PLAN_DETAIL.PLAN_TYPE_CODE,
NULL AS PLAN_TYPE_DESC,
--SAT_PLAN_DETAIL.PLAN_TYPE_DESC, NEEDS ADDED BACK IN
SAT_MEMBERSHIP_GROUP_DETAIL.GROUP_NAME,
SAT_MEMBERSHIP_GROUP_DETAIL.SUB_GROUP_NAME,
SAT_PLAN_ACCUMULATOR_MEMBER.SPEND_AMT,
SAT_PLAN_ACCUMULATOR_MEMBER.ROLLOVER_CONSUMED_AMT,
SAT_PLAN_ACCUMULATOR_MEMBER.ROLLOVER_MAX_AMT
FROM HUBDATA.HUB_PLAN_ACCUMULATOR
JOIN HUBDATA.EFF_SAT_PLAN_ACCUMULATOR
    ON HUB_PLAN_ACCUMULATOR.HUB_PLAN_ACCUMULATOR_HKEY = EFF_SAT_PLAN_ACCUMULATOR.HUB_PLAN_ACCUMULATOR_HKEY
    AND EFF_SAT_PLAN_ACCUMULATOR.IS_CURRENT_ROW_FLAG = TRUE
    AND EFF_SAT_PLAN_ACCUMULATOR.DELETED_DATETIME > CURRENT_TIMESTAMP()
LEFT OUTER JOIN HUBDATA.SAT_PLAN_ACCUMULATOR
    ON HUB_PLAN_ACCUMULATOR.HUB_PLAN_ACCUMULATOR_HKEY = SAT_PLAN_ACCUMULATOR.HUB_PLAN_ACCUMULATOR_HKEY
    AND SAT_PLAN_ACCUMULATOR.IS_CURRENT_ROW_FLAG = TRUE
LEFT OUTER JOIN HUBDATA.SAT_PLAN_ACCUMULATOR_THRESHOLD
    ON HUB_PLAN_ACCUMULATOR.HUB_PLAN_ACCUMULATOR_HKEY = SAT_PLAN_ACCUMULATOR_THRESHOLD.HUB_PLAN_ACCUMULATOR_HKEY
    AND SAT_PLAN_ACCUMULATOR_THRESHOLD.IS_CURRENT_ROW_FLAG = TRUE
LEFT OUTER JOIN (HUBDATA.LNK_PLAN_ACCUMULATOR_MEMBERSHIP_GROUP
                    JOIN HUBDATA.EFF_SAT_MEMBERSHIP_GROUP
                        ON(EFF_SAT_MEMBERSHIP_GROUP.HUB_MEMBERSHIP_GROUP_HKEY = LNK_PLAN_ACCUMULATOR_MEMBERSHIP_GROUP.HUB_MEMBERSHIP_GROUP_HKEY
                        AND EFF_SAT_MEMBERSHIP_GROUP.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_MEMBERSHIP_GROUP.DELETED_DATETIME > CURRENT_TIMESTAMP())
                  )
    ON (LNK_PLAN_ACCUMULATOR_MEMBERSHIP_GROUP.HUB_PLAN_ACCUMULATOR_HKEY = HUB_PLAN_ACCUMULATOR.HUB_PLAN_ACCUMULATOR_HKEY
    AND LNK_PLAN_ACCUMULATOR_MEMBERSHIP_GROUP.IS_CURRENT_ROW_FLAG = TRUE)
LEFT OUTER JOIN HUBDATA.HUB_MEMBERSHIP_GROUP
    ON (LNK_PLAN_ACCUMULATOR_MEMBERSHIP_GROUP.HUB_MEMBERSHIP_GROUP_HKEY = HUB_MEMBERSHIP_GROUP.HUB_MEMBERSHIP_GROUP_HKEY
    AND LNK_PLAN_ACCUMULATOR_MEMBERSHIP_GROUP.IS_CURRENT_ROW_FLAG = TRUE)
LEFT OUTER JOIN HUBDATA.SAT_MEMBERSHIP_GROUP_DETAIL
    ON (SAT_MEMBERSHIP_GROUP_DETAIL.HUB_MEMBERSHIP_GROUP_HKEY = HUB_MEMBERSHIP_GROUP.HUB_MEMBERSHIP_GROUP_HKEY
    AND SAT_MEMBERSHIP_GROUP_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
LEFT OUTER JOIN (HUBDATA.LNK_PLAN_ACCUMULATOR_PLAN
                    JOIN HUBDATA.EFF_SAT_PLAN
                        ON(EFF_SAT_PLAN.HUB_PLAN_HKEY = LNK_PLAN_ACCUMULATOR_PLAN.HUB_PLAN_HKEY
                        AND EFF_SAT_PLAN.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_PLAN.DELETED_DATETIME > CURRENT_TIMESTAMP())
                  )
    ON (LNK_PLAN_ACCUMULATOR_PLAN.HUB_PLAN_ACCUMULATOR_HKEY = HUB_PLAN_ACCUMULATOR.HUB_PLAN_ACCUMULATOR_HKEY
    AND LNK_PLAN_ACCUMULATOR_PLAN.IS_CURRENT_ROW_FLAG = TRUE)
LEFT OUTER JOIN HUBDATA.HUB_PLAN
    ON (HUB_PLAN.HUB_PLAN_HKEY = LNK_PLAN_ACCUMULATOR_PLAN.HUB_PLAN_HKEY
    AND LNK_PLAN_ACCUMULATOR_PLAN.IS_CURRENT_ROW_FLAG = TRUE)
LEFT OUTER JOIN HUBDATA.SAT_PLAN_DETAIL
    ON (SAT_PLAN_DETAIL.HUB_PLAN_HKEY = HUB_PLAN.HUB_PLAN_HKEY
    AND SAT_PLAN_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
LEFT OUTER JOIN (HUBDATA.LNK_PLAN_ACCUMULATOR_CODESET
                    JOIN HUBDATA.EFF_SAT_ACCUMULATOR_CODESET
                        ON(EFF_SAT_ACCUMULATOR_CODESET.HUB_ACCUMULATOR_CODESET_HKEY = LNK_PLAN_ACCUMULATOR_CODESET.HUB_ACCUMULATOR_CODESET_HKEY
                        AND EFF_SAT_ACCUMULATOR_CODESET.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_ACCUMULATOR_CODESET.DELETED_DATETIME > CURRENT_TIMESTAMP())
                  )
    ON (LNK_PLAN_ACCUMULATOR_CODESET.HUB_PLAN_ACCUMULATOR_HKEY = HUB_PLAN_ACCUMULATOR.HUB_PLAN_ACCUMULATOR_HKEY
    AND LNK_PLAN_ACCUMULATOR_CODESET.IS_CURRENT_ROW_FLAG = TRUE)
LEFT OUTER JOIN HUBDATA.HUB_ACCUMULATOR_CODESET
    ON LNK_PLAN_ACCUMULATOR_CODESET.HUB_ACCUMULATOR_CODESET_HKEY = HUB_ACCUMULATOR_CODESET.HUB_ACCUMULATOR_CODESET_HKEY
    AND LNK_PLAN_ACCUMULATOR_CODESET.IS_CURRENT_ROW_FLAG = TRUE
LEFT OUTER JOIN HUBDATA.SAT_ACCUMULATOR_CODESET
    ON HUB_ACCUMULATOR_CODESET.HUB_ACCUMULATOR_CODESET_HKEY = SAT_ACCUMULATOR_CODESET.HUB_ACCUMULATOR_CODESET_HKEY
    AND SAT_ACCUMULATOR_CODESET.IS_CURRENT_ROW_FLAG = TRUE
LEFT OUTER JOIN (HUBDATA.LNK_PLAN_ACCUMULATOR_MEMBER
                    JOIN HUBDATA.EFF_SAT_MEMBER
                        ON(EFF_SAT_MEMBER.HUB_MEMBER_HKEY = LNK_PLAN_ACCUMULATOR_MEMBER.HUB_MEMBER_HKEY
                        AND EFF_SAT_MEMBER.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_MEMBER.DELETED_DATETIME > CURRENT_TIMESTAMP())
                    JOIN HUBDATA.HUB_MEMBER
                        ON (HUB_MEMBER.HUB_MEMBER_HKEY = LNK_PLAN_ACCUMULATOR_MEMBER.HUB_MEMBER_HKEY)
                    JOIN HUBDATA.SAT_PLAN_ACCUMULATOR_MEMBER
                        ON (LNK_PLAN_ACCUMULATOR_MEMBER.LNK_PLAN_ACCUMULATOR_MEMBER_HKEY = SAT_PLAN_ACCUMULATOR_MEMBER.LNK_PLAN_ACCUMULATOR_MEMBER_HKEY
                        AND SAT_PLAN_ACCUMULATOR_MEMBER.IS_CURRENT_ROW_FLAG = TRUE)
                )
    ON (HUB_PLAN_ACCUMULATOR.HUB_PLAN_ACCUMULATOR_HKEY = LNK_PLAN_ACCUMULATOR_MEMBER.HUB_PLAN_ACCUMULATOR_HKEY)
LEFT OUTER JOIN REFDATA.CLAIM_ACCUMULATOR_THRESHOLD REF_CLAIM_ACCUMULATOR_THRESHOLD
    ON (HUB_PLAN_ACCUMULATOR.TPA_CLIENT_ID = REF_CLAIM_ACCUMULATOR_THRESHOLD.TPA_CLIENT_ID
    AND HUB_PLAN_ACCUMULATOR.TPA_ID = REF_CLAIM_ACCUMULATOR_THRESHOLD.TPA_ID
    AND HUB_PLAN_ACCUMULATOR.TPA_DIV_ID = REF_CLAIM_ACCUMULATOR_THRESHOLD.TPA_DIV_ID
    AND HUB_PLAN_ACCUMULATOR.DATA_SOURCE_NAME = REF_CLAIM_ACCUMULATOR_THRESHOLD.DATA_SOURCE_NAME
    AND SAT_PLAN_ACCUMULATOR_THRESHOLD.ACCUMULATOR_THRESHOLD_CODE = REF_CLAIM_ACCUMULATOR_THRESHOLD.CODE)
;