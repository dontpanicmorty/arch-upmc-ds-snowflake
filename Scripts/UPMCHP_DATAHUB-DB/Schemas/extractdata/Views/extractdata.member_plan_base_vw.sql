CREATE OR REPLACE VIEW EXTRACTDATA.MEMBER_PLAN_BASE_VW
COMMENT = 'Joins core tables from hubdata data vault model for common PLAN detail consumption'
AS
SELECT HUB_PLAN.HUB_PLAN_HKEY
,HUB_PLAN.TPA_CLIENT_ID
,HUB_PLAN.TPA_ID
,HUB_PLAN.TPA_DIV_ID
,HUB_PLAN.DATA_SOURCE_NAME
,HUB_PLAN.PLAN_CODE
-- --SAT_PLAN_DETAIL_ACA COLUMNS
,SAT_PLAN_DETAIL_ACA.HIOS_ID
,SAT_PLAN_DETAIL_ACA.MIN_BENEFIT_YEAR
,SAT_PLAN_DETAIL_ACA.MARKET_SEGMENT_NAME
,SAT_PLAN_DETAIL_ACA.PLAN_TYPE_NAME
,SAT_PLAN_DETAIL_ACA.PRODUCT_CODE
,SAT_PLAN_DETAIL_ACA.MARKETING_PLAN_NAME
,SAT_PLAN_DETAIL_ACA.METAL_LEVEL_CODE
,SAT_PLAN_DETAIL_ACA.ON_EXCHANGE_IND
,SAT_PLAN_DETAIL_ACA.NETWORK_NAME
,SAT_PLAN_DETAIL_ACA.COST_SHARE_TYPE_NAME
-- --SAT_PLAN_DETAIL COLUMNS
,SAT_PLAN_DETAIL.PLAN_DESC
,SAT_PLAN_DETAIL.PLAN_TYPE_CODE
,SAT_PLAN_DETAIL.LOB_CODE
,NULL AS LOB_Desc-- Needs ref table?
,SAT_PLAN_DETAIL.LOB_PRODUCT_CODE
,NULL AS LOB_Product_Desc -- Needs ref table?
,NULL AS LOB_Plan_Type_Desc -- Needs ref table?
,SAT_PLAN_DETAIL.PLAN_CATEGORY_NAME
,SAT_PLAN_DETAIL.HEALTHY_U_IND
,SAT_PLAN_DETAIL.WELLNESS_IND
,SAT_PLAN_DETAIL.COMPANY_CODE
,SAT_PLAN_DETAIL.FUNDING_TYPE_DESC
,SAT_PLAN_DETAIL.BUSINESS_UNIT_DESC
,SAT_PLAN_DETAIL.GRANDFATHERED_ACA_PLAN_IND
FROM HUBDATA.HUB_PLAN
    JOIN HUBDATA.EFF_SAT_PLAN
        ON(EFF_SAT_PLAN.HUB_PLAN_HKEY = HUB_PLAN.HUB_PLAN_HKEY
        AND EFF_SAT_PLAN.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_PLAN.DELETED_DATETIME > CURRENT_TIMESTAMP())
    LEFT JOIN HUBDATA.SAT_PLAN_DETAIL
        ON (HUB_PLAN.HUB_PLAN_HKEY = SAT_PLAN_DETAIL.HUB_PLAN_HKEY
        AND SAT_PLAN_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
    LEFT JOIN HUBDATA.SAT_PLAN_DETAIL_ACA
        ON (HUB_PLAN.HUB_PLAN_HKEY = SAT_PLAN_DETAIL_ACA.HUB_PLAN_HKEY
        AND SAT_PLAN_DETAIL_ACA.IS_CURRENT_ROW_FLAG = TRUE)
;