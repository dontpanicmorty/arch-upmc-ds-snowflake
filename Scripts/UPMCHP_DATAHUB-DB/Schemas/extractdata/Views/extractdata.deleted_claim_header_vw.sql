CREATE OR REPLACE VIEW EXTRACTDATA.DELETED_CLAIM_HEADER_VW 
COMMENT='All deleted claim header records'
AS
SELECT
HUB_CLAIM.HUB_CLAIM_HKEY
,EFF_SAT_CLAIM_HEADER.DELETED_DATETIME
,HUB_CLAIM.CLAIM_NBR
,HUB_CLAIM.DATA_SOURCE_NAME
,HUB_CLAIM.TPA_CLIENT_ID
,HUB_CLAIM.TPA_ID
,HUB_CLAIM.TPA_DIV_ID
,LNK_CLAIM_MEMBER.M_MEMBER_NBR

FROM HUBDATA.EFF_SAT_CLAIM_HEADER
    INNER JOIN HUBDATA.HUB_CLAIM 
        ON EFF_SAT_CLAIM_HEADER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
    INNER JOIN HUBDATA.LNK_CLAIM_MEMBER
        ON LNK_CLAIM_MEMBER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY    
    WHERE
     EFF_SAT_CLAIM_HEADER.DELETED_DATETIME < TO_TIMESTAMP('9999-12-30')
        AND EFF_SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE
    ;