CREATE OR REPLACE VIEW EXTRACTDATA.REFDATA_CLAIM_PROCEDURE_CODE_VW
COMMENT = 'Reference Data for Procedure Codes that appear on claims'
AS
SELECT DISTINCT
HUB_CLAIM_DETAIL.TPA_CLIENT_ID,
HUB_CLAIM_DETAIL.TPA_ID,
HUB_CLAIM_DETAIL.TPA_DIV_ID,
HUB_CLAIM_DETAIL.DATA_SOURCE_NAME,
REF_CLAIM_PROCEDURE.CODE AS PROCEDURE_CODE,
REF_CLAIM_PROCEDURE.CODE_DESC AS PROCEDURE_CODE_DESC,
REF_CLAIM_PROCEDURE.CODE_DESC_LONG AS PROCEDURE_CODE_DESC_LONG,
REF_CLAIM_PROCEDURE.CODE_SPANISH_DESC AS PROCEDURE_CODE_SPANISH_DESC
FROM HUBDATA.HUB_CLAIM_DETAIL
JOIN HUBDATA.EFF_SAT_CLAIM_LINE
    ON (HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = EFF_SAT_CLAIM_LINE.HUB_CLAIM_DETAIL_HKEY
    AND EFF_SAT_CLAIM_LINE.IS_CURRENT_ROW_FLAG = TRUE
    AND EFF_SAT_CLAIM_LINE.DELETED_DATETIME > CURRENT_TIMESTAMP()
    )
JOIN HUBDATA.SAT_CLAIM_LINE
    ON (HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = SAT_CLAIM_LINE.HUB_CLAIM_DETAIL_HKEY
    AND SAT_CLAIM_LINE.IS_CURRENT_ROW_FLAG = TRUE)
JOIN REFDATA.CLAIM_PROCEDURE REF_CLAIM_PROCEDURE
    ON (SAT_CLAIM_LINE.PROCEDURE_CODE = REF_CLAIM_PROCEDURE.CODE
    AND HUB_CLAIM_DETAIL.TPA_CLIENT_ID = REF_CLAIM_PROCEDURE.TPA_CLIENT_ID
    AND HUB_CLAIM_DETAIL.TPA_ID = REF_CLAIM_PROCEDURE.TPA_ID
    AND HUB_CLAIM_DETAIL.TPA_DIV_ID = REF_CLAIM_PROCEDURE.TPA_DIV_ID
    AND HUB_CLAIM_DETAIL.DATA_SOURCE_NAME = REF_CLAIM_PROCEDURE.DATA_SOURCE_NAME)
;