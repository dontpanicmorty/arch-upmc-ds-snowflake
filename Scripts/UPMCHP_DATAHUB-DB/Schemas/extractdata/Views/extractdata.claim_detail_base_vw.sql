CREATE OR REPLACE VIEW EXTRACTDATA.CLAIM_DETAIL_BASE_VW
COMMENT = 'Joins core tables from hubdata data vault model for common claim detail consumption'
AS
SELECT
HUB_CLAIM.HUB_CLAIM_HKEY,
HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY,
HUB_CLAIM_DETAIL.TPA_CLIENT_ID,
HUB_CLAIM_DETAIL.TPA_ID,
HUB_CLAIM_DETAIL.TPA_DIV_ID,
HUB_CLAIM_DETAIL.DATA_SOURCE_NAME,
HUB_CLAIM_DETAIL.CLAIM_NBR,
HUB_CLAIM_DETAIL.CLAIM_LINE_NBR,
HUB_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR,
HUB_CLAIM_DETAIL.CLAIM_LINE_PROCEDURE_ADJ_CODE,
LNK_CLAIM_MEMBER.HUB_MEMBER_HKEY,
LNK_CLAIM_MEMBER.M_MEMBER_NBR AS MEMBER_NBR,
LEFT(LNK_CLAIM_MEMBER.M_MEMBER_NBR,9) AS SUBSCRIBER_ID,
RIGHT(LNK_CLAIM_MEMBER.M_MEMBER_NBR,2) AS PERSON_ID,
LNK_CLAIM_MEMBERSHIP_GROUP.MG_GROUP_NBR AS GROUP_NBR,
LNK_CLAIM_MEMBERSHIP_GROUP.MG_SUB_GROUP_NBR AS SUB_GROUP_NBR,
SAT_CLAIM_LINE_AMOUNT.ALLOWED_AMOUNT,
SAT_CLAIM_LINE_AMOUNT.CHARGE_AMOUNT,
SAT_CLAIM_LINE_AMOUNT.CLAIM_AMT_01,
SAT_CLAIM_LINE_AMOUNT.CLAIM_AMT_01_DESC,
SAT_CLAIM_LINE_AMOUNT.CLAIM_AMT_02,
SAT_CLAIM_LINE_AMOUNT.CLAIM_AMT_02_DESC,
SAT_CLAIM_LINE_AMOUNT.COPAY_AMT_01,
SAT_CLAIM_LINE_AMOUNT.COPAY_AMT_02,
SAT_CLAIM_LINE_AMOUNT.COPAY_AMT_03,
SAT_CLAIM_LINE_AMOUNT.DEDUCTIBLE_AMOUNT,
SAT_CLAIM_LINE_AMOUNT.NOT_COVERED_AMOUNT,
SAT_CLAIM_LINE_AMOUNT.PAID_AMOUNT,
SAT_CLAIM_LINE_AMOUNT.PAID_GROSS_AMOUNT,
SAT_CLAIM_LINE_AMOUNT.PAY_FOR_PERFORMANCE_AMOUNT,
SAT_CLAIM_LINE_AMOUNT.WITHHOLD_AMOUNT,
SAT_CLAIM_LINE_AMOUNT.COINSURANCE_AMOUNT,
SAT_CLAIM_LINE_AMOUNT.CODE_REVIEW_ORIGINAL_BILLING_AMOUNT,
SAT_CLAIM_LINE_AMOUNT.CODE_REVIEW_ORIGINAL_NET_AMOUNT,
SAT_CLAIM_LINE_AMOUNT.APPROVED_AMT,
SAT_CLAIM_LINE_AMOUNT.INTEREST_DISCOUNT_AMOUNT,
SAT_CLAIM_LINE_AMOUNT.THIRD_PARTY_PAID_AMOUNT,
SAT_CLAIM_LINE_AMOUNT.THIRD_PARTY_ALLOWED_AMOUNT,
SAT_CLAIM_LINE_AMOUNT.OIC_PAID_AMOUNT,
SAT_CLAIM_LINE_AMOUNT.OIC_ALLOWED_AMOUNT,
SAT_CLAIM_LINE_AMOUNT.HRA_APPLIED_AMT,
SAT_CLAIM_LINE_AMOUNT.HIA_APPLIED_AMT,
COPAY_REASON.REASON_CODE AS COPAY_REASON_CODE,
IFF(COPAY_REASON.REASON_CODE IS NULL, NULL, IFNULL(REF_CLAIM_PROCESSING_COPAY.CODE_DESC, 'Description Not Found')) AS COPAY_REASON_CODE_DESC,
COPAY_REASON.CODE_POSITION AS COPAY_REASON_CODE_POSITION,
COINSURANCE_REASON.REASON_CODE AS COINSURANCE_REASON_CODE,
IFF(COINSURANCE_REASON.REASON_CODE IS NULL, NULL, IFNULL(REF_CLAIM_PROCESSING_COINSURANCE.CODE_DESC, 'Description Not Found')) AS COINSURANCE_REASON_CODE_DESC,
COINSURANCE_REASON.CODE_POSITION AS COINSURANCE_REASON_CODE_POSITION,
SAT_CLAIM_LINE.CLAIM_TYPE_CODE,
SAT_CLAIM_LINE.CLAIM_RECEIVED_DATE,
SAT_CLAIM_LINE.PROCEDURE_CODE,
IFNULL(REF_CLAIM_PROCEDURE.CODE_DESC, 'Description Not Found') AS PROCEDURE_CODE_DESC,
IFF(REF_CLAIM_PROCEDURE.CLAIM_PROCEDURE_HKEY IS NULL, 'Description Not Found', IFNULL(REF_CLAIM_PROCEDURE.CODE_DESC_LONG, 'Undefined')) AS PROCEDURE_CODE_DESC_LONG,
IFF(REF_CLAIM_PROCEDURE.CLAIM_PROCEDURE_HKEY IS NULL, 'Description Not Found', IFNULL(REF_CLAIM_PROCEDURE.CODE_SPANISH_DESC, 'Undefined')) AS PROCEDURE_CODE_SPANISH_DESC,
SAT_CLAIM_LINE.PROCEDURE_QUANTITY,
SAT_CLAIM_LINE.SERVICE_BEGIN_DATE,
SAT_CLAIM_LINE.SERVICE_END_DATE,
SAT_CLAIM_LINE.ADD_DATE,
SAT_CLAIM_LINE.ACCOUNTS_PAYABLE_PAY_STATUS_CODE,
SAT_CLAIM_LINE.ADJUDICATION_STATUS,
SAT_CLAIM_LINE.AP_POSTING_DATE,
SAT_CLAIM_LINE.BENEFIT_CATEGORY_CODE,
IFF(SAT_CLAIM_LINE.BENEFIT_CATEGORY_CODE IS NULL, NULL, IFNULL(REF_BENEFIT_CATEGORY.CODE_DESC, 'Description Not Found')) AS BENEFIT_CATEGORY_CODE_DESC,
SAT_CLAIM_LINE.BUCKET_STATUS_FLAG,
SAT_CLAIM_LINE.CHECK_DATE,
SAT_CLAIM_LINE.CHECK_NUMBER,
SAT_CLAIM_LINE.CLAIM_DAY_CNT,
SAT_CLAIM_LINE.CLEAN_CLAIM_IND,
SAT_CLAIM_LINE.COMPANY_CODE,
SAT_CLAIM_LINE.DENIED_DAY_CNT,
SAT_CLAIM_LINE.ELIGIBILITY_MISC_STATUS_CODE,
SAT_CLAIM_HEADER.CARE_TYPE_NAME,
SAT_CLAIM_LINE.FORM_NUMBER,
SAT_CLAIM_LINE.GL_DISTRIBUTION_CODE,
SAT_CLAIM_LINE.IS_PROCESSING_COMPLETE,
SAT_CLAIM_LINE.KEY_TO_SOURCE_FILE,
SAT_CLAIM_LINE.PAY_STATUS_CODE,
SAT_CLAIM_LINE.PAYMENT_DATE,
SAT_CLAIM_LINE.TOOTH_QUADRANT,
IFF(SAT_CLAIM_LINE.TOOTH_QUADRANT IS NULL, NULL, IFNULL(REF_TOOTH_QUADRANT.CODE_DESC, 'Description Not Found')) AS TOOTH_QUADRANT_DESC,
SAT_CLAIM_LINE.SERVICE_CNT,
SERVICE_REASONS.SERVICE_REASON_ARRAY,
SAT_CLAIM_LINE.SERVICE_STATUS_CODE,
SAT_CLAIM_LINE.SERVICE_STATUS_DESC,
SAT_CLAIM_LINE.SERVICE_TYPE_CODE,
IFF(SAT_CLAIM_LINE.SERVICE_TYPE_CODE IS NULL, NULL, IFNULL(REF_CLAIM_SERVICE_TYPE.CODE_DESC,'Description Not Found')) AS SERVICE_TYPE_DESC,
SAT_CLAIM_LINE.TRANSACTION_TYPE_CODE,
SAT_CLAIM_LINE.TRANSACTION_TYPE_DESC,
SAT_CLAIM_LINE.SOURCE_LAST_UPDATED_DATETIME,
SAT_CLAIM_LINE.TOOTH_ID,
SAT_CLAIM_LINE.TOOTH_ARCH,
IFF(SAT_CLAIM_LINE.TOOTH_ARCH IS NULL, NULL, IFNULL(REF_TOOTH_ARCH.CODE_DESC, 'Description Not Found')) AS TOOTH_ARCH_DESC,
SAT_CLAIM_LINE.MEMBER_AGE_NBR,
PROCEDURE_MODIFIER_CODES.PROCEDURE_MODIFIER_01,
PROCEDURE_MODIFIER_CODES_DESC.PROCEDURE_MODIFIER_01_DESC,
PROCEDURE_MODIFIER_CODES.PROCEDURE_MODIFIER_02,
PROCEDURE_MODIFIER_CODES_DESC.PROCEDURE_MODIFIER_02_DESC,
PROCEDURE_MODIFIER_CODES.PROCEDURE_MODIFIER_03,
PROCEDURE_MODIFIER_CODES_DESC.PROCEDURE_MODIFIER_03_DESC,
PROCEDURE_MODIFIER_CODES.PROCEDURE_MODIFIER_04,
PROCEDURE_MODIFIER_CODES_DESC.PROCEDURE_MODIFIER_04_DESC,
IFF(SAT_CLAIM_LINE.PAY_STATUS_CODE IS NULL, NULL, IFNULL(REF_CLAIM_PAY_STATUS.CODE_DESC, 'Description Not Found')) AS PAY_STATUS_DESC,
HUB_PROVIDER_RENDERING.PROVIDER_ID AS RENDERING_PROVIDER_ID,
SAT_PROVIDER_DETAIL_RENDERING.FULL_NAME AS RENDERING_PROVIDER_FULL_NAME,
SAT_PROVIDER_DETAIL_RENDERING.NATIONAL_PROVIDER_ID AS RENDERING_PROVIDER_NPI,
HUB_PROVIDER_ASSIGNED.PROVIDER_ID AS ASSIGNED_PROVIDER_ID,
SAT_PROVIDER_DETAIL_ASSIGNED.FULL_NAME AS ASSIGNED_PROVIDER_FULL_NAME,
SAT_PROVIDER_DETAIL_ASSIGNED.NATIONAL_PROVIDER_ID AS ASSIGNED_PROVIDER_NPI,
ADJUSTMENT_REASON.ADJUSTMENT_REASON_ARRAY,
NOT_COVERED_REASONS.NOT_COVERED_REASON_ARRAY,
-- This all authorization stuff needs moved out of here and claim info added to extract.auht_* views
HUB_CLAIM_AUTHORIZATION.HUB_CLAIM_AUTHORIZATION_HKEY,
HUB_CLAIM_AUTHORIZATION_DETAIL.HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY,
HUB_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR,  --SAT_CLAIM_LINE.AUTHORIZATION_NBR (will be come this when removed and add mc400upm),
HUB_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_LINE_NBR,
--------------------------------
SAT_CLAIM_LINE.BENEFIT_LEVEL_CODE,
IFF(SAT_CLAIM_LINE.BENEFIT_LEVEL_CODE IS NULL, NULL, IFNULL(REF_PLAN_BENEFIT_LEVEL.CODE_DESC, 'Description Not Found')) AS BENEFIT_LEVEL_DESC,
DEDUCTIBLE_REASON.REASON_CODE AS DEDUCTIBLE_REASON_CODE,
IFF(DEDUCTIBLE_REASON.REASON_CODE IS NULL, NULL, IFNULL(REF_CLAIM_PROCESSING_DEDUCTIBLE.CODE_DESC, 'Description Not Found')) AS DEDUCTIBLE_REASON_CODE_DESC,
DEDUCTIBLE_REASON.CODE_POSITION AS DEDUCTIBLE_REASON_CODE_POSITION,
SAT_CLAIM_LINE_AMOUNT.MEMBER_PAY_FLAG,
SAT_CLAIM_LINE.LOCATION_CODE,
IFF(SAT_CLAIM_LINE.LOCATION_CODE IS NULL, NULL, IFNULL(REF_CLAIM_LOCATION_TYPE.CODE_DESC,'Description Not Found')) AS LOCATION_DESC,
SAT_CLAIM_LINE.REVENUE_CODE,
IFNULL(REF_CLAIM_REVENUE_CODE.CODE_DESC, 'Description Not Found') AS REVENUE_CODE_DESC,
IFF(REF_CLAIM_REVENUE_CODE.CLAIM_REVENUE_CODE_HKEY IS NULL, 'Description Not Found', IFNULL(REF_CLAIM_REVENUE_CODE.CODE_DESC_LONG, 'Undefined')) AS REVENUE_CODE_DESC_LONG,
IFF(REF_CLAIM_REVENUE_CODE.CLAIM_REVENUE_CODE_HKEY IS NULL, 'Description Not Found', IFNULL(REF_CLAIM_REVENUE_CODE.CODE_SPANISH_DESC, 'Undefined')) AS REVENUE_CODE_SPANISH_DESC,
    NULL AS MEMBER_LIABILITY_AMT, --not in datahub yet
PROCEDURE_CATEGORY_CODES.PROCEDURE_CATEGORY_ARRAY,
SAT_CLAIM_LINE.TOOTH_SURFACE_ARRAY,
SAT_CLAIM_LINE.HCPCS_CODE,
IFNULL(REF_CLAIM_HCPCS.CODE_DESC, 'Description Not Found') AS HCPCS_CODE_DESC,
IFF(REF_CLAIM_HCPCS.CLAIM_PROCEDURE_HKEY IS NULL, 'Description Not Found', IFNULL(REF_CLAIM_HCPCS.CODE_DESC_LONG, 'Undefined')) AS HCPCS_CODE_DESC_LONG,
IFF(REF_CLAIM_HCPCS.CLAIM_PROCEDURE_HKEY IS NULL, 'Description Not Found', IFNULL(REF_CLAIM_HCPCS.CODE_SPANISH_DESC, 'Undefined')) AS HCPCS_CODE_SPANISH_DESC,
SAT_CLAIM_LINE.CMS_CURRENT_ITERATION_FLAG
FROM HUBDATA.HUB_CLAIM_DETAIL 

    JOIN HUBDATA.EFF_SAT_CLAIM_LINE
        ON(EFF_SAT_CLAIM_LINE.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
        AND EFF_SAT_CLAIM_LINE.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_CLAIM_LINE.DELETED_DATETIME > CURRENT_TIMESTAMP())

    JOIN HUBDATA.LNK_CLAIM_DETAIL
        ON (LNK_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
        AND LNK_CLAIM_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

    JOIN HUBDATA.HUB_CLAIM
        ON (HUB_CLAIM.HUB_CLAIM_HKEY = LNK_CLAIM_DETAIL.HUB_CLAIM_HKEY
        AND LNK_CLAIM_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

    JOIN HUBDATA.EFF_SAT_CLAIM_HEADER
        ON(EFF_SAT_CLAIM_HEADER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND EFF_SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_CLAIM_HEADER.DELETED_DATETIME > CURRENT_TIMESTAMP())
   
    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_MEMBERSHIP_GROUP
                    JOIN HUBDATA.EFF_SAT_MEMBERSHIP_GROUP
                        ON(EFF_SAT_MEMBERSHIP_GROUP.HUB_MEMBERSHIP_GROUP_HKEY = LNK_CLAIM_MEMBERSHIP_GROUP.HUB_MEMBERSHIP_GROUP_HKEY
                        AND EFF_SAT_MEMBERSHIP_GROUP.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_MEMBERSHIP_GROUP.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_MEMBERSHIP_GROUP.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_MEMBERSHIP_GROUP.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_MEMBER
                    JOIN HUBDATA.EFF_SAT_MEMBER
                        ON(EFF_SAT_MEMBER.HUB_MEMBER_HKEY = LNK_CLAIM_MEMBER.HUB_MEMBER_HKEY
                        AND EFF_SAT_MEMBER.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_MEMBER.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_MEMBER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_MEMBER.IS_CURRENT_ROW_FLAG = TRUE)
        
    LEFT OUTER JOIN HUBDATA.SAT_CLAIM_LINE_AMOUNT
        ON (HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = SAT_CLAIM_LINE_AMOUNT.HUB_CLAIM_DETAIL_HKEY
        AND SAT_CLAIM_LINE_AMOUNT.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_CLAIM_LINE
        ON (HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = SAT_CLAIM_LINE.HUB_CLAIM_DETAIL_HKEY
        AND SAT_CLAIM_LINE.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_CLAIM_HEADER 
        ON (HUB_CLAIM.HUB_CLAIM_HKEY = SAT_CLAIM_HEADER.HUB_CLAIM_HKEY
        AND SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE)

    --Adjustment Reason Codes
    LEFT OUTER JOIN (
            SELECT
            SAT_CLAIM_LINE_PROCESSING_REASON.HUB_CLAIM_DETAIL_HKEY
            ,ARRAY_UNIQUE_AGG(
                OBJECT_CONSTRUCT(
                    'code', SAT_CLAIM_LINE_PROCESSING_REASON.REASON_CODE,
                    'description', IFNULL(CLAIM_PROCESSING_REASON.CODE_DESC, 'Description Not Found')
                    )
            ) AS ADJUSTMENT_REASON_ARRAY
            FROM HUBDATA.SAT_CLAIM_LINE_PROCESSING_REASON
                JOIN HUBDATA.HUB_CLAIM_DETAIL
                    ON (HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = SAT_CLAIM_LINE_PROCESSING_REASON.HUB_CLAIM_DETAIL_HKEY)
                LEFT OUTER JOIN REFDATA.CLAIM_PROCESSING_REASON
                    ON (CLAIM_PROCESSING_REASON.TPA_CLIENT_ID = HUB_CLAIM_DETAIL.TPA_CLIENT_ID
                    AND CLAIM_PROCESSING_REASON.TPA_ID = HUB_CLAIM_DETAIL.TPA_ID
                    AND CLAIM_PROCESSING_REASON.TPA_DIV_ID = HUB_CLAIM_DETAIL.TPA_DIV_ID
                    AND CLAIM_PROCESSING_REASON.DATA_SOURCE_NAME = HUB_CLAIM_DETAIL.DATA_SOURCE_NAME
                    AND CLAIM_PROCESSING_REASON.CLAIM_PROCESSING_REASON_TYPE = SAT_CLAIM_LINE_PROCESSING_REASON.REASON_TYPE_CODE
                    AND CLAIM_PROCESSING_REASON.CODE = SAT_CLAIM_LINE_PROCESSING_REASON.REASON_CODE)
            WHERE SAT_CLAIM_LINE_PROCESSING_REASON.IS_CURRENT_ROW_FLAG = TRUE
            AND SAT_CLAIM_LINE_PROCESSING_REASON.REASON_TYPE_CODE = 'Adjustment'
            GROUP BY SAT_CLAIM_LINE_PROCESSING_REASON.HUB_CLAIM_DETAIL_HKEY
            ) AS ADJUSTMENT_REASON
        ON ADJUSTMENT_REASON.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY

    --Deductible Reason Code
    LEFT OUTER JOIN (
            SELECT SAT_CLAIM_LINE_PROCESSING_REASON.HUB_CLAIM_DETAIL_HKEY, REASON_CODE, REASON_TYPE_CODE, CODE_POSITION
            FROM HUBDATA.SAT_CLAIM_LINE_PROCESSING_REASON
            WHERE SAT_CLAIM_LINE_PROCESSING_REASON.IS_CURRENT_ROW_FLAG = TRUE
            AND SAT_CLAIM_LINE_PROCESSING_REASON.REASON_TYPE_CODE = 'Deductible'
            ) AS DEDUCTIBLE_REASON
        ON DEDUCTIBLE_REASON.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY

    --Deductible Reason Desc
    LEFT OUTER JOIN REFDATA.CLAIM_PROCESSING_REASON REF_CLAIM_PROCESSING_DEDUCTIBLE
        ON (REF_CLAIM_PROCESSING_DEDUCTIBLE.TPA_CLIENT_ID = HUB_CLAIM_DETAIL.TPA_CLIENT_ID
        AND REF_CLAIM_PROCESSING_DEDUCTIBLE.TPA_ID = HUB_CLAIM_DETAIL.TPA_ID
        AND REF_CLAIM_PROCESSING_DEDUCTIBLE.TPA_DIV_ID = HUB_CLAIM_DETAIL.TPA_DIV_ID
        AND REF_CLAIM_PROCESSING_DEDUCTIBLE.DATA_SOURCE_NAME = HUB_CLAIM_DETAIL.DATA_SOURCE_NAME
        AND REF_CLAIM_PROCESSING_DEDUCTIBLE.CLAIM_PROCESSING_REASON_TYPE = DEDUCTIBLE_REASON.REASON_TYPE_CODE
        AND REF_CLAIM_PROCESSING_DEDUCTIBLE.CODE = DEDUCTIBLE_REASON.REASON_CODE)

    --CoPay Reason Code
    LEFT OUTER JOIN (
            SELECT SAT_CLAIM_LINE_PROCESSING_REASON.HUB_CLAIM_DETAIL_HKEY, REASON_CODE, REASON_TYPE_CODE, CODE_POSITION
            FROM HUBDATA.SAT_CLAIM_LINE_PROCESSING_REASON         
            WHERE SAT_CLAIM_LINE_PROCESSING_REASON.IS_CURRENT_ROW_FLAG = TRUE
            AND SAT_CLAIM_LINE_PROCESSING_REASON.REASON_TYPE_CODE = 'CoPay'
            ) AS COPAY_REASON
        ON COPAY_REASON.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY

    --CoPay Reason Desc
    LEFT OUTER JOIN REFDATA.CLAIM_PROCESSING_REASON REF_CLAIM_PROCESSING_COPAY
        ON (REF_CLAIM_PROCESSING_COPAY.TPA_CLIENT_ID = HUB_CLAIM_DETAIL.TPA_CLIENT_ID
        AND REF_CLAIM_PROCESSING_COPAY.TPA_ID = HUB_CLAIM_DETAIL.TPA_ID
        AND REF_CLAIM_PROCESSING_COPAY.TPA_DIV_ID = HUB_CLAIM_DETAIL.TPA_DIV_ID
        AND REF_CLAIM_PROCESSING_COPAY.DATA_SOURCE_NAME = HUB_CLAIM_DETAIL.DATA_SOURCE_NAME
        AND REF_CLAIM_PROCESSING_COPAY.CLAIM_PROCESSING_REASON_TYPE = COPAY_REASON.REASON_TYPE_CODE
        AND REF_CLAIM_PROCESSING_COPAY.CODE = COPAY_REASON.REASON_CODE)

   --CoInsurance Reason Code
   LEFT OUTER JOIN (
            SELECT SAT_CLAIM_LINE_PROCESSING_REASON.HUB_CLAIM_DETAIL_HKEY, REASON_CODE, REASON_TYPE_CODE, CODE_POSITION
            FROM HUBDATA.SAT_CLAIM_LINE_PROCESSING_REASON
            WHERE SAT_CLAIM_LINE_PROCESSING_REASON.IS_CURRENT_ROW_FLAG = TRUE
            AND SAT_CLAIM_LINE_PROCESSING_REASON.REASON_TYPE_CODE = 'CoInsurance'
            ) AS COINSURANCE_REASON
        ON COINSURANCE_REASON.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY

    --CoInsurance Reason Desc
    LEFT OUTER JOIN REFDATA.CLAIM_PROCESSING_REASON REF_CLAIM_PROCESSING_COINSURANCE
        ON (REF_CLAIM_PROCESSING_COINSURANCE.TPA_CLIENT_ID = HUB_CLAIM_DETAIL.TPA_CLIENT_ID
        AND REF_CLAIM_PROCESSING_COINSURANCE.TPA_ID = HUB_CLAIM_DETAIL.TPA_ID
        AND REF_CLAIM_PROCESSING_COINSURANCE.TPA_DIV_ID = HUB_CLAIM_DETAIL.TPA_DIV_ID
        AND REF_CLAIM_PROCESSING_COINSURANCE.DATA_SOURCE_NAME = HUB_CLAIM_DETAIL.DATA_SOURCE_NAME
        AND REF_CLAIM_PROCESSING_COINSURANCE.CLAIM_PROCESSING_REASON_TYPE = COINSURANCE_REASON.REASON_TYPE_CODE
        AND REF_CLAIM_PROCESSING_COINSURANCE.CODE = COINSURANCE_REASON.REASON_CODE)

 --Service Reason Array
    LEFT OUTER JOIN (
            SELECT
            HUB_CLAIM_DETAIL_HKEY
            ,ARRAY_UNIQUE_AGG(
                OBJECT_CONSTRUCT(
                    'code', REASON_CODE,
                    'type', REASON_TYPE_CODE,
                    'description', CODE_DESC
                    )
            ) AS SERVICE_REASON_ARRAY
            FROM (
            
                    SELECT SAT_CLAIM_LINE_PROCESSING_REASON.HUB_CLAIM_DETAIL_HKEY,
                    SAT_CLAIM_LINE_PROCESSING_REASON.REASON_CODE,
                    SAT_CLAIM_LINE_PROCESSING_REASON.REASON_TYPE_CODE,
                    IFNULL(REF_CLAIM_PROCESSING_REASON.CODE_DESC, 'Description Not Found') AS CODE_DESC,
                    FROM HUBDATA.SAT_CLAIM_LINE_PROCESSING_REASON       
                        JOIN HUBDATA.LNK_CLAIM_DETAIL
                            ON (LNK_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = SAT_CLAIM_LINE_PROCESSING_REASON.HUB_CLAIM_DETAIL_HKEY
                            AND LNK_CLAIM_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
                        JOIN HUBDATA.HUB_CLAIM
                            ON (HUB_CLAIM.HUB_CLAIM_HKEY = LNK_CLAIM_DETAIL.HUB_CLAIM_HKEY)
                        JOIN HUBDATA.SAT_CLAIM_HEADER
                            ON (SAT_CLAIM_HEADER.HUB_CLAIM_HKEY = LNK_CLAIM_DETAIL.HUB_CLAIM_HKEY
                            AND SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE)
                        LEFT OUTER JOIN REFDATA.CLAIM_PROCESSING_REASON REF_CLAIM_PROCESSING_REASON
                            ON (REF_CLAIM_PROCESSING_REASON.TPA_CLIENT_ID = HUB_CLAIM.TPA_CLIENT_ID
                            AND REF_CLAIM_PROCESSING_REASON.TPA_ID = HUB_CLAIM.TPA_ID
                            AND REF_CLAIM_PROCESSING_REASON.TPA_DIV_ID = HUB_CLAIM.TPA_DIV_ID
                            AND REF_CLAIM_PROCESSING_REASON.DATA_SOURCE_NAME = HUB_CLAIM.DATA_SOURCE_NAME
                            AND REF_CLAIM_PROCESSING_REASON.CLAIM_PROCESSING_REASON_TYPE = SAT_CLAIM_LINE_PROCESSING_REASON.REASON_TYPE_CODE
                            AND REF_CLAIM_PROCESSING_REASON.CODE = SAT_CLAIM_LINE_PROCESSING_REASON.REASON_CODE)
                    WHERE SAT_CLAIM_LINE_PROCESSING_REASON.IS_CURRENT_ROW_FLAG = TRUE
                    AND SAT_CLAIM_LINE_PROCESSING_REASON.REASON_TYPE_CODE = 'Service'
                    ORDER BY REF_CLAIM_PROCESSING_REASON.CODE -- so that array order is consistent each time we query
                ) 
            GROUP BY HUB_CLAIM_DETAIL_HKEY
        ) SERVICE_REASONS
        ON SERVICE_REASONS.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY

    --Claim Procedure Desc
    LEFT OUTER JOIN REFDATA.CLAIM_PROCEDURE REF_CLAIM_PROCEDURE
        ON (REF_CLAIM_PROCEDURE.TPA_CLIENT_ID = HUB_CLAIM_DETAIL.TPA_CLIENT_ID
        AND REF_CLAIM_PROCEDURE.TPA_ID = HUB_CLAIM_DETAIL.TPA_ID
        AND REF_CLAIM_PROCEDURE.TPA_DIV_ID = HUB_CLAIM_DETAIL.TPA_DIV_ID
        AND REF_CLAIM_PROCEDURE.DATA_SOURCE_NAME = HUB_CLAIM_DETAIL.DATA_SOURCE_NAME
        AND REF_CLAIM_PROCEDURE.CODE = SAT_CLAIM_LINE.PROCEDURE_CODE)

    --Revenue Code Desc
    LEFT OUTER JOIN REFDATA.CLAIM_REVENUE_CODE REF_CLAIM_REVENUE_CODE
        ON (REF_CLAIM_REVENUE_CODE.CODE = SAT_CLAIM_LINE.REVENUE_CODE)

    --Claim HCPCS Desc
    LEFT OUTER JOIN REFDATA.CLAIM_PROCEDURE REF_CLAIM_HCPCS
        ON (REF_CLAIM_HCPCS.TPA_CLIENT_ID = HUB_CLAIM_DETAIL.TPA_CLIENT_ID
        AND REF_CLAIM_HCPCS.TPA_ID = HUB_CLAIM_DETAIL.TPA_ID
        AND REF_CLAIM_HCPCS.TPA_DIV_ID = HUB_CLAIM_DETAIL.TPA_DIV_ID
        AND REF_CLAIM_HCPCS.DATA_SOURCE_NAME = HUB_CLAIM_DETAIL.DATA_SOURCE_NAME
        AND REF_CLAIM_HCPCS.CODE = SAT_CLAIM_LINE.HCPCS_CODE)
    
    --Pay Status Desc
    LEFT OUTER JOIN REFDATA.CLAIM_PAY_STATUS REF_CLAIM_PAY_STATUS
        ON (REF_CLAIM_PAY_STATUS.CODE = SAT_CLAIM_LINE.PAY_STATUS_CODE)

    --Plan Benefit Level Desc
    LEFT OUTER JOIN REFDATA.PLAN_BENEFIT_LEVEL REF_PLAN_BENEFIT_LEVEL
        ON (REF_PLAN_BENEFIT_LEVEL.TPA_CLIENT_ID = HUB_CLAIM_DETAIL.TPA_CLIENT_ID
        AND REF_PLAN_BENEFIT_LEVEL.TPA_ID = HUB_CLAIM_DETAIL.TPA_ID
        AND REF_PLAN_BENEFIT_LEVEL.TPA_DIV_ID = HUB_CLAIM_DETAIL.TPA_DIV_ID
        AND REF_PLAN_BENEFIT_LEVEL.DATA_SOURCE_NAME = HUB_CLAIM_DETAIL.DATA_SOURCE_NAME
        AND REF_PLAN_BENEFIT_LEVEL.CODE = SAT_CLAIM_LINE.BENEFIT_LEVEL_CODE)

    --Location Type Decc
    LEFT OUTER JOIN REFDATA.CLAIM_LOCATION_TYPE REF_CLAIM_LOCATION_TYPE
        ON (REF_CLAIM_LOCATION_TYPE.CODE = SAT_CLAIM_LINE.LOCATION_CODE)
   
    --Service Type Desc
    LEFT OUTER JOIN REFDATA.CLAIM_SERVICE_TYPE REF_CLAIM_SERVICE_TYPE
        ON (REF_CLAIM_SERVICE_TYPE.CODE = SAT_CLAIM_LINE.SERVICE_TYPE_CODE)

    --Tooth Quadrant Desc
    LEFT OUTER JOIN REFDATA.CLAIM_QUAD_ARCH REF_TOOTH_QUADRANT
        ON (REF_TOOTH_QUADRANT.CODE = SAT_CLAIM_LINE.TOOTH_QUADRANT)

    --Tooth Arch Desc
    LEFT OUTER JOIN REFDATA.CLAIM_QUAD_ARCH REF_TOOTH_ARCH
        ON (REF_TOOTH_ARCH.CODE = SAT_CLAIM_LINE.TOOTH_ARCH)
    
    --Benefit Category Desc
    LEFT OUTER JOIN REFDATA.CLAIM_BENEFIT_CATEGORY REF_BENEFIT_CATEGORY
        ON (REF_BENEFIT_CATEGORY.TPA_CLIENT_ID = HUB_CLAIM_DETAIL.TPA_CLIENT_ID
        AND REF_BENEFIT_CATEGORY.TPA_ID = HUB_CLAIM_DETAIL.TPA_ID
        AND REF_BENEFIT_CATEGORY.TPA_DIV_ID = HUB_CLAIM_DETAIL.TPA_DIV_ID
        AND REF_BENEFIT_CATEGORY.DATA_SOURCE_NAME = HUB_CLAIM_DETAIL.DATA_SOURCE_NAME
        AND REF_BENEFIT_CATEGORY.PLAN_TYPE_CODE = SAT_CLAIM_HEADER.PLAN_TYPE_CODE
        AND REF_BENEFIT_CATEGORY.CODE = SAT_CLAIM_LINE.BENEFIT_CATEGORY_CODE)

    --Not Covered Reason Array
    LEFT OUTER JOIN (
            SELECT
            HUB_CLAIM_DETAIL_HKEY
            ,ARRAY_UNIQUE_AGG(
                OBJECT_CONSTRUCT(
                    'code', NOT_COVERED_REASON_CODE,
                    'type', NOT_COVERED_REASON_TYPE,
                    'description', CODE_DESC
                    )
            ) AS NOT_COVERED_REASON_ARRAY
            FROM ( 
                SELECT SAT_CLAIM_LINE_NOT_COVERED_REASON.HUB_CLAIM_DETAIL_HKEY,
                    SAT_CLAIM_LINE_NOT_COVERED_REASON.NOT_COVERED_REASON_CODE,
                    SAT_CLAIM_LINE_NOT_COVERED_REASON.NOT_COVERED_REASON_TYPE,
                    IFNULL(REF_CLAIM_NOT_COVERED_REASON.CODE_DESC, 'Description Not Found') AS CODE_DESC,
                    FROM HUBDATA.SAT_CLAIM_LINE_NOT_COVERED_REASON       
                        JOIN HUBDATA.LNK_CLAIM_DETAIL
                            ON (LNK_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = SAT_CLAIM_LINE_NOT_COVERED_REASON.HUB_CLAIM_DETAIL_HKEY
                            AND LNK_CLAIM_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
                        JOIN HUBDATA.HUB_CLAIM
                            ON (HUB_CLAIM.HUB_CLAIM_HKEY = LNK_CLAIM_DETAIL.HUB_CLAIM_HKEY)
                        JOIN HUBDATA.SAT_CLAIM_HEADER
                            ON (SAT_CLAIM_HEADER.HUB_CLAIM_HKEY = LNK_CLAIM_DETAIL.HUB_CLAIM_HKEY
                            AND SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE)
                        LEFT OUTER JOIN REFDATA.CLAIM_NOT_COVERED_REASON REF_CLAIM_NOT_COVERED_REASON
                            ON (REF_CLAIM_NOT_COVERED_REASON.TPA_CLIENT_ID = HUB_CLAIM.TPA_CLIENT_ID
                            AND REF_CLAIM_NOT_COVERED_REASON.TPA_ID = HUB_CLAIM.TPA_ID
                            AND REF_CLAIM_NOT_COVERED_REASON.TPA_DIV_ID = HUB_CLAIM.TPA_DIV_ID
                            AND REF_CLAIM_NOT_COVERED_REASON.DATA_SOURCE_NAME = HUB_CLAIM.DATA_SOURCE_NAME
                            AND REF_CLAIM_NOT_COVERED_REASON.LINE_OF_BUSINESS_CODE = SAT_CLAIM_HEADER.LINE_OF_BUSINESS_CODE
                            AND REF_CLAIM_NOT_COVERED_REASON.NOT_COVERED_REASON_TYPE = SAT_CLAIM_LINE_NOT_COVERED_REASON.NOT_COVERED_REASON_TYPE
                            AND REF_CLAIM_NOT_COVERED_REASON.CODE = SAT_CLAIM_LINE_NOT_COVERED_REASON.NOT_COVERED_REASON_CODE)
                    WHERE SAT_CLAIM_LINE_NOT_COVERED_REASON.IS_CURRENT_ROW_FLAG = TRUE
                    ORDER BY SAT_CLAIM_LINE_NOT_COVERED_REASON.HUB_CLAIM_DETAIL_HKEY, REF_CLAIM_NOT_COVERED_REASON.MEMBER_PAY_FLAG DESC, SAT_CLAIM_LINE_NOT_COVERED_REASON.NOT_COVERED_REASON_CODE
                    )
            GROUP BY HUB_CLAIM_DETAIL_HKEY) NOT_COVERED_REASONS
        ON NOT_COVERED_REASONS.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY

   --
    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_DETAIL_RENDERING_PROVIDER
                    JOIN HUBDATA.EFF_SAT_PROVIDER EFF_SAT_PROVIDER_RENDERING
                        ON(EFF_SAT_PROVIDER_RENDERING.HUB_PROVIDER_HKEY = LNK_CLAIM_DETAIL_RENDERING_PROVIDER.HUB_PROVIDER_HKEY
                        AND EFF_SAT_PROVIDER_RENDERING.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_PROVIDER_RENDERING.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_DETAIL_RENDERING_PROVIDER.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
        AND LNK_CLAIM_DETAIL_RENDERING_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.HUB_PROVIDER HUB_PROVIDER_RENDERING
        ON (HUB_PROVIDER_RENDERING.HUB_PROVIDER_HKEY = LNK_CLAIM_DETAIL_RENDERING_PROVIDER.HUB_PROVIDER_HKEY
        AND LNK_CLAIM_DETAIL_RENDERING_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_PROVIDER_DETAIL AS SAT_PROVIDER_DETAIL_RENDERING
        ON (HUB_PROVIDER_RENDERING.HUB_PROVIDER_HKEY = SAT_PROVIDER_DETAIL_RENDERING.HUB_PROVIDER_HKEY
        AND SAT_PROVIDER_DETAIL_RENDERING.IS_CURRENT_ROW_FLAG = TRUE)
    
    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_ASSIGNED_PROVIDER
                    JOIN HUBDATA.EFF_SAT_PROVIDER EFF_SAT_PROVIDER_ASSIGNED
                        ON(EFF_SAT_PROVIDER_ASSIGNED.HUB_PROVIDER_HKEY = LNK_CLAIM_ASSIGNED_PROVIDER.HUB_PROVIDER_HKEY
                        AND EFF_SAT_PROVIDER_ASSIGNED.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_PROVIDER_ASSIGNED.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_ASSIGNED_PROVIDER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_ASSIGNED_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.HUB_PROVIDER HUB_PROVIDER_ASSIGNED
        ON (HUB_PROVIDER_ASSIGNED.HUB_PROVIDER_HKEY = LNK_CLAIM_ASSIGNED_PROVIDER.HUB_PROVIDER_HKEY
        AND LNK_CLAIM_ASSIGNED_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_PROVIDER_DETAIL AS SAT_PROVIDER_DETAIL_ASSIGNED
        ON (HUB_PROVIDER_ASSIGNED.HUB_PROVIDER_HKEY = SAT_PROVIDER_DETAIL_ASSIGNED.HUB_PROVIDER_HKEY
        AND SAT_PROVIDER_DETAIL_ASSIGNED.IS_CURRENT_ROW_FLAG = TRUE)

    -- Procedure Modifier Codes
    LEFT OUTER JOIN (
            SELECT HUB_CLAIM_DETAIL_HKEY, PROCEDURE_MODIFIER_01, PROCEDURE_MODIFIER_02, PROCEDURE_MODIFIER_03, PROCEDURE_MODIFIER_04
            FROM (SELECT SAT_CLAIM_LINE_PROCEDURE_MODIFIER.HUB_CLAIM_DETAIL_HKEY, SAT_CLAIM_LINE_PROCEDURE_MODIFIER.MODIFIER_CODE, SAT_CLAIM_LINE_PROCEDURE_MODIFIER.CODE_POSITION
                    FROM HUBDATA.SAT_CLAIM_LINE_PROCEDURE_MODIFIER
                    WHERE SAT_CLAIM_LINE_PROCEDURE_MODIFIER.IS_CURRENT_ROW_FLAG = TRUE
                    ) SAT_CLAIM_LINE_PROCEDURE_MODIFIER
                PIVOT(MAX(MODIFIER_CODE) FOR CODE_POSITION IN (1,2,3,4)
                ) AS T1 (HUB_CLAIM_DETAIL_HKEY, PROCEDURE_MODIFIER_01, PROCEDURE_MODIFIER_02, PROCEDURE_MODIFIER_03, PROCEDURE_MODIFIER_04)
            ) PROCEDURE_MODIFIER_CODES
        ON (PROCEDURE_MODIFIER_CODES.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY)

    -- Procedure Modifier Desc
    LEFT OUTER JOIN (
            SELECT HUB_CLAIM_DETAIL_HKEY, PROCEDURE_MODIFIER_01_DESC, PROCEDURE_MODIFIER_02_DESC, PROCEDURE_MODIFIER_03_DESC, PROCEDURE_MODIFIER_04_DESC
            FROM (SELECT SAT_CLAIM_LINE_PROCEDURE_MODIFIER.HUB_CLAIM_DETAIL_HKEY
                    ,IFNULL(CLAIM_PROCEDURE_MODIFIER.CODE_DESC,'Description Not Found') AS CODE_DESC
                    ,SAT_CLAIM_LINE_PROCEDURE_MODIFIER.CODE_POSITION
                    FROM HUBDATA.SAT_CLAIM_LINE_PROCEDURE_MODIFIER
                        JOIN HUBDATA.HUB_CLAIM_DETAIL
                            ON (HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = SAT_CLAIM_LINE_PROCEDURE_MODIFIER.HUB_CLAIM_DETAIL_HKEY)
                        LEFT OUTER JOIN REFDATA.CLAIM_PROCEDURE_MODIFIER
                            ON (CLAIM_PROCEDURE_MODIFIER.TPA_CLIENT_ID = HUB_CLAIM_DETAIL.TPA_CLIENT_ID
                            AND CLAIM_PROCEDURE_MODIFIER.TPA_ID = HUB_CLAIM_DETAIL.TPA_ID
                            AND CLAIM_PROCEDURE_MODIFIER.TPA_DIV_ID = HUB_CLAIM_DETAIL.TPA_DIV_ID
                            AND CLAIM_PROCEDURE_MODIFIER.DATA_SOURCE_NAME = HUB_CLAIM_DETAIL.DATA_SOURCE_NAME
                            AND CLAIM_PROCEDURE_MODIFIER.CODE = SAT_CLAIM_LINE_PROCEDURE_MODIFIER.MODIFIER_CODE)
                    WHERE SAT_CLAIM_LINE_PROCEDURE_MODIFIER.IS_CURRENT_ROW_FLAG = TRUE
                    ) SAT_CLAIM_LINE_PROCEDURE_MODIFIER
                PIVOT(MAX(CODE_DESC) FOR CODE_POSITION IN (1,2,3,4)
                ) AS T1 (HUB_CLAIM_DETAIL_HKEY, PROCEDURE_MODIFIER_01_DESC, PROCEDURE_MODIFIER_02_DESC, PROCEDURE_MODIFIER_03_DESC, PROCEDURE_MODIFIER_04_DESC)
            ) PROCEDURE_MODIFIER_CODES_DESC
        ON (PROCEDURE_MODIFIER_CODES_DESC.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY)

    --Procedure Category Array
    LEFT OUTER JOIN (
            SELECT
            PROCEDURE_CATEGORY.HUB_CLAIM_DETAIL_HKEY
            ,ARRAY_UNIQUE_AGG(
                OBJECT_CONSTRUCT(
                    'code', PROCEDURE_CATEGORY.CATEGORY_CODE,
                    'description', IFNULL(CLAIM_PROCEDURE_CATEGORY.CODE_DESC, 'Description Not Found')
                    )
            ) AS PROCEDURE_CATEGORY_ARRAY
            FROM (SELECT SAT_CLAIM_LINE_PROCEDURE_CATEGORY.HUB_CLAIM_DETAIL_HKEY, PROCEDURE_CATEGORY.VALUE::varchar AS CATEGORY_CODE
                    FROM HUBDATA.SAT_CLAIM_LINE_PROCEDURE_CATEGORY
                        ,TABLE(FLATTEN(input => SAT_CLAIM_LINE_PROCEDURE_CATEGORY.PROCEDURE_CATEGORY_ARRAY, MODE=>'ARRAY')) PROCEDURE_CATEGORY
                    WHERE SAT_CLAIM_LINE_PROCEDURE_CATEGORY.IS_CURRENT_ROW_FLAG = TRUE
                    ) PROCEDURE_CATEGORY
                JOIN HUBDATA.HUB_CLAIM_DETAIL
                    ON (HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = PROCEDURE_CATEGORY.HUB_CLAIM_DETAIL_HKEY)
                
                LEFT OUTER JOIN REFDATA.CLAIM_PROCEDURE_CATEGORY
                    ON (CLAIM_PROCEDURE_CATEGORY.TPA_CLIENT_ID = HUB_CLAIM_DETAIL.TPA_CLIENT_ID
                    AND CLAIM_PROCEDURE_CATEGORY.TPA_ID = HUB_CLAIM_DETAIL.TPA_ID
                    AND CLAIM_PROCEDURE_CATEGORY.TPA_DIV_ID = HUB_CLAIM_DETAIL.TPA_DIV_ID
                    AND CLAIM_PROCEDURE_CATEGORY.DATA_SOURCE_NAME = HUB_CLAIM_DETAIL.DATA_SOURCE_NAME
                    AND CLAIM_PROCEDURE_CATEGORY.CODE = PROCEDURE_CATEGORY.CATEGORY_CODE)
            GROUP BY PROCEDURE_CATEGORY.HUB_CLAIM_DETAIL_HKEY 
            ) AS PROCEDURE_CATEGORY_CODES
        ON PROCEDURE_CATEGORY_CODES.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_AUTHORIZATION_DETAIL_CLAIM_DETAIL
                    JOIN HUBDATA.EFF_SAT_CLAIM_AUTHORIZATION_DETAIL
                        ON(EFF_SAT_CLAIM_AUTHORIZATION_DETAIL.HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY = LNK_CLAIM_AUTHORIZATION_DETAIL_CLAIM_DETAIL.HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY
                        AND EFF_SAT_CLAIM_AUTHORIZATION_DETAIL.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_CLAIM_AUTHORIZATION_DETAIL.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_AUTHORIZATION_DETAIL_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
        AND LNK_CLAIM_AUTHORIZATION_DETAIL_CLAIM_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
    
    LEFT OUTER JOIN HUBDATA.HUB_CLAIM_AUTHORIZATION_DETAIL
        ON (HUB_CLAIM_AUTHORIZATION_DETAIL.HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY = LNK_CLAIM_AUTHORIZATION_DETAIL_CLAIM_DETAIL.HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY
        AND LNK_CLAIM_AUTHORIZATION_DETAIL_CLAIM_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_AUTHORIZATION_DETAIL
                    JOIN HUBDATA.EFF_SAT_CLAIM_AUTHORIZATION
                        ON(EFF_SAT_CLAIM_AUTHORIZATION.HUB_CLAIM_AUTHORIZATION_HKEY = LNK_CLAIM_AUTHORIZATION_DETAIL.HUB_CLAIM_AUTHORIZATION_HKEY
                        AND EFF_SAT_CLAIM_AUTHORIZATION.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_CLAIM_AUTHORIZATION.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_AUTHORIZATION_DETAIL.HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY = HUB_CLAIM_AUTHORIZATION_DETAIL.HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY
        AND LNK_CLAIM_AUTHORIZATION_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
    
    LEFT OUTER JOIN HUBDATA.HUB_CLAIM_AUTHORIZATION
        ON (HUB_CLAIM_AUTHORIZATION.HUB_CLAIM_AUTHORIZATION_HKEY = LNK_CLAIM_AUTHORIZATION_DETAIL.HUB_CLAIM_AUTHORIZATION_HKEY
        AND LNK_CLAIM_AUTHORIZATION_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
WHERE SAT_CLAIM_HEADER.CARE_TYPE_NAME <> 'pharmacy'
