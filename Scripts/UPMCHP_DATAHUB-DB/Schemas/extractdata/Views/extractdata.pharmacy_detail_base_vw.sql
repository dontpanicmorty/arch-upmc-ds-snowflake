CREATE OR REPLACE VIEW EXTRACTDATA.PHARMACY_DETAIL_BASE_VW
AS
SELECT DISTINCT
HUB_PROVIDER.HUB_PROVIDER_HKEY
,HUB_OFFICE.HUB_OFFICE_HKEY
,HUB_PROVIDER.TPA_CLIENT_ID
,HUB_PROVIDER.TPA_ID
,HUB_PROVIDER.TPA_DIV_ID
,HUB_PROVIDER.DATA_SOURCE_NAME
,HUB_PROVIDER.PROVIDER_ID
,HUB_OFFICE.OFFICE_ID
,SAT_PROVIDER_DETAIL.FULL_NAME AS PHARMACY_NAME
,SAT_PROVIDER_DETAIL.PROVIDER_TYPE_NAME
,0 ADDRESS_TYPE_CODE
,'Unknown' AS ADDRESS_TYPE_DESC
,SAT_OFFICE_ADDRESS.ADDRESS_LINE_1
,IFNULL(SAT_OFFICE_ADDRESS.ADDRESS_LINE_2,'') AS ADDRESS_LINE_2
,SAT_OFFICE_ADDRESS.CITY_NAME AS ADDRESS_CITY
,SAT_OFFICE_ADDRESS.STATE_ABBREV_NAME AS ADDRESS_STATE_ABBREV_NAME
,SAT_OFFICE_ADDRESS.ZIP_CODE AS ADDRESS_ZIP_CODE
,SAT_OFFICE_ADDRESS.STATE_FULL_NAME AS ADDRESS_STATE_FULL_NAME
,'Unknown' AS ADDRESS_COUNTY_NAME
,SAT_OFFICE_ADDRESS.COUNTRY_NAME AS ADDRESS_COUNTRY_NAME
,CONCAT(ADDRESS_LINE_1, IFF(ADDRESS_LINE_2 <> '', ', ', ''), IFNULL(ADDRESS_LINE_2,''), ', ', ADDRESS_CITY, ', ', IFF(ADDRESS_STATE_ABBREV_NAME <> 'Unknown', ADDRESS_STATE_ABBREV_NAME, ''), ' ', ADDRESS_ZIP_CODE, ' ', IFF(ADDRESS_COUNTRY_NAME = 'United States', 'USA', 'Unknown')) AS FULL_ADDRESS_FORMATTED
,'Unknown' AS ADDRESS_COUNTRY_ISO2
,'Unknown' AS ADDRESS_COUNTRY_ISO3
,NULL AS ADDRESS_LATITUDE_NBR
,NULL AS ADDRESS_LONGITUDE_NBR
,'Unknown' AS OFFICE_MANAGER_NAME
,'Unknown' AS HANDICAP_ACCESS_IND
,'Unknown' AS TELE_HEALTH_IND
,'Unknown' AS RECEIVES_MAIL_IND
,'Unknown' AS E_PRESCRIBE_IND
,'Unknown' AS MA_SUPER_PCP_IND
,'Unknown' AS EMR_SYSTEM_NAME
,SAT_OFFICE_DETAIL.PRIMARY_PHONE_NBR
,IFNULL(SAT_OFFICE_DETAIL.PRIMARY_PHONE_EXTENSION_NBR, 'Unknown') AS PRIMARY_PHONE_EXTENSION_NBR
,CASE
    WHEN LEN(SAT_OFFICE_DETAIL.PRIMARY_PHONE_NBR) = 10 THEN CONCAT('+1 ', SUBSTR(SAT_OFFICE_DETAIL.PRIMARY_PHONE_NBR, 1, 3), '-', SUBSTR(SAT_OFFICE_DETAIL.PRIMARY_PHONE_NBR, 4, 3), '-', SUBSTR(SAT_OFFICE_DETAIL.PRIMARY_PHONE_NBR, 7, 4))
    WHEN LEN(SAT_OFFICE_DETAIL.PRIMARY_PHONE_NBR) = 11 AND LEFT(SAT_OFFICE_DETAIL.PRIMARY_PHONE_NBR, 1) = '1' THEN CONCAT('+1 ', SUBSTR(SAT_OFFICE_DETAIL.PRIMARY_PHONE_NBR, 2, 3), '-', SUBSTR(SAT_OFFICE_DETAIL.PRIMARY_PHONE_NBR, 5, 3), '-', SUBSTR(SAT_OFFICE_DETAIL.PRIMARY_PHONE_NBR, 8, 4))
    ELSE 'Unknown'
END AS PRIMARY_PHONE_NBR_FORMATTED
,IFNULL(SAT_OFFICE_DETAIL.ALTERNATE_PHONE_NBR, 'Unknown') AS ALTERNATE_PHONE_NBR
,IFNULL(SAT_OFFICE_DETAIL.ALTERNATE_PHONE_EXTENSION_NBR, 'Unknown') AS ALTERNATE_PHONE_EXTENSION_NBR
,CASE
    WHEN LEN(SAT_OFFICE_DETAIL.ALTERNATE_PHONE_NBR) = 10 THEN CONCAT('+1 ', SUBSTR(SAT_OFFICE_DETAIL.ALTERNATE_PHONE_NBR, 1, 3), '-', SUBSTR(SAT_OFFICE_DETAIL.ALTERNATE_PHONE_NBR, 4, 3), '-', SUBSTR(SAT_OFFICE_DETAIL.ALTERNATE_PHONE_NBR, 7, 4))
    WHEN LEN(SAT_OFFICE_DETAIL.ALTERNATE_PHONE_NBR) = 11 AND LEFT(SAT_OFFICE_DETAIL.ALTERNATE_PHONE_NBR, 1) = '1' THEN CONCAT('+1 ', SUBSTR(SAT_OFFICE_DETAIL.ALTERNATE_PHONE_NBR, 2, 3), '-', SUBSTR(SAT_OFFICE_DETAIL.ALTERNATE_PHONE_NBR, 5, 3), '-', SUBSTR(SAT_OFFICE_DETAIL.ALTERNATE_PHONE_NBR, 8, 4))
    ELSE 'Unknown'
END AS ALTERNATE_PHONE_NBR_FORMATTED
,IFNULL(SAT_OFFICE_DETAIL.PRIMARY_FAX_NBR, 'Unknown') AS FAX_NBR
,CASE
    WHEN LEN(SAT_OFFICE_DETAIL.PRIMARY_FAX_NBR) = 10 THEN CONCAT('+1 ', SUBSTR(SAT_OFFICE_DETAIL.PRIMARY_FAX_NBR, 1, 3), '-', SUBSTR(SAT_OFFICE_DETAIL.PRIMARY_FAX_NBR, 4, 3), '-', SUBSTR(SAT_OFFICE_DETAIL.PRIMARY_FAX_NBR, 7, 4))
    WHEN LEN(SAT_OFFICE_DETAIL.PRIMARY_FAX_NBR) = 11 AND LEFT(SAT_OFFICE_DETAIL.PRIMARY_FAX_NBR, 1) = '1' THEN CONCAT('+1 ', SUBSTR(SAT_OFFICE_DETAIL.PRIMARY_FAX_NBR, 2, 3), '-', SUBSTR(SAT_OFFICE_DETAIL.PRIMARY_FAX_NBR, 5, 3), '-', SUBSTR(SAT_OFFICE_DETAIL.PRIMARY_FAX_NBR, 8, 4))
    ELSE 'Unknown'
END AS FAX_NBR_FORMATTED
,'Unknown' AS INTERNATIONAL_PHONE_CODE
,IFNULL(SAT_OFFICE_DETAIL.EMAIL_ADDRESS, 'Unknown') AS EMAIL_ADDRESS_TEXT
,PROVIDER_IDENTIFIER.PROVIDER_IDENTIFIER_ARRAY AS PHARMACY_IDENTIFIER_ARRAY
,SAT_PROVIDER_DETAIL.FIRST_NAME
,SAT_PROVIDER_DETAIL.LAST_NAME
,SAT_PROVIDER_DETAIL.MIDDLE_NAME
,SAT_PROVIDER_DETAIL.MIDDLE_INITIAL_NAME
,SAT_PROVIDER_DETAIL.SUFFIX_NAME
,SAT_PROVIDER_DETAIL.GENDER_NAME
,CASE UPPER(SAT_PROVIDER_DETAIL.GENDER_NAME)
    WHEN 'MALE' THEN 'M'
    WHEN 'FEMALE' THEN 'F'
    WHEN 'UNKNOWN' THEN 'U'
    ELSE NULL
END AS GENDER_CODE
,SAT_PROVIDER_DETAIL.SOCIAL_SECURITY_NBR
,NULL AS TAX_ID_NBR
,SAT_PROVIDER_DETAIL.EMAIL_ADDRESS
,SAT_PROVIDER_DETAIL.DEGREE_TEXT
,SAT_PROVIDER_DETAIL.LOCUM_TENENS_IND
,SAT_PROVIDER_DETAIL.INVISIBLE_PROVIDER_IND
,SAT_PROVIDER_DETAIL.TEMPORARY_PROVIDER_IND
,SAT_PROVIDER_DETAIL.NATIONAL_PROVIDER_ID
,SAT_PROVIDER_DETAIL.DATE_OF_BIRTH
,NULL AS UPIN_NBR --needed for dim_provider will happen when move providerODS
,NULL AS WEBSITE_URL --needed for dim_provider will happen when move providerODS
,SAT_PROVIDER_DETAIL.PRIMARY_SPECIALTY_NAME  --needed for dim_provider will happen when move providerODS
,TO_NUMBER(NULL) AS PRIMARY_PHO_CODE --needed for dim_provider will happen when move providerODS
,NULL AS PRIMARY_PHO_NAME --needed for dim_provider will happen when move providerODS
,TO_DATE(NULL) AS PRIMARY_PHO_TERMINATION_DATE --needed for dim_provider will happen when move providerODS
,TO_NUMBER(NULL) AS SECONDARY_PHO_CODE --needed for dim_provider will happen when move providerODS
,NULL AS SECONDARY_PHO_NAME --needed for dim_provider will happen when move providerODS
,TO_DATE(NULL) AS SECONDARY_PHO_TERMINATION_DATE --needed for dim_provider will happen when move providerODS
,TO_NUMBER(NULL) AS TERTIARY_PHO_CODE --needed for dim_provider will happen when move providerODS
,NULL AS TERTIARY_PHO_NAME --needed for dim_provider will happen when move providerODS
,TO_DATE(NULL) AS TERTIARY_PHO_TERMINATION_DATE --needed for dim_provider will happen when move providerODS
,TO_DATE('1900-01-01') AS PROVIDER_START_DATE --default for now
,'Y' AS ACTIVE_IND  --default for now
,NULL AS PA_MEDICAID_IND --needed for dim_provider will happen when move providerODS
,NULL AS PP_ACA_ENHANCED_PAY_IND --needed for dim_provider will happen when move providerODS
,NULL AS MALPRACTICE_COVERAGE_IND --needed for dim_provider will happen when move providerODS
,TO_NUMBER(NULL) AS OWNERSHIP_STATUS_CODE --needed for dim_provider will happen when move providerODS
,NULL AS OWNERSHIP_STATUS_DESC --needed for dim_provider will happen when move providerODS
,NULL AS URI

FROM HUBDATA.HUB_CLAIM

    JOIN HUBDATA.EFF_SAT_CLAIM_HEADER
        ON(EFF_SAT_CLAIM_HEADER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND EFF_SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_CLAIM_HEADER.DELETED_DATETIME > CURRENT_TIMESTAMP())

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_DETAIL
                    JOIN HUBDATA.EFF_SAT_CLAIM_LINE
                        ON(EFF_SAT_CLAIM_LINE.HUB_CLAIM_DETAIL_HKEY = LNK_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
                        AND EFF_SAT_CLAIM_LINE.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_CLAIM_LINE.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_DETAIL.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.HUB_CLAIM_DETAIL
        ON (HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = LNK_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
        AND LNK_CLAIM_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
        
    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_OFFICE
                    JOIN HUBDATA.EFF_SAT_OFFICE
                        ON(EFF_SAT_OFFICE.HUB_OFFICE_HKEY = LNK_CLAIM_OFFICE.HUB_OFFICE_HKEY
                        AND EFF_SAT_OFFICE.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_OFFICE.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_OFFICE.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_OFFICE.IS_CURRENT_ROW_FLAG = TRUE)
    
    LEFT OUTER JOIN HUBDATA.HUB_OFFICE
        ON (LNK_CLAIM_OFFICE.HUB_OFFICE_HKEY = HUB_OFFICE.HUB_OFFICE_HKEY)

    LEFT OUTER JOIN HUBDATA.SAT_OFFICE_DETAIL
        ON (LNK_CLAIM_OFFICE.HUB_OFFICE_HKEY = SAT_OFFICE_DETAIL.HUB_OFFICE_HKEY
        AND SAT_OFFICE_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_OFFICE_ADDRESS
        ON (LNK_CLAIM_OFFICE.HUB_OFFICE_HKEY = SAT_OFFICE_ADDRESS.HUB_OFFICE_HKEY
        AND SAT_OFFICE_ADDRESS.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_DETAIL_PHARMACY
                    JOIN HUBDATA.EFF_SAT_PROVIDER
                        ON(EFF_SAT_PROVIDER.HUB_PROVIDER_HKEY = LNK_CLAIM_DETAIL_PHARMACY.HUB_PROVIDER_HKEY
                        AND EFF_SAT_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_PROVIDER.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_DETAIL_PHARMACY.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
        AND LNK_CLAIM_DETAIL_PHARMACY.IS_CURRENT_ROW_FLAG = TRUE)
    
    LEFT OUTER JOIN HUBDATA.HUB_PROVIDER
        ON (LNK_CLAIM_DETAIL_PHARMACY.HUB_PROVIDER_HKEY = HUB_PROVIDER.HUB_PROVIDER_HKEY)

    LEFT OUTER JOIN HUBDATA.SAT_PROVIDER_DETAIL
        ON (LNK_CLAIM_DETAIL_PHARMACY.HUB_PROVIDER_HKEY = SAT_PROVIDER_DETAIL.HUB_PROVIDER_HKEY
        AND SAT_PROVIDER_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN (SELECT
                    SAT_PROVIDER_IDENTIFIER.HUB_PROVIDER_HKEY
                    ,ARRAY_AGG(DISTINCT OBJECT_CONSTRUCT
                            ('identifierName', SAT_PROVIDER_IDENTIFIER.IDENTIFIER_NAME,
                             'identifierSubtype', SAT_PROVIDER_IDENTIFIER.IDENTIFIER_SUBTYPE,
                              'identifierNbr', SAT_PROVIDER_IDENTIFIER.IDENTIFIER_NBR))
                    WITHIN GROUP (ORDER BY OBJECT_CONSTRUCT
                            ('identifierName', SAT_PROVIDER_IDENTIFIER.IDENTIFIER_NAME,
                             'identifierSubtype', SAT_PROVIDER_IDENTIFIER.IDENTIFIER_SUBTYPE,
                              'identifierNbr', SAT_PROVIDER_IDENTIFIER.IDENTIFIER_NBR)) AS PROVIDER_IDENTIFIER_ARRAY
                    FROM HUBDATA.SAT_PROVIDER_IDENTIFIER
                    WHERE IS_CURRENT_ROW_FLAG = TRUE
                    GROUP BY SAT_PROVIDER_IDENTIFIER.HUB_PROVIDER_HKEY
                    ) PROVIDER_IDENTIFIER
        ON (PROVIDER_IDENTIFIER.HUB_PROVIDER_HKEY = HUB_PROVIDER.HUB_PROVIDER_HKEY)

WHERE HUB_CLAIM.DATA_SOURCE_NAME = 'ESI'
AND SAT_PROVIDER_DETAIL.PROVIDER_TYPE_NAME = 'Pharmacy'
;