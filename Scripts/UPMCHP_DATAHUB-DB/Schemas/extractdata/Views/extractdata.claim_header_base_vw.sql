CREATE OR REPLACE VIEW EXTRACTDATA.CLAIM_HEADER_BASE_VW
COMMENT = 'LEFT OUTER JOINs core tables from hubdata data vault model for common claim header consumption'
AS
SELECT
HUB_CLAIM.HUB_CLAIM_HKEY,
HUB_CLAIM.TPA_CLIENT_ID,
HUB_CLAIM.TPA_ID,
HUB_CLAIM.TPA_DIV_ID,
HUB_CLAIM.DATA_SOURCE_NAME,
HUB_CLAIM.CLAIM_NBR,
HUB_CLAIM.INSERT_DATETIME AS HUB_INSERT_DATETIME,
LNK_CLAIM_BILLING_PROVIDER.MG_MEDICAL_GROUP_ID,
HUB_MEMBER.HUB_MEMBER_HKEY,
HUB_MEMBER.MEMBER_NBR,
LEFT(HUB_MEMBER.MEMBER_NBR,9) AS SUBSCRIBER_ID,
RIGHT(HUB_MEMBER.MEMBER_NBR,2) AS PERSON_ID,
LNK_CLAIM_MEMBERSHIP_GROUP.MG_GROUP_NBR AS GROUP_NBR,
LNK_CLAIM_MEMBERSHIP_GROUP.MG_SUB_GROUP_NBR AS SUB_GROUP_NBR,
SAT_PLAN_DETAIL.PLAN_DESC AS PLAN_DESC,
NULL AS PLAN_TYPE_DESC,
--SAT_PLAN_DETAIL.PLAN_TYPE_DESC AS PLAN_TYPE_DESC,  NEEDS ADDED BACK IN AFTER REFDATA TABLE
RIDER_CODES.RIDER_CODE_ARRAY AS RIDER_CODES,
SAT_MEMBERSHIP_GROUP_DETAIL.GROUP_NAME,
SAT_MEMBERSHIP_GROUP_DETAIL.SUB_GROUP_NAME,
SAT_CLAIM_HEADER.CLAIM_ENTRY_DATE,
SAT_CLAIM_HEADER.LINE_OF_BUSINESS_CODE,
SAT_CLAIM_HEADER.PLAN_CODE,
SAT_CLAIM_HEADER.PLAN_TYPE_CODE,
SAT_CLAIM_HEADER.BILLING_PROVIDER_PARTICIPATING_STATUS_CODE,
SAT_CLAIM_HEADER.ADMITTED_FLAG,
SAT_CLAIM_HEADER.ADMITTED_DATE,
SAT_CLAIM_HEADER.ADMITTED_HOUR,
SAT_CLAIM_HEADER.ADMISSION_SOURCE_CODE,
IFF(SAT_CLAIM_HEADER.ADMISSION_SOURCE_CODE IS NULL, NULL, IFNULL(REF_CLAIM_ADMISSION_SOURCE.CODE_DESC,'Description Not Found')) AS ADMISSION_SOURCE_DESC,
SAT_CLAIM_HEADER.ADMISSION_TYPE_CODE,
IFF(SAT_CLAIM_HEADER.ADMISSION_TYPE_CODE IS NULL, NULL, IFNULL(REF_CLAIM_ADMISSION_TYPE.CODE_DESC,'Description Not Found')) AS ADMISSION_TYPE_DESC,
SAT_CLAIM_HEADER.DISCHARGE_DATE,
SAT_CLAIM_HEADER.DISCHARGE_HOUR,
SAT_CLAIM_HEADER.DISCHARGE_STATUS_CODE,
IFF(SAT_CLAIM_HEADER.DISCHARGE_STATUS_CODE IS NULL, NULL, IFNULL(REF_CLAIM_DISCHARGE_STATUS.CODE_DESC,'Description Not Found')) AS DISCHARGE_STATUS_DESC,
SAT_CLAIM_HEADER.BILLING_TYPE_CODE,
IFF(SAT_CLAIM_HEADER.BILLING_TYPE_CODE IS NULL, NULL, IFNULL(REF_CLAIM_BILLING_TYPE.CODE_DESC,'Description Not Found')) AS BILLING_TYPE_DESC,
SAT_CLAIM_HEADER.CALCULATED_BILL_TOTAL_AMT,
SAT_CLAIM_HEADER.CARE_TYPE_NAME,
SAT_CLAIM_HEADER.DIVISION_NUMBER,
SAT_CLAIM_HEADER.ELECTRONIC_CLAIM_TYPE_CODE,
IFF(SAT_CLAIM_HEADER.ELECTRONIC_CLAIM_TYPE_CODE IS NULL, NULL, IFNULL(REF_CLAIM_ELECTRONIC_TYPE.CODE_DESC,'Description Not Found')) AS ELECTRONIC_CLAIM_TYPE_DESC,
SAT_CLAIM_HEADER.ENCOUNTER_REASON_CODE,
SAT_CLAIM_HEADER.FORM_NUMBER AS FORM_NBR,
SAT_CLAIM_HEADER.IS_PROCESSING_COMPLETE,
SAT_CLAIM_HEADER.MICROFILM_NBR,
SAT_CLAIM_HEADER.PLACE_OF_SERVICE_CODE,
IFF(SAT_CLAIM_HEADER.PLACE_OF_SERVICE_CODE IS NULL, NULL, IFNULL(REF_CLAIM_PLACE_OF_SERVICE.CODE_DESC,'Description Not Found')) AS PLACE_OF_SERVICE_DESC,
SAT_CLAIM_HEADER.PRICING_ZIP_SOURCE, 
SAT_CLAIM_HEADER.PATIENT_ACCOUNT_NUMBER,
SAT_CLAIM_HEADER.SHOCK_CLAIM_IND,
SAT_CLAIM_HEADER.SOURCE_LAST_UPDATED_DATETIME,
SAT_CLAIM_HEADER.IS_PREDETERMINATION_CLAIM_FLAG,
SAT_CLAIM_HEADER.ORIGINAL_CLAIM_ID,
SAT_CLAIM_HEADER.MULTISOURCE_CLAIM_IND,
BILLING_PROVIDER.MEDICAL_GROUP_ID AS BILLING_PROVIDER_ID,
BILLING_PROVIDER_DETAIL.MEDICAL_GROUP_NAME AS BILLING_PROVIDER_NAME,
BILLING_PROVIDER_DETAIL.TAX_ID_NBR AS BILLING_PROVIDER_TAX_ID_NBR,
BILLING_PROVIDER_DETAIL.NPI_NBR AS BILLING_PROVIDER_NPI,
SAT_CLAIM_HEADER.BILLING_PROVIDER_VENDOR_NBR,
HUB_OFFICE.OFFICE_ID,
SAT_OFFICE_DETAIL.OFFICE_NAME,
LNK_CLAIM_ATTENDING_PHYSICIAN.P_PROVIDER_ID AS ATTENDING_PHYSICIAN_ID,
SAT_CLAIM_ICD_DIAGNOSIS.ICD_DIAGNOSIS_CODES AS ICD_DIAGNOSIS_CODES_ARRAY,
LNK_CLAIM_REFERRING_PROVIDER.P_PROVIDER_ID AS REFERRING_PROVIDER_ID,
SAT_CLAIM_HEADER.CLAIM_TYPE_CODE,
SAT_CLAIM_HEADER.IPA_CODE,
SAT_CLAIM_HEADER.SERVICE_ZIP_CODE,
SAT_CLAIM_HEADER.EDI_837_FACILITY_NPI_NBR,
SAT_CLAIM_HEADER.EDI_837_FACILITY_NAME,
SAT_CLAIM_HEADER.EDI_837_FACILITY_TELEPHONE_NBR,
SAT_CLAIM_HEADER.EDI_837_FACILITY_ADDRESS_LINE_1_TEXT,
SAT_CLAIM_HEADER.EDI_837_FACILITY_ADDRESS_LINE_2_TEXT,
SAT_CLAIM_HEADER.EDI_837_FACILITY_CITY_NAME,
SAT_CLAIM_HEADER.EDI_837_FACILITY_STATE_ABBREV_NAME,
SAT_CLAIM_HEADER.EDI_837_FACILITY_ZIP_CODE_NBR,
SAT_CLAIM_HEADER.EDI_837_FACILITY_OTHER_ID,
SAT_CLAIM_HEADER.SEVERITY_OF_ILLNESS,
SAT_CLAIM_HEADER.DIAGNOSIS_RELATED_GROUP_CODE,
SAT_CLAIM_HEADER.PROVIDER_SPECIALTY,
SAT_CLAIM_HEADER.PAID_STATUS_FOR_CMS

FROM HUBDATA.HUB_CLAIM

    JOIN HUBDATA.EFF_SAT_CLAIM_HEADER
        ON(EFF_SAT_CLAIM_HEADER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND EFF_SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_CLAIM_HEADER.DELETED_DATETIME > CURRENT_TIMESTAMP())
    
    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_MEMBERSHIP_GROUP
                    JOIN HUBDATA.EFF_SAT_MEMBERSHIP_GROUP
                        ON(EFF_SAT_MEMBERSHIP_GROUP.HUB_MEMBERSHIP_GROUP_HKEY = LNK_CLAIM_MEMBERSHIP_GROUP.HUB_MEMBERSHIP_GROUP_HKEY
                        AND EFF_SAT_MEMBERSHIP_GROUP.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_MEMBERSHIP_GROUP.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_MEMBERSHIP_GROUP.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_MEMBERSHIP_GROUP.IS_CURRENT_ROW_FLAG = TRUE)
   
    LEFT OUTER JOIN HUBDATA.SAT_MEMBERSHIP_GROUP_DETAIL
        ON (SAT_MEMBERSHIP_GROUP_DETAIL.HUB_MEMBERSHIP_GROUP_HKEY = LNK_CLAIM_MEMBERSHIP_GROUP.HUB_MEMBERSHIP_GROUP_HKEY
        AND SAT_MEMBERSHIP_GROUP_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_MEMBER
                    JOIN HUBDATA.EFF_SAT_MEMBER
                        ON(EFF_SAT_MEMBER.HUB_MEMBER_HKEY = LNK_CLAIM_MEMBER.HUB_MEMBER_HKEY
                        AND EFF_SAT_MEMBER.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_MEMBER.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_MEMBER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_MEMBER.IS_CURRENT_ROW_FLAG = TRUE)
            
    LEFT OUTER JOIN HUBDATA.HUB_MEMBER
        ON (HUB_MEMBER.HUB_MEMBER_HKEY = LNK_CLAIM_MEMBER.HUB_MEMBER_HKEY
        AND LNK_CLAIM_MEMBER.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_CLAIM_HEADER
        ON (HUB_CLAIM.HUB_CLAIM_HKEY = SAT_CLAIM_HEADER.HUB_CLAIM_HKEY
        AND SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_BILLING_PROVIDER
                    JOIN HUBDATA.EFF_SAT_MEDICAL_GROUP
                        ON(EFF_SAT_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY = LNK_CLAIM_BILLING_PROVIDER.HUB_MEDICAL_GROUP_HKEY
                        AND EFF_SAT_MEDICAL_GROUP.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_MEDICAL_GROUP.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_BILLING_PROVIDER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_BILLING_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.HUB_MEDICAL_GROUP BILLING_PROVIDER
        ON (BILLING_PROVIDER.HUB_MEDICAL_GROUP_HKEY = LNK_CLAIM_BILLING_PROVIDER.HUB_MEDICAL_GROUP_HKEY
        AND LNK_CLAIM_BILLING_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_MEDICAL_GROUP_DETAIL BILLING_PROVIDER_DETAIL
        ON (BILLING_PROVIDER.HUB_MEDICAL_GROUP_HKEY = BILLING_PROVIDER_DETAIL.HUB_MEDICAL_GROUP_HKEY 
        AND BILLING_PROVIDER_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_REFERRING_PROVIDER
                    JOIN HUBDATA.EFF_SAT_PROVIDER EFF_SAT_PROVIDER_REFERRING
                        ON (EFF_SAT_PROVIDER_REFERRING.HUB_PROVIDER_HKEY = LNK_CLAIM_REFERRING_PROVIDER.HUB_PROVIDER_HKEY
                        AND EFF_SAT_PROVIDER_REFERRING.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_PROVIDER_REFERRING.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_REFERRING_PROVIDER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_REFERRING_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_CLAIM_ICD_DIAGNOSIS
        ON (SAT_CLAIM_ICD_DIAGNOSIS.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND SAT_CLAIM_ICD_DIAGNOSIS.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_PLAN
                    JOIN HUBDATA.EFF_SAT_PLAN
                        ON(EFF_SAT_PLAN.HUB_PLAN_HKEY = LNK_CLAIM_PLAN.HUB_PLAN_HKEY
                        AND EFF_SAT_PLAN.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_PLAN.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_PLAN.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_PLAN.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.HUB_PLAN
        ON (HUB_PLAN.HUB_PLAN_HKEY = LNK_CLAIM_PLAN.HUB_PLAN_HKEY
        AND LNK_CLAIM_PLAN.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_PLAN_DETAIL
        ON (SAT_PLAN_DETAIL.HUB_PLAN_HKEY = HUB_PLAN.HUB_PLAN_HKEY
        AND SAT_PLAN_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

     LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_OFFICE
                    JOIN HUBDATA.EFF_SAT_OFFICE
                        ON(EFF_SAT_OFFICE.HUB_OFFICE_HKEY = LNK_CLAIM_OFFICE.HUB_OFFICE_HKEY
                        AND EFF_SAT_OFFICE.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_OFFICE.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_OFFICE.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_OFFICE.IS_CURRENT_ROW_FLAG = TRUE)
        
    LEFT OUTER JOIN HUBDATA.HUB_OFFICE
        ON (HUB_OFFICE.HUB_OFFICE_HKEY = LNK_CLAIM_OFFICE.HUB_OFFICE_HKEY
        AND LNK_CLAIM_OFFICE.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_OFFICE_DETAIL
        ON (SAT_OFFICE_DETAIL.HUB_OFFICE_HKEY = LNK_CLAIM_OFFICE.HUB_OFFICE_HKEY
        AND SAT_OFFICE_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN REFDATA.CLAIM_PLACE_OF_SERVICE REF_CLAIM_PLACE_OF_SERVICE
        ON (REF_CLAIM_PLACE_OF_SERVICE.CODE = SAT_CLAIM_HEADER.PLACE_OF_SERVICE_CODE)

    LEFT OUTER JOIN
            (SELECT 
            LNK_CLAIM_RIDER.HUB_CLAIM_HKEY
            ,HUB_MEMBERSHIP_GROUP_HKEY
            ,ARRAY_AGG(HUB_RIDER.RIDER_CODE) WITHIN GROUP (ORDER BY HUB_RIDER.RIDER_CODE) AS RIDER_CODE_ARRAY
            FROM HUBDATA.LNK_CLAIM_RIDER
                JOIN HUBDATA.HUB_RIDER
                    ON (HUB_RIDER.HUB_RIDER_HKEY = LNK_CLAIM_RIDER.HUB_RIDER_HKEY)
                JOIN HUBDATA.EFF_SAT_RIDER
                    ON(EFF_SAT_RIDER.HUB_RIDER_HKEY = HUB_RIDER.HUB_RIDER_HKEY
                        AND EFF_SAT_RIDER.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_RIDER.DELETED_DATETIME > CURRENT_TIMESTAMP())
            WHERE LNK_CLAIM_RIDER.IS_CURRENT_ROW_FLAG = TRUE
            GROUP BY LNK_CLAIM_RIDER.HUB_CLAIM_HKEY, LNK_CLAIM_RIDER.HUB_MEMBERSHIP_GROUP_HKEY
            ) RIDER_CODES
        ON (RIDER_CODES.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND RIDER_CODES.HUB_MEMBERSHIP_GROUP_HKEY = LNK_CLAIM_MEMBERSHIP_GROUP.HUB_MEMBERSHIP_GROUP_HKEY)

    LEFT OUTER JOIN REFDATA.CLAIM_ELECTRONIC_TYPE REF_CLAIM_ELECTRONIC_TYPE
        ON (REF_CLAIM_ELECTRONIC_TYPE.CODE = SAT_CLAIM_HEADER.ELECTRONIC_CLAIM_TYPE_CODE)

    LEFT OUTER JOIN REFDATA.CLAIM_BILLING_TYPE REF_CLAIM_BILLING_TYPE
        ON (REF_CLAIM_BILLING_TYPE.CODE = SAT_CLAIM_HEADER.BILLING_TYPE_CODE)

    LEFT OUTER JOIN REFDATA.CLAIM_ADMISSION_SOURCE REF_CLAIM_ADMISSION_SOURCE
        ON (REF_CLAIM_ADMISSION_SOURCE.TPA_CLIENT_ID = HUB_CLAIM.TPA_CLIENT_ID
        AND REF_CLAIM_ADMISSION_SOURCE.TPA_ID = HUB_CLAIM.TPA_ID
        AND REF_CLAIM_ADMISSION_SOURCE.TPA_DIV_ID = HUB_CLAIM.TPA_DIV_ID
        AND REF_CLAIM_ADMISSION_SOURCE.DATA_SOURCE_NAME = HUB_CLAIM.DATA_SOURCE_NAME
        AND REF_CLAIM_ADMISSION_SOURCE.ADMISSION_TYPE_CODE = SAT_CLAIM_HEADER.ADMISSION_TYPE_CODE
        AND REF_CLAIM_ADMISSION_SOURCE.CODE = SAT_CLAIM_HEADER.ADMISSION_SOURCE_CODE)

    LEFT OUTER JOIN REFDATA.CLAIM_ADMISSION_TYPE REF_CLAIM_ADMISSION_TYPE
        ON (REF_CLAIM_ADMISSION_TYPE.TPA_CLIENT_ID = HUB_CLAIM.TPA_CLIENT_ID
        AND REF_CLAIM_ADMISSION_TYPE.TPA_ID = HUB_CLAIM.TPA_ID
        AND REF_CLAIM_ADMISSION_TYPE.TPA_DIV_ID = HUB_CLAIM.TPA_DIV_ID
        AND REF_CLAIM_ADMISSION_TYPE.DATA_SOURCE_NAME = HUB_CLAIM.DATA_SOURCE_NAME
        AND REF_CLAIM_ADMISSION_TYPE.CODE = SAT_CLAIM_HEADER.ADMISSION_TYPE_CODE)

    LEFT OUTER JOIN REFDATA.CLAIM_DISCHARGE_STATUS REF_CLAIM_DISCHARGE_STATUS
        ON (REF_CLAIM_DISCHARGE_STATUS.TPA_CLIENT_ID = HUB_CLAIM.TPA_CLIENT_ID
        AND REF_CLAIM_DISCHARGE_STATUS.TPA_ID = HUB_CLAIM.TPA_ID
        AND REF_CLAIM_DISCHARGE_STATUS.TPA_DIV_ID = HUB_CLAIM.TPA_DIV_ID
        AND REF_CLAIM_DISCHARGE_STATUS.DATA_SOURCE_NAME = HUB_CLAIM.DATA_SOURCE_NAME
        AND REF_CLAIM_DISCHARGE_STATUS.CODE = SAT_CLAIM_HEADER.DISCHARGE_STATUS_CODE)

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_ATTENDING_PHYSICIAN
                    JOIN HUBDATA.EFF_SAT_PROVIDER EFF_SAT_PROVIDER_ATTENDING
                        ON(EFF_SAT_PROVIDER_ATTENDING.HUB_PROVIDER_HKEY = LNK_CLAIM_ATTENDING_PHYSICIAN.HUB_PROVIDER_HKEY
                        AND EFF_SAT_PROVIDER_ATTENDING.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_PROVIDER_ATTENDING.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_ATTENDING_PHYSICIAN.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_ATTENDING_PHYSICIAN.IS_CURRENT_ROW_FLAG = TRUE)

WHERE SAT_CLAIM_HEADER.CARE_TYPE_NAME <> 'pharmacy'
;