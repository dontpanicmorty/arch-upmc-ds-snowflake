CREATE OR REPLACE VIEW EXTRACTDATA.DRUG_DETAIL_BASE_VW
COMMENT = 'LEFT OUTER JOINs core tables from hubdata data vault model for common drug consumption'
AS
SELECT
    HUB_DRUG.HUB_DRUG_HKEY,
    HUB_DRUG.TPA_CLIENT_ID,
    HUB_DRUG.TPA_ID,
    HUB_DRUG.TPA_DIV_ID,
    HUB_DRUG.DATA_SOURCE_NAME,
    HUB_DRUG.NDC_CODE,
    SAT_DRUG_DETAIL.DOSAGE_METHOD_CODE,
    SAT_DRUG_DETAIL.BRAND_DRUG_NAME,
    SAT_DRUG_DETAIL.DOSAGE_METHOD_DESC,
    SAT_DRUG_DETAIL.GENERIC_DRUG_NAME,
    SAT_DRUG_DETAIL.DRUG_STRENGTH_DESC,
    SAT_DRUG_DETAIL.THER_CLASS_AHFS_CODE,
    SAT_DRUG_DETAIL.THER_CLASS_AHFS_DESC,
    SAT_DRUG_DETAIL.THER_CLASS_GEN_CODE,
    SAT_DRUG_DETAIL.THER_CLASS_GEN_DESC,
    SAT_DRUG_DETAIL.DRUG_CLASS_CODE,
    SAT_DRUG_DETAIL.DRUG_CLASS_DESC,
    SAT_DRUG_DETAIL.ABUSE_RATING_CODE,
    SAT_DRUG_DETAIL.ABUSE_RATING_DESC,
    SAT_DRUG_DETAIL.DRUG_FORM_CODE,
    SAT_DRUG_DETAIL.DRUG_FORM_DESC,
    SAT_DRUG_DETAIL.ROUTE_CODE,
    SAT_DRUG_DETAIL.ROUTE_DESC,
    SAT_DRUG_DETAIL.GCN_CODE,
    SAT_DRUG_DETAIL.DRUG_LABEL_NAME,
    SAT_DRUG_DETAIL.GENERIC_PRICE_CODE,
    SAT_DRUG_DETAIL.GENERIC_PRICE_DESC,
    SAT_DRUG_DETAIL.HIC3_CODE,
    SAT_DRUG_DETAIL.HIC3_DESC,
    SAT_DRUG_DETAIL.GENERIC_SOURCE_CODE,
    SAT_DRUG_DETAIL.GENERIC_SOURCE_DESC,
    SAT_DRUG_DETAIL.INNOVATOR_FLAG,
    SAT_DRUG_DETAIL.NEW_DRUG_APPLICATOR_FLAG,
    SAT_DRUG_DETAIL.GENERIC_THERAPEUTIC_FLAG,
    SAT_DRUG_DETAIL.GENERIC_MANUFACTURER_FLAG,
    SAT_DRUG_DETAIL.MAINTENANCE_DRUG_FLAG,
    SAT_DRUG_DETAIL.MED_ID,
    SAT_DRUG_DETAIL.MED_DESC,
    SAT_DRUG_DETAIL.MED_NAME_ID,
    SAT_DRUG_DETAIL.MED_NAME,
    SAT_DRUG_DETAIL.WHOLESALE_ACQUISIT_COST_DATE,
    SAT_DRUG_DETAIL.WHOLESALE_ACQUISITION_COST_AMT,
    SAT_DRUG_DETAIL.GSN_CODE,
    SAT_DRUG_DETAIL.SPECIALTY_DRUG_IND,
    SAT_DRUG_DETAIL.MEDISPAN_GPI_CODE,
    SAT_DRUG_DETAIL.MEDISPAN_GPI_DESC, 
    SAT_DRUG_DETAIL.MANUFACTURER_NAME

FROM HUBDATA.HUB_DRUG
    JOIN HUBDATA.EFF_SAT_DRUG
        ON (EFF_SAT_DRUG.HUB_DRUG_HKEY = HUB_DRUG.HUB_DRUG_HKEY
        AND EFF_SAT_DRUG.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_DRUG.DELETED_DATETIME > CURRENT_TIMESTAMP())
    LEFT JOIN HUBDATA.SAT_DRUG_DETAIL
        ON (HUB_DRUG.HUB_DRUG_HKEY = SAT_DRUG_DETAIL.HUB_DRUG_HKEY
        AND SAT_DRUG_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
;