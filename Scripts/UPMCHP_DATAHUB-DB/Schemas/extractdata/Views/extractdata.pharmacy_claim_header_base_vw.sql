CREATE OR REPLACE VIEW EXTRACTDATA.PHARMACY_CLAIM_HEADER_BASE_VW
COMMENT = 'LEFT OUTER JOINs core tables from hubdata data vault model for common pharmacy claim header consumption'
AS
SELECT
    HUB_CLAIM.HUB_CLAIM_HKEY,
    HUB_CLAIM.TPA_CLIENT_ID,
    HUB_CLAIM.TPA_ID,
    HUB_CLAIM.TPA_DIV_ID,
    HUB_CLAIM.DATA_SOURCE_NAME,
    HUB_CLAIM.CLAIM_NBR,
    SAT_CLAIM_HEADER.LINE_OF_BUSINESS_CODE AS ORIGINAL_CLAIM_LOB,
    SAT_CLAIM_HEADER.CARE_TYPE_NAME,
    SAT_CLAIM_HEADER.CLAIM_TYPE_CODE,
    IFF(SAT_CLAIM_HEADER.CLAIM_TYPE_CODE IS NULL, NULL, IFNULL(REF_CLAIM_TYPE_CODE.CODE_DESC,'Description Not Found')) AS CLAIM_TYPE_DESC,
    SAT_CLAIM_LINE_PHARMACY.DISPENSE_CODE,
    IFF(SAT_CLAIM_LINE_PHARMACY.DISPENSE_CODE IS NULL, NULL, IFNULL(REF_CLAIM_DISPENSE_CODE.CODE_DESC,'Description Not Found')) AS DISPENSE_CODE_DESC,
    SAT_CLAIM_LINE_PHARMACY.REFILL_CODE, 
    SAT_CLAIM_LINE_PHARMACY.PRESCRIPTION_NBR,
    SAT_CLAIM_LINE_PHARMACY.AUTHORIZATION_NBR, 
    SAT_CLAIM_LINE_PHARMACY.PRESCRIPTION_ORIGIN_CODE,
    IFF(SAT_CLAIM_LINE_PHARMACY.PRESCRIPTION_ORIGIN_CODE IS NULL, NULL, IFNULL(REF_CLAIM_PRESCRIPTION_ORIGIN_CODE.CODE_DESC,'Description Not Found')) AS PRESCRIPTION_ORIGIN_DESC,
    'N/A' AS PHARMACY_NETWORK_CODE,
    'Not Applicable' AS PHARMACY_NETWORK_DESC,
    SAT_CLAIM_LINE_PHARMACY.PRICE_SOURCE_CODE,
    IFF(SAT_CLAIM_LINE_PHARMACY.PRICE_SOURCE_CODE IS NULL, NULL, IFNULL(REF_CLAIM_PRICE_SOURCE_CODE.CODE_DESC,'Description Not Found')) AS PRICE_SOURCE_DESC,
    SAT_CLAIM_LINE_PHARMACY.COMPOUND_CODE,
    IFF(SAT_CLAIM_LINE_PHARMACY.COMPOUND_CODE IS NULL, NULL, IFNULL(REF_CLAIM_COMPOUND_CODE.CODE_DESC,'Description Not Found')) AS COMPOUND_CODE_DESC,
    SAT_CLAIM_LINE_PHARMACY.ESI_FUNDED_IND,
    IFF(SAT_CLAIM_LINE_PHARMACY.ESI_FUNDED_IND IS NULL, NULL, IFNULL(REF_CLAIM_ESI_FUNDED_IND.CODE_DESC,'Description Not Found')) AS ESI_FUNDED_IND_DESC,
    SAT_CLAIM_LINE_PHARMACY.TROOP_ELIGIBILITY_CODE, 
    IFNULL(SAT_CLAIM_LINE_PHARMACY.LOW_INCOME_SUBSIDY_CODE, 'N/A') AS LOW_INCOME_SUBSIDY_CODE,
    IFF(SAT_CLAIM_LINE_PHARMACY.LOW_INCOME_SUBSIDY_CODE IS NULL, 'Not Applicable', IFNULL(REF_CLAIM_LOW_INCOME_SUBSIDY_CODE.CODE_DESC,'Description Not Found')) AS LOW_INCOME_SUBSIDY_DESC,
    SAT_CLAIM_LINE_PHARMACY.PARTIAL_FILL_STATUS_CODE,
    IFF(SAT_CLAIM_LINE_PHARMACY.PARTIAL_FILL_STATUS_CODE IS NULL, NULL, IFNULL(REF_CLAIM_PARTIAL_FILL_STATUS_CODE.CODE_DESC,'Description Not Found')) AS PARTIAL_FILL_STATUS_DESC,
    SAT_CLAIM_LINE_PHARMACY.FORMULARY_FLAG_CODE,
    IFF(FORMULARY_FLAG_CODE IS NULL, NULL, IFNULL(REF_CLAIM_FORMULARY_FLAG_CODE.CODE_DESC,'Description Not Found')) AS FORMULARY_FLAG_CODE_DESC,
    SAT_CLAIM_LINE_PHARMACY.DISPENSE_PHARMACY_TYPE_CODE, 
    IFF(DISPENSE_PHARMACY_TYPE_CODE IS NULL, NULL, IFNULL(REF_CLAIM_DISPENSE_PHARMACY_TYPE_CODE.CODE_DESC,'Description Not Found')) AS DISPENSE_PHARMACY_TYPE_DESC,
    SAT_CLAIM_LINE_PHARMACY.OTHER_COVERAGE_CODE,
    IFF(SAT_CLAIM_LINE_PHARMACY.OTHER_COVERAGE_CODE IS NULL, NULL, IFNULL(REF_CLAIM_OTHER_COVERAGE_CODE.CODE_DESC,'Description Not Found')) AS OTHER_COVERAGE_DESC,
    SAT_CLAIM_LINE_PHARMACY.DRUG_DISCOUNT_EXCLUSION_CODE,
    IFF(SAT_CLAIM_LINE_PHARMACY.DRUG_DISCOUNT_EXCLUSION_CODE IS NULL, NULL, IFNULL(REF_CLAIM_DRUG_DISCOUNT_EXCLUSION_CODE.CODE_DESC,'Description Not Found')) AS DRUG_DISCOUNT_EXCLUSION_DESC,
    SAT_CLAIM_LINE_PHARMACY.DRUG_DISCOUNT_APPLICABLE_CODE,
    IFF(SAT_CLAIM_LINE_PHARMACY.DRUG_DISCOUNT_APPLICABLE_CODE IS NULL, NULL, IFNULL(REF_CLAIM_DRUG_DISCOUNT_APPLICABLE_CODE.CODE_DESC,'Description Not Found')) AS DRUG_DISCOUNT_APPLICABLE_DESC,
    SAT_CLAIM_LINE_PHARMACY.AWP_INDICATION_CODE,
    IFF(SAT_CLAIM_LINE_PHARMACY.AWP_INDICATION_CODE IS NULL, NULL, IFNULL(REF_CLAIM_AWP_INDICATION_CODE.CODE_DESC,'Description Not Found')) AS AWP_INDICATION_DESC,
    SAT_CLAIM_LINE_PHARMACY.PATIENT_RESIDENCE_CODE,
    IFF(PATIENT_RESIDENCE_CODE IS NULL, NULL, IFNULL(REF_CLAIM_PATIENT_RESIDENCE_CODE.CODE_DESC,'Description Not Found')) AS PATIENT_RESIDENCE_DESC,
    SAT_CLAIM_LINE_PHARMACY.BENEFIT_PLAN_LEVEL_CODE,
    SAT_CLAIM_LINE_PHARMACY.FILL_METHOD_CODE, 
    IFF(SAT_CLAIM_LINE_PHARMACY.FILL_METHOD_CODE IS NULL, NULL, IFNULL(REF_CLAIM_FILL_METHOD_CODE.CODE_DESC,'Description Not Found')) AS FILL_METHOD_DESC,
    SAT_CLAIM_LINE_PHARMACY.ESI_PLAN_NBR, 
    SAT_CLAIM_LINE_PHARMACY.CMS_CONTRACT_ID,
    SAT_CLAIM_LINE_PHARMACY.CMS_PBP_ID,
    SAT_CLAIM_LINE_PHARMACY.CLAIM_GENERIC_PRICE_CODE,
    IFF(SAT_CLAIM_LINE_PHARMACY.CLAIM_GENERIC_PRICE_CODE IS NULL, NULL, IFNULL(REF_CLAIM_GENERIC_PRICE_CODE.CODE_DESC,'Description Not Found')) AS CLAIM_GENERIC_PRICE_DESC,
    SAT_CLAIM_LINE_PHARMACY.SAVE_ON_RX_IND,
    SAT_CLAIM_LINE_PHARMACY.M3P_ORIGIN,
    IFF(SAT_CLAIM_LINE_PHARMACY.M3P_ORIGIN IS NULL, NULL, IFNULL(REF_CLAIM_M3P_ORIGIN.CODE_DESC,'Description Not Found')) AS M3P_ORIGIN_DESC,
    SAT_CLAIM_LINE_PHARMACY.MANUFACTURER_DISCOUNT_TYPE,
    IFF(SAT_CLAIM_LINE_PHARMACY.MANUFACTURER_DISCOUNT_TYPE IS NULL, NULL, IFNULL(REF_CLAIM_MANUFACTURER_DISCOUNT_TYPE.CODE_DESC,'Description Not Found')) AS MANUFACTURER_DISCOUNT_TYPE_DESC,
    SAT_DRUG_DETAIL.HIC3_CODE AS CLAIM_HIC3_CODE,
    SAT_DRUG_DETAIL.HIC3_DESC AS CLAIM_HIC3_DESC,
    SAT_DRUG_DETAIL.GENERIC_SOURCE_CODE AS CLAIM_GENERIC_SOURCE_CODE,
    SAT_DRUG_DETAIL.GENERIC_SOURCE_DESC AS CLAIM_GENERIC_SOURCE_DESC,
    SAT_CLAIM_LINE_PHARMACY.PRICING_USED_IND,
    IFF(SAT_CLAIM_LINE_PHARMACY.PRICING_USED_IND IS NULL, NULL, IFNULL(REF_CLAIM_PRICING_USED_IND.CODE_DESC,'Description Not Found')) AS PRICING_USED_IND_DESC,
    SAT_CLAIM_LINE_PHARMACY.SUPPLEMENTAL_COVERAGE_TROOP_QUALIFICATION,
    IFF(SAT_CLAIM_LINE_PHARMACY.SUPPLEMENTAL_COVERAGE_TROOP_QUALIFICATION IS NULL, NULL, IFNULL(REF_CLAIM_SUPPLEMENTAL_COVERAGE_TROOP_QUALIFICATION.CODE_DESC,'Description Not Found')) AS SUPPLEMENTAL_COVERAGE_TROOP_DESC,
    LNK_CLAIM_DETAIL_DRUG.HUB_DRUG_HKEY,
    LNK_CLAIM_DETAIL_DRUG.D_NDC_CODE AS NDC_CODE,
    LNK_CLAIM_MEMBER.HUB_MEMBER_HKEY,
    LNK_CLAIM_MEMBER.M_MEMBER_NBR AS MEMBER_NBR,
    LNK_CLAIM_MEMBERSHIP_GROUP.HUB_MEMBERSHIP_GROUP_HKEY,
    LNK_CLAIM_MEMBERSHIP_GROUP.MG_GROUP_NBR AS GROUP_NBR,
    LNK_CLAIM_MEMBERSHIP_GROUP.MG_SUB_GROUP_NBR AS SUB_GROUP_NBR,
    LNK_CLAIM_PLAN.HUB_PLAN_HKEY,
    LNK_CLAIM_PLAN.P_PLAN_CODE AS PLAN_CODE,
    SAT_PLAN_DETAIL.PLAN_TYPE_CODE,
    HUB_RIDER.RIDER_CODE,
    SAT_CLAIM_LINE_PHARMACY.MEMBER_AGE_NBR,
    SAT_CLAIM_LINE_PHARMACY.RX_FORMULARY_CODE,
    REF_RIDER_FORMULARY_CODE.CODE_DESC AS RX_FORMULARY_DESC,
    HUB_OFFICE_PHARMACY.HUB_OFFICE_HKEY AS HUB_OFFICE_PHARMACY_HKEY,
    HUB_OFFICE_PHARMACY.OFFICE_ID AS OFFICE_ID_PHARMACY,
    HUB_OFFICE_PRESCRIBER.HUB_OFFICE_HKEY AS HUB_OFFICE_PRESCRIBER_HKEY,
    HUB_OFFICE_PRESCRIBER.OFFICE_ID AS OFFICE_ID_PRESCRIBER,
    HUB_PROVIDER_PHARMACY.HUB_PROVIDER_HKEY AS HUB_PROVIDER_PHARMACY_HKEY,
    HUB_PROVIDER_PHARMACY.PROVIDER_ID AS PROVIDER_ID_PHARMACY,
    HUB_PROVIDER_PRESCRIBER.HUB_PROVIDER_HKEY AS HUB_PROVIDER_PRESCRIBER_HKEY,
    HUB_PROVIDER_PRESCRIBER.PROVIDER_ID AS PROVIDER_ID_PRESCRIBER

FROM HUBDATA.HUB_CLAIM

    JOIN HUBDATA.EFF_SAT_CLAIM_HEADER
        ON(EFF_SAT_CLAIM_HEADER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND EFF_SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_CLAIM_HEADER.DELETED_DATETIME > CURRENT_TIMESTAMP())

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_DETAIL
                    JOIN HUBDATA.EFF_SAT_CLAIM_LINE
                        ON(EFF_SAT_CLAIM_LINE.HUB_CLAIM_DETAIL_HKEY = LNK_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
                        AND EFF_SAT_CLAIM_LINE.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_CLAIM_LINE.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_DETAIL.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.HUB_CLAIM_DETAIL
        ON (HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = LNK_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
        AND LNK_CLAIM_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
    
    LEFT OUTER JOIN HUBDATA.SAT_CLAIM_HEADER
        ON (HUB_CLAIM.HUB_CLAIM_HKEY = SAT_CLAIM_HEADER.HUB_CLAIM_HKEY
        AND SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_CLAIM_LINE_PHARMACY
        ON (HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = SAT_CLAIM_LINE_PHARMACY.HUB_CLAIM_DETAIL_HKEY
        AND SAT_CLAIM_LINE_PHARMACY.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_DETAIL_DRUG
                    JOIN HUBDATA.EFF_SAT_DRUG
                        ON(EFF_SAT_DRUG.HUB_DRUG_HKEY = LNK_CLAIM_DETAIL_DRUG.HUB_DRUG_HKEY
                        AND EFF_SAT_DRUG.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_DRUG.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_DETAIL_DRUG.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
        AND LNK_CLAIM_DETAIL_DRUG.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_DRUG_DETAIL
        ON (LNK_CLAIM_DETAIL_DRUG.HUB_DRUG_HKEY = SAT_DRUG_DETAIL.HUB_DRUG_HKEY
        AND SAT_DRUG_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
  LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_MEMBERSHIP_GROUP
                    JOIN HUBDATA.EFF_SAT_MEMBERSHIP_GROUP
                        ON(EFF_SAT_MEMBERSHIP_GROUP.HUB_MEMBERSHIP_GROUP_HKEY = LNK_CLAIM_MEMBERSHIP_GROUP.HUB_MEMBERSHIP_GROUP_HKEY
                        AND EFF_SAT_MEMBERSHIP_GROUP.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_MEMBERSHIP_GROUP.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_MEMBERSHIP_GROUP.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_MEMBERSHIP_GROUP.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_MEMBER
                    JOIN HUBDATA.EFF_SAT_MEMBER
                        ON(EFF_SAT_MEMBER.HUB_MEMBER_HKEY = LNK_CLAIM_MEMBER.HUB_MEMBER_HKEY
                        AND EFF_SAT_MEMBER.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_MEMBER.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_MEMBER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_MEMBER.IS_CURRENT_ROW_FLAG = TRUE)
    
    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_PLAN
                    JOIN HUBDATA.EFF_SAT_PLAN
                        ON(EFF_SAT_PLAN.HUB_PLAN_HKEY = LNK_CLAIM_PLAN.HUB_PLAN_HKEY
                        AND EFF_SAT_PLAN.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_PLAN.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_PLAN.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_PLAN.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.SAT_PLAN_DETAIL
        ON (LNK_CLAIM_PLAN.HUB_PLAN_HKEY = SAT_PLAN_DETAIL.HUB_PLAN_HKEY
        AND LNK_CLAIM_PLAN.IS_CURRENT_ROW_FLAG = TRUE
        AND SAT_PLAN_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_RIDER
                    JOIN HUBDATA.EFF_SAT_RIDER
                        ON(EFF_SAT_RIDER.HUB_RIDER_HKEY = LNK_CLAIM_RIDER.HUB_RIDER_HKEY
                        AND EFF_SAT_RIDER.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_RIDER.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_RIDER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_RIDER.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN HUBDATA.HUB_RIDER
        ON (LNK_CLAIM_RIDER.HUB_RIDER_HKEY = HUB_RIDER.HUB_RIDER_HKEY
        AND LNK_CLAIM_RIDER.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_OFFICE
                    JOIN HUBDATA.EFF_SAT_OFFICE EFF_SAT_OFFICE_PHARMACY
                        ON(EFF_SAT_OFFICE_PHARMACY.HUB_OFFICE_HKEY = LNK_CLAIM_OFFICE.HUB_OFFICE_HKEY
                        AND EFF_SAT_OFFICE_PHARMACY.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_OFFICE_PHARMACY.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_OFFICE.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_OFFICE.IS_CURRENT_ROW_FLAG = TRUE)
    
    LEFT OUTER JOIN HUBDATA.HUB_OFFICE HUB_OFFICE_PHARMACY--Pharmacy HUB_OFFICE Records
        ON (LNK_CLAIM_OFFICE.HUB_OFFICE_HKEY = HUB_OFFICE_PHARMACY.HUB_OFFICE_HKEY)

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_DETAIL_PHARMACY
                    JOIN HUBDATA.EFF_SAT_PROVIDER EFF_SAT_PROVIDER_PHARMACY
                        ON(EFF_SAT_PROVIDER_PHARMACY.HUB_PROVIDER_HKEY = LNK_CLAIM_DETAIL_PHARMACY.HUB_PROVIDER_HKEY
                        AND EFF_SAT_PROVIDER_PHARMACY.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_PROVIDER_PHARMACY.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_DETAIL_PHARMACY.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
        AND LNK_CLAIM_DETAIL_PHARMACY.IS_CURRENT_ROW_FLAG = TRUE)
    
    LEFT OUTER JOIN HUBDATA.HUB_PROVIDER HUB_PROVIDER_PHARMACY --Pharmacy HUB_PROVIDER Records
        ON (LNK_CLAIM_DETAIL_PHARMACY.HUB_PROVIDER_HKEY = HUB_PROVIDER_PHARMACY.HUB_PROVIDER_HKEY)

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_PRESCRIBER
                    JOIN HUBDATA.EFF_SAT_OFFICE EFF_SAT_OFFICE_PRESCRIBER
                        ON(EFF_SAT_OFFICE_PRESCRIBER.HUB_OFFICE_HKEY = LNK_CLAIM_PRESCRIBER.HUB_OFFICE_HKEY
                        AND EFF_SAT_OFFICE_PRESCRIBER.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_OFFICE_PRESCRIBER.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_PRESCRIBER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_PRESCRIBER.IS_CURRENT_ROW_FLAG = TRUE)
    
    LEFT OUTER JOIN HUBDATA.HUB_OFFICE HUB_OFFICE_PRESCRIBER --Prescriber HUB_OFFICE Records
        ON (LNK_CLAIM_PRESCRIBER.HUB_OFFICE_HKEY = HUB_OFFICE_PRESCRIBER.HUB_OFFICE_HKEY)

    LEFT OUTER JOIN (HUBDATA.LNK_CLAIM_DETAIL_RENDERING_PROVIDER
                    JOIN HUBDATA.EFF_SAT_PROVIDER EFF_SAT_PROVIDER_PRESCRIBER
                        ON(EFF_SAT_PROVIDER_PRESCRIBER.HUB_PROVIDER_HKEY = LNK_CLAIM_DETAIL_RENDERING_PROVIDER.HUB_PROVIDER_HKEY
                        AND EFF_SAT_PROVIDER_PRESCRIBER.IS_CURRENT_ROW_FLAG = TRUE
                        AND EFF_SAT_PROVIDER_PRESCRIBER.DELETED_DATETIME > CURRENT_TIMESTAMP())
                        )
        ON (LNK_CLAIM_DETAIL_RENDERING_PROVIDER.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
        AND LNK_CLAIM_DETAIL_RENDERING_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE)
    
    LEFT OUTER JOIN HUBDATA.HUB_PROVIDER HUB_PROVIDER_PRESCRIBER --Prescriber HUB_PROVIDER Records
        ON (LNK_CLAIM_DETAIL_RENDERING_PROVIDER.HUB_PROVIDER_HKEY = HUB_PROVIDER_PRESCRIBER.HUB_PROVIDER_HKEY)    

    LEFT OUTER JOIN REFDATA.CLAIM_TYPE_CODE REF_CLAIM_TYPE_CODE
        ON (HUB_CLAIM_DETAIL.TPA_CLIENT_ID = REF_CLAIM_TYPE_CODE.TPA_CLIENT_ID
        AND HUB_CLAIM_DETAIL.TPA_ID = REF_CLAIM_TYPE_CODE.TPA_ID
        AND HUB_CLAIM_DETAIL.TPA_DIV_ID = REF_CLAIM_TYPE_CODE.TPA_DIV_ID
        AND HUB_CLAIM_DETAIL.DATA_SOURCE_NAME = REF_CLAIM_TYPE_CODE.DATA_SOURCE_NAME
        AND SAT_CLAIM_HEADER.CLAIM_TYPE_CODE = REF_CLAIM_TYPE_CODE.CODE)

    LEFT OUTER JOIN REFDATA.CLAIM_COMPOUND_CODE REF_CLAIM_COMPOUND_CODE
        ON (HUB_CLAIM_DETAIL.TPA_CLIENT_ID = REF_CLAIM_COMPOUND_CODE.TPA_CLIENT_ID
        AND HUB_CLAIM_DETAIL.TPA_ID = REF_CLAIM_COMPOUND_CODE.TPA_ID
        AND HUB_CLAIM_DETAIL.TPA_DIV_ID = REF_CLAIM_COMPOUND_CODE.TPA_DIV_ID
        AND HUB_CLAIM_DETAIL.DATA_SOURCE_NAME = REF_CLAIM_COMPOUND_CODE.DATA_SOURCE_NAME
        AND SAT_CLAIM_LINE_PHARMACY.COMPOUND_CODE = REF_CLAIM_COMPOUND_CODE.CODE)

    LEFT OUTER JOIN REFDATA.CLAIM_DRUG_DISCOUNT_APPLICABLE_CODE REF_CLAIM_DRUG_DISCOUNT_APPLICABLE_CODE
         ON (HUB_CLAIM_DETAIL.TPA_CLIENT_ID = REF_CLAIM_DRUG_DISCOUNT_APPLICABLE_CODE.TPA_CLIENT_ID
        AND HUB_CLAIM_DETAIL.TPA_ID = REF_CLAIM_DRUG_DISCOUNT_APPLICABLE_CODE.TPA_ID
        AND HUB_CLAIM_DETAIL.TPA_DIV_ID = REF_CLAIM_DRUG_DISCOUNT_APPLICABLE_CODE.TPA_DIV_ID
        AND HUB_CLAIM_DETAIL.DATA_SOURCE_NAME = REF_CLAIM_DRUG_DISCOUNT_APPLICABLE_CODE.DATA_SOURCE_NAME
        AND SAT_CLAIM_LINE_PHARMACY.DRUG_DISCOUNT_APPLICABLE_CODE = REF_CLAIM_DRUG_DISCOUNT_APPLICABLE_CODE.CODE)
    
    LEFT OUTER JOIN REFDATA.CLAIM_DRUG_DISCOUNT_EXCLUSION_CODE REF_CLAIM_DRUG_DISCOUNT_EXCLUSION_CODE
        ON (HUB_CLAIM_DETAIL.TPA_CLIENT_ID = REF_CLAIM_DRUG_DISCOUNT_EXCLUSION_CODE.TPA_CLIENT_ID
        AND HUB_CLAIM_DETAIL.TPA_ID = REF_CLAIM_DRUG_DISCOUNT_EXCLUSION_CODE.TPA_ID
        AND HUB_CLAIM_DETAIL.TPA_DIV_ID = REF_CLAIM_DRUG_DISCOUNT_EXCLUSION_CODE.TPA_DIV_ID
        AND HUB_CLAIM_DETAIL.DATA_SOURCE_NAME = REF_CLAIM_DRUG_DISCOUNT_EXCLUSION_CODE.DATA_SOURCE_NAME
        AND SAT_CLAIM_LINE_PHARMACY.DRUG_DISCOUNT_EXCLUSION_CODE = REF_CLAIM_DRUG_DISCOUNT_EXCLUSION_CODE.CODE)

    LEFT OUTER JOIN REFDATA.CLAIM_GENERIC_PRICE_CODE REF_CLAIM_GENERIC_PRICE_CODE
        ON (HUB_CLAIM_DETAIL.TPA_CLIENT_ID = REF_CLAIM_GENERIC_PRICE_CODE.TPA_CLIENT_ID
        AND HUB_CLAIM_DETAIL.TPA_ID = REF_CLAIM_GENERIC_PRICE_CODE.TPA_ID
        AND HUB_CLAIM_DETAIL.TPA_DIV_ID = REF_CLAIM_GENERIC_PRICE_CODE.TPA_DIV_ID
        AND HUB_CLAIM_DETAIL.DATA_SOURCE_NAME = REF_CLAIM_GENERIC_PRICE_CODE.DATA_SOURCE_NAME
        AND SAT_CLAIM_LINE_PHARMACY.CLAIM_GENERIC_PRICE_CODE = REF_CLAIM_GENERIC_PRICE_CODE.CODE)
    
    LEFT OUTER JOIN REFDATA.CLAIM_ESI_FUNDED_IND REF_CLAIM_ESI_FUNDED_IND
        ON (HUB_CLAIM_DETAIL.TPA_CLIENT_ID = REF_CLAIM_ESI_FUNDED_IND.TPA_CLIENT_ID
        AND HUB_CLAIM_DETAIL.TPA_ID = REF_CLAIM_ESI_FUNDED_IND.TPA_ID
        AND HUB_CLAIM_DETAIL.TPA_DIV_ID = REF_CLAIM_ESI_FUNDED_IND.TPA_DIV_ID
        AND HUB_CLAIM_DETAIL.DATA_SOURCE_NAME = REF_CLAIM_ESI_FUNDED_IND.DATA_SOURCE_NAME
        AND SAT_CLAIM_LINE_PHARMACY.ESI_FUNDED_IND = REF_CLAIM_ESI_FUNDED_IND.CODE)

    LEFT OUTER JOIN REFDATA.CLAIM_PRICING_USED_IND REF_CLAIM_PRICING_USED_IND
        ON (HUB_CLAIM_DETAIL.TPA_CLIENT_ID = REF_CLAIM_PRICING_USED_IND.TPA_CLIENT_ID
        AND HUB_CLAIM_DETAIL.TPA_ID = REF_CLAIM_PRICING_USED_IND.TPA_ID
        AND HUB_CLAIM_DETAIL.TPA_DIV_ID = REF_CLAIM_PRICING_USED_IND.TPA_DIV_ID
        AND HUB_CLAIM_DETAIL.DATA_SOURCE_NAME = REF_CLAIM_PRICING_USED_IND.DATA_SOURCE_NAME
        AND SAT_CLAIM_LINE_PHARMACY.PRICING_USED_IND = REF_CLAIM_PRICING_USED_IND.CODE)

    LEFT OUTER JOIN REFDATA.CLAIM_LOW_INCOME_SUBSIDY_CODE REF_CLAIM_LOW_INCOME_SUBSIDY_CODE
        ON (HUB_CLAIM_DETAIL.TPA_CLIENT_ID = REF_CLAIM_LOW_INCOME_SUBSIDY_CODE.TPA_CLIENT_ID
        AND HUB_CLAIM_DETAIL.TPA_ID = REF_CLAIM_LOW_INCOME_SUBSIDY_CODE.TPA_ID
        AND HUB_CLAIM_DETAIL.TPA_DIV_ID = REF_CLAIM_LOW_INCOME_SUBSIDY_CODE.TPA_DIV_ID
        AND HUB_CLAIM_DETAIL.DATA_SOURCE_NAME = REF_CLAIM_LOW_INCOME_SUBSIDY_CODE.DATA_SOURCE_NAME
        AND SAT_CLAIM_LINE_PHARMACY.LOW_INCOME_SUBSIDY_CODE = REF_CLAIM_LOW_INCOME_SUBSIDY_CODE.CODE)

    LEFT OUTER JOIN REFDATA.CLAIM_OTHER_COVERAGE_CODE REF_CLAIM_OTHER_COVERAGE_CODE
        ON (HUB_CLAIM_DETAIL.TPA_CLIENT_ID = REF_CLAIM_OTHER_COVERAGE_CODE.TPA_CLIENT_ID
        AND HUB_CLAIM_DETAIL.TPA_ID = REF_CLAIM_OTHER_COVERAGE_CODE.TPA_ID
        AND HUB_CLAIM_DETAIL.TPA_DIV_ID = REF_CLAIM_OTHER_COVERAGE_CODE.TPA_DIV_ID
