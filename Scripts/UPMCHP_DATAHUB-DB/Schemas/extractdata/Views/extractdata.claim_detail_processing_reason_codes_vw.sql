CREATE OR REPLACE VIEW EXTRACTDATA.CLAIM_DETAIL_PROCESSING_REASON_CODES_VW
AS
SELECT 
SAT_CLAIM_LINE_PROCESSING_REASON.HUB_CLAIM_DETAIL_HKEY
,SAT_CLAIM_LINE_PROCESSING_REASON.REASON_TYPE_CODE
,SAT_CLAIM_LINE_PROCESSING_REASON.CODE_POSITION
,SAT_CLAIM_LINE_PROCESSING_REASON.REASON_CODE
,IFNULL(REF_CLAIM_PROCESSING_REASON.CODE_DESC, 'Description Not Found') AS CODE_DESC
,IFF(REF_CLAIM_PROCESSING_REASON.CLAIM_PROCESSING_REASON_HKEY IS NULL, 'Description Not Found', IFNULL(REF_CLAIM_PROCESSING_REASON.CODE_DESC_LONG, 'Undefined')) AS CODE_DESC_LONG
,IFF(REF_CLAIM_PROCESSING_REASON.CLAIM_PROCESSING_REASON_HKEY IS NULL, 'Description Not Found', IFNULL(REF_CLAIM_PROCESSING_REASON.CODE_SPANISH_DESC, 'Undefined')) AS CODE_SPANISH_DESC
,IFF(REF_CLAIM_PROCESSING_REASON.CLAIM_PROCESSING_REASON_HKEY IS NULL, 'Description Not Found', IFNULL(REF_CLAIM_PROCESSING_REASON.HIPAA_277_CODE, 'Undefined')) AS HIPAA_277_CODE
,IFF(REF_CLAIM_PROCESSING_REASON.CLAIM_PROCESSING_REASON_HKEY IS NULL, 'Description Not Found', IFNULL(REF_CLAIM_PROCESSING_REASON.HIPAA_835_CODE, 'Undefined')) AS HIPAA_835_CODE
,HUB_CLAIM_DETAIL.TPA_CLIENT_ID
,HUB_CLAIM_DETAIL.TPA_DIV_ID
,HUB_CLAIM_DETAIL.TPA_ID
,HUB_CLAIM_DETAIL.DATA_SOURCE_NAME
,HUB_CLAIM_DETAIL.CLAIM_NBR
,HUB_CLAIM_DETAIL.CLAIM_LINE_NBR
,HUB_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR
,HUB_CLAIM_DETAIL.CLAIM_LINE_PROCEDURE_ADJ_CODE
,HUB_CLAIM.HUB_CLAIM_HKEY
FROM HUBDATA.HUB_CLAIM
   JOIN HUBDATA.EFF_SAT_CLAIM_HEADER
        ON(EFF_SAT_CLAIM_HEADER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND EFF_SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_CLAIM_HEADER.DELETED_DATETIME > CURRENT_TIMESTAMP())

	LEFT OUTER JOIN HUBDATA.SAT_CLAIM_HEADER
        ON (HUB_CLAIM.HUB_CLAIM_HKEY = SAT_CLAIM_HEADER.HUB_CLAIM_HKEY
        AND SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE)

    JOIN HUBDATA.LNK_CLAIM_DETAIL
        ON (LNK_CLAIM_DETAIL.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

    JOIN HUBDATA.HUB_CLAIM_DETAIL
        ON (HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = LNK_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY)

    JOIN HUBDATA.EFF_SAT_CLAIM_LINE
        ON(EFF_SAT_CLAIM_LINE.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
        AND EFF_SAT_CLAIM_LINE.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_CLAIM_LINE.DELETED_DATETIME > CURRENT_TIMESTAMP())

    JOIN HUBDATA.SAT_CLAIM_LINE_PROCESSING_REASON
        ON (SAT_CLAIM_LINE_PROCESSING_REASON.HUB_CLAIM_DETAIL_HKEY = LNK_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
        AND SAT_CLAIM_LINE_PROCESSING_REASON.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT OUTER JOIN REFDATA.CLAIM_PROCESSING_REASON REF_CLAIM_PROCESSING_REASON
        ON (REF_CLAIM_PROCESSING_REASON.TPA_CLIENT_ID = HUB_CLAIM_DETAIL.TPA_CLIENT_ID
        AND REF_CLAIM_PROCESSING_REASON.TPA_ID = HUB_CLAIM_DETAIL.TPA_ID
        AND REF_CLAIM_PROCESSING_REASON.TPA_DIV_ID = HUB_CLAIM_DETAIL.TPA_DIV_ID
        AND REF_CLAIM_PROCESSING_REASON.DATA_SOURCE_NAME = HUB_CLAIM_DETAIL.DATA_SOURCE_NAME
        AND REF_CLAIM_PROCESSING_REASON.CLAIM_PROCESSING_REASON_TYPE = SAT_CLAIM_LINE_PROCESSING_REASON.REASON_TYPE_CODE
        AND REF_CLAIM_PROCESSING_REASON.CODE = SAT_CLAIM_LINE_PROCESSING_REASON.REASON_CODE)

WHERE SAT_CLAIM_HEADER.CARE_TYPE_NAME <> 'pharmacy'
;