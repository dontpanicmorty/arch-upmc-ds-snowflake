CREATE OR REPLACE VIEW EXTRACTDATA.CLAIM_HEADER_ICD_DIAGNOSIS_CODES_VW
AS
SELECT
HUB_CLAIM.HUB_CLAIM_HKEY
,HUB_CLAIM.TPA_CLIENT_ID
,HUB_CLAIM.TPA_ID
,HUB_CLAIM.TPA_DIV_ID
,HUB_CLAIM.DATA_SOURCE_NAME
,HUB_CLAIM.CLAIM_NBR
,ICD_DIAGNOSIS_CODES.ICD_DIAGNOSIS_CODE_POSITION AS CODE_POSITION_NBR
,ICD_DIAGNOSIS_CODES.ICD_DIAGNOSIS_CODE_VALUE AS CODE_VALUE
,IFF(REF_CLAIM_ICD_DIAGNOSIS.CLAIM_ICD_DIAGNOSIS_HKEY IS NULL, 'Description Not Found', REF_CLAIM_ICD_DIAGNOSIS.CODE_DESC) AS CODE_DESC
,IFF(REF_CLAIM_ICD_DIAGNOSIS.CLAIM_ICD_DIAGNOSIS_HKEY IS NULL, 'Description Not Found', IFNULL(REF_CLAIM_ICD_DIAGNOSIS.CODE_DESC_LONG, 'Undefined')) AS CODE_DESC_LONG
,IFF(REF_CLAIM_ICD_DIAGNOSIS.CLAIM_ICD_DIAGNOSIS_HKEY IS NULL, 'Description Not Found', IFNULL(REF_CLAIM_ICD_DIAGNOSIS.CODE_SPANISH_DESC, 'Undefined')) AS CODE_SPANISH_DESC
,ICD_DIAGNOSIS_CODES.ICD_DIAGNOSIS_CODE_VERSION AS CODE_VERSION
,ICD_DIAGNOSIS_CODES.ICD_DIAGNOSIS_CODE_QUALIFIER AS CODE_QUALIFIER
,ICD_DIAGNOSIS_CODES.POA_CODE
,REF_CLAIM_ICD_DIAGNOSIS.GROUP_CODE
,IFF(REF_CLAIM_ICD_DIAGNOSIS.CLAIM_ICD_DIAGNOSIS_HKEY IS NULL, 'Description Not Found', IFNULL(REF_CLAIM_ICD_DIAGNOSIS.GROUP_DESC, 'Undefined')) AS GROUP_DESC
,IFF(REF_CLAIM_ICD_DIAGNOSIS.ICD_DIAGNOSIS_CATEGORIES = [], NULL ,REF_CLAIM_ICD_DIAGNOSIS.ICD_DIAGNOSIS_CATEGORIES) AS ICD_DIAGNOSIS_CATEGORIES

FROM HUBDATA.HUB_CLAIM

    JOIN HUBDATA.EFF_SAT_CLAIM_HEADER
        ON(EFF_SAT_CLAIM_HEADER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND EFF_SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_CLAIM_HEADER.DELETED_DATETIME > CURRENT_TIMESTAMP())

	LEFT OUTER JOIN HUBDATA.SAT_CLAIM_HEADER
		ON (HUB_CLAIM.HUB_CLAIM_HKEY = SAT_CLAIM_HEADER.HUB_CLAIM_HKEY
		AND SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE)

    JOIN (SELECT
            SAT_CLAIM_ICD_DIAGNOSIS.HUB_CLAIM_HKEY
            ,DIAGNOSIS_CODES.VALUE:"icdDiagnosisCodePosition"::number AS ICD_DIAGNOSIS_CODE_POSITION
            ,DIAGNOSIS_CODES.VALUE:"icdDiagnosisCodeQualifier"::varchar AS ICD_DIAGNOSIS_CODE_QUALIFIER
            ,DIAGNOSIS_CODES.VALUE:"icdDiagnosisCodeValue"::varchar AS ICD_DIAGNOSIS_CODE_VALUE
            ,DIAGNOSIS_CODES.VALUE:"icdDiagnosisCodeVersion"::varchar AS ICD_DIAGNOSIS_CODE_VERSION
            ,DIAGNOSIS_CODES.VALUE:"poaCode"::varchar AS POA_CODE
            FROM HUBDATA.SAT_CLAIM_ICD_DIAGNOSIS
                ,TABLE(FLATTEN(input => SAT_CLAIM_ICD_DIAGNOSIS.ICD_DIAGNOSIS_CODES)) DIAGNOSIS_CODES
            WHERE SAT_CLAIM_ICD_DIAGNOSIS.IS_CURRENT_ROW_FLAG = TRUE
        ) ICD_DIAGNOSIS_CODES
        ON (ICD_DIAGNOSIS_CODES.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY)

    LEFT OUTER JOIN REFDATA.CLAIM_ICD_DIAGNOSIS REF_CLAIM_ICD_DIAGNOSIS
        ON (REF_CLAIM_ICD_DIAGNOSIS.TPA_CLIENT_ID = HUB_CLAIM.TPA_CLIENT_ID
        AND REF_CLAIM_ICD_DIAGNOSIS.TPA_ID = HUB_CLAIM.TPA_ID
        AND REF_CLAIM_ICD_DIAGNOSIS.TPA_DIV_ID = HUB_CLAIM.TPA_DIV_ID
        AND REF_CLAIM_ICD_DIAGNOSIS.DATA_SOURCE_NAME = HUB_CLAIM.DATA_SOURCE_NAME
        AND REF_CLAIM_ICD_DIAGNOSIS.CODE_VERSION = ICD_DIAGNOSIS_CODES.ICD_DIAGNOSIS_CODE_VERSION
        AND REF_CLAIM_ICD_DIAGNOSIS.CODE = ICD_DIAGNOSIS_CODES.ICD_DIAGNOSIS_CODE_VALUE)

WHERE SAT_CLAIM_HEADER.CARE_TYPE_NAME <> 'pharmacy'
;