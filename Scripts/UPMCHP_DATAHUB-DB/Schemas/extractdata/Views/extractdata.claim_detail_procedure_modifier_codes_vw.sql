CREATE OR REPLACE VIEW EXTRACTDATA.CLAIM_DETAIL_PROCEDURE_MODIFIER_CODES_VW
AS
SELECT 
LNK_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
,SAT_CLAIM_LINE_PROCEDURE_MODIFIER.MODIFIER_CODE
,IFNULL(CLAIM_PROCEDURE_MODIFIER.CODE_DESC, 'Description Not Found') AS MODIFIER_DESC
,IFF(CLAIM_PROCEDURE_MODIFIER.CLAIM_PROCEDURE_MODIFIER_HKEY IS NULL, 'Description Not Found', IFNULL(CLAIM_PROCEDURE_MODIFIER.CODE_DESC_LONG, 'Undefined')) AS MODIFIER_DESC_LONG
,IFF(CLAIM_PROCEDURE_MODIFIER.CLAIM_PROCEDURE_MODIFIER_HKEY IS NULL, 'Description Not Found', IFNULL(CLAIM_PROCEDURE_MODIFIER.CODE_SPANISH_DESC, 'Undefined')) AS MODIFIER_SPANISH_DESC
,SAT_CLAIM_LINE_PROCEDURE_MODIFIER.CODE_POSITION
,HUB_CLAIM.DATA_SOURCE_NAME
,HUB_CLAIM.TPA_CLIENT_ID
,HUB_CLAIM.TPA_DIV_ID
,HUB_CLAIM.TPA_ID
,HUB_CLAIM_DETAIL.CLAIM_NBR
,HUB_CLAIM_DETAIL.CLAIM_LINE_NBR
,HUB_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR
,HUB_CLAIM_DETAIL.CLAIM_LINE_PROCEDURE_ADJ_CODE
FROM HUBDATA.HUB_CLAIM_DETAIL

    JOIN HUBDATA.EFF_SAT_CLAIM_LINE
        ON(EFF_SAT_CLAIM_LINE.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
        AND EFF_SAT_CLAIM_LINE.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_CLAIM_LINE.DELETED_DATETIME > CURRENT_TIMESTAMP())

    JOIN HUBDATA.SAT_CLAIM_LINE_PROCEDURE_MODIFIER
        ON (SAT_CLAIM_LINE_PROCEDURE_MODIFIER.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
        AND SAT_CLAIM_LINE_PROCEDURE_MODIFIER.IS_CURRENT_ROW_FLAG = TRUE)
  
    JOIN HUBDATA.LNK_CLAIM_DETAIL
        ON (LNK_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
        AND LNK_CLAIM_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
    
    JOIN HUBDATA.HUB_CLAIM
        ON (HUB_CLAIM.HUB_CLAIM_HKEY = LNK_CLAIM_DETAIL.HUB_CLAIM_HKEY
        AND LNK_CLAIM_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

	LEFT OUTER JOIN HUBDATA.SAT_CLAIM_HEADER
        ON (HUB_CLAIM.HUB_CLAIM_HKEY = SAT_CLAIM_HEADER.HUB_CLAIM_HKEY
        AND SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE)

    JOIN HUBDATA.EFF_SAT_CLAIM_HEADER
        ON(EFF_SAT_CLAIM_HEADER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND EFF_SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_CLAIM_HEADER.DELETED_DATETIME > CURRENT_TIMESTAMP())

    LEFT OUTER JOIN REFDATA.CLAIM_PROCEDURE_MODIFIER
        ON (HUB_CLAIM.TPA_ID = CLAIM_PROCEDURE_MODIFIER.TPA_ID
        AND HUB_CLAIM.TPA_DIV_ID = CLAIM_PROCEDURE_MODIFIER.TPA_DIV_ID
        AND HUB_CLAIM.TPA_CLIENT_ID = CLAIM_PROCEDURE_MODIFIER.TPA_CLIENT_ID
        AND HUB_CLAIM.DATA_SOURCE_NAME = CLAIM_PROCEDURE_MODIFIER.DATA_SOURCE_NAME
        AND  SAT_CLAIM_LINE_PROCEDURE_MODIFIER.MODIFIER_CODE= CLAIM_PROCEDURE_MODIFIER.CODE)
        
WHERE SAT_CLAIM_LINE_PROCEDURE_MODIFIER.IS_CURRENT_ROW_FLAG = TRUE
AND SAT_CLAIM_HEADER.CARE_TYPE_NAME <> 'pharmacy'
;