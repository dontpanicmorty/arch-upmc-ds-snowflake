CREATE OR REPLACE TABLE EXTRACTDATA.CLAIM_JSON
(
    CLAIM_JSON_KEY NUMBER(38,0) NOT NULL
	,INSERT_DATETIME TIMESTAMP_TZ(9) NOT NULL DEFAULT CURRENT_TIMESTAMP()
    ,LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) NOT NULL DEFAULT CURRENT_TIMESTAMP()
	,DATA_SOURCE_NAME VARCHAR
	,CLAIM_NBR VARCHAR
	,MULTISOURCE_CLAIM_IND CHAR(1)
	,JSON_DATA VARIANT
    ,CONSTRAINT PK_CLAIM_JSON PRIMARY KEY (CLAIM_JSON_KEY)
	,CONSTRAINT UK_CLAIM_JSON UNIQUE (DATA_SOURCE_NAME, CLAIM_NBR)
)COMMENT = 'Stores a JSON version of claims data with an array of details under the header for loading to Cosmos'
;