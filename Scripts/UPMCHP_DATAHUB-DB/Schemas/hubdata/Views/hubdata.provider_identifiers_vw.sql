CREATE OR REPLACE VIEW HUBDATA.PROVIDER_IDENTIFIERS_VW AS

WITH PROVIDER_ONE AS (
    SELECT DISTINCT
        HUB_PROVIDER.HUB_PROVIDER_HKEY AS HKEY,
        HUB_PROVIDER.TPA_CLIENT_ID,
        HUB_PROVIDER.TPA_ID,
        HUB_PROVIDER.TPA_DIV_ID,
        HUB_PROVIDER.DATA_SOURCE_NAME,
        HUB_PROVIDER.PROVIDER_ID,
        SAT_PROVIDER_DETAIL.PROVIDER_TYPE_NAME,
        'National Provider Identifier' AS IDENTIFIER_NAME,
        CASE
            WHEN SAT_PROVIDER_DETAIL.PROVIDER_TYPE_NAME = 'Practitioner' THEN 'Type 1'
            WHEN SAT_PROVIDER_DETAIL.PROVIDER_TYPE_NAME = 'Facility' THEN 'Type 2'
            ELSE 'Unknown'
        END AS IDENTIFIER_SUBTYPE,
        SAT_PROVIDER_DETAIL.NATIONAL_PROVIDER_ID AS IDENTIFIER_NBR
    FROM
        HUBDATA.HUB_PROVIDER
    INNER JOIN
        HUBDATA.EFF_SAT_PROVIDER
        ON EFF_SAT_PROVIDER.HUB_PROVIDER_HKEY = HUB_PROVIDER.HUB_PROVIDER_HKEY
        AND EFF_SAT_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_PROVIDER.DELETED_DATETIME > CURRENT_TIMESTAMP()
    INNER JOIN
        HUBDATA.SAT_PROVIDER_DETAIL
        ON SAT_PROVIDER_DETAIL.HUB_PROVIDER_HKEY = HUB_PROVIDER.HUB_PROVIDER_HKEY
        AND SAT_PROVIDER_DETAIL.IS_CURRENT_ROW_FLAG = TRUE
    WHERE
        SAT_PROVIDER_DETAIL.NATIONAL_PROVIDER_ID IS NOT NULL
        AND HUB_PROVIDER.DATA_SOURCE_NAME IN ('MC400Dnt', 'NVA', 'Skygen')
)

, PROVIDER_TWO AS (
    SELECT DISTINCT
        HUB_PROVIDER.HUB_PROVIDER_HKEY AS HKEY,
        HUB_PROVIDER.TPA_CLIENT_ID,
        HUB_PROVIDER.TPA_ID,
        HUB_PROVIDER.TPA_DIV_ID,
        HUB_PROVIDER.DATA_SOURCE_NAME,
        HUB_PROVIDER.PROVIDER_ID,
        SAT_PROVIDER_DETAIL.PROVIDER_TYPE_NAME,
        SAT_PROVIDER_IDENTIFIER.IDENTIFIER_NAME,
        SAT_PROVIDER_IDENTIFIER.IDENTIFIER_SUBTYPE,
        SAT_PROVIDER_IDENTIFIER.IDENTIFIER_NBR
    FROM
        HUBDATA.HUB_PROVIDER
    INNER JOIN
        HUBDATA.EFF_SAT_PROVIDER
        ON EFF_SAT_PROVIDER.HUB_PROVIDER_HKEY = HUB_PROVIDER.HUB_PROVIDER_HKEY
        AND EFF_SAT_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_PROVIDER.DELETED_DATETIME > CURRENT_TIMESTAMP()
    INNER JOIN
        HUBDATA.SAT_PROVIDER_DETAIL
        ON SAT_PROVIDER_DETAIL.HUB_PROVIDER_HKEY = HUB_PROVIDER.HUB_PROVIDER_HKEY
        AND SAT_PROVIDER_DETAIL.IS_CURRENT_ROW_FLAG = TRUE
    INNER JOIN
        HUBDATA.SAT_PROVIDER_IDENTIFIER
        ON SAT_PROVIDER_IDENTIFIER.HUB_PROVIDER_HKEY = HUB_PROVIDER.HUB_PROVIDER_HKEY
        AND SAT_PROVIDER_IDENTIFIER.IS_CURRENT_ROW_FLAG = TRUE
    WHERE HUB_PROVIDER.DATA_SOURCE_NAME NOT IN ('MC400Dnt', 'NVA', 'Skygen')
)

, MEDICAL_GROUP_ONE AS (
    SELECT DISTINCT
        HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY AS HKEY,
        HUB_MEDICAL_GROUP.TPA_CLIENT_ID,
        HUB_MEDICAL_GROUP.TPA_ID,
        HUB_MEDICAL_GROUP.TPA_DIV_ID,
        HUB_MEDICAL_GROUP.DATA_SOURCE_NAME,
        HUB_MEDICAL_GROUP.MEDICAL_GROUP_ID AS PROVIDER_ID,
        'Medical Group' AS PROVIDER_TYPE_NAME,
        'National Provider Identifier' AS IDENTIFIER_NAME,
        'Type 2' AS IDENTIFIER_SUBTYPE,
        SAT_MEDICAL_GROUP_DETAIL.NPI_NBR AS IDENTIFIER_NBR
    FROM
        HUBDATA.HUB_MEDICAL_GROUP
    INNER JOIN
        HUBDATA.EFF_SAT_MEDICAL_GROUP
        ON EFF_SAT_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY = HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY
        AND EFF_SAT_MEDICAL_GROUP.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_MEDICAL_GROUP.DELETED_DATETIME > CURRENT_TIMESTAMP()
    INNER JOIN
        HUBDATA.SAT_MEDICAL_GROUP_DETAIL
        ON SAT_MEDICAL_GROUP_DETAIL.HUB_MEDICAL_GROUP_HKEY = HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY
        AND SAT_MEDICAL_GROUP_DETAIL.IS_CURRENT_ROW_FLAG = TRUE
    WHERE
        SAT_MEDICAL_GROUP_DETAIL.NPI_NBR IS NOT NULL
        AND HUB_MEDICAL_GROUP.DATA_SOURCE_NAME IN ('MC400Dnt', 'NVA', 'Skygen')
)

, MEDICAL_GROUP_TWO AS (
    SELECT DISTINCT
        HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY AS HKEY,
        HUB_MEDICAL_GROUP.TPA_CLIENT_ID,
        HUB_MEDICAL_GROUP.TPA_ID,
        HUB_MEDICAL_GROUP.TPA_DIV_ID,
        HUB_MEDICAL_GROUP.DATA_SOURCE_NAME,
        HUB_MEDICAL_GROUP.MEDICAL_GROUP_ID AS PROVIDER_ID,
        'Medical Group' AS PROVIDER_TYPE_NAME,
        SAT_MEDICAL_GROUP_IDENTIFIER.IDENTIFIER_NAME,
        SAT_MEDICAL_GROUP_IDENTIFIER.IDENTIFIER_SUBTYPE,
        SAT_MEDICAL_GROUP_IDENTIFIER.IDENTIFIER_NBR
    FROM
        HUBDATA.HUB_MEDICAL_GROUP
    INNER JOIN
        HUBDATA.EFF_SAT_MEDICAL_GROUP
        ON EFF_SAT_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY = HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY
        AND EFF_SAT_MEDICAL_GROUP.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_MEDICAL_GROUP.DELETED_DATETIME > CURRENT_TIMESTAMP()
    INNER JOIN
        HUBDATA.SAT_MEDICAL_GROUP_DETAIL
        ON SAT_MEDICAL_GROUP_DETAIL.HUB_MEDICAL_GROUP_HKEY = HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY
        AND SAT_MEDICAL_GROUP_DETAIL.IS_CURRENT_ROW_FLAG = TRUE
    INNER JOIN
        HUBDATA.SAT_MEDICAL_GROUP_IDENTIFIER
        ON SAT_MEDICAL_GROUP_IDENTIFIER.HUB_MEDICAL_GROUP_HKEY = HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY
        AND SAT_MEDICAL_GROUP_IDENTIFIER.IS_CURRENT_ROW_FLAG = TRUE
    WHERE HUB_MEDICAL_GROUP.DATA_SOURCE_NAME NOT IN ('MC400Dnt', 'NVA', 'Skygen')
)

SELECT
    HKEY,
    TPA_CLIENT_ID,
    TPA_ID,
    TPA_DIV_ID,
    DATA_SOURCE_NAME,
    PROVIDER_ID,
    PROVIDER_TYPE_NAME,
    IDENTIFIER_NAME,
    IDENTIFIER_SUBTYPE,
    IDENTIFIER_NBR
FROM
    PROVIDER_ONE

    UNION ALL

SELECT
    HKEY,
    TPA_CLIENT_ID,
    TPA_ID,
    TPA_DIV_ID,
    DATA_SOURCE_NAME,
    PROVIDER_ID,
    PROVIDER_TYPE_NAME,
    IDENTIFIER_NAME,
    IDENTIFIER_SUBTYPE,
    IDENTIFIER_NBR
FROM
    MEDICAL_GROUP_ONE

    UNION ALL

SELECT
    HKEY,
    TPA_CLIENT_ID,
    TPA_ID,
    TPA_DIV_ID,
    DATA_SOURCE_NAME,
    PROVIDER_ID,
    PROVIDER_TYPE_NAME,
    IDENTIFIER_NAME,
    IDENTIFIER_SUBTYPE,
    IDENTIFIER_NBR
FROM
    PROVIDER_TWO

    UNION ALL

SELECT
    HKEY,
    TPA_CLIENT_ID,
    TPA_ID,
    TPA_DIV_ID,
    DATA_SOURCE_NAME,
    PROVIDER_ID,
    PROVIDER_TYPE_NAME,
    IDENTIFIER_NAME,
    IDENTIFIER_SUBTYPE,
    IDENTIFIER_NBR
FROM
    MEDICAL_GROUP_TWO
;