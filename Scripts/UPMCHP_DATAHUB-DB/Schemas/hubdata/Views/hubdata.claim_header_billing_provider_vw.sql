CREATE OR REPLACE VIEW HUBDATA.CLAIM_HEADER_BILLING_PROVIDER_VW
AS
SELECT
HUB_CLAIM.TPA_CLIENT_ID
,HUB_CLAIM.TPA_ID
,HUB_CLAIM.TPA_DIV_ID
,HUB_CLAIM.DATA_SOURCE_NAME
,HUB_CLAIM.CLAIM_NBR
,HUB_MEDICAL_GROUP.MEDICAL_GROUP_ID AS BILLING_PROVIDER_ID
,SAT_MEDICAL_GROUP_DETAIL.MEDICAL_GROUP_NAME AS BILLING_PROVIDER_NAME
,SAT_MEDICAL_GROUP_DETAIL.TAX_ID_NBR AS BILLING_PROVIDER_TIN
,SAT_MEDICAL_GROUP_DETAIL.NPI_NBR AS BILLING_PROVIDER_NPI
,HUB_CLAIM.HUB_CLAIM_HKEY
,HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY

FROM HUBDATA.HUB_CLAIM
    JOIN HUBDATA.EFF_SAT_CLAIM_HEADER
        ON (EFF_SAT_CLAIM_HEADER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND EFF_SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_CLAIM_HEADER.DELETED_DATETIME > CURRENT_TIMESTAMP())

    JOIN HUBDATA.LNK_CLAIM_BILLING_PROVIDER
        ON (LNK_CLAIM_BILLING_PROVIDER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_BILLING_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE)

    JOIN HUBDATA.HUB_MEDICAL_GROUP
        ON (HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY = LNK_CLAIM_BILLING_PROVIDER.HUB_MEDICAL_GROUP_HKEY)

    JOIN HUBDATA.EFF_SAT_MEDICAL_GROUP
        ON (EFF_SAT_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY = LNK_CLAIM_BILLING_PROVIDER.HUB_MEDICAL_GROUP_HKEY
        AND EFF_SAT_MEDICAL_GROUP.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_MEDICAL_GROUP.DELETED_DATETIME > CURRENT_TIMESTAMP())

    LEFT OUTER JOIN HUBDATA.SAT_MEDICAL_GROUP_DETAIL
        ON (SAT_MEDICAL_GROUP_DETAIL.HUB_MEDICAL_GROUP_HKEY = LNK_CLAIM_BILLING_PROVIDER.HUB_MEDICAL_GROUP_HKEY 
        AND SAT_MEDICAL_GROUP_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
;