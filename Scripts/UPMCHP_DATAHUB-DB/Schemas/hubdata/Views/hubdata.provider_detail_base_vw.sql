create or replace view HUBDATA.PROVIDER_DETAIL_BASE_VW(
	TPA_CLIENT_ID,
	TPA_ID,
	TPA_DIV_ID,
	DATA_SOURCE_NAME,
	PROVIDER_ID,
	PROVIDER_TYPE_NAME,
	FULL_NAME,
	FIRST_NAME,
	LAST_NAME,
	MIDDLE_NAME,
	MIDDLE_INITIAL_NAME,
	SUFFIX_NAME,
	GENDER_NAME,
	GENDER_CODE,
	SOCIAL_SECURITY_NBR,
	TAX_ID_NBR,
	EMAIL_ADDRESS,
	DEGREE_TEXT,
	LOCUM_TENENS_IND,
	INVISIBLE_PROVIDER_IND,
	TEMPORARY_PROVIDER_IND,
	NATIONAL_PROVIDER_ID,
	DATE_OF_BIRTH,
	UPIN_NBR,
	WEBSITE_URL,
	PRIMARY_SPECIALTY_NAME,
	PRIMARY_PHO_CODE,
	PRIMARY_PHO_NAME,
	PRIMARY_PHO_TERMINATION_DATE,
	SECONDARY_PHO_CODE,
	SECONDARY_PHO_NAME,
	SECONDARY_PHO_TERMINATION_DATE,
	TERTIARY_PHO_CODE,
	TERTIARY_PHO_NAME,
	TERTIARY_PHO_TERMINATION_DATE,
	PROVIDER_START_DATE,
	ACTIVE_IND,
	PA_MEDICAID_IND,
	PP_ACA_ENHANCED_PAY_IND,
	MALPRACTICE_COVERAGE_IND,
	OWNERSHIP_STATUS_CODE,
	OWNERSHIP_STATUS_DESC,
	URI,
	HKEY
) as
SELECT
HUB_PROVIDER.TPA_CLIENT_ID
,HUB_PROVIDER.TPA_ID
,HUB_PROVIDER.TPA_DIV_ID
,HUB_PROVIDER.DATA_SOURCE_NAME
,HUB_PROVIDER.PROVIDER_ID
,SAT_PROVIDER_DETAIL.PROVIDER_TYPE_NAME
,SAT_PROVIDER_DETAIL.FULL_NAME
,SAT_PROVIDER_DETAIL.FIRST_NAME
,SAT_PROVIDER_DETAIL.LAST_NAME
,SAT_PROVIDER_DETAIL.MIDDLE_NAME
,SAT_PROVIDER_DETAIL.MIDDLE_INITIAL_NAME
,SAT_PROVIDER_DETAIL.SUFFIX_NAME
,SAT_PROVIDER_DETAIL.GENDER_NAME
,CASE UPPER(SAT_PROVIDER_DETAIL.GENDER_NAME)
    WHEN 'MALE' THEN 'M'
    WHEN 'FEMALE' THEN 'F'
    WHEN 'UNKNOWN' THEN 'U'
    ELSE NULL
END AS GENDER_CODE
,SAT_PROVIDER_DETAIL.SOCIAL_SECURITY_NBR
,NULL AS TAX_ID_NBR
,SAT_PROVIDER_DETAIL.EMAIL_ADDRESS
,SAT_PROVIDER_DETAIL.DEGREE_TEXT
,SAT_PROVIDER_DETAIL.LOCUM_TENENS_IND
,SAT_PROVIDER_DETAIL.INVISIBLE_PROVIDER_IND
,SAT_PROVIDER_DETAIL.TEMPORARY_PROVIDER_IND
,SAT_PROVIDER_DETAIL.NATIONAL_PROVIDER_ID
,SAT_PROVIDER_DETAIL.DATE_OF_BIRTH
,SAT_PROVIDER_DETAIL.UPIN_NBR
,NULL AS WEBSITE_URL
,SAT_PROVIDER_DETAIL.PRIMARY_SPECIALTY_NAME
,TO_NUMBER(NULL) AS PRIMARY_PHO_CODE --ODS static tables required
,SAT_PROVIDER_ATTRIBUTE.PRIMARY_PHO_NAME
,SAT_PROVIDER_ATTRIBUTE.PRIMARY_PHO_TERMINATION_DATE
,TO_NUMBER(NULL) AS SECONDARY_PHO_CODE --ODS static tables required
,SAT_PROVIDER_ATTRIBUTE.SECONDARY_PHO_NAME 
,SAT_PROVIDER_ATTRIBUTE.SECONDARY_PHO_TERMINATION_DATE 
,TO_NUMBER(NULL) AS TERTIARY_PHO_CODE --ODS static tables required
,SAT_PROVIDER_ATTRIBUTE.TERTIARY_PHO_NAME
,SAT_PROVIDER_ATTRIBUTE.TERTIARY_PHO_TERMINATION_DATE
,IFF(DATA_SOURCE_NAME = 'Cactus', SAT_PROVIDER_DETAIL.PROVIDER_START_DATE, TO_DATE('1900-01-01')) AS PROVIDER_START_DATE --default for non-Cactus records for now
,IFF(DATA_SOURCE_NAME = 'Cactus', SAT_PROVIDER_DETAIL.PROVIDER_ACTIVE_IND, 'Y') AS ACTIVE_IND --default for non-Cactus records for now
,SAT_PROVIDER_ATTRIBUTE.PA_MEDICAID_IND
,SAT_PROVIDER_ATTRIBUTE.PP_ACA_ENHANCED_PAY_IND 
,SAT_PROVIDER_ATTRIBUTE.MALPRACTICE_COVERAGE_IND
,TO_NUMBER(NULL) AS OWNERSHIP_STATUS_CODE
,NULL AS OWNERSHIP_STATUS_DESC
,NULL AS URI
,HUB_PROVIDER.HUB_PROVIDER_HKEY AS HKEY
FROM HUBDATA.HUB_PROVIDER
    JOIN HUBDATA.EFF_SAT_PROVIDER
        ON(EFF_SAT_PROVIDER.HUB_PROVIDER_HKEY = HUB_PROVIDER.HUB_PROVIDER_HKEY
        AND EFF_SAT_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_PROVIDER.DELETED_DATETIME > CURRENT_TIMESTAMP())
    JOIN HUBDATA.SAT_PROVIDER_DETAIL
        ON (SAT_PROVIDER_DETAIL.HUB_PROVIDER_HKEY = HUB_PROVIDER.HUB_PROVIDER_HKEY
        AND SAT_PROVIDER_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
    LEFT JOIN HUBDATA.SAT_PROVIDER_ATTRIBUTE
        ON (HUB_PROVIDER.HUB_PROVIDER_HKEY = SAT_PROVIDER_ATTRIBUTE.HUB_PROVIDER_HKEY
        AND SAT_PROVIDER_ATTRIBUTE.IS_CURRENT_ROW_FLAG = TRUE)    
WHERE HUB_PROVIDER.DATA_SOURCE_NAME NOT IN ('ESI') --exclude pharmacy records

UNION ALL

SELECT
HUB_MEDICAL_GROUP.TPA_CLIENT_ID
,HUB_MEDICAL_GROUP.TPA_ID
,HUB_MEDICAL_GROUP.TPA_DIV_ID
,HUB_MEDICAL_GROUP.DATA_SOURCE_NAME
,HUB_MEDICAL_GROUP.MEDICAL_GROUP_ID AS PROVIDER_ID
,'Medical Group' AS PROVIDER_TYPE_NAME
,SAT_MEDICAL_GROUP_DETAIL.MEDICAL_GROUP_NAME AS FULL_NAME
,NULL AS FIRST_NAME
,NULL AS LAST_NAME
,NULL AS MIDDLE_NAME
,NULL AS MIDDLE_INITIAL_NAME
,NULL AS SUFFIX_NAME
,NULL AS GENDER_NAME
,NULL AS GENDER_CODE
,NULL AS SOCIAL_SECURITY_NBR
,SAT_MEDICAL_GROUP_DETAIL.TAX_ID_NBR
,SAT_MEDICAL_GROUP_DETAIL.EMAIL_ADDRESS
,NULL AS DEGREE_TEXT
,NULL AS LOCUM_TENENS_IND
,NULL AS INVISIBLE_PROVIDER_IND
,NULL AS TEMPORARY_PROVIDER_IND
,SAT_MEDICAL_GROUP_DETAIL.NPI_NBR AS NATIONAL_PROVIDER_ID
,TO_DATE(NULL) AS DATE_OF_BIRTH
,NULL AS UPIN_NBR
,NULL AS WEBSITE_URL
,NULL AS PRIMARY_SPECIALTY_NAME
,TO_NUMBER(NULL) AS PRIMARY_PHO_CODE
,NULL AS PRIMARY_PHO_NAME
,NULL AS PRIMARY_PHO_TERMINATION_DATE
,TO_NUMBER(NULL) AS SECONDARY_PHO_CODE
,NULL AS SECONDARY_PHO_NAME
,NULL AS SECONDARY_PHO_TERMINATION_DATE
,TO_NUMBER(NULL) AS TERTIARY_PHO_CODE
,NULL AS TERTIARY_PHO_NAME
,NULL AS TERTIARY_PHO_TERMINATION_DATE
,IFF(DATA_SOURCE_NAME = 'Cactus', SAT_MEDICAL_GROUP_DETAIL.MEDICAL_GROUP_START_DATE, TO_DATE('1900-01-01')) AS PROVIDER_START_DATE
,IFF(DATA_SOURCE_NAME = 'Cactus', SAT_MEDICAL_GROUP_DETAIL.MEDICAL_GROUP_ACTIVE_IND, 'Y') AS ACTIVE_IND
,SAT_MEDICAL_GROUP_ATTRIBUTE.PA_MEDICAID_IND
,SAT_MEDICAL_GROUP_ATTRIBUTE.PP_ACA_ENHANCED_PAY_IND
,SAT_MEDICAL_GROUP_ATTRIBUTE.MALPRACTICE_COVERAGE_IND
,TO_NUMBER(NULL) AS OWNERSHIP_STATUS_CODE --ODS static tables required
, SAT_MEDICAL_GROUP_OWNERSHIP_STATUS.OWNERSHIP_NAME AS OWNERSHIP_STATUS_DESC
,NULL AS URI
,HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY AS HKEY

FROM HUBDATA.HUB_MEDICAL_GROUP
    JOIN HUBDATA.EFF_SAT_MEDICAL_GROUP
        ON(EFF_SAT_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY = HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY
        AND EFF_SAT_MEDICAL_GROUP.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_MEDICAL_GROUP.DELETED_DATETIME > CURRENT_TIMESTAMP())
    JOIN HUBDATA.SAT_MEDICAL_GROUP_DETAIL
        ON (SAT_MEDICAL_GROUP_DETAIL.HUB_MEDICAL_GROUP_HKEY = HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY
        AND SAT_MEDICAL_GROUP_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
    LEFT JOIN HUBDATA.SAT_MEDICAL_GROUP_ATTRIBUTE
         ON (HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY = SAT_MEDICAL_GROUP_ATTRIBUTE.HUB_MEDICAL_GROUP_HKEY
         AND SAT_MEDICAL_GROUP_ATTRIBUTE.IS_CURRENT_ROW_FLAG = TRUE)
    LEFT JOIN HUBDATA.SAT_MEDICAL_GROUP_OWNERSHIP_STATUS 
         ON (HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY = SAT_MEDICAL_GROUP_OWNERSHIP_STATUS.HUB_MEDICAL_GROUP_HKEY
         AND SAT_MEDICAL_GROUP_OWNERSHIP_STATUS.IS_CURRENT_ROW_FLAG = TRUE)
WHERE HUB_MEDICAL_GROUP.DATA_SOURCE_NAME NOT IN ('ESI') --exclude pharmacy
;