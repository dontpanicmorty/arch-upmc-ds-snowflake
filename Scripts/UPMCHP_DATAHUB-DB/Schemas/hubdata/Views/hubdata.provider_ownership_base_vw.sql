CREATE OR REPLACE VIEW HUBDATA.PROVIDER_OWNERSHIP_BASE_VW
AS
SELECT
      HUB_MEDICAL_GROUP.TPA_CLIENT_ID
      ,HUB_MEDICAL_GROUP.TPA_ID
      ,HUB_MEDICAL_GROUP.TPA_DIV_ID
      ,HUB_MEDICAL_GROUP.DATA_SOURCE_NAME
      ,HUB_MEDICAL_GROUP.MEDICAL_GROUP_ID
      ,SAT_MEDICAL_GROUP_OWNERSHIP_STATUS.OWNERSHIP_NAME AS OWNERSHIP_DESCRIPTION
      ,SAT_MEDICAL_GROUP_OWNERSHIP_STATUS.ROW_EFFECTIVE_DATETIME AS OWNERSHIP_START_DATE
      ,SAT_MEDICAL_GROUP_OWNERSHIP_STATUS.ROW_EXPIRATION_DATETIME AS OWNERSHIP_TERM_DATE
      ,HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY AS HUB_MEDICAL_GROUP_HKEY
FROM HUBDATA.HUB_MEDICAL_GROUP
JOIN HUBDATA.EFF_SAT_MEDICAL_GROUP 
     ON(EFF_SAT_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY = HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY 
     AND EFF_SAT_MEDICAL_GROUP.IS_CURRENT_ROW_FLAG = TRUE
     AND EFF_SAT_MEDICAL_GROUP.DELETED_DATETIME > CURRENT_TIMESTAMP())
INNER JOIN HUBDATA.SAT_MEDICAL_GROUP_OWNERSHIP_STATUS 
      ON (HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY = SAT_MEDICAL_GROUP_OWNERSHIP_STATUS.HUB_MEDICAL_GROUP_HKEY 
      AND SAT_MEDICAL_GROUP_OWNERSHIP_STATUS.IS_CURRENT_ROW_FLAG = TRUE);

      SELECT * FROM HUBDATA.PROVIDER_OWNERSHIP_BASE_VW;