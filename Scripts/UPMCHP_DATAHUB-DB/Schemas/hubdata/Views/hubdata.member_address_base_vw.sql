--placeholder to frame out member address view instead of jamming it onto claims
CREATE OR REPLACE VIEW HUBDATA.MEMBER_ADDRESS_BASE_VW
COMMENT = 'Joins Member address tables from hubdata data vault model for common member address consumption'
AS
SELECT 
HUB_MEMBER_ADDRESS.HUB_MEMBER_ADDRESS_HKEY
,HUB_MEMBER_ADDRESS.TPA_CLIENT_ID
,HUB_MEMBER_ADDRESS.TPA_ID
,HUB_MEMBER_ADDRESS.TPA_DIV_ID
,HUB_MEMBER_ADDRESS.DATA_SOURCE_NAME
,HUB_MEMBER_ADDRESS.MEMBER_NBR
,HUB_MEMBER_ADDRESS.ADDRESS_TYPE_CODE
,SAT_MEMBER_ADDRESS.ADDRESS_LINE_1_TEXT
,SAT_MEMBER_ADDRESS.ADDRESS_LINE_2_TEXT
,SAT_MEMBER_ADDRESS.CITY_NAME
,SAT_MEMBER_ADDRESS.STATE_ABBREV_NAME
,SAT_MEMBER_ADDRESS.ZIP_CODE_NBR
,SAT_MEMBER_ADDRESS.COUNTY_NAME
,SAT_MEMBER_ADDRESS.FIPS_CODE
,SAT_MEMBER_ADDRESS.FIPS_STATE_CODE
,SAT_MEMBER_ADDRESS.FIPS_COUNTY_CODE
,SAT_MEMBER_ADDRESS.CMS_COUNTY_CODE
,SAT_MEMBER_ADDRESS.LATITUDE_NBR
,SAT_MEMBER_ADDRESS.LONGITUDE_NBR
,SAT_MEMBER_ADDRESS.CONGRESSIONAL_DISTRICT_NAME

FROM HUBDATA.HUB_MEMBER_ADDRESS
    JOIN HUBDATA.EFF_SAT_MEMBER_ADDRESS
        ON(EFF_SAT_MEMBER_ADDRESS.HUB_MEMBER_ADDRESS_HKEY = HUB_MEMBER_ADDRESS.HUB_MEMBER_ADDRESS_HKEY
        AND EFF_SAT_MEMBER_ADDRESS.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_MEMBER_ADDRESS.DELETED_DATETIME > CURRENT_TIMESTAMP())
    JOIN HUBDATA.SAT_MEMBER_ADDRESS
        ON (HUB_MEMBER_ADDRESS.HUB_MEMBER_ADDRESS_HKEY = SAT_MEMBER_ADDRESS.HUB_MEMBER_ADDRESS_HKEY
        AND SAT_MEMBER_ADDRESS.IS_CURRENT_ROW_FLAG = TRUE)
;