CREATE OR REPLACE VIEW HUBDATA.PLAN_BASE_VW
COMMENT = 'Joins core tables from hubdata data vault model for common PLAN detail consumption'
AS
SELECT HUB_PLAN.HUB_PLAN_HKEY
,HUB_PLAN.TPA_CLIENT_ID
,HUB_PLAN.TPA_ID
,HUB_PLAN.TPA_DIV_ID
,HUB_PLAN.DATA_SOURCE_NAME
,HUB_PLAN.PLAN_CODE
,SAT_PLAN_DETAIL_ACA.HIOS_ID AS ACA_HIOS_ID
,SAT_PLAN_DETAIL_ACA.MIN_BENEFIT_YEAR AS ACA_MIN_BENEFIT_YEAR
,SAT_PLAN_DETAIL_ACA.MARKET_SEGMENT_NAME AS ACA_MARKET_SEGMENT_NAME
,SAT_PLAN_DETAIL_ACA.PLAN_TYPE_NAME AS ACA_PLAN_TYPE_NAME
,SAT_PLAN_DETAIL_ACA.PRODUCT_CODE AS ACA_PRODUCT_CODE
,SAT_PLAN_DETAIL_ACA.MARKETING_PLAN_NAME AS ACA_MARKETING_PLAN_NAME
,SAT_PLAN_DETAIL_ACA.METAL_LEVEL_CODE AS ACA_METAL_LEVEL_CODE
,SAT_PLAN_DETAIL_ACA.ON_EXCHANGE_IND AS ACA_ON_EXCHANGE_IND
,SAT_PLAN_DETAIL_ACA.NETWORK_NAME AS ACA_NETWORK_NAME
,SAT_PLAN_DETAIL_ACA.COST_SHARE_TYPE_NAME AS ACA_COST_SHARE_TYPE_NAME
,SAT_PLAN_DETAIL.PLAN_DESC
,SAT_PLAN_DETAIL.PLAN_TYPE_CODE
,SAT_PLAN_DETAIL.LOB_CODE
,CASE
    WHEN SAT_PLAN_DETAIL.LOB_CODE = 'CHC'
        THEN 'CHC'
    WHEN SAT_PLAN_DETAIL.LOB_CODE = 'MA'
        THEN 'MEDICAID'
    WHEN SAT_PLAN_DETAIL.LOB_CODE = 'CHIP'
        THEN 'CHIP'
    WHEN SAT_PLAN_DETAIL.LOB_CODE = 'WL'
        THEN 'WELLNESS'
    WHEN SAT_PLAN_DETAIL.LOB_CODE = 'MC'
        THEN 'MEDICARE'
    WHEN SAT_PLAN_DETAIL.LOB_CODE = 'CM'
        THEN 'COMMERCIAL'
    ELSE IFNULL(SAT_PLAN_DETAIL.LOB_CODE, 'Description Not Found')
END AS LOB_DESC
,SAT_PLAN_DETAIL.LOB_PRODUCT_CODE
,CASE
    WHEN SAT_PLAN_DETAIL.LOB_PRODUCT_CODE IS NULL THEN NULL
    ELSE IFNULL(REF_LOB_PRODUCT_DESC.PROGRAM_DESC, 'Description Not Found')
END AS LOB_PRODUCT_DESC
,CASE
    WHEN SAT_PLAN_DETAIL.PLAN_TYPE_CODE IS NULL THEN NULL
    ELSE IFNULL(REF_LOB_PLAN_TYPE_DESC.PLAN_TYPE_DESC, 'Description Not Found')
END AS LOB_PLAN_TYPE_DESC
,SAT_PLAN_DETAIL.PLAN_CATEGORY_NAME
,SAT_PLAN_DETAIL.HEALTHY_U_IND
,SAT_PLAN_DETAIL.WELLNESS_IND
,SAT_PLAN_DETAIL.COMPANY_CODE
,SAT_PLAN_DETAIL.FUNDING_TYPE_DESC
,SAT_PLAN_DETAIL.BUSINESS_UNIT_DESC
,SAT_PLAN_DETAIL.GRANDFATHERED_ACA_PLAN_IND
,PLAN_SEGMENT.PLAN_SEGMENT_ARRAY
FROM HUBDATA.HUB_PLAN
    JOIN HUBDATA.EFF_SAT_PLAN
        ON(EFF_SAT_PLAN.HUB_PLAN_HKEY = HUB_PLAN.HUB_PLAN_HKEY
        AND EFF_SAT_PLAN.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_PLAN.DELETED_DATETIME > CURRENT_TIMESTAMP())
    LEFT JOIN HUBDATA.SAT_PLAN_DETAIL
        ON (HUB_PLAN.HUB_PLAN_HKEY = SAT_PLAN_DETAIL.HUB_PLAN_HKEY
        AND SAT_PLAN_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
    LEFT JOIN HUBDATA.SAT_PLAN_DETAIL_ACA
        ON (HUB_PLAN.HUB_PLAN_HKEY = SAT_PLAN_DETAIL_ACA.HUB_PLAN_HKEY
        AND SAT_PLAN_DETAIL_ACA.IS_CURRENT_ROW_FLAG = TRUE)
    LEFT JOIN REFDATA.LOB_PLAN_TYPE REF_LOB_PRODUCT_DESC
        ON (REF_LOB_PRODUCT_DESC.PROGRAM_CODE = SAT_PLAN_DETAIL.LOB_PRODUCT_CODE)
        AND REF_LOB_PRODUCT_DESC.TPA_CLIENT_ID = HUB_PLAN.TPA_CLIENT_ID
        AND REF_LOB_PRODUCT_DESC.TPA_ID = HUB_PLAN.TPA_ID
        AND REF_LOB_PRODUCT_DESC.TPA_DIV_ID = HUB_PLAN.TPA_DIV_ID
    LEFT JOIN REFDATA.LOB_PLAN_TYPE REF_LOB_PLAN_TYPE_DESC
        ON (REF_LOB_PLAN_TYPE_DESC.PLAN_TYPE = SAT_PLAN_DETAIL.PLAN_TYPE_CODE)
        AND REF_LOB_PLAN_TYPE_DESC.TPA_CLIENT_ID = HUB_PLAN.TPA_CLIENT_ID
        AND REF_LOB_PLAN_TYPE_DESC.TPA_ID = HUB_PLAN.TPA_ID
        AND REF_LOB_PLAN_TYPE_DESC.TPA_DIV_ID = HUB_PLAN.TPA_DIV_ID
    LEFT JOIN(
        SELECT
            LNK_PLAN_PLAN_SEGMENT.HUB_PLAN_HKEY
            ,ARRAY_AGG(
                OBJECT_CONSTRUCT_KEEP_NULL(
                     'planSegmentCode', HUB_PLAN_SEGMENT.PLAN_SEGMENT_CODE
                    ,'effectiveStartDate', SAT_PLAN_SEGMENT_DETAIL.EFFECTIVE_START_DATE
                    ,'effectiveEndDate', SAT_PLAN_SEGMENT_DETAIL.EFFECTIVE_END_DATE
                    ,'segmentDesc', SAT_PLAN_SEGMENT_DETAIL.SEGMENT_DESC
                    ,'copayDesc', SAT_PLAN_SEGMENT_DETAIL.COPAY_DESC
                    ,'coinsuranceDesc', SAT_PLAN_SEGMENT_DETAIL.COINSURANCE_DESC
                    ,'mentalHealthDesc', SAT_PLAN_SEGMENT_DETAIL.MENTAL_HEALTH_DESC
                    ,'mentalHealthLimitDesc', SAT_PLAN_SEGMENT_DETAIL.MENTAL_HEALTH_LIMIT_DESC
                    ,'otherBenefitsDesc', SAT_PLAN_SEGMENT_DETAIL.OTHER_BENEFITS_DESC
                    ,'outOfNetworkDesc', SAT_PLAN_SEGMENT_DETAIL.OUT_OF_NETWORK_DESC
                    )
            ) WITHIN GROUP (ORDER BY HUB_PLAN_SEGMENT.PLAN_SEGMENT_CODE)
            AS PLAN_SEGMENT_ARRAY

        FROM HUBDATA.HUB_PLAN_SEGMENT
            JOIN HUBDATA.EFF_SAT_PLAN_SEGMENT
                ON (EFF_SAT_PLAN_SEGMENT.HUB_PLAN_SEGMENT_HKEY = HUB_PLAN_SEGMENT.HUB_PLAN_SEGMENT_HKEY
                AND EFF_SAT_PLAN_SEGMENT.IS_CURRENT_ROW_FLAG = TRUE
                AND EFF_SAT_PLAN_SEGMENT.DELETED_DATETIME > CURRENT_TIMESTAMP())
            
            JOIN HUBDATA.SAT_PLAN_SEGMENT_DETAIL
                ON(HUB_PLAN_SEGMENT.HUB_PLAN_SEGMENT_HKEY = SAT_PLAN_SEGMENT_DETAIL.HUB_PLAN_SEGMENT_HKEY
                AND SAT_PLAN_SEGMENT_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

            JOIN HUBDATA.LNK_PLAN_PLAN_SEGMENT
                ON (LNK_PLAN_PLAN_SEGMENT.HUB_PLAN_SEGMENT_HKEY = HUB_PLAN_SEGMENT.HUB_PLAN_SEGMENT_HKEY
                AND LNK_PLAN_PLAN_SEGMENT.IS_CURRENT_ROW_FLAG = TRUE)

        GROUP BY LNK_PLAN_PLAN_SEGMENT.HUB_PLAN_HKEY
    ) PLAN_SEGMENT
     ON (PLAN_SEGMENT.HUB_PLAN_HKEY = HUB_PLAN.HUB_PLAN_HKEY)
;
