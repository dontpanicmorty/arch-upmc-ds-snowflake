--placeholder to frame out member view instead of jamming it onto claims
CREATE OR REPLACE VIEW HUBDATA.MEMBER_DETAIL_BASE_VW
COMMENT = 'Joins core tables from hubdata data vault model for common member detail consumption'
AS
SELECT
HUB_MEMBER.HUB_MEMBER_HKEY
,HUB_MEMBER.TPA_CLIENT_ID
,HUB_MEMBER.TPA_ID
,HUB_MEMBER.TPA_DIV_ID
,HUB_MEMBER.DATA_SOURCE_NAME
,HUB_MEMBER.MEMBER_NBR
,SAT_MEMBER_DETAIL.SUBSCRIBER_NBR
,SAT_MEMBER_DETAIL.PERSON_NBR
,SAT_MEMBER_IDENTIFIER.MASTER_MEMBER_ID
,SAT_MEMBER_DETAIL.MEMBER_TYPE_CODE
,SAT_MEMBER_DETAIL.FULL_NAME
,SAT_MEMBER_DETAIL.LAST_NAME
,SAT_MEMBER_DETAIL.FIRST_NAME
,SAT_MEMBER_DETAIL.MIDDLE_NAME
,SAT_MEMBER_DETAIL.MIDDLE_INITIAL_NAME
,SAT_MEMBER_DETAIL.NAME_SUFFIX
,SAT_MEMBER_DETAIL.SALUTORY_NAME
,SAT_MEMBER_DETAIL.GENDER_CODE
,CASE
    WHEN SAT_MEMBER_DETAIL.GENDER_CODE IS NULL THEN NULL
    ELSE IFNULL(REF_GENDER.CODE_DESC, 'Description Not Found')
END AS GENDER_DESC
,SAT_MEMBER_DETAIL.RACE_CODE
,SAT_MEMBER_DETAIL.BIRTH_DATE
,SAT_MEMBER_DETAIL.DEATH_DATE
,SAT_MEMBER_DETAIL.ADDED_DATE
,SAT_MEMBER_DETAIL.SUBSCRIBER_RELATIONSHIP_CODE
,CASE
    WHEN SAT_MEMBER_DETAIL.SUBSCRIBER_RELATIONSHIP_CODE IS NULL THEN NULL
    ELSE IFNULL(REF_SUBSCRIBER_RELATIONSHIP.CODE_DESC, 'Description Not Found')
END AS SUBSCRIBER_RELATIONSHIP_DESC
,CASE
    WHEN SAT_MEMBER_DETAIL.SUBSCRIBER_RELATIONSHIP_CODE IS NULL THEN NULL
    ELSE IFNULL(REF_SUBSCRIBER_RELATIONSHIP.TYPE_CODE, 'Type Not Found')
END AS SUBSCRIBER_RELATIONSHIP_TYPE_CODE
,SAT_MEMBER_DETAIL.MARITAL_STATUS_CODE
--,NULLIF(SAT_MEMBER_DETAIL.MARITAL_STATUS_CODE IS NULL, NULL, IFNULL(REF_MARITAL_STATUS.CODE_DESC,'Description Not Found')) AS MARITAL_STATUS_DESC
,SAT_MEMBER_DETAIL.MARITAL_STATUS_EFF_DATE
,SAT_MEMBER_DETAIL.RESTRICTED_MEMBER_FLAG
,SAT_MEMBER_DETAIL.DPW_COUNTY_CODE
,SAT_MEMBER_CURRENT_ATTRIBUTE.PRIVACY_RESTRICTION_FLAG
,SAT_MEMBER_CURRENT_ATTRIBUTE.PRIVACY_ALERT_FLAG
,SAT_MEMBER_IDENTIFIER.SOCIAL_SECURITY_NBR
,SAT_MEMBER_IDENTIFIER.EMPI_NBR
,SAT_MEMBER_DETAIL.RESPONSIBLE_PARTY_NAME
,SAT_MEMBER_IDENTIFIER.MA_RECIPIENT_ID
,SAT_MEMBER_IDENTIFIER.MEDICAID_ID
,SAT_MEMBER_IDENTIFIER.EPIC_MR_NBR
,SAT_MEMBER_IDENTIFIER.EPIC_ENT_ID
,SAT_MEMBER_IDENTIFIER.MEDIPAC_MR_NBR
,SAT_MEMBER_IDENTIFIER.HFCA_NBR
,SAT_MEMBER_IDENTIFIER.EMPLOYEE_NBR
,SAT_MEMBER_IDENTIFIER.SECONDARY_MEMBER_IDENTIFIER_TEXT
,SAT_MEMBER_IDENTIFIER.TERTIARY_MEMBER_IDENTIFIER_TEXT
,SAT_MEMBER_CURRENT_ATTRIBUTE.ELIG_STATUS_CODE01 AS CURRENT_ELIG_STATUS_CODE01
,SAT_MEMBER_CURRENT_ATTRIBUTE.ELIG_STATUS_DESC01 AS CURRENT_ELIG_STATUS_DESC01
,SAT_MEMBER_CURRENT_ATTRIBUTE.ELIG_STATUS_CODE02 AS CURRENT_ELIG_STATUS_CODE02
,SAT_MEMBER_CURRENT_ATTRIBUTE.ELIG_STATUS_DESC02 AS CURRENT_ELIG_STATUS_DESC02
,SAT_MEMBER_CURRENT_ATTRIBUTE.PART_D_RISK_FACTOR
,SAT_MEMBER_CURRENT_ATTRIBUTE.CHRONIC_CONDITION_CNT
,SAT_MEMBER_CURRENT_ATTRIBUTE.PREGNANCY_DUE_DATE
,MEMBER_ADDRESS.ADDRESS_ARRAY

FROM HUBDATA.HUB_MEMBER
    JOIN HUBDATA.EFF_SAT_MEMBER
        ON(EFF_SAT_MEMBER.HUB_MEMBER_HKEY = HUB_MEMBER.HUB_MEMBER_HKEY
        AND EFF_SAT_MEMBER.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_MEMBER.DELETED_DATETIME > CURRENT_TIMESTAMP())

    LEFT JOIN HUBDATA.SAT_MEMBER_DETAIL
        ON (HUB_MEMBER.HUB_MEMBER_HKEY = SAT_MEMBER_DETAIL.HUB_MEMBER_HKEY
        AND SAT_MEMBER_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT JOIN HUBDATA.SAT_MEMBER_IDENTIFIER
        ON (HUB_MEMBER.HUB_MEMBER_HKEY = SAT_MEMBER_IDENTIFIER.HUB_MEMBER_HKEY
        AND SAT_MEMBER_IDENTIFIER.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT JOIN HUBDATA.SAT_MEMBER_CURRENT_ATTRIBUTE
        ON (HUB_MEMBER.HUB_MEMBER_HKEY = SAT_MEMBER_CURRENT_ATTRIBUTE.HUB_MEMBER_HKEY
        AND SAT_MEMBER_CURRENT_ATTRIBUTE.IS_CURRENT_ROW_FLAG = TRUE)

    LEFT JOIN REFDATA.GENDER REF_GENDER
        ON (REF_GENDER.CODE = SAT_MEMBER_DETAIL.GENDER_CODE)

    LEFT JOIN REFDATA.MEMBER_RELATIONSHIPS REF_SUBSCRIBER_RELATIONSHIP
        ON (REF_SUBSCRIBER_RELATIONSHIP.CODE = SAT_MEMBER_DETAIL.SUBSCRIBER_RELATIONSHIP_CODE)

    LEFT JOIN (
            SELECT
            LNK_MEMBER_MEMBER_ADDRESS.HUB_MEMBER_HKEY
            ,ARRAY_AGG(
                OBJECT_CONSTRUCT_KEEP_NULL(
                    'addressType', HUB_MEMBER_ADDRESS.ADDRESS_TYPE_CODE
                    ,'addressLine1Text', SAT_MEMBER_ADDRESS.ADDRESS_LINE_1_TEXT
                    ,'addressLine2Text', SAT_MEMBER_ADDRESS.ADDRESS_LINE_2_TEXT
                    ,'cityName', SAT_MEMBER_ADDRESS.CITY_NAME
                    ,'stateAbbrevName', SAT_MEMBER_ADDRESS.STATE_ABBREV_NAME
                    ,'zipCodeNbr', SAT_MEMBER_ADDRESS.ZIP_CODE_NBR
                    ,'countyName', SAT_MEMBER_ADDRESS.COUNTY_NAME
                    ,'fipsCode', SAT_MEMBER_ADDRESS.FIPS_CODE
                    ,'fipsStateCode', SAT_MEMBER_ADDRESS.FIPS_STATE_CODE
                    ,'fipsCountyCode', SAT_MEMBER_ADDRESS.FIPS_COUNTY_CODE
                    ,'cmsCountyCode', SAT_MEMBER_ADDRESS.CMS_COUNTY_CODE
                    ,'latitudeNbr', SAT_MEMBER_ADDRESS.LATITUDE_NBR
                    ,'longitudeNbr', SAT_MEMBER_ADDRESS.LONGITUDE_NBR
                    ,'congressionalDistrictName', SAT_MEMBER_ADDRESS.CONGRESSIONAL_DISTRICT_NAME
                    )
                ) WITHIN GROUP (ORDER BY HUB_MEMBER_ADDRESS.ADDRESS_TYPE_CODE)
                AS ADDRESS_ARRAY

            FROM HUBDATA.HUB_MEMBER_ADDRESS
                JOIN HUBDATA.EFF_SAT_MEMBER_ADDRESS
                    ON (EFF_SAT_MEMBER_ADDRESS.HUB_MEMBER_ADDRESS_HKEY = HUB_MEMBER_ADDRESS.HUB_MEMBER_ADDRESS_HKEY
                    AND EFF_SAT_MEMBER_ADDRESS.IS_CURRENT_ROW_FLAG = TRUE
                    AND EFF_SAT_MEMBER_ADDRESS.DELETED_DATETIME > CURRENT_TIMESTAMP())

                JOIN HUBDATA.SAT_MEMBER_ADDRESS
                    ON (HUB_MEMBER_ADDRESS.HUB_MEMBER_ADDRESS_HKEY = SAT_MEMBER_ADDRESS.HUB_MEMBER_ADDRESS_HKEY
                    AND SAT_MEMBER_ADDRESS.IS_CURRENT_ROW_FLAG = TRUE)

                JOIN HUBDATA.LNK_MEMBER_MEMBER_ADDRESS
                    ON (LNK_MEMBER_MEMBER_ADDRESS.HUB_MEMBER_ADDRESS_HKEY = HUB_MEMBER_ADDRESS.HUB_MEMBER_ADDRESS_HKEY
                    AND LNK_MEMBER_MEMBER_ADDRESS.IS_CURRENT_ROW_FLAG = TRUE)
            GROUP BY LNK_MEMBER_MEMBER_ADDRESS.HUB_MEMBER_HKEY
            ) MEMBER_ADDRESS
        ON (MEMBER_ADDRESS.HUB_MEMBER_HKEY = HUB_MEMBER.HUB_MEMBER_HKEY)
;
