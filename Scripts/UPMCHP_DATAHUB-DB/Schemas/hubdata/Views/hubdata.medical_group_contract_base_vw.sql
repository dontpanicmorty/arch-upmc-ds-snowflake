CREATE OR REPLACE VIEW HUBDATA.MEDICAL_GROUP_CONTRACT_BASE_VW
AS
SELECT DISTINCT
HUB_OFFICE.TPA_CLIENT_ID
,HUB_OFFICE.TPA_ID
,HUB_OFFICE.TPA_DIV_ID
,HUB_OFFICE.DATA_SOURCE_NAME
,NULL AS CARE_TYPE_NAME
,HUB_MEDICAL_GROUP.MEDICAL_GROUP_ID
,HUB_OFFICE.OFFICE_ID
,HUBDATA.HUB_MEDICAL_GROUP_CONTRACT.MEDICAL_GROUP_CONTRACT_ID
,SAT_OFFICE_DETAIL.OFFICE_NAME
,SAT_MEDICAL_GROUP_OFFICE_LINK_DETAIL.MEDICAL_GROUP_ADDRESS_ACTIVE_IND AS PROVIDER_ADDRESS_ACTIVE_IND
,SAT_OFFICE_ADDRESS.ADDRESS_TYPE_CODE AS PROVIDER_ADDRESS_TYPE_CODE
,SAT_OFFICE_ADDRESS.ADDRESS_LINE_1 AS PROVIDER_ADDRESS_LINE_1
,SAT_OFFICE_ADDRESS.ADDRESS_LINE_2 AS PROVIDER_ADDRESS_LINE_2
,SAT_OFFICE_ADDRESS.CITY_NAME AS PROVIDER_CITY_NAME
,SAT_OFFICE_ADDRESS.COUNTY_NAME AS PROVIDER_COUNTY_NAME
,SAT_OFFICE_ADDRESS.ZIP_CODE AS PROVIDER_ZIP_CODE
,SAT_OFFICE_ADDRESS.STATE_ABBREV_NAME AS PROVIDER_STATE_ABBREV_NAME
,SAT_OFFICE_ADDRESS.STATE_FULL_NAME AS PROVIDER_STATE_FULL_NAME
,SAT_OFFICE_ADDRESS.COUNTRY_NAME AS PROVIDER_COUNTRY_NAME
,HUB_STANDARD_ADDRESS.HUB_STANDARD_ADDRESS_HKEY AS MASTER_ADDRESS_HKEY
,SAT_STANDARD_ADDRESS_DETAIL.DELIVERY_LINE_1 AS VERIFIED_DELIVERY_LINE_1
,SAT_STANDARD_ADDRESS_DETAIL.DELIVERY_LINE_2 AS VERIFIED_DELIVERY_LINE_2
,SAT_STANDARD_ADDRESS_DETAIL.DELIVERY_LAST_LINE AS VERIFIED_DELIVERY_LAST_LINE
,SAT_STANDARD_ADDRESS_DETAIL.SMARTY_KEY AS VERIFIED_SMARTY_KEY
,SAT_STANDARD_ADDRESS_DETAIL.URBANIZATION AS VERIFIED_URBANIZATION
,SAT_STANDARD_ADDRESS_DETAIL.PRIMARY_NUMBER AS VERIFIED_PRIMARY_NUMBER
,SAT_STANDARD_ADDRESS_DETAIL.STREET_NAME AS VERIFIED_STREET_NAME
,SAT_STANDARD_ADDRESS_DETAIL.STREET_PREDIRECTION AS VERIFIED_STREET_PREDIRECTION
,SAT_STANDARD_ADDRESS_DETAIL.STREET_POSTDIRECTION AS VERIFIED_STREET_POSTDIRECTION
,SAT_STANDARD_ADDRESS_DETAIL.STREET_SUFFIX AS VERIFIED_STREET_SUFFIX
,SAT_STANDARD_ADDRESS_DETAIL.SECONDARY_NUMBER AS VERIFIED_SECONDARY_NUMBER
,SAT_STANDARD_ADDRESS_DETAIL.SECONDARY_DESIGNATOR AS VERIFIED_SECONDARY_DESIGNATOR
,SAT_STANDARD_ADDRESS_DETAIL.EXTRA_SECONDARY_NUMBER AS VERIFIED_EXTRA_SECONDARY_NUMBER
,SAT_STANDARD_ADDRESS_DETAIL.EXTRA_SECONDARY_DESIGNATOR AS VERIFIED_EXTRA_SECONDARY_DESIGNATOR
,SAT_STANDARD_ADDRESS_DETAIL.PMB_DESIGNATOR AS VERIFIED_PMB_DESIGNATOR
,SAT_STANDARD_ADDRESS_DETAIL.PMB_NUMBER AS VERIFIED_PMB_NUMBER
,SAT_STANDARD_ADDRESS_DETAIL.CITY_NAME AS VERIFIED_CITY_NAME
,SAT_STANDARD_ADDRESS_DETAIL.DEFAULT_CITY_NAME AS VERIFIED_DEFAULT_CITY_NAME
,SAT_STANDARD_ADDRESS_DETAIL.STATE_ABBREVIATION AS VERIFIED_STATE_ABBREVIATION
,SAT_STANDARD_ADDRESS_DETAIL.ZIPCODE AS VERIFIED_ZIPCODE
,SAT_STANDARD_ADDRESS_DETAIL.PLUS4_CODE AS VERIFIED_PLUS4_CODE
,SAT_STANDARD_ADDRESS_DETAIL.RECORD_TYPE AS VERIFIED_RECORD_TYPE
,SAT_STANDARD_ADDRESS_DETAIL.ZIP_TYPE AS VERIFIED_ZIP_TYPE
,SAT_STANDARD_ADDRESS_DETAIL.COUNTY_FIPS AS VERIFIED_COUNTY_FIPS
,SAT_STANDARD_ADDRESS_DETAIL.COUNTY_NAME AS VERIFIED_COUNTY_NAME
,SAT_STANDARD_ADDRESS_DETAIL.CONGRESSIONAL_DISTRICT_CODE AS VERIFIED_CONGRESSIONAL_DISTRICT_CODE
,SAT_STANDARD_ADDRESS_DETAIL.LATITUDE AS VERIFIED_LATITUDE
,SAT_STANDARD_ADDRESS_DETAIL.LONGITUDE AS VERIFIED_LONGITUDE
,SAT_STANDARD_ADDRESS_DETAIL.LAT_LONG_PRECISION AS VERIFIED_LAT_LONG_PRECISION
,SAT_STANDARD_ADDRESS_DETAIL.TIME_ZONE AS VERIFIED_TIME_ZONE
,SAT_STANDARD_ADDRESS_DETAIL.UTC_OFFSET AS VERIFIED_UTC_OFFSET
,SAT_STANDARD_ADDRESS_DETAIL.DST_INDICATOR AS VERIFIED_DST_INDICATOR
,SAT_STANDARD_ADDRESS_DETAIL.DPV_FOOTNOTES AS VERIFIED_DPV_FOOTNOTES
,SAT_STANDARD_ADDRESS_DETAIL.RAW_RESPONSE AS VERIFIED_RAW_RESPONSE
,SAT_MEDICAL_GROUP_OFFICE_LINK_DETAIL.MEDICAL_GROUP_ADDRESS_START_DATE
,SAT_MEDICAL_GROUP_OFFICE_LINK_DETAIL.MEDICAL_GROUP_ADDRESS_TERM_DATE
,HUB_MEDICAL_GROUP_CONTRACT.HUB_MEDICAL_GROUP_CONTRACT_HKEY
,SAT_MEDICAL_GROUP_CONTRACT_STATUS.MEDICAL_GROUP_CONTRACT_ACTIVE_IND
,NULL AS CONTRACT_MODEL_TEXT
,SAT_MEDICAL_GROUP_CONTRACT_STATUS.MEDICAL_GROUP_CONTRACT_START_DATE
,SAT_MEDICAL_GROUP_CONTRACT_STATUS.MEDICAL_GROUP_CONTRACT_END_DATE AS MEDICAL_GROUP_CONTRACT_TERM_DATE
,SAT_MEDICAL_GROUP_CONTRACT_DETAIL.MEDICAL_GROUP_CONTRACT_NAME AS PRODUCT_NAME
,SAT_MEDICAL_GROUP_CONTRACT_DETAIL.MEDICAL_GROUP_CONTRACT_TYPE_NAME AS PRODUCT_TYPE
,SAT_MEDICAL_GROUP_CONTRACT_DETAIL.MEDICAL_GROUP_CONTRACT_LEVEL_NAME AS PRODUCT_LEVEL_NAME
,HUB_OFFICE.HUB_OFFICE_HKEY
,HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY
FROM HUBDATA.HUB_OFFICE
    JOIN HUBDATA.EFF_SAT_OFFICE
        ON (EFF_SAT_OFFICE.HUB_OFFICE_HKEY = HUB_OFFICE.HUB_OFFICE_HKEY
        AND EFF_SAT_OFFICE.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_OFFICE.DELETED_DATETIME > CURRENT_TIMESTAMP())
    INNER JOIN (HUBDATA.LNK_MEDICAL_GROUP_OFFICE 
        JOIN HUBDATA.EFF_SAT_MEDICAL_GROUP 
            ON (EFF_SAT_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY = LNK_MEDICAL_GROUP_OFFICE.HUB_MEDICAL_GROUP_HKEY 
            AND EFF_SAT_MEDICAL_GROUP.IS_CURRENT_ROW_FLAG = TRUE 
            AND EFF_SAT_MEDICAL_GROUP.DELETED_DATETIME > CURRENT_TIMESTAMP())) 
        ON (HUB_OFFICE.HUB_OFFICE_HKEY = LNK_MEDICAL_GROUP_OFFICE.HUB_OFFICE_HKEY 
        AND LNK_MEDICAL_GROUP_OFFICE.IS_CURRENT_ROW_FLAG = TRUE)
    INNER JOIN HUBDATA.HUB_MEDICAL_GROUP 
        ON LNK_MEDICAL_GROUP_OFFICE.HUB_MEDICAL_GROUP_HKEY = HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY
    INNER JOIN HUBDATA.SAT_OFFICE_ADDRESS 
        ON (HUB_OFFICE.HUB_OFFICE_HKEY = SAT_OFFICE_ADDRESS.HUB_OFFICE_HKEY 
        AND SAT_OFFICE_ADDRESS.IS_CURRENT_ROW_FLAG = TRUE)
    INNER JOIN HUBDATA.SAT_OFFICE_DETAIL 
        ON (HUB_OFFICE.HUB_OFFICE_HKEY = SAT_OFFICE_DETAIL.HUB_OFFICE_HKEY 
        AND SAT_OFFICE_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)    
    LEFT JOIN (HUBDATA.LNK_ADDRESS_QUERY_OFFICE 
        JOIN HUBDATA.EFF_SAT_ADDRESS_QUERY 
            ON (EFF_SAT_ADDRESS_QUERY.HUB_ADDRESS_QUERY_HKEY = LNK_ADDRESS_QUERY_OFFICE.HUB_ADDRESS_QUERY_HKEY 
            AND EFF_SAT_ADDRESS_QUERY.IS_CURRENT_ROW_FLAG = TRUE 
            AND EFF_SAT_ADDRESS_QUERY.DELETED_DATETIME > CURRENT_TIMESTAMP())) 
        ON (HUB_OFFICE.HUB_OFFICE_HKEY = LNK_ADDRESS_QUERY_OFFICE.HUB_OFFICE_HKEY 
        AND LNK_ADDRESS_QUERY_OFFICE.IS_CURRENT_ROW_FLAG = TRUE) 
    LEFT JOIN HUBDATA.LNK_ADDRESS_QUERY_STANDARD_ADDRESS 
    ON (LNK_ADDRESS_QUERY_OFFICE.HUB_ADDRESS_QUERY_HKEY = LNK_ADDRESS_QUERY_STANDARD_ADDRESS.HUB_ADDRESS_QUERY_HKEY 
    AND LNK_ADDRESS_QUERY_STANDARD_ADDRESS.IS_CURRENT_ROW_FLAG = TRUE)  
    LEFT JOIN HUBDATA.HUB_STANDARD_ADDRESS 
        ON LNK_ADDRESS_QUERY_STANDARD_ADDRESS.HUB_STANDARD_ADDRESS_HKEY = HUB_STANDARD_ADDRESS.HUB_STANDARD_ADDRESS_HKEY
    LEFT JOIN HUBDATA.SAT_STANDARD_ADDRESS_DETAIL 
        ON (HUB_STANDARD_ADDRESS.HUB_STANDARD_ADDRESS_HKEY = SAT_STANDARD_ADDRESS_DETAIL.HUB_STANDARD_ADDRESS_HKEY 
        AND SAT_STANDARD_ADDRESS_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
    INNER JOIN (HUBDATA.LNK_MEDICAL_GROUP_CONTRACT 
        JOIN HUBDATA.EFF_SAT_MEDICAL_GROUP_CONTRACT 
                ON (EFF_SAT_MEDICAL_GROUP_CONTRACT.HUB_MEDICAL_GROUP_CONTRACT_HKEY = LNK_MEDICAL_GROUP_CONTRACT.HUB_MEDICAL_GROUP_CONTRACT_HKEY 
                AND EFF_SAT_MEDICAL_GROUP_CONTRACT.IS_CURRENT_ROW_FLAG = TRUE 
                AND EFF_SAT_MEDICAL_GROUP_CONTRACT.DELETED_DATETIME > CURRENT_TIMESTAMP())) 
        ON (HUB_MEDICAL_GROUP.HUB_MEDICAL_GROUP_HKEY = LNK_MEDICAL_GROUP_CONTRACT.HUB_MEDICAL_GROUP_HKEY 
        AND LNK_MEDICAL_GROUP_CONTRACT.IS_CURRENT_ROW_FLAG = TRUE)
    INNER JOIN HUBDATA.HUB_MEDICAL_GROUP_CONTRACT 
        ON HUB_MEDICAL_GROUP_CONTRACT.HUB_MEDICAL_GROUP_CONTRACT_HKEY = LNK_MEDICAL_GROUP_CONTRACT.HUB_MEDICAL_GROUP_CONTRACT_HKEY
    JOIN HUBDATA.EFF_SAT_MEDICAL_GROUP_CONTRACT EFF 
        ON (HUB_MEDICAL_GROUP_CONTRACT.HUB_MEDICAL_GROUP_CONTRACT_HKEY = EFF.HUB_MEDICAL_GROUP_CONTRACT_HKEY 
        AND EFF.IS_CURRENT_ROW_FLAG = TRUE 
        AND EFF.DELETED_DATETIME > CURRENT_TIMESTAMP())
    INNER JOIN HUBDATA.SAT_MEDICAL_GROUP_CONTRACT_STATUS 
        ON (HUB_MEDICAL_GROUP_CONTRACT.HUB_MEDICAL_GROUP_CONTRACT_HKEY = SAT_MEDICAL_GROUP_CONTRACT_STATUS.HUB_MEDICAL_GROUP_CONTRACT_HKEY 
        AND SAT_MEDICAL_GROUP_CONTRACT_STATUS.IS_CURRENT_ROW_FLAG = TRUE)
    INNER JOIN HUBDATA.SAT_MEDICAL_GROUP_CONTRACT_DETAIL 
        ON (HUB_MEDICAL_GROUP_CONTRACT.HUB_MEDICAL_GROUP_CONTRACT_HKEY = SAT_MEDICAL_GROUP_CONTRACT_DETAIL.HUB_MEDICAL_GROUP_CONTRACT_HKEY 
        AND SAT_MEDICAL_GROUP_CONTRACT_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
    LEFT JOIN HUBDATA.SAT_MEDICAL_GROUP_OFFICE_LINK_DETAIL
	ON (LNK_MEDICAL_GROUP_OFFICE.LNK_MEDICAL_GROUP_OFFICE_HKEY = SAT_MEDICAL_GROUP_OFFICE_LINK_DETAIL.LNK_MEDICAL_GROUP_OFFICE_HKEY 
	AND SAT_MEDICAL_GROUP_OFFICE_LINK_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
    ;
