CREATE OR REPLACE VIEW HUBDATA.CLAIM_HEADER_REFERRING_PROVIDER_VW
AS
SELECT
HUB_CLAIM.TPA_CLIENT_ID
,HUB_CLAIM.TPA_ID
,HUB_CLAIM.TPA_DIV_ID
,HUB_CLAIM.DATA_SOURCE_NAME
,HUB_CLAIM.CLAIM_NBR
,HUB_PROVIDER.PROVIDER_ID AS REFERRING_PROVIDER_ID
,SAT_PROVIDER_DETAIL.FULL_NAME AS REFERRING_PROVIDER_FULL_NAME
,SAT_PROVIDER_DETAIL.SOCIAL_SECURITY_NBR AS REFERRING_PROVIDER_TIN
,SAT_PROVIDER_DETAIL.NATIONAL_PROVIDER_ID AS REFERRING_PROVIDER_NPI
,HUB_CLAIM.HUB_CLAIM_HKEY
,HUB_PROVIDER.HUB_PROVIDER_HKEY

FROM HUBDATA.HUB_CLAIM
    JOIN HUBDATA.EFF_SAT_CLAIM_HEADER
        ON (EFF_SAT_CLAIM_HEADER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND EFF_SAT_CLAIM_HEADER.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_CLAIM_HEADER.DELETED_DATETIME > CURRENT_TIMESTAMP())

    JOIN HUBDATA.LNK_CLAIM_REFERRING_PROVIDER
        ON (LNK_CLAIM_REFERRING_PROVIDER.HUB_CLAIM_HKEY = HUB_CLAIM.HUB_CLAIM_HKEY
        AND LNK_CLAIM_REFERRING_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE)

    JOIN HUBDATA.HUB_PROVIDER
        ON (HUB_PROVIDER.HUB_PROVIDER_HKEY = LNK_CLAIM_REFERRING_PROVIDER.HUB_PROVIDER_HKEY)

    JOIN HUBDATA.EFF_SAT_PROVIDER
        ON (EFF_SAT_PROVIDER.HUB_PROVIDER_HKEY = LNK_CLAIM_REFERRING_PROVIDER.HUB_PROVIDER_HKEY
        AND EFF_SAT_PROVIDER.IS_CURRENT_ROW_FLAG = TRUE
        AND EFF_SAT_PROVIDER.DELETED_DATETIME > CURRENT_TIMESTAMP())

    LEFT OUTER JOIN HUBDATA.SAT_PROVIDER_DETAIL
        ON (SAT_PROVIDER_DETAIL.HUB_PROVIDER_HKEY = LNK_CLAIM_REFERRING_PROVIDER.HUB_PROVIDER_HKEY
        AND SAT_PROVIDER_DETAIL.IS_CURRENT_ROW_FLAG = TRUE)
;
