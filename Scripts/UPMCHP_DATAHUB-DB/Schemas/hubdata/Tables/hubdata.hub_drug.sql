CREATE OR REPLACE TABLE HUBDATA.HUB_DRUG
(
	HUB_DRUG_HKEY VARCHAR(32) NOT NULL,
	INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP() NOT NULL,
	TPA_CLIENT_ID VARCHAR NOT NULL,
	TPA_ID VARCHAR NOT NULL,
	TPA_DIV_ID VARCHAR NOT NULL,
	DATA_SOURCE_NAME VARCHAR NOT NULL,
	NDC_CODE VARCHAR NOT NULL,
	CONSTRAINT PK_HUB_DRUG PRIMARY KEY (HUB_DRUG_HKEY),
	CONSTRAINT UK_HUB_DRUG UNIQUE (TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, NDC_CODE)
)
COMMENT = 'This is the main HUB table for Drugs'    
;