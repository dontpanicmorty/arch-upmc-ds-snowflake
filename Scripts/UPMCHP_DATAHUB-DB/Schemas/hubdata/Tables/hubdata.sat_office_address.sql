CREATE OR REPLACE TABLE HUBDATA.SAT_OFFICE_ADDRESS
(
	HUB_OFFICE_HKEY VARCHAR(32) NOT NULL,
	ADDRESS_TYPE_CODE VARCHAR NOT NULL,
	ROW_EFFECTIVE_DATETIME TIMESTAMP_TZ(9) NOT NULL,
	ROW_EXPIRATION_DATETIME TIMESTAMP_TZ(9),
	IS_CURRENT_ROW_FLAG BOOLEAN NOT NULL,
	HASH_DIFF VARCHAR(32) NOT NULL,
	ADDRESS_LINE_1 VARCHAR,
	ADDRESS_LINE_2 VARCHAR,
	CITY_NAME VARCHAR,
	COUNTY_NAME VARCHAR,
	ZIP_CODE VARCHAR,
	STATE_ABBREV_NAME VARCHAR,
	STATE_FULL_NAME VARCHAR,
	COUNTRY_NAME VARCHAR,
	CONSTRAINT FK_SATOFFICEADDRESS_HUB_OFFICE_HKEY FOREIGN KEY (HUB_OFFICE_HKEY) REFERENCES HUBDATA.HUB_OFFICE (HUB_OFFICE_HKEY),
	CONSTRAINT PK_SAT_OFFICE_ADDRESS PRIMARY KEY (HUB_OFFICE_HKEY, ADDRESS_TYPE_CODE, ROW_EFFECTIVE_DATETIME),
	CONSTRAINT UK_SAT_OFFICE_ADDRESS UNIQUE (HUB_OFFICE_HKEY, ADDRESS_TYPE_CODE, ROW_EFFECTIVE_DATETIME)
)
COMMENT = 'This table contains sattelite data on office addresses'
