CREATE OR REPLACE TABLE HUBDATA.SAT_CLAIM_ICD_PROCEDURE
(
    HUB_CLAIM_HKEY VARCHAR(32) NOT NULL,
    ROW_EFFECTIVE_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    ROW_EXPIRATION_DATETIME TIMESTAMP_TZ(9),
    IS_CURRENT_ROW_FLAG BOOLEAN DEFAULT TRUE NOT NULL,
    HASH_DIFF VARCHAR(32) NOT NULL,
    ICD_PROCEDURE_CODES VARIANT NOT NULL,
    CONSTRAINT FK_SATCLAIMICDPROCEDURE_HUB_CLAIM_HKEY FOREIGN KEY (HUB_CLAIM_HKEY) REFERENCES HUBDATA.HUB_CLAIM (HUB_CLAIM_HKEY),
    CONSTRAINT PK_SAT_CLAIM_ICD_PROCEDURE PRIMARY KEY (HUB_CLAIM_HKEY, ROW_EFFECTIVE_DATETIME),
    CONSTRAINT UK_SAT_CLAIM_ICD_PROCEDURE UNIQUE (HUB_CLAIM_HKEY, ROW_EFFECTIVE_DATETIME)
)
COMMENT = 'Array of all the ICD Procedure codes for a claim.'
;