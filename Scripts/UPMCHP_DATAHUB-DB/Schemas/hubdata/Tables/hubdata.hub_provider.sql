CREATE OR REPLACE TABLE	HUBDATA.HUB_PROVIDER
(
    HUB_PROVIDER_HKEY VARCHAR(32) NOT NULL,
    INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP() NOT NULL,
    SOURCE_KEY VARCHAR,
    TPA_CLIENT_ID VARCHAR NOT NULL,
    TPA_ID VARCHAR NOT NULL,
    TPA_DIV_ID VARCHAR NOT NULL,
