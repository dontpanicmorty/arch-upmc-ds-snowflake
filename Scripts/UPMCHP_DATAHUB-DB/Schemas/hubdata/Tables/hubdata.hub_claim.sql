CREATE OR REPLACE TABLE HUBDATA.HUB_CLAIM
(
	HUB_CLAIM_HKEY VARCHAR(32) NOT NULL,
	INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP() NOT NULL,
	SOURCE_KEY VARCHAR,
	TPA_CLIENT_ID VARCHAR NOT NULL,
	TPA_ID VARCHAR NOT NULL,
	TPA_DIV_ID VARCHAR NOT NULL,
	DATA_SOURCE_NAME VARCHAR NOT NULL,
	CLAIM_NBR VARCHAR NOT NULL,
	CONSTRAINT PK_HUB_CLAIM PRIMARY KEY (HUB_CLAIM_HKEY),
	CONSTRAINT UK_HUB_CLAIM UNIQUE (TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_NBR)
)
COMMENT = 'This is the main HUB table for Claims'    
;