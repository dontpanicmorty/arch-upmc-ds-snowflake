    PLAN_TYPE_CODE VARCHAR COMMENT 'Plan type code',
    LOB_CODE VARCHAR COMMENT 'Line of business code',
    LOB_PRODUCT_CODE VARCHAR COMMENT 'LOB product code',
    PLAN_CATEGORY_NAME VARCHAR COMMENT 'Plan category name',
    HEALTHY_U_IND VARCHAR COMMENT 'Healthy U indicator',
    WELLNESS_IND VARCHAR COMMENT 'Wellness indicator',
    COMPANY_CODE VARCHAR COMMENT 'Company code',
    FUNDING_TYPE_DESC VARCHAR COMMENT 'Funding type description',
    BUSINESS_UNIT_DESC VARCHAR COMMENT 'Business unit description',
    GRANDFATHERED_ACA_PLAN_IND VARCHAR,
