CREATE OR REPLACE TABLE HUBDATA.HUB_MEMBER
(
    HUB_MEMBER_HKEY VARCHAR(32) NOT NULL,
    INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP() NOT NULL,
    SOURCE_KEY VARCHAR,
    TPA_CLIENT_ID VARCHAR NOT NULL,
    TPA_DIV_ID VARCHAR NOT NULL,
    TPA_ID VARCHAR NOT NULL,
    DATA_SOURCE_NAME VARCHAR NOT NULL,
    MEMBER_NBR VARCHAR NOT NULL,
    CONSTRAINT PK_HUB_MEMBER PRIMARY KEY (HUB_MEMBER_HKEY),
    CONSTRAINT UK_HUB_MEMBER UNIQUE (TPA_CLIENT_ID, TPA_DIV_ID, TPA_ID, DATA_SOURCE_NAME, MEMBER_NBR)
)
COMMENT = 'This HUB table contains Member data'
;