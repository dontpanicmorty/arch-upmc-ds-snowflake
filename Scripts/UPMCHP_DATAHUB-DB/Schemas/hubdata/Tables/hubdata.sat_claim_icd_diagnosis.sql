CREATE OR REPLACE TABLE HUBDATA.SAT_CLAIM_ICD_DIAGNOSIS
(
    HUB_CLAIM_HKEY VARCHAR(32) NOT NULL,
    ROW_EFFECTIVE_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    ROW_EXPIRATION_DATETIME TIMESTAMP_TZ(9),
    IS_CURRENT_ROW_FLAG BOOLEAN DEFAULT TRUE NOT NULL,
    HASH_DIFF VARCHAR(32) NOT NULL,
    ICD_DIAGNOSIS_CODES VARIANT NOT NULL,
