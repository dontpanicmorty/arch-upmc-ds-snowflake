    CONSTRAINT PK_SAT_CLAIM_ICD_DIAGNOSIS PRIMARY KEY (HUB_CLAIM_HKEY, ROW_EFFECTIVE_DATETIME),
    CONSTRAINT UK_SAT_CLAIM_ICD_DIAGNOSIS UNIQUE (HUB_CLAIM_HKEY, ROW_EFFECTIVE_DATETIME)
)
COMMENT = 'JSON array of all the ICD diagnosis codes for a claim.'
