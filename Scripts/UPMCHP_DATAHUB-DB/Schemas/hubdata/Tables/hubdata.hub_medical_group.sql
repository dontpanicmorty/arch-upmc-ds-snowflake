    CONSTRAINT UK_HUB_MEDICAL_GROUP UNIQUE (TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEDICAL_GROUP_ID)
)
COMMENT = 'This is the HUB table for Medical Groups sometimes referred to as billing providers'
;