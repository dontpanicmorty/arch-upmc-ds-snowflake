CREATE OR REPLACE TABLE HUBDATA.SAT_MEMBER_DETAIL
(
    HUB_MEMBER_HKEY VARCHAR(32) NOT NULL,
    ROW_EFFECTIVE_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    ROW_EXPIRATION_DATETIME TIMESTAMP_TZ(9),
    IS_CURRENT_ROW_FLAG BOOLEAN NOT NULL,
    HASH_DIFF VARCHAR(32) NOT NULL,
    MEMBER_TYPE_CODE VARCHAR NOT NULL COMMENT 'Member Type of (MEDICAL UPMC or DENTAL UPMC)',
    SUBSCRIBER_NBR VARCHAR NOT NULL COMMENT 'Member Subscriber Number',
    PERSON_NBR VARCHAR NOT NULL COMMENT 'Member Person Number',
    FULL_NAME VARCHAR NOT NULL COMMENT 'Member Full Name',
    LAST_NAME VARCHAR NOT NULL COMMENT 'Member Last Name',
    FIRST_NAME VARCHAR NOT NULL COMMENT 'Member First Name',
    MIDDLE_NAME VARCHAR COMMENT 'Member Middle Name',
    MIDDLE_INITIAL_NAME VARCHAR COMMENT 'Member Middle Initial',
    NAME_SUFFIX VARCHAR COMMENT 'Member Name Suffix',
    SALUTORY_NAME VARCHAR COMMENT 'Member Salutory  Name',
    GENDER_CODE VARCHAR NOT NULL COMMENT 'Member Gender Code',
    RACE_CODE VARCHAR COMMENT 'Member Race Code',
    ADDED_DATE DATE NOT NULL COMMENT 'Date member was added to the core system',
    BIRTH_DATE DATE NOT NULL COMMENT 'Member Birth Date',
    DEATH_DATE DATE COMMENT 'Member Date Death',
    SUBSCRIBER_RELATIONSHIP_CODE VARCHAR COMMENT 'Subscriber Relationship Code',
    RESPONSIBLE_PARTY_NAME VARCHAR COMMENT 'Member Responsible Party Name',
    MARITAL_STATUS_CODE VARCHAR COMMENT 'Member Marital Status Code',
    MARITAL_STATUS_EFF_DATE DATE COMMENT 'Member Marital Status Code Effective Date',
    DPW_COUNTY_CODE VARCHAR COMMENT 'Member DPW County Code',
    RESTRICTED_MEMBER_FLAG BOOLEAN NOT NULL COMMENT 'Restricted Member Flag (True, False)',
    CONSTRAINT FK_SATMEMBERDETAIL_HUB_MEMBER_HKEY FOREIGN KEY (HUB_MEMBER_HKEY) REFERENCES HUBDATA.HUB_MEMBER (HUB_MEMBER_HKEY),
    CONSTRAINT PK_SAT_MEMBER_DETAIL PRIMARY KEY (HUB_MEMBER_HKEY, ROW_EFFECTIVE_DATETIME),
    CONSTRAINT UK_SAT_MEMBER_DETAIL UNIQUE (HUB_MEMBER_HKEY, ROW_EFFECTIVE_DATETIME)
)
COMMENT = 'This table contains Member Detail data'
;
