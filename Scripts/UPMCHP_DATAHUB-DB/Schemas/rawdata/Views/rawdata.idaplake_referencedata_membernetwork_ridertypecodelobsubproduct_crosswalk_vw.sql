CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_MEMBERNETWORK_RIDERTYPECODELOBSUBPRODUCT_CROSSWALK_VW 
COMMENT = 'View to external stage for Member Network Rider Type Code LOB Sub Product Crosswalk'
AS
SELECT 
    $1 AS CLIENT_ID
    ,$2 AS TPA_ID
    ,$3 AS TPA_DIV_ID
    ,$4 AS RIDER_TYPE_CODE
    ,$5 AS LINE_OF_BUSINESS
    ,$6 AS CARE_TYPE_DESC
    ,$7 AS SUB_PRODUCT_KEY
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/member/membernetwork/MemberNetwork_RiderTypeCodeLOBSubProduct_Crosswalk.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT)
;