CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_ESI_MANUFACTURER_DISCOUNT_TYPE_VW
COMMENT = 'View to external stage for ESI Manufacturer Discount Type refdata set'
AS
SELECT
$1 AS CODE
,$2 AS CODE_DESC
,$3 AS CODE_DESC_LONG
,$4 AS CODE_SPANISH_DESC
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/claim/esi/esi_manufacturer_discount_type.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT);