CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_ESI_SUPPLEMENTAL_COVERAGE_TROOP_QUALIFICATION_VW
COMMENT = 'View to external stage for ESI Supplemental Coverage Troop Qualification refdata set'
AS
SELECT
$1 AS CODE
,$2 AS CODE_DESC
,$3 AS CODE_DESC_LONG
,$4 AS CODE_SPANISH_DESC
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/claim/esi/esi_supplemental_coverage_troop_qualification.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT);