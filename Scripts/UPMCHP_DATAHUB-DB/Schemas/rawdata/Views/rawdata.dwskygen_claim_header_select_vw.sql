CREATE OR REPLACE VIEW RAWDATA.DWSKYGEN_CLAIM_HEADER_SELECT_VW
COMMENT = 'Joins tables from SkygenDW at the claimHeader level for easier change data set processing'
AS
SELECT Factclaims_VW.ENCOUNTER_ID AS CLAIM_NBR
,FactClaims_VW.ORIGINAL_ENCOUNTER_ID
,CASE 
	WHEN FactClaims_VW.DateOfServiceKey > 0 THEN TRY_TO_DATE(TO_CHAR(FactClaims_VW.DateOfServiceKey),'YYYYMMDD')
	ELSE NULL
END as ADMIT_DATE
,CASE 
	WHEN FactClaims_VW.DateReceivedKey > 0 THEN TRY_TO_DATE(TO_CHAR(FactClaims_VW.DateReceivedKey),'YYYYMMDD')
	ELSE NULL
END as CLAIM_ENTRY_DATE
,DimClaimType_VW.ClaimType as SKYGEN_CLAIM_TYPE_CODE
,FactClaims_VW.SUBSCRIBER_ID as MEMBER_NBR
,DimDemographic_VW.Gender as MEMBER_GENDER_CODE
,CASE 
	WHEN DimBenefitLevel_VW.OON_FLAG = 0 THEN 'P'
	WHEN DimBenefitLevel_VW.OON_FLAG = 1 THEN 'N'
	ELSE NULL
END AS PARTICIPATING_PROVIDER_CODE
,DimBenefitPlan_VW.PlanCategory as PLAN_CATEGORY
,FactClaims_VW.PREDETERMINATION_CLAIM_ID
,FactClaims_VW.PAYEE_NPI as BILLING_PROVIDER_NPI
,DimTaxEntity_VW.TAX_ID as BILLING_PROVIDER_TAX_ID
,DimNetwork_VW.Name as NETWORK_ID
,DimNetwork_VW.Name as NETWORK_NAME
,TO_VARCHAR(DimRecordSource_VW.RECORD_SOURCE_ID) AS RECORD_SOURCE_ID
,CONCAT('PAYEE_', DimPayee_VW.PAYEE_ID) AS BILLING_PROVIDER_ID
,CONCAT('LOCATION_', DimLocation_VW.LOCATION_ID) AS PROVIDER_OFFICE_ID
,FactClaims_VW.CLIENT_CLAIM_ID
,FactClaims_VW.ENCOUNTER_ID
,PREMIUM_GROUP_AGG.COMPANY_CODE
,PREMIUM_GROUP_AGG.CORP_ID
,PREMIUM_GROUP_AGG.GROUP_NBR
,PREMIUM_GROUP_AGG.SUB_GROUP_NBR
,PREMIUM_GROUP_AGG.PLAN_TYPE_CODE
,PREMIUM_GROUP_AGG.PLAN_CODE
,ARRAY_UNIQUE_AGG(PREMIUM_GROUP_AGG.RIDER_CODE) AS RIDER_CODES
,CASE
	WHEN FactClaims_VW.PREDETERMINATION_CLAIM_ID IS NULL THEN FALSE
	ELSE TRUE
END IS_PREDETERMINATION_CLAIM_FLAG  

FROM &{DWSKYGEN}.DBO.FactClaims_VW
	INNER JOIN &{DWSKYGEN}.DBO.DimClaimType_VW
		on FactClaims_VW.ClaimTypeKey = DimClaimType_VW.ClaimTypeKey
	INNER JOIN &{DWSKYGEN}.DBO.DimDemographic_VW
		on FactClaims_VW.MemberDemographicKey = DimDemographic_VW.MemberDemographicKey
	INNER JOIN &{DWSKYGEN}.DBO.DimBenefitLevel_VW
		on FactClaims_VW.BenefitLevelKey = DimBenefitLevel_VW.BenefitLevelKey
	INNER JOIN &{DWSKYGEN}.DBO.DimBenefitPlan_VW
		on FactClaims_VW.BenefitPlanKey = DimBenefitPlan_VW.BenefitPlanKey
	INNER JOIN &{DWSKYGEN}.DBO.DimProviderSimple_VW
		on FactClaims_VW.ProviderSimpleKey = DimProviderSimple_VW.ProviderKey
	INNER JOIN &{DWSKYGEN}.DBO.DimNetwork_VW
		on FactClaims_VW.NetworkKey = DimNetwork_VW.NetworkKey
    INNER JOIN &{DWSKYGEN}.DBO.DimTaxEntity_VW
        on FactClaims_VW.TaxEntityKey = DimTaxEntity_VW.TaxEntityKey
    INNER JOIN &{DWSKYGEN}.DBO.DimRecordSource_VW
        on FactClaims_VW.RecordSourceKey = DimRecordSource_VW.RecordSourceKey
	INNER JOIN &{DWSKYGEN}.DBO.DimPayee_VW
		on FactClaims_VW.PayeeKey = DimPayee_VW.PayeeKey
	INNER JOIN &{DWSKYGEN}.DBO.DimLocation_VW
		on FactClaims_VW.LocationKey = DimLocation_VW.LocationKey
	LEFT JOIN (
         SELECT RANK() OVER (PARTITION BY PREMIUMGROUPKEY, PREMIUM_GROUP_ID ORDER BY EFFECTIVE_DATE DESC) AS RNK
		,PREMIUM_GROUP_DETAIL_VW.PREMIUMGROUPKEY
		,PREMIUM_GROUP_DETAIL_VW.PREMIUM_GROUP_ID
		,PREMIUM_GROUP_DETAIL_VW.Company_Code AS COMPANY_CODE
		,PREMIUM_GROUP_DETAIL_VW.CorpID as CORP_ID
		,PREMIUM_GROUP_DETAIL_VW.Group_Number AS GROUP_NBR
		,PREMIUM_GROUP_DETAIL_VW.SubGroup AS SUB_GROUP_NBR
		,PREMIUM_GROUP_DETAIL_VW.Plan_Type AS PLAN_TYPE_CODE
		,PREMIUM_GROUP_DETAIL_VW.Plan_Code AS PLAN_CODE
		,PREMIUM_GROUP_DETAIL_VW.Rider AS RIDER_CODE
		FROM &{DWSKYGEN}.DBO.PREMIUM_GROUP_DETAIL_VW
	) AS PREMIUM_GROUP_AGG
	ON FactClaims_VW.PremiumGroupKey = PREMIUM_GROUP_AGG.PREMIUMGROUPKEY
	AND RNK = 1

WHERE FactClaims_VW.ProcessingStateKey IN (1,2,3,13,14)--TEMPORARY FIX, must go back and fix once skygen does more research on their side.

GROUP BY
CLAIM_NBR
,FactClaims_VW.ORIGINAL_ENCOUNTER_ID
,ADMIT_DATE
,CLAIM_ENTRY_DATE
,SKYGEN_CLAIM_TYPE_CODE
,MEMBER_NBR
,MEMBER_GENDER_CODE
,PARTICIPATING_PROVIDER_CODE
,PLAN_CATEGORY
,FactClaims_VW.PREDETERMINATION_CLAIM_ID
,BILLING_PROVIDER_NPI
,BILLING_PROVIDER_TAX_ID
,NETWORK_ID
,NETWORK_NAME
,RECORD_SOURCE_ID
,BILLING_PROVIDER_ID
,PROVIDER_OFFICE_ID
,FactClaims_VW.CLIENT_CLAIM_ID
,FactClaims_VW.ENCOUNTER_ID
,PREMIUM_GROUP_AGG.COMPANY_CODE
,PREMIUM_GROUP_AGG.CORP_ID
,PREMIUM_GROUP_AGG.GROUP_NBR
,PREMIUM_GROUP_AGG.SUB_GROUP_NBR
,PREMIUM_GROUP_AGG.PLAN_TYPE_CODE
,PREMIUM_GROUP_AGG.PLAN_CODE
;

!set variable_substitution=false;