CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_SOURCE_DATA_MAPPING_VW
COMMENT = 'View to external stage for Data Source Mapping refdata set'
AS
SELECT
$1 AS DATA_DOMAIN_NAME,
$2 AS REFERENCE_SET_NAME,
$3 AS TPA_CLIENT_ID,
$4 AS TPA_ID,
$5 AS TPA_DIV_ID,
$6 AS DATA_SOURCE_NAME,
$7 AS SOURCE_VALUE,
$8 AS SOURCE_VERSION_NBR,
$9 AS TARGET_VALUE,
$10 AS EFFECTIVE_START_DATE,
$11 AS EFFECTIVE_END_DATE,
$12 AS DATA_STEWARD_NAME
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/source_data_mapping.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT);