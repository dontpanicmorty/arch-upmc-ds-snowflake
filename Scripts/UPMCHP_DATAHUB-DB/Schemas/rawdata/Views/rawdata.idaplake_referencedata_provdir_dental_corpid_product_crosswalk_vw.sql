CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_PROVDIR_DENTAL_CORPID_PRODUCT_CROSSWALK_VW 
COMMENT ='View to external stage for Provider Dental Corp ID Product Crosswalk'
AS
SELECT 
    $1 AS PRODUCT_TYPE_NAME
    ,$2 AS PRODUCT_NAME
    ,$3 AS CORP_ID
    ,$4 AS LINE_OF_BUSINESS
    ,$5 AS PROVDIR_H2_SUB_PRODUCT_KEY
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/provider/Provider_Dental_CorpID_Product_Crosswalk.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT)
;