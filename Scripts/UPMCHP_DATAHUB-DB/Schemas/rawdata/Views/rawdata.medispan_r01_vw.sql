CREATE OR REPLACE VIEW RAWDATA.MEDISPAN_R01_VW
COMMENT='View for Average Wholesale Unit Pricing Data from Medispan Files'
AS
WITH MEDISPAN_LOGIC AS (
    
    SELECT  DISTINCT TRIM(SUBSTR(RECORD_DATA,1,11)) NDC,
        TO_NUMBER(INSERT(TRIM(SUBSTR(RECORD_DATA, 28,13)),9,0,'.'),13,5) AWP_UNIT_PRICE,
        TO_NUMBER(INSERT(TRIM(SUBSTR(RECORD_DATA, 59,13)),9,0,'.'),13,5) OLDER_AWP_UNIT_PRICE,
        TO_DATE(TRIM(SUBSTR(RECORD_DATA, 41,8)),'YYYYMMDD') EFFECTIVE_DATE,
        IFNULL(LAG(DATEADD(DAY, -1, EFFECTIVE_DATE)) OVER (PARTITION BY NDC ORDER BY EFFECTIVE_DATE),TO_DATE('0001-01-01')) AS EFFECTIVE_START_DATE,
        IFNULL(LEAD(DATEADD(DAY, -1, EFFECTIVE_DATE)) OVER (PARTITION BY NDC ORDER BY EFFECTIVE_DATE),TO_DATE('9999-12-31')) AS EFFECTIVE_END_DATE
FROM    RAWDATA.MEDISPAN
WHERE   TRIM(SUBSTR(RECORD_DATA, 13,3)) = 'R01'
AND   FILENAME = (
                SELECT DISTINCT FILENAME
                FROM   RAWDATA.MEDISPAN
                ORDER BY FILENAME DESC
                LIMIT 1
            )
    )

SELECT NDC,
OLDER_AWP_UNIT_PRICE AS AWP_UNIT_PRICE,
EFFECTIVE_START_DATE AS EFFECTIVE_START_DATE,
DATEADD(DAY, -1, EFFECTIVE_DATE) AS EFFECTIVE_END_DATE
FROM MEDISPAN_LOGIC
WHERE EFFECTIVE_START_DATE = '0001-01-01'

UNION ALL

SELECT NDC,
AWP_UNIT_PRICE,
EFFECTIVE_DATE AS EFFECTIVE_START_DATE,
EFFECTIVE_END_DATE
FROM MEDISPAN_LOGIC
;
