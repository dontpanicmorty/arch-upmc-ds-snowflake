CREATE OR REPLACE VIEW RAWDATA.CLAIM_ESI_WEEKLY_FINANCIAL_VALIDATION_COUNT_CURRENT_VW
AS

WITH CLAIMS_FILE AS (
SELECT 
'CLAIMS FILE' AS SOURCE_NAME,
COUNT(*) AS RECORD_COUNT
FROM RAWDATA.ESI_CLAIM_WEEKLY
WHERE SUBSTR(RECORD_DATA,1,1) = '4'
AND TRY_TO_DATE(LEFT(RIGHT(FILENAME, 18),8),'MMDDYYYY') = (SELECT DATE FROM RAWDATA.IDAPLAKE_CLAIM_ESI_WEEKLY_FINANCIAL_PMDA_L4YA_CURRENT_VW)
)

,LFGA_FINANCIAL_EXTRACT AS (
SELECT 
'L4GA FINANCIAL EXTRACT' AS SOURCE_NAME,
(
SELECT VOLUME
FROM RAWDATA.IDAPLAKE_CLAIM_ESI_WEEKLY_FINANCIAL_L4GA_CURRENT_VW
) AS L4GA_RECORD_COUNT
)

,PMDA_L4YA_FINANCIAL_EXTRACT AS (
SELECT 
'PMDA_L4YA FINANCIAL EXTRACT' AS SOURCE_NAME,
(
SELECT VOLUME
FROM RAWDATA.IDAPLAKE_CLAIM_ESI_WEEKLY_FINANCIAL_PMDA_L4YA_CURRENT_VW
) AS PMDA_L4YA_RECORD_COUNT
)

SELECT SOURCE_NAME, RECORD_COUNT
FROM CLAIMS_FILE

UNION ALL

SELECT SOURCE_NAME, L4GA_RECORD_COUNT
FROM LFGA_FINANCIAL_EXTRACT

UNION ALL

SELECT SOURCE_NAME, PMDA_L4YA_RECORD_COUNT
FROM PMDA_L4YA_FINANCIAL_EXTRACT
;