CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_CLAIM_OPTUM_MODIFIER_FLAG_EFF_VW
COMMENT = 'View to external stage for Optum Modifier Flag Eff refdata set'
AS
SELECT
$1 AS MODIFIER
,$2 AS DESCRIPTION
,$3 AS AMBULANCE
,$4 AS EFFECTIVE_DATE
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/claim/optum/OPTUM_MODIFIER_FLAG_EFF.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_OPTUM_FILE_FORMAT);