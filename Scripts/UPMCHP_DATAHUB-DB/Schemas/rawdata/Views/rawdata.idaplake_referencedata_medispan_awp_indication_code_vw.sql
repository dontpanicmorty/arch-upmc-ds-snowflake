CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_MEDISPAN_AWP_INDICATION_CODE_VW
COMMENT = 'View to external stage for Medispan AWP Indication Code refdata set'
AS
SELECT
$1 AS CODE
,$2 AS CODE_DESC
,$3 AS CODE_DESC_LONG
,$4 AS CODE_SPANISH_DESC
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/claim/medispan/medispan_awp_indication_code.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT);