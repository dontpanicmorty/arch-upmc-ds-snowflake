CREATE OR REPLACE VIEW RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION_SELECT_VW
COMMENT = 'Joins tables from SkygenDW at the authorization level for easier change data set processing'
AS
SELECT FACTAUTHORIZATIONS_VW.AUTHORIZATION_NUMBER AS AUTHORIZATION_NBR
,FACTAUTHORIZATIONS_VW.SUBSCRIBER_ID AS MEMBER_NBR
,CONCAT('PAYEE_', DIMPAYEE_VW.PAYEE_ID) AS SUBMITTING_PROVIDER_ID
,CONCAT('PROVIDER_', DIMPROVIDERSIMPLE_VW.PROVIDER_ID) AS RENDERING_PROVIDER_ID
,DIMAUTHORIZATIONSTATUS_VW.AUTHORIZATION_STATUS AS STATUS
,DIMAUTHORIZATIONSTATUS_VW.AUTHORIZATIONSTATUSDESCRIPTION AS STATUS_DESC
,DIMDETERMINATIONSTATE_VW.AUTHORIZATIONDETERMINATIONSTATUSID AS DETERMINATION_STATUS
,DIMDETERMINATIONSTATE_VW.AUTHORIZATIONDETERMINATIONSTATUSDESCRIPTION AS DETERMINATION_STATUS_DESC
,CONCAT('LOCATION_', DIMLOCATION_VW.LOCATION_ID) AS OFFICE_ID
,TRY_TO_DATE(TO_CHAR(FACTAUTHORIZATIONS_VW.DATEDETERMINATIONKEY), 'yyyymmdd') AS DETERMINATION_DATE
,PREMIUM_GROUP_AGG.PLAN_CODE
,PREMIUM_GROUP_AGG.PLAN_TYPE_CODE
FROM &{DWSKYGEN}.DBO.FACTAUTHORIZATIONS_VW
JOIN &{DWSKYGEN}.DBO.DIMPAYEE_VW 
    ON FACTAUTHORIZATIONS_VW.PAYEEKEY = DIMPAYEE_VW.PAYEEKEY
JOIN &{DWSKYGEN}.DBO.DIMPROVIDERSIMPLE_VW 
    ON FACTAUTHORIZATIONS_VW.PROVIDERSIMPLEKEY = DIMPROVIDERSIMPLE_VW.PROVIDERKEY
JOIN &{DWSKYGEN}.DBO.DIMAUTHORIZATIONSTATUS_VW
    ON FACTAUTHORIZATIONS_VW.AUTHORIZATIONSTATUSKEY = DIMAUTHORIZATIONSTATUS_VW.AUTHORIZATIONSTATUSKEY
JOIN &{DWSKYGEN}.DBO.DIMAUTHORIZATIONFLAG_VW
    ON FACTAUTHORIZATIONS_VW.AUTHORIZATIONFLAGKEY = DIMAUTHORIZATIONFLAG_VW.AUTHORIZATIONFLAGKEY
JOIN &{DWSKYGEN}.DBO.DIMDETERMINATIONSTATE_VW
    ON FACTAUTHORIZATIONS_VW.DETERMINATIONSTATEKEY = DIMDETERMINATIONSTATE_VW.DETERMINATIONSTATEKEY
JOIN &{DWSKYGEN}.DBO.DIMLOCATION_VW
    ON FACTAUTHORIZATIONS_VW.LOCATIONKEY = DIMLOCATION_VW.LOCATIONKEY
LEFT JOIN (
         SELECT RANK() OVER (PARTITION BY PREMIUMGROUPKEY, PREMIUM_GROUP_ID ORDER BY EFFECTIVE_DATE DESC) AS RNK
		,PREMIUM_GROUP_DETAIL_VW.PREMIUMGROUPKEY
		,PREMIUM_GROUP_DETAIL_VW.PREMIUM_GROUP_ID
		,PREMIUM_GROUP_DETAIL_VW.Company_Code AS COMPANY_CODE
		,PREMIUM_GROUP_DETAIL_VW.CorpID as CORP_ID
		,PREMIUM_GROUP_DETAIL_VW.Group_Number AS GROUP_NBR
		,PREMIUM_GROUP_DETAIL_VW.SubGroup AS SUB_GROUP_NBR
		,PREMIUM_GROUP_DETAIL_VW.Plan_Type AS PLAN_TYPE_CODE
		,PREMIUM_GROUP_DETAIL_VW.Plan_Code AS PLAN_CODE
		,PREMIUM_GROUP_DETAIL_VW.Rider AS RIDER_CODE
		FROM &{DWSKYGEN}.DBO.PREMIUM_GROUP_DETAIL_VW
	) AS PREMIUM_GROUP_AGG
	ON FACTAUTHORIZATIONS_VW.PREMIUMGROUPKEY = PREMIUM_GROUP_AGG.PREMIUMGROUPKEY
	AND RNK = 1
WHERE AUTHORIZATION_NBR NOT IN (SELECT AUTHORIZATION_NUMBER
                                                                              FROM  &{DWSKYGEN}.DBO.FACTAUTHORIZATIONS_VW
                                                                              GROUP BY AUTHORIZATION_NUMBER
                                                                              HAVING COUNT(*) > 1
                                                        ) --remove dupes due to data issue
AND DIMLOCATION_VW.RECORDISCURRENT = TRUE
;


!set variable_substitution=false;