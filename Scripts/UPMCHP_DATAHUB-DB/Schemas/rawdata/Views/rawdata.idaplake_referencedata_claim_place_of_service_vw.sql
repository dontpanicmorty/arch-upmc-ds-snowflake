CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_CLAIM_PLACE_OF_SERVICE_VW
COMMENT = 'View to external stage for Claim Place Of Service refdata set'
AS
SELECT
$1 AS CODE
,$2 AS CODE_DESC
,$3 AS CODE_DESC_LONG
,$4 AS CODE_SPANISH_DESC
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/claim/claim_place_of_service.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT);