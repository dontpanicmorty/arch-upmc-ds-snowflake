CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_HRA_HIA_AUDIT_HISTORICAL_VW AS (
SELECT METADATA$FILENAME,
      METADATA$FILE_ROW_NUMBER,
      $1 AS IDW_FACT_PHARMACY_KEY, 
      $2 AS ORG_HRA_SPENDING_AMT, 
      $3 AS UPD_HRA_SPENDING_AMT, 
      $4 AS ORG_HIA_SPENDING_AMT,
      $5 AS UPD_HIA_SPENDING_AMT,
      $6 AS LOAD_DATE,
      $7 AS CLAIM_ID,
      $8 AS XREF_CLAIM_ID,
      $9 AS TRANSACTION_TYPE_CODE
FROM @RAWDATA.HPDSDATALAKE_IDAPLAKE/claim/esi/historical/hra_hia_audit/hra_hia_audit_historical.csv
(FILE_FORMAT => 'RAWDATA.IDAPLAKE_ESI_HISTORICAL_FILE_FORMAT')
QUALIFY ROW_NUMBER() OVER(PARTITION BY CLAIM_ID, XREF_CLAIM_ID ORDER BY LOAD_DATE) = 1 --exclude erroneous duplicate records where values did not actually change
);