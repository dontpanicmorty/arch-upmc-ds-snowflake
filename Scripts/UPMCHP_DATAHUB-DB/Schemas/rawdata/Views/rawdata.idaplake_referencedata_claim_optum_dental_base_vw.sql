CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_CLAIM_OPTUM_DENTAL_BASE_VW
COMMENT = 'View to external stage for Optum Dental Base refdata set'
AS
SELECT
$1 AS CODE
,$2 AS SHORT_DESCRIPTION
,$3 AS LONG_DESCRIPTION
,$4 AS FULL_DESCRIPTION
,$5 AS STATUS
,$6 AS CATEGORY_CODE
,$7 AS CLASS_CODE
,$8 AS MED_COVG_GUIDELINES
,$9 AS ORAL_HEALTH_ASSMT
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/claim/optum/OPTUM_DENTAL_BASE.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_OPTUM_FILE_FORMAT);