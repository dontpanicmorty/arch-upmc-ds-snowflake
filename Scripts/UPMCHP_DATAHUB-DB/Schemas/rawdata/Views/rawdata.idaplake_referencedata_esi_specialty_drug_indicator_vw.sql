CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_ESI_SPECIALTY_DRUG_INDICATOR_VW
COMMENT = 'View to external stage for ESI Specialty Drug Indicator refdata set'
AS
SELECT
$1 AS GCN_CODE,
TO_DATE($2, 'YYYY-MM-DD') AS EXPIRATION_DATE
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/claim/esi/esi_specialty_drug_indicator.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT);