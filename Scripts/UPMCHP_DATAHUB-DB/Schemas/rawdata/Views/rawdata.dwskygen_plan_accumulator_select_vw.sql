CREATE OR REPLACE VIEW RAWDATA.DWSKYGEN_PLAN_ACCUMULATOR_SELECT_VW
COMMENT = 'Skygen Plan Accumulators'
AS
WITH ROLLOVER_CTE AS (
SELECT DISTINCT
    ELIGIBIILITY_AGG.SUBSCRIBERID AS MEMBER_NBR,
    'Skygen' AS DATA_SOURCE_NAME, 
    'dental' AS CARE_TYPE_NAME,
    TO_VARCHAR(FACTMEMBERACCUMULATORS_VW.MEMBERACCUMULATORID) AS MEMBER_ACCUMULATOR_ID,
    FACTMEMBERACCUMULATORS_VW.MEMBERACCUMULATORDESCRIPTION AS MEMBER_ACCUMULATOR_DESC,
    IFNULL(TRY_TO_DATE(TO_VARCHAR(FACTMEMBERACCUMULATORS_VW.DATEEFFECTIVEKEY), 'YYYYMMDD'),'1900-01-01') AS ACCUMULATOR_EFFECTIVE_START_DATE,
    IFNULL(TRY_TO_DATE(TO_VARCHAR(FACTMEMBERACCUMULATORS_VW.DATETERMINATIONKEY), 'YYYYMMDD'),'9999-12-31') AS ACCUMULATOR_EFFECTIVE_END_DATE,
    IFNULL(TRY_TO_DATE(TO_VARCHAR(FACTPREMIUMGROUPBENEFITPLANS_VW.DATEEFFECTIVEKEY), 'YYYYMMDD'),'1900-01-01') AS PLAN_EFFECTIVE_START_DATE,
    IFNULL(TRY_TO_DATE(TO_VARCHAR(FACTPREMIUMGROUPBENEFITPLANS_VW.DATETERMINATIONKEY), 'YYYYMMDD'),'9999-12-31') AS PLAN_EFFECTIVE_END_DATE,
    DIMCODESET_VW.CODESETDESCRIPTION AS BENEFIT_CODESET_NAME,
    DIMCODESET_VW.CODESETCATEGORYDESCRIPTION AS ACCUMULATOR_CATEGORY,
    DIMCODESET_VW.CODESETCLASSIFICATIONDESCRIPTION AS CODESET_CLASSIFICATION_DESC,
    DIMCODESET_VW.CODESETCATEGORYDESCRIPTION AS CODESET_CATEGORY_DESC,
    DIMPERIODBENEFITLEVEL_VW.PERIODBENEFITLEVELDESCRIPTION AS BENEFIT_LEVEL_DESC,
    LEFT(DIMPREMIUMGROUP_VW.GROUPNUMBER,6) AS GROUP_NBR,
    DIMPREMIUMGROUP_VW.GROUPNAME AS GROUP_NAME,
    PREMIUM_GROUP_AGG.SUB_GROUP_NBR,
    UPPER(DIMBENEFITPLAN_VW.PLANPROGRAMCODE) AS PLAN_CODE,
    DIMBENEFITPLAN_VW.PLANNAME AS PLAN_NAME,
    PREMIUM_GROUP_AGG.PLAN_TYPE_CODE,
    TO_VARCHAR(DIMENROLLEE_VW.ENROLLEE_ID) AS ENROLLEE_ID,
    IFNULL(TRY_TO_DATE(TO_VARCHAR(ELIGIBIILITY_AGG.DATEEFFECTIVEKEY), 'YYYYMMDD'),'1900-01-01') AS ELIGIBILITY_START_DATE,
    IFNULL(TRY_TO_DATE(TO_VARCHAR(ELIGIBIILITY_AGG.DATETERMINATEDKEY), 'YYYYMMDD'),'9999-12-31') AS ELIGIBILITY_END_DATE,
    TO_VARCHAR(DIMBENEFITPLAN_VW.PRODUCT_ID) AS PRODUCT_ID, 
    TO_VARCHAR(DIMCODESET_VW.CODESET_ID) AS CODESET_ID,
    TO_VARCHAR(DIMCODESET_VW.CODESETCATEGORY) AS ACCUMULATOR_TYPE_CODE,
    DIMCODESET_VW.CODESETCATEGORYDESCRIPTION AS ACCUMULATOR_TYPE_DESC,
    CASE
        WHEN MEMBER_ACCUMULATOR_DESC = 'ACCUM_MEM_LIFE' THEN 'Lifetime'
        ELSE FACTMEMBERACCUMULATORS_VW.ACCUMULATORTYPEDESCRIPTION
    END AS ACCUMULATOR_PERIOD_TYPE_DESC,
    TO_VARCHAR(FACTMEMBERACCUMULATORS_VW.PERIODBENEFITLEVELKEY) AS ACCUMULATOR_PERIOD_BENEFIT_LEVEL_CODE,
    DIMPERIODBENEFITLEVEL_VW.PERIODBENEFITLEVELDESCRIPTION AS ACCUMULATOR_PERIOD_BENEFIT_LEVEL_DESC,
    TO_VARCHAR(DIMSUBSCRIBERCONTRACTTYPE_VW.SUBSCRIBERCONTRACTTYPEKEY) AS ACCUMULATOR_THRESHOLD_CODE,
    DIMSUBSCRIBERCONTRACTTYPE_VW.SUBSCRIBERCONTRACTTYPEDESCRIPTION AS ACCUMULATOR_THRESHOLD_DESC,
    TRIM(DIMBENEFITACCUMULATORTYPE_VW.BENEFIT_ACCUM_TYPE) AS SUBSCRIBER_TYPE_CODE,
    CASE 
        WHEN TRIM(DIMBENEFITACCUMULATORTYPE_VW.BENEFIT_ACCUM_TYPE) = 'M' THEN 'Member'
        WHEN TRIM(DIMBENEFITACCUMULATORTYPE_VW.BENEFIT_ACCUM_TYPE)  = 'S' THEN 'Subscriber'
        ELSE 'Unknown'
    END AS SUBSCRIBER_TYPE_DESC,
    TO_VARCHAR(FACTMEMBERACCUMULATORS_VW.CODESETKEY) AS CODESET_CODE,
    CASE
        WHEN DIMPERIODBENEFITLEVEL_VW.OONFLAG = TRUE THEN FALSE
        WHEN DIMPERIODBENEFITLEVEL_VW.OONFLAG = FALSE THEN TRUE
        ELSE NULL
    END AS IN_NETWORK_FLAG,
    CASE 
        WHEN ACCUMULATOR_CATEGORY = 'Deductible' THEN FACTMEMBERACCUMULATORS_VW.DEDUCTIBLEAMOUNT
        WHEN (FACTBENEFITPLANTHRESHOLDS_VW.THRESHOLD_AMOUNT < FACTMEMBERACCUMULATORS_VW.MAXIMUMAMOUNT) THEN (FACTMEMBERACCUMULATORS_VW.MAXIMUMAMOUNT - FACTBENEFITPLANTHRESHOLDS_VW.THRESHOLD_AMOUNT)
        ELSE FACTMEMBERACCUMULATORS_VW.MAXIMUMAMOUNT
    END AS CONSUMED_AMT, 

    FACTBENEFITPLANTHRESHOLDS_VW.THRESHOLD_AMOUNT AS THRESHOLD_AMT,
    FACTMEMBERACCUMULATORS_VW.MAXIMUMROLLOVERAMOUNT AS ROLLOVER_MAX_AMT,
    DIMPERIODBENEFITLEVEL_VW.COINSURANCEFORMULA AS COINSURANCE_FORMULA,
    DIMPERIODBENEFITLEVEL_VW.DEDUCTIBLEFORMULA AS DEDUCTIBLE_FORMULA,
    DIMPERIODBENEFITLEVEL_VW.BENEFITMAXIMUMFORMULA AS BENEFIT_MAX_FORMULA,
    DIMPERIODBENEFITLEVEL_VW.OOPFORMULA AS OUT_OF_POCKET_FORMULA
FROM &{DWSKYGEN}.DBO.FACTMEMBERACCUMULATORS_VW 
    JOIN (SELECT ENROLLEEKEY, BENEFITPLANKEY, PREMIUMGROUPKEY, SUBSCRIBERID, MIN(DATEEFFECTIVEKEY) AS DATEEFFECTIVEKEY, MAX(DATETERMINATEDKEY) AS DATETERMINATEDKEY
          FROM &{DWSKYGEN}.DBO.FACTELIGIBILITY_VW
          WHERE DATEEFFECTIVEKEY <> DATETERMINATEDKEY
          GROUP BY ENROLLEEKEY, BENEFITPLANKEY, PREMIUMGROUPKEY, SUBSCRIBERID
        ) ELIGIBIILITY_AGG
        ON (FACTMEMBERACCUMULATORS_VW.ENROLLEEKEY = ELIGIBIILITY_AGG.ENROLLEEKEY 
        AND FACTMEMBERACCUMULATORS_VW.BENEFITPLANKEY = ELIGIBIILITY_AGG.BENEFITPLANKEY)
    JOIN &{DWSKYGEN}.DBO.DIMENROLLEE_VW
        ON (ELIGIBIILITY_AGG.ENROLLEEKEY = DIMENROLLEE_VW.ENROLLEEKEY)
    JOIN &{DWSKYGEN}.DBO.DIMBENEFITPLAN_VW
        ON (FACTMEMBERACCUMULATORS_VW.BENEFITPLANKEY = DIMBENEFITPLAN_VW.BENEFITPLANKEY)
    JOIN &{DWSKYGEN}.DBO.DIMCODESET_VW
        ON (FACTMEMBERACCUMULATORS_VW.CODESETKEY = DIMCODESET_VW.CODESETKEY)
    JOIN &{DWSKYGEN}.DBO.DIMPERIODBENEFITLEVEL_VW 
        ON (FACTMEMBERACCUMULATORS_VW.PERIODBENEFITLEVELKEY = DIMPERIODBENEFITLEVEL_VW.PERIODBENEFITLEVELKEY)
    JOIN &{DWSKYGEN}.DBO.DIMPREMIUMGROUP_VW
        ON (ELIGIBIILITY_AGG.PREMIUMGROUPKEY = DIMPREMIUMGROUP_VW.PREMIUMGROUPKEY
        AND ((MEMBER_ACCUMULATOR_ID IN (1,3) AND DIMPREMIUMGROUP_VW.EFFECTIVEDATE <= TRY_TO_DATE(TO_VARCHAR(FACTMEMBERACCUMULATORS_VW.DATEEFFECTIVEKEY),'YYYYMMDD'))
        OR MEMBER_ACCUMULATOR_ID = 2)) --lifetime accumulators (MEMBERACCUMULATORID) have effective/termination dates of 0 so we need to ignore dates in joins
LEFT JOIN (
         SELECT RANK() OVER (PARTITION BY PREMIUMGROUPKEY, PREMIUM_GROUP_ID ORDER BY EFFECTIVE_DATE DESC) AS RNK
  ,PREMIUM_GROUP_DETAIL_VW.PREMIUMGROUPKEY
  ,PREMIUM_GROUP_DETAIL_VW.PREMIUM_GROUP_ID
  ,PREMIUM_GROUP_DETAIL_VW.Company_Code AS COMPANY_CODE
  ,PREMIUM_GROUP_DETAIL_VW.CorpID as CORP_ID
  ,PREMIUM_GROUP_DETAIL_VW.Group_Number AS GROUP_NBR
  ,PREMIUM_GROUP_DETAIL_VW.SubGroup AS SUB_GROUP_NBR
  ,PREMIUM_GROUP_DETAIL_VW.Plan_Type AS PLAN_TYPE_CODE
  ,PREMIUM_GROUP_DETAIL_VW.Plan_Code AS PLAN_CODE
  ,PREMIUM_GROUP_DETAIL_VW.Rider AS RIDER_CODE
  FROM &{DWSKYGEN}.DBO.PREMIUM_GROUP_DETAIL_VW
 ) AS PREMIUM_GROUP_AGG
 ON (DIMPREMIUMGROUP_VW.PREMIUMGROUPKEY = PREMIUM_GROUP_AGG.PREMIUMGROUPKEY
     AND RNK = 1)    
JOIN &{DWSKYGEN}.DBO.FACTBENEFITPLANTHRESHOLDS_VW 
        ON (FACTBENEFITPLANTHRESHOLDS_VW.BENEFITPLANKEY = FACTMEMBERACCUMULATORS_VW.BENEFITPLANKEY
        AND FACTMEMBERACCUMULATORS_VW.PERIODBENEFITLEVELKEY = FACTBENEFITPLANTHRESHOLDS_VW.PERIODBENEFITLEVELKEY
        AND FACTMEMBERACCUMULATORS_VW.CODESETKEY = FACTBENEFITPLANTHRESHOLDS_VW.CODESETKEY
        AND CASE 
                WHEN MEMBER_ACCUMULATOR_ID IN ('1', '2') THEN '1'
                WHEN MEMBER_ACCUMULATOR_ID  = '3' THEN '2'
                ELSE MEMBER_ACCUMULATOR_ID
            END = FACTBENEFITPLANTHRESHOLDS_VW.BENEFITACCUMULATORTYPEKEY
        )    
      JOIN &{DWSKYGEN}.DBO.DIMSUBSCRIBERCONTRACTTYPE_VW
        ON (FACTBENEFITPLANTHRESHOLDS_VW.SUBSCRIBERCONTRACTTYPEKEY = DIMSUBSCRIBERCONTRACTTYPE_VW.SUBSCRIBERCONTRACTTYPEKEY)
      JOIN &{DWSKYGEN}.DBO.FACTPREMIUMGROUPPLANPERIODS_VW
        ON (FACTPREMIUMGROUPPLANPERIODS_VW.PREMIUMGROUPKEY = ELIGIBIILITY_AGG.PREMIUMGROUPKEY
        AND FACTPREMIUMGROUPPLANPERIODS_VW.BENEFITPLANKEY = FACTMEMBERACCUMULATORS_VW.BENEFITPLANKEY
        AND ((MEMBER_ACCUMULATOR_ID IN (1,3) AND FACTPREMIUMGROUPPLANPERIODS_VW.DATEEFFECTIVEKEY <= FACTMEMBERACCUMULATORS_VW.DATEEFFECTIVEKEY)
        OR MEMBER_ACCUMULATOR_ID = 2)) --lifetime accumulators (MEMBERACCUMULATORID) have effective/termination dates of 0 so we need to ignore dates in joins
    JOIN &{DWSKYGEN}.DBO.DIMBENEFITACCUMULATORTYPE_VW
        ON (DIMBENEFITACCUMULATORTYPE_VW.BENEFITACCUMULATORTYPEKEY = FACTBENEFITPLANTHRESHOLDS_VW.BENEFITACCUMULATORTYPEKEY)
    JOIN &{DWSKYGEN}.DBO.FACTPREMIUMGROUPBENEFITPLANS_VW
        ON (DIMBENEFITPLAN_VW.BENEFITPLANKEY = FACTPREMIUMGROUPBENEFITPLANS_VW.BENEFITPLANKEY
        AND DIMPREMIUMGROUP_VW.PREMIUMGROUPKEY = FACTPREMIUMGROUPBENEFITPLANS_VW.PREMIUMGROUPKEY)

  WHERE PLAN_CODE LIKE 'R%'
  AND CODESET_CATEGORY_DESC IN ('Benefit Max', 'Deductible', 'Orthodontics')
  AND ACCUMULATOR_THRESHOLD_CODE = 1
  AND ELIGIBIILITY_AGG.PREMIUMGROUPKEY <> 1 
  AND ELIGIBILITY_START_DATE <> ELIGIBILITY_END_DATE
  AND ((MEMBER_ACCUMULATOR_ID IN (1,3) AND ACCUMULATOR_EFFECTIVE_START_DATE <> ACCUMULATOR_EFFECTIVE_END_DATE)
        OR MEMBER_ACCUMULATOR_ID = 2) 
)

, ELIGIBILITY_HISTORY_CTE AS (
SELECT MEMBERNBR,
            TPACLIENT, 
            TPADIVISION, 
            TPAIDOFCLIENT, 
            TO_DATE(TO_CHAR(ELIGIBILITYSTARTDATE), 'YYYYMMDD') AS ELIGIBILITYSTARTDATE,
            IFNULL(TRY_TO_DATE(TO_CHAR(ELIGIBILITYENDDATE), 'YYYYMMDD'), '9999-12-31') AS ELIGIBILITYENDDATE,
            COVERAGEGROUPCODE, 
            SUBGROUPCODE, 
            PLANTYPE,
            PLANCODE, 
            RIDERS
        FROM RAWDATA.MC400_DWOAO_ELIGIBILITYHISTORY
 
        UNION ALL

        SELECT MEMBERNBR,
                TPACLIENT, 
                TPADIVISION, 
                TPAIDOFCLIENT, 
                TO_DATE(TO_CHAR(ELIGIBILITYSTARTDATE), 'YYYYMMDD') AS ELIGIBILITYSTARTDATE,
                IFNULL(TRY_TO_DATE(TO_CHAR(ELIGIBILITYENDDATE), 'YYYYMMDD'), '9999-12-31') AS ELIGIBILITYENDDATE,
                COVERAGEGROUPCODE, 
                SUBGROUPCODE, 
                PLANTYPE,
                PLANCODE, 
                RIDERS
        FROM MC400.DWDNV_NONCLAIMS.ELIGIBILITYHISTORY

)


SELECT DISTINCT
ROLLOVER_CTE.MEMBER_NBR,
IFNULL(MEMBERS_MemberNbr.TpaClient, MEMBERS_EMPNO.TpaClient) AS TPA_CLIENT_ID,
IFNULL(MEMBERS_MemberNbr.TpaIdOfClient, MEMBERS_EMPNO.TpaIdOfClient) AS TPA_ID,
IFNULL(MEMBERS_MemberNbr.TpaDivision, MEMBERS_EMPNO.TpaDivision) AS TPA_DIV_ID,
ROLLOVER_CTE.DATA_SOURCE_NAME, 
ROLLOVER_CTE.CARE_TYPE_NAME,
ROLLOVER_CTE.MEMBER_ACCUMULATOR_ID,
ROLLOVER_CTE.MEMBER_ACCUMULATOR_DESC,
ROLLOVER_CTE.ACCUMULATOR_EFFECTIVE_START_DATE,
ROLLOVER_CTE.ACCUMULATOR_EFFECTIVE_END_DATE,
ROLLOVER_CTE.PLAN_EFFECTIVE_START_DATE,
ROLLOVER_CTE.PLAN_EFFECTIVE_END_DATE,
ROLLOVER_CTE.BENEFIT_CODESET_NAME,
ROLLOVER_CTE.ACCUMULATOR_CATEGORY,
ROLLOVER_CTE.CODESET_CLASSIFICATION_DESC,
ROLLOVER_CTE.CODESET_CATEGORY_DESC,
ROLLOVER_CTE.BENEFIT_LEVEL_DESC,
ROLLOVER_CTE.GROUP_NBR,
ROLLOVER_CTE.GROUP_NAME,
ROLLOVER_CTE.SUB_GROUP_NBR,
ROLLOVER_CTE.PLAN_CODE,
ROLLOVER_CTE.PLAN_NAME,
ROLLOVER_CTE.PLAN_TYPE_CODE,
ROLLOVER_CTE.ENROLLEE_ID,
ROLLOVER_CTE.ELIGIBILITY_START_DATE,
ROLLOVER_CTE.ELIGIBILITY_END_DATE,
ROLLOVER_CTE.PRODUCT_ID, 
ROLLOVER_CTE.CODESET_ID, 
ROLLOVER_CTE.ACCUMULATOR_TYPE_CODE,
ROLLOVER_CTE.ACCUMULATOR_TYPE_DESC,
ROLLOVER_CTE.ACCUMULATOR_PERIOD_TYPE_DESC,
ROLLOVER_CTE.ACCUMULATOR_PERIOD_BENEFIT_LEVEL_CODE,
ROLLOVER_CTE.ACCUMULATOR_PERIOD_BENEFIT_LEVEL_DESC,
ROLLOVER_CTE.ACCUMULATOR_THRESHOLD_CODE,
ROLLOVER_CTE.ACCUMULATOR_THRESHOLD_DESC,
ROLLOVER_CTE.SUBSCRIBER_TYPE_CODE,
ROLLOVER_CTE.SUBSCRIBER_TYPE_DESC,
ROLLOVER_CTE.CODESET_CODE,
ROLLOVER_CTE.IN_NETWORK_FLAG,
ROLLOVER_CTE.CONSUMED_AMT, 
ROLLOVER_CTE.THRESHOLD_AMT,
ROLLOVER_CTE.ROLLOVER_MAX_AMT,
ROLLOVER_CTE.COINSURANCE_FORMULA,
ROLLOVER_CTE.DEDUCTIBLE_FORMULA,
ROLLOVER_CTE.BENEFIT_MAX_FORMULA,
ROLLOVER_CTE.OUT_OF_POCKET_FORMULA

FROM ROLLOVER_CTE
    LEFT OUTER JOIN --Get full list of members from MC400 to find member for claim
            (SELECT MemberNbr, TpaClient, TpaIdOfClient, TpaDivision, MedicaidId
            FROM RAWDATA.MC400_DWOAO_MEMBERS
            UNION ALL
            SELECT MemberNbr, TpaClient, TpaIdOfClient, TpaDivision, MedicaidId
            FROM &{MC400}.DWDNV_NONCLAIMS.MEMBERS
            ) AS MEMBERS_MemberNbr
        ON (ROLLOVER_CTE.MEMBER_NBR = MEMBERS_MemberNbr.MemberNbr)

    LEFT OUTER JOIN ELIGIBILITY_HISTORY_CTE AS EligibilityHistory--Get Eligibility for member found by member in mc400
        ON (EligibilityHistory.TpaClient = MEMBERS_MemberNbr.TpaClient
        AND EligibilityHistory.TpaIdOfClient = MEMBERS_MemberNbr.TpaIdOfClient
        AND EligibilityHistory.TpaDivision = MEMBERS_MemberNbr.TpaDivision
        AND EligibilityHistory.MemberNbr = MEMBERS_MemberNbr.MemberNbr
        AND EligibilityHistory.EligibilityStartDate <= ROLLOVER_CTE.ELIGIBILITY_START_DATE
        AND EligibilityHistory.EligibilityEndDate >= ROLLOVER_CTE.ELIGIBILITY_END_DATE)

     LEFT OUTER JOIN --Find members by EmployeeNbr where eligibility matches
            (SELECT DISTINCT MC400_DWOAO_MEMBERS.MemberNbr, 
                    MC400_DWOAO_MEMBERS.EmployeeNbr,
                    MC400_DWOAO_MEMBERS.TpaClient,
                    MC400_DWOAO_MEMBERS.TpaIdOfClient,
                    MC400_DWOAO_MEMBERS.TpaDivision,
                    MC400_DWOAO_MEMBERS.MedicaidId,
                    ELIGIBILITY_HISTORY_CTE.EligibilityStartDate,
                    ELIGIBILITY_HISTORY_CTE.EligibilityEndDate,
                    ELIGIBILITY_HISTORY_CTE.CoverageGroupCode,
                    ELIGIBILITY_HISTORY_CTE.SubGroupCode,
                    ELIGIBILITY_HISTORY_CTE.PlanType,
                    ELIGIBILITY_HISTORY_CTE.PlanCode,
                    ELIGIBILITY_HISTORY_CTE.Riders
            FROM RAWDATA.MC400_DWOAO_MEMBERS
                JOIN ELIGIBILITY_HISTORY_CTE
                    ON (MC400_DWOAO_MEMBERS.MemberNbr = ELIGIBILITY_HISTORY_CTE.MemberNbr
                    AND MC400_DWOAO_MEMBERS.TpaClient = ELIGIBILITY_HISTORY_CTE.TpaClient
                    AND MC400_DWOAO_MEMBERS.TpaIdOfClient = ELIGIBILITY_HISTORY_CTE.TpaIdOfClient
                    AND MC400_DWOAO_MEMBERS.TpaDivision = ELIGIBILITY_HISTORY_CTE.TpaDivision
                    AND ELIGIBILITY_HISTORY_CTE.PlanType IN ('1','B','D','4')) /*THIS NEEDS TO BE CONVERTED TO A DYNAMIC LOOKUP TO A REF TABLE FOR LOB = MA*/
            ) AS MEMBERS_EMPNO
        ON (MEMBERS_EMPNO.EMPLOYEENBR = ROLLOVER_CTE.MEMBER_NBR
        AND MEMBERS_EMPNO.ELIGIBILITYSTARTDATE <= ROLLOVER_CTE.ELIGIBILITY_START_DATE
        AND MEMBERS_EMPNO.ELIGIBILITYENDDATE >= ROLLOVER_CTE.ELIGIBILITY_END_DATE)
    
    LEFT OUTER JOIN ELIGIBILITY_HISTORY_CTE AS EligibilityHistory_Split --Get Eligibility for members with split policies or surviving annuitants
        ON (EligibilityHistory_Split.TpaClient = MEMBERS_MemberNbr.TpaClient
        AND EligibilityHistory_Split.TpaIdOfClient = MEMBERS_MemberNbr.TpaIdOfClient
        AND EligibilityHistory_Split.TpaDivision = MEMBERS_MemberNbr.TpaDivision
        AND EligibilityHistory_Split.MemberNbr = SUBSTR(IFNULL(MEMBERS_MemberNbr.MedicaidID, MEMBERS_EMPNO.MedicaidID),1,11)
        AND EligibilityHistory_Split.EligibilityStartDate <= ROLLOVER_CTE.ELIGIBILITY_START_DATE
        AND EligibilityHistory_Split.EligibilityEndDate >= ROLLOVER_CTE.ELIGIBILITY_END_DATE)
       
    LEFT OUTER JOIN RAWDATA.MC400_DWOAO_MASTERMEMBERID
        ON (MC400_DWOAO_MASTERMEMBERID.TpaClient = IFNULL(MEMBERS_MemberNbr.TpaClient, MEMBERS_EMPNO.TpaClient)
        AND MC400_DWOAO_MASTERMEMBERID.TpaIdOfClient = IFNULL(MEMBERS_MemberNbr.TpaIdOfClient, MEMBERS_EMPNO.TpaIdOfClient)
        AND MC400_DWOAO_MASTERMEMBERID.TpaDivision = IFNULL(MEMBERS_MemberNbr.TpaDivision, MEMBERS_EMPNO.TpaDivision)
        AND MC400_DWOAO_MASTERMEMBERID.SOURCEID = IFNULL(MEMBERS_MemberNbr.MemberNbr, MEMBERS_EMPNO.MemberNbr))

WHERE IFNULL(MEMBERS_MemberNbr.MemberNbr, MEMBERS_EMPNO.MemberNbr) IS NOT NULL /*handles outlier scenarios where we cant find a match*/ 
AND TPA_CLIENT_ID IS NOT NULL
AND ROLLOVER_CTE.MEMBER_NBR <> '9999999999' /*7/27/20123 HOTFIX. Need input from business on if or how we handle these. Very small percentage*/
;
