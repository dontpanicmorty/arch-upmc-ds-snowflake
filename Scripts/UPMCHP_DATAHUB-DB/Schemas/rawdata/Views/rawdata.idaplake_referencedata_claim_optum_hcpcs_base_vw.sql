CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_CLAIM_OPTUM_HCPCS_BASE_VW
COMMENT = 'View to external stage for Optum HCPCS Base refdata set'
AS
SELECT
$1 AS HCPCS_CODE
,$2 AS SHORT_DESCRIPTION
,$3 AS LONG_DESCRIPTION
,$4 AS FULL_DESCRIPTION
,$5 AS STATUS
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/claim/optum/OPTUM_HCPCS_BASE.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_OPTUM_FILE_FORMAT);