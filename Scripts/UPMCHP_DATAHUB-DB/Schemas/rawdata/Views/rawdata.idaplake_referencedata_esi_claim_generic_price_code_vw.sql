CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_ESI_CLAIM_GENERIC_PRICE_CODE_VW
COMMENT = 'View to external stage for ESI Claim Generic Price Code refdata set'
AS
SELECT
$1 AS CODE
,$2 AS CODE_DESC
,$3 AS CODE_DESC_LONG
,$4 AS CODE_SPANISH_DESC
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/claim/esi/esi_claim_generic_price_code.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT);