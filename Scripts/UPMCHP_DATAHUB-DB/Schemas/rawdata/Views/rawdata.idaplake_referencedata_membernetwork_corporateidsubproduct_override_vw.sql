CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_MEMBERNETWORK_CORPORATEIDSUBPRODUCT_OVERRIDE_VW
COMMENT = 'View to external stage for Member Network Corporate ID SubProduct Override'
AS
SELECT 
    $1 AS CLIENT_ID
    ,$2 AS TPA_ID
    ,$3 AS TPA_DIV_ID
    ,$4 AS CORPORATE_ID
    ,$5 AS COVERAGE_GROUP_CODE
    ,$6 AS PLAN_NAME
    ,$7 AS PLAN_TYPE_CODE
    ,$8 AS IN_PROVIDER_NETWORK_ID
    ,$9 AS OUT_PROVIDER_NETWORK_ID
    ,$10 AS IN_SUB_PRODUCT_KEY
    ,$11 AS OUT_SUB_PRODUCT_KEY
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/member/membernetwork/MemberNetwork_CorporateIdSubProduct_Override.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT)
;