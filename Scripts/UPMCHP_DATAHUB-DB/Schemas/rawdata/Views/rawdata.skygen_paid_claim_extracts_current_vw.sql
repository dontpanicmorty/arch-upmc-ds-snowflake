
CREATE OR REPLACE VIEW RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW
COMMENT = 'Most current version of a claim across all the raw ingested files'
AS
WITH CTE_CURRENT_CLAIM_FILE
AS
(
SELECT DISTINCT FILENAME, CLAIM_NO, ITEM_NO, UTIL.FXN_ARRAY_HASH([BILLED_AMT]) AS CLAIM_LINE_SEQ_NBR
FROM RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS
QUALIFY RANK() OVER (PARTITION BY CLAIM_NO, ITEM_NO, UTIL.FXN_ARRAY_HASH([BILLED_AMT])
    ORDER BY 
        CASE
            WHEN REGEXP_INSTR(SPLIT_PART(FILENAME, '_', 5),'commercial',1,1,0,'i') = 1 THEN --if part 5 has the word commerical we need section 6
                TO_TIMESTAMP_NTZ(SPLIT_PART(SPLIT_PART(FILENAME, '_', 6), '.', 1), 'MMDDYYYY')
            ELSE
                CASE 
                    WHEN LEN(SPLIT_PART(SPLIT_PART(FILENAME,'_',5), '.', 1)) = 8 THEN --if it just a date
                        TO_TIMESTAMP_NTZ(SPLIT_PART(SPLIT_PART(FILENAME,'_',5), '.', 1), 'MMDDYYYY')
                    WHEN LEN(SPLIT_PART(SPLIT_PART(FILENAME,'_',5), '.', 1)) = 12 THEN --if it is a date and time 
                        TO_TIMESTAMP_NTZ(SPLIT_PART(SPLIT_PART(FILENAME,'_',5), '.', 1), 'YYYYMMDDHHMI')
                    ELSE TO_TIMESTAMP_NTZ('THROW ERROR')
                END
        END
     DESC) = 1

)

,CTE_CLAIM_WITH_MULTI_MEMBER
AS
(
SELECT
CLAIM_NO, COUNT(1) AS MEMBER_COUNT
FROM (SELECT DISTINCT
    SKYGEN_PAID_CLAIM_EXTRACTS.CLAIM_NO
    ,SKYGEN_PAID_CLAIM_EXTRACTS.SUBSCRIBER_ID
    FROM RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS
        JOIN CTE_CURRENT_CLAIM_FILE
            ON (CTE_CURRENT_CLAIM_FILE.FILENAME = SKYGEN_PAID_CLAIM_EXTRACTS.FILENAME
            AND CTE_CURRENT_CLAIM_FILE.CLAIM_NO = SKYGEN_PAID_CLAIM_EXTRACTS.CLAIM_NO
            AND CTE_CURRENT_CLAIM_FILE.ITEM_NO = SKYGEN_PAID_CLAIM_EXTRACTS.ITEM_NO
            AND CTE_CURRENT_CLAIM_FILE.CLAIM_LINE_SEQ_NBR = UTIL.FXN_ARRAY_HASH([SKYGEN_PAID_CLAIM_EXTRACTS.BILLED_AMT]))
    ) CLAIM_MEMBER
GROUP BY CLAIM_NO
HAVING COUNT(1) > 1
)

