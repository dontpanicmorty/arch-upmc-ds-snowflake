CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_CLAIM_AUTHORIZATION_STATUS_VW
COMMENT = 'View to external stage for Claim Authorization Status refdata set'
AS
SELECT
$1 AS AUTHORIZATION_STATUS
,$2 AS AUTHORIZATION_STATUS_DESCRIPTION
,$3 AS DATA_SOURCE_NAME
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/claim/claim_authorization_status.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT)
;