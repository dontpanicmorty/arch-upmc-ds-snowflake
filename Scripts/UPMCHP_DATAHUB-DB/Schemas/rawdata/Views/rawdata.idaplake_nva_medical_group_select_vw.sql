CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_NVA_MEDICAL_GROUP_SELECT_VW AS 
SELECT DISTINCT
	METADATA$FILENAME
	,$1 AS COMPANY
	,$2 AS TPA_ID
	,$3 AS PRODUCT
	,$4 AS PRODUCT_KEY
	,$5 AS REGION
	,$6 AS DIRECTORY_SECTION
	,$7 AS DIRECTORY_SECTION_SORT
	,$8 AS SECTION_SUBCATEGORY
	,$9 AS SECTION_SUBCATEGORY_SORT
	,$10 AS PROVIDER_TYPE
	,$11 AS PROVIDER_ID
	,$12 AS PROVIDER_SUF1
	,$13 AS PROVIDER_SUF2
	,$14 AS PROVIDER_NPI
	,TRIM($15) AS ECP_TYPE
	,$16 AS FULL_NAME
	,$17 AS LAST_NAME
	,$18 AS FIRST_NAME
	,$19 AS SUFFIX
	,$20 AS DEGREE
	,$21 AS GENDER
	,$22 AS SPECIALITY
	,$23 AS BOARD_SERTIFICATION
	,$24 AS LIMITATIONS
	,$25 AS OPEN_CLOSE
	,$26 AS RECOGNITION
	,$27 AS MEDICAID_INDICATOR
	,$28 AS LANGUAGE
	,$29 AS HOSPITAL_PRIVILEGES
	,LPAD(TRIM($30), 4, '0') AS LOCATION_ID
	,$31 AS LOCATION_NAME
	,$32 AS ADDRESS_1
	,$33 AS ADDRESS_2
	,$34 AS CITY
	,$35 AS STATE
	,$36 AS ZIP
	,$37 AS COUNTY
	,$38 AS PHONE
	,$39 AS TOLL_FREE_PHONE
	,$40 AS TTY_PHONE
	,$41 AS HANDICAPPED_ACCESSIBLE
	,$42 AS E_PRESSCRIBE
	,$43 AS LONGITUDE
	,$44 AS LATITUDE
	,$45 AS MONDAY_HOURS
	,$46 AS TUESDAY_HOURS
	,$47 AS WEDNESDAY_HOURS
	,$48 AS THURSDAY_HOURS
	,$49 AS FRIDAY_HOURS
	,$50 AS SATURDAY_HOURS
	,$51 AS SUNDAY_HOURS
	,$52 AS SERVICE_TEXT
	,$53 AS COMMERCIAL
	,$54 AS MEDICARE
	,$55 AS U135
	,$56 AS DISCOUNT_NETWORK
	,$57 AS HCMS
	,$58 AS WHMS
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/provider/nva'(PATTERN => 'provider/nva/.*NVA.*[.]txt', FILE_FORMAT => RAWDATA.IDAPLAKE_PROVIDER_NVA_FILE_FORMAT)
WHERE ECP_TYPE = 'Clinic'
QUALIFY ROW_NUMBER() --pull most recent version of each provider record, deduping by language
    OVER(PARTITION BY PROVIDER_ID, PROVIDER_NPI, LOCATION_ID
        ORDER BY LEFT(RIGHT(METADATA$FILENAME,12),8) DESC, LANGUAGE) = 1
;