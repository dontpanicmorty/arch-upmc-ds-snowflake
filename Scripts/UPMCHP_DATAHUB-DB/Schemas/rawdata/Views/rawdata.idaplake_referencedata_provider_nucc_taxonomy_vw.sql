CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_PROVIDER_NUCC_TAXONOMY_VW
COMMENT = 'View to external stage for NUCC Taxonomy refdata set'
AS
SELECT
METADATA$FILENAME,
$1 AS CODE,
$2 AS GROUPING,
$3 AS CLASSIFICATION,
$4 AS SPECIALIZATION,
$5 AS DEFINITION
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/provider/nucc_taxonomy/'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_PROVIDER_NUCC_TAXONOMY_FILE_FORMAT
    ,PATTERN => 'provider/nucc_taxonomy/nucc_taxonomy_.*.csv'
    )
;