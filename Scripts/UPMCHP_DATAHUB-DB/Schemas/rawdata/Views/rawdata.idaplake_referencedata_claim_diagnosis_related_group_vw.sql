CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_CLAIM_DIAGNOSIS_RELATED_GROUP_VW
COMMENT = 'View to external stage for Diagnosis Related Group refdata set'
AS
SELECT
$1 AS DIAGNOSIS_RELATED_GROUP_CODE,
$2 AS DIAGNOSIS_RELATED_GROUP_CODE_DESC,
$3 AS SEVERITY_OF_ILLNESS_NBR,
$4 AS DIAGNOSIS_RELATED_GROUP_TYPE_CODE,
$5 AS DIAGNOSIS_RELATED_GROUP_VERSION_NBR,
$6 AS DIAGNOSIS_RELATED_GROUP_CATEGORY_NAME,
$7 AS MDC_CODE,
$8 AS MDC_DESC,
$9 AS RELATIVE_VALUE_NBR,
$10 AS AVERAGE_LENGTH_OF_STAY_NBR,
$11 AS EFFECTIVE_START_DATE,
$12 AS EFFECTIVE_END_DATE
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/claim/claim_diagnosis_related_group.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT);