CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_CLAIM_PLACE_OF_SERVICE_LOCATION_TYPE_REL_VW
COMMENT = 'View to external stage for Claim Location refdata set'
AS
SELECT
$1 AS PLACE_OF_SERVICE_CODE
,$2 AS LOCATION_TYPE_CODE
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/claim/claim_place_of_service_location_type_rel.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT)
;