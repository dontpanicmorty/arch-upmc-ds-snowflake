CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_PROVDIR_VISION_PRODUCT_CROSSWALK_VW
COMMENT ='View to external stage for Provider Vision Product Crosswalk'
AS
SELECT 
     $1 AS PRODUCT_NAME
    ,$2 AS PRODUCT_TYPE_NAME
    ,$3 AS GROUP_CODE
    ,$4 AS CORP_ID
    ,$5 AS RIDER_TYPE_CODE
    ,$6 AS PROVDIR_H2_SUB_PRODUCT_KEY
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/provider/Provider_Vision_Product_Crosswalk.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT)
;