CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_CLAIM_PHARMACY_CROSSWALK_VW
COMMENT = 'View to external stage for Pharmacy Crosswalk reference data set'
AS
SELECT
$1 AS BPL_ID
,$2 AS BPL_NAME
,$3 AS EFF_DATE
,$4 AS TERM_DATE
,$5 AS FORM_ID
,$6 AS PHCY_NET
,$7 AS MARKET_SEG
,$8 AS TPA_CLIENT_ID
,$9 AS TPA_ID
,$10 AS TPA_DIV_ID
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/claim/esi/pharmacy_crosswalk_data_final.txt'
(FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT)
;