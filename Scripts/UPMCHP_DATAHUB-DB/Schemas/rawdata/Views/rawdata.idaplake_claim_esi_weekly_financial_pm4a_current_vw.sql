CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_CLAIM_ESI_WEEKLY_FINANCIAL_PM4A_CURRENT_VW
AS 
SELECT 
METADATA$FILENAME AS FILENAME,
METADATA$FILE_ROW_NUMBER AS FILE_ROW_NUMBER,
$1 AS DIV,
TO_DATE(LEFT(RIGHT(REPLACE(FILENAME,' ', ''),12),8),'YYYYMMDD') AS DATE,
$3 AS "GROUP",
TO_NUMBER(REPLACE($4,',',''),12,0) AS VOLUME,
TO_NUMBER(REPLACE($5,',',''),12,2) AS CLAIM_AMT,
TO_NUMBER(REPLACE($6,',',''),12,2) AS ADMIN_FEES,
TO_NUMBER(REPLACE($7,',',''),12,2) AS COPAY,
TO_NUMBER(REPLACE($8,',',''),12,2) AS TOTAL
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/claim/esi'(PATTERN => 'claim/esi/financial_validation_weekly/\\d{4}/\\d{2}/\\d{2}/(?i)PM4A.*.csv', FILE_FORMAT => RAWDATA.IDAPLAKE_CLAIM_ESI_WEEKLY_FINANCIAL_FILE_FORMAT)
WHERE DIV = 'Summary'
  QUALIFY FILENAME =
        MAX(FILENAME) OVER () --only pull data from latest version
;