CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_MEMBERNETWORK_PHARMACYLOBSUBPRODUCT_CROSSWALK_VW
COMMENT = 'View to external stage for Member Network Pharmacy LOB Sub Product Crosswalk'
AS
SELECT 
    $1 AS CLIENT_ID
    ,$2 AS TPA_ID
    ,$3 AS TPA_DIV_ID
    ,$4 AS PLAN_TYPE_CODE
    ,$5 AS IPA_CODE
    ,$6 AS LOB
    ,$7 AS SUB_PRODUCT_KEY
    ,$8 AS NOTES_TEXT
    ,$9 AS NETWORK_ID
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/member/membernetwork/MemberNetwork_PharmacyLOBSubProduct_Crosswalk.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT)
;