CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_CLAIM_OPTUM_ICD10CM_BASE_VW
COMMENT = 'View to external stage for Optum ICD10CM Base refdata set'
AS
SELECT
$1 AS CODE
,$2 AS VALIDITY
,$3 AS SHORT_DESCRIPTION
,$4 AS LONG_DESCRIPTION
,$5 AS FULL_DESCRIPTION
,$6 AS STATUS
,$7 AS CODE_TYPE
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/claim/optum/OPTUM_ICD10CM_BASE.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_OPTUM_FILE_FORMAT);