CREATE OR REPLACE VIEW RAWDATA.EMPI_DAILY_GLOBAL_CURRENT_VW
COMMENT = 'Most current version of a Enterprise Person Member Index daily global record across all the raw ingested files'
AS
SELECT
     FILENAME
    ,FILE_ROW_NUMBER
    ,FILE_LOAD_DATETIME
    ,HEALTHPLAN_ID
    ,MMI
    ,LAST_NAME
    ,FIRST_NAME
    ,MIDDLE_NAME
    ,DOB
    ,GENDER
    ,EMPI_ID
    ,EPIC_MRN
    ,MEDIPAC_MRN
    ,AMWELL_ID
    ,HORIZON_HOMECARE_ID
    ,EPIC_EAST_MRN
    ,SEXO
    ,BGENDER
    ,GENDER_ID
    ,EPIC_ENTERPRISE_ID
FROM RAWDATA.EMPI_DAILY_GLOBAL
QUALIFY ROW_NUMBER() 
    OVER(PARTITION BY HEALTHPLAN_ID
        ORDER BY TO_TIMESTAMP_NTZ(REPLACE(SPLIT_PART(SPLIT_PART(empi_daily_global.FILENAME, '_', 7), '.', 1), '-', ' '), 'YYYYMMDD HH24MI') DESC) = 1
;