CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_CLAIM_OPTUM_CPT_BASE_VW
COMMENT = 'View to external stage for Optum CPT Base refdata set'
AS
SELECT
$1 AS CPT_CODE
--,$2 AS PLACE_HOLDER
,$3 AS SHORT_DESCRIPTION
,$4 AS LONG_DESCRIPTION
,$5 AS FULL_DESCRIPTION
,$6 AS NF_TOTAL_RVU
,$7 AS FAC_TOTAL_RVU
,$8 AS STATUS
,$9 AS RESEQUENCED
,$10 AS SEQ_ORDER
,$11 AS CONSUMER_DESCRIPTION
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/claim/optum/OPTUM_CPT_BASE.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_OPTUM_FILE_FORMAT);