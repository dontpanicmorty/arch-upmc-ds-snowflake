CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_NVA_NOT_COVERED_REASON_CODES_VW
COMMENT = 'View to external stage for NVA Not Covered Reason Codes refdata set'
AS
SELECT
$1 AS LOB
,$2 AS CODE
,$3 AS CODE_TYPE
,$4 AS CODE_DESC
,$5 AS CODE_DESC_LONG
,$6 AS CODE_SPANISH_DESC
,$7 AS CMS_CODE_DESC
,$8 AS MEMBER_PAY_IND
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/claim/nva/NVA_Not_Covered_Reason_Codes.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT)
;