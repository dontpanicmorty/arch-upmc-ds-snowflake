CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_CLAIM_ICD_DIAGNOSIS_QUALIFIER_VW
COMMENT = 'View to external stage for Claim ICD Diagnosis Qualifier refdata set'
AS
SELECT
$1 AS CODE
,$2 AS CODE_DESC
,$3 AS CODE_DESC_LONG
,$4 AS CODE_SPANISH_DESC
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/claim/claim_icd_diagnosis_qualifier.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT);