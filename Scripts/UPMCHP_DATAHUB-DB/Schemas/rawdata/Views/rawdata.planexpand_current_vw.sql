CREATE OR REPLACE VIEW RAWDATA.PLANEXPAND_CURRENT_VW
AS
 SELECT PHARMACY_CLAIM_REFERENCE_NUMBER,
        CASE
            WHEN TRIM(TRANSACTION_TYPE) IN ('PD', 'MA', 'RC') THEN 'P'
            WHEN TRIM(TRANSACTION_TYPE)  IN ('RV', 'PR') THEN 'R'
        ELSE NULL
    END AS CLAIM_TRANSACTION_TYPE,
    
    CASE
        WHEN TOTAL_SPENDING_ACCOUNT_AMOUNT LIKE '% %' OR TOTAL_SPENDING_ACCOUNT_AMOUNT IS NULL THEN 0
        WHEN (CLAIM_TRANSACTION_TYPE = 'R' AND HIA_SPENDING_ACCOUNT_AMOUNT > 0) OR (CLAIM_TRANSACTION_TYPE = 'P' AND HIA_SPENDING_ACCOUNT_AMOUNT < 0) THEN -1*HIA_SPENDING_ACCOUNT_AMOUNT
        ELSE IFNULL(HIA_SPENDING_ACCOUNT_AMOUNT,0)
    END AS HIA_SPENDING_AMT,

      CASE
        WHEN TOTAL_SPENDING_ACCOUNT_AMOUNT LIKE '% %' OR TOTAL_SPENDING_ACCOUNT_AMOUNT IS NULL THEN 0
        WHEN (CLAIM_TRANSACTION_TYPE = 'R' AND HRA_SPENDING_ACCOUNT_AMOUNT > 0) OR (CLAIM_TRANSACTION_TYPE = 'P' AND HRA_SPENDING_ACCOUNT_AMOUNT < 0) THEN -1*HRA_SPENDING_ACCOUNT_AMOUNT
        ELSE IFNULL(HRA_SPENDING_ACCOUNT_AMOUNT,0)
    END AS HRA_SPENDING_AMT,  
    
    IFNULL(HIA_SPENDING_AMT + HRA_SPENDING_AMT,0) AS TOTAL_SPENDING_AMT

FROM RAWDATA.PLANEXPAND_RX_SPENDING_ACCOUNTS
WHERE SUBSTR(PHARMACY_CLAIM_REFERENCE_NUMBER,1,1) NOT IN ('P','L')
QUALIFY ROW_NUMBER() OVER(PARTITION BY PHARMACY_CLAIM_REFERENCE_NUMBER, CLAIM_TRANSACTION_TYPE, TOTAL_SPENDING_ACCOUNT_AMOUNT
    ORDER BY FILENAME DESC) = 1
;