CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_CLAIM_ICD_CLASS_VW
COMMENT = 'View to external stage for Claim ICD Class refdata set'
AS
SELECT
$1 AS CODE_VERSION_NBR
,$2 AS CODE
,$3 AS CODE_DESC
,$4 AS CODE_DESC_LONG
,$5 AS CODE_SPANISH_DESC
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/claim/claim_icd_class.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT);