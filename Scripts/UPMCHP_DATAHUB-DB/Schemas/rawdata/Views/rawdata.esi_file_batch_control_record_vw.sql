CREATE OR REPLACE VIEW RAWDATA.ESI_FILE_BATCH_CONTROL_RECORD_VW
COMMENT = 'Batch control record from ESI contains aggrgates at the batch level to vaidate weekly file'
AS
WITH base AS (
    SELECT  TRIM(SUBSTR(RECORD_DATA,1,1)) AS RECORD_IDENTIFIER,
            TRIM(SUBSTR(RECORD_DATA,2,10)) AS PROCESSOR_NUMBER,
            TRIM(SUBSTR(RECORD_DATA,12,5)) AS BATCH_NUMBER,
            TRIM(SUBSTR(RECORD_DATA,17,4)) AS PHARMACY_COUNT,
            TRIM(SUBSTR(RECORD_DATA,21,298)) AS COMMENTS_2,
            TRIM(SUBSTR(RECORD_DATA,319,8)) AS TOTAL_CLAIM_COUNT,
            TRIM(SUBSTR(RECORD_DATA,327,11)) AS TOTAL_BILLED_AMOUNT,
            TRIM(SUBSTR(RECORD_DATA,338,10)) AS TOTAL_ADMIN_FEE,
            TRIM(SUBSTR(RECORD_DATA,348,1353)) AS EXPANSION_AREA,
    FROM    RAWDATA.ESI_CLAIM_WEEKLY
    WHERE   SUBSTR(RECORD_DATA,1,1) = '8'    
)
SELECT  TO_NUMBER(RECORD_IDENTIFIER) AS RECORD_IDENTIFIER,
        TO_NUMBER(PROCESSOR_NUMBER) AS PROCESSOR_NUMBER,
        TO_NUMBER(BATCH_NUMBER) AS BATCH_NUMBER,
        TO_NUMBER(PHARMACY_COUNT) AS PHARMACY_COUNT,
        UTIL.FXN_STRING_OR_NULL(COMMENTS_2) AS COMMENTS_2,
        TO_NUMBER(TOTAL_CLAIM_COUNT) AS TOTAL_CLAIM_COUNT,
        STAGEDATA.FXN_PARSE_CLAIM_OVERPUNCH(TOTAL_BILLED_AMOUNT)::NUMBER(38,2) AS TOTAL_BILLED_AMOUNT,
        STAGEDATA.FXN_PARSE_CLAIM_OVERPUNCH(TOTAL_ADMIN_FEE)::NUMBER(38,2) AS TOTAL_ADMIN_FEE,
        UTIL.FXN_STRING_OR_NULL(EXPANSION_AREA) AS EXPANSION_AREA
FROM    base