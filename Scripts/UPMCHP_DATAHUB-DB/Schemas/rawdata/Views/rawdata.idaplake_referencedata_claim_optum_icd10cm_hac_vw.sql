CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_CLAIM_OPTUM_ICD10CM_HAC_VW
COMMENT = 'View to external stage for Optum ICD10CM HAC refdata set'
AS
SELECT
$1 AS HAC
,$2 AS DRIVER
,$3 AS CONDITIONAL
,$4 AS CONDITIONAL_2
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/claim/optum/OPTUM_ICD10CM_HAC.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_OPTUM_FILE_FORMAT);