CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_DATA_SOURCE_VW
COMMENT = 'View to external stage for Data Source refdata set'
AS
SELECT
$1 AS CODE
,$2 AS CODE_DESC
,$3 AS CODE_DESC_LONG
,$4 AS CODE_SPANISH_DESC
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/enterprise/data_source.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT)
;