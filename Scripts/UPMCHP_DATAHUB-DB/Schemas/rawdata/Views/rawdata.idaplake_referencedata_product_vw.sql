CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_PRODUCT_VW
COMMENT = 'View to external stage for Care Type refdata set'
AS
SELECT
$1 AS PRODUCT_CODE
,$2 AS PRODUCT_DESC
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/provider/Product.txt'
    (FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT);

