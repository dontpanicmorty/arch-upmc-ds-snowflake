CREATE OR REPLACE VIEW RAWDATA.IDAPLAKE_REFERENCEDATA_MEMBERNETWORK_PLANCODESUBPRODUCT_CROSSWALK_VW
COMMENT = 'View to external stage for Member Network Plan Code Sub Product Crosswalk'
AS
SELECT
    $1 AS CLIENT_ID
    ,$2 AS TPA_ID
    ,$3 AS TPA_DIV_ID
    ,$4 AS PLAN_CODE
    ,$5 AS SUB_PRODUCT_KEY
FROM '@RAWDATA.HPDSDATALAKE_IDAPLAKE/referencedata/member/membernetwork/MemberNetwork_PlanCodeSubProduct_Crosswalk.txt'
(FILE_FORMAT => RAWDATA.IDAPLAKE_REFERENCEDATA_FILE_FORMAT)
;