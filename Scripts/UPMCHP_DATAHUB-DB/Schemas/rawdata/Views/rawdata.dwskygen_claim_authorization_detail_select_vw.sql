!set variable_substitution=true;

CREATE OR REPLACE VIEW RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL_SELECT_VW
COMMENT = 'Joins tables from SkygenDW at the authorization detail level for easier change data set processing'
AS
SELECT FACTAUTHORIZATIONSERVICES_VW.AUTHORIZATION_NUMBER AS AUTHORIZATION_NBR
,FACTAUTHORIZATIONSERVICES_VW.ITEM_NUMBER AS AUTHORIZATION_LINE_NBR
,CONCAT('PROVIDER_', DIMPROVIDERSIMPLE_VW.PROVIDER_ID) AS RENDERING_PROVIDER_ID
,DIMCODE_VW.CODE AS PROCEDURE_CODE
,DimCode_VW.DescriptionShort AS PROCEDURE_DESC
,DIMDETERMINATIONSTATE_VW.SERVICEDETERMINATIONSTATUSID AS DETERMINATION_STATUS
,DIMDETERMINATIONSTATE_VW.SERVICEDETERMINATIONSTATUSDESCRIPTION AS DETERMINATION_STATUS_DESC
,TRY_TO_DATE(TO_CHAR(FACTAUTHORIZATIONSERVICES_VW.DATEDETERMINATIONKEY), 'yyyymmdd') AS DETERMINATION_DATE
,TRY_TO_DATE(TO_CHAR(FACTAUTHORIZATIONSERVICES_VW.DATEOFSERVICEFROMKEY), 'yyyymmdd') AS SERVICE_BEGIN_DATE
,TRY_TO_DATE(TO_CHAR(FACTAUTHORIZATIONSERVICES_VW.DATEOFSERVICETOKEY), 'yyyymmdd') AS SERVICE_END_DATE
,FACTAUTHORIZATIONSERVICES_VW.QUANTITY_AUTHORIZED AS AUTHORIZED_QTY
,FACTAUTHORIZATIONSERVICES_VW.QUANTITY_CONSUMED AS CONSUMED_QTY
,FACTAUTHORIZATIONSERVICES_VW.QUANTITY_DENIED AS DENIED_QTY
,FACTAUTHORIZATIONSERVICES_VW.QUANTITY_REQUESTED AS REQUESTED_QTY
,FACTAUTHORIZATIONSERVICES_VW.AUTHORIZED_AMOUNT AS AUTHORIZED_AMT
,FACTAUTHORIZATIONSERVICES_VW.AUTHORIZED_AMOUNT_PER_UNIT AS AUTHORIZED_PER_UNIT_AMT
,FACTAUTHORIZATIONSERVICES_VW.BALANCE_DUE_AMOUNT AS BALANCE_DUE_AMT
,FACTAUTHORIZATIONSERVICES_VW.BILLED_AMOUNT AS BILLED_AMT
,FACTAUTHORIZATIONSERVICES_VW.ALLOWED_AMOUNT AS ALLOWED_AMT
,FACTAUTHORIZATIONSERVICES_VW.UC_AMOUNT AS USUAL_AND_CUSTOMARY_AMT
,FACTAUTHORIZATIONSERVICES_VW.PAYABLE_AMOUNT AS PAYABLE_AMT
,FACTAUTHORIZATIONSERVICES_VW.PAID_AMOUNT AS PAID_AMT
,FACTAUTHORIZATIONSERVICES_VW.COINSURANCE_AMOUNT AS COINSURANCE_AMT
,FACTAUTHORIZATIONSERVICES_VW.COPAY_AMOUNT AS COPAY_AMT
,FACTAUTHORIZATIONSERVICES_VW.DEDUCTIBLE_APPLIED_AMOUNT AS DEDUCTIBLE_APPLIED_AMT
,FACTAUTHORIZATIONSERVICES_VW.PATIENT_PAY_APPLIED_AMOUNT AS PATIENT_PAY_APPLIED_AMT
,DIMTOOTH_VW.TOOTHID AS TOOTH_ID
,DIMTOOTH_VW.ARCH AS TOOTH_ARCH
,DIMTOOTH_VW.QUADRANT AS TOOTH_QUADRANT
FROM &{DWSKYGEN}.DBO.FACTAUTHORIZATIONSERVICES_VW
JOIN &{DWSKYGEN}.DBO.DIMPROVIDERSIMPLE_VW
    ON FACTAUTHORIZATIONSERVICES_VW.PROVIDERSIMPLEKEY = DIMPROVIDERSIMPLE_VW.PROVIDERKEY
JOIN &{DWSKYGEN}.DBO.DIMCODE_VW  
    ON FACTAUTHORIZATIONSERVICES_VW.CODEKEY = DIMCODE_VW.CODEKEY
JOIN &{DWSKYGEN}.DBO.DIMDETERMINATIONSTATE_VW
    ON FACTAUTHORIZATIONSERVICES_VW.DETERMINATIONSTATEKEY = DIMDETERMINATIONSTATE_VW.DETERMINATIONSTATEKEY
JOIN &{DWSKYGEN}.DBO.DIMTOOTH_VW
    ON FACTAUTHORIZATIONSERVICES_VW.TOOTHKEY = DIMTOOTH_VW.TOOTHKEY
WHERE AUTHORIZATION_NBR NOT IN (SELECT AUTHORIZATION_NUMBER
                                    FROM  &{DWSKYGEN}.DBO.FACTAUTHORIZATIONS_VW
                                    GROUP BY AUTHORIZATION_NUMBER
                                    HAVING COUNT(*) > 1
                                ) --remove dupes due to data issue
;

!set variable_substitution=false;