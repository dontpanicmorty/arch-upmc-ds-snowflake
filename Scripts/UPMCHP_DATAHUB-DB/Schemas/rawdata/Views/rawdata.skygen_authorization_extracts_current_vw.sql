COMMENT = 'Most current version of an authorization across all the raw ingested files'
AS
WITH CTE_CURRENT_AUTH_FILE
AS
(
SELECT DISTINCT FILENAME, AUTHORIZATION_NUMBER, ITEM_NUMBER
FROM RAWDATA.SKYGEN_AUTHORIZATION_EXTRACTS
QUALIFY RANK() OVER (PARTITION BY AUTHORIZATION_NUMBER, ITEM_NUMBER
    ORDER BY TO_TIMESTAMP_NTZ(SUBSTRING(SKYGEN_AUTHORIZATION_EXTRACTS.FILENAME,58,8),'YYYYMMDD') DESC) = 1

)
,CTE_AUTH_WITH_MULTI_MEMBER
AS
(
SELECT
AUTHORIZATION_NUMBER, COUNT(1) AS MEMBER_COUNT
FROM (SELECT DISTINCT
    SKYGEN_AUTHORIZATION_EXTRACTS.AUTHORIZATION_NUMBER
    ,SKYGEN_AUTHORIZATION_EXTRACTS.SUBSCRIBER_ID
    FROM RAWDATA.SKYGEN_AUTHORIZATION_EXTRACTS
        JOIN CTE_CURRENT_AUTH_FILE
            ON (CTE_CURRENT_AUTH_FILE.FILENAME = SKYGEN_AUTHORIZATION_EXTRACTS.FILENAME
            AND CTE_CURRENT_AUTH_FILE.AUTHORIZATION_NUMBER = SKYGEN_AUTHORIZATION_EXTRACTS.AUTHORIZATION_NUMBER
            AND CTE_CURRENT_AUTH_FILE.ITEM_NUMBER = SKYGEN_AUTHORIZATION_EXTRACTS.ITEM_NUMBER)
    ) AUTH_MEMBER
GROUP BY AUTHORIZATION_NUMBER
HAVING COUNT(1) > 1
)

