CREATE OR REPLACE VIEW STAGEDATA.SAT_STANDARD_ADDRESS_CACTUS_SELECT_VW
COMMENT = 'This is the Sat view containing Standard Addresses for cactus'
AS
SELECT
    'N/A' AS SOURCE_KEY
    , '000001' AS TPA_CLIENT_ID
    , '000001' AS TPA_ID
    , '0001' AS TPA_DIV_ID
    , 'Cactus' AS DATA_SOURCE_NAME
    , SJR.VALUE:DELIVERY_LINE_1::STRING AS DELIVERY_LINE_1
    , SJR.VALUE:DELIVERY_LINE_2::STRING AS DELIVERY_LINE_2
    , SJR.VALUE:LAST_LINE::STRING AS DELIVERY_LAST_LINE
    , SJR.VALUE:SMARTY_KEY::STRING AS SMARTY_KEY
    , SJR.VALUE:COMPONENTS:URBANIZATION::STRING AS URBANIZATION
    , SJR.VALUE:COMPONENTS:PRIMARY_NUMBER::STRING AS PRIMARY_NUMBER
    , SJR.VALUE:COMPONENTS:STREET_NAME::STRING AS STREET_NAME
    , SJR.VALUE:COMPONENTS:STREET_PREDIRECTION::STRING AS STREET_PREDIRECTION
    , SJR.VALUE:COMPONENTS:STREET_POSTDIRECTION::STRING AS STREET_POSTDIRECTION
    , SJR.VALUE:COMPONENTS:STREET_SUFFIX::STRING AS STREET_SUFFIX
    , SJR.VALUE:COMPONENTS:SECONDARY_NUMBER::STRING AS SECONDARY_NUMBER
    , SJR.VALUE:COMPONENTS:SECONDARY_DESIGNATOR::STRING AS SECONDARY_DESIGNATOR
    , SJR.VALUE:COMPONENTS:EXTRA_SECONDARY_NUMBER::STRING AS EXTRA_SECONDARY_NUMBER
    , SJR.VALUE:COMPONENTS:EXTRA_SECONDARY_DESIGNATOR::STRING AS EXTRA_SECONDARY_DESIGNATOR
    , SJR.VALUE:COMPONENTS:PMB_DESIGNATOR::STRING AS PMB_DESIGNATOR
    , SJR.VALUE:COMPONENTS:PMB_NUMBER::STRING AS PMB_NUMBER
    , SJR.VALUE:COMPONENTS:CITY_NAME::STRING AS CITY_NAME
    , SJR.VALUE:COMPONENTS:DEFAULT_CITY_NAME::STRING AS DEFAULT_CITY_NAME
    , SJR.VALUE:COMPONENTS:STATE_ABBREVIATION::STRING AS STATE_ABBREVIATION
    , SJR.VALUE:COMPONENTS:ZIPCODE::STRING AS ZIPCODE
    , SJR.VALUE:COMPONENTS:PLUS4_CODE::STRING AS PLUS4_CODE
    , SJR.VALUE:METADATA:RECORD_TYPE::STRING AS RECORD_TYPE
    , SJR.VALUE:METADATA:ZIP_TYPE::STRING AS ZIP_TYPE
    , SJR.VALUE:METADATA:COUNTY_FIPS::STRING AS COUNTY_FIPS
    , SJR.VALUE:METADATA:COUNTY_NAME::STRING AS COUNTY_NAME
    , SJR.VALUE:METADATA:CONGRESSIONAL_DISTRICT::STRING AS CONGRESSIONAL_DISTRICT_CODE
    , SJR.VALUE:METADATA:LATITUDE::STRING AS LATITUDE
    , SJR.VALUE:METADATA:LONGITUDE::STRING AS LONGITUDE
    , SJR.VALUE:METADATA:PRECISION::STRING AS LAT_LONG_PRECISION
    , SJR.VALUE:METADATA:TIME_ZONE::STRING AS TIME_ZONE
    , SJR.VALUE:METADATA:UTC_OFFSET::STRING AS UTC_OFFSET
    , SJR.VALUE:METADATA:DST::STRING AS DST_INDICATOR
    , SJR.VALUE:ANALYSIS:DPV_FOOTNOTES::STRING AS DPV_FOOTNOTES
    , AQR.SMARTY_JSON_RESPONSE AS RAW_RESPONSE
    , UTIL.FXN_ARRAY_HASH([
        TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, NVL(DELIVERY_LINE_1, ''), NVL(DELIVERY_LINE_2, ''), NVL(DELIVERY_LAST_LINE, '')
    ]) AS HUB_STANDARD_ADDRESS_HKEY
    , UTIL.FXN_ARRAY_HASH([
        NVL(DELIVERY_LINE_1, ''), NVL(DELIVERY_LINE_2, ''), NVL(DELIVERY_LAST_LINE, ''), SMARTY_KEY, URBANIZATION, PRIMARY_NUMBER, STREET_NAME, STREET_PREDIRECTION, STREET_POSTDIRECTION, STREET_SUFFIX, SECONDARY_NUMBER, SECONDARY_DESIGNATOR, EXTRA_SECONDARY_NUMBER, EXTRA_SECONDARY_DESIGNATOR, PMB_DESIGNATOR, PMB_NUMBER, CITY_NAME, DEFAULT_CITY_NAME, STATE_ABBREVIATION, ZIPCODE, PLUS4_CODE, RECORD_TYPE, ZIP_TYPE, COUNTY_FIPS, COUNTY_NAME, CONGRESSIONAL_DISTRICT_CODE, LATITUDE, LONGITUDE, LAT_LONG_PRECISION, TIME_ZONE, UTC_OFFSET, DST_INDICATOR, DPV_FOOTNOTES, RAW_RESPONSE
    ]) AS HASH_DIFF
FROM RAWDATA.WRK_ADDRESS_QUERY_RESPONSE AS AQR,
LATERAL FLATTEN(INPUT => AQR.SMARTY_JSON_RESPONSE) AS SJR
;