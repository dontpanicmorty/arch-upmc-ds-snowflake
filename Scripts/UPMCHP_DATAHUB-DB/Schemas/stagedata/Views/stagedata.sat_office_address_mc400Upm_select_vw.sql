CREATE OR REPLACE VIEW STAGEDATA.SAT_OFFICE_ADDRESS_MC400UPM_SELECT_VW
COMMENT='This is a SAT view for provider office address data'
AS
SELECT
    TPACLIENT AS TPA_CLIENT_ID
    , TPAIDOFCLIENT AS TPA_ID
    , TPADIVISION AS TPA_DIV_ID
    , 'MC400Upm' AS DATA_SOURCE_NAME
    , CONCAT('OFFICE_', ProviderNbr) AS OFFICE_ID
    , 'Unknown' AS ADDRESS_TYPE_CODE
    , NULLIF(ADDRESS1,'') AS ADDRESS_LINE_1
    , NULLIF(ADDRESS2,'') AS ADDRESS_LINE_2
    , NULLIF(CITY,'') AS CITY_NAME
    , NULL AS COUNTY_NAME
    , NULLIF(ZIPCODE,'') AS ZIP_CODE
    , NULLIF(STATE,'') AS STATE_ABBREV_NAME
    , NULL AS STATE_FULL_NAME
    , NULL AS COUNTRY_NAME
    , UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, OFFICE_ID]) AS HUB_OFFICE_HKEY
    , UTIL.FXN_ARRAY_HASH([ADDRESS_TYPE_CODE, ADDRESS_LINE_1, ADDRESS_LINE_2, CITY_NAME, COUNTY_NAME, ZIP_CODE, STATE_ABBREV_NAME, STATE_FULL_NAME, COUNTRY_NAME]) AS HASH_DIFF
FROM RAWDATA.MC400_DWOAO_PROVIDERS
WHERE
    LEN(PROVIDERNBR) = 6
    AND PROVIDERNBR NOT LIKE ' %'
;