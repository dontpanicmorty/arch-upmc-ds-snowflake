CREATE OR REPLACE VIEW STAGEDATA.HUB_STANDARD_ADDRESS_CACTUS_SELECT_VW
COMMENT = 'This is the Hub view containing Standard Addresses for cactus'
AS
SELECT
    'N/A' AS SOURCE_KEY,
    '000001' AS TPA_CLIENT_ID,
    '000001' AS TPA_ID,
    '0001' AS TPA_DIV_ID,
    'Cactus' AS DATA_SOURCE_NAME,
    RESPONSE.value:delivery_line_1::string AS DELIVERY_LINE_1,
    RESPONSE.value:delivery_line_2::string AS DELIVERY_LINE_2,
    RESPONSE.value:last_line::string AS DELIVERY_LAST_LINE,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, DELIVERY_LINE_1, DELIVERY_LINE_2, DELIVERY_LAST_LINE]) AS HUB_STANDARD_ADDRESS_HKEY
FROM RAWDATA.WRK_ADDRESS_QUERY_RESPONSE,
     LATERAL FLATTEN(input => WRK_ADDRESS_QUERY_RESPONSE.SMARTY_JSON_RESPONSE:response) RESPONSE
;
