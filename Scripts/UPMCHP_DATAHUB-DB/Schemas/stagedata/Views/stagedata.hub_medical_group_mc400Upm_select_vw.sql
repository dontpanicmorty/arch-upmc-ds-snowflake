CREATE OR REPLACE VIEW STAGEDATA.HUB_MEDICAL_GROUP_MC400UPM_SELECT_VW
COMMENT='This is a HUB View containing Medical Group or billing provider data'
AS
SELECT
'N/A' AS SOURCE_KEY
,TpaClient AS TPA_CLIENT_ID
,TpaIdOfClient AS TPA_ID
,TpaDivision AS TPA_DIV_ID
,'MC400Upm' AS DATA_SOURCE_NAME
,ProviderNbr AS MEDICAL_GROUP_ID
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY
FROM RAWDATA.MC400_DWOAO_PROVIDERS
WHERE UPPER(SUBSTR(ProviderNbr,1,1)) = 'V' --MC400 Business logic
;