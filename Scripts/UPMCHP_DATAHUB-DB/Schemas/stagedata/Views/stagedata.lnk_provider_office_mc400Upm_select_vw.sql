CREATE OR REPLACE VIEW STAGEDATA.LNK_PROVIDER_OFFICE_MC400UPM_SELECT_VW
COMMENT = 'This is an MC400 LNK select view of provider and office data'
AS
SELECT
    TPAIDOFCLIENT AS P_TPA_CLIENT_ID,
    TPACLIENT AS P_TPA_ID,
    TPADIVISION AS P_TPA_DIV_ID,
    'MC400Upm' AS P_DATA_SOURCE_NAME,
    PROVIDERNBR AS P_PROVIDER_ID,
    TPAIDOFCLIENT AS O_TPA_CLIENT_ID,
    TPACLIENT AS O_TPA_ID,
    TPADIVISION AS O_TPA_DIV_ID,
    'MC400Upm' AS O_DATA_SOURCE_NAME,
    CONCAT('OFFICE_', PROVIDERNBR) AS O_OFFICE_ID,
    UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID, O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, O_OFFICE_ID]) AS LNK_PROVIDER_OFFICE_HKEY,
    UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS HUB_PROVIDER_HKEY,
    UTIL.FXN_ARRAY_HASH([O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, O_OFFICE_ID]) AS HUB_OFFICE_HKEY
FROM RAWDATA.MC400_DWOAO_PROVIDERS
WHERE
    UPPER(SUBSTR(PROVIDERNBR,1,1)) != 'V'   
    AND UPPER(SUBSTR(PRIMARYSPECIALTY,1,4)) NOT IN ('INST-TAXID','INST-DEFAU')
    AND LEN(PROVIDERNBR) = 6
    AND PROVIDERNBR NOT LIKE ' %'
;