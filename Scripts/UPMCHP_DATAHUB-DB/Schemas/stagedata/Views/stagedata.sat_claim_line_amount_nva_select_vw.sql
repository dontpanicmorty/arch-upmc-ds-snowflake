CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_LINE_AMOUNT_NVA_SELECT_VW
COMMENT = 'This is a SAT View containing Claim Line Amount data'
AS
SELECT DISTINCT 
    IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID, '000001') AS TPA_CLIENT_ID,
    IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_ID, '000001') AS TPA_ID,
    IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID, '0001') AS TPA_DIV_ID,
    IFNULL(LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME, 'NVA') AS DATA_SOURCE_NAME,
    NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo" AS CLAIM_NBR, 
    NVA_PAID_CLAIM_EXTRACTS_VW."ClaimSeqNo" AS CLAIM_LINE_NBR, 
    CONCAT(NVA_PAID_CLAIM_EXTRACTS_VW."ClaimSeqNo", NVA_PAID_CLAIM_EXTRACTS_VW."Trantype") AS CLAIM_LINE_SEQ_NBR, 
    'N/A' AS CLAIM_LINE_PROCEDURE_ADJ_CODE, 
    NVA_PAID_CLAIM_EXTRACTS_VW."AllowedAmt" AS ALLOWED_AMOUNT, 
    NVA_PAID_CLAIM_EXTRACTS_VW."ChargeAmt" AS CHARGE_AMOUNT, 
    NULL AS CLAIM_AMT_01, 
    NULL AS CLAIM_AMT_01_DESC, 
    NULL AS CLAIM_AMT_02, 
    NULL AS CLAIM_AMT_02_DESC, 
    NVA_PAID_CLAIM_EXTRACTS_VW."Copay" AS COPAY_AMT_01, 
    NULL AS COPAY_AMT_02, 
    NULL AS COPAY_AMT_03, 
    NULL AS DEDUCTIBLE_AMOUNT, 
    NVA_PAID_CLAIM_EXTRACTS_VW."Non-CoveredAmt" AS NOT_COVERED_AMOUNT, 
    NVA_PAID_CLAIM_EXTRACTS_VW."PaidAmt" AS PAID_AMOUNT, 
    NVA_PAID_CLAIM_EXTRACTS_VW."PaidAmt" AS PAID_GROSS_AMOUNT, 
    NULL AS PAY_FOR_PERFORMANCE_AMOUNT, 
    NULL AS WITHHOLD_AMOUNT, 
    NULL AS COINSURANCE_AMOUNT, 
    NULL AS CODE_REVIEW_ORIGINAL_BILLING_AMOUNT, 
    NULL AS CODE_REVIEW_ORIGINAL_NET_AMOUNT, 
    NVA_PAID_CLAIM_EXTRACTS_VW."PaidAmt" AS APPROVED_AMT, 
    NULL AS INTEREST_DISCOUNT_AMOUNT, 
    NVA_PAID_CLAIM_EXTRACTS_VW."COBamt" AS THIRD_PARTY_PAID_AMOUNT, 
    NULL AS THIRD_PARTY_ALLOWED_AMOUNT, 
    NULL AS OIC_PAID_AMOUNT, 
    NULL AS OIC_ALLOWED_AMOUNT, 
    NULL AS HRA_APPLIED_AMT, 
    NULL AS HIA_APPLIED_AMT, 
    NULL AS MEMBER_PAY_FLAG,
    UTIL.FXN_ARRAY_HASH([IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID, '000001'), IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_ID, '000001'), IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID, '0001'), IFNULL(LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME, 'NVA'), NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo", CLAIM_LINE_NBR, CLAIM_LINE_SEQ_NBR, CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY, 
    UTIL.FXN_ARRAY_HASH([ALLOWED_AMOUNT, CHARGE_AMOUNT, CLAIM_AMT_01, CLAIM_AMT_01_DESC, CLAIM_AMT_02, CLAIM_AMT_02_DESC, COPAY_AMT_01, COPAY_AMT_02, COPAY_AMT_03, DEDUCTIBLE_AMOUNT, NOT_COVERED_AMOUNT, PAID_AMOUNT, PAID_GROSS_AMOUNT, PAY_FOR_PERFORMANCE_AMOUNT, WITHHOLD_AMOUNT, COINSURANCE_AMOUNT, CODE_REVIEW_ORIGINAL_BILLING_AMOUNT, CODE_REVIEW_ORIGINAL_NET_AMOUNT, APPROVED_AMT, INTEREST_DISCOUNT_AMOUNT, THIRD_PARTY_PAID_AMOUNT, THIRD_PARTY_ALLOWED_AMOUNT, OIC_PAID_AMOUNT, OIC_ALLOWED_AMOUNT, HRA_APPLIED_AMT, HIA_APPLIED_AMT, MEMBER_PAY_FLAG]) AS HASH_DIFF
FROM RAWDATA.NVA_PAID_CLAIM_EXTRACTS_VW
LEFT JOIN STAGEDATA.LKP_CLAIM_MEMBER_NVA
        ON (LKP_CLAIM_MEMBER_NVA.CLAIM_NBR = NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo")
;