CREATE OR REPLACE VIEW STAGEDATA.REF_CLAIM_PROCEDURE_MODIFIER_NVA_SELECT_VW
COMMENT = 'This is a REF View containing Claim Procedure Modifier data'
--THIS IS A TEMPORARY SOLUTION AND WE WILL NEED TO REFACTOR TO UTILIZE THE OPTUM FILES
AS
SELECT DISTINCT
LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_NVA.TPA_ID
,LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID
,'NVA' AS DATA_SOURCE_NAME
,Modifier as CODE
,IFF(IFNULL(ModifierDescription,'') = '', 'Description Not Found', ModifierDescription) AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CODE]) AS CLAIM_PROCEDURE_MODIFIER_HKEY
FROM RAWDATA.NVA_PAID_CLAIM_EXTRACTS_VW
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_NVA
        ON (LKP_CLAIM_MEMBER_NVA.CLAIM_NBR = NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo")
    JOIN RAWDATA.MC400_DWOAO_PROCEDUREMODIFIER
        ON (NVA_PAID_CLAIM_EXTRACTS_VW."Mod1" = MC400_DWOAO_PROCEDUREMODIFIER.Modifier
        AND LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID = MC400_DWOAO_PROCEDUREMODIFIER.TPACLIENT
        AND LKP_CLAIM_MEMBER_NVA.TPA_ID = MC400_DWOAO_PROCEDUREMODIFIER.TPAIDOFCLIENT
        AND LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID = MC400_DWOAO_PROCEDUREMODIFIER.TPADIVISION)
WHERE NVA_PAID_CLAIM_EXTRACTS_VW."Mod1" IS NOT NULL
;