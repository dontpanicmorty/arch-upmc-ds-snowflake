CREATE OR REPLACE VIEW STAGEDATA.LNK_MEDICAL_GROUP_OFFICE_MC400UPM_SELECT_VW
COMMENT = 'This is an MC400 UPM LNK select view of medical group and office data'
AS
SELECT DISTINCT
    TPACLIENT AS MG_TPA_CLIENT_ID,
    TPAIDOFCLIENT AS MG_TPA_ID,
    TPADIVISION AS MG_TPA_DIV_ID,
    'MC400Upm' AS MG_DATA_SOURCE_NAME,
    PROVIDERNBR AS MEDICAL_GROUP_ID,
    TPACLIENT AS O_TPA_CLIENT_ID,
    TPAIDOFCLIENT AS O_TPA_ID,
    TPADIVISION AS O_TPA_DIV_ID,
    'MC400Upm' AS O_DATA_SOURCE_NAME,
    CONCAT('OFFICE_', PROVIDERNBR) AS OFFICE_ID,
    UTIL.FXN_ARRAY_HASH([MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MEDICAL_GROUP_ID, O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, OFFICE_ID]) AS LNK_MEDICAL_GROUP_OFFICE_HKEY,
    UTIL.FXN_ARRAY_HASH([MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY,
    UTIL.FXN_ARRAY_HASH([O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, OFFICE_ID]) AS HUB_OFFICE_HKEY
FROM RAWDATA.MC400_DWOAO_PROVIDERS
WHERE
    -- MC400 Business logic for medical groups
    UPPER(SUBSTR(PROVIDERNBR,1,1)) = 'V'
    AND LEN(PROVIDERNBR) = 6
    AND PROVIDERNBR NOT LIKE ' %'
;