CREATE OR REPLACE VIEW STAGEDATA.SAT_MEDICAL_GROUP_CONTRACT_DETAIL_CACTUS_SELECT_VW
COMMENT = 'This is a SAT View containing Cactus Medical Group Contract data'
AS
SELECT DISTINCT
'000001' AS TPA_CLIENT_ID
,'000001' AS TPA_ID
,'0001' AS TPA_DIV_ID
,'Cactus' AS DATA_SOURCE_NAME
, TRIM(CACTUS_GROUPID.GROUPID_K) AS MEDICAL_GROUP_CONTRACT_ID
, IFF(TRIM(REF1.DESCRIPTION) = 'No Value Specified', NULL, TRIM(REF1.DESCRIPTION)) AS MEDICAL_GROUP_CONTRACT_NAME
, IFF(TRIM(REF2.DESCRIPTION) = 'No Value Specified', NULL, TRIM(REF2.DESCRIPTION)) AS MEDICAL_GROUP_CONTRACT_TYPE_NAME
, NULL AS MEDICAL_GROUP_CONTRACT_PATIENT_RESTRICTION_NAME
, IFF(TRIM(REF3.DESCRIPTION) = 'No Value Specified', NULL, TRIM(REF3.DESCRIPTION)) AS MEDICAL_GROUP_CONTRACT_LEVEL_NAME
, UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEDICAL_GROUP_CONTRACT_ID]) AS HUB_MEDICAL_GROUP_CONTRACT_HKEY
, UTIL.FXN_ARRAY_HASH([MEDICAL_GROUP_CONTRACT_NAME, MEDICAL_GROUP_CONTRACT_TYPE_NAME, MEDICAL_GROUP_CONTRACT_PATIENT_RESTRICTION_NAME, MEDICAL_GROUP_CONTRACT_LEVEL_NAME]) AS HASH_DIFF
FROM RAWDATA.CACTUS_GROUPID
LEFT JOIN RAWDATA.CACTUS_GROUPS
    ON CACTUS_GROUPID.GROUP_K = CACTUS_GROUPS.GROUP_K
INNER JOIN RAWDATA.CACTUS_GROUPADDRESS
    ON CACTUS_GROUPID.GROUP_K = CACTUS_GROUPADDRESS.GROUP_K
LEFT JOIN RAWDATA.CACTUS_REFTABLE REF1
    ON CACTUS_GROUPID.USERDEF_RTK1 = REF1.REFTABLE_K
LEFT JOIN RAWDATA.CACTUS_REFTABLE REF2
    ON CACTUS_GROUPID.USERDEF_RTK2 = REF2.REFTABLE_K
LEFT JOIN RAWDATA.CACTUS_REFTABLE REF3
    ON CACTUS_GROUPID.USERDEF_RTK3 = REF3.REFTABLE_K
LEFT JOIN (
	    SELECT G.ID,COUNT(*) AS CNT 
	    FROM RAWDATA.CACTUS_GROUPS G 
	    GROUP BY G.ID HAVING COUNT(*) > 1) DUPES
    ON CACTUS_GROUPS.ID = DUPES.ID
WHERE CACTUS_GROUPID.USERDEF_RTK3 NOT IN ('#0000K4D5N', '#0000K4D5O')
AND NULLIF(TRIM(CACTUS_GROUPS.ID), '') IS NOT NULL	
AND NULLIF(TRIM(CACTUS_GROUPADDRESS.GROUP_K), '') IS NOT NULL	
AND DUPES.ID IS NULL	
;