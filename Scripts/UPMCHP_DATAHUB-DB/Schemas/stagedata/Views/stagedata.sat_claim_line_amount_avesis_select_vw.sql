CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_LINE_AMOUNT_AVESIS_SELECT_VW
COMMENT = 'This is a SAT View containing Claim Line Amount data'
AS
    SELECT DISTINCT 
        LKP_CLAIM_MEMBER_AVESIS.TPA_CLIENT_ID,
        LKP_CLAIM_MEMBER_AVESIS.TPA_ID,
        LKP_CLAIM_MEMBER_AVESIS.TPA_DIV_ID,
        LKP_CLAIM_MEMBER_AVESIS.DATA_SOURCE_NAME,
        AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO AS CLAIM_NBR, 
        AVESIS_PAID_CLAIM_EXTRACTS.ITEM_NO AS CLAIM_LINE_NBR, 
        UTIL.FXN_ARRAY_HASH([SUBSCRIBER_ID,CHECK_NO,CLAIM_TYPE,ADJUDICATION_DT,SERVICE_DT,ANSI_CODE,EXCEPTION_CODE,ADJUSTMENT_CODE,PROC_CODE,QUANTITY,TOOTH_ID,PROV_LOC_ID,PRVD_ID,COUNTY_CODE,LOB_IND]) AS CLAIM_LINE_SEQ_NBR, 
        RANK() OVER (PARTITION BY CLAIM_NBR,CLAIM_LINE_NBR
	    ORDER BY CLAIM_NBR,CLAIM_LINE_NBR, AVESIS_PAID_CLAIM_EXTRACTS.FILE_ROW_NUMBER ASC)::VARCHAR AS CLAIM_LINE_PROCEDURE_ADJ_CODE,
        AVESIS_PAID_CLAIM_EXTRACTS.ALLOW_AMT AS ALLOWED_AMOUNT, 
        AVESIS_PAID_CLAIM_EXTRACTS.BILLED_AMT AS CHARGE_AMOUNT, 
        NULL AS CLAIM_AMT_01, 
        NULL AS CLAIM_AMT_01_DESC, 
        NULL AS CLAIM_AMT_02, 
        NULL AS CLAIM_AMT_02_DESC, 
        AVESIS_PAID_CLAIM_EXTRACTS.COPAY_AMT AS COPAY_AMT_01, 
        NULL AS COPAY_AMT_02, 
        NULL AS COPAY_AMT_03, 
        NULL AS DEDUCTIBLE_AMOUNT, 
        NULL AS NOT_COVERED_AMOUNT, 
        AVESIS_PAID_CLAIM_EXTRACTS.PAYMENT_AMT AS PAID_AMOUNT, 
        AVESIS_PAID_CLAIM_EXTRACTS.PAYMENT_AMT AS PAID_GROSS_AMOUNT, 
        NULL AS PAY_FOR_PERFORMANCE_AMOUNT, 
        NULL AS WITHHOLD_AMOUNT, 
        NULL AS COINSURANCE_AMOUNT, 
        NULL AS CODE_REVIEW_ORIGINAL_BILLING_AMOUNT, 
        NULL AS CODE_REVIEW_ORIGINAL_NET_AMOUNT, 
        AVESIS_PAID_CLAIM_EXTRACTS.APPROV_AMT AS APPROVED_AMT, 
        NULL AS INTEREST_DISCOUNT_AMOUNT, 
        AVESIS_PAID_CLAIM_EXTRACTS.COB_AMT AS THIRD_PARTY_PAID_AMOUNT, 
        NULL AS THIRD_PARTY_ALLOWED_AMOUNT, 
        NULL AS OIC_PAID_AMOUNT, 
        NULL AS OIC_ALLOWED_AMOUNT, 
        NULL AS HRA_APPLIED_AMT, 
        NULL AS HIA_APPLIED_AMT, 
        NULL AS MEMBER_PAY_FLAG,
        AVESIS_PAID_CLAIM_EXTRACTS.ADJUDICATION_DT,
        UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_NBR, CLAIM_LINE_NBR, CLAIM_LINE_SEQ_NBR, CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY, 
        UTIL.FXN_ARRAY_HASH([ALLOWED_AMOUNT, CHARGE_AMOUNT, CLAIM_AMT_01, CLAIM_AMT_01_DESC, CLAIM_AMT_02, CLAIM_AMT_02_DESC, COPAY_AMT_01, COPAY_AMT_02, COPAY_AMT_03, DEDUCTIBLE_AMOUNT, NOT_COVERED_AMOUNT, PAID_AMOUNT, PAID_GROSS_AMOUNT, PAY_FOR_PERFORMANCE_AMOUNT, WITHHOLD_AMOUNT, COINSURANCE_AMOUNT, CODE_REVIEW_ORIGINAL_BILLING_AMOUNT, CODE_REVIEW_ORIGINAL_NET_AMOUNT, APPROVED_AMT, INTEREST_DISCOUNT_AMOUNT, THIRD_PARTY_PAID_AMOUNT, THIRD_PARTY_ALLOWED_AMOUNT, OIC_PAID_AMOUNT, OIC_ALLOWED_AMOUNT, HRA_APPLIED_AMT, HIA_APPLIED_AMT, MEMBER_PAY_FLAG]) AS HASH_DIFF
    FROM RAWDATA.AVESIS_PAID_CLAIM_EXTRACTS
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_AVESIS
        ON (LKP_CLAIM_MEMBER_AVESIS.CLAIM_NBR = AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO)
    JOIN (
            SELECT 
                AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO AS CD_CLAIM_NBR, 
                FILENAME, 
                FILE_ROW_NUMBER,
                AVESIS_PAID_CLAIM_EXTRACTS.ITEM_NO AS CD_CLAIM_LINE_NBR,
                UTIL.FXN_ARRAY_HASH([SUBSCRIBER_ID,CHECK_NO,CLAIM_TYPE,ADJUDICATION_DT,SERVICE_DT,ANSI_CODE,EXCEPTION_CODE,ADJUSTMENT_CODE,PROC_CODE,QUANTITY,TOOTH_ID,PROV_LOC_ID,PRVD_ID,COUNTY_CODE,LOB_IND]) AS CD_CLAIM_LINE_SEQ_NBR
            FROM RAWDATA.AVESIS_PAID_CLAIM_EXTRACTS
            WHERE AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO IS NOT NULL
                QUALIFY ROW_NUMBER() -- get the most current submitted file for a claim line
                    OVER(PARTITION BY AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO
                        ORDER BY TO_DATE(SPLIT_PART(SPLIT_PART(AVESIS_PAID_CLAIM_EXTRACTS.FILENAME, '_', 5), '.', 1), 'YYYYMMDD') DESC, FILE_ROW_NUMBER) = 1 
        ) CURRENT_CLAIM_FILE
        ON (CURRENT_CLAIM_FILE.CD_CLAIM_NBR = AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO
        AND CURRENT_CLAIM_FILE.CD_CLAIM_LINE_NBR = AVESIS_PAID_CLAIM_EXTRACTS.ITEM_NO
        AND CURRENT_CLAIM_FILE.CD_CLAIM_LINE_SEQ_NBR = UTIL.FXN_ARRAY_HASH([SUBSCRIBER_ID,CHECK_NO,CLAIM_TYPE,ADJUDICATION_DT,SERVICE_DT,ANSI_CODE,EXCEPTION_CODE,ADJUSTMENT_CODE,PROC_CODE,QUANTITY,TOOTH_ID,PROV_LOC_ID,PRVD_ID,COUNTY_CODE,LOB_IND])
        AND CURRENT_CLAIM_FILE.FILENAME = AVESIS_PAID_CLAIM_EXTRACTS.FILENAME
        AND CURRENT_CLAIM_FILE.FILE_ROW_NUMBER = AVESIS_PAID_CLAIM_EXTRACTS.FILE_ROW_NUMBER
        )
WHERE AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO IS NOT NULL
;