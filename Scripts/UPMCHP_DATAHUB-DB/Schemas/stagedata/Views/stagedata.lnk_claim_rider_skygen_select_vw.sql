CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_RIDER_SKYGEN_SELECT_VW
COMMENT = 'Source view for SKGYEN data into LNK_CLAIM_RIDER'
AS

SELECT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS C_TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS C_TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS C_TPA_DIV_ID,
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_HEADER.CLAIM_NBR AS C_CLAIM_NBR,
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS R_TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS R_TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS R_TPA_DIV_ID,
'MC400Upm' AS R_DATA_SOURCE_NAME,
RIDERS.VALUE AS R_RIDER_CODE,
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS MG_TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS MG_TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS MG_TPA_DIV_ID,
'MC400Upm' AS MG_DATA_SOURCE_NAME,
IFNULL(DWSKYGEN_CLAIM_HEADER.GROUP_NBR, LKP_CLAIM_MEMBER_SKYGEN.COVERAGE_GROUP_CODE) AS MG_GROUP_NBR,
IFNULL(DWSKYGEN_CLAIM_HEADER.SUB_GROUP_NBR, LKP_CLAIM_MEMBER_SKYGEN.SUB_GROUP_CODE) AS MG_SUB_GROUP_NBR,
UTIL.FXN_ARRAY_HASH(
        [C_TPA_CLIENT_ID
        ,C_TPA_ID
        ,C_TPA_DIV_ID
        ,C_DATA_SOURCE_NAME
        ,C_CLAIM_NBR
        ,R_TPA_CLIENT_ID
        ,R_TPA_ID
        ,R_TPA_DIV_ID
        ,R_DATA_SOURCE_NAME
        ,R_RIDER_CODE
        ,MG_TPA_CLIENT_ID
        ,MG_TPA_ID
        ,MG_TPA_DIV_ID
        ,MG_DATA_SOURCE_NAME
        ,MG_GROUP_NBR
        ,MG_SUB_GROUP_NBR
        ]) AS LNK_CLAIM_RIDER_HKEY,
UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY,
UTIL.FXN_ARRAY_HASH([R_TPA_CLIENT_ID, R_TPA_ID, R_TPA_DIV_ID, R_DATA_SOURCE_NAME, R_RIDER_CODE]) AS HUB_RIDER_HKEY,
UTIL.FXN_ARRAY_HASH([MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_GROUP_NBR, MG_SUB_GROUP_NBR]) AS HUB_MEMBERSHIP_GROUP_HKEY

FROM RAWDATA.DWSKYGEN_CLAIM_HEADER
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN 
        ON (DWSKYGEN_CLAIM_HEADER.CLAIM_NBR = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
    ,LATERAL FLATTEN(INPUT => DWSKYGEN_CLAIM_HEADER.RIDER_CODES) RIDERS
WHERE
MG_GROUP_NBR IS NOT NULL
AND MG_SUB_GROUP_NBR IS NOT NULL
AND DWSKYGEN_CLAIM_HEADER.RIDER_CODES <> [] --rider codes array is not null

UNION ALL

SELECT DISTINCT
    LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS C_TPA_CLIENT_ID, 
    LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS C_TPA_ID, 
    LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS C_TPA_DIV_ID, 
    LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME, 
    SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO AS C_CLAIM_NBR, 
    LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS R_TPA_CLIENT_ID,
    LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS R_TPA_ID,
    LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS R_TPA_DIV_ID,
    'MC400Upm' AS R_DATA_SOURCE_NAME,
    RIDERS.VALUE AS R_RIDER_CODE,
    LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS MG_TPA_CLIENT_ID,
    LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS MG_TPA_ID,
    LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS MG_TPA_DIV_ID,
    'MC400Upm' AS MG_DATA_SOURCE_NAME,
    IFNULL(SUBSTR(GRP_PLN_ID, 1, 6), LKP_CLAIM_MEMBER_SKYGEN.COVERAGE_GROUP_CODE) AS MG_GROUP_NBR,
    CASE 
        WHEN CLAIM_DUP.CLAIM_NO IS NULL
            THEN IFNULL(SUBSTR(GRP_PLN_ID, 7, 3), LKP_CLAIM_MEMBER_SKYGEN.SUB_GROUP_CODE)
        ELSE LKP_CLAIM_MEMBER_SKYGEN.SUB_GROUP_CODE
    END AS MG_SUB_GROUP_NBR,
    UTIL.FXN_ARRAY_HASH(
        [C_TPA_CLIENT_ID
        ,C_TPA_ID
        ,C_TPA_DIV_ID
        ,C_DATA_SOURCE_NAME
        ,C_CLAIM_NBR
        ,R_TPA_CLIENT_ID
        ,R_TPA_ID
        ,R_TPA_DIV_ID
        ,R_DATA_SOURCE_NAME
        ,R_RIDER_CODE
        ,MG_TPA_CLIENT_ID
        ,MG_TPA_ID
        ,MG_TPA_DIV_ID
        ,MG_DATA_SOURCE_NAME
        ,MG_GROUP_NBR
        ,MG_SUB_GROUP_NBR
        ]) AS LNK_CLAIM_RIDER_HKEY,
        UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY,
        UTIL.FXN_ARRAY_HASH([R_TPA_CLIENT_ID, R_TPA_ID, R_TPA_DIV_ID, R_DATA_SOURCE_NAME, R_RIDER_CODE]) AS HUB_RIDER_HKEY,
        UTIL.FXN_ARRAY_HASH([MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_GROUP_NBR, MG_SUB_GROUP_NBR]) AS HUB_MEMBERSHIP_GROUP_HKEY

FROM RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW
    LEFT JOIN (
                SELECT CLAIM_NO
                FROM
                (
                    SELECT DISTINCT CLAIM_NO, GRP_PLN_ID
                    FROM RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW
                    WHERE GRP_PLN_ID IS NOT NULL
                ) CLAIM_GRP_PLN
                GROUP BY CLAIM_NO
                HAVING COUNT(1) > 1
              ) CLAIM_DUP 
        ON (CLAIM_DUP.CLAIM_NO = SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO)
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR = SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO
    ,LATERAL FLATTEN(INPUT => LKP_CLAIM_MEMBER_SKYGEN.RIDERS_ARRAY) RIDERS
WHERE SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO NOT IN (SELECT CLAIM_NBR FROM RAWDATA.DWSKYGEN_CLAIM_HEADER )
;