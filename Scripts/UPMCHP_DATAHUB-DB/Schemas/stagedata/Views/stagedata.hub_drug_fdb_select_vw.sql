CREATE OR REPLACE VIEW STAGEDATA.HUB_DRUG_FDB_SELECT_VW
COMMENT = 'This is a HUB View containing Drug data'
AS
SELECT
'000001' AS TPA_CLIENT_ID,
'000001' AS TPA_ID,
'0001' AS TPA_DIV_ID,
'FDB' AS DATA_SOURCE_NAME,
NDC_DRUG_CODE AS NDC_CODE,
UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, NDC_CODE]) AS HUB_DRUG_HKEY
FROM STAGEDATA.LKP_CLAIM_DRUG_VW
;