CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_ICD_DIAGNOSIS_SKYGEN_SELECT_VW
COMMENT = 'This is a SAT View containing Claim ICD Diagnosis data'
AS

SELECT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
,LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME
,DWSKYGEN_CLAIM_HEADER_DIAGNOSIS_CODE_SELECT_VW.CLAIM_NBR
,UTIL.FXN_ARRAY_HASH(
    [
    LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID,
    LKP_CLAIM_MEMBER_SKYGEN.TPA_ID,
    LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID,
    LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME,
    DWSKYGEN_CLAIM_HEADER_DIAGNOSIS_CODE_SELECT_VW.CLAIM_NBR
    ]
) AS HUB_CLAIM_HKEY,
ARRAY_AGG(DISTINCT OBJECT_CONSTRUCT
        (
        'icdDiagnosisCodePosition', ICD_POSITION,
        'icdDiagnosisCodeVersion', '10',
        'icdDiagnosisCodeValue', DIAGNOSIS_CODE,
        'icdDiagnosisCodeQualifier', CODE_QUALIFIER,
        'poaCode', NULL
        ))
    WITHIN GROUP (ORDER BY OBJECT_CONSTRUCT(
        'icdDiagnosisCodePosition', ICD_POSITION,
        'icdDiagnosisCodeVersion', '10',
        'icdDiagnosisCodeValue', DIAGNOSIS_CODE,
        'icdDiagnosisCodeQualifier', CODE_QUALIFIER,
        'poaCode', NULL
        ))
AS ICD_DIAGNOSIS_CODES,
UTIL.FXN_ARRAY_HASH([ICD_DIAGNOSIS_CODES]) AS HASH_DIFF
FROM RAWDATA.DWSKYGEN_CLAIM_HEADER_DIAGNOSIS_CODE_SELECT_VW
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (DWSKYGEN_CLAIM_HEADER_DIAGNOSIS_CODE_SELECT_VW.CLAIM_NBR = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
GROUP BY 
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
,LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME
,DWSKYGEN_CLAIM_HEADER_DIAGNOSIS_CODE_SELECT_VW.CLAIM_NBR

UNION ALL

SELECT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
,LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME
,DIAG_CODES.CLAIM_NO AS CLAIM_NBR
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_NBR]) AS HUB_CLAIM_HKEY
,STAGEDATA.FXN_BUILD_CLAIM_GROUP_CODE_ARRAY
    ('diagnosisCode', LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME
    ,object_construct_keep_null(
    'DIAGNOSIS1', DIAG_CODES.PRIMARY_DIAG_CODE,
    'DIAGNOSIS2', DIAG_CODES.DIAG_2,
    'DIAGNOSIS3', DIAG_CODES.DIAG_3,
    'DIAGNOSIS4', DIAG_CODES.DIAG_4,
    'DIAGNOSIS5', DIAG_CODES.DIAG_5,
    'DIAGNOSIS6', DIAG_CODES.DIAG_6,
    'DIAGNOSIS7', DIAG_CODES.DIAG_7,
    'DIAGNOSIS8', DIAG_CODES.DIAG_8,
    'DIAGNOSIS9', DIAG_CODES.DIAG_9,
    'DIAGNOSIS10', DIAG_CODES.DIAG_10,
    'DIAGNOSIS11', DIAG_CODES.DIAG_11,
    'DIAGNOSIS12', DIAG_CODES.DIAG_12
    ), 12) AS ICD_DIAGNOSIS_CODES,
UTIL.FXN_ARRAY_HASH([ICD_DIAGNOSIS_CODES]) AS HASH_DIFF
FROM (
        SELECT DISTINCT
        CLAIM_NO,
        FIRST_VALUE(PRIMARY_DIAG_CODE) OVER (PARTITION BY CLAIM_NO ORDER BY ITEM_NO) AS PRIMARY_DIAG_CODE,
        FIRST_VALUE(DIAG_2) OVER (PARTITION BY CLAIM_NO ORDER BY ITEM_NO) AS DIAG_2,
        FIRST_VALUE(DIAG_3) OVER (PARTITION BY CLAIM_NO ORDER BY ITEM_NO) AS DIAG_3,
        FIRST_VALUE(DIAG_4) OVER (PARTITION BY CLAIM_NO ORDER BY ITEM_NO) AS DIAG_4,
        FIRST_VALUE(DIAG_5) OVER (PARTITION BY CLAIM_NO ORDER BY ITEM_NO) AS DIAG_5,
        FIRST_VALUE(DIAG_6) OVER (PARTITION BY CLAIM_NO ORDER BY ITEM_NO) AS DIAG_6,
        FIRST_VALUE(DIAG_7) OVER (PARTITION BY CLAIM_NO ORDER BY ITEM_NO) AS DIAG_7,
        FIRST_VALUE(DIAG_8) OVER (PARTITION BY CLAIM_NO ORDER BY ITEM_NO) AS DIAG_8,
        FIRST_VALUE(DIAG_9) OVER (PARTITION BY CLAIM_NO ORDER BY ITEM_NO) AS DIAG_9,
        FIRST_VALUE(DIAG_10) OVER (PARTITION BY CLAIM_NO ORDER BY ITEM_NO) AS DIAG_10,
        FIRST_VALUE(DIAG_11) OVER (PARTITION BY CLAIM_NO ORDER BY ITEM_NO) AS DIAG_11,
        FIRST_VALUE(DIAG_12) OVER (PARTITION BY CLAIM_NO ORDER BY ITEM_NO) AS DIAG_12
        FROM RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW
        WHERE PRIMARY_DIAG_CODE IS NOT NULL
    ) DIAG_CODES
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (DIAG_CODES.CLAIM_NO = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
WHERE DIAG_CODES.CLAIM_NO NOT IN (SELECT CLAIM_NBR FROM RAWDATA.DWSKYGEN_CLAIM_HEADER)
;
