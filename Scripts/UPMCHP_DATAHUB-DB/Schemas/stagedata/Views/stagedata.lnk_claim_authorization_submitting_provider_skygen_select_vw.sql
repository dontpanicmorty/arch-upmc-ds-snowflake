CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_AUTHORIZATION_SUBMITTING_PROVIDER_SKYGEN_SELECT_VW
COMMENT = 'Source view for Skygen data into LNK_CLAIM_AUTHORIZATION_SUBMITTING_PROVIDER'
AS
SELECT DISTINCT
'N/A' AS SOURCE_KEY,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID AS A_TPA_CLIENT_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID AS A_TPA_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID AS A_TPA_DIV_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME AS A_DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_AUTHORIZATION.AUTHORIZATION_NBR AS A_AUTHORIZATION_NBR,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID AS MG_TPA_CLIENT_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID AS MG_TPA_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID AS MG_TPA_DIV_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME AS MG_DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_AUTHORIZATION.SUBMITTING_PROVIDER_ID AS MG_MEDICAL_GROUP_ID,
UTIL.FXN_ARRAY_HASH([A_TPA_CLIENT_ID, A_TPA_ID, A_TPA_DIV_ID, A_DATA_SOURCE_NAME, A_AUTHORIZATION_NBR, MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_MEDICAL_GROUP_ID]) AS LNK_CLAIM_AUTHORIZATION_SUBMITTING_PROVIDER_HKEY,
UTIL.FXN_ARRAY_HASH([A_TPA_CLIENT_ID, A_TPA_ID, A_TPA_DIV_ID, A_DATA_SOURCE_NAME, A_AUTHORIZATION_NBR]) AS HUB_CLAIM_AUTHORIZATION_HKEY,
UTIL.FXN_ARRAY_HASH([MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY
FROM RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION
    JOIN STAGEDATA.LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN
        ON (DWSKYGEN_CLAIM_AUTHORIZATION.AUTHORIZATION_NBR = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.AUTHORIZATION_NBR)
WHERE SUBMITTING_PROVIDER_ID NOT IN ('PAYEE_-1','PAYEE_0')

UNION ALL

SELECT DISTINCT
'N/A' AS SOURCE_KEY,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID AS A_TPA_CLIENT_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID AS A_TPA_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID AS A_TPA_DIV_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME AS A_DATA_SOURCE_NAME,
SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER AS A_AUTHORIZATION_NBR,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID AS MG_TPA_CLIENT_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID AS MG_TPA_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID AS MG_TPA_DIV_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME AS MG_DATA_SOURCE_NAME,
CONCAT('PAYEE_', SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.PAYEE_ID) AS MG_MEDICAL_GROUP_ID,
UTIL.FXN_ARRAY_HASH([A_TPA_CLIENT_ID, A_TPA_ID, A_TPA_DIV_ID, A_DATA_SOURCE_NAME, A_AUTHORIZATION_NBR, MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_MEDICAL_GROUP_ID]) AS LNK_CLAIM_AUTHORIZATION_SUBMITTING_PROVIDER_HKEY,
UTIL.FXN_ARRAY_HASH([A_TPA_CLIENT_ID, A_TPA_ID, A_TPA_DIV_ID, A_DATA_SOURCE_NAME, A_AUTHORIZATION_NBR]) AS HUB_CLAIM_AUTHORIZATION_HKEY,
UTIL.FXN_ARRAY_HASH([MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY
FROM RAWDATA.SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW
    JOIN STAGEDATA.LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN
        ON (LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.AUTHORIZATION_NBR = SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER)
    JOIN RAWDATA.DWSKYGEN_PROVIDER_DETAIL
        ON (DWSKYGEN_PROVIDER_DETAIL.TPA_CLIENT_ID = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID
        AND DWSKYGEN_PROVIDER_DETAIL.TPA_ID = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID
        AND DWSKYGEN_PROVIDER_DETAIL.TPA_DIV_ID = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID
        AND DWSKYGEN_PROVIDER_DETAIL.PROVIDER_ID = CONCAT('PAYEE_', SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.PAYEE_ID))
WHERE SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.PAYEE_ID IS NOT NULL
AND SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.PAYEE_ID NOT IN ('-1','0')
AND SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER NOT IN (SELECT AUTHORIZATION_NBR FROM RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL)
;
