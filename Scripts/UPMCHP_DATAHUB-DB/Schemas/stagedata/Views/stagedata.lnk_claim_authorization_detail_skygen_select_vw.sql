CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_AUTHORIZATION_DETAIL_SKYGEN_SELECT_VW
COMMENT = 'Source view for SKGYEN data into LNK_CLAIM_AUTHORIZATION_DETAIL'
AS
SELECT DISTINCT
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID AS A_TPA_CLIENT_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID AS A_TPA_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID AS A_TPA_DIV_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME AS A_DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_AUTHORIZATION.AUTHORIZATION_NBR AS A_AUTHORIZATION_NBR,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID AS AD_TPA_CLIENT_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID AS AD_TPA_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID AS AD_TPA_DIV_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME AS AD_DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR AS AD_AUTHORIZATION_NBR,
DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_LINE_NBR AS AD_AUTHORIZATION_LINE_NBR,
UTIL.FXN_ARRAY_HASH([A_TPA_CLIENT_ID, A_TPA_ID, A_TPA_DIV_ID, A_DATA_SOURCE_NAME, A_AUTHORIZATION_NBR, AD_TPA_CLIENT_ID, AD_TPA_ID, AD_TPA_DIV_ID, AD_DATA_SOURCE_NAME, AD_AUTHORIZATION_NBR, AD_AUTHORIZATION_LINE_NBR]) AS LNK_CLAIM_AUTHORIZATION_DETAIL_HKEY,
UTIL.FXN_ARRAY_HASH([A_TPA_CLIENT_ID, A_TPA_ID, A_TPA_DIV_ID, A_DATA_SOURCE_NAME, A_AUTHORIZATION_NBR]) AS HUB_CLAIM_AUTHORIZATION_HKEY,
UTIL.FXN_ARRAY_HASH([AD_TPA_CLIENT_ID, AD_TPA_ID, AD_TPA_DIV_ID, AD_DATA_SOURCE_NAME, AD_AUTHORIZATION_NBR, AD_AUTHORIZATION_LINE_NBR]) AS HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY
FROM RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION
    JOIN RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL
        ON DWSKYGEN_CLAIM_AUTHORIZATION.AUTHORIZATION_NBR = DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR
    JOIN STAGEDATA.LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN
        ON DWSKYGEN_CLAIM_AUTHORIZATION.AUTHORIZATION_NBR = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.AUTHORIZATION_NBR

UNION ALL

SELECT
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID AS A_TPA_CLIENT_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID AS A_TPA_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID AS A_TPA_DIV_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME AS A_DATA_SOURCE_NAME,
    SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER AS A_AUTHORIZATION_NBR,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID AS AD_TPA_CLIENT_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID AS AD_TPA_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID AS AD_TPA_DIV_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME AS AD_DATA_SOURCE_NAME,
    SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER AS AD_AUTHORIZATION_NBR,
    COALESCE(SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.ITEM_NUMBER, 'N/A') AS AD_AUTHORIZATION_LINE_NBR,
    UTIL.FXN_ARRAY_HASH([A_TPA_CLIENT_ID, A_TPA_ID, A_TPA_DIV_ID, A_DATA_SOURCE_NAME, A_AUTHORIZATION_NBR, AD_TPA_CLIENT_ID, AD_TPA_ID, AD_TPA_DIV_ID, AD_DATA_SOURCE_NAME, AD_AUTHORIZATION_NBR, AD_AUTHORIZATION_LINE_NBR]) AS LNK_CLAIM_AUTHORIZATION_DETAIL_HKEY,
    UTIL.FXN_ARRAY_HASH([A_TPA_CLIENT_ID, A_TPA_ID, A_TPA_DIV_ID, A_DATA_SOURCE_NAME, A_AUTHORIZATION_NBR]) AS HUB_CLAIM_AUTHORIZATION_HKEY,
    UTIL.FXN_ARRAY_HASH([AD_TPA_CLIENT_ID, AD_TPA_ID, AD_TPA_DIV_ID, AD_DATA_SOURCE_NAME, AD_AUTHORIZATION_NBR, AD_AUTHORIZATION_LINE_NBR]) AS HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY
FROM RAWDATA.SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW
    JOIN STAGEDATA.LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN
        ON (SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.AUTHORIZATION_NBR)
WHERE AUTHORIZATION_NUMBER NOT IN (SELECT AUTHORIZATION_NBR FROM RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION)
;
