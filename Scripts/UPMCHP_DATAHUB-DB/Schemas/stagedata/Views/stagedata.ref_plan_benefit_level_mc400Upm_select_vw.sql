CREATE OR REPLACE VIEW STAGEDATA.REF_PLAN_BENEFIT_LEVEL_MC400UPM_SELECT_VW
AS
SELECT
 TpaClient AS TPA_CLIENT_ID
,TpaIdOfClient AS TPA_ID
,TpaDivision AS TPA_DIV_ID
,'MC400Upm' AS DATA_SOURCE_NAME
,CodeValue AS CODE
,Description AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CODE]) AS PLAN_BENEFIT_LEVEL_HKEY
FROM RAWDATA.MC400_DWOAO_GENERICCODES GenericCodes
WHERE UPPER(CodeField) = 'BENLVL'
AND (TpaClient, TpaIdOfClient, TpaDivision, CodeValue) IN
    (SELECT TpaClient, TpaIdOfClient, TpaDivision, BenefitLevel 
    FROM RAWDATA.MC400_DWOAO_CLAIMSDETAIL)
;
