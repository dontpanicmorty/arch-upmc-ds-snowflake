CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_LINE_PROCEDURE_MODIFIER_NVA_SELECT_VW
COMMENT = 'This is a SAT View containing Claim Line Processing Reason data'
AS
SELECT
    LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID AS TPA_CLIENT_ID, 
    LKP_CLAIM_MEMBER_NVA.TPA_ID AS TPA_ID, 
    LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID AS TPA_DIV_ID, 
    LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME AS DATA_SOURCE_NAME,
    NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo" AS CLAIM_NBR, 
    NVA_PAID_CLAIM_EXTRACTS_VW."ClaimSeqNo" AS CLAIM_LINE_NBR, 
    CONCAT(NVA_PAID_CLAIM_EXTRACTS_VW."ClaimSeqNo", NVA_PAID_CLAIM_EXTRACTS_VW."Trantype") AS CLAIM_LINE_SEQ_NBR, 
    'N/A' AS CLAIM_LINE_PROCEDURE_ADJ_CODE, 
    NVA_PAID_CLAIM_EXTRACTS_VW."Mod1" AS MODIFIER_CODE,
    1 AS CODE_POSITION, --currently there is only one modifier code for NVA
    UTIL.FXN_ARRAY_HASH([MODIFIER_CODE, CODE_POSITION]) AS HASH_DIFF,
    UTIL.FXN_ARRAY_HASH(
            [TPA_CLIENT_ID, 
            TPA_ID, 
            TPA_DIV_ID, 
            DATA_SOURCE_NAME, 
            LKP_CLAIM_MEMBER_NVA.CLAIM_NBR, 
            CLAIM_LINE_NBR,
            CLAIM_LINE_SEQ_NBR, 
            CLAIM_LINE_PROCEDURE_ADJ_CODE
            ]) AS HUB_CLAIM_DETAIL_HKEY
FROM RAWDATA.NVA_PAID_CLAIM_EXTRACTS_VW 
JOIN STAGEDATA.LKP_CLAIM_MEMBER_NVA
        ON (LKP_CLAIM_MEMBER_NVA.CLAIM_NBR = NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo")
WHERE NVA_PAID_CLAIM_EXTRACTS_VW."Mod1" IS NOT NULL
;