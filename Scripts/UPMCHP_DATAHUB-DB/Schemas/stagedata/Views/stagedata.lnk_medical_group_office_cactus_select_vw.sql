CREATE OR REPLACE VIEW STAGEDATA.LNK_MEDICAL_GROUP_OFFICE_CACTUS_SELECT_VW
COMMENT = 'This is a Cactus LNK select view of medical group and office data'
AS
WITH DUPLICATE_GROUPS AS (
    SELECT ID
    FROM RAWDATA.CACTUS_GROUPS
    GROUP BY ID
    HAVING COUNT(*) > 1
)
SELECT DISTINCT
    '000001' AS MG_TPA_CLIENT_ID,
    '000001' AS MG_TPA_ID,
    '0001' AS MG_TPA_DIV_ID,
    'Cactus' AS MG_DATA_SOURCE_NAME,
    TRIM(GRP.ID) AS MEDICAL_GROUP_ID,
    '000001' AS O_TPA_CLIENT_ID,
    '000001' AS O_TPA_ID,
    '0001' AS O_TPA_DIV_ID,
    'Cactus' AS O_DATA_SOURCE_NAME,
    TRIM(GRP_ADR.ID) AS OFFICE_ID,
    UTIL.FXN_ARRAY_HASH([MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MEDICAL_GROUP_ID, O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, OFFICE_ID]) AS LNK_MEDICAL_GROUP_OFFICE_HKEY,
    UTIL.FXN_ARRAY_HASH([MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY,
    UTIL.FXN_ARRAY_HASH([O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, OFFICE_ID]) AS HUB_OFFICE_HKEY
FROM
    RAWDATA.CACTUS_GROUPS AS GRP
INNER JOIN
    RAWDATA.CACTUS_GROUPADDRESS AS GRP_ADR
    ON GRP.GROUP_K = GRP_ADR.GROUP_K
LEFT JOIN
    RAWDATA.CACTUS_ADDRESSES AS ADR
    ON GRP_ADR.ADDRESS_K = ADR.ADDRESS_K
LEFT JOIN
    DUPLICATE_GROUPS AS DUP
    ON GRP.ID = DUP.ID
WHERE
    NULLIF(GRP.ID, '') IS NOT NULL
    AND NULLIF(GRP_ADR.ID, '') IS NOT NULL
    AND NULLIF(GRP_ADR.TAXIDNUMBER, '') IS NOT NULL
    AND DUP.ID IS NULL
    AND (NULLIF(ADR.ADDRESSLINE1, '') IS NOT NULL OR NULLIF(ADR.ADDRESSLINE2, '') IS NOT NULL)
;