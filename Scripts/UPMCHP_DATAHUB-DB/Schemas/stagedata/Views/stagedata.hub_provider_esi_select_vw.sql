CREATE OR REPLACE VIEW STAGEDATA.HUB_PROVIDER_ESI_SELECT_VW
COMMENT = 'Source view for ESI data into HUB_PROVIDER'
AS
SELECT
'N/A' AS SOURCE_KEY,
'000001' AS TPA_CLIENT_ID,
'000001' AS TPA_ID,
'0001' AS TPA_DIV_ID,
'ESI' AS DATA_SOURCE_NAME,
CONCAT('ESI', 'Pharmacy', NABP_NBR, IFF(LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_NPI = 'UNKNOWN', '', LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_NPI)) AS PROVIDER_ID,
UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY
FROM STAGEDATA.LKP_CLAIM_PHARMACY_DETAIL
JOIN STAGEDATA.LKP_CLAIM_PHARMACY_CLAIM 
    ON LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_NUMBER = LKP_CLAIM_PHARMACY_DETAIL.NABP_NBR

UNION

SELECT
'N/A' AS SOURCE_KEY,
'000001' AS TPA_CLIENT_ID,
'000001' AS TPA_ID,
'0001' AS TPA_DIV_ID,
'ESI' AS DATA_SOURCE_NAME,
CONCAT('ESI', 'Prescriber', PRESCRIBER_ID) AS PROVIDER_ID,
UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY
FROM STAGEDATA.LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL
;