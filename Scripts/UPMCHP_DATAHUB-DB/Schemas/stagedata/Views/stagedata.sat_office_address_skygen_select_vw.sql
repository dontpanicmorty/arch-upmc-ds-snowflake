CREATE OR REPLACE VIEW STAGEDATA.SAT_OFFICE_ADDRESS_SKYGEN_SELECT_VW
COMMENT = 'This is a SAT View containing office detail data'
AS
SELECT 
    DWSKYGEN_PROVIDER_OFFICE.OFFICE_ID,
    DWSKYGEN_PROVIDER_OFFICE.TPA_CLIENT_ID,
    DWSKYGEN_PROVIDER_OFFICE.TPA_ID,
    DWSKYGEN_PROVIDER_OFFICE.TPA_DIV_ID,
    'Skygen' AS DATA_SOURCE_NAME,
    'Physical' AS ADDRESS_TYPE_CODE,
    DWSKYGEN_PROVIDER_OFFICE.ADDRESS_LINE_1,
    DWSKYGEN_PROVIDER_OFFICE.ADDRESS_LINE_2,
    DWSKYGEN_PROVIDER_OFFICE.CITY_NAME,
    NULL AS COUNTY_NAME,
    DWSKYGEN_PROVIDER_OFFICE.ZIP_5 AS ZIP_CODE,
    DWSKYGEN_PROVIDER_OFFICE.STATE_ABBREV_NAME AS STATE_ABBREV_NAME,
    NULL AS STATE_FULL_NAME,
    NULL AS COUNTRY_NAME,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, 
                        TPA_ID, 
                        TPA_DIV_ID, 
                        DATA_SOURCE_NAME, 
                        OFFICE_ID]
                        ) AS HUB_OFFICE_HKEY,
    UTIL.FXN_ARRAY_HASH([ADDRESS_TYPE_CODE,
                        ADDRESS_LINE_1,
                        ADDRESS_LINE_2,
                        CITY_NAME,
                        COUNTY_NAME,
                        ZIP_CODE,
                        STATE_ABBREV_NAME,
                        STATE_FULL_NAME,
                        COUNTRY_NAME]
                        ) AS HASH_DIFF
FROM RAWDATA.DWSKYGEN_PROVIDER_OFFICE;