CREATE OR REPLACE VIEW STAGEDATA.SAT_PROVIDER_OFFICE_LINK_DETAIL_CACTUS_SELECT_VW
COMMENT = 'This is a SAT View containing Provider Office and Groups data'
AS
SELECT DISTINCT
    CAST(CACTUS_PROVIDERADDRESSES.FROMDATE AS DATE) AS PROVIDER_ADDRESS_START_DATE,
    CAST(CACTUS_PROVIDERADDRESSES.TODATE AS DATE) AS PROVIDER_ADDRESS_TERM_DATE,
    CACTUS_PROVIDERADDRESSES.ACTIVE AS PROVIDER_ADDRESS_ACTIVE_IND,
    IFF(CACTUS_PROVIDERADDRESSES.USERDEF_RTK2 = 'D0KU0NLSWV', TRUE, FALSE) AS SUPPRESS_IN_DIRECTORY_IND, --'D0KU0NLSWV' is suppressed from directory to column SUPPRESS_IN_DIRECTORY_IND
    UTIL.FXN_ARRAY_HASH([
        '000001',
        '000001',
        '0001',
        'Cactus',
        TRIM(CACTUS_PROVIDERS.ID),
        '000001',
        '000001',
        '0001',
        'Cactus',
        TRIM(CACTUS_PROVIDERADDRESSES.USERDEF_C1),
        '000001',
        '000001',
        '0001',
        'Cactus',
        TRIM(CACTUS_GROUPS.ID)
    ]) AS LNK_PROVIDER_OFFICE_HKEY,
    UTIL.FXN_ARRAY_HASH([
        PROVIDER_ADDRESS_START_DATE,
        PROVIDER_ADDRESS_TERM_DATE,
        PROVIDER_ADDRESS_ACTIVE_IND,
        SUPPRESS_IN_DIRECTORY_IND
    ]) AS HASH_DIFF
FROM 
    RAWDATA.CACTUS_PROVIDERS
INNER JOIN RAWDATA.CACTUS_PROVIDERADDRESSES 
    ON CACTUS_PROVIDERS.PROVIDER_K = CACTUS_PROVIDERADDRESSES.PROVIDER_K
INNER JOIN RAWDATA.CACTUS_ADDRESSES 
    ON CACTUS_PROVIDERADDRESSES.ADDRESS_K = CACTUS_ADDRESSES.ADDRESS_K

INNER JOIN RAWDATA.CACTUS_GROUPSPROVIDERSADDRESSES
    ON CACTUS_PROVIDERADDRESSES.PROVIDERADDRESS_K = CACTUS_GROUPSPROVIDERSADDRESSES.PROVIDERADDRESS_K
INNER JOIN RAWDATA.CACTUS_GROUPADDRESS 
    ON CACTUS_GROUPADDRESS.GROUPADDRESS_K = CACTUS_GROUPSPROVIDERSADDRESSES.GROUPADDRESS_K
INNER JOIN RAWDATA.CACTUS_GROUPS
    ON CACTUS_GROUPS.GROUP_K = CACTUS_GROUPADDRESS.GROUP_K
LEFT JOIN (
    SELECT 
        ID, 
        COUNT(*) AS CNT 
    FROM (
        SELECT DISTINCT 
            CACTUS_PROVIDERS.ID, 
            CACTUS_PROVIDERS.PROVIDER_K 
        FROM 
            RAWDATA.CACTUS_PROVIDERS 
        INNER JOIN RAWDATA.CACTUS_ENTITYASSIGNMENTS 
            ON CACTUS_ENTITYASSIGNMENTS.PROVIDER_K = CACTUS_PROVIDERS.PROVIDER_K
    ) A
    GROUP BY ID 
    HAVING COUNT(*) > 1
) DUPES 
    ON CACTUS_PROVIDERS.ID = DUPES.ID
INNER JOIN (
    SELECT DISTINCT PROVIDER_K 
    FROM RAWDATA.CACTUS_ENTITYASSIGNMENTS 
    WHERE CACTUS_ENTITYASSIGNMENTS.RECORDTYPE = 'E'
) EA 
    ON EA.PROVIDER_K = CACTUS_PROVIDERS.PROVIDER_K
WHERE 
    CACTUS_PROVIDERS.STATUS_RTK NOT IN ('#0000K408T', '#0000K408U', '#0000K408S') --Provider statuses "Applicant", "Committee Reviewer", "Lead" do not interface out of Cactus
    AND NULLIF(CACTUS_PROVIDERS.ID, '') IS NOT NULL
    AND NULLIF(TRIM(CACTUS_PROVIDERADDRESSES.USERDEF_C1), '') IS NOT NULL
    AND NULLIF(TRIM(CACTUS_GROUPS.ID), '') IS NOT NULL
    AND CACTUS_PROVIDERADDRESSES.FROMDATE IS NOT NULL
    AND (
        CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG != 1 
        OR CACTUS_PROVIDERS.LASTNAME != '' 
        OR CACTUS_PROVIDERS.FIRSTNAME != ''
    )
    AND (
        CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG != 2 
        OR (CACTUS_PROVIDERS.LONGNAME != '' AND CACTUS_PROVIDERADDRESSES.ACTIVE = 1)
    )
    AND (
        NULLIF(CACTUS_ADDRESSES.ADDRESSLINE1, '') IS NOT NULL 
        OR NULLIF(CACTUS_ADDRESSES.ADDRESSLINE2, '') IS NOT NULL
    )
    AND DUPES.ID IS NULL;