!set variable_substitution=true;
CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_HEADER_NVA_SELECT_VW
COMMENT = 'Source view for NVA data into SAT_CLAIM_HEADER'
AS
SELECT DISTINCT
IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID, '000001') AS TPA_CLIENT_ID
,IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_ID, '000001') AS TPA_ID
,IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID, '0001') AS TPA_DIV_ID
,IFNULL(LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME, 'NVA') AS DATA_SOURCE_NAME
,NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo" AS CLAIM_NBR
,TRY_TO_DATE(NVA_PAID_CLAIM_EXTRACTS_VW."ReceivedDate") AS CLAIM_ENTRY_DATE
,COALESCE(LKP_CLAIM_MEMBER_NVA.PLAN_CODE, NVA_PAID_CLAIM_EXTRACTS_VW."PlanCode") AS PLAN_CODE
,LKP_CLAIM_MEMBER_NVA.PLAN_TYPE_CODE AS PLAN_TYPE_CODE
,CASE
    WHEN NVA_PAID_CLAIM_EXTRACTS_VW."BillProvName" = 'NON PARTICIPATING PROVIDER' THEN 'N'
    ELSE 'P'
END AS BILLING_PROVIDER_PARTICIPATING_STATUS_CODE
,LOB_PLAN_TYPE.LINE_OF_BUSINESS_CODE AS LINE_OF_BUSINESS_CODE
,NULL AS ADMITTED_FLAG
,NVA_PAID_CLAIM_EXTRACTS_VW.DOS AS ADMITTED_DATE
,NULL AS ADMITTED_HOUR
,NULL AS ADMISSION_SOURCE_CODE
,NULL AS ADMISSION_TYPE_CODE
,NULL AS DISCHARGE_DATE
,NULL AS DISCHARGE_HOUR
,NULL AS DISCHARGE_STATUS_CODE
,NULL AS BILLING_TYPE_CODE
,NULL AS CALCULATED_BILL_TOTAL_AMT -- NEED TO VALIDATE LATER AS ALL ADJ TRAN_TYPE HAVE NEGATIVE TOTAL_CHARGE_AMT 
,'vision' AS CARE_TYPE_NAME
,SUBSTR(NVA_PAID_CLAIM_EXTRACTS_VW."Group", 5, 9) AS DIVISION_NUMBER
,NULL AS ELECTRONIC_CLAIM_TYPE_CODE
,NULL AS ENCOUNTER_REASON_CODE
,NULL AS FORM_NUMBER
,TRUE AS IS_PROCESSING_COMPLETE
,NULL AS MICROFILM_NBR
,NVA_PAID_CLAIM_EXTRACTS_VW."POS" AS PLACE_OF_SERVICE_CODE
,NULL AS PRICING_ZIP_SOURCE
,NULL AS PATIENT_ACCOUNT_NUMBER
,NULL AS SHOCK_CLAIM_IND
,NULL AS SOURCE_LAST_UPDATED_DATETIME
,FALSE AS IS_PREDETERMINATION_CLAIM_FLAG
,NULL AS ORIGINAL_CLAIM_ID
,NULL AS MULTISOURCE_CLAIM_IND
,'E' AS CLAIM_TYPE_CODE --(E)ncounter or (I)npatient
,NULL AS IPA_CODE
,NULL AS BILLING_PROVIDER_VENDOR_NBR
,NULL AS SERVICE_ZIP_CODE
,NULL AS EDI_837_FACILITY_NPI_NBR
,NULL AS EDI_837_FACILITY_NAME
,NULL AS EDI_837_FACILITY_TELEPHONE_NBR
,NULL AS EDI_837_FACILITY_ADDRESS_LINE_1_TEXT
,NULL AS EDI_837_FACILITY_ADDRESS_LINE_2_TEXT
,NULL AS EDI_837_FACILITY_CITY_NAME
,NULL AS EDI_837_FACILITY_STATE_ABBREV_NAME
,NULL AS EDI_837_FACILITY_ZIP_CODE_NBR
,NULL AS EDI_837_FACILITY_OTHER_ID
,NULL AS SEVERITY_OF_ILLNESS
,NULL AS DIAGNOSIS_RELATED_GROUP_CODE
,NULL AS PROVIDER_SPECIALTY
,NULL AS PAID_STATUS_FOR_CMS
,UTIL.FXN_ARRAY_HASH([
    IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID, '000001')
    ,IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_ID, '000001')
    ,IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID, '0001')
    ,IFNULL(LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME, 'NVA')
    ,NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo"
]) AS HUB_CLAIM_HKEY
,UTIL.FXN_ARRAY_HASH([
    CLAIM_ENTRY_DATE
    ,LINE_OF_BUSINESS_CODE
    ,PLAN_CODE
    ,COALESCE(LKP_CLAIM_MEMBER_NVA.PLAN_CODE, NVA_PAID_CLAIM_EXTRACTS_VW."PlanCode")
    ,BILLING_PROVIDER_PARTICIPATING_STATUS_CODE
    ,ADMITTED_FLAG
    ,ADMITTED_DATE
    ,ADMITTED_HOUR
    ,ADMISSION_SOURCE_CODE
    ,ADMISSION_TYPE_CODE
    ,DISCHARGE_DATE
    ,DISCHARGE_HOUR
    ,DISCHARGE_STATUS_CODE
    ,BILLING_TYPE_CODE
    ,CALCULATED_BILL_TOTAL_AMT
    ,CARE_TYPE_NAME
    ,DIVISION_NUMBER
    ,ELECTRONIC_CLAIM_TYPE_CODE
    ,ENCOUNTER_REASON_CODE
    ,FORM_NUMBER
    ,IS_PROCESSING_COMPLETE
    ,MICROFILM_NBR
    ,PLACE_OF_SERVICE_CODE 
    ,PRICING_ZIP_SOURCE
    ,PATIENT_ACCOUNT_NUMBER
    ,SHOCK_CLAIM_IND
    ,SOURCE_LAST_UPDATED_DATETIME
    ,IS_PREDETERMINATION_CLAIM_FLAG
    ,ORIGINAL_CLAIM_ID
    ,MULTISOURCE_CLAIM_IND
    ,CLAIM_TYPE_CODE
    ,IPA_CODE
    ,BILLING_PROVIDER_VENDOR_NBR
    ,SERVICE_ZIP_CODE
    ,EDI_837_FACILITY_NPI_NBR
    ,EDI_837_FACILITY_NAME
    ,EDI_837_FACILITY_TELEPHONE_NBR
    ,EDI_837_FACILITY_ADDRESS_LINE_1_TEXT
    ,EDI_837_FACILITY_ADDRESS_LINE_2_TEXT
    ,EDI_837_FACILITY_CITY_NAME
    ,EDI_837_FACILITY_STATE_ABBREV_NAME
    ,EDI_837_FACILITY_ZIP_CODE_NBR
    ,EDI_837_FACILITY_OTHER_ID
    ,SEVERITY_OF_ILLNESS
    ,DIAGNOSIS_RELATED_GROUP_CODE
    ,PROVIDER_SPECIALTY
    ,PAID_STATUS_FOR_CMS
]) AS HASH_DIFF

FROM RAWDATA.NVA_PAID_CLAIM_EXTRACTS_VW
    LEFT JOIN STAGEDATA.LKP_CLAIM_MEMBER_NVA
        ON (LKP_CLAIM_MEMBER_NVA.CLAIM_NBR = NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo")

    LEFT OUTER JOIN &{IDAP_LAKE}.NETWORK.LOB_PLAN_TYPE
        ON (LOB_PLAN_TYPE.TPA_CLIENT_ID = LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID
        AND LOB_PLAN_TYPE.TPA_ID = LKP_CLAIM_MEMBER_NVA.TPA_ID
        AND LOB_PLAN_TYPE.TPA_DIV_ID = LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID
        AND LOB_PLAN_TYPE.PLAN_TYPE = LKP_CLAIM_MEMBER_NVA.PLAN_TYPE_CODE)        
QUALIFY ROW_NUMBER() -- take the most recent submission to remove duplicates
    OVER(PARTITION BY NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo"
        ORDER BY SPLIT_PART(SPLIT_PART(NVA_PAID_CLAIM_EXTRACTS_VW.FILENAME, '_', 7), '.', 1) DESC) = 1
;
!set variable_substitution=false;