CREATE OR REPLACE VIEW STAGEDATA.REF_CLAIM_PROCESSING_REASON_ENVOLVE_SELECT_VW
COMMENT = 'Source view for ENVOLVE Claim Processing Reason(s) data'
AS 
-- Adjustment reasons for 0001
SELECT
    '000001' AS TPA_CLIENT_ID
    ,'000001' AS TPA_ID
    ,'0001' AS TPA_DIV_ID
    ,'Envolve' AS DATA_SOURCE_NAME
    ,'Adjustment' AS CLAIM_PROCESSING_REASON_TYPE
    ,'9999999999999999' AS CODE
    ,'GENERIC ADJUSTMENT CODE' AS CODE_DESC
    ,NULL AS CODE_DESC_LONG
    ,NULL AS CODE_SPANISH_DESC
    ,NULL AS HIPAA_277_CODE
    ,NULL AS HIPAA_835_CODE
    ,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_PROCESSING_REASON_TYPE, CODE]) AS CLAIM_PROCESSING_REASON_HKEY
;