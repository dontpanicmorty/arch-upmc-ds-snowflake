CREATE OR REPLACE VIEW STAGEDATA.SAT_OFFICE_DETAIL_MC400UPM_SELECT_VW
COMMENT='This is a SAT view for provider office detail data'
AS
SELECT
    TPACLIENT AS TPA_CLIENT_ID
    , TPAIDOFCLIENT AS TPA_ID
    , TPADIVISION AS TPA_DIV_ID
    , 'MC400Upm' AS DATA_SOURCE_NAME
    , CONCAT('OFFICE_', PROVIDERNBR) AS OFFICE_ID
    , NULL AS OFFICE_NAME
    , NULLIF(PHONENBR,'') AS PRIMARY_PHONE_NBR
    , NULLIF(PHONEEXTENSION,'') AS PRIMARY_PHONE_EXTENSION_NBR
    , NULL AS ALTERNATE_PHONE_NBR
    , NULL AS ALTERNATE_PHONE_EXTENSION_NBR
    , NULLIF(FAXNBR,'') AS PRIMARY_FAX_NBR
    , NULL AS ALTERNATE_FAX_NBR
    , NULLIF(EMAILADDRESS,'') AS EMAIL_ADDRESS
    , NULL AS HANDICAP_ACCESS_IND
    , NULL AS TELEHEALTH_IND
    , NULL AS RECEIVES_MAIL_IND
    , NULL AS EPRESCRIBE_IND
    , NULL AS MA_SUPER_PCP_IND
    , NULL AS EMR_SYSTEM_NAME
    , NULL AS OFFICE_MANAGER_NAME
    , UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, OFFICE_ID]) AS HUB_OFFICE_HKEY
    , UTIL.FXN_ARRAY_HASH([OFFICE_NAME, PRIMARY_PHONE_NBR, PRIMARY_PHONE_EXTENSION_NBR, ALTERNATE_PHONE_NBR, ALTERNATE_PHONE_EXTENSION_NBR, PRIMARY_FAX_NBR, ALTERNATE_FAX_NBR, EMAIL_ADDRESS, HANDICAP_ACCESS_IND, TELEHEALTH_IND, RECEIVES_MAIL_IND, EPRESCRIBE_IND, MA_SUPER_PCP_IND, EMR_SYSTEM_NAME, OFFICE_MANAGER_NAME]) AS HASH_DIFF
FROM RAWDATA.MC400_DWOAO_PROVIDERS
WHERE
    LEN(PROVIDERNBR) = 6
    AND PROVIDERNBR NOT LIKE ' %'
;