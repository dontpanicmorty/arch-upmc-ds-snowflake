AS
SELECT DISTINCT
    'N/A' AS SOURCE_KEY,
    TPA_CLIENT_ID AS PA_TPA_CLIENT_ID,
    TPA_ID AS PA_TPA_ID,
    TPA_DIV_ID AS PA_TPA_DIV_ID,
    DATA_SOURCE_NAME AS PA_DATA_SOURCE_NAME,
    CARE_TYPE_NAME AS PA_CARE_TYPE_NAME,
    PLAN_CODE AS PA_PLAN_CODE,
    GROUP_NBR AS PA_GROUP_NBR,
    SUB_GROUP_NBR AS PA_SUB_GROUP_NBR,
    ACCUMULATOR_TYPE_CODE AS PA_ACCUMULATOR_TYPE_CODE,
    ACCUMULATOR_PERIOD_BENEFIT_LEVEL_CODE AS PA_ACCUMULATOR_PERIOD_BENEFIT_LEVEL_CODE,
    SUBSCRIBER_TYPE_CODE AS PA_SUBSCRIBER_TYPE_CODE,
    CODESET_CODE AS PA_CODESET_CODE,
    IN_NETWORK_FLAG AS PA_IN_NETWORK_FLAG,
    TPA_CLIENT_ID AS AC_TPA_CLIENT_ID,
    TPA_ID AS AC_TPA_ID,
    TPA_DIV_ID AS AC_TPA_DIV_ID,
    DATA_SOURCE_NAME AS AC_DATA_SOURCE_NAME,
    CODESET_CODE AS AC_CODESET_CODE,
    UTIL.FXN_ARRAY_HASH([PA_TPA_CLIENT_ID, PA_TPA_ID, PA_TPA_DIV_ID, PA_DATA_SOURCE_NAME, PA_CARE_TYPE_NAME, PA_PLAN_CODE, PA_GROUP_NBR, PA_SUB_GROUP_NBR, PA_ACCUMULATOR_TYPE_CODE, PA_ACCUMULATOR_PERIOD_BENEFIT_LEVEL_CODE, PA_SUBSCRIBER_TYPE_CODE, PA_CODESET_CODE, PA_IN_NETWORK_FLAG, AC_TPA_CLIENT_ID, AC_TPA_ID, AC_TPA_DIV_ID, AC_DATA_SOURCE_NAME, AC_CODESET_CODE]) AS LNK_PLAN_ACCUMULATOR_CODESET_HKEY,
    UTIL.FXN_ARRAY_HASH([PA_TPA_CLIENT_ID, PA_TPA_ID, PA_TPA_DIV_ID, PA_DATA_SOURCE_NAME, PA_CARE_TYPE_NAME, PA_PLAN_CODE, PA_GROUP_NBR, PA_SUB_GROUP_NBR, PA_ACCUMULATOR_TYPE_CODE, PA_ACCUMULATOR_PERIOD_BENEFIT_LEVEL_CODE, PA_SUBSCRIBER_TYPE_CODE, PA_CODESET_CODE, PA_IN_NETWORK_FLAG]) AS HUB_PLAN_ACCUMULATOR_HKEY,
    UTIL.FXN_ARRAY_HASH([AC_TPA_CLIENT_ID, AC_TPA_ID, AC_TPA_DIV_ID, AC_DATA_SOURCE_NAME, AC_CODESET_CODE]) AS HUB_ACCUMULATOR_CODESET_HKEY
FROM RAWDATA.DWSKYGEN_PLAN_ACCUMULATOR
;