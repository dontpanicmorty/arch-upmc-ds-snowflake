CREATE OR REPLACE VIEW STAGEDATA.HUB_OFFICE_ESI_SELECT_VW
COMMENT = 'This is a HUB View containing ESI office data'
AS
SELECT DISTINCT 
    'N/A' AS SOURCE_KEY,
    '000001' AS TPA_CLIENT_ID,
    '000001' AS TPA_ID,
    '0001' AS TPA_DIV_ID,
    'ESI' AS DATA_SOURCE_NAME,
    CONCAT('ESI','Prescriber', PRESCRIBER_ID) AS OFFICE_ID,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, OFFICE_ID]) AS HUB_OFFICE_HKEY
FROM STAGEDATA.LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL --Prescribers

UNION

SELECT DISTINCT 
    'N/A' AS SOURCE_KEY,
    '000001' AS TPA_CLIENT_ID,
    '000001' AS TPA_ID,
    '0001' AS TPA_DIV_ID,
    'ESI' AS DATA_SOURCE_NAME,
    CONCAT('ESI', 'Pharmacy', NABP_NBR, IFF(LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_NPI = 'UNKNOWN', '', LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_NPI)) AS OFFICE_ID,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, OFFICE_ID]) AS HUB_OFFICE_HKEY
FROM STAGEDATA.LKP_CLAIM_PHARMACY_CLAIM
JOIN STAGEDATA.LKP_CLAIM_PHARMACY_DETAIL 
    ON LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_NUMBER = LKP_CLAIM_PHARMACY_DETAIL.NABP_NBR
;