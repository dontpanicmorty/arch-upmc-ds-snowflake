CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_HEADER_AVESIS_SELECT_VW
COMMENT = 'Source view for AVESIS data into SAT_CLAIM_HEADER'
AS
SELECT DISTINCT
 LKP_CLAIM_MEMBER_AVESIS.TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_AVESIS.TPA_ID
,LKP_CLAIM_MEMBER_AVESIS.TPA_DIV_ID
,LKP_CLAIM_MEMBER_AVESIS.DATA_SOURCE_NAME
,AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO AS CLAIM_NBR
,NULL AS CLAIM_ENTRY_DATE
,LKP_CLAIM_MEMBER_AVESIS.PLAN_CODE AS PLAN_CODE
,LKP_CLAIM_MEMBER_AVESIS.PLAN_TYPE_CODE AS PLAN_TYPE_CODE
,NULL AS BILLING_PROVIDER_PARTICIPATING_STATUS_CODE
,CASE 
    WHEN LOB_IND = 'FDD' THEN 'FEHB'
    WHEN LOB_IND = 'MCD' THEN 'MC'
    WHEN LOB_IND = 'CHD' THEN 'CHIP'
    WHEN LOB_IND = 'MAD' THEN 'MA'
    WHEN LOB_IND = 'CHC' THEN 'CHC'
    ELSE NULL
    END AS LINE_OF_BUSINESS_CODE 
,NULL AS ADMITTED_FLAG
,TO_DATE(AVESIS_PAID_CLAIM_EXTRACTS.SERVICE_DT, 'YYYYMMDD')  AS ADMITTED_DATE
,NULL AS ADMITTED_HOUR
,NULL AS ADMISSION_SOURCE_CODE
,NULL AS ADMISSION_TYPE_CODE
,NULL AS DISCHARGE_DATE
,NULL AS DISCHARGE_HOUR
,NULL AS DISCHARGE_STATUS_CODE
,NULL AS BILLING_TYPE_CODE
,NULL AS CALCULATED_BILL_TOTAL_AMT 
,'dental' AS CARE_TYPE_NAME
,AVESIS_PAID_CLAIM_EXTRACTS.GRP_PLN_ID AS DIVISION_NUMBER
,NULL AS ELECTRONIC_CLAIM_TYPE_CODE
,NULL AS ENCOUNTER_REASON_CODE
,NULL AS FORM_NUMBER
,TRUE AS IS_PROCESSING_COMPLETE
,NULL AS MICROFILM_NBR
,COALESCE(AVESIS_PAID_CLAIM_EXTRACTS.POS,'') AS PLACE_OF_SERVICE_CODE
,NULL AS PRICING_ZIP_SOURCE
,NULL AS PATIENT_ACCOUNT_NUMBER
,'N' AS SHOCK_CLAIM_IND
,NULL AS SOURCE_LAST_UPDATED_DATETIME
,FALSE AS IS_PREDETERMINATION_CLAIM_FLAG
,NULL AS ORIGINAL_CLAIM_ID
,NULL AS MULTISOURCE_CLAIM_IND
,'E' AS CLAIM_TYPE_CODE
,NULL AS IPA_CODE
,NULL AS BILLING_PROVIDER_VENDOR_NBR
,NULL AS SERVICE_ZIP_CODE
,NULL AS EDI_837_FACILITY_NPI_NBR
,NULL AS EDI_837_FACILITY_NAME
,NULL AS EDI_837_FACILITY_TELEPHONE_NBR
,NULL AS EDI_837_FACILITY_ADDRESS_LINE_1_TEXT
,NULL AS EDI_837_FACILITY_ADDRESS_LINE_2_TEXT
,NULL AS EDI_837_FACILITY_CITY_NAME
,NULL AS EDI_837_FACILITY_STATE_ABBREV_NAME
,NULL AS EDI_837_FACILITY_ZIP_CODE_NBR
,NULL AS EDI_837_FACILITY_OTHER_ID
,NULL AS SEVERITY_OF_ILLNESS
,NULL AS DIAGNOSIS_RELATED_GROUP_CODE
,NULL AS PROVIDER_SPECIALTY
,NULL AS PAID_STATUS_FOR_CMS
,UTIL.FXN_ARRAY_HASH([
     LKP_CLAIM_MEMBER_AVESIS.TPA_CLIENT_ID
    ,LKP_CLAIM_MEMBER_AVESIS.TPA_ID
    ,LKP_CLAIM_MEMBER_AVESIS.TPA_DIV_ID
    ,DATA_SOURCE_NAME
    ,CLAIM_NBR
]) AS HUB_CLAIM_HKEY
,UTIL.FXN_ARRAY_HASH([
    CLAIM_ENTRY_DATE
    ,LINE_OF_BUSINESS_CODE
    ,PLAN_CODE
    ,BILLING_PROVIDER_PARTICIPATING_STATUS_CODE
    ,ADMITTED_FLAG
    ,ADMITTED_DATE
    ,ADMITTED_HOUR
    ,ADMISSION_SOURCE_CODE
    ,ADMISSION_TYPE_CODE
    ,DISCHARGE_DATE
    ,DISCHARGE_HOUR
    ,DISCHARGE_STATUS_CODE
    ,BILLING_TYPE_CODE
    ,CALCULATED_BILL_TOTAL_AMT
    ,CARE_TYPE_NAME
    ,DIVISION_NUMBER
    ,ELECTRONIC_CLAIM_TYPE_CODE
    ,ENCOUNTER_REASON_CODE
    ,FORM_NUMBER
    ,IS_PROCESSING_COMPLETE
    ,MICROFILM_NBR
    ,PLACE_OF_SERVICE_CODE
    ,PRICING_ZIP_SOURCE
    ,PATIENT_ACCOUNT_NUMBER
    ,SHOCK_CLAIM_IND
    ,SOURCE_LAST_UPDATED_DATETIME
    ,IS_PREDETERMINATION_CLAIM_FLAG
    ,ORIGINAL_CLAIM_ID
    ,MULTISOURCE_CLAIM_IND
    ,CLAIM_TYPE_CODE
    ,IPA_CODE
    ,BILLING_PROVIDER_VENDOR_NBR
    ,SERVICE_ZIP_CODE
    ,EDI_837_FACILITY_NPI_NBR
    ,EDI_837_FACILITY_NAME
    ,EDI_837_FACILITY_TELEPHONE_NBR
    ,EDI_837_FACILITY_ADDRESS_LINE_1_TEXT
    ,EDI_837_FACILITY_ADDRESS_LINE_2_TEXT
    ,EDI_837_FACILITY_CITY_NAME
    ,EDI_837_FACILITY_STATE_ABBREV_NAME
    ,EDI_837_FACILITY_ZIP_CODE_NBR
    ,EDI_837_FACILITY_OTHER_ID
    ,SEVERITY_OF_ILLNESS
    ,DIAGNOSIS_RELATED_GROUP_CODE
    ,PROVIDER_SPECIALTY
    ,PAID_STATUS_FOR_CMS
]) AS HASH_DIFF
FROM RAWDATA.AVESIS_PAID_CLAIM_EXTRACTS
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_AVESIS
        ON (LKP_CLAIM_MEMBER_AVESIS.CLAIM_NBR = AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO)
    JOIN (
            SELECT 
                AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO AS CD_CLAIM_NBR, 
                FILENAME, 
                FILE_ROW_NUMBER,
                AVESIS_PAID_CLAIM_EXTRACTS.ITEM_NO AS CD_CLAIM_LINE_NBR,
                UTIL.FXN_ARRAY_HASH([SUBSCRIBER_ID,CHECK_NO,CLAIM_TYPE,ADJUDICATION_DT,SERVICE_DT,ANSI_CODE,EXCEPTION_CODE,ADJUSTMENT_CODE,PROC_CODE,QUANTITY,TOOTH_ID,PROV_LOC_ID,PRVD_ID,COUNTY_CODE,LOB_IND]) AS CD_CLAIM_LINE_SEQ_NBR
            FROM RAWDATA.AVESIS_PAID_CLAIM_EXTRACTS
            WHERE AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO IS NOT NULL
                QUALIFY ROW_NUMBER() -- get the most current submitted file for a claim line
                    OVER(PARTITION BY AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO
                        ORDER BY TO_DATE(SPLIT_PART(SPLIT_PART(AVESIS_PAID_CLAIM_EXTRACTS.FILENAME, '_', 5), '.', 1), 'YYYYMMDD') DESC, FILE_ROW_NUMBER) = 1  
        ) CURRENT_CLAIM_FILE
        ON (CURRENT_CLAIM_FILE.CD_CLAIM_NBR = AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO
        AND CURRENT_CLAIM_FILE.CD_CLAIM_LINE_NBR = AVESIS_PAID_CLAIM_EXTRACTS.ITEM_NO
        AND CURRENT_CLAIM_FILE.CD_CLAIM_LINE_SEQ_NBR = UTIL.FXN_ARRAY_HASH([SUBSCRIBER_ID,CHECK_NO,CLAIM_TYPE,ADJUDICATION_DT,SERVICE_DT,ANSI_CODE,EXCEPTION_CODE,ADJUSTMENT_CODE,PROC_CODE,QUANTITY,TOOTH_ID,PROV_LOC_ID,PRVD_ID,COUNTY_CODE,LOB_IND])
        AND CURRENT_CLAIM_FILE.FILENAME = AVESIS_PAID_CLAIM_EXTRACTS.FILENAME
        AND CURRENT_CLAIM_FILE.FILE_ROW_NUMBER = AVESIS_PAID_CLAIM_EXTRACTS.FILE_ROW_NUMBER
        )
WHERE AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO IS NOT NULL 
;