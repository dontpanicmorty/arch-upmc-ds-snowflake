CREATE OR REPLACE VIEW STAGEDATA.REF_CLAIM_PROCEDURE_MODIFIER_ENVOLVE_SELECT_VW
COMMENT = 'This is a REF View containing Claim Procedure Modifier data'
--THIS IS A TEMPORARY SOLUTION AND WE WILL NEED TO REFACTOR TO UTILIZE THE OPTUM FILES
AS
SELECT DISTINCT
LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID
,LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID
,LKP_CLAIM_MEMBER_ENVOLVE.DATA_SOURCE_NAME AS DATA_SOURCE_NAME
,ENVOLVE_CLAIM_EXTRACTS.MODIFIER_1 as CODE
,IFF(IFNULL(ModifierDescription,'') = '', 'Description Not Found', ModifierDescription) AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CODE]) AS CLAIM_PROCEDURE_MODIFIER_HKEY
FROM RAWDATA.ENVOLVE_CLAIM_EXTRACTS
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_ENVOLVE
        ON (LKP_CLAIM_MEMBER_ENVOLVE.CLAIM_NBR = ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO)
    LEFT JOIN RAWDATA.MC400_DWOAO_PROCEDUREMODIFIER
        ON (ENVOLVE_CLAIM_EXTRACTS.MODIFIER_1 = MC400_DWOAO_PROCEDUREMODIFIER.Modifier
            AND LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID = MC400_DWOAO_PROCEDUREMODIFIER.TPACLIENT
            AND LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID = MC400_DWOAO_PROCEDUREMODIFIER.TPAIDOFCLIENT
            AND LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID = MC400_DWOAO_PROCEDUREMODIFIER.TPADIVISION)
WHERE ENVOLVE_CLAIM_EXTRACTS.MODIFIER_1 IS NOT NULL
;