CREATE OR REPLACE VIEW STAGEDATA.HUB_ACCUMULATOR_CODESET_SKYGEN_SELECT_VW
AS
SELECT DISTINCT
    'N/A' AS SOURCE_KEY,
    TPA_CLIENT_ID,
    TPA_ID,
    TPA_DIV_ID,
    DATA_SOURCE_NAME,
    CODESET_CODE,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CODESET_CODE]) AS HUB_ACCUMULATOR_CODESET_HKEY
FROM RAWDATA.DWSKYGEN_PLAN_ACCUMULATOR
;