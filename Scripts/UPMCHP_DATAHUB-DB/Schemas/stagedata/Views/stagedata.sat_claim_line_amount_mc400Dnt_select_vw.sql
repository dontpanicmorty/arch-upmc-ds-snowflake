!set variable_substitution=true;
CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_LINE_AMOUNT_MC400Dnt_SELECT_VW
COMMENT='This is a SAT View containing Claim Line Amount data'
AS
SELECT 
'000001' AS TPA_CLIENT_ID
,'000001' AS TPA_ID
,'0001' AS TPA_DIV_ID
,'MC400Dnt' AS DATA_SOURCE_NAME
,CLAIMNBR AS CLAIM_NBR
,STAGEDATA.FXN_GET_CLAIM_LINE_NBR_MC400(DATA_SOURCE_NAME, CLAIMSDETAIL.ProcedureModifier, CLAIMSDETAIL.ProcedureCode, CLAIMSDETAIL.SpecificDateOfService) AS CLAIM_LINE_NBR
,CLAIMSEQUENCE AS CLAIM_LINE_SEQ_NBR
,STAGEDATA.FXN_GET_CLAIM_LINE_PROCEDURE_ADJ_CODE_MC400(DATA_SOURCE_NAME, CLAIMSDETAIL.ProcedureAdj) AS CLAIM_LINE_PROCEDURE_ADJ_CODE
,AllowedAmt AS ALLOWED_AMOUNT
,BilledAmt AS CHARGE_AMOUNT
,NULL AS CLAIM_AMT_01
,NULL AS CLAIM_AMT_01_DESC
,NULL AS CLAIM_AMT_02
,NULL AS CLAIM_AMT_02_DESC
,IFF(UPPER(CoPayReason) = 'CO', CopayAmt, 0) AS COPAY_AMT_01
,NULL AS COPAY_AMT_02 --n/a for DNV
,NULL as COPAY_AMT_03 --n/a for DNV
,DeductAmt AS DEDUCTIBLE_AMOUNT
,NotCoveredAmt AS NOT_COVERED_AMOUNT
,NetAmt AS PAID_AMOUNT
,NULL AS PAID_GROSS_AMOUNT --n/a for DNV
,0 AS PAY_FOR_PERFORMANCE_AMOUNT
,WithHoldAmt AS WITHHOLD_AMOUNT
,IFF(UPPER(CoPayReason) <> 'CO', CopayAmt, 0) AS COINSURANCE_AMOUNT
,CodeReviewOrigBilledAmt AS CODE_REVIEW_ORIGINAL_BILLING_AMOUNT
,CodeReviewOriginalNetAmt AS CODE_REVIEW_ORIGINAL_NET_AMOUNT
,NULL AS APPROVED_AMT --n/a for DNV
,InterestDiscountAmt AS INTEREST_DISCOUNT_AMOUNT
,OicPaidAmount AS THIRD_PARTY_PAID_AMOUNT
,OicAllowedAmount AS THIRD_PARTY_ALLOWED_AMOUNT
,oicPaidAmount AS OIC_PAID_AMOUNT
,oicAllowedAmount AS OIC_ALLOWED_AMOUNT
,NULL AS HRA_APPLIED_AMT --n/a for DNV
,NULL AS HIA_APPLIED_AMT --n/a for DNV

/* mc400upm will need this logic for medical...
CASE 
    WHEN SAT_CLAIM_LINE_AMOUNT.CLAIM_AMT_01_DESC = 'HRA' THEN CLAIM_AMT_01
    WHEN SAT_CLAIM_LINE_AMOUNT.CLAIM_AMT_02_DESC = 'HRA' THEN CLAIM_AMT_02
    ELSE 0
 AS HRA_APPLIED_AMT,
CASE WHEN SAT_CLAIM_LINE_AMOUNT.CLAIM_AMT_01_DESC = 'HIA' THEN CLAIM_AMT_01
     WHEN SAT_CLAIM_LINE_AMOUNT.CLAIM_AMT_02_DESC = 'HIA' THEN CLAIM_AMT_02
     Else 0 END AS HIA_APPLIED_AMT,
*/
,NULL AS MEMBER_PAY_FLAG

,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_NBR, CLAIM_LINE_NBR, CLAIM_LINE_SEQ_NBR, CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY
,UTIL.FXN_ARRAY_HASH([
    ALLOWED_AMOUNT
    ,CHARGE_AMOUNT
    ,CLAIM_AMT_01
    ,CLAIM_AMT_01_DESC
    ,CLAIM_AMT_02
    ,CLAIM_AMT_02_DESC
    ,COPAY_AMT_01
    ,COPAY_AMT_02 --n/a for DNV
    ,COPAY_AMT_03 --n/a for DNV
    ,DEDUCTIBLE_AMOUNT
    ,NOT_COVERED_AMOUNT
    ,PAID_AMOUNT
    ,PAID_GROSS_AMOUNT -- n/a for DNV
    ,PAY_FOR_PERFORMANCE_AMOUNT
    ,WITHHOLD_AMOUNT
    ,COINSURANCE_AMOUNT
    ,CODE_REVIEW_ORIGINAL_BILLING_AMOUNT
    ,CODE_REVIEW_ORIGINAL_NET_AMOUNT
    ,APPROVED_AMT
    ,INTEREST_DISCOUNT_AMOUNT
    ,THIRD_PARTY_PAID_AMOUNT
    ,THIRD_PARTY_ALLOWED_AMOUNT
    ,OIC_PAID_AMOUNT
    ,OIC_ALLOWED_AMOUNT
    ,HRA_APPLIED_AMT
    ,HIA_APPLIED_AMT
    ,MEMBER_PAY_FLAG
]) AS HASH_DIFF

FROM &{MC400}.DWDNV.ClaimsDetail
WHERE ClaimsDetail.ClaimNbr IN
	(
		SELECT ClaimNbr FROM &{MC400}.DWDNV.CLAIMS 
		WHERE CLAIMS.MemberNbr <> '99999999901' --Exclude Generic Default Member Claims
	)
;
!set variable_substitution=false;