CREATE OR REPLACE VIEW STAGEDATA.SAT_PROVIDER_DETAIL_SKYGEN_SELECT_VW
COMMENT = 'This is a SAT View containing Skygen provider details'
AS
SELECT 
DWSKYGEN_PROVIDER_DETAIL.TPA_CLIENT_ID
,DWSKYGEN_PROVIDER_DETAIL.TPA_ID
,DWSKYGEN_PROVIDER_DETAIL.TPA_DIV_ID
,'Skygen' as DATA_SOURCE_NAME
,DWSKYGEN_PROVIDER_DETAIL.PROVIDER_ID
,DWSKYGEN_PROVIDER_DETAIL.PROVIDER_TYPE AS PROVIDER_TYPE_NAME
,DWSKYGEN_PROVIDER_DETAIL.PROVIDER_FULL_NAME AS FULL_NAME
,DWSKYGEN_PROVIDER_DETAIL.PROVIDER_FIRST_NAME AS FIRST_NAME
,DWSKYGEN_PROVIDER_DETAIL.PROVIDER_LAST_NAME AS LAST_NAME
,DWSKYGEN_PROVIDER_DETAIL.PROVIDER_MIDDLE_NAME AS MIDDLE_NAME
,SUBSTRING (DWSKYGEN_PROVIDER_DETAIL.PROVIDER_MIDDLE_NAME, 1, 1) AS MIDDLE_INITIAL_NAME
,DWSKYGEN_PROVIDER_DETAIL.PROVIDER_GENDER AS GENDER_NAME
,DWSKYGEN_PROVIDER_DETAIL.PROVIDER_EMAIL AS EMAIL_ADDRESS
,DWSKYGEN_PROVIDER_DETAIL.PROVIDER_SSN AS SOCIAL_SECURITY_NBR
,NULL AS DEGREE_TEXT
,NULL AS SUFFIX_NAME
,NULL AS LOCUM_TENENS_IND
,NULL AS INVISIBLE_PROVIDER_IND
,NULL AS TEMPORARY_PROVIDER_IND
,DWSKYGEN_PROVIDER_DETAIL.PROVIDER_NPI AS NATIONAL_PROVIDER_ID
,NULL AS DATE_OF_BIRTH
,NULL AS PRIMARY_PREFERRED_DELIVERY_METHOD_CODE
,NULL AS BOARD_CERTIFIED_IND
,NULL AS STATE_MEDICAID_ID
,NULL AS PRIMARY_SPECIALTY_NAME
,NULL AS PRIMARY_TAXONOMY_CODE
,NULL AS PRESCRIBER_SOURCE_CODE
,NULL AS UPIN_NBR
,NULL AS PROVIDER_START_DATE 
,NULL AS PROVIDER_ACTIVE_IND
,NULL AS FACILITY_INCEPTION_DATE
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY
,UTIL.FXN_ARRAY_HASH([
    PROVIDER_TYPE_NAME,
    FULL_NAME,
    FIRST_NAME,
    LAST_NAME,
    MIDDLE_NAME,
    MIDDLE_INITIAL_NAME,
    GENDER_NAME,
    EMAIL_ADDRESS,
    SOCIAL_SECURITY_NBR,
    DEGREE_TEXT,
    SUFFIX_NAME,
    LOCUM_TENENS_IND,
    INVISIBLE_PROVIDER_IND,
    TEMPORARY_PROVIDER_IND,
    NATIONAL_PROVIDER_ID,
    DATE_OF_BIRTH,
    PRIMARY_PREFERRED_DELIVERY_METHOD_CODE,
    BOARD_CERTIFIED_IND,
    STATE_MEDICAID_ID,
    PRIMARY_SPECIALTY_NAME,
    PRIMARY_TAXONOMY_CODE,
    PRESCRIBER_SOURCE_CODE,
    UPIN_NBR, 
    PROVIDER_START_DATE, 
    PROVIDER_ACTIVE_IND,
    FACILITY_INCEPTION_DATE
]) AS HASH_DIFF
FROM RAWDATA.DWSKYGEN_PROVIDER_DETAIL
WHERE PROVIDER_TYPE = 'Practitioner'
;