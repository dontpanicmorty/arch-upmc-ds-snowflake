!set variable_substitution=true;
CREATE OR REPLACE VIEW STAGEDATA.REF_CLAIM_PROCESSING_REASON_MC400DNT_SELECT_VW
COMMENT = 'Source view for MC400Dnt Claim Processing Reason(s) data'
AS 
SELECT
'000001' AS TPA_CLIENT_ID
,'000001' AS TPA_ID
,'0001' AS TPA_DIV_ID
,'MC400Dnt' AS DATA_SOURCE_NAME
,'CoPay' AS CLAIM_PROCESSING_REASON_TYPE
,Code AS CODE
-- you need to string the records together one description is split across multiple records
,LISTAGG(TRIM(Description),' ') WITHIN GROUP (ORDER BY CoPayRsnCodeSeq ASC) AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,Hipaa277ReasonCode AS HIPAA_277_CODE
,Hipaa835ReasonCode AS HIPAA_835_CODE
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_PROCESSING_REASON_TYPE, CODE]) AS CLAIM_PROCESSING_REASON_HKEY
FROM &{MC400}.DWDNV.CoPayReason
WHERE DELETEDFLAG = '1900-01-01 00:00:00.000'
AND Code IN --only take codes that are on a claim
    (
        SELECT DISTINCT CoPayReason
        FROM &{MC400}.DWDNV.ClaimsDetail
    )
GROUP BY TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_PROCESSING_REASON_TYPE, CODE, HIPAA_277_CODE, HIPAA_835_CODE

UNION ALL

SELECT
'000001' AS TPA_CLIENT_ID
,'000001' AS TPA_ID
,'0001' AS TPA_DIV_ID
,'MC400Dnt' AS DATA_SOURCE_NAME
,'Deductible' AS CLAIM_PROCESSING_REASON_TYPE
,DeductibleReason AS CODE
-- you need to string the records together one description is split across multiple records
,LISTAGG(TRIM(DeductibleReasonDescrption),' ') WITHIN GROUP (ORDER BY DeductibleRsnCodeSeq ASC) AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,NULL AS HIPAA_277_CODE
,NULL AS HIPAA_835_CODE
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_PROCESSING_REASON_TYPE, CODE]) AS CLAIM_PROCESSING_REASON_HKEY
FROM &{MC400}.DWDNV.DeductibleReasonMaster
WHERE DELETEDFLAG = '1900-01-01 00:00:00.000'
AND Code IN --only take codes that are on a claim
    (
        SELECT DISTINCT DeductibleReason
        FROM &{MC400}.DWDNV.ClaimsDetail
    )
GROUP BY TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_PROCESSING_REASON_TYPE, CODE

UNION ALL

SELECT //pretty sure coInsurance reasons do not exist for mc400Dnt
'000001' AS TPA_CLIENT_ID
,'000001' AS TPA_ID
,'0001' AS TPA_DIV_ID
,'MC400Dnt' AS DATA_SOURCE_NAME
,'CoInsurance' AS CLAIM_PROCESSING_REASON_TYPE
,Code AS CODE
-- you need to string the records together one description is split across multiple records
,LISTAGG(TRIM(Description),' ') WITHIN GROUP (ORDER BY CoPayRsnCodeSeq ASC) AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,Hipaa277ReasonCode AS HIPAA_277_CODE
,Hipaa835ReasonCode AS HIPAA_835_CODE
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_PROCESSING_REASON_TYPE, CODE]) AS CLAIM_PROCESSING_REASON_HKEY
FROM &{MC400}.DWDNV.CoPayReason
WHERE DELETEDFLAG = '1900-01-01 00:00:00.000'
AND Code IN --only take codes that are on a claim
    (
        SELECT DISTINCT CoInsuranceReason
        FROM &{MC400}.DWDNV.ClaimsDetail
    )
GROUP BY TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_PROCESSING_REASON_TYPE, CODE, HIPAA_277_CODE, HIPAA_835_CODE

UNION ALL

SELECT
'000001' AS TPA_CLIENT_ID
,'000001' AS TPA_ID
,'0001' AS TPA_DIV_ID
,'MC400Dnt' AS DATA_SOURCE_NAME
,'Service' AS CLAIM_PROCESSING_REASON_TYPE
,Code AS CODE
,TRIM(Description) AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,NULL AS HIPAA_277_CODE
,NULL AS HIPAA_835_CODE
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_PROCESSING_REASON_TYPE, CODE]) AS CLAIM_PROCESSING_REASON_HKEY
FROM &{MC400}.DWDNV.ServiceReason
WHERE DELETEDFLAG = '1900-01-01 00:00:00.000'
AND Code IN --only take codes that are on a claim
    (
        SELECT DISTINCT ServiceReason
        FROM &{MC400}.DWDNV.ClaimsDetail
    )

UNION ALL

SELECT
'000001' AS TPA_CLIENT_ID
,'000001' AS TPA_ID
,'0001' AS TPA_DIV_ID
,'MC400Dnt' AS DATA_SOURCE_NAME
,'Adjustment' AS CLAIM_PROCESSING_REASON_TYPE
,Code AS CODE
-- you need to string the records together one description is split across multiple records
,LISTAGG(TRIM(Description),' ') WITHIN GROUP (ORDER BY AdjustmentRsnCodeSeq ASC) AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,Hipaa277ReasonCode AS HIPAA_277_CODE
,Hipaa835ReasonCode AS HIPAA_835_CODE
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_PROCESSING_REASON_TYPE, CODE]) AS CLAIM_PROCESSING_REASON_HKEY
FROM &{MC400}.DWDNV.AdjustmentReason
WHERE DELETEDFLAG = '1900-01-01 00:00:00.000'
AND Code IN --only take codes that are on a claim
    (
        SELECT AdjustmentReason1
        FROM &{MC400}.DWDNV.ClaimsDetail
        UNION
        SELECT AdjustmentReason2
        FROM &{MC400}.DWDNV.ClaimsDetail
    )
GROUP BY TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_PROCESSING_REASON_TYPE, CODE, HIPAA_277_CODE, HIPAA_835_CODE
;

!set variable_substitution=false;
