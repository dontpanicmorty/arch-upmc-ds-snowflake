!set variable_substitution=true;

CREATE OR REPLACE VIEW STAGEDATA.SAT_MARKETING_CUTLOG_SELECT_VW COMMENT = 'Source view for SAT_MARKETING_CUTLOG' AS
SELECT DISTINCT
        CURRENT_TIMESTAMP() AS ROW_EFFECTIVE_DATETIME,
        '12/31/9999' AS ROW_EXPIRATION_DATETIME, 
        --CASE 
        --WHEN CURRENT_TIMESTAMP() BETWEEN ROW_EFFECTIVE_DATETIME and ROW_EXPIRATION_DATETIME THEN 1
        --ELSE 0
        --END AS IS_CURRENT_ROW_FLAG,
        CURRENT_TIMESTAMP BETWEEN CURRENT_TIMESTAMP() AND  '9999-12-31' AS IS_CURRENT_ROW_FLAG,
        CUTCORRESPONDENCELOGFILE.REFERENCEID as MEMBER_NBR, 
      --  ROW_NUMBER() OVER (
      --  PARTITION BY  CUTCORRESPONDENCELOGFILE.CUTIDENTIFIER, ACTIVITYREPRESENTATIVEID , CUTACTIVITYFILE.ACTIVITYCODE , CUTACTIVITYFILE.ACTIVITYDATE
      --  ORDER BY TBD.THEDATE DESC
      --  ) ACTIVE_ACCOUNT,
        CUTCORRESPONDENCELOGFILE.CUTIDENTIFIER AS CUT_IDENTIFIER,
        CUTACTIVITYFILE.ACTIVITYCODE AS ACTIVITY_CODE,
        ACTIVITYREPRESENTATIVEID AS ACTIVITY_REPRESENTATIVE_ID, 
        CUTCORRESPONDENCELOGFILE.CORRESPONDENCETYPE AS CORRESPONDENCE_TYPE ,
        CUTCONTACTTYPE AS CUT_CONTACT_TYPE ,  
        CUTCONTACTIDENTIFIER AS CUT_CONTACT_ID,
        IFNULL(CUTCONTACTIDNAME,'Unknown') AS CUT_CONTACT_ID_NAME, 
        CUTCONTACTNAME AS CUT_CONTACT_NAME,
         'MC400Upm' AS MC_DATA_SOURCE_NAME,
        UTIL.FXN_ARRAY_HASH([MC_DATA_SOURCE_NAME, CUTCORRESPONDENCELOGFILE.CUTIDENTIFIER, CUTACTIVITYFILE.ACTIVITYCODE, CUTACTIVITYFILE.ACTIVITYDATE, CUTACTIVITYFILE.ACTIVITYTIME]) AS HUB_MARKETING_CUTLOG_HKEY,
        UTIL.FXN_ARRAY_HASH([MEMBER_NBR, ACTIVITY_REPRESENTATIVE_ID, CORRESPONDENCE_TYPE, CUT_CONTACT_TYPE, CUT_CONTACT_ID, CUT_CONTACT_ID_NAME, CUT_CONTACT_NAME]) AS HASH_DIFF
FROM &{MC400}.DWOAO.CUTCORRESPONDENCELOGFILE CUTCORRESPONDENCELOGFILE
INNER JOIN &{MC400}.DWOAO.CUTACTIVITYFILE CUTACTIVITYFILE
        ON CUTCORRESPONDENCELOGFILE.CUTIDENTIFIER = CUTACTIVITYFILE.CUTIDENTIFIER
        AND CUTCORRESPONDENCELOGFILE.TPACLIENT = CUTACTIVITYFILE.TPACLIENT
        AND CUTCORRESPONDENCELOGFILE.TPAIDOFCLIENT = CUTACTIVITYFILE.TPAIDOFCLIENT
INNER JOIN &{MC400}.DWOAO.TIMEBYDAY TBD
        ON CUTACTIVITYFILE.ACTIVITYDATE = TBD.TIMEID
WHERE (TBD.YEAR >= YEAR(GETDATE()) - 1 
        AND CUTCORRESPONDENCELOGFILE.TPAIDOFCLIENT = '000001'
        AND CUTCORRESPONDENCELOGFILE.TPACLIENT = '000001'
        AND CUTCORRESPONDENCELOGFILE.TPADIVISION = '0001')
;

!set variable_substitution=false;