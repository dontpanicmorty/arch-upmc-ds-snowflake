CREATE OR REPLACE VIEW STAGEDATA.REF_CLAIM_PROCEDURE_CATEGORY_SKYGEN_SELECT_VW
COMMENT = 'This is a REF View containing Claim Procedure Category data'
AS

SELECT DISTINCT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
,LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME
,PROCEDURE_CODE as CODE
,PROCEDURE_DESC as CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CODE]) AS CLAIM_PROCEDURE_CATEGORY_HKEY
FROM RAWDATA.DWSKYGEN_CLAIM_DETAIL
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR = DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR)

;