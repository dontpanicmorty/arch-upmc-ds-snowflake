CREATE OR REPLACE VIEW STAGEDATA.SAT_RIDER_DETAIL_MC400UPM_SELECT_VW
COMMENT = 'This is a SAT View containing rider detail data'
AS
SELECT
TpaClient AS TPA_CLIENT_ID
,TpaIdOfClient AS TPA_ID
,TpaDivision AS TPA_DIV_ID
,'MC400Upm' AS DATA_SOURCE_NAME
,RiderCode AS RIDER_CODE
,RiderDesc AS RIDER_DESC
,TRY_TO_DATE(TO_CHAR(RiderEffDate),'YYYYMMDD') AS RIDER_EFFECTIVE_DATE
,IFNULL(TRY_TO_DATE(TO_CHAR(RiderTermDate), 'YYYYMMDD'), '9999-12-31') AS RIDER_TERMINATION_DATE
,TieringMethod AS TIER_METHOD_CODE
,RiderAmt1 AS RIDER_AMT_1
,RiderAmt2 AS RIDER_AMT_2
,RiderAmt3 AS RIDER_AMT_3
,RiderAmt4 AS RIDER_AMT_4
,RiderAmt5 AS RIDER_AMT_5
,RiderAmt6 AS RIDER_AMT_6
,RiderAmt7 AS RIDER_AMT_7
,RiderAmt8 AS RIDER_AMT_8
,RiderAmt9 AS RIDER_AMT_9
,RiderAmt10 AS RIDER_AMT_10
,RiderType AS RIDER_TYPE_CODE
,ArCashDistCode AS AR_CASH_GL_DISTRIBUTION_CODE
,CompanyCode AS COMPANY_CODE
,EligRule AS ELIGIBILITY_RULE_CODE
,GlDistributionCode AS GL_DISTRIBUTION_CODE
,GroupNbr AS GROUP_NBR
,IFF(SubGroup = '', 'UNK', SubGroup) AS SUB_GROUP_NBR
,CASE
    WHEN SUBSTR(GROUP_NBR,1,2) = 'MA' AND RIDER_TYPE_CODE = 'RX' THEN '6'
    WHEN GROUP_NBR LIKE 'SNP%' AND RIDER_TYPE_CODE = 'RX' THEN '8'
    WHEN GROUP_NBR LIKE 'MC%' AND RIDER_TYPE_CODE = 'RX' THEN '7'
    ELSE 'N'
END AS FORMULARY_CODE
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, RIDER_CODE]) AS HUB_RIDER_HKEY

FROM RAWDATA.MC400_DWOAO_RIDERS
;
