CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_DETAIL_RENDERING_PROVIDER_NVA_SELECT_VW
COMMENT = 'Source view for NVA data into LNK_CLAIM_DETAIL_RENDERING_PROVIDER'
AS
SELECT
LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID AS CD_TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_NVA.TPA_ID AS CD_TPA_ID
,LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID AS CD_TPA_DIV_ID
,LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME AS CD_DATA_SOURCE_NAME
,NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo" AS CD_CLAIM_NBR
,NVA_PAID_CLAIM_EXTRACTS_VW."ClaimSeqNo" AS CD_CLAIM_LINE_NBR
,CONCAT(NVA_PAID_CLAIM_EXTRACTS_VW."ClaimSeqNo", NVA_PAID_CLAIM_EXTRACTS_VW."Trantype") AS CD_CLAIM_LINE_SEQ_NBR
,'N/A' AS CD_CLAIM_LINE_PROCEDURE_ADJ_CODE
,'000001' AS P_TPA_CLIENT_ID
,'000001' AS P_TPA_ID
,'0001' AS P_TPA_DIV_ID
,'NVA' AS P_DATA_SOURCE_NAME
,COALESCE(Practitioner.PROVIDER_ID, Facility.PROVIDER_ID) AS P_PROVIDER_ID
,UTIL.FXN_ARRAY_HASH([CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE, P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS LNK_CLAIM_DETAIL_RENDERING_PROVIDER_HKEY
,UTIL.FXN_ARRAY_HASH([CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY
,UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS HUB_PROVIDER_HKEY

FROM RAWDATA.NVA_PAID_CLAIM_EXTRACTS_VW
   JOIN STAGEDATA.LKP_CLAIM_MEMBER_NVA
      ON (LKP_CLAIM_MEMBER_NVA.CLAIM_NBR = NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo")

   LEFT OUTER JOIN (SELECT DISTINCT
         CONCAT(PROVIDER_NPI,TRIM(ECP_TYPE)) AS PROVIDER_ID
         FROM RAWDATA.NVA_PROVIDER
         QUALIFY ROW_NUMBER() -- Get the most current values for a given npi/ecp_type across all the files
            OVER(PARTITION BY NVA_PROVIDER.PROVIDER_NPI, TRIM(NVA_PROVIDER.ECP_TYPE)
               ORDER BY SPLIT_PART(SPLIT_PART(NVA_PROVIDER.FILENAME, '_', 7), '.', 1) DESC) = 1
      ) Practitioner
      ON (Practitioner.PROVIDER_ID = CONCAT(NVA_PAID_CLAIM_EXTRACTS_VW."RendProvNPI",'Doctor'))

   LEFT OUTER JOIN (SELECT DISTINCT
         CONCAT(PROVIDER_NPI,TRIM(ECP_TYPE)) AS PROVIDER_ID
         FROM RAWDATA.NVA_PROVIDER
         QUALIFY ROW_NUMBER() -- Get the most current values for a given npi/ecp_type across all the files
            OVER(PARTITION BY NVA_PROVIDER.PROVIDER_NPI, TRIM(NVA_PROVIDER.ECP_TYPE)
               ORDER BY SPLIT_PART(SPLIT_PART(NVA_PROVIDER.FILENAME, '_', 7), '.', 1) DESC) = 1
      ) Facility
      ON (Facility.PROVIDER_ID = CONCAT(NVA_PAID_CLAIM_EXTRACTS_VW."RendProvNPI",'Clinic'))

WHERE NVA_PAID_CLAIM_EXTRACTS_VW."RendProvID" IS NOT NULL
AND P_PROVIDER_ID IS NOT NULL
;