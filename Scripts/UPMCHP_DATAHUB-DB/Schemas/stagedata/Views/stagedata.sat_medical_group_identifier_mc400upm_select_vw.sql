
CREATE OR REPLACE VIEW STAGEDATA.SAT_MEDICAL_GROUP_IDENTIFIER_MC400UPM_SELECT_VW
COMMENT = 'This is a MC400 SAT View containing Medical Group Identifier data'
AS
--Med Group NPI
(
 SELECT DISTINCT
    P.TpaClient AS TPA_CLIENT_ID,
    P.TpaIdOfClient AS TPA_ID,
    P.TpaDivision AS TPA_DIV_ID,
    'MC400Upm' AS DATA_SOURCE_NAME,
    P.PROVIDERNBR AS MEDICAL_GROUP_ID,
    'National Provider Identifier' AS IDENTIFIER_NAME,
    TRIM(SP.PROVIDERSUBPART) AS IDENTIFIER_NBR,
    'Type 2' AS IDENTIFIER_SUBTYPE,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY,
    UTIL.FXN_ARRAY_HASH([IDENTIFIER_NAME, IDENTIFIER_NBR, IDENTIFIER_SUBTYPE]) AS HASH_DIFF
    FROM RAWDATA.MC400_DWOAO_PROVIDERS P
    INNER JOIN RAWDATA.MC400_DWOAO_PROVIDERSUBPART SP
        ON P.PROVIDERNBR = SP.PROVIDERNUMBER
    WHERE UPPER(SUBSTRING(PROVIDERNBR,1,1)) = 'V'
        AND SP.PROVIDERSUBPART <> ''

UNION

 SELECT DISTINCT
    P.TpaClient AS TPA_CLIENT_ID,
    P.TpaIdOfClient AS TPA_ID,
    P.TpaDivision AS TPA_DIV_ID,
    'MC400Upm' AS DATA_SOURCE_NAME,
    P.PROVIDERNBR AS MEDICAL_GROUP_ID,
    'National Provider Identifier'  AS IDENTIFIER_NAME,
    TRIM(P.NATIONALPROVIDERNBR) AS IDENTIFIER_NBR,
    'Type 2' AS IDENTIFIER_SUBTYPE,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY,
    UTIL.FXN_ARRAY_HASH([IDENTIFIER_NAME, IDENTIFIER_NBR, IDENTIFIER_SUBTYPE]) AS HASH_DIFF
    FROM RAWDATA.MC400_DWOAO_PROVIDERS P
    WHERE UPPER(SUBSTRING(PROVIDERNBR,1,1)) = 'V'
    AND P.NATIONALPROVIDERNBR <> ''
)

UNION
--Med Group MA
(
 SELECT DISTINCT
     P.TpaClient AS TPA_CLIENT_ID,
     P.TpaIdOfClient AS TPA_ID,
     P.TpaDivision AS TPA_DIV_ID,
     'MC400Upm' AS DATA_SOURCE_NAME,
     PROVIDERNBR AS MEDICAL_GROUP_ID,
     'State Medicaid ID'   AS IDENTIFIER_NAME,
     TRIM(StateMedicaidID)  AS IDENTIFIER_NBR,
     'Unknown' AS IDENTIFIER_SUBTYPE,
     UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY,
     UTIL.FXN_ARRAY_HASH([IDENTIFIER_NAME, IDENTIFIER_NBR, IDENTIFIER_SUBTYPE]) AS HASH_DIFF
     FROM RAWDATA.MC400_DWOAO_PROVIDERS P
     WHERE UPPER(SUBSTRING(MEDICAL_GROUP_ID,1,1)) = 'V'
     AND StateMedicaidID <> ''
     AND StateMedicaidID NOT LIKE '%88888%'
)

UNION
--Med Group MC
(
 SELECT DISTINCT
     P.TpaClient AS TPA_CLIENT_ID,
     P.TpaIdOfClient AS TPA_ID,
     P.TpaDivision AS TPA_DIV_ID,
     'MC400Upm' AS DATA_SOURCE_NAME,
     PROVIDERNBR AS MEDICAL_GROUP_ID,
     'Medicare Nbr' AS IDENTIFIER_NAME,
     TRIM(MedicareNbr) AS IDENTIFIER_NBR,
     'Unknown' AS IDENTIFIER_SUBTYPE,
     UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY,
     UTIL.FXN_ARRAY_HASH([IDENTIFIER_NAME, IDENTIFIER_NBR, IDENTIFIER_SUBTYPE]) AS HASH_DIFF
     FROM RAWDATA.MC400_DWOAO_PROVIDERS P
     WHERE UPPER(SUBSTRING(MEDICAL_GROUP_ID ,1,1)) = 'V'
     AND MEDICARENBR NOT IN ('', 'TAXID', 'TAX ID', 'TAXOD')
);
