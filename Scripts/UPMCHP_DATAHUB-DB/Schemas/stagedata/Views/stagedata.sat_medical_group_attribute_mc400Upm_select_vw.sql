CREATE OR REPLACE VIEW STAGEDATA.SAT_MEDICAL_GROUP_ATTRIBUTE_MC400UPM_SELECT_VW(
	TPA_CLIENT_ID,
	TPA_ID,
	TPA_DIV_ID,
	DATA_SOURCE_NAME,
	MEDICAL_GROUP_ID,
	PRIMARY_PHO_NAME,
	PRIMARY_PHO_TERMINATION_DATE,
	SECONDARY_PHO_NAME,
	SECONDARY_PHO_TERMINATION_DATE,
	TERTIARY_PHO_NAME,
	TERTIARY_PHO_TERMINATION_DATE,
	PA_MEDICAID_IND,
	PP_ACA_ENHANCED_PAY_IND,
	MALPRACTICE_COVERAGE_IND,
	HUB_MEDICAL_GROUP_HKEY,
	HASH_DIFF
) COMMENT='This is a SAT View containing MC400 Medical Group Attribute data'
AS
 
WITH PRV_CTE AS (
SELECT DISTINCT
PRV414_VW.IRSSSN,
'Y' AS PA_MEDICAID_IND_CTE
FROM  &{IDAP_LAKE}.PROVIDER.PRV430 PRV430
LEFT JOIN &{IDAP_LAKE}.PROVIDER.PRV414_VW PRV414_VW
ON PRV430.SERVICELOCATION = PRV414_VW.SERVICELOC
AND PRV430.PROMISEPROVIDERNUMBER = PRV414_VW.PROMISEPROV
WHERE  PRV414_VW.ENDDATE = '22991231' 
AND PRV414_VW.SPECCODEEND = '22991231' 
AND PRV414_VW.STATUSCODE = 'A' 
AND PRV414_VW.IRSSSNIND = 'I'
)
 
SELECT DISTINCT
TPACLIENT AS TPA_CLIENT_ID
,TPAIDOFCLIENT AS TPA_ID
,TPADIVISION AS TPA_DIV_ID
,'MC400Upm' AS DATA_SOURCE_NAME
,PROVIDERNBR AS MEDICAL_GROUP_ID
,NULL AS PRIMARY_PHO_NAME
,NULL AS PRIMARY_PHO_TERMINATION_DATE
,NULL AS SECONDARY_PHO_NAME
,NULL AS SECONDARY_PHO_TERMINATION_DATE
,NULL AS TERTIARY_PHO_NAME
,NULL AS TERTIARY_PHO_TERMINATION_DATE
,IFF(PRV_CTE.PA_MEDICAID_IND_CTE IS NULL, 'N', PRV_CTE.PA_MEDICAID_IND_CTE) AS PA_MEDICAID_IND
,NULL AS PP_ACA_ENHANCED_PAY_IND
,NULL AS MALPRACTICE_COVERAGE_IND
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY
,UTIL.FXN_ARRAY_HASH([PRIMARY_PHO_NAME, PRIMARY_PHO_TERMINATION_DATE,SECONDARY_PHO_NAME,SECONDARY_PHO_TERMINATION_DATE,
TERTIARY_PHO_NAME, TERTIARY_PHO_TERMINATION_DATE, PA_MEDICAID_IND, PP_ACA_ENHANCED_PAY_IND, MALPRACTICE_COVERAGE_IND]) AS HASH_DIFF
FROM RAWDATA.MC400_DWOAO_PROVIDERS
LEFT JOIN PRV_CTE
ON RAWDATA.MC400_DWOAO_PROVIDERS.ALTERNATEPROVIDERNO = PRV_CTE.IRSSSN
WHERE UPPER(SUBSTR(ProviderNbr,1,1)) = 'V'
AND ALTERNATEPROVIDERNO <> ''
;
!set variable_substitution=false;
