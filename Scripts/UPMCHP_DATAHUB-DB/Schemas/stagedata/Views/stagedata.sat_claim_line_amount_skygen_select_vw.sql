!set variable_substitution=true;
CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_LINE_AMOUNT_SKYGEN_SELECT_VW
COMMENT = 'This is a SAT View containing Claim Line Amount data'
AS

SELECT
    LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID,
    LKP_CLAIM_MEMBER_SKYGEN.TPA_ID,
    LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID,
    LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME,
    DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR,
    DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_NBR,
    DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR, 
    DWSKYGEN_CLAIM_DETAIL.PROCEDURE_ADJ_CODE AS CLAIM_LINE_PROCEDURE_ADJ_CODE,
ALLOWED_AMOUNT,
BILLED_AMOUNT AS CHARGE_AMOUNT,
NULL AS CLAIM_AMT_01,
NULL AS CLAIM_AMT_01_DESC,
NULL AS CLAIM_AMT_02,
NULL AS CLAIM_AMT_02_DESC,
COPAY_AMOUNT AS COPAY_AMT_01,
NULL AS COPAY_AMT_02,
NULL as COPAY_AMT_03,
DEDUCTIBLE_AMOUNT,
CASE
    WHEN (MEMBER_PAY_NOT_COVERED_REASONS.MEMBER_PAY_IND = 'Y' 
            OR DEDUCTIBLE_AMOUNT > 0 
            OR COPAY_AMT_01 > 0 
            OR COINSURANCE_AMOUNT > 0)
            AND DWSKYGEN_CLAIM_DETAIL.PROCEDURE_CODE BETWEEN 'D8000' AND 'D8999' 
        THEN ALLOWED_AMOUNT
    WHEN (MEMBER_PAY_NOT_COVERED_REASONS.MEMBER_PAY_IND = 'Y'
            AND DEDUCTIBLE_AMOUNT = 0
            AND COPAY_AMT_01 = 0
            AND COINSURANCE_AMOUNT = 0)
            AND DWSKYGEN_CLAIM_DETAIL.PROCEDURE_CODE NOT BETWEEN 'D8000' AND 'D8999'
        THEN (BILLED_AMOUNT - PAID_AMOUNT)
    ELSE NOT_COVERED_AMOUNT
END AS NOT_COVERED_AMOUNT,
PAID_AMOUNT,
NULL AS PAID_GROSS_AMOUNT,
NULL AS PAY_FOR_PERFORMANCE_AMOUNT,
NULL AS WITHHOLD_AMOUNT,
COINSURANCE_AMOUNT,
NULL AS CODE_REVIEW_ORIGINAL_BILLING_AMOUNT,
NULL AS CODE_REVIEW_ORIGINAL_NET_AMOUNT,
PAID_AMOUNT AS APPROVED_AMT,
NULL AS INTEREST_DISCOUNT_AMOUNT,
THIRD_PARTY_PAID_AMOUNT,
NULL AS THIRD_PARTY_ALLOWED_AMOUNT,
NULL AS OIC_PAID_AMOUNT,
NULL AS OIC_ALLOWED_AMOUNT,
NULL AS HRA_APPLIED_AMT,
NULL AS HIA_APPLIED_AMT,
   CASE
        WHEN (MEMBER_PAY_NOT_COVERED_REASONS.MEMBER_PAY_IND = 'Y' OR DEDUCTIBLE_AMOUNT > 0 OR COPAY_AMT_01 > 0 OR COINSURANCE_AMOUNT > 0)
            THEN TRUE
        ELSE FALSE
    END 
AS MEMBER_PAY_FLAG,

UTIL.FXN_ARRAY_HASH([LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID, LKP_CLAIM_MEMBER_SKYGEN.TPA_ID, LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID, LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME, DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR, DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_NBR, DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR, CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY,
UTIL.FXN_ARRAY_HASH([
    ALLOWED_AMOUNT
    ,CHARGE_AMOUNT
    ,CLAIM_AMT_01
    ,CLAIM_AMT_01_DESC
    ,CLAIM_AMT_02
    ,CLAIM_AMT_02_DESC
    ,COPAY_AMT_01
    ,COPAY_AMT_02
    ,COPAY_AMT_03
    ,DEDUCTIBLE_AMOUNT
    ,CASE
        WHEN (MEMBER_PAY_NOT_COVERED_REASONS.MEMBER_PAY_IND = 'Y' OR DEDUCTIBLE_AMOUNT > 0 OR COPAY_AMT_01 > 0 OR COINSURANCE_AMOUNT > 0) AND DWSKYGEN_CLAIM_DETAIL.PROCEDURE_CODE BETWEEN 'D8000' AND 'D8999' THEN ALLOWED_AMOUNT
        WHEN (MEMBER_PAY_NOT_COVERED_REASONS.MEMBER_PAY_IND = 'Y' AND DEDUCTIBLE_AMOUNT = 0 AND COPAY_AMT_01 = 0 AND COINSURANCE_AMOUNT = 0) AND DWSKYGEN_CLAIM_DETAIL.PROCEDURE_CODE NOT BETWEEN 'D8000' AND 'D8999' THEN (BILLED_AMOUNT - PAID_AMOUNT)
        ELSE NOT_COVERED_AMOUNT
    END 
    ,PAID_AMOUNT
    ,PAID_GROSS_AMOUNT
    ,PAY_FOR_PERFORMANCE_AMOUNT
    ,WITHHOLD_AMOUNT
    ,COINSURANCE_AMOUNT
    ,CODE_REVIEW_ORIGINAL_BILLING_AMOUNT
    ,CODE_REVIEW_ORIGINAL_NET_AMOUNT
    ,APPROVED_AMT
    ,INTEREST_DISCOUNT_AMOUNT
    ,THIRD_PARTY_PAID_AMOUNT
    ,THIRD_PARTY_ALLOWED_AMOUNT
    ,OIC_PAID_AMOUNT
    ,OIC_ALLOWED_AMOUNT
    ,HRA_APPLIED_AMT
    ,HIA_APPLIED_AMT
    ,MEMBER_PAY_FLAG
]) AS HASH_DIFF
FROM RAWDATA.DWSKYGEN_CLAIM_DETAIL
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
    LEFT OUTER JOIN --join out the the not covered reason to find out if ANY have a member_pay_flag of true to set accordingly
                (
                SELECT DISTINCT
                DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.CLAIM_NBR
                ,DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.CLAIM_LINE_NBR
                ,DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.CLAIM_LINE_SEQ_NBR
                ,DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.PROCEDURE_ADJ_CODE
                ,IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW.MEMBER_PAY_IND
                FROM RAWDATA.DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW
                    JOIN RAWDATA.DWSKYGEN_CLAIM_HEADER
                        ON (DWSKYGEN_CLAIM_HEADER.CLAIM_NBR = DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.CLAIM_NBR)
                    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
                        ON (DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.CLAIM_NBR = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
                    JOIN &{IDAP_LAKE}.NETWORK.LOB_PLAN_TYPE
                        ON (LOB_PLAN_TYPE.TPA_CLIENT_ID = LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
                        AND LOB_PLAN_TYPE.TPA_ID = LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
                        AND LOB_PLAN_TYPE.TPA_DIV_ID = LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
                        AND LOB_PLAN_TYPE.PLAN_TYPE = IFNULL(DWSKYGEN_CLAIM_HEADER.PLAN_TYPE_CODE, LKP_CLAIM_MEMBER_SKYGEN.PLAN_TYPE))
                    JOIN RAWDATA.IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW
                        ON (IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW.LOB = LOB_PLAN_TYPE.LINE_OF_BUSINESS_CODE
                        AND IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW.CODE = DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.DENIAL_CODE
                        AND IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW.CODE_TYPE = DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.TYPEDESCRIPTION
                        AND IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW.MEMBER_PAY_IND = 'Y'
                        )
                ) MEMBER_PAY_NOT_COVERED_REASONS
        ON (MEMBER_PAY_NOT_COVERED_REASONS.CLAIM_NBR = DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR
        AND MEMBER_PAY_NOT_COVERED_REASONS.CLAIM_LINE_NBR = DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_NBR
        AND MEMBER_PAY_NOT_COVERED_REASONS.CLAIM_LINE_SEQ_NBR = DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR
        AND MEMBER_PAY_NOT_COVERED_REASONS.PROCEDURE_ADJ_CODE = DWSKYGEN_CLAIM_DETAIL.PROCEDURE_ADJ_CODE)

UNION ALL

SELECT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID,
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME,
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO AS CLAIM_NBR,
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.ITEM_NO AS CLAIM_LINE_NBR,
UTIL.FXN_ARRAY_HASH([SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.BILLED_AMT]) AS CLAIM_LINE_SEQ_NBR,
'N/A' AS CLAIM_LINE_PROCEDURE_ADJ_CODE,
TO_NUMBER(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.ALLOW_AMT, 38, 4) AS ALLOWED_AMOUNT,
TO_NUMBER(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.BILLED_AMT, 38, 4) AS CHARGE_AMOUNT,
NULL AS CLAIM_AMT_01,
NULL AS CLAIM_AMT_01_DESC,
NULL AS CLAIM_AMT_02,
NULL AS CLAIM_AMT_02_DESC,
TO_NUMBER(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.COPAY_AMT, 38, 4) AS COPAY_AMT_01,
NULL AS COPAY_AMT_02,
NULL as COPAY_AMT_03,
NULL AS DEDUCTIBLE_AMOUNT,
CASE
    WHEN (MEMBER_PAY_NOT_COVERED_REASONS.MEMBER_PAY_IND = 'Y' 
            --OR DEDUCTIBLE_AMOUNT > 0 
            OR COPAY_AMT_01 > 0)
            --OR COINSURANCE_AMOUNT > 0)
            AND SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.PROC_CODE BETWEEN 'D8000' AND 'D8999'
        THEN SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.ALLOW_AMT
    WHEN (MEMBER_PAY_NOT_COVERED_REASONS.MEMBER_PAY_IND = 'Y'
            --AND DEDUCTIBLE_AMOUNT = 0
            AND COPAY_AMT_01 = 0)
            --AND COINSURANCE_AMOUNT = 0)
            AND SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.PROC_CODE NOT BETWEEN 'D8000' AND 'D8999'
        THEN (TO_NUMBER(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.BILLED_AMT, 38, 4) - TO_NUMBER(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.PAYMENT_AMT, 38, 4))
    ELSE NULL
END AS NOT_COVERED_AMOUNT,
TO_NUMBER(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.PAYMENT_AMT, 38, 4) AS PAID_AMOUNT,
NULL AS PAID_GROSS_AMOUNT,
NULL AS PAY_FOR_PERFORMANCE_AMOUNT,
NULL AS WITHHOLD_AMOUNT,
NULL AS COINSURANCE_AMOUNT,
NULL AS CODE_REVIEW_ORIGINAL_BILLING_AMOUNT,
NULL AS CODE_REVIEW_ORIGINAL_NET_AMOUNT,
TO_NUMBER(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.APPROV_AMT, 38, 4) AS APPROVED_AMT,
NULL AS INTEREST_DISCOUNT_AMOUNT,
TO_NUMBER(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.COB_AMT, 38, 4) AS THIRD_PARTY_PAID_AMOUNT,
NULL AS THIRD_PARTY_ALLOWED_AMOUNT,
NULL AS OIC_PAID_AMOUNT,
NULL AS OIC_ALLOWED_AMOUNT,
NULL AS HRA_APPLIED_AMT,
NULL AS HIA_APPLIED_AMT,
CASE
    WHEN (MEMBER_PAY_NOT_COVERED_REASONS.MEMBER_PAY_IND = 'Y'
        --OR DEDUCTIBLE_AMOUNT > 0
        OR COPAY_AMT_01 > 0)
        --OR COINSURANCE_AMOUNT > 0)
    THEN TRUE
    ELSE FALSE
END AS MEMBER_PAY_FLAG,

UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_NBR, CLAIM_LINE_NBR, CLAIM_LINE_SEQ_NBR, CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY,
UTIL.FXN_ARRAY_HASH([
    ALLOWED_AMOUNT
    ,CHARGE_AMOUNT
    ,CLAIM_AMT_01
    ,CLAIM_AMT_01_DESC
    ,CLAIM_AMT_02
    ,CLAIM_AMT_02_DESC
    ,COPAY_AMT_01
    ,COPAY_AMT_02
    ,COPAY_AMT_03
    ,DEDUCTIBLE_AMOUNT
    ,NOT_COVERED_AMOUNT
    ,PAID_AMOUNT
    ,PAID_GROSS_AMOUNT
    ,PAY_FOR_PERFORMANCE_AMOUNT
    ,WITHHOLD_AMOUNT
    ,COINSURANCE_AMOUNT
    ,CODE_REVIEW_ORIGINAL_BILLING_AMOUNT
    ,CODE_REVIEW_ORIGINAL_NET_AMOUNT
    ,APPROVED_AMT
    ,INTEREST_DISCOUNT_AMOUNT
    ,THIRD_PARTY_PAID_AMOUNT
    ,THIRD_PARTY_ALLOWED_AMOUNT
    ,OIC_PAID_AMOUNT
    ,OIC_ALLOWED_AMOUNT
    ,HRA_APPLIED_AMT
    ,HIA_APPLIED_AMT
    ,MEMBER_PAY_FLAG
]) AS HASH_DIFF

FROM RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)

    LEFT OUTER JOIN --join out the the not covered reason to find out if ANY have a member_pay_flag of true to set accordingly
                (
                SELECT
                SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO AS MP_CLAIM_NBR
                ,SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.ITEM_NO AS MP_CLAIM_LINE_NBR
                ,UTIL.FXN_ARRAY_HASH([SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.BILLED_AMT]) AS MP_CLAIM_LINE_SEQ_NBR
                ,'N/A' AS MP_CLAIM_LINE_PROCEDURE_ADJ_CODE
                ,IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW.MEMBER_PAY_IND
                FROM RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW
                    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
                        ON (LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR = SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO)
                    JOIN &{IDAP_LAKE}.NETWORK.LOB_PLAN_TYPE
                        ON (LOB_PLAN_TYPE.TPA_CLIENT_ID = LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
                        AND LOB_PLAN_TYPE.TPA_ID = LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
                        AND LOB_PLAN_TYPE.TPA_DIV_ID = LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
                        AND LOB_PLAN_TYPE.PLAN_TYPE = LKP_CLAIM_MEMBER_SKYGEN.PLAN_TYPE)
                    JOIN RAWDATA.IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW
                        ON (IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW.LOB = REPLACE(LOB_PLAN_TYPE.LINE_OF_BUSINESS_CODE, '-', '')
                        AND IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW.CODE = SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.EXCEPTION_CODE
                        AND IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW.CODE_TYPE = 'Reason'
                        AND IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW.MEMBER_PAY_IND = 'Y')
                ) MEMBER_PAY_NOT_COVERED_REASONS
        ON (MEMBER_PAY_NOT_COVERED_REASONS.MP_CLAIM_NBR = SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO
        AND MEMBER_PAY_NOT_COVERED_REASONS.MP_CLAIM_LINE_NBR = SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.ITEM_NO
        AND MEMBER_PAY_NOT_COVERED_REASONS.MP_CLAIM_LINE_SEQ_NBR = UTIL.FXN_ARRAY_HASH([SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.BILLED_AMT])
        AND MEMBER_PAY_NOT_COVERED_REASONS.MP_CLAIM_LINE_PROCEDURE_ADJ_CODE = 'N/A')

WHERE SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO NOT IN (SELECT CLAIM_NBR FROM RAWDATA.DWSKYGEN_CLAIM_HEADER) --Exclude claims in dwskygen, they supersede
;

