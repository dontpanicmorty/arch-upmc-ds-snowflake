CREATE OR REPLACE VIEW STAGEDATA.HUB_MEMBER_MC400Dnt_SELECT_VW
COMMENT = 'Source view for MC400Dnt data into HUB_MEMBER'
AS
SELECT
TO_VARCHAR(MC400_DWDNV_MEMBERS.MC400_RRN) AS SOURCE_KEY,
'000001' AS TPA_CLIENT_ID,
'000001' AS TPA_ID,
'0001' as TPA_DIV_ID,
'MC400Dnt' AS DATA_SOURCE_NAME,
TRIM(MC400_DWDNV_MEMBERS.MemberNbr) AS MEMBER_NBR,
UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEMBER_NBR]) as HUB_MEMBER_HKEY
FROM RAWDATA.MC400_DWDNV_MEMBERS
WHERE MC400_DWDNV_MEMBERS.MemberNbr <> '99999999901'--this is a junk catch all member number
;