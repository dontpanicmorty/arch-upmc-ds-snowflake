CREATE OR REPLACE VIEW STAGEDATA.HUB_PLAN_MC400UPM_SELECT_VW
COMMENT = 'This is a HUB View containing Plan data'
AS
SELECT
RowId AS SOURCE_KEY,
TpaClient AS TPA_CLIENT_ID,
TpaIdOfClient AS TPA_ID,
TpaDivision AS TPA_DIV_ID,
'MC400Upm' AS DATA_SOURCE_NAME,
PlanCode AS PLAN_CODE,
UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PLAN_CODE]) AS HUB_PLAN_HKEY
FROM RAWDATA.MC400_DWOAO_PLANMASTER
;
