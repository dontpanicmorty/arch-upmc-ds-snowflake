CREATE OR REPLACE VIEW STAGEDATA.SAT_PROVIDER_IDENTIFIER_CACTUS_SELECT_VW
COMMENT = 'This is a SAT View containing Provider Identifier data'
AS
(SELECT DISTINCT
'000001' AS TPA_CLIENT_ID,
'000001' AS TPA_ID,
'0001' AS TPA_DIV_ID,
'Cactus' AS DATA_SOURCE_NAME,
RTRIM(CACTUS_PROVIDERS.ID) AS PROVIDER_ID,
    TRIM(CACTUS_REFTABLE.DESCRIPTION) AS IDENTIFIER_NAME,
    CASE 
        WHEN RTRIM(CACTUS_PROVIDERLICENSES.LICENSENUMBER) = '' THEN NULL
        ELSE RTRIM(CACTUS_PROVIDERLICENSES.LICENSENUMBER) 
    END AS IDENTIFIER_NBR,
    'N/A' AS IDENTIFIER_SUBTYPE,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY, 
    UTIL.FXN_ARRAY_HASH([IDENTIFIER_NAME, IDENTIFIER_NBR, IDENTIFIER_SUBTYPE]) AS HASH_DIFF
	FROM RAWDATA.CACTUS_PROVIDERS
INNER JOIN RAWDATA.CACTUS_PROVIDERLICENSES
ON CACTUS_PROVIDERS.PROVIDER_K = CACTUS_PROVIDERLICENSES.PROVIDER_K
INNER JOIN RAWDATA.CACTUS_REFTABLE
ON CACTUS_PROVIDERLICENSES.LICENSE_RTK = CACTUS_REFTABLE.REFTABLE_K
INNER JOIN (
    SELECT DISTINCT PROVIDER_K
    FROM RAWDATA.CACTUS_ENTITYASSIGNMENTS
    WHERE RECORDTYPE = 'E'
    ) AS EA
    ON CACTUS_PROVIDERS.PROVIDER_K = EA.PROVIDER_K
LEFT JOIN (
SELECT ID, COUNT(*) AS CNT FROM(
SELECT DISTINCT P.ID, P.PROVIDER_K
FROM RAWDATA.CACTUS_PROVIDERS P
INNER JOIN RAWDATA.CACTUS_ENTITYASSIGNMENTS E
ON E.PROVIDER_K = P.PROVIDER_K) A
GROUP BY ID HAVING COUNT(*) > 1 ) DUPES
ON CACTUS_PROVIDERS.ID = DUPES.ID
WHERE CACTUS_PROVIDERS.STATUS_RTK NOT IN ('#0000K408T','#0000K408U','#0000K408S')
AND NOT (CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 AND (CACTUS_PROVIDERS.LASTNAME = '' AND CACTUS_PROVIDERS.FIRSTNAME =''))
AND NOT(CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 2 AND CACTUS_PROVIDERS.LONGNAME  ='')
AND NULLIF(CACTUS_PROVIDERS.ID, '') IS NOT NULL
AND DUPES.ID IS NULL
AND NULLIF(CACTUS_PROVIDERLICENSES.LICENSENUMBER, '') IS NOT NULL)

UNION

(SELECT DISTINCT
'000001' AS TPA_CLIENT_ID,
'000001' AS TPA_ID,
'0001' AS TPA_DIV_ID,
'Cactus' AS DATA_SOURCE_NAME,
RTRIM(CACTUS_PROVIDERS.ID) AS PROVIDER_ID,
    'National Provider Identifier' AS IDENTIFIER_NAME,
    CASE 
        WHEN RTRIM(CACTUS_PROVIDERS.NPI) = '' THEN NULL
        ELSE RTRIM(CACTUS_PROVIDERS.NPI) 
    END AS IDENTIFIER_NBR,
    CASE 
        WHEN CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 AND CACTUS_PROVIDERS.NPI <> '' THEN 'Type 1'	
        WHEN CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 2 AND CACTUS_PROVIDERS.NPI <> '' THEN 'Type 2' 
        ELSE 'N/A' 
    END AS IDENTIFIER_SUBTYPE,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY, 
    UTIL.FXN_ARRAY_HASH([IDENTIFIER_NAME, IDENTIFIER_NBR, IDENTIFIER_SUBTYPE]) AS HASH_DIFF
FROM RAWDATA.CACTUS_PROVIDERS
INNER JOIN (
    SELECT DISTINCT PROVIDER_K
    FROM RAWDATA.CACTUS_ENTITYASSIGNMENTS
    WHERE RECORDTYPE = 'E'
    ) AS EA
    ON CACTUS_PROVIDERS.PROVIDER_K = EA.PROVIDER_K
LEFT JOIN (
SELECT ID, COUNT(*) AS CNT FROM(
SELECT DISTINCT P.ID, P.PROVIDER_K
FROM RAWDATA.CACTUS_PROVIDERS P
INNER JOIN RAWDATA.CACTUS_ENTITYASSIGNMENTS E
ON E.PROVIDER_K = P.PROVIDER_K) A
GROUP BY ID HAVING COUNT(*) > 1 ) DUPES
ON CACTUS_PROVIDERS.ID = DUPES.ID
WHERE CACTUS_PROVIDERS.STATUS_RTK NOT IN ('#0000K408T','#0000K408U','#0000K408S')
AND NOT (CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 AND (CACTUS_PROVIDERS.LASTNAME = '' AND CACTUS_PROVIDERS.FIRSTNAME =''))
AND NOT(CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 2 AND CACTUS_PROVIDERS.LONGNAME  ='')
AND NULLIF(CACTUS_PROVIDERS.ID, '') IS NOT NULL
AND DUPES.ID IS NULL
AND NULLIF(CACTUS_PROVIDERS.NPI, '') IS  NOT NULL)
;