CREATE OR REPLACE VIEW STAGEDATA.REF_CLAIM_PROCEDURE_MODIFIER_SKYGEN_SELECT_VW
COMMENT = 'This is a REF View containing Claim Procedure Modifier data'
AS

SELECT DISTINCT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
,LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME
,DWSKYGEN_CLAIM_DETAIL.PROCEDURE_MODIFIER_01 as CODE
,IFNULL(DimSubcode_vw.SubCodeDescription,'Description Not Found') as CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CODE]) AS CLAIM_PROCEDURE_MODIFIER_HKEY
FROM RAWDATA.DWSKYGEN_CLAIM_DETAIL
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR = DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR)
    LEFT OUTER JOIN &{DWSKYGEN}.DBO.DimTooth_vw
        ON (DimTooth_vw.ToothId = DWSKYGEN_CLAIM_DETAIL.PROCEDURE_MODIFIER_01
        AND DimTooth_vw.RecordIsCurrent = true)
    LEFT OUTER JOIN &{DWSKYGEN}.DBO.DimSubcode_vw
        ON (DimSubcode_vw.SubCode = DimTooth_vw.SubCode
        and DimSubcode_vw.RecordIsCurrent = true)
WHERE DWSKYGEN_CLAIM_DETAIL.PROCEDURE_MODIFIER_01 IS NOT NULL
;

!set variable_substitution=false;