CREATE OR REPLACE VIEW STAGEDATA.HUB_OFFICE_SKYGEN_SELECT_VW
COMMENT = 'This is a HUB View containing Skygen office data'
AS
SELECT DISTINCT 
    'N/A' AS SOURCE_KEY,
    TPA_CLIENT_ID,
    TPA_ID,
    TPA_DIV_ID,
    'Skygen' AS DATA_SOURCE_NAME,
    OFFICE_ID,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, OFFICE_ID]) AS HUB_OFFICE_HKEY
FROM RAWDATA.DWSKYGEN_PROVIDER_OFFICE_SELECT_VW;