CREATE OR REPLACE VIEW STAGEDATA.REF_CLAIM_PROCESSING_REASON_NVA_SELECT_VW
AS
 SELECT DISTINCT
     LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID
    ,LKP_CLAIM_MEMBER_NVA.TPA_ID
    ,LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID
    ,LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME
    ,IDAPLAKE_REFERENCEDATA_NVA_PROCESSING_REASON_CODES_VW.CLAIM_PROCESSING_REASON_TYPE
    ,CASE
        WHEN NVA_PAID_CLAIM_EXTRACTS_VW."ReasonSuf1" IS NOT NULL THEN CONCAT(NVA_PAID_CLAIM_EXTRACTS_VW."ReasonCd1", '_', NVA_PAID_CLAIM_EXTRACTS_VW."ReasonSuf1")
        ELSE NVA_PAID_CLAIM_EXTRACTS_VW."ReasonCd1"
    END AS CODE
    ,IDAPLAKE_REFERENCEDATA_NVA_PROCESSING_REASON_CODES_VW.CODE_DESC
    ,NULL AS CODE_DESC_LONG
    ,NULL AS CODE_SPANISH_DESC
    ,NULL AS HIPAA_277_CODE
    ,NULL AS HIPAA_835_CODE 
    ,UTIL.FXN_ARRAY_HASH(
        [TPA_CLIENT_ID
        ,TPA_ID
        ,TPA_DIV_ID
        ,DATA_SOURCE_NAME
        ,CLAIM_PROCESSING_REASON_TYPE
        ,CASE
            WHEN NVA_PAID_CLAIM_EXTRACTS_VW."ReasonSuf1" IS NOT NULL THEN CONCAT(NVA_PAID_CLAIM_EXTRACTS_VW."ReasonCd1", '_', NVA_PAID_CLAIM_EXTRACTS_VW."ReasonSuf1")
            ELSE NVA_PAID_CLAIM_EXTRACTS_VW."ReasonCd1"
        END
        ]) AS CLAIM_PROCESSING_REASON_HKEY

FROM RAWDATA.NVA_PAID_CLAIM_EXTRACTS_VW
JOIN STAGEDATA.LKP_CLAIM_MEMBER_NVA
        ON (LKP_CLAIM_MEMBER_NVA.CLAIM_NBR = NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo")
    JOIN RAWDATA.IDAPLAKE_REFERENCEDATA_NVA_PROCESSING_REASON_CODES_VW
        ON (IDAPLAKE_REFERENCEDATA_NVA_PROCESSING_REASON_CODES_VW.CODE = CASE
            WHEN NVA_PAID_CLAIM_EXTRACTS_VW."ReasonSuf1" IS NOT NULL THEN CONCAT(NVA_PAID_CLAIM_EXTRACTS_VW."ReasonCd1", '_', NVA_PAID_CLAIM_EXTRACTS_VW."ReasonSuf1")
            ELSE NVA_PAID_CLAIM_EXTRACTS_VW."ReasonCd1"
        END )
WHERE NVA_PAID_CLAIM_EXTRACTS_VW."ReasonCd1" IS NOT NULL

UNION

SELECT DISTINCT
     LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID
    ,LKP_CLAIM_MEMBER_NVA.TPA_ID
    ,LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID
    ,LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME
    ,IDAPLAKE_REFERENCEDATA_NVA_PROCESSING_REASON_CODES_VW.CLAIM_PROCESSING_REASON_TYPE
    ,CASE
        WHEN NVA_PAID_CLAIM_EXTRACTS_VW."ReasonSuf2" IS NOT NULL THEN CONCAT(NVA_PAID_CLAIM_EXTRACTS_VW."ReasonCd2", '_', NVA_PAID_CLAIM_EXTRACTS_VW."ReasonSuf2")
        ELSE NVA_PAID_CLAIM_EXTRACTS_VW."ReasonCd2"
    END AS CODE
    ,IDAPLAKE_REFERENCEDATA_NVA_PROCESSING_REASON_CODES_VW.CODE_DESC
    ,NULL AS CODE_DESC_LONG
    ,NULL AS CODE_SPANISH_DESC
    ,NULL AS HIPAA_277_CODE
    ,NULL AS HIPAA_835_CODE 
    ,UTIL.FXN_ARRAY_HASH(
        [TPA_CLIENT_ID
        ,TPA_ID
        ,TPA_DIV_ID
        ,DATA_SOURCE_NAME
        ,CLAIM_PROCESSING_REASON_TYPE
        ,CASE
            WHEN NVA_PAID_CLAIM_EXTRACTS_VW."ReasonSuf2" IS NOT NULL THEN CONCAT(NVA_PAID_CLAIM_EXTRACTS_VW."ReasonCd2", '_', NVA_PAID_CLAIM_EXTRACTS_VW."ReasonSuf2")
            ELSE NVA_PAID_CLAIM_EXTRACTS_VW."ReasonCd2"
        END
        ]) AS CLAIM_PROCESSING_REASON_HKEY

FROM RAWDATA.NVA_PAID_CLAIM_EXTRACTS_VW
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_NVA
        ON (LKP_CLAIM_MEMBER_NVA.CLAIM_NBR = NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo")
    JOIN RAWDATA.IDAPLAKE_REFERENCEDATA_NVA_PROCESSING_REASON_CODES_VW
        ON (IDAPLAKE_REFERENCEDATA_NVA_PROCESSING_REASON_CODES_VW.CODE = CASE
            WHEN NVA_PAID_CLAIM_EXTRACTS_VW."ReasonSuf2" IS NOT NULL THEN CONCAT(NVA_PAID_CLAIM_EXTRACTS_VW."ReasonCd2", '_', NVA_PAID_CLAIM_EXTRACTS_VW."ReasonSuf2")
            ELSE NVA_PAID_CLAIM_EXTRACTS_VW."ReasonCd2"
        END )
WHERE NVA_PAID_CLAIM_EXTRACTS_VW."ReasonCd2" IS NOT NULL
;