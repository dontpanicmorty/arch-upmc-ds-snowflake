!set variable_substitution=true;

CREATE OR REPLACE VIEW STAGEDATA.SAT_MEDICAL_GROUP_ATTRIBUTE_CACTUS_SELECT_VW
COMMENT = 'This SAT table has medical group attribute records from IDAP provider tables'
AS
WITH IDAP_PROVIDERS AS (
    SELECT DISTINCT
        PRV414.IRSSSN,
        'Y' AS PA_MEDICAID_IND_CTE
    FROM
        &{IDAP_LAKE}.PROVIDER.PRV430 AS PRV430
    LEFT JOIN
        &{IDAP_LAKE}.PROVIDER.PRV414_VW AS PRV414
        ON PRV430.SERVICELOCATION = PRV414.SERVICELOC
        AND PRV430.PROMISEPROVIDERNUMBER = PRV414.PROMISEPROV
    WHERE
        PRV414.ENDDATE = '22991231' 
        AND PRV414.SPECCODEEND = '22991231' 
        AND PRV414.STATUSCODE = 'A'
        AND PRV414.IRSSSNIND = 'I'
)
, DUPLICATE_GROUPS AS (
    SELECT ID
    FROM RAWDATA.CACTUS_GROUPS
    GROUP BY ID
    HAVING COUNT(*) > 1
)
SELECT DISTINCT
    '000001' AS TPA_CLIENT_ID,
    '000001' AS TPA_ID,
    '0001' AS TPA_DIV_ID,
    'Cactus' AS DATA_SOURCE_NAME,
    TRIM(GRP.ID) AS MEDICAL_GROUP_ID,
    -- May need to translate some PRIMARY_PHO_NAMEs to match the PHO values later on
    NULLIF(TRIM(REF.DESCRIPTION), 'No Value Specified') AS PRIMARY_PHO_NAME,
    NULL AS PRIMARY_PHO_TERMINATION_DATE,
    NULL AS SECONDARY_PHO_NAME,
    NULL AS SECONDARY_PHO_TERMINATION_DATE,
    NULL AS TERTIARY_PHO_NAME,
    NULL AS TERTIARY_PHO_TERMINATION_DATE,
    NVL(IDAP_PROVIDERS.PA_MEDICAID_IND_CTE, 'N') AS PA_MEDICAID_IND,
    NULL AS PP_ACA_ENHANCED_PAY_IND,
    NULL AS MALPRACTICE_COVERAGE_IND,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY,
    UTIL.FXN_ARRAY_HASH([PRIMARY_PHO_NAME, PRIMARY_PHO_TERMINATION_DATE, SECONDARY_PHO_NAME, SECONDARY_PHO_TERMINATION_DATE, TERTIARY_PHO_NAME, TERTIARY_PHO_TERMINATION_DATE, PA_MEDICAID_IND, PP_ACA_ENHANCED_PAY_IND, MALPRACTICE_COVERAGE_IND]) AS HASH_DIFF
FROM
    RAWDATA.CACTUS_GROUPS AS GRP
INNER JOIN
    RAWDATA.CACTUS_GROUPADDRESS AS GRP_ADR
    ON GRP.GROUP_K = GRP_ADR.GROUP_K
LEFT JOIN
    DUPLICATE_GROUPS AS DUP
    ON GRP.ID = DUP.ID
LEFT JOIN
    IDAP_PROVIDERS
    ON GRP_ADR.TAXIDNUMBER = IDAP_PROVIDERS.IRSSSN
INNER JOIN
    RAWDATA.CACTUS_REFTABLE AS REF
    ON GRP.USERDEF_RTK2 = REF.REFTABLE_K
WHERE
    NULLIF(TRIM(GRP.ID), '') IS NOT NULL
    AND NULLIF(TRIM(GRP_ADR.GROUP_K), '') IS NOT NULL
    AND NULLIF(TRIM(GRP_ADR.TAXIDNUMBER), '') IS NOT NULL
    AND DUP.ID IS NULL
;

!set variable_substitution=false;