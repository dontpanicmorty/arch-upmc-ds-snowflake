CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_HEADER_MC400UPM_SELECT_VW
COMMENT='This SAT table contains Claim Header data'
AS

WITH 
appermanentPayment_CTE
AS
(
    --TPA might need added to this is some way, but it should be ok for now
    SELECT --mc400 logic because the data is junk!
    tableRowId, IFF(fileType = 'H','I',fileType) AS fileType, checkNbr, checkDate, postDate, status
    FROM RAWDATA.MC400_DWOAO_APPERMANENTPAYMENT
    QUALIFY DENSE_RANK() OVER(PARTITION BY tpaRowId, tableRowId, fileType ORDER BY sysGenId) = 1
)

,apWork_CTE
AS
(
    SELECT  --mc400 logic because the data is junk!
    tpaRowId, filetype, IFF(fileType = 'I', hinsdprowid, hencdprowid) as tableRowId, status, postDate
    FROM RAWDATA.MC400_DWOAO_APWORK
    QUALIFY DENSE_RANK() OVER(PARTITION BY tpaRowId, fileType, tableRowId ORDER BY sysGenId, ChgOrig) = 1
)

,PAID_STATUS_FOR_CMS_CTE AS (

SELECT      MC400_DWOAO_CLAIMSDETAIL.TPACLIENT,
            MC400_DWOAO_CLAIMSDETAIL.TPAIDOFCLIENT,
            MC400_DWOAO_CLAIMSDETAIL.TPADIVISION,
            MC400_DWOAO_CLAIMSDETAIL.CLAIMNBR,
            SUM(MC400_DWOAO_CLAIMSDETAIL.NetAmt - MC400_DWOAO_CLAIMSDETAIL.PayForPerformance) AS PAID_AMT,
            SUM(MC400_DWOAO_CLAIMSDETAIL.BilledAmt) AS CHARGE_AMT,
            SUM(MC400_DWOAO_CLAIMSDETAIL.NotCoveredAmt) AS NOT_COVERED_AMT,
            SUM(MC400_DWOAO_CLAIMSDETAIL.DeductAmt) AS DEDUCTIBLE_AMT,
            SUM(MC400_DWOAO_CLAIMSDETAIL.CopayAmt) AS COPAY_AMT,
            SUM(MC400_DWOAO_CLAIMSDETAIL.CoInsuranceAmt) AS COINSURANCE_AMT,
            SUM(MC400_DWOAO_CLAIMSDETAIL.AllowedAmt) AS BENEFIT_ALLOW_AMT,
            SUM(MC400_DWOAO_CLAIMSDETAIL.CopayAmt + MC400_DWOAO_CLAIMSDETAIL.DeductAmt + MC400_DWOAO_CLAIMSDETAIL.CoInsuranceAmt) AS COST_SHARE_AMT

FROM RAWDATA.MC400_DWOAO_CLAIMSDETAIL
WHERE MC400_DWOAO_CLAIMSDETAIL.MEMBERNBR <> '99999999901' --EXCLUDE GENERIC DEFAULT MEMBER CLAIMS
GROUP BY TPACLIENT, TPAIDOFCLIENT, TPADIVISION, CLAIMNBR
)

SELECT
Claims.TpaClient AS TPA_CLIENT_ID
,Claims.TpaIdOfClient AS TPA_ID
,Claims.TpaDivision AS TPA_DIV_ID
,'MC400Upm' AS DATA_SOURCE_NAME
,Claims.ClaimNbr AS CLAIM_NBR
,TRY_TO_DATE(TO_VARCHAR(Claims.ClaimEntryDate),'YYYYMMDD') AS CLAIM_ENTRY_DATE
,LOB_PLAN_TYPE.LINE_OF_BUSINESS_CODE AS LINE_OF_BUSINESS_CODE
,Claims.PlanCode AS PLAN_CODE
,Claims.PlanType AS PLAN_TYPE_CODE
,IFF(TRIM(Claims.ParticipatingProvider) = '', NULL, TRIM(Claims.ParticipatingProvider)) AS BILLING_PROVIDER_PARTICIPATING_STATUS_CODE
,CASE (Claims.AdmitFlag)
    WHEN 'Y' THEN TRUE
    WHEN 'N' THEN FALSE
    ELSE NULL
END AS ADMITTED_FLAG
,TRY_TO_DATE(TO_VARCHAR(Claims.AdmitDate),'YYYYMMDD') AS ADMITTED_DATE
,IFF(Claims.AdmissionHour = 0, NULL, Claims.AdmissionHour) AS ADMITTED_HOUR
,IFF(TRIM(Claims.AdmissionSource) = '', NULL, TRIM(Claims.AdmissionSource)) AS ADMISSION_SOURCE_CODE
,IFF(TRIM(Claims.AdmissionType) = '', NULL, TRIM(Claims.AdmissionType)) AS ADMISSION_TYPE_CODE
,TRY_TO_DATE(TO_VARCHAR(Claims.DischargeDate),'YYYYMMDD') AS DISCHARGE_DATE
,IFF(Claims.DischargeHour = 0, NULL, Claims.DischargeHour) AS DISCHARGE_HOUR
,IFF(TRIM(Claims.DischargeStatus) = '', NULL, TRIM(Claims.DischargeStatus)) AS DISCHARGE_STATUS_CODE
,IFF(TRIM(Claims.BillType) = '', NULL, Claims.BillType) AS BILLING_TYPE_CODE
,Claims.CalculatedBilledTotal AS CALCULATED_BILL_TOTAL_AMT
,'medical' AS CARE_TYPE_NAME
,CONCAT(Claims.GroupNbr, Claims.SubGroup) AS DIVISION_NUMBER
,IFF(TRIM(Claims.UserField) = '', NULL, TRIM(Claims.UserField)) AS ELECTRONIC_CLAIM_TYPE_CODE
,IFF(TRIM(Claims.EncounterReason) = '', NULL, TRIM(Claims.EncounterReason)) ENCOUNTER_REASON_CODE
,Claims.FormNbr AS FORM_NUMBER
,NULL AS IS_PROCESSING_COMPLETE --n/a this is a MarkLogic specific field, needs removed
,MicroFilmDocuments.DocumnetId AS MICROFILM_NBR
,Claims.PlaceOfService AS PLACE_OF_SERVICE_CODE
,IFF(TRIM(Claims.PricingZipSource) = '', NULL, TRIM(Claims.PricingZipSource)) AS PRICING_ZIP_SOURCE
,IFF(TRIM(Claims.ProviderAcctNbr) = '', NULL, TRIM(Claims.ProviderAcctNbr)) AS PATIENT_ACCOUNT_NUMBER
,CASE WHEN (IFNULL(CLAIM_DETAIL_SUM_AMT.SUM_NET_AMT,0) > 200000)
    THEN 'Y'
    ELSE 'N'
END AS SHOCK_CLAIM_IND
,Claims.LastUpdated AS SOURCE_LAST_UPDATED_DATETIME
,FALSE AS IS_PREDETERMINATION_CLAIM_FLAG  --Might need to revist
,NULL AS ORIGINAL_CLAIM_ID
,NULL AS MULTISOURCE_CLAIM_IND -- Might need updated in conjunction withy Skygen resubmits
,Claims.ClaimType AS CLAIM_TYPE_CODE --(E)ncounter or (I)npatient
,IFF(TRIM(Claims.IPACode) = '', NULL, TRIM(Claims.IPACode)) AS IPA_CODE
,Claims.VendorNbr AS BILLING_PROVIDER_VENDOR_NBR
,IFF(TRIM(Claims.PaidPresZipcode) = '', NULL, TRIM(Claims.PaidPresZipcode)) SERVICE_ZIP_CODE
,IFF(TRIM(Claims.Blk32NPI) = '', NULL, TRIM(Claims.Blk32NPI)) AS EDI_837_FACILITY_NPI_NBR
,IFF(TRIM(Claims.Blk32Facility) = '', NULL, TRIM(Claims.Blk32Facility)) AS EDI_837_FACILITY_NAME
,IFF(TRIM(Claims.Blk32Tel) = '', NULL, TRIM(Claims.Blk32Tel)) AS EDI_837_FACILITY_TELEPHONE_NBR
,IFF(TRIM(Claims.Blk32Addr1) = '', NULL, TRIM(Claims.Blk32Addr1)) AS EDI_837_FACILITY_ADDRESS_LINE_1_TEXT
,IFF(TRIM(Claims.Blk32Addr2) = '', NULL, TRIM(Claims.blk32addr2)) AS EDI_837_FACILITY_ADDRESS_LINE_2_TEXT
,IFF(TRIM(Claims.Blk32City) = '', NULL, TRIM(Claims.Blk32City)) AS EDI_837_FACILITY_CITY_NAME
,IFF(TRIM(Claims.Blk32State) = '', NULL, TRIM(Claims.Blk32State)) AS EDI_837_FACILITY_STATE_ABBREV_NAME
,IFF(TRIM(Claims.Blk32ZIP) = '', NULL, TRIM(Claims.Blk32ZIP)) AS EDI_837_FACILITY_ZIP_CODE_NBR
,IFF(TRIM(Claims.Blk32BlockB) = '', NULL, TRIM(Claims.Blk32BlockB)) AS EDI_837_FACILITY_OTHER_ID
,IFF(TRIM(Claims.SeverityOfIllness) = '', NULL, TRIM(Claims.SeverityOfIllness)) AS SEVERITY_OF_ILLNESS
,IFF(TRIM(Claims.DrgCode) = '', NULL, TRIM(Claims.DrgCode)) AS DIAGNOSIS_RELATED_GROUP_CODE
,IFF(TRIM(Claims.ProviderSpecialty) = '', NULL, TRIM(Claims.ProviderSpecialty)) AS PROVIDER_SPECIALTY
,CASE
    WHEN PAID_STATUS_FOR_CMS_CTE.PAID_AMT + PAID_STATUS_FOR_CMS_CTE.COST_SHARE_AMT > 0 THEN 'PAID'
    WHEN PAID_STATUS_FOR_CMS_CTE.PAID_AMT + PAID_STATUS_FOR_CMS_CTE.COST_SHARE_AMT = 0  AND PAID_STATUS_FOR_CMS_CTE.NOT_COVERED_AMT > 0 THEN 'DENIED'
    WHEN PAID_STATUS_FOR_CMS_CTE.PAID_AMT + PAID_STATUS_FOR_CMS_CTE.NOT_COVERED_AMT + PAID_STATUS_FOR_CMS_CTE.COST_SHARE_AMT + PAID_STATUS_FOR_CMS_CTE.BENEFIT_ALLOW_AMT = 0 AND PAID_STATUS_FOR_CMS_CTE.CHARGE_AMT > 0 THEN 'DENIED'
    WHEN PAID_STATUS_FOR_CMS_CTE.PAID_AMT + PAID_STATUS_FOR_CMS_CTE.NOT_COVERED_AMT + PAID_STATUS_FOR_CMS_CTE.COST_SHARE_AMT + PAID_STATUS_FOR_CMS_CTE.BENEFIT_ALLOW_AMT + PAID_STATUS_FOR_CMS_CTE.CHARGE_AMT < 0 THEN 'REVERSED'
    WHEN PAID_STATUS_FOR_CMS_CTE.PAID_AMT + PAID_STATUS_FOR_CMS_CTE.NOT_COVERED_AMT + PAID_STATUS_FOR_CMS_CTE.COST_SHARE_AMT + PAID_STATUS_FOR_CMS_CTE.BENEFIT_ALLOW_AMT + PAID_STATUS_FOR_CMS_CTE.CHARGE_AMT = 0 THEN 'REVERSED'
    WHEN PAID_STATUS_FOR_CMS_CTE.PAID_AMT + PAID_STATUS_FOR_CMS_CTE.COST_SHARE_AMT + PAID_STATUS_FOR_CMS_CTE.NOT_COVERED_AMT = 0 AND PAID_STATUS_FOR_CMS_CTE.BENEFIT_ALLOW_AMT > 0 THEN 'OIC'
    ELSE 'UNKNOWN'
END AS PAID_STATUS_FOR_CMS

,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_NBR]) AS HUB_CLAIM_HKEY
,UTIL.FXN_ARRAY_HASH([
    CLAIM_ENTRY_DATE
    ,LINE_OF_BUSINESS_CODE
    ,PLAN_CODE
    ,PLAN_TYPE_CODE
    ,BILLING_PROVIDER_PARTICIPATING_STATUS_CODE
    ,ADMITTED_FLAG
    ,ADMITTED_DATE
    ,ADMITTED_HOUR
    ,ADMISSION_SOURCE_CODE
    ,ADMISSION_TYPE_CODE
    ,DISCHARGE_DATE
    ,DISCHARGE_HOUR
    ,DISCHARGE_STATUS_CODE
    ,BILLING_TYPE_CODE
    ,CALCULATED_BILL_TOTAL_AMT
    ,CARE_TYPE_NAME
    ,DIVISION_NUMBER
    ,ELECTRONIC_CLAIM_TYPE_CODE
    ,ENCOUNTER_REASON_CODE
    ,FORM_NUMBER
    ,IS_PROCESSING_COMPLETE
    ,MICROFILM_NBR
    ,PLACE_OF_SERVICE_CODE
    ,PRICING_ZIP_SOURCE
    ,PATIENT_ACCOUNT_NUMBER
    ,SHOCK_CLAIM_IND
    ,SOURCE_LAST_UPDATED_DATETIME
    ,IS_PREDETERMINATION_CLAIM_FLAG
    ,ORIGINAL_CLAIM_ID
    ,MULTISOURCE_CLAIM_IND
    ,CLAIM_TYPE_CODE
    ,IPA_CODE
    ,BILLING_PROVIDER_VENDOR_NBR
    ,SERVICE_ZIP_CODE
    ,EDI_837_FACILITY_NPI_NBR
    ,EDI_837_FACILITY_NAME
    ,EDI_837_FACILITY_TELEPHONE_NBR
    ,EDI_837_FACILITY_ADDRESS_LINE_1_TEXT
    ,EDI_837_FACILITY_ADDRESS_LINE_2_TEXT
    ,EDI_837_FACILITY_CITY_NAME
    ,EDI_837_FACILITY_STATE_ABBREV_NAME
    ,EDI_837_FACILITY_ZIP_CODE_NBR
    ,EDI_837_FACILITY_OTHER_ID
    ,SEVERITY_OF_ILLNESS
    ,DIAGNOSIS_RELATED_GROUP_CODE
    ,PROVIDER_SPECIALTY
    ,PAID_STATUS_FOR_CMS
]) AS HASH_DIFF

FROM RAWDATA.MC400_DWOAO_CLAIMS Claims
    LEFT OUTER JOIN
        (
            SELECT TpaClient, TpaIdOfClient, TpaDivision, ClaimNbr, SUM(NetAmt) AS SUM_NET_AMT
            FROM RAWDATA.MC400_DWOAO_CLAIMSDETAIL
            GROUP BY TpaClient, TpaIdOfClient, TpaDivision, ClaimNbr
        ) CLAIM_DETAIL_SUM_AMT
        ON (CLAIM_DETAIL_SUM_AMT.TpaClient = Claims.TpaClient
        AND CLAIM_DETAIL_SUM_AMT.TpaIdOfClient = Claims.TpaIdOfClient
        AND CLAIM_DETAIL_SUM_AMT.TpaDivision = Claims.TpaDivision
        AND CLAIM_DETAIL_SUM_AMT.ClaimNbr = Claims.ClaimNbr)

    LEFT OUTER JOIN RAWDATA.MC400_DWOAO_MICROFILMDOCUMENTS MicroFilmDocuments
        ON (MicroFilmDocuments.TpaClient = Claims.TpaClient
        AND MicroFilmDocuments.TpaIdOfClient = Claims.TpaIdOfClient
        AND MicroFilmDocuments.TpaDivision = Claims.TpaDivision
        AND MicroFilmDocuments.FormNumber = Claims.FormNbr
        AND MicroFilmDocuments.PrimaryDateOfService = Claims.AdmitDate
        AND MicroFilmDocuments.APSourceFileType = Claims.ClaimType
        AND MicroFilmDocuments.DocumnetId <> ''
        AND MicroFilmDocuments.DeletedFlag = '1900-01-01 00:00:00.000')

    LEFT OUTER JOIN &{IDAP_LAKE}.NETWORK.LOB_PLAN_TYPE
        ON (LOB_PLAN_TYPE.TPA_CLIENT_ID = Claims.TPACLIENT
        AND LOB_PLAN_TYPE.TPA_ID = Claims.TPAIDOFCLIENT
        AND LOB_PLAN_TYPE.TPA_DIV_ID = Claims.TPADIVISION
        AND LOB_PLAN_TYPE.PLAN_TYPE = Claims.PlanType)
    
    LEFT OUTER JOIN PAID_STATUS_FOR_CMS_CTE
        ON (Claims.CLAIMNBR = PAID_STATUS_FOR_CMS_CTE.CLAIMNBR
        AND Claims.TPACLIENT = PAID_STATUS_FOR_CMS_CTE.TPACLIENT
        AND Claims.TPAIDOFCLIENT = PAID_STATUS_FOR_CMS_CTE.TPAIDOFCLIENT
        AND Claims.TPADIVISION = PAID_STATUS_FOR_CMS_CTE.TPADIVISION
        )

WHERE Claims.MemberNbr <> '99999999901' --Exclude Generic Default Member Claims
;

