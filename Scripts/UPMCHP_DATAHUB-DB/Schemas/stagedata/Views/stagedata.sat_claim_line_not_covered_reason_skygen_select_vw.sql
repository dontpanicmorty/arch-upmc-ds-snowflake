CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_LINE_NOT_COVERED_REASON_SKYGEN_SELECT_VW
COMMENT = 'This is a SAT View containing Claim Line Not Covered Reason data'
AS

SELECT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
,LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME
,DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.CLAIM_NBR
,DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.CLAIM_LINE_NBR
,DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.CLAIM_LINE_SEQ_NBR
,DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.PROCEDURE_ADJ_CODE
,DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.TYPEDESCRIPTION AS NOT_COVERED_REASON_TYPE
,TO_VARCHAR(DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.DENIAL_CODE) AS NOT_COVERED_REASON_CODE
,UTIL.FXN_ARRAY_HASH([NULL]) AS HASH_DIFF
,UTIL.FXN_ARRAY_HASH(
            [LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
            ,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
            ,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
            ,LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME
            ,DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.CLAIM_NBR
            ,DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.CLAIM_LINE_NBR
            ,DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.CLAIM_LINE_SEQ_NBR
            ,DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.PROCEDURE_ADJ_CODE
            ]) AS HUB_CLAIM_DETAIL_HKEY

FROM RAWDATA.DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.CLAIM_NBR = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
    JOIN RAWDATA.DWSKYGEN_CLAIM_DETAIL --make sure we only pull claims that are already filtered
        ON (DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR = DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.CLAIM_NBR
        AND DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_NBR = DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.CLAIM_LINE_NBR
        AND DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR = DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.CLAIM_LINE_SEQ_NBR
        AND DWSKYGEN_CLAIM_DETAIL.PROCEDURE_ADJ_CODE = DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.PROCEDURE_ADJ_CODE)

UNION ALL

SELECT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
,LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME
,SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO AS CLAIM_NBR
,SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.ITEM_NO AS CLAIM_LINE_NBR
,UTIL.FXN_ARRAY_HASH([SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.BILLED_AMT]) AS CLAIM_LINE_SEQ_NBR
,'N/A' AS PROCEDURE_ADJ_CODE
,'Reason' AS NOT_COVERED_REASON_TYPE
,REPLACE(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.EXCEPTION_CODE, '-', '') AS NOT_COVERED_REASON_CODE
,UTIL.FXN_ARRAY_HASH([NULL]) AS HASH_DIFF
,UTIL.FXN_ARRAY_HASH(
    [TPA_CLIENT_ID
    ,TPA_ID
    ,TPA_DIV_ID
    ,DATA_SOURCE_NAME
    ,CLAIM_NBR
    ,CLAIM_LINE_NBR
    ,CLAIM_LINE_SEQ_NBR
    ,PROCEDURE_ADJ_CODE
]) AS HUB_CLAIM_DETAIL_HKEY

FROM RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)    

WHERE SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.EXCEPTION_CODE IS NOT NULL
AND SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO NOT IN (SELECT CLAIM_NBR FROM RAWDATA.DWSKYGEN_CLAIM_HEADER) --Exclude claims in dwskygen, they supersede
;
