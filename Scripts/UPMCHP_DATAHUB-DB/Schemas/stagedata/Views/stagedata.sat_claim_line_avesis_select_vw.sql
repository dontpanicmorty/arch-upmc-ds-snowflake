CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_LINE_AVESIS_SELECT_VW
COMMENT = 'This is a SAT View containing Claim Line data'
AS
SELECT DISTINCT 
    LKP_CLAIM_MEMBER_AVESIS.TPA_CLIENT_ID,
	LKP_CLAIM_MEMBER_AVESIS.TPA_ID,
	LKP_CLAIM_MEMBER_AVESIS.TPA_DIV_ID,
	LKP_CLAIM_MEMBER_AVESIS.DATA_SOURCE_NAME,
    AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO AS CLAIM_NBR, 
    AVESIS_PAID_CLAIM_EXTRACTS.ITEM_NO AS CLAIM_LINE_NBR, 
    UTIL.FXN_ARRAY_HASH([SUBSCRIBER_ID,CHECK_NO,CLAIM_TYPE,ADJUDICATION_DT,SERVICE_DT,ANSI_CODE,EXCEPTION_CODE,ADJUSTMENT_CODE,PROC_CODE,QUANTITY,TOOTH_ID,PROV_LOC_ID,PRVD_ID,COUNTY_CODE,LOB_IND]) AS CLAIM_LINE_SEQ_NBR, 
    RANK() OVER (PARTITION BY CLAIM_NBR,CLAIM_LINE_NBR
	    ORDER BY CLAIM_NBR,CLAIM_LINE_NBR, AVESIS_PAID_CLAIM_EXTRACTS.FILE_ROW_NUMBER ASC)::VARCHAR AS CLAIM_LINE_PROCEDURE_ADJ_CODE,
    'E' AS CLAIM_TYPE_CODE, --(E)ncounter or (I)npatient 
    NULL AS CLAIM_RECEIVED_DATE, 
    AVESIS_PAID_CLAIM_EXTRACTS.PROC_CODE as PROCEDURE_CODE, 
    NULLIF(AVESIS_PAID_CLAIM_EXTRACTS.QUANTITY, '') AS PROCEDURE_QUANTITY, 
    TO_DATE(AVESIS_PAID_CLAIM_EXTRACTS.SERVICE_DT, 'YYYYMMDD') AS SERVICE_BEGIN_DATE, 
    NULL AS SERVICE_END_DATE, 
    NULL AS ADD_DATE, 
    NULL AS ACCOUNTS_PAYABLE_PAY_STATUS_CODE, 
    NULL AS ADJUDICATION_STATUS, 
    NULL AS AP_POSTING_DATE, 
    NULL AS BENEFIT_CATEGORY_CODE, 
    NULL AS BENEFIT_LEVEL_CODE, 
    NULL AS BUCKET_STATUS_FLAG, 
    NULL AS CHECK_DATE, 
    AVESIS_PAID_CLAIM_EXTRACTS.CHECK_NO AS CHECK_NUMBER, 
    NULL AS CLAIM_DAY_CNT, 
    NULL AS CLEAN_CLAIM_IND, 
    NULL AS COMPANY_CODE, 
    NULL AS DENIED_DAY_CNT, 
    ELIGIBILITYHISTORY.MISCSTATUSCODE AS ELIGIBILITY_MISC_STATUS_CODE, 
    NULL AS FORM_NUMBER, 
    NULL AS GL_DISTRIBUTION_CODE, 
    TRUE AS IS_PROCESSING_COMPLETE, 
    NULL AS KEY_TO_SOURCE_FILE, 
    'O' AS LOCATION_CODE, 
    '3' AS PAY_STATUS_CODE, 
    AVESIS_PAID_CLAIM_EXTRACTS.ADJUDICATION_DT AS PAYMENT_DATE, 
    NULL AS TOOTH_QUADRANT, 
    NULL AS REVENUE_CODE, 
    NULL AS SERVICE_CNT, 
    NULL AS SERVICE_REASON_CODE, 
    CASE
        WHEN AVESIS_PAID_CLAIM_EXTRACTS.PAYMENT_AMT <> 0 THEN 'P'
        WHEN AVESIS_PAID_CLAIM_EXTRACTS.PAYMENT_AMT = 0 THEN 'D'
        ELSE 'U'
    END AS SERVICE_STATUS_CODE, 
    CASE
        WHEN AVESIS_PAID_CLAIM_EXTRACTS.PAYMENT_AMT <> 0 THEN 'Paid'
        WHEN AVESIS_PAID_CLAIM_EXTRACTS.PAYMENT_AMT = 0 THEN 'Denied'
        ELSE 'Unknown'
    END AS SERVICE_STATUS_DESC, 
    CASE 
        WHEN POS IN ('IN','EC','AC','99','81','72','71','54','51','50','49','41','33','32','31','3','24','23','22','21','20','19','16','15','14','13','12','11','10','1','03','02','01') THEN 'P'
        ELSE 'U'
    END AS SERVICE_TYPE_CODE,  -- Need to circle back to fix this 
    CASE 
        WHEN AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_TYPE = 'P' THEN 'C' 
        WHEN AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_TYPE <> 'P' THEN 'A'
    END AS TRANSACTION_TYPE_CODE, 
    CASE 
        WHEN AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_TYPE = 'P' THEN 'Charge' 
        WHEN AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_TYPE <> 'P' THEN 'Adjustment'
    END AS TRANSACTION_TYPE_DESC,
    NULL AS SOURCE_LAST_UPDATED_DATETIME, 
    NULL AS TOOTH_ID, 
    NULL AS TOOTH_ARCH, 
    TO_ARRAY(NULL) AS TOOTH_SURFACE_ARRAY,
    CASE WHEN LEN(AVESIS_PAID_CLAIM_EXTRACTS.AGE) <= 3
            THEN NULLIF(AVESIS_PAID_CLAIM_EXTRACTS.AGE,'') 
            ELSE NULL END AS MEMBER_AGE_NBR, 
    NULL AS AUTHORIZATION_NBR, 
    NULL AS HCPCS_CODE,
    NULL AS CMS_CURRENT_ITERATION_FLAG,
    UTIL.FXN_ARRAY_HASH([LKP_CLAIM_MEMBER_AVESIS.TPA_CLIENT_ID, LKP_CLAIM_MEMBER_AVESIS.TPA_ID, LKP_CLAIM_MEMBER_AVESIS.TPA_DIV_ID, LKP_CLAIM_MEMBER_AVESIS.DATA_SOURCE_NAME, CLAIM_NBR, CLAIM_LINE_NBR, CLAIM_LINE_SEQ_NBR, CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY, 
    UTIL.FXN_ARRAY_HASH([CLAIM_TYPE_CODE, CLAIM_RECEIVED_DATE, PROCEDURE_CODE, PROCEDURE_QUANTITY, SERVICE_BEGIN_DATE, SERVICE_END_DATE, ADD_DATE, ACCOUNTS_PAYABLE_PAY_STATUS_CODE, ADJUDICATION_STATUS, AP_POSTING_DATE, BENEFIT_CATEGORY_CODE, BENEFIT_LEVEL_CODE, BUCKET_STATUS_FLAG, CHECK_DATE, CHECK_NUMBER, CLAIM_DAY_CNT, CLEAN_CLAIM_IND, COMPANY_CODE, DENIED_DAY_CNT, ELIGIBILITY_MISC_STATUS_CODE, FORM_NUMBER, GL_DISTRIBUTION_CODE, IS_PROCESSING_COMPLETE, KEY_TO_SOURCE_FILE, SERVICE_TYPE_CODE, LOCATION_CODE, PAY_STATUS_CODE, PAYMENT_DATE, TOOTH_QUADRANT, REVENUE_CODE, SERVICE_CNT, SERVICE_REASON_CODE, SERVICE_STATUS_CODE, SERVICE_STATUS_DESC, SERVICE_TYPE_CODE, TRANSACTION_TYPE_CODE, TRANSACTION_TYPE_DESC, SOURCE_LAST_UPDATED_DATETIME, TOOTH_ID, TOOTH_ARCH, TOOTH_SURFACE_ARRAY, MEMBER_AGE_NBR, AUTHORIZATION_NBR, HCPCS_CODE, CMS_CURRENT_ITERATION_FLAG]) AS HASH_DIFF
FROM RAWDATA.AVESIS_PAID_CLAIM_EXTRACTS 
JOIN STAGEDATA.LKP_CLAIM_MEMBER_AVESIS
        ON (LKP_CLAIM_MEMBER_AVESIS.CLAIM_NBR = AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO)
JOIN (
        SELECT 
            AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO AS CD_CLAIM_NBR, 
            FILENAME, 
            FILE_ROW_NUMBER,
            AVESIS_PAID_CLAIM_EXTRACTS.ITEM_NO AS CD_CLAIM_LINE_NBR,
            UTIL.FXN_ARRAY_HASH([SUBSCRIBER_ID,CHECK_NO,CLAIM_TYPE,ADJUDICATION_DT,SERVICE_DT,ANSI_CODE,EXCEPTION_CODE,ADJUSTMENT_CODE,PROC_CODE,QUANTITY,TOOTH_ID,PROV_LOC_ID,PRVD_ID,COUNTY_CODE,LOB_IND]) AS CD_CLAIM_LINE_SEQ_NBR
        FROM RAWDATA.AVESIS_PAID_CLAIM_EXTRACTS
        WHERE AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO IS NOT NULL
            QUALIFY ROW_NUMBER() -- get the most current submitted file for a claim line
                OVER(PARTITION BY AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO, AVESIS_PAID_CLAIM_EXTRACTS.ITEM_NO
                    ORDER BY TO_DATE(SPLIT_PART(SPLIT_PART(AVESIS_PAID_CLAIM_EXTRACTS.FILENAME, '_', 5), '.', 1), 'YYYYMMDD') DESC, FILE_ROW_NUMBER) = 1 
    ) CURRENT_CLAIM_FILE
    ON (CURRENT_CLAIM_FILE.CD_CLAIM_NBR = AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO
    AND CURRENT_CLAIM_FILE.CD_CLAIM_LINE_NBR = AVESIS_PAID_CLAIM_EXTRACTS.ITEM_NO
    AND CURRENT_CLAIM_FILE.CD_CLAIM_LINE_SEQ_NBR = UTIL.FXN_ARRAY_HASH([SUBSCRIBER_ID,CHECK_NO,CLAIM_TYPE,ADJUDICATION_DT,SERVICE_DT,ANSI_CODE,EXCEPTION_CODE,ADJUSTMENT_CODE,PROC_CODE,QUANTITY,TOOTH_ID,PROV_LOC_ID,PRVD_ID,COUNTY_CODE,LOB_IND])
    AND CURRENT_CLAIM_FILE.FILENAME = AVESIS_PAID_CLAIM_EXTRACTS.FILENAME
    AND CURRENT_CLAIM_FILE.FILE_ROW_NUMBER = AVESIS_PAID_CLAIM_EXTRACTS.FILE_ROW_NUMBER
    )
LEFT JOIN &{MC400}.DWOAO.ELIGIBILITYHISTORY
        ON ELIGIBILITYHISTORY.MEMBERNBR = AVESIS_PAID_CLAIM_EXTRACTS.SUBSCRIBER_ID
        AND REPLACE(TO_CHAR(AVESIS_PAID_CLAIM_EXTRACTS.SERVICE_DT), '-', '')::INT BETWEEN ELIGIBILITYHISTORY.ELIGIBILITYSTARTDATE AND ELIGIBILITYHISTORY.ELIGIBILITYENDDATE 
WHERE AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO IS NOT NULL
;

