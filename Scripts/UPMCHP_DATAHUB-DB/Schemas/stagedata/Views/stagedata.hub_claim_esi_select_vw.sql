CREATE OR REPLACE VIEW STAGEDATA.HUB_CLAIM_ESI_SELECT_VW
COMMENT='Source view for ESI data into HUB_CLAIM'
AS
SELECT DISTINCT
'N/A' AS SOURCE_KEY,
'000001' AS TPA_CLIENT_ID,
'000001' AS TPA_ID,
'0001' AS TPA_DIV_ID,
'ESI' AS DATA_SOURCE_NAME,
CLAIM_ID AS CLAIM_NBR,
UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, 
                     TPA_ID,
                     TPA_DIV_ID,
                     DATA_SOURCE_NAME,
                     CLAIM_NBR]) AS HUB_CLAIM_HKEY
FROM STAGEDATA.LKP_CLAIM_PHARMACY_CLAIM
;