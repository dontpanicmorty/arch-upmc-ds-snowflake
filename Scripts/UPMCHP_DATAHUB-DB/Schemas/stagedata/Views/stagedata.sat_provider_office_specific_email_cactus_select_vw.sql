CREATE OR REPLACE VIEW STAGEDATA.SAT_PROVIDER_OFFICE_SPECIFIC_EMAIL_CACTUS_SELECT_VW
COMMENT = 'This is a SAT View containing Provider Detail data'
AS
SELECT DISTINCT
'000001' AS P_TPA_CLIENT_ID,
'000001' AS P_TPA_ID,
'0001' AS P_TPA_DIV_ID,
'Cactus' AS P_DATA_SOURCE_NAME,
CACTUS_PROVIDERS.ID AS P_PROVIDER_ID,
'000001' AS O_TPA_CLIENT_ID,
'000001' AS O_TPA_ID,
'0001' AS O_TPA_DIV_ID,
'Cactus' AS O_DATA_SOURCE_NAME,
NULLIF(TRIM(CACTUS_PROVIDERADDRESSES.USERDEF_C1), '') AS O_OFFICE_ID,
IFF(CACTUS_PROVIDERADDRESSES.EMAILADDRESS NOT LIKE '%@%', NULL, TRIM(CACTUS_PROVIDERADDRESSES.EMAILADDRESS)) AS EMAIL_ADDRESS,
UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID, O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, O_OFFICE_ID]) AS LNK_PROVIDER_OFFICE_HKEY,
UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS HUB_PROVIDER_HKEY,
UTIL.FXN_ARRAY_HASH([O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, O_OFFICE_ID]) AS HUB_OFFICE_HKEY,
UTIL.FXN_ARRAY_HASH([EMAIL_ADDRESS]) AS HASH_DIFF
FROM RAWDATA.CACTUS_PROVIDERADDRESSES
LEFT JOIN RAWDATA.CACTUS_PROVIDERS ON CACTUS_PROVIDERADDRESSES.PROVIDER_K = CACTUS_PROVIDERS.PROVIDER_K
LEFT JOIN RAWDATA.CACTUS_ADDRESSES ON CACTUS_PROVIDERADDRESSES.ADDRESS_K = CACTUS_ADDRESSES.ADDRESS_K
LEFT JOIN (
    SELECT ID,COUNT(*) AS CNT FROM( 
        SELECT DISTINCT CACTUS_PROVIDERS.ID,CACTUS_PROVIDERS.PROVIDER_K FROM RAWDATA.CACTUS_PROVIDERS 
    INNER JOIN RAWDATA.CACTUS_ENTITYASSIGNMENTS
        ON CACTUS_ENTITYASSIGNMENTS.PROVIDER_K = CACTUS_PROVIDERS.PROVIDER_K) A
    GROUP BY ID HAVING COUNT(*) > 1 ) DUPES
    ON CACTUS_PROVIDERS.ID = DUPES.ID
INNER JOIN (SELECT DISTINCT PROVIDER_K FROM RAWDATA.CACTUS_ENTITYASSIGNMENTS WHERE CACTUS_ENTITYASSIGNMENTS.RECORDTYPE = 'E') EA
    ON EA.PROVIDER_K = CACTUS_PROVIDERS.PROVIDER_K 
WHERE CACTUS_PROVIDERS.STATUS_RTK NOT IN ('#0000K408T','#0000K408U','#0000K408S')
AND NULLIF(CACTUS_PROVIDERS.ID, '') IS NOT NULL
AND NULLIF(CACTUS_PROVIDERADDRESSES.PROVIDER_K, '') IS NOT NULL
AND NULLIF(CACTUS_PROVIDERADDRESSES.USERDEF_C1, '') IS NOT NULL
AND (CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG != 1 OR CACTUS_PROVIDERS.LASTNAME != '' OR CACTUS_PROVIDERS.FIRSTNAME != '')
AND (CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG != 2 OR (CACTUS_PROVIDERS.LONGNAME != '' AND CACTUS_PROVIDERADDRESSES.ACTIVE = 1))
AND (NULLIF(CACTUS_ADDRESSES.ADDRESSLINE1, '') IS NOT NULL OR NULLIF(CACTUS_ADDRESSES.ADDRESSLINE2, '') IS NOT NULL)
AND DUPES.ID IS NULL
AND CACTUS_PROVIDERADDRESSES.ACTIVE = TRUE
AND (CACTUS_PROVIDERADDRESSES.EMAILADDRESS <> '' AND CACTUS_PROVIDERADDRESSES.EMAILADDRESS LIKE '%@%')
;