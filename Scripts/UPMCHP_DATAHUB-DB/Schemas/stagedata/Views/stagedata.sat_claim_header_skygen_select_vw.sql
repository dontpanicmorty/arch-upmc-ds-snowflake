CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_HEADER_SKYGEN_SELECT_VW
COMMENT = 'This is a SAT View containing Skygen Claim Header data'
AS
SELECT 
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID,
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_HEADER.CLAIM_NBR,
DWSKYGEN_CLAIM_HEADER.CLAIM_ENTRY_DATE,
IFNULL(DWSKYGEN_CLAIM_HEADER.PLAN_CODE, LKP_CLAIM_MEMBER_SKYGEN.PLAN_CODE) AS PLAN_CODE,
IFNULL(DWSKYGEN_CLAIM_HEADER.PLAN_CODE, LKP_CLAIM_MEMBER_SKYGEN.PLAN_CODE) AS PLAN_CODE_HASH,
IFNULL(DWSKYGEN_CLAIM_HEADER.PLAN_TYPE_CODE, LKP_CLAIM_MEMBER_SKYGEN.PLAN_TYPE) AS PLAN_TYPE_CODE,
DWSKYGEN_CLAIM_HEADER.PARTICIPATING_PROVIDER_CODE AS BILLING_PROVIDER_PARTICIPATING_STATUS_CODE,
IFNULL(LOB_PLAN_TYPE.LINE_OF_BUSINESS_CODE, 'UNK') AS LINE_OF_BUSINESS_CODE,
IFNULL(LOB_PLAN_TYPE.LINE_OF_BUSINESS_CODE, 'UNK') AS LINE_OF_BUSINESS_CODE_HASH,
NULL AS ADMITTED_FLAG,
DWSKYGEN_CLAIM_HEADER.ADMIT_DATE AS ADMITTED_DATE,
NULL AS ADMITTED_HOUR,
NULL AS ADMISSION_SOURCE_CODE,
NULL AS ADMISSION_TYPE_CODE,
NULL AS DISCHARGE_DATE,
NULL AS DISCHARGE_HOUR,
NULL AS DISCHARGE_STATUS_CODE,
NULL AS BILLING_TYPE_CODE,
CLAIM_LINE_AGG.CALCULATED_BILL_TOTAL_AMT,
'dental' AS CARE_TYPE_NAME,
CONCAT(DWSKYGEN_CLAIM_HEADER.GROUP_NBR, DWSKYGEN_CLAIM_HEADER.SUB_GROUP_NBR) AS DIVISION_NUMBER,
DWSKYGEN_CLAIM_HEADER.RECORD_SOURCE_ID AS ELECTRONIC_CLAIM_TYPE_CODE,
NULL AS ENCOUNTER_REASON_CODE,
DWSKYGEN_CLAIM_HEADER.CLAIM_NBR AS FORM_NUMBER,
TRUE AS IS_PROCESSING_COMPLETE,
NULL AS MICROFILM_NBR,
CLAIM_LINE_FIELDS.PLACE_OF_SERVICE_CODE,
NULL AS PRICING_ZIP_SOURCE,
NULL AS PATIENT_ACCOUNT_NUMBER,
NULL AS SHOCK_CLAIM_IND,
DWSKYGEN_CLAIM_HEADER.INSERT_DATETIME AS SOURCE_LAST_UPDATED_DATETIME,
CASE WHEN
    DWSKYGEN_CLAIM_HEADER.PREDETERMINATION_CLAIM_ID IS NULL THEN FALSE
    ELSE TRUE
END AS IS_PREDETERMINATION_CLAIM_FLAG,
CASE --the starting with 000 means the claim came from skygen via &{MC400} as a historical claim. this will need modified as we layer more sources
    WHEN DWSKYGEN_CLAIM_HEADER.ORIGINAL_ENCOUNTER_ID LIKE '000%' THEN DWSKYGEN_CLAIM_HEADER.CLIENT_CLAIM_ID
    ELSE NULL
END AS ORIGINAL_CLAIM_ID,
CASE
    WHEN DWSKYGEN_CLAIM_HEADER.ORIGINAL_ENCOUNTER_ID LIKE '000%' THEN 'Y'
    ELSE 'N'
END AS MULTISOURCE_CLAIM_IND,
'E' AS CLAIM_TYPE_CODE, --Encounter
NULL AS IPA_CODE,
NULL AS BILLING_PROVIDER_VENDOR_NBR,
NULL AS SERVICE_ZIP_CODE,
NULL AS EDI_837_FACILITY_NPI_NBR,
NULL AS EDI_837_FACILITY_NAME,
NULL AS EDI_837_FACILITY_TELEPHONE_NBR,
NULL AS EDI_837_FACILITY_ADDRESS_LINE_1_TEXT,
NULL AS EDI_837_FACILITY_ADDRESS_LINE_2_TEXT,
NULL AS EDI_837_FACILITY_CITY_NAME,
NULL AS EDI_837_FACILITY_STATE_ABBREV_NAME,
NULL AS EDI_837_FACILITY_ZIP_CODE_NBR,
NULL AS EDI_837_FACILITY_OTHER_ID,
NULL AS SEVERITY_OF_ILLNESS,
NULL AS DIAGNOSIS_RELATED_GROUP_CODE,
NULL AS PROVIDER_SPECIALTY,
NULL AS PAID_STATUS_FOR_CMS,
UTIL.FXN_ARRAY_HASH([LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID, LKP_CLAIM_MEMBER_SKYGEN.TPA_ID, LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID, DATA_SOURCE_NAME, DWSKYGEN_CLAIM_HEADER.CLAIM_NBR]) AS HUB_CLAIM_HKEY,
UTIL.FXN_ARRAY_HASH([
    CLAIM_ENTRY_DATE
    ,LINE_OF_BUSINESS_CODE_HASH --Since column exists on other sources it will not take the computed column
    ,PLAN_CODE_HASH --Since column exists on other sources it will not take the computed column
    ,PLAN_TYPE_CODE
    ,BILLING_PROVIDER_PARTICIPATING_STATUS_CODE
    ,ADMITTED_FLAG
    ,ADMITTED_DATE
    ,ADMITTED_HOUR
    ,ADMISSION_SOURCE_CODE
    ,ADMISSION_TYPE_CODE
    ,DISCHARGE_DATE
    ,DISCHARGE_HOUR
    ,DISCHARGE_STATUS_CODE
    ,BILLING_TYPE_CODE
    ,CALCULATED_BILL_TOTAL_AMT
    ,CARE_TYPE_NAME
    ,DIVISION_NUMBER
    ,ELECTRONIC_CLAIM_TYPE_CODE
    ,ENCOUNTER_REASON_CODE
    ,FORM_NUMBER
    ,IS_PROCESSING_COMPLETE
    ,MICROFILM_NBR
    ,PLACE_OF_SERVICE_CODE
    ,PRICING_ZIP_SOURCE
    ,PATIENT_ACCOUNT_NUMBER
    ,SHOCK_CLAIM_IND
    ,SOURCE_LAST_UPDATED_DATETIME
    ,IS_PREDETERMINATION_CLAIM_FLAG
    ,ORIGINAL_CLAIM_ID
    ,MULTISOURCE_CLAIM_IND
    ,CLAIM_TYPE_CODE
    ,IPA_CODE
    ,BILLING_PROVIDER_VENDOR_NBR
    ,SERVICE_ZIP_CODE
    ,EDI_837_FACILITY_NPI_NBR
    ,EDI_837_FACILITY_NAME
    ,EDI_837_FACILITY_TELEPHONE_NBR
    ,EDI_837_FACILITY_ADDRESS_LINE_1_TEXT
    ,EDI_837_FACILITY_ADDRESS_LINE_2_TEXT
    ,EDI_837_FACILITY_CITY_NAME
    ,EDI_837_FACILITY_STATE_ABBREV_NAME
    ,EDI_837_FACILITY_ZIP_CODE_NBR
    ,EDI_837_FACILITY_OTHER_ID
    ,SEVERITY_OF_ILLNESS
    ,DIAGNOSIS_RELATED_GROUP_CODE
    ,PROVIDER_SPECIALTY
    ,PAID_STATUS_FOR_CMS
]) AS HASH_DIFF

FROM RAWDATA.DWSKYGEN_CLAIM_HEADER
	INNER JOIN /*Only time we should ever get header without detail is when details have been deleted*/
            (
            SELECT CLAIM_NBR, PLACE_OF_SERVICE_CODE
            FROM (
                SELECT CLAIM_NBR, CLAIM_LINE_NBR, CLAIM_LINE_SEQ_NBR, PROCEDURE_ADJ_CODE, PLACE_OF_SERVICE_CODE,
                RANK() OVER (PARTITION BY CLAIM_NBR
                    order by CLAIM_NBR desc, CLAIM_LINE_NBR desc, CLAIM_LINE_SEQ_NBR desc, PROCEDURE_ADJ_CODE desc)
                AS NEWEST_LINE
                FROM RAWDATA.DWSKYGEN_CLAIM_DETAIL 
                ) CLAIM_LINE_NEWEST
            WHERE CLAIM_LINE_NEWEST.NEWEST_LINE = 1
            ) CLAIM_LINE_FIELDS
		ON (DWSKYGEN_CLAIM_HEADER.CLAIM_NBR = CLAIM_LINE_FIELDS.CLAIM_NBR)

	INNER JOIN 
            (
            SELECT CLAIM_NBR, SUM(BILLED_AMOUNT) AS CALCULATED_BILL_TOTAL_AMT
            FROM RAWDATA.DWSKYGEN_CLAIM_DETAIL
            GROUP BY CLAIM_NBR
            ) CLAIM_LINE_AGG
		ON (DWSKYGEN_CLAIM_HEADER.CLAIM_NBR = CLAIM_LINE_AGG.CLAIM_NBR)

    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (DWSKYGEN_CLAIM_HEADER.CLAIM_NBR = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
    

    LEFT OUTER JOIN &{IDAP_LAKE}.NETWORK.LOB_PLAN_TYPE
        ON (LOB_PLAN_TYPE.TPA_CLIENT_ID = LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
        AND LOB_PLAN_TYPE.TPA_ID = LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
        AND LOB_PLAN_TYPE.TPA_DIV_ID = LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
        AND LOB_PLAN_TYPE.PLAN_TYPE = IFNULL(DWSKYGEN_CLAIM_HEADER.PLAN_TYPE_CODE, LKP_CLAIM_MEMBER_SKYGEN.PLAN_TYPE))

UNION ALL

SELECT DISTINCT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID,
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME,
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO AS CLAIM_NBR,
NULL AS CLAIM_ENTRY_DATE,
LKP_CLAIM_MEMBER_SKYGEN.PLAN_CODE AS PLAN_CODE,
LKP_CLAIM_MEMBER_SKYGEN.PLAN_CODE AS PLAN_CODE_HASH,
LKP_CLAIM_MEMBER_SKYGEN.PLAN_TYPE AS PLAN_TYPE_CODE,
NULL AS BILLING_PROVIDER_PARTICIPATING_STATUS_CODE,  --might be able to populate this (in or our of network)
IFNULL(LOB_PLAN_TYPE.LINE_OF_BUSINESS_CODE, 'UNK') AS LINE_OF_BUSINESS_CODE,
IFNULL(LOB_PLAN_TYPE.LINE_OF_BUSINESS_CODE, 'UNK') AS LINE_OF_BUSINESS_CODE_HASH,
NULL AS ADMITTED_FLAG,
TO_DATE(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.SERVICE_DT, 'YYYYMMDD') AS ADMITTED_DATE,
NULL AS ADMITTED_HOUR,
NULL AS ADMISSION_SOURCE_CODE,
NULL AS ADMISSION_TYPE_CODE,
NULL AS DISCHARGE_DATE,
NULL AS DISCHARGE_HOUR,
NULL AS DISCHARGE_STATUS_CODE,
NULL AS BILLING_TYPE_CODE,
CLAIM_LINE_AGG.CALCULATED_BILL_TOTAL_AMT,
'dental' AS CARE_TYPE_NAME,
CONCAT(LKP_CLAIM_MEMBER_SKYGEN.COVERAGE_GROUP_CODE, LKP_CLAIM_MEMBER_SKYGEN.SUB_GROUP_CODE) AS DIVISION_NUMBER,
NULL AS ELECTRONIC_CLAIM_TYPE_CODE, --This could probably be a 3-electonic
NULL AS ENCOUNTER_REASON_CODE,
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO AS FORM_NUMBER,
TRUE AS IS_PROCESSING_COMPLETE,
NULL AS MICROFILM_NBR,
LPAD(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.POS, 2, '0') AS PLACE_OF_SERVICE_CODE,
NULL AS PRICING_ZIP_SOURCE,
NULL AS PATIENT_ACCOUNT_NUMBER,
NULL AS SHOCK_CLAIM_IND,
NULL AS SOURCE_LAST_UPDATED_DATETIME,
FALSE AS IS_PREDETERMINATION_CLAIM_FLAG,
NULL AS ORIGINAL_CLAIM_ID,
NULL AS MULTISOURCE_CLAIM_IND,
'E' AS CLAIM_TYPE_CODE, --Encounter
NULL AS IPA_CODE,
NULL AS BILLING_PROVIDER_VENDOR_NBR,
NULL AS SERVICE_ZIP_CODE,
NULL AS EDI_837_FACILITY_NPI_NBR,
NULL AS EDI_837_FACILITY_NAME,
NULL AS EDI_837_FACILITY_TELEPHONE_NBR,
NULL AS EDI_837_FACILITY_ADDRESS_LINE_1_TEXT,
NULL AS EDI_837_FACILITY_ADDRESS_LINE_2_TEXT,
NULL AS EDI_837_FACILITY_CITY_NAME,
NULL AS EDI_837_FACILITY_STATE_ABBREV_NAME,
NULL AS EDI_837_FACILITY_ZIP_CODE_NBR,
NULL AS EDI_837_FACILITY_OTHER_ID,
NULL AS SEVERITY_OF_ILLNESS,
NULL AS DIAGNOSIS_RELATED_GROUP_CODE,
NULL AS PROVIDER_SPECIALTY,
NULL AS PAID_STATUS_FOR_CMS,
UTIL.FXN_ARRAY_HASH([LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID, LKP_CLAIM_MEMBER_SKYGEN.TPA_ID, LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID, DATA_SOURCE_NAME, SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO]) AS HUB_CLAIM_HKEY,
UTIL.FXN_ARRAY_HASH([
    CLAIM_ENTRY_DATE
    ,LINE_OF_BUSINESS_CODE_HASH --Since column exists on other sources it will not take the computed column
    ,PLAN_CODE_HASH --Since column exists on other sources it will not take the computed column
    ,PLAN_TYPE_CODE
    ,BILLING_PROVIDER_PARTICIPATING_STATUS_CODE
    ,ADMITTED_FLAG
    ,ADMITTED_DATE
    ,ADMITTED_HOUR
    ,ADMISSION_SOURCE_CODE
    ,ADMISSION_TYPE_CODE
    ,DISCHARGE_DATE
    ,DISCHARGE_HOUR
    ,DISCHARGE_STATUS_CODE
    ,BILLING_TYPE_CODE
    ,CALCULATED_BILL_TOTAL_AMT
    ,CARE_TYPE_NAME
    ,DIVISION_NUMBER
    ,ELECTRONIC_CLAIM_TYPE_CODE
    ,ENCOUNTER_REASON_CODE
    ,FORM_NUMBER
    ,IS_PROCESSING_COMPLETE
    ,MICROFILM_NBR
    ,PLACE_OF_SERVICE_CODE
    ,PRICING_ZIP_SOURCE
    ,PATIENT_ACCOUNT_NUMBER
    ,SHOCK_CLAIM_IND
    ,SOURCE_LAST_UPDATED_DATETIME
    ,IS_PREDETERMINATION_CLAIM_FLAG
    ,ORIGINAL_CLAIM_ID
    ,MULTISOURCE_CLAIM_IND
    ,CLAIM_TYPE_CODE
    ,IPA_CODE
    ,BILLING_PROVIDER_VENDOR_NBR
    ,SERVICE_ZIP_CODE
    ,EDI_837_FACILITY_NPI_NBR
    ,EDI_837_FACILITY_NAME
    ,EDI_837_FACILITY_TELEPHONE_NBR
    ,EDI_837_FACILITY_ADDRESS_LINE_1_TEXT
    ,EDI_837_FACILITY_ADDRESS_LINE_2_TEXT
    ,EDI_837_FACILITY_CITY_NAME
    ,EDI_837_FACILITY_STATE_ABBREV_NAME
    ,EDI_837_FACILITY_ZIP_CODE_NBR
    ,EDI_837_FACILITY_OTHER_ID
    ,SEVERITY_OF_ILLNESS
    ,DIAGNOSIS_RELATED_GROUP_CODE
    ,PROVIDER_SPECIALTY
    ,PAID_STATUS_FOR_CMS
]) AS HASH_DIFF
FROM RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW	
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)

    JOIN
        (
        SELECT CLAIM_NO, SUM(BILLED_AMT::number(38,4)) AS CALCULATED_BILL_TOTAL_AMT
        FROM RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW
        GROUP BY CLAIM_NO
        ) CLAIM_LINE_AGG
		ON (SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO = CLAIM_LINE_AGG.CLAIM_NO)

    LEFT OUTER JOIN &{IDAP_LAKE}.NETWORK.LOB_PLAN_TYPE
        ON (LOB_PLAN_TYPE.TPA_CLIENT_ID = LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
        AND LOB_PLAN_TYPE.TPA_ID = LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
        AND LOB_PLAN_TYPE.TPA_DIV_ID = LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
        AND LOB_PLAN_TYPE.PLAN_TYPE = LKP_CLAIM_MEMBER_SKYGEN.PLAN_TYPE)

WHERE SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO NOT IN (SELECT CLAIM_NBR FROM RAWDATA.DWSKYGEN_CLAIM_HEADER) --Exclude claims in dwskygen, they supersede
;

