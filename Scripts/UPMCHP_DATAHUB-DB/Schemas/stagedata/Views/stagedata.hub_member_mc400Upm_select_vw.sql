CREATE OR REPLACE VIEW STAGEDATA.HUB_MEMBER_MC400Upm_SELECT_VW
COMMENT = 'Source view for MC400Upm data into HUB_MEMBER'
AS
SELECT 
'N/A' AS SOURCE_KEY,
MC400_DWOAO_MEMBERS.TpaClient AS TPA_CLIENT_ID,
MC400_DWOAO_MEMBERS.TpaIdOfClient AS TPA_ID,
MC400_DWOAO_MEMBERS.TpaDivision AS TPA_DIV_ID,
'MC400Upm' AS DATA_SOURCE_NAME,
TRIM(MC400_DWOAO_MEMBERS.MemberNbr) AS MEMBER_NBR,
UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEMBER_NBR]) as HUB_MEMBER_HKEY
FROM RAWDATA.MC400_DWOAO_MEMBERS  --This is both dwoao & dwoao_nonclaims
WHERE MC400_DWOAO_MEMBERS.MemberNbr <> '99999999901' --this is a junk catch all member number
;