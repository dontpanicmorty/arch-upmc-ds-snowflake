CREATE OR REPLACE VIEW STAGEDATA.SAT_ACCUMULATOR_CODESET_SKYGEN_SELECT_VW
AS
SELECT DISTINCT
    TPA_CLIENT_ID,
    TPA_ID,
    TPA_DIV_ID,
    DATA_SOURCE_NAME,
    CODESET_CODE,
    BENEFIT_CODESET_NAME AS CODESET_DESC,
    CODESET_CLASSIFICATION_DESC,
    CODESET_CATEGORY_DESC,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CODESET_CODE]) AS HUB_ACCUMULATOR_CODESET_HKEY,
    UTIL.FXN_ARRAY_HASH([CODESET_DESC, CODESET_CLASSIFICATION_DESC, CODESET_CATEGORY_DESC]) AS HASH_DIFF
FROM RAWDATA.DWSKYGEN_PLAN_ACCUMULATOR
;