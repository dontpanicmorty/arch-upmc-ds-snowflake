CREATE OR REPLACE VIEW STAGEDATA.SAT_PLAN_DETAIL_ACA_MC400Upm_SELECT_VW
COMMENT = 'This is a SAT source view containing ACA plan detail data'
AS
SELECT
 PlanMaster .TpaClient AS TPA_CLIENT_ID
,PlanMaster .TpaIdOfClient AS TPA_ID
,PlanMaster .TpaDivision AS TPA_DIV_ID
,'MC400Upm' AS DATA_SOURCE_NAME
,PlanMaster .PlanCode AS PLAN_CODE
,NULLIF(TRIM(SG_ACA_PLANS.HIOS_ID),'') AS HIOS_ID
,TO_VARCHAR(SG_ACA_PLANS.MIN_BENEFIT_YEAR::numeric) AS MIN_BENEFIT_YEAR
,'Small Group' AS MARKET_SEGMENT_NAME
,NULLIF(TRIM(SG_ACA_PLANS.PLAN_TYPE), '') AS PLAN_TYPE_NAME
,NULLIF(TRIM(SG_ACA_PLANS.PRODUCT), '') AS PRODUCT_CODE
,NULLIF(TRIM(SG_ACA_PLANS.MARKETING_PLAN_NAME), '') AS MARKETING_PLAN_NAME
,NULLIF(TRIM(SG_ACA_PLANS.METAL_LEVEL), '') AS METAL_LEVEL_CODE
,CASE UPPER(SG_ACA_PLANS.ON_VS_OFF)
    WHEN 'ON EXCHANGE' THEN 'Y'
    WHEN 'OFF EXCHANGE' THEN 'N'
    ELSE NULL
END AS ON_EXCHANGE_IND
,NULLIF(TRIM(SG_ACA_PLANS.NETWORK_NAME), '') AS NETWORK_NAME
,'NULL' AS COST_SHARE_TYPE_NAME
,UTIL.FXN_ARRAY_HASH([ PlanMaster .TpaClient, PlanMaster .TpaIdOfClient, PlanMaster .TpaDivision, DATA_SOURCE_NAME, PlanMaster .PlanCode]) AS HUB_PLAN_HKEY
FROM RAWDATA.MC400_DWOAO_PlanMaster  PlanMaster 
    JOIN  RAWDATA.HP_ANALYTICS_SG_ACA_PLANS SG_ACA_PLANS
        ON (SG_ACA_PLANS.PLAN_CODE= PlanMaster .PlanCode)

UNION ALL

SELECT
 PlanMaster .TpaClient AS TPA_CLIENT_ID
,PlanMaster .TpaIdOfClient AS TPA_ID
,PlanMaster .TpaDivision AS TPA_DIV_ID
,'MC400Upm' AS DATA_SOURCE_NAME
,PlanMaster .PlanCode AS PLAN_CODE
,NULLIF(TRIM(IA_ACA_PLANS.HIOS_ID),'') AS HIOS_ID
,TO_VARCHAR(IA_ACA_PLANS.MIN_BENEFIT_YEAR::numeric) AS MIN_BENEFIT_YEAR
,'Individual' AS MARKET_SEGMENT_NAME
,NULLIF(TRIM(IA_ACA_PLANS.PLAN_TYPE), '') AS PLAN_TYPE_NAME
,NULLIF(TRIM(IA_ACA_PLANS.PRODUCT), '') AS PRODUCT_CODE
,NULLIF(TRIM(IA_ACA_PLANS.MARKETING_PLAN_NAME), '') AS MARKETING_PLAN_NAME
,NULLIF(TRIM(IA_ACA_PLANS.METAL_LEVEL), '') AS METAL_LEVEL_CODE
,CASE UPPER(IA_ACA_PLANS.ON_VS_OFF)
    WHEN 'ON EXCHANGE' THEN 'Y'
    WHEN 'OFF EXCHANGE' THEN 'N'
    ELSE NULL
END AS ON_EXCHANGE_IND
,NULLIF(TRIM(IA_ACA_PLANS.NETWORK_NAME), '') AS NETWORK_NAME
,NULLIF(TRIM(COALESCE(IA_ACA_PLANS.COST_SHARE_TYPE, NULL)), '') AS COST_SHARE_TYPE_NAME
,UTIL.FXN_ARRAY_HASH([ PlanMaster .TpaClient, PlanMaster .TpaIdOfClient, PlanMaster .TpaDivision, DATA_SOURCE_NAME, PlanMaster .PlanCode]) AS HUB_PLAN_HKEY
FROM RAWDATA.MC400_DWOAO_PlanMaster  PlanMaster 
    JOIN RAWDATA.HP_ANALYTICS_IA_ACA_PLANS IA_ACA_PLANS
        ON (IA_ACA_PLANS.PLAN_CODE= PlanMaster .PlanCode)


;


