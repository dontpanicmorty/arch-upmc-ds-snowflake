CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_MEMBER_NVA_SELECT_VW
COMMENT = 'Source view for NVA data into LNK_CLAIM_MEMBER'
AS
SELECT DISTINCT
    LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID AS C_TPA_CLIENT_ID, 
    LKP_CLAIM_MEMBER_NVA.TPA_ID AS C_TPA_ID, 
    LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID AS C_TPA_DIV_ID, 
    LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME, 
    NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo" AS C_CLAIM_NBR, 
    LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID AS M_TPA_CLIENT_ID, 
    LKP_CLAIM_MEMBER_NVA.TPA_ID AS M_TPA_ID, 
    LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID AS M_TPA_DIV_ID, 
    'MC400Upm' AS M_DATA_SOURCE_NAME,
    LKP_CLAIM_MEMBER_NVA.MEMBER_NBR AS M_MEMBER_NBR, 
    UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, M_TPA_CLIENT_ID, M_TPA_ID, M_TPA_DIV_ID, M_DATA_SOURCE_NAME, M_MEMBER_NBR]) AS LNK_CLAIM_MEMBER_HKEY, 
    UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY, 
    UTIL.FXN_ARRAY_HASH([M_TPA_CLIENT_ID, M_TPA_ID, M_TPA_DIV_ID, M_DATA_SOURCE_NAME, M_MEMBER_NBR]) AS HUB_MEMBER_HKEY
FROM RAWDATA.NVA_PAID_CLAIM_EXTRACTS_VW
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_NVA
        ON (LKP_CLAIM_MEMBER_NVA.CLAIM_NBR = NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo")
QUALIFY ROW_NUMBER() -- take the most recent submission to remove duplicates
    OVER(PARTITION BY NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo"
        ORDER BY SPLIT_PART(SPLIT_PART(NVA_PAID_CLAIM_EXTRACTS_VW.FILENAME, '_', 7), '.', 1) DESC) = 1
;