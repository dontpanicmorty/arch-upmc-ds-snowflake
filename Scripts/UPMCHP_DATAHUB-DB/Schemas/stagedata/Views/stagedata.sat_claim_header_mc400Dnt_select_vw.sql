!set variable_substitution=true;
CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_HEADER_MC400Dnt_SELECT_VW
COMMENT = 'This SAT table contains Claim Header data'
AS
SELECT
'000001' AS TPA_CLIENT_ID
,'000001' AS TPA_ID
,'0001' AS TPA_DIV_ID
,'MC400Dnt' AS DATA_SOURCE_NAME
,Claims.ClaimNbr AS CLAIM_NBR
,TRY_TO_DATE(TO_VARCHAR(Claims.ClaimEntryDate),'YYYYMMDD') AS CLAIM_ENTRY_DATE
,LOB_PLAN_TYPE.LINE_OF_BUSINESS_CODE AS LINE_OF_BUSINESS_CODE
,Claims.PlanCode AS PLAN_CODE
,Claims.PlanType AS PLAN_TYPE_CODE
,IFF(TRIM(Claims.ParticipatingProvider) = '', NULL, TRIM(Claims.ParticipatingProvider)) AS BILLING_PROVIDER_PARTICIPATING_STATUS_CODE
,CASE (Claims.AdmitFlag)
    WHEN 'Y' THEN TRUE
    WHEN 'N' THEN FALSE
    ELSE NULL
END AS ADMITTED_FLAG
,TRY_TO_DATE(TO_VARCHAR(Claims.AdmitDate),'YYYYMMDD') AS ADMITTED_DATE
,IFF(Claims.AdmissionHour = 0, NULL, Claims.AdmissionHour) AS ADMITTED_HOUR
,IFF(TRIM(Claims.AdmissionSource) = '', NULL, TRIM(Claims.AdmissionSource)) AS ADMISSION_SOURCE_CODE
,IFF(TRIM(Claims.AdmissionType) = '', NULL, TRIM(Claims.AdmissionType)) AS ADMISSION_TYPE_CODE
,IFF(Claims.DischargeDate = 0, NULL, TRY_TO_DATE(TO_VARCHAR(Claims.DischargeDate),'YYYYMMDD')) AS DISCHARGE_DATE
,IFF(Claims.DischargeHour = 0, NULL, Claims.DischargeHour) AS DISCHARGE_HOUR
,IFF(TRIM(Claims.DischargeStatus) = '', NULL, TRIM(Claims.DischargeStatus)) AS DISCHARGE_STATUS_CODE
,IFF(TRIM(Claims.BillType) = '', NULL, Claims.BillType) AS BILLING_TYPE_CODE
,Claims.CalculatedBilledTotal AS CALCULATED_BILL_TOTAL_AMT
,CASE UPPER(Claims.ClaimTypeCode)
    WHEN 'D' THEN 'dental'
    WHEN 'P' THEN 'dental' -- Pre-determination
    WHEN 'V' THEN 'vision'
    WHEN 'A' THEN 'vision' -- Pre-determination
    ELSE 'unknown'
END AS CARE_TYPE_NAME
,CONCAT(Claims.GroupNbr, Claims.SubGroup) AS DIVISION_NUMBER
,IFF(TRIM(Claims.UserField) = '', NULL, TRIM(Claims.UserField)) AS ELECTRONIC_CLAIM_TYPE_CODE
,IFF(TRIM(Claims.EncounterReason) = '', NULL, TRIM(Claims.EncounterReason)) ENCOUNTER_REASON_CODE
,Claims.FormNbr AS FORM_NUMBER
,NULL AS IS_PROCESSING_COMPLETE --n/a this is a MarkLogic specific field, needs removed
,MicroFilmDocuments.DocumnetId AS MICROFILM_NBR
,Claims.PlaceOfService AS PLACE_OF_SERVICE_CODE
,NULL AS PRICING_ZIP_SOURCE --n/a for DNV
,IFF(Claims.ProviderAcctNbr = '', NULL, Claims.ProviderAcctNbr) AS PATIENT_ACCOUNT_NUMBER
,CASE WHEN (IFNULL(CLAIM_DETAIL_SUM_AMT.SUM_NET_AMT,0) > 200000)
    THEN 'Y'
    ELSE 'N'
END AS SHOCK_CLAIM_IND
,Claims.LastUpdated AS SOURCE_LAST_UPDATED_DATETIME
,CASE UPPER(Claims.ClaimTypeCode)
    WHEN 'A' THEN TRUE -- Pre-determination dental
    WHEN 'P' THEN TRUE -- Pre-determination vision
    ELSE FALSE
END AS IS_PREDETERMINATION_CLAIM_FLAG
,NULL AS ORIGINAL_CLAIM_ID
,NULL AS MULTISOURCE_CLAIM_IND -- Might need updated in conjunction withy Skygen resubmits
,Claims.ClaimType AS CLAIM_TYPE_CODE --Encounter or Inpatient
,IFF(TRIM(Claims.IPACode) = '', NULL, TRIM(Claims.IPACode)) AS IPA_CODE
,Claims.VendorNbr AS BILLING_PROVIDER_VENDOR_NBR
,NULL AS SERVICE_ZIP_CODE
,NULL AS EDI_837_FACILITY_NPI_NBR
,NULL AS EDI_837_FACILITY_NAME
,NULL AS EDI_837_FACILITY_TELEPHONE_NBR
,NULL AS EDI_837_FACILITY_ADDRESS_LINE_1_TEXT
,NULL AS EDI_837_FACILITY_ADDRESS_LINE_2_TEXT
,NULL AS EDI_837_FACILITY_CITY_NAME
,NULL AS EDI_837_FACILITY_STATE_ABBREV_NAME
,NULL AS EDI_837_FACILITY_ZIP_CODE_NBR
,NULL AS EDI_837_FACILITY_OTHER_ID
,NULL AS SEVERITY_OF_ILLNESS
,NULL AS DIAGNOSIS_RELATED_GROUP_CODE
,IFF(TRIM(Claims.ProviderSpecialty) = '', NULL, TRIM(Claims.ProviderSpecialty)) AS PROVIDER_SPECIALTY
,NULL AS PAID_STATUS_FOR_CMS
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_NBR]) AS HUB_CLAIM_HKEY
,UTIL.FXN_ARRAY_HASH([
    CLAIM_ENTRY_DATE
    ,LINE_OF_BUSINESS_CODE
    ,PLAN_CODE
    ,PLAN_TYPE_CODE
    ,BILLING_PROVIDER_PARTICIPATING_STATUS_CODE
    ,ADMITTED_FLAG
    ,ADMITTED_DATE
    ,ADMITTED_HOUR
    ,ADMISSION_SOURCE_CODE
    ,ADMISSION_TYPE_CODE
    ,DISCHARGE_DATE
    ,DISCHARGE_HOUR
    ,DISCHARGE_STATUS_CODE
    ,BILLING_TYPE_CODE
    ,CALCULATED_BILL_TOTAL_AMT
    ,CARE_TYPE_NAME
    ,DIVISION_NUMBER
    ,ELECTRONIC_CLAIM_TYPE_CODE
    ,ENCOUNTER_REASON_CODE
    ,FORM_NUMBER
    ,IS_PROCESSING_COMPLETE
    ,MICROFILM_NBR
    ,PLACE_OF_SERVICE_CODE
    ,PRICING_ZIP_SOURCE
    ,PATIENT_ACCOUNT_NUMBER
    ,SHOCK_CLAIM_IND
    ,SOURCE_LAST_UPDATED_DATETIME
    ,IS_PREDETERMINATION_CLAIM_FLAG
    ,ORIGINAL_CLAIM_ID
    ,MULTISOURCE_CLAIM_IND
    ,CLAIM_TYPE_CODE
    ,IPA_CODE
    ,BILLING_PROVIDER_VENDOR_NBR
    ,SERVICE_ZIP_CODE
    ,EDI_837_FACILITY_NPI_NBR
    ,EDI_837_FACILITY_NAME
    ,EDI_837_FACILITY_TELEPHONE_NBR
    ,EDI_837_FACILITY_ADDRESS_LINE_1_TEXT
    ,EDI_837_FACILITY_ADDRESS_LINE_2_TEXT
    ,EDI_837_FACILITY_CITY_NAME
    ,EDI_837_FACILITY_STATE_ABBREV_NAME
    ,EDI_837_FACILITY_ZIP_CODE_NBR
    ,EDI_837_FACILITY_OTHER_ID
    ,SEVERITY_OF_ILLNESS
    ,DIAGNOSIS_RELATED_GROUP_CODE
    ,PROVIDER_SPECIALTY
    ,PAID_STATUS_FOR_CMS
]) AS HASH_DIFF

FROM &{MC400}.DWDNV.CLAIMS CLAIMS
    LEFT OUTER JOIN
        (
            SELECT ClaimNbr, SUM(NetAmt) AS SUM_NET_AMT
            FROM &{MC400}.DWDNV.CLAIMSDETAIL
            GROUP BY ClaimNbr
        ) CLAIM_DETAIL_SUM_AMT
        ON (CLAIM_DETAIL_SUM_AMT.ClaimNbr = Claims.ClaimNbr)

    LEFT OUTER JOIN &{MC400}.DWDNV.MicroFilmDocuments
        ON (MicroFilmDocuments.FormNumber = Claims.FormNbr
        AND MicroFilmDocuments.PrimaryDateOfService = Claims.AdmitDate
        AND MicroFilmDocuments.APSourceFileType = Claims.ClaimType
        AND MicroFilmDocuments.DocumnetId <> ''
        AND MicroFilmDocuments.DeletedFlag = '1900-01-01 00:00:00.000')

    LEFT OUTER JOIN &{IDAP_LAKE}.NETWORK.LOB_PLAN_TYPE LOB_PLAN_TYPE
        ON (LOB_PLAN_TYPE.TPA_CLIENT_ID = '000001'
        AND LOB_PLAN_TYPE.TPA_ID = '000001'
        AND LOB_PLAN_TYPE.TPA_DIV_ID = '0001'
        AND LOB_PLAN_TYPE.PLAN_TYPE = Claims.PlanType)

WHERE CLAIMS.MemberNbr <> '99999999901' --Exclude Generic Default Member Claims
;

!set variable_substitution=false;
