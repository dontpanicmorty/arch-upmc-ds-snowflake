CREATE OR REPLACE VIEW STAGEDATA.HUB_MEMBERSHIP_GROUP_MC400UPM_SELECT_VW
COMMENT = 'This is a HUB View containing Membership Group data'
AS
SELECT
'N/A' AS SOURCE_KEY
,TpaClient AS TPA_CLIENT_ID
,TpaIdOfClient AS TPA_ID
,TpaDivision AS TPA_DIV_ID,
'MC400Upm' AS DATA_SOURCE_NAME,
TRIM(GroupNbr) AS GROUP_NBR,
TRIM(SubGroup) AS SUB_GROUP_NBR,
UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, GROUP_NBR, SUB_GROUP_NBR]) AS HUB_MEMBERSHIP_GROUP_HKEY
FROM RAWDATA.MC400_DWOAO_SUBGROUPS
;
