CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_PLAN_ENVOLVE_SELECT_VW
COMMENT = 'Source view for ENVOLVE data into LNK_CLAIM_PLAN'
AS
SELECT DISTINCT
    LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID AS C_TPA_CLIENT_ID, 
    LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID AS C_TPA_ID,
    LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID AS C_TPA_DIV_ID,
    LKP_CLAIM_MEMBER_ENVOLVE.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME,
    ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO AS C_CLAIM_NBR,
    LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID AS P_TPA_CLIENT_ID,
    LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID AS P_TPA_ID,
    LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID AS P_TPA_DIV_ID,
    'MC400Upm' AS P_DATA_SOURCE_NAME, --Plans are sourced from MC400Upm
    LKP_CLAIM_MEMBER_ENVOLVE.PLAN_CODE AS P_PLAN_CODE,
    UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PLAN_CODE]) AS LNK_CLAIM_PLAN_HKEY,
    UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY,
    UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PLAN_CODE]) AS HUB_PLAN_HKEY
FROM RAWDATA.ENVOLVE_CLAIM_EXTRACTS
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_ENVOLVE
        ON (LKP_CLAIM_MEMBER_ENVOLVE.CLAIM_NBR = ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO)
WHERE P_PLAN_CODE IS NOT NULL
QUALIFY ROW_NUMBER() -- get the most current submitted file for a claim line
    OVER(PARTITION BY ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO,ENVOLVE_CLAIM_EXTRACTS.ITEM_NO
    ORDER BY SPLIT_PART(SPLIT_PART(ENVOLVE_CLAIM_EXTRACTS.FILENAME, '_', 7), '.', 1) DESC) = 1 
;