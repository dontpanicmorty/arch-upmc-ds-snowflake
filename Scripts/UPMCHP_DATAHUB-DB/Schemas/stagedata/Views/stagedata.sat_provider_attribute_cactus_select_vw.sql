CREATE OR REPLACE VIEW STAGEDATA.SAT_PROVIDER_ATTRIBUTE_CACTUS_SELECT_VW(
TPA_CLIENT_ID,
TPA_ID,
TPA_DIV_ID,
DATA_SOURCE_NAME,
PROVIDER_ID,
PRIMARY_PHO_NAME,
PRIMARY_PHO_TERMINATION_DATE,
SECONDARY_PHO_NAME,
SECONDARY_PHO_TERMINATION_DATE,
TERTIARY_PHO_NAME,
TERTIARY_PHO_TERMINATION_DATE,
PA_MEDICAID_IND,
PP_ACA_ENHANCED_PAY_IND,
MALPRACTICE_COVERAGE_IND,
HUB_PROVIDER_HKEY,
HASH_DIFF
) COMMENT='This is a SAT View containing Provider Attribute data'
 AS

WITH PRV_CTE AS (
SELECT DISTINCT
PRV430.NPINUMBER,
'Y' AS PA_MEDICAID_IND_CTE
FROM &{IDAP_LAKE}.PROVIDER.PRV430 AS PRV430
LEFT JOIN &{IDAP_LAKE}.PROVIDER.PRV414_VW AS PRV414_VW
ON SERVICELOCATION = PRV414_VW.SERVICELOC
AND PRV430.PROMISEPROVIDERNUMBER = PRV414_VW.PROMISEPROV
WHERE PRV414_VW.ENDDATE = '22991231'
AND PRV414_VW.SPECCODEEND = '22991231'
AND PRV414_VW.STATUSCODE = 'A'
)

SELECT DISTINCT
'000001' AS TPA_CLIENT_ID,
    '000001' AS TPA_ID,
    '0001' AS TPA_DIV_ID,
    'Cactus' AS DATA_SOURCE_NAME,
        RTRIM(CACTUS_PROVIDERS.ID) AS PROVIDER_ID,
        IFF(TRIM(REF1.DESCRIPTION) = 'No Value Specified', NULL, TRIM(REF1.DESCRIPTION)) AS PRIMARY_PHO_NAME,
        CAST(CACTUS_PROVIDERS.USERDEF_D1 AS DATE) AS PRIMARY_PHO_TERMINATION_DATE,
        IFF(TRIM(REF2.DESCRIPTION) = 'No Value Specified', NULL, TRIM(REF2.DESCRIPTION)) AS SECONDARY_PHO_NAME,
        CAST(CACTUS_PROVIDERS.USERDEF_D2 AS DATE) AS SECONDARY_PHO_TERMINATION_DATE,
        IFF(TRIM(REF3.DESCRIPTION) = 'No Value Specified', NULL, TRIM(REF3.DESCRIPTION)) AS TERTIARY_PHO_NAME,
        CAST(CACTUS_PROVIDERS.USERDEF_D3 AS DATE) AS TERTIARY_PHO_TERMINATION_DATE,
        IFF(PRV_CTE.PA_MEDICAID_IND_CTE is null, 'N', PRV_CTE.PA_MEDICAID_IND_CTE) as PA_MEDICAID_IND,
        IFF(CACTUS_PROVIDERS.USERDEF_L1 = '1','Y','N') AS PP_ACA_ENHANCED_PAY_IND,
        IFF(CACTUS_PROVIDERS.PROVIDER_K IN (SELECT  PROVIDER_K FROM RAWDATA.CACTUS_PROVIDERINSURANCE),'Y','N') AS MALPRACTICE_COVERAGE_IND,
        UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY,
        UTIL.FXN_ARRAY_HASH([PRIMARY_PHO_NAME, PRIMARY_PHO_TERMINATION_DATE, SECONDARY_PHO_NAME, SECONDARY_PHO_TERMINATION_DATE,
        TERTIARY_PHO_NAME, TERTIARY_PHO_TERMINATION_DATE, PA_MEDICAID_IND, PP_ACA_ENHANCED_PAY_IND, MALPRACTICE_COVERAGE_IND]) AS HASH_DIFF
        FROM RAWDATA.CACTUS_PROVIDERS CACTUS_PROVIDERS
        LEFT JOIN RAWDATA.CACTUS_REFTABLE REF1
        ON CACTUS_PROVIDERS.USERDEF_RTK1=REF1.REFTABLE_K
        LEFT JOIN RAWDATA.CACTUS_REFTABLE REF2
        ON CACTUS_PROVIDERS.USERDEF_RTK2=REF2.REFTABLE_K
        LEFT JOIN RAWDATA.CACTUS_REFTABLE REF3
        ON CACTUS_PROVIDERS.USERDEF_RTK3=REF3.REFTABLE_K
        LEFT JOIN PRV_CTE
        ON CACTUS_PROVIDERS.NPI = PRV_CTE.NPINUMBER
    INNER JOIN (
    SELECT DISTINCT PROVIDER_K
    FROM RAWDATA.CACTUS_ENTITYASSIGNMENTS
    WHERE RECORDTYPE = 'E'
    ) AS EA
    ON CACTUS_PROVIDERS.PROVIDER_K = EA.PROVIDER_K
LEFT JOIN (
SELECT ID, COUNT(*) AS CNT FROM(
SELECT DISTINCT P.ID, P.PROVIDER_K
FROM RAWDATA.CACTUS_PROVIDERS P
INNER JOIN RAWDATA.CACTUS_ENTITYASSIGNMENTS E
ON E.PROVIDER_K = P.PROVIDER_K) A
GROUP BY ID HAVING COUNT(*) > 1 ) DUPES
ON CACTUS_PROVIDERS.ID = DUPES.ID
WHERE CACTUS_PROVIDERS.STATUS_RTK NOT IN ('#0000K408T','#0000K408U','#0000K408S')
AND NOT (CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 AND (CACTUS_PROVIDERS.LASTNAME = '' AND CACTUS_PROVIDERS.FIRSTNAME =''))
AND NOT(CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 2 AND CACTUS_PROVIDERS.LONGNAME  ='')
AND NULLIF(CACTUS_PROVIDERS.ID, '') IS NOT NULL
AND DUPES.ID IS NULL;


