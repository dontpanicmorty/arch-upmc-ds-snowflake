!set variable_substitution=true;

CREATE OR REPLACE VIEW STAGEDATA.LNK_OCF_MEMBER_SELECT_VW COMMENT = 'Source view for LNK_OCF_MEMBER' AS
SELECT DISTINCT
    CURRENT_DATE() AS INSERT_DATETIME,
    'MC400Upm' AS MOCF_DATA_SOURCE_NAME,
    IFNULL(RECORD_SOURCE,'Unknown') AS MOCF_RECORD_SOURCE, 
    IFNULL(PRODUCT_CODE,'Unknown') AS MOCF_PRODUCT_CODE,
    IFNULL(CUSTOMER,'Unknown') AS MOCF_CUSTOMER,
    IMB AS MOCF_IMB,
    CID AS MOCF_COMMUNICATION_ID,
    JOB_ID AS MOCF_JOB_ID,
    SEQUENCE_NO AS MOCF_SEQUENCE_NBR, 
    QUANTITY AS MOCF_QUANTITY,
    IFNULL(HUBMEMBERMC400.TPACLIENT,'Unknown') AS M_TPA_CLIENT_ID,
    IFNULL(HUBMEMBERMC400.TPADIVISION,'Unknown') AS M_TPA_DIV_ID,
    IFNULL(HUBMEMBERMC400.TPADIVISION,'Unknown') AS M_TPA_ID,
    IFF(HUBMEMBERMC400.MEMBERNBR IS NULL, 'Unknown', 'MC400Upm') AS M_DATA_SOURCE_NAME,
    HUBMEMBERMC400.membernbr AS M_MEMBER_NBR,
    UTIL.FXN_ARRAY_HASH([MOCF_DATA_SOURCE_NAME, MOCF_RECORD_SOURCE, MOCF_PRODUCT_CODE, MOCF_CUSTOMER, MOCF_IMB, MOCF_COMMUNICATION_ID, MOCF_JOB_ID, MOCF_SEQUENCE_NBR, MOCF_QUANTITY, M_TPA_CLIENT_ID, M_TPA_DIV_ID, M_TPA_ID, M_DATA_SOURCE_NAME, M_MEMBER_NBR]) AS LNK_OCF_MEMBER_HKEY,
    UTIL.FXN_ARRAY_HASH([MOCF_DATA_SOURCE_NAME, MOCF_RECORD_SOURCE, MOCF_PRODUCT_CODE, MOCF_CUSTOMER, MOCF_IMB, MOCF_COMMUNICATION_ID, MOCF_JOB_ID, MOCF_SEQUENCE_NBR, MOCF_QUANTITY]) AS HUB_MARKETING_OCF_HKEY,
    UTIL.FXN_ARRAY_HASH([M_TPA_CLIENT_ID, M_TPA_ID, M_TPA_DIV_ID, M_DATA_SOURCE_NAME, M_MEMBER_NBR]) AS 
    HUB_MEMBER_HKEY
FROM &{IDAP_LAKE}.MEMBER_COMMUNICATIONS.PNF_CONTACT_HISTORY_DETAIL PNFCONTACTHISTORYDETAIL
    INNER JOIN &{MC400}.DWOAO.MEMBERS HUBMEMBERMC400
        ON HUBMEMBERMC400.MEMBERNBR = PNFCONTACTHISTORYDETAIL.MEMBER_NO;

!set variable_substitution=false;
