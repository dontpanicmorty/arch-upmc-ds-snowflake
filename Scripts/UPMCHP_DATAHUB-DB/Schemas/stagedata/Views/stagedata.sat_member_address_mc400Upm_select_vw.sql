CREATE OR REPLACE VIEW STAGEDATA.SAT_MEMBER_ADDRESS_MC400Upm_SELECT_VW
COMMENT = 'Source view for MC400Upm data into HUB_MEMBER_ADDRESS'
AS

SELECT
Members.TpaClient AS TPA_CLIENT_ID
,Members.TpaIdOfClient AS TPA_ID
,Members.TpaDivision AS TPA_DIV_ID
,'MC400Upm' AS DATA_SOURCE_NAME
,TRIM(Members.MemberNbr) AS MEMBER_NBR
,'Physical' AS ADDRESS_TYPE_CODE -- Physical = 1
,TRIM(Members.MemberAddress1) AS ADDRESS_LINE_1_TEXT
,NULLIF(TRIM(Members.MemberAddress2), '')  AS ADDRESS_LINE_2_TEXT
,NULLIF(TRIM(Members.MemberCity), '') AS CITY_NAME
,NULLIF(TRIM(Members.MemberState), '') AS STATE_ABBREV_NAME
,NULLIF(TRIM(Members.MemberZipCode), '') AS ZIP_CODE_NBR
,NULL AS COUNTY_NAME
,NULL AS FIPS_CODE
,NULL AS FIPS_STATE_CODE
,NULL AS FIPS_COUNTY_CODE
,NULL AS CMS_COUNTY_CODE
,NULL AS LATITUDE_NBR
,NULL AS LONGITUDE_NBR
,NULL AS CONGRESSIONAL_DISTRICT_NAME
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEMBER_NBR, ADDRESS_TYPE_CODE]) as HUB_MEMBER_ADDRESS_HKEY
FROM RAWDATA.MC400_DWOAO_MEMBERS Members
WHERE Members.MemberNbr <> '99999999901'--this is a junk catch all member number
AND TRIM(Members.MemberAddress1) <> ''
AND NOT CONTAINS(UPPER(Members.MemberAddress1), 'REMOVE') --ignore anything that has remove in it


UNION ALL

SELECT
Members.TpaClient AS TPA_CLIENT_ID
,Members.TpaIdOfClient AS TPA_ID
,Members.TpaDivision AS TPA_DIV_ID
,'MC400Upm' AS DATA_SOURCE_NAME
,TRIM(Members.MemberNbr) AS MEMBER_NBR
,'Mailing' AS ADDRESS_TYPE_CODE -- Mailing = 2
,TRIM(Members.MailingAddress1) AS ADDRESS_LINE_1_TEXT
,NULLIF(TRIM(Members.MailingAddress2), '') AS ADDRESS_LINE_2_TEXT
,NULLIF(TRIM(Members.MailingCity), '') AS CITY_NAME
,NULLIF(TRIM(Members.MailingState), '') AS STATE_ABBREV_NAME
,NULLIF(TRIM(Members.MailingZipCode), '') AS ZIP_CODE_NBR
,NULL AS COUNTY_NAME
,NULL AS FIPS_CODE
,NULL AS FIPS_STATE_CODE
,NULL AS FIPS_COUNTY_CODE
,NULL AS CMS_COUNTY_CODE
,NULL AS LATITUDE_NBR
,NULL AS LONGITUDE_NBR
,NULL AS CONGRESSIONAL_DISTRICT_NAME
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEMBER_NBR, ADDRESS_TYPE_CODE]) as HUB_MEMBER_ADDRESS_HKEY
FROM RAWDATA.MC400_DWOAO_MEMBERS Members
WHERE Members.MemberNbr <> '99999999901'--this is a junk catch all member number
AND TRIM(Members.MailingAddress1) <> ''
AND NOT CONTAINS(UPPER(Members.MailingAddress1), 'REMOVE') --ignore anything that has remove in it

UNION ALL 

SELECT
Members.TPACLIENT AS TPA_CLIENT_ID
,Members.TPAIDOFCLIENT AS TPA_ID
,Members.TPADIVISION AS TPA_DIV_ID
,'MC400Upm' AS DATA_SOURCE_NAME
,TRIM(Members.MemberNbr) AS MEMBER_NBR
,'H6' AS ADDRESS_TYPE_CODE
,TRIM(MemberHippaPrivacyData.ConfidentialAddressLine1) AS ADDRESS_LINE_1_TEXT
,NULLIF(TRIM(MemberHippaPrivacyData.ConfidentialAddressLine2), '') AS ADDRESS_LINE_2_TEXT
,NULLIF(TRIM(MemberHippaPrivacyData.ConfidentialAddressCity), '') AS CITY_NAME
,NULLIF(TRIM(MemberHippaPrivacyData.ConfidentialAddressState), '') AS STATE_ABBREV_NAME
,NULLIF(TRIM(MemberHippaPrivacyData.ConfidentialAddressZipCode), '') AS ZIP_CODE_NBR
,NULL AS COUNTY_NAME
,NULL AS FIPS_CODE
,NULL AS FIPS_STATE_CODE
,NULL AS FIPS_COUNTY_CODE
,NULL AS CMS_COUNTY_CODE
,NULL AS LATITUDE_NBR
,NULL AS LONGITUDE_NBR
,NULL AS CONGRESSIONAL_DISTRICT_NAME
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEMBER_NBR, ADDRESS_TYPE_CODE]) as HUB_MEMBER_ADDRESS_HKEY
FROM RAWDATA.MC400_DWOAO_MEMBERS Members
    JOIN RAWDATA.MC400_DWOAO_MEMBERHIPAAPRIVACYDATA MemberHippaPrivacyData
        ON (MemberHippaPrivacyData.SubscriberNumber = Members.SubscriberNbr
        AND MemberHippaPrivacyData.PersonNumber = Members.PersonNbr)
WHERE Members.MemberNbr <> '99999999901' --this is a junk catch all member number
AND MemberHippaPrivacyData.HipaaFormType = 'H6'
AND MemberHippaPrivacyData.EffectiveRecord = 'Y'
AND MemberHippaPrivacyData.ActiveRecord = 'Y'
AND TRIM(MemberHippaPrivacyData.ConfidentialAddressLine1) <> ''
;
