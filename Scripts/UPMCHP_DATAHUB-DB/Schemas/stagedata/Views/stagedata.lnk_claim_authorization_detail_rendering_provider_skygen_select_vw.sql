CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_AUTHORIZATION_DETAIL_RENDERING_PROVIDER_SKYGEN_SELECT_VW
COMMENT = 'Source view for SKYGEN data into LNK_CLAIM_AUTHORIZATION_DETAIL_RENDERING_PROVIDER'
AS
SELECT 
'N/A' AS SOURCE_KEY,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID AS AD_TPA_CLIENT_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID AS AD_TPA_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID AS AD_TPA_DIV_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME AS AD_DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR AS AD_AUTHORIZATION_NBR,
DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_LINE_NBR AS AD_AUTHORIZATION_LINE_NBR,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID AS P_TPA_CLIENT_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID AS P_TPA_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID AS P_TPA_DIV_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME AS P_DATA_SOURCE_NAME,
IFNULL(DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.RENDERING_PROVIDER_ID,'UNK') AS P_PROVIDER_ID,
UTIL.FXN_ARRAY_HASH([AD_TPA_CLIENT_ID, AD_TPA_ID, AD_TPA_DIV_ID, AD_DATA_SOURCE_NAME, AD_AUTHORIZATION_NBR, AD_AUTHORIZATION_LINE_NBR, P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS LNK_CLAIM_AUTHORIZATION_DETAIL_RENDERING_PROVIDER_HKEY,
UTIL.FXN_ARRAY_HASH([AD_TPA_CLIENT_ID, AD_TPA_ID, AD_TPA_DIV_ID, AD_DATA_SOURCE_NAME, AD_AUTHORIZATION_NBR, AD_AUTHORIZATION_LINE_NBR]) AS HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY,
UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS HUB_PROVIDER_HKEY
FROM RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL
    JOIN STAGEDATA.LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN
        ON DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.AUTHORIZATION_NBR
WHERE RENDERING_PROVIDER_ID NOT IN ('PROVIDER_-1','PROVIDER_0')

UNION ALL

SELECT 
'N/A' AS SOURCE_KEY,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID AS AD_TPA_CLIENT_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID AS AD_TPA_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID AS AD_TPA_DIV_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME AS AD_DATA_SOURCE_NAME,
SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER AS AD_AUTHORIZATION_NBR,
COALESCE(SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.ITEM_NUMBER, 'N/A') AS AD_AUTHORIZATION_LINE_NBR,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID AS P_TPA_CLIENT_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID AS P_TPA_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID AS P_TPA_DIV_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME AS P_DATA_SOURCE_NAME,
IFNULL(CONCAT('PROVIDER_', SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.PROVIDER_ID),'UNK') AS P_PROVIDER_ID,
UTIL.FXN_ARRAY_HASH([AD_TPA_CLIENT_ID, AD_TPA_ID, AD_TPA_DIV_ID, AD_DATA_SOURCE_NAME, AD_AUTHORIZATION_NBR, AD_AUTHORIZATION_LINE_NBR, P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS LNK_CLAIM_AUTHORIZATION_DETAIL_RENDERING_PROVIDER_HKEY,
UTIL.FXN_ARRAY_HASH([AD_TPA_CLIENT_ID, AD_TPA_ID, AD_TPA_DIV_ID, AD_DATA_SOURCE_NAME, AD_AUTHORIZATION_NBR, AD_AUTHORIZATION_LINE_NBR]) AS HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY,
UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS HUB_PROVIDER_HKEY
FROM RAWDATA.SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW
    JOIN STAGEDATA.LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN
        ON (SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.AUTHORIZATION_NBR)
WHERE SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.PROVIDER_ID IS NOT NULL
AND SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.PROVIDER_ID NOT IN ('-1','0')
AND SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER NOT IN (SELECT AUTHORIZATION_NBR FROM RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL)
;
