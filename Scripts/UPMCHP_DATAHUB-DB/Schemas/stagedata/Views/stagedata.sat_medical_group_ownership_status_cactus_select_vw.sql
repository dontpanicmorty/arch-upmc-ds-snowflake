CREATE OR REPLACE VIEW STAGEDATA.SAT_MEDICAL_GROUP_OWNERSHIP_STATUS_CACTUS_SELECT_VW
COMMENT = 'Source view for Cactus data into SAT_MEDICAL_GROUP_OWNERSHIP'
AS
WITH DUPES AS (
    SELECT G.ID,COUNT(*) AS CNT
		FROM RAWDATA.CACTUS_GROUPS G
		GROUP BY G.ID HAVING COUNT(*) > 1
)

SELECT DISTINCT
      '000001' AS TPA_CLIENT_ID
    , '000001' AS TPA_ID
    , '0001' AS TPA_DIV_ID
    , 'Cactus' AS DATA_SOURCE_NAME
    , TRIM(CACTUS_GROUPS.ID) as MEDICAL_GROUP_ID
	, TRIM(CACTUS_REFTABLE.DESCRIPTION) AS OWNERSHIP_NAME
	, IFF(TRIM(CACTUS_REFTABLE.DESCRIPTION) = 'Owned', TRUE, FALSE) AS UPMC_OWNERSHIP_IND
	, IFF(TRIM(CACTUS_REFTABLE.DESCRIPTION) = 'Joint Venture', TRUE, FALSE) AS JOINT_OWNERSHIP_IND
	, IFF(TRIM(CACTUS_REFTABLE.DESCRIPTION) NOT IN ('Owned', 'Joint Venture'), TRUE, FALSE) AS NOT_OWNED_IND
	, UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY 
	, UTIL.FXN_ARRAY_HASH([OWNERSHIP_NAME, UPMC_OWNERSHIP_IND, JOINT_OWNERSHIP_IND, NOT_OWNED_IND])  AS HASH_DIFF
    
FROM
    RAWDATA.CACTUS_GROUPS AS CACTUS_GROUPS
LEFT JOIN
    RAWDATA.CACTUS_REFTABLE CACTUS_REFTABLE
	ON CACTUS_GROUPS.USERDEF_RTK1 = CACTUS_REFTABLE.REFTABLE_K
LEFT JOIN 
    RAWDATA.CACTUS_GROUPADDRESS  CACTUS_GROUPADDRESS 
	ON CACTUS_GROUPS.GROUP_K = CACTUS_GROUPADDRESS.GROUP_K
LEFT JOIN
    DUPES AS DUPES
    ON CACTUS_GROUPS.ID = DUPES.ID
WHERE
	NULLIF(TRIM(CACTUS_GROUPS.ID), '') IS NOT NULL
AND NULLIF(TRIM(CACTUS_GROUPADDRESS.GROUP_K), '') IS NOT NULL
AND DUPES.ID IS NULL
;
