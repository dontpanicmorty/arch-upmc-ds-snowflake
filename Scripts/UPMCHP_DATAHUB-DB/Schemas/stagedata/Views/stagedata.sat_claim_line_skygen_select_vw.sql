CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_LINE_SKYGEN_SELECT_VW
COMMENT = 'This is a SAT View containing Claim Line data'
AS

SELECT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID,
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR,
CLAIM_LINE_NBR,CLAIM_LINE_SEQ_NBR,
PROCEDURE_ADJ_CODE,
'E' AS CLAIM_TYPE_CODE, --Encounter
CLAIM_RECEIVED_DATE,
CASE
    WHEN (PROCEDURE_CODE LIKE '-%' OR PROCEDURE_CODE = '0') THEN NULL
    ELSE PROCEDURE_CODE
END AS PROCEDURE_CODE,
PROCEDURE_QTY AS PROCEDURE_QUANTITY,
SERVICE_BEGIN_DATE AS SERVICE_BEGIN_DATE,
SERVICE_END_DATE AS SERVICE_END_DATE,
CLAIM_RECEIVED_DATE AS ADD_DATE,
PAY_STATUS AS ACCOUNTS_PAYABLE_PAY_STATUS_CODE,
NULL AS ADJUDICATION_STATUS,
AP_POSTING_DATE,
DWSKYGEN_CLAIM_DETAIL.BENEFIT_CATEGORY_CODE AS BENEFIT_CATEGORY_CODE,
DWSKYGEN_CLAIM_DETAIL.BENEFIT_LEVEL_CODE AS BENEFIT_LEVEL_CODE,
NULL AS BUCKET_STATUS_FLAG,
CHECK_DATE AS CHECK_DATE,
CHECK_NBR AS CHECK_NUMBER,
NULL AS CLAIM_DAY_CNT,
CLEAN_CLAIM_IND,
DWSKYGEN_CLAIM_HEADER.COMPANY_CODE,
NULL AS DENIED_DAY_CNT,
NULL AS ELIGIBILITY_MISC_STATUS_CODE,
DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR AS FORM_NUMBER,
NULL AS GL_DISTRIBUTION_CODE,
NULL AS IS_PROCESSING_COMPLETE,
NULL AS KEY_TO_SOURCE_FILE,
CASE 
    WHEN DWSKYGEN_CLAIM_DETAIL.LOCATION_TYPE_CODE = '2' THEN 'N'
    ELSE DWSKYGEN_CLAIM_DETAIL.LOCATION_TYPE_CODE
END AS LOCATION_CODE,
PAY_STATUS AS PAY_STATUS_CODE,
CHECK_DATE AS PAYMENT_DATE,
TOOTH_QUADRANT,
NULL AS REVENUE_CODE,
NULL AS SERVICE_CNT,
NULL AS SERVICE_REASON_CODE,
CASE
    WHEN (DWSKYGEN_CLAIM_DETAIL.PAY_STATUS IS NULL
         OR DWSKYGEN_CLAIM_DETAIL.ALLOWED_AMOUNT IS NULL
         OR DWSKYGEN_CLAIM_DETAIL.NOT_COVERED_AMOUNT IS NULL
         OR DWSKYGEN_CLAIM_DETAIL.PAID_AMOUNT IS NULL
         OR DWSKYGEN_CLAIM_DETAIL.DEDUCTIBLE_AMOUNT IS NULL
         OR DWSKYGEN_CLAIM_DETAIL.THIRD_PARTY_PAID_AMOUNT IS NULL
         ) THEN 'U'
    WHEN DWSKYGEN_CLAIM_DETAIL.PAY_STATUS IN ('1','2') THEN 'I' 
    WHEN (DWSKYGEN_CLAIM_DETAIL.PAID_AMOUNT <> 0
        OR DWSKYGEN_CLAIM_DETAIL.DEDUCTIBLE_AMOUNT <> 0
        OR (DWSKYGEN_CLAIM_DETAIL.ALLOWED_AMOUNT <> 0 AND DWSKYGEN_CLAIM_DETAIL.ALLOWED_AMOUNT <> DWSKYGEN_CLAIM_DETAIL.NOT_COVERED_AMOUNT)
        OR (DWSKYGEN_CLAIM_DETAIL.THIRD_PARTY_PAID_AMOUNT <> 0 AND DWSKYGEN_CLAIM_DETAIL.NOT_COVERED_AMOUNT = 0)
        ) THEN 'P'
     ELSE 'D'
END AS SERVICE_STATUS_CODE,
CASE
    WHEN (DWSKYGEN_CLAIM_DETAIL.PAY_STATUS IS NULL
         OR DWSKYGEN_CLAIM_DETAIL.ALLOWED_AMOUNT IS NULL
         OR DWSKYGEN_CLAIM_DETAIL.NOT_COVERED_AMOUNT IS NULL
         OR DWSKYGEN_CLAIM_DETAIL.PAID_AMOUNT IS NULL
         OR DWSKYGEN_CLAIM_DETAIL.DEDUCTIBLE_AMOUNT IS NULL
         OR DWSKYGEN_CLAIM_DETAIL.THIRD_PARTY_PAID_AMOUNT IS NULL
         ) THEN 'Unknown'
    WHEN DWSKYGEN_CLAIM_DETAIL.PAY_STATUS IN ('1','2') THEN 'InProcess' 
    WHEN (DWSKYGEN_CLAIM_DETAIL.PAID_AMOUNT <> 0
        OR DWSKYGEN_CLAIM_DETAIL.DEDUCTIBLE_AMOUNT <> 0
        OR (DWSKYGEN_CLAIM_DETAIL.ALLOWED_AMOUNT <> 0 AND DWSKYGEN_CLAIM_DETAIL.ALLOWED_AMOUNT <> DWSKYGEN_CLAIM_DETAIL.NOT_COVERED_AMOUNT)
        OR (DWSKYGEN_CLAIM_DETAIL.THIRD_PARTY_PAID_AMOUNT <> 0 AND DWSKYGEN_CLAIM_DETAIL.NOT_COVERED_AMOUNT = 0)
        ) THEN 'Paid' 
     ELSE 'Denied'
END AS SERVICE_STATUS_DESC,
CASE 
    WHEN DWSKYGEN_CLAIM_DETAIL.PLACE_OF_SERVICE_TYPE = '0' THEN 'NA'
    WHEN DWSKYGEN_CLAIM_DETAIL.PLACE_OF_SERVICE_TYPE = '1' THEN 'F'
    WHEN DWSKYGEN_CLAIM_DETAIL.PLACE_OF_SERVICE_TYPE = '2' THEN 'P'
    ELSE DWSKYGEN_CLAIM_DETAIL.PLACE_OF_SERVICE_TYPE
END AS SERVICE_TYPE_CODE,
CASE
    WHEN DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR = 0 THEN 'C'
    WHEN DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR >= 1 THEN 'A'
    ELSE NULL
END AS TRANSACTION_TYPE_CODE,
CASE
    WHEN DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR = 0 THEN 'Charge'
    WHEN DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR >= 1 THEN 'Adjustment'
    ELSE NULL
END AS TRANSACTION_TYPE_DESC,
DWSKYGEN_CLAIM_DETAIL.LAST_UPDATED_DATETIME AS SOURCE_LAST_UPDATED_DATETIME,
IFF(DWSKYGEN_CLAIM_DETAIL.TOOTH_ID = 'NA', NULL ,DWSKYGEN_CLAIM_DETAIL.TOOTH_ID) AS TOOTH_ID,
IFF(DWSKYGEN_CLAIM_DETAIL.TOOTH_ARCH = 'NA', NULL, DWSKYGEN_CLAIM_DETAIL.TOOTH_ARCH) AS TOOTH_ARCH,
CASE 
    WHEN TO_NUMBER(DWSKYGEN_CLAIM_DETAIL.MEMBER_AGE) < 0 THEN NULL 
    ELSE TO_NUMBER(DWSKYGEN_CLAIM_DETAIL.MEMBER_AGE)
END AS MEMBER_AGE_NBR,
DWSKYGEN_CLAIM_DETAIL.AUTH_NBR AS AUTHORIZATION_NBR,
IFF(DWSKYGEN_CLAIM_DETAIL.TOOTH_SURFACE_CODE_LIST = 'NA', NULL, STRTOK_TO_ARRAY(TOOTH_SURFACE_CODE_LIST, ',')) AS TOOTH_SURFACE_ARRAY,
NULL AS HCPCS_CODE,
NULL AS CMS_CURRENT_ITERATION_FLAG,

UTIL.FXN_ARRAY_HASH([LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID, LKP_CLAIM_MEMBER_SKYGEN.TPA_ID, LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID, DATA_SOURCE_NAME, DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR, CLAIM_LINE_NBR,CLAIM_LINE_SEQ_NBR, PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY,
UTIL.FXN_ARRAY_HASH(
    [CLAIM_TYPE_CODE
    ,CLAIM_RECEIVED_DATE
    ,CASE
        WHEN (PROCEDURE_CODE LIKE '-%' OR PROCEDURE_CODE = '0') THEN NULL
        ELSE PROCEDURE_CODE
    END
    ,PROCEDURE_QUANTITY
    ,SERVICE_BEGIN_DATE
    ,SERVICE_END_DATE
    ,ADD_DATE
    ,ACCOUNTS_PAYABLE_PAY_STATUS_CODE
    ,ADJUDICATION_STATUS
    ,AP_POSTING_DATE
    ,BENEFIT_CATEGORY_CODE
    ,BENEFIT_LEVEL_CODE
    ,BUCKET_STATUS_FLAG
    ,CHECK_DATE
    ,CHECK_NUMBER
    ,CLAIM_DAY_CNT
    ,CLEAN_CLAIM_IND
    ,COMPANY_CODE
    ,DENIED_DAY_CNT
    ,ELIGIBILITY_MISC_STATUS_CODE
    ,FORM_NUMBER
    ,GL_DISTRIBUTION_CODE
    ,IS_PROCESSING_COMPLETE
    ,KEY_TO_SOURCE_FILE
    ,LOCATION_CODE
    ,PAY_STATUS_CODE
    ,PAYMENT_DATE 
    ,TOOTH_QUADRANT
    ,REVENUE_CODE
    ,SERVICE_CNT
    ,SERVICE_REASON_CODE
    ,SERVICE_STATUS_CODE
    ,SERVICE_STATUS_DESC
    ,SERVICE_TYPE_CODE
    ,TRANSACTION_TYPE_CODE
    ,TRANSACTION_TYPE_DESC
    ,SOURCE_LAST_UPDATED_DATETIME
    ,TOOTH_ID
    ,TOOTH_ARCH
    ,MEMBER_AGE_NBR
    ,AUTHORIZATION_NBR
    ,TOOTH_SURFACE_ARRAY
    ,HCPCS_CODE
    ,CMS_CURRENT_ITERATION_FLAG]
) AS HASH_DIFF

FROM RAWDATA.DWSKYGEN_CLAIM_DETAIL
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (RAWDATA.DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
    JOIN RAWDATA.DWSKYGEN_CLAIM_HEADER
        ON (DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR = DWSKYGEN_CLAIM_HEADER.CLAIM_NBR)

UNION ALL

SELECT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID,
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME,
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO AS CLAIM_NBR,
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.ITEM_NO AS CLAIM_LINE_NBR,
UTIL.FXN_ARRAY_HASH([SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.BILLED_AMT]) AS CLAIM_LINE_SEQ_NBR,
'N/A' AS PROCEDURE_ADJ_CODE,
'E' AS CLAIM_TYPE_CODE, --Encounter
NULL AS CLAIM_RECEIVED_DATE,
IFF(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.PROC_CODE = '0', NULL, SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.PROC_CODE) AS PROCEDURE_CODE,
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.QUANTITY AS PROCEDURE_QUANTITY,
TO_DATE(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.SERVICE_DT, 'YYYYMMDD') AS SERVICE_BEGIN_DATE,
TO_DATE(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.SERVICE_DT, 'YYYYMMDD') AS SERVICE_END_DATE,
NULL AS ADD_DATE,
CASE UPPER(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_TYPE)  -- This logic is done to match the codes on the files with dwskygen data
    WHEN 'P' THEN '3' --Paid
    WHEN 'D' THEN '-3' --Denied 
    WHEN 'A' THEN '-4' --Recoded (Adjustment)
    ELSE NULL
END AS ACCOUNTS_PAYABLE_PAY_STATUS_CODE,
NULL AS ADJUDICATION_STATUS,
TO_DATE(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.ADJUDICATION_DT, 'YYYYMMDD') AS AP_POSTING_DATE,
'TBD' AS BENEFIT_CATEGORY_CODE,  --Done to match what is done with DWSKYGEN
NULL AS BENEFIT_LEVEL_CODE,
NULL AS BUCKET_STATUS_FLAG,
TO_DATE(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.ADJUDICATION_DT, 'YYYYMMDD') AS CHECK_DATE,
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CHECK_NO AS CHECK_NUMBER,
NULL AS CLAIM_DAY_CNT,
'Y' AS CLEAN_CLAIM_IND,
NULL AS COMPANY_CODE,
NULL AS DENIED_DAY_CNT,
NULL AS ELIGIBILITY_MISC_STATUS_CODE,
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO AS FORM_NUMBER,
NULL AS GL_DISTRIBUTION_CODE,
NULL AS IS_PROCESSING_COMPLETE,
NULL AS KEY_TO_SOURCE_FILE,
'N' AS LOCATION_CODE, -- Not Applicable
CASE UPPER(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_TYPE)  -- This logic is done to match the codes on the files with dwskygen data
    WHEN 'P' THEN '3' --Paid
    WHEN 'D' THEN '-3' --Denied 
    WHEN 'A' THEN '-4' --Recoded (Adjustment)
    ELSE NULL
END AS PAY_STATUS_CODE,
TO_DATE(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.ADJUDICATION_DT, 'YYYYMMDD') AS PAYMENT_DATE,
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.QUAD AS TOOTH_QUADRANT,
NULL AS REVENUE_CODE,
NULL AS SERVICE_CNT,
NULL AS SERVICE_REASON_CODE,
CASE WHEN UPPER(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_TYPE) IN ('P','D')
    THEN SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_TYPE
    ELSE 'U'
END AS SERVICE_STATUS_CODE,
CASE UPPER(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_TYPE)
    WHEN 'P' THEN 'Paid'
    WHEN 'D' THEN 'Denied'
    ELSE 'Unknown'
END AS SERVICE_STATUS_DESC,
'P' AS SERVICE_TYPE_CODE, --Professional Service
CASE UPPER(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_TYPE)
    WHEN 'P' THEN 'C'
    WHEN 'A' THEN 'A'
    ELSE NULL
END AS TRANSACTION_TYPE_CODE,
CASE UPPER(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_TYPE)
    WHEN 'P' THEN 'Charge'
    WHEN 'A' THEN 'Adjustment'
    ELSE NULL
END AS TRANSACTION_TYPE_DESC,
NULL AS SOURCE_LAST_UPDATED_DATETIME,
IFF(UPPER(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.TOOTH_ID) = 'NA', NULL, SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.TOOTH_ID) AS TOOTH_ID,
IFF(UPPER(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.ARCH) = 'NA', NULL, SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.ARCH) AS TOOTH_ARCH,
CASE 
    WHEN TO_NUMBER(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.AGE) < 0 THEN NULL 
    ELSE TO_NUMBER(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.AGE)
END AS MEMBER_AGE_NBR,
NULL AS AUTHORIZATION_NBR,
IFF(UPPER(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.SURFACE_1) = 'NA', TO_ARRAY(NULL), ARRAY_CONSTRUCT_COMPACT
    (
        SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.SURFACE_1,
        SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.SURFACE_2,
        SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.SURFACE_3,
        SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.SURFACE_4,
        SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.SURFACE_5
    )
) AS TOOTH_SURFACE_ARRAY,
NULL AS HCPCS_CODE,
NULL AS CMS_CURRENT_ITERATION_FLAG,

UTIL.FXN_ARRAY_HASH([LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID, LKP_CLAIM_MEMBER_SKYGEN.TPA_ID, LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID, DATA_SOURCE_NAME, SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO, SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.ITEM_NO, CLAIM_LINE_SEQ_NBR, PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY,
UTIL.FXN_ARRAY_HASH(
    [CLAIM_TYPE_CODE
    ,CLAIM_RECEIVED_DATE
    ,PROCEDURE_CODE
    ,PROCEDURE_QUANTITY
    ,SERVICE_BEGIN_DATE
    ,SERVICE_END_DATE
    ,ADD_DATE
    ,ACCOUNTS_PAYABLE_PAY_STATUS_CODE
    ,ADJUDICATION_STATUS
    ,AP_POSTING_DATE
    ,BENEFIT_CATEGORY_CODE
    ,BENEFIT_LEVEL_CODE
    ,BUCKET_STATUS_FLAG
    ,CHECK_DATE
    ,CHECK_NO
    ,CLAIM_DAY_CNT
    ,CLEAN_CLAIM_IND
    ,COMPANY_CODE
    ,DENIED_DAY_CNT
    ,ELIGIBILITY_MISC_STATUS_CODE
    ,FORM_NUMBER
    ,GL_DISTRIBUTION_CODE
    ,IS_PROCESSING_COMPLETE
    ,KEY_TO_SOURCE_FILE
    ,LOCATION_CODE
    ,PAY_STATUS_CODE
    ,PAYMENT_DATE
    ,TOOTH_QUADRANT
    ,REVENUE_CODE
    ,SERVICE_CNT
    ,SERVICE_REASON_CODE
    ,SERVICE_STATUS_CODE
    ,SERVICE_STATUS_DESC
    ,SERVICE_TYPE_CODE
    ,TRANSACTION_TYPE_CODE
    ,TRANSACTION_TYPE_DESC
    ,SOURCE_LAST_UPDATED_DATETIME
    ,TOOTH_ID
    ,TOOTH_ARCH
    ,MEMBER_AGE_NBR
    ,AUTHORIZATION_NBR
    ,TOOTH_SURFACE_ARRAY
    ,HCPCS_CODE
    ,CMS_CURRENT_ITERATION_FLAG]
) AS HASH_DIFF

FROM RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)    
WHERE SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO NOT IN (SELECT CLAIM_NBR FROM RAWDATA.DWSKYGEN_CLAIM_HEADER )
;
