!set variable_substitution=true;
CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_RIDER_MC400Dnt_SELECT_VW
COMMENT='This is a LNK View containing Claim Rider  data'
AS
SELECT DISTINCT
'000001' AS C_TPA_CLIENT_ID
,'000001' AS C_TPA_ID
,'0001' AS C_TPA_DIV_ID
,'MC400Dnt' AS C_DATA_SOURCE_NAME
,CLAIMS.ClaimNbr AS C_CLAIM_NBR
,'000001' AS R_TPA_CLIENT_ID
,'000001' AS R_TPA_ID
,'0001' AS R_TPA_DIV_ID
,'MC400Dnt' AS R_DATA_SOURCE_NAME
,RIDER_CODES.VALUE::string AS R_RIDER_CODE
,'000001' AS MG_TPA_CLIENT_ID
,'000001' AS MG_TPA_ID
,'0001' AS MG_TPA_DIV_ID
,'MC400Upm' AS MG_DATA_SOURCE_NAME
,GroupNbr AS MG_GROUP_NBR
,SubGroup AS MG_SUB_GROUP_NBR
,UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID ,C_TPA_ID, C_TPA_DIV_ID,C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY
,UTIL.FXN_ARRAY_HASH([R_TPA_CLIENT_ID, R_TPA_ID, R_TPA_DIV_ID, R_DATA_SOURCE_NAME, R_RIDER_CODE]) AS HUB_RIDER_HKEY
,UTIL.FXN_ARRAY_HASH([MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_GROUP_NBR, MG_SUB_GROUP_NBR]) AS HUB_MEMBERSHIP_GROUP_HKEY
,UTIL.FXN_ARRAY_HASH(
        [C_TPA_CLIENT_ID
        ,C_TPA_ID
        ,C_TPA_DIV_ID
        ,C_DATA_SOURCE_NAME
        ,C_CLAIM_NBR
        ,R_TPA_CLIENT_ID
        ,R_TPA_ID
        ,R_TPA_DIV_ID
        ,R_DATA_SOURCE_NAME
        ,R_RIDER_CODE
        ,MG_TPA_CLIENT_ID
        ,MG_TPA_ID
        ,MG_TPA_DIV_ID
        ,MG_DATA_SOURCE_NAME
        ,MG_GROUP_NBR
        ,MG_SUB_GROUP_NBR]
) AS LNK_CLAIM_RIDER_HKEY

FROM &{MC400}.DWDNV.CLAIMS
        ,LATERAL FLATTEN(input => (REGEXP_SUBSTR_ALL(REPLACE(CLAIMS.RIDERS,' ',''), '.{1,2}'))) RIDER_CODES  --split riders by every two characters
WHERE MemberNbr <> '99999999901' --Exclude Generic Default Member Claims
;

 !set variable_substitution=false;