CREATE OR REPLACE VIEW STAGEDATA.LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL_VW
COMMENT = 'Information on Prescribers on Pharmacy Claims'
AS

WITH PRESCRIBER_IDS as (
SELECT DISTINCT PRESCRIBER_IDENTIFIER, PRESCRIBER_LAST_NAME
FROM STAGEDATA.LKP_CLAIM_PHARMACY_CLAIM
WHERE PRESCRIBER_IDENTIFIER IS NOT NULL
)

,PRESCRIBER_IDENTIFIER_CTE AS (

SELECT DISTINCT PRESCRIBER_IDS.PRESCRIBER_IDENTIFIER AS PRESCRIBER_ID,
COALESCE(IFF(CMS_NPI_VW.NPI IS NOT NULL, 'N',NULL), IFNULL(CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.PRESCRIBER_SOURCE_CODE,'P')) AS PRESCRIBER_SOURCE_CODE,
COALESCE(CMS_NPI_VW.ENTITY_TYPE_CODE, NULLIF(CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.PRESCRIBER_NPI_TYPE, 'UNKNOWN')) AS PRESCRIBER_NPI_TYPE,
COALESCE(CMS_NPI_VW.PROVIDER_ORGANIZATION_NAME, CONCAT(CMS_NPI_VW.PROVIDER_LAST_NAME, ', ', CMS_NPI_VW.PROVIDER_FIRST_NAME), IFF(CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.PRESCRIBER_NAME<> 'UNKNOWN', CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.PRESCRIBER_NAME, NULL), 'UNKNOWN') AS PRESCRIBER_NAME,

CASE
    WHEN CMS_NPI_VW.PROVIDER_FIRST_LINE_BUSINESS_MAILING_ADDRESS IS NOT NULL THEN CMS_NPI_VW.PROVIDER_FIRST_LINE_BUSINESS_MAILING_ADDRESS
    ELSE NULLIF(CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.MAILING_ADDRESS_LINE_PRIMARY, 'UNKNOWN')
END AS MAILING_ADDRESS_LINE_PRIMARY,

CASE
    WHEN CMS_NPI_VW.PROVIDER_FIRST_LINE_BUSINESS_MAILING_ADDRESS IS NOT NULL THEN CMS_NPI_VW.PROVIDER_SECOND_LINE_BUSINESS_MAILING_ADDRESS
    ELSE NULLIF(CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.MAILING_ADDRESS_LINE_SECONDARY, 'UNKNOWN')
END AS MAILING_ADDRESS_LINE_SECONDARY,

CASE
    WHEN CMS_NPI_VW.PROVIDER_FIRST_LINE_BUSINESS_MAILING_ADDRESS IS NOT NULL THEN CMS_NPI_VW.PROVIDER_BUSINESS_MAILING_ADDRESS_CITY_NAME
    ELSE NULLIF(CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.MAILING_ADDRESS_CITY, 'UNKNOWN')
END AS MAILING_ADDRESS_CITY,

CASE
    WHEN CMS_NPI_VW.PROVIDER_FIRST_LINE_BUSINESS_MAILING_ADDRESS IS NOT NULL THEN CMS_NPI_VW.PROVIDER_BUSINESS_MAILING_ADDRESS_STATE_NAME
    ELSE NULLIF(CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.MAILING_ADDRESS_STATE, 'UNKNOWN')
END AS MAILING_ADDRESS_STATE,

CASE
    WHEN CMS_NPI_VW.PROVIDER_FIRST_LINE_BUSINESS_MAILING_ADDRESS IS NOT NULL THEN CMS_NPI_VW.PROVIDER_BUSINESS_MAILING_ADDRESS_POSTAL_CODE
    ELSE NULLIF(CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.MAILING_ADDRESS_ZIP_CODE, 'UNKNOWN')
END AS MAILING_ADDRESS_ZIP_CODE,

CASE
    WHEN CMS_NPI_VW.PROVIDER_FIRST_LINE_BUSINESS_MAILING_ADDRESS IS NOT NULL THEN CMS_NPI_VW.PROVIDER_BUSINESS_MAILING_ADDRESS_TELEPHONE_NUMBER
    ELSE NULLIF(CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.MAILING_ADDRESS_TELEPHONE_NBR, 'UNKNOWN')
END AS MAILING_ADDRESS_TELEPHONE_NBR,

CASE
    WHEN CMS_NPI_VW.PROVIDER_FIRST_LINE_BUSINESS_MAILING_ADDRESS IS NOT NULL THEN CMS_NPI_VW.PROVIDER_BUSINESS_MAILING_ADDRESS_FAX_NUMBER
    ELSE NULLIF(CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.MAILING_ADDRESS_FAX_NBR, 'UNKNOWN')
END AS MAILING_ADDRESS_FAX_NBR,

CASE
    WHEN CMS_NPI_VW.PROVIDER_FIRST_LINE_BUSINESS_PRACTICE_LOCATION_ADDRESS IS NOT NULL THEN CMS_NPI_VW.PROVIDER_FIRST_LINE_BUSINESS_PRACTICE_LOCATION_ADDRESS
    ELSE NULLIF(CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.PRACTICE_ADDRESS_LINE_PRIMARY, 'UNKNOWN')
END AS PRACTICE_ADDRESS_LINE_PRIMARY,

CASE 
    WHEN CMS_NPI_VW.PROVIDER_FIRST_LINE_BUSINESS_PRACTICE_LOCATION_ADDRESS IS NOT NULL THEN CMS_NPI_VW.PROVIDER_SECOND_LINE_BUSINESS_PRACTICE_LOCATION_ADDRESS
    ELSE NULLIF(CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.PRACTICE_ADDRESS_LINE_SECONDARY, 'UNKNOWN')
END AS PRACTICE_ADDRESS_LINE_SECONDARY,

CASE 
    WHEN CMS_NPI_VW.PROVIDER_FIRST_LINE_BUSINESS_PRACTICE_LOCATION_ADDRESS IS NOT NULL THEN CMS_NPI_VW.PROVIDER_BUSINESS_PRACTICE_LOCATION_ADDRESS_CITY_NAME
    ELSE NULLIF(CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.PRACTICE_ADDRESS_CITY, 'UNKNOWN')
END AS PRACTICE_ADDRESS_CITY,

CASE 
    WHEN CMS_NPI_VW.PROVIDER_FIRST_LINE_BUSINESS_PRACTICE_LOCATION_ADDRESS IS NOT NULL THEN CMS_NPI_VW.PROVIDER_BUSINESS_PRACTICE_LOCATION_ADDRESS_STATE_NAME
    ELSE NULLIF(CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.PRACTICE_ADDRESS_STATE, 'UNKNOWN')
END AS PRACTICE_ADDRESS_STATE,

CASE 
    WHEN CMS_NPI_VW.PROVIDER_FIRST_LINE_BUSINESS_PRACTICE_LOCATION_ADDRESS IS NOT NULL THEN CMS_NPI_VW.PROVIDER_BUSINESS_PRACTICE_LOCATION_ADDRESS_POSTAL_CODE
    ELSE NULLIF(CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.PRACTICE_ADDRESS_ZIP_CODE, 'UNKNOWN')
END AS PRACTICE_ADDRESS_ZIP_CODE,

CASE 
    WHEN CMS_NPI_VW.PROVIDER_FIRST_LINE_BUSINESS_PRACTICE_LOCATION_ADDRESS IS NOT NULL THEN CMS_NPI_VW.PROVIDER_BUSINESS_PRACTICE_LOCATION_ADDRESS_TELEPHONE_NUMBER
    ELSE NULLIF(CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.PRACTICE_ADDRESS_TELEPHONE_NBR, 'UNKNOWN')
END AS PRACTICE_ADDRESS_TELEPHONE_NBR,

CASE 
    WHEN CMS_NPI_VW.PROVIDER_FIRST_LINE_BUSINESS_PRACTICE_LOCATION_ADDRESS IS NOT NULL THEN CMS_NPI_VW.PROVIDER_BUSINESS_PRACTICE_LOCATION_ADDRESS_FAX_NUMBER
    ELSE NULLIF(CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.PRACTICE_ADDRESS_FAX_NBR, 'UNKNOWN')
END AS PRACTICE_ADDRESS_FAX_NBR,

CASE
    WHEN CMS_NPI_VW.HEALTHCARE_PROVIDER_PRIMARY_TAXONOMY_SWITCH_1 = 'Y' THEN HEALTHCARE_PROVIDER_TAXONOMY_CODE_1
    WHEN CMS_NPI_VW.HEALTHCARE_PROVIDER_PRIMARY_TAXONOMY_SWITCH_2 = 'Y' THEN HEALTHCARE_PROVIDER_TAXONOMY_CODE_2
    WHEN CMS_NPI_VW.HEALTHCARE_PROVIDER_PRIMARY_TAXONOMY_SWITCH_3 = 'Y' THEN HEALTHCARE_PROVIDER_TAXONOMY_CODE_3 
    WHEN CMS_NPI_VW.HEALTHCARE_PROVIDER_PRIMARY_TAXONOMY_SWITCH_4 = 'Y' THEN HEALTHCARE_PROVIDER_TAXONOMY_CODE_4 
    WHEN CMS_NPI_VW.HEALTHCARE_PROVIDER_PRIMARY_TAXONOMY_SWITCH_5 = 'Y' THEN HEALTHCARE_PROVIDER_TAXONOMY_CODE_5 
    WHEN CMS_NPI_VW.HEALTHCARE_PROVIDER_PRIMARY_TAXONOMY_SWITCH_6 = 'Y' THEN HEALTHCARE_PROVIDER_TAXONOMY_CODE_6 
    WHEN CMS_NPI_VW.HEALTHCARE_PROVIDER_PRIMARY_TAXONOMY_SWITCH_7 = 'Y' THEN HEALTHCARE_PROVIDER_TAXONOMY_CODE_7 
    WHEN CMS_NPI_VW.HEALTHCARE_PROVIDER_PRIMARY_TAXONOMY_SWITCH_8 = 'Y' THEN HEALTHCARE_PROVIDER_TAXONOMY_CODE_8 
    WHEN CMS_NPI_VW.HEALTHCARE_PROVIDER_PRIMARY_TAXONOMY_SWITCH_9 = 'Y' THEN HEALTHCARE_PROVIDER_TAXONOMY_CODE_9 
    WHEN CMS_NPI_VW.HEALTHCARE_PROVIDER_PRIMARY_TAXONOMY_SWITCH_10 = 'Y' THEN HEALTHCARE_PROVIDER_TAXONOMY_CODE_10 
    WHEN CMS_NPI_VW.HEALTHCARE_PROVIDER_PRIMARY_TAXONOMY_SWITCH_11 = 'Y' THEN HEALTHCARE_PROVIDER_TAXONOMY_CODE_11
    WHEN CMS_NPI_VW.HEALTHCARE_PROVIDER_PRIMARY_TAXONOMY_SWITCH_12 = 'Y' THEN HEALTHCARE_PROVIDER_TAXONOMY_CODE_12 
    WHEN CMS_NPI_VW.HEALTHCARE_PROVIDER_PRIMARY_TAXONOMY_SWITCH_13 = 'Y' THEN HEALTHCARE_PROVIDER_TAXONOMY_CODE_13
    WHEN CMS_NPI_VW.HEALTHCARE_PROVIDER_PRIMARY_TAXONOMY_SWITCH_14 = 'Y' THEN HEALTHCARE_PROVIDER_TAXONOMY_CODE_14 
    WHEN CMS_NPI_VW.HEALTHCARE_PROVIDER_PRIMARY_TAXONOMY_SWITCH_15 = 'Y' THEN HEALTHCARE_PROVIDER_TAXONOMY_CODE_15
    ELSE NULLIF(CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.PRIMARY_TAXONOMY_CODE,'UNKNOWN')
END AS PRIMARY_TAXONOMY_CODE
FROM PRESCRIBER_IDS
LEFT JOIN RAWDATA.CMS_NPI_VW
    ON (PRESCRIBER_IDS.PRESCRIBER_IDENTIFIER = CMS_NPI_VW.NPI)
LEFT JOIN RAWDATA.CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER
    ON (PRESCRIBER_IDS.PRESCRIBER_IDENTIFIER = CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER.PRESCRIBER_ID)
--need full case statement due to its alias being an explicitly defined field in CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER
)

SELECT  CURRENT_TIMESTAMP() AS INSERT_DATETIME,
        PRESCRIBER_ID,
        PRESCRIBER_SOURCE_CODE,
        PRESCRIBER_NPI_TYPE,
        PRESCRIBER_NAME,
        MAILING_ADDRESS_LINE_PRIMARY,
        MAILING_ADDRESS_LINE_SECONDARY,
        MAILING_ADDRESS_CITY,
        MAILING_ADDRESS_STATE,
        MAILING_ADDRESS_ZIP_CODE,
        MAILING_ADDRESS_TELEPHONE_NBR,
        MAILING_ADDRESS_FAX_NBR,
        PRACTICE_ADDRESS_LINE_PRIMARY,
        PRACTICE_ADDRESS_LINE_SECONDARY,
        PRACTICE_ADDRESS_CITY,
        PRACTICE_ADDRESS_STATE,
        PRACTICE_ADDRESS_ZIP_CODE,
        PRACTICE_ADDRESS_TELEPHONE_NBR,
        PRACTICE_ADDRESS_FAX_NBR,
        PRIMARY_TAXONOMY_CODE
FROM PRESCRIBER_IDENTIFIER_CTE

UNION

SELECT  CURRENT_TIMESTAMP() AS INSERT_DATETIME,
        PRESCRIBER_ID,
        PRESCRIBER_SOURCE_CODE,
        PRESCRIBER_NPI_TYPE,
        NULLIF(PRESCRIBER_NAME,'UNKNOWN') AS PRESCRIBER_NAME,
        NULLIF(MAILING_ADDRESS_LINE_PRIMARY,'UNKNOWN') AS MAILING_ADDRESS_LINE_PRIMARY,
        NULLIF(MAILING_ADDRESS_LINE_SECONDARY,'UNKNOWN') AS MAILING_ADDRESS_LINE_SECONDARY,
        NULLIF(MAILING_ADDRESS_CITY,'UNKNOWN') AS MAILING_ADDRESS_CITY,
        NULLIF(MAILING_ADDRESS_STATE,'UNKNOWN') AS MAILING_ADDRESS_STATE,
        NULLIF(MAILING_ADDRESS_ZIP_CODE,'UNKNOWN') AS MAILING_ADDRESS_ZIP_CODE,
        NULLIF(MAILING_ADDRESS_TELEPHONE_NBR,'UNKNOWN') AS MAILING_ADDRESS_TELEPHONE_NBR,
        NULLIF(MAILING_ADDRESS_FAX_NBR,'UNKNOWN') AS MAILING_ADDRESS_FAX_NBR,
        NULLIF(PRACTICE_ADDRESS_LINE_PRIMARY,'UNKNOWN') AS PRACTICE_ADDRESS_LINE_PRIMARY,
        NULLIF(PRACTICE_ADDRESS_LINE_SECONDARY,'UNKNOWN') AS PRACTICE_ADDRESS_LINE_SECONDARY,
        NULLIF(PRACTICE_ADDRESS_CITY,'UNKNOWN') AS PRACTICE_ADDRESS_CITY,
        NULLIF(PRACTICE_ADDRESS_STATE,'UNKNOWN') AS PRACTICE_ADDRESS_STATE,
        NULLIF(PRACTICE_ADDRESS_ZIP_CODE,'UNKNOWN') AS PRACTICE_ADDRESS_ZIP_CODE,
        NULLIF(PRACTICE_ADDRESS_TELEPHONE_NBR,'UNKNOWN') AS PRACTICE_ADDRESS_TELEPHONE_NBR,
        NULLIF(PRACTICE_ADDRESS_FAX_NBR,'UNKNOWN') AS PRACTICE_ADDRESS_FAX_NBR,
        NULLIF(PRIMARY_TAXONOMY_CODE,'UNKNOWN') AS PRIMARY_TAXONOMY_CODE
FROM RAWDATA.CLAIM_CMS_HISTORICAL_NPI_PRESCRIBER
WHERE PRESCRIBER_ID IN (SELECT PRESCRIBER_IDENTIFIER FROM STAGEDATA.LKP_CLAIM_PHARMACY_CLAIM)
AND PRESCRIBER_ID NOT IN (SELECT PRESCRIBER_ID FROM PRESCRIBER_IDENTIFIER_CTE)
QUALIFY ROW_NUMBER() OVER(PARTITION BY PRESCRIBER_ID ORDER BY IDW_UPDATE_DATE DESC) = 1
;