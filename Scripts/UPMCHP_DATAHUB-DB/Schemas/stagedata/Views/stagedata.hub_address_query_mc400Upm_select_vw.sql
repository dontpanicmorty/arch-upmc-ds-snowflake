CREATE OR REPLACE VIEW STAGEDATA.HUB_ADDRESS_QUERY_MC400UPM_SELECT_VW
COMMENT = 'This is a STAGEDATA.HUB MC400 UPM select view of address query data'
AS
SELECT DISTINCT
    NULL AS SOURCE_KEY,
    TPACLIENT AS TPA_CLIENT_ID,
    TPAIDOFCLIENT AS TPA_ID,
    TPADIVISION AS TPA_DIV_ID,
    'MC400Upm' AS DATA_SOURCE_NAME,
    REGEXP_REPLACE(
        TRIM(
            CONCAT_WS(
                ' ',
                NVL(ADDRESS1, ''),
                NVL(ADDRESS2, ''),
                NVL(CITY, ''),
                NVL(STATE, ''),
                NVL(LEFT(TRIM(ZIPCODE), 5), '')
            )
        ),'\\s+', ' '
    ) AS CONCATENATED_ADDRESS,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CONCATENATED_ADDRESS]) AS HUB_ADDRESS_QUERY_HKEY
FROM
    RAWDATA.MC400_DWOAO_PROVIDERS
WHERE
    LEN(PROVIDERNBR) = 6
    AND PROVIDERNBR NOT LIKE ' %'
;