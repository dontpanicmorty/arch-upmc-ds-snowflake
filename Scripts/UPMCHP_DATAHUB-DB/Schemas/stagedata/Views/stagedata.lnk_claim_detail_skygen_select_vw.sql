CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_DETAIL_SKYGEN_SELECT_VW
COMMENT='Source view for SKGYEN data into LNK_CLAIM_DETAIL'
AS
SELECT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS C_TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS C_TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS C_TPA_DIV_ID,
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_HEADER.CLAIM_NBR AS C_CLAIM_NBR,
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS CD_TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS CD_TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS CD_TPA_DIV_ID,
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS CD_DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR AS CD_CLAIM_NBR,
DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_NBR AS CD_CLAIM_LINE_NBR,
DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR CD_CLAIM_LINE_SEQ_NBR,
DWSKYGEN_CLAIM_DETAIL.PROCEDURE_ADJ_CODE AS CD_CLAIM_LINE_PROCEDURE_ADJ_CODE,
UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS LNK_CLAIM_DETAIL_HKEY,
UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY,
UTIL.FXN_ARRAY_HASH([CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY

FROM RAWDATA.DWSKYGEN_CLAIM_HEADER
    JOIN RAWDATA.DWSKYGEN_CLAIM_DETAIL /*possible to have headers without details, unsure of business requirement. waiting for info*/
        ON (DWSKYGEN_CLAIM_HEADER.CLAIM_NBR = DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR)
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (DWSKYGEN_CLAIM_HEADER.CLAIM_NBR = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)

UNION ALL

SELECT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS C_TPA_CLIENT_ID, 
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS C_TPA_ID, 
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS C_TPA_DIV_ID, 
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME, 
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO AS C_CLAIM_NBR, 
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS CD_TPA_CLIENT_ID, 
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS CD_TPA_ID, 
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS CD_TPA_DIV_ID, 
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS CD_DATA_SOURCE_NAME, 
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO AS CD_CLAIM_NBR, 
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.ITEM_NO AS CD_CLAIM_LINE_NBR, 
UTIL.FXN_ARRAY_HASH([SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.BILLED_AMT]) AS CD_CLAIM_LINE_SEQ_NBR,
'N/A' AS CD_CLAIM_LINE_PROCEDURE_ADJ_CODE, 
UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS LNK_CLAIM_DETAIL_HKEY, 
UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY, 
UTIL.FXN_ARRAY_HASH([CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY

FROM RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR = SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO)
WHERE SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO NOT IN (SELECT CLAIM_NBR FROM RAWDATA.DWSKYGEN_CLAIM_HEADER) --Exclude claims in dwskygen, they supersede
;