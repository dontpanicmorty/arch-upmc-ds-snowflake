CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_BILLING_PROVIDER_ENVOLVE_SELECT_VW
COMMENT = 'Source view for ENVOLVE data into LNK_CLAIM_BILLING_PROVIDER'
AS
SELECT DISTINCT
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID AS C_TPA_CLIENT_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID AS C_TPA_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID AS C_TPA_DIV_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME, 
     ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO AS C_CLAIM_NBR, 
     'N/A' AS C_CLAIM_LINE_PROCEDURE_ADJ_CODE, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID AS MG_TPA_CLIENT_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID AS MG_TPA_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID AS MG_TPA_DIV_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.DATA_SOURCE_NAME AS MG_DATA_SOURCE_NAME, 
     CONCAT('0','ENVOLVE', ENVOLVE_CLAIM_EXTRACTS.PRVD_ID, ENVOLVE_CLAIM_EXTRACTS.PROV_LOC_ID) AS MG_MEDICAL_GROUP_ID, 
     UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_MEDICAL_GROUP_ID]) AS LNK_CLAIM_BILLING_PROVIDER_HKEY,
     UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY, 
     UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, MG_MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY, 
 FROM RAWDATA.ENVOLVE_CLAIM_EXTRACTS
     JOIN STAGEDATA.LKP_CLAIM_MEMBER_ENVOLVE
        ON (LKP_CLAIM_MEMBER_ENVOLVE.CLAIM_NBR = ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO)
     JOIN RAWDATA.ENVOLVE_PROVIDER
        ON (ENVOLVE_CLAIM_EXTRACTS.PRVD_ID = ENVOLVE_PROVIDER.PROVIDER_NBR)
        AND (ENVOLVE_CLAIM_EXTRACTS.PROV_LOC_ID = RIGHT(ENVOLVE_PROVIDER.MA_PROVIDER_NBR,6))
 WHERE ENVOLVE_CLAIM_EXTRACTS.PRVD_ID IS NOT NULL AND ENVOLVE_PROVIDER.MA_PROVIDER_NBR IS NOT NULL
      AND (TRIM(ENVOLVE_PROVIDER.FIRST_NAME) = '' OR TRY_TO_NUMBER(ENVOLVE_PROVIDER.FIRST_NAME) IS NOT NULL)
 QUALIFY ROW_NUMBER() -- get the most current submitted file for a claim line
    OVER(PARTITION BY ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO,ENVOLVE_CLAIM_EXTRACTS.ITEM_NO
    ORDER BY SPLIT_PART(SPLIT_PART(ENVOLVE_CLAIM_EXTRACTS.FILENAME, '_', 7), '.', 1) DESC) = 1 
UNION ALL
SELECT DISTINCT
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID AS C_TPA_CLIENT_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID AS C_TPA_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID AS C_TPA_DIV_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME, 
     ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO AS C_CLAIM_NBR, 
     'N/A' AS C_CLAIM_LINE_PROCEDURE_ADJ_CODE, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID AS MG_TPA_CLIENT_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID AS MG_TPA_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID AS MG_TPA_DIV_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.DATA_SOURCE_NAME AS MG_DATA_SOURCE_NAME, 
     CONCAT('0','ENVOLVE', ENVOLVE_CLAIM_EXTRACTS.PRVD_ID) AS MG_MEDICAL_GROUP_ID, 
     UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_MEDICAL_GROUP_ID]) AS LNK_CLAIM_BILLING_PROVIDER_HKEY,
     UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY, 
     UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, MG_MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY, 
 FROM RAWDATA.ENVOLVE_CLAIM_EXTRACTS
     JOIN STAGEDATA.LKP_CLAIM_MEMBER_ENVOLVE
        ON (LKP_CLAIM_MEMBER_ENVOLVE.CLAIM_NBR = ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO)
     JOIN RAWDATA.ENVOLVE_PROVIDER
        ON (ENVOLVE_CLAIM_EXTRACTS.PRVD_ID = ENVOLVE_PROVIDER.PROVIDER_NBR)
      WHERE ENVOLVE_CLAIM_EXTRACTS.PRVD_ID IS NOT NULL AND ENVOLVE_PROVIDER.MA_PROVIDER_NBR IS NULL
      AND (TRIM(ENVOLVE_PROVIDER.FIRST_NAME) = '' OR TRY_TO_NUMBER(ENVOLVE_PROVIDER.FIRST_NAME) IS NOT NULL)
 QUALIFY ROW_NUMBER() -- get the most current submitted file for a claim line
    OVER(PARTITION BY ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO,ENVOLVE_CLAIM_EXTRACTS.ITEM_NO
    ORDER BY SPLIT_PART(SPLIT_PART(ENVOLVE_CLAIM_EXTRACTS.FILENAME, '_', 7), '.', 1) DESC) = 1 
;