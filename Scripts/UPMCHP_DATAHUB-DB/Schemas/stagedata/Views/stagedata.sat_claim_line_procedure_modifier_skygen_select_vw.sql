CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_LINE_PROCEDURE_MODIFIER_SKYGEN_SELECT_VW
COMMENT = 'This is a SAT View containing Claim Line Procedure Modifier data for Skygen'
AS

SELECT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS TPA_CLIENT_ID, 
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS TPA_ID, 
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS TPA_DIV_ID, 
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR AS CLAIM_NBR,
DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_NBR AS CLAIM_LINE_NBR,
DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR AS CLAIM_LINE_SEQ_NBR, 
DWSKYGEN_CLAIM_DETAIL.PROCEDURE_ADJ_CODE AS PROCEDURE_ADJ_CODE,
DWSKYGEN_CLAIM_DETAIL.PROCEDURE_MODIFIER_01 AS MODIFIER_CODE,
1 AS CODE_POSITION, --currently there is only one modifier code for Skygen
UTIL.FXN_ARRAY_HASH([NULL]) AS HASH_DIFF,
UTIL.FXN_ARRAY_HASH(
        [TPA_CLIENT_ID, 
        TPA_ID, 
        TPA_DIV_ID, 
        DATA_SOURCE_NAME, 
        DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR, 
        CLAIM_LINE_NBR,
        CLAIM_LINE_SEQ_NBR, 
        PROCEDURE_ADJ_CODE
        ]) AS HUB_CLAIM_DETAIL_HKEY

FROM RAWDATA.DWSKYGEN_CLAIM_DETAIL
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
WHERE DWSKYGEN_CLAIM_DETAIL.PROCEDURE_MODIFIER_01 IS NOT NULL
;
/*
************************  This code is intentionally commented as there are no modifier values in the flat files ***************************

UNION ALL

SELECT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS TPA_CLIENT_ID, 
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS TPA_ID, 
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS TPA_DIV_ID, 
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS DATA_SOURCE_NAME,
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO AS CLAIM_NBR,
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.ITEM_NO AS CLAIM_LINE_NBR,
UTIL.FXN_ARRAY_HASH([SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.BILLED_AMT]) AS CLAIM_LINE_SEQ_NBR,
'N/A' AS PROCEDURE_ADJ_CODE,
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.MODIFIER_1 AS MODIFIER_CODE,
1 AS CODE_POSITION, --currently there is only one modifier code for Skygen
UTIL.FXN_ARRAY_HASH([NULL]) AS HASH_DIFF,
UTIL.FXN_ARRAY_HASH(
        [TPA_CLIENT_ID, 
        TPA_ID, 
        TPA_DIV_ID, 
        DATA_SOURCE_NAME, 
        CLAIM_NBR, 
        CLAIM_LINE_NBR,
        CLAIM_LINE_SEQ_NBR, 
        PROCEDURE_ADJ_CODE
        ]) AS HUB_CLAIM_DETAIL_HKEY

FROM RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
WHERE SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.MODIFIER_1 IS NOT NULL
AND SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO NOT IN (SELECT CLAIM_NBR FROM RAWDATA.DWSKYGEN_CLAIM_HEADER )
*/

