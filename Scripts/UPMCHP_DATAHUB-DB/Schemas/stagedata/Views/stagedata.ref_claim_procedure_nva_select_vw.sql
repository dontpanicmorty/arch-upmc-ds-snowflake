CREATE OR REPLACE VIEW STAGEDATA.REF_CLAIM_PROCEDURE_NVA_SELECT_VW
COMMENT='Source view for refdata.claim_procedure'
AS
SELECT DISTINCT
LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_NVA.TPA_ID
,LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID
,LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME
,ProcedureCodes_CURRENT.Code AS CODE
,TRIM(ProcedureCodes_CURRENT.ProcedureDescription) AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, ProcedureCodes_CURRENT.Code]) AS CLAIM_PROCEDURE_HKEY

FROM RAWDATA.NVA_PAID_CLAIM_EXTRACTS_VW
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_NVA
        ON (LKP_CLAIM_MEMBER_NVA.CLAIM_NBR = NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo")
    LEFT JOIN (SELECT TpaClient, TpaIdOfClient, TpaDivision, Code, ProcedureDescription
            FROM  RAWDATA.MC400_DWOAO_PROCEDURECODES PROCEDURECODES --THIS IS A TEMPORARY SOLUTION AND WE WILL NEED TO REFACTOR TO UTILIZE THE OPTUM FILES
            QUALIFY ROW_NUMBER() OVER(PARTITION BY TPACLIENT, TpaIdOfClient, TpaDivision, Code ORDER BY EffectiveDate DESC) = 1
            ) ProcedureCodes_CURRENT
        ON (ProcedureCodes_CURRENT.TpaClient = LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID
        AND ProcedureCodes_CURRENT.TpaIdOfClient = LKP_CLAIM_MEMBER_NVA.TPA_ID
        AND ProcedureCodes_CURRENT.TpaDivision = LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID
        AND ProcedureCodes_CURRENT.CODE = NVA_PAID_CLAIM_EXTRACTS_VW."ProcedureCode")
WHERE ProcedureCodes_CURRENT.ProcedureDescription <> ''
;