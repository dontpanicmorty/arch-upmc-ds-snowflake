CREATE OR REPLACE VIEW STAGEDATA.LNK_ADDRESS_QUERY_OFFICE_MC400UPM_SELECT_VW
COMMENT = 'This is an MC400 UPM LNK select view of address query and office data'
AS
SELECT
    TPACLIENT AS AQ_TPA_CLIENT_ID,
    TPAIDOFCLIENT AS AQ_TPA_ID,
    TPADIVISION AS AQ_TPA_DIV_ID,
    'MC400Upm' AS AQ_DATA_SOURCE_NAME,
    REGEXP_REPLACE(
        TRIM(
            CONCAT_WS(
                ' ',
                NVL(ADDRESS1, ''),
                NVL(ADDRESS2, ''),
                NVL(CITY, ''),
                NVL(STATE, ''),
                NVL(LEFT(TRIM(ZIPCODE), 5), '')
            )
        ),'\\s+', ' '
    ) AS AQ_CONCATENATED_ADDRESS,
    TPACLIENT AS O_TPA_CLIENT_ID,
    TPAIDOFCLIENT AS O_TPA_ID,
    TPADIVISION AS O_TPA_DIV_ID,
    'MC400Upm' AS O_DATA_SOURCE_NAME,
    CONCAT('OFFICE_', PROVIDERNBR) AS O_OFFICE_ID,
    UTIL.FXN_ARRAY_HASH([AQ_TPA_CLIENT_ID, AQ_TPA_ID, AQ_TPA_DIV_ID, AQ_DATA_SOURCE_NAME, AQ_CONCATENATED_ADDRESS, O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, O_OFFICE_ID]) AS LNK_ADDRESS_QUERY_OFFICE_HKEY,
    UTIL.FXN_ARRAY_HASH([AQ_TPA_CLIENT_ID, AQ_TPA_ID, AQ_TPA_DIV_ID, AQ_DATA_SOURCE_NAME, AQ_CONCATENATED_ADDRESS]) AS HUB_ADDRESS_QUERY_HKEY,
    UTIL.FXN_ARRAY_HASH([O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, O_OFFICE_ID]) AS HUB_OFFICE_HKEY
FROM RAWDATA.MC400_DWOAO_PROVIDERS
WHERE
    LEN(PROVIDERNBR) = 6
    AND PROVIDERNBR NOT LIKE ' %'
;