CREATE OR REPLACE VIEW STAGEDATA.LNK_ADDRESS_QUERY_STANDARD_ADDRESS_CACTUS_SELECT_VW
COMMENT = 'Link between address query and standard address for Cactus'
AS
SELECT 'N/A' AS SOURCE_KEY,
    '000001' AS AQ_TPA_CLIENT_ID,
    '000001' AS AQ_TPA_ID,
    '0001' AS AQ_TPA_DIV_ID,
    'Cactus' AS AQ_DATA_SOURCE_NAME,
    'N/A' AS SA_SOURCE_KEY,
    '000001' AS SA_TPA_CLIENT_ID,
    '000001' AS SA_TPA_ID,
    '0001' AS SA_TPA_DIV_ID,
    'Cactus' AS SA_DATA_SOURCE_NAME,
    RESPONSE_FLAT.value:delivery_line_1::string AS DELIVERY_LINE_1,
    RESPONSE_FLAT.value:delivery_line_2::string AS DELIVERY_LINE_2,
    RESPONSE_FLAT.value:last_line::string AS DELIVERY_LAST_LINE,
    WRK_ADDRESS_QUERY_BATCH.SINGLE_LINE_ADDRESS_BLOCK AS SINGLE_LINE_ADDRESS_BLOCK,
    UTIL.FXN_ARRAY_HASH([SA_TPA_CLIENT_ID, SA_TPA_ID, SA_TPA_DIV_ID, SA_DATA_SOURCE_NAME, DELIVERY_LINE_1, DELIVERY_LINE_2, DELIVERY_LAST_LINE]) AS HUB_STANDARD_ADDRESS_HKEY,
    UTIL.FXN_ARRAY_HASH([AQ_TPA_CLIENT_ID, AQ_TPA_ID, AQ_TPA_DIV_ID, AQ_DATA_SOURCE_NAME, SINGLE_LINE_ADDRESS_BLOCK]) AS HUB_ADDRESS_QUERY_HKEY,
    UTIL.FXN_ARRAY_HASH([AQ_TPA_CLIENT_ID, AQ_TPA_ID, AQ_TPA_DIV_ID, AQ_DATA_SOURCE_NAME, SINGLE_LINE_ADDRESS_BLOCK, SA_TPA_CLIENT_ID, SA_TPA_ID, SA_TPA_DIV_ID, SA_DATA_SOURCE_NAME, DELIVERY_LINE_1, DELIVERY_LINE_2, DELIVERY_LAST_LINE]) AS LNK_ADDRESS_QUERY_STANDARD_ADDRESS_HKEY,
    DATE_TRUNC('day', CURRENT_TIMESTAMP()) AS ROW_EFFECTIVE_DATETIME,
    DATEADD(day, 364, DATE_TRUNC('day', CURRENT_TIMESTAMP())) AS ROW_EXPIRATION_DATETIME
 FROM RAWDATA.WRK_ADDRESS_QUERY_RESPONSE 
    JOIN RAWDATA.WRK_ADDRESS_QUERY_BATCH 
    ON WRK_ADDRESS_QUERY_RESPONSE.BATCH_NUMBER = WRK_ADDRESS_QUERY_BATCH.BATCH_NUMBER, 
    LATERAL FLATTEN(input => RAWDATA.WRK_ADDRESS_QUERY_RESPONSE.SMARTY_JSON_RESPONSE) AS RESPONSE_FLAT
;
