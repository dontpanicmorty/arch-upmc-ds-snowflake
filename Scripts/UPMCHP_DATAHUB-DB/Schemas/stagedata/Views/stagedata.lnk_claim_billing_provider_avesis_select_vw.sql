CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_BILLING_PROVIDER_AVESIS_SELECT_VW
COMMENT = 'Source view for AVESIS data into LNK_CLAIM_BILLING_PROVIDER'
AS

WITH QUALIFY_CTE AS
    (SELECT *
     FROM RAWDATA.AVESIS_PROVIDER
     QUALIFY ROW_NUMBER()
        OVER(PARTITION BY AVESIS_PROVIDER.PLAN_PRVD_NO
            ORDER BY SPLIT_PART(SPLIT_PART(AVESIS_PROVIDER.FILENAME, '_', 4), '.', 1) DESC) = 1 
    )
    
SELECT DISTINCT
     LKP_CLAIM_MEMBER_AVESIS.TPA_CLIENT_ID AS C_TPA_CLIENT_ID, 
     LKP_CLAIM_MEMBER_AVESIS.TPA_ID AS C_TPA_ID, 
     LKP_CLAIM_MEMBER_AVESIS.TPA_DIV_ID AS C_TPA_DIV_ID, 
     LKP_CLAIM_MEMBER_AVESIS.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME,  
     AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO AS C_CLAIM_NBR, 
     LKP_CLAIM_MEMBER_AVESIS.TPA_CLIENT_ID AS MG_TPA_CLIENT_ID, 
     LKP_CLAIM_MEMBER_AVESIS.TPA_ID AS MG_TPA_ID, 
     LKP_CLAIM_MEMBER_AVESIS.TPA_DIV_ID AS MG_TPA_DIV_ID, 
     LKP_CLAIM_MEMBER_AVESIS.DATA_SOURCE_NAME AS MG_DATA_SOURCE_NAME, 
     TRIM(AVESIS_PAID_CLAIM_EXTRACTS.PRVD_ID) AS MG_MEDICAL_GROUP_ID, 
     UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_MEDICAL_GROUP_ID]) AS LNK_CLAIM_BILLING_PROVIDER_HKEY,
     UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY, 
     UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, MG_MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY
 FROM RAWDATA.AVESIS_PAID_CLAIM_EXTRACTS
     JOIN STAGEDATA.LKP_CLAIM_MEMBER_AVESIS
        ON (LKP_CLAIM_MEMBER_AVESIS.CLAIM_NBR = AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO)
      JOIN QUALIFY_CTE
        ON TRIM(AVESIS_PAID_CLAIM_EXTRACTS.PRVD_ID) = TRIM(QUALIFY_CTE.PLAN_PRVD_NO)
    JOIN (
            SELECT 
                AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO AS CD_CLAIM_NBR, 
                FILENAME, 
                FILE_ROW_NUMBER,
                AVESIS_PAID_CLAIM_EXTRACTS.ITEM_NO AS CD_CLAIM_LINE_NBR,
                UTIL.FXN_ARRAY_HASH([SUBSCRIBER_ID,CHECK_NO,CLAIM_TYPE,ADJUDICATION_DT,SERVICE_DT,ANSI_CODE,EXCEPTION_CODE,ADJUSTMENT_CODE,PROC_CODE,QUANTITY,TOOTH_ID,PROV_LOC_ID,PRVD_ID,COUNTY_CODE,LOB_IND]) AS CD_CLAIM_LINE_SEQ_NBR
            FROM RAWDATA.AVESIS_PAID_CLAIM_EXTRACTS
            WHERE AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO IS NOT NULL
                QUALIFY ROW_NUMBER() -- get the most current submitted file for a claim line
                    OVER(PARTITION BY AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO
                        ORDER BY TO_DATE(SPLIT_PART(SPLIT_PART(AVESIS_PAID_CLAIM_EXTRACTS.FILENAME, '_', 5), '.', 1), 'YYYYMMDD') DESC, FILE_ROW_NUMBER) = 1 
        ) CURRENT_CLAIM_FILE
        ON (CURRENT_CLAIM_FILE.CD_CLAIM_NBR = AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO
        AND CURRENT_CLAIM_FILE.CD_CLAIM_LINE_NBR = AVESIS_PAID_CLAIM_EXTRACTS.ITEM_NO
        AND CURRENT_CLAIM_FILE.CD_CLAIM_LINE_SEQ_NBR = UTIL.FXN_ARRAY_HASH([SUBSCRIBER_ID,CHECK_NO,CLAIM_TYPE,ADJUDICATION_DT,SERVICE_DT,ANSI_CODE,EXCEPTION_CODE,ADJUSTMENT_CODE,PROC_CODE,QUANTITY,TOOTH_ID,PROV_LOC_ID,PRVD_ID,COUNTY_CODE,LOB_IND])
        AND CURRENT_CLAIM_FILE.FILENAME = AVESIS_PAID_CLAIM_EXTRACTS.FILENAME
        AND CURRENT_CLAIM_FILE.FILE_ROW_NUMBER = AVESIS_PAID_CLAIM_EXTRACTS.FILE_ROW_NUMBER
        )
WHERE TRIM(AVESIS_PAID_CLAIM_EXTRACTS.PRVD_ID) IS NOT NULL
AND  AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO IS NOT NULL
AND NULLIF(TRIM(QUALIFY_CTE.PLAN_PRVD_NO), '') IS NOT NULL
AND TRIM(PLAN_PRVD_NO) <> 'DIRECT'
;