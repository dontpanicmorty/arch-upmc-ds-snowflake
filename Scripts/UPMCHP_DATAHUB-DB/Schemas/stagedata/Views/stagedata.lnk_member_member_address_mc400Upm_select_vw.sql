CREATE OR REPLACE VIEW STAGEDATA.LNK_MEMBER_MEMBER_ADDRESS_MC400UPM_SELECT_VW 
COMMENT = 'This is a LNK View containing mc400Upm Member and Member Address data'
AS
-- Physical
SELECT
Members.TpaClient AS M_TPA_CLIENT_ID
,Members.TpaIdOfClient AS M_TPA_ID
,Members.TpaDivision AS M_TPA_DIV_ID
,'MC400Upm' AS M_DATA_SOURCE_NAME
,TRIM(Members.MemberNbr) AS M_MEMBER_NBR
,Members.TpaClient AS MA_TPA_CLIENT_ID
,Members.TpaIdOfClient AS MA_TPA_ID
,Members.TpaDivision AS MA_TPA_DIV_ID
,'MC400Upm' AS MA_DATA_SOURCE_NAME
,TRIM(Members.MemberNbr) AS MA_MEMBER_NBR
,'Physical' AS MA_ADDRESS_TYPE_CODE
,UTIL.FXN_ARRAY_HASH([M_TPA_CLIENT_ID, M_TPA_ID, M_TPA_DIV_ID, M_DATA_SOURCE_NAME, M_MEMBER_NBR, MA_TPA_CLIENT_ID, MA_TPA_ID, MA_TPA_DIV_ID, MA_DATA_SOURCE_NAME, MA_MEMBER_NBR, MA_ADDRESS_TYPE_CODE]) AS LNK_MEMBER_MEMBER_ADDRESS_HKEY 
,UTIL.FXN_ARRAY_HASH([M_TPA_CLIENT_ID, M_TPA_ID, M_TPA_DIV_ID, M_DATA_SOURCE_NAME, M_MEMBER_NBR]) AS HUB_MEMBER_HKEY
,UTIL.FXN_ARRAY_HASH([MA_TPA_CLIENT_ID, MA_TPA_ID, MA_TPA_DIV_ID, MA_DATA_SOURCE_NAME, MA_MEMBER_NBR, MA_ADDRESS_TYPE_CODE]) AS HUB_MEMBER_ADDRESS_HKEY
FROM RAWDATA.MC400_DWOAO_MEMBERS Members
WHERE Members.MemberNbr <> '99999999901' --this is a junk catch all member number
AND TRIM(Members.MemberAddress1) <> ''
AND NOT CONTAINS(UPPER(Members.MemberAddress1), 'REMOVE') --ignore anything that has remove in it

UNION ALL

-- Mailing
SELECT 
 Members.TpaClient AS M_TPA_CLIENT_ID
,Members.TpaIdOfClient AS M_TPA_ID
,Members.TpaDivision AS M_TPA_DIV_ID
,'MC400Upm'AS M_DATA_SOURCE_NAME
,TRIM(Members.MemberNbr) AS M_MEMBER_NBR
,Members.TpaClient AS MA_TPA_CLIENT_ID
,Members.TpaIdOfClient AS MA_TPA_ID
,Members.TpaDivision AS MA_TPA_DIV_ID
,'MC400Upm' AS MA_DATA_SOURCE_NAME
,TRIM(Members.MemberNbr) AS MA_MEMBER_NBR
,'Mailing' AS MA_ADDRESS_TYPE_CODE
,UTIL.FXN_ARRAY_HASH([M_TPA_CLIENT_ID, M_TPA_ID, M_TPA_DIV_ID, M_DATA_SOURCE_NAME, M_MEMBER_NBR, MA_TPA_CLIENT_ID, MA_TPA_ID, MA_TPA_DIV_ID, MA_DATA_SOURCE_NAME, MA_MEMBER_NBR, MA_ADDRESS_TYPE_CODE]) AS LNK_MEMBER_MEMBER_ADDRESS_HKEY 
,UTIL.FXN_ARRAY_HASH([M_TPA_CLIENT_ID, M_TPA_ID, M_TPA_DIV_ID, M_DATA_SOURCE_NAME, M_MEMBER_NBR]) AS HUB_MEMBER_HKEY
,UTIL.FXN_ARRAY_HASH([MA_TPA_CLIENT_ID, MA_TPA_ID, MA_TPA_DIV_ID, MA_DATA_SOURCE_NAME, MA_MEMBER_NBR, MA_ADDRESS_TYPE_CODE]) AS HUB_MEMBER_ADDRESS_HKEY
FROM RAWDATA.MC400_DWOAO_MEMBERS Members
WHERE Members.MemberNbr <> '99999999901'--this is a junk catch all member number
AND TRIM(Members.MailingAddress1) <> ''
AND NOT CONTAINS(UPPER(Members.MailingAddress1), 'REMOVE') --ignore anything that has remove in it

UNION ALL

--H6
SELECT 
 Members.TpaClient AS M_TPA_CLIENT_ID
,Members.TpaIdOfClient AS M_TPA_ID
,Members.TpaDivision AS M_TPA_DIV_ID
,'MC400Upm'AS M_DATA_SOURCE_NAME
,TRIM(Members.MemberNbr) AS M_MEMBER_NBR
,Members.TpaClient AS MA_TPA_CLIENT_ID
,Members.TpaIdOfClient AS MA_TPA_ID
,Members.TpaDivision AS MA_TPA_DIV_ID
,'MC400Upm' AS MA_DATA_SOURCE_NAME
,TRIM(Members.MemberNbr) AS MA_MEMBER_NBR
,'H6' AS MA_ADDRESS_TYPE_CODE
,UTIL.FXN_ARRAY_HASH([M_TPA_CLIENT_ID, M_TPA_ID, M_TPA_DIV_ID, M_DATA_SOURCE_NAME, M_MEMBER_NBR, MA_TPA_CLIENT_ID, MA_TPA_ID, MA_TPA_DIV_ID, MA_DATA_SOURCE_NAME, MA_MEMBER_NBR, MA_ADDRESS_TYPE_CODE]) AS LNK_MEMBER_MEMBER_ADDRESS_HKEY 
,UTIL.FXN_ARRAY_HASH([M_TPA_CLIENT_ID, M_TPA_ID, M_TPA_DIV_ID, M_DATA_SOURCE_NAME, M_MEMBER_NBR]) AS HUB_MEMBER_HKEY
,UTIL.FXN_ARRAY_HASH([MA_TPA_CLIENT_ID, MA_TPA_ID, MA_TPA_DIV_ID, MA_DATA_SOURCE_NAME, MA_MEMBER_NBR, MA_ADDRESS_TYPE_CODE]) AS HUB_MEMBER_ADDRESS_HKEY
FROM RAWDATA.MC400_DWOAO_MEMBERS Members
   JOIN RAWDATA.MC400_DWOAO_MEMBERHIPAAPRIVACYDATA MemberHippaPrivacyData
      ON (MemberHippaPrivacyData.SubscriberNumber = Members.SubscriberNbr
        AND MemberHippaPrivacyData.PersonNumber = Members.PersonNbr)
WHERE Members.MemberNbr <> '99999999901' --this is a junk catch all member number
AND MemberHippaPrivacyData.HipaaFormType = 'H6'
AND MemberHippaPrivacyData.EffectiveRecord = 'Y'
AND MemberHippaPrivacyData.ActiveRecord = 'Y'
AND TRIM(MemberHippaPrivacyData.ConfidentialAddressLine1) <> ''
;