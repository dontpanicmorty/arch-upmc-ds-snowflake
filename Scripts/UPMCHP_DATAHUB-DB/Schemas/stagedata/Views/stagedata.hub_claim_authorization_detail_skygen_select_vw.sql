CREATE OR REPLACE VIEW STAGEDATA.HUB_CLAIM_AUTHORIZATION_DETAIL_SKYGEN_SELECT_VW
COMMENT = 'This is a HUB View containing Authorization Detail data'
AS
SELECT
    'N/A' AS SOURCE_KEY,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_LINE_NBR,
    UTIL.FXN_ARRAY_HASH(
            [LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID, 
            LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID, 
            LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID, 
            DATA_SOURCE_NAME, 
            DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR,
            AUTHORIZATION_LINE_NBR]
    ) AS HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY
FROM RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL
    JOIN STAGEDATA.LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN
        ON DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.AUTHORIZATION_NBR

UNION ALL

SELECT
    'N/A' AS SOURCE_KEY,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME,
    SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER AS AUTHORIZATION_NBR,
    IFNULL(SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.ITEM_NUMBER,'N/A') AS AUTHORIZATION_LINE_NBR,
    UTIL.FXN_ARRAY_HASH([
        TPA_CLIENT_ID,
        TPA_ID,
        TPA_DIV_ID,
        DATA_SOURCE_NAME,
        AUTHORIZATION_NBR,
        AUTHORIZATION_LINE_NBR
    ]) AS HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY
FROM RAWDATA.SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW
JOIN STAGEDATA.LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN
    ON (SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.AUTHORIZATION_NBR)
WHERE AUTHORIZATION_NUMBER NOT IN (SELECT AUTHORIZATION_NBR FROM RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL)
;