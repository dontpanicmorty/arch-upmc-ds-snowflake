!set variable_substitution=true;

CREATE OR REPLACE VIEW STAGEDATA.REF_CLAIM_PROCEDURE_MODIFIER_MC400DNT_SELECT_VW
COMMENT = 'This is a REF View containing Claim Procedure Modifier data'
AS
SELECT
'000001' AS TPA_CLIENT_ID
,'000001' AS TPA_ID
,'0001' AS TPA_DIV_ID
,'MC400Dnt' AS DATA_SOURCE_NAME
,Modifier as CODE
,IFF(IFNULL(ModifierDescription,'') = '', 'Description Not Found', ModifierDescription) AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CODE]) AS CLAIM_PROCEDURE_MODIFIER_HKEY
FROM &{MC400}.DWDNV.ProcedureModifier
WHERE Modifier IN 
    (SELECT DISTINCT MODIFIER_CODE
    FROM &{MC400}.DWDNV.CLAIMSDETAIL
        UNPIVOT (MODIFIER_CODE FOR COLUMN_NAME IN (PROCEDUREMODIFIER, MODIFIER2, MODIFIER3, MODIFIER4))
    )
ORDER BY CODE
;

!set variable_substitution=false;