CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_PLAN_NVA_SELECT_VW
COMMENT = 'Source view for NVA data into LNK_CLAIM_PLAN'
AS
SELECT DISTINCT
    LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID AS C_TPA_CLIENT_ID, 
    LKP_CLAIM_MEMBER_NVA.TPA_ID AS C_TPA_ID,
    LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID AS C_TPA_DIV_ID,
    LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME,
    NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo" AS C_CLAIM_NBR,
    LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID AS P_TPA_CLIENT_ID,
    LKP_CLAIM_MEMBER_NVA.TPA_ID AS P_TPA_ID,
    LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID AS P_TPA_DIV_ID,
    'MC400Upm' AS P_DATA_SOURCE_NAME, --Plans are sourced from MC400Upm
    LKP_CLAIM_MEMBER_NVA.PLAN_CODE AS P_PLAN_CODE,
    UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PLAN_CODE]) AS LNK_CLAIM_PLAN_HKEY,
    UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY,
    UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PLAN_CODE]) AS HUB_PLAN_HKEY
FROM RAWDATA.NVA_PAID_CLAIM_EXTRACTS_VW
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_NVA
        ON (LKP_CLAIM_MEMBER_NVA.CLAIM_NBR = NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo")
WHERE P_PLAN_CODE IS NOT NULL
;