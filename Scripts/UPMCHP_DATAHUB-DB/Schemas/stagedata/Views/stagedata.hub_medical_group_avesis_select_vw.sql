CREATE OR REPLACE VIEW STAGEDATA.HUB_MEDICAL_GROUP_AVESIS_SELECT_VW
COMMENT = 'This is a HUB View containing Medical Group or billing provider data'
AS

WITH QUALIFY_CTE AS
    (SELECT *
     FROM RAWDATA.AVESIS_PROVIDER
     QUALIFY ROW_NUMBER()
        OVER(PARTITION BY AVESIS_PROVIDER.PLAN_PRVD_NO
            ORDER BY SPLIT_PART(SPLIT_PART(AVESIS_PROVIDER.FILENAME, '_', 4), '.', 1) DESC) = 1 
    )

SELECT DISTINCT
    'N/A' AS SOURCE_KEY,
    '000001' AS TPA_CLIENT_ID,
    '000001' AS TPA_ID,
    '0001' AS TPA_DIV_ID,
    'Avesis' AS DATA_SOURCE_NAME,
    TRIM(PLAN_PRVD_NO) AS MEDICAL_GROUP_ID,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY
FROM QUALIFY_CTE
WHERE NULLIF(TRIM(PLAN_PRVD_NO), '') IS NOT NULL
AND TRIM(PLAN_PRVD_NO) <> 'DIRECT'
;
