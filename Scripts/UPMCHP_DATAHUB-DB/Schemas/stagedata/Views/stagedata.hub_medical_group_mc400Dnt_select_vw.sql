!set variable_substitution=true;
CREATE OR REPLACE VIEW STAGEDATA.HUB_MEDICAL_GROUP_MC400DNT_SELECT_VW
COMMENT = 'This is a HUB View containing Medical Group or billing provider data'
AS
SELECT
ProvidersSeqNbr AS SOURCE_KEY
,'000001' AS TPA_CLIENT_ID
,'000001' AS TPA_ID
,'0001' AS TPA_DIV_ID
,'MC400Dnt' AS DATA_SOURCE_NAME
,ProviderNbr AS MEDICAL_GROUP_ID
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY
FROM &{MC400}.DWDNV.PROVIDERS
WHERE UPPER(SUBSTR(ProviderNbr,1,1)) = 'V' --MC400 Business logic
;


!set variable_substitution=false;