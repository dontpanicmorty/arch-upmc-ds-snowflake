CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_OFFICE_ESI_SELECT_VW
COMMENT = 'Source view for ESI data into LNK_CLAIM_OFFICE'
AS
SELECT DISTINCT
 '000001' AS C_TPA_CLIENT_ID
,'000001' AS C_TPA_ID
,'0001' AS C_TPA_DIV_ID
,'ESI' AS C_DATA_SOURCE_NAME
,LKP_CLAIM_PHARMACY_CLAIM.CLAIM_ID AS C_CLAIM_NBR
,'000001' AS O_TPA_CLIENT_ID
,'000001' AS O_TPA_ID
,'0001' AS O_TPA_DIV_ID
,'ESI' AS O_DATA_SOURCE_NAME
,CONCAT('ESI', 'Pharmacy', NABP_NBR, IFF(PHARMACY_NPI = 'UNKNOWN', '', PHARMACY_NPI)) AS O_OFFICE_ID
,UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, O_OFFICE_ID]) AS LNK_CLAIM_OFFICE_HKEY
,UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY
,UTIL.FXN_ARRAY_HASH([O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, O_OFFICE_ID]) AS HUB_OFFICE_HKEY
FROM STAGEDATA.LKP_CLAIM_PHARMACY_CLAIM
    JOIN STAGEDATA.LKP_CLAIM_PHARMACY_DETAIL
        ON (LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_NUMBER = LKP_CLAIM_PHARMACY_DETAIL.NABP_NBR
        AND IFNULL(LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_IDENTIFIER,'UNKNOWN')= LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_NPI)
;