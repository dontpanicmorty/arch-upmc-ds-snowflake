!set variable_substitution=true;

CREATE OR REPLACE VIEW STAGEDATA.REF_CLAIM_BILLING_TYPE_MC400DNT_SELECT_VW
COMMENT = 'This is a REF View containing Claim Bill Type data'
AS
SELECT
'000001' AS TPA_CLIENT_ID
,'000001' AS TPA_ID
,'0001' AS TPA_DIV_ID
,'MC400Dnt' AS DATA_SOURCE_NAME
,GenericCodeValue as CODE
,IFF(IFNULL(GenericCodeDescription,'') = '', NULL, GenericCodeDescription) AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CODE]) AS CLAIM_BILLING_TYPE_HKEY
FROM &{MC400}.DWDNV.UB92FieldValidation
WHERE UPPER(GenericCodeFieldName) = 'BILLTYPE'
AND GenericCodeValue IN (SELECT DISTINCT BillType FROM &{MC400}.DWDNV.Claims WHERE MemberNbr <> '99999999901') --Exclude Generic Default Member Claims
ORDER BY CODE
;

!set variable_substitution=false;