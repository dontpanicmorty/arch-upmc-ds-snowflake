!set variable_substitution=true;

CREATE OR REPLACE VIEW STAGEDATA.HUB_MARKETING_CUTLOG_SELECT_VW COMMENT = 'Source view for HUB_MARKETING_CUTLOG' AS
SELECT DISTINCT 
    'MC400Upm' AS DATA_SOURCE_NAME,
    CUTCORRESPONDENCELOGFILE.cutidentifier as CUT_IDENTIFIER,
    CUTACTIVITYFILE.ACTIVITYCODE ACTIVITY_CODE,
    CUTCORRESPONDENCELOGFILE.TPAIDOFCLIENT AS TPA_CLIENT_ID,
    CUTCORRESPONDENCELOGFILE.TPACLIENT AS TPA_ID,
    CUTCORRESPONDENCELOGFILE.TPADIVISION AS TPA_DIV_ID,
    CUTACTIVITYFILE.ACTIVITYDATE AS ACTIVITY_DATE,
    CUTACTIVITYFILE.ACTIVITYTIME AS ACTIVITY_TIME,
    UTIL.FXN_ARRAY_HASH([ DATA_SOURCE_NAME, CUT_IDENTIFIER, ACTIVITY_CODE, ACTIVITY_DATE, ACTIVITY_TIME ]) AS HUB_MARKETING_CUTLOG_HKEY
FROM  &{MC400}.DWOAO.CUTCORRESPONDENCELOGFILE CUTCORRESPONDENCELOGFILE
    INNER JOIN &{MC400}.DWOAO.CUTACTIVITYFILE CUTACTIVITYFILE ON CUTCORRESPONDENCELOGFILE.CUTIDENTIFIER = CUTACTIVITYFILE.CUTIDENTIFIER
    AND CUTCORRESPONDENCELOGFILE.TPACLIENT = CUTACTIVITYFILE.TPACLIENT
    AND CUTCORRESPONDENCELOGFILE.TPAIDOFCLIENT = CUTACTIVITYFILE.TPAIDOFCLIENT
    INNER JOIN &{MC400}.DWOAO.TIMEBYDAY TIMEBYDAY
    ON to_char(CUTACTIVITYFILE.ActivityDate) = to_char(TIMEBYDAY.TimeID)
 WHERE TIMEBYDAY.year >= year(GETDATE()) - 1 
    AND CUTCORRESPONDENCELOGFILE.TPAIDOFCLIENT = '000001'
    AND CUTCORRESPONDENCELOGFILE.TPACLIENT = '000001'
    AND CUTCORRESPONDENCELOGFILE.TPADIVISION = '0001';

!set variable_substitution=false;