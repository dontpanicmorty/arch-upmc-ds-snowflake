CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_AUTHORIZATION_OFFICE_SKYGEN_SELECT_VW
COMMENT = 'Source view for Skygen data into LNK_CLAIM_AUTHORIZATION_OFFICE'
AS
SELECT DISTINCT
'N/A' AS SOURCE_KEY,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID AS A_TPA_CLIENT_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID AS A_TPA_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID AS A_TPA_DIV_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME AS A_DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_AUTHORIZATION.AUTHORIZATION_NBR AS A_AUTHORIZATION_NBR,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID AS O_TPA_CLIENT_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID AS O_TPA_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID AS O_TPA_DIV_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME AS O_DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_AUTHORIZATION.OFFICE_ID AS O_OFFICE_ID,
UTIL.FXN_ARRAY_HASH([A_TPA_CLIENT_ID, A_TPA_ID, A_TPA_DIV_ID, A_DATA_SOURCE_NAME, A_AUTHORIZATION_NBR, O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, O_OFFICE_ID]) AS LNK_CLAIM_AUTHORIZATION_OFFICE_HKEY,
UTIL.FXN_ARRAY_HASH([A_TPA_CLIENT_ID, A_TPA_ID, A_TPA_DIV_ID, A_DATA_SOURCE_NAME, A_AUTHORIZATION_NBR]) AS HUB_CLAIM_AUTHORIZATION_HKEY,
UTIL.FXN_ARRAY_HASH([O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, O_OFFICE_ID]) AS HUB_OFFICE_HKEY
FROM RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION
    JOIN STAGEDATA.LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN
        ON DWSKYGEN_CLAIM_AUTHORIZATION.AUTHORIZATION_NBR = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.AUTHORIZATION_NBR
WHERE O_OFFICE_ID NOT IN ('LOCATION_-1','LOCATION_0')
;