CREATE OR REPLACE VIEW STAGEDATA.LNK_PROVIDER_OFFICE_CACTUS_SELECT_VW
COMMENT = 'This is a Cactus LNK select view of provider and office data'
AS
WITH DUPLICATES AS (
    SELECT PRV.ID
    FROM
        RAWDATA.CACTUS_PROVIDERS AS PRV
    INNER JOIN
        RAWDATA.CACTUS_ENTITYASSIGNMENTS AS EA
        ON PRV.PROVIDER_K = EA.PROVIDER_K
    GROUP BY PRV.ID
    HAVING COUNT(DISTINCT PRV.PROVIDER_K) > 1
)
SELECT DISTINCT
    '000001' AS P_TPA_CLIENT_ID,
    '000001' AS P_TPA_ID,
    '0001' AS P_TPA_DIV_ID,
    'Cactus' AS P_DATA_SOURCE_NAME,
    PRV.ID AS P_PROVIDER_ID,
    '000001' AS O_TPA_CLIENT_ID,
    '000001' AS O_TPA_ID,
    '0001' AS O_TPA_DIV_ID,
    'Cactus' AS O_DATA_SOURCE_NAME,
    NULLIF(TRIM(PRV_ADR.USERDEF_C1), '') AS O_OFFICE_ID,
    UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID, O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, O_OFFICE_ID]) AS LNK_PROVIDER_OFFICE_HKEY,
    UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS HUB_PROVIDER_HKEY,
    UTIL.FXN_ARRAY_HASH([O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, O_OFFICE_ID]) AS HUB_OFFICE_HKEY
FROM
    RAWDATA.CACTUS_PROVIDERS AS PRV
LEFT JOIN
    RAWDATA.CACTUS_PROVIDERADDRESSES AS PRV_ADR
    ON PRV.PROVIDER_K = PRV_ADR.PROVIDER_K
LEFT JOIN
    RAWDATA.CACTUS_ADDRESSES AS ADR
    ON PRV_ADR.ADDRESS_K = ADR.ADDRESS_K
LEFT JOIN
    DUPLICATES AS DUP
    ON PRV.ID = DUP.ID
INNER JOIN (
    SELECT DISTINCT PROVIDER_K
    FROM RAWDATA.CACTUS_ENTITYASSIGNMENTS
    WHERE RECORDTYPE = 'E'
    ) AS EA
    ON PRV.PROVIDER_K = EA.PROVIDER_K
WHERE
    NULLIF(PRV.ID, '') IS NOT NULL
    AND PRV.STATUS_RTK NOT IN ('#0000K408T','#0000K408U','#0000K408S') --Provider statuses "Applicant", "Committee Reviewer", "Lead" do not interface out of Cactus
    AND (PRV.INDIVIDUALINSTITUTIONFLAG != 1 OR PRV.LASTNAME != '' OR PRV.FIRSTNAME != '')
    AND (PRV.INDIVIDUALINSTITUTIONFLAG != 2 OR (PRV.LONGNAME != '' AND PRV_ADR.ACTIVE = 1))
    AND NULLIF(PRV_ADR.PROVIDER_K, '') IS NOT NULL
    AND NULLIF(PRV_ADR.USERDEF_C1, '') IS NOT NULL
    AND (NULLIF(ADR.ADDRESSLINE1, '') IS NOT NULL OR NULLIF(ADR.ADDRESSLINE2, '') IS NOT NULL)
    AND DUP.ID IS NULL
    AND PRV_ADR.ACTIVE = TRUE
;