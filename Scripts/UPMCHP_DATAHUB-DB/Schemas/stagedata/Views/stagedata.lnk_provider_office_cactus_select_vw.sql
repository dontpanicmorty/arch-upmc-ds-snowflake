CREATE OR REPLACE VIEW STAGEDATA.LNK_PROVIDER_OFFICE_CACTUS_SELECT_VW
COMMENT = 'This is a Cactus LNK select view of provider and office data and medical group data '
AS
WITH cte_DUPS AS (
    SELECT CACTUS_PROVIDERS.ID
    FROM
        RAWDATA.CACTUS_PROVIDERS
    INNER JOIN
        RAWDATA.CACTUS_ENTITYASSIGNMENTS
        ON CACTUS_PROVIDERS.PROVIDER_K = CACTUS_ENTITYASSIGNMENTS.PROVIDER_K
    GROUP BY CACTUS_PROVIDERS.ID
    HAVING COUNT(DISTINCT CACTUS_PROVIDERS.PROVIDER_K) > 1
)
SELECT DISTINCT
    '000001' AS P_TPA_CLIENT_ID,
    '000001' AS P_TPA_ID,
    '0001' AS P_TPA_DIV_ID,
    'Cactus' AS P_DATA_SOURCE_NAME,
    RTRIM(CACTUS_PROVIDERS.ID) AS P_PROVIDER_ID,
    '000001' AS O_TPA_CLIENT_ID,
    '000001' AS O_TPA_ID,
    '0001' AS O_TPA_DIV_ID,
    'Cactus' AS O_DATA_SOURCE_NAME,
    NULLIF(TRIM(CACTUS_PROVIDERADDRESSES.USERDEF_C1), '') AS O_OFFICE_ID,
    '000001' AS MG_TPA_CLIENT_ID,
    '000001' AS MG_TPA_ID,
    '0001' AS MG_TPA_DIV_ID,
    'Cactus' AS MG_DATA_SOURCE_NAME,
     TRIM(CACTUS_GROUPS.ID) AS MG_MEDICAL_GROUP_ID,
    
    UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID, O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, O_OFFICE_ID, MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_MEDICAL_GROUP_ID]) AS LNK_PROVIDER_OFFICE_HKEY,
    UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS HUB_PROVIDER_HKEY,
    UTIL.FXN_ARRAY_HASH([O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, O_OFFICE_ID]) AS HUB_OFFICE_HKEY,
    UTIL.FXN_ARRAY_HASH([MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY
FROM
    RAWDATA.CACTUS_PROVIDERS
INNER JOIN
    RAWDATA.CACTUS_PROVIDERADDRESSES
    ON CACTUS_PROVIDERS.PROVIDER_K = CACTUS_PROVIDERADDRESSES.PROVIDER_K
INNER JOIN
    RAWDATA.CACTUS_ADDRESSES
    ON CACTUS_PROVIDERADDRESSES.ADDRESS_K = CACTUS_ADDRESSES.ADDRESS_K
INNER JOIN
    RAWDATA.CACTUS_GROUPSPROVIDERSADDRESSES
    ON CACTUS_PROVIDERADDRESSES.PROVIDERADDRESS_K = CACTUS_GROUPSPROVIDERSADDRESSES.PROVIDERADDRESS_K
INNER JOIN 
    RAWDATA.CACTUS_GROUPADDRESS 
    ON CACTUS_GROUPADDRESS.GROUPADDRESS_K = CACTUS_GROUPSPROVIDERSADDRESSES.GROUPADDRESS_K
INNER JOIN 
    RAWDATA.CACTUS_GROUPS 
    ON CACTUS_GROUPADDRESS.GROUP_K = CACTUS_GROUPS.GROUP_K
INNER JOIN 
    RAWDATA.CACTUS_ENTITYASSIGNMENTS
    ON CACTUS_PROVIDERS.PROVIDER_K = CACTUS_ENTITYASSIGNMENTS.PROVIDER_K
        AND CACTUS_ENTITYASSIGNMENTS.RECORDTYPE = 'E'
LEFT JOIN
    cte_DUPS
    ON CACTUS_PROVIDERS.ID = cte_DUPS.ID
WHERE
    NULLIF(CACTUS_PROVIDERS.ID, '') IS NOT NULL
    AND NULLIF(TRIM(CACTUS_PROVIDERADDRESSES.USERDEF_C1), '') IS NOT NULL
    AND NULLIF(TRIM(CACTUS_GROUPS.ID), '') IS NOT NULL
    AND CACTUS_PROVIDERS.STATUS_RTK NOT IN ('#0000K408T','#0000K408U','#0000K408S') --Provider statuses "Applicant", "Committee Reviewer", "Lead" do not interface out of Cactus
    AND (CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG != 1 OR CACTUS_PROVIDERS.LASTNAME != '' OR CACTUS_PROVIDERS.FIRSTNAME != '')
    AND (CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG != 2 OR (CACTUS_PROVIDERS.LONGNAME != '' AND CACTUS_PROVIDERADDRESSES.ACTIVE = 1))    
    AND (NULLIF(CACTUS_ADDRESSES.ADDRESSLINE1, '') IS NOT NULL OR NULLIF(CACTUS_ADDRESSES.ADDRESSLINE2, '') IS NOT NULL)
    AND cte_DUPS.ID IS NULL
    --AND CACTUS_PROVIDERADDRESSES.ACTIVE = TRUE