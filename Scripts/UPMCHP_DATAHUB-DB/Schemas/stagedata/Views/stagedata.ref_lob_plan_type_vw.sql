CREATE OR REPLACE VIEW STAGEDATA.REF_LOB_PLAN_TYPE_VW
COMMENT='Source view for refdata.lob_plan_type'
AS
SELECT
TPA_CLIENT_ID
,TPA_ID
,TPA_DIV_ID
,LINE_OF_BUSINESS_CODE
,PLAN_TYPE
,PLAN_TYPE_DESC
,PLAN_TYPE_SOURCE
,PROGRAM_CODE
,PROGRAM_DESC
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, LINE_OF_BUSINESS_CODE, PLAN_TYPE]) AS LOB_PLAN_TYPE_HKEY

FROM RAWDATA.LOB_PLAN_TYPE
;