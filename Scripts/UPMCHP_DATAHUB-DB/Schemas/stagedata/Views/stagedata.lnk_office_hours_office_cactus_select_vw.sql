CREATE OR REPLACE VIEW STAGEDATA.LNK_OFFICE_HOURS_OFFICE_CACTUS_SELECT_VW
COMMENT = 'This is a Cactus LNK select view of office hours and Office data'
AS
WITH DUPLICATE_GROUPS AS (
    SELECT ID
    FROM RAWDATA.CACTUS_GROUPS
    GROUP BY ID
    HAVING COUNT(*) > 1
)
, MONDAYS AS (
    SELECT
        GROUPADDRESS_K,
        'MONDAY' AS DAY_OF_WEEK,
        TRY_TO_TIME(MONDAYHOURS_AMOPEN, 'HH12MI') AS AM_OPEN,
        TRY_TO_TIME(MONDAYHOURS_AMCLOSE, 'HH12MI') AS AM_CLOSE,
        DATEADD('HH', 12, TRY_TO_TIME(MONDAYHOURS_PMOPEN, 'HH12MI')) AS PM_OPEN,
        DATEADD('HH', 12, TRY_TO_TIME(MONDAYHOURS_PMCLOSE, 'HH12MI')) AS PM_CLOSE
    FROM RAWDATA.CACTUS_GROUPADDRESS
    WHERE (AM_OPEN IS NOT NULL OR PM_OPEN IS NOT NULL)
)
, MONDAY_SPANS AS (
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        AM_OPEN AS OPEN_TIME,
        NVL(AM_CLOSE, PM_CLOSE) AS CLOSE_TIME
    FROM MONDAYS
    WHERE AM_OPEN IS NOT NULL
        UNION ALL
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        PM_OPEN AS OPEN_TIME,
        PM_CLOSE AS CLOSE_TIME
    FROM MONDAYS
    WHERE PM_OPEN IS NOT NULL
)
, TUESDAYS AS (
    SELECT
        GROUPADDRESS_K,
        'TUESDAY' AS DAY_OF_WEEK,
        TRY_TO_TIME(TUESDAYHOURS_AMOPEN, 'HH12MI') AS AM_OPEN,
        TRY_TO_TIME(TUESDAYHOURS_AMCLOSE, 'HH12MI') AS AM_CLOSE,
        DATEADD('HH', 12, TRY_TO_TIME(TUESDAYHOURS_PMOPEN, 'HH12MI')) AS PM_OPEN,
        DATEADD('HH', 12, TRY_TO_TIME(TUESDAYHOURS_PMCLOSE, 'HH12MI')) AS PM_CLOSE
    FROM RAWDATA.CACTUS_GROUPADDRESS
    WHERE (AM_OPEN IS NOT NULL OR PM_OPEN IS NOT NULL)
)
, TUESDAY_SPANS AS (
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        AM_OPEN AS OPEN_TIME,
        NVL(AM_CLOSE, PM_CLOSE) AS CLOSE_TIME
    FROM TUESDAYS
    WHERE AM_OPEN IS NOT NULL
        UNION ALL
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        PM_OPEN AS OPEN_TIME,
        PM_CLOSE AS CLOSE_TIME
    FROM TUESDAYS
    WHERE PM_OPEN IS NOT NULL
)
, WEDNESDAYS AS (
    SELECT
        GROUPADDRESS_K,
        'WEDNESDAY' AS DAY_OF_WEEK,
        TRY_TO_TIME(WEDNESDAYHOURS_AMOPEN, 'HH12MI') AS AM_OPEN,
        TRY_TO_TIME(WEDNESDAYHOURS_AMCLOSE, 'HH12MI') AS AM_CLOSE,
        DATEADD('HH', 12, TRY_TO_TIME(WEDNESDAYHOURS_PMOPEN, 'HH12MI')) AS PM_OPEN,
        DATEADD('HH', 12, TRY_TO_TIME(WEDNESDAYHOURS_PMCLOSE, 'HH12MI')) AS PM_CLOSE
    FROM RAWDATA.CACTUS_GROUPADDRESS
    WHERE (AM_OPEN IS NOT NULL OR PM_OPEN IS NOT NULL)
)
, WEDNESDAY_SPANS AS (
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        AM_OPEN AS OPEN_TIME,
        NVL(AM_CLOSE, PM_CLOSE) AS CLOSE_TIME
    FROM WEDNESDAYS
    WHERE AM_OPEN IS NOT NULL
        UNION ALL
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        PM_OPEN AS OPEN_TIME,
        PM_CLOSE AS CLOSE_TIME
    FROM WEDNESDAYS
    WHERE PM_OPEN IS NOT NULL
)
, THURSDAYS AS (
    SELECT
        GROUPADDRESS_K,
        'THURSDAY' AS DAY_OF_WEEK,
        TRY_TO_TIME(THURSDAYHOURS_AMOPEN, 'HH12MI') AS AM_OPEN,
        TRY_TO_TIME(THURSDAYHOURS_AMCLOSE, 'HH12MI') AS AM_CLOSE,
        DATEADD('HH', 12, TRY_TO_TIME(THURSDAYHOURS_PMOPEN, 'HH12MI')) AS PM_OPEN,
        DATEADD('HH', 12, TRY_TO_TIME(THURSDAYHOURS_PMCLOSE, 'HH12MI')) AS PM_CLOSE
    FROM RAWDATA.CACTUS_GROUPADDRESS
    WHERE (AM_OPEN IS NOT NULL OR PM_OPEN IS NOT NULL)
)
, THURSDAY_SPANS AS (
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        AM_OPEN AS OPEN_TIME,
        NVL(AM_CLOSE, PM_CLOSE) AS CLOSE_TIME
    FROM THURSDAYS
    WHERE AM_OPEN IS NOT NULL
        UNION ALL
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        PM_OPEN AS OPEN_TIME,
        PM_CLOSE AS CLOSE_TIME
    FROM THURSDAYS
    WHERE PM_OPEN IS NOT NULL
)
, FRIDAYS AS (
    SELECT
        GROUPADDRESS_K,
        'FRIDAY' AS DAY_OF_WEEK,
        TRY_TO_TIME(FRIDAYHOURS_AMOPEN, 'HH12MI') AS AM_OPEN,
        TRY_TO_TIME(FRIDAYHOURS_AMCLOSE, 'HH12MI') AS AM_CLOSE,
        DATEADD('HH', 12, TRY_TO_TIME(FRIDAYHOURS_PMOPEN, 'HH12MI')) AS PM_OPEN,
        DATEADD('HH', 12, TRY_TO_TIME(FRIDAYHOURS_PMCLOSE, 'HH12MI')) AS PM_CLOSE
    FROM RAWDATA.CACTUS_GROUPADDRESS
    WHERE (AM_OPEN IS NOT NULL OR PM_OPEN IS NOT NULL)
)
, FRIDAY_SPANS AS (
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        AM_OPEN AS OPEN_TIME,
        NVL(AM_CLOSE, PM_CLOSE) AS CLOSE_TIME
    FROM FRIDAYS
    WHERE AM_OPEN IS NOT NULL
        UNION ALL
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        PM_OPEN AS OPEN_TIME,
        PM_CLOSE AS CLOSE_TIME
    FROM FRIDAYS
    WHERE PM_OPEN IS NOT NULL
)
, SATURDAYS AS (
    SELECT
        GROUPADDRESS_K,
        'SATURDAY' AS DAY_OF_WEEK,
        TRY_TO_TIME(SATURDAYHOURS_AMOPEN, 'HH12MI') AS AM_OPEN,
        TRY_TO_TIME(SATURDAYHOURS_AMCLOSE, 'HH12MI') AS AM_CLOSE,
        DATEADD('HH', 12, TRY_TO_TIME(SATURDAYHOURS_PMOPEN, 'HH12MI')) AS PM_OPEN,
        DATEADD('HH', 12, TRY_TO_TIME(SATURDAYHOURS_PMCLOSE, 'HH12MI')) AS PM_CLOSE
    FROM RAWDATA.CACTUS_GROUPADDRESS
    WHERE (AM_OPEN IS NOT NULL OR PM_OPEN IS NOT NULL)
)
, SATURDAY_SPANS AS (
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        AM_OPEN AS OPEN_TIME,
        NVL(AM_CLOSE, PM_CLOSE) AS CLOSE_TIME
    FROM SATURDAYS
    WHERE AM_OPEN IS NOT NULL
        UNION ALL
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        PM_OPEN AS OPEN_TIME,
        PM_CLOSE AS CLOSE_TIME
    FROM SATURDAYS
    WHERE PM_OPEN IS NOT NULL
)
, SUNDAYS AS (
    SELECT
        GROUPADDRESS_K,
        'SUNDAY' AS DAY_OF_WEEK,
        TRY_TO_TIME(SUNDAYHOURS_AMOPEN, 'HH12MI') AS AM_OPEN,
        TRY_TO_TIME(SUNDAYHOURS_AMCLOSE, 'HH12MI') AS AM_CLOSE,
        DATEADD('HH', 12, TRY_TO_TIME(SUNDAYHOURS_PMOPEN, 'HH12MI')) AS PM_OPEN,
        DATEADD('HH', 12, TRY_TO_TIME(SUNDAYHOURS_PMCLOSE, 'HH12MI')) AS PM_CLOSE
    FROM RAWDATA.CACTUS_GROUPADDRESS
    WHERE (AM_OPEN IS NOT NULL OR PM_OPEN IS NOT NULL)
)
, SUNDAY_SPANS AS (
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        AM_OPEN AS OPEN_TIME,
        NVL(AM_CLOSE, PM_CLOSE) AS CLOSE_TIME
    FROM SUNDAYS
    WHERE AM_OPEN IS NOT NULL
        UNION ALL
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        PM_OPEN AS OPEN_TIME,
        PM_CLOSE AS CLOSE_TIME
    FROM SUNDAYS
    WHERE PM_OPEN IS NOT NULL
)
, HUB_HOURS AS (
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        OPEN_TIME,
        CLOSE_TIME
    FROM MONDAY_SPANS
        UNION ALL
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        OPEN_TIME,
        CLOSE_TIME
    FROM TUESDAY_SPANS
        UNION ALL
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        OPEN_TIME,
        CLOSE_TIME
    FROM WEDNESDAY_SPANS
        UNION ALL
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        OPEN_TIME,
        CLOSE_TIME
    FROM THURSDAY_SPANS
        UNION ALL
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        OPEN_TIME,
        CLOSE_TIME
    FROM FRIDAY_SPANS
        UNION ALL
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        OPEN_TIME,
        CLOSE_TIME
    FROM SATURDAY_SPANS
        UNION ALL
    SELECT
        GROUPADDRESS_K,
        DAY_OF_WEEK,
        OPEN_TIME,
        CLOSE_TIME
    FROM SUNDAY_SPANS
)
SELECT DISTINCT
    '000001' AS O_TPA_CLIENT_ID,
    '000001' AS O_TPA_ID,
    '0001' AS O_TPA_DIV_ID,
    'Cactus' AS O_DATA_SOURCE_NAME,
    NULLIF(TRIM(GRP_ADR.ID), '') AS O_OFFICE_ID,
    '000001' AS OH_TPA_CLIENT_ID,
    '000001' AS OH_TPA_ID,
    '0001' AS OH_TPA_DIV_ID,
    'Cactus' AS OH_DATA_SOURCE_NAME,
    OH.DAY_OF_WEEK AS OH_DAY_OF_WEEK,
    OH.OPEN_TIME AS OH_OPEN_TIME,
    OH.CLOSE_TIME AS OH_CLOSE_TIME,

    UTIL.FXN_ARRAY_HASH([
        O_TPA_CLIENT_ID,
        O_TPA_ID,
        O_TPA_DIV_ID,
        O_DATA_SOURCE_NAME,
        O_OFFICE_ID,
        OH_TPA_CLIENT_ID,
        OH_TPA_ID,
        OH_TPA_DIV_ID,
        OH_DATA_SOURCE_NAME,
        OH_DAY_OF_WEEK,
        OH_OPEN_TIME,
        OH_CLOSE_TIME
    ]) AS LNK_OFFICE_HOURS_OFFICE_HKEY,

    UTIL.FXN_ARRAY_HASH([
        OH_TPA_CLIENT_ID,
        OH_TPA_ID,
        OH_TPA_DIV_ID,
        OH_DATA_SOURCE_NAME,
        OH_DAY_OF_WEEK,
        OH_OPEN_TIME,
        OH_CLOSE_TIME
    ]) AS HUB_OFFICE_HOURS_HKEY,

    UTIL.FXN_ARRAY_HASH([
        O_TPA_CLIENT_ID,
        O_TPA_ID,
        O_TPA_DIV_ID,
        O_DATA_SOURCE_NAME,
        O_OFFICE_ID
    ]) AS HUB_OFFICE_HKEY
FROM
    RAWDATA.CACTUS_GROUPADDRESS AS GRP_ADR
INNER JOIN
    HUB_HOURS AS OH
    ON GRP_ADR.GROUPADDRESS_K = OH.GROUPADDRESS_K
LEFT JOIN
    RAWDATA.CACTUS_GROUPS AS GRP
    ON GRP_ADR.GROUP_K = GRP.GROUP_K
LEFT JOIN
    DUPLICATE_GROUPS AS DUP
    ON GRP.ID = DUP.ID
LEFT JOIN
    RAWDATA.CACTUS_ADDRESSES AS ADR
    ON GRP_ADR.ADDRESS_K = ADR.ADDRESS_K
WHERE
    NULLIF(TRIM(GRP_ADR.ID), '') IS NOT NULL
    AND NULLIF(TRIM(GRP_ADR.GROUP_K), '') IS NOT NULL
    AND NULLIF(TRIM(GRP_ADR.TAXIDNUMBER), '') IS NOT NULL
    AND NULLIF(TRIM(GRP.ID) , '') IS NOT NULL
    AND (NULLIF(ADR.ADDRESSLINE1, '') IS NOT NULL OR NULLIF(ADR.ADDRESSLINE2, '') IS NOT NULL)
    AND DUP.ID IS NULL
    AND GRP_ADR.ACTIVE = TRUE
;