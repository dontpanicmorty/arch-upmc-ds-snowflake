CREATE OR REPLACE VIEW STAGEDATA.HUB_OFFICE_CACTUS_SELECT_VW
COMMENT = 'Source view for Cactus data into HUB_OFFICE'
AS
WITH DUPLICATE_PROVIDERS AS (
    SELECT PRV.ID
    FROM
        RAWDATA.CACTUS_PROVIDERS AS PRV
    INNER JOIN
        RAWDATA.CACTUS_ENTITYASSIGNMENTS AS EA
        ON PRV.PROVIDER_K = EA.PROVIDER_K
    GROUP BY PRV.ID
    HAVING COUNT(DISTINCT PRV.PROVIDER_K) > 1
)
, DUPLICATE_GROUPS AS (
    SELECT ID
    FROM RAWDATA.CACTUS_GROUPS
    GROUP BY ID HAVING COUNT(*) > 1
)
, DISTINCT_ENTITYASSIGNMENTS AS (
    SELECT DISTINCT PROVIDER_K
    FROM RAWDATA.CACTUS_ENTITYASSIGNMENTS
    WHERE RECORDTYPE = 'E'
)
SELECT DISTINCT
    'N/A' AS SOURCE_KEY,
    '000001' AS TPA_CLIENT_ID,
    '000001' AS TPA_ID,
    '0001' AS TPA_DIV_ID,
    'Cactus' AS DATA_SOURCE_NAME,
    NULLIF(TRIM(PRV_ADR.USERDEF_C1), '') AS OFFICE_ID,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, OFFICE_ID]) AS HUB_OFFICE_HKEY
FROM
    RAWDATA.CACTUS_PROVIDERADDRESSES AS PRV_ADR
LEFT JOIN
    RAWDATA.CACTUS_PROVIDERS AS PRV
    ON PRV_ADR.PROVIDER_K = PRV.PROVIDER_K
LEFT JOIN
    RAWDATA.CACTUS_ADDRESSES AS ADR
    ON PRV_ADR.ADDRESS_K = ADR.ADDRESS_K
LEFT JOIN 
    DUPLICATE_PROVIDERS AS DUP
    ON PRV.ID = DUP.ID
INNER JOIN
    DISTINCT_ENTITYASSIGNMENTS AS DEA
    ON PRV.PROVIDER_K = DEA.PROVIDER_K
WHERE
    NULLIF(PRV_ADR.PROVIDER_K, '') IS NOT NULL
    AND NULLIF(PRV_ADR.USERDEF_C1, '') IS NOT NULL
    AND NULLIF(PRV.ID, '') IS NOT NULL
    AND PRV.STATUS_RTK NOT IN ('#0000K408T','#0000K408U','#0000K408S') ----Provider statuses "Applicant", "Committee Reviewer", "Lead" do not interface out of Cactus 
    AND (PRV.INDIVIDUALINSTITUTIONFLAG != 1 OR PRV.LASTNAME != '' OR PRV.FIRSTNAME != '')
    AND (PRV.INDIVIDUALINSTITUTIONFLAG != 2 OR (PRV.LONGNAME != '' AND PRV_ADR.ACTIVE = 1))
    AND (NULLIF(ADR.ADDRESSLINE1, '') IS NOT NULL OR NULLIF(ADR.ADDRESSLINE2, '') IS NOT NULL)
    AND DUP.ID IS NULL

UNION

--HUB_OFFICE MED GROUPS
SELECT DISTINCT
    'N/A' AS SOURCE_KEY,
    '000001' AS TPA_CLIENT_ID,
    '000001' AS TPA_ID,
    '0001' AS TPA_DIV_ID,
    'Cactus' AS DATA_SOURCE_NAME,
    NULLIF(TRIM(GRP_ADR.ID), '') AS OFFICE_ID,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, OFFICE_ID]) AS HUB_OFFICE_HKEY
FROM
    RAWDATA.CACTUS_GROUPADDRESS AS GRP_ADR
INNER JOIN
    RAWDATA.CACTUS_GROUPS AS GRP
    ON GRP_ADR.GROUP_K = GRP.GROUP_K
INNER JOIN
    RAWDATA.CACTUS_ADDRESSES AS ADR
    ON GRP_ADR.ADDRESS_K = ADR.ADDRESS_K
LEFT JOIN
    DUPLICATE_GROUPS AS DUP
    ON GRP.ID = DUP.ID
WHERE
    NULLIF(GRP_ADR.ID, '') IS NOT NULL
    AND NULLIF(GRP_ADR.GROUP_K, '') IS NOT NULL
    AND NULLIF(GRP_ADR.TAXIDNUMBER, '') IS NOT NULL
    AND NULLIF(GRP_ADR.ID, '') IS NOT NULL
    AND NULLIF(GRP.ID, '') IS NOT NULL
    AND (NULLIF(ADR.ADDRESSLINE1, '') IS NOT NULL OR NULLIF(ADR.ADDRESSLINE2, '') IS NOT NULL)
    AND DUP.ID IS NULL
;