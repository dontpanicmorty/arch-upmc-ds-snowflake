CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_DETAIL_RENDERING_PROVIDER_SKYGEN_SELECT_VW
COMMENT = 'Source view for SKYGEN data into LNK_CLAIM_DETAIL_RENDERING_PROVIDER'
AS

SELECT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS CD_TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS CD_TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS CD_TPA_DIV_ID,
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS CD_DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR AS CD_CLAIM_NBR,
DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_NBR AS CD_CLAIM_LINE_NBR,
DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR AS CD_CLAIM_LINE_SEQ_NBR,
DWSKYGEN_CLAIM_DETAIL.PROCEDURE_ADJ_CODE AS CD_CLAIM_LINE_PROCEDURE_ADJ_CODE,
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS P_TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS P_TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS P_TPA_DIV_ID,
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS P_DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_DETAIL.RENDERING_PROVIDER_ID AS P_PROVIDER_ID,
UTIL.FXN_ARRAY_HASH([CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE, P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS LNK_CLAIM_DETAIL_RENDERING_PROVIDER_HKEY,
UTIL.FXN_ARRAY_HASH([CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY,
UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS HUB_PROVIDER_HKEY
FROM RAWDATA.DWSKYGEN_CLAIM_DETAIL
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
WHERE DWSKYGEN_CLAIM_DETAIL.RENDERING_PROVIDER_ID IS NOT NULL


UNION ALL

SELECT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS CD_TPA_CLIENT_ID, 
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS CD_TPA_ID, 
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS CD_TPA_DIV_ID, 
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS CD_DATA_SOURCE_NAME, 
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO AS CD_CLAIM_NBR, 
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.ITEM_NO AS CD_CLAIM_LINE_NBR, 
UTIL.FXN_ARRAY_HASH([SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.BILLED_AMT]) AS CD_CLAIM_LINE_SEQ_NBR,
'N/A' AS CD_CLAIM_LINE_PROCEDURE_ADJ_CODE,
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS P_TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS P_TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS P_TPA_DIV_ID,
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS P_DATA_SOURCE_NAME,
CONCAT('PROVIDER_', SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.PRVD_ID) AS P_PROVIDER_ID,
UTIL.FXN_ARRAY_HASH([CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE, P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS LNK_CLAIM_DETAIL_RENDERING_PROVIDER_HKEY,
UTIL.FXN_ARRAY_HASH([CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY,
UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS HUB_PROVIDER_HKEY

FROM RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR = SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO)
    JOIN RAWDATA.DWSKYGEN_PROVIDER_DETAIL
        ON (DWSKYGEN_PROVIDER_DETAIL.TPA_CLIENT_ID = LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
        AND DWSKYGEN_PROVIDER_DETAIL.TPA_ID = LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
        AND DWSKYGEN_PROVIDER_DETAIL.TPA_DIV_ID = LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
        AND DWSKYGEN_PROVIDER_DETAIL.PROVIDER_ID = CONCAT('PROVIDER_', SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.PRVD_ID))
        
WHERE SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO NOT IN (SELECT CLAIM_NBR FROM RAWDATA.DWSKYGEN_CLAIM_HEADER) --Exclude claims in dwskygen, they supersede
AND SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.PRVD_ID IS NOT NULL
;
