CREATE OR REPLACE VIEW STAGEDATA.LNK_PLAN_PLAN_SEGMENT_MC400UPM_SELECT_VW
COMMENT = 'This is a LNK View between hub_plan and hub_plan_segment'
AS
SELECT
PlanMaster.TpaClient AS P_TPA_CLIENT_ID
,PlanMaster.TpaIdOfClient AS P_TPA_ID
,PlanMaster.TpaDivision AS P_TPA_DIV_ID
,'MC400Upm' AS P_DATA_SOURCE_NAME
,PlanMaster.PlanCode AS P_PLAN_CODE
,TpaCustomer.TpaClient AS PS_TPA_CLIENT_ID
,TpaCustomer.TpaIdOfClient AS PS_TPA_ID
,TpaCustomer.TpaDivision AS PS_TPA_DIV_ID
,'MC400Upm' AS PS_DATA_SOURCE_NAME
,PlanCodeSegmentIdMaster.PlanCode AS PS_PLAN_CODE
,PlanCodeSegmentIdMaster.PlanSegmentId AS PS_PLAN_SEGMENT_CODE
,UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PLAN_CODE, PS_TPA_CLIENT_ID, PS_TPA_DIV_ID, PS_TPA_ID, PS_DATA_SOURCE_NAME, PS_PLAN_CODE, PS_PLAN_SEGMENT_CODE]) AS LNK_PLAN_PLAN_SEGMENT_HKEY
,UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PLAN_CODE]) AS HUB_PLAN_HKEY
,UTIL.FXN_ARRAY_HASH([PS_TPA_CLIENT_ID, PS_TPA_ID, PS_TPA_DIV_ID, PS_DATA_SOURCE_NAME, PS_PLAN_CODE, PS_PLAN_SEGMENT_CODE]) AS HUB_PLAN_SEGMENT_HKEY

FROM RAWDATA.MC400_DWOAO_PLANMASTER PlanMaster
    JOIN RAWDATA.MC400_DWOAO_PLANCODESEGMENTIDMASTER PlanCodeSegmentIdMaster
        ON (PlanCodeSegmentIdMaster.Plancode = PlanMaster.Plancode)
    JOIN RAWDATA.MC400_DWOAO_TPACUSTOMER TpaCustomer
        ON(TpaCustomer.Id = PlanCodeSegmentIdMaster.TpaClientRowId)
    WHERE PlanCodeSegmentIdMaster.PlanSegmentId <> '000'
;

