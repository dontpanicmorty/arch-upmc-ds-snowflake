CREATE OR REPLACE VIEW STAGEDATA.SAT_OFFICE_DETAIL_ESI_SELECT_VW 
COMMENT = 'This is a SAT View containing ESI office detail'
AS
SELECT
    '000001' AS TPA_CLIENT_ID
    ,'000001' AS TPA_ID
    ,'0001' AS TPA_DIV_ID
    ,'ESI' AS DATA_SOURCE_NAME
    ,CONCAT('ESI','Prescriber', PRESCRIBER_ID) AS OFFICE_ID
    ,IFNULL(PRESCRIBER_NAME, 'UNKNOWN') AS OFFICE_NAME
    ,IFF(REGEXP_LIKE(REGEXP_REPLACE(LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL.PRACTICE_ADDRESS_TELEPHONE_NBR, '[()\\-\\s]', ''), '^[0-9]{2,}$')=TRUE, REGEXP_REPLACE(LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL.PRACTICE_ADDRESS_TELEPHONE_NBR, '[()\\-\\s]', ''), NULL)  AS PRIMARY_PHONE_NBR --cleaning to remove parentheses and dashes, and checking that field is a number that is at least 2 digits long
    ,NULL AS PRIMARY_PHONE_EXTENSION_NBR
    ,IFF(REGEXP_LIKE(REGEXP_REPLACE(LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL.MAILING_ADDRESS_TELEPHONE_NBR, '[()\\-\\s]', ''), '^[0-9]{2,}$')=TRUE, REGEXP_REPLACE(LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL.MAILING_ADDRESS_TELEPHONE_NBR, '[()\\-\\s]', ''), NULL)  AS ALTERNATE_PHONE_NBR --cleaning to remove parentheses and dashes, and checking that field is a number that is at least 2 digits long
	,NULL AS ALTERNATE_PHONE_EXTENSION_NBR
	,IFF(REGEXP_LIKE(REGEXP_REPLACE(LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL.PRACTICE_ADDRESS_FAX_NBR, '[()\\-\\s]', ''), '^[0-9]{2,}$')=TRUE, REGEXP_REPLACE(LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL.PRACTICE_ADDRESS_FAX_NBR, '[()\\-\\s]', ''), NULL)  AS PRIMARY_FAX_NBR --cleaning to remove parentheses and dashes, and checking that field is a number that is at least 2 digits long
	,IFF(REGEXP_LIKE(REGEXP_REPLACE(LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL.MAILING_ADDRESS_FAX_NBR, '[()\\-\\s]', ''), '^[0-9]{2,}$')=TRUE, REGEXP_REPLACE(LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL.MAILING_ADDRESS_FAX_NBR, '[()\\-\\s]', ''), NULL)  AS ALTERNATE_FAX_NBR --cleaning to remove parentheses and dashes, and checking that field is a number that is at least 2 digits long
	,NULL AS EMAIL_ADDRESS
	,NULL AS OFFICE_MANAGER_NAME
	,NULL AS HANDICAP_ACCESS_IND
	,NULL AS TELEHEALTH_IND
	,NULL AS RECEIVES_MAIL_IND
	,NULL AS EPRESCRIBE_IND
	,NULL AS MA_SUPER_PCP_IND
	,NULL AS EMR_SYSTEM_NAME
    , UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID,
                        TPA_ID, 
                        TPA_DIV_ID, 
                        DATA_SOURCE_NAME, 
                        OFFICE_ID]
                        ) AS HUB_OFFICE_HKEY
    ,UTIL.FXN_ARRAY_HASH([OFFICE_NAME
                        ,PRIMARY_PHONE_NBR
                        ,PRIMARY_PHONE_EXTENSION_NBR
	                    ,ALTERNATE_PHONE_NBR
	                    ,ALTERNATE_PHONE_EXTENSION_NBR
	                    ,PRIMARY_FAX_NBR
						,ALTERNATE_FAX_NBR
	                    ,EMAIL_ADDRESS
	                    ,OFFICE_MANAGER_NAME
	                    ,HANDICAP_ACCESS_IND
	                    ,TELEHEALTH_IND
	                    ,RECEIVES_MAIL_IND
	                    ,EPRESCRIBE_IND
	                    ,MA_SUPER_PCP_IND
	                    ,EMR_SYSTEM_NAME]
                        ) AS HASH_DIFF
FROM STAGEDATA.LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL
WHERE (PRIMARY_PHONE_NBR IS NOT NULL OR PRIMARY_FAX_NBR IS NOT NULL)

UNION 

SELECT DISTINCT
    '000001' AS TPA_CLIENT_ID
    ,'000001' AS TPA_ID
    ,'0001' AS TPA_DIV_ID
    ,'ESI' AS DATA_SOURCE_NAME
    ,CONCAT('ESI', 'Pharmacy', NABP_NBR, IFF(LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_NPI = 'UNKNOWN', '', LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_NPI)) AS OFFICE_ID
    ,IFNULL(PHARMACY_NAME, 'UNKNOWN') AS OFFICE_NAME
    ,IFF(REGEXP_LIKE(REGEXP_REPLACE(LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_TELEPHONE_NUMBER, '[()\\-\\s]', ''), '^[0-9]{2,}$')=TRUE, REGEXP_REPLACE(LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_TELEPHONE_NUMBER, '[()\\-\\s]', ''), NULL) AS PRIMARY_PHONE_NBR  --cleaning to remove parentheses and dashes, and checking that field is a number that is at least 2 digits long
    ,NULL AS PRIMARY_PHONE_EXTENSION_NBR
	,NULL AS ALTERNATE_PHONE_NBR
	,NULL AS ALTERNATE_PHONE_EXTENSION_NBR
	,NULL AS PRIMARY_FAX_NBR
	,NULL AS ALTERNATE_FAX_NBR
	,NULL AS EMAIL_ADDRESS
	,NULL AS OFFICE_MANAGER_NAME
	,NULL AS HANDICAP_ACCESS_IND
	,NULL AS TELEHEALTH_IND
	,NULL AS RECEIVES_MAIL_IND
	,NULL AS EPRESCRIBE_IND
	,NULL AS MA_SUPER_PCP_IND
	,NULL AS EMR_SYSTEM_NAME
    ,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID,
                        TPA_ID, 
                        TPA_DIV_ID, 
                        DATA_SOURCE_NAME, 
                        OFFICE_ID]
                        ) AS HUB_OFFICE_HKEY
    ,UTIL.FXN_ARRAY_HASH([OFFICE_NAME
                        ,PRIMARY_PHONE_NBR
                        ,PRIMARY_PHONE_EXTENSION_NBR
	                    ,ALTERNATE_PHONE_NBR
	                    ,ALTERNATE_PHONE_EXTENSION_NBR
	                    ,PRIMARY_FAX_NBR
						,ALTERNATE_FAX_NBR
	                    ,EMAIL_ADDRESS
	                    ,OFFICE_MANAGER_NAME
	                    ,HANDICAP_ACCESS_IND
	                    ,TELEHEALTH_IND
	                    ,RECEIVES_MAIL_IND
	                    ,EPRESCRIBE_IND
	                    ,MA_SUPER_PCP_IND
	                    ,EMR_SYSTEM_NAME]
                        ) AS HASH_DIFF
FROM STAGEDATA.LKP_CLAIM_PHARMACY_DETAIL
JOIN STAGEDATA.LKP_CLAIM_PHARMACY_CLAIM
    ON (LKP_CLAIM_PHARMACY_DETAIL.NABP_NBR = LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_NUMBER)
WHERE PRIMARY_PHONE_NBR IS NOT NULL
;