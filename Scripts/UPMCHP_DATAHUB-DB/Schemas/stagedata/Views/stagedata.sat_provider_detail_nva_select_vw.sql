CREATE OR REPLACE VIEW STAGEDATA.SAT_PROVIDER_DETAIL_NVA_SELECT_VW
COMMENT = 'This is a SAT View containing Provider Detail data'
AS
SELECT DISTINCT
'000001' AS TPA_CLIENT_ID
,'000001' AS TPA_ID
,'0001' AS TPA_DIV_ID
,'NVA' AS DATA_SOURCE_NAME
,CONCAT(PROVIDER_NPI, TRIM(ECP_TYPE)) AS PROVIDER_ID
,CASE UPPER(TRIM(ECP_TYPE))
	WHEN 'DOCTOR' THEN 'Practitioner'
	WHEN 'CLINIC' THEN 'Facility'
	ELSE 'Unknown'
END AS PROVIDER_TYPE_NAME
,CASE PROVIDER_TYPE_NAME
	WHEN 'Practitioner' THEN CONCAT(REGEXP_REPLACE(LAST_NAME, '\\s(OD|ODD|MD)$'),', ',REGEXP_REPLACE(FIRST_NAME, '\\s.\.?$'))
	WHEN 'Facility' THEN FULL_NAME
	ELSE CONCAT('NVA NPI ', PROVIDER_NPI)
END AS FULL_NAME
,REGEXP_REPLACE(LAST_NAME, '\\s(OD|ODD|MD)$') AS LAST_NAME
,REGEXP_REPLACE(FIRST_NAME, '\\s.\.?$') AS FIRST_NAME
,NULL AS MIDDLE_NAME
,NULL AS MIDDLE_INITIAL_NAME
,IFNULL(GENDER,'Unknown') AS GENDER_NAME
,NULL AS EMAIL_ADDRESS
,NULL AS SOCIAL_SECURITY_NBR
,DEGREE AS DEGREE_TEXT
,SUFFIX AS SUFFIX_NAME
,NULL AS LOCUM_TENENS_IND
,NULL AS INVISIBLE_PROVIDER_IND
,NULL AS TEMPORARY_PROVIDER_IND
,NULL AS DATE_OF_BIRTH
,NULL AS PRIMARY_PREFERRED_DELIVERY_METHOD_CODE
,NULL AS BOARD_CERTIFIED_IND
,MEDICAID_INDICATOR AS STATE_MEDICAID_ID
,SPECIALITY AS PRIMARY_SPECIALTY_NAME
,PROVIDER_NPI AS NATIONAL_PROVIDER_ID
,NULL AS PRIMARY_TAXONOMY_CODE
,NULL AS PRESCRIBER_SOURCE_CODE
,NULL AS UPIN_NBR
,NULL AS PROVIDER_START_DATE
,NULL AS PROVIDER_ACTIVE_IND
,NULL AS FACILITY_INCEPTION_DATE
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CONCAT(PROVIDER_NPI, TRIM(ECP_TYPE))]) AS HUB_PROVIDER_HKEY
,UTIL.FXN_ARRAY_HASH([
    PROVIDER_TYPE_NAME,
    FULL_NAME,
    FIRST_NAME,
    LAST_NAME,
    MIDDLE_NAME,
    MIDDLE_INITIAL_NAME,
    GENDER_NAME,
    EMAIL_ADDRESS,
    SOCIAL_SECURITY_NBR,
    DEGREE_TEXT,
    SUFFIX_NAME,
    LOCUM_TENENS_IND,
    INVISIBLE_PROVIDER_IND,
    TEMPORARY_PROVIDER_IND,
    NATIONAL_PROVIDER_ID,
    DATE_OF_BIRTH,
    PRIMARY_PREFERRED_DELIVERY_METHOD_CODE,
    BOARD_CERTIFIED_IND,
    STATE_MEDICAID_ID,
    PRIMARY_SPECIALTY_NAME,
    PRIMARY_TAXONOMY_CODE,
    PRESCRIBER_SOURCE_CODE,
    UPIN_NBR, 
    PROVIDER_START_DATE, 
    PROVIDER_ACTIVE_IND, 
    FACILITY_INCEPTION_DATE
]) AS HASH_DIFF
FROM RAWDATA.NVA_PROVIDER
QUALIFY ROW_NUMBER() -- Get the most current values for a given npi/ecp_type across all the files
    OVER(PARTITION BY NVA_PROVIDER.PROVIDER_NPI, TRIM(NVA_PROVIDER.ECP_TYPE)
        ORDER BY SPLIT_PART(SPLIT_PART(NVA_PROVIDER.FILENAME, '_', 7), '.', 1) DESC) = 1
;