CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_PRESCRIBER_ESI_SELECT_VW
COMMENT = 'Source view for ESI data into LNK_CLAIM_PRESCRIBER'
AS
SELECT
 '000001' AS C_TPA_CLIENT_ID
,'000001' AS C_TPA_ID
,'0001' AS C_TPA_DIV_ID
,'ESI' AS C_DATA_SOURCE_NAME
,LKP_CLAIM_PHARMACY_CLAIM.CLAIM_ID AS C_CLAIM_NBR
,'000001' AS P_TPA_CLIENT_ID
,'000001' AS P_TPA_ID
,'0001' AS P_TPA_DIV_ID
,'ESI' AS P_DATA_SOURCE_NAME
,CONCAT('ESI', 'Prescriber', LKP_CLAIM_PHARMACY_CLAIM.PRESCRIBER_IDENTIFIER) AS P_OFFICE_ID
,UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_OFFICE_ID]) AS LNK_CLAIM_PRESCRIBER_HKEY
,UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY
,UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_OFFICE_ID]) AS HUB_OFFICE_HKEY
FROM STAGEDATA.LKP_CLAIM_PHARMACY_CLAIM
    JOIN STAGEDATA.LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL
        ON (LKP_CLAIM_PHARMACY_CLAIM.PRESCRIBER_IDENTIFIER = LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL.PRESCRIBER_ID)
;