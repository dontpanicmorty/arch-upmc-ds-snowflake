CREATE OR REPLACE VIEW STAGEDATA.SAT_OFFICE_DETAIL_CACTUS_SELECT_VW(
	TPA_CLIENT_ID,
	TPA_ID,
	TPA_DIV_ID,
	DATA_SOURCE_NAME,
	OFFICE_ID,
	OFFICE_NAME,
	PRIMARY_PHONE_NBR,
	PRIMARY_PHONE_EXTENSION_NBR,
	ALTERNATE_PHONE_NBR,
	ALTERNATE_PHONE_EXTENSION_NBR,
	PRIMARY_FAX_NBR,
	ALTERNATE_FAX_NBR,
	EMAIL_ADDRESS,
	OFFICE_MANAGER_NAME,
	HANDICAP_ACCESS_IND,
	TELEHEALTH_IND,
	RECEIVES_MAIL_IND,
	EPRESCRIBE_IND,
	MA_SUPER_PCP_IND,
	EMR_SYSTEM_NAME,
	HUB_OFFICE_HKEY,
	HASH_DIFF
) COMMENT='This is a satellite office detail view containing Cactus data'
AS
WITH DUPLICATE_PROVIDERS AS (
    SELECT PRV.ID
    FROM
        RAWDATA.CACTUS_PROVIDERS AS PRV
    INNER JOIN
        RAWDATA.CACTUS_ENTITYASSIGNMENTS AS EA
        ON PRV.PROVIDER_K = EA.PROVIDER_K
    GROUP BY PRV.ID
    HAVING COUNT(DISTINCT PRV.PROVIDER_K) > 1
)
, DUPLICATE_GROUPS AS (
    SELECT ID
    FROM RAWDATA.CACTUS_GROUPS
    GROUP BY ID HAVING COUNT(*) > 1
)
, DISTINCT_ENTITYASSIGNMENTS AS (
    SELECT DISTINCT PROVIDER_K
    FROM RAWDATA.CACTUS_ENTITYASSIGNMENTS
    WHERE RECORDTYPE = 'E'
)
, TELEHEALTH_PROVIDERS AS (
    SELECT DISTINCT
        TRIM(REF_A.DESCRIPTION) AS SERVICE,
        PRV.ID,
        ADR.ADDRESSLINE1,
        ADR.ADDRESSLINE2,
        PRV_ADR.USERDEF_C1,
        ADR.ADDRESS_K
    FROM
        RAWDATA.CACTUS_SERVICECATEGORYREFERENCES AS SCR_A
    LEFT OUTER JOIN
        RAWDATA.CACTUS_REFTABLE AS REF_A
        ON SCR_A.SERVICECATEGORY_K = REF_A.REFTABLE_K
    LEFT OUTER JOIN
        RAWDATA.CACTUS_SERVICECATEGORYREFERENCES AS SCR_B
        ON SCR_A.PARENT_K = SCR_B.SERVICECATEGORYREFERENCE_K
    LEFT OUTER JOIN
        RAWDATA.CACTUS_REFTABLE AS REF_B
        ON SCR_B.SERVICECATEGORY_K = REF_B.REFTABLE_K
    LEFT OUTER JOIN
        RAWDATA.CACTUS_ADDRESSES AS ADR
        ON SCR_B.PARENT_K = ADR.ADDRESS_K
    LEFT OUTER JOIN
        RAWDATA.CACTUS_PROVIDERADDRESSES AS PRV_ADR
        ON ADR.ADDRESS_K = PRV_ADR.ADDRESS_K
    LEFT OUTER JOIN
        RAWDATA.CACTUS_PROVIDERS AS PRV
        ON PRV_ADR.PROVIDER_K = PRV.PROVIDER_K
    WHERE
        NULLIF(ADR.ADDRESS_K, '') IS NOT NULL
        AND REF_A.DESCRIPTION = 'Telehealth'
)
, TELEHEALTH_GROUPS AS (
    SELECT DISTINCT
        TRIM(REF_A.DESCRIPTION) AS SERVICE,
        GRP.ID AS GROUPID,
        ADR.ADDRESSLINE1,
        ADR.ADDRESSLINE2,
        GRP_ADR.ID AS OFFICEID,
        ADR.ADDRESS_K
    FROM
        RAWDATA.CACTUS_SERVICECATEGORYREFERENCES AS SCR_A
    LEFT OUTER JOIN
        RAWDATA.CACTUS_REFTABLE AS REF_A
        ON SCR_A.SERVICECATEGORY_K = REF_A.REFTABLE_K
    LEFT OUTER JOIN
        RAWDATA.CACTUS_SERVICECATEGORYREFERENCES AS SCR_B
        ON SCR_A.PARENT_K = SCR_B.SERVICECATEGORYREFERENCE_K
    LEFT OUTER JOIN
        RAWDATA.CACTUS_REFTABLE AS REF_B
        ON SCR_B.SERVICECATEGORY_K = REF_B.REFTABLE_K
    LEFT OUTER JOIN
        RAWDATA.CACTUS_ADDRESSES AS ADR
        ON SCR_B.PARENT_K = ADR.ADDRESS_K
    LEFT OUTER JOIN
        RAWDATA.CACTUS_GROUPADDRESS AS GRP_ADR
        ON ADR.ADDRESS_K = GRP_ADR.ADDRESS_K
    LEFT OUTER JOIN
        RAWDATA.CACTUS_GROUPS AS GRP
        ON GRP_ADR.GROUP_K = GRP.GROUP_K
    WHERE
        NULLIF(ADR.ADDRESS_K, '') IS NOT NULL
        AND REF_A.DESCRIPTION = 'Telehealth'
)
,GROUP_OFFICES as (
SELECT DISTINCT
    '000001' AS  CTE_TPA_CLIENT_ID,
    '000001' AS CTE_TPA_ID,
    '0001' AS CTE_TPA_DIV_ID,
    'Cactus' AS CTE_DATA_SOURCE_NAME,
    NULLIF(TRIM(GRP_ADR.ID), '') AS  CTE_OFFICE_ID,
    NULLIF(TRIM(GRP_ADR.ALTERNATEGROUPNAME), '') AS  CTE_OFFICE_NAME,
    NULLIF(TRIM(ADR.PHONE), '') AS CTE_PRIMARY_PHONE_NBR,
    NULLIF(TRIM(ADR.EXTENSION), '') AS  CTE_PRIMARY_PHONE_EXTENSION_NBR,
    NULLIF(TRIM(ADR.ALTERNATEPHONE), '') AS  CTE_ALTERNATE_PHONE_NBR,
    NULLIF(TRIM(ADR.ALTERNATEEXTENSION), '') AS  CTE_ALTERNATE_PHONE_EXTENSION_NBR,
    NULLIF(TRIM(ADR.FAX), '') AS CTE_PRIMARY_FAX_NBR,
    NULL AS  CTE_ALTERNATE_FAX_NBR,
    IFF(GRP_ADR.EMAILADDRESS NOT LIKE '%@%', NULL, TRIM(GRP_ADR.EMAILADDRESS)) AS  CTE_EMAIL_ADDRESS,
    NULLIF(TRIM(ADR.OFFICEMANAGERNAME), '') AS  CTE_OFFICE_MANAGER_NAME,
    CASE
        WHEN GRP_ADR.USERDEF_L2 = 1 THEN TRUE
        WHEN GRP_ADR.USERDEF_L2 IS NULL THEN NULL
        ELSE FALSE
    END AS  CTE_HANDICAP_ACCESS_IND,
    IFF(TEL_GRP.SERVICE IS NULL, FALSE, TRUE) AS  CTE_TELEHEALTH_IND,
    CASE
        WHEN GRP_ADR.USERDEF_RTK1 = 'D0PN0QHNO5' THEN FALSE
        WHEN GRP_ADR.USERDEF_RTK1 IS NULL THEN NULL
        ELSE TRUE
    END AS  CTE_RECEIVES_MAIL_IND,
    CASE
        WHEN ADR.USERDEF_L1 = 1 THEN TRUE
        WHEN ADR.USERDEF_L1 IS NULL THEN NULL
        ELSE FALSE
    END AS  CTE_EPRESCRIBE_IND,
    CASE
        WHEN GRP_ADR.USERDEF_RTK2 = 'D0XP0N0CNG' THEN TRUE
        WHEN GRP_ADR.USERDEF_RTK2 IS NULL THEN NULL
        ELSE FALSE
    END AS  CTE_MA_SUPER_PCP_IND,
    NULLIF(TRIM(REF.DESCRIPTION), 'No Value Specified') AS  CTE_EMR_SYSTEM_NAME,
    UTIL.FXN_ARRAY_HASH([ CTE_TPA_CLIENT_ID,  CTE_TPA_ID,  CTE_TPA_DIV_ID,  CTE_DATA_SOURCE_NAME,  CTE_OFFICE_ID]) AS  CTE_HUB_OFFICE_HKEY,
    UTIL.FXN_ARRAY_HASH([
         CTE_OFFICE_NAME,
         CTE_PRIMARY_PHONE_NBR,
         CTE_PRIMARY_PHONE_EXTENSION_NBR,
         CTE_ALTERNATE_PHONE_NBR,
         CTE_ALTERNATE_PHONE_EXTENSION_NBR,
         CTE_PRIMARY_FAX_NBR,
         CTE_ALTERNATE_FAX_NBR,
         CTE_EMAIL_ADDRESS,
         CTE_OFFICE_MANAGER_NAME,
         CTE_HANDICAP_ACCESS_IND,
         CTE_TELEHEALTH_IND,
         CTE_RECEIVES_MAIL_IND,
         CTE_EPRESCRIBE_IND,
         CTE_MA_SUPER_PCP_IND,
         CTE_EMR_SYSTEM_NAME
    ]) AS CTE_HASH_DIFF
FROM
    RAWDATA.CACTUS_GROUPADDRESS AS GRP_ADR
LEFT JOIN
    RAWDATA.CACTUS_GROUPS AS GRP
    ON GRP_ADR.GROUP_K = GRP.GROUP_K
LEFT JOIN
    RAWDATA.CACTUS_ADDRESSES AS ADR
    ON GRP_ADR.ADDRESS_K = ADR.ADDRESS_K
LEFT JOIN
    RAWDATA.CACTUS_REFTABLE AS REF
    ON REF.REFTABLE_K = ADR.USERDEF_RTK1
LEFT JOIN
    DUPLICATE_GROUPS AS DUP
    ON GRP.ID = DUP.ID
LEFT JOIN
    TELEHEALTH_GROUPS AS TEL_GRP
    ON GRP.ID = TEL_GRP.GROUPID
    AND (
        CASE
            WHEN ADR.ADDRESSLINE1 = '' AND ADR.ADDRESSLINE2 != '' THEN TRIM(ADR.ADDRESSLINE2)
            WHEN ADR.ADDRESSLINE1 = '' AND ADR.ADDRESSLINE2 = '' THEN NULL
            ELSE TRIM(ADR.ADDRESSLINE1)
        END
    ) = TEL_GRP.ADDRESSLINE1
    AND TRIM(ADR.ADDRESSLINE2) = TEL_GRP.ADDRESSLINE2
    AND GRP_ADR.ID = TEL_GRP.OFFICEID
    AND ADR.ADDRESS_K = TEL_GRP.ADDRESS_K
WHERE
    NULLIF(GRP_ADR.ID, '') IS NOT NULL
    AND NULLIF(GRP_ADR.GROUP_K, '') IS NOT NULL
    AND NULLIF(GRP_ADR.TAXIDNUMBER, '') IS NOT NULL
    AND NULLIF(GRP.ID, '') IS NOT NULL
    AND (NULLIF(ADR.ADDRESSLINE1, '') IS NOT NULL OR NULLIF(ADR.ADDRESSLINE2, '') IS NOT NULL)
    AND DUP.ID IS NULL
    AND GRP_ADR.ACTIVE = TRUE
)
SELECT
    CTE_TPA_CLIENT_ID
    ,CTE_TPA_ID
    ,CTE_TPA_DIV_ID
    ,CTE_DATA_SOURCE_NAME
    ,CTE_OFFICE_ID
    ,CTE_OFFICE_NAME
    ,CTE_PRIMARY_PHONE_NBR
    ,CTE_PRIMARY_PHONE_EXTENSION_NBR
    ,CTE_ALTERNATE_PHONE_NBR
    ,CTE_ALTERNATE_PHONE_EXTENSION_NBR
    ,CTE_PRIMARY_FAX_NBR
    ,CTE_ALTERNATE_FAX_NBR
    ,CTE_EMAIL_ADDRESS
    ,CTE_OFFICE_MANAGER_NAME
    ,CTE_HANDICAP_ACCESS_IND
    ,CTE_TELEHEALTH_IND
    ,CTE_RECEIVES_MAIL_IND
    ,CTE_EPRESCRIBE_IND
    ,CTE_MA_SUPER_PCP_IND
    ,CTE_EMR_SYSTEM_NAME
    ,CTE_HUB_OFFICE_HKEY
    ,CTE_HASH_DIFF
FROM
    GROUP_OFFICES

UNION ALL

SELECT DISTINCT
    '000001' AS TPA_CLIENT_ID,
    '000001' AS TPA_ID,
    '0001' AS TPA_DIV_ID,
    'Cactus' AS DATA_SOURCE_NAME,
    NULLIF(TRIM(PRV_ADR.USERDEF_C1), '') AS OFFICE_ID,
    NULLIF(TRIM(GRP_ADR.ALTERNATEGROUPNAME), '') AS OFFICE_NAME,
    NULLIF(TRIM(ADR.PHONE), '') AS PRIMARY_PHONE_NBR,
    NULLIF(TRIM(ADR.EXTENSION), '') AS PRIMARY_PHONE_EXTENSION_NBR,
    NULLIF(TRIM(ADR.ALTERNATEPHONE), '') AS ALTERNATE_PHONE_NBR,
    NULLIF(TRIM(ADR.ALTERNATEEXTENSION), '') AS ALTERNATE_PHONE_EXTENSION_NBR,
    NULLIF(TRIM(ADR.FAX), '') AS PRIMARY_FAX_NBR,
    NULL AS ALTERNATE_FAX_NBR,
    IFF(PRV_ADR.EMAILADDRESS NOT LIKE '%@%', NULL, TRIM(PRV_ADR.EMAILADDRESS)) AS EMAIL_ADDRESS,
    NULLIF(TRIM(ADR.OFFICEMANAGERNAME), '') AS OFFICE_MANAGER_NAME,
    IFF(GRP_ADR.USERDEF_L2 = 1, TRUE, FALSE) AS HANDICAP_ACCESS_IND,
    IFF(TEL_PRV.SERVICE IS NULL, FALSE, TRUE) AS TELEHEALTH_IND,
    IFF(GRP_ADR.USERDEF_RTK1 = 'D0PN0QHNO5', FALSE, TRUE) AS RECEIVES_MAIL_IND,
    IFF(ADR.USERDEF_L1 = 1, TRUE, FALSE) AS EPRESCRIBE_IND,
    IFF(GRP_ADR.USERDEF_RTK2 = 'D0XP0N0CNG', TRUE, FALSE) AS MA_SUPER_PCP_IND,
    NULLIF(TRIM(REF.DESCRIPTION), 'No Value Specified') AS EMR_SYSTEM_NAME,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME,OFFICE_ID]) AS HUB_OFFICE_HKEY,
    UTIL.FXN_ARRAY_HASH([
        OFFICE_NAME,
        PRIMARY_PHONE_NBR,
        PRIMARY_PHONE_EXTENSION_NBR,
        ALTERNATE_PHONE_NBR,
        ALTERNATE_PHONE_EXTENSION_NBR,
        PRIMARY_FAX_NBR,
        ALTERNATE_FAX_NBR,
        EMAIL_ADDRESS,
        OFFICE_MANAGER_NAME,
        HANDICAP_ACCESS_IND,
        TELEHEALTH_IND,
        RECEIVES_MAIL_IND,
        EPRESCRIBE_IND,
        MA_SUPER_PCP_IND,
        EMR_SYSTEM_NAME
    ]) AS HASH_DIFF

FROM
    RAWDATA.CACTUS_PROVIDERADDRESSES AS PRV_ADR
LEFT JOIN GROUP_OFFICES on GROUP_OFFICES. CTE_OFFICE_ID = PRV_ADR.USERDEF_C1
LEFT JOIN
    RAWDATA.CACTUS_PROVIDERS AS PRV
    ON PRV_ADR.PROVIDER_K = PRV.PROVIDER_K
INNER JOIN
    DISTINCT_ENTITYASSIGNMENTS AS DEA
    ON PRV.PROVIDER_K = DEA.PROVIDER_K
LEFT JOIN
    RAWDATA.CACTUS_ADDRESSES AS ADR
    ON PRV_ADR.ADDRESS_K = ADR.ADDRESS_K
LEFT JOIN
    RAWDATA.CACTUS_GROUPSPROVIDERSADDRESSES AS GRP_PRV_ADR
    ON PRV_ADR.PROVIDERADDRESS_K = GRP_PRV_ADR.PROVIDERADDRESS_K
LEFT JOIN
    RAWDATA.CACTUS_GROUPADDRESS AS GRP_ADR
    ON GRP_PRV_ADR.GROUPADDRESS_K = GRP_ADR.GROUPADDRESS_K
LEFT JOIN
    TELEHEALTH_PROVIDERS AS TEL_PRV
    ON PRV.ID = TEL_PRV.ID
    AND (
        CASE
            WHEN ADR.ADDRESSLINE1 = '' AND ADR.ADDRESSLINE2 != '' THEN TRIM(ADR.ADDRESSLINE2)
            WHEN ADR.ADDRESSLINE1 = '' AND ADR.ADDRESSLINE2 = '' THEN NULL
            ELSE TRIM(ADR.ADDRESSLINE1)
        END
    ) = TEL_PRV.ADDRESSLINE1
    AND TRIM(ADR.ADDRESSLINE2) = TEL_PRV.ADDRESSLINE2
    AND PRV_ADR.USERDEF_C1 = TEL_PRV.USERDEF_C1
    AND ADR.ADDRESS_K = TEL_PRV.ADDRESS_K
LEFT JOIN
    RAWDATA.CACTUS_REFTABLE AS REF
    ON ADR.USERDEF_RTK1 = REF.REFTABLE_K
LEFT JOIN
    DUPLICATE_PROVIDERS AS DUP
    ON PRV.ID = DUP.ID
WHERE
    NULLIF(PRV_ADR.PROVIDER_K, '') IS NOT NULL
    AND NULLIF(PRV_ADR.USERDEF_C1, '') IS NOT NULL
    AND NULLIF(PRV.ID, '') IS NOT NULL
    AND PRV.STATUS_RTK NOT IN ('#0000K408T','#0000K408U','#0000K408S')
    AND (PRV.INDIVIDUALINSTITUTIONFLAG != 1 OR PRV.LASTNAME != '' OR PRV.FIRSTNAME != '')
    AND (PRV.INDIVIDUALINSTITUTIONFLAG != 2 OR (PRV.LONGNAME != '' AND PRV_ADR.ACTIVE = 1))
    AND (NULLIF(ADR.ADDRESSLINE1, '') IS NOT NULL OR NULLIF(ADR.ADDRESSLINE2, '') IS NOT NULL)
    AND DUP.ID IS NULL
    AND PRV_ADR.ACTIVE = TRUE
    AND GROUP_OFFICES. CTE_OFFICE_ID IS NULL  
ORDER BY CTE_OFFICE_ID, CTE_HASH_DIFF
;