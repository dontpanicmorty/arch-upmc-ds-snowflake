CREATE OR REPLACE VIEW STAGEDATA.SAT_MEMBER_CURRENT_ATTRIBUTE_MC400DNT_SELECT_VW AS
SELECT
 '000001' AS TPA_CLIENT_ID
,'000001' AS TPA_ID
,'0001' AS TPA_DIV_ID
,'MC400Dnt' AS DATA_SOURCE_NAME
,TRIM(Members.MEMBERNBR) AS MEMBER_NBR
,NULL AS ELIG_STATUS_CODE01
,NULL AS ELIG_STATUS_DESC01
,NULL AS ELIG_STATUS_CODE02
,NULL AS ELIG_STATUS_DESC02
,NULL AS PART_D_RISK_FACTOR
,NULL AS CHRONIC_CONDITION_CNT
,NULL AS PRIVACY_RESTRICTION_FLAG -- 019
,NULL AS PRIVACY_ALERT_FLAG -- 033
,NULL AS PREGNANCY_DUE_DATE
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEMBER_NBR]) AS HUB_MEMBER_HKEY

FROM RAWDATA.MC400_DWDNV_MEMBERS Members
WHERE Members.MemberNbr <> '99999999901' --this is a junk catch all member number
;
