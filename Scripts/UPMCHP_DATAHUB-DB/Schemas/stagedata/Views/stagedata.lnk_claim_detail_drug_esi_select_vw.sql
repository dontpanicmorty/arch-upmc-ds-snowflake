CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_DETAIL_DRUG_ESI_SELECT_VW
COMMENT = 'Link between hub_claim_detail and hub_drug'
AS
SELECT
'000001' AS CD_TPA_CLIENT_ID
,'000001' AS CD_TPA_ID
,'0001' AS CD_TPA_DIV_ID
,'ESI' AS CD_DATA_SOURCE_NAME
,LKP_CLAIM_PHARMACY_CLAIM.CLAIM_ID AS CD_CLAIM_NBR
,LKP_CLAIM_PHARMACY_CLAIM.CLAIM_ID AS CD_CLAIM_LINE_NBR
,LKP_CLAIM_PHARMACY_CLAIM.XREF_CLAIM_ID AS CD_CLAIM_LINE_SEQ_NBR
,LKP_CLAIM_PHARMACY_CLAIM.TRANSACTION_TYPE_CODE AS CD_CLAIM_LINE_PROCEDURE_ADJ_CODE
,'000001' AS D_TPA_CLIENT_ID
,'000001' AS D_TPA_ID
,'0001' AS D_TPA_DIV_ID
,'FDB' AS D_DATA_SOURCE_NAME
,LKP_CLAIM_DRUG_VW.NDC_DRUG_CODE AS D_NDC_CODE
,UTIL.FXN_ARRAY_HASH([CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE, D_TPA_CLIENT_ID, D_TPA_ID, D_TPA_DIV_ID, D_DATA_SOURCE_NAME, D_NDC_CODE]) AS LNK_CLAIM_DETAIL_DRUG_HKEY
,UTIL.FXN_ARRAY_HASH([CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY
,UTIL.FXN_ARRAY_HASH([D_TPA_CLIENT_ID, D_TPA_ID, D_TPA_DIV_ID, D_DATA_SOURCE_NAME, D_NDC_CODE]) AS HUB_DRUG_HKEY
 
FROM STAGEDATA.LKP_CLAIM_PHARMACY_CLAIM
JOIN STAGEDATA.LKP_CLAIM_DRUG_VW
    ON LKP_CLAIM_PHARMACY_CLAIM.NDC_NUMBER = LKP_CLAIM_DRUG_VW.NDC_DRUG_CODE
;