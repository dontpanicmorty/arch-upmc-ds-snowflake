!set variable_substitution=true;
CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_AUTHORIZATION_SKYGEN_SELECT_VW
COMMENT = 'This is a SAT View containing Skygen AUTHORIZATION Header data'
AS

SELECT 
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME,
    DWSKYGEN_CLAIM_AUTHORIZATION.AUTHORIZATION_NBR,
    'dental' AS CARE_TYPE_NAME,
    DWSKYGEN_CLAIM_AUTHORIZATION.STATUS_DESC,
    DWSKYGEN_CLAIM_AUTHORIZATION.DETERMINATION_STATUS_DESC,
    DWSKYGEN_CLAIM_AUTHORIZATION.DETERMINATION_DATE AS DETERMINATION_DATE,
    IFNULL(DWSKYGEN_CLAIM_AUTHORIZATION.PLAN_CODE, LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.PLAN_CODE) AS PLAN_CODE,
    IFNULL(DWSKYGEN_CLAIM_AUTHORIZATION.PLAN_TYPE_CODE, LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.PLAN_TYPE) AS PLAN_TYPE_CODE,
    IFNULL(LOB_PLAN_TYPE.LINE_OF_BUSINESS_CODE, 'UNK') AS LINE_OF_BUSINESS_CODE,
    UTIL.FXN_ARRAY_HASH([LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID, LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID, LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID, DATA_SOURCE_NAME, DWSKYGEN_CLAIM_AUTHORIZATION.AUTHORIZATION_NBR]) AS HUB_CLAIM_AUTHORIZATION_HKEY,
    UTIL.FXN_ARRAY_HASH([CARE_TYPE_NAME,
                        STATUS_DESC,
                        DETERMINATION_STATUS_DESC,
                        DETERMINATION_DATE,
                        IFNULL(DWSKYGEN_CLAIM_AUTHORIZATION.PLAN_CODE, LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.PLAN_CODE),
                        IFNULL(DWSKYGEN_CLAIM_AUTHORIZATION.PLAN_TYPE_CODE, LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.PLAN_TYPE),
                        LINE_OF_BUSINESS_CODE]) AS HASH_DIFF
FROM RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION
    JOIN STAGEDATA.LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN
        ON (DWSKYGEN_CLAIM_AUTHORIZATION.AUTHORIZATION_NBR = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.AUTHORIZATION_NBR)
    LEFT OUTER JOIN &{IDAP_LAKE}.NETWORK.LOB_PLAN_TYPE
        ON (LOB_PLAN_TYPE.TPA_CLIENT_ID = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID
        AND LOB_PLAN_TYPE.TPA_ID = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID
        AND LOB_PLAN_TYPE.TPA_DIV_ID = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID
        AND LOB_PLAN_TYPE.PLAN_TYPE = IFNULL(DWSKYGEN_CLAIM_AUTHORIZATION.PLAN_TYPE_CODE, LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.PLAN_TYPE))

UNION ALL

SELECT DISTINCT
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME,
    SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER AS AUTHORIZATION_NBR,
    'dental' AS CARE_TYPE_NAME,
    CASE
        WHEN AUTHORIZATION_STATUS = '1' THEN 'Valid'
        WHEN AUTHORIZATION_STATUS = '2' THEN 'Voided'
        ELSE 'Unknown'
    END AS STATUS_DESC,
    CASE
        WHEN AUTHORIZATION_DETERMINATION_STATUS = '1' THEN 'Pending'
        WHEN AUTHORIZATION_DETERMINATION_STATUS = '2' THEN 'Approved with Denials'
        WHEN AUTHORIZATION_DETERMINATION_STATUS = '3' THEN 'Denied'
        WHEN AUTHORIZATION_DETERMINATION_STATUS = '4' THEN 'Approved'
        ELSE 'Unknown'
    END AS DETERMINATION_STATUS_DESC,
    TO_DATE(SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.INITIAL_DETERMINATION_DATE) AS DETERMINATION_DATE,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.PLAN_CODE AS PLAN_CODE,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.PLAN_TYPE AS PLAN_TYPE_CODE,
    IFNULL(LOB_PLAN_TYPE.LINE_OF_BUSINESS_CODE, 'UNK') AS LINE_OF_BUSINESS_CODE,
    UTIL.FXN_ARRAY_HASH([LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID, LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID, LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID, DATA_SOURCE_NAME, SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER]) AS HUB_CLAIM_AUTHORIZATION_HKEY,
    UTIL.FXN_ARRAY_HASH([CARE_TYPE_NAME,
                        STATUS_DESC,
                        DETERMINATION_STATUS_DESC,
                        TO_DATE(SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.INITIAL_DETERMINATION_DATE),
                        LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.PLAN_CODE,
                        LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.PLAN_TYPE,
                        LINE_OF_BUSINESS_CODE]) AS HASH_DIFF
FROM RAWDATA.SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW
    JOIN STAGEDATA.LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN
        ON (SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.AUTHORIZATION_NBR)
    LEFT OUTER JOIN &{IDAP_LAKE}.NETWORK.LOB_PLAN_TYPE
        ON (LOB_PLAN_TYPE.TPA_CLIENT_ID = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID
        AND LOB_PLAN_TYPE.TPA_ID = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID
        AND LOB_PLAN_TYPE.TPA_DIV_ID = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID
        AND LOB_PLAN_TYPE.PLAN_TYPE = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.PLAN_TYPE)
WHERE SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER NOT IN (SELECT AUTHORIZATION_NBR FROM RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION)
;
!set variable_substitution=false;