CREATE OR REPLACE VIEW STAGEDATA.REF_CLAIM_NOT_COVERED_REASON_SKYGEN_SELECT_VW
AS

SELECT DISTINCT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
,LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME
,IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW.LOB AS LINE_OF_BUSINESS_CODE
,DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.TypeDescription AS NOT_COVERED_REASON_TYPE
,DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.DENIAL_CODE AS CODE
,IFNULL(IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW.CMS_CODE_DESC, IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW.CODE_DESC) AS CODE_DESC
,IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW.CODE_DESC_LONG AS CODE_DESC_LONG
,IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW.CODE_SPANISH_DESC AS CODE_SPANISH_DESC
,NULL AS HIPAA_277_CODE
,NULL AS HIPAA_835_CODE
,TO_BOOLEAN(IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW.MEMBER_PAY_IND) AS MEMBER_PAY_FLAG
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME, LINE_OF_BUSINESS_CODE, NOT_COVERED_REASON_TYPE, DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.DENIAL_CODE]) AS CLAIM_NOT_COVERED_REASON_HKEY

FROM RAWDATA.IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW
    JOIN RAWDATA.DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW
        ON (IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW.CODE = DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.DENIAL_CODE
        AND IDAPLAKE_REFERENCEDATA_SKYGEN_NOT_COVERED_REASON_CODES_VW.CODE_TYPE = DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.TypeDescription)
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.CLAIM_NBR = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
    JOIN RAWDATA.DWSKYGEN_CLAIM_DETAIL --make sure we only pull claims that are already filtered
        ON (DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR = DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.CLAIM_NBR
        AND DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_NBR = DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.CLAIM_LINE_NBR
        AND DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR = DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.CLAIM_LINE_SEQ_NBR
        AND DWSKYGEN_CLAIM_DETAIL.PROCEDURE_ADJ_CODE = DWSKYGEN_CLAIM_DETAIL_DENIAL_REASON_SELECT_VW.PROCEDURE_ADJ_CODE)
;
