CREATE OR REPLACE VIEW STAGEDATA.LNK_MEDICAL_GROUP_CONTRACT_CACTUS_SELECT_VW
COMMENT = 'This is a Cactus LNK select view between medical groups and contracts'
AS
SELECT DISTINCT
    '000001' AS MG_TPA_CLIENT_ID
    , '000001' AS MG_TPA_ID
    , '0001' AS MG_TPA_DIV_ID
    , 'Cactus' AS MG_DATA_SOURCE_NAME
    , TRIM(CACTUS_GROUPS.ID) AS MG_MEDICAL_GROUP_ID
    , '000001' AS MGC_TPA_CLIENT_ID
    , '000001' AS MGC_TPA_ID
    , '0001' AS MGC_TPA_DIV_ID
    , 'Cactus' AS MGC_DATA_SOURCE_NAME
    , TRIM(CACTUS_GROUPID.GROUPID_K) AS MGC_MEDICAL_GROUP_CONTRACT_ID
    , UTIL.FXN_ARRAY_HASH([MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_MEDICAL_GROUP_ID, MGC_TPA_CLIENT_ID, MGC_TPA_ID, MGC_TPA_DIV_ID, MGC_DATA_SOURCE_NAME, MGC_MEDICAL_GROUP_CONTRACT_ID]) AS LNK_MEDICAL_GROUP_CONTRACT_HKEY
    , UTIL.FXN_ARRAY_HASH([MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY
    , UTIL.FXN_ARRAY_HASH([MGC_TPA_CLIENT_ID, MGC_TPA_ID, MGC_TPA_DIV_ID, MGC_DATA_SOURCE_NAME, MGC_MEDICAL_GROUP_CONTRACT_ID]) AS HUB_MEDICAL_GROUP_CONTRACT_HKEY
FROM RAWDATA.CACTUS_GROUPS
INNER JOIN RAWDATA.CACTUS_GROUPID
    ON CACTUS_GROUPS.GROUP_K = CACTUS_GROUPID.GROUP_K 
INNER JOIN RAWDATA.CACTUS_GROUPADDRESS
ON CACTUS_GROUPID.GROUP_K = CACTUS_GROUPADDRESS.GROUP_K
LEFT JOIN (
	SELECT G.ID,COUNT(*) AS CNT 
	FROM RAWDATA.CACTUS_GROUPS G 
	GROUP BY G.ID HAVING COUNT(*) > 1) DUPES
    ON CACTUS_GROUPS.ID = DUPES.ID
WHERE CACTUS_GROUPID.USERDEF_RTK3 NOT IN ('#0000K4D5N', '#0000K4D5O') -- Group product levels "Pending (Network)" and "Executed (Network)" do not interface out of Cactus
AND NULLIF(TRIM(CACTUS_GROUPS.ID), '') IS NOT NULL	
AND NULLIF(TRIM(CACTUS_GROUPADDRESS.GROUP_K), '') IS NOT NULL	
AND DUPES.ID IS NULL	
;


