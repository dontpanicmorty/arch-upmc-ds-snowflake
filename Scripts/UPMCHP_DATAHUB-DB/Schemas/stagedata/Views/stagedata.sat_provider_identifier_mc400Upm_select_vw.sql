CREATE OR REPLACE VIEW STAGEDATA.SAT_PROVIDER_IDENTIFIER_MC400UPM_SELECT_VW
COMMENT = 'This is a MC400 SAT View containing Provider Identifier data'
AS
SELECT DISTINCT
TPACLIENT AS TPA_CLIENT_ID,
TPAIDOFCLIENT AS TPA_ID,
TPADIVISION AS TPA_DIV_ID,
'MC400Upm' AS DATA_SOURCE_NAME,
PROVIDERNBR AS PROVIDER_ID,
'National Provider Identifier' AS IDENTIFIER_NAME,
TRIM(NATIONALPROVIDERNBR) AS IDENTIFIER_NBR,
'Type 1' AS IDENTIFIER_SUBTYPE,
UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY,
UTIL.FXN_ARRAY_HASH([IDENTIFIER_NAME,IDENTIFIER_NBR, IDENTIFIER_SUBTYPE]) AS HASH_DIFF
FROM RAWDATA.MC400_DWOAO_PROVIDERS
WHERE UPPER(SUBSTRING(PROVIDERNBR,1,1)) <> 'V' 
AND UPPER(TRIM(PRIMARYSPECIALTY)) NOT IN ('INST-TAXID','INST-DEFAU')
AND UPPER(TRIM(PRIMARYSPECIALTY)) NOT LIKE 'INST%'
AND (NATIONALPROVIDERNBR <> '')

UNION


SELECT DISTINCT
MC400_DWOAO_PROVIDERS.TPACLIENT AS TPA_CLIENT_ID,
MC400_DWOAO_PROVIDERS.TPAIDOFCLIENT AS TPA_ID,
MC400_DWOAO_PROVIDERS.TPADIVISION AS TPA_DIV_ID,
'MC400Upm' AS DATA_SOURCE_NAME,
MC400_DWOAO_PROVIDERS.PROVIDERNBR AS PROVIDER_ID,
'National Provider Identifier'  AS IDENTIFIER_NAME,
TRIM(MC400_DWOAO_PROVIDERSUBPART.PROVIDERSUBPART)  AS IDENTIFIER_NBR,
'Type 2' AS IDENTIFIER_SUBTYPE,
UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY,
UTIL.FXN_ARRAY_HASH([IDENTIFIER_NAME, IDENTIFIER_NBR, IDENTIFIER_SUBTYPE]) AS HASH_DIFF
FROM RAWDATA.MC400_DWOAO_PROVIDERS
LEFT JOIN RAWDATA.MC400_DWOAO_PROVIDERSUBPART
ON MC400_DWOAO_PROVIDERS.PROVIDERNBR = MC400_DWOAO_PROVIDERSUBPART.PROVIDERNUMBER
WHERE UPPER(SUBSTRING(MC400_DWOAO_PROVIDERS.PROVIDERNBR,1,1)) <> 'V' 
AND UPPER(TRIM(MC400_DWOAO_PROVIDERS.PRIMARYSPECIALTY)) NOT IN ('INST-TAXID','INST-DEFAU')
AND UPPER(TRIM(MC400_DWOAO_PROVIDERS.PRIMARYSPECIALTY)) LIKE 'INST%'
AND MC400_DWOAO_PROVIDERS.NATIONALPROVIDERNBR <> ''
AND MC400_DWOAO_PROVIDERSUBPART.PROVIDERSUBPART <> ''

UNION

SELECT DISTINCT
TPACLIENT AS TPA_CLIENT_ID,
TPAIDOFCLIENT AS TPA_ID,
TPADIVISION AS TPA_DIV_ID,
'MC400Upm' AS DATA_SOURCE_NAME,
PROVIDERNBR AS PROVIDER_ID,
'State Medical License' AS IDENTIFIER_NAME,
TRIM(STATELICENSE) AS IDENTIFIER_NBR,
'Unknown' AS IDENTIFIER_SUBTYPE,
UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY,
UTIL.FXN_ARRAY_HASH([IDENTIFIER_NAME, IDENTIFIER_NBR, IDENTIFIER_SUBTYPE]) AS HASH_DIFF
FROM RAWDATA.MC400_DWOAO_PROVIDERS
WHERE UPPER(SUBSTRING(PROVIDERNBR,1,1)) <> 'V' 
AND UPPER(TRIM(PRIMARYSPECIALTY)) NOT IN ('INST-TAXID','INST-DEFAU')
AND UPPER(TRIM(PRIMARYSPECIALTY)) NOT LIKE 'INST%'
AND STATELICENSE <> ''

UNION

SELECT DISTINCT
TPACLIENT AS TPA_CLIENT_ID,
TPAIDOFCLIENT AS TPA_ID,
TPADIVISION AS TPA_DIV_ID,
'MC400Upm' AS DATA_SOURCE_NAME,
PROVIDERNBR AS PROVIDER_ID,
'Medicaid Number' AS IDENTIFIER_NAME,
TRIM(STATEMEDICAIDID) AS IDENTIFIER_NBR,
'Unknown' AS IDENTIFIER_SUBTYPE,
UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY,
UTIL.FXN_ARRAY_HASH([IDENTIFIER_NAME, IDENTIFIER_NBR, IDENTIFIER_SUBTYPE ]) AS HASH_DIFF
FROM RAWDATA.MC400_DWOAO_PROVIDERS
WHERE UPPER(SUBSTRING(PROVIDERNBR,1,1)) <> 'V' 
AND UPPER(TRIM(PRIMARYSPECIALTY)) NOT IN ('INST-TAXID','INST-DEFAU')
AND STATEMEDICAIDID not like '%8888888%'
AND STATEMEDICAIDID <> '' 

UNION

SELECT DISTINCT
TPACLIENT AS TPA_CLIENT_ID,
TPAIDOFCLIENT AS TPA_ID,
TPADIVISION AS TPA_DIV_ID,
'MC400Upm' AS DATA_SOURCE_NAME,
PROVIDERNBR AS PROVIDER_ID,
'Medicare Number' AS IDENTIFIER_NAME, 
TRIM(MEDICARENBR) AS IDENTIFIER_NBR,
'Unknown' AS IDENTIFIER_SUBTYPE,
UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY,
UTIL.FXN_ARRAY_HASH([IDENTIFIER_NAME, IDENTIFIER_NBR, IDENTIFIER_SUBTYPE]) AS HASH_DIFF
FROM RAWDATA.MC400_DWOAO_PROVIDERS
WHERE UPPER(SUBSTRING(PROVIDERNBR,1,1)) <> 'V' 
AND UPPER(TRIM(PRIMARYSPECIALTY)) NOT IN ('INST-TAXID','INST-DEFAU')
AND MEDICARENBR <> '';