CREATE OR REPLACE VIEW STAGEDATA.SAT_PROVIDER_CONTRACT_DETAIL_CACTUS_SELECT_VW
COMMENT = 'This is a STAGEDATA Cactus SAT select view containing provider contract detail data'
AS
WITH ENTITY_VERIFICATION AS (
    SELECT DISTINCT PROVIDER_K
    FROM RAWDATA.CACTUS_ENTITYASSIGNMENTS
    WHERE RECORDTYPE = 'E'
)
, DUPLICATE_PROVIDERS AS (
    SELECT PRV.ID
    FROM
        RAWDATA.CACTUS_PROVIDERS AS PRV
    INNER JOIN
        RAWDATA.CACTUS_ENTITYASSIGNMENTS AS EA
        ON PRV.PROVIDER_K = EA.PROVIDER_K
    GROUP BY PRV.ID
    HAVING COUNT(DISTINCT PRV.PROVIDER_K) > 1
)
SELECT DISTINCT
     '000001' AS TPA_CLIENT_ID
    , '000001' AS TPA_ID
    , '0001' AS TPA_DIV_ID
    , 'Cactus' AS DATA_SOURCE_NAME
    , TRIM(EA.EA_K) AS PROVIDER_CONTRACT_ID
    , NULLIF(TRIM(REF1.DESCRIPTION), 'No Value Specified') AS PROVIDER_CONTRACT_NAME
    , NULLIF(TRIM(REF2.DESCRIPTION), 'No Value Specified') AS PROVIDER_CONTRACT_TYPE_NAME
    , NULLIF(TRIM(REF3.DESCRIPTION), 'No Value Specified') AS PROVIDER_CONTRACT_PATIENT_RESTRICTION_NAME
    , NULLIF(TRIM(REF4.DESCRIPTION), 'No Value Specified') AS PROVIDER_CONTRACT_LEVEL_NAME
    , UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_CONTRACT_ID]) AS HUB_PROVIDER_CONTRACT_HKEY
    , UTIL.FXN_ARRAY_HASH([PROVIDER_CONTRACT_NAME, PROVIDER_CONTRACT_TYPE_NAME, PROVIDER_CONTRACT_PATIENT_RESTRICTION_NAME, PROVIDER_CONTRACT_LEVEL_NAME]) AS HASH_DIFF
FROM
    RAWDATA.CACTUS_ENTITYASSIGNMENTS AS EA
INNER JOIN
    RAWDATA.CACTUS_PROVIDERS AS PRV
    ON EA.PROVIDER_K = PRV.PROVIDER_K
INNER JOIN
    RAWDATA.CACTUS_REFTABLE AS REF1
    ON EA.ASSIGNMENT_RTK = REF1.REFTABLE_K
INNER JOIN
    RAWDATA.CACTUS_REFTABLE AS REF2
    ON EA.USERDEF_RTK6 = REF2.REFTABLE_K
INNER JOIN
    RAWDATA.CACTUS_REFTABLE AS REF3
    ON EA.USERDEF_RTK5 = REF3.REFTABLE_K
INNER JOIN
    RAWDATA.CACTUS_REFTABLE AS REF4
    ON EA.USERDEF_RTK1 = REF4.REFTABLE_K
INNER JOIN
    ENTITY_VERIFICATION AS DEA
    ON PRV.PROVIDER_K = DEA.PROVIDER_K
LEFT JOIN
    DUPLICATE_PROVIDERS AS DUP
    ON PRV.ID = DUP.ID
WHERE
    EA.RECORDTYPE = 'A'
    AND EA.USERDEF_RTK1 NOT IN ('#0000K498H', '#0000K498K')
    AND PRV.STATUS_RTK NOT IN ('#0000K408T','#0000K408U','#0000K408S')
    AND NOT (PRV.INDIVIDUALINSTITUTIONFLAG = 1 AND PRV.LASTNAME = '' AND PRV.FIRSTNAME = '')
    AND NOT (PRV.INDIVIDUALINSTITUTIONFLAG = 2 AND PRV.LONGNAME = '')
    AND NULLIF(PRV.ID, '') IS NOT NULL
    AND DUP.ID IS NULL
;