CREATE OR REPLACE VIEW STAGEDATA.LNK_PROVIDER_CONTRACT_CACTUS_SELECT_VW
COMMENT = 'This is a Cactus LNK select view between providers and contracts'
AS
SELECT DISTINCT
    '000001' AS P_TPA_CLIENT_ID
    , '000001' AS P_TPA_ID
    , '0001' AS P_TPA_DIV_ID
    , 'Cactus' AS P_DATA_SOURCE_NAME
    , TRIM(CACTUS_PROVIDERS.ID) AS P_PROVIDER_ID
    , '000001' AS PC_TPA_CLIENT_ID
    , '000001' AS PC_TPA_ID
    , '0001' AS PC_TPA_DIV_ID
    , 'Cactus' AS PC_DATA_SOURCE_NAME
    , TRIM(CACTUS_ENTITYASSIGNMENTS.EA_K) AS PC_PROVIDER_CONTRACT_ID
    , UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID, PC_TPA_CLIENT_ID, PC_TPA_ID, PC_TPA_DIV_ID, PC_DATA_SOURCE_NAME, PC_PROVIDER_CONTRACT_ID]) AS LNK_PROVIDER_CONTRACT_HKEY
    , UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS HUB_PROVIDER_HKEY
    , UTIL.FXN_ARRAY_HASH([PC_TPA_CLIENT_ID, PC_TPA_ID, PC_TPA_DIV_ID, PC_DATA_SOURCE_NAME, PC_PROVIDER_CONTRACT_ID]) AS HUB_PROVIDER_CONTRACT_HKEY
FROM RAWDATA.CACTUS_PROVIDERS
INNER JOIN RAWDATA.CACTUS_ENTITYASSIGNMENTS
    ON CACTUS_PROVIDERS.PROVIDER_K = CACTUS_ENTITYASSIGNMENTS.PROVIDER_K
INNER JOIN (
    SELECT DISTINCT PROVIDER_K
    FROM RAWDATA.CACTUS_ENTITYASSIGNMENTS
    WHERE RECORDTYPE = 'E'
    ) AS EA
    ON CACTUS_PROVIDERS.PROVIDER_K = EA.PROVIDER_K
LEFT JOIN ( 
	SELECT ID, COUNT(*) AS CNT FROM( 
	SELECT DISTINCT P.ID, P.PROVIDER_K 
	FROM RAWDATA.CACTUS_PROVIDERS P
	INNER JOIN RAWDATA.CACTUS_ENTITYASSIGNMENTS E
	ON E.PROVIDER_K = P.PROVIDER_K) A
	GROUP BY ID HAVING COUNT(*) > 1 ) DUPES
	ON CACTUS_PROVIDERS.ID = DUPES.ID
WHERE CACTUS_ENTITYASSIGNMENTS.RECORDTYPE = 'A'	
AND CACTUS_ENTITYASSIGNMENTS.USERDEF_RTK1 NOT IN ('#0000K498H', '#0000K498K')	-- Provider product levels "Pending (Network)" and "Executed (Network)" do not interface out of Cactus
AND CACTUS_PROVIDERS.STATUS_RTK NOT IN ('#0000K408T','#0000K408U','#0000K408S')	 -- Provider statuses "Applicant", "Committee Reviewer", "Lead" do not interface out of Cactus 
AND NOT (CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 
AND (CACTUS_PROVIDERS.LASTNAME = '' AND CACTUS_PROVIDERS.FIRSTNAME = ''))	
AND NOT(CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 2 AND CACTUS_PROVIDERS.LONGNAME = '')	
AND NULLIF(CACTUS_PROVIDERS.ID, '') IS NOT NULL	
AND DUPES.ID IS NULL
;


