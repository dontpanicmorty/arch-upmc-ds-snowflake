CREATE OR REPLACE VIEW STAGEDATA.LKP_CLAIM_PHARMACY_DETAIL_VW
COMMENT = 'Parsed ESI weekly pharmacy detail files'
AS 
WITH PARSED_PHARMACY_DATA AS
(SELECT  TRIM(SUBSTR(RECORD_DATA,17,15)) AS NABP_NBR,
        TRIM(CONCAT(LTRIM(SUBSTR(RECORD_DATA,32,20)),RTRIM(SUBSTR(RECORD_DATA,322,5)))) AS PHARMACY_NAME,
        TRIM(CONCAT(LTRIM(SUBSTR(RECORD_DATA,52,20)),RTRIM(SUBSTR(RECORD_DATA,327,2)))) AS PHARMACY_ADDRESS,
        TRIM(SUBSTR(RECORD_DATA,72,18)) AS PHARMACY_LOCATION_CITY,
        TRIM(SUBSTR(RECORD_DATA,90,2)) AS PHARMACY_LOCATION_STATE,
        TRIM(SUBSTR(RECORD_DATA,92,9)) AS PHARMACY_ZIP_CODE,
        CASE
            WHEN TRIM(CLAIM_PHARMACY_NPI_LKP_HISTORICAL.NPI) = '' OR CLAIM_PHARMACY_NPI_LKP_HISTORICAL.NPI IS NULL THEN 'UNKNOWN'
            ELSE TRIM(CLAIM_PHARMACY_NPI_LKP_HISTORICAL.NPI) 
        END AS PHARMACY_NPI,
        IFNULL(TO_VARCHAR(CMS_NPI_VW.ENTITY_TYPE_CODE), 'UNKNOWN') AS PHARMACY_NPI_TYPE,
        TRIM(SUBSTR(RECORD_DATA,101,10)) AS PHARMACY_TELEPHONE_NUMBER
FROM    RAWDATA.ESI_CLAIM_WEEKLY
LEFT JOIN RAWDATA.CLAIM_PHARMACY_NPI_LKP_HISTORICAL
    ON TRIM(SUBSTR(ESI_CLAIM_WEEKLY.RECORD_DATA,17,15)) = CLAIM_PHARMACY_NPI_LKP_HISTORICAL.NABP_NBR
LEFT JOIN RAWDATA.CMS_NPI_VW
    ON CLAIM_PHARMACY_NPI_LKP_HISTORICAL.NPI = CMS_NPI_VW.NPI
WHERE   SUBSTR(RECORD_DATA,1,1) = '2' --Pharmacy records only
AND LEN(NABP_NBR) = 7 --remove 6-character NABPs
AND (PHARMACY_NAME <> 'PA PACE PROGRAM' AND CONCAT(SUBSTR(PHARMACY_ADDRESS,1,13), ', ', PHARMACY_LOCATION_CITY, ', ' ,PHARMACY_LOCATION_STATE) <> '555 WALNUT ST, HARRISBURG, PA')-- per Pharmacy Team will want to ignore these records
QUALIFY ROW_NUMBER() OVER(PARTITION BY NABP_NBR, PHARMACY_NPI ORDER BY ESI_CLAIM_WEEKLY.FILENAME DESC) = 1
)

, HISTORICAL_PHARMACY_DATA AS (
SELECT DISTINCT
       CLAIM_CMS_HISTORICAL_NPI_PHARMACY.NABP_NBR,
       CLAIM_CMS_HISTORICAL_NPI_PHARMACY.PHARMACY_NAME,
       CLAIM_CMS_HISTORICAL_NPI_PHARMACY.PHARMACY_ADDRESS,
       CLAIM_CMS_HISTORICAL_NPI_PHARMACY.PHARMACY_LOCATION_CITY,
       CLAIM_CMS_HISTORICAL_NPI_PHARMACY.PHARMACY_LOCATION_STATE,
       CLAIM_CMS_HISTORICAL_NPI_PHARMACY.PHARMACY_ZIP_CODE,
       IFNULL(CLAIM_CMS_HISTORICAL_NPI_PHARMACY.PHARMACY_NPI,'UNKNOWN') AS PHARMACY_NPI,
       CLAIM_CMS_HISTORICAL_NPI_PHARMACY.PHARMACY_NPI_TYPE,
       CLAIM_CMS_HISTORICAL_NPI_PHARMACY.PHARMACY_TELEPHONE_NUMBER
FROM RAWDATA.CLAIM_CMS_HISTORICAL_NPI_PHARMACY
LEFT JOIN PARSED_PHARMACY_DATA
    ON (PARSED_PHARMACY_DATA.NABP_NBR = CLAIM_CMS_HISTORICAL_NPI_PHARMACY.NABP_NBR
    AND PARSED_PHARMACY_DATA.PHARMACY_NPI = IFNULL(CLAIM_CMS_HISTORICAL_NPI_PHARMACY.PHARMACY_NPI,'UNKNOWN'))
WHERE PARSED_PHARMACY_DATA.NABP_NBR IS NULL
)

,GAP_FILLING_CTE_1 AS (

SELECT DISTINCT 

LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_NUMBER AS NABP_NBR,
PARSED_PHARMACY_DATA.PHARMACY_NAME,
PARSED_PHARMACY_DATA.PHARMACY_ADDRESS,
PARSED_PHARMACY_DATA.PHARMACY_LOCATION_CITY,
PARSED_PHARMACY_DATA.PHARMACY_LOCATION_STATE,
PARSED_PHARMACY_DATA.PHARMACY_ZIP_CODE,
IFNULL(LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_IDENTIFIER,'UNKNOWN') AS PHARMACY_NPI,
IFNULL(TO_VARCHAR(CMS_NPI_VW.ENTITY_TYPE_CODE), 'UNKNOWN') AS PHARMACY_NPI_TYPE,
PARSED_PHARMACY_DATA.PHARMACY_TELEPHONE_NUMBER
FROM STAGEDATA.LKP_CLAIM_PHARMACY_CLAIM
LEFT JOIN PARSED_PHARMACY_DATA
    ON LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_NUMBER = PARSED_PHARMACY_DATA.NABP_NBR
LEFT JOIN RAWDATA.CMS_NPI_VW
    ON LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_IDENTIFIER = CMS_NPI_VW.NPI
LEFT JOIN PARSED_PHARMACY_DATA PARSED_PHARMACY_DATA_NABP_NPI
    ON (LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_NUMBER = PARSED_PHARMACY_DATA_NABP_NPI.NABP_NBR
    AND LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_IDENTIFIER = PARSED_PHARMACY_DATA_NABP_NPI.PHARMACY_NPI)
LEFT JOIN HISTORICAL_PHARMACY_DATA
    ON (LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_NUMBER = HISTORICAL_PHARMACY_DATA.NABP_NBR
    AND IFNULL(LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_IDENTIFIER,'UNKNOWN') = HISTORICAL_PHARMACY_DATA.PHARMACY_NPI)
WHERE PARSED_PHARMACY_DATA_NABP_NPI.NABP_NBR IS NULL
AND HISTORICAL_PHARMACY_DATA.NABP_NBR IS NULL
)

,GAP_FILLING_CTE_2 AS (
SELECT DISTINCT 
LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_NUMBER AS NABP_NBR,
PARSED_PHARMACY_DATA.PHARMACY_NAME,
PARSED_PHARMACY_DATA.PHARMACY_ADDRESS,
PARSED_PHARMACY_DATA.PHARMACY_LOCATION_CITY,
PARSED_PHARMACY_DATA.PHARMACY_LOCATION_STATE,
PARSED_PHARMACY_DATA.PHARMACY_ZIP_CODE,
'UNKNOWN' AS PHARMACY_NPI,
IFNULL(TO_VARCHAR(CMS_NPI_VW.ENTITY_TYPE_CODE), 'UNKNOWN') AS PHARMACY_NPI_TYPE,
PARSED_PHARMACY_DATA.PHARMACY_TELEPHONE_NUMBER
FROM STAGEDATA.LKP_CLAIM_PHARMACY_CLAIM
LEFT JOIN PARSED_PHARMACY_DATA
    ON LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_NUMBER = PARSED_PHARMACY_DATA.NABP_NBR
LEFT JOIN RAWDATA.CMS_NPI_VW
    ON LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_IDENTIFIER = CMS_NPI_VW.NPI
LEFT JOIN PARSED_PHARMACY_DATA PARSED_PHARMACY_DATA_NABP_NPI
    ON (LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_NUMBER = PARSED_PHARMACY_DATA_NABP_NPI.NABP_NBR
    AND PARSED_PHARMACY_DATA_NABP_NPI.PHARMACY_NPI = 'UNKNOWN')
LEFT JOIN HISTORICAL_PHARMACY_DATA
    ON (LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_NUMBER = HISTORICAL_PHARMACY_DATA.NABP_NBR
    AND HISTORICAL_PHARMACY_DATA.PHARMACY_NPI = 'UNKNOWN')
LEFT JOIN GAP_FILLING_CTE_1
    ON (LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_NUMBER = GAP_FILLING_CTE_1.NABP_NBR
    AND GAP_FILLING_CTE_1.PHARMACY_NPI = 'UNKNOWN')
WHERE PARSED_PHARMACY_DATA_NABP_NPI.NABP_NBR IS NULL
AND HISTORICAL_PHARMACY_DATA.NABP_NBR IS NULL
AND GAP_FILLING_CTE_1.NABP_NBR IS NULL
AND LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_IDENTIFIER IS NULL
AND LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_NUMBER= '7099999'
)

SELECT NABP_NBR,
       PHARMACY_NAME,
       PHARMACY_ADDRESS,
       PHARMACY_LOCATION_CITY,
       PHARMACY_LOCATION_STATE,
       PHARMACY_ZIP_CODE,
       PHARMACY_NPI,
       PHARMACY_NPI_TYPE,
       PHARMACY_TELEPHONE_NUMBER
FROM PARSED_PHARMACY_DATA

UNION

SELECT NABP_NBR,
       PHARMACY_NAME,
       PHARMACY_ADDRESS,
       PHARMACY_LOCATION_CITY,
       PHARMACY_LOCATION_STATE,
       PHARMACY_ZIP_CODE,
       PHARMACY_NPI,
       PHARMACY_NPI_TYPE,
       PHARMACY_TELEPHONE_NUMBER
FROM HISTORICAL_PHARMACY_DATA

UNION

SELECT NABP_NBR,
       PHARMACY_NAME,
       PHARMACY_ADDRESS,
       PHARMACY_LOCATION_CITY,
       PHARMACY_LOCATION_STATE,
       PHARMACY_ZIP_CODE,
       PHARMACY_NPI,
       PHARMACY_NPI_TYPE,
       PHARMACY_TELEPHONE_NUMBER
FROM GAP_FILLING_CTE_1

UNION

SELECT NABP_NBR,
       PHARMACY_NAME,
       PHARMACY_ADDRESS,
       PHARMACY_LOCATION_CITY,
       PHARMACY_LOCATION_STATE,
       PHARMACY_ZIP_CODE,
       PHARMACY_NPI,
       PHARMACY_NPI_TYPE,
       PHARMACY_TELEPHONE_NUMBER
FROM GAP_FILLING_CTE_2
;