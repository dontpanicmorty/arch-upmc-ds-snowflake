            CASE
                WHEN IDAPLAKE_REFERENCEDATA_ESI_SPECIALTY_DRUG_INDICATOR_VW.GCN_CODE IS NOT NULL THEN TO_VARCHAR('1')
                ELSE TO_VARCHAR('0')
            END AS SPECIALTY_DRUG_IND,
            MEDISPAN_AWP.AWP_INDICATOR_CODE, 
            FDB_RLBLRID3_LBLR_DESC.MFG AS MANUFACTURER_NAME

    FROM    RNDC14_NDC_MSTR
    JOIN 	RGCNSEQ4_GCNSEQNO_MSTR ON RGCNSEQ4_GCNSEQNO_MSTR.GCN_SEQNO = RNDC14_NDC_MSTR.GCN_SEQNO
    LEFT JOIN AHFS_LATEST ON TO_NUMBER(AHFS_LATEST.GCN_SEQNO) = TO_NUMBER(RNDC14_NDC_MSTR.GCN_SEQNO)
    LEFT JOIN RHICLSQ1_HICLSEQNO_MSTR ON RHICLSQ1_HICLSEQNO_MSTR.HICL_SEQNO = RGCNSEQ4_GCNSEQNO_MSTR.HICL_SEQNO
    LEFT JOIN RAPPLSL0_FDA_NDC_NDA_ANDA ON RAPPLSL0_FDA_NDC_NDA_ANDA.NDC = RNDC14_NDC_MSTR.NDC
    LEFT JOIN (
        SELECT  RMIID1_MED.MEDID AS MEDID,
                RMIID1_MED.ROUTED_DOSAGE_FORM_MED_ID AS ROUTED_DOSAGE_FORM_MED_ID,
                RMIID1_MED.MED_MEDID_DESC AS MED_MEDID_DESC,
                RMINDC1_NDC_MEDID.NDC
                
        FROM    RMINDC1_NDC_MEDID
        JOIN    RMIID1_MED ON RMIID1_MED.MEDID = RMINDC1_NDC_MEDID.MEDID
        WHERE   RMIID1_MED.MED_STATUS_CD = '0'
    ) AS MED ON MED.NDC = RNDC14_NDC_MSTR.NDC
    LEFT JOIN(
        SELECT  RMINMID1_MED_NAME.MED_NAME_ID, 
                RMINMID1_MED_NAME.MED_NAME, 
                RMIDFID1_ROUTED_DOSE_FORM_MED.ROUTED_DOSAGE_FORM_MED_ID 
        FROM    RMINMID1_MED_NAME
        JOIN    RMIRMID1_ROUTED_MED ON RMIRMID1_ROUTED_MED.MED_NAME_ID = RMINMID1_MED_NAME.MED_NAME_ID
        JOIN    RMIDFID1_ROUTED_DOSE_FORM_MED ON RMIDFID1_ROUTED_DOSE_FORM_MED.ROUTED_MED_ID = RMIRMID1_ROUTED_MED.ROUTED_MED_ID
    ) R_MED ON R_MED.ROUTED_DOSAGE_FORM_MED_ID = MED.ROUTED_DOSAGE_FORM_MED_ID
    LEFT JOIN RHIC3D3_HIC_THERAP_CLASS_DESC ON RHIC3D3_HIC_THERAP_CLASS_DESC.HIC3_SEQN  = RGCNSEQ4_GCNSEQNO_MSTR.HIC3_SEQN
    LEFT JOIN RNP2_NDC_PRICE ON RNP2_NDC_PRICE.NDC = RNDC14_NDC_MSTR.NDC
    LEFT JOIN RGTCD0_GEN_THERAP_CLASS ON RGTCD0_GEN_THERAP_CLASS.GTC = RGCNSEQ4_GCNSEQNO_MSTR.GTC
    LEFT JOIN RDOSED2_DOSE_DESC ON RDOSED2_DOSE_DESC.GCDF = RGCNSEQ4_GCNSEQNO_MSTR.GCDF
    LEFT JOIN MEDISPAN_GPI ON MEDISPAN_GPI.NDC = RNDC14_NDC_MSTR.NDC
    LEFT JOIN MEDISPAN_AWP ON MEDISPAN_AWP.NDC = RNDC14_NDC_MSTR.NDC
    LEFT JOIN RROUTED3_ROUTE_DESC ON RROUTED3_ROUTE_DESC.GCRT = RGCNSEQ4_GCNSEQNO_MSTR.GCRT
    LEFT JOIN RGCN0_GCN_GCNSEQNO_LINK ON RNDC14_NDC_MSTR.GCN_SEQNO = RGCN0_GCN_GCNSEQNO_LINK.GCN_SEQNO
    LEFT JOIN RAWDATA.IDAPLAKE_REFERENCEDATA_ESI_SPECIALTY_DRUG_INDICATOR_VW ON (RGCN0_GCN_GCNSEQNO_LINK.GCN = IDAPLAKE_REFERENCEDATA_ESI_SPECIALTY_DRUG_INDICATOR_VW.GCN_CODE
        AND IDAPLAKE_REFERENCEDATA_ESI_SPECIALTY_DRUG_INDICATOR_VW.EXPIRATION_DATE > CURRENT_DATE())
    LEFT JOIN FDB_RLBLRID3_LBLR_DESC ON RNDC14_NDC_MSTR.LBLRID = FDB_RLBLRID3_LBLR_DESC.LBLRID

UNION

