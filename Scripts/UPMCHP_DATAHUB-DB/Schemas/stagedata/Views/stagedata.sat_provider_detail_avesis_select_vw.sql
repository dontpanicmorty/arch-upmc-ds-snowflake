CREATE OR REPLACE VIEW STAGEDATA.SAT_PROVIDER_DETAIL_AVESIS_SELECT_VW
COMMENT = 'This is a SAT View containing Provider Detail data'
AS

WITH QUALIFY_CTE AS
    (SELECT *
     FROM RAWDATA.AVESIS_PROVIDER
     QUALIFY ROW_NUMBER()
        OVER(PARTITION BY AVESIS_PROVIDER.PLAN_PRVD_NO
            ORDER BY SPLIT_PART(SPLIT_PART(AVESIS_PROVIDER.FILENAME, '_', 4), '.', 1) DESC) = 1 
    )
,
CTE AS (
	SELECT DISTINCT
		'000001' AS TPA_CLIENT_ID,
    	'000001' AS TPA_ID,
    	'0001' AS TPA_DIV_ID,
    	'Avesis' AS DATA_SOURCE_NAME,
 		TRIM(PLAN_PRVD_NO) AS PROVIDER_ID, 
 		'Practitioner' AS PROVIDER_TYPE_NAME, 
 		CONCAT(COALESCE(TRIM(PRVD_FIRST_NAM),''), COALESCE(TRIM(PRVD_LAST_NAM),'') ) AS FULL_NAME,  
 		TRIM(PRVD_FIRST_NAM) AS FIRST_NAME,
 		TRIM(PRVD_LAST_NAM) AS LAST_NAME, 
 		NULL AS MIDDLE_NAME, 
 		NULL AS MIDDLE_INITIAL_NAME, 
 		'Unknown' AS GENDER_NAME, 
 		NULL AS EMAIL_ADDRESS, 
 		NULL AS SOCIAL_SECURITY_NBR, 
 		TRIM(MED_DEGREE) AS DEGREE_TEXT, 
 		NULL AS SUFFIX_NAME, 
 		NULL AS LOCUM_TENENS_IND, 
 		NULL AS INVISIBLE_PROVIDER_IND, 
 		NULL AS TEMPORARY_PROVIDER_IND, 
		NULL AS DATE_OF_BIRTH,
        NULL AS PRIMARY_PREFERRED_DELIVERY_METHOD_CODE,
        NULL AS BOARD_CERTIFIED_IND,
        NULL AS STATE_MEDICAID_ID,
        NULL AS PRIMARY_SPECIALTY_NAME,
 		NULL AS NATIONAL_PROVIDER_ID,
		NULL AS PRIMARY_TAXONOMY_CODE,
		NULL AS PRESCRIBER_SOURCE_CODE,
		NULL AS UPIN_NBR,
		NULL AS PROVIDER_START_DATE,
		NULL AS PROVIDER_ACTIVE_IND,
		NULL AS FACILITY_INCEPTION_DATE,
 		UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY, 
		UTIL.FXN_ARRAY_HASH([PROVIDER_TYPE_NAME, FULL_NAME, FIRST_NAME, LAST_NAME, MIDDLE_NAME, MIDDLE_INITIAL_NAME, GENDER_NAME, EMAIL_ADDRESS, SOCIAL_SECURITY_NBR, DEGREE_TEXT, SUFFIX_NAME, LOCUM_TENENS_IND, INVISIBLE_PROVIDER_IND, TEMPORARY_PROVIDER_IND, DATE_OF_BIRTH,
    PRIMARY_PREFERRED_DELIVERY_METHOD_CODE,BOARD_CERTIFIED_IND,STATE_MEDICAID_ID,PRIMARY_SPECIALTY_NAME,NATIONAL_PROVIDER_ID, PRIMARY_TAXONOMY_CODE, PRESCRIBER_SOURCE_CODE, UPIN_NBR, PROVIDER_START_DATE, PROVIDER_ACTIVE_IND, FACILITY_INCEPTION_DATE]) AS HASH_DIFF
	FROM QUALIFY_CTE
	 WHERE NULLIF(TRIM(PLAN_PRVD_NO), '') IS NOT NULL 
	 	AND MA_PRVD_NO IS NOT NULL
		AND TRIM(PRVD_FIRST_NAM) <> ''
   		AND TRY_CAST(PRVD_FIRST_NAM AS NUMBER) IS NULL

UNION ALL 

SELECT DISTINCT
		'000001' AS TPA_CLIENT_ID,
    	'000001' AS TPA_ID,
    	'0001' AS TPA_DIV_ID,
    	'Avesis' AS DATA_SOURCE_NAME,
 		TRIM(PLAN_PRVD_NO) AS PROVIDER_ID, 
 		'Practitioner' AS PROVIDER_TYPE_NAME, 
 		CONCAT(COALESCE(TRIM(PRVD_FIRST_NAM),''), COALESCE(TRIM(PRVD_LAST_NAM),'') ) AS FULL_NAME,  
 		TRIM(PRVD_FIRST_NAM) AS FIRST_NAME,
 		TRIM(PRVD_LAST_NAM) AS LAST_NAME, 
 		NULL AS MIDDLE_NAME, 
 		NULL AS MIDDLE_INITIAL_NAME, 
 		'Unknown' AS GENDER_NAME, 
 		NULL AS EMAIL_ADDRESS, 
 		NULL AS SOCIAL_SECURITY_NBR, 
 		TRIM(MED_DEGREE) AS DEGREE_TEXT, 
 		NULL AS SUFFIX_NAME, 
 		NULL AS LOCUM_TENENS_IND, 
 		NULL AS INVISIBLE_PROVIDER_IND, 
 		NULL AS TEMPORARY_PROVIDER_IND, 
		NULL AS DATE_OF_BIRTH,
        NULL AS PRIMARY_PREFERRED_DELIVERY_METHOD_CODE,
        NULL AS BOARD_CERTIFIED_IND,
        NULL AS STATE_MEDICAID_ID,
        NULL AS PRIMARY_SPECIALTY_NAME,
 		NULL AS NATIONAL_PROVIDER_ID,
		NULL AS PRIMARY_TAXONOMY_CODE,
		NULL AS PRESCRIBER_SOURCE_CODE, 
		NULL AS UPIN_NBR,
		NULL AS PROVIDER_START_DATE,
		NULL AS PROVIDER_ACTIVE_IND,
		NULL AS FACILITY_INCEPTION_DATE,
 		UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY, 
		UTIL.FXN_ARRAY_HASH([PROVIDER_TYPE_NAME, FULL_NAME, FIRST_NAME, LAST_NAME, MIDDLE_NAME, MIDDLE_INITIAL_NAME, GENDER_NAME, EMAIL_ADDRESS, SOCIAL_SECURITY_NBR, DEGREE_TEXT, SUFFIX_NAME, LOCUM_TENENS_IND, INVISIBLE_PROVIDER_IND, TEMPORARY_PROVIDER_IND, DATE_OF_BIRTH,
    PRIMARY_PREFERRED_DELIVERY_METHOD_CODE,BOARD_CERTIFIED_IND,STATE_MEDICAID_ID,PRIMARY_SPECIALTY_NAME,NATIONAL_PROVIDER_ID, PRIMARY_TAXONOMY_CODE, PRESCRIBER_SOURCE_CODE, UPIN_NBR, PROVIDER_START_DATE, PROVIDER_ACTIVE_IND, FACILITY_INCEPTION_DATE]) AS HASH_DIFF
	FROM QUALIFY_CTE
	 WHERE NULLIF(TRIM(PLAN_PRVD_NO), '') IS NOT NULL 
	 	AND MA_PRVD_NO IS NULL
  		AND TRIM(PRVD_FIRST_NAM) <> ''
   		AND TRY_CAST(PRVD_FIRST_NAM AS NUMBER) IS NULL
)

SELECT DISTINCT * FROM CTE
;