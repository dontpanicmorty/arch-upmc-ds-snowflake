CREATE OR REPLACE VIEW STAGEDATA.REF_CLAIM_PROCEDURE_SKYGEN_SELECT_VW
COMMENT = 'Source view for refdata.claim_procedure'
AS

SELECT
TPA_CLIENT_ID
,TPA_ID
,TPA_DIV_ID
,DATA_SOURCE_NAME
,CODE
,CODE_DESC
,CODE_DESC_LONG
,CODE_SPANISH_DESC
,CLAIM_PROCEDURE_HKEY
,PRIORITY
FROM
(
    SELECT DISTINCT
    LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
    ,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
    ,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
    ,LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME
    ,PROCEDURE_CODE AS CODE
    ,PROCEDURE_DESC AS CODE_DESC
    ,NULL AS CODE_DESC_LONG
    ,NULL AS CODE_SPANISH_DESC
    ,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CODE]) AS CLAIM_PROCEDURE_HKEY
    ,1 AS PRIORITY
    FROM RAWDATA.DWSKYGEN_CLAIM_DETAIL
        JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
            ON (LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR = DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR)

    UNION ALL

    SELECT DISTINCT
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID
    ,LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID
    ,LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID
    ,LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME
    ,DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.PROCEDURE_CODE AS CODE
    ,DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.PROCEDURE_DESC AS CODE_DESC
    ,NULL AS CODE_DESC_LONG
    ,NULL AS CODE_SPANISH_DESC
    ,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CODE]) AS CLAIM_PROCEDURE_HKEY
    ,2 AS PRIORITY
    FROM RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL
        JOIN STAGEDATA.LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN
            ON (LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.AUTHORIZATION_NBR = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.AUTHORIZATION_NBR)
    WHERE DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.PROCEDURE_CODE <> '-3'

    UNION ALL

    SELECT DISTINCT
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID
    ,LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID
    ,LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID
    ,LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME
    ,SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.CODE
    ,SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.PROCEDURE_CODE_DESCRIPTION AS CODE_DESC
    ,NULL AS CODE_DESC_LONG
    ,NULL AS CODE_SPANISH_DESC
    ,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CODE]) AS CLAIM_PROCEDURE_HKEY
    ,3 AS PRIORITY
    FROM RAWDATA.SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW
        JOIN STAGEDATA.LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN
            ON (SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.AUTHORIZATION_NBR)
)
QUALIFY ROW_NUMBER() OVER (PARTITION BY TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CODE ORDER BY PRIORITY) = 1
-- gets a distinct list of all the codes with an order of precidence and takes the first one for the tpa, datasource, code
;
