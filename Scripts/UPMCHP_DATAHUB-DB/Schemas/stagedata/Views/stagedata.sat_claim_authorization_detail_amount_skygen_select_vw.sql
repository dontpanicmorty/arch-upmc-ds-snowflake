CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_AUTHORIZATION_DETAIL_AMOUNT_SKYGEN_SELECT_VW
COMMENT = 'This is a SAT View containing Skygen AUTHORIZATION Header data'
AS

SELECT 
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_LINE_NBR,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZED_AMT,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZED_PER_UNIT_AMT,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.BALANCE_DUE_AMT,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.BILLED_AMT,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.ALLOWED_AMT,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.USUAL_AND_CUSTOMARY_AMT,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.PAYABLE_AMT,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.PAID_AMT,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.COINSURANCE_AMT,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.COPAY_AMT,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.DEDUCTIBLE_APPLIED_AMT,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.PATIENT_PAY_APPLIED_AMT,
    UTIL.FXN_ARRAY_HASH([LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID, LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID, LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID, DATA_SOURCE_NAME, DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR, DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_LINE_NBR]) AS HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY,
    UTIL.FXN_ARRAY_HASH([AUTHORIZED_AMT,
                        AUTHORIZED_PER_UNIT_AMT,
                        BALANCE_DUE_AMT,
                        BILLED_AMT,
                        ALLOWED_AMT,
                        USUAL_AND_CUSTOMARY_AMT,
                        PAYABLE_AMT,
                        PAID_AMT,
                        COINSURANCE_AMT,
                        COPAY_AMT,
                        DEDUCTIBLE_APPLIED_AMT,
                        PATIENT_PAY_APPLIED_AMT
                         ]) AS HASH_DIFF
FROM RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION
    JOIN STAGEDATA.LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN
        ON (DWSKYGEN_CLAIM_AUTHORIZATION.AUTHORIZATION_NBR = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.AUTHORIZATION_NBR)
    JOIN RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL
        ON (DWSKYGEN_CLAIM_AUTHORIZATION.AUTHORIZATION_NBR = DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR)  

UNION ALL

SELECT 
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME,
    SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER AS AUTHORIZATION_NBR,
    COALESCE(SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.ITEM_NUMBER,'N/A') AS AUTHORIZATION_LINE_NBR,    
    NULL AS AUTHORIZED_AMT,
    SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZED_AMOUNT_PER_UNIT,
    SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.BALANCE_DUE_AMOUNT,
    NULL AS BILLED_AMT,
    NULL AS ALLOWED_AMT,
    NULL AS USUAL_AND_CUSTOMARY_AMT,
    NULL AS PAYABLE_AMT,
    NULL AS PAID_AMT,
    NULL AS COINSURANCE_AMT,
    NULL AS COPAY_AMT,
    NULL AS DEDUCTIBLE_APPLIED_AMT,
    NULL AS PATIENT_PAY_APPLIED_AMT,
    UTIL.FXN_ARRAY_HASH([LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID, LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID, LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID, DATA_SOURCE_NAME, AUTHORIZATION_NBR, AUTHORIZATION_LINE_NBR]) AS HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY,
    UTIL.FXN_ARRAY_HASH([AUTHORIZED_AMT,
                        AUTHORIZED_AMOUNT_PER_UNIT,
                        BALANCE_DUE_AMOUNT,
                        BILLED_AMT,
                        ALLOWED_AMT,
                        USUAL_AND_CUSTOMARY_AMT,
                        PAYABLE_AMT,
                        PAID_AMT,
                        COINSURANCE_AMT,
                        COPAY_AMT,
                        DEDUCTIBLE_APPLIED_AMT,
                        PATIENT_PAY_APPLIED_AMT
                         ]) AS HASH_DIFF
FROM RAWDATA.SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW
    JOIN STAGEDATA.LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN
        ON (SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.AUTHORIZATION_NBR)
WHERE SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER NOT IN (SELECT AUTHORIZATION_NBR FROM RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION)
;