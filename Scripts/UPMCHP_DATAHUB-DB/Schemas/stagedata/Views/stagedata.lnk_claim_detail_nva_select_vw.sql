CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_DETAIL_NVA_SELECT_VW
COMMENT = 'Source view for NVA data into LNK_CLAIM_DETAIL'
AS
SELECT DISTINCT
    IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID, '000001') AS C_TPA_CLIENT_ID, 
    IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_ID, '000001') AS C_TPA_ID, 
    IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID, '0001') AS C_TPA_DIV_ID, 
    IFNULL(LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME, 'NVA') AS C_DATA_SOURCE_NAME, 
    NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo" AS C_CLAIM_NBR, 
    IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID, '000001') AS CD_TPA_CLIENT_ID, 
    IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_ID, '000001') AS CD_TPA_ID, 
    IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID, '0001') AS CD_TPA_DIV_ID, 
    IFNULL(LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME, 'NVA') AS CD_DATA_SOURCE_NAME, 
    NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo" AS CD_CLAIM_NBR, 
    NVA_PAID_CLAIM_EXTRACTS_VW."ClaimSeqNo" AS CD_CLAIM_LINE_NBR, 
    CONCAT(NVA_PAID_CLAIM_EXTRACTS_VW."ClaimSeqNo", NVA_PAID_CLAIM_EXTRACTS_VW."Trantype") AS CD_CLAIM_LINE_SEQ_NBR,
    'N/A' AS CD_CLAIM_LINE_PROCEDURE_ADJ_CODE, 
    UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS LNK_CLAIM_DETAIL_HKEY, 
    UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY, 
    UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY, 
FROM RAWDATA.NVA_PAID_CLAIM_EXTRACTS_VW
    LEFT JOIN STAGEDATA.LKP_CLAIM_MEMBER_NVA
        ON (LKP_CLAIM_MEMBER_NVA.CLAIM_NBR = NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo")
; 