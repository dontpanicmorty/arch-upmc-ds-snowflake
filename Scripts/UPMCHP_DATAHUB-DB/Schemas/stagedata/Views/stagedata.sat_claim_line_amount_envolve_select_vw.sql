CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_LINE_AMOUNT_ENVOLVE_SELECT_VW
COMMENT = 'This is a SAT View containing Claim Line Amount data'
AS
SELECT DISTINCT 
    LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID,
	LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID,
	LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID,
	LKP_CLAIM_MEMBER_ENVOLVE.DATA_SOURCE_NAME, 
    ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO AS CLAIM_NBR, 
    ENVOLVE_CLAIM_EXTRACTS.ITEM_NO AS CLAIM_LINE_NBR, 
    CONCAT(COALESCE(ENVOLVE_CLAIM_EXTRACTS.EOB_MAIL_DATE,''), COALESCE(ENVOLVE_CLAIM_EXTRACTS.COUNTY_CODE,''),'P') AS CLAIM_LINE_SEQ_NBR, 
    'N/A' AS CLAIM_LINE_PROCEDURE_ADJ_CODE, 
    ENVOLVE_CLAIM_EXTRACTS.ALLOW_AMT AS ALLOWED_AMOUNT, 
    ENVOLVE_CLAIM_EXTRACTS.BILLED_AMT AS CHARGE_AMOUNT, 
    NULL AS CLAIM_AMT_01, 
    NULL AS CLAIM_AMT_01_DESC, 
    NULL AS CLAIM_AMT_02, 
    NULL AS CLAIM_AMT_02_DESC, 
    ENVOLVE_CLAIM_EXTRACTS.COPAY_AMT AS COPAY_AMT_01, 
    NULL AS COPAY_AMT_02, 
    NULL AS COPAY_AMT_03, 
    NULL AS DEDUCTIBLE_AMOUNT, 
    NULL AS NOT_COVERED_AMOUNT, 
    ENVOLVE_CLAIM_EXTRACTS.PAYMENT_AMT AS PAID_AMOUNT, 
    ENVOLVE_CLAIM_EXTRACTS.PAYMENT_AMT AS PAID_GROSS_AMOUNT, 
    NULL AS PAY_FOR_PERFORMANCE_AMOUNT, 
    NULL AS WITHHOLD_AMOUNT, 
    NULL AS COINSURANCE_AMOUNT, 
    NULL AS CODE_REVIEW_ORIGINAL_BILLING_AMOUNT, 
    NULL AS CODE_REVIEW_ORIGINAL_NET_AMOUNT, 
    ENVOLVE_CLAIM_EXTRACTS.APPROV_AMT AS APPROVED_AMT, 
    NULL AS INTEREST_DISCOUNT_AMOUNT, 
    ENVOLVE_CLAIM_EXTRACTS.COB_AMT AS THIRD_PARTY_PAID_AMOUNT, 
    NULL AS THIRD_PARTY_ALLOWED_AMOUNT, 
    NULL AS OIC_PAID_AMOUNT, 
    NULL AS OIC_ALLOWED_AMOUNT, 
    NULL AS HRA_APPLIED_AMT, 
    NULL AS HIA_APPLIED_AMT, 
    NULL AS MEMBER_PAY_FLAG,
    UTIL.FXN_ARRAY_HASH([LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID, LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID, LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID, LKP_CLAIM_MEMBER_ENVOLVE.DATA_SOURCE_NAME, CLAIM_NBR, CLAIM_LINE_NBR, CLAIM_LINE_SEQ_NBR, CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY, 
    UTIL.FXN_ARRAY_HASH([ALLOWED_AMOUNT, CHARGE_AMOUNT, CLAIM_AMT_01, CLAIM_AMT_01_DESC, CLAIM_AMT_02, CLAIM_AMT_02_DESC, COPAY_AMT_01, COPAY_AMT_02, COPAY_AMT_03, DEDUCTIBLE_AMOUNT, NOT_COVERED_AMOUNT, PAID_AMOUNT, PAID_GROSS_AMOUNT, PAY_FOR_PERFORMANCE_AMOUNT, WITHHOLD_AMOUNT, COINSURANCE_AMOUNT, CODE_REVIEW_ORIGINAL_BILLING_AMOUNT, CODE_REVIEW_ORIGINAL_NET_AMOUNT, APPROVED_AMT, INTEREST_DISCOUNT_AMOUNT, THIRD_PARTY_PAID_AMOUNT, THIRD_PARTY_ALLOWED_AMOUNT, OIC_PAID_AMOUNT, OIC_ALLOWED_AMOUNT, HRA_APPLIED_AMT, HIA_APPLIED_AMT, MEMBER_PAY_FLAG]) AS HASH_DIFF
FROM RAWDATA.ENVOLVE_CLAIM_EXTRACTS
JOIN STAGEDATA.LKP_CLAIM_MEMBER_ENVOLVE
        ON (LKP_CLAIM_MEMBER_ENVOLVE.CLAIM_NBR = ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO)
QUALIFY ROW_NUMBER() -- get the most current submitted file for a claim line
    OVER(PARTITION BY ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO,ENVOLVE_CLAIM_EXTRACTS.ITEM_NO
    ORDER BY SPLIT_PART(SPLIT_PART(ENVOLVE_CLAIM_EXTRACTS.FILENAME, '_', 7), '.', 1) DESC) = 1 
;