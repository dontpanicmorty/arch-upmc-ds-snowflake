CREATE OR REPLACE VIEW STAGEDATA.REF_CLAIM_ICD_DIAGNOSIS_SKYGEN_SELECT_VW
AS

SELECT DISTINCT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS TPA_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS TPA_DIV_ID
,LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME
,DWSKYGEN_CLAIM_HEADER_DIAGNOSIS_CODE_SELECT_VW.CODE_VERSION
,DWSKYGEN_CLAIM_HEADER_DIAGNOSIS_CODE_SELECT_VW.DIAGNOSIS_CODE AS CODE
,DWSKYGEN_CLAIM_HEADER_DIAGNOSIS_CODE_SELECT_VW.DIAGNOSISDESCRIPTION AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,DWSKYGEN_CLAIM_HEADER_DIAGNOSIS_CODE_SELECT_VW.GROUP_CODE
,DWSKYGEN_CLAIM_HEADER_DIAGNOSIS_CODE_SELECT_VW.GROUP_DESC
,NULL AS ICD_DIAGNOSIS_CATEGORIES
,UTIL.FXN_ARRAY_HASH(
        [TPA_CLIENT_ID
        ,TPA_ID
        ,TPA_DIV_ID 
        ,DATA_SOURCE_NAME
        ,CODE_VERSION
        ,CODE
        ]) AS CLAIM_ICD_DIAGNOSIS_HKEY
FROM RAWDATA.DWSKYGEN_CLAIM_HEADER_DIAGNOSIS_CODE_SELECT_VW
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR = DWSKYGEN_CLAIM_HEADER_DIAGNOSIS_CODE_SELECT_VW.CLAIM_NBR)

UNION ALL

SELECT DISTINCT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS TPA_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS TPA_DIV_ID
,LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME
,10 AS CODE_VERSION
,SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.PRIMARY_DIAG_CODE AS CODE
,'Description Not Found' AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,SUBSTRING(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.PRIMARY_DIAG_CODE, 1, 
        IFF(CHARINDEX('.', SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.PRIMARY_DIAG_CODE) > 0, 
        CHARINDEX('.', SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.PRIMARY_DIAG_CODE) - 1, 
        LEN(SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.PRIMARY_DIAG_CODE))
) AS GROUP_CODE
,NULL AS GROUP_DESC
,NULL AS ICD_DIAGNOSIS_CATEGORIES
,UTIL.FXN_ARRAY_HASH(
        [TPA_CLIENT_ID
        ,TPA_ID
        ,TPA_DIV_ID 
        ,DATA_SOURCE_NAME
        ,CODE_VERSION
        ,CODE
]) AS CLAIM_ICD_DIAGNOSIS_HKEY
FROM RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW
        JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
                ON (SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
WHERE SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.PRIMARY_DIAG_CODE IS NOT NULL
AND SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.PRIMARY_DIAG_CODE NOT IN (SELECT DISTINCT DIAGNOSIS_CODE FROM RAWDATA.DWSKYGEN_CLAIM_HEADER_DIAGNOSIS_CODE_SELECT_VW)
;
