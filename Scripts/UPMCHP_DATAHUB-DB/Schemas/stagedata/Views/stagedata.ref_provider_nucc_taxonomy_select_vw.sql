CREATE OR REPLACE VIEW STAGEDATA.REF_PROVIDER_NUCC_TAXONOMY_SELECT_VW
AS
SELECT
CODE AS TAXONOMY_CODE,
GROUPING AS TAXONOMY_GROUPING,
CLASSIFICATION AS TAXONOMY_CLASSIFICATION,
SPECIALIZATION AS TAXONOMY_SPECIALIZATION,
DEFINITION AS TAXONOMY_DEFINITION,
UTIL.FXN_ARRAY_HASH([TAXONOMY_CODE]) AS PROVIDER_NUCC_TAXONOMY_HKEY
FROM RAWDATA.IDAPLAKE_REFERENCEDATA_PROVIDER_NUCC_TAXONOMY_VW
QUALIFY ROW_NUMBER() OVER(PARTITION BY CODE ORDER BY METADATA$FILENAME DESC) = 1
;