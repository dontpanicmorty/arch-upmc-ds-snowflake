CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_DETAIL_RENDERING_PROVIDER_ENVOLVE_SELECT_VW
COMMENT = 'Source view for ENVOLVE data into LNK_CLAIM_DETAIL_RENDERING_PROVIDER'
AS
SELECT DISTINCT
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID AS CD_TPA_CLIENT_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID AS CD_TPA_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID AS CD_TPA_DIV_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.DATA_SOURCE_NAME AS CD_DATA_SOURCE_NAME, 
     ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO AS CD_CLAIM_NBR, 
     ENVOLVE_CLAIM_EXTRACTS.ITEM_NO AS CD_CLAIM_LINE_NBR, 
     CONCAT(COALESCE(ENVOLVE_CLAIM_EXTRACTS.EOB_MAIL_DATE,''), COALESCE(ENVOLVE_CLAIM_EXTRACTS.COUNTY_CODE,''),'P') AS CD_CLAIM_LINE_SEQ_NBR, 
     'N/A' AS CD_CLAIM_LINE_PROCEDURE_ADJ_CODE, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID AS P_TPA_CLIENT_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID AS P_TPA_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID AS P_TPA_DIV_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.DATA_SOURCE_NAME AS P_DATA_SOURCE_NAME, 
     CONCAT('0','ENVOLVE', ENVOLVE_CLAIM_EXTRACTS.PRVD_ID, ENVOLVE_CLAIM_EXTRACTS.PROV_LOC_ID) AS P_PROVIDER_ID, 
     UTIL.FXN_ARRAY_HASH([CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE, P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS LNK_CLAIM_DETAIL_RENDERING_PROVIDER_HKEY, 
     UTIL.FXN_ARRAY_HASH([CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY, 
     UTIL.FXN_ARRAY_HASH([CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS HUB_PROVIDER_HKEY, 
 FROM RAWDATA.ENVOLVE_CLAIM_EXTRACTS
     JOIN STAGEDATA.LKP_CLAIM_MEMBER_ENVOLVE
        ON (LKP_CLAIM_MEMBER_ENVOLVE.CLAIM_NBR = ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO)
     JOIN RAWDATA.ENVOLVE_PROVIDER
        ON (ENVOLVE_CLAIM_EXTRACTS.PRVD_ID = ENVOLVE_PROVIDER.PROVIDER_NBR)
         AND (ENVOLVE_CLAIM_EXTRACTS.PROV_LOC_ID = RIGHT(ENVOLVE_PROVIDER.MA_PROVIDER_NBR,6))
 WHERE ENVOLVE_CLAIM_EXTRACTS.PRVD_ID IS NOT NULL AND ENVOLVE_CLAIM_EXTRACTS.PROV_LOC_ID IS NOT NULL
   AND TRIM(ENVOLVE_PROVIDER.FIRST_NAME) <> ''
   AND TRY_CAST(FIRST_NAME AS NUMBER) IS NULL
 QUALIFY ROW_NUMBER() -- get the most current submitted file for a claim line
    OVER(PARTITION BY ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO,ENVOLVE_CLAIM_EXTRACTS.ITEM_NO
    ORDER BY SPLIT_PART(SPLIT_PART(ENVOLVE_CLAIM_EXTRACTS.FILENAME, '_', 7), '.', 1) DESC) = 1 

UNION ALL
SELECT DISTINCT
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID AS CD_TPA_CLIENT_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID AS CD_TPA_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID AS CD_TPA_DIV_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.DATA_SOURCE_NAME AS CD_DATA_SOURCE_NAME, 
     ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO AS CD_CLAIM_NBR, 
     ENVOLVE_CLAIM_EXTRACTS.ITEM_NO AS CD_CLAIM_LINE_NBR, 
     CONCAT(COALESCE(ENVOLVE_CLAIM_EXTRACTS.EOB_MAIL_DATE,''), COALESCE(ENVOLVE_CLAIM_EXTRACTS.COUNTY_CODE,''),'P') AS CD_CLAIM_LINE_SEQ_NBR, 
     'N/A' AS CD_CLAIM_LINE_PROCEDURE_ADJ_CODE, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID AS P_TPA_CLIENT_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID AS P_TPA_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID AS P_TPA_DIV_ID, 
     LKP_CLAIM_MEMBER_ENVOLVE.DATA_SOURCE_NAME AS P_DATA_SOURCE_NAME, 
     CONCAT('0','ENVOLVE', ENVOLVE_CLAIM_EXTRACTS.PRVD_ID) AS P_PROVIDER_ID, 
     UTIL.FXN_ARRAY_HASH([CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE, P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS LNK_CLAIM_DETAIL_RENDERING_PROVIDER_HKEY, 
     UTIL.FXN_ARRAY_HASH([CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY, 
     UTIL.FXN_ARRAY_HASH([CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS HUB_PROVIDER_HKEY, 
 FROM RAWDATA.ENVOLVE_CLAIM_EXTRACTS
     JOIN STAGEDATA.LKP_CLAIM_MEMBER_ENVOLVE
        ON (LKP_CLAIM_MEMBER_ENVOLVE.CLAIM_NBR = ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO)
     JOIN RAWDATA.ENVOLVE_PROVIDER
        ON (ENVOLVE_CLAIM_EXTRACTS.PRVD_ID = ENVOLVE_PROVIDER.PROVIDER_NBR)
 WHERE ENVOLVE_CLAIM_EXTRACTS.PRVD_ID IS NOT NULL AND ENVOLVE_CLAIM_EXTRACTS.PROV_LOC_ID IS NULL
   AND TRIM(ENVOLVE_PROVIDER.FIRST_NAME) <> ''
   AND TRY_CAST(FIRST_NAME AS NUMBER) IS NULL
 QUALIFY ROW_NUMBER() -- get the most current submitted file for a claim line
    OVER(PARTITION BY ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO,ENVOLVE_CLAIM_EXTRACTS.ITEM_NO
    ORDER BY SPLIT_PART(SPLIT_PART(ENVOLVE_CLAIM_EXTRACTS.FILENAME, '_', 7), '.', 1) DESC) = 1 
   ;