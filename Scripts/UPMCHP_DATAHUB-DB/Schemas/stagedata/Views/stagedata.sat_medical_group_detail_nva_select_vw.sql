CREATE OR REPLACE VIEW STAGEDATA.SAT_MEDICAL_GROUP_DETAIL_NVA_SELECT_VW
COMMENT = 'This is a SAT View containing Medical Group Details'
AS 
SELECT DISTINCT
'000001' AS TPA_CLIENT_ID
,'000001' AS TPA_ID
,'0001' AS TPA_DIV_ID
,'NVA' AS DATA_SOURCE_NAME
,CONCAT(PROVIDER_ID) AS MEDICAL_GROUP_ID
,CONCAT('NVA TaxID ', PROVIDER_ID) AS MEDICAL_GROUP_NAME
,PROVIDER_ID AS TAX_ID_NBR
,NULL AS EMAIL_ADDRESS
,NULL AS NPI_NBR
,NULL AS MEDICAL_GROUP_START_DATE
,NULL AS MEDICAL_GROUP_ACTIVE_IND
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY
,UTIL.FXN_ARRAY_HASH(
    [
    MEDICAL_GROUP_NAME
    ,TAX_ID_NBR
    ,EMAIL_ADDRESS
    ,NPI_NBR
    ,MEDICAL_GROUP_START_DATE
    ,MEDICAL_GROUP_ACTIVE_IND
    ]
) AS HASH_DIFF
FROM RAWDATA.NVA_PROVIDER
WHERE PROVIDER_ID IS NOT NULL
-- Get the list of numbers across all provider files regardless of when they were sent

UNION

SELECT DISTINCT
'000001' AS TPA_CLIENT_ID
,'000001' AS TPA_ID
,'0001' AS TPA_DIV_ID
,'NVA' AS DATA_SOURCE_NAME
,"BillProvID" AS MEDICAL_GROUP_ID
,CONCAT('NVA TaxID ', "BillProvID") AS MEDICAL_GROUP_NAME
,"BillProvID" AS TAX_ID_NBR
,NULL AS EMAIL_ADDRESS
,NULL AS NPI_NBR
,NULL AS MEDICAL_GROUP_START_DATE
,NULL AS MEDICAL_GROUP_ACTIVE_IND
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY
,UTIL.FXN_ARRAY_HASH(
    [
    MEDICAL_GROUP_NAME
    ,TAX_ID_NBR
    ,EMAIL_ADDRESS
    ,NPI_NBR
    ,MEDICAL_GROUP_START_DATE
    ,MEDICAL_GROUP_ACTIVE_IND
    ]
) AS HASH_DIFF
FROM RAWDATA.NVA_PAID_CLAIM_EXTRACTS_VW
WHERE "BillProvID" IS NOT NULL
-- Get the list of numbers across all claim files regardless of when they were sent
;