CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_BILLING_PROVIDER_NVA_SELECT_VW
COMMENT = 'Source view for NVA data into LNK_CLAIM_BILLING_PROVIDER'
AS

SELECT DISTINCT
LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID AS C_TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_NVA.TPA_ID AS C_TPA_ID
,LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID AS C_TPA_DIV_ID
,LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME
,NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo" AS C_CLAIM_NBR
,'000001' AS MG_TPA_CLIENT_ID
,'000001' AS MG_TPA_ID
,'0001' AS MG_TPA_DIV_ID
,'NVA' MG_DATA_SOURCE_NAME
,CONCAT(NVA_PAID_CLAIM_EXTRACTS_VW."BillProvID") AS MG_MEDICAL_GROUP_ID
,UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_MEDICAL_GROUP_ID]) AS LNK_CLAIM_BILLING_PROVIDER_HKEY
,UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY
,UTIL.FXN_ARRAY_HASH([MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY
FROM RAWDATA.NVA_PAID_CLAIM_EXTRACTS_VW
	JOIN STAGEDATA.LKP_CLAIM_MEMBER_NVA
		ON (LKP_CLAIM_MEMBER_NVA.CLAIM_NBR = NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo")
WHERE NVA_PAID_CLAIM_EXTRACTS_VW."BillProvID" IS NOT NULL
;
