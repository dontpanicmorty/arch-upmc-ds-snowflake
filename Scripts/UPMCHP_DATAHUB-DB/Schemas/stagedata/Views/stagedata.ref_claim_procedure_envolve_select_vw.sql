CREATE OR REPLACE VIEW STAGEDATA.REF_CLAIM_PROCEDURE_ENVOLVE_SELECT_VW
COMMENT='Source view for refdata.claim_procedure'
--THIS IS A TEMPORARY SOLUTION AND WE WILL NEED TO REFACTOR TO UTILIZE THE OPTUM FILES
AS
SELECT DISTINCT
LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID
,LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID
,LKP_CLAIM_MEMBER_ENVOLVE.DATA_SOURCE_NAME
,ProcedureCodes_CURRENT.Code AS CODE
,TRIM(ProcedureCodes_CURRENT.ProcedureDescription) AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, ENVOLVE_CLAIM_EXTRACTS.PROC_CODE]) AS CLAIM_PROCEDURE_HKEY
FROM RAWDATA.ENVOLVE_CLAIM_EXTRACTS
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_ENVOLVE
        ON (LKP_CLAIM_MEMBER_ENVOLVE.CLAIM_NBR = ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO)
    LEFT JOIN (SELECT TpaClient, TpaIdOfClient, TpaDivision, Code, ProcedureDescription
            FROM  RAWDATA.MC400_DWOAO_PROCEDURECODES PROCEDURECODES
            QUALIFY ROW_NUMBER() OVER(PARTITION BY TPACLIENT, TpaIdOfClient, TpaDivision, Code ORDER BY EffectiveDate DESC) = 1
            ) ProcedureCodes_CURRENT
        ON (ProcedureCodes_CURRENT.TpaClient = LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID
        AND ProcedureCodes_CURRENT.TpaIdOfClient = LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID
        AND ProcedureCodes_CURRENT.TpaDivision = LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID
        AND ProcedureCodes_CURRENT.CODE = ENVOLVE_CLAIM_EXTRACTS.PROC_CODE)
WHERE ProcedureCodes_CURRENT.ProcedureDescription <> ''
AND REGEXP_LIKE(TRIM(ProcedureCodes_CURRENT.Code), '^[a-zA-Z0-9]{5}$')  --only including 5-character alphanumeric codes to exclude revenue codes
;