CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_RIDER_NVA_SELECT_VW
COMMENT = 'Source view for NVA data into LNK_CLAIM_RIDER'
AS
SELECT DISTINCT
LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID AS C_TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_NVA.TPA_ID AS C_TPA_ID,
LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID AS C_TPA_DIV_ID,
LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME,
NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo" AS C_CLAIM_NBR,
LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID AS R_TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_NVA.TPA_ID AS R_TPA_ID,
LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID AS R_TPA_DIV_ID,
'MC400Upm' AS R_DATA_SOURCE_NAME,
TRIM(RIDERS.VALUE) AS R_RIDER_CODE,
LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID AS MG_TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_NVA.TPA_ID AS MG_TPA_ID,
LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID AS MG_TPA_DIV_ID,
'MC400Upm' AS MG_DATA_SOURCE_NAME,
LKP_CLAIM_MEMBER_NVA.GROUP_CODE AS MG_GROUP_NBR, --Using this due to dummy information used on actual NVA Files
LKP_CLAIM_MEMBER_NVA.SUB_GROUP_CODE AS MG_SUB_GROUP_NBR, --Using this due to dummy information used on actual NVA Files
UTIL.FXN_ARRAY_HASH(
        [C_TPA_CLIENT_ID
        ,C_TPA_ID
        ,C_TPA_DIV_ID
        ,C_DATA_SOURCE_NAME
        ,C_CLAIM_NBR
        ,R_TPA_CLIENT_ID
        ,R_TPA_ID
        ,R_TPA_DIV_ID
        ,R_DATA_SOURCE_NAME
        ,R_RIDER_CODE
        ,MG_TPA_CLIENT_ID
        ,MG_TPA_ID
        ,MG_TPA_DIV_ID
        ,MG_DATA_SOURCE_NAME
        ,MG_GROUP_NBR
        ,MG_SUB_GROUP_NBR
        ]) AS LNK_CLAIM_RIDER_HKEY,
UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY,
UTIL.FXN_ARRAY_HASH([R_TPA_CLIENT_ID, R_TPA_ID, R_TPA_DIV_ID, R_DATA_SOURCE_NAME, R_RIDER_CODE]) AS HUB_RIDER_HKEY,
UTIL.FXN_ARRAY_HASH([MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_GROUP_NBR, MG_SUB_GROUP_NBR]) AS HUB_MEMBERSHIP_GROUP_HKEY

FROM RAWDATA.NVA_PAID_CLAIM_EXTRACTS_VW
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_NVA
        ON (LKP_CLAIM_MEMBER_NVA.CLAIM_NBR = NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo")
    ,LATERAL FLATTEN(INPUT => LKP_CLAIM_MEMBER_NVA.RIDER_ARRAY) RIDERS
;