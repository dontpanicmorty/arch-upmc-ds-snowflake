CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_BILLING_PROVIDER_SKYGEN_SELECT_VW
COMMENT = 'Source view for Skygen data into LNK_CLAIM_BILLING_PROVIDER'
AS
SELECT
'N/A' AS SOURCE_KEY,
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS C_TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS C_TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS C_TPA_DIV_ID,
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_HEADER.CLAIM_NBR AS C_CLAIM_NBR,
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS MG_TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS MG_TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS MG_TPA_DIV_ID,
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS MG_DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_HEADER.BILLING_PROVIDER_ID AS MG_MEDICAL_GROUP_ID,
UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_MEDICAL_GROUP_ID]) AS LNK_CLAIM_BILLING_PROVIDER_HKEY,
UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY,
UTIL.FXN_ARRAY_HASH([MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY

FROM RAWDATA.DWSKYGEN_CLAIM_HEADER
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (DWSKYGEN_CLAIM_HEADER.CLAIM_NBR = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
WHERE BILLING_PROVIDER_ID NOT IN ('PAYEE_-1','PAYEE_0')
;