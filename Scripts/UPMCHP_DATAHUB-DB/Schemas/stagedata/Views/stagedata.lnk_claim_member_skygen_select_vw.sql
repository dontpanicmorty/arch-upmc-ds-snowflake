CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_MEMBER_SKYGEN_SELECT_VW
COMMENT = 'Source view for Skygen data into LNK_CLAIM_MEMBER'
AS
SELECT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS C_TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID C_TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS C_TPA_DIV_ID,
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_HEADER.CLAIM_NBR AS C_CLAIM_NBR,
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS M_TPA_CLIENT_ID, 
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS M_TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS M_TPA_DIV_ID,
LKP_CLAIM_MEMBER_SKYGEN.MC400_MEMBER_NBR AS M_MEMBER_NBR,
'MC400Upm' AS M_DATA_SOURCE_NAME,
UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, M_TPA_CLIENT_ID, M_TPA_DIV_ID, M_TPA_ID, M_DATA_SOURCE_NAME, M_MEMBER_NBR]) AS LNK_CLAIM_MEMBER_HKEY,
UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY,
UTIL.FXN_ARRAY_HASH([M_TPA_CLIENT_ID, M_TPA_ID, M_TPA_DIV_ID, M_DATA_SOURCE_NAME, M_MEMBER_NBR]) AS HUB_MEMBER_HKEY

FROM RAWDATA.DWSKYGEN_CLAIM_HEADER
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (DWSKYGEN_CLAIM_HEADER.CLAIM_NBR = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)

UNION ALL

SELECT DISTINCT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS C_TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID C_TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS C_TPA_DIV_ID,
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME,
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO AS C_CLAIM_NBR,
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS M_TPA_CLIENT_ID, 
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS M_TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS M_TPA_DIV_ID,
LKP_CLAIM_MEMBER_SKYGEN.MC400_MEMBER_NBR AS M_MEMBER_NBR,
'MC400Upm' AS M_DATA_SOURCE_NAME,
UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, M_TPA_CLIENT_ID, M_TPA_DIV_ID, M_TPA_ID, M_DATA_SOURCE_NAME, M_MEMBER_NBR]) AS LNK_CLAIM_MEMBER_HKEY,
UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY,
UTIL.FXN_ARRAY_HASH([M_TPA_CLIENT_ID, M_TPA_ID, M_TPA_DIV_ID, M_DATA_SOURCE_NAME, M_MEMBER_NBR]) AS HUB_MEMBER_HKEY
FROM RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
WHERE CLAIM_NO NOT IN (SELECT CLAIM_NBR FROM RAWDATA.DWSKYGEN_CLAIM_HEADER)
;