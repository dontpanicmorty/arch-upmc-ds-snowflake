CREATE OR REPLACE VIEW STAGEDATA.REF_CLAIM_PROCESSING_REASON_AVESIS_SELECT_VW
COMMENT = 'Source view for Avesis Claim Processing Reason(s) data'
AS 

WITH AdjCdDesc_ranked AS (
SELECT DISTINCT
 LKP_CLAIM_MEMBER_AVESIS.TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_AVESIS.TPA_ID
,LKP_CLAIM_MEMBER_AVESIS.TPA_DIV_ID
,LKP_CLAIM_MEMBER_AVESIS.DATA_SOURCE_NAME
,'Adjustment' AS CLAIM_PROCESSING_REASON_TYPE
,ADJUSTMENT_CODE AS CODE
,ADJUSTMENT_CODE_DESCRIPTION AS CODE_DESC
,ROW_NUMBER() OVER (PARTITION BY ADJUSTMENT_CODE ORDER BY ADJUSTMENT_CODE_DESCRIPTION) AS rn
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,NULL AS HIPAA_277_CODE
,NULL AS HIPAA_835_CODE
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_PROCESSING_REASON_TYPE, CODE]) AS CLAIM_PROCESSING_REASON_HKEY
FROM RAWDATA.AVESIS_PAID_CLAIM_EXTRACTS
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_AVESIS
        ON (LKP_CLAIM_MEMBER_AVESIS.CLAIM_NBR = AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO)
WHERE ADJUSTMENT_CODE IS NOT NULL
AND AVESIS_PAID_CLAIM_EXTRACTS.CLAIM_NO IS NOT NULL
)
SELECT DISTINCT
    TPA_CLIENT_ID
    ,TPA_ID
    ,TPA_DIV_ID
    ,DATA_SOURCE_NAME
    ,CLAIM_PROCESSING_REASON_TYPE
    ,CODE
    ,CODE_DESC
    ,CODE_DESC_LONG
    ,CODE_SPANISH_DESC
    ,HIPAA_277_CODE
    ,HIPAA_835_CODE
    ,CLAIM_PROCESSING_REASON_HKEY
FROM ADJCDDESC_RANKED
WHERE RN = 1    --grab the first description in the raw file. Avoids having multiple code_descriptions per code
;