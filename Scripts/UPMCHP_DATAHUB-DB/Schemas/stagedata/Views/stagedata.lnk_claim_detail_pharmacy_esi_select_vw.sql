CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_DETAIL_PHARMACY_ESI_SELECT_VW
COMMENT = 'Source view for ESI data into LNK_CLAIM_DETAIL_PHARMACY'
AS
SELECT
'000001' AS CD_TPA_CLIENT_ID,
'000001' AS CD_TPA_ID,
'0001' AS CD_TPA_DIV_ID,
'ESI' AS CD_DATA_SOURCE_NAME,
 LKP_CLAIM_PHARMACY_CLAIM.CLAIM_ID AS CD_CLAIM_NBR,
 LKP_CLAIM_PHARMACY_CLAIM.CLAIM_ID AS CD_CLAIM_LINE_NBR,
 LKP_CLAIM_PHARMACY_CLAIM.XREF_CLAIM_ID AS CD_CLAIM_LINE_SEQ_NBR,
 LKP_CLAIM_PHARMACY_CLAIM.TRANSACTION_TYPE_CODE AS CD_CLAIM_LINE_PROCEDURE_ADJ_CODE,
'000001' AS P_TPA_CLIENT_ID,
'000001' AS P_TPA_ID,
'0001' AS P_TPA_DIV_ID,
'ESI' AS P_DATA_SOURCE_NAME,
CONCAT('ESI', 'Pharmacy', NABP_NBR, IFF(PHARMACY_NPI = 'UNKNOWN', '', PHARMACY_NPI)) AS P_PROVIDER_ID,
UTIL.FXN_ARRAY_HASH([CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE, P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS LNK_CLAIM_DETAIL_PHARMACY_HKEY,
UTIL.FXN_ARRAY_HASH([CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY,
UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PROVIDER_ID]) AS HUB_PROVIDER_HKEY
FROM STAGEDATA.LKP_CLAIM_PHARMACY_CLAIM
JOIN STAGEDATA.LKP_CLAIM_PHARMACY_DETAIL
    ON (LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_NUMBER = LKP_CLAIM_PHARMACY_DETAIL.NABP_NBR
    AND IFNULL(LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_IDENTIFIER,'UNKNOWN')= LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_NPI)
;