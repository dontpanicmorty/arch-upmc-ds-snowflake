CREATE OR REPLACE VIEW STAGEDATA.REF_CLAIM_PROCEDURE_CATEGORY_MC400UPM_SELECT_VW
COMMENT = 'Souce view for load REFDATA.CLAIM_PROCEDURE_CATEORY data'
AS
SELECT
TpaClient AS TPA_CLIENT_ID
,TpaIdOfClient AS TPA_ID
,TpaDivision AS TPA_DIV_ID
,'MC400Upm' AS DATA_SOURCE_NAME
,ProcedureType AS CODE
,TRIM(ProcedureTypeDesc) AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CODE]) AS CLAIM_PROCEDURE_CATEGORY_HKEY
FROM RAWDATA.MC400_DWOAO_PROCEDURETYPES
;