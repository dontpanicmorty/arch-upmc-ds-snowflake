CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_RIDER_ESI_SELECT_VW
COMMENT = 'Source view for ESI data into LNK_CLAIM_RIDER'
AS
SELECT DISTINCT
'000001' AS C_TPA_CLIENT_ID,
'000001' AS C_TPA_ID,
'0001'AS C_TPA_DIV_ID,
'ESI' AS C_DATA_SOURCE_NAME,
CLAIM_ID AS C_CLAIM_NBR,
'000001' AS R_TPA_CLIENT_ID,
'000001' AS R_TPA_ID,
'0001'AS R_TPA_DIV_ID,
'MC400Upm' AS R_DATA_SOURCE_NAME,
CASE
    WHEN BPL_RIDER_CODE_ARRAY <> [] THEN TRIM(SUBSTR(ARRAY_TO_STRING(BPL_RIDER_CODE_ARRAY, ' '),1,4))
    WHEN LINE_OF_BUSINESS_CODE IN ('CM', 'MC') AND RIDER_ARRAY <> [] AND SUBSTR(TRIM(RIDER_ARRAY[0]),1,1) IN ('X', 'R', 'P', 'H', 'J', 'K') THEN TRIM(RIDER_ARRAY[0])
    WHEN LINE_OF_BUSINESS_CODE IN ('CM', 'MC') AND RIDER_ARRAY <> [] AND SUBSTR(TRIM(RIDER_ARRAY[1]),1,1) IN ('X', 'R', 'P', 'H', 'J', 'K') THEN TRIM(RIDER_ARRAY[1])
    WHEN LINE_OF_BUSINESS_CODE IN ('CM', 'MC') AND RIDER_ARRAY <> [] AND SUBSTR(TRIM(RIDER_ARRAY[2]),1,1) IN ('X', 'R', 'P', 'H', 'J', 'K') THEN TRIM(RIDER_ARRAY[2])
    WHEN LINE_OF_BUSINESS_CODE IN ('CM', 'MC') AND RIDER_ARRAY <> [] AND SUBSTR(TRIM(RIDER_ARRAY[3]),1,1) IN ('X', 'R', 'P', 'H', 'J', 'K') THEN TRIM(RIDER_ARRAY[3])
    ELSE NULL
END AS R_RIDER_CODE,
'000001' AS MG_TPA_CLIENT_ID,
'000001' AS MG_TPA_ID,
'0001'AS MG_TPA_DIV_ID,
'MC400Upm' AS MG_DATA_SOURCE_NAME,
GROUP_NBR AS MG_GROUP_NBR,
SUB_GROUP_NBR AS MG_SUB_GROUP_NBR,
UTIL.FXN_ARRAY_HASH(
        [C_TPA_CLIENT_ID
        ,C_TPA_ID
        ,C_TPA_DIV_ID
        ,C_DATA_SOURCE_NAME
        ,C_CLAIM_NBR
        ,R_TPA_CLIENT_ID
        ,R_TPA_ID
        ,R_TPA_DIV_ID
        ,R_DATA_SOURCE_NAME
        ,R_RIDER_CODE
        ,MG_TPA_CLIENT_ID
        ,MG_TPA_ID
        ,MG_TPA_DIV_ID
        ,MG_DATA_SOURCE_NAME
        ,MG_GROUP_NBR
        ,MG_SUB_GROUP_NBR
        ]) AS LNK_CLAIM_RIDER_HKEY,
UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY,
UTIL.FXN_ARRAY_HASH([R_TPA_CLIENT_ID, R_TPA_ID, R_TPA_DIV_ID, R_DATA_SOURCE_NAME, R_RIDER_CODE]) AS HUB_RIDER_HKEY,
UTIL.FXN_ARRAY_HASH([MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_GROUP_NBR, MG_SUB_GROUP_NBR]) AS HUB_MEMBERSHIP_GROUP_HKEY

FROM STAGEDATA.LKP_CLAIM_PHARMACY_MEMBER
WHERE
MG_GROUP_NBR IS NOT NULL
AND MG_SUB_GROUP_NBR IS NOT NULL
AND R_RIDER_CODE IS NOT NULL--claim is mapped to a rider code
AND R_RIDER_CODE IN (SELECT RIDERCODE FROM RAWDATA.MC400_DWOAO_RIDERS)
;