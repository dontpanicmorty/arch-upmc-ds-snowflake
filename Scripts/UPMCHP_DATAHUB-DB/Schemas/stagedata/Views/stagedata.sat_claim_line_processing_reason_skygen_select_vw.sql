CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_LINE_PROCESSING_REASON_SKYGEN_SELECT_VW
COMMENT = 'This is a SAT View containing Claim Line Processing Reason data'
AS

SELECT
    LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME,
    'Adjustment' AS REASON_TYPE_CODE,
    1 AS CODE_POSITION,
    DWSKYGEN_CLAIM_DETAIL.ADJUSTMENT_REASON_CODE_01 AS REASON_CODE,
    UTIL.FXN_ARRAY_HASH([REASON_CODE]) AS HASH_DIFF,
    UTIL.FXN_ARRAY_HASH(
        [LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
        ,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
        ,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
        ,DATA_SOURCE_NAME
        ,DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR
        ,DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_NBR
        ,DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR
        ,DWSKYGEN_CLAIM_DETAIL.PROCEDURE_ADJ_CODE]
        ) AS HUB_CLAIM_DETAIL_HKEY    
FROM RAWDATA.DWSKYGEN_CLAIM_DETAIL
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
WHERE TO_NUMBER(DWSKYGEN_CLAIM_DETAIL.ADJUSTMENT_REASON_CODE_01) > 0 -- exclude all not applicable codes

UNION ALL

SELECT
    LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME,
    'Deductible' AS REASON_TYPE_CODE,
    1 AS CODE_POSITION,
      CASE
        WHEN DWSKYGEN_CLAIM_HEADER.PARTICIPATING_PROVIDER_CODE = 'P' THEN 'IN'
        ELSE 'DE'
    END AS REASON_CODE,
    UTIL.FXN_ARRAY_HASH([REASON_CODE]) AS HASH_DIFF,
    UTIL.FXN_ARRAY_HASH(
        [LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
        ,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
        ,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
        ,DATA_SOURCE_NAME
        ,DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR
        ,DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_NBR
        ,DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR
        ,DWSKYGEN_CLAIM_DETAIL.PROCEDURE_ADJ_CODE]
        ) AS HUB_CLAIM_DETAIL_HKEY    
FROM RAWDATA.DWSKYGEN_CLAIM_DETAIL
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
    JOIN RAWDATA.DWSKYGEN_CLAIM_HEADER
        ON (DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR = DWSKYGEN_CLAIM_HEADER.CLAIM_NBR)
WHERE DWSKYGEN_CLAIM_DETAIL.MEMBER_PAY_FLAG = TRUE 
        AND DWSKYGEN_CLAIM_DETAIL.DEDUCTIBLE_AMOUNT > 0

UNION ALL

SELECT
    LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME,
    'CoPay' AS REASON_TYPE_CODE,
    1 AS CODE_POSITION,
    'CO' AS REASON_CODE,
    UTIL.FXN_ARRAY_HASH([REASON_CODE]) AS HASH_DIFF,
    UTIL.FXN_ARRAY_HASH(
        [LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
        ,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
        ,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
        ,DATA_SOURCE_NAME
        ,DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR
        ,DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_NBR
        ,DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR
        ,DWSKYGEN_CLAIM_DETAIL.PROCEDURE_ADJ_CODE]
        ) AS HUB_CLAIM_DETAIL_HKEY    
FROM RAWDATA.DWSKYGEN_CLAIM_DETAIL
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
WHERE DWSKYGEN_CLAIM_DETAIL.MEMBER_PAY_FLAG = TRUE 
        AND DWSKYGEN_CLAIM_DETAIL.COPAY_AMOUNT > 0

UNION ALL

SELECT
    LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME,
    'CoInsurance' AS REASON_TYPE_CODE,
    1 AS CODE_POSITION,
    CASE
        WHEN DWSKYGEN_CLAIM_HEADER.PARTICIPATING_PROVIDER_CODE = 'P' THEN 'C2'
        WHEN DWSKYGEN_CLAIM_HEADER.PARTICIPATING_PROVIDER_CODE = 'N' THEN 'C3'
        ELSE 'C1' 
    END AS REASON_CODE,
    UTIL.FXN_ARRAY_HASH([REASON_CODE]) AS HASH_DIFF,
    UTIL.FXN_ARRAY_HASH(
        [LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
        ,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
        ,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
        ,DATA_SOURCE_NAME
        ,DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR
        ,DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_NBR
        ,DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR
        ,DWSKYGEN_CLAIM_DETAIL.PROCEDURE_ADJ_CODE]
        ) AS HUB_CLAIM_DETAIL_HKEY    
FROM RAWDATA.DWSKYGEN_CLAIM_DETAIL
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
    JOIN RAWDATA.DWSKYGEN_CLAIM_HEADER
        ON (DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR = DWSKYGEN_CLAIM_HEADER.CLAIM_NBR)
WHERE DWSKYGEN_CLAIM_DETAIL.MEMBER_PAY_FLAG = TRUE 
        AND DWSKYGEN_CLAIM_DETAIL.COINSURANCE_AMOUNT > 0

UNION ALL

SELECT
    LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME,
    'Adjustment' AS REASON_TYPE_CODE,
    1 AS CODE_POSITION,    
    SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.ADJUSTMENT_CODE AS REASON_CODE,
    UTIL.FXN_ARRAY_HASH([REASON_CODE]) AS HASH_DIFF,
    UTIL.FXN_ARRAY_HASH(
        [LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
        ,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
        ,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
        ,LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME
        ,SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO
        ,SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.ITEM_NO
        ,UTIL.FXN_ARRAY_HASH([SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.BILLED_AMT])
        ,'N/A']
        ) AS HUB_CLAIM_DETAIL_HKEY    
FROM RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
WHERE SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.ADJUSTMENT_CODE IS NOT NULL -- exclude all not applicable codes
AND SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO NOT IN (SELECT CLAIM_NBR FROM RAWDATA.DWSKYGEN_CLAIM_DETAIL) --Exclude claims in dwskygen, they supersede
;
