!set variable_substitution=true;
CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_LINE_NVA_SELECT_VW
COMMENT = 'This is a SAT View containing Claim Line data'
AS
SELECT DISTINCT 
    IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID, '000001') AS TPA_CLIENT_ID,
    IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_ID, '000001') AS TPA_ID,
    IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID, '0001') AS TPA_DIV_ID,
    IFNULL(LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME, 'NVA') AS DATA_SOURCE_NAME,
    NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo" AS CLAIM_NBR, 
    NVA_PAID_CLAIM_EXTRACTS_VW."ClaimSeqNo" AS CLAIM_LINE_NBR, 
    CONCAT(NVA_PAID_CLAIM_EXTRACTS_VW."ClaimSeqNo", NVA_PAID_CLAIM_EXTRACTS_VW."Trantype") AS CLAIM_LINE_SEQ_NBR, 
    'N/A' AS CLAIM_LINE_PROCEDURE_ADJ_CODE, 
    'E' AS CLAIM_TYPE_CODE, --(E)ncounter or (I)npatient
    NVA_PAID_CLAIM_EXTRACTS_VW."ReceivedDate" AS CLAIM_RECEIVED_DATE, 
    NVA_PAID_CLAIM_EXTRACTS_VW."ProcedureCode" as PROCEDURE_CODE, 
    NVA_PAID_CLAIM_EXTRACTS_VW."Units" AS PROCEDURE_QUANTITY, 
    NVA_PAID_CLAIM_EXTRACTS_VW.DOS AS SERVICE_BEGIN_DATE, 
    NULL AS SERVICE_END_DATE, 
    NULL AS ADD_DATE, 
    '3' AS ACCOUNTS_PAYABLE_PAY_STATUS_CODE, 
    NULL AS ADJUDICATION_STATUS, 
    NULL AS AP_POSTING_DATE, 
    NULL AS BENEFIT_CATEGORY_CODE, 
    NULL AS BENEFIT_LEVEL_CODE, 
    NULL AS BUCKET_STATUS_FLAG, 
    NULL AS CHECK_DATE, 
    NULL AS CHECK_NUMBER, 
    NULL AS CLAIM_DAY_CNT,
    NULL AS CLEAN_CLAIM_IND, 
    NULL AS COMPANY_CODE, 
    NULL AS DENIED_DAY_CNT, 
    ELIGIBILITYHISTORY.MISCSTATUSCODE AS ELIGIBILITY_MISC_STATUS_CODE, 
    NULL AS FORM_NUMBER, 
    NULL AS GL_DISTRIBUTION_CODE, 
    TRUE AS IS_PROCESSING_COMPLETE, 
    NULL AS KEY_TO_SOURCE_FILE, 
    'O' AS LOCATION_CODE, --all vision claims are outpatient, per Jen Rice on 5/30/25
    '3' AS PAY_STATUS_CODE, 
    NVA_PAID_CLAIM_EXTRACTS_VW."PaidDate" AS PAYMENT_DATE, 
    NULL AS TOOTH_QUADRANT, 
    NULL AS REVENUE_CODE, 
    NULL AS SERVICE_CNT, 
    NULL AS SERVICE_REASON_CODE, 
    CASE
        WHEN NVA_PAID_CLAIM_EXTRACTS_VW."PaidAmt" <> 0 THEN 'P'
        WHEN NVA_PAID_CLAIM_EXTRACTS_VW."PaidAmt" = 0 THEN 'D'
        ELSE 'U'
    END AS SERVICE_STATUS_CODE, --no 'I' because all NVA claims included in the files have already been adjudicated
    CASE
        WHEN NVA_PAID_CLAIM_EXTRACTS_VW."PaidAmt" <> 0 THEN 'Paid'
        WHEN NVA_PAID_CLAIM_EXTRACTS_VW."PaidAmt" = 0 THEN 'Denied'
        ELSE 'Unknown'
    END AS SERVICE_STATUS_DESC, --no 'InProcess' because all NVA claims included in the files have already been adjudicated
    CASE 
        WHEN POS IN ('11', '22', '23', '32', '33') THEN 'P' --Logic Accurate, per Jen Rice on 5/30/25 
        WHEN POS IS NULL THEN 'U'
        ELSE 'U'
    END AS SERVICE_TYPE_CODE,
    NVA_PAID_CLAIM_EXTRACTS_VW."Trantype" AS TRANSACTION_TYPE_CODE, 
    NVA_PAID_CLAIM_EXTRACTS_VW."TranDesc" AS TRANSACTION_TYPE_DESC, 
    NULL AS SOURCE_LAST_UPDATED_DATETIME, 
    NULL AS TOOTH_ID, 
    NULL AS TOOTH_ARCH, 
    TO_ARRAY(NULL) AS TOOTH_SURFACE_ARRAY,
    TO_DECIMAL(DATEDIFF(DAY, TO_DATE(NVA_PAID_CLAIM_EXTRACTS_VW.DOB), TO_DATE(NVA_PAID_CLAIM_EXTRACTS_VW.DOS)) / 365.25, 10, 2) AS MEMBER_AGE_NBR, 
    NULL AS AUTHORIZATION_NBR,
    NULL AS HCPCS_CODE,
    NULL AS CMS_CURRENT_ITERATION_FLAG,
    UTIL.FXN_ARRAY_HASH([IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID, '000001'), IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_ID, '000001'), IFNULL(LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID, '0001'), IFNULL(LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME, 'NVA'), NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo", CLAIM_LINE_NBR, CLAIM_LINE_SEQ_NBR, CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY, 
    UTIL.FXN_ARRAY_HASH([CLAIM_TYPE_CODE, CLAIM_RECEIVED_DATE, PROCEDURE_CODE, PROCEDURE_QUANTITY, SERVICE_BEGIN_DATE, SERVICE_END_DATE, ADD_DATE, ACCOUNTS_PAYABLE_PAY_STATUS_CODE, ADJUDICATION_STATUS, AP_POSTING_DATE, BENEFIT_CATEGORY_CODE, BENEFIT_LEVEL_CODE, BUCKET_STATUS_FLAG, CHECK_DATE, CHECK_NUMBER, CLAIM_DAY_CNT, CLEAN_CLAIM_IND, COMPANY_CODE, DENIED_DAY_CNT, ELIGIBILITY_MISC_STATUS_CODE, FORM_NUMBER, GL_DISTRIBUTION_CODE, IS_PROCESSING_COMPLETE, KEY_TO_SOURCE_FILE, SERVICE_TYPE_CODE, LOCATION_CODE, PAY_STATUS_CODE, PAYMENT_DATE, TOOTH_QUADRANT, REVENUE_CODE, SERVICE_CNT, SERVICE_REASON_CODE, SERVICE_STATUS_CODE, SERVICE_STATUS_DESC, SERVICE_TYPE_CODE, TRANSACTION_TYPE_CODE, TRANSACTION_TYPE_DESC, SOURCE_LAST_UPDATED_DATETIME, TOOTH_ID, TOOTH_ARCH, MEMBER_AGE_NBR, AUTHORIZATION_NBR, TOOTH_SURFACE_ARRAY, HCPCS_CODE, CMS_CURRENT_ITERATION_FLAG]) AS HASH_DIFF
FROM RAWDATA.NVA_PAID_CLAIM_EXTRACTS_VW 
LEFT JOIN STAGEDATA.LKP_CLAIM_MEMBER_NVA
        ON (LKP_CLAIM_MEMBER_NVA.CLAIM_NBR = NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo")
LEFT JOIN &{MC400}.DWOAO.ELIGIBILITYHISTORY
        ON ELIGIBILITYHISTORY.MEMBERNBR = NVA_PAID_CLAIM_EXTRACTS_VW."MemberID" 
        AND REPLACE(TO_CHAR(NVA_PAID_CLAIM_EXTRACTS_VW.DOS), '-', '')::INT BETWEEN ELIGIBILITYHISTORY.ELIGIBILITYSTARTDATE AND ELIGIBILITYHISTORY.ELIGIBILITYENDDATE
;
!set variable_substitution=false;