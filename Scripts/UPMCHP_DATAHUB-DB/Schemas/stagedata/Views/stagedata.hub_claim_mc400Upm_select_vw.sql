CREATE OR REPLACE VIEW STAGEDATA.HUB_CLAIM_MC400UPM_SELECT_VW
COMMENT='Source view for MC400Upm data into HUB_CLAIM'
AS
SELECT 
'N/A' AS SOURCE_KEY,
TpaClient AS TPA_CLIENT_ID,
TpaIdOfClient AS TPA_ID,
TpaDivision AS TPA_DIV_ID,
'MC400Upm' AS DATA_SOURCE_NAME,
ClaimNbr AS CLAIM_NBR,
UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_NBR]) AS HUB_CLAIM_HKEY
FROM RAWDATA.MC400_DWOAO_CLAIMS
WHERE MemberNbr <> '99999999901'
;
