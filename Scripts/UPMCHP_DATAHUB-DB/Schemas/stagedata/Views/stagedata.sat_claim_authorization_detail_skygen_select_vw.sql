CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_AUTHORIZATION_DETAIL_SKYGEN_SELECT_VW
COMMENT = 'This is a SAT View containing Skygen AUTHORIZATION Header data'
AS

SELECT 
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_LINE_NBR,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.PROCEDURE_CODE,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.DETERMINATION_STATUS_DESC AS DETERMINATION_STATUS_DESC,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.DETERMINATION_DATE AS DETERMINATION_DATE,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.SERVICE_BEGIN_DATE,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.SERVICE_END_DATE,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZED_QTY,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.CONSUMED_QTY,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.DENIED_QTY,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.REQUESTED_QTY,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.TOOTH_ID,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.TOOTH_ARCH,
    DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.TOOTH_QUADRANT,
    UTIL.FXN_ARRAY_HASH([LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID, LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID, LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID, DATA_SOURCE_NAME, DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR, DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_LINE_NBR]) AS HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY,
    UTIL.FXN_ARRAY_HASH([PROCEDURE_CODE,
                        DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.DETERMINATION_STATUS_DESC,
                        DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.DETERMINATION_DATE ,
                        SERVICE_BEGIN_DATE,
                        SERVICE_END_DATE,
                        AUTHORIZED_QTY,
                        CONSUMED_QTY,
                        DENIED_QTY,
                        REQUESTED_QTY,
                        TOOTH_ID,
                        TOOTH_ARCH,
                        TOOTH_QUADRANT
                         ]) AS HASH_DIFF
FROM RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION
    JOIN STAGEDATA.LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN
        ON (DWSKYGEN_CLAIM_AUTHORIZATION.AUTHORIZATION_NBR = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.AUTHORIZATION_NBR)
    JOIN RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL
        ON (DWSKYGEN_CLAIM_AUTHORIZATION.AUTHORIZATION_NBR = DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR)  

UNION ALL

SELECT 
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID,
    LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME,
    SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER AS AUTHORIZATION_NBR,
    COALESCE(SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.ITEM_NUMBER, 'N/A') AS AUTHORIZATION_LINE_NBR,
    SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.CODE AS PROCEDURE_CODE,
    CASE
        WHEN SERVICE_DETERMINATION_STATUS = '-2' THEN 'Missing Value'
        WHEN SERVICE_DETERMINATION_STATUS = '1' THEN 'Pending'
        WHEN SERVICE_DETERMINATION_STATUS = '2' THEN 'Preliminary Denied'
        WHEN SERVICE_DETERMINATION_STATUS = '3' THEN 'Denied'
        WHEN SERVICE_DETERMINATION_STATUS = '4' THEN 'Approved'
        WHEN SERVICE_DETERMINATION_STATUS = '5' THEN 'Preliminary Approved'
        WHEN SERVICE_DETERMINATION_STATUS = '6' THEN 'Not Applicable'
        ELSE 'Unknown'
    END AS DETERMINATION_STATUS_DESC,
    SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.DETERMINATION_DATE AS DETERMINATION_DATE,
    SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.DATE_OF_SERVICE_FROM AS SERVICE_BEGIN_DATE,
    SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.DATE_OF_SERVICE_TO AS SERVICE_END_DATE,
    SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.QUANTITY_AUTHORIZED AS AUTHORIZED_QTY,
    SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.QUANTITY_CONSUMED AS CONSUMED_QTY,
    SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.QUANTITY_DENIED AS DENIED_QTY,
    SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.QUANTITY_REQUESTED AS REQUESTED_QTY,
    SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.TOOTH_ID,
    SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.ARCH AS TOOTH_ARCH,
    SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.QUADRANT AS TOOTH_QUADRANT,
    UTIL.FXN_ARRAY_HASH([LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID, LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID, LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID, DATA_SOURCE_NAME, SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER, AUTHORIZATION_LINE_NBR]) AS HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY,
    UTIL.FXN_ARRAY_HASH([PROCEDURE_CODE,
                        DETERMINATION_STATUS_DESC,
                        SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.DETERMINATION_DATE,
                        SERVICE_BEGIN_DATE,
                        SERVICE_END_DATE,
                        AUTHORIZED_QTY,
                        CONSUMED_QTY,
                        DENIED_QTY,
                        REQUESTED_QTY,
                        TOOTH_ID,
                        TOOTH_ARCH,
                        TOOTH_QUADRANT
                         ]) AS HASH_DIFF
FROM RAWDATA.SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW
    JOIN STAGEDATA.LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN
        ON (SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.AUTHORIZATION_NBR)
WHERE SKYGEN_AUTHORIZATION_EXTRACTS_CURRENT_VW.AUTHORIZATION_NUMBER NOT IN (SELECT AUTHORIZATION_NBR FROM RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION)
;