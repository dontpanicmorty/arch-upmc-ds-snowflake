CREATE OR REPLACE VIEW STAGEDATA.SAT_MEDICAL_GROUP_DETAIL_AVESIS_SELECT_VW
COMMENT = 'This is a SAT View containing Provider Detail data'
AS

WITH QUALIFY_CTE AS
    (SELECT *
     FROM RAWDATA.AVESIS_PROVIDER
     QUALIFY ROW_NUMBER()
        OVER(PARTITION BY AVESIS_PROVIDER.PLAN_PRVD_NO
            ORDER BY SPLIT_PART(SPLIT_PART(AVESIS_PROVIDER.FILENAME, '_', 4), '.', 1) DESC) = 1 
    )

, CTE AS
  (SELECT DISTINCT
		'000001' AS TPA_CLIENT_ID,
        '000001' AS TPA_ID,
        '0001' AS TPA_DIV_ID,
        'Avesis' AS DATA_SOURCE_NAME,
 		 TRIM(PLAN_PRVD_NO) AS MEDICAL_GROUP_ID, 
 		'Facility' AS PROVIDER_TYPE_NAME, 
 		CONCAT(COALESCE(TRIM(PRVD_FIRST_NAM),''), COALESCE(TRIM(PRVD_LAST_NAM),'') ) AS MEDICAL_GROUP_NAME,  
 		NULL AS TAX_ID_NBR, 
        NULL AS EMAIL_ADDRESS,
        NULL AS NPI_NBR,
        NULL AS MEDICAL_GROUP_START_DATE,
        NULL AS MEDICAL_GROUP_ACTIVE_IND,
        UTIL.FXN_ARRAY_HASH(['000001', '000001', '0001', DATA_SOURCE_NAME, MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY,
        UTIL.FXN_ARRAY_HASH(
        [
        MEDICAL_GROUP_NAME
        ,TAX_ID_NBR
        ,EMAIL_ADDRESS
        ,NPI_NBR
        ,MEDICAL_GROUP_START_DATE
        ,MEDICAL_GROUP_ACTIVE_IND
        ]
    ) AS HASH_DIFF
FROM QUALIFY_CTE
WHERE NULLIF(TRIM(PLAN_PRVD_NO), '') IS NOT NULL AND MA_PRVD_NO IS NOT NULL
        AND TRIM(PLAN_PRVD_NO) <> 'DIRECT'
        AND (TRIM(PRVD_FIRST_NAM) = ''
      OR TRY_TO_NUMBER(PRVD_FIRST_NAM) IS NOT NULL)

UNION ALL 

SELECT DISTINCT
		'000001' AS TPA_CLIENT_ID,
        '000001' AS TPA_ID,
        '0001' AS TPA_DIV_ID,
        'Avesis' AS DATA_SOURCE_NAME,
 		TRIM(PLAN_PRVD_NO) AS MEDICAL_GROUP_ID, 
 		'Facility' AS PROVIDER_TYPE_NAME, 
 		CONCAT(COALESCE(TRIM(PRVD_FIRST_NAM),''), COALESCE(TRIM(PRVD_LAST_NAM),'') ) AS MEDICAL_GROUP_NAME,  
 		NULL AS TAX_ID_NBR, 
        NULL AS EMAIL_ADDRESS,
        NULL AS NPI_NBR,
        NULL AS MEDICAL_GROUP_START_DATE,
        NULL AS MEDICAL_GROUP_ACTIVE_IND,
        UTIL.FXN_ARRAY_HASH(['000001', '000001', '0001', DATA_SOURCE_NAME, MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY,
        UTIL.FXN_ARRAY_HASH(
        [
        MEDICAL_GROUP_NAME
        ,TAX_ID_NBR
        ,EMAIL_ADDRESS
        ,NPI_NBR
        ,MEDICAL_GROUP_START_DATE
        ,MEDICAL_GROUP_ACTIVE_IND
        ]
    ) AS HASH_DIFF
FROM QUALIFY_CTE
	 WHERE NULLIF(TRIM(PLAN_PRVD_NO), '') IS NOT NULL AND MA_PRVD_NO IS NULL
        AND TRIM(PLAN_PRVD_NO) <> 'DIRECT'
        AND (TRIM(PRVD_FIRST_NAM) = ''
      OR TRY_TO_NUMBER(PRVD_FIRST_NAM) IS NOT NULL)
)

SELECT DISTINCT * FROM CTE
;