CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_PLAN_SKYGEN_SELECT_VW
COMMENT='Source view for Skygen data into LNK_CLAIM_PLAN'
AS

SELECT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS C_TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS C_TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS C_TPA_DIV_ID,
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_HEADER.CLAIM_NBR AS C_CLAIM_NBR,
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS P_TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS P_TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS P_TPA_DIV_ID,
'MC400Upm' AS P_DATA_SOURCE_NAME, --Plans are sourced from MC400Upm
IFNULL(DWSKYGEN_CLAIM_HEADER.PLAN_CODE, LKP_CLAIM_MEMBER_SKYGEN.PLAN_CODE) AS P_PLAN_CODE,
UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PLAN_CODE]) AS LNK_CLAIM_PLAN_HKEY,
UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY,
UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PLAN_CODE]) AS HUB_PLAN_HKEY

FROM RAWDATA.DWSKYGEN_CLAIM_HEADER
    INNER JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (DWSKYGEN_CLAIM_HEADER.CLAIM_NBR = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR)
WHERE P_PLAN_CODE IS NOT NULL

UNION ALL

SELECT DISTINCT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS C_TPA_CLIENT_ID, 
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS C_TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS C_TPA_DIV_ID,
LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME,
SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO AS C_CLAIM_NBR,
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS P_TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS P_TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS P_TPA_DIV_ID,
'MC400Upm' AS P_DATA_SOURCE_NAME, --Plans are sourced from MC400Upm
LKP_CLAIM_MEMBER_SKYGEN.PLAN_CODE AS P_PLAN_CODE,  --They do not provide a plan numberon the claim so we will just use what they have on eligibility
UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PLAN_CODE]) AS LNK_CLAIM_PLAN_HKEY,
UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY,
UTIL.FXN_ARRAY_HASH([P_TPA_CLIENT_ID, P_TPA_ID, P_TPA_DIV_ID, P_DATA_SOURCE_NAME, P_PLAN_CODE]) AS HUB_PLAN_HKEY

FROM RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR = SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO)
WHERE SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO NOT IN (SELECT CLAIM_NBR FROM RAWDATA.DWSKYGEN_CLAIM_HEADER)
AND P_PLAN_CODE IS NOT NULL
;
