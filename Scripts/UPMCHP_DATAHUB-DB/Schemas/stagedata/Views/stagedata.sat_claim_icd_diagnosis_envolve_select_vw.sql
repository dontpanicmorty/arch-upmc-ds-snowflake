CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_ICD_DIAGNOSIS_ENVOLVE_SELECT_VW 
COMMENT= 'Source view for ENVOLVE data into SAT_CLAIM_ICD_DIAGNOSIS'
AS 
SELECT DISTINCT
    LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID,
	LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID,
	LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID,
	LKP_CLAIM_MEMBER_ENVOLVE.DATA_SOURCE_NAME, 
    ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO AS CLAIM_NBR, 
    STAGEDATA.FXN_BUILD_CLAIM_GROUP_CODE_ARRAY('diagnosisCode', DATA_SOURCE_NAME
        , object_construct_keep_null(
            'DIAGNOSIS1', PRIMARY_DIAG_CODE,
            'DIAGNOSIS2', DIAG_2,
            'DIAGNOSIS3', DIAG_3,
            'DIAGNOSIS4', DIAG_4,
            'DIAGNOSIS5', DIAG_5,
            'DIAGNOSIS6', DIAG_6,
            'DIAGNOSIS7', DIAG_7,
            'DIAGNOSIS8', DIAG_8,
            'DIAGNOSIS9', DIAG_9,
            'DIAGNOSIS10', DIAG_10,
            'DIAGNOSIS11', DIAG_11,
            'DIAGNOSIS12', DIAG_12,
            'ICD_VERSION_CODE',ICD_TYPE_INDICATOR
        ), 12) AS ICD_DIAGNOSIS_CODES, 
	UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_NBR]) AS HUB_CLAIM_HKEY, 
    UTIL.FXN_ARRAY_HASH([ICD_DIAGNOSIS_CODES, HUB_CLAIM_HKEY]) AS HASH_DIFF
FROM RAWDATA.ENVOLVE_CLAIM_EXTRACTS
JOIN STAGEDATA.LKP_CLAIM_MEMBER_ENVOLVE
        ON (LKP_CLAIM_MEMBER_ENVOLVE.CLAIM_NBR = ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO)
WHERE PRIMARY_DIAG_CODE IS NOT NULL
QUALIFY ROW_NUMBER() -- get the most current submitted file for a claim line
    OVER(PARTITION BY ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO,ENVOLVE_CLAIM_EXTRACTS.ITEM_NO
    ORDER BY SPLIT_PART(SPLIT_PART(ENVOLVE_CLAIM_EXTRACTS.FILENAME, '_', 7), '.', 1) DESC) = 1 
;