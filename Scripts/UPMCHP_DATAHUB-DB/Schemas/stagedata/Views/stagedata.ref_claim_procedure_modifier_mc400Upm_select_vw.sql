CREATE OR REPLACE VIEW STAGEDATA.REF_CLAIM_PROCEDURE_MODIFIER_MC400UPM_SELECT_VW
COMMENT = 'This is a REF View containing Claim Procedure Modifier data'
AS
SELECT
TpaClient AS TPA_CLIENT_ID
,TpaIdOfClient AS TPA_ID
,TpaDivision AS TPA_DIV_ID
,'MC400Upm' AS DATA_SOURCE_NAME
,Modifier as CODE
,IFF(IFNULL(ModifierDescription,'') = '', 'Description Not Found', ModifierDescription) AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CODE]) AS CLAIM_PROCEDURE_MODIFIER_HKEY
FROM RAWDATA.MC400_DWOAO_PROCEDUREMODIFIER
WHERE (TpaClient, TpaIdOfClient, TpaDivision, Modifier) IN 
    (SELECT DISTINCT TpaClient, TpaIdOfClient, TpaDivision, MODIFIER_CODE
        FROM RAWDATA.MC400_DWOAO_CLAIMSDETAIL
        UNPIVOT (MODIFIER_CODE FOR COLUMN_NAME IN (ProcedureModifier, MODIFIER2, MODIFIER3, MODIFIER4))
    )
ORDER BY CODE
;