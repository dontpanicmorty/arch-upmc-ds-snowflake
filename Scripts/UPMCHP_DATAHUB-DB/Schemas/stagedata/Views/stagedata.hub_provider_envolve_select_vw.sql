CREATE OR REPLACE VIEW STAGEDATA.HUB_PROVIDER_ENVOLVE_SELECT_VW
COMMENT = 'Source view for ENVOLVE data into HUB_PROVIDER'
AS
SELECT DISTINCT
    'N/A' AS SOURCE_KEY,
    '000001' AS TPA_CLIENT_ID,
    '000001' AS TPA_ID,
    '0001' AS TPA_DIV_ID,
    'Envolve' AS DATA_SOURCE_NAME,
    CONCAT('0','ENVOLVE', TRIM(PROVIDER_NBR),RIGHT(MA_PROVIDER_NBR,6)) AS PROVIDER_ID,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY
 FROM RAWDATA.ENVOLVE_PROVIDER
   WHERE (TRIM(FIRST_NAME) <> ''
      AND TRY_CAST(FIRST_NAME AS NUMBER) IS NULL) AND MA_PROVIDER_NBR IS NOT NULL
QUALIFY ROW_NUMBER() -- get the most current submitted file 
    OVER(PARTITION BY ENVOLVE_PROVIDER.PROVIDER_NBR,RIGHT(ENVOLVE_PROVIDER.MA_PROVIDER_NBR,6)
    ORDER BY SPLIT_PART(SPLIT_PART(ENVOLVE_PROVIDER.FILENAME, '_', 7), '.', 1) DESC) = 1 
 UNION ALL
SELECT DISTINCT
    'N/A' AS SOURCE_KEY,
    '000001' AS TPA_CLIENT_ID,
    '000001' AS TPA_ID,
    '0001' AS TPA_DIV_ID,
    'Envolve' AS DATA_SOURCE_NAME,
    CONCAT('0','ENVOLVE', TRIM(PROVIDER_NBR)) AS PROVIDER_ID,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY
 FROM RAWDATA.ENVOLVE_PROVIDER
   WHERE (TRIM(FIRST_NAME) <> ''
      AND TRY_CAST(FIRST_NAME AS NUMBER) IS NULL) AND MA_PROVIDER_NBR IS NULL
QUALIFY ROW_NUMBER() -- get the most current submitted file 
    OVER(PARTITION BY ENVOLVE_PROVIDER.PROVIDER_NBR,RIGHT(ENVOLVE_PROVIDER.MA_PROVIDER_NBR,6)
    ORDER BY SPLIT_PART(SPLIT_PART(ENVOLVE_PROVIDER.FILENAME, '_', 7), '.', 1) DESC) = 1 
 ;