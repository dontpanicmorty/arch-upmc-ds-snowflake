CREATE OR REPLACE VIEW STAGEDATA.HUB_CLAIM_DETAIL_ESI_SELECT_VW
COMMENT='Source view for ESI data into HUB_CLAIM_DETAIL'
AS
SELECT 
'N/A' AS SOURCE_KEY,
'000001' AS TPA_CLIENT_ID,
'000001' AS TPA_ID,
'0001' AS TPA_DIV_ID,
'ESI' AS DATA_SOURCE_NAME,
CLAIM_ID AS CLAIM_NBR,
CLAIM_ID AS CLAIM_LINE_NBR,
XREF_CLAIM_ID AS CLAIM_LINE_SEQ_NBR,
TRANSACTION_TYPE_CODE AS CLAIM_LINE_PROCEDURE_ADJ_CODE,
UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID,
                     TPA_ID,
                     TPA_DIV_ID,
                     DATA_SOURCE_NAME,
                     CLAIM_NBR,
                     CLAIM_LINE_NBR,
                     CLAIM_LINE_SEQ_NBR,
                     CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY
FROM STAGEDATA.LKP_CLAIM_PHARMACY_CLAIM
;