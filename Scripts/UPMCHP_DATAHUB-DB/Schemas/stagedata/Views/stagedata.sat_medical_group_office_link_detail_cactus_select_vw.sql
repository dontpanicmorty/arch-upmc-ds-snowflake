CREATE OR REPLACE VIEW STAGEDATA.SAT_MEDICAL_GROUP_OFFICE_LINK_DETAIL_CACTUS_SELECT_VW
COMMENT = 'This is a SAT View containing Medical Group Office data'
AS
SELECT DISTINCT
    CAST(CACTUS_GROUPADDRESS.USERDEF_D1 AS DATE) AS MEDICAL_GROUP_ADDRESS_START_DATE,
    CAST(CACTUS_GROUPADDRESS.USERDEF_D2 AS DATE) AS MEDICAL_GROUP_ADDRESS_TERM_DATE,
    CACTUS_GROUPADDRESS.ACTIVE AS MEDICAL_GROUP_ADDRESS_ACTIVE_IND,
    UTIL.FXN_ARRAY_HASH([
        '000001',
        '000001',
        '0001',
        'Cactus',
        TRIM(CACTUS_GROUPS.ID),
        '000001',
        '000001',
        '0001',
        'Cactus',
        TRIM(CACTUS_GROUPADDRESS.ID)
    ]) AS LNK_MEDICAL_GROUP_OFFICE_HKEY,
    UTIL.FXN_ARRAY_HASH([
        MEDICAL_GROUP_ADDRESS_START_DATE,
        MEDICAL_GROUP_ADDRESS_TERM_DATE,
        MEDICAL_GROUP_ADDRESS_ACTIVE_IND
    ]) AS HASH_DIFF
FROM 
    RAWDATA.CACTUS_GROUPS
INNER JOIN RAWDATA.CACTUS_GROUPADDRESS 
    ON CACTUS_GROUPS.GROUP_K = CACTUS_GROUPADDRESS.GROUP_K
INNER JOIN RAWDATA.CACTUS_ADDRESSES 
    ON CACTUS_GROUPADDRESS.ADDRESS_K = CACTUS_ADDRESSES.ADDRESS_K
LEFT JOIN (
    SELECT 
        CACTUS_GROUPS.ID,
        COUNT(*) AS cnt
    FROM 
        RAWDATA.CACTUS_GROUPS
    GROUP BY 
        CACTUS_GROUPS.ID
    HAVING 
        COUNT(*) > 1
) DUPES
ON CACTUS_GROUPS.ID = DUPES.ID
WHERE 
    CACTUS_GROUPADDRESS.ID IS NOT NULL AND CACTUS_GROUPADDRESS.ID <> ''
    AND CACTUS_GROUPADDRESS.GROUP_K IS NOT NULL AND CACTUS_GROUPADDRESS.GROUP_K <> ''
    AND CACTUS_GROUPADDRESS.TAXIDNUMBER IS NOT NULL AND CACTUS_GROUPADDRESS.TAXIDNUMBER <> ''
    AND CACTUS_GROUPADDRESS.USERDEF_D1 IS NOT NULL
    AND CACTUS_GROUPS.ID IS NOT NULL AND CACTUS_GROUPS.ID <> ''
    AND (CACTUS_ADDRESSES.ADDRESSLINE1 IS NOT NULL AND CACTUS_ADDRESSES.ADDRESSLINE1 <> ''
        OR CACTUS_ADDRESSES.ADDRESSLINE2 IS NOT NULL AND CACTUS_ADDRESSES.ADDRESSLINE2 <> '')
    AND DUPES.ID IS NULL;