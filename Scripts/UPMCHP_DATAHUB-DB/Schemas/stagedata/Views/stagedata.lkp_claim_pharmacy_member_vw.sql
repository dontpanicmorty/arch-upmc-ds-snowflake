SELECT CLAIM_ID, CARDHOLDER_ID_NUMBER, MEMBERNBR, COVERAGEGROUPCODE AS GROUP_NBR, SUBGROUPCODE AS SUB_GROUP_NBR, PLANCODE AS PLAN_CODE, PLANTYPE AS PLAN_TYPE_CODE, 
ELIGIBILITYSTARTDATE, ELIGIBILITYENDDATE, DATE_FILLED, LINE_OF_BUSINESS_CODE, X.BENEFIT_CODE, HIT, X.RIDER_ARRAY, ARRAY_AGG(DISTINCT RIDER_BASE.RIDERCODE) WITHIN GROUP (ORDER BY RIDER_BASE.RIDERCODE DESC) AS BPL_RIDER_CODE_ARRAY
FROM    (
    SELECT  CLAIM_ID, CARDHOLDER_ID_NUMBER, MEMBERNBR, COVERAGEGROUPCODE, SUBGROUPCODE, PLANCODE, PLANTYPE, RIDER_ARRAY, ELIGIBILITYSTARTDATE, ELIGIBILITYENDDATE, DATE_FILLED, LINE_OF_BUSINESS_CODE, BENEFIT_CODE, HIT,
            ROW_NUMBER() OVER (PARTITION BY CLAIM_ID ORDER BY HIT) AS BEST_HIT
    FROM    (
        SELECT  CLAIM_ID, CARDHOLDER_ID_NUMBER, MEMBERNBR, COVERAGEGROUPCODE, SUBGROUPCODE, PLANCODE, PLANTYPE, RIDER_ARRAY, ELIGIBILITYSTARTDATE, ELIGIBILITYENDDATE, DATE_FILLED, LINE_OF_BUSINESS_CODE, BENEFIT_CODE, HIT
        FROM    MEMBER_MATCH_SPAN
    
        UNION 

        SELECT  CLAIM_ID, CARDHOLDER_ID_NUMBER, MEMBERNBR, COVERAGEGROUPCODE, SUBGROUPCODE, PLANCODE, PLANTYPE, RIDER_ARRAY, ELIGIBILITYSTARTDATE, ELIGIBILITYENDDATE, DATE_FILLED, LINE_OF_BUSINESS_CODE, BENEFIT_CODE, HIT
        FROM    MEMBER_PER_MATCH_SPAN

        UNION

        SELECT  CLAIM_ID, CARDHOLDER_ID_NUMBER, MEMBERNBR, COVERAGEGROUPCODE, SUBGROUPCODE, PLANCODE, PLANTYPE, RIDER_ARRAY, ELIGIBILITYSTARTDATE, ELIGIBILITYENDDATE, DATE_FILLED, LINE_OF_BUSINESS_CODE, BENEFIT_CODE, HIT
        FROM    MEMBER_EMP_MATCH_SPAN

        UNION

        SELECT  CLAIM_ID, CARDHOLDER_ID_NUMBER, MEMBERNBR, COVERAGEGROUPCODE, SUBGROUPCODE, PLANCODE, PLANTYPE, RIDER_ARRAY, ELIGIBILITYSTARTDATE, ELIGIBILITYENDDATE, DATE_FILLED, LINE_OF_BUSINESS_CODE, BENEFIT_CODE, HIT
        FROM    MEMBER_EMP_PER_MATCH_SPAN

        UNION

        SELECT  CLAIM_ID, CARDHOLDER_ID_NUMBER, MEMBERNBR, COVERAGEGROUPCODE, SUBGROUPCODE, PLANCODE, PLANTYPE, RIDER_ARRAY, ELIGIBILITYSTARTDATE, ELIGIBILITYENDDATE, DATE_FILLED, LINE_OF_BUSINESS_CODE, BENEFIT_CODE, HIT
        FROM    MEMBER_EMP_NODOB_MATCH_SPAN

        UNION

        SELECT  CLAIM_ID, CARDHOLDER_ID_NUMBER, MEMBERNBR, COVERAGEGROUPCODE, SUBGROUPCODE, PLANCODE, PLANTYPE, RIDER_ARRAY, ELIGIBILITYSTARTDATE, ELIGIBILITYENDDATE, DATE_FILLED, LINE_OF_BUSINESS_CODE, BENEFIT_CODE, HIT
        FROM    MEMBER_SUB_MATCH_SPAN

        UNION

        SELECT  CLAIM_ID, CARDHOLDER_ID_NUMBER, MEMBERNBR, COVERAGEGROUPCODE, SUBGROUPCODE, PLANCODE, PLANTYPE, RIDER_ARRAY, ELIGIBILITYSTARTDATE, ELIGIBILITYENDDATE, DATE_FILLED, LINE_OF_BUSINESS_CODE, BENEFIT_CODE, HIT
        FROM    MEMBER_SUB_PER_MATCH_SPAN

        UNION

        SELECT  CLAIM_ID, CARDHOLDER_ID_NUMBER, MEMBERNBR, COVERAGEGROUPCODE, SUBGROUPCODE, PLANCODE, PLANTYPE, RIDER_ARRAY, ELIGIBILITYSTARTDATE, ELIGIBILITYENDDATE, DATE_FILLED, LINE_OF_BUSINESS_CODE, BENEFIT_CODE, HIT
        FROM    MEMBER_CONTRACT_MATCH_SPAN
    
        UNION

        SELECT  CLAIM_ID, CARDHOLDER_ID_NUMBER, MEMBERNBR, COVERAGEGROUPCODE, SUBGROUPCODE, PLANCODE, PLANTYPE, RIDER_ARRAY, ELIGIBILITYSTARTDATE, ELIGIBILITYENDDATE, DATE_FILLED, LINE_OF_BUSINESS_CODE, BENEFIT_CODE, HIT
