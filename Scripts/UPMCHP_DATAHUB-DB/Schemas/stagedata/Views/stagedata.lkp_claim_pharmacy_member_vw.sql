CREATE OR REPLACE VIEW STAGEDATA.LKP_CLAIM_PHARMACY_MEMBER_VW
AS
WITH MEMBER_BASE AS (
    SELECT  M.MEMBERNBR,
            M.PERSONNBR,
            M.EMPLOYEENBR,
            M.SUBSCRIBERNBR,
            H.EXTERNALMEMBER,
            TRIM(M.MEMBERSFIRSTNAME) AS MEMBERSFIRSTNAME,
            TRIM(M.MEMBERSLASTNAME) AS MEMBERSLASTNAME,
            TO_DATE(
                CASE
                    WHEN M.MEMBERDATEOFBIRTH = 0 THEN '99991231'
                    ELSE M.MEMBERDATEOFBIRTH::VARCHAR
                END
            , 'YYYYMMDD') AS MEMBERDATEOFBIRTH,
            M.TPAIDOFCLIENT,
            M.TPACLIENT, 
            M.TPADIVISION, 
            H.COVERAGEGROUPCODE,
            H.SUBGROUPCODE,
            H.PLANCODE,
            H.PLANTYPE,
            REGEXP_SUBSTR_ALL(H.RIDERS, '.{1,4}') AS RIDER_ARRAY,
            TO_DATE(H.ELIGIBILITYSTARTDATE::VARCHAR, 'YYYYMMDD') AS ELIGIBILITYSTARTDATE,
            TO_DATE(CASE
                WHEN H.ELIGIBILITYENDDATE = 0 THEN '99991231'
                ELSE H.ELIGIBILITYENDDATE::VARCHAR
            END, 'YYYYMMDD') AS ELIGIBILITYENDDATE,
            CASE
                WHEN LOB.LINE_OF_BUSINESS_CODE = 'CHIP' THEN 'CM'
                ELSE LOB.LINE_OF_BUSINESS_CODE
            END AS LINE_OF_BUSINESS_CODE
    FROM    RAWDATA.MC400_DWOAO_MEMBERS M
    JOIN    RAWDATA.MC400_DWOAO_ELIGIBILITYHISTORY H ON H.MEMBERNBR = M.MEMBERNBR
    JOIN    &{IDAP_LAKE}.NETWORK.LOB_PLAN_TYPE LOB ON LOB.PLAN_TYPE = H.PLANTYPE
        AND LOB.TPA_CLIENT_ID = H.TPACLIENT
        AND LOB.TPA_DIV_ID = H.TPADIVISION
        AND LOB.TPA_ID = H.TPAIDOFCLIENT
),
CLAIM_BASE AS(
    SELECT  CLAIM_ID,
            CARDHOLDER_ID_NUMBER,
            CARDHOLDER_FIRST_NAME,
            CARDHOLDER_LAST_NAME,
            PATIENT_FIRST_NAME,
            PATIENT_LAST_NAME,
            DATE_FILLED,
            DATE_OF_BIRTH,
            LINE_OF_BUSINESS_CODE,
            BENEFIT_CODE
    FROM    STAGEDATA.LKP_CLAIM_PHARMACY_CLAIM
),
RIDER_BASE AS (
SELECT RIDERCODE,
GROUPNBR,
SUBGROUP,
TO_DATE(RIDEREFFDATE::VARCHAR, 'YYYYMMDD') AS RIDEREFFDATE,
            TO_DATE(CASE
                WHEN RIDERTERMDATE = 0 THEN '99991231'
                ELSE RIDERTERMDATE::VARCHAR
            END, 'YYYYMMDD') AS RIDERTERMDATE,
FROM RAWDATA.MC400_DWOAO_RIDERS
),
MEMBER_MATCH_SPAN AS (
    SELECT  CLAIM_ID, CARDHOLDER_ID_NUMBER, MEMBERNBR, COVERAGEGROUPCODE, SUBGROUPCODE, PLANCODE, PLANTYPE, ELIGIBILITYSTARTDATE, ELIGIBILITYENDDATE, RIDER_ARRAY, DATE_FILLED, C.LINE_OF_BUSINESS_CODE, BENEFIT_CODE, 10 AS HIT
    FROM    CLAIM_BASE  C
    JOIN    MEMBER_BASE M ON M.MEMBERNBR = C.CARDHOLDER_ID_NUMBER
        AND C.DATE_FILLED BETWEEN M.ELIGIBILITYSTARTDATE AND M.ELIGIBILITYENDDATE
        AND C.LINE_OF_BUSINESS_CODE = M.LINE_OF_BUSINESS_CODE
),
MEMBER_PER_MATCH_SPAN AS (
    SELECT  CLAIM_ID, CARDHOLDER_ID_NUMBER, MEMBERNBR, COVERAGEGROUPCODE, SUBGROUPCODE, PLANCODE, PLANTYPE, ELIGIBILITYSTARTDATE, ELIGIBILITYENDDATE, RIDER_ARRAY, DATE_FILLED, C.LINE_OF_BUSINESS_CODE, BENEFIT_CODE, 20 AS HIT
    FROM    CLAIM_BASE  C
    JOIN    MEMBER_BASE M ON M.MEMBERNBR = LEFT(C.CARDHOLDER_ID_NUMBER, LENGTH(C.CARDHOLDER_ID_NUMBER)-2)
        AND RIGHT(C.CARDHOLDER_ID_NUMBER, 2) = M.PERSONNBR
        AND C.DATE_OF_BIRTH = M.MEMBERDATEOFBIRTH
        AND C.DATE_FILLED BETWEEN M.ELIGIBILITYSTARTDATE AND M.ELIGIBILITYENDDATE
        AND C.LINE_OF_BUSINESS_CODE = M.LINE_OF_BUSINESS_CODE
),
MEMBER_EMP_MATCH_SPAN AS (
