    FROM    CLAIM_BASE  C
    JOIN    MEMBER_BASE M ON M.EMPLOYEENBR = SUBSTR(C.CARDHOLDER_ID_NUMBER,1,10)
        AND C.DATE_FILLED BETWEEN M.ELIGIBILITYSTARTDATE AND M.ELIGIBILITYENDDATE
