CREATE OR REPLACE VIEW STAGEDATA.HUB_MARKETING_OUTBOUND_COMM_FULLFILLMENT_SELECT_VW COMMENT = 'Source view for HUB_MARKETING_OUTBOUND_COMM_FULLFILLMENT' AS
SELECT DISTINCT 'MC400Upm' AS DATA_SOURCE_NAME,
    IFNULL(RECORD_SOURCE,'Unknown') AS RECORD_SOURCE,
    IFNULL(PRODUCT_CODE,'Unknown') AS PRODUCT_CODE,
    IFNULL(CUSTOMER,'Unknown') AS CUSTOMER,
    IMB AS IMB,
    CID AS COMMUNICATION_ID,
    JOB_ID AS JOB_ID,
    SEQUENCE_NO AS SEQUENCE_NBR,
    QUANTITY AS QUANTITY,
    UTIL.FXN_ARRAY_HASH([ DATA_SOURCE_NAME, RECORD_SOURCE, PRODUCT_CODE, CUSTOMER, IMB, COMMUNICATION_ID, JOB_ID, SEQUENCE_NBR, QUANTITY ]) AS HUB_MARKETING_OCF_HKEY
FROM  &{IDAP_LAKE}.MEMBER_COMMUNICATIONS.PNF_CONTACT_HISTORY_DETAIL
;

