CREATE OR REPLACE VIEW STAGEDATA.SAT_PROVIDER_DETAIL_ESI_SELECT_VW
COMMENT = 'This is a SAT View containing ESI provider details'
AS
SELECT DISTINCT
'000001' AS TPA_CLIENT_ID,
'000001' AS TPA_ID,
'0001' AS TPA_DIV_ID,
'ESI' AS DATA_SOURCE_NAME,
CONCAT('ESI', 'Pharmacy', NABP_NBR, IFF(LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_NPI = 'UNKNOWN', '', LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_NPI)) AS PROVIDER_ID,
'Pharmacy' AS PROVIDER_TYPE_NAME,
IFNULL(LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_NAME, 'UNKNOWN') AS FULL_NAME,
NULL	AS FIRST_NAME,
NULL	AS LAST_NAME,
NULL	AS MIDDLE_NAME,
NULL	AS MIDDLE_INITIAL_NAME,
'Unknown' AS GENDER_NAME,
NULL	AS EMAIL_ADDRESS,
NULL	AS SOCIAL_SECURITY_NBR,
NULL	AS DEGREE_TEXT,
NULL	AS SUFFIX_NAME,
NULL	AS LOCUM_TENENS_IND,
NULL	AS INVISIBLE_PROVIDER_IND,
NULL	AS TEMPORARY_PROVIDER_IND,
LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_NPI AS NATIONAL_PROVIDER_ID,
NULL	AS DATE_OF_BIRTH,
NULL	AS PRIMARY_PREFERRED_DELIVERY_METHOD_CODE,
NULL	AS BOARD_CERTIFIED_IND,
NULL	AS STATE_MEDICAID_ID,
NULL	AS PRIMARY_SPECIALTY_NAME,
NULL	AS PRIMARY_TAXONOMY_CODE,
NULL    AS PRESCRIBER_SOURCE_CODE,
NULL    AS UPIN_NBR,
NULL    AS PROVIDER_START_DATE,
NULL    AS PROVIDER_ACTIVE_IND,
NULL    AS FACILITY_INCEPTION_DATE,
UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY,
UTIL.FXN_ARRAY_HASH([
    'Pharmacy',
    IFNULL(LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_NAME, 'UNKNOWN'),
    NULL,
    NULL,
    NULL,
    NULL,
    'Unknown',
    NULL,
    NULL,
    NULL,
    NULL,
    NULL,
    NULL,
    NULL,
    LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_NPI,
    NULL,
    NULL,
    NULL,
    NULL,
    NULL,
    NULL,
    NULL,
    NULL,
    NULL,
    NULL,
    NULL
]) AS HASH_DIFF
FROM STAGEDATA.LKP_CLAIM_PHARMACY_DETAIL
JOIN STAGEDATA.LKP_CLAIM_PHARMACY_CLAIM
    ON (LKP_CLAIM_PHARMACY_DETAIL.NABP_NBR = LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_NUMBER)

UNION

SELECT
'000001' AS TPA_CLIENT_ID,
'000001' AS TPA_ID,
'0001' AS TPA_DIV_ID,
'ESI' AS DATA_SOURCE_NAME,
CONCAT('ESI', 'Prescriber', PRESCRIBER_ID) AS PROVIDER_ID,
'Practitioner' AS PROVIDER_TYPE_NAME,
IFNULL(LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL.PRESCRIBER_NAME, 'UNKNOWN') AS FULL_NAME,
NULL	AS FIRST_NAME,
NULL	AS LAST_NAME,
NULL	AS MIDDLE_NAME,
NULL	AS MIDDLE_INITIAL_NAME,
'Unknown' AS GENDER_NAME,
NULL	AS EMAIL_ADDRESS,
NULL	AS SOCIAL_SECURITY_NBR,
NULL	AS DEGREE_TEXT,
NULL	AS SUFFIX_NAME,
NULL	AS LOCUM_TENENS_IND,
NULL	AS INVISIBLE_PROVIDER_IND,
NULL	AS TEMPORARY_PROVIDER_IND,
LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL.PRESCRIBER_ID AS NATIONAL_PROVIDER_ID,
NULL	AS DATE_OF_BIRTH,
NULL	AS PRIMARY_PREFERRED_DELIVERY_METHOD_CODE,
NULL	AS BOARD_CERTIFIED_IND,
NULL	AS STATE_MEDICAID_ID,
NULL	AS PRIMARY_SPECIALTY_NAME,
LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL.PRIMARY_TAXONOMY_CODE,
LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL.PRESCRIBER_SOURCE_CODE,
NULL    AS UPIN_NBR,
NULL    AS PROVIDER_START_DATE,
NULL    AS PROVIDER_ACTIVE_IND,
NULL    AS FACILITY_INCEPTION_DATE,
UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY,
UTIL.FXN_ARRAY_HASH([
    PROVIDER_TYPE_NAME,
    FULL_NAME,
    FIRST_NAME,
    LAST_NAME, 
    MIDDLE_NAME,
    MIDDLE_INITIAL_NAME,
    GENDER_NAME,
    EMAIL_ADDRESS,
    SOCIAL_SECURITY_NBR,
    DEGREE_TEXT,
    SUFFIX_NAME,
    LOCUM_TENENS_IND,
    INVISIBLE_PROVIDER_IND,
    TEMPORARY_PROVIDER_IND,
    NATIONAL_PROVIDER_ID,
    DATE_OF_BIRTH,
    PRIMARY_PREFERRED_DELIVERY_METHOD_CODE,
    BOARD_CERTIFIED_IND,
    STATE_MEDICAID_ID,
    PRIMARY_SPECIALTY_NAME,
    PRIMARY_TAXONOMY_CODE,
    PRESCRIBER_SOURCE_CODE,
    UPIN_NBR,
    PROVIDER_START_DATE,
	PROVIDER_ACTIVE_IND,
	FACILITY_INCEPTION_DATE
]) AS HASH_DIFF
FROM STAGEDATA.LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL
;