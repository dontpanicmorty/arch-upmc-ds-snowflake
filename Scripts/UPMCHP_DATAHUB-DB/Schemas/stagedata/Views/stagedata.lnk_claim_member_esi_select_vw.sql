COMMENT = 'Source view for ESI data into LNK_CLAIM_MEMBER'
AS
SELECT
'000001' AS C_TPA_CLIENT_ID,
'000001' AS C_TPA_ID,
'0001' AS C_TPA_DIV_ID,
'ESI' AS C_DATA_SOURCE_NAME,
CLAIM_ID AS C_CLAIM_NBR,
'000001' AS M_TPA_CLIENT_ID,
'000001' AS M_TPA_ID,
'0001' AS M_TPA_DIV_ID,
MEMBERNBR AS M_MEMBER_NBR,
'MC400Upm' AS M_DATA_SOURCE_NAME,
UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, M_TPA_CLIENT_ID, M_TPA_DIV_ID, M_TPA_ID, M_DATA_SOURCE_NAME, M_MEMBER_NBR]) AS LNK_CLAIM_MEMBER_HKEY,
