CREATE OR REPLACE VIEW STAGEDATA.SAT_PROVIDER_IDENTIFIER_ESI_SELECT_VW
COMMENT = 'This is a SAT View containing ESI provider indentifiers'
AS
SELECT
    'N/A' AS SOURCE_KEY
    ,'000001' AS TPA_CLIENT_ID
    ,'000001' AS TPA_ID
    ,'0001' AS TPA_DIV_ID
    ,'ESI' AS DATA_SOURCE_NAME
    ,CONCAT('ESI', 'Prescriber', PRESCRIBER_ID) AS PROVIDER_ID
    ,PRESCRIBER_ID AS IDENTIFIER_NBR
    ,'National Provider Identifier' AS IDENTIFIER_NAME
    ,CASE
        WHEN PRESCRIBER_NPI_TYPE = '1' THEN 'Type 1'
        WHEN PRESCRIBER_NPI_TYPE = '2' THEN 'Type 2'
        ELSE 'Unknown'
    END AS IDENTIFIER_SUBTYPE
    ,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY
    ,UTIL.FXN_ARRAY_HASH([IDENTIFIER_NBR, IDENTIFIER_NAME, IDENTIFIER_SUBTYPE]) AS HASH_DIFF
FROM STAGEDATA.LKP_CLAIM_PHARMACY_PRESCRIBER_DETAIL

UNION ALL

SELECT DISTINCT
    'N/A' AS SOURCE_KEY
    ,'000001' AS TPA_CLIENT_ID
    ,'000001' AS TPA_ID
    ,'0001' AS TPA_DIV_ID
    ,'ESI' AS DATA_SOURCE_NAME
    ,CONCAT('ESI', 'Pharmacy', NABP_NBR, IFF(LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_NPI = 'UNKNOWN', '', LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_NPI)) AS PROVIDER_ID
    ,PHARMACY_NPI AS IDENTIFIER_NBR
    ,'National Provider Identifier' AS IDENTIFIER_NAME
    ,CASE
        WHEN PHARMACY_NPI_TYPE = '1' THEN 'Type 1'
        WHEN PHARMACY_NPI_TYPE = '2' THEN 'Type 2'
        ELSE 'Unknown'
    END AS IDENTIFIER_SUBTYPE
    ,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY
    ,UTIL.FXN_ARRAY_HASH([IDENTIFIER_NBR, IDENTIFIER_NAME, IDENTIFIER_SUBTYPE]) AS HASH_DIFF
FROM STAGEDATA.LKP_CLAIM_PHARMACY_DETAIL
JOIN STAGEDATA.LKP_CLAIM_PHARMACY_CLAIM
    ON (LKP_CLAIM_PHARMACY_DETAIL.NABP_NBR = LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_NUMBER)

UNION ALL 

SELECT DISTINCT
    'N/A' AS SOURCE_KEY
    ,'000001' AS TPA_CLIENT_ID
    ,'000001' AS TPA_ID
    ,'0001' AS TPA_DIV_ID
    ,'ESI' AS DATA_SOURCE_NAME
    ,CONCAT('ESI', 'Pharmacy', NABP_NBR, IFF(LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_NPI = 'UNKNOWN', '', LKP_CLAIM_PHARMACY_DETAIL.PHARMACY_NPI)) AS PROVIDER_ID
    ,NABP_NBR AS IDENTIFIER_NBR
    ,'NABP Number' AS IDENTIFIER_NAME
    ,'N/A' AS IDENTIFIER_SUBTYPE
    ,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY
    ,UTIL.FXN_ARRAY_HASH([IDENTIFIER_NBR, IDENTIFIER_NAME, IDENTIFIER_SUBTYPE]) AS HASH_DIFF
FROM STAGEDATA.LKP_CLAIM_PHARMACY_DETAIL
JOIN STAGEDATA.LKP_CLAIM_PHARMACY_CLAIM
    ON (LKP_CLAIM_PHARMACY_DETAIL.NABP_NBR = LKP_CLAIM_PHARMACY_CLAIM.PHARMACY_NUMBER)
;