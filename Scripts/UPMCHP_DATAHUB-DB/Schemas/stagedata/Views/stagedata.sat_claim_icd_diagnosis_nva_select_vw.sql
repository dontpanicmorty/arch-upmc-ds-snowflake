CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_ICD_DIAGNOSIS_NVA_SELECT_VW 
COMMENT= 'Source view for NVA data into SAT_CLAIM_ICD_DIAGNOSIS'
AS 
SELECT DISTINCT
    LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID,
	LKP_CLAIM_MEMBER_NVA.TPA_ID,
	LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID,
	LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME, 
    NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo" AS CLAIM_NBR, 
    STAGEDATA.FXN_BUILD_CLAIM_GROUP_CODE_ARRAY('diagnosisCode', DATA_SOURCE_NAME, OBJECT_CONSTRUCT_KEEP_NULL(
        'DIAGNOSIS1', NVA_PAID_CLAIM_EXTRACTS_VW."Diag1",
        'DIAGNOSIS2', NVA_PAID_CLAIM_EXTRACTS_VW."Diag2",
        'DIAGNOSIS3', NVA_PAID_CLAIM_EXTRACTS_VW."Diag3",
        'ICD_TYPE',NVA_PAID_CLAIM_EXTRACTS_VW.ICD_TYPE), 3) AS ICD_DIAGNOSIS_CODES, 
	UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_NBR]) AS HUB_CLAIM_HKEY, 
    UTIL.FXN_ARRAY_HASH([ICD_DIAGNOSIS_CODES, HUB_CLAIM_HKEY]) AS HASH_DIFF
FROM RAWDATA.NVA_PAID_CLAIM_EXTRACTS_VW
JOIN STAGEDATA.LKP_CLAIM_MEMBER_NVA
        ON (LKP_CLAIM_MEMBER_NVA.CLAIM_NBR = NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo")
QUALIFY ROW_NUMBER() -- get the most current submitted file for a claim line
    OVER(PARTITION BY NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo"
        ORDER BY SPLIT_PART(SPLIT_PART(NVA_PAID_CLAIM_EXTRACTS_VW.FILENAME, '_', 7), '.', 1) DESC) = 1
;