CREATE OR REPLACE VIEW STAGEDATA.SAT_MEDICAL_GROUP_DETAIL_ENVOLVE_SELECT_VW
COMMENT = 'This is a SAT View containing Provider Detail data'
AS
 	WITH CTE AS
  (SELECT DISTINCT
		'000001' AS TPA_CLIENT_ID,
    '000001' AS TPA_ID,
    '0001' AS TPA_DIV_ID,
    'Envolve' AS DATA_SOURCE_NAME,
 		CONCAT('0','ENVOLVE', TRIM(PROVIDER_NBR), RIGHT(MA_PROVIDER_NBR,6)) AS MEDICAL_GROUP_ID, 
 		'Facility' AS PROVIDER_TYPE_NAME, 
 		CONCAT(COALESCE(FIRST_NAME,''), COALESCE(LAST_NAME,'') ) AS MEDICAL_GROUP_NAME,  
 		NULL AS TAX_ID_NBR, --yes, AlternateProviderNo is TIN
    NULL AS EMAIL_ADDRESS,
    NULL AS NPI_NBR,
    NULL AS MEDICAL_GROUP_START_DATE,
    NULL AS MEDICAL_GROUP_ACTIVE_IND,
    UTIL.FXN_ARRAY_HASH(['000001', '000001', '0001', DATA_SOURCE_NAME, MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY,
    UTIL.FXN_ARRAY_HASH(
        [
        MEDICAL_GROUP_NAME
        ,TAX_ID_NBR
        ,EMAIL_ADDRESS
        ,NPI_NBR
        ,MEDICAL_GROUP_START_DATE
        ,MEDICAL_GROUP_ACTIVE_IND
        ]
    ) AS HASH_DIFF
FROM RAWDATA.ENVOLVE_PROVIDER
	 WHERE PROVIDER_NBR IS NOT NULL AND MA_PROVIDER_NBR IS NOT NULL
        AND (TRIM(FIRST_NAME) = ''
      OR TRY_TO_NUMBER(FIRST_NAME) IS NOT NULL) 
QUALIFY ROW_NUMBER() -- get the most current submitted file 
    OVER(PARTITION BY ENVOLVE_PROVIDER.PROVIDER_NBR,RIGHT(ENVOLVE_PROVIDER.MA_PROVIDER_NBR,6)
    ORDER BY SPLIT_PART(SPLIT_PART(ENVOLVE_PROVIDER.FILENAME, '_', 7), '.', 1) DESC) = 1 
UNION ALL 

SELECT DISTINCT
		'000001' AS TPA_CLIENT_ID,
    '000001' AS TPA_ID,
    '0001' AS TPA_DIV_ID,
    'Envolve' AS DATA_SOURCE_NAME,
 		CONCAT('0','ENVOLVE', TRIM(PROVIDER_NBR)) AS MEDICAL_GROUP_ID, 
 		'Facility' AS PROVIDER_TYPE_NAME, 
 		CONCAT(COALESCE(FIRST_NAME,''), COALESCE(LAST_NAME,'') ) AS MEDICAL_GROUP_NAME,  
 		NULL AS TAX_ID_NBR, --yes, AlternateProviderNo is TIN
    NULL AS EMAIL_ADDRESS,
    NULL AS NPI_NBR,
    NULL AS MEDICAL_GROUP_START_DATE,
    NULL AS MEDICAL_GROUP_ACTIVE_IND,
    UTIL.FXN_ARRAY_HASH(['000001', '000001', '0001', DATA_SOURCE_NAME, MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY,
    UTIL.FXN_ARRAY_HASH(
        [
        MEDICAL_GROUP_NAME
        ,TAX_ID_NBR
        ,EMAIL_ADDRESS
        ,NPI_NBR
        ,MEDICAL_GROUP_START_DATE
        ,MEDICAL_GROUP_ACTIVE_IND
        ]
    ) AS HASH_DIFF
FROM RAWDATA.ENVOLVE_PROVIDER
	 WHERE PROVIDER_NBR IS NOT NULL AND MA_PROVIDER_NBR IS NULL
        AND (TRIM(FIRST_NAME) = ''
      OR TRY_TO_NUMBER(FIRST_NAME) IS NOT NULL) 
QUALIFY ROW_NUMBER() -- get the most current submitted file 
    OVER(PARTITION BY ENVOLVE_PROVIDER.PROVIDER_NBR,RIGHT(ENVOLVE_PROVIDER.MA_PROVIDER_NBR,6)
    ORDER BY SPLIT_PART(SPLIT_PART(ENVOLVE_PROVIDER.FILENAME, '_', 7), '.', 1) DESC) = 1 
)
SELECT DISTINCT * FROM CTE
;