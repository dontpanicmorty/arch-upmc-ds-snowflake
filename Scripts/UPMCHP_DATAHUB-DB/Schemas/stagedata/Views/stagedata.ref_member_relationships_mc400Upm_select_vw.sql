CREATE OR REPLACE VIEW STAGEDATA.REF_MEMBER_RELATIONSHIPS_MC400Upm_SELECT_VW
COMMENT='Source view for refdata.member_relationships'
AS
SELECT
'000001' AS TPA_CLIENT_ID
,'000001' AS TPA_ID
,'0001' AS TPA_DIV_ID
,'MC400Upm' AS DATA_SOURCE_NAME
,UPPER(RelationshipCode) AS CODE
,RelationshipDescription AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,RelationshipType AS TYPE_CODE -- needs to be excel sheet in the 'coe' site
,NULL AS TYPE_DESC -- will probably be case statement WHEN 'D' THEN 'Dependent' WHEN 'S' THEN 'Subscriber'
,HippaRelationshipCode AS HIPPA_CODE
,UTIL.FXN_ARRAY_HASH([CODE]) as MEMBER_RELATIONSHIPS_HKEY
FROM RAWDATA.MC400_DWOAO_RELATIONSHIPDESCRIPTIONS
WHERE CODE IN (SELECT DISTINCT UPPER(RelationshipCode) FROM RAWDATA.MC400_DWOAO_MEMBERS WHERE RelationshipCode <> '')

UNION -- Unioning because we have a shared code set with
      -- differentiating TPA_DIV_IDs [Dental and Vision '0002'] and [Medical '0001']

SELECT
'000001' AS TPA_CLIENT_ID
,'000001' AS TPA_ID
,'0002' AS TPA_DIV_ID
,'MC400Upm' AS DATA_SOURCE_NAME
,UPPER(RelationshipCode) AS CODE
,RelationshipDescription AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,RelationshipType AS TYPE_CODE
,NULL AS TYPE_DESC
,HippaRelationshipCode AS HIPPA_CODE
,UTIL.FXN_ARRAY_HASH([CODE]) as MEMBER_RELATIONSHIPS_HKEY
FROM RAWDATA.MC400_DWOAO_RELATIONSHIPDESCRIPTIONS
WHERE CODE IN (SELECT DISTINCT UPPER(RelationshipCode) FROM RAWDATA.MC400_DWOAO_MEMBERS WHERE RelationshipCode <> '')
;
