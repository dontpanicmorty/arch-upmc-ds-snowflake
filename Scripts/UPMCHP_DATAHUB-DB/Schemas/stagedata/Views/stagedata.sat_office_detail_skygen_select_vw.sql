CREATE OR REPLACE VIEW STAGEDATA.SAT_OFFICE_DETAIL_SKYGEN_SELECT_VW
COMMENT = 'This is a SAT View containing office detail data'
AS
SELECT 
    DWSKYGEN_PROVIDER_OFFICE.OFFICE_ID,
    DWSKYGEN_PROVIDER_OFFICE.TPA_CLIENT_ID,
    DWSKYGEN_PROVIDER_OFFICE.TPA_ID,
    DWSKYGEN_PROVIDER_OFFICE.TPA_DIV_ID,
    'Skygen' AS DATA_SOURCE_NAME,
    DWSKYGEN_PROVIDER_OFFICE.OFFICE_NAME,
    DWSKYGEN_PROVIDER_OFFICE.OFFICE_PHONE_NBR AS PRIMARY_PHONE_NBR,
    NULL AS PRIMARY_PHONE_EXTENSION_NBR,
	NULL AS ALTERNATE_PHONE_NBR,
	NULL AS ALTERNATE_PHONE_EXTENSION_NBR,
	NULL AS PRIMARY_FAX_NBR,
    NULL AS ALTERNATE_FAX_NBR,
	NULL AS EMAIL_ADDRESS,
	NULL AS OFFICE_MANAGER_NAME,
	NULL AS HANDICAP_ACCESS_IND,
	NULL AS TELEHEALTH_IND,
	NULL AS RECEIVES_MAIL_IND,
	NULL AS EPRESCRIBE_IND,
	NULL AS MA_SUPER_PCP_IND,
	NULL AS EMR_SYSTEM_NAME,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, 
                        TPA_ID, 
                        TPA_DIV_ID, 
                        DATA_SOURCE_NAME, 
                        OFFICE_ID]
                        ) AS HUB_OFFICE_HKEY,
    UTIL.FXN_ARRAY_HASH([OFFICE_NAME,
                        PRIMARY_PHONE_NBR,
                        PRIMARY_PHONE_EXTENSION_NBR,
                        ALTERNATE_PHONE_NBR,
                        ALTERNATE_PHONE_EXTENSION_NBR,
                        PRIMARY_FAX_NBR,
                        ALTERNATE_FAX_NBR,
                        EMAIL_ADDRESS,
                        OFFICE_MANAGER_NAME,
                        HANDICAP_ACCESS_IND,
                        TELEHEALTH_IND,
                        RECEIVES_MAIL_IND,
                        EPRESCRIBE_IND,
                        MA_SUPER_PCP_IND,
                        EMR_SYSTEM_NAME]
                        ) AS HASH_DIFF
FROM RAWDATA.DWSKYGEN_PROVIDER_OFFICE
;