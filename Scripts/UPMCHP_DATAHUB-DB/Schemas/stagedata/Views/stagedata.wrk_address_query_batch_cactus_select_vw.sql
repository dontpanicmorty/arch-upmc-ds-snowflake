CREATE OR REPLACE VIEW STAGEDATA.WRK_ADDRESS_QUERY_BATCH_CACTUS_SELECT_VW
COMMENT = 'This HUB table contains batched provider address records from the Smarty.com API response'
AS

WITH BATCHED_RECORDS AS (
    SELECT
        HUB_ADDRESS_QUERY.HUB_ADDRESS_QUERY_HKEY
        , CEIL(ROW_NUMBER() OVER (ORDER BY HUB_ADDRESS_QUERY.HUB_ADDRESS_QUERY_HKEY) / 100) AS BATCH_NUMBER
        , HUB_ADDRESS_QUERY.CONCATENATED_ADDRESS AS SINGLE_LINE_ADDRESS_BLOCK
        , OBJECT_CONSTRUCT(
            'street', HUB_ADDRESS_QUERY.CONCATENATED_ADDRESS
            , 'input_id', HUB_ADDRESS_QUERY.HUB_ADDRESS_QUERY_HKEY
            , 'match', 'enhanced'
            , 'candidates', 1
        ) AS SMARTY_JSON_REQUEST_SEGMENT
    FROM
        HUBDATA.HUB_ADDRESS_QUERY AS HUB_ADDRESS_QUERY 
    LEFT OUTER JOIN
        HUBDATA.LNK_ADDRESS_QUERY_STANDARD_ADDRESS AS LNK_ADDRESS_QUERY_STANDARD_ADDRESS
        ON HUB_ADDRESS_QUERY.HUB_ADDRESS_QUERY_HKEY = LNK_ADDRESS_QUERY_STANDARD_ADDRESS.HUB_ADDRESS_QUERY_HKEY
    WHERE (
        LNK_ADDRESS_QUERY_STANDARD_ADDRESS.HUB_ADDRESS_QUERY_HKEY IS NULL
        OR LNK_ADDRESS_QUERY_STANDARD_ADDRESS.ROW_EXPIRATION_DATETIME >= CURRENT_TIMESTAMP()
    )
)
SELECT
     HUB_ADDRESS_QUERY_HKEY
    , BATCH_NUMBER
    , ROW_NUMBER() OVER (PARTITION BY BATCH_NUMBER ORDER BY HUB_ADDRESS_QUERY_HKEY) AS SEQUENCE_NUMBER
    , SINGLE_LINE_ADDRESS_BLOCK
    , SMARTY_JSON_REQUEST_SEGMENT
FROM BATCHED_RECORDS
;