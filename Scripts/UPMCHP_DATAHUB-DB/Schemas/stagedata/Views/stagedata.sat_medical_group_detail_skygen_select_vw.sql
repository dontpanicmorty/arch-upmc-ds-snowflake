CREATE OR REPLACE VIEW STAGEDATA.SAT_MEDICAL_GROUP_DETAIL_SKYGEN_SELECT_VW
COMMENT = 'This is a SAT View containing Skygen provider details'
AS
SELECT --MIGHT NEED TPA FIX DEPENDING ON HOW SOURCE VIEW GETS UPDATED TO HANDLE TPAS
TPA_CLIENT_ID
,TPA_ID
,TPA_DIV_ID
,'Skygen' AS DATA_SOURCE_NAME
,PROVIDER_ID
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_MEDICAL_GROUP_HKEY
,PROVIDER_FULL_NAME AS MEDICAL_GROUP_NAME
,TAX_ID AS TAX_ID_NBR
,PROVIDER_EMAIL AS EMAIL_ADDRESS
,IFF(TRIM(PROVIDER_NPI) = 'Unknown', NULL, PROVIDER_NPI) AS NPI_NBR
,NULL AS MEDICAL_GROUP_START_DATE
,NULL AS MEDICAL_GROUP_ACTIVE_IND
,UTIL.FXN_ARRAY_HASH([
    MEDICAL_GROUP_NAME,
    TAX_ID_NBR,
    EMAIL_ADDRESS,
    NPI_NBR,
    MEDICAL_GROUP_START_DATE,
    MEDICAL_GROUP_ACTIVE_IND
   ]) AS HASH_DIFF
FROM RAWDATA.DWSKYGEN_PROVIDER_DETAIL
WHERE PROVIDER_TYPE = 'Medical Group';