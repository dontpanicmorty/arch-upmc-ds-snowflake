        FILE_RECEIVE_DATE,
        DUE_DATE,
        IFNULL(JOB_DESCRIPTION,'Unknown') AS JOB_DESCRIPTION,
        IFNULL(COMPANY,'Unknown') AS COMPANY,
        IFNULL(TYPE_OF_ENVELOPE,'Unknown') AS TYPE_OF_ENVELOPE,
        IFNULL(SLA_DAYS,'Unknown') AS SLA_DAYS,
        IFNULL(LOB,'Unknown') AS LOB,
        IFNULL(ITEM_ID,'Unknown') AS ITEM_ID,
        QUANTITY,
        CPP_PRODUCTION,
        CPP_POSTAGE,
        MEMBER_NO AS MEMBER_NBR,
        VENDOR_NO AS VENDOR_NBR,
        PROVIDER_NO AS PROVIDER_NBR,
        FULL_NAME,
        ADDRESS_1,
        ADDRESS_2,
        ADDRESS_3,
        CITY,
        STATE,
        ZIP,
        CITY_STATE_ZIP,
        NUMBER_OF_PAGES,
        PREFIX,
        FIRST_NAME,
        MIDDLE_NAME,
        LAST_NAME,
        SUFFIX,
        MISC_0,
        MISC_1,
        MISC_2,
        MISC_3,
        MISC_4,
        MISC_5,
        MISC_6,
        MISC_7,
        MISC_8,
        MISC_9,
        MISC_10,
        RESERVICES,
        LOAD_DATE,
        UPDATE_DATE ,
        SEARCH_FIELD,
        UPMCHP_DATAHUB.UTIL.FXN_ARRAY_HASH(['MC400Upm',RECORD_SOURCE,PRODUCT_CODE,CUSTOMER,IMB,CID,JOB_ID, SEQUENCE_NO, QUANTITY]) AS HUB_MARKETING_OCF_HKEY,
        UPMCHP_DATAHUB.UTIL.FXN_ARRAY_HASH([ RDATE, JOB_DATE, COMPLETION_DATE, JOB_NBR, INBOUND_FILE_NAME, SLA_FLAG, FILE_ERROR_FLAG, PNF_FILE_NAME, FILE_RECEIVE_DATE, DUE_DATE, JOB_DESCRIPTION, COMPANY, TYPE_OF_ENVELOPE, SLA_DAYS, LOB, ITEM_ID, QUANTITY, CPP_PRODUCTION, CPP_POSTAGE, MEMBER_NBR, VENDOR_NBR, PROVIDER_NBR, FULL_NAME, concat(''',ADDRESS_1,'''),concat(''',ADDRESS_2,'''),concat(''',ADDRESS_3,'''),  concat(''',CITY,'''), "STATE", "ZIP", concat(''',CITY_STATE_ZIP,'''), NUMBER_OF_PAGES, PREFIX, FIRST_NAME, MIDDLE_NAME, LAST_NAME, SUFFIX, MISC_0, MISC_1, MISC_2, MISC_3, MISC_4, MISC_5, MISC_6, MISC_7, MISC_8, MISC_9, MISC_10, RESERVICES, LOAD_DATE, UPDATE_DATE, SEARCH_FIELD ]) AS HASH_DIFF
