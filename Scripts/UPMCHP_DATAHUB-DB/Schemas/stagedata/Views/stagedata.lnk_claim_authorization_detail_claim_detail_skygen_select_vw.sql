CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_AUTHORIZATION_DETAIL_CLAIM_DETAIL_SKYGEN_SELECT_VW
COMMENT = 'Source view for SKGYEN data into LNK_CLAIM_AUTHORIZATION_DETAIL_CLAIM_DETAIL'
AS
SELECT DISTINCT
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_CLIENT_ID AS AD_TPA_CLIENT_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_ID AS AD_TPA_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.TPA_DIV_ID AS AD_TPA_DIV_ID,
LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.DATA_SOURCE_NAME AS AD_DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR AS AD_AUTHORIZATION_NBR,
DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_LINE_NBR AS AD_AUTHORIZATION_LINE_NBR,
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS CD_TPA_CLIENT_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS CD_TPA_ID,
LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS CD_TPA_DIV_ID,
'Skygen' AS CD_DATA_SOURCE_NAME,
DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR AS CD_CLAIM_NBR,
DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_NBR AS CD_CLAIM_LINE_NBR,
DWSKYGEN_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR CD_CLAIM_LINE_SEQ_NBR,
DWSKYGEN_CLAIM_DETAIL.PROCEDURE_ADJ_CODE AS CD_CLAIM_LINE_PROCEDURE_ADJ_CODE,
UTIL.FXN_ARRAY_HASH([AD_TPA_CLIENT_ID, AD_TPA_ID, AD_TPA_DIV_ID, AD_DATA_SOURCE_NAME, AD_AUTHORIZATION_NBR, AD_AUTHORIZATION_LINE_NBR, CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS LNK_CLAIM_AUTHORIZATION_DETAIL_CLAIM_DETAIL_HKEY,
UTIL.FXN_ARRAY_HASH([AD_TPA_CLIENT_ID, AD_TPA_ID, AD_TPA_DIV_ID, AD_DATA_SOURCE_NAME, AD_AUTHORIZATION_NBR, AD_AUTHORIZATION_LINE_NBR]) AS HUB_CLAIM_AUTHORIZATION_DETAIL_HKEY,
UTIL.FXN_ARRAY_HASH([CD_TPA_CLIENT_ID, CD_TPA_ID, CD_TPA_DIV_ID, CD_DATA_SOURCE_NAME, CD_CLAIM_NBR, CD_CLAIM_LINE_NBR, CD_CLAIM_LINE_SEQ_NBR, CD_CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY
FROM RAWDATA.DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL
    JOIN RAWDATA.DWSKYGEN_CLAIM_DETAIL
        ON (DWSKYGEN_CLAIM_DETAIL.AUTH_NBR = DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR
        AND DWSKYGEN_CLAIM_DETAIL.AUTH_ITEM_NBR = DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_LINE_NBR)
    JOIN STAGEDATA.LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN
        ON  DWSKYGEN_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR = LKP_CLAIM_AUTHORIZATION_MEMBER_SKYGEN.AUTHORIZATION_NBR
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR = LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR
;