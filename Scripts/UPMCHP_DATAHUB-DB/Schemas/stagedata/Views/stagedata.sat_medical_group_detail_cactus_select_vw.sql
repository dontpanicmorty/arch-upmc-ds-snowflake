CREATE OR REPLACE VIEW STAGEDATA.SAT_MEDICAL_GROUP_DETAIL_CACTUS_SELECT_VW
COMMENT = 'This is a Cactus SAT view containg MEDICAL_GROUP_DETAILS data.'
AS
WITH GROUPADDRESS_TAXIDNBR AS (
    SELECT
        GROUP_K,
        MAX(TRIM(TAXIDNUMBER)) AS TAXIDNUMBER 
    FROM RAWDATA.CACTUS_GROUPADDRESS 
    GROUP BY GROUP_K
)
, DUPLICATE_GROUPS AS (
    SELECT ID
    FROM RAWDATA.CACTUS_GROUPS
    GROUP BY ID
    HAVING COUNT(*) > 1
)
, GROUP_START_DATE AS (
    SELECT 
   CAST(MIN(RAWDATA.CACTUS_GROUPID.STARTDATE)AS DATE) AS STARTDATE, 
    RAWDATA.CACTUS_GROUPID.GROUP_K AS GROUP_K 
    FROM RAWDATA.CACTUS_GROUPID 
    GROUP BY GROUP_K
)
SELECT DISTINCT
     '000001' AS TPA_CLIENT_ID
    , '000001' AS TPA_ID
    , '0001' AS TPA_DIV_ID
    , 'Cactus' AS DATA_SOURCE_NAME
    , TRIM(GRP.ID) AS MEDICAL_GROUP_ID
    , TRIM(GRP.GROUPNAME) AS MEDICAL_GROUP_NAME
    , GRP_TAX.TAXIDNUMBER AS TAX_ID_NBR
    , NULL AS EMAIL_ADDRESS
    , NULL AS NPI_NBR
    , GROUP_START_DATE.STARTDATE AS MEDICAL_GROUP_START_DATE 
    , GRP.ACTIVE AS MEDICAL_GROUP_ACTIVE_IND
    , UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEDICAL_GROUP_ID]) AS HUB_MEDICAL_GROUP_HKEY
    , UTIL.FXN_ARRAY_HASH([MEDICAL_GROUP_NAME, TAX_ID_NBR, EMAIL_ADDRESS, NPI_NBR, MEDICAL_GROUP_START_DATE, MEDICAL_GROUP_ACTIVE_IND]) AS HASH_DIFF
FROM
    RAWDATA.CACTUS_GROUPS AS GRP
LEFT JOIN
    GROUPADDRESS_TAXIDNBR AS GRP_TAX
    ON GRP.GROUP_K = GRP_TAX.GROUP_K
INNER JOIN
    RAWDATA.CACTUS_GROUPADDRESS AS GRP_ADR
    ON GRP.GROUP_K = GRP_ADR.GROUP_K
LEFT JOIN
    DUPLICATE_GROUPS AS DUP
    ON GRP.ID = DUP.ID
LEFT JOIN
    GROUP_START_DATE
    ON GRP.GROUP_K = GROUP_START_DATE.GROUP_K
WHERE
    NULLIF(TRIM(GRP.ID), '') IS NOT NULL
    AND DUP.ID IS NULL
;