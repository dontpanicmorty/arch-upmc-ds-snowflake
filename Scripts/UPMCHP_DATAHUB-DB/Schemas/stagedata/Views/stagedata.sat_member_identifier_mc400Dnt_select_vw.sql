CREATE OR REPLACE VIEW STAGEDATA.SAT_MEMBER_IDENTIFIER_MC400DNT_SELECT_VW
COMMENT = 'Source select view for MC400Dnt member data to load HUBDATA.SAT_MEMBER_IDENTIFIER'
AS
SELECT
 '000001' AS TPA_CLIENT_ID
,'000001' AS TPA_ID
,'0001' AS TPA_DIV_ID
,'MC400Dnt' AS DATA_SOURCE_NAME
,TRIM(Members.MEMBERNBR) AS MEMBER_NBR -- this column is not availble in the DDL & it is being used to calculate Hash
,MastermemberId.MASTERMEMBER AS MASTER_MEMBER_ID
,IFF(TRY_TO_NUMBER(Members.MemberSocialSecurity) = 0, NULL, NULLIF(TRIM(Members.MemberSocialSecurity), '')) AS SOCIAL_SECURITY_NBR
,NULLIF(TRIM(Members.MEDICAIDID), '') AS MEDICAID_ID
,NULLIF(TRIM(Members.HCFANBR), '') AS HFCA_NBR
,NULLIF(TRIM(Members.EMPLOYEENBR), '') AS EMPLOYEE_NBR
,NULLIF(TRIM(EMPI_DAILY_GLOBAL_CURRENT_VW.EMPI_ID), '') AS EMPI_NBR
,NULLIF(TRIM(EMPI_DAILY_GLOBAL_CURRENT_VW.EPIC_MRN), '') AS EPIC_MR_NBR
,NULLIF(TRIM(EMPI_DAILY_GLOBAL_CURRENT_VW.EPIC_ENTERPRISE_ID), '') AS EPIC_ENT_ID
,NULLIF(TRIM(EMPI_DAILY_GLOBAL_CURRENT_VW.MEDIPAC_MRN), '') AS MEDIPAC_MR_NBR
,NULL AS MA_RECIPIENT_ID -- This is a new column of data, we dont have source info for it.
,NULLIF(TRIM(Members.OTHERCOVERAGE1), '') AS SECONDARY_MEMBER_IDENTIFIER_TEXT
,NULLIF(TRIM(Members.OTHERCOVERAGE2), '') AS TERTIARY_MEMBER_IDENTIFIER_TEXT
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, MEMBER_NBR]) AS HUB_MEMBER_HKEY

FROM RAWDATA.MC400_DWDNV_MEMBERS Members
    LEFT JOIN RAWDATA.EMPI_DAILY_GLOBAL_CURRENT_VW
        ON (EMPI_DAILY_GLOBAL_CURRENT_VW.HEALTHPLAN_ID = Members.MemberNbr)
    LEFT JOIN RAWDATA.MC400_DWOAO_MASTERMEMBERID MastermemberId
        ON (MastermemberId.SourceId = Members.MemberNbr)
WHERE Members.MemberNbr <> '99999999901' --this is a junk catch all member number
;