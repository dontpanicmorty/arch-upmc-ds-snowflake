!set variable_substitution=true;

CREATE OR REPLACE VIEW STAGEDATA.LNK_CUTLOG_MEMBER_SELECT_VW COMMENT = 'Source view for LNK_CUTLOG_MEMBER'
AS
SELECT DISTINCT
    'MC400Upm' AS MC_DATA_SOURCE_NAME,
    CUTCORRESPONDENCELOGFILE.CUTIDENTIFIER AS MC_CUT_IDENTIFIER,
    CUTACTIVITYFILE.ACTIVITYCODE AS MC_ACTIVITY_CODE,
    CUTACTIVITYFILE.ACTIVITYDATE AS MC_ACTIVITY_DATE,
    CUTACTIVITYFILE.ACTIVITYTIME AS MC_ACTIVITY_TIME,
    Members.TPACLIENT AS M_TPA_CLIENT_ID,
    Members.TPADIVISION AS M_TPA_DIV_ID,
    Members.TPAIDOFCLIENT AS M_TPA_ID,
    'MC400Upm' AS M_DATA_SOURCE_NAME,
    Members.MemberNbr AS M_MEMBER_NBR,
    CUTCORRESPONDENCELOGFILE.TPACLIENT AS MC_TPA_CLIENT_ID,
    CUTCORRESPONDENCELOGFILE.TPAIDOFCLIENT AS MC_TPA_ID,
    CUTCORRESPONDENCELOGFILE.TPADIVISION AS MC_TPA_DIV_ID,

    UTIL.FXN_ARRAY_HASH([MC_DATA_SOURCE_NAME,MC_CUT_IDENTIFIER, MC_ACTIVITY_CODE, MC_ACTIVITY_DATE, MC_ACTIVITY_TIME]) HUB_MARKETING_CUTLOG_HKEY,    UTIL.FXN_ARRAY_HASH([MC_DATA_SOURCE_NAME,MC_CUT_IDENTIFIER, MC_ACTIVITY_CODE, MC_ACTIVITY_DATE, MC_ACTIVITY_TIME, M_TPA_CLIENT_ID, M_TPA_ID, M_TPA_DIV_ID, M_DATA_SOURCE_NAME, M_MEMBER_NBR]) AS LNK_CUTLOG_MEMBER_HKEY,
    UTIL.FXN_ARRAY_HASH([M_TPA_CLIENT_ID, M_TPA_ID, M_TPA_DIV_ID, M_DATA_SOURCE_NAME,M_MEMBER_NBR]) AS HUB_MEMBER_HKEY
FROM &{MC400}.DWOAO.CUTCORRESPONDENCELOGFILE CUTCORRESPONDENCELOGFILE
    INNER JOIN &{MC400}.DWOAO.CUTACTIVITYFILE CUTACTIVITYFILE
        ON CUTCORRESPONDENCELOGFILE.CUTIDENTIFIER = CUTACTIVITYFILE.CUTIDENTIFIER
        AND CUTCORRESPONDENCELOGFILE.TPACLIENT = CUTACTIVITYFILE.TPACLIENT
        AND CUTCORRESPONDENCELOGFILE.TPAIDOFCLIENT = CUTACTIVITYFILE.TPAIDOFCLIENT
    INNER JOIN &{MC400}.DWOAO.TIMEBYDAY TBD
        ON CUTACTIVITYFILE.ACTIVITYDATE = TBD.TIMEID
    INNER JOIN &{MC400}.DWOAO.MEMBERS Members
        ON (CUTCORRESPONDENCELOGFILE.TPACLIENT = Members.TPACLIENT
        AND CUTCORRESPONDENCELOGFILE.TPAIDOFCLIENT = Members.TPAIDOFCLIENT        
        AND CUTCORRESPONDENCELOGFILE.TPADIVISION = Members.TPADIVISION
        AND CUTCORRESPONDENCELOGFILE.REFERENCEID = Members.MemberNbr)
    WHERE TBD.YEAR >= YEAR(GETDATE()) - 1 
    AND CUTCORRESPONDENCELOGFILE.TPAIDOFCLIENT = '000001'
    AND CUTCORRESPONDENCELOGFILE.TPACLIENT = '000001'
    AND CUTCORRESPONDENCELOGFILE.TPADIVISION = '0001'
    ;

    !set variable_substitution=false;