CREATE OR REPLACE VIEW STAGEDATA.REF_CLAIM_NOT_COVERED_REASON_ENVOLVE_SELECT_VW
AS
SELECT DISTINCT
LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID
,LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID
,LKP_CLAIM_MEMBER_ENVOLVE.DATA_SOURCE_NAME
,IFNULL(SUBSTRING(ENVOLVE_CLAIM_EXTRACTS.LOB_IND,1,2),'') AS LINE_OF_BUSINESS_CODE
,'Reason' AS NOT_COVERED_REASON_TYPE
,ENVOLVE_CLAIM_EXTRACTS.EXCEPTION_CODE AS CODE
,IFNULL(COALESCE(TRIM(REGEXP_SUBSTR(EXCEPTION_CODE_DESCRIPTION,'denied[: ,]*(.*)', 1, 1, 'i', 1)), EXCEPTION_CODE_DESCRIPTION),'') AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,NULL AS HIPAA_277_CODE
,NULL AS HIPAA_835_CODE 
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, LINE_OF_BUSINESS_CODE, NOT_COVERED_REASON_TYPE, CODE]) AS CLAIM_NOT_COVERED_REASON_HKEY
,TO_BOOLEAN(NULL) AS MEMBER_PAY_FLAG

FROM RAWDATA.ENVOLVE_CLAIM_EXTRACTS
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_ENVOLVE
            ON (LKP_CLAIM_MEMBER_ENVOLVE.CLAIM_NBR = ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO)
WHERE UPPER(SUBSTRING(ENVOLVE_CLAIM_EXTRACTS.EXCEPTION_CODE, 1, 1)) = 'D'
QUALIFY ROW_NUMBER() -- get the most current submitted file for a claim line
    OVER(PARTITION BY ENVOLVE_CLAIM_EXTRACTS.EXCEPTION_CODE
    ORDER BY SPLIT_PART(SPLIT_PART(ENVOLVE_CLAIM_EXTRACTS.FILENAME, '_', 7), '.', 1) DESC) = 1 
;