CREATE OR REPLACE VIEW STAGEDATA.SAT_PROVIDER_DETAIL_CACTUS_SELECT_VW
COMMENT = 'This is a SAT View containing Provider Detail data'
AS
SELECT DISTINCT
		'000001' AS TPA_CLIENT_ID,
    	'000001' AS TPA_ID,
    	'0001' AS TPA_DIV_ID,
    	'Cactus' AS DATA_SOURCE_NAME,
 		TRIM(CACTUS_PROVIDERS.ID) AS PROVIDER_ID,
    	CASE 
            WHEN CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 THEN 'Practitioner'
            WHEN  CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 2 THEN 'Facility'
            ELSE 'Unknown' 
        END AS PROVIDER_TYPE_NAME,
        CASE 
            WHEN CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 THEN CONCAT(RTRIM(CACTUS_PROVIDERS.LASTNAME),', ',RTRIM(FIRSTNAME))
            WHEN  CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 2 THEN TRIM(CACTUS_PROVIDERS.LONGNAME) 
        END AS FULL_NAME, 
 		CASE
            WHEN CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 THEN RTRIM(FIRSTNAME)
            ELSE NULL 
        END AS FIRST_NAME,
 		CASE 
            WHEN CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 THEN RTRIM(LASTNAME)
            ELSE NULL 
        END AS LAST_NAME, 
 		CASE 
            WHEN CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 AND LEN(RTRIM(MIDDLENAME)) > 1 THEN MIDDLENAME 
            ELSE NULL 
        END AS MIDDLE_NAME, 
 		CASE 
            WHEN CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 AND SUBSTRING(CACTUS_PROVIDERS.MIDDLENAME,1,1) = '' THEN NULL 
            WHEN SUBSTRING(CACTUS_PROVIDERS.MIDDLENAME,1,1) <> '' THEN SUBSTRING(CACTUS_PROVIDERS.MIDDLENAME,1,1) ELSE NULL 
        END AS MIDDLE_INITIAL_NAME, 
 		CASE 
            WHEN CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 AND CACTUS_PROVIDERS.SEX = 'M' THEN 'Male'	
            WHEN CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 AND CACTUS_PROVIDERS.SEX = 'F' THEN 'Female' 
            WHEN CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 AND (CACTUS_PROVIDERS.SEX <> 'F' AND CACTUS_PROVIDERS.SEX <> 'M') THEN 'Unknown' 
            ELSE 'n/a'
        END AS GENDER_NAME, 
 		CASE 
            WHEN RTRIM(CACTUS_PROVIDERS.CONTACTEMAILADDRESS) = '' THEN NULL 
            ELSE RTRIM(CACTUS_PROVIDERS.CONTACTEMAILADDRESS) 
        END AS EMAIL_ADDRESS, 
 		CASE 
	        WHEN CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 AND RTRIM(CACTUS_PROVIDERS.SSN) <> '' THEN RTRIM(CACTUS_PROVIDERS.SSN) 
	        ELSE NULL 
        END AS SOCIAL_SECURITY_NBR, 
 		CASE 
            WHEN CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 
                AND RTRIM(CACTUS_PROVIDERS.DISPLAYDEGREES_SHORT) <> '' THEN RTRIM(CACTUS_PROVIDERS.DISPLAYDEGREES_SHORT) 
            ELSE NULL 
        END AS DEGREE_TEXT, 
 		CASE 
            WHEN CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 AND RTRIM(CACTUS_PROVIDERS.SUFFIX) <> '' THEN RTRIM(CACTUS_PROVIDERS.SUFFIX) 
            ELSE NULL 
        END AS SUFFIX_NAME,
        CASE 
            WHEN CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1  AND CACTUS_PROVIDERS.STATUS_RTK = 'D3HS0JCQUW' THEN 'Y' 
            ELSE 'N' 
        END AS LOCUM_TENENS_IND,
        CASE 
            WHEN CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 AND CACTUS_PROVIDERS.STATUS_RTK = 'D0XO0RMNA0' THEN 'Y' 
            ELSE 'N' 
        END AS INVISIBLE_PROVIDER_IND,
        CASE 
            WHEN CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 AND CACTUS_PROVIDERS.STATUS_RTK = 'D0XO0RMCBP' THEN 'Y' 
            ELSE 'N' 
        END AS TEMPORARY_PROVIDER_IND,
        IFF(CACTUS_PROVIDERS.NPI <> '', TRIM(CACTUS_PROVIDERS.NPI), NULL) AS NATIONAL_PROVIDER_ID ,
		CASE 
            WHEN CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 AND CACTUS_PROVIDERS.DATEOFBIRTH IS NOT NULL THEN CAST(CACTUS_PROVIDERS.DATEOFBIRTH AS DATE)
            ELSE NULL
        END AS DATE_OF_BIRTH,
        IFF(CACTUS_PROVIDERS.UPIN <> '', TRIM(CACTUS_PROVIDERS.UPIN), NULL) AS UPIN_NBR,
        NULL AS PRIMARY_PREFERRED_DELIVERY_METHOD_CODE,
        NULL AS BOARD_CERTIFIED_IND,
        NULL AS STATE_MEDICAID_ID,
        NULL AS PRIMARY_SPECIALTY_NAME, 
        NULL AS PRIMARY_TAXONOMY_CODE,
        NULL AS PRESCRIBER_SOURCE_CODE,
        CAST(CACTUS_ENTITYASSIGNMENTS.ORIGINALAPPOINTMENTDATE AS DATE) AS PROVIDER_START_DATE,
        IFF(CACTUS_PROVIDERS.ACTIVE IS NULL, 'N', IFF(RTRIM(CACTUS_PROVIDERS.ACTIVE) = '', 'N', 
	        IFF(CACTUS_PROVIDERS.ACTIVE = '1', 'Y', 'N'))) AS PROVIDER_ACTIVE_IND,
        IFF(CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 2 AND CACTUS_PROVIDERS.DATEOFBIRTH IS NOT NULL, 
	        CAST(CACTUS_PROVIDERS.DATEOFBIRTH AS DATE), NULL) AS FACILITY_INCEPTION_DATE, 
 		UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY, 
		UTIL.FXN_ARRAY_HASH([
	        PROVIDER_TYPE_NAME,
	        FULL_NAME,
	        FIRST_NAME,
	        LAST_NAME,
	        MIDDLE_NAME,
	        MIDDLE_INITIAL_NAME,
	        GENDER_NAME,
	        EMAIL_ADDRESS,
	        SOCIAL_SECURITY_NBR,
	        DEGREE_TEXT,
	        SUFFIX_NAME,
	        LOCUM_TENENS_IND,
	        INVISIBLE_PROVIDER_IND,
	        TEMPORARY_PROVIDER_IND,
	        NATIONAL_PROVIDER_ID,
	        DATE_OF_BIRTH,
	        UPIN_NBR,
	        PRIMARY_PREFERRED_DELIVERY_METHOD_CODE,
	        BOARD_CERTIFIED_IND,
	        STATE_MEDICAID_ID,
	        PRIMARY_SPECIALTY_NAME,
	        PRIMARY_TAXONOMY_CODE,
	        PRESCRIBER_SOURCE_CODE,
	        PROVIDER_START_DATE,
	        PROVIDER_ACTIVE_IND,
	        FACILITY_INCEPTION_DATE]) AS HASH_DIFF
	FROM RAWDATA.CACTUS_PROVIDERS
        LEFT JOIN RAWDATA.CACTUS_PROVIDERBOARDS
            ON CACTUS_PROVIDERS.PROVIDER_K = CACTUS_PROVIDERBOARDS.PROVIDER_K
        INNER JOIN RAWDATA.CACTUS_ENTITYASSIGNMENTS
            ON CACTUS_PROVIDERS.PROVIDER_K = CACTUS_ENTITYASSIGNMENTS.PROVIDER_K
        INNER JOIN (
        SELECT DISTINCT PROVIDER_K
        FROM RAWDATA.CACTUS_ENTITYASSIGNMENTS
        WHERE RECORDTYPE = 'E'
            ) AS EA
        ON CACTUS_PROVIDERS.PROVIDER_K = EA.PROVIDER_K
        LEFT JOIN (
            SELECT ID, COUNT(*) AS CNT FROM(
                SELECT DISTINCT P.ID, P.PROVIDER_K
                     FROM RAWDATA.CACTUS_PROVIDERS P
            INNER JOIN RAWDATA.CACTUS_ENTITYASSIGNMENTS E
            ON E.PROVIDER_K = P.PROVIDER_K) A
    GROUP BY ID HAVING COUNT(*) > 1 ) DUPES
ON CACTUS_PROVIDERS.ID = DUPES.ID
WHERE CACTUS_ENTITYASSIGNMENTS.RECORDTYPE = 'E' AND CACTUS_PROVIDERS.STATUS_RTK NOT IN ('#0000K408T','#0000K408U','#0000K408S')
AND NOT (CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 1 AND (CACTUS_PROVIDERS.LASTNAME = '' AND CACTUS_PROVIDERS.FIRSTNAME =''))
AND NOT(CACTUS_PROVIDERS.INDIVIDUALINSTITUTIONFLAG = 2 AND CACTUS_PROVIDERS.LONGNAME  ='')
AND NULLIF(CACTUS_PROVIDERS.ID, '') IS NOT NULL
AND DUPES.ID IS NULL;