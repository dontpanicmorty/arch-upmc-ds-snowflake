CREATE OR REPLACE VIEW STAGEDATA.HUB_RIDER_MC400DNT_SELECT_VW
COMMENT = 'This is a HUB View containing Rider data'
AS
SELECT DISTINCT
'N/A' AS SOURCE_KEY
,'000001' AS TPA_CLIENT_ID
,'000001' AS TPA_ID
,'0001' AS TPA_DIV_ID
,'MC400Dnt' AS DATA_SOURCE_NAME
,RiderCode AS RIDER_CODE
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, RIDER_CODE]) AS HUB_RIDER_HKEY
FROM RAWDATA.MC400_DWDNV_RIDERS
;
