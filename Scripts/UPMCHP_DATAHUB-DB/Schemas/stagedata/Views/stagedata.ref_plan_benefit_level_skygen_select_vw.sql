CREATE OR REPLACE VIEW STAGEDATA.REF_PLAN_BENEFIT_LEVEL_SKYGEN_SELECT_VW
AS
SELECT DISTINCT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS TPA_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS TPA_DIV_ID
,LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME
,BENEFIT_LEVEL_CODE AS CODE
,BENEFIT_LEVEL_DESC AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CODE]) AS PLAN_BENEFIT_LEVEL_HKEY
FROM RAWDATA.DWSKYGEN_CLAIM_DETAIL
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR = DWSKYGEN_CLAIM_DETAIL.CLAIM_NBR)
;
