CREATE OR REPLACE VIEW EXTRACTDATA.REFDATA_CLAIM_REVENUE_CODE_VW
COMMENT = 'Reference Data for Revenue Codes that appear on claims'
AS
SELECT DISTINCT
REF_CLAIM_REVENUE_CODE.CODE AS REVENUE_CODE,
REF_CLAIM_REVENUE_CODE.CODE_DESC AS REVENUE_CODE_DESC,
REF_CLAIM_REVENUE_CODE.CODE_DESC_LONG AS REVENUE_CODE_DESC_LONG,
REF_CLAIM_REVENUE_CODE.CODE_SPANISH_DESC AS REVENUE_CODE_SPANISH_DESC
FROM HUBDATA.HUB_CLAIM_DETAIL
JOIN HUBDATA.EFF_SAT_CLAIM_LINE
    ON (HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = EFF_SAT_CLAIM_LINE.HUB_CLAIM_DETAIL_HKEY
    AND EFF_SAT_CLAIM_LINE.IS_CURRENT_ROW_FLAG = TRUE
    AND EFF_SAT_CLAIM_LINE.DELETED_DATETIME > CURRENT_TIMESTAMP()
    )
JOIN HUBDATA.SAT_CLAIM_LINE
    ON (HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY
    AND SAT_CLAIM_LINE.IS_CURRENT_ROW_FLAG = TRUE)
JOIN REFDATA.CLAIM_REVENUE_CODE REF_CLAIM_REVENUE_CODE
    ON (SAT_CLAIM_LINE.REVENUE_CODE = REF_CLAIM_REVENUE_CODE.CODE)
;