CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_OFFICE_SKYGEN_SELECT_VW
COMMENT = 'Source view for Skygen data into LNK_CLAIM_OFFICE'
AS
SELECT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS C_TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS C_TPA_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS C_TPA_DIV_ID
,LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME
,DWSKYGEN_CLAIM_HEADER.CLAIM_NBR AS C_CLAIM_NBR
,LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS O_TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS O_TPA_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS O_TPA_DIV_ID
,LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS O_DATA_SOURCE_NAME
,DWSKYGEN_CLAIM_HEADER.PROVIDER_OFFICE_ID AS O_OFFICE_ID
,UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, O_OFFICE_ID]) AS LNK_CLAIM_OFFICE_HKEY
,UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY
,UTIL.FXN_ARRAY_HASH([O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, O_OFFICE_ID]) AS HUB_OFFICE_HKEY
FROM RAWDATA.DWSKYGEN_CLAIM_HEADER
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR = DWSKYGEN_CLAIM_HEADER.CLAIM_NBR)
WHERE O_OFFICE_ID <> 'LOCATION_0' -- exclude records with unknown Office ID values

UNION ALL

SELECT DISTINCT
LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS C_TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS C_TPA_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS C_TPA_DIV_ID
,LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME
,SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO AS C_CLAIM_NBR
,LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID AS O_TPA_CLIENT_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_ID AS O_TPA_ID
,LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID AS O_TPA_DIV_ID
,LKP_CLAIM_MEMBER_SKYGEN.DATA_SOURCE_NAME AS O_DATA_SOURCE_NAME
,CONCAT('LOCATION_', SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.PROV_LOC_ID) AS O_OFFICE_ID
,UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, O_OFFICE_ID]) AS LNK_CLAIM_OFFICE_HKEY
,UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY
,UTIL.FXN_ARRAY_HASH([O_TPA_CLIENT_ID, O_TPA_ID, O_TPA_DIV_ID, O_DATA_SOURCE_NAME, O_OFFICE_ID]) AS HUB_OFFICE_HKEY

FROM RAWDATA.SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW
    INNER JOIN STAGEDATA.LKP_CLAIM_MEMBER_SKYGEN
        ON (LKP_CLAIM_MEMBER_SKYGEN.CLAIM_NBR = SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO)
    JOIN RAWDATA.DWSKYGEN_PROVIDER_OFFICE
        ON (DWSKYGEN_PROVIDER_OFFICE.TPA_CLIENT_ID = LKP_CLAIM_MEMBER_SKYGEN.TPA_CLIENT_ID
        AND DWSKYGEN_PROVIDER_OFFICE.TPA_ID = LKP_CLAIM_MEMBER_SKYGEN.TPA_ID
        AND DWSKYGEN_PROVIDER_OFFICE.TPA_DIV_ID = LKP_CLAIM_MEMBER_SKYGEN.TPA_DIV_ID
        AND DWSKYGEN_PROVIDER_OFFICE.OFFICE_ID = CONCAT('LOCATION_', SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.PROV_LOC_ID))

WHERE SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.CLAIM_NO NOT IN (SELECT CLAIM_NBR FROM RAWDATA.DWSKYGEN_CLAIM_HEADER) --Exclude claims in dwskygen, they supersede
AND SKYGEN_PAID_CLAIM_EXTRACTS_CURRENT_VW.PROV_LOC_ID IS NOT NULL
AND O_OFFICE_ID <> 'LOCATION_0' -- exclude records with unknown Office ID values
;
