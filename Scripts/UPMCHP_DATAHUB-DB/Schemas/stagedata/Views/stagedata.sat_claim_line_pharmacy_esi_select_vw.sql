    END AS ORIGINAL_HIA_SPENDING_AMT,
FROM STAGEDATA.LKP_CLAIM_PHARMACY_CLAIM
LEFT JOIN RAWDATA.PLANEXPAND_CURRENT_VW
    ON (PLANEXPAND_CURRENT_VW.PHARMACY_CLAIM_REFERENCE_NUMBER =  IFF(LKP_CLAIM_PHARMACY_CLAIM.CLAIM_TYPE = 'P', LKP_CLAIM_PHARMACY_CLAIM.CLAIM_ID, LKP_CLAIM_PHARMACY_CLAIM.XREF_CLAIM_ID)
