    AND PLANEXPAND_CURRENT_VW.TOTAL_SPENDING_AMT = LKP_CLAIM_PHARMACY_CLAIM.HRA_APPLIED_AMOUNT)
LEFT JOIN HUBDATA.SAT_CLAIM_LINE_PHARMACY
    ON (SAT_CLAIM_LINE_PHARMACY.HUB_CLAIM_DETAIL_HKEY = UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_NBR, CLAIM_LINE_NBR, CLAIM_LINE_SEQ_NBR, CLAIM_LINE_PROCEDURE_ADJ_CODE])
    AND SAT_CLAIM_LINE_PHARMACY.IS_CURRENT_ROW_FLAG = TRUE)
LEFT JOIN RAWDATA.IDAPLAKE_HRA_HIA_AUDIT_HISTORICAL_VW 
    ON (IDAPLAKE_HRA_HIA_AUDIT_HISTORICAL_VW.CLAIM_ID = LKP_CLAIM_PHARMACY_CLAIM.CLAIM_ID)
