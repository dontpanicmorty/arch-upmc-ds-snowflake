        WHEN SAT_CLAIM_LINE_PHARMACY.ORIGINAL_HRA_SPENDING_AMT IS NOT NULL THEN SAT_CLAIM_LINE_PHARMACY.ORIGINAL_HRA_SPENDING_AMT
        WHEN IDAPLAKE_HRA_HIA_AUDIT_HISTORICAL_VW.ORG_HRA_SPENDING_AMT IS NOT NULL THEN IDAPLAKE_HRA_HIA_AUDIT_HISTORICAL_VW.ORG_HRA_SPENDING_AMT
