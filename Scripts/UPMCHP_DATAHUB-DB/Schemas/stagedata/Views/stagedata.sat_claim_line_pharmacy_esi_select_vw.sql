        WHEN SAT_CLAIM_LINE_PHARMACY.ORIGINAL_HIA_SPENDING_AMT IS NOT NULL THEN SAT_CLAIM_LINE_PHARMACY.ORIGINAL_HIA_SPENDING_AMT
