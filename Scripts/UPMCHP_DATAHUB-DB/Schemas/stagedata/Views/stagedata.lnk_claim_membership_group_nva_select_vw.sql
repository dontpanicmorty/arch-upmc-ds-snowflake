CREATE OR REPLACE VIEW STAGEDATA.LNK_CLAIM_MEMBERSHIP_GROUP_NVA_SELECT_VW
COMMENT = 'Source view for NVA data into LNK_CLAIM_MEMBERSHIP_GROUP'
AS
SELECT DISTINCT
    LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID AS C_TPA_CLIENT_ID, 
    LKP_CLAIM_MEMBER_NVA.TPA_ID AS C_TPA_ID, 
    LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID AS C_TPA_DIV_ID, 
    LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME AS C_DATA_SOURCE_NAME, 
    NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo" AS C_CLAIM_NBR, 
    LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID AS MG_TPA_CLIENT_ID, 
    LKP_CLAIM_MEMBER_NVA.TPA_ID AS MG_TPA_ID, 
    LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID AS MG_TPA_DIV_ID, 
    'MC400Upm' as MG_DATA_SOURCE_NAME,
    TRIM(LKP_CLAIM_MEMBER_NVA.GROUP_CODE) AS MG_GROUP_NBR,
    TRIM(LKP_CLAIM_MEMBER_NVA.SUB_GROUP_CODE) AS MG_SUB_GROUP_NBR,
    UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR, MG_DATA_SOURCE_NAME, MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_GROUP_NBR, MG_SUB_GROUP_NBR]) AS LNK_CLAIM_MEMBERSHIP_GROUP_HKEY, 
    UTIL.FXN_ARRAY_HASH([C_TPA_CLIENT_ID, C_TPA_ID, C_TPA_DIV_ID, C_DATA_SOURCE_NAME, C_CLAIM_NBR]) AS HUB_CLAIM_HKEY, 
    UTIL.FXN_ARRAY_HASH([MG_TPA_CLIENT_ID, MG_TPA_ID, MG_TPA_DIV_ID, MG_DATA_SOURCE_NAME, MG_GROUP_NBR, MG_SUB_GROUP_NBR]) AS HUB_MEMBERSHIP_GROUP_HKEY
FROM RAWDATA.NVA_PAID_CLAIM_EXTRACTS_VW
    JOIN STAGEDATA.LKP_CLAIM_MEMBER_NVA
        ON (LKP_CLAIM_MEMBER_NVA.CLAIM_NBR = NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo")
WHERE MG_GROUP_NBR IS NOT NULL
AND MG_SUB_GROUP_NBR IS NOT NULL
;