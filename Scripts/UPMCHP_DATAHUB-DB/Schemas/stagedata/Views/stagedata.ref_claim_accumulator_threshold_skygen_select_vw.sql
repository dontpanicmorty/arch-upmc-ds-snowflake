CREATE OR REPLACE VIEW STAGEDATA.REF_CLAIM_ACCUMULATOR_THRESHOLD_SKYGEN_SELECT_VW
AS
SELECT DISTINCT
TPA_CLIENT_ID
,TPA_ID
,TPA_DIV_ID
,DATA_SOURCE_NAME
,ACCUMULATOR_THRESHOLD_CODE AS CODE
,ACCUMULATOR_THRESHOLD_DESC AS CODE_DESC
,NULL AS CODE_DESC_LONG
,NULL AS CODE_SPANISH_DESC
,UTIL.FXN_ARRAY_HASH(
        [TPA_CLIENT_ID
        ,TPA_ID
        ,TPA_DIV_ID
        ,DATA_SOURCE_NAME
        ,CODE
        ]) AS CLAIM_ACCUMULATOR_THRESHOLD_HKEY
FROM RAWDATA.DWSKYGEN_PLAN_ACCUMULATOR
;