CREATE OR REPLACE VIEW STAGEDATA.HUB_PROVIDER_SKYGEN_SELECT_VW
COMMENT = 'This is a HUB View containing Provider data'
AS
SELECT
'N/A' AS SOURCE_KEY,
TPA_CLIENT_ID,
TPA_ID,
TPA_DIV_ID,
'Skygen' AS DATA_SOURCE_NAME,
PROVIDER_ID,
UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PROVIDER_ID]) AS HUB_PROVIDER_HKEY

FROM RAWDATA.DWSKYGEN_PROVIDER_DETAIL
WHERE PROVIDER_TYPE = 'Practitioner'
;