CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_LINE_ENVOLVE_SELECT_VW
COMMENT = 'This is a SAT View containing Claim Line data'
AS
SELECT DISTINCT 
    LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID,
    LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID,
    LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID,
    LKP_CLAIM_MEMBER_ENVOLVE.DATA_SOURCE_NAME,
    ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO AS CLAIM_NBR, 
    ENVOLVE_CLAIM_EXTRACTS.ITEM_NO AS CLAIM_LINE_NBR, 
    CONCAT(COALESCE(ENVOLVE_CLAIM_EXTRACTS.EOB_MAIL_DATE,''), COALESCE(ENVOLVE_CLAIM_EXTRACTS.COUNTY_CODE,''),'P') AS CLAIM_LINE_SEQ_NBR, 
    'N/A' AS CLAIM_LINE_PROCEDURE_ADJ_CODE, 
    'E' AS CLAIM_TYPE_CODE, --(E)ncounter or (I)npatient
    NULL AS CLAIM_RECEIVED_DATE, 
    ENVOLVE_CLAIM_EXTRACTS.PROC_CODE as PROCEDURE_CODE, 
    NULLIF(ENVOLVE_CLAIM_EXTRACTS.QUANTITY, '') AS PROCEDURE_QUANTITY, 
    TO_DATE(ENVOLVE_CLAIM_EXTRACTS.SERVICE_DT, 'YYYYMMDD') AS SERVICE_BEGIN_DATE, 
    NULL AS SERVICE_END_DATE, 
    NULL AS ADD_DATE, 
    NULL AS ACCOUNTS_PAYABLE_PAY_STATUS_CODE, 
    NULL AS ADJUDICATION_STATUS, 
    NULL AS AP_POSTING_DATE, 
    NULL AS BENEFIT_CATEGORY_CODE, 
    NULL AS BENEFIT_LEVEL_CODE, 
    NULL AS BUCKET_STATUS_FLAG, 
    NULL AS CHECK_DATE, 
    ENVOLVE_CLAIM_EXTRACTS.CHECK_NO AS CHECK_NUMBER, 
    NULL AS CLAIM_DAY_CNT, 
    NULL AS CLEAN_CLAIM_IND, 
    NULL AS COMPANY_CODE, 
    NULL AS DENIED_DAY_CNT, 
    ELIGIBILITYHISTORY.MISCSTATUSCODE AS ELIGIBILITY_MISC_STATUS_CODE, 
    NULL AS FORM_NUMBER, 
    NULL AS GL_DISTRIBUTION_CODE, 
    TRUE AS IS_PROCESSING_COMPLETE, 
    NULL AS KEY_TO_SOURCE_FILE, 
    'O' AS LOCATION_CODE, 
    '3' AS PAY_STATUS_CODE, 
    TO_DATE(ENVOLVE_CLAIM_EXTRACTS.ADJUDICATION_DT, 'YYYYMMDD') AS PAYMENT_DATE, 
    NULL AS TOOTH_QUADRANT, 
    NULL AS REVENUE_CODE, 
    NULL AS SERVICE_CNT, 
    NULL AS SERVICE_REASON_CODE, 
    CASE
        WHEN ENVOLVE_CLAIM_EXTRACTS.PAYMENT_AMT <> 0 THEN 'P'
        WHEN ENVOLVE_CLAIM_EXTRACTS.PAYMENT_AMT = 0 THEN 'D'
        ELSE 'U'
    END AS SERVICE_STATUS_CODE, 
    CASE
        WHEN ENVOLVE_CLAIM_EXTRACTS.PAYMENT_AMT <> 0 THEN 'Paid'
        WHEN ENVOLVE_CLAIM_EXTRACTS.PAYMENT_AMT = 0 THEN 'Denied'
        ELSE 'Unknown'
    END AS SERVICE_STATUS_DESC, 
    CASE 
        WHEN POS IN ('IN','EC','AC','99','81','72','71','54','51','50','49','41','33','32','31','3','24','23','22','21','20','19','16','15','14','13','12','11','10','1','03','02','01') THEN 'P'
        ELSE 'U'
    END AS SERVICE_TYPE_CODE,  -- Need to circle back to fix this 
    CASE 
        WHEN ENVOLVE_CLAIM_EXTRACTS.CLAIM_TYPE = 'P' THEN 'C' 
        WHEN ENVOLVE_CLAIM_EXTRACTS.CLAIM_TYPE <> 'P' THEN 'A'
    END AS TRANSACTION_TYPE_CODE, 
    CASE 
        WHEN ENVOLVE_CLAIM_EXTRACTS.CLAIM_TYPE = 'P' THEN 'Charge' 
        WHEN ENVOLVE_CLAIM_EXTRACTS.CLAIM_TYPE <> 'P' THEN 'Adjustment'
    END AS TRANSACTION_TYPE_DESC,
    NULL AS SOURCE_LAST_UPDATED_DATETIME, 
    NULL AS TOOTH_ID, 
    NULL AS TOOTH_ARCH, 
    TO_ARRAY(NULL) AS TOOTH_SURFACE_ARRAY,
    NULLIF(ENVOLVE_CLAIM_EXTRACTS.AGE,'') AS MEMBER_AGE_NBR, 
    NULL AS AUTHORIZATION_NBR,
    NULL AS HCPCS_CODE,
    NULL AS CMS_CURRENT_ITERATION_FLAG, 
    UTIL.FXN_ARRAY_HASH([LKP_CLAIM_MEMBER_ENVOLVE.TPA_CLIENT_ID, LKP_CLAIM_MEMBER_ENVOLVE.TPA_ID, LKP_CLAIM_MEMBER_ENVOLVE.TPA_DIV_ID, LKP_CLAIM_MEMBER_ENVOLVE.DATA_SOURCE_NAME, CLAIM_NBR, CLAIM_LINE_NBR, CLAIM_LINE_SEQ_NBR, CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY, 
    UTIL.FXN_ARRAY_HASH([CLAIM_TYPE_CODE, CLAIM_RECEIVED_DATE, PROCEDURE_CODE, PROCEDURE_QUANTITY, SERVICE_BEGIN_DATE, SERVICE_END_DATE, ADD_DATE, ACCOUNTS_PAYABLE_PAY_STATUS_CODE, ADJUDICATION_STATUS, AP_POSTING_DATE, BENEFIT_CATEGORY_CODE, BENEFIT_LEVEL_CODE, BUCKET_STATUS_FLAG, CHECK_DATE, CHECK_NUMBER, CLAIM_DAY_CNT, CLEAN_CLAIM_IND, COMPANY_CODE, DENIED_DAY_CNT, ELIGIBILITY_MISC_STATUS_CODE, FORM_NUMBER, GL_DISTRIBUTION_CODE, IS_PROCESSING_COMPLETE, KEY_TO_SOURCE_FILE, SERVICE_TYPE_CODE, LOCATION_CODE, PAY_STATUS_CODE, PAYMENT_DATE, TOOTH_QUADRANT, REVENUE_CODE, SERVICE_CNT, SERVICE_REASON_CODE, SERVICE_STATUS_CODE, SERVICE_STATUS_DESC, SERVICE_TYPE_CODE, TRANSACTION_TYPE_CODE, TRANSACTION_TYPE_DESC, SOURCE_LAST_UPDATED_DATETIME, TOOTH_ID, TOOTH_ARCH, MEMBER_AGE_NBR, AUTHORIZATION_NBR, TOOTH_SURFACE_ARRAY, HCPCS_CODE, CMS_CURRENT_ITERATION_FLAG]) AS HASH_DIFF
FROM RAWDATA.ENVOLVE_CLAIM_EXTRACTS 
JOIN STAGEDATA.LKP_CLAIM_MEMBER_ENVOLVE
        ON (LKP_CLAIM_MEMBER_ENVOLVE.CLAIM_NBR = ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO)
LEFT JOIN MC400.DWOAO.ELIGIBILITYHISTORY
        ON ELIGIBILITYHISTORY.MEMBERNBR = ENVOLVE_CLAIM_EXTRACTS.SUBSCRIBER_ID
        AND REPLACE(TO_CHAR(ENVOLVE_CLAIM_EXTRACTS.SERVICE_DT), '-', '')::INT BETWEEN ELIGIBILITYHISTORY.ELIGIBILITYSTARTDATE AND ELIGIBILITYHISTORY.ELIGIBILITYENDDATE 
QUALIFY ROW_NUMBER() -- get the most current submitted file for a claim line
    OVER(PARTITION BY ENVOLVE_CLAIM_EXTRACTS.CLAIM_NO,ENVOLVE_CLAIM_EXTRACTS.ITEM_NO
    ORDER BY SPLIT_PART(SPLIT_PART(ENVOLVE_CLAIM_EXTRACTS.FILENAME, '_', 7), '.', 1) DESC) = 1 
;