CREATE OR REPLACE VIEW STAGEDATA.SAT_CLAIM_LINE_PROCESSING_REASON_NVA_SELECT_VW
COMMENT = 'This is a SAT View containing Claim Line Processing Reason data'
AS
SELECT DISTINCT 
    LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID,
	LKP_CLAIM_MEMBER_NVA.TPA_ID,
	LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID,
	LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME,
    NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo" AS CLAIM_NBR, 
    NVA_PAID_CLAIM_EXTRACTS_VW."ClaimSeqNo" AS CLAIM_LINE_NBR, 
    CONCAT(NVA_PAID_CLAIM_EXTRACTS_VW."ClaimSeqNo", NVA_PAID_CLAIM_EXTRACTS_VW."Trantype") AS CLAIM_LINE_SEQ_NBR, 
    'N/A' AS CLAIM_LINE_PROCEDURE_ADJ_CODE, 
    CLAIM_PROCESSING_REASON.CLAIM_PROCESSING_REASON_TYPE AS REASON_TYPE_CODE,
    1 AS CODE_POSITION, 
    CLAIM_PROCESSING_REASON.CODE AS REASON_CODE, 
    UTIL.FXN_ARRAY_HASH([LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID, LKP_CLAIM_MEMBER_NVA.TPA_ID, LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID, LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME, CLAIM_NBR, CLAIM_LINE_NBR, CLAIM_LINE_SEQ_NBR, CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY, 
    UTIL.FXN_ARRAY_HASH([REASON_CODE]) AS HASH_DIFF
FROM RAWDATA.NVA_PAID_CLAIM_EXTRACTS_VW 
JOIN STAGEDATA.LKP_CLAIM_MEMBER_NVA
        ON (LKP_CLAIM_MEMBER_NVA.CLAIM_NBR = NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo")
LEFT JOIN REFDATA.CLAIM_PROCESSING_REASON 
    ON CLAIM_PROCESSING_REASON.CODE = CASE WHEN NVA_PAID_CLAIM_EXTRACTS_VW."ReasonSuf1" IS NOT NULL THEN CONCAT(NVA_PAID_CLAIM_EXTRACTS_VW."ReasonCd1", '_', NVA_PAID_CLAIM_EXTRACTS_VW."ReasonSuf1") ELSE NVA_PAID_CLAIM_EXTRACTS_VW."ReasonCd1" END 
    AND CLAIM_PROCESSING_REASON.DATA_SOURCE_NAME = 'NVA' 
WHERE CLAIM_PROCESSING_REASON.CLAIM_PROCESSING_REASON_TYPE IN ('Adjustment', 'CoInsurance', 'Deductible', 'Service', 'CoPay') 

UNION 

SELECT DISTINCT
    LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID,
	LKP_CLAIM_MEMBER_NVA.TPA_ID,
	LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID,
	LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME,
    NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo" AS CLAIM_NBR, 
    NVA_PAID_CLAIM_EXTRACTS_VW."ClaimSeqNo" AS CLAIM_LINE_NBR, 
    CONCAT(NVA_PAID_CLAIM_EXTRACTS_VW."ClaimSeqNo", NVA_PAID_CLAIM_EXTRACTS_VW."Trantype") AS CLAIM_LINE_SEQ_NBR, 
    'N/A' AS CLAIM_LINE_PROCEDURE_ADJ_CODE, 
    CLAIM_PROCESSING_REASON.CLAIM_PROCESSING_REASON_TYPE AS REASON_TYPE_CODE,
    2 AS CODE_POSITION, 
    CLAIM_PROCESSING_REASON.CODE AS REASON_CODE, 
    UTIL.FXN_ARRAY_HASH([LKP_CLAIM_MEMBER_NVA.TPA_CLIENT_ID, LKP_CLAIM_MEMBER_NVA.TPA_ID, LKP_CLAIM_MEMBER_NVA.TPA_DIV_ID, LKP_CLAIM_MEMBER_NVA.DATA_SOURCE_NAME, CLAIM_NBR, CLAIM_LINE_NBR, CLAIM_LINE_SEQ_NBR, CLAIM_LINE_PROCEDURE_ADJ_CODE]) AS HUB_CLAIM_DETAIL_HKEY, 
    UTIL.FXN_ARRAY_HASH([REASON_CODE]) AS HASH_DIFF
FROM RAWDATA.NVA_PAID_CLAIM_EXTRACTS_VW 
JOIN STAGEDATA.LKP_CLAIM_MEMBER_NVA
    ON (LKP_CLAIM_MEMBER_NVA.CLAIM_NBR = NVA_PAID_CLAIM_EXTRACTS_VW."ClaimNo")
LEFT JOIN REFDATA.CLAIM_PROCESSING_REASON 
    ON CLAIM_PROCESSING_REASON.CODE = CASE WHEN NVA_PAID_CLAIM_EXTRACTS_VW."ReasonSuf2" IS NOT NULL THEN CONCAT(NVA_PAID_CLAIM_EXTRACTS_VW."ReasonCd2", '_', NVA_PAID_CLAIM_EXTRACTS_VW."ReasonSuf2") ELSE NVA_PAID_CLAIM_EXTRACTS_VW."ReasonCd2" END 
    AND CLAIM_PROCESSING_REASON.DATA_SOURCE_NAME = 'NVA' 
WHERE CLAIM_PROCESSING_REASON.CLAIM_PROCESSING_REASON_TYPE IN ('Adjustment', 'CoInsurance', 'Deductible', 'Service', 'CoPay') 
;