CREATE OR REPLACE VIEW STAGEDATA.HUB_ADDRESS_QUERY_CACTUS_SELECT_VW
COMMENT = 'This is a Cactus HUB select view of address query and office data'
AS
WITH DUPLICATE_PROVIDERS AS (
    SELECT PRV.ID
    FROM
        RAWDATA.CACTUS_PROVIDERS AS PRV
    INNER JOIN
        RAWDATA.CACTUS_ENTITYASSIGNMENTS AS EA
        ON PRV.PROVIDER_K = EA.PROVIDER_K
    GROUP BY PRV.ID
    HAVING COUNT(DISTINCT PRV.PROVIDER_K) > 1
)
, DUPLICATE_GROUPS AS (
    SELECT ID
    FROM RAWDATA.CACTUS_GROUPS
    GROUP BY ID HAVING COUNT(*) > 1
)
SELECT DISTINCT
    NULL AS SOURCE_KEY,
    '000001' AS TPA_CLIENT_ID,
    '000001' AS TPA_ID,
    '0001' AS TPA_DIV_ID,
    'Cactus' AS DATA_SOURCE_NAME,
    REGEXP_REPLACE(
        TRIM(
            CONCAT_WS(
                ' ',
                TRIM(COALESCE(NULLIF(ADR.ADDRESSLINE1, ''), NULLIF(ADR.ADDRESSLINE2, ''), '')),
                TRIM(NVL(IFF(ADR.ADDRESSLINE1 = '' AND ADR.ADDRESSLINE2 != '', NULL, NULLIF(ADR.ADDRESSLINE2, '')), '')),
                NVL(ADR.CITY, ''),
                NVL(ADR.STATE, ''),
                NVL(LEFT(TRIM(ADR.ZIPCODE), 5), '')
                )
        ),'\\s+', ' '
    ) AS CONCATENATED_ADDRESS,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CONCATENATED_ADDRESS]) AS HUB_ADDRESS_QUERY_HKEY
FROM
    RAWDATA.CACTUS_PROVIDERADDRESSES AS PRV_ADR
LEFT JOIN
    RAWDATA.CACTUS_PROVIDERS AS PRV
    ON PRV_ADR.PROVIDER_K = PRV.PROVIDER_K
LEFT JOIN
    RAWDATA.CACTUS_ADDRESSES AS ADR
    ON PRV_ADR.ADDRESS_K = ADR.ADDRESS_K
LEFT JOIN
    DUPLICATE_PROVIDERS AS DUP
    ON PRV.ID = DUP.ID
INNER JOIN (
    SELECT DISTINCT PROVIDER_K
    FROM RAWDATA.CACTUS_ENTITYASSIGNMENTS
    WHERE RECORDTYPE = 'E'
    ) AS EA
    ON PRV.PROVIDER_K = EA.PROVIDER_K
WHERE
    NULLIF(PRV_ADR.PROVIDER_K, '') IS NOT NULL
    AND NULLIF(PRV.ID, '') IS NOT NULL
    AND PRV.STATUS_RTK NOT IN ('#0000K408T','#0000K408U','#0000K408S') --Provider statuses "Applicant", "Committee Reviewer", "Lead" do not interface out of Cactus 
    AND (PRV.INDIVIDUALINSTITUTIONFLAG != 1 OR PRV.LASTNAME != '' OR PRV.FIRSTNAME != '')
    AND (PRV.INDIVIDUALINSTITUTIONFLAG != 2 OR (PRV.LONGNAME != '' AND PRV_ADR.ACTIVE = 1))
    AND (NULLIF(ADR.ADDRESSLINE1, '') IS NOT NULL OR NULLIF(ADR.ADDRESSLINE2, '') IS NOT NULL)
    AND DUP.ID IS NULL

UNION

SELECT DISTINCT
    NULL AS SOURCE_KEY,
    '000001' AS TPA_CLIENT_ID,
    '000001' AS TPA_ID,
    '0001' AS TPA_DIV_ID,
    'Cactus' AS DATA_SOURCE_NAME,
    REGEXP_REPLACE(
        TRIM(
            CONCAT_WS(
                ' ',
                NVL(TRIM(NVL(NULLIF(ADR.ADDRESSLINE1, ''), NULLIF(ADR.ADDRESSLINE2, ''))), ''),
                NVL(TRIM(IFF(ADR.ADDRESSLINE1 = '' AND ADR.ADDRESSLINE2 != '', NULL, NULLIF(ADR.ADDRESSLINE2, ''))), ''),
                NVL(ADR.CITY, ''),
                NVL(ADR.STATE, ''),
                NVL(LEFT(TRIM(ADR.ZIPCODE), 5), '')
                )
        ),'\\s+', ' '
    ) AS CONCATENATED_ADDRESS,
    UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CONCATENATED_ADDRESS]) AS HUB_ADDRESS_QUERY_HKEY
FROM
    RAWDATA.CACTUS_GROUPADDRESS AS GRP_ADR
LEFT JOIN
    RAWDATA.CACTUS_GROUPS AS GRP
    ON GRP_ADR.GROUP_K = GRP.GROUP_K
LEFT JOIN
    RAWDATA.CACTUS_ADDRESSES AS ADR
    ON GRP_ADR.ADDRESS_K = ADR.ADDRESS_K
LEFT JOIN
    DUPLICATE_GROUPS AS DUP
    ON GRP.ID = DUP.ID
WHERE
    NULLIF(TRIM(GRP_ADR.ID), '') IS NOT NULL
    AND NULLIF(TRIM(GRP_ADR.GROUP_K), '') IS NOT NULL
    AND NULLIF(TRIM(GRP_ADR.TAXIDNUMBER), '') IS NOT NULL
    AND NULLIF(TRIM(GRP.ID), '') IS NOT NULL
    AND (NULLIF(ADR.ADDRESSLINE1, '') IS NOT NULL OR NULLIF(ADR.ADDRESSLINE2, '') IS NOT NULL)
    AND DUP.ID IS NULL
;