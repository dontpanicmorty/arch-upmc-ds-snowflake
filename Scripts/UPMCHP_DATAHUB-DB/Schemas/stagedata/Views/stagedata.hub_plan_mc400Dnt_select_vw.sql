CREATE OR REPLACE VIEW STAGEDATA.HUB_PLAN_MC400DNT_SELECT_VW
COMMENT = 'This is a HUB View containing Plan data'
AS
SELECT
MC400_RRN AS SOURCE_KEY,
'000001' AS TPA_CLIENT_ID,
'000001' AS TPA_ID,
'0001' AS TPA_DIV_ID,
'MC400Dnt' AS DATA_SOURCE_NAME,
PlanCode AS PLAN_CODE,
UTIL.FXN_ARRAY_HASH([TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, PLAN_CODE]) AS HUB_PLAN_HKEY
FROM RAWDATA.MC400_DWDNV_PLANMASTER
;