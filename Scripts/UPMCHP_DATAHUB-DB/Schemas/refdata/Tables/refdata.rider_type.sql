CREATE OR REPLACE TABLE REFDATA.RIDER_TYPE
(
    RIDER_TYPE_HKEY VARCHAR(32) NOT NULL,
    INSERT_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    CODE VARCHAR NOT NULL,
    CODE_DESC VARCHAR NOT NULL,
    CODE_DESC_LONG VARCHAR NULL,
    CODE_SPANISH_DESC VARCHAR NULL,    
    CONSTRAINT PK_RIDER_TYPE PRIMARY KEY (RIDER_TYPE_HKEY),
    CONSTRAINT UK_RIDER_TYPE UNIQUE (CODE)
)
COMMENT = 'Rider Type code(s) and description(s) reference data'
;