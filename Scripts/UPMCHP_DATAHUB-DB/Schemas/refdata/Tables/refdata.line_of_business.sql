CREATE OR REPLACE TABLE REFDATA.LINE_OF_BUSINESS
(
    LINE_OF_BUISNESS_HKEY VARCHAR(32) NOT NULL,
    INSERT_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    CODE VARCHAR NOT NULL,
    CODE_DESC VARCHAR NOT NULL,
    CODE_DESC_LONG VARCHAR NULL,
    CODE_SPANISH_DESC VARCHAR NULL,    
    CONSTRAINT PK_LINE_OF_BUSINESS PRIMARY KEY (LINE_OF_BUISNESS_HKEY),
    CONSTRAINT UK_LINE_OF_BUSINESS UNIQUE (CODE)
)
COMMENT = 'Line Of Business code(s) and description(s) reference data'
;