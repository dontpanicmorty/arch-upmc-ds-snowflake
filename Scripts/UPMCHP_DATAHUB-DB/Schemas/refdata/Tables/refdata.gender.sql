CREATE OR REPLACE TABLE REFDATA.GENDER
(
    GENDER_HKEY VARCHAR(32) NOT NULL,
    INSERT_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    CODE VARCHAR NOT NULL,
    CODE_DESC VARCHAR NOT NULL,
    CODE_DESC_LONG VARCHAR NULL,
    CODE_SPANISH_DESC VARCHAR NULL,
    CONSTRAINT PK_GENDER PRIMARY KEY (GENDER_HKEY),
    CONSTRAINT UK_GENDER UNIQUE (CODE)
)
COMMENT = 'Gender code(s) and description(s) reference data'
;