CREATE OR REPLACE TABLE REFDATA.DATA_SOURCE
(
    DATA_SOURCE_HKEY VARCHAR(32) NOT NULL,
    INSERT_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    CODE VARCHAR NOT NULL,
    CODE_DESC VARCHAR NOT NULL,
    CODE_DESC_LONG VARCHAR NULL,
    CODE_SPANISH_DESC VARCHAR NULL,    
    CONSTRAINT PK_DATA_SOURCE PRIMARY KEY (DATA_SOURCE_HKEY),
    CONSTRAINT UK_DATA_SOURCE UNIQUE (CODE)
)
COMMENT = 'Data source names and description(s) reference data'
;