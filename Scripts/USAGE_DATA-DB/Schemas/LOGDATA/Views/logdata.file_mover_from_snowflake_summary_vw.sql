CREATE OR REPLACE VIEW LOGDATA.FILE_MOVER_FROM_SNOWFLAKE_SUMMARY_VW AS
WITH DECODED AS (
    SELECT
        EVENT_TIMESTAMP::TIMESTAMP_NTZ AS EVENT_TIMESTAMP,
        METADATA_FILENAME,
        MOVED_FILENAME,
        LOGDATA.FXN_JAVASCRIPT_URI_DECODE(MOVED_FILENAME) AS FULL_DECODED_FILENAME
    FROM LOGDATA.FILE_MOVER_FROM_SNOWFLAKE_RAW_LOGS
)
SELECT
    EVENT_TIMESTAMP,
    METADATA_FILENAME,
    MOVED_FILENAME,
    FULL_DECODED_FILENAME,
    SPLIT_PART(FULL_DECODED_FILENAME, '/', 5) AS DEPARTMENT_DATABASE,
    SPLIT_PART(FULL_DECODED_FILENAME, 'files/', 2) AS DECODED_FILENAME
FROM DECODED;