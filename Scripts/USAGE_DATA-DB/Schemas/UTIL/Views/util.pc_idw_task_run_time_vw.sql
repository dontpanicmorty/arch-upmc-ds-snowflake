CREATE OR REPLACE VIEW UTIL.PC_IDW_TASK_RUN_TIME_VW
      AS (
SELECT
    $1:WORKFLOW_ID::NUMBER AS WORKFLOW_ID,
    $1:WORKFLOW_RUN_ID::NUMBER AS WORKFLOW_RUN_ID,
    $1:WORKLET_RUN_ID::NUMBER AS WORKLET_RUN_ID,
    $1:CHILD_RUN_ID::NUMBER AS CHILD_RUN_ID,
    $1:INSTANCE_ID::NUMBER AS INSTANCE_ID,
    $1:INSTANCE_NAME::TEXT AS INSTANCE_NAME,
    $1:TASK_ID::NUMBER AS TASK_ID,
    $1:TASK_TYPE::TEXT AS TASK_TYPE,
    $1:START_TIME::TEXT AS START_TIME,
    $1:END_TIME::TEXT AS END_TIME,
    $1:RUN_ERR_CODE::NUMBER AS RUN_ERROR_CODE,
    $1:RUN_ERR_MSG::TEXT AS RUN_ERROR_MSG,
    $1:RUN_STATUS_CODE::NUMBER AS RUN_STATUS_CODE,
    $1:TASK_NAME::TEXT AS TASK_NAME,
    $1:RUN_MODE::TEXT AS RUN_MODE,
    $1:VERSION_NUMBER::NUMBER AS VERSION_NUMBER,
    $1:SERVER_ID::NUMBER AS SERVER_ID,
    $1:SERVER_NAME::TEXT AS SERVER_NAME,
    $1:FRAGMENT_ID::NUMBER AS FRAGMENT_ID,
    $1:SERVER_NODE_ID::NUMBER AS SERVER_NODE_ID,
    $1:SERVER_NODE_NAME::TEXT AS SERVER_NODE_NAME
FROM @UTIL.SNOWFLAKEDATA_USAGE_DATA_DB_EXTRACT/logdata/powercenter/idw_task_run_time/
   (FILE_FORMAT =>  'UTIL.DB_EXTRACT_PARQUET_FILE_FORMAT' )
);