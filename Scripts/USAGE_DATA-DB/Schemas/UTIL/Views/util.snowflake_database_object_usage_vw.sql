CREATE OR REPLACE VIEW UTIL.SNOWFLAKE_DATABASE_OBJECT_USAGE_VW(
	QUERY_ID,
	QUERY_START_TIME,
	USER_NAME,
	DISPLAY_NAME,
	QUERY_TYPE,
	QUERY_TEXT,
	WAREHOUSE_NAME,
	ENVIRONMENT_NAME,
	TOTAL_ELAPSED_TIME,
	OBJECTS_ACCESSED,
	DATABASE_NAME,
	SCHEMA_NAME,
	TABLE_NAME
) as
SELECT  QUERY_ID,
        QUERY_START_TIME,
        USER_NAME,
        DISPLAY_NAME,
        QUERY_TYPE,
        QUERY_TEXT,
        WAREHOUSE_NAME,
        ENVIRONMENT_NAME,
        TOTAL_ELAPSED_TIME,
        OBJECTS_ACCESSED,
        DATABASE_NAME,
        SCHEMA_NAME,
        TABLE_NAME
FROM UTIL.SNOWFLAKE_DIRECT_OBJECT_USAGE_VW
UNION ALL
SELECT  QUERY_ID,
        QUERY_START_TIME,
        USER_NAME,
        DISPLAY_NAME,
        QUERY_TYPE,
        QUERY_TEXT,
        WAREHOUSE_NAME,
        ENVIRONMENT_NAME,
        TOTAL_ELAPSED_TIME,
        OBJECTS_ACCESSED,
        DATABASE_NAME,
        SCHEMA_NAME,
        TABLE_NAME
FROM UTIL.SNOWFLAKE_BASE_OBJECT_USAGE_VW;