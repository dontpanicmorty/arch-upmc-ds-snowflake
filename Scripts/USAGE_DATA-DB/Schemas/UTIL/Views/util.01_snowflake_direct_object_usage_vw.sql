CREATE OR REPLACE VIEW UTIL.SNOWFLAKE_DIRECT_OBJECT_USAGE_VW(
	QUERY_ID,
	QUERY_START_TIME,
	USER_NAME,
	DISPLAY_NAME,
	QUERY_TYPE,
	QUERY_TEXT,
	WAREHOUSE_NAME,
	ENVIRONMENT_NAME,
	TOTAL_ELAPSED_TIME,
	OBJECTS_ACCESSED,
	DATABASE_NAME,
	SCHEMA_NAME,
	TABLE_NAME
) as
WITH MAIN AS (
    SELECT  QH.QUERY_ID,
            QH.USER_NAME,
            U.DISPLAY_NAME,
			QH.QUERY_TYPE,
            QH.QUERY_TEXT,
            QH.WAREHOUSE_NAME,
            AH.QUERY_START_TIME,
            QH.TOTAL_ELAPSED_TIME,
			CASE
                WHEN QH.DATABASE_NAME LIKE '%_TST' 
                THEN 'TEST'
                WHEN QH.DATABASE_NAME LIKE '%_DEV'
                THEN 'DEV'
                WHEN QH.DATABASE_NAME LIKE 'DEPT_%'
                THEN 'DEPT'
                WHEN QH.DATABASE_NAME NOT LIKE '%_TST' AND QH.DATABASE_NAME NOT LIKE '%_DEV' AND QH.DATABASE_NAME IS NOT NULL
                THEN 'PROD'
            END AS ENVIRONMENT_NAME,
            QH.DATABASE_NAME,
            LISTAGG(DIRECT.VALUE:objectName::string, ', ') WITHIN GROUP (ORDER BY QH.USER_NAME, QH.QUERY_TEXT, QH.WAREHOUSE_NAME, QH.TOTAL_ELAPSED_TIME) AS DIRECT_ACCESSED_TABLES,
            LISTAGG(BASE.VALUE:objectName::string, ', ') WITHIN GROUP (ORDER BY QH.USER_NAME, QH.QUERY_TEXT, QH.WAREHOUSE_NAME, QH.TOTAL_ELAPSED_TIME) AS BASE_ACCESSED_TABLES
    FROM    SNOWFLAKE.ACCOUNT_USAGE.USERS U
         JOIN
            SNOWFLAKE.ACCOUNT_USAGE.ACCESS_HISTORY AH
         ON AH.USER_NAME = U.NAME
         JOIN
            SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY QH        
         ON QH.QUERY_ID = AH.QUERY_ID,
          LATERAL FLATTEN(INPUT => AH.DIRECT_OBJECTS_ACCESSED) DIRECT,
          LATERAL FLATTEN(INPUT => AH.BASE_OBJECTS_ACCESSED) BASE
    WHERE     QH.START_TIME > (CURRENT_DATE()-60)
    AND       QH.USER_NAME NOT IN ('DWSREPLICATION@UPMC.EDU', 'DSSF_PIPELINES@UPMC.EDU')
    AND       QH.DATABASE_NAME NOT LIKE '%@%'
    AND       QH.DATABASE_NAME NOT LIKE '%LOCAL'
    AND       QH.DATABASE_NAME NOT LIKE '%ARCHIVE%'
    GROUP BY QH.QUERY_ID, QH.USER_NAME, U.DISPLAY_NAME, AH.QUERY_START_TIME, QH.QUERY_TYPE, QH.QUERY_TEXT, QH.DATABASE_NAME, QH.WAREHOUSE_NAME, QH.TOTAL_ELAPSED_TIME
    )
, BYTABLE AS
(
SELECT  DISTINCT
        M1.QUERY_ID,
        M1.QUERY_START_TIME,
        M1.USER_NAME,
        M1.DISPLAY_NAME,
		M1.QUERY_TYPE,
        M1.QUERY_TEXT,
        M1.WAREHOUSE_NAME,
		M1.ENVIRONMENT_NAME,
        M1.TOTAL_ELAPSED_TIME, 
        TB.VALUE::string AS DIRECT_ACCESSED_TABLES
FROM    MAIN M1,
    LATERAL FLATTEN(INPUT => SPLIT(M1.DIRECT_ACCESSED_TABLES, ', ')) TB
)
SELECT
    T.QUERY_ID
    ,T.QUERY_START_TIME
    ,T.USER_NAME
    ,T.DISPLAY_NAME
	,T.QUERY_TYPE
    ,T.QUERY_TEXT
    ,T.WAREHOUSE_NAME
	,T.ENVIRONMENT_NAME
    ,T.TOTAL_ELAPSED_TIME
    ,T.DIRECT_ACCESSED_TABLES AS OBJECTS_ACCESSED
    ,MAX(CASE WHEN TB.INDEX = 0 AND TB.VALUE != '' THEN TB.VALUE::string ELSE NULL END) AS DATABASE_NAME
    ,MAX(CASE WHEN TB.INDEX = 1 THEN TB.VALUE::string ELSE NULL END) AS SCHEMA_NAME
    ,MAX(CASE WHEN TB.INDEX = 2 THEN TB.VALUE::string ELSE NULL END) AS TABLE_NAME
FROM    BYTABLE T
    ,LATERAL FLATTEN (INPUT => SPLIT(T.DIRECT_ACCESSED_TABLES, '.')) TB
GROUP BY
    T.QUERY_ID
    ,T.QUERY_START_TIME
    ,T.USER_NAME
    ,T.DISPLAY_NAME
	,T.QUERY_TYPE
    ,T.QUERY_TEXT
    ,T.WAREHOUSE_NAME
	,T.ENVIRONMENT_NAME
    ,T.TOTAL_ELAPSED_TIME
    ,T.DIRECT_ACCESSED_TABLES
;