CREATE OR REPLACE VIEW UTIL.PC_IDW_SESSION_TASK_LOG_VW
      AS (
SELECT 
    $1:WORKFLOW_ID::TEXT AS WORKFLOW_ID,
    $1:WORKFLOW_RUN_ID::NUMBER AS WORKFLOW_RUN_ID,
    $1:WORKLET_RUN_ID::NUMBER AS WORKLET_RUN_ID,
    $1:INSTANCE_ID::NUMBER AS INSTANCE_ID,
    $1:MAPPING_NAME::TEXT AS MAPPING_NAME,
    $1:LOG_FILE::TEXT AS LOG_FILE,
    $1:SRC_SUCCESS_ROWS::NUMBER AS SOURCE_SUCCESS_ROWS,
    $1:SRC_FAILED_ROWS::NUMBER AS SOURCE_FAILED_ROWS,
    $1:TARG_SUCCESS_ROWS::NUMBER AS TARGET_SUCCESS_ROWS,
    $1:TARG_FAILED_ROWS::NUMBER AS TARGET_FAILED_ROWS,
    $1:TOTAL_TRANS_ERRS::NUMBER AS TOTAL_TRANSFORMATION_ERRORS,
    $1:FIRST_ERROR_CODE::NUMBER AS FIRST_ERROR_CODE,
    $1:FIRST_ERROR_MSG::TEXT AS FIRST_ERROR_MESSAGE,
    $1:CODEPAGE_ID::NUMBER AS CODEPAGE_ID,
    $1:VERSION_NUMBER::NUMBER AS VERSION_NUMBER,
    $1:ERROR_LOG_FILE::TEXT AS ERROR_LOG_FILE
FROM @UTIL.SNOWFLAKEDATA_USAGE_DATA_DB_EXTRACT/logdata/powercenter/idw_sess_task_log/
   (FILE_FORMAT =>  'UTIL.DB_EXTRACT_PARQUET_FILE_FORMAT' )
);