CREATE OR REPLACE VIEW UTIL.DS_ORACLE_EVHRPT_TABLE_USAGE_VW
AS(
SELECT  $1:QUERY_COUNT::REAL as QUERY_COUNT,
        SPLIT_PART($1:OBJECT_NAME::TEXT, '.', 1) as SCHEMA_NAME,
        SPLIT_PART($1:OBJECT_NAME::TEXT, '.', 2) as TABLE_NAME,
        $1:UNIQUE_USER_COUNT::REAL as UNIQUE_USER_COUNT,
        $1:USERS_THAT_QUERIED::TEXT as USERS_THAT_QUERIED,
        METADATA$FILE_LAST_MODIFIED AS LOAD_TIME,
        METADATA$FILENAME AS FILENAME,
FROM    @UTIL.SNOWFLAKEDATA_USAGE_DATA_DB_EXTRACT/logdata/oracle/evhrpt/ds/
        (FILE_FORMAT =>  'UTIL.DB_EXTRACT_PARQUET_FILE_FORMAT' )
order by 1 desc   
)
;