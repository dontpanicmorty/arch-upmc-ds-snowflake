CREATE OR REPLACE VIEW UTIL.PC_IDW_DEPLOY_DETAILS_VW
    AS (
SELECT 
   $1:DEP_RUN_ID::NUMBER AS DEPLOY_RUN_ID,
   $1:OBJECT_ID::NUMBER AS OBJECT_ID,
   $1:OBJECT_NAME::TEXT AS OBJECT_NAME,
   $1:OBJECT_TYPE::NUMBER AS OBJECT_TYPE,
   $1:OBJECT_TYPE_NAME::TEXT AS OBJECT_TYPE_NAME,
   $1:SRC_VERSION_NUMBER::NUMBER AS SOURCE_VERSION_NUMBER,
   $1:TARG_VERSION_NUMBER::NUMBER AS TARGET_VERSION_NUMBER,
   $1:SRC_SUBJECT_ID::NUMBER AS SOURCE_SUBJECT_ID,
   $1:TARG_SUBJECT_ID::NUMBER AS TARGET_SUBJECT_ID,
   $1:SRC_SUBJECT_AREA::TEXT AS SOURCE_SUBJECT_AREA,
   $1:TARG_SUBJECT_AREA::TEXT AS TARGET_SUBJECT_AREA,
   $1:IS_SHORTCUT::NUMBER AS IS_SHORTCUT,
   $1:DEP_GROUP_ID::NUMBER AS DEPLOY_GROUP_ID,
   $1:DEP_GROUP_NAME::TEXT AS DEPLOY_GROUP_NAME,
   $1:DEPLOY_TIME::TEXT AS DEPLOY_TIME,
   $1:DEPLOY_TYPE::NUMBER AS DEPLOY_TYPE,
   $1:TARGET_REP_NAME::TEXT AS TARGET_REPOSITORY_NAME,
   $1:REP_GID::TEXT AS REPOSITORY_GID,
   $1:USER_ID::NUMBER AS USER_ID,
   $1:GROUP_ID::NUMBER AS GROUP_ID,
   $1:USER_NAME::TEXT AS USER_NAME,
   $1:UTC_DEPLOY_TIME::NUMBER AS UTC_DEPLOY_TIME,
   $1:DEPLOY_STATUS::NUMBER AS DEPLOY_STATUS,
   $1:ROLLBACK_TIME::TEXT AS ROLLBACK_TIME
FROM @UTIL.SNOWFLAKEDATA_USAGE_DATA_DB_EXTRACT/logdata/powercenter/idw_deploy_details/
   (FILE_FORMAT =>  'UTIL.DB_EXTRACT_PARQUET_FILE_FORMAT' )
);