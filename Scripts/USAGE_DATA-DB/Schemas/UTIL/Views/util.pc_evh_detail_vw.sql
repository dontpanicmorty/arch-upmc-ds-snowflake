CREATE OR REPLACE VIEW UTIL.PC_EVH_DETAIL_VW(
	FOLDER_NAME,
	WORKFLOW_NAME,
	TASK_NAME,
	CONNECTION_NAME,
	INSTANCE_NAME,
	MAPPING_NAME,
    SOURCE_NAME,
	TARGET_NAME
) AS (
SELECT 
        $1:SUBJECT_AREA::TEXT AS FOLDER_NAME,  
        $1:WORKFLOW_NAME::TEXT AS WORKFLOW_NAME, 
        $1:TASK_NAME::TEXT AS TASK_NAME,  
        $1:CONNECTION_NAME::TEXT AS CONNECTION_NAME, 
        $1:INSTANCE_NAME::TEXT AS INSTANCE_NAME, 
        $1:MAPPING_NAME::TEXT AS MAPPING_NAME, 
        $1:SOURCE_NAME::TEXT AS SOURCE_NAME, 
        $1:TARGET_NAME::TEXT AS TARGET_NAME
from @UTIL.SNOWFLAKEDATA_USAGE_DATA_DB_EXTRACT/logdata/powercenter/evh/ 
(FILE_FORMAT =>  'UTIL.DB_EXTRACT_PARQUET_FILE_FORMAT' )
)
;