CREATE OR REPLACE VIEW UTIL.PC_IDW_DETAIL_VW(
	FOLDER_NAME,
	WORKFLOW_NAME,
    WORKLET_NAME,
	SESSION_NAME,
	MAPPING_NAME,
    SOURCE_NAME,
	TARGET_NAME
) as(
SELECT  $1:FOLDER_NAME::TEXT AS FOLDER_NAME, 
        $1:WORKFLOW_NAME::TEXT AS WORKFLOW_NAME, 
        $1:WORKLET_NAME::TEXT AS WORKLET_NAME, 
        $1:SESSION_NAME::TEXT AS SESSION_NAME, 
        $1:MAPPING_NAME::TEXT as MAPPING_NAME,
        $1:SOURCE_NAME::TEXT AS SOURCE_NAME, 
        $1:TARGET_NAME::TEXT as TARGET_NAME
from @UTIL.SNOWFLAKEDATA_USAGE_DATA_DB_EXTRACT/logdata/powercenter/idw/ 
(FILE_FORMAT =>  'UTIL.DB_EXTRACT_PARQUET_FILE_FORMAT' )
)
;