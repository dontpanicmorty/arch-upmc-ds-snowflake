CREATE OR REPLACE VIEW UTIL.PC_EVH_RUN_TIME_STATS_VW
AS(
SELECT 
        $1:SUBJECT_AREA::VARCHAR AS FOLDER_NAME, 
        $1:WORKFLOW_RUN_ID::VARCHAR AS WORKFLOW_RUN_ID,
        $1:WORKFLOW_NAME::VARCHAR AS WORKFLOW_NAME,
        $1:START_TIME::TIMESTAMP_NTZ AS START_TIME,
        $1:END_TIME::TIMESTAMP_NTZ AS END_TIME
from @UTIL.SNOWFLAKEDATA_USAGE_DATA_DB_EXTRACT/logdata/powercenter/evhruntime/
(FILE_FORMAT =>  'UTIL.DB_EXTRACT_PARQUET_FILE_FORMAT' )
);