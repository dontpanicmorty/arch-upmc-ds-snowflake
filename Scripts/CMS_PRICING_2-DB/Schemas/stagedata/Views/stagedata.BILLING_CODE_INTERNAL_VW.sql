-- Meant to map structures in RAWDATA/IDAP_LAKE
!set variable_substitution=true;

CREATE OR REPLACE VIEW STAGEDATA.BILLING_CODE_INTERNAL_VW
AS
SELECT BILLING_CODE_LKP.BILLING_CODE,
    BILLING_CODE_LKP.BILLING_CODE_TYPE AS BILLING_CODE_TYPE_NAME, 
    BILLING_CODE_TYPE.BILLING_CODE_TYPE_VERSION AS BILLING_CODE_TYPE_VERSION_TEXT, 
    BILLING_CODE_LKP.DESCRIPTION AS BILLING_CODE_DESC,
    BILLING_CODE_LKP.NAME AS SERVICE_NAME, -- on in_network_base 
    BILLING_CODE_TYPE.START_DATE AS START_DATE,
    BILLING_CODE_TYPE.END_DATE AS END_DATE
FROM &{IDAP_LAKE}.PRICING.BILLING_CODE_LKP
INNER JOIN &{IDAP_LAKE}.PRICING.BILLING_CODE_TYPE
    ON BILLING_CODE_LKP.BILLING_CODE_TYPE = BILLING_CODE_TYPE.BILLING_CODE_TYPE
;

!set variable_substitution=false;