!set variable_substitution=true;

CREATE OR REPLACE VIEW STAGEDATA.PRICING_PLAN_SELECT_VW
AS
-- Actually the simplest thing here
SELECT DISTINCT 
  3 AS REPORTING_ENTITY_KEY, -- from StaticData, UPMC value
  PLAN_NAME, 
  PLAN_ID_TYPE, 
  PLAN_ID, 
  MARKET_TYPE AS PLAN_MARKET_TYPE_NAME,
  IFF(
        PLAN_NAME IS NOT NULL
        AND REGEXP_INSTR(PLAN_NAME, '\\s-\\s') > 0,
        TRIM(SPLIT_PART(PLAN_NAME, ' - ',1)),
        NULL
    ) AS PLAN_SPONSOR_NAME,
    IFF( 
        PLAN_NAME IS NOT NULL 
        AND REGEXP_INSTR(PLAN_NAME, '\\s-\\s') > 0,
        TRIM(SUBSTR(PLAN_NAME, LENGTH(SPLIT_PART(PLAN_NAME, ' - ', 1)) + 4)),
        TRIM(PLAN_NAME) 
    )   AS SPECIFIC_PLAN_NAME,
    COALESCE(l1.LEGAL_ENTITY, l2.LEGAL_ENTITY, 
      IFF(PLAN_NAME IS NOT NULL AND REGEXP_INSTR(PLAN_NAME, '\\s-\\s') > 0,
      REPLACE(INITCAP(TRIM(SPLIT_PART(PLAN_NAME, ' - ',1))), 'Upmc', 'UPMC'), NULL)
    ) AS ISSUER_NAME
FROM &{IDAP_LAKE}.PRICING.PLAN_INFO PLAN_INFO
LEFT JOIN &{CMS_PRICING}.STAGEDATA.LEGAL_ENTITY l1
       ON PLAN_INFO.PLAN_ID_TYPE = 'HIOS'
      AND SUBSTR(PLAN_INFO.PLAN_ID, 1, 5) = l1.ISSUER_HIOS_ID
LEFT JOIN &{CMS_PRICING}.STAGEDATA.LEGAL_ENTITY l2
       ON PLAN_INFO.PLAN_ID_TYPE = 'EIN'
      AND PLAN_INFO.PLAN_ID = REPLACE(l2.TIN_FEIN, '-', '');
;

!set variable_substitution=false;