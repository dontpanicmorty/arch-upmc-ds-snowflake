CREATE OR REPLACE VIEW STAGEDATA.PAYMENT_PROVIDERS_SELECT_VW
AS
SELECT PAYMENTS_KEY,
    CHARGE_AMT AS BILLED_CHARGE_AMT,
    ARRAY_AGG(DISTINCT NPI) WITHIN GROUP (ORDER BY NPI ASC) AS NPI_NBRS
FROM (
    -- Yeah. We basically need to pull out anything we could possibly need,
    -- pre-formatted, then zip ALL the way back down to get the PAYMENTS_KEY.
    -- This'll get simplified once we're not pulling from a single table.
    SELECT CHARGE_AMT,
      NPI,
      TAX_ID,
      BILLING_CODE,
      ALLOW_AMT,
      OUT_OF_NETWORK_FILE_DESC,
      ARRAY_AGG(DISTINCT PLACE_OF_SERVICE_CODE) WITHIN GROUP (ORDER BY PLACE_OF_SERVICE_CODE ASC) AS PLACE_OF_SERVICE_CODES,
      CASE WHEN LEN(TRIM(BILLING_CODE_MODIFIER)) > 0 
        THEN ARRAY_AGG(DISTINCT BILLING_CODE_MODIFIER) WITHIN GROUP (ORDER BY BILLING_CODE_MODIFIER ASC)
        ELSE ARRAY_CONSTRUCT() 
      END AS BILLING_CODE_MODIFIERS
    FROM STAGEDATA.OUT_OF_NETWORK_CLAIMS_THRESHOLD_VW
    GROUP BY CHARGE_AMT, ALLOW_AMT, BILLING_CODE_MODIFIER, BILLING_CODE, TAX_ID, NPI, OUT_OF_NETWORK_FILE_DESC
) OUT_OF_NETWORK_CLAIMS_THRESHOLD_VW 

INNER JOIN EXTRACTDATA.BILLING_CODE ON
    BILLING_CODE.BILLING_CODE = OUT_OF_NETWORK_CLAIMS_THRESHOLD_VW.BILLING_CODE

INNER JOIN EXTRACTDATA.PRICING_FILE ON
  PRICING_FILE.FILE_DESC = OUT_OF_NETWORK_FILE_DESC

INNER JOIN EXTRACTDATA.OUT_OF_NETWORK_BASE ON 
  OUT_OF_NETWORK_BASE.PRICING_FILE_KEY = PRICING_FILE.PRICING_FILE_KEY
  -- service_name join is a dupe, not needed
  AND OUT_OF_NETWORK_BASE.BILLING_CODE_KEY = BILLING_CODE.BILLING_CODE_KEY
  
INNER JOIN EXTRACTDATA.ALLOWED_AMOUNTS ON 
  ALLOWED_AMOUNTS.OUT_OF_NETWORK_BASE_KEY = OUT_OF_NETWORK_BASE.OUT_OF_NETWORK_BASE_KEY
  AND TAX_ID_NBR = OUT_OF_NETWORK_CLAIMS_THRESHOLD_VW.TAX_ID
  AND TAX_ID_TYPE_CODE = 'ein' 
  AND BILLING_CLASS_NAME = 'professional' -- TODO
  AND ALLOWED_AMOUNTS.PLACE_OF_SERVICE_CODES = OUT_OF_NETWORK_CLAIMS_THRESHOLD_VW.PLACE_OF_SERVICE_CODES

INNER JOIN EXTRACTDATA.PAYMENTS ON
    PAYMENTS.ALLOWED_AMOUNTS_KEY = ALLOWED_AMOUNTS.ALLOWED_AMOUNTS_KEY
    AND ALLOWED_AMT = ALLOW_AMT
    AND PAYMENTS.BILLING_CODE_MODIFIERS = OUT_OF_NETWORK_CLAIMS_THRESHOLD_VW.BILLING_CODE_MODIFIERS
  
GROUP BY TAX_ID, ALLOW_AMT, OUT_OF_NETWORK_CLAIMS_THRESHOLD_VW.PLACE_OF_SERVICE_CODES, BILLING_CODE.BILLING_CODE, OUT_OF_NETWORK_CLAIMS_THRESHOLD_VW.BILLING_CODE_MODIFIERS, CHARGE_AMT, PAYMENTS_KEY
;