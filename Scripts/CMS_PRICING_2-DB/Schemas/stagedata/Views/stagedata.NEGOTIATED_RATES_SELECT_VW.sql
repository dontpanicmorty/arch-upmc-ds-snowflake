CREATE OR REPLACE VIEW STAGEDATA.NEGOTIATED_RATES_SELECT_VW
AS
-- For practitioner: get all negotiated_price_key objects, prov_set/provider_type,
-- then join out to in_network_base_key
WITH PRACTITIONER_NEGOTIATED_PRICE_LKP AS (
    SELECT NEGOTIATED_PRICE_INTERNAL_HOLD.SEGMENT,
      NEGOTIATED_PRICE_INTERNAL_HOLD.SCHEDULE_DETAIL,
      NEGOTIATED_PRICE_INTERNAL_HOLD.SCHEDULE_TYPE,
      NEGOTIATED_PRICE.NEGOTIATED_PRICE_KEY,
      NEGOTIATED_PRICE_INTERNAL_HOLD.PROV_SET,
      NEGOTIATED_PRICE_INTERNAL_HOLD.PROVIDER_TYPE,
      NEGOTIATED_PRICE_INTERNAL_HOLD.STATE,
      NEGOTIATED_PRICE_INTERNAL_HOLD.MATCH_STATE,
      IN_NETWORK_BASE_KEY
    FROM (
        SELECT *
        FROM STAGEDATA.NEGOTIATED_PRICE_INTERNAL_HOLD
        WHERE SOURCE_TYPE = 'practitioner'
    ) NEGOTIATED_PRICE_INTERNAL_HOLD

    INNER JOIN EXTRACTDATA.NEGOTIATED_PRICE ON
      NEGOTIATED_PRICE.NEGOTIATED_TYPE_NAME = NEGOTIATED_PRICE_INTERNAL_HOLD.NEGOTIATED_TYPE_NAME
      AND NEGOTIATED_PRICE.NEGOTIATED_RATE_AMT = NEGOTIATED_PRICE_INTERNAL_HOLD.NEGOTIATED_RATE_AMT
      AND NEGOTIATED_PRICE.EXPIRATION_DATE = NEGOTIATED_PRICE_INTERNAL_HOLD.EXPIRATION_DATE
      AND NEGOTIATED_PRICE.PLACE_OF_SERVICE_CODES = NEGOTIATED_PRICE_INTERNAL_HOLD.PLACE_OF_SERVICE_CODES
      AND NEGOTIATED_PRICE.BILLING_CLASS_NAME = NEGOTIATED_PRICE_INTERNAL_HOLD.BILLING_CLASS_NAME
      AND NEGOTIATED_PRICE.BILLING_CODE_MODIFIERS = NEGOTIATED_PRICE_INTERNAL_HOLD.BILLING_CODE_MODIFIERS

    INNER JOIN STAGEDATA.FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW ON
      NEGOTIATED_PRICE_INTERNAL_HOLD.PROV_SET = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROV_SET
      AND NEGOTIATED_PRICE_INTERNAL_HOLD.PROVIDER_TYPE = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROVIDER_TYPE
      AND NEGOTIATED_PRICE_INTERNAL_HOLD.SEGMENT = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SEGMENT
      AND NEGOTIATED_PRICE_INTERNAL_HOLD.SCHEDULE_TYPE = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SCHEDULE_TYPE
      AND NEGOTIATED_PRICE_INTERNAL_HOLD.SCHEDULE_DETAIL = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SCHEDULE_DETAIL

    INNER JOIN EXTRACTDATA.PRICING_FILE ON
      PRICING_FILE.FILE_DESC = STAGEDATA.FXN_MAKE_IN_NETWORK_FILE_DESC(
        NEGOTIATED_PRICE_INTERNAL_HOLD.SEGMENT, 
        FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROV_SET
      )

    INNER JOIN STAGEDATA.IN_NETWORK_BASE_SELECT_VW ON 
        NEGOTIATED_PRICE_INTERNAL_HOLD.BILLING_CODE = IN_NETWORK_BASE_SELECT_VW.BILLING_CODE
        AND PRICING_FILE.PRICING_FILE_KEY = IN_NETWORK_BASE_SELECT_VW.PRICING_FILE_KEY

    INNER JOIN EXTRACTDATA.IN_NETWORK_BASE ON -- for the key
      IN_NETWORK_BASE.PRICING_FILE_KEY = IN_NETWORK_BASE_SELECT_VW.PRICING_FILE_KEY
      AND IN_NETWORK_BASE.NEGOTIATION_ARRANGEMENT_NAME = IN_NETWORK_BASE_SELECT_VW.NEGOTIATION_ARRANGEMENT_NAME
      AND IN_NETWORK_BASE.SERVICE_NAME = IN_NETWORK_BASE_SELECT_VW.SERVICE_NAME
      AND IN_NETWORK_BASE.BILLING_CODE_KEY = IN_NETWORK_BASE_SELECT_VW.BILLING_CODE_KEY
),
-- For practitioner: all provider_group links with price_key/prov_set/provider_type
-- as joins
PRACTITIONER_PROVIDER_LKP AS (
  SELECT SEGMENT,
    SCHEDULE_DETAIL,
    SCHEDULE_TYPE,
    NEGOTIATED_PRICE_KEY,
    PROV_SET,
    PROVIDER_TYPE,
    STATE,
    MATCH_STATE,
    PRICING_PROVIDER_GROUP_KEY
  FROM STAGEDATA.PRICING_PROVIDER_GROUP_INTERNAL_VW
  INNER JOIN EXTRACTDATA.PRICING_PROVIDER_GROUP ON
      EXTRACTDATA.PRICING_PROVIDER_GROUP.PRICING_PROVIDER_SET_KEYS = PRICING_PROVIDER_GROUP_INTERNAL_VW.PRICING_PROVIDER_SET_KEYS
  WHERE SOURCE_TYPE = 'practitioner'
),
-- For inpatient: get all negotiated_price_key objects, vendor,
-- then join out to in_network_base_key
INPATIENT_NEGOTIATED_PRICE_LKP AS (
  SELECT NEGOTIATED_PRICE_INTERNAL_HOLD.SEGMENT,
    NEGOTIATED_PRICE.NEGOTIATED_PRICE_KEY,
    NEGOTIATED_PRICE_INTERNAL_HOLD.VENDOR,
    NEGOTIATED_PRICE_INTERNAL_HOLD.BILLING_CODE,
    IN_NETWORK_BASE_KEY
  FROM (
      SELECT *
      FROM STAGEDATA.NEGOTIATED_PRICE_INTERNAL_HOLD
      WHERE SOURCE_TYPE = 'inpatient'
  ) NEGOTIATED_PRICE_INTERNAL_HOLD

  INNER JOIN EXTRACTDATA.NEGOTIATED_PRICE ON
    NEGOTIATED_PRICE.NEGOTIATED_TYPE_NAME = NEGOTIATED_PRICE_INTERNAL_HOLD.NEGOTIATED_TYPE_NAME
    AND NEGOTIATED_PRICE.NEGOTIATED_RATE_AMT = NEGOTIATED_PRICE_INTERNAL_HOLD.NEGOTIATED_RATE_AMT
    AND NEGOTIATED_PRICE.EXPIRATION_DATE = NEGOTIATED_PRICE_INTERNAL_HOLD.EXPIRATION_DATE
    AND NEGOTIATED_PRICE.PLACE_OF_SERVICE_CODES = NEGOTIATED_PRICE_INTERNAL_HOLD.PLACE_OF_SERVICE_CODES
    AND NEGOTIATED_PRICE.BILLING_CLASS_NAME = NEGOTIATED_PRICE_INTERNAL_HOLD.BILLING_CLASS_NAME
    AND NEGOTIATED_PRICE.BILLING_CODE_MODIFIERS = NEGOTIATED_PRICE_INTERNAL_HOLD.BILLING_CODE_MODIFIERS

  INNER JOIN STAGEDATA.FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW ON
    NEGOTIATED_PRICE_INTERNAL_HOLD.PROV_SET = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROV_SET
    AND NEGOTIATED_PRICE_INTERNAL_HOLD.PROVIDER_TYPE = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROVIDER_TYPE
    AND NEGOTIATED_PRICE_INTERNAL_HOLD.SEGMENT = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SEGMENT
    AND NEGOTIATED_PRICE_INTERNAL_HOLD.SCHEDULE_TYPE = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SCHEDULE_TYPE
    AND NEGOTIATED_PRICE_INTERNAL_HOLD.SCHEDULE_DETAIL = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SCHEDULE_DETAIL

  INNER JOIN EXTRACTDATA.PRICING_FILE ON
    PRICING_FILE.FILE_DESC = STAGEDATA.FXN_MAKE_IN_NETWORK_FILE_DESC(
      NEGOTIATED_PRICE_INTERNAL_HOLD.SEGMENT, 
      FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROV_SET
    )

  INNER JOIN STAGEDATA.IN_NETWORK_BASE_SELECT_VW ON 
      NEGOTIATED_PRICE_INTERNAL_HOLD.BILLING_CODE = IN_NETWORK_BASE_SELECT_VW.BILLING_CODE
      AND PRICING_FILE.PRICING_FILE_KEY = IN_NETWORK_BASE_SELECT_VW.PRICING_FILE_KEY

  INNER JOIN EXTRACTDATA.IN_NETWORK_BASE ON -- for the key
    IN_NETWORK_BASE.PRICING_FILE_KEY = IN_NETWORK_BASE_SELECT_VW.PRICING_FILE_KEY
    AND IN_NETWORK_BASE.NEGOTIATION_ARRANGEMENT_NAME = IN_NETWORK_BASE_SELECT_VW.NEGOTIATION_ARRANGEMENT_NAME
    AND IN_NETWORK_BASE.SERVICE_NAME = IN_NETWORK_BASE_SELECT_VW.SERVICE_NAME
    AND IN_NETWORK_BASE.BILLING_CODE_KEY = IN_NETWORK_BASE_SELECT_VW.BILLING_CODE_KEY
),

-- For inpatient: all provider_group links with price_key/vendor as joins
INPATIENT_PROVIDER_LKP AS (
  SELECT SEGMENT,
    NEGOTIATED_PRICE_KEY,
    VENDORS,
    BILLING_CODE,
    PRICING_PROVIDER_GROUP_KEY
  FROM STAGEDATA.PRICING_PROVIDER_GROUP_INTERNAL_VW
  INNER JOIN EXTRACTDATA.PRICING_PROVIDER_GROUP ON
      EXTRACTDATA.PRICING_PROVIDER_GROUP.PRICING_PROVIDER_SET_KEYS = PRICING_PROVIDER_GROUP_INTERNAL_VW.PRICING_PROVIDER_SET_KEYS
  WHERE SOURCE_TYPE = 'inpatient'
)

-- Do the joins from above, reduce to in_network_base_key/price_key/group_key, union
SELECT DISTINCT IN_NETWORK_BASE_KEY, 
  PRACTITIONER_PROVIDER_LKP.NEGOTIATED_PRICE_KEY, 
  PRICING_PROVIDER_GROUP_KEY
FROM PRACTITIONER_NEGOTIATED_PRICE_LKP
INNER JOIN PRACTITIONER_PROVIDER_LKP ON 
  PRACTITIONER_PROVIDER_LKP.NEGOTIATED_PRICE_KEY = PRACTITIONER_NEGOTIATED_PRICE_LKP.NEGOTIATED_PRICE_KEY
  AND PRACTITIONER_PROVIDER_LKP.PROV_SET = PRACTITIONER_NEGOTIATED_PRICE_LKP.PROV_SET
  AND PRACTITIONER_PROVIDER_LKP.PROVIDER_TYPE = PRACTITIONER_NEGOTIATED_PRICE_LKP.PROVIDER_TYPE
  AND PRACTITIONER_PROVIDER_LKP.SEGMENT = PRACTITIONER_NEGOTIATED_PRICE_LKP.SEGMENT
  AND PRACTITIONER_PROVIDER_LKP.SCHEDULE_DETAIL = PRACTITIONER_NEGOTIATED_PRICE_LKP.SCHEDULE_DETAIL
  AND PRACTITIONER_PROVIDER_LKP.SCHEDULE_TYPE = PRACTITIONER_NEGOTIATED_PRICE_LKP.SCHEDULE_TYPE
  AND PRACTITIONER_PROVIDER_LKP.MATCH_STATE = PRACTITIONER_NEGOTIATED_PRICE_LKP.MATCH_STATE
  AND CASE WHEN PRACTITIONER_PROVIDER_LKP.MATCH_STATE = 'Y'
    THEN PRACTITIONER_PROVIDER_LKP.STATE = PRACTITIONER_NEGOTIATED_PRICE_LKP.STATE
    ELSE 1
    END

UNION 

SELECT DISTINCT IN_NETWORK_BASE_KEY, 
  INPATIENT_PROVIDER_LKP.NEGOTIATED_PRICE_KEY, 
  PRICING_PROVIDER_GROUP_KEY
FROM INPATIENT_NEGOTIATED_PRICE_LKP
INNER JOIN INPATIENT_PROVIDER_LKP ON 
  INPATIENT_PROVIDER_LKP.NEGOTIATED_PRICE_KEY = INPATIENT_NEGOTIATED_PRICE_LKP.NEGOTIATED_PRICE_KEY
  AND INPATIENT_PROVIDER_LKP.SEGMENT = INPATIENT_NEGOTIATED_PRICE_LKP.SEGMENT
  AND INPATIENT_PROVIDER_LKP.BILLING_CODE = INPATIENT_NEGOTIATED_PRICE_LKP.BILLING_CODE
  AND ARRAY_CONTAINS(INPATIENT_NEGOTIATED_PRICE_LKP.VENDOR::variant, INPATIENT_PROVIDER_LKP.VENDORS)
;