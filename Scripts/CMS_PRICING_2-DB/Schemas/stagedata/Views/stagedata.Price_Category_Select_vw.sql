--GATHERS DATA NEEDED FROM CONTRACTS TABLE
CREATE OR REPLACE VIEW STAGEDATA.PRICE_CATEGORY_SELECT_VW
AS
(
SELECT DISTINCT PRICECATEGORY AS PRICE_CATEGORY_NAME FROM RAWDATA.DWOAO_PRICECATEGORYPROCEDURE
    UNION
    SELECT DISTINCT PRICECATEGORY FROM RAWDATA.DWOAO_PRICINGHISTPRICECATG
    UNION
    SELECT DISTINCT PRICECATEGORY FROM RAWDATA.DWOAO_PROVIDERTYPESCHEDULE
    UNION
    SELECT DISTINCT PRICECATEGORY FROM RAWDATA.DWOAO_PERDIEMPRICECATEGORY
    UNION
    SELECT DISTINCT PRICECATEGORY FROM RAWDATA.DWOAO_PROVIDERPRICINGHISTORY
);