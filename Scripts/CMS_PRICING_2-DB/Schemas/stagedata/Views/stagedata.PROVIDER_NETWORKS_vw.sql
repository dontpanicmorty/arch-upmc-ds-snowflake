--TIN Replacement Logic is 2 part: 
--1. If the TIN for the Group is ALSO a SSN for a Provider in Cactus, then we replace the TIN with the NPI for that Cactus Provider ID. This works because the Group level provider and Practitioner LEvel Provider will be the same 'person', and thats why they share a TIN/SSN
--2. If the Group has fewer than 5 Providers affiliated, according to oao and cactus, we replace the Groups TIN with the Groups NPI. 
        --To do this I count up how many affiliated Providers they have according to OAO and Cactus, and then compare to OAO first. 
        --If they have < 5 in OAO, and they are a valid Provider in Cactus that does NOT show more than 5, I treat them as a small Group and replace the TIN.
        --If they have < 5 in OAO and we have no record of them in Cactus, then I treat them as small.
        --If they have < 5 in OAO but appear in Cactus and have more than 5 there, we do NOT replace the TIN.

--Revised 8/2/2024 based on new standards set by the business.  NPI pulls and main data source now comes from Provider ODS as source.  Removal of small group logic as well.

CREATE OR REPLACE VIEW STAGEDATA.PROVIDER_NETWORKS_VW
AS
(
WITH

PROVIDER_GROUP_BASE AS (
SELECT
ODSDATA_PROVIDER.PROVIDER_KEY,
ODSDATA_PRACTITIONER.FULL_NAME,
ODSDATA_MEDICAL_GROUP.MEDICAL_GROUP_KEY
FROM RAWDATA.ODSDATA_PROVIDER
    JOIN RAWDATA.ODSDATA_DATA_SOURCE
        ON ODSDATA_PROVIDER.DATA_SOURCE_KEY = ODSDATA_DATA_SOURCE.DATA_SOURCE_KEY
        AND ODSDATA_DATA_SOURCE.DATA_SOURCE_NAME = 'Cactus'
	JOIN RAWDATA.ODSDATA_PRACTITIONER
		ON ODSDATA_PROVIDER.PROVIDER_KEY = ODSDATA_PRACTITIONER.PRACTITIONER_KEY
	JOIN RAWDATA.ODSDATA_PROVIDER_ADDRESS_REL
		ON ODSDATA_PROVIDER.PROVIDER_KEY = ODSDATA_PROVIDER_ADDRESS_REL.PROVIDER_KEY
	JOIN RAWDATA.ODSDATA_MEDICAL_GROUP
		ON ODSDATA_PROVIDER_ADDRESS_REL.OWNING_MEDICAL_GROUP_KEY = ODSDATA_MEDICAL_GROUP.MEDICAL_GROUP_KEY
),

PROVIDER_GROUP_DETAIL AS (
SELECT
PROVIDER_GROUP_BASE.PROVIDER_KEY,
PROVIDER_GROUP_BASE.FULL_NAME,
PROVIDER_GROUP_BASE.MEDICAL_GROUP_KEY,
ODSDATA_MEDICAL_GROUP.MEDICAL_GROUP_NAME,
ODSDATA_PROVIDER.SOURCE_PROVIDER_NBR as GROUP_VENDOR_ID,
ODSDATA_MEDICAL_GROUP.TIN_NBR,
ODSDATA_PROVIDER.ACTIVE_IND,
ODSDATA_DATA_SOURCE.DATA_SOURCE_NAME
FROM PROVIDER_GROUP_BASE
	JOIN RAWDATA.ODSDATA_PROVIDER
		ON ODSDATA_PROVIDER.PROVIDER_KEY = PROVIDER_GROUP_BASE.MEDICAL_GROUP_KEY
	JOIN RAWDATA.ODSDATA_DATA_SOURCE
		ON ODSDATA_PROVIDER.DATA_SOURCE_KEY = ODSDATA_DATA_SOURCE.DATA_SOURCE_KEY
		AND ODSDATA_DATA_SOURCE.DATA_SOURCE_NAME = 'Cactus'
    JOIN RAWDATA.ODSDATA_MEDICAL_GROUP
        ON ODSDATA_PROVIDER.PROVIDER_KEY = ODSDATA_MEDICAL_GROUP.MEDICAL_GROUP_KEY
),

ODS_BASE AS (
SELECT DISTINCT
PROVIDER_GROUP_DETAIL.PROVIDER_KEY,
PROVIDER_GROUP_DETAIL.FULL_NAME,
ODSDATA_PRACTITIONER.SOCIAL_SECURITY_NBR,
ODSDATA_PROVIDER.SOURCE_PROVIDER_NBR AS PROVIDER_VENDOR_ID,
ODSDATA_PROVIDER_LICENSE_REL.LICENSE_NBR AS NPI,
ODSDATA_PROVIDER.ACTIVE_IND AS IND_PROV_ACTIVE_IND,
ODSDATA_DATA_SOURCE.DATA_SOURCE_NAME AS IND_PROV_DATA_SOURCE_NAME,
PROVIDER_GROUP_DETAIL.MEDICAL_GROUP_KEY,
PROVIDER_GROUP_DETAIL.MEDICAL_GROUP_NAME,
PROVIDER_GROUP_DETAIL.GROUP_VENDOR_ID,
INSERT(LPAD(PROVIDER_GROUP_DETAIL.GROUP_VENDOR_ID, 6, 0),1,1,'V') AS VENDOR_ID,
PROVIDER_GROUP_DETAIL.TIN_NBR,
PROVIDER_GROUP_DETAIL.ACTIVE_IND,
PROVIDER_GROUP_DETAIL.DATA_SOURCE_NAME
FROM PROVIDER_GROUP_DETAIL
	JOIN RAWDATA.ODSDATA_PROVIDER
		ON ODSDATA_PROVIDER.PROVIDER_KEY = PROVIDER_GROUP_DETAIL.PROVIDER_KEY
	JOIN RAWDATA.ODSDATA_DATA_SOURCE
		ON ODSDATA_PROVIDER.DATA_SOURCE_KEY = ODSDATA_DATA_SOURCE.DATA_SOURCE_KEY
		AND ODSDATA_DATA_SOURCE.DATA_SOURCE_NAME = 'Cactus'
	JOIN RAWDATA.ODSDATA_PRACTITIONER
		ON ODSDATA_PROVIDER.PROVIDER_KEY = ODSDATA_PRACTITIONER.PRACTITIONER_KEY
	JOIN RAWDATA.ODSDATA_PROVIDER_LICENSE_REL
		ON ODSDATA_PROVIDER.PROVIDER_KEY = ODSDATA_PROVIDER_LICENSE_REL.PROVIDER_KEY
    JOIN RAWDATA.ODSDATA_LICENSE_TYPE
        ON ODSDATA_PROVIDER_LICENSE_REL.LICENSE_TYPE_KEY = ODSDATA_LICENSE_TYPE.LICENSE_TYPE_KEY
		AND ODSDATA_LICENSE_TYPE.LICENSE_TYPE_DESC = 'National Provider Identifier'
    JOIN RAWDATA.ODSDATA_LICENSE_STATUS
        ON ODSDATA_PROVIDER_LICENSE_REL.LICENSE_STATUS_KEY = ODSDATA_LICENSE_STATUS.LICENSE_STATUS_KEY
		and ODSDATA_LICENSE_STATUS.LICENSE_STATUS_DESC = 'Active'
WHERE PROVIDER_GROUP_DETAIL.ACTIVE_IND = 'Y'
),

OAO_BILLING_ODS_RENDER as(
SELECT DISTINCT 
MRF_CONTRACTS_VW.PROVIDER_NBR as VENDOR_ID
,DWOAO_PROVIDERS.ALTERNATEPROVIDERNO AS GROUP_TIN
,MRF_CONTRACTS_VW.PLAN_TYPE
,MRF_CONTRACTS_VW.PROVIDER_IPA_CODE
,MRF_CONTRACTS_VW.GROUP_CARRIER
,MRF_CONTRACTS_VW.PROVIDER_NBR AS  PROVIDER_ID
,MRF_CONTRACTS_VW.RENDERING_PROV_AFFILIATION AS RENDERING_PROVIDER_NBR
,MRF_CONTRACTS_VW.PROVIDER_TYPE --billing provider type
,COALESCE(DWOAO_PROVIDERSUBPART.PROVIDERSUBPART,'UNKNOWN') AS NPI --group npi. bottom of union will have the rendering-level npi
,'GROUP' as NPI_TYPE
,DWOAO_PROVIDERS.NATIONALPROVIDERNBR AS MASK1
,ARRAY_CONTAINS('INST-TAXID'::VARIANT,(ARRAY_AGG(DISTINCT PROVIDER_TYPE) OVER (PARTITION BY DWOAO_PROVIDERS.ALTERNATEPROVIDERNO, MRF_CONTRACTS_VW.PROVIDER_NBR))) INST_TAXID_BOOL
FROM STAGEDATA.MRF_CONTRACTS_VW
    LEFT JOIN RAWDATA.DWOAO_PROVIDERSUBPART --get all npis for the group
        ON DWOAO_PROVIDERSUBPART.PROVIDERNUMBER = MRF_CONTRACTS_VW.PROVIDER_NBR
    JOIN RAWDATA.DWOAO_PROVIDERS --used to get the TaxId from AlternateProviderNo. From Askey on 6/8
        ON MRF_CONTRACTS_VW.PROVIDER_NBR = DWOAO_PROVIDERS.PROVIDERNBR
WHERE (MRF_CONTRACTS_VW.PROVIDER_NBR LIKE 'V%' AND LENGTH(MRF_CONTRACTS_VW.PROVIDER_NBR) = 6)
  AND ALTERNATEPROVIDERNO NOT IN ('777777777','999999999','AAAAAAAAA','NONE','FOREIGN','XXXXXXXXX')  
  
UNION ALL

     --billing TIN and the Rendering Provider NPI's directly associated with that TIN, and provider_type. 
SELECT DISTINCT 
MRF_CONTRACTS_VW.PROVIDER_NBR as VENDOR_ID
,ODS_BASE.TIN_NBR AS GROUP_TIN
,MRF_CONTRACTS_VW.PLAN_TYPE
,MRF_CONTRACTS_VW.PROVIDER_IPA_CODE
,MRF_CONTRACTS_VW.GROUP_CARRIER
,MRF_CONTRACTS_VW.RENDERING_PROV_AFFILIATION
,MRF_CONTRACTS_VW.RENDERING_PROV_AFFILIATION as RENDERING_PROVIDER_NBR
,MRF_CONTRACTS_VW.RENDERINGPROVAFFILIATION_PROVIDERTYPE as PROVIDER_TYPE --rendering providers type
,ODS_BASE.NPI AS RENDERING_PROV_NPI --rendering NPI, as opposed to the billing npi up top
,'PROVIDER' as NPI_TYPE
,DWOAO_PROVIDERS.NATIONALPROVIDERNBR AS MASK1
,ARRAY_CONTAINS('INST-TAXID'::VARIANT,(ARRAY_AGG(DISTINCT PROVIDER_TYPE) OVER (PARTITION BY ODS_BASE.TIN_NBR, MRF_CONTRACTS_VW.PROVIDER_NBR))) INST_TAXID_BOOL
FROM STAGEDATA.MRF_CONTRACTS_VW
    INNER JOIN ODS_BASE  
        ON MRF_CONTRACTS_VW.RENDERING_PROV_AFFILIATION = ODS_BASE.PROVIDER_VENDOR_ID
        AND MRF_CONTRACTS_VW.PROVIDER_NBR = ODS_BASE.VENDOR_ID
        --AND ODS_BASE.ACTIVE_IND = 'Y'
    INNER JOIN RAWDATA.DWOAO_PROVIDERS --used to get the TaxId from AlternateProviderNo. From Askey on 6/8
        ON MRF_CONTRACTS_VW.PROVIDER_NBR = DWOAO_PROVIDERS.PROVIDERNBR
WHERE (MRF_CONTRACTS_VW.PROVIDER_NBR like 'V%' AND LENGTH(MRF_CONTRACTS_VW.PROVIDER_NBR) = 6)
   AND ODS_BASE.TIN_NBR NOT IN ('777777777','999999999','AAAAAAAAA','NONE','FOREIGN','XXXXXXXXX')  
)
  
SELECT DISTINCT
OAO_BILLING_ODS_RENDER.VENDOR_ID
,OAO_BILLING_ODS_RENDER.GROUP_TIN
,CACTUS_PROVIDERS.SSN
,CASE WHEN CACTUS_PROVIDERS.SSN IS NOT NULL AND TYPECHECK1.GROUP_TIN IS NULL THEN '1'ELSE '0' END AS SSN_EXISTS
,CASE WHEN CACTUS_PROVIDERS.SSN IS NOT NULL AND TYPECHECK.GROUP_TIN IS NULL THEN NVL(OAO_BILLING_ODS_RENDER.MASK1,OAO_BILLING_ODS_RENDER.NPI)
    ELSE OAO_BILLING_ODS_RENDER.GROUP_TIN END AS DERIVED_TAXID
,CASE WHEN CACTUS_PROVIDERS.SSN IS NOT NULL AND TYPECHECK.GROUP_TIN IS NULL THEN 'npi' ELSE 'ein' END AS TAXID_TYPE
,OAO_BILLING_ODS_RENDER.PROVIDER_TYPE
,OAO_BILLING_ODS_RENDER.NPI
,LOWER(OAO_BILLING_ODS_RENDER.NPI_TYPE) as NPI_TYPE
,PRICING_NETWORK.PRICING_NETWORK_NAME
FROM OAO_BILLING_ODS_RENDER
    LEFT JOIN RAWDATA.CACTUS_PROVIDERS 
        ON CACTUS_PROVIDERS.SSN = OAO_BILLING_ODS_RENDER.GROUP_TIN
    JOIN STAGEDATA.PRICING_NETWORK_CROSSWALK 
        ON OAO_BILLING_ODS_RENDER.PLAN_TYPE = PRICING_NETWORK_CROSSWALK.PLAN_TYPE
        AND OAO_BILLING_ODS_RENDER.PROVIDER_IPA_CODE = PRICING_NETWORK_CROSSWALK.IPA_CODE
    JOIN STAGEDATA.PRICING_NETWORK 
        on PRICING_NETWORK.PRICING_NETWORK_KEY = PRICING_NETWORK_CROSSWALK.PRICING_NETWORK_KEY
       LEFT JOIN (
        SELECT GROUP_TIN, VENDOR_ID FROM OAO_BILLING_ODS_RENDER 
        WHERE PROVIDER_TYPE IN ('INST-AMBSU','INST-AMBUL','INST-DIALY','INST-HOMEH','INST-HOSP','INST-HOSPC','INST-HSPHH','INST-LAB','INST-LTACC','INST-MHREI','INST-MHREO','INST-MRI','INST-PRIDN','INST-REHAO','INST-SNF','INST-SNFAD','INST-SNFPE','INST-URGIC','INST-INFTH')
            ) TYPECHECK1
     ON TYPECHECK1.GROUP_TIN = OAO_BILLING_ODS_RENDER.GROUP_TIN
     AND TYPECHECK1.VENDOR_ID = OAO_BILLING_ODS_RENDER.VENDOR_ID
     LEFT JOIN (
        SELECT GROUP_TIN, VENDOR_ID FROM OAO_BILLING_ODS_RENDER
        WHERE INST_TAXID_BOOL = FALSE
        AND OAO_BILLING_ODS_RENDER.NPI IS NOT NULL
            ) TYPECHECK
     ON TYPECHECK.GROUP_TIN = OAO_BILLING_ODS_RENDER.GROUP_TIN
     AND TYPECHECK.VENDOR_ID = OAO_BILLING_ODS_RENDER.VENDOR_ID
WHERE 1=1 
AND OAO_BILLING_ODS_RENDER.NPI IS NOT NULL AND OAO_BILLING_ODS_RENDER.NPI <> 'UNKNOWN' ORDER BY GROUP_TIN
);

