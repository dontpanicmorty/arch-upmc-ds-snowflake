-- Meant to map structures in RAWDATA/IDAP_LAKE
!set variable_substitution=true;
CREATE OR REPLACE VIEW STAGEDATA.PROVIDER_SET_SELECT_VW (
    TAX_ID_NBR,
    TAX_ID_TYPE_CODE,
    NPI_NBR,
    NETWORK_NAME,
    BUSINESS_NAME
) AS
WITH
    TAX_NPIS AS (
        SELECT
            DERIVED_TAXID AS TAX_ID_NBR,
            TAXID_TYPE AS TAX_ID_TYPE_CODE,
            ARRAY_AGG(DISTINCT NPI) WITHIN GROUP (
                ORDER BY
                    NPI ASC
            ) AS NPI_NBR,
            PRICING_NETWORK_DISPLAY_NAME AS NETWORK_NAME
        FROM
            STAGEDATA.INPATIENT_FEE_SCHEDULE_SELECT_HOLD
            INNER JOIN STAGEDATA.FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW ON INPATIENT_FEE_SCHEDULE_SELECT_HOLD.SCHEDULE_TYPE = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SCHEDULE_TYPE
            AND INPATIENT_FEE_SCHEDULE_SELECT_HOLD.SEGMENT = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SEGMENT
            INNER JOIN STAGEDATA.PROVIDER_NETWORKS_VW PROVIDER_NETWORKS ON PROVIDER_NETWORKS.PROVIDER_TYPE = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROVIDER_TYPE
            AND PROVIDER_NETWORKS.PRICING_NETWORK_NAME = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROV_SET
            AND INPATIENT_FEE_SCHEDULE_SELECT_HOLD.VENDOR = PROVIDER_NETWORKS.VENDOR_ID
            INNER JOIN STAGEDATA.PRICING_NETWORK ON FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROV_SET = PRICING_NETWORK.PRICING_NETWORK_NAME
        GROUP BY
            FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROVIDER_TYPE,
            FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROV_SET,
            INPATIENT_FEE_SCHEDULE_SELECT_HOLD.SEGMENT,
            INPATIENT_FEE_SCHEDULE_SELECT_HOLD.SCHEDULE_TYPE,
            DERIVED_TAXID,
            TAXID_TYPE,
            PRICING_NETWORK.PRICING_NETWORK_DISPLAY_NAME
        UNION
        SELECT
            DERIVED_TAXID AS TAX_ID_NBR,
            TAXID_TYPE AS TAX_ID_TYPE_CODE,
            ARRAY_AGG(DISTINCT NPI) WITHIN GROUP (
                ORDER BY
                    NPI ASC
            ) AS NPI_NBR,
            PRICING_NETWORK_DISPLAY_NAME AS NETWORK_NAME
        FROM
            (
                -- Restrict to distinct combinations to avoid dupes
                SELECT DISTINCT
                    SCHEDULE_TYPE,
                    SEGMENT,
                    SCHEDULE_DETAIL,
                    STATE,
                    MATCH_STATE
                FROM
                    STAGEDATA.PRACTITIONER_FEE_SCHEDULE_SELECT_HOLD
            ) PRACTITIONER_FEE_SCHEDULE
            INNER JOIN STAGEDATA.FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW ON PRACTITIONER_FEE_SCHEDULE.SCHEDULE_TYPE = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SCHEDULE_TYPE
            AND PRACTITIONER_FEE_SCHEDULE.SEGMENT = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SEGMENT
            AND PRACTITIONER_FEE_SCHEDULE.SCHEDULE_DETAIL = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SCHEDULE_DETAIL
            INNER JOIN STAGEDATA.PROVIDER_NETWORKS_VW PROVIDER_NETWORKS ON PROVIDER_NETWORKS.PROVIDER_TYPE = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROVIDER_TYPE
            AND PROVIDER_NETWORKS.PRICING_NETWORK_NAME = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROV_SET
            INNER JOIN STAGEDATA.PRICING_NETWORK ON FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROV_SET = PRICING_NETWORK.PRICING_NETWORK_NAME
            INNER JOIN STAGEDATA.VENDOR_STATE_VW ON VENDOR_STATE_VW.VENDOR_ID = PROVIDER_NETWORKS.VENDOR_ID
            AND CASE
                WHEN PRACTITIONER_FEE_SCHEDULE.MATCH_STATE = 'Y' THEN VENDOR_STATE_VW.VENDOR_STATE = PRACTITIONER_FEE_SCHEDULE.STATE
                ELSE 1
            END
        GROUP BY
            FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROVIDER_TYPE,
            FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROV_SET,
            PRACTITIONER_FEE_SCHEDULE.SEGMENT,
            PRACTITIONER_FEE_SCHEDULE.SCHEDULE_DETAIL,
            PRACTITIONER_FEE_SCHEDULE.SCHEDULE_TYPE,
            STATE,
            MATCH_STATE,
            DERIVED_TAXID,
            TAXID_TYPE,
            PRICING_NETWORK.PRICING_NETWORK_DISPLAY_NAME
    ),
    BUSINESS_NAMES AS (
        SELECT
            -- Normalize TAX_ID_NUMBER to digits only
            REGEXP_REPLACE(TAX_ID_NUMBER::STRING, '[^0-9]', '') AS TAX_ID_NUMBER,
            -- Business name normalization
            REGEXP_REPLACE(
                REGEXP_REPLACE(
                    COALESCE(
                        PROVIDER_FULL_NAME, -- prefer IDAP full name
                        MG.MEDICAL_GROUP_NAME -- fallback to medical group name
                    ),
                    '\\bUpmc\\b',
                    'UPMC',
                    1,
                    0,
                    'i'
                ),
                '(\\s*-\\s*)?(TAXID|TAX)\\b',
                '',
                1,
                0,
                'i'
            ) AS BUSINESS_NAME,
            PROVIDER_NUMBER
        FROM
            IDAP_AUXILIARY.PROVIDER_ONLINE.DIRECTORY_NON_PARTICIPANT DNP
            LEFT JOIN RAWDATA.ODSDATA_MEDICAL_GROUP MG ON REGEXP_REPLACE(DNP.TAX_ID_NUMBER::STRING, '[^0-9]', '') = REGEXP_REPLACE(MG.TIN_NBR::STRING, '[^0-9]', '')
        WHERE
            DNP.PROVIDER_SUB_TYPE_DESCRIPTION = 'Medical Group'
            AND TAX_ID_NUMBER IS NOT NULL
            AND REGEXP_REPLACE(TAX_ID_NUMBER::STRING, '[^0-9]', '') <> ''
        QUALIFY
            ROW_NUMBER() OVER (
                PARTITION BY
                    REGEXP_REPLACE(TAX_ID_NUMBER::STRING, '[^0-9]', '')
                ORDER BY
                    PROVIDER_NUMBER
            ) = 1
    ),
    AGGREGATE_NETWORKS AS (
        SELECT
            TAX_ID_NBR,
            TAX_ID_TYPE_CODE,
            NPI_NBR,
            ARRAY_AGG(DISTINCT NETWORK_NAME) WITHIN GROUP (
                ORDER BY
                    NETWORK_NAME ASC
            ) AS NETWORK_NAME
        FROM
            TAX_NPIS
        GROUP BY
            TAX_ID_NBR,
            TAX_ID_TYPE_CODE,
            NPI_NBR
    )
SELECT
    AGGREGATE_NETWORKS.TAX_ID_NBR AS TAX_ID_NBR,
    TAX_ID_TYPE_CODE,
    NPI_NBR,
    NETWORK_NAME,
    BUSINESS_NAME
FROM
    AGGREGATE_NETWORKS
    LEFT JOIN BUSINESS_NAMES ON AGGREGATE_NETWORKS.TAX_ID_NBR = BUSINESS_NAMES.TAX_ID_NUMBER;

!set variable_substitution=false;