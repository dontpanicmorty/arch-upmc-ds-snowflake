CREATE OR REPLACE VIEW STAGEDATA.MRF_PRICE_CATEGORY_VW
AS
(
SELECT DISTINCT
TRIM(PROVIDER_NBR) AS VENDOR_ID
,TRIM(PLAN_TYPE) AS PLAN_TYPE
,COALESCE(TRIM(PLACE_OF_SERVICE),'NoValue') AS PLACE_OF_SERVICE
,COALESCE(TRIM(GROUP_CARRIER_PRICE_GROUP),'NoValue') AS GROUP_CARRIER_PRICE_GROUP
,CASE WHEN TRIM(PROVIDER_NBR) = 'V0V1FC' AND TRIM(PLAN_TYPE) IN ('I','I01','N','O') THEN COALESCE(TRIM(IPA_PRICE_GROUP),'01') 
    WHEN TRIM(PROVIDER_NBR) = 'V0V1FC' AND TRIM(PLAN_TYPE) NOT IN ('I','I01','N','O') THEN COALESCE(TRIM(IPA_PRICE_GROUP),'02') 
	WHEN IPA_PRICE_GROUP IS NULL THEN '01'
    ELSE IPA_PRICE_GROUP
END AS IPA_CODE
,TRIM(PRICE_CATEGORY) AS PRICE_CATEGORY
,PRICE_CATEGORY_KEY
,CAST(PRICE_CAT_SEQUENCE AS INT) AS PRICE_CAT_SEQUENCE
FROM STAGEDATA.MRF_PRICING_HIST_PRICE_CATG_VW
    JOIN STAGEDATA.PRICE_CATEGORY
        ON PRICE_CATEGORY.PRICE_CATEGORY_NAME = MRF_PRICING_HIST_PRICE_CATG_VW.PRICE_CATEGORY
);