CREATE OR REPLACE VIEW STAGEDATA.OUT_OF_NETWORK_BASE_SELECT_VW

AS
-- Out-of-network base is effectively one-to-one with billing_code/plan_code combo
SELECT DISTINCT BILLING_CODE_INTERNAL_VW.BILLING_CODE, -- for internal joins
  SERVICE_NAME,
  PRICING_FILE_KEY, -- todo; lower than lowest active value
  BILLING_CODE_KEY,
  PLAN_CODE
FROM STAGEDATA.OUT_OF_NETWORK_CLAIMS_THRESHOLD_VW

INNER JOIN STAGEDATA.BILLING_CODE_INTERNAL_VW ON
    BILLING_CODE_INTERNAL_VW.BILLING_CODE = STAGEDATA.OUT_OF_NETWORK_CLAIMS_THRESHOLD_VW.BILLING_CODE

INNER JOIN EXTRACTDATA.BILLING_CODE ON
    BILLING_CODE.BILLING_CODE = BILLING_CODE_INTERNAL_VW.BILLING_CODE and
     DATEADD(day,-180,current_date) >=  CAST(BILLING_CODE_INTERNAL_VW.START_DATE AS DATE)AND
     DATEADD(day,-180,current_date) <= CAST(BILLING_CODE_INTERNAL_VW.END_DATE AS DATE) AND
     EXTRACTDATA.BILLING_CODE.BILLING_CODE_TYPE_VERSION_TEXT = BILLING_CODE_INTERNAL_VW.BILLING_CODE_TYPE_VERSION_TEXT

INNER JOIN EXTRACTDATA.PRICING_FILE ON
    FILE_DESC = OUT_OF_NETWORK_FILE_DESC
;