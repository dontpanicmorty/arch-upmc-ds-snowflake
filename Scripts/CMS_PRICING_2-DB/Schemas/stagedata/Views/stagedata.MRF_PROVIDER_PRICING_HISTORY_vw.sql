CREATE OR REPLACE VIEW STAGEDATA.MRF_PROVIDER_PRICING_HISTORY_VW
AS
(
SELECT DISTINCT DWOAO_PROVIDERPRICINGHISTORY.PROVIDERNBR AS PROVIDER_NBR
,DWOAO_PROVIDERPRICINGHISTORY.AMBULATORYSURGERYFEESCH AS AMBULATORY_SURGERY_FEE_SCH
,DWOAO_PROVIDERPRICINGHISTORY.ASACONVERSIONFACTORSET AS ASA_CONVERSION_FACTOR_SET
,DWOAO_PROVIDERPRICINGHISTORY.AVERAGEWHOLESALEPRICE AS AVERAGE_WHOLESALE_PRICE
,DWOAO_PROVIDERPRICINGHISTORY.EFFECTIVEDATE AS EFFECTIVE_DATE
,DWOAO_PROVIDERPRICINGHISTORY.CASERATESCHEDULE AS CASE_RATE_SCHEDULE
,DWOAO_PROVIDERPRICINGHISTORY.FACTOR1 AS FACTOR_1
,DWOAO_PROVIDERPRICINGHISTORY.FACTOR2 AS FACTOR_2
,DWOAO_PROVIDERPRICINGHISTORY.FIFTHLEVELPRICECATEGORY AS FIFTH_LEVEL_PRICE_CATEGORY
,DWOAO_PROVIDERPRICINGHISTORY.FOURTHLEVELPRICECATEGORY AS FOURTH_LEVEL_PRICE_CATEGORY
,COALESCE(DWOAO_PROVIDERPRICINGHISTORY.GROUPCARRIERPRICEGROUP, 'NoValue') AS GROUP_CARRIER_PRICE_GROUP
,CASE WHEN DWOAO_PROVIDERPRICINGHISTORY.PROVIDERNBR = 'V0V1FC' AND DWOAO_PROVIDERPRICINGHISTORY.PLANTYPE IN ('I','I01','N','O') THEN COALESCE(DWOAO_PROVIDERPRICINGHISTORY.IPAPRICEGROUP,'01') 
     WHEN DWOAO_PROVIDERPRICINGHISTORY.PROVIDERNBR = 'V0V1FC' AND DWOAO_PROVIDERPRICINGHISTORY.PLANTYPE NOT IN ('I','I01','N','O') THEN COALESCE(DWOAO_PROVIDERPRICINGHISTORY.IPAPRICEGROUP,'02')
	 WHEN DWOAO_PROVIDERPRICINGHISTORY.IPAPRICEGROUP IS NULL THEN '01'
     ELSE DWOAO_PROVIDERPRICINGHISTORY.IPAPRICEGROUP END AS IPA_PRICE_GROUP
,DWOAO_PROVIDERPRICINGHISTORY.PERCENTAGE
,DWOAO_PROVIDERPRICINGHISTORY.PERCENTAGERULE AS PERCENTAGE_RULE
,DWOAO_PROVIDERPRICINGHISTORY.PHARMACYPRICECATEGORY AS PHARMACY_PRICE_CATEGORY
,COALESCE(DWOAO_PROVIDERPRICINGHISTORY.PLACEOFSERVICE, 'NoValue') AS PLACE_OF_SERVICE
,DWOAO_PROVIDERPRICINGHISTORY.PLANTYPE AS PLAN_TYPE
,DWOAO_PROVIDERPRICINGHISTORY.PRICECATEGORY AS PRICE_CATEGORY
,DWOAO_PROVIDERPRICINGHISTORY.PRICINGRULE AS PRICING_RULE
,DWOAO_PROVIDERPRICINGHISTORY.TERMDATE AS TERM_DATE
,DWOAO_PROVIDERPRICINGHISTORY.CUSTOMPRICINGRULESET AS CUSTOM_PRICING_RULE_SET
,DWOAO_PROVIDERPRICINGHISTORY.PROVIDERTYPESCHEDULE AS PROVIDER_TYPE_SCHEDULE
FROM RAWDATA.DWOAO_PROVIDERPRICINGHISTORY 
    WHERE DWOAO_PROVIDERPRICINGHISTORY.PLANTYPE IN (SELECT PLAN_TYPE_CODE FROM STAGEDATA.PLAN_TYPE)
	AND  (DWOAO_PROVIDERPRICINGHISTORY.IPAPRICEGROUP IN (SELECT IPA_CODE FROM STAGEDATA.IPA)
	        OR DWOAO_PROVIDERPRICINGHISTORY.IPAPRICEGROUP IS NULL)
    AND DWOAO_PROVIDERPRICINGHISTORY.PROVIDERNBR IN (SELECT PROVIDER_NBR FROM STAGEDATA.MRF_CONTRACTS_VW)
    --AND ASA_CONVERSION_FACTOR_SET <> 'A01'
);