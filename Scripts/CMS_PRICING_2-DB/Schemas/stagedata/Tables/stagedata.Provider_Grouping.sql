-- Transient as it's updated from the spu_run_extract sproc
CREATE OR REPLACE TRANSIENT TABLE STAGEDATA.PROVIDER_GROUPING 
(
		PROVIDER_GROUPING_KEY NUMBER(38,0) NOT NULL AUTOINCREMENT ORDER START 1 INCREMENT 1,
		INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		GROUP_CARRIER_PRICE_GROUP_KEY NUMBER(38,0),
		IPA_KEY NUMBER(38,0),
		PLAN_TYPE_KEY NUMBER(38,0),
		TAX_ID_NBR VARCHAR,
		VENDOR_NBR VARCHAR,
		TAX_ID_TYPE_CODE VARCHAR,
		PROVIDER_TYPE_NAME VARCHAR COMMENT 'ALSO KNOWN AS MC400 PROVIDERSPECIALTY',
		RENDERING_PROVIDER_NBR VARCHAR,
		RENDERING_PROVIDER_NPI_NBRS ARRAY,
		CONSTRAINT FK_PROVIDER_GROUPING_GROUP_CARRIER_PRICE_GROUP_KEY FOREIGN KEY (GROUP_CARRIER_PRICE_GROUP_KEY) REFERENCES STAGEDATA.GROUP_CARRIER_PRICE_GROUP (GROUP_CARRIER_PRICE_GROUP_KEY),
		CONSTRAINT FK_PROVIDER_GROUPING_IPA_KEY FOREIGN KEY (IPA_KEY) REFERENCES STAGEDATA.IPA (IPA_KEY),
		CONSTRAINT FK_PROVIDER_GROUPING_PLAN_TYPE_KEY FOREIGN KEY (PLAN_TYPE_KEY) REFERENCES STAGEDATA.PLAN_TYPE (PLAN_TYPE_KEY),
		CONSTRAINT PK_PROVIDER_GROUPING PRIMARY KEY (PROVIDER_GROUPING_KEY),
		CONSTRAINT UK_PROVIDER_GROUPING UNIQUE (GROUP_CARRIER_PRICE_GROUP_KEY, IPA_KEY, PLAN_TYPE_KEY, TAX_ID_NBR, PROVIDER_TYPE_NAME, RENDERING_PROVIDER_NBR, RENDERING_PROVIDER_NPI_NBRS)
	)
	 COMMENT='Holds unique combos of TIN, NPI, Type or Sepcialty, IPA, planType, GPG code';