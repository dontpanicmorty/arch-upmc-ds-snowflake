CREATE OR REPLACE TABLE EXTRACTDATA.PROVIDER_SET (
	PROVIDER_SET_KEY NUMBER(38, 0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL UNIQUE,
	INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
	TAX_ID_NBR VARCHAR NOT NULL,
	TAX_ID_TYPE_CODE VARCHAR NOT NULL,
	NPI_NBR ARRAY NOT NULL,
	BUSINESS_NAME VARCHAR,
	NETWORK_NAME ARRAY,
	CONSTRAINT PK_PROVIDERS_OBJECT PRIMARY KEY (PROVIDER_SET_KEY),
	CONSTRAINT UK_PRICING_PROVIDER_GROUP UNIQUE (TAX_ID_NBR, TAX_ID_TYPE_CODE, NPI_NBR)
) COMMENT = 'Distinct set of TINs and associated NPIs that have been used in at least one negotiated_rate';