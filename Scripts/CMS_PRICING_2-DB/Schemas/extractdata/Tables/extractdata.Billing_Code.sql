CREATE OR REPLACE TABLE
	EXTRACTDATA.BILLING_CODE (
		BILLING_CODE_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL UNIQUE,
		INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		BILLING_CODE VARCHAR NOT NULL,
		BILLING_CODE_TYPE_NAME VARCHAR COMMENT 'cpt, hcpcs, icd, msdrg, aprdrg, etc',
		BILLING_CODE_TYPE_VERSION_TEXT VARCHAR NOT NULL COMMENT 'version of the code such as icd 9 or 10',
		BILLING_CODE_DESC VARCHAR NOT NULL,
		CONSTRAINT PK_BILLING_CODE PRIMARY KEY (BILLING_CODE_KEY),
		CONSTRAINT UK_BILLING_CODE UNIQUE (BILLING_CODE, BILLING_CODE_TYPE_NAME, BILLING_CODE_TYPE_VERSION_TEXT),
		CONSTRAINT UK_BILLING_CODE_TYPE UNIQUE (BILLING_CODE_TYPE_NAME)
	)
	 COMMENT='Contains all possible codes used for billing';