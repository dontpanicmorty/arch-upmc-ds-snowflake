CREATE OR REPLACE TABLE EXTRACTDATA.NEGOTIATED_PRICE (
	NEGOTIATED_PRICE_KEY NUMBER(38, 0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL UNIQUE,
	INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
	NEGOTIATED_TYPE_NAME VARCHAR NOT NULL,
	NEGOTIATED_RATE_AMT NUMBER(20, 2) NOT NULL,
	EXPIRATION_DATE DATE,
	PLACE_OF_SERVICE_CODES ARRAY,
	BILLING_CLASS_NAME VARCHAR NOT NULL COMMENT 'institutional or professional',
	BILLING_CODE_MODIFIERS ARRAY NOT NULL COMMENT 'Array of relevant modifier values. Only applicable to FFS networks and even then its optional',
	OUTPATIENT_PROCEDURE_CODE VARCHAR COMMENT 'The outpatient procedure code associated with this negotiated price, if applicable',
	OUTPATIENT_MODIFIER ARRAY COMMENT 'The outpatient modifier associated with this negotiated price, if applicable',
	OUTPATIENT_PRICE NUMBER(20, 2) COMMENT 'The outpatient price associated with this negotiated price, if applicable',
	CONSTRAINT PK_NEGOTIATED_PRICE PRIMARY KEY (NEGOTIATED_PRICE_KEY),
	CONSTRAINT UK_NEGOTIATED_PRICE UNIQUE (
		NEGOTIATED_RATE_AMT,
		BILLING_CODE_MODIFIERS,
		PLACE_OF_SERVICE_CODES,
		BILLING_CLASS_NAME,
		NEGOTIATED_TYPE_NAME,
		OUTPATIENT_PROCEDURE_CODE,
		OUTPATIENT_MODIFIER,
		OUTPATIENT_PRICE
	)
) COMMENT = 'Negotiated price for a given plan and code combination';