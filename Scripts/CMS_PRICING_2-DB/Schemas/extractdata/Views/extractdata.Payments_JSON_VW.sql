CREATE OR REPLACE VIEW EXTRACTDATA.PAYMENTS_JSON_VW
AS
-- No aggregate here because it'll break the 16MB barrier pretty easily
SELECT ALLOWED_AMOUNTS_KEY, OBJECT_CONSTRUCT(
    'allowed_amount', ALLOWED_AMT,
    'billing_code_modifier', BILLING_CODE_MODIFIERS,
    'providers', PAYMENT_PROVIDERS_JSON
) AS PAYMENTS_JSON
FROM EXTRACTDATA.PAYMENTS
LEFT JOIN EXTRACTDATA.PAYMENT_PROVIDERS_JSON_VW 
    ON EXTRACTDATA.PAYMENTS.PAYMENTS_KEY = EXTRACTDATA.PAYMENT_PROVIDERS_JSON_VW.PAYMENTS_KEY
;