CREATE OR REPLACE VIEW EXTRACTDATA.NEGOTIATED_RATES_JSON_VW
AS
-- Outer aggregation: group by IN_NETWORK_BASE_KEY
SELECT IN_NETWORK_BASE_KEY, ARRAY_AGG(NEGOTIATED_RATE_BASE_JSON) AS NEGOTIATED_RATE_JSON
FROM (
  -- Inner aggregation: prices and references
   SELECT IN_NETWORK_BASE_KEY,
    OBJECT_CONSTRUCT(
      'negotiated_prices', ARRAY_AGG(NEGOTIATED_PRICE_JSON), 
      -- Should be an array of one group ID using lookup at top level of JSON,
      -- array needed to match schema
      'provider_references', ARRAY_AGG(DISTINCT PRICING_PROVIDER_GROUP_KEY)
    ) AS NEGOTIATED_RATE_BASE_JSON
  FROM EXTRACTDATA.NEGOTIATED_RATES
  LEFT JOIN EXTRACTDATA.NEGOTIATED_PRICE_JSON_VW 
      ON EXTRACTDATA.NEGOTIATED_PRICE_JSON_VW.NEGOTIATED_PRICE_KEY = EXTRACTDATA.NEGOTIATED_RATES.NEGOTIATED_PRICE_KEY
  GROUP BY IN_NETWORK_BASE_KEY, PRICING_PROVIDER_GROUP_KEY
) NEGOTIATED_RATE_BASE
GROUP BY IN_NETWORK_BASE_KEY
;