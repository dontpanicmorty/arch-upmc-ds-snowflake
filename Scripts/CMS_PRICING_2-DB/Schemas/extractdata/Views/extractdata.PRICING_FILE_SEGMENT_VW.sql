CREATE OR REPLACE MATERIALIZED VIEW EXTRACTDATA.PRICING_FILE_SEGMENT_VW
COMMENT='Returns necessary data from extractdata PRICING_FILE table for Healthsparq file creation.'
AS
SELECT PRICING_FILE_KEY,
    REPORTING_ENTITY_KEY,
    FILE_TYPE_NAME,
    FILE_DESC,
    TRIM(SPLIT_PART(SPLIT_PART(FILE_DESC, ':',2),',',1)) AS SEGMENT,
    TRIM(SPLIT_PART(SPLIT_PART(FILE_DESC, ':',3),',',1)) AS PROVIDER_SET
FROM EXTRACTDATA.PRICING_FILE
WHERE FILE_TYPE_NAME = 'in-network-rates'
AND REPORTING_ENTITY_KEY = 3
;
