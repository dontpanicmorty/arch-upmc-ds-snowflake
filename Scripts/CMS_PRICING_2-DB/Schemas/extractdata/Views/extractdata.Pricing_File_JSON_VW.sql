CREATE OR REPLACE VIEW EXTRACTDATA.PRICING_FILE_JSON_VW
AS
-- Makes easier-to-select JSON from pricing_file
SELECT FILE_TYPE_NAME,
  PRICING_FILE_KEY,
  OBJECT_CONSTRUCT(
    'location', EXTRACTDATA.FXN_PREPEND_STAGING_CONTAINER_URL(
        EXTRACTDATA.FXN_MAKE_URL_PATH(FILE_TYPE_NAME, PRICING_FILE.PRICING_FILE_KEY)
    ),
    'description', FILE_DESC
  ) AS PRICING_FILE_JSON
FROM EXTRACTDATA.PRICING_FILE