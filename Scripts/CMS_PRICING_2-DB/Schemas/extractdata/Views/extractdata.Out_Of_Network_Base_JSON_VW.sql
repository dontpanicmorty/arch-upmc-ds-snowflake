CREATE OR REPLACE VIEW EXTRACTDATA.OUT_OF_NETWORK_BASE_JSON_VW
AS
-- Group by pricing_file_key so we can just join in
SELECT PRICING_FILE_KEY, ARRAY_AGG(OUT_OF_NETWORK_INTERNAL_JSON) AS OUT_OF_NETWORK_JSON
FROM (
  -- Simple JSON reconstruction, other JSON_VWs come pre-agg'd
  SELECT OUT_OF_NETWORK_BASE.PRICING_FILE_KEY,
      OBJECT_CONSTRUCT(
        'name', SERVICE_NAME,
        'billing_code_type', BILLING_CODE_TYPE_NAME,
        'billing_code_type_version', BILLING_CODE_TYPE_VERSION_TEXT,
        'billing_code', BILLING_CODE,
        'description', BILLING_CODE_DESC,
        'allowed_amounts', ALLOWED_AMOUNTS_JSON
      ) OUT_OF_NETWORK_INTERNAL_JSON
  FROM EXTRACTDATA.OUT_OF_NETWORK_BASE
  LEFT JOIN EXTRACTDATA.ALLOWED_AMOUNTS_JSON_VW
      ON EXTRACTDATA.OUT_OF_NETWORK_BASE.OUT_OF_NETWORK_BASE_KEY = EXTRACTDATA.ALLOWED_AMOUNTS_JSON_VW.OUT_OF_NETWORK_BASE_KEY
  LEFT JOIN EXTRACTDATA.BILLING_CODE 
      ON EXTRACTDATA.OUT_OF_NETWORK_BASE.BILLING_CODE_KEY = EXTRACTDATA.BILLING_CODE.BILLING_CODE_KEY
) OUT_OF_NETWORK_INTERNAL
GROUP BY PRICING_FILE_KEY