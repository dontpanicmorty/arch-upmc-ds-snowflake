CREATE OR REPLACE VIEW EXTRACTDATA.PRICING_PROVIDER_REFERENCE_JSON_VW AS
-- Streamlines creating the top-level provider_references object by pre-fabbing
-- the object and linking out
SELECT
  IN_NETWORK_BASE.PRICING_FILE_KEY,
  ARRAY_AGG(DISTINCT PRICING_PROVIDER_REFERENCE_BASE_JSON) AS PRICING_PROVIDER_REFERENCE_JSON
FROM
  EXTRACTDATA.IN_NETWORK_BASE
  INNER JOIN EXTRACTDATA.NEGOTIATED_RATES 
  ON IN_NETWORK_BASE.IN_NETWORK_BASE_KEY = NEGOTIATED_RATES.IN_NETWORK_BASE_KEY
  LEFT JOIN (
    SELECT
      PRICING_PROVIDER_GROUP_KEY,
      OBJECT_CONSTRUCT(
        'network_name', NETWORK_NAME,
        'provider_group_id', PRICING_PROVIDER_GROUP_KEY,
        'provider_groups', JSON_DATA
      ) AS PRICING_PROVIDER_REFERENCE_BASE_JSON
    FROM
      EXTRACTDATA.PRICING_PROVIDER_GROUP_FILE_JSON_VW
  ) AS PRICING_PROVIDER_REFERENCE_BASE 
  ON PRICING_PROVIDER_REFERENCE_BASE.PRICING_PROVIDER_GROUP_KEY = NEGOTIATED_RATES.PRICING_PROVIDER_GROUP_KEY
GROUP BY
  PRICING_FILE_KEY;