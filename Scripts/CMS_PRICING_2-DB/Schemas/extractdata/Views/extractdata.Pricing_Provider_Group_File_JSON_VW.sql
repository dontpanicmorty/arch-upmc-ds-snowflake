CREATE OR REPLACE VIEW EXTRACTDATA.PRICING_PROVIDER_GROUP_FILE_JSON_VW AS
-- Key should become a component of URL, object_construct makes root-level object
SELECT
  EXTRACTDATA.FXN_MAKE_URL_PATH ('provider-reference', PRICING_PROVIDER_GROUP_KEY) AS URL_PATH,
  EXTRACTDATA.FXN_PREPEND_STAGING_CONTAINER_URL (URL_PATH) AS URL,
  PRICING_PROVIDER_GROUP_KEY,
  NETWORK_NAME,
  ARRAY_AGG(PROVIDER_SET_OBJECT) AS JSON_DATA
FROM
  (
    -- Flatten the array of set keys into separate rows
    SELECT
      PRICING_PROVIDER_GROUP_KEY,
      SET_KEYS.VALUE AS PROVIDER_SET_KEY
    FROM
      EXTRACTDATA.PRICING_PROVIDER_GROUP,
      LATERAL FLATTEN(INPUT => PRICING_PROVIDER_SET_KEYS) SET_KEYS
  ) PROVIDER_GROUP
  LEFT JOIN (
    -- For each provider set, make the corresponding JSON object
    SELECT
      PROVIDER_SET_KEY,
      NETWORK_NAME,
      OBJECT_CONSTRUCT(
        'npi', NPI_NBR,
        'tin', OBJECT_CONSTRUCT(
            'business_name', BUSINESS_NAME,
            'type', TAX_ID_TYPE_CODE,
            'value', TAX_ID_NBR
          )
      ) AS PROVIDER_SET_OBJECT
    FROM
      EXTRACTDATA.PROVIDER_SET
  ) PROVIDER_SET_JSON 
  ON PROVIDER_SET_JSON.PROVIDER_SET_KEY = PROVIDER_GROUP.PROVIDER_SET_KEY
GROUP BY
  PROVIDER_GROUP.PRICING_PROVIDER_GROUP_KEY,
  NETWORK_NAME;