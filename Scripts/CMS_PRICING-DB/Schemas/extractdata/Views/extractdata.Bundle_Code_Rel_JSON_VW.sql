CREATE OR REPLACE VIEW EXTRACTDATA.BUNDLE_CODE_REL_JSON_VW
AS
-- Simple JSON reconstruction, grouped by IN_NETWORK_BASE
SELECT IN_NETWORK_BASE_KEY, 
  ARRAY_AGG(OBJECT_CONSTRUCT(
    'billing_code_type', BILLING_CODE_TYPE_NAME,
    'billing_code_type_version', BILLING_CODE_TYPE_VERSION_TEXT,
    'billing_code', BILLING_CODE,
    'description', BILLING_CODE_DESC
  )) AS BUNDLE_CODE_REL_JSON
FROM EXTRACTDATA.BUNDLE_CODE_REL
LEFT JOIN EXTRACTDATA.BILLING_CODE 
    ON EXTRACTDATA.BUNDLE_CODE_REL.BILLING_CODE_KEY = EXTRACTDATA.BILLING_CODE.BILLING_CODE_KEY
GROUP BY IN_NETWORK_BASE_KEY
;