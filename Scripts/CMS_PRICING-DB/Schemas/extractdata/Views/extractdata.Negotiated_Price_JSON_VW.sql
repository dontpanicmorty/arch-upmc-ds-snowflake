CREATE OR REPLACE VIEW EXTRACTDATA.NEGOTIATED_PRICE_JSON_VW
AS
-- Simple JSON reconstruction
SELECT NEGOTIATED_PRICE_KEY,
  OBJECT_CONSTRUCT(
    'negotiated_type', NEGOTIATED_TYPE_NAME,
    'negotiated_rate', NEGOTIATED_RATE_AMT, 
    'expiration_date', EXPIRATION_DATE, 
    'service_code', PLACE_OF_SERVICE_CODES, 
    'billing_class', BILLING_CLASS_NAME, 
    'billing_code_modifier', BILLING_CODE_MODIFIERS
  ) AS NEGOTIATED_PRICE_JSON
FROM EXTRACTDATA.NEGOTIATED_PRICE
;