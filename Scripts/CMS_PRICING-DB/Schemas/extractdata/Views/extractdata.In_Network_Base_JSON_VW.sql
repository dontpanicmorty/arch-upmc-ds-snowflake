CREATE OR REPLACE VIEW EXTRACTDATA.IN_NETWORK_BASE_JSON_VW
AS
-- Simple JSON reconstruction, other JSON_VWs come pre-agg'd
SELECT IN_NETWORK_BASE.PRICING_FILE_KEY, 
OBJECT_CONSTRUCT(
  'negotiation_arrangement', NEGOTIATION_ARRANGEMENT_NAME, 
  'name', SERVICE_NAME,
  'billing_code_type', BILLING_CODE_TYPE_NAME,
  'billing_code_type_version', BILLING_CODE_TYPE_VERSION_TEXT,
  'billing_code', BILLING_CODE,
  'description', BILLING_CODE_DESC,
  -- Same data should have two different names based off one column
  CASE WHEN (NEGOTIATION_ARRANGEMENT_NAME = 'capitation') THEN 'covered_services' ELSE 'bundled_codes' END, BUNDLE_CODE_REL_JSON,
  'negotiated_rates', NEGOTIATED_RATE_JSON
) AS IN_NETWORK_JSON
FROM EXTRACTDATA.IN_NETWORK_BASE
INNER JOIN EXTRACTDATA.BILLING_CODE 
    ON EXTRACTDATA.IN_NETWORK_BASE.BILLING_CODE_KEY = EXTRACTDATA.BILLING_CODE.BILLING_CODE_KEY
LEFT JOIN EXTRACTDATA.BUNDLE_CODE_REL_JSON_VW
    ON EXTRACTDATA.IN_NETWORK_BASE.IN_NETWORK_BASE_KEY = EXTRACTDATA.BUNDLE_CODE_REL_JSON_VW.IN_NETWORK_BASE_KEY
INNER JOIN EXTRACTDATA.NEGOTIATED_RATES_JSON_VW
    ON EXTRACTDATA.IN_NETWORK_BASE.IN_NETWORK_BASE_KEY = EXTRACTDATA.NEGOTIATED_RATES_JSON_VW.IN_NETWORK_BASE_KEY
;