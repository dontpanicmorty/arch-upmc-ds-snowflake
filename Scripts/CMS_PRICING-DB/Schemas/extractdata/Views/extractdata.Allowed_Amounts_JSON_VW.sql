CREATE OR REPLACE VIEW EXTRACTDATA.ALLOWED_AMOUNTS_JSON_VW
AS
-- Two-tier object-construct with an array_agg
SELECT OUT_OF_NETWORK_BASE_KEY,
    ARRAY_AGG(OBJECT_CONSTRUCT(
        'tin', OBJECT_CONSTRUCT('type', TAX_ID_TYPE_CODE, 'value', TAX_ID_NBR),
        'service_code', PLACE_OF_SERVICE_CODES,
        'billing_class', BILLING_CLASS_NAME,
        'payments', PAYMENTS_JSON
    )) AS ALLOWED_AMOUNTS_JSON
FROM EXTRACTDATA.ALLOWED_AMOUNTS
LEFT JOIN (
  -- In the case we can use one of these views without hitting the 16MB limit,
  -- do the array_agg in here
  SELECT ALLOWED_AMOUNTS_KEY, ARRAY_AGG(PAYMENTS_JSON) AS PAYMENTS_JSON
  FROM EXTRACTDATA.PAYMENTS_JSON_VW
  GROUP BY ALLOWED_AMOUNTS_KEY
) PAYMENTS_JSON_INTERNAL ON
    ALLOWED_AMOUNTS.ALLOWED_AMOUNTS_KEY = PAYMENTS_JSON_INTERNAL.ALLOWED_AMOUNTS_KEY
GROUP BY OUT_OF_NETWORK_BASE_KEY
;
