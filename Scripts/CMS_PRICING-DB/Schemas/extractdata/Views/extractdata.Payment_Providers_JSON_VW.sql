CREATE OR REPLACE VIEW EXTRACTDATA.PAYMENT_PROVIDERS_JSON_VW
AS
-- Simple aggregate on the leaf-level objects
SELECT PAYMENTS_KEY, ARRAY_AGG(
  OBJECT_CONSTRUCT(
    'billed_charge', BILLED_CHARGE_AMT, 
    'npi', NPI_NBRS
  )
) AS PAYMENT_PROVIDERS_JSON
FROM EXTRACTDATA.PAYMENT_PROVIDERS
GROUP BY PAYMENTS_KEY
;