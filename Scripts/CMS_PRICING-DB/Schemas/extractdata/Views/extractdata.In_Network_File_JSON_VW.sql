CREATE OR REPLACE VIEW EXTRACTDATA.IN_NETWORK_FILE_JSON_VW
AS
-- Simple JSON construct since everything else currently is linked by PRICING_FILE_KEY
SELECT
  IN_NETWORK_FILE_BASE_SELECT_VW.PRICING_FILE_KEY,
  EXTRACTDATA.FXN_MAKE_URL_PATH('in-network-rates', IN_NETWORK_FILE_BASE_SELECT_VW.PRICING_FILE_KEY) AS URL_PATH,
  EXTRACTDATA.FXN_PREPEND_STAGING_CONTAINER_URL(URL_PATH) AS URL, 
    OBJECT_CONSTRUCT(
    'reporting_entity_name', REPORTING_ENTITY_NAME,
    'reporting_entity_type', REPORTING_ENTITY_TYPE,
    'last_updated_on', LAST_UPDATED_ON_DATE,
    'version', VERSION,
    'provider_references', PRICING_PROVIDER_REFERENCE_JSON,
    'in_network', ARRAY_AGG(IN_NETWORK_JSON)
  ) AS JSON_DATA
FROM EXTRACTDATA.IN_NETWORK_FILE_BASE_SELECT_VW 
-- Use direct link to reportingEntity instead of going through plan
LEFT JOIN EXTRACTDATA.IN_NETWORK_BASE_JSON_VW ON IN_NETWORK_FILE_BASE_SELECT_VW.PRICING_FILE_KEY = IN_NETWORK_BASE_JSON_VW.PRICING_FILE_KEY
WHERE FILE_TYPE_NAME = 'in-network-rates'
GROUP BY IN_NETWORK_FILE_BASE_SELECT_VW.PRICING_FILE_KEY, REPORTING_ENTITY_NAME, REPORTING_ENTITY_TYPE, LAST_UPDATED_ON_DATE, VERSION, PRICING_PROVIDER_REFERENCE_JSON
;