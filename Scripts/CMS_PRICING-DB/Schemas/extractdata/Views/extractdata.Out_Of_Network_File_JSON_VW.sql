CREATE OR REPLACE VIEW EXTRACTDATA.OUT_OF_NETWORK_FILE_JSON_VW
AS
-- Simple JSON construct since everything else currently is linked by PRICING_FILE_KEY
SELECT PRICING_FILE.PRICING_FILE_KEY,
  EXTRACTDATA.FXN_MAKE_URL_PATH('allowed-amounts', PRICING_FILE.PRICING_FILE_KEY) AS URL_PATH,
  EXTRACTDATA.FXN_PREPEND_STAGING_CONTAINER_URL(URL_PATH) AS URL, 
    OBJECT_CONSTRUCT(
    'reporting_entity_name', REPORTING_ENTITY_NAME,
    'reporting_entity_type', REPORTING_ENTITY_TYPE,
    'last_updated_on', CURRENT_DATE(),
    'version', '1.0.0',
    'out_of_network', OUT_OF_NETWORK_JSON
  ) AS JSON_DATA
FROM EXTRACTDATA.PRICING_FILE 
-- Use direct link to reportingEntity instead of going through plan
LEFT JOIN EXTRACTDATA.REPORTING_ENTITY ON REPORTING_ENTITY.REPORTING_ENTITY_KEY = PRICING_FILE.REPORTING_ENTITY_KEY
LEFT JOIN EXTRACTDATA.OUT_OF_NETWORK_BASE_JSON_VW ON PRICING_FILE.PRICING_FILE_KEY = OUT_OF_NETWORK_BASE_JSON_VW.PRICING_FILE_KEY
WHERE FILE_TYPE_NAME = 'allowed-amounts'
