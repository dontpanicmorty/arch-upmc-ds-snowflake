CREATE OR REPLACE VIEW EXTRACTDATA.IN_NETWORK_FILE_BASE_SELECT_VW
AS
-- Returns everything needed for the base level of an in-network-file except
-- for the massive in_network array
SELECT PRICING_FILE.PRICING_FILE_KEY,
  FILE_TYPE_NAME,
  REPORTING_ENTITY_NAME,
  REPORTING_ENTITY_TYPE, 
  LAST_UPDATED_ON_DATE,
  '1.0.0' AS VERSION,
  PRICING_PROVIDER_REFERENCE_JSON
FROM EXTRACTDATA.PRICING_FILE 
-- Use direct link to reportingEntity instead of going through plan
LEFT JOIN EXTRACTDATA.REPORTING_ENTITY ON REPORTING_ENTITY.REPORTING_ENTITY_KEY = PRICING_FILE.REPORTING_ENTITY_KEY
LEFT JOIN EXTRACTDATA.PRICING_PROVIDER_REFERENCE_JSON_VW ON PRICING_FILE.PRICING_FILE_KEY = PRICING_PROVIDER_REFERENCE_JSON_VW.PRICING_FILE_KEY
WHERE FILE_TYPE_NAME = 'in-network-rates'
;