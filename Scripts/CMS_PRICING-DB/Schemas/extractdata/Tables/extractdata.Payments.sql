CREATE OR REPLACE TABLE
	EXTRACTDATA.PAYMENTS (
		PAYMENTS_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL UNIQUE,
		INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		ALLOWED_AMOUNTS_KEY NUMBER(38,0),
		ALLOWED_AMT NUMBER(20,2) NOT NULL,
		BILLING_CODE_MODIFIERS ARRAY NOT NULL,
		CONSTRAINT FK_PAYMENTS_ALLOWED_AMOUNTS FOREIGN KEY (ALLOWED_AMOUNTS_KEY) REFERENCES EXTRACTDATA.ALLOWED_AMOUNTS (ALLOWED_AMOUNTS_KEY),
		CONSTRAINT PK_PAYMENTS PRIMARY KEY (PAYMENTS_KEY),
		CONSTRAINT UK_PAYMENTS UNIQUE (ALLOWED_AMT, BILLING_CODE_MODIFIERS, ALLOWED_AMOUNTS_KEY)
	)
	 COMMENT='Payment amounts for out of network and the providers related to it';