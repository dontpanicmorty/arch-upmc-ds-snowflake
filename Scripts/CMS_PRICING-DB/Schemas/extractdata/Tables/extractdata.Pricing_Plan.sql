		CONSTRAINT FK_PRICING_PLAN_REPORTING_ENTITY FOREIGN KEY (REPORTING_ENTITY_KEY) REFERENCES EXTRACTDATA.REPORTING_ENTITY (REPORTING_ENTITY_KEY),
