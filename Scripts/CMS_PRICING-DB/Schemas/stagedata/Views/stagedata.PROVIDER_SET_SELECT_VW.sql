-- Meant to map structures in RAWDATA/IDAP_LAKE
!set variable_substitution=true;

CREATE OR REPLACE VIEW STAGEDATA.PROVIDER_SET_SELECT_VW
AS
SELECT DERIVED_TAXID AS TAX_ID_NBR,
    TAXID_TYPE AS TAX_ID_TYPE_CODE,
    ARRAY_AGG(DISTINCT NPI) WITHIN GROUP (ORDER BY NPI ASC) AS NPI_NBR
FROM STAGEDATA.INPATIENT_FEE_SCHEDULE_SELECT_HOLD

INNER JOIN STAGEDATA.FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW ON 
    INPATIENT_FEE_SCHEDULE_SELECT_HOLD.SCHEDULE_TYPE = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SCHEDULE_TYPE AND
    INPATIENT_FEE_SCHEDULE_SELECT_HOLD.SEGMENT = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SEGMENT

INNER JOIN STAGEDATA.PROVIDER_NETWORKS_VW PROVIDER_NETWORKS ON
    PROVIDER_NETWORKS.PROVIDER_TYPE = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROVIDER_TYPE AND
    PROVIDER_NETWORKS.PRICING_NETWORK_NAME = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROV_SET AND
    INPATIENT_FEE_SCHEDULE_SELECT_HOLD.VENDOR = PROVIDER_NETWORKS.VENDOR_ID

GROUP BY FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROVIDER_TYPE,
    FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROV_SET,
    INPATIENT_FEE_SCHEDULE_SELECT_HOLD.SEGMENT,
    INPATIENT_FEE_SCHEDULE_SELECT_HOLD.SCHEDULE_TYPE,
    DERIVED_TAXID, TAXID_TYPE


UNION 


SELECT DERIVED_TAXID AS TAX_ID_NBR,
    TAXID_TYPE AS TAX_ID_TYPE_CODE,
    ARRAY_AGG(DISTINCT NPI) WITHIN GROUP (ORDER BY NPI ASC) AS NPI_NBR
FROM (
  -- Restrict to distinct combinations to avoid dupes
  SELECT DISTINCT SCHEDULE_TYPE, SEGMENT, SCHEDULE_DETAIL, STATE, MATCH_STATE
  FROM STAGEDATA.PRACTITIONER_FEE_SCHEDULE_SELECT_HOLD
) PRACTITIONER_FEE_SCHEDULE

INNER JOIN STAGEDATA.FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW ON
  PRACTITIONER_FEE_SCHEDULE.SCHEDULE_TYPE = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SCHEDULE_TYPE AND
  PRACTITIONER_FEE_SCHEDULE.SEGMENT = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SEGMENT AND
  PRACTITIONER_FEE_SCHEDULE.SCHEDULE_DETAIL = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SCHEDULE_DETAIL

INNER JOIN STAGEDATA.PROVIDER_NETWORKS_VW PROVIDER_NETWORKS ON
    PROVIDER_NETWORKS.PROVIDER_TYPE = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROVIDER_TYPE AND
    PROVIDER_NETWORKS.PRICING_NETWORK_NAME = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROV_SET

INNER JOIN STAGEDATA.VENDOR_STATE_VW ON
    VENDOR_STATE_VW.VENDOR_ID = PROVIDER_NETWORKS.VENDOR_ID AND 
        CASE WHEN PRACTITIONER_FEE_SCHEDULE.MATCH_STATE = 'Y'
            THEN VENDOR_STATE_VW.VENDOR_STATE = PRACTITIONER_FEE_SCHEDULE.STATE
            ELSE 1
            END
      

GROUP BY FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROVIDER_TYPE,
    FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROV_SET,
    PRACTITIONER_FEE_SCHEDULE.SEGMENT,
    PRACTITIONER_FEE_SCHEDULE.SCHEDULE_DETAIL,
    PRACTITIONER_FEE_SCHEDULE.SCHEDULE_TYPE,
    STATE, MATCH_STATE,
    DERIVED_TAXID, TAXID_TYPE
;
!set variable_substitution=false;