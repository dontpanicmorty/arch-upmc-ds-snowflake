--GATHERS DATA NEEDED FROM CONTRACTS TABLE
CREATE OR REPLACE VIEW STAGEDATA.MRF_CONTRACTS_VW
AS
(
WITH MRF_CONTRACTS AS (
SELECT DWOAO_CONTRACTS.PROVIDERNBR AS PROVIDER_NBR
,DWOAO_CONTRACTS.PLANTYPE AS PLAN_TYPE
,DWOAO_CONTRACTS.PROVIDERIPACODE AS PROVIDER_IPA_CODE
,DWOAO_CONTRACTS.EFFECTIVEDATE AS EFFECTIVE_DATE
,DWOAO_CONTRACTS.TERMDATE AS TERM_DATE
,COALESCE(DWOAO_CONTRACTS.GROUPCARRIER, 'NoValue') AS GROUP_CARRIER
,DWOAO_PROVIDERSPECIALTY.SPECIALTY AS PROVIDER_TYPE
,DWOAO_PROVIDERAFFILIATION.RENDERINGPROVAFFILIATION AS RENDERING_PROV_AFFILIATION
FROM RAWDATA.DWOAO_CONTRACTS
    INNER JOIN RAWDATA.DWOAO_PROVIDERS
        ON DWOAO_CONTRACTS.PROVIDERNBR = DWOAO_PROVIDERS.PROVIDERNBR
    INNER JOIN RAWDATA.DWOAO_PROVIDERSPECIALTY
        ON DWOAO_PROVIDERS.PRIMARYSPECIALTY = DWOAO_PROVIDERSPECIALTY.SPECIALTY
    LEFT OUTER JOIN RAWDATA.DWOAO_PROVIDERAFFILIATION
        ON DWOAO_PROVIDERAFFILIATION.PHYSICIANGROUP = DWOAO_CONTRACTS.PROVIDERNBR 
        AND DWOAO_PROVIDERAFFILIATION.PLANTYPE = DWOAO_CONTRACTS.PLANTYPE 
        AND DWOAO_CONTRACTS.PROVIDERIPACODE = DWOAO_PROVIDERAFFILIATION.MEMBERIPA
    WHERE DWOAO_CONTRACTS.PLANTYPE IN (SELECT PLAN_TYPE_CODE FROM STAGEDATA.PLAN_TYPE)
    AND DWOAO_CONTRACTS.PROVIDERIPACODE IN (SELECT IPA_CODE FROM STAGEDATA.IPA)
)
--ADDING SPECIALTY FOR RENDERING PROVIDERS
SELECT MRF_CONTRACTS.PROVIDER_NBR
,PLAN_TYPE
,PROVIDER_IPA_CODE
,EFFECTIVE_DATE
,TERM_DATE
,GROUP_CARRIER
,PROVIDER_TYPE
,RENDERING_PROV_AFFILIATION
,PRIMARYSPECIALTY AS RENDERINGPROVAFFILIATION_PROVIDERTYPE
FROM MRF_CONTRACTS
    LEFT JOIN RAWDATA.DWOAO_PROVIDERS
        ON MRF_CONTRACTS.RENDERING_PROV_AFFILIATION = DWOAO_PROVIDERS.PROVIDERNBR
);