!set variable_substitution=true;

create or replace view STAGEDATA.PRICING_RULE_065_VW
AS
(
WITH STEP1 AS
(
/***
First need to find records that go through Rule 050 Logic
******/

SELECT DISTINCT
    MRF_PROVIDER_PRICING_HISTORY_VW.PROVIDER_NBR AS VENDOR_ID,
    MRF_CONTRACTS_VW.PROVIDER_TYPE AS PROVIDER_TYPE,
    CASE When MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE in ('N','O') THEN '102'
        WHEN MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE = 'H' AND MRF_PROVIDER_PRICING_HISTORY_VW.GROUP_CARRIER_PRICE_GROUP = 'NoValue' Then 'Standard'
    WHEN MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE = 'H' AND MRF_PROVIDER_PRICING_HISTORY_VW.GROUP_CARRIER_PRICE_GROUP = 'FED65' Then '100' END AS SEGMENT,
	MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE AS PLAN_TYPE,
    MRF_PROVIDER_PRICING_HISTORY_VW.IPA_PRICE_GROUP AS IPA_CODE,
    MRF_PROVIDER_PRICING_HISTORY_VW.PLACE_OF_SERVICE AS POS_CODE,
    MRF_PROVIDER_PRICING_HISTORY_VW.GROUP_CARRIER_PRICE_GROUP AS CARRIER_GROUP,
	MRF_PROVIDER_PRICING_HISTORY_VW.CASE_RATE_SCHEDULE AS CASE_RATE_SCHEDULE,
    MRF_PROVIDER_PRICING_HISTORY_VW.CUSTOM_PRICING_RULE_SET AS CUSTOM_PRICE_RULESET,
    MRF_PROVIDER_PRICING_HISTORY_VW.PRICING_RULE as PRICING_RULE,
    MRF_PRICE_CATEGORY_VW.PRICE_CATEGORY,
    MRF_PRICE_CATEGORY_VW.PRICE_CAT_SEQUENCE AS PRICE_CATEGORY_SEQ,
    MRF_FEE_SCHEDULE_VW.PROCEDURE_CODE,
    MRF_FEE_SCHEDULE_VW.MODIFIER,
    MRF_FEE_SCHEDULE_VW.PROCEDURE_MODIFIER_CONCAT,
    MRF_FEE_SCHEDULE_VW.PRICE,
	MRF_FEE_SCHEDULE_VW.PERCENTAGE,
    NULL  AS PRICE_RULE_CODE                      
--select *
FROM StageData.MRF_PROVIDER_PRICING_HISTORY_VW
	JOIN StageData.MRF_CONTRACTS_VW on MRF_CONTRACTS_VW.PROVIDER_NBR = MRF_PROVIDER_PRICING_HISTORY_VW.PROVIDER_NBR and
	MRF_CONTRACTS_VW.PLAN_TYPE = MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE AND MRF_CONTRACTS_VW.PROVIDER_IPA_CODE = MRF_PROVIDER_PRICING_HISTORY_VW.IPA_PRICE_GROUP and MRF_CONTRACTS_VW.GROUP_CARRIER = MRF_PROVIDER_PRICING_HISTORY_VW.GROUP_CARRIER_PRICE_GROUP
   JOIN StageData.MRF_PRICE_CATEGORY_VW on MRF_PROVIDER_PRICING_HISTORY_VW.PROVIDER_NBR = MRF_PRICE_CATEGORY_VW.VENDOR_ID
	AND MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE = MRF_PRICE_CATEGORY_VW.PLAN_TYPE AND   MRF_PROVIDER_PRICING_HISTORY_VW.IPA_PRICE_GROUP = MRF_PRICE_CATEGORY_VW.IPA_CODE
	AND MRF_PROVIDER_PRICING_HISTORY_VW.PLACE_OF_SERVICE = MRF_PRICE_CATEGORY_VW.PLACE_OF_SERVICE AND MRF_PROVIDER_PRICING_HISTORY_VW.GROUP_CARRIER_PRICE_GROUP = MRF_PRICE_CATEGORY_VW.GROUP_CARRIER_PRICE_GROUP
 	JOIN StageData.MRF_FEE_SCHEDULE_VW on MRF_PRICE_CATEGORY_VW.PRICE_CATEGORY = MRF_FEE_SCHEDULE_VW.PRICE_CATEGORY
     WHERE MRF_PROVIDER_PRICING_HISTORY_VW.PRICING_RULE = '065' AND MRF_CONTRACTS_VW.PROVIDER_TYPE in ('INST-HOSP') AND MRF_PROVIDER_PRICING_HISTORY_VW.PLACE_OF_SERVICE = 'NoValue' And MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE in ('H','N','O')
UNION
/***
Next need to find remaining codes to go through 009 Percent of Billed
******/

SELECT DISTINCT
    MRF_PROVIDER_PRICING_HISTORY_VW.PROVIDER_NBR AS VENDOR_ID,
    MRF_CONTRACTS_VW.PROVIDER_TYPE AS PROVIDER_TYPE,
    CASE When MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE in ('N','O') THEN '102'
        WHEN MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE = 'H' AND MRF_PROVIDER_PRICING_HISTORY_VW.GROUP_CARRIER_PRICE_GROUP = 'NoValue' Then 'Standard'
    WHEN MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE = 'H' AND MRF_PROVIDER_PRICING_HISTORY_VW.GROUP_CARRIER_PRICE_GROUP = 'FED65' Then '100' END AS SEGMENT,
	MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE AS PLAN_TYPE,
    MRF_PROVIDER_PRICING_HISTORY_VW.IPA_PRICE_GROUP AS IPA_CODE,
    MRF_PROVIDER_PRICING_HISTORY_VW.PLACE_OF_SERVICE AS POS_CODE,
    MRF_PROVIDER_PRICING_HISTORY_VW.GROUP_CARRIER_PRICE_GROUP AS CARRIER_GROUP,
	MRF_PROVIDER_PRICING_HISTORY_VW.CASE_RATE_SCHEDULE AS CASE_RATE_SCHEDULE,
    MRF_PROVIDER_PRICING_HISTORY_VW.CUSTOM_PRICING_RULE_SET AS CUSTOM_PRICE_RULESET,
    MRF_PROVIDER_PRICING_HISTORY_VW.PRICING_RULE as PRICING_RULE,
    NULL AS PRICE_CATEGORY,
    NULL AS PRICE_CATEGORY_SEQ,
    NULL AS PROCEDURE_CODE,
    NULL AS MODIFIER,
    NULL AS PROCEDURE_MODIFIER_CONCAT,
    0.00 AS PRICE,
  MRF_PROVIDER_PRICING_HISTORY_VW.FACTOR_2 AS PERCENTAGE, -- This is the %HIAA Field needed for 065
    NULL  AS PRICE_RULE_CODE     
FROM StageData.MRF_PROVIDER_PRICING_HISTORY_VW
	    JOIN StageData.MRF_CONTRACTS_VW on MRF_CONTRACTS_VW.PROVIDER_NBR = MRF_PROVIDER_PRICING_HISTORY_VW.PROVIDER_NBR and
	        MRF_CONTRACTS_VW.PLAN_TYPE = MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE AND MRF_CONTRACTS_VW.PROVIDER_IPA_CODE = MRF_PROVIDER_PRICING_HISTORY_VW.IPA_PRICE_GROUP and MRF_CONTRACTS_VW.GROUP_CARRIER = MRF_PROVIDER_PRICING_HISTORY_VW.GROUP_CARRIER_PRICE_GROUP
        JOIN StageData.MRF_PRICE_CATEGORY_VW on MRF_PROVIDER_PRICING_HISTORY_VW.PROVIDER_NBR = MRF_PRICE_CATEGORY_VW.VENDOR_ID
	        AND MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE = MRF_PRICE_CATEGORY_VW.PLAN_TYPE AND   MRF_PROVIDER_PRICING_HISTORY_VW.IPA_PRICE_GROUP = MRF_PRICE_CATEGORY_VW.IPA_CODE
	        AND MRF_PROVIDER_PRICING_HISTORY_VW.PLACE_OF_SERVICE = MRF_PRICE_CATEGORY_VW.PLACE_OF_SERVICE AND MRF_PROVIDER_PRICING_HISTORY_VW.GROUP_CARRIER_PRICE_GROUP = MRF_PRICE_CATEGORY_VW.GROUP_CARRIER_PRICE_GROUP
 	  --  JOIN StageData.MRF_FEE_SCHEDULE_VW on MRF_PRICE_CATEGORY_VW.PRICE_CATEGORY = MRF_FEE_SCHEDULE_VW.PRICE_CATEGORY REMOVED 9/22/2022 JOIN was excluded vendors without Fee Schedule 
             WHERE MRF_PROVIDER_PRICING_HISTORY_VW.PRICING_RULE = '065'AND MRF_CONTRACTS_VW.PROVIDER_TYPE in ('INST-HOSP') AND MRF_PROVIDER_PRICING_HISTORY_VW.PLACE_OF_SERVICE = 'NoValue' And MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE IN ('H','N','O')
),
  
/***
Run the Flat Fee Schedule 050 Logic
*****/
FINAL050STEP AS
--GET FINAL PRICES BASED ON WHAT FEE SCHEDULE THEY HIT
(
SELECT DISTINCT
	VENDOR_ID,
	PRICE_CATEGORY AS FEE_SCHEDULE_NAME,
	NULL AS CASE_RATE_SCHEDULE,
    SEGMENT,
	PLAN_TYPE,
	PROVIDER_TYPE,
    IPA_CODE,
    POS_CODE,
	CARRIER_GROUP,
    PROCEDURE_CODE,
    MODIFIER, 
    PROCEDURE_MODIFIER_CONCAT,
	PRICE,
	Percentage
FROM
    (
    SELECT
       	VENDOR_ID,
    	CASE_RATE_SCHEDULE,
        SEGMENT,
	    PLAN_TYPE,
	    PROVIDER_TYPE,
        IPA_CODE,
        POS_CODE,
	    CARRIER_GROUP,
        PROCEDURE_CODE,
        MODIFIER, 
        PROCEDURE_MODIFIER_CONCAT,
	    PRICE,
	    PERCENTAGE,
        PRICE_CATEGORY,
        PRICE_CATEGORY_SEQ,
        RANK
    FROM
        (
        SELECT
      	VENDOR_ID,
    	CASE_RATE_SCHEDULE,
        SEGMENT,
	    PLAN_TYPE,
	    PROVIDER_TYPE,
        IPA_CODE,
        POS_CODE,
	    CARRIER_GROUP,
        PROCEDURE_CODE,
        MODIFIER, 
        PROCEDURE_MODIFIER_CONCAT,
	    PRICE,
	    Percentage,
        PRICE_CATEGORY,
        PRICE_CATEGORY_SEQ,
        ROW_NUMBER () OVER (PARTITION BY VENDOR_ID, PLAN_TYPE, IPA_CODE, CARRIER_GROUP, PRICING_RULE, PROCEDURE_MODIFIER_CONCAT ORDER BY PRICE_CATEGORY_SEQ ASC) AS RANK
        FROM
            STEP1 Where Price_Category is NOT NULL 

                 ) 
    WHERE 
        RANK = 1 
    ) 
GROUP BY
	VENDOR_ID,
	PRICE_CATEGORY,
	PLAN_TYPE,SEGMENT,
	PROVIDER_TYPE,
    IPA_CODE,
    POS_CODE,
	CARRIER_GROUP,
	PRICE,
	Percentage, 
    PROCEDURE_CODE,
    MODIFIER, 
    PROCEDURE_MODIFIER_CONCAT
  ),
   
PROCEDURE_CODES_CTE AS
(
SELECT DISTINCT 
  DWOAO_PROCEDURECODES.CODE
FROM RAWDATA.DWOAO_PROCEDURECODES
JOIN &{IDAP_LAKE}.PRICING.BILLING_CODE_LKP  
  ON BILLING_CODE_LKP.BILLING_CODE = DWOAO_PROCEDURECODES.CODE
WHERE BILLING_CODE_LKP.BILLING_CODE_TYPE IN ('CPT','HCPCS')AND DWOAO_PROCEDURECODES.ASACODEFLAG <> '1' 
 /**REMOVED 9/12/2022 AND NOT EXISTS (SELECT * FROM FINAL050STEP F2 WHERE F2.PROCEDURE_MODIFIER_CONCAT = PC.CODE)***/
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY1),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY2),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY3),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY4),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY5),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY6),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY7),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY8),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY9),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY10),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY11),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY12),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY13),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY14),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY15),'NULL') NOT IN ('ID','IP')
),
FINAL009STEP AS
(
SELECT DISTINCT
      	STEP1.VENDOR_ID,
    	STEP1.CASE_RATE_SCHEDULE,
        STEP1.SEGMENT,
	    STEP1.PLAN_TYPE,
	    STEP1.PROVIDER_TYPE,
        STEP1.IPA_CODE,
        STEP1.POS_CODE,
	    STEP1.CARRIER_GROUP,
        PROCEDURE_CODES_CTE.CODE AS PROCEDURE_CODE,
        NULL AS MODIFIER,
        PROCEDURE_CODES_CTE.CODE AS PROCEDURE_MODIFIER_CONCAT,
	    STEP1.PRICE,
	    STEP1.Percentage,
        STEP1.PRICE_CATEGORY AS FEE_SCHEDULE_NAME,
        STEP1.PRICE_CATEGORY_SEQ
FROM STEP1, PROCEDURE_CODES_CTE
WHERE STEP1.PRICE_CATEGORY IS NULL And STEP1.PRICE_RULE_CODE IS NULL AND  STEP1.Percentage > 0
/**Added in 9/12/2022****/
    AND NOT EXISTS (SELECT 1 FROM FINAL050STEP WHERE STEP1.VENDOR_ID = FINAL050STEP.VENDOR_ID AND PROCEDURE_CODES_CTE.CODE = FINAL050STEP.PROCEDURE_CODE)
),

FINAL_PULL AS(
Select DISTINCT
VENDOR_ID,FEE_SCHEDULE_NAME,SEGMENT,PLAN_TYPE,PROVIDER_TYPE, IPA_CODE,POS_CODE,CARRIER_GROUP,PROCEDURE_CODE,MODIFIER,PROCEDURE_MODIFIER_CONCAT,PRICE,PERCENTAGE from FINAL050STEP
UNION ALL
Select DISTINCT
VENDOR_ID,FEE_SCHEDULE_NAME,SEGMENT,PLAN_TYPE,PROVIDER_TYPE, IPA_CODE,POS_CODE,CARRIER_GROUP,PROCEDURE_CODE,MODIFIER,PROCEDURE_MODIFIER_CONCAT,PRICE,PERCENTAGE from FINAL009STEP
Order BY PROCEDURE_MODIFIER_CONCAT
)

SELECT
  'INPATIENT' AS SCHEDULE_TYPE,
  UPPER(SEGMENT) AS SEGMENT,
  VENDOR_ID AS VENDOR,
  PROCEDURE_CODE AS BILLING_CODE,
  MODIFIER AS BILLING_CODE_MODIFIER,
  --PROCEDURE_MODIFIER_CONCAT AS BILLING_CODE,
  NULL AS MS_DRG_TITLE,
  CASE WHEN PRICE <> 0.00 THEN PRICE
       WHEN PRICE = 0.00 THEN PERCENTAGE END AS RATE,
  CASE WHEN PRICE <> 0.00 THEN 'negotiated' 
       WHEN PRICE = 0.00 THEN 'percentage' END AS NEGOTIATION_TYPE,
  TO_CHAR(SYSDATE(), 'MM/DD/YYYY') AS FILE_DATE,
  NULL AS ADDITIONAL_INFORMATION
  FROM FINAL_PULL
);

