CREATE OR REPLACE VIEW STAGEDATA.MRF_VENDOR_PRICE_FINAL_VW
AS
(
SELECT DISTINCT MRF_CONTRACTS_VW.PROVIDER_NBR AS VENDOR_ID
,MRF_CONTRACTS_VW.PROVIDER_TYPE AS PROVIDER_TYPE
,MRF_CONTRACTS_VW.RENDERING_PROV_AFFILIATION AS RENDERING_PROV_AFFILIATION
,MRF_CONTRACTS_VW.RENDERINGPROVAFFILIATION_PROVIDERTYPE AS RENDERING_PROV_AFFILIATION_PROVIDER_TYPE
,MRF_CONTRACTS_VW.PLAN_TYPE AS PLAN_TYPE
,MRF_CONTRACTS_VW.PROVIDER_IPA_CODE AS PROVIDER_IPA_CODE
,MRF_PROVIDER_PRICING_HISTORY_VW.PLACE_OF_SERVICE AS PLACE_OF_SERVICE
,MRF_PROVIDER_PRICING_HISTORY_VW.GROUP_CARRIER_PRICE_GROUP AS GROUP_CARRIER_PRICE_GROUP
,MRF_PROVIDER_PRICING_HISTORY_VW.CASE_RATE_SCHEDULE 
,MRF_PROVIDER_PRICING_HISTORY_VW.PERCENTAGE
,MRF_PROVIDER_PRICING_HISTORY_VW.CUSTOM_PRICING_RULE_SET 
,MRF_PROVIDER_PRICING_HISTORY_VW.PRICING_RULE 
,MRF_PROVIDER_PRICING_HISTORY_VW.PROVIDER_TYPE_SCHEDULE 
,DWOAO_PROVIDERTYPESCHEDULE.PRICECATEGORY AS PRICE_CATEGORY
,PRICE_CATEGORY.PRICE_CATEGORY_KEY
,DWOAO_PROVIDERTYPESCHEDULE.PROVIDERTYPESCHEDULESEQNBR AS PROVIDER_TYPE_SCHEDULE_SEQ
FROM STAGEDATA.MRF_CONTRACTS_VW
	JOIN STAGEDATA.MRF_PROVIDER_PRICING_HISTORY_VW 
        ON MRF_CONTRACTS_VW.PROVIDER_NBR = MRF_PROVIDER_PRICING_HISTORY_VW.PROVIDER_NBR 
            AND MRF_CONTRACTS_VW.PLAN_TYPE = MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE 
            AND MRF_CONTRACTS_VW.PROVIDER_IPA_CODE = MRF_PROVIDER_PRICING_HISTORY_VW.IPA_PRICE_GROUP
	LEFT JOIN RAWDATA.DWOAO_PROVIDERTYPESCHEDULE 
        ON  PROVIDERTYPESCHEDULE = MRF_PROVIDER_PRICING_HISTORY_VW.PROVIDER_TYPE_SCHEDULE 
            AND MRF_CONTRACTS_VW.RENDERINGPROVAFFILIATION_PROVIDERTYPE = DWOAO_PROVIDERTYPESCHEDULE.PROVIDERTYPE
    INNER JOIN STAGEDATA.PRICE_CATEGORY --removes NULL priceCategories
        ON PRICE_CATEGORY.PRICE_CATEGORY_NAME = DWOAO_PROVIDERTYPESCHEDULE.PRICECATEGORY
);