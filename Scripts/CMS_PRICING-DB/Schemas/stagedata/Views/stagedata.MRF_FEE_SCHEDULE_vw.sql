create or replace view STAGEDATA.MRF_FEE_SCHEDULE_VW 
AS
(
SELECT DWOAO_PRICECATEGORYPROCEDURE.PRICECATEGORY AS PRICE_CATEGORY
,DWOAO_PRICECATEGORYPROCEDURE.PROCEDURECODE AS PROCEDURE_CODE
,DWOAO_PRICECATEGORYPROCEDURE.MODIFIER
,CASE WHEN DWOAO_PRICECATEGORYPROCEDURE.MODIFIER IS NULL 
        THEN DWOAO_PRICECATEGORYPROCEDURE.PROCEDURECODE 
      ELSE CONCAT (DWOAO_PRICECATEGORYPROCEDURE.PROCEDURECODE,DWOAO_PRICECATEGORYPROCEDURE.MODIFIER) 
      END AS PROCEDURE_MODIFIER_CONCAT
,DWOAO_PRICECATEGORYPROCEDURE.EFFECTIVEDATE AS EFFECTIVE_DATE
,DWOAO_PRICECATEGORYPROCEDURE.TERMDATE AS TERM_DATE
,DWOAO_PRICECATEGORYPROCEDURE.PRICETYPE AS PRICE_TYPE
,DWOAO_PRICECATEGORYPROCEDURE.DAYSINCLUDED AS DAYS_INCLUDED
,DWOAO_PRICECATEGORYPROCEDURE.PROCESSINGCODES AS PROCESSING_CODES
,DWOAO_PRICECATEGORYPROCEDURE.PRICE
,DWOAO_PRICECATEGORYPROCEDURE.PERCENTAGE
,DWOAO_PRICECATEGORYPROCEDURE.WITHHOLDPERCENTAGE AS WITHHOLD_PERCENTAGE
,DWOAO_PRICECATEGORYPROCEDURE.ADJUSTMENTREASON AS ADJUSTMENT_REASON
,DWOAO_PRICECATEGORYPROCEDURE.ALLOWEDBILLEDAMTFLAG AS ALLOWED_BILLED_AMT_FLAG
,DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY1 AS PROC_CODE_CATEGORY_1
,DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY2 AS PROC_CODE_CATEGORY_2
,DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY3 AS PROC_CODE_CATEGORY_3
,DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY4 AS PROC_CODE_CATEGORY_4
,DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY5 AS PROC_CODE_CATEGORY_5
,DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY6 AS PROC_CODE_CATEGORY_6
,DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY7 AS PROC_CODE_CATEGORY_7
,DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY8 AS PROC_CODE_CATEGORY_8
,DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY9 AS PROC_CODE_CATEGORY_9
,DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY10 AS PROC_CODE_CATEGORY_10
,DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY11 AS PROC_CODE_CATEGORY_11
,DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY12 AS PROC_CODE_CATEGORY_12
,DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY13 AS PROC_CODE_CATEGORY_13
,DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY14 AS PROC_CODE_CATEGORY_14
,DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY15 AS PROC_CODE_CATEGORY_15
,PRICE_CATEGORY.PRICE_CATEGORY_KEY
FROM RAWDATA.DWOAO_PRICECATEGORYPROCEDURE   
        JOIN STAGEDATA.PRICE_CATEGORY
        ON PRICE_CATEGORY.PRICE_CATEGORY_name = DWOAO_PRICECATEGORYPROCEDURE.PRICECATEGORY
WHERE DWOAO_PRICECATEGORYPROCEDURE.PRICECATEGORY NOT IN ('90999','ANCILL','CARDNO','CRHDEF','DEFHMK','DEFPRV','DEFTMC','DEFTMH','DEFTSL','DENYNC','FAKEMH','GEXCEP',
        'MC45%','MCPQRS','MODCG','MVOBIN','NCCHRG','NOPAY','NPMODA','OBERSU','OBSDEF','OBSINC','PHASUP','PHC38','REVRUL','SCH2GE','SCH3GE','SURG45','SWADFT','WHEEL','XRHDEF') --Removed '2DMAMM','ADJUNC'
AND IFNULL(TRIM(DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY1),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY2),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY3),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY4),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY5),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY6),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY7),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY8),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY9),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY10),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY11),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY12),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY13),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY14),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PRICECATEGORYPROCEDURE.PROCCODECATEGORY15),'NULL') NOT IN ('ID','IP')
AND NOT (DWOAO_PRICECATEGORYPROCEDURE.PERCENTAGE = 1.00 AND DWOAO_PRICECATEGORYPROCEDURE.PROCESSINGCODES IS NOT NULL)
);