CREATE OR REPLACE VIEW STAGEDATA.IN_NETWORK_BASE_SELECT_VW
AS
-- Crosswalk from plan_info to billing_codes, effectively
WITH BILLING_CODE_LKP AS (
  SELECT DISTINCT NEGOTIATED_PRICE_INTERNAL_HOLD.SEGMENT, 
    NEGOTIATED_PRICE_INTERNAL_HOLD.PROV_SET, 
    NEGOTIATED_PRICE_INTERNAL_HOLD.BILLING_CODE
  FROM STAGEDATA.FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW
    
  LEFT OUTER JOIN STAGEDATA.NEGOTIATED_PRICE_INTERNAL_HOLD ON
    NEGOTIATED_PRICE_INTERNAL_HOLD.PROV_SET = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROV_SET AND
    NEGOTIATED_PRICE_INTERNAL_HOLD.PROVIDER_TYPE = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROVIDER_TYPE AND
    NEGOTIATED_PRICE_INTERNAL_HOLD.SEGMENT = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SEGMENT AND
    NEGOTIATED_PRICE_INTERNAL_HOLD.SCHEDULE_DETAIL = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SCHEDULE_DETAIL
)

SELECT BILLING_CODE_LKP.BILLING_CODE, -- for internal joins
    PRICING_FILE_KEY, 
    'ffs' AS NEGOTIATION_ARRANGEMENT_NAME,
    SERVICE_NAME,
    BILLING_CODE_KEY
    
FROM STAGEDATA.PRICING_FILE_SELECT_VW

INNER JOIN EXTRACTDATA.PRICING_FILE ON
    PRICING_FILE.FILE_DESC = PRICING_FILE_SELECT_VW.FILE_DESC
    
INNER JOIN BILLING_CODE_LKP ON 
    PRICING_FILE_SELECT_VW.SEGMENT = BILLING_CODE_LKP.SEGMENT AND
    PRICING_FILE_SELECT_VW.PROV_SET = BILLING_CODE_LKP.PROV_SET

INNER JOIN STAGEDATA.BILLING_CODE_INTERNAL_VW ON
    BILLING_CODE_INTERNAL_VW.BILLING_CODE = BILLING_CODE_LKP.BILLING_CODE AND
    CURRENT_DATE >=  CAST(BILLING_CODE_INTERNAL_VW.START_DATE AS DATE)AND
    CURRENT_DATE <= CAST(BILLING_CODE_INTERNAL_VW.END_DATE AS DATE)


INNER JOIN EXTRACTDATA.BILLING_CODE ON
    BILLING_CODE.BILLING_CODE = BILLING_CODE_LKP.BILLING_CODE AND
    BILLING_CODE.BILLING_CODE_TYPE_VERSION_TEXT = BILLING_CODE_INTERNAL_VW.BILLING_CODE_TYPE_VERSION_TEXT

WHERE PRICING_FILE_SELECT_VW.FILE_TYPE_NAME = 'in-network-rates'
;
