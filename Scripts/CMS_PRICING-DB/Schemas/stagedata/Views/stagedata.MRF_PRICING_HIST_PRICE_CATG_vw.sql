--Data needed from the PRICINGHISTPRICECATG table To generate sequences
CREATE OR REPLACE VIEW STAGEDATA.MRF_PRICING_HIST_PRICE_CATG_VW
AS
(
SELECT PC.PROVIDERNO AS PROVIDER_NBR
,PC.ENTITY 
,PC.GROUPCARRIERPRICEGROUP AS GROUP_CARRIER_PRICE_GROUP
,PC.IPAPRICEGROUP AS IPA_PRICE_GROUP
,PC.PLACEOFSERVICE AS PLACE_OF_SERVICE
,PC.PLANTYPE AS PLAN_TYPE
,PC.EFFECTIVEDATE AS EFFECTIVE_DATE
,PC.POSUSERDEFINEDFIELD AS POS_USER_DEFINED_FIELD
,PC.PRICECATEGORY AS PRICE_CATEGORY
,PC.PRICECATSEQUENCE AS PRICE_CAT_SEQUENCE
,PC.REIMBURSEMENTFLAG AS REIMBURSEMENT_FLAG
,PC.TERMDATE AS TERM_DATE
FROM RAWDATA.DWOAO_PRICINGHISTPRICECATG PC
  INNER JOIN STAGEDATA.MRF_ACTIVE_PROVIDER_PRICING_VW HP
	  ON PC.PROVIDERNO = HP.PROVIDER_NBR
        AND COALESCE(PC.PLANTYPE,'NULL') = COALESCE(HP.PLAN_TYPE,'NULL')
		    AND COALESCE(PC.IPAPRICEGROUP,'NULL') = COALESCE(HP.IPA_PRICE_GROUP,'NULL')
		    AND COALESCE(PC.GROUPCARRIERPRICEGROUP,'NULL') = COALESCE(HP.GROUP_CARRIER_PRICE_GROUP,'NULL')
		    AND COALESCE(PC.PLACEOFSERVICE,'NULL') = COALESCE(HP.PLACE_OF_SERVICE,'NULL')
		    AND PC.EFFECTIVEDATE = HP.EFFECTIVE_DATE
WHERE COALESCE(GROUPCARRIERPRICEGROUP, 'NoValue') IN (SELECT GROUP_CARRIER_PRICE_GROUP_CODE FROM STAGEDATA.GROUP_CARRIER_PRICE_GROUP)			
ORDER BY pc.ProviderNo, pc.PlanType	
);