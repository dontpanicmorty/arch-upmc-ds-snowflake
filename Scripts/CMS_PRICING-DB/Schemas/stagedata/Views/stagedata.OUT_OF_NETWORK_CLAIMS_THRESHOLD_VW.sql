CREATE OR REPLACE VIEW STAGEDATA.OUT_OF_NETWORK_CLAIMS_THRESHOLD_VW
AS
 SELECT A.BILLING_PROVIDER_ID, 
 A.TAX_ID, 
 A.PROVIDER_TYPE, 
 A.NPI, 
 A.CLAIM_NBR, 
 A.CLAIM_IPA_CODE, 
 A.ALLOW_AMT, 
 A.CHARGE_AMT, 
 A.PLACE_OF_SERVICE_CODE, 
 A.BILLING_CODE, 
 A.BILLING_CODE_MODIFIER, 
 A.PLAN_CODE, 
 A.EMPLOYERTIN, 
 A.CLAIM_TYPE,
 STAGEDATA.FXN_MAKE_ALLOWED_AMOUNTS_FILE_DESC(A.PLAN_CODE, p.THRESHOLD_GROUPING, p.PLAN_ID) AS OUT_OF_NETWORK_FILE_DESC
FROM     RAWDATA.DWOAO_OUT_OF_NETWORK_CLAIMS A 
JOIN &{IDAP_LAKE}.PRICING.PLAN_INFO  p ON p.PLAN_CODE = a.PLAN_CODE AND THRESHOLD_GROUPING = 'PLAN_CODE' 
JOIN ( SELECT  TAX_ID, NPI, PLACE_OF_SERVICE_CODE,PLAN_CODE,BILLING_CODE, COUNT(*) AS count
        FROM     RAWDATA.DWOAO_OUT_OF_NETWORK_CLAIMS A2
	    GROUP BY TAX_ID, NPI, PLACE_OF_SERVICE_CODE, PLAN_CODE, BILLING_CODE
		HAVING COUNT(*) >= 20) y ON y.TAX_ID = A.TAX_ID AND y.NPI = A.NPI AND y.PLACE_OF_SERVICE_CODE = A.PLACE_OF_SERVICE_CODE AND y.PLAN_CODE = A.PLAN_CODE AND y.BILLING_CODE = A.BILLING_CODE
WHERE ALLOW_AMT > 0 
UNION
 /**
Claims that should use Threshold Grouping by CLIENT_GROUP
 ****/
 SELECT  
 A.BILLING_PROVIDER_ID, 
 A.TAX_ID, 
 A.PROVIDER_TYPE, 
 A.NPI, 
 A.CLAIM_NBR, 
 A.CLAIM_IPA_CODE, 
 A.ALLOW_AMT, 
 A.CHARGE_AMT, 
 A.PLACE_OF_SERVICE_CODE, 
 A.BILLING_CODE, 
 A.BILLING_CODE_MODIFIER, 
 A.PLAN_CODE, 
 A.EMPLOYERTIN, 
 A.CLAIM_TYPE,
 STAGEDATA.FXN_MAKE_ALLOWED_AMOUNTS_FILE_DESC(A.PLAN_CODE, p.THRESHOLD_GROUPING, p.PLAN_ID) AS OUT_OF_NETWORK_FILE_DESC
FROM    RAWDATA.DWOAO_OUT_OF_NETWORK_CLAIMS A 
JOIN &{IDAP_LAKE}.PRICING.PLAN_INFO  p ON p.PLAN_CODE = a.PLAN_CODE AND EmployerTIN = p.PLAN_ID AND THRESHOLD_GROUPING = 'CLIENT_GROUP'
JOIN ( SELECT  TAX_ID, NPI, PLACE_OF_SERVICE_CODE,PLAN_CODE,BILLING_CODE,EmployerTIN, COUNT(*) AS count
        FROM    RAWDATA.DWOAO_OUT_OF_NETWORK_CLAIMS A2
	    GROUP BY TAX_ID, NPI, PLACE_OF_SERVICE_CODE,PLAN_CODE, BILLING_CODE,EmployerTIN
		 HAVING COUNT(*) >= 20) y ON y.TAX_ID = A.TAX_ID AND y.NPI = A.NPI AND y.PLACE_OF_SERVICE_CODE = A.PLACE_OF_SERVICE_CODE AND y.PLAN_CODE = A.PLAN_CODE AND y.BILLING_CODE = A.BILLING_CODE
			AND y.EmployerTIN = A.EmployerTIN
WHERE ALLOW_AMT > 0 
;

!set variable_substitution=false;
