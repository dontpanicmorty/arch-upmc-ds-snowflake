!set variable_substitution=true;

create or replace view STAGEDATA.PRICING_RULE_009_VW
AS
(
WITH STEP1 AS
(
SELECT DISTINCT
MRF_PROVIDER_PRICING_HISTORY_VW.PROVIDER_NBR AS VENDOR_ID,
MRF_CONTRACTS_VW.PROVIDER_TYPE,
CASE When MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE in ('N','O') THEN '102'
    WHEN MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE = 'H' AND MRF_PROVIDER_PRICING_HISTORY_VW.GROUP_CARRIER_PRICE_GROUP = 'NoValue' Then 'Standard'
    WHEN MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE = 'H' AND MRF_PROVIDER_PRICING_HISTORY_VW.GROUP_CARRIER_PRICE_GROUP = 'FED65' Then '100' END AS SEGMENT,
MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE,
MRF_PROVIDER_PRICING_HISTORY_VW.IPA_PRICE_GROUP,
MRF_PROVIDER_PRICING_HISTORY_VW.PLACE_OF_SERVICE,
MRF_PROVIDER_PRICING_HISTORY_VW.GROUP_CARRIER_PRICE_GROUP,
MRF_PROVIDER_PRICING_HISTORY_VW.CUSTOM_PRICING_RULE_SET,
MRF_PROVIDER_PRICING_HISTORY_VW.PRICING_RULE,
0.00 AS PRICE,
MRF_PROVIDER_PRICING_HISTORY_VW.PERCENTAGE
FROM STAGEDATA.MRF_PROVIDER_PRICING_HISTORY_VW 
JOIN STAGEDATA.MRF_CONTRACTS_VW
    ON MRF_CONTRACTS_VW.PROVIDER_NBR = MRF_PROVIDER_PRICING_HISTORY_VW.PROVIDER_NBR 
        AND MRF_CONTRACTS_VW.PLAN_TYPE = MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE
        AND MRF_CONTRACTS_VW.PROVIDER_IPA_CODE = MRF_PROVIDER_PRICING_HISTORY_VW.IPA_PRICE_GROUP
        AND MRF_CONTRACTS_VW.GROUP_CARRIER = MRF_PROVIDER_PRICING_HISTORY_VW.GROUP_CARRIER_PRICE_GROUP
WHERE
MRF_PROVIDER_PRICING_HISTORY_VW.PRICING_RULE IN ('009') AND MRF_CONTRACTS_VW.PROVIDER_TYPE in ('INST-HOSP') AND MRF_PROVIDER_PRICING_HISTORY_VW.PLACE_OF_SERVICE = 'NoValue' And MRF_PROVIDER_PRICING_HISTORY_VW.PLAN_TYPE in ('H','N','O')
),

PROCEDURE_CODES_CTE AS
(
SELECT DISTINCT DWOAO_PROCEDURECODES.CODE
FROM RAWDATA.DWOAO_PROCEDURECODES JOIN &{IDAP_LAKE}.PRICING.BILLING_CODE_LKP ON BILLING_CODE_LKP.BILLING_CODE = DWOAO_PROCEDURECODES.CODE
  WHERE BILLING_CODE_LKP.BILLING_CODE_TYPE IN ('CPT','HCPCS')AND DWOAO_PROCEDURECODES.ASACODEFLAG <> '1'
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY1),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY2),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY3),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY4),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY5),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY6),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY7),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY8),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY9),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY10),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY11),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY12),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY13),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY14),'NULL') NOT IN ('ID','IP')
AND IFNULL(TRIM(DWOAO_PROCEDURECODES.PROCCODECATEGORY15),'NULL') NOT IN ('ID','IP')
),
  
FINAL_PULL AS(
SELECT DISTINCT
STEP1.VENDOR_ID,
' ' AS FEE_SCHEDULE_NAME,
STEP1.SEGMENT,
STEP1.PLAN_TYPE,
STEP1.PROVIDER_TYPE,
STEP1.IPA_PRICE_GROUP,
STEP1.PLACE_OF_SERVICE,
STEP1.GROUP_CARRIER_PRICE_GROUP,
PROCEDURE_CODES_CTE.CODE AS PROCEDURE_CODE,
NULL AS MODIFIER,
STEP1.PRICE,
STEP1.PERCENTAGE
FROM STEP1 , PROCEDURE_CODES_CTE
)
  
SELECT
  'INPATIENT' AS SCHEDULE_TYPE,
  UPPER(SEGMENT) AS SEGMENT,
  VENDOR_ID AS VENDOR,
  PROCEDURE_CODE AS BILLING_CODE,
  MODIFIER AS BILLING_CODE_MODIFIER,
  --PROCEDURE_MODIFIER_CONCAT AS BILLING_CODE,
  NULL AS MS_DRG_TITLE,
  CASE WHEN PRICE <> 0.00 THEN PRICE
       WHEN PRICE = 0.00 THEN PERCENTAGE END AS RATE,
  CASE WHEN PRICE <> 0.00 THEN 'negotiated' 
       WHEN PRICE = 0.00 THEN 'percentage' END AS NEGOTIATION_TYPE,
  TO_CHAR(SYSDATE(), 'MM/DD/YYYY') AS FILE_DATE,
  NULL AS ADDITIONAL_INFORMATION
  FROM FINAL_PULL
);

!set variable_substitution=false;