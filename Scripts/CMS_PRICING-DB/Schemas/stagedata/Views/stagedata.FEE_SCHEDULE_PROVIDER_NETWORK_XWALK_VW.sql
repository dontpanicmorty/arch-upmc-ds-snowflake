-- Meant to map structures in RAWDATA/IDAP_LAKE
!set variable_substitution=true;

CREATE OR REPLACE VIEW STAGEDATA.FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW
AS
SELECT DISTINCT 
  FEE_SCHEDULES.SEGMENT, 
  FEE_SCHEDULES.SCHEDULE_TYPE, 
  FEE_SCHEDULES.SCHEDULE_DETAIL, 
  SCHEDULE_TYPE.PROVIDER_TYPE, 
  PLAN_INFO.PROV_SET,
  -- not needed when this is used to link to providers, but included to prevent
  -- double joins to SCHEDULE_TYPE
  SCHEDULE_TYPE.BILLING_CLASS
FROM (
  SELECT DISTINCT SCHEDULE_TYPE, SEGMENT, SCHEDULE_DETAIL
  FROM STAGEDATA.PRACTITIONER_FEE_SCHEDULE_SELECT_HOLD PRACTITIONER_FEE_SCHEDULE

    UNION 

  SELECT DISTINCT SCHEDULE_TYPE, SEGMENT, 'NONE' AS SCHEDULE_DETAIL
  FROM STAGEDATA.INPATIENT_FEE_SCHEDULE_SELECT_HOLD
) FEE_SCHEDULES

INNER JOIN (
  -- Restrict to distinct combinations to avoid dupes
  SELECT DISTINCT PROV_SET, SEGMENT
  FROM &{IDAP_LAKE}.PRICING.PLAN_INFO
) PLAN_INFO ON
    PLAN_INFO.SEGMENT = FEE_SCHEDULES.SEGMENT


INNER JOIN (
  -- Restrict to distinct combinations to avoid dupes
  SELECT DISTINCT PROVIDER_TYPE, 
    SCHEDULE_TYPE, 
    COALESCE(SCHEDULE_DETAIL, 'NONE') AS SCHEDULE_DETAIL, 
    BILLING_CLASS
  FROM &{IDAP_LAKE}.PRICING.SCHEDULE_TYPE
) SCHEDULE_TYPE ON
    SCHEDULE_TYPE.SCHEDULE_TYPE = FEE_SCHEDULES.SCHEDULE_TYPE AND
    SCHEDULE_TYPE.SCHEDULE_DETAIL = FEE_SCHEDULES.SCHEDULE_DETAIL
;

!set variable_substitution=false;