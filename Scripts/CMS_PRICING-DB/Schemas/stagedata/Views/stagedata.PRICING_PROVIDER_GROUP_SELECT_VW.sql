CREATE OR REPLACE VIEW STAGEDATA.PRICING_PROVIDER_GROUP_SELECT_VW
AS
-- Pre-compile the list of distinct prov_set/provider_type for practitioner
WITH PRACTITIONER_PROV_SET_LIST AS (
  SELECT DISTINCT SEGMENT, SCHEDULE_DETAIL, SCHEDULE_TYPE, PROV_SET, PROVIDER_TYPE, STATE, MATCH_STATE
  FROM STAGEDATA.NEGOTIATED_PRICE_INTERNAL_HOLD
  WHERE SOURCE_TYPE = 'practitioner'
),
-- Then join that into the lists of unique provider set keys
PRACTITIONER_PROVIDER_LOOKUP AS (
  SELECT PRACTITIONER_PROV_SET_LIST.SEGMENT,
    PRACTITIONER_PROV_SET_LIST.SCHEDULE_DETAIL,
    PRACTITIONER_PROV_SET_LIST.SCHEDULE_TYPE,
    PRACTITIONER_PROV_SET_LIST.PROV_SET,
    PRACTITIONER_PROV_SET_LIST.PROVIDER_TYPE,
    PRACTITIONER_PROV_SET_LIST.STATE,
    PRACTITIONER_PROV_SET_LIST.MATCH_STATE,
    ARRAY_AGG(DISTINCT PROVIDER_SET_KEY) WITHIN GROUP (ORDER BY PROVIDER_SET_KEY ASC) AS PRICING_PROVIDER_SET_KEYS

  FROM PRACTITIONER_PROV_SET_LIST

  INNER JOIN STAGEDATA.PROVIDER_SET_INTERNAL_HOLD ON 
      PRACTITIONER_PROV_SET_LIST.SEGMENT = PROVIDER_SET_INTERNAL_HOLD.SEGMENT AND
      PRACTITIONER_PROV_SET_LIST.SCHEDULE_DETAIL = PROVIDER_SET_INTERNAL_HOLD.SCHEDULE_DETAIL AND
      PRACTITIONER_PROV_SET_LIST.SCHEDULE_TYPE = PROVIDER_SET_INTERNAL_HOLD.SCHEDULE_TYPE AND
      PRACTITIONER_PROV_SET_LIST.PROV_SET = PROVIDER_SET_INTERNAL_HOLD.PROV_SET AND
      PRACTITIONER_PROV_SET_LIST.PROVIDER_TYPE = PROVIDER_SET_INTERNAL_HOLD.PROVIDER_TYPE AND
        CASE WHEN PRACTITIONER_PROV_SET_LIST.MATCH_STATE = 'Y'
          THEN PRACTITIONER_PROV_SET_LIST.STATE = PROVIDER_SET_INTERNAL_HOLD.STATE
          ELSE 1
          END

  INNER JOIN EXTRACTDATA.PROVIDER_SET ON 
      PROVIDER_SET.TAX_ID_NBR = PROVIDER_SET_INTERNAL_HOLD.TAX_ID_NBR AND
      PROVIDER_SET.TAX_ID_TYPE_CODE = PROVIDER_SET_INTERNAL_HOLD.TAX_ID_TYPE_CODE AND
      PROVIDER_SET.NPI_NBR = PROVIDER_SET_INTERNAL_HOLD.NPI_NBR

  GROUP BY PRACTITIONER_PROV_SET_LIST.SEGMENT,
    PRACTITIONER_PROV_SET_LIST.SCHEDULE_DETAIL,
    PRACTITIONER_PROV_SET_LIST.SCHEDULE_TYPE,
    PRACTITIONER_PROV_SET_LIST.PROV_SET, 
    PRACTITIONER_PROV_SET_LIST.PROVIDER_TYPE, 
    PRACTITIONER_PROV_SET_LIST.STATE, 
    PRACTITIONER_PROV_SET_LIST.MATCH_STATE
),
-- Then join that into the corresponding negotiated_price objects
PRACTITIONER_NEGOTIATED_PRICE_LOOKUP AS (
  SELECT DISTINCT PRICING_PROVIDER_SET_KEYS
  FROM STAGEDATA.NEGOTIATED_PRICE_INTERNAL_HOLD

  -- ARH 2022-12-08: This was introduced because there are cases where we may 
  -- have billing codes from MC400 pricing rules that are not in the BILLING_CODE_LKP
  -- sheet provided by business. This means we'd be generating provider-reference
  -- files that are unused by in-network files, which is a problem for Healthsparq.
  -- It sucks, but this is an easy way to prevent "missing data" that's not
  -- really missing.
  INNER JOIN EXTRACTDATA.BILLING_CODE ON 
    BILLING_CODE.BILLING_CODE = NEGOTIATED_PRICE_INTERNAL_HOLD.BILLING_CODE

  INNER JOIN EXTRACTDATA.NEGOTIATED_PRICE ON
    NEGOTIATED_PRICE.NEGOTIATED_TYPE_NAME = NEGOTIATED_PRICE_INTERNAL_HOLD.NEGOTIATED_TYPE_NAME
    AND NEGOTIATED_PRICE.NEGOTIATED_RATE_AMT = NEGOTIATED_PRICE_INTERNAL_HOLD.NEGOTIATED_RATE_AMT
    AND NEGOTIATED_PRICE.EXPIRATION_DATE = NEGOTIATED_PRICE_INTERNAL_HOLD.EXPIRATION_DATE
    AND NEGOTIATED_PRICE.PLACE_OF_SERVICE_CODES = NEGOTIATED_PRICE_INTERNAL_HOLD.PLACE_OF_SERVICE_CODES
    AND NEGOTIATED_PRICE.BILLING_CLASS_NAME = NEGOTIATED_PRICE_INTERNAL_HOLD.BILLING_CLASS_NAME
    AND NEGOTIATED_PRICE.BILLING_CODE_MODIFIERS = NEGOTIATED_PRICE_INTERNAL_HOLD.BILLING_CODE_MODIFIERS

  INNER JOIN PRACTITIONER_PROVIDER_LOOKUP ON
      NEGOTIATED_PRICE_INTERNAL_HOLD.SEGMENT = PRACTITIONER_PROVIDER_LOOKUP.SEGMENT AND
      NEGOTIATED_PRICE_INTERNAL_HOLD.SCHEDULE_DETAIL = PRACTITIONER_PROVIDER_LOOKUP.SCHEDULE_DETAIL AND
      NEGOTIATED_PRICE_INTERNAL_HOLD.SCHEDULE_TYPE = PRACTITIONER_PROVIDER_LOOKUP.SCHEDULE_TYPE AND
      NEGOTIATED_PRICE_INTERNAL_HOLD.PROV_SET = PRACTITIONER_PROVIDER_LOOKUP.PROV_SET AND
      NEGOTIATED_PRICE_INTERNAL_HOLD.PROVIDER_TYPE = PRACTITIONER_PROVIDER_LOOKUP.PROVIDER_TYPE AND
        CASE WHEN PRACTITIONER_PROVIDER_LOOKUP.MATCH_STATE = 'Y'
          THEN PRACTITIONER_PROVIDER_LOOKUP.STATE = NEGOTIATED_PRICE_INTERNAL_HOLD.STATE
          ELSE 1
          END
),
INPATIENT_PROVIDER_LOOKUP AS (
  SELECT DISTINCT NEGOTIATED_PRICE_INTERNAL_HOLD.SEGMENT, VENDOR, PROVIDER_SET_KEY
  FROM STAGEDATA.NEGOTIATED_PRICE_INTERNAL_HOLD

  INNER JOIN STAGEDATA.FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW ON
      NEGOTIATED_PRICE_INTERNAL_HOLD.SCHEDULE_TYPE = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SCHEDULE_TYPE AND
      NEGOTIATED_PRICE_INTERNAL_HOLD.SEGMENT = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SEGMENT

  INNER JOIN STAGEDATA.PROVIDER_NETWORKS_VW PROVIDER_NETWORKS ON
      PROVIDER_NETWORKS.PROVIDER_TYPE = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROVIDER_TYPE AND
      PROVIDER_NETWORKS.PRICING_NETWORK_NAME = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.PROV_SET AND
      NEGOTIATED_PRICE_INTERNAL_HOLD.VENDOR = PROVIDER_NETWORKS.VENDOR_ID

  INNER JOIN STAGEDATA.PROVIDER_SET_INTERNAL_HOLD ON
      PROVIDER_SET_INTERNAL_HOLD.TAX_ID_NBR = DERIVED_TAXID

  INNER JOIN EXTRACTDATA.PROVIDER_SET ON
      PROVIDER_SET.TAX_ID_NBR = PROVIDER_SET_INTERNAL_HOLD.TAX_ID_NBR AND
      PROVIDER_SET.TAX_ID_TYPE_CODE = PROVIDER_SET_INTERNAL_HOLD.TAX_ID_TYPE_CODE AND
      PROVIDER_SET.NPI_NBR = PROVIDER_SET_INTERNAL_HOLD.NPI_NBR

  WHERE SOURCE_TYPE = 'inpatient'
),
INPATIENT_NEGOTIATED_PRICE_LOOKUP AS (
  SELECT DISTINCT 
    ARRAY_AGG(DISTINCT PROVIDER_SET_KEY) WITHIN GROUP (ORDER BY PROVIDER_SET_KEY ASC) AS PRICING_PROVIDER_SET_KEYS
  FROM STAGEDATA.NEGOTIATED_PRICE_INTERNAL_HOLD

  -- ARH 2022-12-08: This was introduced because there are cases where we may 
  -- have billing codes from MC400 pricing rules that are not in the BILLING_CODE_LKP
  -- sheet provided by business. This means we'd be generating provider-reference
  -- files that are unused by in-network files, which is a problem for Healthsparq.
  -- It sucks, but this is an easy way to prevent "missing data" that's not
  -- really missing.
  INNER JOIN EXTRACTDATA.BILLING_CODE ON 
    BILLING_CODE.BILLING_CODE = NEGOTIATED_PRICE_INTERNAL_HOLD.BILLING_CODE

  INNER JOIN EXTRACTDATA.NEGOTIATED_PRICE ON
    NEGOTIATED_PRICE.NEGOTIATED_TYPE_NAME = NEGOTIATED_PRICE_INTERNAL_HOLD.NEGOTIATED_TYPE_NAME
    AND NEGOTIATED_PRICE.NEGOTIATED_RATE_AMT = NEGOTIATED_PRICE_INTERNAL_HOLD.NEGOTIATED_RATE_AMT
    AND NEGOTIATED_PRICE.EXPIRATION_DATE = NEGOTIATED_PRICE_INTERNAL_HOLD.EXPIRATION_DATE
    AND NEGOTIATED_PRICE.PLACE_OF_SERVICE_CODES = NEGOTIATED_PRICE_INTERNAL_HOLD.PLACE_OF_SERVICE_CODES
    AND NEGOTIATED_PRICE.BILLING_CLASS_NAME = NEGOTIATED_PRICE_INTERNAL_HOLD.BILLING_CLASS_NAME
    AND NEGOTIATED_PRICE.BILLING_CODE_MODIFIERS = NEGOTIATED_PRICE_INTERNAL_HOLD.BILLING_CODE_MODIFIERS

  INNER JOIN INPATIENT_PROVIDER_LOOKUP ON
    NEGOTIATED_PRICE_INTERNAL_HOLD.VENDOR = INPATIENT_PROVIDER_LOOKUP.VENDOR
    AND NEGOTIATED_PRICE_INTERNAL_HOLD.SEGMENT = INPATIENT_PROVIDER_LOOKUP.SEGMENT

  WHERE SOURCE_TYPE = 'inpatient'
  GROUP BY NEGOTIATED_PRICE_KEY, SOURCE_TYPE,
    NEGOTIATED_PRICE_INTERNAL_HOLD.SEGMENT,
    NEGOTIATED_PRICE_INTERNAL_HOLD.SCHEDULE_DETAIL,
    NEGOTIATED_PRICE_INTERNAL_HOLD.SCHEDULE_TYPE,
    NEGOTIATED_PRICE_INTERNAL_HOLD.BILLING_CODE,
    NEGOTIATED_PRICE_INTERNAL_HOLD.NEGOTIATED_TYPE_NAME,
    NEGOTIATED_PRICE_INTERNAL_HOLD.NEGOTIATED_RATE_AMT,
    NEGOTIATED_PRICE_INTERNAL_HOLD.BILLING_CLASS_NAME
)

-- Then use negotiated_price as a seed and reach back out to grab everything
SELECT PRICING_PROVIDER_SET_KEYS
FROM PRACTITIONER_NEGOTIATED_PRICE_LOOKUP

UNION

SELECT PRICING_PROVIDER_SET_KEYS
FROM INPATIENT_NEGOTIATED_PRICE_LOOKUP;