-- Meant to map structures in RAWDATA/IDAP_LAKE - used to copy to EXTRACTDATA
-- as it only provides uniques
!set variable_substitution=true;

CREATE OR REPLACE VIEW STAGEDATA.NEGOTIATED_PRICE_SELECT_VW
AS

-- from PRACTITIONER_FEE_SCHEDULE
SELECT DISTINCT
    PRACTITIONER_FEE_SCHEDULE.NEGOTIATED_TYPE_NAME,
    PRACTITIONER_FEE_SCHEDULE.EXPIRATION_DATE,
    PRACTITIONER_FEE_SCHEDULE.NEGOTIATED_RATE_AMT,
    PLACE_OF_SERVICE_CODES,
    PRACTITIONER_FEE_SCHEDULE.BILLING_CODE_MODIFIERS,
    BILLING_CLASS AS BILLING_CLASS_NAME
    
FROM STAGEDATA.PRACTITIONER_FEE_SCHEDULE_SELECT_HOLD PRACTITIONER_FEE_SCHEDULE
   
INNER JOIN STAGEDATA.FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW ON
  PRACTITIONER_FEE_SCHEDULE.SCHEDULE_TYPE = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SCHEDULE_TYPE AND
  PRACTITIONER_FEE_SCHEDULE.SEGMENT = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SEGMENT AND
  PRACTITIONER_FEE_SCHEDULE.SCHEDULE_DETAIL = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SCHEDULE_DETAIL

UNION 

-- from INPATIENT_FEE_SCHEDULE_SELECT_HOLD
SELECT DISTINCT
    NEGOTIATION_TYPE_NAME AS NEGOTIATED_TYPE_NAME, 
    '12/31/9999' AS EXPIRATION_DATE,
    TO_NUMBER(REPLACE(RATE,','), 20, 2) AS NEGOTIATED_RATE_AMT, --rpad 0s and remove commas
    ARRAY_CONSTRUCT() AS PLACE_OF_SERVICE_CODES, -- not relevant
    ARRAY_CONSTRUCT() AS BILLING_CODE_MODIFIERS, -- also not relevant because they're DRG codes
    BILLING_CLASS AS BILLING_CLASS_NAME
    
FROM STAGEDATA.INPATIENT_FEE_SCHEDULE_SELECT_HOLD

INNER JOIN STAGEDATA.FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW ON
  INPATIENT_FEE_SCHEDULE_SELECT_HOLD.SCHEDULE_TYPE = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SCHEDULE_TYPE AND
  INPATIENT_FEE_SCHEDULE_SELECT_HOLD.SEGMENT = FEE_SCHEDULE_PROVIDER_NETWORK_XWALK_VW.SEGMENT
;

!set variable_substitution=false;