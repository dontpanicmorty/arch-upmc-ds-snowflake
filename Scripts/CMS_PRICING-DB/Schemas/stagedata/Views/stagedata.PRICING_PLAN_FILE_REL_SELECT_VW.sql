CREATE OR REPLACE VIEW STAGEDATA.PRICING_PLAN_FILE_REL_SELECT_VW
AS
SELECT DISTINCT PRICING_FILE_KEY, PRICING_PLAN_KEY
FROM &{IDAP_LAKE}.PRICING.PLAN_INFO

INNER JOIN EXTRACTDATA.REPORTING_ENTITY ON
    REPORTING_ENTITY_NAME = 'UPMC Health Plan'
    
-- Very slow join, but with only 2k lines, we're not too worried at the moment
INNER JOIN EXTRACTDATA.PRICING_FILE ON
    PRICING_FILE.FILE_DESC = STAGEDATA.FXN_MAKE_IN_NETWORK_FILE_DESC(SEGMENT, PROV_SET)
    OR PRICING_FILE.FILE_DESC = STAGEDATA.FXN_MAKE_ALLOWED_AMOUNTS_FILE_DESC(PLAN_CODE, THRESHOLD_GROUPING, PLAN_ID)

INNER JOIN EXTRACTDATA.PRICING_PLAN ON
    PRICING_PLAN.REPORTING_ENTITY_KEY = 3 -- from StaticData, UPMC value
    AND PRICING_PLAN.PLAN_NAME = PLAN_INFO.PLAN_NAME
    AND PRICING_PLAN.PLAN_ID_TYPE = PLAN_INFO.PLAN_ID_TYPE
    AND PRICING_PLAN.PLAN_ID = PLAN_INFO.PLAN_ID
    AND PRICING_PLAN.PLAN_MARKET_TYPE_NAME = PLAN_INFO.MARKET_TYPE
;

!set variable_substitution=false;