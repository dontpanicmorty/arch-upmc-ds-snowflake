--GATHERS DATA NEEDED FROM CONTRACTS TABLE
CREATE OR REPLACE VIEW STAGEDATA.PROVIDER_GROUPING_SELECT_VW
AS
(
WITH CHECK_CTE AS(
	SELECT MRF_CONTRACTS_VW.PROVIDER_NBR as VENDOR_ID
	,DWOAO_VENDORS.FEIN AS GROUP_TIN
	,GroupNPI.PROVIDERSUBPART as GROUP_NPI
	,CASE WHEN TINCheck.ssn IS NOT NULL THEN '1' else '0' END as SSN_EXISTS
	,CASE WHEN TINCheck.ssn IS NOT NULL THEN GROUP_NPI else DWOAO_VENDORS.FEIN END as TAX_ID_NBR --Only 1 provider has a TaxID that exists as an SSN AND has a record in subpart
	,CASE WHEN TINCheck.ssn IS NOT NULL THEN 'npi' else 'ein' END as TAX_ID_TYPE_CODE
	,MRF_CONTRACTS_VW.PLAN_TYPE AS PLAN_TYPE_CODE
	,MRF_CONTRACTS_VW.PROVIDER_IPA_CODE AS IPA_CODE
	,MRF_CONTRACTS_VW.GROUP_CARRIER AS GROUP_CARRIER_PRICE_GROUP
	,MRF_CONTRACTS_VW.PROVIDER_TYPE --can maybe get rid of this but keeping it for now in case we somehow have to join against it
	,MRF_CONTRACTS_VW.RENDERING_PROV_AFFILIATION
	,ARRAY_AGG(DISTINCT ProviderNPI.PROVIDERSUBPART) AS RENDERING_PROVIDER_NPI_NBRS
	FROM STAGEDATA.MRF_CONTRACTS_VW
		LEFT JOIN RAWDATA.DWOAO_PROVIDERSUBPART ProviderNPI --> this should be an inner but for some reasON filters out a lot of data. might have to get NPI from providers when it's not in here?
			ON MRF_CONTRACTS_VW.RENDERING_PROV_AFFILIATION = ProviderNPI.PROVIDERNUMBER
		LEFT JOIN RAWDATA.DWOAO_PROVIDERSUBPART GroupNPI
			ON GroupNPI.providernumber = MRF_CONTRACTS_VW.provider_nbr
			AND GroupNPI.ProviderSubpartDesign = 'M'
		INNER JOIN RAWDATA.DWOAO_VENDORS
			ON LPAD(LTRIM(MRF_CONTRACTS_VW.PROVIDER_NBR,'V' ) , 10, 0) = DWOAO_VENDORS.VENDORNBR
		LEFT JOIN rawdata.dwoao_providers as TINCheck --does the Group's TIN match to an SSN ON the Provider table
			ON TINCheck.ssn = dwoao_vendors.fein
	GROUP BY DWOAO_VENDORS.FEIN
	,MRF_CONTRACTS_VW.PROVIDER_NBR
	,MRF_CONTRACTS_VW.PLAN_TYPE
	,MRF_CONTRACTS_VW.PROVIDER_IPA_CODE
	,MRF_CONTRACTS_VW.GROUP_CARRIER
	,MRF_CONTRACTS_VW.PROVIDER_TYPE
	,MRF_CONTRACTS_VW.RENDERING_PROV_AFFILIATION
	,GroupNPI.PROVIDERSUBPART
	,CASE WHEN TINCheck.ssn IS NOT NULL THEN '1' else '0' END
	,CASE WHEN TINCheck.ssn IS NOT NULL THEN GROUP_NPI else DWOAO_VENDORS.FEIN END
	,CASE WHEN TINCheck.ssn IS NOT NULL THEN 'npi' else 'ein' END
)
SELECT
VENDOR_ID AS VENDOR_NBR
,TAX_ID_NBR
,TAX_ID_TYPE_CODE
,GROUP_CARRIER_PRICE_GROUP_KEY
,PROVIDER_TYPE AS PROVIDER_TYPE_NAME
,RENDERING_PROV_AFFILIATION AS RENDERING_PROVIDER_NBR
,IPA_KEY
,PLAN_TYPE_KEY
,RENDERING_PROVIDER_NPI_NBRS
FROM CHECK_CTE
    INNER JOIN STAGEDATA.IPA
        ON CHECK_CTE.IPA_CODE = IPA.IPA_CODE
    INNER JOIN STAGEDATA.PLAN_TYPE
        ON CHECK_CTE.PLAN_TYPE_CODE = PLAN_TYPE.PLAN_TYPE_CODE
    INNER JOIN STAGEDATA.GROUP_CARRIER_PRICE_GROUP
        ON CHECK_CTE.GROUP_CARRIER_PRICE_GROUP = GROUP_CARRIER_PRICE_GROUP.GROUP_CARRIER_PRICE_GROUP_CODE
);