--Gathering data to calculate pricing rules
CREATE OR REPLACE VIEW STAGEDATA.MRF_ACTIVE_PROVIDER_PRICING_VW
AS
(
SELECT DISTINCT PH.PROVIDERNBR AS PROVIDER_NBR
,PH.AMBULATORYSURGERYFEESCH AS AMBULATORY_SURGERY_FEE_SCH
,PH.ASACONVERSIONFACTORSET AS ASA_CONVERSION_FACTOR_SET
,PH.AVERAGEWHOLESALEPRICE AS AVERAGE_WHOLESALE_PRICE
,PH.CASERATESCHEDULE AS CASE_RATE_SCHEDULE
,PH.CONTRACTSTATUS AS CONTRACT_STATUS
,PH.CRVSCONVERSIONFACTORSET AS CRVS_CONVERSION_FACTOR_SET
,PH.DISPENSINGFEE AS DISPENSING_FEE
,PH.EFFECTIVEDATE AS EFFECTIVE_DATE
,PH.ENTITY 
,PH.FACTOR1 AS FACTOR_1
,PH.FACTOR2 AS FACTOR_2
,PH.FIFTHLEVELPRICECATEGORY AS FIFTH_LEVEL_PRICE_CATEGORY
,PH.FOURTHLEVELPRICECATEGORY AS FOURTH_LEVEL_PRICE_CATEGORY
,PH.GROUPCARRIERPRICEGROUP AS GROUP_CARRIER_PRICE_GROUP
,PH.IPAPRICEGROUP AS IPA_PRICE_GROUP
,PH.MODIFIERSCHEDULE AS MODIFIER_SCHEDULE
,PH.PERCENTAGE 
,PH.PERCENTAGERULE AS PERCENTAGE_RULE
,PH.PHARMACYPRICECATEGORY AS PHARMACY_PRICE_CATEGORY
,PH.PLACEOFSERVICE AS PLACE_OF_SERVICE
,PH.PLANTYPE AS PLAN_TYPE
,PH.POSUSERDEFINEDFIELD AS POS_USER_DEFINED_FIELD
,PH.PRICECATEGORY AS PRICE_CATEGORY
,PH.PRICINGRULE AS PRICING_RULE
,PH.RBRVSCARRIER AS RBRVS_CARRIER
,PH.RBRVSCONVERSIONFACTORSET AS RBRVS_CONVERSION_FACTOR_SET
,PH.RBRVSLOCALITY AS RBRVS_LOCALITY
,PH.RBRVSPERCENTACE AS RBRVS_PERCENTACE
,PH.RBRVSVERSION AS RBRVS_VERSION
,PH.REIMBURSEMENTFLAG AS REIMBURSEMENT_FLAG
,PH.SECONDLEVELPRICECATEGORY AS SECOND_LEVEL_PRICE_CATEGORY
,PH.THIRDLEVELPRICECATEGORY AS THIRD_LEVEL_PRICE_CATEGORY
,PH.TERMDATE AS TERM_DATE	
,PH.WITHHOLD1 AS WITHHOLD_1
,PH.WITHHOLD2 AS WITHHOLD_2
,PH.AGESCHEDULECODE AS AGE_SCHEDULE_CODE
,PH.CUSTOMPRICINGRULESET AS CUSTOM_PRICING_RULE_SET
,PH.MODIFIER59PRICINGFLAG AS MODIFIER_59_PRICING_FLAG
,PH.MULTIPLESURGERYMETHOD AS MULTIPLE_SURGERY_METHOD
,PH.PROVIDERTYPESCHEDULE AS PROVIDER_TYPE_SCHEDULE
,PH.SERVICEREASONSCHEDULE AS SERVICE_REASON_SCHEDULE
,PH.USEMPFSDBPRICING AS USE_MPFSDB_PRICING
FROM RAWDATA.DWOAO_PROVIDERPRICINGHISTORY PH
    WHERE 	PH.PLANTYPE IN (SELECT PLAN_TYPE_CODE FROM STAGEDATA.PLAN_TYPE)
    AND (PH.IPAPRICEGROUP IN (SELECT IPA_CODE FROM STAGEDATA.IPA)
		  OR PH.IPAPRICEGROUP IS NULL)
    AND PH.PROVIDERNBR IN (SELECT DISTINCT PROVIDER_NBR FROM STAGEDATA.MRF_CONTRACTS_VW)
);