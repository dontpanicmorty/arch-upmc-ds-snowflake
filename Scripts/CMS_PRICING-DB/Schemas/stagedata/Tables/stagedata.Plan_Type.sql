-- Transient as it's updated from the spu_run_extract sproc
CREATE OR REPLACE TRANSIENT TABLE STAGEDATA.PLAN_TYPE
(
	PLAN_TYPE_KEY NUMBER(38,0) NOT NULL AUTOINCREMENT ORDER START 1 INCREMENT 1,
	INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
	PLAN_TYPE_CODE VARCHAR NOT NULL,
	CONSTRAINT PK_PLAN_TYPE PRIMARY KEY (PLAN_TYPE_KEY),
	CONSTRAINT UK_PLAN_TYPE UNIQUE (PLAN_TYPE_CODE)
) COMMENT='Stores unique values of PLAN_TYPE Code that have been approved for pricing rules';