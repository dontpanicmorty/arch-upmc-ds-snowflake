-- Transient as it's updated from the spu_run_extract sproc
CREATE OR REPLACE TRANSIENT TABLE STAGEDATA.IPA
(
	IPA_KEY NUMBER(38,0) NOT NULL AUTOINCREMENT ORDER START 1 INCREMENT 1,
	INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
	IPA_CODE VARCHAR NOT NULL,
	CONSTRAINT PK_IPA PRIMARY KEY (IPA_KEY),
	CONSTRAINT UK_IPA UNIQUE (IPA_CODE)
) COMMENT='Stores unique values of IPA Code that have been approved for pricing rules';