-- Transient as it's updated from static data
CREATE OR REPLACE TRANSIENT TABLE STAGEDATA.LEGAL_ENTITY
( 
    LEGAL_ENTITY_KEY INTEGER AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
    INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP() NOT NULL, 
    LEGAL_ENTITY      VARCHAR NOT NULL,
    TIN_FEIN          VARCHAR NOT NULL,
    PAYEE_GROUP       VARCHAR,
    NAIC_COMPANY_CODE VARCHAR,
    ISSUER_HIOS_ID    VARCHAR,
    PLAN_YEAR_2025    VARCHAR,
    PLAN_YEAR_2026    VARCHAR,
    NOTES             VARCHAR,
    
    CONSTRAINT PK_LEGAL_ENTITY PRIMARY KEY (LEGAL_ENTITY_KEY),
    CONSTRAINT UK_LEGAL_ENTITY UNIQUE (LEGAL_ENTITY, TIN_FEIN)
)COMMENT = 'Stores legal entity static config values used for pricing.';


