-- Transient as it's updated from the spu_run_extract sproc
CREATE OR REPLACE TRANSIENT TABLE STAGEDATA.PRICE_CATEGORY
(
	PRICE_CATEGORY_KEY NUMBER(38,0) NOT NULL AUTOINCREMENT ORDER START 1 INCREMENT 1,
	INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
	PRICE_CATEGORY_NAME VARCHAR,
	CONSTRAINT PK_PRICE_CATEGORY PRIMARY KEY (PRICE_CATEGORY_KEY),
	CONSTRAINT UK_PRICE_CATEGORY UNIQUE (PRICE_CATEGORY_NAME)
) COMMENT='Stores unique values of PriceCategory built from a few tables and assigns them an integer key to improve join performance downstream';