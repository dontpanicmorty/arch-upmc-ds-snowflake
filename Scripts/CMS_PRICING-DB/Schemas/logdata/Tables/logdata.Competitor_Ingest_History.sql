CREATE OR REPLACE TABLE	LOGDATA.COMPETITOR_INGEST_HISTORY (
	COMPETITOR_INGEST_HISTORY_KEY NUMBER(38,0) AUTOINCREMENT ORDER NOT NULL,
	INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP,
	-- Because we care more about what year/month we're ingesting und
	INSERT_YEARMONTH VARCHAR DEFAULT CONCAT(
		DATE_PART(YEAR, CURRENT_TIMESTAMP()),
		'-',
		DATE_PART(MONTH, CURRENT_TIMESTAMP())
	),
	URL VARCHAR NOT NULL,
	RAW_BYTES NUMBER(38,0),
	DECOMPRESSED_BYTES NUMBER(38,0),
	HTTP_CODE INTEGER,
	ERROR_MESSAGE VARCHAR,
	CONSTRAINT PK_COMPETITOR_INGEST_HISTORY PRIMARY KEY (COMPETITOR_INGEST_HISTORY_KEY),
	CONSTRAINT UK_COMPETITOR_INGEST_HISTORY UNIQUE (INSERT_YEARMONTH, URL)
);