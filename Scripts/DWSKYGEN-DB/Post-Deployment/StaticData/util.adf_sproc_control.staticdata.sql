MERGE INTO UTIL.ADF_SPROC_CONTROL AS TGT
USING (SELECT ADF_SPROC_CONTROL_KEY, SCHEMA_NAME, PROCEDURE_NAME
	FROM UTIL.TMP_ADF_SPROC_CONTROL
	MINUS 
	SELECT ADF_SPROC_CONTROL_KEY, SCHEMA_NAME, PROCEDURE_NAME
	FROM UTIL.ADF_SPROC_CONTROL
	) AS SRC
ON TGT.ADF_SPROC_CONTROL_KEY = SRC.ADF_SPROC_CONTROL_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.SCHEMA_NAME = SRC.SCHEMA_NAME
	,TGT.PROCEDURE_NAME = SRC.PROCEDURE_NAME
WHEN NOT MATCHED 
THEN INSERT
	(ADF_SPROC_CONTROL_KEY
	,SCHEMA_NAME
	,PROCEDURE_NAME
	)
VALUES
	(
	SRC.ADF_SPROC_CONTROL_KEY
	,SRC.SCHEMA_NAME
	,SRC.PROCEDURE_NAME
	);
	
--Flip the minus and delete from the target
DELETE FROM UTIL.ADF_SPROC_CONTROL TGT
USING
(SELECT ADF_SPROC_CONTROL_KEY, SCHEMA_NAME, PROCEDURE_NAME
	FROM UTIL.ADF_SPROC_CONTROL
	MINUS 
	SELECT ADF_SPROC_CONTROL_KEY, SCHEMA_NAME, PROCEDURE_NAME
	FROM UTIL.TMP_ADF_SPROC_CONTROL
	) SRC
WHERE TGT.ADF_SPROC_CONTROL_KEY = SRC.ADF_SPROC_CONTROL_KEY;	 