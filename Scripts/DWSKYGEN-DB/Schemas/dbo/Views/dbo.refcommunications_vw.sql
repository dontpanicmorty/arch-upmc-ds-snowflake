CREATE OR REPLACE VIEW DBO.RefCommunications_VW
AS 
SELECT 	$1:COMMUNICATION_ID::NUMBER(38, 0) AS COMMUNICATION_ID, 
		$1:FOLLOWUP_ID::NUMBER(38, 0) AS FOLLOWUP_ID, 
		$1:LONG_NOTES::VARCHAR AS LONG_NOTES, 
		$1:ATTACHMENT_ID::NUMBER(38, 0) AS ATTACHMENT_ID, 
		$1:AUTHORIZATION_REF::VARCHAR AS AUTHORIZATION_REF, 
		$1:ENCOUNTER_REF::VARCHAR AS ENCOUNTER_REF, 
		$1:PROVIDER_REF::VARCHAR AS PROVIDER_REF, 
		$1:CALLBACK_NUMBER::VARCHAR AS CALLBACK_NUMBER, 
		$1:CALL_REFERENCE_NUMBER::NUMBER(38, 0) AS CALL_REFERENCE_NUMBER, 
		$1:COMMUNICATOR_NAME::VARCHAR AS COMMUNICATOR_NAME, 
		$1:RecordUpdateDatetime::TIMESTAMP_NTZ AS RecordUpdateDatetime
FROM 	'@DBO.HPDSDATALAKE_DBEXTRACT_DWSKYGEN/dbo/RefCommunications/'
		( FILE_FORMAT => DBO.DWSKYGEN_PARQUET_FILE_FORMAT);
