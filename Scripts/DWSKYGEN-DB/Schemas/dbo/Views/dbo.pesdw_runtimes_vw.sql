CREATE OR REPLACE VIEW DBO.PESDW_Runtimes_VW
AS 
SELECT 	$1:PROCESS_NAME::VARCHAR AS PROCESS_NAME, 
		$1:STATUS_DESCRIPTION::VARCHAR AS STATUS_DESCRIPTION, 
		$1:START_TIME::TIMESTAMP_TZ AS START_TIME, 
		$1:END_TIME::TIMESTAMP_TZ AS END_TIME
FROM 	'@DBO.HPDSDATALAKE_DBEXTRACT_DWSKYGEN/dbo/PESDW_Runtimes/'
		( FILE_FORMAT => DBO.DWSKYGEN_PARQUET_FILE_FORMAT);
