CREATE OR REPLACE VIEW DBO.RefEnrolleeReportingCategories_VW
AS 
SELECT 	$1:EnrolleeKey::NUMBER(38, 0) AS EnrolleeKey, 
		$1:REPORTING_CATEGORY::NUMBER(38, 0) AS REPORTING_CATEGORY, 
		$1:REPORTING_IDENTIFIER_TYPE::VARCHAR AS REPORTING_IDENTIFIER_TYPE, 
		$1:EFFECTIVE_DATE::DATE AS EFFECTIVE_DATE, 
		$1:TERMINATION_DATE::DATE AS TERMINATION_DATE, 
		$1:REPORTING_IDENTIFIER::VARCHAR AS REPORTING_IDENTIFIER, 
		$1:ReportingCategoryDescription::VARCHAR AS ReportingCategoryDescription, 
		$1:Partition::NUMBER(38, 0) AS Partition, 
		$1:RecordUpdateDatetime::TIMESTAMP_NTZ AS RecordUpdateDatetime
FROM 	'@DBO.HPDSDATALAKE_DBEXTRACT_DWSKYGEN/dbo/RefEnrolleeReportingCategories/'
		( FILE_FORMAT => DBO.DWSKYGEN_PARQUET_FILE_FORMAT);
