CREATE OR REPLACE VIEW DBO.FactClaimRecodedServices_VW
AS 
SELECT 	$1:CLAIM_ID::NUMBER(38, 0) AS CLAIM_ID, 
		$1:ITEM_NUMBER::NUMBER(38, 0) AS ITEM_NUMBER, 
		$1:NEW_CLAIM_ID::NUMBER(38, 0) AS NEW_CLAIM_ID, 
		$1:NEW_ITEM_NUMBER::NUMBER(38, 0) AS NEW_ITEM_NUMBER, 
		$1:Partition::NUMBER(38, 0) AS Partition, 
		$1:RecordUpdateDatetime::TIMESTAMP_NTZ AS RecordUpdateDatetime
FROM 	'@DBO.HPDSDATALAKE_DBEXTRACT_DWSKYGEN/dbo/FactClaimRecodedServices/'
		( FILE_FORMAT => DBO.DWSKYGEN_PARQUET_FILE_FORMAT);
