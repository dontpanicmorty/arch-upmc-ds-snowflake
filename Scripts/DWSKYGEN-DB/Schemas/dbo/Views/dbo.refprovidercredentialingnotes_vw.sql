CREATE OR REPLACE VIEW DBO.RefProviderCredentialingNotes_VW
AS 
SELECT 	$1:DateCreationKey::NUMBER(38, 0) AS DateCreationKey, 
		$1:DomainSourceKey::NUMBER(38, 0) AS DomainSourceKey, 
		$1:PROVIDER_CREDENTIALING_NOTE_ID::NUMBER(38, 0) AS PROVIDER_CREDENTIALING_NOTE_ID, 
		$1:PROVIDER_CREDENTIALING_PERIOD_REQUIREMENT_ID::NUMBER(38, 0) AS PROVIDER_CREDENTIALING_PERIOD_REQUIREMENT_ID, 
		$1:NOTE::VARCHAR AS NOTE, 
		$1:RecordUpdateDatetime::TIMESTAMP_NTZ AS RecordUpdateDatetime
FROM 	'@DBO.HPDSDATALAKE_DBEXTRACT_DWSKYGEN/dbo/RefProviderCredentialingNotes/'
		( FILE_FORMAT => DBO.DWSKYGEN_PARQUET_FILE_FORMAT);
