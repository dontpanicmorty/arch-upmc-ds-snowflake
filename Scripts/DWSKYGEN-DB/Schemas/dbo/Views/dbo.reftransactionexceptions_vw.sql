CREATE OR REPLACE VIEW DBO.RefTransactionExceptions_VW
AS 
SELECT 	$1:TRANSACTION_EXCEPTION_ID::NUMBER(38, 0) AS TRANSACTION_EXCEPTION_ID, 
		$1:TRANSACTION_ID::NUMBER(38, 0) AS TRANSACTION_ID, 
		$1:TRANSACTION_EXCEPTION_MESSAGE::VARCHAR AS TRANSACTION_EXCEPTION_MESSAGE, 
		$1:CREATION_DATE::TIMESTAMP_NTZ AS CREATION_DATE, 
		$1:RecordUpdateDatetime::TIMESTAMP_NTZ AS RecordUpdateDatetime
FROM 	'@DBO.HPDSDATALAKE_DBEXTRACT_DWSKYGEN/dbo/RefTransactionExceptions/'
		( FILE_FORMAT => DBO.DWSKYGEN_PARQUET_FILE_FORMAT);
