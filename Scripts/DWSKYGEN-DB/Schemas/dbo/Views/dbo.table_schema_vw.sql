CREATE OR REPLACE VIEW DBO.Table_Schema_VW
AS 
SELECT 	$1:ReleaseDateTime::TIMESTAMP_NTZ AS ReleaseDateTime, 
		$1:TABLE_SCHEMA::VARCHAR AS TABLE_SCHEMA, 
		$1:TABLE_NAME::VARCHAR AS TABLE_NAME, 
		$1:COLUMN_NAME::VARCHAR AS COLUMN_NAME, 
		$1:ORDINAL_POSITION::NUMBER(38, 0) AS ORDINAL_POSITION, 
		$1:IS_ESDW_TABLE::BOOLEAN AS IS_ESDW_TABLE, 
		$1:IS_NULLABLE::BOOLEAN AS IS_NULLABLE, 
		$1:IS_UNIQUE_COLUMN::BOOLEAN AS IS_UNIQUE_COLUMN, 
		$1:DATA_TYPE::VARCHAR AS DATA_TYPE, 
		$1:CHARACTER_MAXIMUM_LENGTH::NUMBER(38, 0) AS CHARACTER_MAXIMUM_LENGTH, 
		$1:NUMERIC_PRECISION::NUMBER(38, 0) AS NUMERIC_PRECISION, 
		$1:NUMERIC_SCALE::NUMBER(38, 0) AS NUMERIC_SCALE, 
		$1:DATETIME_PRECISION::NUMBER(38, 0) AS DATETIME_PRECISION
FROM 	'@DBO.HPDSDATALAKE_DBEXTRACT_DWSKYGEN/dbo/Table_Schema/'
		( FILE_FORMAT => DBO.DWSKYGEN_PARQUET_FILE_FORMAT);
