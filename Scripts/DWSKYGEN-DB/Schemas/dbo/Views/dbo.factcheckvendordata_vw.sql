CREATE OR REPLACE VIEW DBO.FactCheckVendorData_VW
AS 
SELECT 	$1:CheckKey::NUMBER(38, 0) AS CheckKey, 
		$1:DateTransactionKey::NUMBER(38, 0) AS DateTransactionKey, 
		$1:VendorKey::NUMBER(38, 0) AS VendorKey, 
		$1:VendorPaymentStatusKey::VARCHAR AS VendorPaymentStatusKey, 
		$1:VendorPaymentTypeKey::VARCHAR AS VendorPaymentTypeKey, 
		$1:VendorReasonCodeKey::NUMBER(38, 0) AS VendorReasonCodeKey, 
		$1:VENDOR_TRANSACTION_ID::VARCHAR AS VENDOR_TRANSACTION_ID, 
		$1:USER_KEY::VARCHAR AS USER_KEY, 
		$1:VENDOR_CHECK_NUMBER::NUMBER(38, 0) AS VENDOR_CHECK_NUMBER, 
		$1:TRANSACTION_AMOUNT::NUMBER(19, 4) AS TRANSACTION_AMOUNT, 
		$1:EIM_JOB_ID::NUMBER(38, 0) AS EIM_JOB_ID, 
		$1:CREATION_DATE::TIMESTAMP_NTZ AS CREATION_DATE, 
		$1:LAST_MODIFIED_DATE::TIMESTAMP_NTZ AS LAST_MODIFIED_DATE, 
		--$1:DW_Hash::VARCHAR AS DW_Hash, 
		$1:Partition::NUMBER(38, 0) AS Partition, 
		$1:RecordUpdateDatetime::TIMESTAMP_NTZ AS RecordUpdateDatetime
FROM 	'@DBO.HPDSDATALAKE_DBEXTRACT_DWSKYGEN/dbo/FactCheckVendorData/'
		( FILE_FORMAT => DBO.DWSKYGEN_PARQUET_FILE_FORMAT);
