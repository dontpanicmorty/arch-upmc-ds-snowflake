CREATE OR REPLACE VIEW DBO.RefPayeesDetailRejects_VW
AS 
SELECT 	$1:PAYEE_ID::NUMBER(38, 0) AS PAYEE_ID, 
		$1:EFFECTIVE_DATE::DATE AS EFFECTIVE_DATE, 
		$1:TERMINATION_DATE::DATE AS TERMINATION_DATE, 
		$1:TAX_ID::VARCHAR AS TAX_ID, 
		$1:CREATION_DATE::TIMESTAMP_NTZ AS CREATION_DATE, 
		$1:LAST_MODIFIED_DATE_TIME::TIMESTAMP_NTZ AS LAST_MODIFIED_DATE_TIME, 
		$1:RecordUpdateDatetime::TIMESTAMP_NTZ AS RecordUpdateDatetime
FROM 	'@DBO.HPDSDATALAKE_DBEXTRACT_DWSKYGEN/dbo/RefPayeesDetailRejects/'
		( FILE_FORMAT => DBO.DWSKYGEN_PARQUET_FILE_FORMAT);