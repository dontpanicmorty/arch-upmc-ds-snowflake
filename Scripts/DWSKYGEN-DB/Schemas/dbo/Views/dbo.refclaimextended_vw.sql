AS 
SELECT 	$1:CLAIM_ID::NUMBER(38, 0) AS CLAIM_ID, 
		$1:ELIG_OTHER_INFO1::VARCHAR AS ELIG_OTHER_INFO1, 
		$1:ELIG_OTHER_INFO2::VARCHAR AS ELIG_OTHER_INFO2, 
		$1:ELIG_OTHER_INFO3::VARCHAR AS ELIG_OTHER_INFO3, 
		$1:REFERRAL_NUMBER::VARCHAR AS REFERRAL_NUMBER, 
		$1:EIM_JOB_ID::NUMBER(38, 0) AS EIM_JOB_ID, 
		$1:SUBMITTER_NAME::VARCHAR AS SUBMITTER_NAME, 
		$1:PAYMENT_NOTES::VARCHAR AS PAYMENT_NOTES, 
		$1:NOTES::VARCHAR AS NOTES, 
		$1:ORTHODONTIC_TREATMENT_FLAG::BOOLEAN AS ORTHODONTIC_TREATMENT_FLAG, 
		$1:TOTAL_MONTHS_TREATMENT::NUMBER(38, 0) AS TOTAL_MONTHS_TREATMENT, 
		$1:REMAINING_MONTHS_TREATMENT::NUMBER(38, 0) AS REMAINING_MONTHS_TREATMENT, 
		$1:Partition::NUMBER(38, 0) AS Partition, 
		$1:RecordUpdateDatetime::TIMESTAMP_NTZ AS RecordUpdateDatetime
FROM 	'@DBO.HPDSDATALAKE_DBEXTRACT_DWSKYGEN/dbo/RefClaimExtended/'
		( FILE_FORMAT => DBO.DWSKYGEN_PARQUET_FILE_FORMAT);
