CREATE OR REPLACE VIEW DBO.vwPeriodLimits_VW
AS 
SELECT 	$1:LoadTargetID::NUMBER(38, 0) AS LoadTargetID, 
		$1:OffsetLimit::NUMBER(38, 0) AS OffsetLimit, 
		$1:LoadTarget::VARCHAR AS LoadTarget, 
		$1:CREATE_DATE::TIMESTAMP_NTZ AS CREATE_DATE, 
		$1:NOTES::VARCHAR AS NOTES
FROM 	'@DBO.HPDSDATALAKE_DBEXTRACT_DWSKYGEN/dbo/vwPeriodLimits/'
		( FILE_FORMAT => DBO.DWSKYGEN_PARQUET_FILE_FORMAT);

