CREATE OR REPLACE VIEW DBO.FactTransactions_VW
AS 
SELECT 	$1:DateStatusKey::NUMBER(38, 0) AS DateStatusKey, 
		$1:EnrolleeKey::NUMBER(38, 0) AS EnrolleeKey, 
		$1:PaymentMethodKey::NUMBER(38, 0) AS PaymentMethodKey, 
		$1:TransactionTypeKey::NUMBER(38, 0) AS TransactionTypeKey, 
		$1:TransactionStatusKey::NUMBER(38, 0) AS TransactionStatusKey, 
		$1:TRANSACTION_ID::NUMBER(38, 0) AS TRANSACTION_ID, 
		$1:INVOICE_ID::NUMBER(38, 0) AS INVOICE_ID, 
		$1:INVOICE_CREDIT_ID::NUMBER(38, 0) AS INVOICE_CREDIT_ID, 
		$1:CREATION_DATE::TIMESTAMP_NTZ AS CREATION_DATE, 
		$1:STATUS_DATE::TIMESTAMP_NTZ AS STATUS_DATE, 
		$1:SETTLED_DATE::DATE AS SETTLED_DATE, 
		$1:AMOUNT::NUMBER(19, 4) AS AMOUNT, 
		$1:EXTERNAL_TRANSACTION_ID::VARCHAR AS EXTERNAL_TRANSACTION_ID, 
		--$1:DW_Hash::VARCHAR AS DW_Hash, 
		$1:Partition::NUMBER(38, 0) AS Partition, 
		$1:RecordUpdateDatetime::TIMESTAMP_NTZ AS RecordUpdateDatetime
FROM 	'@DBO.HPDSDATALAKE_DBEXTRACT_DWSKYGEN/dbo/FactTransactions/'
		( FILE_FORMAT => DBO.DWSKYGEN_PARQUET_FILE_FORMAT);
