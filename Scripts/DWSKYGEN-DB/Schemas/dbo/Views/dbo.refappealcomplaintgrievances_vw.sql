CREATE OR REPLACE VIEW DBO.RefAppealComplaintGrievances_VW
AS 
SELECT 	$1:APPEAL_ID::NUMBER(38, 0) AS APPEAL_ID, 
		$1:AppealDescription::VARCHAR AS AppealDescription, 
		$1:RESOLUTION_DETAILS::VARCHAR AS RESOLUTION_DETAILS, 
		$1:APPEAL_NUMBER::VARCHAR AS APPEAL_NUMBER, 
		$1:CLIENT_REFERENCE_NUMBER::VARCHAR AS CLIENT_REFERENCE_NUMBER, 
		$1:APPEAL_NOTES::VARCHAR AS APPEAL_NOTES, 
		$1:CLAIM_ID::NUMBER(38, 0) AS CLAIM_ID, 
		$1:AUTHORIZATION_ID::NUMBER(38, 0) AS AUTHORIZATION_ID, 
		$1:APPEAL_BASED_ON::VARCHAR AS APPEAL_BASED_ON, 
		$1:COMPLAINT_AGAINST::VARCHAR AS COMPLAINT_AGAINST, 
		$1:Partition::NUMBER(38, 0) AS Partition, 
		$1:RecordUpdateDatetime::TIMESTAMP_NTZ AS RecordUpdateDatetime--, 
		--$1:DW_Hash::VARCHAR AS DW_Hash
FROM 	'@DBO.HPDSDATALAKE_DBEXTRACT_DWSKYGEN/dbo/RefAppealComplaintGrievances/'
		( FILE_FORMAT => DBO.DWSKYGEN_PARQUET_FILE_FORMAT);
