CREATE OR REPLACE VIEW DBO.Table_ForeignKey_VW
AS 
SELECT 	$1:TABLE_NAME::VARCHAR AS TABLE_NAME,
        $1:SURROGATE_KEY::VARCHAR AS SURROGATE_KEY,
        $1:ORDINAL_POSITION::NUMBER(38, 0) AS ORDINAL_POSITION,
        $1:DIMENSION_TABLE::VARCHAR AS DIMENSION_TABLE,
        $1:DIMENSION_SURROGATE_KEY::VARCHAR AS DIMENSION_SURROGATE_KEY,
        $1:RecordCreateDatetime::TIMESTAMP_NTZ AS RecordCreateDatetime,
        $1:RecordUpdateDatetime::TIMESTAMP_NTZ AS RecordUpdateDatetime
FROM 	'@DBO.HPDSDATALAKE_DBEXTRACT_DWSKYGEN/dbo/Table_ForeignKey/'
		( FILE_FORMAT => DBO.DWSKYGEN_PARQUET_FILE_FORMAT);