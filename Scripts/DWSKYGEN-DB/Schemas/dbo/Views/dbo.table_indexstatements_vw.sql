CREATE OR REPLACE VIEW DBO.Table_IndexStatements_VW
AS 
SELECT 	$1:TABLE_SCHEMA::VARCHAR AS TABLE_SCHEMA,
        $1:TABLE_NAME::VARCHAR AS TABLE_NAME,
        $1:CONSTRAINT_TYPE::VARCHAR AS CONSTRAINT_TYPE,
        $1:pkName::VARCHAR AS pkName,
        $1:PrimaryKeyStatment::VARCHAR AS PrimaryKeyStatment,
FROM 	'@DBO.HPDSDATALAKE_DBEXTRACT_DWSKYGEN/dbo/Table_IndexStatements/'
		( FILE_FORMAT => DBO.DWSKYGEN_PARQUET_FILE_FORMAT);
