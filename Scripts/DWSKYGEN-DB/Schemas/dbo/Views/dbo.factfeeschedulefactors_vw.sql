CREATE OR REPLACE VIEW DBO.FactFeeScheduleFactors_VW
AS 
SELECT 	$1:ZIP_RANGE_ID::NUMBER(38, 0) AS ZIP_RANGE_ID, 
		$1:PERCENTILE::NUMBER(38, 0) AS PERCENTILE, 
		$1:CODE_START::VARCHAR AS CODE_START, 
		$1:CODE_END::VARCHAR AS CODE_END, 
		$1:EFFECTIVE_DATE::DATE AS EFFECTIVE_DATE, 
		$1:TERMINATION_DATE::DATE AS TERMINATION_DATE, 
		$1:PERCENTILE_CONVERSION_FACTOR::NUMBER(38, 0) AS PERCENTILE_CONVERSION_FACTOR, 
		$1:GEOCODE_START::VARCHAR AS GEOCODE_START, 
		$1:GEOCODE_END::VARCHAR AS GEOCODE_END, 
		$1:Partition::NUMBER(38, 0) AS Partition, 
		$1:RecordUpdateDatetime::TIMESTAMP_NTZ AS RecordUpdateDatetime
FROM 	'@DBO.HPDSDATALAKE_DBEXTRACT_DWSKYGEN/dbo/FactFeeScheduleFactors/'
		( FILE_FORMAT => DBO.DWSKYGEN_PARQUET_FILE_FORMAT);
