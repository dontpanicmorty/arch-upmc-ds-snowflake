CREATE OR REPLACE VIEW DBO.RefAuthorizationServiceExtended_VW
AS 
SELECT 	$1:AUTHORIZATION_ID::NUMBER(38, 0) AS AUTHORIZATION_ID, 
		$1:ITEM_NUMBER::NUMBER(38, 0) AS ITEM_NUMBER, 
		$1:CODE::VARCHAR AS CODE, 
		$1:RecordUpdateDatetime::TIMESTAMP_NTZ AS RecordUpdateDatetime
FROM 	'@DBO.HPDSDATALAKE_DBEXTRACT_DWSKYGEN/dbo/RefAuthorizationServiceExtended/'
		( FILE_FORMAT => DBO.DWSKYGEN_PARQUET_FILE_FORMAT);
