--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.TERMINATION_REASON_DATA_SOURCE_REL AS TGT
USING (SELECT DATA_SOURCE_KEY, TERMINATION_REASON_KEY, TERMINATION_REASON_SOURCE_DESC
	FROM ODSDATA.TMP_TERMINATION_REASON_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, TERMINATION_REASON_KEY, TERMINATION_REASON_SOURCE_DESC
	FROM ODSDATA.TERMINATION_REASON_DATA_SOURCE_REL
	) AS SRC
ON TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.TERMINATION_REASON_KEY = SRC.TERMINATION_REASON_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.TERMINATION_REASON_SOURCE_DESC = SRC.TERMINATION_REASON_SOURCE_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(DATA_SOURCE_KEY
	,TERMINATION_REASON_KEY
	,TERMINATION_REASON_SOURCE_DESC
	)
VALUES
	(
	SRC.DATA_SOURCE_KEY
	,SRC.TERMINATION_REASON_KEY
	,SRC.TERMINATION_REASON_SOURCE_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.TERMINATION_REASON_DATA_SOURCE_REL TGT
USING
(SELECT DATA_SOURCE_KEY, TERMINATION_REASON_KEY, TERMINATION_REASON_SOURCE_DESC
	FROM ODSDATA.TERMINATION_REASON_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, TERMINATION_REASON_KEY, TERMINATION_REASON_SOURCE_DESC
	FROM ODSDATA.TMP_TERMINATION_REASON_DATA_SOURCE_REL
	) SRC
WHERE TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.TERMINATION_REASON_KEY = SRC.TERMINATION_REASON_KEY;