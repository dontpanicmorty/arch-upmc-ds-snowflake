	ODSDATA.TMP_TERMINATION_REASON_DATA_SOURCE_REL (
		TERMINATION_REASON_DATA_SOURCE_REL_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		DATA_SOURCE_KEY NUMBER(38,0) NOT NULL,
		TERMINATION_REASON_KEY NUMBER(38,0) NOT NULL,
		TERMINATION_REASON_SOURCE_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT FK_TERMINATION_REASON_DATA_SOURCE_REL_DATA_SOURCE FOREIGN KEY (DATA_SOURCE_KEY) REFERENCES ODSDATA.DATA_SOURCE (DATA_SOURCE_KEY),
		CONSTRAINT FK_TERMINATION_REASON_DATA_SOURCE_REL_TERMINATION_REASON FOREIGN KEY (TERMINATION_REASON_KEY) REFERENCES ODSDATA.TERMINATION_REASON (TERMINATION_REASON_KEY),
		CONSTRAINT PK_TERMINATION_REASON_DATA_SOURCE_REL PRIMARY KEY (TERMINATION_REASON_DATA_SOURCE_REL_KEY),
		CONSTRAINT UK_TERMINATION_REASON_DATA_SOURCE_REL UNIQUE (DATA_SOURCE_KEY, TERMINATION_REASON_KEY, TERMINATION_REASON_SOURCE_DESC)
	)COMMENT='Relates source TerminationReason values to standard values in TerminationReason'
;

