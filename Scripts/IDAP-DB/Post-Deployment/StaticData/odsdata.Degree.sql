--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.DEGREE AS TGT
USING (SELECT DEGREE_KEY, DEGREE_NAME
	FROM ODSDATA.TMP_DEGREE
	MINUS 
	SELECT DEGREE_KEY, DEGREE_NAME
	FROM ODSDATA.DEGREE
	) AS SRC
ON TGT.DEGREE_KEY = SRC.DEGREE_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.DEGREE_NAME = SRC.DEGREE_NAME
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(DEGREE_KEY
	,DEGREE_NAME
	)
VALUES
	(
	SRC.DEGREE_KEY
	,SRC.DEGREE_NAME
	);
	
