CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_WEEK_DAY (
		WEEK_DAY_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		WEEK_DAY_NAME VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_WEEK_DAY PRIMARY KEY (WEEK_DAY_KEY),
		CONSTRAINT UK_WEEK_DAY UNIQUE (WEEK_DAY_NAME)
	)COMMENT='Contains a list of the only allowable days of the week.'
;

INSERT INTO ODSDATA.TMP_WEEK_DAY (WEEK_DAY_KEY,WEEK_DAY_NAME) VALUES
	 (1,'Monday'),
	 (2,'Tuesday'),
	 (3,'Wednesday'),
	 (4,'Thursday'),
	 (5,'Friday'),
	 (6,'Saturday'),
	 (7,'Sunday');

--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.WEEK_DAY AS TGT
USING (SELECT WEEK_DAY_KEY, WEEK_DAY_NAME
	FROM ODSDATA.TMP_WEEK_DAY
	MINUS 
	SELECT WEEK_DAY_KEY, WEEK_DAY_NAME
	FROM ODSDATA.WEEK_DAY
	) AS SRC
ON TGT.WEEK_DAY_KEY = SRC.WEEK_DAY_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.WEEK_DAY_NAME = SRC.WEEK_DAY_NAME
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(WEEK_DAY_KEY
	,WEEK_DAY_NAME
	)
VALUES
	(
	SRC.WEEK_DAY_KEY
	,SRC.WEEK_DAY_NAME
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.WEEK_DAY TGT
USING
(SELECT WEEK_DAY_KEY, WEEK_DAY_NAME
	FROM ODSDATA.WEEK_DAY
	MINUS 
	SELECT WEEK_DAY_KEY, WEEK_DAY_NAME
	FROM ODSDATA.TMP_WEEK_DAY
	) SRC
WHERE TGT.WEEK_DAY_KEY = SRC.WEEK_DAY_KEY;