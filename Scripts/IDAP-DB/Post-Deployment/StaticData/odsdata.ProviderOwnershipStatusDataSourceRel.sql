CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_PROVIDER_OWNERSHIP_STATUS_DATA_SOURCE_REL (
		PROVIDER_OWNERSHIP_STATUS_DATA_SOURCE_REL_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		DATA_SOURCE_KEY NUMBER(38,0) NOT NULL,
		PROVIDER_OWNERSHIP_STATUS_KEY NUMBER(38,0) NOT NULL,
		PROVIDER_OWNERSHIP_STATUS_SOURCE_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT FK_PROVIDER_OWNERSHIP_STATUS_DATA_SOURCE_REL_DATA_SOURCE FOREIGN KEY (DATA_SOURCE_KEY) REFERENCES ODSDATA.DATA_SOURCE (DATA_SOURCE_KEY),
		CONSTRAINT FK_PROVIDER_OWNERSHIP_STATUS_DATA_SOURCE_REL_PROVIDER_OWNERSHIP_STATUS FOREIGN KEY (PROVIDER_OWNERSHIP_STATUS_KEY) REFERENCES ODSDATA.PROVIDER_OWNERSHIP_STATUS (PROVIDER_OWNERSHIP_STATUS_KEY),
		CONSTRAINT PK_PROVIDER_OWNERSHIP_STATUS_DATA_SOURCE_REL PRIMARY KEY (PROVIDER_OWNERSHIP_STATUS_DATA_SOURCE_REL_KEY),
		CONSTRAINT UK_PROVIDER_OWNERSHIP_STATUS_DATA_SOURCE_REL UNIQUE (DATA_SOURCE_KEY, PROVIDER_OWNERSHIP_STATUS_KEY, PROVIDER_OWNERSHIP_STATUS_SOURCE_DESC)
	)COMMENT='Relates source ProviderOwnershpStatus values to standard values in ProviderOwnershipStatus'
;

INSERT INTO ODSDATA.TMP_PROVIDER_OWNERSHIP_STATUS_DATA_SOURCE_REL
(DATA_SOURCE_KEY, PROVIDER_OWNERSHIP_STATUS_KEY, PROVIDER_OWNERSHIP_STATUS_SOURCE_DESC)
VALUES
(1, 1, 'Owned'),
(1, 2, 'Joint Venture'),
(1, 3, 'Not Owned'),
(1, 4, 'No Value Specified');

--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.PROVIDER_OWNERSHIP_STATUS_DATA_SOURCE_REL AS TGT
USING (SELECT DATA_SOURCE_KEY, PROVIDER_OWNERSHIP_STATUS_KEY, PROVIDER_OWNERSHIP_STATUS_SOURCE_DESC
	FROM ODSDATA.TMP_PROVIDER_OWNERSHIP_STATUS_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, PROVIDER_OWNERSHIP_STATUS_KEY, PROVIDER_OWNERSHIP_STATUS_SOURCE_DESC
	FROM ODSDATA.PROVIDER_OWNERSHIP_STATUS_DATA_SOURCE_REL
	) AS SRC
ON TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.PROVIDER_OWNERSHIP_STATUS_KEY = SRC.PROVIDER_OWNERSHIP_STATUS_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.PROVIDER_OWNERSHIP_STATUS_SOURCE_DESC = SRC.PROVIDER_OWNERSHIP_STATUS_SOURCE_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(DATA_SOURCE_KEY
	,PROVIDER_OWNERSHIP_STATUS_KEY
	,PROVIDER_OWNERSHIP_STATUS_SOURCE_DESC
	)
VALUES
	(
	SRC.DATA_SOURCE_KEY
	,SRC.PROVIDER_OWNERSHIP_STATUS_KEY
	,SRC.PROVIDER_OWNERSHIP_STATUS_SOURCE_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.PROVIDER_OWNERSHIP_STATUS_DATA_SOURCE_REL TGT
USING
(SELECT DATA_SOURCE_KEY, PROVIDER_OWNERSHIP_STATUS_KEY, PROVIDER_OWNERSHIP_STATUS_SOURCE_DESC
	FROM ODSDATA.PROVIDER_OWNERSHIP_STATUS_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, PROVIDER_OWNERSHIP_STATUS_KEY, PROVIDER_OWNERSHIP_STATUS_SOURCE_DESC
	FROM ODSDATA.TMP_PROVIDER_OWNERSHIP_STATUS_DATA_SOURCE_REL
	) SRC
WHERE TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.PROVIDER_OWNERSHIP_STATUS_KEY = SRC.PROVIDER_OWNERSHIP_STATUS_KEY;