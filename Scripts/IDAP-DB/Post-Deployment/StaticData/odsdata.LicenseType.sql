--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.LICENSE_TYPE AS TGT
USING (SELECT LICENSE_TYPE_KEY, LICENSE_TYPE_DESC, LICENSE_TYPE_CODE
	FROM ODSDATA.TMP_LICENSE_TYPE
	MINUS 
	SELECT LICENSE_TYPE_KEY, LICENSE_TYPE_DESC, LICENSE_TYPE_CODE
	FROM ODSDATA.LICENSE_TYPE
	) AS SRC
ON TGT.LICENSE_TYPE_KEY = SRC.LICENSE_TYPE_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.LICENSE_TYPE_DESC = SRC.LICENSE_TYPE_DESC
	,TGT.LICENSE_TYPE_CODE = SRC.LICENSE_TYPE_CODE
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(LICENSE_TYPE_KEY
	,LICENSE_TYPE_DESC
	,LICENSE_TYPE_CODE
	)
VALUES
	(
	SRC.LICENSE_TYPE_KEY
	,SRC.LICENSE_TYPE_DESC
	,SRC.LICENSE_TYPE_CODE
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.LICENSE_TYPE TGT
USING
(SELECT LICENSE_TYPE_KEY, LICENSE_TYPE_DESC, LICENSE_TYPE_CODE
	FROM ODSDATA.LICENSE_TYPE
	MINUS 
	SELECT LICENSE_TYPE_KEY, LICENSE_TYPE_DESC, LICENSE_TYPE_CODE
	FROM ODSDATA.TMP_LICENSE_TYPE
	) SRC
WHERE TGT.LICENSE_TYPE_KEY = SRC.LICENSE_TYPE_KEY;