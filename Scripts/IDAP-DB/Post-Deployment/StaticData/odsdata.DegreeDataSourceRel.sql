CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_DEGREE_DATA_SOURCE_REL (
		DEGREE_DATA_SOURCE_REL_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		DATA_SOURCE_KEY NUMBER(38,0) NOT NULL,
		DEGREE_KEY NUMBER(38,0) NOT NULL,
		DEGREE_SOURCE_NAME VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT FK_DEGREE_DATA_SOURCE_REL_DATA_SOURCE FOREIGN KEY (DATA_SOURCE_KEY) REFERENCES ODSDATA.DATA_SOURCE (DATA_SOURCE_KEY),
		CONSTRAINT FK_DEGREE_DATA_SOURCE_REL_DEGREE FOREIGN KEY (DEGREE_KEY) REFERENCES ODSDATA.DEGREE (DEGREE_KEY),
		CONSTRAINT PK_DEGREE_DATA_SOURCE_REL PRIMARY KEY (DEGREE_DATA_SOURCE_REL_KEY),
		CONSTRAINT UK_DEGREE_DATA_SOURCE_REL UNIQUE (DEGREE_KEY, DATA_SOURCE_KEY, DEGREE_SOURCE_NAME)
	)COMMENT='Relates source Degree values to standard values in Degree'
;

