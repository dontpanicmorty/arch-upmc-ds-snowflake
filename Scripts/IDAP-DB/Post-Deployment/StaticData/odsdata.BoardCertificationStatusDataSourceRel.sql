CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_BOARD_CERTIFICATION_STATUS_DATA_SOURCE_REL (
		BOARD_CERTIFICATION_STATUS_DATA_SOURCE_REL_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		DATA_SOURCE_KEY NUMBER(38,0) NOT NULL,
		BOARD_CERTIFICATION_STATUS_KEY NUMBER(38,0) NOT NULL,
		BOARD_CERTIFICATION_STATUS_SOURCE_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT FK_BOARD_CERTIFICATION_STATUS_DATA_SOURCE_REL_BOARD_CERTIFICATION_STATUS FOREIGN KEY (BOARD_CERTIFICATION_STATUS_KEY) REFERENCES ODSDATA.BOARD_CERTIFICATION_STATUS (BOARD_CERTIFICATION_STATUS_KEY),
		CONSTRAINT FK_BOARD_CERTIFICATION_STATUS_DATA_SOURCE_REL_DATA_SOURCE FOREIGN KEY (DATA_SOURCE_KEY) REFERENCES ODSDATA.DATA_SOURCE (DATA_SOURCE_KEY),
		CONSTRAINT PK_BOARD_CERTIFICATION_STATUS_DATA_SOURCE_REL PRIMARY KEY (BOARD_CERTIFICATION_STATUS_DATA_SOURCE_REL_KEY),
		CONSTRAINT UK_BOARD_CERTIFICATION_STATUS_DATA_SOURCE_REL UNIQUE (DATA_SOURCE_KEY, BOARD_CERTIFICATION_STATUS_KEY, BOARD_CERTIFICATION_STATUS_SOURCE_DESC)
	)COMMENT='Relates source BoardCertificationStatus values to standard values in BoardCertificationStatus'
;

