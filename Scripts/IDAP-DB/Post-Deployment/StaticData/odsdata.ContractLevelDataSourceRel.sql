CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_CONTRACT_LEVEL_DATA_SOURCE_REL (
		CONTRACT_LEVEL_DATA_SOURCE_REL_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		DATA_SOURCE_KEY NUMBER(38,0) NOT NULL,
		CONTRACT_LEVEL_KEY NUMBER(38,0) NOT NULL,
		CONTRACT_LEVEL_SOURCE_CODE VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT FK_CONTRACT_LEVEL_DATA_SOURCE_REL_CONTRACT_LEVEL FOREIGN KEY (CONTRACT_LEVEL_KEY) REFERENCES ODSDATA.CONTRACT_LEVEL (CONTRACT_LEVEL_KEY),
		CONSTRAINT FK_CONTRACT_LEVEL_DATA_SOURCE_REL_DATA_SOURCE FOREIGN KEY (DATA_SOURCE_KEY) REFERENCES ODSDATA.DATA_SOURCE (DATA_SOURCE_KEY),
		CONSTRAINT PK_CONTRACT_LEVEL_DATA_SOURCE_REL PRIMARY KEY (CONTRACT_LEVEL_DATA_SOURCE_REL_KEY),
		CONSTRAINT UK_CONTRACT_LEVEL_DATA_SOURCE_REL UNIQUE (DATA_SOURCE_KEY, CONTRACT_LEVEL_KEY, CONTRACT_LEVEL_SOURCE_CODE)
	)COMMENT='Relates source ContractLevel values to standard values in ContractLevel'
;

INSERT INTO ODSDATA.TMP_CONTRACT_LEVEL_DATA_SOURCE_REL
(DATA_SOURCE_KEY, CONTRACT_LEVEL_KEY, CONTRACT_LEVEL_SOURCE_CODE)
VALUES
(1, 1, 'Level 1'),
(1, 2, 'Level 2'),
(1, 3, 'No Value Specified'),
(1, 4, 'Pending (Network)'),
(1, 5, 'Executed (Network)');

--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.CONTRACT_LEVEL_DATA_SOURCE_REL AS TGT
USING (SELECT DATA_SOURCE_KEY, CONTRACT_LEVEL_KEY, CONTRACT_LEVEL_SOURCE_CODE
	FROM ODSDATA.TMP_CONTRACT_LEVEL_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, CONTRACT_LEVEL_KEY, CONTRACT_LEVEL_SOURCE_CODE
	FROM ODSDATA.CONTRACT_LEVEL_DATA_SOURCE_REL
	) AS SRC
ON TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.CONTRACT_LEVEL_KEY = SRC.CONTRACT_LEVEL_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.CONTRACT_LEVEL_SOURCE_CODE = SRC.CONTRACT_LEVEL_SOURCE_CODE
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(DATA_SOURCE_KEY
	,CONTRACT_LEVEL_KEY
	,CONTRACT_LEVEL_SOURCE_CODE
	)
VALUES
	(
	SRC.DATA_SOURCE_KEY
	,SRC.CONTRACT_LEVEL_KEY
	,SRC.CONTRACT_LEVEL_SOURCE_CODE
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.CONTRACT_LEVEL_DATA_SOURCE_REL TGT
USING
(SELECT DATA_SOURCE_KEY, CONTRACT_LEVEL_KEY, CONTRACT_LEVEL_SOURCE_CODE
	FROM ODSDATA.CONTRACT_LEVEL_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, CONTRACT_LEVEL_KEY, CONTRACT_LEVEL_SOURCE_CODE
	FROM ODSDATA.TMP_CONTRACT_LEVEL_DATA_SOURCE_REL
	) SRC
WHERE TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.CONTRACT_LEVEL_KEY = SRC.CONTRACT_LEVEL_KEY;