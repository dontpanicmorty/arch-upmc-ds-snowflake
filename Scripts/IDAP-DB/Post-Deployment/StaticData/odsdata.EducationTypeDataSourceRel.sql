CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_EDUCATION_TYPE_DATA_SOURCE_REL (
		EDUCATION_TYPE_DATA_SOURCE_REL_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		DATA_SOURCE_KEY NUMBER(38,0) NOT NULL,
		EDUCATION_TYPE_KEY NUMBER(38,0) NOT NULL,
		EDUCATION_TYPE_SOURCE_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT FK_EDUCATION_TYPE_DATA_SOURCE_REL_DATA_SOURCE FOREIGN KEY (DATA_SOURCE_KEY) REFERENCES ODSDATA.DATA_SOURCE (DATA_SOURCE_KEY),
		CONSTRAINT FK_EDUCATION_TYPE_DATA_SOURCE_REL_EDUCATION_TYPE FOREIGN KEY (EDUCATION_TYPE_KEY) REFERENCES ODSDATA.EDUCATION_TYPE (EDUCATION_TYPE_KEY),
		CONSTRAINT PK_EDUCATION_TYPE_DATA_SOURCE_REL PRIMARY KEY (EDUCATION_TYPE_DATA_SOURCE_REL_KEY),
		CONSTRAINT UK_EDUCATION_TYPE_DATA_SOURCE_REL UNIQUE (DATA_SOURCE_KEY, EDUCATION_TYPE_KEY, EDUCATION_TYPE_SOURCE_DESC)
	)COMMENT='Relates source EducationType values to standard values in EducationType'
