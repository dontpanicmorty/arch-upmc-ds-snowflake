(SELECT DATA_SOURCE_KEY, LANGUAGE_KEY, LANGUAGE_SOURCE_NAME
	FROM ODSDATA.LANGUAGE_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, LANGUAGE_KEY, LANGUAGE_SOURCE_NAME
	FROM ODSDATA.TMP_LANGUAGE_DATA_SOURCE_REL
	) SRC
WHERE TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
