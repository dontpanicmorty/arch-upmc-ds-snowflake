--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.LANGUAGE_DATA_SOURCE_REL AS TGT
USING (SELECT DATA_SOURCE_KEY, LANGUAGE_KEY, LANGUAGE_SOURCE_NAME
	FROM ODSDATA.TMP_LANGUAGE_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, LANGUAGE_KEY, LANGUAGE_SOURCE_NAME
	FROM ODSDATA.LANGUAGE_DATA_SOURCE_REL
	) AS SRC
ON TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.LANGUAGE_KEY = SRC.LANGUAGE_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.LANGUAGE_SOURCE_NAME = SRC.LANGUAGE_SOURCE_NAME
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(DATA_SOURCE_KEY
	,LANGUAGE_KEY
	,LANGUAGE_SOURCE_NAME
	)
VALUES
	(
	SRC.DATA_SOURCE_KEY
	,SRC.LANGUAGE_KEY
	,SRC.LANGUAGE_SOURCE_NAME
	);
	
