--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.PHYSICIAN_HOSPITAL_ORGANIZATION_DATA_SOURCE_REL AS TGT
USING (SELECT DATA_SOURCE_KEY, PHYSICIAN_HOSPITAL_ORGANIZATION_KEY, PHYSICIAN_HOSPITAL_ORGANIZATION_SOURCE_NAME
	FROM ODSDATA.TMP_PHYSICIAN_HOSPITAL_ORGANIZATION_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, PHYSICIAN_HOSPITAL_ORGANIZATION_KEY, PHYSICIAN_HOSPITAL_ORGANIZATION_SOURCE_NAME
	FROM ODSDATA.PHYSICIAN_HOSPITAL_ORGANIZATION_DATA_SOURCE_REL
	) AS SRC
ON TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.PHYSICIAN_HOSPITAL_ORGANIZATION_KEY = SRC.PHYSICIAN_HOSPITAL_ORGANIZATION_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.PHYSICIAN_HOSPITAL_ORGANIZATION_SOURCE_NAME = SRC.PHYSICIAN_HOSPITAL_ORGANIZATION_SOURCE_NAME
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(DATA_SOURCE_KEY
	,PHYSICIAN_HOSPITAL_ORGANIZATION_KEY
	,PHYSICIAN_HOSPITAL_ORGANIZATION_SOURCE_NAME
	)
VALUES
	(
	SRC.DATA_SOURCE_KEY
	,SRC.PHYSICIAN_HOSPITAL_ORGANIZATION_KEY
	,SRC.PHYSICIAN_HOSPITAL_ORGANIZATION_SOURCE_NAME
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.PHYSICIAN_HOSPITAL_ORGANIZATION_DATA_SOURCE_REL TGT
USING
(SELECT DATA_SOURCE_KEY, PHYSICIAN_HOSPITAL_ORGANIZATION_KEY, PHYSICIAN_HOSPITAL_ORGANIZATION_SOURCE_NAME
	FROM ODSDATA.PHYSICIAN_HOSPITAL_ORGANIZATION_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, PHYSICIAN_HOSPITAL_ORGANIZATION_KEY, PHYSICIAN_HOSPITAL_ORGANIZATION_SOURCE_NAME
	FROM ODSDATA.TMP_PHYSICIAN_HOSPITAL_ORGANIZATION_DATA_SOURCE_REL
	) SRC
WHERE TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.PHYSICIAN_HOSPITAL_ORGANIZATION_KEY = SRC.PHYSICIAN_HOSPITAL_ORGANIZATION_KEY;