CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_BOARD_CERTIFICATION_STATUS (
		BOARD_CERTIFICATION_STATUS_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		BOARD_CERTIFICATION_STATUS_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_BOARD_CERTIFICATION_STATUS PRIMARY KEY (BOARD_CERTIFICATION_STATUS_KEY),
		CONSTRAINT UK_BOARD_CERTIFICATION_STATUS UNIQUE (BOARD_CERTIFICATION_STATUS_DESC)		
	)COMMENT='The status of a Board Certification'
;

INSERT INTO ODSDATA.TMP_BOARD_CERTIFICATION_STATUS (BOARD_CERTIFICATION_STATUS_KEY,BOARD_CERTIFICATION_STATUS_DESC) VALUES
	 (1,'Active'),
	 (2,'Inactive'),
	 (3,'Eligible'),
	 (4,'Unknown');

--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.BOARD_CERTIFICATION_STATUS AS TGT
USING (SELECT BOARD_CERTIFICATION_STATUS_KEY, BOARD_CERTIFICATION_STATUS_DESC
	FROM ODSDATA.TMP_BOARD_CERTIFICATION_STATUS
	MINUS 
	SELECT BOARD_CERTIFICATION_STATUS_KEY, BOARD_CERTIFICATION_STATUS_DESC
	FROM ODSDATA.BOARD_CERTIFICATION_STATUS
	) AS SRC
ON TGT.BOARD_CERTIFICATION_STATUS_KEY = SRC.BOARD_CERTIFICATION_STATUS_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.BOARD_CERTIFICATION_STATUS_DESC = SRC.BOARD_CERTIFICATION_STATUS_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(BOARD_CERTIFICATION_STATUS_KEY
	,BOARD_CERTIFICATION_STATUS_DESC
	)
VALUES
	(
	SRC.BOARD_CERTIFICATION_STATUS_KEY
	,SRC.BOARD_CERTIFICATION_STATUS_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.BOARD_CERTIFICATION_STATUS TGT
USING
(SELECT BOARD_CERTIFICATION_STATUS_KEY BOARD_CERTIFICATION_STATUS_KEY, BOARD_CERTIFICATION_STATUS_DESC
	FROM ODSDATA.BOARD_CERTIFICATION_STATUS
	MINUS 
	SELECT BOARD_CERTIFICATION_STATUS_KEY, BOARD_CERTIFICATION_STATUS_DESC
	FROM ODSDATA.TMP_BOARD_CERTIFICATION_STATUS
	) SRC
WHERE TGT.BOARD_CERTIFICATION_STATUS_KEY = SRC.BOARD_CERTIFICATION_STATUS_KEY;