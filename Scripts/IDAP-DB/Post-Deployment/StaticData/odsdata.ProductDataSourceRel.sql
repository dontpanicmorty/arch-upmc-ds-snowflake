		CONSTRAINT UK_PRODUCT_DATA_SOURCE_REL UNIQUE (DATA_SOURCE_KEY, PRODUCT_KEY, PRODUCT_SOURCE_NAME, TPA_HIERARCHY_KEY)
	)COMMENT='Relates source Product values to standard values in Product'
