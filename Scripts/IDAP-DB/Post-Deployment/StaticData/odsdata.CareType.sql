CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_CARE_TYPE (
		CARE_TYPE_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		CARE_TYPE_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		TELEHEALTH_IND CHAR(1) NOT NULL,
		CONSTRAINT PK_CARE_TYPE PRIMARY KEY (CARE_TYPE_KEY),
		CONSTRAINT UK_CARE_TYPE UNIQUE (CARE_TYPE_DESC)
	)COMMENT='The type of care that can be recieved. This classification is for general type of insurance or care. Examples: Medical, Dental, Vision, CCBH'
;

INSERT INTO ODSDATA.TMP_CARE_TYPE (CARE_TYPE_KEY,CARE_TYPE_DESC,TELEHEALTH_IND) VALUES
	 (1,'Medical','Y'),
	 (2,'Behavioral Health','Y'),
	 (3,'Vision','N'),
	 (4,'Dental','N'),
	 (5,'Home & Community-Based Services','N'),
	 (6,'Pharmacy','N');

--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.CARE_TYPE AS TGT
USING (SELECT CARE_TYPE_KEY, CARE_TYPE_DESC, TELEHEALTH_IND
	FROM ODSDATA.TMP_CARE_TYPE
	MINUS 
	SELECT CARE_TYPE_KEY, CARE_TYPE_DESC, TELEHEALTH_IND
	FROM ODSDATA.CARE_TYPE
	) AS SRC
ON TGT.CARE_TYPE_KEY = SRC.CARE_TYPE_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.CARE_TYPE_DESC = SRC.CARE_TYPE_DESC
	,TGT.TELEHEALTH_IND = SRC.TELEHEALTH_IND
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(CARE_TYPE_KEY
	,CARE_TYPE_DESC
	,TELEHEALTH_IND
	)
VALUES
	(
	SRC.CARE_TYPE_KEY
	,SRC.CARE_TYPE_DESC
	,SRC.TELEHEALTH_IND
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.CARE_TYPE TGT
USING
(SELECT CARE_TYPE_KEY, CARE_TYPE_DESC, TELEHEALTH_IND
	FROM ODSDATA.CARE_TYPE
	MINUS 
	SELECT CARE_TYPE_KEY, CARE_TYPE_DESC, TELEHEALTH_IND
	FROM ODSDATA.TMP_CARE_TYPE
	) SRC
WHERE TGT.CARE_TYPE_KEY = SRC.CARE_TYPE_KEY;