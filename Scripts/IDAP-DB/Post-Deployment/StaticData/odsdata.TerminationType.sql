CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_TERMINATION_TYPE (
		TERMINATION_TYPE_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		TERMINATION_TYPE_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_TERMINATION_TYPE PRIMARY KEY (TERMINATION_TYPE_KEY),
		CONSTRAINT UK_TERMINATION_TYPE UNIQUE (TERMINATION_TYPE_DESC)
	)COMMENT='The type ofTermination. This will allow for termination reasons to be used for each type. Examples: ContractTermination, Provider Termination, Address Termination, etc'
;

INSERT INTO ODSDATA.TMP_TERMINATION_TYPE (TERMINATION_TYPE_KEY,TERMINATION_TYPE_DESC) VALUES
	 (1,'Contract Termination');

--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.TERMINATION_TYPE AS TGT
USING (SELECT TERMINATION_TYPE_KEY, TERMINATION_TYPE_DESC
	FROM ODSDATA.TMP_TERMINATION_TYPE
	MINUS 
	SELECT TERMINATION_TYPE_KEY, TERMINATION_TYPE_DESC
	FROM ODSDATA.TERMINATION_TYPE
	) AS SRC
ON TGT.TERMINATION_TYPE_KEY = SRC.TERMINATION_TYPE_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.TERMINATION_TYPE_DESC = SRC.TERMINATION_TYPE_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(TERMINATION_TYPE_KEY
	,TERMINATION_TYPE_DESC
	)
VALUES
	(
	SRC.TERMINATION_TYPE_KEY
	,SRC.TERMINATION_TYPE_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.TERMINATION_TYPE TGT
USING
(SELECT TERMINATION_TYPE_KEY, TERMINATION_TYPE_DESC
	FROM ODSDATA.TERMINATION_TYPE
	MINUS 
	SELECT TERMINATION_TYPE_KEY, TERMINATION_TYPE_DESC
	FROM ODSDATA.TMP_TERMINATION_TYPE
	) SRC
WHERE TGT.TERMINATION_TYPE_KEY = SRC.TERMINATION_TYPE_KEY;