CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_TPA_HIERARCHY (
		TPA_HIERARCHY_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		CLIENT_ID CHAR(6) NOT NULL,
		TPA_ID CHAR(6) NOT NULL,
		TPA_DIV_ID CHAR(4) NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		TPA_DESC VARCHAR NOT NULL,
		CONSTRAINT PK_TPA_HIERARCHY PRIMARY KEY (TPA_HIERARCHY_KEY),
		CONSTRAINT UK_TPA_HIERARCHY UNIQUE (CLIENT_ID, TPA_ID, TPA_DIV_ID)
	)COMMENT='Contains information concerning Third Party Administrators.'
;

INSERT INTO ODSDATA.TMP_TPA_HIERARCHY (TPA_HIERARCHY_KEY,CLIENT_ID,TPA_ID,TPA_DIV_ID,TPA_DESC) VALUES
	 (1,'000001','000001','0001','UPMC');

--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.TPA_HIERARCHY AS TGT
USING (SELECT TPA_HIERARCHY_KEY, CLIENT_ID, TPA_ID, TPA_DIV_ID, TPA_DESC
	FROM ODSDATA.TMP_TPA_HIERARCHY
	MINUS 
	SELECT TPA_HIERARCHY_KEY, CLIENT_ID, TPA_ID, TPA_DIV_ID, TPA_DESC
	FROM ODSDATA.TPA_HIERARCHY
	) AS SRC
ON TGT.TPA_HIERARCHY_KEY = SRC.TPA_HIERARCHY_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.TPA_HIERARCHY_KEY = SRC.TPA_HIERARCHY_KEY
	,CLIENT_ID = SRC.CLIENT_ID
	,TGT.TPA_ID = SRC.TPA_ID
	,TGT.TPA_DIV_ID = SRC.TPA_ID
	,TGT.TPA_DESC = SRC.TPA_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(TPA_HIERARCHY_KEY
	,CLIENT_ID
	,TPA_ID
	,TPA_DIV_ID
	,TPA_DESC
	)
VALUES
	(
	SRC.TPA_HIERARCHY_KEY
	,SRC.CLIENT_ID
	,SRC.TPA_ID
	,SRC.TPA_DIV_ID
	,SRC.TPA_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.TPA_HIERARCHY TGT
USING
(SELECT TPA_HIERARCHY_KEY, CLIENT_ID, TPA_ID, TPA_DIV_ID, TPA_DESC
	FROM ODSDATA.TPA_HIERARCHY
	MINUS 
	SELECT TPA_HIERARCHY_KEY, CLIENT_ID, TPA_ID, TPA_DIV_ID, TPA_DESC
	FROM ODSDATA.TMP_TPA_HIERARCHY
	) SRC
WHERE TGT.TPA_HIERARCHY_KEY = SRC.TPA_HIERARCHY_KEY;