CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_CONTRACT_LEVEL (
		CONTRACT_LEVEL_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		CONTRACT_LEVEL_CODE CHAR(1) NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONTRACT_LEVEL_DESC VARCHAR,
		CONSTRAINT PK_CONTRACT_LEVEL PRIMARY KEY (CONTRACT_LEVEL_KEY),
		CONSTRAINT UK_CONTRACT_LEVEL UNIQUE (CONTRACT_LEVEL_CODE)
	)COMMENT='The level of a Contract.'
;

INSERT INTO ODSDATA.TMP_CONTRACT_LEVEL (CONTRACT_LEVEL_KEY,CONTRACT_LEVEL_CODE,CONTRACT_LEVEL_DESC) VALUES
	 (1,'1','Level 1'),
	 (2,'2','Level 2'),
	 (3,'0','Unknown'),
	 (4,'P','Pending (Network)'),
	 (5,'E','Executed (Network)');

--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.CONTRACT_LEVEL AS TGT
USING (SELECT CONTRACT_LEVEL_KEY, CONTRACT_LEVEL_CODE, CONTRACT_LEVEL_DESC
	FROM ODSDATA.TMP_CONTRACT_LEVEL
	MINUS 
	SELECT CONTRACT_LEVEL_KEY, CONTRACT_LEVEL_CODE, CONTRACT_LEVEL_DESC
	FROM ODSDATA.CONTRACT_LEVEL
	) AS SRC
ON TGT.CONTRACT_LEVEL_KEY = SRC.CONTRACT_LEVEL_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.CONTRACT_LEVEL_CODE = SRC.CONTRACT_LEVEL_CODE
	,TGT.CONTRACT_LEVEL_DESC = SRC.CONTRACT_LEVEL_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(CONTRACT_LEVEL_KEY
	,CONTRACT_LEVEL_CODE
	,CONTRACT_LEVEL_DESC
	)
VALUES
	(
	SRC.CONTRACT_LEVEL_KEY
	,SRC.CONTRACT_LEVEL_CODE
	,SRC.CONTRACT_LEVEL_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.CONTRACT_LEVEL TGT
USING
(SELECT CONTRACT_LEVEL_KEY, CONTRACT_LEVEL_CODE, CONTRACT_LEVEL_DESC
	FROM ODSDATA.CONTRACT_LEVEL
	MINUS 
	SELECT CONTRACT_LEVEL_KEY, CONTRACT_LEVEL_CODE, CONTRACT_LEVEL_DESC
	FROM ODSDATA.TMP_CONTRACT_LEVEL
	) SRC
WHERE TGT.CONTRACT_LEVEL_KEY = SRC.CONTRACT_LEVEL_KEY;