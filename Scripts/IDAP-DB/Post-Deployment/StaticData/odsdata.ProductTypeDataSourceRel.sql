--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.PRODUCT_TYPE_DATA_SOURCE_REL AS TGT
USING (SELECT DATA_SOURCE_KEY, PRODUCT_TYPE_KEY, PRODUCT_TYPE_SOURCE_NAME, TPA_HIERARCHY_KEY
	FROM ODSDATA.TMP_PRODUCT_TYPE_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, PRODUCT_TYPE_KEY, PRODUCT_TYPE_SOURCE_NAME, TPA_HIERARCHY_KEY
	FROM ODSDATA.PRODUCT_TYPE_DATA_SOURCE_REL
	) AS SRC
ON TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.PRODUCT_TYPE_KEY = SRC.PRODUCT_TYPE_KEY
AND TGT.TPA_HIERARCHY_KEY = SRC.TPA_HIERARCHY_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.PRODUCT_TYPE_SOURCE_NAME = SRC.PRODUCT_TYPE_SOURCE_NAME
	,TGT.TPA_HIERARCHY_KEY = SRC.TPA_HIERARCHY_KEY
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(DATA_SOURCE_KEY
	,PRODUCT_TYPE_KEY
	,PRODUCT_TYPE_SOURCE_NAME
	,TPA_HIERARCHY_KEY
	)
VALUES
	(
	SRC.DATA_SOURCE_KEY
	,SRC.PRODUCT_TYPE_KEY
	,SRC.PRODUCT_TYPE_SOURCE_NAME
	,SRC.TPA_HIERARCHY_KEY
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.PRODUCT_TYPE_DATA_SOURCE_REL TGT
USING
(SELECT DATA_SOURCE_KEY, PRODUCT_TYPE_KEY, PRODUCT_TYPE_SOURCE_NAME, TPA_HIERARCHY_KEY
	FROM ODSDATA.PRODUCT_TYPE_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, PRODUCT_TYPE_KEY, PRODUCT_TYPE_SOURCE_NAME, TPA_HIERARCHY_KEY
	FROM ODSDATA.TMP_PRODUCT_TYPE_DATA_SOURCE_REL
	) SRC
WHERE TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.PRODUCT_TYPE_KEY = SRC.PRODUCT_TYPE_KEY
AND TGT.TPA_HIERARCHY_KEY = SRC.TPA_HIERARCHY_KEY;