CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_ADDRESS_USAGE_TYPE_DATA_SOURCE_REL (
		ADDRESS_USAGE_TYPE_DATA_SOURCE_REL_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		DATA_SOURCE_KEY NUMBER(38,0) NOT NULL,
		ADDRESS_USAGE_TYPE_KEY NUMBER(38,0) NOT NULL,
		ADDRESS_USAGE_TYPE_SOURCE_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT FK_ADDRESS_USAGE_TYPE_DATA_SOURCE_REL_ADDRESS_USAGE_TYPE FOREIGN KEY (ADDRESS_USAGE_TYPE_KEY) REFERENCES ODSDATA.ADDRESS_USAGE_TYPE (ADDRESS_USAGE_TYPE_KEY),
		CONSTRAINT FK_ADDRESS_USAGE_TYPE_DATA_SOURCE_REL_DATA_SOURCE FOREIGN KEY (DATA_SOURCE_KEY) REFERENCES ODSDATA.DATA_SOURCE (DATA_SOURCE_KEY),
		CONSTRAINT PK_ADDRESS_USAGE_TYPE_DATA_SOURCE_REL PRIMARY KEY (ADDRESS_USAGE_TYPE_DATA_SOURCE_REL_KEY),
		CONSTRAINT UK_ADDRESS_USAGE_TYPE_DATA_SOURCE_REL UNIQUE (ADDRESS_USAGE_TYPE_SOURCE_DESC, DATA_SOURCE_KEY, ADDRESS_USAGE_TYPE_KEY)
	)COMMENT='Relates source AddressUsageType values to standard values in AddressUsageType'
;

INSERT INTO ODSDATA.TMP_ADDRESS_USAGE_TYPE_DATA_SOURCE_REL
(DATA_SOURCE_KEY, ADDRESS_USAGE_TYPE_KEY, ADDRESS_USAGE_TYPE_SOURCE_DESC)
VALUES
(1, 2, 'Contracting Address'),
(1, 5, 'Credentialing Address'),
(1, 4, 'No Value Specified'),
(1, 1, 'Office Address'),
(1, 3, 'PayTo address/Billing'),
(1, 6, 'Report Mailing Address');

--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.ADDRESS_USAGE_TYPE_DATA_SOURCE_REL AS TGT
USING (SELECT DATA_SOURCE_KEY, ADDRESS_USAGE_TYPE_KEY, ADDRESS_USAGE_TYPE_SOURCE_DESC
	FROM ODSDATA.TMP_ADDRESS_USAGE_TYPE_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, ADDRESS_USAGE_TYPE_KEY, ADDRESS_USAGE_TYPE_SOURCE_DESC
	FROM ODSDATA.ADDRESS_USAGE_TYPE_DATA_SOURCE_REL
	) AS SRC
ON TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.ADDRESS_USAGE_TYPE_KEY = SRC.ADDRESS_USAGE_TYPE_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.ADDRESS_USAGE_TYPE_SOURCE_DESC = SRC.ADDRESS_USAGE_TYPE_SOURCE_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(DATA_SOURCE_KEY
	,ADDRESS_USAGE_TYPE_KEY
	,ADDRESS_USAGE_TYPE_SOURCE_DESC
	)
VALUES
	(
	SRC.DATA_SOURCE_KEY
	,SRC.ADDRESS_USAGE_TYPE_KEY
	,SRC.ADDRESS_USAGE_TYPE_SOURCE_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.ADDRESS_USAGE_TYPE_DATA_SOURCE_REL TGT
USING
(SELECT DATA_SOURCE_KEY, ADDRESS_USAGE_TYPE_KEY, ADDRESS_USAGE_TYPE_SOURCE_DESC
	FROM ODSDATA.ADDRESS_USAGE_TYPE_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, ADDRESS_USAGE_TYPE_KEY, ADDRESS_USAGE_TYPE_SOURCE_DESC
	FROM ODSDATA.TMP_ADDRESS_USAGE_TYPE_DATA_SOURCE_REL
	) SRC
WHERE TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.ADDRESS_USAGE_TYPE_KEY = SRC.ADDRESS_USAGE_TYPE_KEY;