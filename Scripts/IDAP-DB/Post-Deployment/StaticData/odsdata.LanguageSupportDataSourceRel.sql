CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_LANGUAGE_SUPPORT_DATA_SOURCE_REL (
		LANGUAGE_SUPPORT_DATA_SOURCE_REL_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		DATA_SOURCE_KEY NUMBER(38,0) NOT NULL,
		LANGUAGE_SUPPORT_KEY NUMBER(38,0) NOT NULL,
		LANGUAGE_SUPPORT_TYPE_SOURCE_NAME VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT FK_LANGUAGE_SUPPORT_DATA_SOURCE_REL_DATA_SOURCE FOREIGN KEY (DATA_SOURCE_KEY) REFERENCES ODSDATA.DATA_SOURCE (DATA_SOURCE_KEY),
		CONSTRAINT FK_LANGUAGE_SUPPORT_DATA_SOURCE_REL_LANGUAGE_SUPPORT FOREIGN KEY (LANGUAGE_SUPPORT_KEY) REFERENCES ODSDATA.LANGUAGE_SUPPORT (LANGUAGE_SUPPORT_KEY),
		CONSTRAINT PK_LANGUAGE_SUPPORT_DATA_SOURCE_REL PRIMARY KEY (LANGUAGE_SUPPORT_DATA_SOURCE_REL_KEY),
		CONSTRAINT UK_LANGUAGE_SUPPORT_DATA_SOURCE_REL UNIQUE (DATA_SOURCE_KEY, LANGUAGE_SUPPORT_KEY, LANGUAGE_SUPPORT_TYPE_SOURCE_NAME)
	)COMMENT='Relates source LanguageSupportType values to standard values in LanguageSupport'
;

INSERT INTO ODSDATA.TMP_LANGUAGE_SUPPORT_DATA_SOURCE_REL
(DATA_SOURCE_KEY, LANGUAGE_SUPPORT_KEY, LANGUAGE_SUPPORT_TYPE_SOURCE_NAME)
VALUES
(1, 1, 'Health Care Provider'),
(1, 2, 'Interpreter'),
(1, 3, 'Office Personnel'),
(1, 4, 'Other Resources'),
(1, 5, 'Staff');

--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.LANGUAGE_SUPPORT_DATA_SOURCE_REL AS TGT
USING (SELECT DATA_SOURCE_KEY, LANGUAGE_SUPPORT_KEY, LANGUAGE_SUPPORT_TYPE_SOURCE_NAME
	FROM ODSDATA.TMP_LANGUAGE_SUPPORT_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, LANGUAGE_SUPPORT_KEY, LANGUAGE_SUPPORT_TYPE_SOURCE_NAME
	FROM ODSDATA.LANGUAGE_SUPPORT_DATA_SOURCE_REL
	) AS SRC
ON TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.LANGUAGE_SUPPORT_KEY = SRC.LANGUAGE_SUPPORT_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.LANGUAGE_SUPPORT_TYPE_SOURCE_NAME = SRC.LANGUAGE_SUPPORT_TYPE_SOURCE_NAME
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(DATA_SOURCE_KEY
	,LANGUAGE_SUPPORT_KEY
	,LANGUAGE_SUPPORT_TYPE_SOURCE_NAME
	)
VALUES
	(
	SRC.DATA_SOURCE_KEY
	,SRC.LANGUAGE_SUPPORT_KEY
	,SRC.LANGUAGE_SUPPORT_TYPE_SOURCE_NAME
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.LANGUAGE_SUPPORT_DATA_SOURCE_REL TGT
USING
(SELECT DATA_SOURCE_KEY, LANGUAGE_SUPPORT_KEY, LANGUAGE_SUPPORT_TYPE_SOURCE_NAME
	FROM ODSDATA.LANGUAGE_SUPPORT_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, LANGUAGE_SUPPORT_KEY, LANGUAGE_SUPPORT_TYPE_SOURCE_NAME
	FROM ODSDATA.TMP_LANGUAGE_SUPPORT_DATA_SOURCE_REL
	) SRC
WHERE TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.LANGUAGE_SUPPORT_KEY = SRC.LANGUAGE_SUPPORT_KEY;