CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_INSTITUTION_FUNCTION (
		INSTITUTION_FUNCTION_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		INSTITUTION_FUNCTION_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_INSTITUTION_FUNCTION PRIMARY KEY (INSTITUTION_FUNCTION_KEY),
		CONSTRAINT UK_INSTITUTION_FUNCTION UNIQUE (INSTITUTION_FUNCTION_DESC)
	)COMMENT='The type of function or roles that an Institution can be involved in. Affiliations, Boards, Education, Insurance, Licenses, etc.'
;

INSERT INTO ODSDATA.TMP_INSTITUTION_FUNCTION (INSTITUTION_FUNCTION_KEY,INSTITUTION_FUNCTION_DESC) VALUES
	 (1,'Affiliations'),
	 (2,'Boards'),
	 (3,'Education'),
	 (4,'Insurance'),
	 (5,'Licenses'),
	 (6,'Plans'),
	 (7,'Meeting'),
	 (8,'Entity');

MERGE INTO ODSDATA.INSTITUTION_FUNCTION AS TGT
USING (SELECT INSTITUTION_FUNCTION_KEY, INSTITUTION_FUNCTION_DESC
	FROM ODSDATA.TMP_INSTITUTION_FUNCTION
	MINUS 
	SELECT INSTITUTION_FUNCTION_KEY, INSTITUTION_FUNCTION_DESC
	FROM ODSDATA.INSTITUTION_FUNCTION
	) AS SRC
ON TGT.INSTITUTION_FUNCTION_KEY = SRC.INSTITUTION_FUNCTION_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.INSTITUTION_FUNCTION_DESC = SRC.INSTITUTION_FUNCTION_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(INSTITUTION_FUNCTION_KEY
	,INSTITUTION_FUNCTION_DESC
	)
VALUES
	(
	SRC.INSTITUTION_FUNCTION_KEY
	,SRC.INSTITUTION_FUNCTION_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.INSTITUTION_FUNCTION TGT
USING
(SELECT INSTITUTION_FUNCTION_KEY, INSTITUTION_FUNCTION_DESC
	FROM ODSDATA.INSTITUTION_FUNCTION
	MINUS 
	SELECT INSTITUTION_FUNCTION_KEY, INSTITUTION_FUNCTION_DESC
	FROM ODSDATA.TMP_INSTITUTION_FUNCTION
	) SRC
WHERE TGT.INSTITUTION_FUNCTION_KEY = SRC.INSTITUTION_FUNCTION_KEY;