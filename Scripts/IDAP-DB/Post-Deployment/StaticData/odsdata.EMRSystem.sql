MERGE INTO ODSDATA.EMR_SYSTEM AS TGT
USING (SELECT EMR_SYSTEM_KEY, EMR_SYSTEM_NAME
	FROM ODSDATA.TMP_EMR_SYSTEM
	MINUS 
	SELECT EMR_SYSTEM_KEY, EMR_SYSTEM_NAME
	FROM ODSDATA.EMR_SYSTEM
	) AS SRC
ON TGT.EMR_SYSTEM_KEY = SRC.EMR_SYSTEM_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.EMR_SYSTEM_NAME = SRC.EMR_SYSTEM_NAME
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(EMR_SYSTEM_KEY
	,EMR_SYSTEM_NAME
	)
VALUES
	(
	SRC.EMR_SYSTEM_KEY
	,SRC.EMR_SYSTEM_NAME
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.EMR_SYSTEM TGT
USING
(SELECT EMR_SYSTEM_KEY, EMR_SYSTEM_NAME
	FROM ODSDATA.EMR_SYSTEM
	MINUS 
	SELECT EMR_SYSTEM_KEY, EMR_SYSTEM_NAME
	FROM ODSDATA.TMP_EMR_SYSTEM
	) SRC
WHERE TGT.EMR_SYSTEM_KEY = SRC.EMR_SYSTEM_KEY;