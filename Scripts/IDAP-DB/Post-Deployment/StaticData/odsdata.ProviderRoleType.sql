CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_PROVIDER_ROLE_TYPE (
		PROVIDER_ROLE_TYPE_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		PROVIDER_ROLE_TYPE_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_PROVIDER_ROLE_TYPE PRIMARY KEY (PROVIDER_ROLE_TYPE_KEY),
		CONSTRAINT UK_PROVIDER_ROLE_TYPE UNIQUE (PROVIDER_ROLE_TYPE_DESC)
	)COMMENT='The type of assingment the provider has . Currently used at a Provider level, Provider at an address, and also at a contract level.'
;

