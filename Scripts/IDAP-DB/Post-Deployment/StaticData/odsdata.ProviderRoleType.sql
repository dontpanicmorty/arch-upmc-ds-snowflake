--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.PROVIDER_ROLE_TYPE AS TGT
USING (SELECT PROVIDER_ROLE_TYPE_KEY, PROVIDER_ROLE_TYPE_DESC
	FROM ODSDATA.TMP_PROVIDER_ROLE_TYPE
	MINUS 
	SELECT PROVIDER_ROLE_TYPE_KEY, PROVIDER_ROLE_TYPE_DESC
	FROM ODSDATA.PROVIDER_ROLE_TYPE
	) AS SRC
ON TGT.PROVIDER_ROLE_TYPE_KEY = SRC.PROVIDER_ROLE_TYPE_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.PROVIDER_ROLE_TYPE_DESC = SRC.PROVIDER_ROLE_TYPE_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(PROVIDER_ROLE_TYPE_KEY
	,PROVIDER_ROLE_TYPE_DESC
	)
VALUES
	(
	SRC.PROVIDER_ROLE_TYPE_KEY
	,SRC.PROVIDER_ROLE_TYPE_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.PROVIDER_ROLE_TYPE TGT
USING
(SELECT PROVIDER_ROLE_TYPE_KEY, PROVIDER_ROLE_TYPE_DESC
	FROM ODSDATA.PROVIDER_ROLE_TYPE
	MINUS 
	SELECT PROVIDER_ROLE_TYPE_KEY, PROVIDER_ROLE_TYPE_DESC
	FROM ODSDATA.TMP_PROVIDER_ROLE_TYPE
	) SRC
WHERE TGT.PROVIDER_ROLE_TYPE_KEY = SRC.PROVIDER_ROLE_TYPE_KEY;