DELETE FROM ODSDATA.TIME TGT
USING
(SELECT TIME_KEY, HOUR_NBR, MINUTE_NBR
	FROM ODSDATA.TIME
	MINUS 
	SELECT TIME_KEY, HOUR_NBR, MINUTE_NBR
	FROM ODSDATA.TMP_TIME
	) SRC
WHERE TGT.TIME_KEY = SRC.TIME_KEY;