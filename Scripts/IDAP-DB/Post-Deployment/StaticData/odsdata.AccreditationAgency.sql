--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.ACCREDITATION_AGENCY AS TGT
USING (SELECT ACCREDITATION_AGENCY_KEY, ACCREDITATION_AGENCY_NAME
	FROM ODSDATA.TMP_ACCREDITATION_AGENCY
	MINUS 
	SELECT ACCREDITATION_AGENCY_KEY, ACCREDITATION_AGENCY_NAME
	FROM ODSDATA.ACCREDITATION_AGENCY
	) AS SRC
ON TGT.ACCREDITATION_AGENCY_KEY = SRC.ACCREDITATION_AGENCY_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.ACCREDITATION_AGENCY_NAME = SRC.ACCREDITATION_AGENCY_NAME
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(ACCREDITATION_AGENCY_KEY
	,ACCREDITATION_AGENCY_NAME
	)
VALUES
	(
	SRC.ACCREDITATION_AGENCY_KEY
	,SRC.ACCREDITATION_AGENCY_NAME
	);
	
