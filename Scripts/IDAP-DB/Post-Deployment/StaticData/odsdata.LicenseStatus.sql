--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.LICENSE_STATUS AS TGT
USING (SELECT LICENSE_STATUS_KEY, LICENSE_STATUS_DESC
	FROM ODSDATA.TMP_LICENSE_STATUS
	MINUS 
	SELECT LICENSE_STATUS_KEY, LICENSE_STATUS_DESC
	FROM ODSDATA.LICENSE_STATUS
	) AS SRC
ON TGT.LICENSE_STATUS_KEY = SRC.LICENSE_STATUS_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.LICENSE_STATUS_DESC = SRC.LICENSE_STATUS_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(LICENSE_STATUS_KEY
	,LICENSE_STATUS_DESC
	)
VALUES
	(
	SRC.LICENSE_STATUS_KEY
	,SRC.LICENSE_STATUS_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.LICENSE_STATUS TGT
USING
(SELECT LICENSE_STATUS_KEY, LICENSE_STATUS_DESC
	FROM ODSDATA.LICENSE_STATUS
	MINUS 
	SELECT LICENSE_STATUS_KEY, LICENSE_STATUS_DESC
	FROM ODSDATA.TMP_LICENSE_STATUS
	) SRC
WHERE TGT.LICENSE_STATUS_KEY = SRC.LICENSE_STATUS_KEY;	 