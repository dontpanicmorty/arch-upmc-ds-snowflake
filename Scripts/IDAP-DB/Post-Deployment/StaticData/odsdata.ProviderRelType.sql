CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_PROVIDER_REL_TYPE (
		PROVIDER_REL_TYPE_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		PROVIDER_REL_TYPE_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_PROVIDER_REL_TYPE PRIMARY KEY (PROVIDER_REL_TYPE_KEY),
		CONSTRAINT UK_PROVIDER_REL_TYPE UNIQUE (PROVIDER_REL_TYPE_DESC)
	)COMMENT='The type of relationship a Provider has with another. These can be GROUP AFFILIATION , etc.'
;

INSERT INTO ODSDATA.TMP_PROVIDER_REL_TYPE (PROVIDER_REL_TYPE_KEY,PROVIDER_REL_TYPE_DESC) VALUES
	 (1,'Group Affiliation');

--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.PROVIDER_REL_TYPE AS TGT
USING (SELECT PROVIDER_REL_TYPE_KEY, PROVIDER_REL_TYPE_DESC
	FROM ODSDATA.TMP_PROVIDER_REL_TYPE
	MINUS 
	SELECT PROVIDER_REL_TYPE_KEY, PROVIDER_REL_TYPE_DESC
	FROM ODSDATA.PROVIDER_REL_TYPE
	) AS SRC
ON TGT.PROVIDER_REL_TYPE_KEY = SRC.PROVIDER_REL_TYPE_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.PROVIDER_REL_TYPE_DESC = SRC.PROVIDER_REL_TYPE_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(PROVIDER_REL_TYPE_KEY
	,PROVIDER_REL_TYPE_DESC
	)
VALUES
	(
	SRC.PROVIDER_REL_TYPE_KEY
	,SRC.PROVIDER_REL_TYPE_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.PROVIDER_REL_TYPE TGT
USING
(SELECT PROVIDER_REL_TYPE_KEY, PROVIDER_REL_TYPE_DESC
	FROM ODSDATA.PROVIDER_REL_TYPE
	MINUS 
	SELECT PROVIDER_REL_TYPE_KEY, PROVIDER_REL_TYPE_DESC
	FROM ODSDATA.TMP_PROVIDER_REL_TYPE
	) SRC
WHERE TGT.PROVIDER_REL_TYPE_KEY = SRC.PROVIDER_REL_TYPE_KEY;