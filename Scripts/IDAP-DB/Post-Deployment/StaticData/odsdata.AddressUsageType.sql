CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_ADDRESS_USAGE_TYPE (
		ADDRESS_USAGE_TYPE_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		ADDRESS_USAGE_TYPE_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_ADDRESS_USAGE_TYPE PRIMARY KEY (ADDRESS_USAGE_TYPE_KEY),
		CONSTRAINT UK_ADDRESS_USAGE_TYPE UNIQUE (ADDRESS_USAGE_TYPE_DESC)
	)COMMENT='An AddressUsageType is a specific purpose of an address. Examples would be Billing, Mailing, Office, etc'
;

