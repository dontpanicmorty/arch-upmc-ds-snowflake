--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.ADDRESS_USAGE_TYPE AS TGT
USING (SELECT ADDRESS_USAGE_TYPE_KEY, ADDRESS_USAGE_TYPE_DESC
	FROM ODSDATA.TMP_ADDRESS_USAGE_TYPE
	MINUS 
	SELECT ADDRESS_USAGE_TYPE_KEY, ADDRESS_USAGE_TYPE_DESC
	FROM ODSDATA.ADDRESS_USAGE_TYPE
	) AS SRC
ON TGT.ADDRESS_USAGE_TYPE_KEY = SRC.ADDRESS_USAGE_TYPE_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.ADDRESS_USAGE_TYPE_DESC = SRC.ADDRESS_USAGE_TYPE_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(ADDRESS_USAGE_TYPE_KEY
	,ADDRESS_USAGE_TYPE_DESC
	)
VALUES
	(
	SRC.ADDRESS_USAGE_TYPE_KEY
	,SRC.ADDRESS_USAGE_TYPE_DESC
	);
	
--Flip the minus and delete from the target
