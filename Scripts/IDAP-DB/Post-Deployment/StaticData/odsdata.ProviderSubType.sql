CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_PROVIDER_SUB_TYPE (
		PROVIDER_SUB_TYPE_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		PROVIDER_SUB_TYPE_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_PROVIDER_SUB_TYPE PRIMARY KEY (PROVIDER_SUB_TYPE_KEY),
		CONSTRAINT UK_PROVIDER_SUB_TYPE UNIQUE (PROVIDER_SUB_TYPE_DESC)
	)COMMENT='Current values : Facility, Practitioner, Group, Pharmacy'
;

INSERT INTO ODSDATA.TMP_PROVIDER_SUB_TYPE (PROVIDER_SUB_TYPE_KEY,PROVIDER_SUB_TYPE_DESC) VALUES
	 (1,'Practitioner'),
	 (2,'Facility'),
	 (3,'Medical Group'),
	 (4,'Pharmacy');

--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.PROVIDER_SUB_TYPE AS TGT
USING (SELECT PROVIDER_SUB_TYPE_KEY, PROVIDER_SUB_TYPE_DESC
	FROM ODSDATA.TMP_PROVIDER_SUB_TYPE
	MINUS 
	SELECT PROVIDER_SUB_TYPE_KEY, PROVIDER_SUB_TYPE_DESC
	FROM ODSDATA.PROVIDER_SUB_TYPE
	) AS SRC
ON TGT.PROVIDER_SUB_TYPE_KEY = SRC.PROVIDER_SUB_TYPE_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.PROVIDER_SUB_TYPE_DESC = SRC.PROVIDER_SUB_TYPE_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(PROVIDER_SUB_TYPE_KEY
	,PROVIDER_SUB_TYPE_DESC
	)
VALUES
	(
	SRC.PROVIDER_SUB_TYPE_KEY
	,SRC.PROVIDER_SUB_TYPE_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.PROVIDER_SUB_TYPE TGT
USING
(SELECT PROVIDER_SUB_TYPE_KEY, PROVIDER_SUB_TYPE_DESC
	FROM ODSDATA.PROVIDER_SUB_TYPE
	MINUS 
	SELECT PROVIDER_SUB_TYPE_KEY, PROVIDER_SUB_TYPE_DESC
	FROM ODSDATA.TMP_PROVIDER_SUB_TYPE
	) SRC
WHERE TGT.PROVIDER_SUB_TYPE_KEY = SRC.PROVIDER_SUB_TYPE_KEY;