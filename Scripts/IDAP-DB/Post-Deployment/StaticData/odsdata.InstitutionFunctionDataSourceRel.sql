CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_INSTITUTION_FUNCTION_DATA_SOURCE_REL (
		INSTITUTION_FUNCTION_DATA_SOURCE_REL_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		DATA_SOURCE_KEY NUMBER(38,0) NOT NULL,
		INSTITUTION_FUNCTION_KEY NUMBER(38,0) NOT NULL,
		INSTITUTION_FUNCTION_SOURCE_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT FK_INSTITUTION_FUNCTION_DATA_SOURCE_REL_DATA_SOURCE FOREIGN KEY (DATA_SOURCE_KEY) REFERENCES ODSDATA.DATA_SOURCE (DATA_SOURCE_KEY),
		CONSTRAINT FK_INSTITUTION_FUNCTION_DATA_SOURCE_REL_INSTITUTION_FUNCTION FOREIGN KEY (INSTITUTION_FUNCTION_KEY) REFERENCES ODSDATA.INSTITUTION_FUNCTION (INSTITUTION_FUNCTION_KEY),
		CONSTRAINT PK_INSTITUTION_FUNCTION_DATA_SOURCE_REL PRIMARY KEY (INSTITUTION_FUNCTION_DATA_SOURCE_REL_KEY),
		CONSTRAINT UK_INSTITUTION_FUNCTION_DATA_SOURCE_REL UNIQUE (DATA_SOURCE_KEY, INSTITUTION_FUNCTION_KEY, INSTITUTION_FUNCTION_SOURCE_DESC)
	)COMMENT='Relates source InstitutionFunction values to standard values in InstitutionFunction'
;

