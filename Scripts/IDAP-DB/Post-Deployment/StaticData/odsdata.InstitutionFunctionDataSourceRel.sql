--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.INSTITUTION_FUNCTION_DATA_SOURCE_REL AS TGT
USING (SELECT DATA_SOURCE_KEY, INSTITUTION_FUNCTION_KEY, INSTITUTION_FUNCTION_SOURCE_DESC
	FROM ODSDATA.TMP_INSTITUTION_FUNCTION_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, INSTITUTION_FUNCTION_KEY, INSTITUTION_FUNCTION_SOURCE_DESC
	FROM ODSDATA.INSTITUTION_FUNCTION_DATA_SOURCE_REL
	) AS SRC
ON TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.INSTITUTION_FUNCTION_KEY = SRC.INSTITUTION_FUNCTION_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.INSTITUTION_FUNCTION_SOURCE_DESC = SRC.INSTITUTION_FUNCTION_SOURCE_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(DATA_SOURCE_KEY
	,INSTITUTION_FUNCTION_KEY
	,INSTITUTION_FUNCTION_SOURCE_DESC
	)
VALUES
	(
	SRC.DATA_SOURCE_KEY
	,SRC.INSTITUTION_FUNCTION_KEY
	,SRC.INSTITUTION_FUNCTION_SOURCE_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.INSTITUTION_FUNCTION_DATA_SOURCE_REL TGT
USING
(SELECT DATA_SOURCE_KEY, INSTITUTION_FUNCTION_KEY, INSTITUTION_FUNCTION_SOURCE_DESC
	FROM ODSDATA.INSTITUTION_FUNCTION_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, INSTITUTION_FUNCTION_KEY, INSTITUTION_FUNCTION_SOURCE_DESC
	FROM ODSDATA.TMP_INSTITUTION_FUNCTION_DATA_SOURCE_REL
	) SRC
WHERE TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.INSTITUTION_FUNCTION_KEY = SRC.INSTITUTION_FUNCTION_KEY;