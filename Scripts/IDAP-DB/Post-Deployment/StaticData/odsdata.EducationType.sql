MERGE INTO ODSDATA.EDUCATION_TYPE AS TGT
USING (SELECT EDUCATION_TYPE_KEY, EDUCATION_TYPE_DESC
	FROM ODSDATA.TMP_EDUCATION_TYPE
	MINUS 
	SELECT EDUCATION_TYPE_KEY, EDUCATION_TYPE_DESC
	FROM ODSDATA.EDUCATION_TYPE
	) AS SRC
ON TGT.EDUCATION_TYPE_KEY = SRC.EDUCATION_TYPE_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.EDUCATION_TYPE_DESC = SRC.EDUCATION_TYPE_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(EDUCATION_TYPE_KEY
	,EDUCATION_TYPE_DESC
	)
VALUES
	(
	SRC.EDUCATION_TYPE_KEY
	,SRC.EDUCATION_TYPE_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.EDUCATION_TYPE TGT
USING
(SELECT EDUCATION_TYPE_KEY, EDUCATION_TYPE_DESC
	FROM ODSDATA.EDUCATION_TYPE
	MINUS 
	SELECT EDUCATION_TYPE_KEY, EDUCATION_TYPE_DESC
	FROM ODSDATA.TMP_EDUCATION_TYPE
	) SRC
WHERE TGT.EDUCATION_TYPE_KEY = SRC.EDUCATION_TYPE_KEY;