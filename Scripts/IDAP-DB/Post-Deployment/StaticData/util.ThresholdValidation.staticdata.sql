--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO UTIL.THRESHOLD_VALIDATION AS TGT
USING (
        SELECT SCHEMA_NAME,
                TABLE_NAME,                                       
                COLUMN_NAME,
                THRESHOLD_PERCENT
        FROM util.tmp_THRESHOLD_VALIDATION
        MINUS 
        SELECT  SCHEMA_NAME,
                TABLE_NAME,
                COLUMN_NAME,
                THRESHOLD_PERCENT
        FROM UTIL.THRESHOLD_VALIDATION
	    ) AS SRC
ON (TGT.SCHEMA_NAME = SRC.SCHEMA_NAME
AND TGT.TABLE_NAME = SRC.TABLE_NAME
AND TGT.COLUMN_NAME = SRC.COLUMN_NAME)
WHEN MATCHED 
THEN UPDATE
	SET TGT.THRESHOLD_PERCENT = SRC.THRESHOLD_PERCENT
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(
        THRESHOLD_VALIDATION_KEY,
        SCHEMA_NAME,
        TABLE_NAME,                                       
        THRESHOLD_PERCENT,
        COLUMN_NAME,
        INSERT_DATETIME,
        LAST_UPDATED_DATETIME
	)
VALUES
	(
        (SELECT IFNULL(MAX(THRESHOLD_VALIDATION_KEY), 1000) FROM UTIL.THRESHOLD_VALIDATION) + ROW_NUMBER() OVER (ORDER BY 1),
        SRC.SCHEMA_NAME,
        SRC.TABLE_NAME,
        SRC.THRESHOLD_PERCENT,
        SRC.COLUMN_NAME,
        CURRENT_TIMESTAMP(),
        CURRENT_TIMESTAMP()
	);
	
--Flip the minus and delete from the target
DELETE FROM UTIL.THRESHOLD_VALIDATION TGT
USING(   
        SELECT  SCHEMA_NAME,
                TABLE_NAME,     
                COLUMN_NAME,
                THRESHOLD_PERCENT
        FROM UTIL.THRESHOLD_VALIDATION
        MINUS 
        SELECT SCHEMA_NAME,
                TABLE_NAME,     
                COLUMN_NAME,
                THRESHOLD_PERCENT
        FROM util.tmp_THRESHOLD_VALIDATION
	) SRC
WHERE TGT.SCHEMA_NAME=SRC.SCHEMA_NAME 
     AND TGT.TABLE_NAME=SRC.TABLE_NAME
     AND TGT.COLUMN_NAME = SRC.COLUMN_NAME;

