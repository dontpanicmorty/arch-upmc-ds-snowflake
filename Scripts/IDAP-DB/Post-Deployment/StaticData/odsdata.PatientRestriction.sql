--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.PATIENT_RESTRICTION AS TGT
USING (SELECT PATIENT_RESTRICTION_KEY, MIN_AGE_NBR, MAX_AGE_NBR, GENDER_KEY, EXISTING_PATIENTS_ONLY_IND, SPECIAL_RESTRICTION_DESC
	FROM ODSDATA.TMP_PATIENT_RESTRICTION
	MINUS 
	SELECT PATIENT_RESTRICTION_KEY, MIN_AGE_NBR, MAX_AGE_NBR, GENDER_KEY, EXISTING_PATIENTS_ONLY_IND, SPECIAL_RESTRICTION_DESC
	FROM ODSDATA.PATIENT_RESTRICTION
	) AS SRC
ON TGT.PATIENT_RESTRICTION_KEY = SRC.PATIENT_RESTRICTION_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.MIN_AGE_NBR = SRC.MIN_AGE_NBR
	,TGT.MAX_AGE_NBR = SRC.MAX_AGE_NBR
	,TGT.GENDER_KEY = SRC.GENDER_KEY
	,TGT.EXISTING_PATIENTS_ONLY_IND = SRC.EXISTING_PATIENTS_ONLY_IND
	,TGT.SPECIAL_RESTRICTION_DESC = SRC.SPECIAL_RESTRICTION_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(
	PATIENT_RESTRICTION_KEY
	,MIN_AGE_NBR
	,MAX_AGE_NBR
	,GENDER_KEY
	,EXISTING_PATIENTS_ONLY_IND
	,SPECIAL_RESTRICTION_DESC
	)
VALUES
	(
	SRC.PATIENT_RESTRICTION_KEY
	,SRC.MIN_AGE_NBR
	,SRC.MAX_AGE_NBR
	,SRC.GENDER_KEY
	,SRC.EXISTING_PATIENTS_ONLY_IND
	,SRC.SPECIAL_RESTRICTION_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.PATIENT_RESTRICTION TGT
USING
(SELECT PATIENT_RESTRICTION_KEY, MIN_AGE_NBR, MAX_AGE_NBR, GENDER_KEY, EXISTING_PATIENTS_ONLY_IND, SPECIAL_RESTRICTION_DESC
	FROM ODSDATA.PATIENT_RESTRICTION
	MINUS 
	SELECT PATIENT_RESTRICTION_KEY, MIN_AGE_NBR, MAX_AGE_NBR, GENDER_KEY, EXISTING_PATIENTS_ONLY_IND, SPECIAL_RESTRICTION_DESC
	FROM ODSDATA.TMP_PATIENT_RESTRICTION
	) SRC
WHERE TGT.PATIENT_RESTRICTION_KEY = SRC.PATIENT_RESTRICTION_KEY;