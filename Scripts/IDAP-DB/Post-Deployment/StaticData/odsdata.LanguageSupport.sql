CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_LANGUAGE_SUPPORT (
		LANGUAGE_SUPPORT_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		LANGUAGE_SUPPORT_TYPE_NAME VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_LANGUAGE_SUPPORT PRIMARY KEY (LANGUAGE_SUPPORT_KEY),
		CONSTRAINT UK_LANGUAGE_SUPPORT UNIQUE (LANGUAGE_SUPPORT_TYPE_NAME)
	)COMMENT='List of standardized language support types. Exampe: Interpreter, Office Personel';

INSERT INTO ODSDATA.TMP_LANGUAGE_SUPPORT (LANGUAGE_SUPPORT_KEY,LANGUAGE_SUPPORT_TYPE_NAME) VALUES
	 (1,'Health Care Provider'),
	 (2,'Interpreter'),
	 (3,'Office Personnel'),
	 (4,'Other Resources'),
	 (5,'Staff');

--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.LANGUAGE_SUPPORT AS TGT
USING (SELECT LANGUAGE_SUPPORT_KEY, LANGUAGE_SUPPORT_TYPE_NAME
	FROM ODSDATA.TMP_LANGUAGE_SUPPORT
	MINUS 
	SELECT LANGUAGE_SUPPORT_KEY, LANGUAGE_SUPPORT_TYPE_NAME
	FROM ODSDATA.LANGUAGE_SUPPORT
	) AS SRC
ON TGT.LANGUAGE_SUPPORT_KEY = SRC.LANGUAGE_SUPPORT_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.LANGUAGE_SUPPORT_TYPE_NAME = SRC.LANGUAGE_SUPPORT_TYPE_NAME
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(LANGUAGE_SUPPORT_KEY
	,LANGUAGE_SUPPORT_TYPE_NAME
	)
VALUES
	(
	SRC.LANGUAGE_SUPPORT_KEY
	,SRC.LANGUAGE_SUPPORT_TYPE_NAME
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.LANGUAGE_SUPPORT TGT
USING
(SELECT LANGUAGE_SUPPORT_KEY, LANGUAGE_SUPPORT_TYPE_NAME
	FROM ODSDATA.LANGUAGE_SUPPORT
	MINUS 
	SELECT LANGUAGE_SUPPORT_KEY, LANGUAGE_SUPPORT_TYPE_NAME
	FROM ODSDATA.TMP_LANGUAGE_SUPPORT
	) SRC
WHERE TGT.LANGUAGE_SUPPORT_KEY = SRC.LANGUAGE_SUPPORT_KEY;