--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.COUNTRY AS TGT
USING (SELECT COUNTRY_KEY, COUNTRY_NAME, ISO2A_NAME, ISO3A_NAME, ISO3N_NAME, INTERNATIONAL_PHONE_CODE
	FROM ODSDATA.TMP_COUNTRY
	MINUS 
	SELECT COUNTRY_KEY, COUNTRY_NAME, ISO2A_NAME, ISO3A_NAME, ISO3N_NAME, INTERNATIONAL_PHONE_CODE
	FROM ODSDATA.COUNTRY
	) AS SRC
ON TGT.COUNTRY_KEY = SRC.COUNTRY_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.COUNTRY_NAME = SRC.COUNTRY_NAME
	,TGT.ISO2A_NAME = SRC.ISO2A_NAME
	,TGT.ISO3A_NAME = SRC.ISO3A_NAME
	,TGT.ISO3N_NAME = SRC.ISO3N_NAME
	,TGT.INTERNATIONAL_PHONE_CODE = SRC.INTERNATIONAL_PHONE_CODE
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(COUNTRY_KEY
	,COUNTRY_NAME
	,ISO2A_NAME
	,ISO3A_NAME
	,ISO3N_NAME
	,INTERNATIONAL_PHONE_CODE
	)
VALUES
	(
	SRC.COUNTRY_KEY
	,SRC.COUNTRY_NAME
	,SRC.ISO2A_NAME
	,SRC.ISO3A_NAME
	,SRC.ISO3N_NAME
	,SRC.INTERNATIONAL_PHONE_CODE
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.COUNTRY TGT
USING
(SELECT COUNTRY_KEY, COUNTRY_NAME, ISO2A_NAME, ISO3A_NAME, ISO3N_NAME, INTERNATIONAL_PHONE_CODE
	FROM ODSDATA.COUNTRY
	MINUS 
	SELECT COUNTRY_KEY, COUNTRY_NAME, ISO2A_NAME, ISO3A_NAME, ISO3N_NAME, INTERNATIONAL_PHONE_CODE
	FROM ODSDATA.TMP_COUNTRY
	) SRC
WHERE TGT.COUNTRY_KEY = SRC.COUNTRY_KEY;	 
	 