CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_SPECIALTY_CATEGORY_DATA_SOURCE_REL (
		SPECIALTY_CATEGORY_DATA_SOURCE_REL_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		DATA_SOURCE_KEY NUMBER(38,0) NOT NULL,
		SPECIALTY_CATEGORY_KEY NUMBER(38,0) NOT NULL,
		SPECIALTY_CATEGORY_SOURCE_NAME VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT FK_SPECIALTY_CATEGORY_DATA_SOURCE_REL_DATA_SOURCE FOREIGN KEY (DATA_SOURCE_KEY) REFERENCES ODSDATA.DATA_SOURCE (DATA_SOURCE_KEY),
		CONSTRAINT FK_SPECIALTY_CATEGORY_DATA_SOURCE_REL_SPECIALTY_CATEGORY FOREIGN KEY (SPECIALTY_CATEGORY_KEY) REFERENCES ODSDATA.SPECIALTY_CATEGORY (SPECIALTY_CATEGORY_KEY),
		CONSTRAINT PK_SPECIALTY_CATEGORY_DATA_SOURCE_REL PRIMARY KEY (SPECIALTY_CATEGORY_DATA_SOURCE_REL_KEY),
		CONSTRAINT UK_SPECIALTY_CATEGORY_DATA_SOURCE_REL UNIQUE (DATA_SOURCE_KEY, SPECIALTY_CATEGORY_KEY, SPECIALTY_CATEGORY_SOURCE_NAME)
	)COMMENT='Relates source SpecialtyCategory values to standard values in SpecialtyCategory'
;

