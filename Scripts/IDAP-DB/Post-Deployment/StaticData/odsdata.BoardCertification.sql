--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.BOARD_CERTIFICATION AS TGT
USING (SELECT BOARD_CERTIFICATION_KEY, BOARD_CERTIFICATION_NAME
	FROM ODSDATA.TMP_BOARD_CERTIFICATION
	MINUS 
	SELECT BOARD_CERTIFICATION_KEY, BOARD_CERTIFICATION_NAME
	FROM ODSDATA.BOARD_CERTIFICATION
	) AS SRC
ON TGT.BOARD_CERTIFICATION_KEY = SRC.BOARD_CERTIFICATION_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.BOARD_CERTIFICATION_NAME = SRC.BOARD_CERTIFICATION_NAME
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(BOARD_CERTIFICATION_KEY
	,BOARD_CERTIFICATION_NAME
	)
VALUES
	(
	SRC.BOARD_CERTIFICATION_KEY
	,SRC.BOARD_CERTIFICATION_NAME
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.BOARD_CERTIFICATION TGT
USING
(SELECT BOARD_CERTIFICATION_KEY, BOARD_CERTIFICATION_NAME
	FROM ODSDATA.BOARD_CERTIFICATION
	MINUS 
	SELECT BOARD_CERTIFICATION_KEY, BOARD_CERTIFICATION_NAME
	FROM ODSDATA.TMP_BOARD_CERTIFICATION
	) SRC
WHERE TGT.BOARD_CERTIFICATION_KEY = SRC.BOARD_CERTIFICATION_KEY;	 