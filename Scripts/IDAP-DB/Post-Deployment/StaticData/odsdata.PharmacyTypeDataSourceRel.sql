	ODSDATA.TMP_PHARMACY_TYPE_DATA_SOURCE_REL (
		PHARMACY_TYPE_DATA_SOURCE_REL_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		DATA_SOURCE_KEY NUMBER(38,0) NOT NULL,
		PHARMACY_TYPE_KEY NUMBER(38,0) NOT NULL,
		PHARMACY_TYPE_SOURCE_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT FK_PHARMACY_TYPE_DATA_SOURCE_REL_DATA_SOURCE FOREIGN KEY (DATA_SOURCE_KEY) REFERENCES ODSDATA.DATA_SOURCE (DATA_SOURCE_KEY),
		CONSTRAINT FK_PHARMACY_TYPE_DATA_SOURCE_REL_PHARMACY_TYPE FOREIGN KEY (PHARMACY_TYPE_KEY) REFERENCES ODSDATA.PHARMACY_TYPE (PHARMACY_TYPE_KEY),
		CONSTRAINT PK_PHARMACY_TYPE_DATA_SOURCE_REL PRIMARY KEY (PHARMACY_TYPE_DATA_SOURCE_REL_KEY),
		CONSTRAINT UK_PHARMACY_TYPE_DATA_SOURCE_REL UNIQUE (DATA_SOURCE_KEY, PHARMACY_TYPE_KEY, PHARMACY_TYPE_SOURCE_DESC)
	)COMMENT='Relates source PharmacyType values to standard values in PharmacyType'
