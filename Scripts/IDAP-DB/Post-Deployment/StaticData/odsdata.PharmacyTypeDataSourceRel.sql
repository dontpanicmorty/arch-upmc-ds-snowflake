--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.PHARMACY_TYPE_DATA_SOURCE_REL AS TGT
USING (SELECT DATA_SOURCE_KEY, PHARMACY_TYPE_KEY, PHARMACY_TYPE_SOURCE_DESC
	FROM ODSDATA.TMP_PHARMACY_TYPE_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, PHARMACY_TYPE_KEY, PHARMACY_TYPE_SOURCE_DESC
	FROM ODSDATA.PHARMACY_TYPE_DATA_SOURCE_REL
	) AS SRC
ON TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.PHARMACY_TYPE_KEY = SRC.PHARMACY_TYPE_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.PHARMACY_TYPE_SOURCE_DESC = SRC.PHARMACY_TYPE_SOURCE_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(DATA_SOURCE_KEY
	,PHARMACY_TYPE_KEY
	,PHARMACY_TYPE_SOURCE_DESC
	)
VALUES
	(
	SRC.DATA_SOURCE_KEY
	,SRC.PHARMACY_TYPE_KEY
	,SRC.PHARMACY_TYPE_SOURCE_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.PHARMACY_TYPE_DATA_SOURCE_REL TGT
USING
(SELECT DATA_SOURCE_KEY, PHARMACY_TYPE_KEY, PHARMACY_TYPE_SOURCE_DESC
	FROM ODSDATA.PHARMACY_TYPE_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, PHARMACY_TYPE_KEY, PHARMACY_TYPE_SOURCE_DESC
	FROM ODSDATA.TMP_PHARMACY_TYPE_DATA_SOURCE_REL
	) SRC
WHERE TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.PHARMACY_TYPE_KEY = SRC.PHARMACY_TYPE_KEY;