	ODSDATA.TMP_PROVIDER_AFFILIATION_TYPE_DATA_SOURCE_REL (
		PROVIDER_AFFILIATION_TYPE_DATA_SOURCE_REL_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
