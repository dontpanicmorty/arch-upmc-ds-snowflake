CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_OWNING_MEDICAL_GROUP_OFFICE_STATUS (
		OWNING_MEDICAL_GROUP_OFFICE_STATUS_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		OWNING_MEDICAL_GROUP_OFFICE_STATUS_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_OWNING_MEDICAL_GROUP_OFFICE_STATUS PRIMARY KEY (OWNING_MEDICAL_GROUP_OFFICE_STATUS_KEY),
		CONSTRAINT UK_OWNING_MEDICAL_GROUP_OFFICE_STATUS UNIQUE (OWNING_MEDICAL_GROUP_OFFICE_STATUS_DESC)
	)COMMENT='List of standard ownning medical group statuses';

INSERT INTO ODSDATA.TMP_OWNING_MEDICAL_GROUP_OFFICE_STATUS (OWNING_MEDICAL_GROUP_OFFICE_STATUS_KEY,OWNING_MEDICAL_GROUP_OFFICE_STATUS_DESC) VALUES
	 (1,'Active'),
	 (2,'Inactive');

--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.OWNING_MEDICAL_GROUP_OFFICE_STATUS AS TGT
USING (SELECT OWNING_MEDICAL_GROUP_OFFICE_STATUS_KEY, OWNING_MEDICAL_GROUP_OFFICE_STATUS_DESC
	FROM ODSDATA.TMP_OWNING_MEDICAL_GROUP_OFFICE_STATUS
	MINUS 
	SELECT OWNING_MEDICAL_GROUP_OFFICE_STATUS_KEY, OWNING_MEDICAL_GROUP_OFFICE_STATUS_DESC
	FROM ODSDATA.OWNING_MEDICAL_GROUP_OFFICE_STATUS
	) AS SRC
ON TGT.OWNING_MEDICAL_GROUP_OFFICE_STATUS_KEY = SRC.OWNING_MEDICAL_GROUP_OFFICE_STATUS_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.OWNING_MEDICAL_GROUP_OFFICE_STATUS_DESC = SRC.OWNING_MEDICAL_GROUP_OFFICE_STATUS_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(OWNING_MEDICAL_GROUP_OFFICE_STATUS_KEY
	,OWNING_MEDICAL_GROUP_OFFICE_STATUS_DESC
	)
VALUES
	(
	SRC.OWNING_MEDICAL_GROUP_OFFICE_STATUS_KEY
	,SRC.OWNING_MEDICAL_GROUP_OFFICE_STATUS_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.OWNING_MEDICAL_GROUP_OFFICE_STATUS TGT
USING
(SELECT OWNING_MEDICAL_GROUP_OFFICE_STATUS_KEY, OWNING_MEDICAL_GROUP_OFFICE_STATUS_DESC
	FROM ODSDATA.OWNING_MEDICAL_GROUP_OFFICE_STATUS
	MINUS 
	SELECT OWNING_MEDICAL_GROUP_OFFICE_STATUS_KEY, OWNING_MEDICAL_GROUP_OFFICE_STATUS_DESC
	FROM ODSDATA.TMP_OWNING_MEDICAL_GROUP_OFFICE_STATUS
	) SRC
WHERE TGT.OWNING_MEDICAL_GROUP_OFFICE_STATUS_KEY = SRC.OWNING_MEDICAL_GROUP_OFFICE_STATUS_KEY;	 