--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.SPECIALTY_CATEGORY AS TGT
USING (SELECT SPECIALTY_CATEGORY_KEY, SPECIALTY_CATEGORY_NAME
	FROM ODSDATA.TMP_SPECIALTY_CATEGORY
	MINUS 
	SELECT SPECIALTY_CATEGORY_KEY, SPECIALTY_CATEGORY_NAME
	FROM ODSDATA.SPECIALTY_CATEGORY
	) AS SRC
ON TGT.SPECIALTY_CATEGORY_KEY = SRC.SPECIALTY_CATEGORY_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.SPECIALTY_CATEGORY_NAME = SRC.SPECIALTY_CATEGORY_NAME
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(SPECIALTY_CATEGORY_KEY
	,SPECIALTY_CATEGORY_NAME
	)
VALUES
	(
	SRC.SPECIALTY_CATEGORY_KEY
	,SRC.SPECIALTY_CATEGORY_NAME
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.SPECIALTY_CATEGORY TGT
USING
(SELECT SPECIALTY_CATEGORY_KEY, SPECIALTY_CATEGORY_NAME
	FROM ODSDATA.SPECIALTY_CATEGORY
	MINUS 
	SELECT SPECIALTY_CATEGORY_KEY, SPECIALTY_CATEGORY_NAME
	FROM ODSDATA.TMP_SPECIALTY_CATEGORY
	) SRC
WHERE TGT.SPECIALTY_CATEGORY_KEY = SRC.SPECIALTY_CATEGORY_KEY;