CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_GENDER (
		GENDER_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		GENDER_NAME VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		GENDER_CODE CHAR(1),
		CONSTRAINT PK_GENDER PRIMARY KEY (GENDER_KEY),
		CONSTRAINT UK_GENDER UNIQUE (GENDER_NAME)
	)COMMENT='A list of gender codes and corresponding decriptions'
;

INSERT INTO ODSDATA.TMP_GENDER (GENDER_KEY,GENDER_NAME, GENDER_CODE) VALUES
	 (1,'Male','M'),
	 (2,'Female','F'),
	 (3,'Unknown','U');

MERGE INTO ODSDATA.GENDER AS TGT
USING (SELECT GENDER_KEY, GENDER_NAME, GENDER_CODE
	FROM ODSDATA.TMP_GENDER
	MINUS 
	SELECT GENDER_KEY, GENDER_NAME, GENDER_CODE
	FROM ODSDATA.GENDER
	) AS SRC
ON TGT.GENDER_KEY = SRC.GENDER_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.GENDER_NAME = SRC.GENDER_NAME
	,TGT.GENDER_CODE = SRC.GENDER_CODE
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(GENDER_KEY
	,GENDER_NAME
	,GENDER_CODE
	)
VALUES
	(
	SRC.GENDER_KEY
	,SRC.GENDER_NAME
	,SRC.GENDER_CODE
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.GENDER TGT
USING
(SELECT GENDER_KEY, GENDER_NAME, GENDER_CODE
	FROM ODSDATA.GENDER
	MINUS 
	SELECT GENDER_KEY, GENDER_NAME, GENDER_CODE
	FROM ODSDATA.TMP_GENDER
	) SRC
WHERE TGT.GENDER_KEY = SRC.GENDER_KEY;	 