CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_TERMINATION_TYPE_DATA_SOURCE_REL (
		TERMINATION_TYPE_DATA_SOURCE_REL_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		DATA_SOURCE_KEY NUMBER(38,0) NOT NULL,
		TERMINATION_TYPE_KEY NUMBER(38,0) NOT NULL,
		TERMINATION_TYPE_SOURCE_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT FK_TERMINATION_TYPE_DATA_SOURCE_REL_DATA_SOURCE FOREIGN KEY (DATA_SOURCE_KEY) REFERENCES ODSDATA.DATA_SOURCE (DATA_SOURCE_KEY),
		CONSTRAINT FK_TERMINATION_TYPE_DATA_SOURCE_REL_TERMINATION_TYPE FOREIGN KEY (TERMINATION_TYPE_KEY) REFERENCES ODSDATA.TERMINATION_TYPE (TERMINATION_TYPE_KEY),
		CONSTRAINT PK_TERMINATION_TYPE_DATA_SOURCE_REL PRIMARY KEY (TERMINATION_TYPE_DATA_SOURCE_REL_KEY),
		CONSTRAINT UK_TERMINATION_TYPE_DATA_SOURCE_REL UNIQUE (DATA_SOURCE_KEY, TERMINATION_TYPE_KEY, TERMINATION_TYPE_SOURCE_DESC)
	)COMMENT='Relates source TerminationType values to standard values in TerminationType'
;

INSERT INTO ODSDATA.TMP_TERMINATION_TYPE_DATA_SOURCE_REL
(DATA_SOURCE_KEY, TERMINATION_TYPE_KEY, TERMINATION_TYPE_SOURCE_DESC)
VALUES
(1, 1, 'Contract Termination');

--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.TERMINATION_TYPE_DATA_SOURCE_REL AS TGT
USING (SELECT DATA_SOURCE_KEY, TERMINATION_TYPE_KEY, TERMINATION_TYPE_SOURCE_DESC
	FROM ODSDATA.TMP_TERMINATION_TYPE_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, TERMINATION_TYPE_KEY, TERMINATION_TYPE_SOURCE_DESC
	FROM ODSDATA.TERMINATION_TYPE_DATA_SOURCE_REL
	) AS SRC
ON TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.TERMINATION_TYPE_KEY = SRC.TERMINATION_TYPE_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.TERMINATION_TYPE_SOURCE_DESC = SRC.TERMINATION_TYPE_SOURCE_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(DATA_SOURCE_KEY
	,TERMINATION_TYPE_KEY
	,TERMINATION_TYPE_SOURCE_DESC
	)
VALUES
	(
	SRC.DATA_SOURCE_KEY
	,SRC.TERMINATION_TYPE_KEY
	,SRC.TERMINATION_TYPE_SOURCE_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.TERMINATION_TYPE_DATA_SOURCE_REL TGT
USING
(SELECT DATA_SOURCE_KEY, TERMINATION_TYPE_KEY, TERMINATION_TYPE_SOURCE_DESC
	FROM ODSDATA.TERMINATION_TYPE_DATA_SOURCE_REL
	MINUS 
	SELECT DATA_SOURCE_KEY, TERMINATION_TYPE_KEY, TERMINATION_TYPE_SOURCE_DESC
	FROM ODSDATA.TMP_TERMINATION_TYPE_DATA_SOURCE_REL
	) SRC
WHERE TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
AND TGT.TERMINATION_TYPE_KEY = SRC.TERMINATION_TYPE_KEY;