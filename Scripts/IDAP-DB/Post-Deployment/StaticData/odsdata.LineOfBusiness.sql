CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_LINE_OF_BUSINESS (
		LINE_OF_BUSINESS_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		LINE_OF_BUSINESS_NAME VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_LINE_OF_BUSINESS PRIMARY KEY (LINE_OF_BUSINESS_KEY),
		CONSTRAINT UK_LINE_OF_BUSINESS UNIQUE (LINE_OF_BUSINESS_NAME)
	)COMMENT='Top level line of business'
;

INSERT INTO ODSDATA.TMP_LINE_OF_BUSINESS (LINE_OF_BUSINESS_KEY,LINE_OF_BUSINESS_NAME) VALUES
	 (1,'CHIP'),
	 (2,'Commercial'),
	 (3,'Exchange'),
	 (4,'Medicaid'),
	 (5,'Medicare'),
	 (6,'SNP'),
	 (7,'CHC');

--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.LINE_OF_BUSINESS AS TGT
USING (SELECT LINE_OF_BUSINESS_KEY, LINE_OF_BUSINESS_NAME
	FROM ODSDATA.TMP_LINE_OF_BUSINESS
	MINUS 
	SELECT LINE_OF_BUSINESS_KEY, LINE_OF_BUSINESS_NAME
	FROM ODSDATA.LINE_OF_BUSINESS
	) AS SRC
ON TGT.LINE_OF_BUSINESS_KEY = SRC.LINE_OF_BUSINESS_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.LINE_OF_BUSINESS_NAME = SRC.LINE_OF_BUSINESS_NAME
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(LINE_OF_BUSINESS_KEY
	,LINE_OF_BUSINESS_NAME
	)
VALUES
	(
	SRC.LINE_OF_BUSINESS_KEY
	,SRC.LINE_OF_BUSINESS_NAME
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.LINE_OF_BUSINESS TGT
USING
(SELECT LINE_OF_BUSINESS_KEY, LINE_OF_BUSINESS_NAME
	FROM ODSDATA.LINE_OF_BUSINESS
	MINUS 
	SELECT LINE_OF_BUSINESS_KEY, LINE_OF_BUSINESS_NAME
	FROM ODSDATA.TMP_LINE_OF_BUSINESS
	) SRC
WHERE TGT.LINE_OF_BUSINESS_KEY = SRC.LINE_OF_BUSINESS_KEY;