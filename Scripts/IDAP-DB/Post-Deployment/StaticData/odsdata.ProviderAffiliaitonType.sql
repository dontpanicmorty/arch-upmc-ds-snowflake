CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_PROVIDER_AFFILIATION_TYPE (
		PROVIDER_AFFILIATION_TYPE_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		PROVIDER_AFFILIATION_TYPE_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_PROVIDER_AFFILIATION_TYPE PRIMARY KEY (PROVIDER_AFFILIATION_TYPE_KEY),
		CONSTRAINT UK_PROVIDER_AFFILIATION_TYPE UNIQUE (PROVIDER_AFFILIATION_TYPE_DESC)
	)COMMENT='The type of relationship between a Provider and a Institution.'
;

