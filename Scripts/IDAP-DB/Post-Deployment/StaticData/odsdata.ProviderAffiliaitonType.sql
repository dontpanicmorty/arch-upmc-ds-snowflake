--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.PROVIDER_AFFILIATION_TYPE AS TGT
USING (SELECT PROVIDER_AFFILIATION_TYPE_KEY, PROVIDER_AFFILIATION_TYPE_DESC
	FROM ODSDATA.TMP_PROVIDER_AFFILIATION_TYPE
	MINUS 
	SELECT PROVIDER_AFFILIATION_TYPE_KEY, PROVIDER_AFFILIATION_TYPE_DESC
	FROM ODSDATA.PROVIDER_AFFILIATION_TYPE
	) AS SRC
ON TGT.PROVIDER_AFFILIATION_TYPE_KEY = SRC.PROVIDER_AFFILIATION_TYPE_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.PROVIDER_AFFILIATION_TYPE_DESC = SRC.PROVIDER_AFFILIATION_TYPE_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(PROVIDER_AFFILIATION_TYPE_KEY
	,PROVIDER_AFFILIATION_TYPE_DESC
	)
VALUES
	(
	SRC.PROVIDER_AFFILIATION_TYPE_KEY
	,SRC.PROVIDER_AFFILIATION_TYPE_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.PROVIDER_AFFILIATION_TYPE TGT
USING
(SELECT PROVIDER_AFFILIATION_TYPE_KEY, PROVIDER_AFFILIATION_TYPE_DESC
	FROM ODSDATA.PROVIDER_AFFILIATION_TYPE
	MINUS 
	SELECT PROVIDER_AFFILIATION_TYPE_KEY, PROVIDER_AFFILIATION_TYPE_DESC
	FROM ODSDATA.TMP_PROVIDER_AFFILIATION_TYPE
	) SRC
WHERE TGT.PROVIDER_AFFILIATION_TYPE_KEY = SRC.PROVIDER_AFFILIATION_TYPE_KEY;	 