CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_DATA_SOURCE (
		DATA_SOURCE_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		DATA_SOURCE_NAME VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		ADDRESS_SPECIFIC_CONTRACT_IND CHAR(1) NOT NULL,
		INCLUDE_SOURCE_IN_IDAP CHAR(1) NOT NULL,
		CONSTRAINT PK_DATA_SOURCE PRIMARY KEY (DATA_SOURCE_KEY),
		CONSTRAINT UK_DATA_SOURCE UNIQUE (DATA_SOURCE_NAME)
	)COMMENT='The souce where the record originated from.. Examples: Cactus, dwOAO, NVA,  CCBH, Dentamax, etc'
;
INSERT INTO ODSDATA.TMP_DATA_SOURCE (DATA_SOURCE_KEY,DATA_SOURCE_NAME,ADDRESS_SPECIFIC_CONTRACT_IND,INCLUDE_SOURCE_IN_IDAP) VALUES
	 (1,'Cactus','N','Y'),
	 (2,'NVA','Y','Y'),
	 (3,'MMO','N','N'),
	 (4,'Dentemax','Y','N'),
	 (5,'CCBH','Y','N'),
	 (6,'ESI','N','N'),
	 (7,'Envolve','N','N'),
	 (8,'Avesis','Y','Y'),
	 (9,'Cigna','Y','N');

MERGE INTO ODSDATA.DATA_SOURCE AS TGT
USING (SELECT DATA_SOURCE_KEY, DATA_SOURCE_NAME, ADDRESS_SPECIFIC_CONTRACT_IND, INCLUDE_SOURCE_IN_IDAP
	FROM ODSDATA.TMP_DATA_SOURCE
	MINUS 
	SELECT DATA_SOURCE_KEY, DATA_SOURCE_NAME, ADDRESS_SPECIFIC_CONTRACT_IND, INCLUDE_SOURCE_IN_IDAP
	FROM ODSDATA.DATA_SOURCE
	) AS SRC
ON TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.DATA_SOURCE_NAME = SRC.DATA_SOURCE_NAME
	,TGT.ADDRESS_SPECIFIC_CONTRACT_IND = SRC.ADDRESS_SPECIFIC_CONTRACT_IND
	,TGT.INCLUDE_SOURCE_IN_IDAP = SRC.INCLUDE_SOURCE_IN_IDAP
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(DATA_SOURCE_KEY
	,DATA_SOURCE_NAME
	,ADDRESS_SPECIFIC_CONTRACT_IND
	,INCLUDE_SOURCE_IN_IDAP
	)
VALUES
	(
	SRC.DATA_SOURCE_KEY
	,SRC.DATA_SOURCE_NAME
	,SRC.ADDRESS_SPECIFIC_CONTRACT_IND
	,SRC.INCLUDE_SOURCE_IN_IDAP
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.DATA_SOURCE TGT
USING
(SELECT DATA_SOURCE_KEY, DATA_SOURCE_NAME, ADDRESS_SPECIFIC_CONTRACT_IND, INCLUDE_SOURCE_IN_IDAP
	FROM ODSDATA.DATA_SOURCE
	MINUS 
	SELECT DATA_SOURCE_KEY, DATA_SOURCE_NAME, ADDRESS_SPECIFIC_CONTRACT_IND, INCLUDE_SOURCE_IN_IDAP
	FROM ODSDATA.TMP_DATA_SOURCE
	) SRC
WHERE TGT.DATA_SOURCE_KEY = SRC.DATA_SOURCE_KEY;