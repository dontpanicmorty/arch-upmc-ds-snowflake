CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_SCHEDULE_TYPE (
		SCHEDULE_TYPE_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		SCHEDULE_TYPE_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_SCHEDULE_TYPE PRIMARY KEY (SCHEDULE_TYPE_KEY),
		CONSTRAINT UK_SCHEDULE_TYPE UNIQUE (SCHEDULE_TYPE_DESC)
	)COMMENT='The type of schedule that can be used. Examples: Operating Hours, etc'
;

INSERT INTO ODSDATA.TMP_SCHEDULE_TYPE (SCHEDULE_TYPE_KEY,SCHEDULE_TYPE_DESC) VALUES
	 (1,'Office Hours');

--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.SCHEDULE_TYPE AS TGT
USING (SELECT SCHEDULE_TYPE_KEY, SCHEDULE_TYPE_DESC
	FROM ODSDATA.TMP_SCHEDULE_TYPE
	MINUS 
	SELECT SCHEDULE_TYPE_KEY, SCHEDULE_TYPE_DESC
	FROM ODSDATA.SCHEDULE_TYPE
	) AS SRC
ON TGT.SCHEDULE_TYPE_KEY = SRC.SCHEDULE_TYPE_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.SCHEDULE_TYPE_DESC = SRC.SCHEDULE_TYPE_DESC
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(SCHEDULE_TYPE_KEY
	,SCHEDULE_TYPE_DESC
	)
VALUES
	(
	SRC.SCHEDULE_TYPE_KEY
	,SRC.SCHEDULE_TYPE_DESC
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.SCHEDULE_TYPE TGT
USING
(SELECT SCHEDULE_TYPE_KEY, SCHEDULE_TYPE_DESC
	FROM ODSDATA.SCHEDULE_TYPE
	MINUS 
	SELECT SCHEDULE_TYPE_KEY, SCHEDULE_TYPE_DESC
	FROM ODSDATA.TMP_SCHEDULE_TYPE
	) SRC
WHERE TGT.SCHEDULE_TYPE_KEY = SRC.SCHEDULE_TYPE_KEY;