--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.LANGUAGE AS TGT
USING (SELECT LANGUAGE_KEY, LANGUAGE_NAME
	FROM ODSDATA.TMP_LANGUAGE
	MINUS 
	SELECT LANGUAGE_KEY, LANGUAGE_NAME
	FROM ODSDATA.LANGUAGE
	) AS SRC
ON TGT.LANGUAGE_KEY = SRC.LANGUAGE_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.LANGUAGE_NAME = SRC.LANGUAGE_NAME
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(LANGUAGE_KEY
	,LANGUAGE_NAME
	)
VALUES
	(
	SRC.LANGUAGE_KEY
	,SRC.LANGUAGE_NAME
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.LANGUAGE TGT
USING
(SELECT LANGUAGE_KEY, LANGUAGE_NAME
	FROM ODSDATA.LANGUAGE
	MINUS 
	SELECT LANGUAGE_KEY, LANGUAGE_NAME
	FROM ODSDATA.TMP_LANGUAGE
	) SRC
WHERE TGT.LANGUAGE_KEY = SRC.LANGUAGE_KEY;