CREATE OR REPLACE TEMPORARY TABLE
	ODSDATA.TMP_LICENSE_STATUS_DATA_SOURCE_REL (
		LICENSE_STATUS_DATA_SOURCE_REL_KEY NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOT NULL,
		DATA_SOURCE_KEY NUMBER(38,0) NOT NULL,
		LICENSE_STATUS_KEY NUMBER(38,0) NOT NULL,
		LICENSE_STATUS_SOURCE_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT FK_LICENSE_STATUS_DATA_SOURCE_REL_DATA_SOURCE FOREIGN KEY (DATA_SOURCE_KEY) REFERENCES ODSDATA.DATA_SOURCE (DATA_SOURCE_KEY),
		CONSTRAINT FK_LICENSE_STATUS_DATA_SOURCE_REL_LICENSE_STATUS FOREIGN KEY (LICENSE_STATUS_KEY) REFERENCES ODSDATA.LICENSE_STATUS (LICENSE_STATUS_KEY),
		CONSTRAINT PK_LICENSE_STATUS_DATA_SOURCE_REL PRIMARY KEY (LICENSE_STATUS_DATA_SOURCE_REL_KEY),
		CONSTRAINT UK_LICENSE_STATUS_DATA_SOURCE_REL UNIQUE (DATA_SOURCE_KEY, LICENSE_STATUS_KEY, LICENSE_STATUS_SOURCE_DESC)
	)COMMENT='Relates source LicenseStatus values to standard values in LicenseStatus'
;

