--Use a minus query to find any diffs and update or insert as needed	 
MERGE INTO ODSDATA.PRODUCT_TYPE AS TGT
USING (SELECT PRODUCT_TYPE_KEY, PRODUCT_TYPE_NAME, TPA_HIERARCHY_KEY
	FROM ODSDATA.TMP_PRODUCT_TYPE
	MINUS 
	SELECT PRODUCT_TYPE_KEY, PRODUCT_TYPE_NAME, TPA_HIERARCHY_KEY
	FROM ODSDATA.PRODUCT_TYPE
	) AS SRC
ON TGT.PRODUCT_TYPE_KEY = SRC.PRODUCT_TYPE_KEY
WHEN MATCHED 
THEN UPDATE
	SET TGT.PRODUCT_TYPE_NAME = SRC.PRODUCT_TYPE_NAME
	,TGT.TPA_HIERARCHY_KEY = SRC.TPA_HIERARCHY_KEY
	,TGT.LAST_UPDATED_DATETIME = CURRENT_TIMESTAMP()
WHEN NOT MATCHED 
THEN INSERT
	(PRODUCT_TYPE_KEY
	,PRODUCT_TYPE_NAME
	,TPA_HIERARCHY_KEY
	)
VALUES
	(
	SRC.PRODUCT_TYPE_KEY
	,SRC.PRODUCT_TYPE_NAME
	,SRC.TPA_HIERARCHY_KEY
	);
	
--Flip the minus and delete from the target
DELETE FROM ODSDATA.PRODUCT_TYPE TGT
USING
(SELECT PRODUCT_TYPE_KEY, PRODUCT_TYPE_NAME, TPA_HIERARCHY_KEY
	FROM ODSDATA.PRODUCT_TYPE
	MINUS 
	SELECT PRODUCT_TYPE_KEY, PRODUCT_TYPE_NAME, TPA_HIERARCHY_KEY
	FROM ODSDATA.TMP_PRODUCT_TYPE
	) SRC
WHERE TGT.PRODUCT_TYPE_KEY = SRC.PRODUCT_TYPE_KEY;