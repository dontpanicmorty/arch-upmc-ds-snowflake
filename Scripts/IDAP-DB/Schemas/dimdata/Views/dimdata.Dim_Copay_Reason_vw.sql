CREATE OR REPLACE MATERIALIZED VIEW DIMDATA.DIM_COPAY_REASON_VW
AS
SELECT
DIM_PROCESSING_REASON_KEY AS DIM_COPAY_REASON_KEY
,INSERT_DATETIME
,LAST_UPDATED_DATETIME
,IS_LOGICAL_DELETE_FLAG
,DIM_TPA_HIERARCHY_KEY
,DATA_SOURCE_NAME
,CODE_POSITION AS COPAY_REASON_CODE_POSITION
,PROCESSING_REASON_CODE AS COPAY_REASON_CODE
,PROCESSING_REASON_DESC AS COPAY_REASON_DESC
,HIPAA_277_CODE
,HIPAA_835_CODE
FROM DIMDATA.DIM_PROCESSING_REASON
WHERE (UPPER(PROCESSING_REASON_TYPE_CODE) = 'COPAY'
    OR DIM_COPAY_REASON_KEY IN ('1', '2')
    )
;