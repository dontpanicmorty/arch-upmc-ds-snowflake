CREATE OR REPLACE VIEW DIMDATA.BRIDGE_PROVIDER_AFFILIATION_VW
AS
SELECT 
BRIDGE_PROVIDER_AFFILIATION_KEY
, MD5_VALUE_TEXT
, INSERT_DATETIME
, LAST_UPDATED_DATETIME
, IS_LOGICAL_DELETE_FLAG
, DIM_PROVIDER_KEY
, DIM_PROVIDER_AFFILIATION_KEY
, AFFILIATION_START_DATE
, AFFILIATION_END_DATE
, AFFILIATION_ACTIVE_IND
, AFFILIATION_ADMIT_PRIVILEGES_IND
FROM DIMDATA.BRIDGE_PROVIDER_AFFILIATION;
