CREATE OR REPLACE MATERIALIZED VIEW DIMDATA.DIM_MEMBER_ADDRESS_PHYSICAL_VW
AS
SELECT 
DIM_MEMBER_ADDRESS_KEY AS DIM_MEMBER_ADDRESS_PHYSICAL_KEY
,MD5_VALUE_TEXT
,DIM_MEMBER_KEY
,MEMBER_ADDRESS_TYPE
,MEMBER_ADDRESSLINE1_TEXT AS MEMBER_ADDRESS_LINE1_TEXT
,MEMBER_ADDRESSLINE2_TEXT AS MEMBER_ADDRESS_LINE2_TEXT
,MEMBER_CITY_NAME
,MEMBER_STATE_ABBREVIATION_NAME
,MEMBER_ZIP_CODE_NBR
,Member_FIPS_Code
,Member_FIPS_State_Code
,Member_FIPS_County_Code
,Member_CMS_County_Code
,MEMBER_COUNTY_DESC
,MEMBER_LATITUDE_NBR
,MEMBER_LONGITUDE_NBR
,EFFECTIVE_START_DATE
,EFFECTIVE_END_DATE
,ACTIVE_IND
,VALID_IND
,CONGRESSIONAL_DISTRICT
,VERIFIED_ADDRESSLINE1_TEXT
,VERIFIED_ADDRESSLINE2_TEXT
,VERIFIED_COUNTY_DESCRIPTION
,VERIFIED_PRIMARY_NUMBER
,VERIFIED_STREET_NAME
,VERIFIED_STREET_PREDIRECTION
,VERIFIED_STREET_POSTDIRECTION
,VERIFIED_STREET_SUFFIX
,VERIFIED_SECONDARY_NUMBER
,VERIFIED_EXTRA_SECONDARY_NUMBER
,VERIFIED_CITY_NAME
,VERIFIED_STATE
,VERIFIED_ZIPCODE5_NBR
,VERIFIED_ZIPCODE9_NBR
,VERIFIED_PRECISION
,INSERT_DATETIME
,LAST_UPDATED_DATETIME
FROM DIMDATA.DIM_MEMBER_ADDRESS
WHERE UPPER(MEMBER_ADDRESS_TYPE) = 'PHYSICAL';