CREATE OR REPLACE VIEW DIMDATA.DIM_PROCEDURE_CATEGORY_VW
AS
    SELECT
	DIM_PROCEDURE_CATEGORY_KEY,
	INSERT_DATETIME,
	LAST_UPDATED_DATETIME,
	IS_LOGICAL_DELETE_FLAG,
	DIM_TPA_HIERARCHY_KEY,
	DATA_SOURCE_NAME,
	PROCEDURE_CATEGORY_CODE,
	PROCEDURE_CATEGORY_DESC
    FROM DIMDATA.DIM_PROCEDURE_CATEGORY
;
