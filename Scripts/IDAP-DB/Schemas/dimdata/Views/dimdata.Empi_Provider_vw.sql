CREATE OR REPLACE VIEW DIMDATA.EMPI_PROVIDER_VW
AS
SELECT
DIM_PROVIDER.DIM_PROVIDER_KEY
,SUBSTRING(DIM_PROVIDER.PROVIDER_ID,3,LEN(DIM_PROVIDER.PROVIDER_ID)) AS PROVIDER_ID
,DIM_PROVIDER.PRACTITIONER_FIRST_NAME
,DIM_PROVIDER.PRACTITIONER_MIDDLE_INITIAL
,DIM_PROVIDER.PRACTITIONER_LAST_NAME
,DIM_PROVIDER.PRACTITIONER_NAME_SUFFIX
,DIM_PROVIDER.PRACTITIONER_GENDER_CODE
,DIM_PROVIDER.PRACTITIONER_GENDER_NAME
,DIM_PROVIDER.PRACTITIONER_BIRTH_DATE
,DIM_PROVIDER.PRACTITIONER_SSN_NBR
,DIM_PROVIDER.PRIMARY_SPECIALTY_NAME
,DIM_PROVIDER.PRACTITIONER_DEGREE
,DIM_PROVIDER_IDENTIFIER.IDENTIFIER_NBR AS NPI
--,DEGREE_TABLE.DEGREES
FROM DIMDATA.DIM_PROVIDER
    LEFT OUTER JOIN DIMDATA.DIM_PROVIDER_IDENTIFIER
        ON (DIM_PROVIDER_IDENTIFIER.DIM_PROVIDER_KEY = DIM_PROVIDER.DIM_PROVIDER_KEY
        AND DIM_PROVIDER_IDENTIFIER.IDENTIFIER_NAME = 'National Provider Identifier'
        AND DIM_PROVIDER_IDENTIFIER.IS_LOGICAL_DELETE_FLAG = 'FALSE')
--    LEFT OUTER JOIN (SELECT BRIDGE_PRACTITIONER_EDUCATION_VW.DIM_PROVIDER_KEY, LISTAGG(DISTINCT DIM_PRACTITIONER_EDUCATION_VW.EDUCATION_DEGREE_NAME,',') WITHIN GROUP (ORDER BY DIM_PRACTITIONER_EDUCATION_VW.EDUCATION_DEGREE_NAME) AS DEGREES
--                    FROM DIMDATA.BRIDGE_PRACTITIONER_EDUCATION_VW
--                        JOIN DIMDATA.DIM_PRACTITIONER_EDUCATION_VW
--                            ON (DIM_PRACTITIONER_EDUCATION_VW.DIM_PRACTITIONER_EDUCATION_KEY = BRIDGE_PRACTITIONER_EDUCATION_VW.DIM_PRACTITIONER_EDUCATION_KEY)
--                    WHERE BRIDGE_PRACTITIONER_EDUCATION_VW.IS_LOGICAL_DELETE_FLAG = 'FALSE'
--                    AND DIM_PRACTITIONER_EDUCATION_VW.EDUCATION_DEGREE_NAME NOT IN ('Unknown')
--                    GROUP BY BRIDGE_PRACTITIONER_EDUCATION_VW.DIM_PROVIDER_KEY
--                    ) DEGREE_TABLE
--        ON (DEGREE_TABLE.DIM_PROVIDER_KEY = DIM_PROVIDER.DIM_PROVIDER_KEY)
WHERE DIM_PROVIDER.TPA_CLIENT_ID = '000001'
AND DIM_PROVIDER.TPA_ID = '000001'
AND DIM_PROVIDER.TPA_DIVISION_ID = '0001'
AND DIM_PROVIDER.PROVIDER_TYPE_CODE = 1 -- PRACTITIONER
AND DIM_PROVIDER.IS_LOGICAL_DELETE_FLAG = 'FALSE'
AND DIM_PROVIDER.IS_CURRENTROW_FLAG = 'TRUE'
AND DIM_PROVIDER.SOURCE_SYSTEM = 'SQLSERVER'
AND SUBSTRING(DIM_PROVIDER.PROVIDER_ID,1,2) = '1-'
AND DIM_PROVIDER.DIM_PROVIDER_KEY IN
    (SELECT DIM_PROVIDER_KEY
    FROM DIMDATA.FACT_PROVIDER_CONTRACT
        JOIN DIMDATA.DIM_DATE_DAY TERM_DATE
            ON (TERM_DATE.DIM_DATE_DAY_KEY = FACT_PROVIDER_CONTRACT.CONTRACT_TERMINATION_DATE_KEY
            AND TERM_DATE.FULL_DATE >= CURRENT_DATE())
    WHERE FACT_PROVIDER_CONTRACT.IS_LOGICAL_DELETE_FLAG = 'FALSE'
    )
;
