CREATE OR REPLACE VIEW DIMDATA.DIM_MEMBER_VW
AS
SELECT 
DIM_MEMBER_KEY
,MD5_VALUE_TEXT
,INSERT_DATETIME
,LAST_UPDATED_DATETIME
,TPA_CLIENT_ID
,TPA_ID
,TPA_DIV_ID
,MEMBER_NBR
,MASTER_MEMBER_ID
,DIMDATA.FXN_MASK_FIELD(MEMBER_FULL_NAME::VARCHAR, RESTRICTED_MEMBER_IND) AS MEMBER_FULL_NAME
,DIMDATA.FXN_MASK_FIELD(MEMBER_LAST_NAME::VARCHAR, RESTRICTED_MEMBER_IND) AS MEMBER_LAST_NAME
,DIMDATA.FXN_MASK_FIELD(MEMBER_FIRST_NAME::VARCHAR, RESTRICTED_MEMBER_IND) AS MEMBER_FIRST_NAME
,DIMDATA.FXN_MASK_FIELD(MEMBER_MIDDLE_NAME::VARCHAR, RESTRICTED_MEMBER_IND) AS MEMBER_MIDDLE_NAME
,DIMDATA.FXN_MASK_FIELD(MEMBER_BIRTH_DATE::DATE, RESTRICTED_MEMBER_IND) AS MEMBER_BIRTH_DATE
,DATEDIFF(YEAR, MEMBER_BIRTH_DATE, CURRENT_TIMESTAMP) AS MEMBER_AGE
,CASE 
    WHEN (DATEDIFF(YEAR, MEMBER_BIRTH_DATE, CURRENT_TIMESTAMP) BETWEEN 0 AND 20) THEN '<=20'
    WHEN (DATEDIFF(YEAR, MEMBER_BIRTH_DATE, CURRENT_TIMESTAMP) BETWEEN 21 AND 25) THEN '21-25'
    WHEN (DATEDIFF(YEAR, MEMBER_BIRTH_DATE, CURRENT_TIMESTAMP) BETWEEN 26 AND 35) THEN '26-35'
    WHEN (DATEDIFF(YEAR, MEMBER_BIRTH_DATE, CURRENT_TIMESTAMP) BETWEEN 36 AND 45) THEN '36-45'
    WHEN (DATEDIFF(YEAR, MEMBER_BIRTH_DATE, CURRENT_TIMESTAMP) BETWEEN 46 AND 55) THEN '46-55'
    WHEN (DATEDIFF(YEAR, MEMBER_BIRTH_DATE, CURRENT_TIMESTAMP) BETWEEN 56 AND 64) THEN '56-64'
        WHEN (DATEDIFF(YEAR, MEMBER_BIRTH_DATE, CURRENT_TIMESTAMP) >= 65) THEN '>=65'
END AS AGE_BREAKOUTS
,GENDER_CODE
,DIMDATA.FXN_MASK_FIELD(SUBSCRIBER_RELATIONSHIP_CODE::VARCHAR, RESTRICTED_MEMBER_IND) AS SUBSCRIBER_RELATIONSHIP_CODE
,DIMDATA.FXN_MASK_FIELD(SUBSCRIBER_RELATIONSHIP_DESC::VARCHAR, PRIVACY_RESTRICTION_IND) AS SUBSCRIBER_RELATIONSHIP_DESC
,MEMBER_ADDED_DATE
,MEMBER_DEATH_DATE
,SUBSCRIBER_RELATIONSHIP_TYPE_CODE
,SUB_SOURCE_NAME
,RESTRICTED_MEMBER_IND
,PRIVACY_RESTRICTION_IND
,PRIVACY_ALERT_IND
,FINANCE_REPORTING_REGION
,DIMDATA.FXN_MASK_FIELD(SOCIAL_SECURITY_NBR::VARCHAR, RESTRICTED_MEMBER_IND) AS SOCIAL_SECURITY_NBR
,EMPI_NBR
,CURRENT_CHCSNP_ALIGNMENT_DESC
,DIMDATA.FXN_MASK_FIELD(RESPONSIBLE_PARTY_NAME::VARCHAR, RESTRICTED_MEMBER_IND) AS RESPONSIBLE_PARTY_NAME
,RECIPIENT_ID
,MEDICAID_ID
,EPIC_MR_NBR
,EPIC_ENT_ID
,MEDIPAC_MR_NBR
,PART_D_RISK_FACTOR
,SECONDARY_MEMBER_IDENTIFIER_TEXT
,TERTIARY_MEMBER_IDENTIFIER_TEXT
,SUBSCRIBER_NBR
,PERSON_NBR
,DIMDATA.FXN_MASK_FIELD(MEMBER_SALUTORY_NAME::VARCHAR, RESTRICTED_MEMBER_IND) AS MEMBER_SALUTORY_NAME
,CURRENT_ELIG_STATUS_CODE01
,CURRENT_ELIG_STATUS_CODE02
,CURRENT_ELIG_STATUS_DESC01
,CURRENT_ELIG_STATUS_DESC02
,DIMDATA.FXN_MASK_FIELD(PREGNANCY_DUE_DATE::DATE, RESTRICTED_MEMBER_IND) AS PREGNANCY_DUE_DATE
,HIC_NBR
,CURRENT_CHRONIC_CONDITION_CNT
,RACE_DESC
,MEMBER_DPW_COUNTY_CODE
,MEMBER_DPW_COUNTY_DESC
,SELECTED_PCP_DIM_PROVIDER_KEY
,SELECTED_PCP_DIM_PROVIDER_ADDRESS_KEY
,IMPUTED_PCP_DIM_PROVIDER_KEY
,IMPUTED_PCP_DIM_PROVIDER_ADDRESS_KEY
,CLAIMS_SHARING_DESC
FROM DIMDATA.DIM_MEMBER
;