CREATE OR REPLACE TABLE	DIMDATA.GRP_CLAIM_RIDER
(
    GRP_CLAIM_RIDER_KEY NUMBER(38,0) NOT NULL,
    DIM_RIDER_KEY NUMBER(38,0) NOT NULL,
    INSERT_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    IS_LOGICAL_DELETE_FLAG BOOLEAN DEFAULT FALSE NOT NULL,
    CONSTRAINT PK_GRP_CLAIM_RIDER PRIMARY KEY (GRP_CLAIM_RIDER_KEY),
    CONSTRAINT UK_GRP_CLAIM_RIDER UNIQUE (GRP_CLAIM_RIDER_KEY, DIM_RIDER_KEY),
