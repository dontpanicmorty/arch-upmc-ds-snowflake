CREATE OR REPLACE TABLE DIMDATA.GRP_ICD_DIAGNOSIS
(
    GRP_ICD_DIAGNOSIS_KEY NUMBER(38,0) NOT NULL,
    INSERT_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    IS_LOGICAL_DELETE_FLAG BOOLEAN DEFAULT FALSE NOT NULL,
    DIM_ICD_DIAGNOSIS_KEY NUMBER(38,0) NOT NULL,
    ICD_POSITION_NBR NUMBER(38,0) NOT NULL,
    POA_CODE VARCHAR NOT NULL COMMENT 'Default value of N/A will be used when no POA code is present',
    ICD_QUALIFIER_CODE VARCHAR NOT NULL,
    ICD_QUALIFIER_DESC VARCHAR,
    PRIMARY_DIAGNOSIS_IND VARCHAR NOT NULL COMMENT 'Replaces the somewhat misleading (weighting factor) from ICD_DIAGNOSIS_GROUP@EDWRPT since it only has two possible values of 1 or 0 where it is = 1 for the primary diagnosis.',
	CONSTRAINT PK_GRP_ICD_DIAGNOSIS_KEY PRIMARY KEY (GRP_ICD_DIAGNOSIS_KEY),
	CONSTRAINT UK_GRP_ICD_DIAGNOSIS_KEY UNIQUE (GRP_ICD_DIAGNOSIS_KEY, DIM_ICD_DIAGNOSIS_KEY, ICD_POSITION_NBR, POA_CODE, ICD_QUALIFIER_CODE),
	CONSTRAINT FK_GRPICDDIAGNOSIS_DIM_ICD_DIAGNOSIS_KEY FOREIGN KEY (DIM_ICD_DIAGNOSIS_KEY) REFERENCES DIMDATA.DIM_ICD_DIAGNOSIS (DIM_ICD_DIAGNOSIS_KEY)
)
COMMENT='Grouping table to facilitate the N:1 relationship between ICD Diagnosis codes and a Claim. One grouping is created for every distinct set of codes + POA(s) that exist so the same key can be reused.'
;
