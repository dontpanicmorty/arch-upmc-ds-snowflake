CREATE OR REPLACE TABLE DIMDATA.DIM_DATA_SOURCE
(
    DIM_DATA_SOURCE_KEY NUMBER(38,0) NOT NULL,
    INSERT_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    IS_LOGICAL_DELETE_FLAG BOOLEAN DEFAULT FALSE NOT NULL,
    DATA_SOURCE_NAME VARCHAR NOT NULL COMMENT 'Source system or vendor name of a given data set',
    DATA_SOURCE_DESC VARCHAR,
    CONSTRAINT PK_DIM_DATA_SOURCE PRIMARY KEY (DIM_DATA_SOURCE_KEY),
    CONSTRAINT UK_DIM_DATA_SOURCE UNIQUE (DATA_SOURCE_NAME)
)COMMENT='Set of distinct data sources'
;
