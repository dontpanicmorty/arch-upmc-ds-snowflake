CREATE OR REPLACE TABLE DIMDATA.DIM_CLAIM_PROCEDURE
(
    DIM_CLAIM_PROCEDURE_KEY NUMBER(38,0) NOT NULL,
    INSERT_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    IS_LOGICAL_DELETE_FLAG BOOLEAN DEFAULT FALSE NOT NULL,
    DIM_TPA_HIERARCHY_KEY INTEGER NOT NULL,
    DATA_SOURCE_NAME VARCHAR NOT NULL,
    PROCEDURE_CODE VARCHAR NOT NULL,
    PROCEDURE_CODE_SHORT_DESC VARCHAR,
    PROCEDURE_CODE_LONG_DESC VARCHAR,
    PROCEDURE_CODE_SPANISH_DESC VARCHAR COMMENT 'Spanish descriptions supplied by Medicare and EOB teams and only apply to a subset of the available codes as of 11/3/2020.',
    CONSTRAINT FK_DIMCLAIMPROCEDURE_DIM_TPA_HIERARCHY_KEY FOREIGN KEY (DIM_TPA_HIERARCHY_KEY) REFERENCES DIMDATA.DIM_TPA_HIERARCHY (DIM_TPA_HIERARCHY_KEY),
    CONSTRAINT PK_DIM_CLAIM_PROCEDURE PRIMARY KEY (DIM_CLAIM_PROCEDURE_KEY),
    CONSTRAINT UK_DIM_CLAIM_PROCEDURE UNIQUE (DIM_TPA_HIERARCHY_KEY, DATA_SOURCE_NAME, PROCEDURE_CODE)
) 
COMMENT='One table containing codes and descriptions for all non-ICD procedure codes (i.e. CPT, HCPCS, CDT).'
