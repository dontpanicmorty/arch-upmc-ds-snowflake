CREATE OR REPLACE TABLE	DIMDATA.GRP_ICD_PROCEDURE
(
    GRP_ICD_PROCEDURE_KEY NUMBER(38,0) NOT NULL,
    INSERT_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    IS_LOGICAL_DELETE_FLAG BOOLEAN DEFAULT FALSE NOT NULL,
    DIM_ICD_PROCEDURE_KEY NUMBER(38,0) NOT NULL,
    ICD_POSITION_NBR NUMBER(38,0) NOT NULL,
    ICD_QUALIFIER_CODE VARCHAR NOT NULL,
    ICD_QUALIFIER_DESC VARCHAR,
    ICD_VERSION_NBR VARCHAR,
	CONSTRAINT FK_GRPICDPROCEDURE_DIM_ICD_PROCEDURE_KEY FOREIGN KEY (DIM_ICD_PROCEDURE_KEY) REFERENCES DIMDATA.DIM_ICD_PROCEDURE (DIM_ICD_PROCEDURE_KEY),
	CONSTRAINT PK_GRP_ICD_PROCEDURE_KEY PRIMARY KEY (GRP_ICD_PROCEDURE_KEY),
	CONSTRAINT UK_GRP_ICD_PROCEDURE_KEY UNIQUE (GRP_ICD_PROCEDURE_KEY, DIM_ICD_PROCEDURE_KEY, ICD_POSITION_NBR, ICD_QUALIFIER_CODE)
) COMMENT='Grouping table to facilitate the N:1 relationship between ICD Surgical (Procedure) codes and a Claim. One grouping is created for every distinct set of codes that exist so the same key can be reused.'
