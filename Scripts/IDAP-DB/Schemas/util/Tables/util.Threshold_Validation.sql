 

CREATE OR REPLACE TABLE UTIL.THRESHOLD_VALIDATION
( 
  THRESHOLD_VALIDATION_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
  INSERT_DATETIME TIMESTAMP_TZ(9) NOT NULL,
  LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) NOT NULL,
  SCHEMA_NAME VARCHAR NOT NULL,
  TABLE_NAME VARCHAR NOT NULL,
  COLUMN_NAME VARCHAR NOT NULL,
  THRESHOLD_PERCENT NUMBER(38,0) NOT NULL,
  CONSTRAINT PK_THRESHOLD_VALIDATION_KEY PRIMARY KEY (THRESHOLD_VALIDATION_KEY),
  CONSTRAINT UK_THRESHOLD_VALIDATION_KEY UNIQUE (SCHEMA_NAME, TABLE_NAME, COLUMN_NAME)
) COMMENT = 'Refrence table for column level threshold values for LOGDATA.BUILD_THRESHOLD_RESULT'
;

 