CREATE OR REPLACE TABLE UTIL.ML_STAGE_ENTITY
(
  ML_STAGE_ENTITY_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
  SCHEMA_NAME VARCHAR NOT NULL,
  TABLE_NAME VARCHAR NOT NULL,
  ENTITY_NAME VARCHAR NOT NULL,
  JSON_PATH VARCHAR,
  CONSTRAINT PK_ML_STAGE_ENTITY_KEY PRIMARY KEY (ML_STAGE_ENTITY_KEY),
  CONSTRAINT UK_ML_STAGE_ENTITY_KEY UNIQUE (SCHEMA_NAME, TABLE_NAME, ENTITY_NAME)
) COMMENT = 'Contains info on entities used in merging MarkLogic data into staging.'
;
