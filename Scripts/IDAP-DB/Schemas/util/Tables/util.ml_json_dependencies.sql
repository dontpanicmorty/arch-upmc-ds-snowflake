CREATE OR REPLACE TABLE UTIL.ML_JSON_DEPENDENCIES
(
    ML_JSON_DEPENDENCIES_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
    VIEW_CATALOG VARCHAR NOT NULL,
    VIEW_SCHEMA VARCHAR NOT NULL,
    VIEW_NAME VARCHAR NOT NULL,
    JSON_ATTRIBUTE_NAME VARCHAR,
    JSON_PATH VARCHAR,
    CONSTRAINT PK_ML_JSON_DEPENDENCIES PRIMARY KEY (ML_JSON_DEPENDENCIES_KEY),
    CONSTRAINT UK_ML_JSON_DEPENDENCIES UNIQUE (VIEW_CATALOG, VIEW_SCHEMA, VIEW_NAME, JSON_ATTRIBUTE_NAME)
) COMMENT = 'Contains info on which MarkLogic json attributes are used by Snowflake views'
;
