!set variable_substitution=true;

CREATE OR REPLACE VIEW  REPORTDATA.MEMBER_DEMOGRAPHICS_VW
AS
SELECT  * 
FROM
    (
        WITH PREFERENCES AS
        (
            SELECT 
            MEMBER_PREFERENCES_VW.MEMBER_PREFERENCES_KEY
            ,MEMBER_PREFERENCES_VW.MEMBER_ID
            ,MEMBER_PREFERENCES_VW.EMAIL_ADDRESS 
            ,MEMBER_PREFERENCES_VW.HOME_PHONE_NUMBER
            ,MEMBER_PREFERENCES_VW.MOBILE_PHONE_NUMBER
            FROM &{IDAP_LAKE}.MEMBER.MEMBER_PREFERENCES_VW     
            WHERE MEMBER_ID !='99999999901'-- Excluding Default Member  
         ),
        HOME_ADDRESS AS
        (
            SELECT 
             MEMBER_PREFERENCES_ADDRESSES_VW.MEMBER_PREFERENCES_KEY AS HOME_MEMBER_PREFERENCES_KEY
            ,MEMBER_PREFERENCES_ADDRESSES_VW.ADDRESS_TYPE AS HOME_ADDRESS_TYPE
            ,MEMBER_PREFERENCES_ADDRESSES_VW.ADDRESS_LINE_1 AS  HOME_ADDRESS_LINE_1
            ,MEMBER_PREFERENCES_ADDRESSES_VW.ADDRESS_LINE_2 AS  HOME_ADDRESS_LINE_2
            ,MEMBER_PREFERENCES_ADDRESSES_VW.ADDRESS_CITY AS  HOME_ADDRESS_CITY
            ,MEMBER_PREFERENCES_ADDRESSES_VW.ADDRESS_STATE AS  HOME_ADDRESS_STATE
            ,MEMBER_PREFERENCES_ADDRESSES_VW.ADDRESS_ZIP_CODE AS  HOME_ADDRESS_ZIP_CODE
            ,ROW_NUMBER() OVER (PARTITION BY HOME_MEMBER_PREFERENCES_KEY ORDER BY ADDRESS_DATA_SOURCE_UPDATED_ON DESC) RowNo1 --Gets most current record 
            FROM &{IDAP_LAKE}.MEMBER.MEMBER_PREFERENCES_ADDRESSES_VW 
            WHERE ADDRESS_TYPE='Physical'     
        ),
        MAILING_ADDRESS AS
        (
             SELECT 
             MEMBER_PREFERENCES_ADDRESSES_VW.MEMBER_PREFERENCES_KEY AS MAILING_MEMBER_PREFERENCES_KEY
            ,MEMBER_PREFERENCES_ADDRESSES_VW.ADDRESS_TYPE  AS MAILING_ADDRESS_TYPE
            ,MEMBER_PREFERENCES_ADDRESSES_VW.ADDRESS_LINE_1 AS MAILING_ADDRESS_LINE_1
            ,MEMBER_PREFERENCES_ADDRESSES_VW.ADDRESS_LINE_2 AS MAILING_ADDRESS_LINE_2
            ,MEMBER_PREFERENCES_ADDRESSES_VW.ADDRESS_CITY AS MAILING_ADDRESS_CITY
            ,MEMBER_PREFERENCES_ADDRESSES_VW.ADDRESS_STATE  AS MAILING_ADDRESS_STATE
            ,MEMBER_PREFERENCES_ADDRESSES_VW.ADDRESS_ZIP_CODE AS MAILING_ADDRESS_ZIP_CODE
            ,ROW_NUMBER() OVER (PARTITION BY MAILING_MEMBER_PREFERENCES_KEY ORDER BY ADDRESS_DATA_SOURCE_UPDATED_ON DESC) RowNo2 --Gets most current record 
            FROM &{IDAP_LAKE}.MEMBER.MEMBER_PREFERENCES_ADDRESSES_VW 
            WHERE ADDRESS_TYPE='Mailing'    
        )

        SELECT 
         MEMBER_PREFERENCES_KEY
        ,MEMBER_ID
        ,EMAIL_ADDRESS
        ,HOME_PHONE_NUMBER
        ,MOBILE_PHONE_NUMBER
        ,HOME_ADDRESS_TYPE
        ,HOME_ADDRESS_LINE_1
        ,HOME_ADDRESS_LINE_2
        ,HOME_ADDRESS_CITY
        ,HOME_ADDRESS_STATE
        ,HOME_ADDRESS_ZIP_CODE
        ,MAILING_ADDRESS_TYPE
        ,MAILING_ADDRESS_LINE_1
        ,MAILING_ADDRESS_LINE_2
        ,MAILING_ADDRESS_CITY
        ,MAILING_ADDRESS_STATE
        ,MAILING_ADDRESS_ZIP_CODE      
        
        FROM  PREFERENCES A
            LEFT JOIN HOME_ADDRESS B 
                ON ( A.MEMBER_PREFERENCES_KEY = B.HOME_MEMBER_PREFERENCES_KEY and RowNo1=1 )
                
            LEFT JOIN MAILING_ADDRESS C
                ON ( A.MEMBER_PREFERENCES_KEY = C.MAILING_MEMBER_PREFERENCES_KEY and RowNo2=1  )

)  

;

!set variable_substitution=false;