CREATE OR REPLACE VIEW  REPORTDATA.MEMBER_DENTAL_CLAIMS_VW
AS
SELECT
 DIM_MEMBER_VW.SUBSCRIBER_NBR
,DIM_MEMBER_VW.PERSON_NBR
,DIM_MEMBER_VW.MEMBER_NBR
,DIM_MEMBER_VW.MEMBER_LAST_NAME 			 
,DIM_MEMBER_VW.MEMBER_FIRST_NAME
,DIM_MEMBER_VW.MEMBER_MIDDLE_NAME
,DIM_MEMBER_VW.MEMBER_FULL_NAME
,DIM_MEMBER_VW.MEDICAID_ID
,DIM_MEMBER_VW.RESTRICTED_MEMBER_IND
,DIM_MEMBER_VW.RECIPIENT_ID AS EMPLOYEE_NBR
,DIM_GROUP_VW.GROUP_NBR
,DIM_GROUP_VW.GROUP_NAME
,DIM_GROUP_VW.CORPORATE_ID
,DIM_SUB_GROUP_VW.SUB_GROUP_NBR
,DIM_SUB_GROUP_VW.SUB_GROUP_NAME
,DIM_PLAN_VW.PLAN_CODE
,DIM_PLAN_VW.PLAN_TYPE_CODE
,DIM_PLAN_VW.LOB_CODE
,DIM_PLAN_VW.LOB_DESC
,DIM_PLAN_VW.FUNDING_TYPE_DESC
,DIM_PLAN_VW.COMPANY_CODE
,FACT_CLAIM_LINE_VW.SERVICE_BEGIN_DATE
,FACT_CLAIM_LINE_VW.SERVICE_END_DATE
,FACT_CLAIM_LINE_VW.CLAIM_NBR
,FACT_CLAIM_LINE_VW.CLAIM_LINE_NBR
,FACT_CLAIM_LINE_VW.PROCEDURE_QTY
,FACT_CLAIM_LINE_VW.PAYMENT_DATE
,FACT_CLAIM_LINE_VW.RECEIVED_DATE
,FACT_CLAIM_LINE_VW.ADMISSION_DATE
,FACT_CLAIM_LINE_VW.CHARGE_AMT
,FACT_CLAIM_LINE_VW.PAID_GROSS_AMT
,FACT_CLAIM_LINE_VW.APPROVED_AMT
,FACT_CLAIM_LINE_VW.NOT_COVERED_AMT
,FACT_CLAIM_LINE_VW.COPAY_AMT
,FACT_CLAIM_LINE_VW.DEDUCTIBLE_AMT
,FACT_CLAIM_LINE_VW.COINSURANCE_AMT
,BILLING_PROVIDER.SOURCE_PROVIDER_NBR AS BILLING_PROVIDER_ID
,BILLING_PROVIDER.PRACTITIONER_LAST_NAME AS BILLING_PROVIDER_LAST_NAME
,BILLING_PROVIDER.PRACTITIONER_FIRST_NAME AS BILLING_PROVIDER_FIRST_NAME
,BILLING_PROVIDER.MEDICAL_GROUP_TIN_NBR AS BILLING_PROVIDER_FTIN_NBR
,RENDERING_PROVIDER.SOURCE_PROVIDER_NBR AS SERVICING_PROVIDER_ID
,RENDERING_PROVIDER.PRACTITIONER_LAST_NAME AS SERVICING_PROVIDER_LAST_NAME
,RENDERING_PROVIDER.PRACTITIONER_FIRST_NAME AS SERVICING_PROVIDER_FIRST_NAME
,DIM_CLAIM_PROCEDURE_VW.PROCEDURE_CODE
,GRP_ICD_DIAGNOSIS_FLAT_VW.DIAGNOSIS_01
,FACT_CLAIM_LINE_VW.DIM_TPA_HIERARCHY_KEY
,FACT_CLAIM_LINE_VW.DIM_CLAIM_DETAIL_KEY
,FACT_CLAIM_LINE_VW.DIM_CLAIM_HEADER_KEY

FROM DIMDATA.FACT_CLAIM_LINE_VW
    INNER JOIN DIMDATA.DIM_MEMBER_VW
        ON (DIM_MEMBER_VW.DIM_MEMBER_KEY = FACT_CLAIM_LINE_VW.DIM_MEMBER_KEY)

    INNER JOIN DIMDATA.DIM_GROUP_VW
        ON (DIM_GROUP_VW.DIM_GROUP_KEY = FACT_CLAIM_LINE_VW.DIM_GROUP_KEY)

    INNER JOIN DIMDATA.DIM_SUB_GROUP_VW
        ON (DIM_SUB_GROUP_VW.DIM_SUB_GROUP_KEY = FACT_CLAIM_LINE_VW.DIM_SUB_GROUP_KEY)

    INNER JOIN DIMDATA.DIM_PLAN_VW
        ON (DIM_PLAN_VW.DIM_PLAN_KEY = FACT_CLAIM_LINE_VW.DIM_PLAN_KEY)  

    LEFT JOIN DIMDATA.DIM_CLAIM_PROCEDURE_VW 
        ON (DIM_CLAIM_PROCEDURE_VW.DIM_CLAIM_PROCEDURE_KEY= FACT_CLAIM_LINE_VW.DIM_CLAIM_PROCEDURE_KEY)

    LEFT JOIN DIMDATA.GRP_ICD_DIAGNOSIS_FLAT_VW
        ON (GRP_ICD_DIAGNOSIS_FLAT_VW.GRP_ICD_DIAGNOSIS_KEY=FACT_CLAIM_LINE_VW.GRP_ICD_DIAGNOSIS_KEY )

    LEFT JOIN DIMDATA.DIM_PROVIDER_VW BILLING_PROVIDER
        ON (BILLING_PROVIDER.DIM_PROVIDER_KEY = FACT_CLAIM_LINE_VW.DIM_BILLING_PROVIDER_KEY) --Billing Provider  

    LEFT JOIN DIMDATA.DIM_PROVIDER_VW  RENDERING_PROVIDER
        ON (RENDERING_PROVIDER.DIM_PROVIDER_KEY = FACT_CLAIM_LINE_VW.DIM_RENDERING_PROVIDER_KEY) --Servicing/Rendering Provider  

WHERE DIM_MEMBER_VW.SUB_SOURCE_NAME = 'DENTAL UPMC'

;
