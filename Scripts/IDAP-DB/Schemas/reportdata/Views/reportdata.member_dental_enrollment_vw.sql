CREATE OR REPLACE VIEW  REPORTDATA.MEMBER_DENTAL_ENROLLMENT_VW
AS
SELECT
 DIM_MEMBER_VW.MASTER_MEMBER_ID 
,DIM_MEMBER_VW.SUBSCRIBER_NBR
,DIM_MEMBER_VW.PERSON_NBR
,DIM_MEMBER_VW.MEMBER_NBR
,DIM_MEMBER_VW.MEMBER_LAST_NAME              
,DIM_MEMBER_VW.MEMBER_FIRST_NAME
,DIM_MEMBER_VW.MEMBER_MIDDLE_NAME
,DIM_MEMBER_VW.MEMBER_FULL_NAME
,DIM_MEMBER_VW.MEMBER_BIRTH_DATE
,DIM_MEMBER_VW.MEMBER_AGE
,DIM_MEMBER_VW.SOCIAL_SECURITY_NBR
,DIM_MEMBER_VW.MEDICAID_ID
,DIM_MEMBER_VW.RESTRICTED_MEMBER_IND
,DIM_MEMBER_VW.RECIPIENT_ID AS EMPLOYEE_NBR
,DIM_GROUP_VW.GROUP_NBR
,DIM_GROUP_VW.GROUP_NAME
,DIM_GROUP_VW.CORPORATE_ID
,DIM_SUB_GROUP_VW.SUB_GROUP_NBR
,DIM_SUB_GROUP_VW.SUB_GROUP_NAME
,DIM_PLAN_VW.PLAN_CODE
,DIM_PLAN_VW.PLAN_TYPE_CODE
,DIM_PLAN_VW.LOB_CODE
,DIM_PLAN_VW.LOB_DESC
,DIM_PLAN_VW.FUNDING_TYPE_DESC
,DIM_PLAN_VW.COMPANY_CODE
,DIM_ENROLLMENT_SPAN_VW.SPAN_TYPE_CODE
,FACT_ENROLLMENT_VW.ELIGIBILITY_START_DATE
,FACT_ENROLLMENT_VW.ELIGIBILITY_END_DATE
,FACT_ENROLLMENT_VW.DIM_TPA_HIERARCHY_KEY
,FACT_ENROLLMENT_VW.DIM_RIDER_KEY
,FACT_ENROLLMENT_VW.DIM_RATE_CELL_KEY
,FACT_ENROLLMENT_VW.DIM_GL_DISTRIBUTION_KEY
FROM DIMDATA.FACT_ENROLLMENT_VW
    INNER JOIN DIMDATA.DIM_MEMBER_VW
        ON (DIM_MEMBER_VW.DIM_MEMBER_KEY = FACT_ENROLLMENT_VW.DIM_MEMBER_KEY)

    INNER JOIN DIMDATA.DIM_GROUP_VW
        ON (DIM_GROUP_VW.DIM_GROUP_KEY = FACT_ENROLLMENT_VW.DIM_GROUP_KEY)

    INNER JOIN DIMDATA.DIM_SUB_GROUP_VW
        ON (DIM_SUB_GROUP_VW.DIM_SUB_GROUP_KEY = FACT_ENROLLMENT_VW.DIM_SUB_GROUP_KEY)

    INNER JOIN DIMDATA.DIM_PLAN_VW
        ON (DIM_PLAN_VW.DIM_PLAN_KEY = FACT_ENROLLMENT_VW.DIM_PLAN_KEY)

    INNER JOIN DIMDATA.DIM_ENROLLMENT_SPAN_VW 
        ON (DIM_ENROLLMENT_SPAN_VW.DIM_ENROLLMENT_SPAN_KEY =FACT_ENROLLMENT_VW.DIM_ENROLLMENT_SPAN_KEY)
           
WHERE DIM_MEMBER_VW.SUB_SOURCE_NAME = 'DENTAL UPMC'
;
