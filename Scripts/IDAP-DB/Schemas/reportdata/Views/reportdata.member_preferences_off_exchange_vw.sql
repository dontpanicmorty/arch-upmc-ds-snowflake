!set variable_substitution=true;

CREATE OR REPLACE VIEW REPORTDATA.MEMBER_PREFERENCES_OFF_EXCHANGE_VW 
COMMENT = 'View driving MPC Reporting for Off Exchange'
AS
SELECT
MEMBER_PREFERENCES_VW.MEMBER_ID,
MEMBER_PREFERENCES_VW.SUBSCRIPTION_TYPE,
MEMBER_PREFERENCES_VW.INSERT_DATETIME,
MEMBER_PREFERENCES_VW.MEMBER_PROFILE_FIRST_NAME,
MEMBER_PREFERENCES_VW.MEMBER_PROFILE_MIDDLE_NAME,
MEMBER_PREFERENCES_VW.MEMBER_PROFILE_LAST_NAME,
MEMBER_PREFERENCES_VW.MEMBER_PROFILE_HAS_H6,
MEMBER_PREFERENCES_VW.EMAIL_ADDRESS,
MEMBER_PREFERENCES_VW.EMAIL_DATA_SOURCE,
MEMBER_PREFERENCES_VW.HOME_PHONE_NUMBER,
MEMBER_PREFERENCES_VW.HOME_PHONE_TYPE,
MEMBER_PREFERENCES_VW.HOME_PHONE_DATA_SOURCE,
MEMBER_PREFERENCES_VW.MOBILE_PHONE_NUMBER,
MEMBER_PREFERENCES_VW.MOBILE_PHONE_TYPE,
MEMBER_PREFERENCES_VW.MOBILE_PHONE_DATA_SOURCE,
    MAILING_ADDRESS.ADDRESS_TYPE MAILING_ADDRESS_TYPE,
    MAILING_ADDRESS.ADDRESS_LINE_1  MAILING_ADDRESS_LINE_1,
    MAILING_ADDRESS.ADDRESS_LINE_2 MAILING_ADDRESS_LINE_2,
    MAILING_ADDRESS.ADDRESS_LINE_3 MAILING_ADDRESS_LINE_3,
    MAILING_ADDRESS.ADDRESS_CITY AS MAILING_CITY,
    MAILING_ADDRESS.ADDRESS_STATE AS MAILING_STATE,
    MAILING_ADDRESS.ADDRESS_ZIP_CODE AS MAILING_ZIP_CODE,
    PHYSICAL_ADDRESS.ADDRESS_LINE_1,
    PHYSICAL_ADDRESS.ADDRESS_LINE_2,
    PHYSICAL_ADDRESS.ADDRESS_LINE_3,
    PHYSICAL_ADDRESS.ADDRESS_CITY,
    PHYSICAL_ADDRESS.ADDRESS_STATE,
    PHYSICAL_ADDRESS.ADDRESS_ZIP_CODE,
    MAILING_ADDRESS.ADDRESS_DATA_SOURCE_NAME,
MEMBER_PREFERENCES_VW.PERSONAL_PREFERENCES_PRONOUN,
MEMBER_PREFERENCES_VW.PERSONAL_PREFERENCES_PREFERRED_NAME,
MEMBER_PREFERENCES_VW.PERSONAL_PREFERENCES_GENDER_IDENTITY,
MEMBER_PREFERENCES_VW.PERSONAL_PREFERENCES_DATA_SOURCE,
MEMBER_PREFERENCES_VW.COMMUNICATION_PREFERENCES_IS_PAPERLESS,
MEMBER_PREFERENCES_VW.COMMUNICATION_PREFERENCES_SPOKEN_LANGUAGE,
MEMBER_PREFERENCES_VW.COMMUNICATION_PREFERENCES_SPOKEN_LANGUAGE_CODE,
MEMBER_PREFERENCES_VW.COMMUNICATION_PREFERENCES_WRITTEN_LANGUAGE,
MEMBER_PREFERENCES_VW.COMMUNICATION_PREFERENCES_WRITTEN_LANGUAGE_CODE,
MEMBER_PREFERENCES_CAMPAIGNS_VW.CONTACT_METHOD_TYPE,
MEMBER_PREFERENCES_VW.CONSENT_ARRAY:HasConsented HAS_CONSENTED


FROM &{IDAP_LAKE}.MEMBER.MEMBER_PREFERENCES_VW 
    INNER JOIN &{IDAP_LAKE}.MEMBER.MEMBER_PREFERENCES_ADDRESSES_VW MAILING_ADDRESS
        ON (MEMBER_PREFERENCES_VW.MEMBER_PREFERENCES_KEY = MAILING_ADDRESS.MEMBER_PREFERENCES_KEY AND MAILING_ADDRESS.ADDRESS_TYPE = 'Mailing')
    INNER JOIN &{IDAP_LAKE}.MEMBER.MEMBER_PREFERENCES_ADDRESSES_VW PHYSICAL_ADDRESS
        ON (MEMBER_PREFERENCES_VW.MEMBER_PREFERENCES_KEY = PHYSICAL_ADDRESS.MEMBER_PREFERENCES_KEY AND PHYSICAL_ADDRESS.ADDRESS_TYPE = 'Physical')
    LEFT JOIN &{IDAP_LAKE}.MEMBER.MEMBER_PREFERENCES_CAMPAIGNS_VW
        ON (MEMBER_PREFERENCES_VW.MEMBER_PREFERENCES_KEY = MEMBER_PREFERENCES_CAMPAIGNS_VW.MEMBER_PREFERENCES_KEY)

-- Join Member Key
    INNER JOIN DIMDATA.DIM_MEMBER ON DIM_MEMBER.MEMBER_NBR = MEMBER_PREFERENCES_VW.MEMBER_ID

-- Join FACT_ENROLLMENT
    INNER JOIN DIMDATA.FACT_ENROLLMENT  on FACT_ENROLLMENT.DIM_MEMBER_KEY = DIM_MEMBER.DIM_MEMBER_KEY AND
--Time specification
    FACT_ENROLLMENT.ELIGIBILITY_START_DATE <= CURRENT_DATE() AND FACT_ENROLLMENT.ELIGIBILITY_END_DATE >= CURRENT_DATE() AND 
    FACT_ENROLLMENT.ELIGIBILITY_START_DATE <> FACT_ENROLLMENT.ELIGIBILITY_END_DATE
-- Join DIM_PLAN -- INNER JOIN (to filter for on/off exchange)
    INNER JOIN DIMDATA.DIM_PLAN on (DIM_PLAN.DIM_PLAN_KEY = FACT_ENROLLMENT.DIM_PLAN_KEY AND ACA_ON_EXCHANGE_IND = 'N' )  
WHERE MEMBER_PREFERENCES_VW.insert_datetime < current_date()
    AND MEMBER_PREFERENCES_VW.insert_datetime >= dateadd('day',-1,current_date())
    ;

!set variable_substitution=false;