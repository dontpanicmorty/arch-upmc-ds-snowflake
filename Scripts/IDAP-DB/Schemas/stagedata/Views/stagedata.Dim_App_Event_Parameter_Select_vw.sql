CREATE OR REPLACE VIEW STAGEDATA.DIM_APP_EVENT_PARAMETER_SELECT_VW 
AS
SELECT
APIM_LOGS_KEY
,PRODUCT AS APP_PRODUCT_NAME
,EVENT_NAME AS EVENT_NAME
,EVENT_VALUES AS EVENT_VALUES
,EVENT_VALUES.value:key::string AS EVENT_PARAMETER_NAME
,EVENT_VALUES.value:value::string AS EVENT_PARAMETER_VALUE
FROM  STAGEDATA.APIM_LOGS_MOBILE_VW
	,TABLE(FLATTEN(EVENT_VALUES, outer=>TRUE)) EVENT_VALUES
WHERE EVENT_PARAMETER_NAME IS NOT NULL
;
