CREATE OR REPLACE VIEW STAGEDATA.BRIDGE_CLAIM_DETAIL_AUTHORIZATION_DETAIL_SELECT_VW
AS
SELECT DISTINCT
DIM_CLAIM_AUTHORIZATION_DETAIL.DIM_CLAIM_AUTHORIZATION_DETAIL_KEY
,DIM_CLAIM_DETAIL.DIM_CLAIM_DETAIL_KEY
FROM STAGEDATA.DIM_CLAIM_AUTHORIZATION_DETAIL_SELECT_VW
    JOIN DIMDATA.DIM_CLAIM_AUTHORIZATION_DETAIL
        ON (DIM_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR = DIM_CLAIM_AUTHORIZATION_DETAIL_SELECT_VW.AUTHORIZATION_NBR
        AND DIM_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_LINE_NBR = DIM_CLAIM_AUTHORIZATION_DETAIL_SELECT_VW.AUTHORIZATION_LINE_NBR
        AND DIM_CLAIM_AUTHORIZATION_DETAIL.DATA_SOURCE_NAME = DIM_CLAIM_AUTHORIZATION_DETAIL_SELECT_VW.DATA_SOURCE_NAME
        AND DIM_CLAIM_AUTHORIZATION_DETAIL.TPA_CLIENT_ID = DIM_CLAIM_AUTHORIZATION_DETAIL_SELECT_VW.TPA_CLIENT_ID
        AND DIM_CLAIM_AUTHORIZATION_DETAIL.TPA_ID = DIM_CLAIM_AUTHORIZATION_DETAIL_SELECT_VW.TPA_ID
        AND DIM_CLAIM_AUTHORIZATION_DETAIL.TPA_DIV_ID = DIM_CLAIM_AUTHORIZATION_DETAIL_SELECT_VW.TPA_DIV_ID
        )
    JOIN STAGEDATA.DIM_CLAIM_DETAIL_SELECT_VW
        ON (DIM_CLAIM_DETAIL_SELECT_VW.AUTHORIZATION_NBR = DIM_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR
        AND DIM_CLAIM_DETAIL_SELECT_VW.AUTHORIZATION_LINE_NBR = DIM_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_LINE_NBR
        AND DIM_CLAIM_DETAIL_SELECT_VW.DATA_SOURCE_NAME = DIM_CLAIM_AUTHORIZATION_DETAIL.DATA_SOURCE_NAME
        AND DIM_CLAIM_DETAIL_SELECT_VW.TPA_CLIENT_ID = DIM_CLAIM_AUTHORIZATION_DETAIL.TPA_CLIENT_ID
        AND DIM_CLAIM_DETAIL_SELECT_VW.TPA_ID = DIM_CLAIM_AUTHORIZATION_DETAIL.TPA_ID
        AND DIM_CLAIM_DETAIL_SELECT_VW.TPA_DIV_ID = DIM_CLAIM_AUTHORIZATION_DETAIL.TPA_DIV_ID
        )
    JOIN DIMDATA.DIM_CLAIM_DETAIL
        ON (DIM_CLAIM_DETAIL.CLAIM_NBR = DIM_CLAIM_DETAIL_SELECT_VW.CLAIM_NBR
        AND DIM_CLAIM_DETAIL.CLAIM_LINE_NBR = DIM_CLAIM_DETAIL_SELECT_VW.CLAIM_LINE_NBR
        AND DIM_CLAIM_DETAIL.CLAIM_SEQUENCE_NBR = DIM_CLAIM_DETAIL_SELECT_VW.CLAIM_SEQUENCE_NBR
        AND DIM_CLAIM_DETAIL.PROCEDURE_ADJ_CODE = DIM_CLAIM_DETAIL_SELECT_VW.PROCEDURE_ADJ_CODE
        AND DIM_CLAIM_DETAIL.DATA_SOURCE_NAME = DIM_CLAIM_DETAIL_SELECT_VW.DATA_SOURCE_NAME
        AND DIM_CLAIM_DETAIL.TPA_CLIENT_ID = DIM_CLAIM_DETAIL_SELECT_VW.TPA_CLIENT_ID
        AND DIM_CLAIM_DETAIL.TPA_ID = DIM_CLAIM_DETAIL_SELECT_VW.TPA_ID
        AND DIM_CLAIM_DETAIL.TPA_DIV_ID = DIM_CLAIM_DETAIL_SELECT_VW.TPA_DIV_ID
        )
;