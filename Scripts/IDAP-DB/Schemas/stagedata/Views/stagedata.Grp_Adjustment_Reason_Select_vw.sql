CREATE OR REPLACE VIEW STAGEDATA.GRP_ADJUSTMENT_REASON_SELECT_VW
AS
SELECT
GRP_ADJUSTMENT_REASON.GRP_ADJUSTMENT_REASON_KEY
,IFNULL(DIM_PROCESSING_REASON.DIM_PROCESSING_REASON_KEY, 1) AS DIM_ADJUSTMENT_REASON_KEY
,ADJUSTMENT_REASON.CLAIM_DETAIL_ADJUSTMENT_REASON_CODE_KEY
FROM STAGEDATA.CLAIM_DETAIL_ADJUSTMENT_REASON_CODE ADJUSTMENT_REASON
    JOIN STAGEDATA.CLAIM_DETAIL_ADJUSTMENT_REASON_CODE_GRP
        ON (CLAIM_DETAIL_ADJUSTMENT_REASON_CODE_GRP.CLAIM_DETAIL_ADJUSTMENT_REASON_CODE_KEY = ADJUSTMENT_REASON.CLAIM_DETAIL_ADJUSTMENT_REASON_CODE_KEY)

    JOIN STAGEDATA.GRP_ADJUSTMENT_REASON
        ON (GRP_ADJUSTMENT_REASON.CODE_VALUE = CLAIM_DETAIL_ADJUSTMENT_REASON_CODE_GRP.CODE_VALUE)

    LEFT OUTER JOIN DIMDATA.DIM_TPA_HIERARCHY
            ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = ADJUSTMENT_REASON.TPA_CLIENT_ID
            AND DIM_TPA_HIERARCHY.TPA_ID = ADJUSTMENT_REASON.TPA_ID
            AND DIM_TPA_HIERARCHY.TPA_DIV_ID = ADJUSTMENT_REASON.TPA_DIV_ID)
            
    LEFT OUTER JOIN DIMDATA.DIM_PROCESSING_REASON
        ON (DIM_PROCESSING_REASON.DIM_TPA_HIERARCHY_KEY = IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1)
        AND DIM_PROCESSING_REASON.DATA_SOURCE_NAME = ADJUSTMENT_REASON.DATA_SOURCE_NAME
        AND DIM_PROCESSING_REASON.PROCESSING_REASON_TYPE_CODE = 'Adjustment'
        AND DIM_PROCESSING_REASON.PROCESSING_REASON_CODE = ADJUSTMENT_REASON.CODE_VALUE
        AND DIM_PROCESSING_REASON.CODE_POSITION = ADJUSTMENT_REASON.CODE_POSITION)
;