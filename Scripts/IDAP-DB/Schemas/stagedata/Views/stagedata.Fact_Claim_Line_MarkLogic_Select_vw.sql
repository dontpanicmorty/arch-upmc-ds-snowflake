CREATE OR REPLACE VIEW STAGEDATA.FACT_CLAIM_LINE_MarkLogic_SELECT_VW
AS
SELECT
IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1) AS DIM_TPA_HIERARCHY_KEY
,IFNULL(DIM_DATA_SOURCE.DIM_DATA_SOURCE_KEY, 1) AS DIM_DATA_SOURCE_KEY
,CLAIM_DETAIL_VW.CLAIM_NBR
,CLAIM_DETAIL_VW.CLAIM_LINE_NBR
,IFNULL(DIM_CLAIM_HEADER.DIM_CLAIM_HEADER_KEY, 1) AS DIM_CLAIM_HEADER_KEY
,DIM_CLAIM_DETAIL.DIM_CLAIM_DETAIL_KEY
,IFNULL(DIM_MEMBER.DIM_MEMBER_KEY, 1) AS DIM_MEMBER_KEY
,IFNULL(DIM_MEMBER_DEMOGRAPHIC.DIM_MEMBER_DEMOGRAPHIC_KEY, 1) AS DIM_MEMBER_DEMOGRAPHIC_KEY
,2 AS DIM_DIAGNOSIS_RELATED_GROUP_KEY
,IFNULL(DIM_ENROLLMENT_SPAN.DIM_ENROLLMENT_SPAN_KEY, 1) AS DIM_ENROLLMENT_SPAN_KEY
,IFNULL(DIM_GROUP.DIM_GROUP_KEY, 1) AS DIM_GROUP_KEY
,IFNULL(DIM_SUB_GROUP.DIM_SUB_GROUP_KEY, 1) AS DIM_SUB_GROUP_KEY
,IFNULL(DIM_PLAN.DIM_PLAN_KEY, 1) AS DIM_PLAN_KEY
,IFNULL(DIM_PLACE_OF_SERVICE.DIM_PLACE_OF_SERVICE_KEY, 1) AS DIM_PLACE_OF_SERVICE_KEY
,IFNULL(DIM_CLAIM_PROCEDURE.DIM_CLAIM_PROCEDURE_KEY, 1) AS DIM_CLAIM_PROCEDURE_KEY
,CASE
    WHEN IFNULL(CLAIM_DETAIL_VW.COPAY_AMT_01, 0) = 0 THEN 2
    ELSE IFNULL(DIM_COPAY_REASON_VW.DIM_COPAY_REASON_KEY, 1)
END AS DIM_COPAY_REASON_KEY
,CASE
    WHEN IFNULL(CLAIM_DETAIL_VW.COINSURANCE_AMT, 0) = 0 THEN 2
    ELSE 1
END AS DIM_COINSURANCE_REASON_KEY --NOT APPLICABLE FOR CLAIMS COMING THROUGH ML
,CASE
    WHEN IFNULL(CLAIM_DETAIL_VW.DEDUCTIBLE_AMT, 0 ) = 0 THEN 2
    ELSE IFNULL(DIM_DEDUCTIBLE_REASON_VW.DIM_DEDUCTIBLE_REASON_KEY, 1)
END AS DIM_DEDUCTIBLE_REASON_KEY
,IFNULL(GRP_ADJUSTMENT_REASON.GRP_ADJUSTMENT_REASON_KEY, 1) AS GRP_ADJUSTMENT_REASON_KEY
,IFNULL(GRP_NOT_COVERED_REASON.GRP_NOT_COVERED_REASON_KEY, 1) AS GRP_NOT_COVERED_REASON_KEY
,IFNULL(GRP_SERVICE_REASON.GRP_SERVICE_REASON_KEY, 1) AS GRP_SERVICE_REASON_KEY
,IFNULL(GRP_CLAIM_RIDER.GRP_CLAIM_RIDER_KEY, 1) AS GRP_CLAIM_RIDER_KEY
,IFNULL(GRP_PROCEDURE_MODIFIER.GRP_PROCEDURE_MODIFIER_KEY, 1) AS GRP_PROCEDURE_MODIFIER_KEY
,IFNULL(GRP_PROCEDURE_CATEGORY.GRP_PROCEDURE_CATEGORY_KEY, 1) AS GRP_PROCEDURE_CATEGORY_KEY
,IFNULL(GRP_ICD_DIAGNOSIS.GRP_ICD_DIAGNOSIS_KEY, 1) AS GRP_ICD_DIAGNOSIS_KEY
,IFNULL(GRP_ICD_PROCEDURE.GRP_ICD_PROCEDURE_KEY, 1) AS GRP_ICD_PROCEDURE_KEY
,IFNULL(BILLING_PROVIDER.DIM_PROVIDER_KEY, 1) AS DIM_BILLING_PROVIDER_KEY
,IFNULL(RENDERING_PROVIDER.DIM_PROVIDER_KEY, 1) AS DIM_RENDERING_PROVIDER_KEY
,IFNULL(DIM_DATE_DAY_RECEIVED.DIM_DATE_DAY_KEY, 1) AS DIM_RECEIVED_DATE_KEY
,IFNULL(DIM_DATE_DAY_PAYMENT.DIM_DATE_DAY_KEY, 1) AS DIM_PAYMENT_DATE_KEY
,IFNULL(DIM_DATE_DAY_SERVICE_BEGIN.DIM_DATE_DAY_KEY, 1) AS DIM_SERVICE_BEGIN_DATE_KEY
,IFNULL(DIM_DATE_DAY_SERVICE_END.DIM_DATE_DAY_KEY, 1) AS DIM_SERVICE_END_DATE_KEY
,IFNULL(DIM_DATE_DAY_DISCHARGE_DATE.DIM_DATE_DAY_KEY, 1) AS DIM_DISCHARGE_DATE_KEY
,IFNULL(DIM_DATE_DAY_ADMIT_DATE.DIM_DATE_DAY_KEY, 1) AS DIM_ADMISSION_DATE_KEY
,IFNULL(DIM_MEMBER_ADDRESS_PHYSICAL_VW.DIM_MEMBER_ADDRESS_PHYSICAL_KEY, 1) AS DIM_MEMBER_ADDRESS_PHYSICAL_KEY
,CASE WHEN (CLAIM_DETAIL_VW.REVENUE_CODE IS NULL) THEN 2
    WHEN (CLAIM_DETAIL_VW.REVENUE_CODE IS NOT NULL AND DIM_REVENUE_PROCEDURE.DIM_REVENUE_PROCEDURE_KEY IS NULL) THEN 1
    ELSE DIM_REVENUE_PROCEDURE.DIM_REVENUE_PROCEDURE_KEY END AS DIM_REVENUE_PROCEDURE_KEY
,CLAIM_DETAIL_VW.SERVICE_BEGIN_DATE AS SERVICE_BEGIN_DATE
,CLAIM_DETAIL_VW.SERVICE_END_DATE AS SERVICE_END_DATE
,CLAIM_DETAIL_VW.CLAIM_RECEIVED_DATE AS RECEIVED_DATE
,CLAIM_DETAIL_VW.PAYMENT_DATE AS PAYMENT_DATE
,CLAIM_DETAIL_VW.PROCEDURE_QTY AS PROCEDURE_QTY
,CLAIM_DETAIL_VW.PAID_AMT AS PAID_AMT
,CLAIM_DETAIL_VW.CHARGE_AMT AS CHARGE_AMT
,CLAIM_DETAIL_VW.APPROVED_AMT AS APPROVED_AMT
,CLAIM_DETAIL_VW.NOT_COVERED_AMT AS NOT_COVERED_AMT
,CLAIM_DETAIL_VW.COPAY_AMT_01 AS COPAY_AMT
,CLAIM_DETAIL_VW.DEDUCTIBLE_AMT AS DEDUCTIBLE_AMT
,CLAIM_DETAIL_VW.COINSURANCE_AMT AS COINSURANCE_AMT
,CLAIM_DETAIL_VW.ALLOWED_AMT AS BENEFIT_ALLOW_AMT
,CLAIM_DETAIL_VW.THIRD_PARTY_PAID_AMT AS THIRD_PARTY_PAID_AMT
,CLAIM_HEADER_VW.DISCHARGE_DATE AS DISCHARGE_DATE
,CLAIM_HEADER_VW.DISCHARGE_HOUR AS DISCHARGE_HOUR
,CLAIM_HEADER_VW.ADMIT_DATE AS ADMISSION_DATE
,CLAIM_HEADER_VW.ADMIT_HOUR AS ADMISSION_HOUR
,CLAIM_DETAIL_VW.MEMBER_LIABILITY AS MEMBER_LIABILITY_AMT
,CLAIM_DETAIL_VW.CLAIM_DAY_CNT AS CLAIM_DAY_CNT
,CASE
    WHEN (CLAIM_HEADER_VW.REFERRING_PROVIDER_DETAIL_KEY IS NULL AND CLAIM_HEADER_VW.REFERRING_PROVIDER_ID IS NULL) THEN 2
    WHEN (CLAIM_HEADER_VW.REFERRING_PROVIDER_DETAIL_KEY IS NULL AND CLAIM_HEADER_VW.REFERRING_PROVIDER_ID IS NOT NULL) THEN 1
    ELSE IFNULL(REFERRING_PROVIDER.DIM_PROVIDER_KEY, 1)
END AS DIM_REFERRING_PROVIDER_KEY
,CASE
    WHEN CLAIM_DETAIL_VW.PAID_GROSS_AMT IS NULL THEN ZEROIFNULL(CLAIM_DETAIL_VW.PAID_AMT) + ZEROIFNULL(CLAIM_DETAIL_VW.PAY_FOR_PERFORMANCE_AMT)
    ELSE CLAIM_DETAIL_VW.PAID_GROSS_AMT
END AS PAID_GROSS_AMT
,CLAIM_DETAIL_VW.SERVICE_CNT AS SERVICE_CNT
,CLAIM_DETAIL_VW.DENIED_DAY_CNT AS DENIED_DAY_CNT
,CASE
    WHEN (CLAIM_HEADER_VW.ATTENDING_PHYSICIAN_DETAIL_KEY IS NULL AND CLAIM_HEADER_VW.ATTENDING_PHYSICIAN_ID IS NULL) THEN 2
    WHEN (CLAIM_HEADER_VW.ATTENDING_PHYSICIAN_DETAIL_KEY IS NULL AND CLAIM_HEADER_VW.ATTENDING_PHYSICIAN_ID IS NOT NULL) THEN 1
    ELSE IFNULL(ATTENDING_PHYSICIAN.DIM_PROVIDER_KEY,1)
END AS DIM_ATTENDING_PHYSICIAN_KEY
,CLAIM_DETAIL_VW.INTEREST_DISCOUNT_AMT AS INTEREST_DISCOUNT_AMT
,CLAIM_DETAIL_VW.OIC_ALLOWED_AMT AS THIRD_PARTY_ALLOWED_AMT
,CLAIM_DETAIL_VW.PAY_FOR_PERFORMANCE_AMT AS PAY_FOR_PERFORMANCE_AMT
,CASE 
    WHEN (CLAIM_DETAIL_VW.CLAIM_AMT_01_DESC= 'HRA') THEN CLAIM_DETAIL_VW.CLAIM_AMT_01
    WHEN (CLAIM_DETAIL_VW.CLAIM_AMT_02_DESC = 'HRA') THEN CLAIM_DETAIL_VW.CLAIM_AMT_02
    ELSE 0
END AS HRA_APPLIED_AMT
,CASE
    WHEN (CLAIM_DETAIL_VW.CLAIM_AMT_01_DESC= 'HIA') THEN CLAIM_DETAIL_VW.CLAIM_AMT_01
    WHEN (CLAIM_DETAIL_VW.CLAIM_AMT_02_DESC = 'HIA') THEN CLAIM_DETAIL_VW.CLAIM_AMT_02
    ELSE 0
END AS HIA_APPLIED_AMT
,CLAIM_DETAIL_VW.CLAIM_ENTRY_DATE AS CLAIM_ENTERED_DATE
,CLAIM_DETAIL_VW.WITHHOLD_AMT AS WITHHOLD_AMT
,CLAIM_DETAIL_VW.AP_POSTING_DATE AS ACCOUNTS_PAYABLE_POSTING_DATE
,CASE
    WHEN (CLAIM_HEADER_VW.ASSIGNED_PROVIDER_KEY IS NULL AND CLAIM_HEADER_VW.ASSIGNED_PROVIDER_ID IS NULL) THEN 2
    WHEN (CLAIM_HEADER_VW.ASSIGNED_PROVIDER_KEY IS NULL AND CLAIM_HEADER_VW.ASSIGNED_PROVIDER_ID IS NOT NULL) THEN 1
    ELSE IFNULL(ASSIGNED_PROVIDER.DIM_PROVIDER_KEY,1) 
END AS DIM_ASSIGNED_PROVIDER_KEY
,CLAIM_DETAIL_VW.ADD_DATE AS SOURCE_SYSTEM_ADD_DATE  

FROM STAGEDATA.CLAIM_DETAIL_VW
    JOIN STAGEDATA.CLAIM_HEADER_VW
        ON (CLAIM_HEADER_VW.UNIVERSAL_CLAIM_ID = CLAIM_DETAIL_VW.UNIVERSAL_CLAIM_ID)

    LEFT OUTER JOIN DIMDATA.DIM_TPA_HIERARCHY
        ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = CLAIM_DETAIL_VW.TPA_CLIENT_ID
        AND DIM_TPA_HIERARCHY.TPA_ID = CLAIM_DETAIL_VW.TPA_ID
        AND DIM_TPA_HIERARCHY.TPA_DIV_ID = CLAIM_DETAIL_VW.TPA_DIV_ID)

    LEFT OUTER JOIN DIMDATA.DIM_DATA_SOURCE
        ON (DIM_DATA_SOURCE.DATA_SOURCE_NAME = CLAIM_DETAIL_VW.DATA_SOURCE_NAME)

    LEFT OUTER JOIN DIMDATA.DIM_CLAIM_HEADER
        ON (DIM_CLAIM_HEADER.TPA_CLIENT_ID = CLAIM_HEADER_VW.TPA_CLIENT_ID
        AND DIM_CLAIM_HEADER.TPA_ID = CLAIM_HEADER_VW.TPA_ID
        AND DIM_CLAIM_HEADER.TPA_DIV_ID = CLAIM_HEADER_VW.TPA_DIV_ID
        AND DIM_CLAIM_HEADER.DATA_SOURCE_NAME = CLAIM_HEADER_VW.DATA_SOURCE_NAME
        AND DIM_CLAIM_HEADER.CLAIM_NBR = CLAIM_HEADER_VW.CLAIM_NBR)

    LEFT OUTER JOIN DIMDATA.DIM_CLAIM_DETAIL
        ON (DIM_CLAIM_DETAIL.TPA_CLIENT_ID = CLAIM_DETAIL_VW.TPA_CLIENT_ID
        AND DIM_CLAIM_DETAIL.TPA_ID = CLAIM_DETAIL_VW.TPA_ID
        AND DIM_CLAIM_DETAIL.TPA_DIV_ID = CLAIM_DETAIL_VW.TPA_DIV_ID
        AND DIM_CLAIM_DETAIL.DATA_SOURCE_NAME = CLAIM_DETAIL_VW.DATA_SOURCE_NAME    
        AND DIM_CLAIM_DETAIL.CLAIM_NBR = CLAIM_DETAIL_VW.CLAIM_NBR
        AND DIM_CLAIM_DETAIL.CLAIM_LINE_NBR = CLAIM_DETAIL_VW.CLAIM_LINE_NBR
        AND DIM_CLAIM_DETAIL.CLAIM_SEQUENCE_NBR = IFNULL(CLAIM_DETAIL_VW.CLAIM_SEQUENCE_NBR, 'n/a')
        AND DIM_CLAIM_DETAIL.PROCEDURE_ADJ_CODE = IFNULL(CLAIM_DETAIL_VW.PROCEDURE_ADJ,'n/a'))

    LEFT OUTER JOIN DIMDATA.DIM_MEMBER
        ON (DIM_MEMBER.TPA_CLIENT_ID = CLAIM_DETAIL_VW.TPA_CLIENT_ID
        AND DIM_MEMBER.TPA_ID = CLAIM_DETAIL_VW.TPA_ID
        AND DIM_MEMBER.TPA_DIV_ID = CLAIM_DETAIL_VW.TPA_DIV_ID
        AND DIM_MEMBER.MEMBER_NBR = CLAIM_DETAIL_VW.MEMBER_NBR)

    LEFT OUTER JOIN DIMDATA.DIM_MEMBER_DEMOGRAPHIC
        ON (DIM_MEMBER_DEMOGRAPHIC.MEMBER_GENDER_CODE = CLAIM_HEADER_VW.MEMBER_GENDER_CODE
        AND DIM_MEMBER_DEMOGRAPHIC.MEMBER_AGE = CLAIM_DETAIL_VW.MEMBER_AGE_NBR)

    LEFT OUTER JOIN (SELECT DIM_ENROLLMENT_SPAN_KEY, TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, MEMBER_NBR, SUB_SOURCE_NAME, ELIGIBILITY_START_DATE, ELIGIBILITY_END_DATE
                    ,RANK() OVER (PARTITION BY TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, MEMBER_NBR, SUB_SOURCE_NAME, SPAN_TYPE_CODE, ELIGIBILITY_START_DATE 
                       ORDER BY ELIGIBILITY_START_DATE DESC, SPAN_TYPE_CODE ASC) AS RANK_NBR
                    FROM DIMDATA.DIM_ENROLLMENT_SPAN
                    WHERE IS_LOGICAL_DELETE_FLAG = FALSE
                    AND DIM_ENROLLMENT_SPAN.ELIGIBILITY_START_DATE <> DIM_ENROLLMENT_SPAN.ELIGIBILITY_END_DATE
                    AND DIM_ENROLLMENT_SPAN.TERMINATION_REASON_CODE <> 'VO'
                    --AND SPAN_TYPE_CODE = 'Active'
                    ) DIM_ENROLLMENT_SPAN
        ON (DIM_ENROLLMENT_SPAN.TPA_CLIENT_ID = CLAIM_DETAIL_VW.TPA_CLIENT_ID
        AND DIM_ENROLLMENT_SPAN.TPA_ID = CLAIM_DETAIL_VW.TPA_ID
        AND DIM_ENROLLMENT_SPAN.TPA_DIV_ID = CLAIM_DETAIL_VW.TPA_DIV_ID
        AND DIM_ENROLLMENT_SPAN.MEMBER_NBR = CLAIM_DETAIL_VW.MEMBER_NBR
        AND DIM_ENROLLMENT_SPAN.SUB_SOURCE_NAME = CLAIM_DETAIL_VW.MEMBER_NBR_TYPE
        AND DIM_ENROLLMENT_SPAN.ELIGIBILITY_START_DATE <= CLAIM_DETAIL_VW.SERVICE_BEGIN_DATE
        AND DIM_ENROLLMENT_SPAN.ELIGIBILITY_END_DATE >= CLAIM_DETAIL_VW.SERVICE_BEGIN_DATE
        AND DIM_ENROLLMENT_SPAN.RANK_NBR = 1 --GET THE MOST CURRENT ACTIVE RECORD
        )
        
    LEFT OUTER JOIN DIMDATA.DIM_GROUP
        ON (DIM_GROUP.TPA_CLIENT_ID = CLAIM_HEADER_VW.TPA_CLIENT_ID
        AND DIM_GROUP.TPA_ID = CLAIM_HEADER_VW.TPA_ID
        AND DIM_GROUP.TPA_DIV_ID = CLAIM_HEADER_VW.TPA_DIV_ID
        AND DIM_GROUP.GROUP_NBR = CLAIM_HEADER_VW.GROUP_NBR)
    
    LEFT OUTER JOIN DIMDATA.DIM_SUB_GROUP
        ON (DIM_SUB_GROUP.TPA_CLIENT_ID = CLAIM_HEADER_VW.TPA_CLIENT_ID
        AND DIM_SUB_GROUP.TPA_ID = CLAIM_HEADER_VW.TPA_ID
        AND DIM_SUB_GROUP.TPA_DIV_ID = CLAIM_HEADER_VW.TPA_DIV_ID
        AND DIM_SUB_GROUP.GROUP_NBR = CLAIM_HEADER_VW.GROUP_NBR
        AND DIM_SUB_GROUP.SUB_GROUP_NBR = CLAIM_HEADER_VW.SUB_GROUP_NBR)

    LEFT OUTER JOIN DIMDATA.DIM_PLAN
        ON (DIM_PLAN.TPA_CLIENT_ID = CLAIM_HEADER_VW.TPA_CLIENT_ID
        AND DIM_PLAN.TPA_ID = CLAIM_HEADER_VW.TPA_ID
        AND DIM_PLAN.TPA_DIV_ID = CLAIM_HEADER_VW.TPA_DIV_ID
        AND DIM_PLAN.PLAN_CODE = CLAIM_HEADER_VW.PLAN_CODE
        AND DIM_PLAN.PLAN_TYPE_CODE = CLAIM_HEADER_VW.PLAN_TYPE_CODE)

    LEFT OUTER JOIN DIMDATA.DIM_PLACE_OF_SERVICE
        ON (DIM_PLACE_OF_SERVICE.DIM_TPA_HIERARCHY_KEY = IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1)
        AND DIM_PLACE_OF_SERVICE.PLACE_OF_SERVICE_CODE = CLAIM_HEADER_VW.PLACE_OF_SERVICE_CODE
        AND DIM_PLACE_OF_SERVICE.SERVICE_TYPE_CODE = CLAIM_DETAIL_VW.SERVICE_TYPE_CODE
        AND DIM_PLACE_OF_SERVICE.LOCATION_CODE = CLAIM_DETAIL_VW.LOCATION_CODE)

    LEFT OUTER JOIN DIMDATA.DIM_CLAIM_PROCEDURE
        ON (DIM_CLAIM_PROCEDURE.DIM_TPA_HIERARCHY_KEY = IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1)
        AND DIM_CLAIM_PROCEDURE.DATA_SOURCE_NAME = CLAIM_DETAIL_VW.DATA_SOURCE_NAME
        AND DIM_CLAIM_PROCEDURE.PROCEDURE_CODE = CLAIM_DETAIL_VW.PROCEDURE_CODE
        AND DIM_CLAIM_PROCEDURE.IS_LOGICAL_DELETE_FLAG = FALSE)

    LEFT OUTER JOIN DIMDATA.DIM_COPAY_REASON_VW
        ON (DIM_COPAY_REASON_VW.DIM_TPA_HIERARCHY_KEY = IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1)
        AND DIM_COPAY_REASON_VW.DATA_SOURCE_NAME = CLAIM_DETAIL_VW.DATA_SOURCE_NAME
        AND DIM_COPAY_REASON_VW.COPAY_REASON_CODE = CLAIM_DETAIL_VW.COPAY_REASON_CODE)
        
    LEFT OUTER JOIN DIMDATA.DIM_DEDUCTIBLE_REASON_VW
        ON (DIM_DEDUCTIBLE_REASON_VW.DIM_TPA_HIERARCHY_KEY = IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1)
        AND DIM_DEDUCTIBLE_REASON_VW.DATA_SOURCE_NAME = CLAIM_DETAIL_VW.DATA_SOURCE_NAME
        AND DIM_DEDUCTIBLE_REASON_VW.DEDUCTIBLE_REASON_CODE = CLAIM_DETAIL_VW.DEDUCTIBLE_REASON_CODE)

    LEFT OUTER JOIN (SELECT CLAIM_DETAIL_ADJUSTMENT_REASON_CODE_GRP.CLAIM_DETAIL_ADJUSTMENT_REASON_CODE_KEY, GRP_ADJUSTMENT_REASON.GRP_ADJUSTMENT_REASON_KEY
                    FROM STAGEDATA.CLAIM_DETAIL_ADJUSTMENT_REASON_CODE_GRP
                        JOIN STAGEDATA.GRP_ADJUSTMENT_REASON
                            ON (GRP_ADJUSTMENT_REASON.CODE_VALUE = CLAIM_DETAIL_ADJUSTMENT_REASON_CODE_GRP.CODE_VALUE)
                    ) GRP_ADJUSTMENT_REASON
        ON (GRP_ADJUSTMENT_REASON.CLAIM_DETAIL_ADJUSTMENT_REASON_CODE_KEY = TO_VARCHAR(CLAIM_DETAIL_VW.CLAIM_DETAIL_KEY))
        
    LEFT OUTER JOIN (SELECT CLAIM_DETAIL_NOT_COVERED_REASON_CODE_GRP.CLAIM_DETAIL_NOT_COVERED_REASON_CODE_KEY, GRP_NOT_COVERED_REASON.GRP_NOT_COVERED_REASON_KEY
                    FROM STAGEDATA.CLAIM_DETAIL_NOT_COVERED_REASON_CODE_GRP
                        JOIN STAGEDATA.GRP_NOT_COVERED_REASON
                            ON (GRP_NOT_COVERED_REASON.CODE_VALUE = CLAIM_DETAIL_NOT_COVERED_REASON_CODE_GRP.CODE_VALUE)
                    ) GRP_NOT_COVERED_REASON
        ON (GRP_NOT_COVERED_REASON.CLAIM_DETAIL_NOT_COVERED_REASON_CODE_KEY = TO_VARCHAR(CLAIM_DETAIL_VW.CLAIM_DETAIL_KEY))

    LEFT OUTER JOIN (SELECT CLAIM_DETAIL_SERVICE_REASON_CODE_GRP.CLAIM_DETAIL_SERVICE_REASON_CODE_KEY, GRP_SERVICE_REASON.GRP_SERVICE_REASON_KEY
                    FROM STAGEDATA.CLAIM_DETAIL_SERVICE_REASON_CODE_GRP
                        JOIN STAGEDATA.GRP_SERVICE_REASON
                            ON (GRP_SERVICE_REASON.CODE_VALUE = CLAIM_DETAIL_SERVICE_REASON_CODE_GRP.CODE_VALUE)
                    ) GRP_SERVICE_REASON
        ON (GRP_SERVICE_REASON.CLAIM_DETAIL_SERVICE_REASON_CODE_KEY = TO_VARCHAR(CLAIM_DETAIL_VW.CLAIM_DETAIL_KEY))

  LEFT OUTER JOIN (SELECT CLAIM_HEADER_RIDER_CODE_GRP.CLAIM_HEADER_RIDER_CODE_KEY, GRP_CLAIM_RIDER.GRP_CLAIM_RIDER_KEY
                    FROM STAGEDATA.CLAIM_HEADER_RIDER_CODE_GRP
                        JOIN STAGEDATA.GRP_CLAIM_RIDER
                            ON (GRP_CLAIM_RIDER.CODE_VALUE = CLAIM_HEADER_RIDER_CODE_GRP.CODE_VALUE)
					) GRP_CLAIM_RIDER
        ON (GRP_CLAIM_RIDER.CLAIM_HEADER_RIDER_CODE_KEY = TO_VARCHAR(CLAIM_HEADER_VW.CLAIM_HEADER_KEY))

   LEFT OUTER JOIN (SELECT CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE_GRP.CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE_KEY, GRP_PROCEDURE_MODIFIER.GRP_PROCEDURE_MODIFIER_KEY
                    FROM STAGEDATA.CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE_GRP
                        JOIN STAGEDATA.GRP_PROCEDURE_MODIFIER
                            ON (GRP_PROCEDURE_MODIFIER.CODE_VALUE = CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE_GRP.CODE_VALUE)
                    ) GRP_PROCEDURE_MODIFIER
        ON (GRP_PROCEDURE_MODIFIER.CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE_KEY = TO_VARCHAR(CLAIM_DETAIL_VW.CLAIM_DETAIL_KEY))

    LEFT OUTER JOIN (SELECT CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE_GRP.CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE_KEY, GRP_PROCEDURE_CATEGORY.GRP_PROCEDURE_CATEGORY_KEY
                    FROM STAGEDATA.CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE_GRP
                        JOIN STAGEDATA.GRP_PROCEDURE_CATEGORY
                            ON (GRP_PROCEDURE_CATEGORY.CODE_VALUE = CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE_GRP.CODE_VALUE)
                    ) GRP_PROCEDURE_CATEGORY
        ON (GRP_PROCEDURE_CATEGORY.CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE_KEY = TO_VARCHAR(CLAIM_DETAIL_VW.CLAIM_DETAIL_KEY))

    LEFT OUTER JOIN (SELECT CLAIM_HEADER_ICD_DIAGNOSIS_CODE_GRP.CLAIM_HEADER_ICD_DIAGNOSIS_CODE_KEY, GRP_ICD_DIAGNOSIS.GRP_ICD_DIAGNOSIS_KEY
                    FROM STAGEDATA.CLAIM_HEADER_ICD_DIAGNOSIS_CODE_GRP
                        JOIN STAGEDATA.GRP_ICD_DIAGNOSIS
                            ON (GRP_ICD_DIAGNOSIS.CODE_VALUE = CLAIM_HEADER_ICD_DIAGNOSIS_CODE_GRP.CODE_VALUE)
                    ) GRP_ICD_DIAGNOSIS
        ON (GRP_ICD_DIAGNOSIS.CLAIM_HEADER_ICD_DIAGNOSIS_CODE_KEY = TO_VARCHAR(CLAIM_HEADER_VW.CLAIM_HEADER_KEY))

    LEFT OUTER JOIN (SELECT CLAIM_HEADER_ICD_PROCEDURE_CODE_GRP.CLAIM_HEADER_ICD_PROCEDURE_CODE_KEY, GRP_ICD_PROCEDURE.GRP_ICD_PROCEDURE_KEY
                    FROM STAGEDATA.CLAIM_HEADER_ICD_PROCEDURE_CODE_GRP
                        JOIN STAGEDATA.GRP_ICD_PROCEDURE
                            ON (GRP_ICD_PROCEDURE.CODE_VALUE = CLAIM_HEADER_ICD_PROCEDURE_CODE_GRP.CODE_VALUE)
                    ) GRP_ICD_PROCEDURE
        ON (GRP_ICD_PROCEDURE.CLAIM_HEADER_ICD_PROCEDURE_CODE_KEY = TO_VARCHAR(CLAIM_HEADER_VW.CLAIM_HEADER_KEY))

    LEFT OUTER JOIN (SELECT PROVIDER_DETAIL_VW.UNIVERSAL_PROVIDER_ID, IFNULL(PROVIDER_FROM_SQLSERVER.DIM_PROVIDER_KEY, PROVIDER_FROM_MARKLOGIC.DIM_PROVIDER_KEY) AS DIM_PROVIDER_KEY
                  FROM STAGEDATA.PROVIDER_DETAIL_VW
                      LEFT OUTER JOIN STAGEDATA.PROVIDER_ODS_DATA_SOURCE
                          ON (PROVIDER_ODS_DATA_SOURCE.DATA_SOURCE_NAME = PROVIDER_DETAIL_VW.DATA_SOURCE_NAME)
                      LEFT OUTER JOIN DIMDATA.DIM_PROVIDER PROVIDER_FROM_SQLSERVER
                          ON (PROVIDER_FROM_SQLSERVER.SOURCE_SYSTEM = 'SQLSERVER'
                          AND PROVIDER_FROM_SQLSERVER.IS_CURRENTROW_FLAG = 'TRUE'
                          AND PROVIDER_FROM_SQLSERVER.TPA_CLIENT_ID = PROVIDER_DETAIL_VW.TPA_CLIENT_ID
                          AND PROVIDER_FROM_SQLSERVER.TPA_ID = PROVIDER_DETAIL_VW.TPA_ID
                          AND PROVIDER_FROM_SQLSERVER.TPA_DIVISION_ID = PROVIDER_DETAIL_VW.TPA_DIV_ID
                          AND PROVIDER_FROM_SQLSERVER.PROVIDER_ID = CONCAT(PROVIDER_ODS_DATA_SOURCE.DATA_SOURCE_KEY,'-',PROVIDER_DETAIL_VW.SOURCE_PROVIDER_NBR))
                      LEFT OUTER JOIN DIMDATA.DIM_PROVIDER PROVIDER_FROM_MARKLOGIC
                          ON (PROVIDER_FROM_MARKLOGIC.SOURCE_SYSTEM = 'MARKLOGIC'
                          AND PROVIDER_FROM_MARKLOGIC.IS_CURRENTROW_FLAG = 'TRUE'
                          AND PROVIDER_FROM_MARKLOGIC.PROVIDER_ID = PROVIDER_DETAIL_VW.UNIVERSAL_PROVIDER_ID)
                    ) BILLING_PROVIDER
        ON (BILLING_PROVIDER.UNIVERSAL_PROVIDER_ID = CLAIM_HEADER_VW.BILLING_PROVIDER_DETAIL_KEY)

    LEFT OUTER JOIN (SELECT PROVIDER_DETAIL_VW.UNIVERSAL_PROVIDER_ID, IFNULL(PROVIDER_FROM_SQLSERVER.DIM_PROVIDER_KEY, PROVIDER_FROM_MARKLOGIC.DIM_PROVIDER_KEY) AS DIM_PROVIDER_KEY
                  FROM STAGEDATA.PROVIDER_DETAIL_VW
                      LEFT OUTER JOIN STAGEDATA.PROVIDER_ODS_DATA_SOURCE
                          ON (PROVIDER_ODS_DATA_SOURCE.DATA_SOURCE_NAME = PROVIDER_DETAIL_VW.DATA_SOURCE_NAME)
                      LEFT OUTER JOIN DIMDATA.DIM_PROVIDER PROVIDER_FROM_SQLSERVER
                          ON (PROVIDER_FROM_SQLSERVER.SOURCE_SYSTEM = 'SQLSERVER'
                          AND PROVIDER_FROM_SQLSERVER.IS_CURRENTROW_FLAG = 'TRUE'
                          AND PROVIDER_FROM_SQLSERVER.TPA_CLIENT_ID = PROVIDER_DETAIL_VW.TPA_CLIENT_ID
                          AND PROVIDER_FROM_SQLSERVER.TPA_ID = PROVIDER_DETAIL_VW.TPA_ID
                          AND PROVIDER_FROM_SQLSERVER.TPA_DIVISION_ID = PROVIDER_DETAIL_VW.TPA_DIV_ID
                          AND PROVIDER_FROM_SQLSERVER.PROVIDER_ID = CONCAT(PROVIDER_ODS_DATA_SOURCE.DATA_SOURCE_KEY,'-',PROVIDER_DETAIL_VW.SOURCE_PROVIDER_NBR))
                      LEFT OUTER JOIN DIMDATA.DIM_PROVIDER PROVIDER_FROM_MARKLOGIC
                          ON (PROVIDER_FROM_MARKLOGIC.SOURCE_SYSTEM = 'MARKLOGIC'
                          AND PROVIDER_FROM_MARKLOGIC.IS_CURRENTROW_FLAG = 'TRUE'
                          AND PROVIDER_FROM_MARKLOGIC.PROVIDER_ID = PROVIDER_DETAIL_VW.UNIVERSAL_PROVIDER_ID)
                    ) RENDERING_PROVIDER
         ON (RENDERING_PROVIDER.UNIVERSAL_PROVIDER_ID = CLAIM_DETAIL_VW.RENDERING_PROVIDER_DETAIL_KEY)

    LEFT OUTER JOIN DIMDATA.DIM_DATE_DAY DIM_DATE_DAY_RECEIVED
        ON (DIM_DATE_DAY_RECEIVED.FULL_DATE = CLAIM_DETAIL_VW.CLAIM_RECEIVED_DATE)

    LEFT OUTER JOIN DIMDATA.DIM_DATE_DAY DIM_DATE_DAY_PAYMENT
        ON (DIM_DATE_DAY_PAYMENT.FULL_DATE = CLAIM_DETAIL_VW.PAYMENT_DATE)

    LEFT OUTER JOIN DIMDATA.DIM_DATE_DAY DIM_DATE_DAY_SERVICE_BEGIN
        ON (DIM_DATE_DAY_SERVICE_BEGIN.FULL_DATE = CLAIM_DETAIL_VW.SERVICE_BEGIN_DATE)

    LEFT OUTER JOIN DIMDATA.DIM_DATE_DAY DIM_DATE_DAY_SERVICE_END
        ON (DIM_DATE_DAY_SERVICE_END.FULL_DATE = CLAIM_DETAIL_VW.SERVICE_END_DATE)
    
    LEFT OUTER JOIN DIMDATA.DIM_DATE_DAY DIM_DATE_DAY_ADMIT_DATE
        ON (DIM_DATE_DAY_ADMIT_DATE.FULL_DATE = CLAIM_HEADER_VW.ADMIT_DATE)

    LEFT OUTER JOIN DIMDATA.DIM_DATE_DAY DIM_DATE_DAY_DISCHARGE_DATE
        ON (DIM_DATE_DAY_DISCHARGE_DATE.FULL_DATE = CLAIM_HEADER_VW.DISCHARGE_DATE)

    LEFT OUTER JOIN DIMDATA.DIM_PROVIDER REFERRING_PROVIDER
        ON (REFERRING_PROVIDER.PROVIDER_ID = CLAIM_HEADER_VW.REFERRING_PROVIDER_DETAIL_KEY
        AND REFERRING_PROVIDER.TPA_CLIENT_ID = CLAIM_HEADER_VW.TPA_CLIENT_ID
        AND REFERRING_PROVIDER.TPA_ID = CLAIM_HEADER_VW.TPA_ID
        AND REFERRING_PROVIDER.TPA_DIVISION_ID = CLAIM_HEADER_VW.TPA_DIV_ID
        AND REFERRING_PROVIDER.ROW_EFFECTIVE_DATETIME <= CLAIM_DETAIL_VW.SERVICE_BEGIN_DATE 
        AND REFERRING_PROVIDER.ROW_EXPIRATION_DATETIME >= CLAIM_DETAIL_VW.SERVICE_BEGIN_DATE) 

    LEFT OUTER JOIN DIMDATA.DIM_PROVIDER ATTENDING_PHYSICIAN
        ON (ATTENDING_PHYSICIAN.PROVIDER_ID = CLAIM_HEADER_VW.ATTENDING_PHYSICIAN_DETAIL_KEY
        AND ATTENDING_PHYSICIAN.TPA_CLIENT_ID = CLAIM_HEADER_VW.TPA_CLIENT_ID
        AND ATTENDING_PHYSICIAN.TPA_ID = CLAIM_HEADER_VW.TPA_ID
        AND ATTENDING_PHYSICIAN.TPA_DIVISION_ID = CLAIM_HEADER_VW.TPA_DIV_ID
        AND ATTENDING_PHYSICIAN.ROW_EFFECTIVE_DATETIME <= CLAIM_DETAIL_VW.SERVICE_BEGIN_DATE 
        AND ATTENDING_PHYSICIAN.ROW_EXPIRATION_DATETIME >= CLAIM_DETAIL_VW.SERVICE_BEGIN_DATE)  

    LEFT OUTER JOIN DIMDATA.DIM_PROVIDER ASSIGNED_PROVIDER
        ON (ASSIGNED_PROVIDER.PROVIDER_ID = CLAIM_HEADER_VW.ASSIGNED_PROVIDER_KEY
        AND ASSIGNED_PROVIDER.TPA_CLIENT_ID = CLAIM_HEADER_VW.TPA_CLIENT_ID
        AND ASSIGNED_PROVIDER.TPA_ID = CLAIM_HEADER_VW.TPA_ID
        AND ASSIGNED_PROVIDER.TPA_DIVISION_ID = CLAIM_HEADER_VW.TPA_DIV_ID
        AND ASSIGNED_PROVIDER.ROW_EFFECTIVE_DATETIME <= CLAIM_DETAIL_VW.SERVICE_BEGIN_DATE 
        AND ASSIGNED_PROVIDER.ROW_EXPIRATION_DATETIME >= CLAIM_DETAIL_VW.SERVICE_BEGIN_DATE)    

     LEFT OUTER JOIN DIMDATA.DIM_MEMBER_ADDRESS_PHYSICAL_VW
        ON (DIM_MEMBER_ADDRESS_PHYSICAL_VW.EFFECTIVE_START_DATE < DIM_MEMBER_ADDRESS_PHYSICAL_VW.EFFECTIVE_END_DATE -- remove same day data errors
        AND DIM_MEMBER_ADDRESS_PHYSICAL_VW.DIM_MEMBER_KEY = DIM_MEMBER.DIM_MEMBER_KEY
        AND DIM_MEMBER_ADDRESS_PHYSICAL_VW.EFFECTIVE_START_DATE <= CLAIM_DETAIL_VW.SERVICE_BEGIN_DATE
        AND DIM_MEMBER_ADDRESS_PHYSICAL_VW.EFFECTIVE_END_DATE >= CLAIM_DETAIL_VW.SERVICE_BEGIN_DATE)

    LEFT OUTER JOIN DIMDATA.DIM_REVENUE_PROCEDURE 
        ON (CLAIM_DETAIL_VW.REVENUE_CODE = DIM_REVENUE_PROCEDURE.REVENUE_CODE)

-- EXCLUDE CLAIMS NOW COMING FROM UPMCHP_DATAHUB
WHERE CLAIM_DETAIL_VW.DATA_SOURCE_NAME NOT IN (SELECT DISTINCT DATA_SOURCE_NAME FROM RAWDATA.DATAHUB_CLAIM_HEADER_BASE)
AND
    (
    CLAIM_HEADER_VW.CLAIM_TYPE_CODE NOT IN ('P','A') -- Filter out Pre-D claims, which shouldn't be with claims data.
    OR CLAIM_HEADER_VW.CLAIM_TYPE_CODE IS NULL -- This line needed because Claim_Type_Code coming from NVA is NULL, which isn't caught in the above line.
    )
