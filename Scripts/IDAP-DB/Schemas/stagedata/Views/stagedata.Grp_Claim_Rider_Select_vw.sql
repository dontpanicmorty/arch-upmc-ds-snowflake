CREATE OR REPLACE VIEW STAGEDATA.GRP_CLAIM_RIDER_SELECT_VW
AS
SELECT
GRP_CLAIM_RIDER.GRP_CLAIM_RIDER_KEY
,COALESCE(DIM_RIDER.DIM_RIDER_KEY,DIM_RIDER_UNK_SUBGROUP.DIM_RIDER_KEY, 1) AS DIM_RIDER_KEY
,CLAIM_HEADER_RIDER_CODE.CLAIM_HEADER_RIDER_CODE_KEY
FROM STAGEDATA.CLAIM_HEADER_RIDER_CODE
	JOIN STAGEDATA.CLAIM_HEADER_RIDER_CODE_GRP
    	ON (CLAIM_HEADER_RIDER_CODE_GRP.CLAIM_HEADER_RIDER_CODE_KEY = CLAIM_HEADER_RIDER_CODE.CLAIM_HEADER_RIDER_CODE_KEY)

	JOIN STAGEDATA.GRP_CLAIM_RIDER
		ON (GRP_CLAIM_RIDER.CODE_VALUE = CLAIM_HEADER_RIDER_CODE_GRP.CODE_VALUE)

	LEFT OUTER JOIN DIMDATA.DIM_RIDER
		ON (DIM_RIDER.TPA_CLIENT_ID = CLAIM_HEADER_RIDER_CODE.TPA_CLIENT_ID
		AND DIM_RIDER.TPA_ID = CLAIM_HEADER_RIDER_CODE.TPA_ID
		AND DIM_RIDER.TPA_DIV_ID = CLAIM_HEADER_RIDER_CODE.TPA_DIV_ID
		AND DIM_RIDER.RIDER_CODE = CLAIM_HEADER_RIDER_CODE.CODE_VALUE
		AND DIM_RIDER.RIDER_EFFECTIVE_DATE <= CLAIM_HEADER_RIDER_CODE.ADMIT_DATE
		AND DIM_RIDER.RIDER_TERMINATION_DATE >= CLAIM_HEADER_RIDER_CODE.ADMIT_DATE
		AND DIM_RIDER.GROUP_NBR = CLAIM_HEADER_RIDER_CODE.GROUP_NBR
		AND DIM_RIDER.SUB_GROUP_NBR = CLAIM_HEADER_RIDER_CODE.SUB_GROUP_NBR)

	LEFT OUTER JOIN DIMDATA.DIM_RIDER DIM_RIDER_UNK_SUBGROUP --workaround for claims tied to riders with blank subgroups in MC400
		ON (DIM_RIDER_UNK_SUBGROUP.TPA_CLIENT_ID = CLAIM_HEADER_RIDER_CODE.TPA_CLIENT_ID
		AND DIM_RIDER_UNK_SUBGROUP.TPA_ID = CLAIM_HEADER_RIDER_CODE.TPA_ID
		AND DIM_RIDER_UNK_SUBGROUP.TPA_DIV_ID = CLAIM_HEADER_RIDER_CODE.TPA_DIV_ID
		AND DIM_RIDER_UNK_SUBGROUP.RIDER_CODE = CLAIM_HEADER_RIDER_CODE.CODE_VALUE
		AND DIM_RIDER_UNK_SUBGROUP.RIDER_EFFECTIVE_DATE <= CLAIM_HEADER_RIDER_CODE.ADMIT_DATE
		AND DIM_RIDER_UNK_SUBGROUP.RIDER_TERMINATION_DATE >= CLAIM_HEADER_RIDER_CODE.ADMIT_DATE
		AND DIM_RIDER_UNK_SUBGROUP.GROUP_NBR = CLAIM_HEADER_RIDER_CODE.GROUP_NBR
		AND DIM_RIDER_UNK_SUBGROUP.SUB_GROUP_NBR = 'UNK')
;