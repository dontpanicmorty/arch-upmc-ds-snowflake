CREATE OR REPLACE VIEW STAGEDATA.DIM_PROVIDER_IDENTIFIER_SELECT_VW
AS
SELECT
'N/A-MARKLOGIC' AS MD5_VALUE_TEXT
,TO_BOOLEAN('FALSE') AS IS_LOGICAL_DELETE_FLAG
,DIM_PROVIDER.DIM_PROVIDER_KEY
,CASE PROVIDER_DETAIL_IDENTIFIERS_VW.IDENTIFICATION_TYPE_DESC 
    WHEN 'NPI' THEN 'National Provider Identifier'
    ELSE PROVIDER_DETAIL_IDENTIFIERS_VW.IDENTIFICATION_TYPE_DESC
END AS IDENTIFIER_NAME
,PROVIDER_DETAIL_IDENTIFIERS_VW.IDENTIFICATION_VALUE AS IDENTIFIER_NBR
,DIM_PROVIDER.SOURCE_SYSTEM
FROM STAGEDATA.PROVIDER_DETAIL_IDENTIFIERS_VW
    JOIN DIMDATA.DIM_PROVIDER
        ON (DIM_PROVIDER.SOURCE_SYSTEM = 'MARKLOGIC'
        AND DIM_PROVIDER.TPA_CLIENT_ID = PROVIDER_DETAIL_IDENTIFIERS_VW.TPA_CLIENT_ID
        AND DIM_PROVIDER.TPA_ID = PROVIDER_DETAIL_IDENTIFIERS_VW.TPA_ID
        AND DIM_PROVIDER.TPA_DIVISION_ID = PROVIDER_DETAIL_IDENTIFIERS_VW.TPA_DIV_ID
        AND DIM_PROVIDER.PROVIDER_ID = PROVIDER_DETAIL_IDENTIFIERS_VW.UNIVERSAL_PROVIDER_ID)
WHERE PROVIDER_DETAIL_IDENTIFIERS_VW.IDENTIFICATION_TYPE_DESC IS NOT NULL
AND PROVIDER_DETAIL_IDENTIFIERS_VW.IDENTIFICATION_VALUE IS NOT NULL
AND PROVIDER_DETAIL_IDENTIFIERS_VW.DATA_SOURCE_NAME NOT IN (SELECT DISTINCT DATA_SOURCE_NAME FROM RAWDATA.DATAHUB_PROVIDER_DETAIL_BASE)
AND PROVIDER_DETAIL_IDENTIFIERS_VW.DATA_SOURCE_NAME NOT IN ('ESI', 'ESIF14') --exclude pharmacy records

UNION ALL

SELECT
'N/A-UPMCHP_DATAHUB' AS MD5_VALUE_TEXT
,TO_BOOLEAN('FALSE') AS IS_LOGICAL_DELETE_FLAG
,DIM_PROVIDER.DIM_PROVIDER_KEY
,'National Provider Identifier' AS IDENTIFIER_NAME
,DATAHUB_PROVIDER_IDENTIFIER.NATIONAL_PROVIDER_ID AS IDENTIFIER_NBR
,DIM_PROVIDER.SOURCE_SYSTEM
FROM RAWDATA.DATAHUB_PROVIDER_IDENTIFIER
    JOIN DIMDATA.DIM_PROVIDER
        ON (DIM_PROVIDER.SOURCE_SYSTEM = 'UPMCHP_DATAHUB'
        AND DIM_PROVIDER.TPA_CLIENT_ID = DATAHUB_PROVIDER_IDENTIFIER.TPA_CLIENT_ID
        AND DIM_PROVIDER.TPA_ID = DATAHUB_PROVIDER_IDENTIFIER.TPA_ID
        AND DIM_PROVIDER.TPA_DIVISION_ID = DATAHUB_PROVIDER_IDENTIFIER.TPA_DIV_ID
        AND DIM_PROVIDER.DATA_SOURCE_NAME = DATAHUB_PROVIDER_IDENTIFIER.DATA_SOURCE_NAME
        AND DIM_PROVIDER.SOURCE_PROVIDER_NBR = DATAHUB_PROVIDER_IDENTIFIER.PROVIDER_ID)
WHERE DATAHUB_PROVIDER_IDENTIFIER.NATIONAL_PROVIDER_ID IS NOT NULL
AND DATAHUB_PROVIDER_IDENTIFIER.DATA_SOURCE_NAME <> 'ESI' --exclude pharmacy records
;