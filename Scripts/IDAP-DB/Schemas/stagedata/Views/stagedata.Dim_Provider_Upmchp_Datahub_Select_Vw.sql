CREATE OR REPLACE VIEW STAGEDATA.DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW
AS
SELECT
'N/A-UPMCHP-DATAHUB' AS MD5_VALUE_TEXT
,TO_BOOLEAN('FALSE') AS IS_LOGICAL_DELETE_FLAG
,TO_TIMESTAMP_TZ('1900-01-01') AS ROW_EFFECTIVE_DATETIME
,TO_TIMESTAMP_TZ('9999-12-31') AS ROW_EXPIRATION_DATETIME
,TO_BOOLEAN('TRUE') AS Is_CurrentRow_Flag
,DATAHUB_PROVIDER_DETAIL_BASE.DATA_SOURCE_NAME
,CONCAT(DATAHUB_PROVIDER_DETAIL_BASE.DATA_SOURCE_NAME,DATAHUB_PROVIDER_DETAIL_BASE.PROVIDER_ID) AS PROVIDER_ID
,DATAHUB_PROVIDER_DETAIL_BASE.TPA_CLIENT_ID
,DATAHUB_PROVIDER_DETAIL_BASE.TPA_ID
,DATAHUB_PROVIDER_DETAIL_BASE.TPA_DIV_ID AS TPA_DIVISION_ID
,CASE (DATAHUB_PROVIDER_DETAIL_BASE.PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN 1
    WHEN 'Facility' THEN 2
    WHEN 'Medical Group' THEN 3
    WHEN 'Pharmacy' THEN 4
    ELSE 0
END AS PROVIDER_TYPE_CODE
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.PROVIDER_TYPE_NAME, 'Unknown') AS PROVIDER_TYPE_DESC
,0 AS Provider_role_type_Code 
,'Unknown' AS Provider_role_type_Desc
,DATAHUB_PROVIDER_DETAIL_BASE.FULL_NAME AS Provider_Full_Name
,CASE (PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.LAST_NAME,'')
    ELSE 'n/a'
END AS Practitioner_Last_Name
,CASE (PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.FIRST_NAME,'')
    ELSE 'n/a'
END AS Practitioner_First_Name
,CASE (PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.MIDDLE_NAME,'')
    ELSE 'n/a'
END AS Practitioner_Middle_Name
,CASE (PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.MIDDLE_INITIAL_NAME,'')
    ELSE 'n/a'
END AS Practitioner_Middle_Initial
,CASE (PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.SUFFIX_NAME,'')
    ELSE 'n/a'
END AS Practitioner_Name_Suffix
,CASE (PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.GENDER_CODE,'U')
    ELSE 'n/a'
END AS Practitioner_gender_code 
,CASE (PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.GENDER_NAME,'Unknown')
    ELSE 'n/a'
END AS Practitioner_Gender_Name 
,DATAHUB_PROVIDER_DETAIL_BASE.DATE_OF_BIRTH AS Practitioner_Birth_Date
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.TAX_ID_NBR,'') AS Medical_Group_TIN_Nbr
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.upin_nbr,'') AS Practitioner_UPIN_Nbr
,CASE (PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.SOCIAL_SECURITY_NBR,'Unknown')
    ELSE 'n/a'
END AS Practitioner_SSN_Nbr
,CASE (PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.DEGREE_TEXT,'Unknown')
    ELSE 'n/a'
END AS Practitioner_Degree
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.EMAIL_ADDRESS,'Unknown') AS Provider_Email_Address
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.WEBSITE_URL,'Unknown') AS Provider_Website_URL
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.PRIMARY_SPECIALTY_NAME,'Unknown') AS Primary_Specialty_Name
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.PRIMARY_PHO_CODE, 0) as Primary_PHO_Code
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.PRIMARY_PHO_NAME,'Unknown') as Primary_PHO_Name
,DATAHUB_PROVIDER_DETAIL_BASE.PRIMARY_PHO_TERMINATION_DATE AS Primary_PHO_Termination_Date
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.SECONDARY_PHO_CODE, 0) AS Secondary_PHO_Code
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.SECONDARY_PHO_NAME,'Unknown') as Secondary_PHO_Name
,DATAHUB_PROVIDER_DETAIL_BASE.SECONDARY_PHO_TERMINATION_DATE AS Secondary_PHO_Termination_Date
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.TERTIARY_PHO_CODE,0) AS Tertiary_PHO_Code
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.TERTIARY_PHO_NAME,'Unknown') AS Tertiary_PHO_Name
,DATAHUB_PROVIDER_DETAIL_BASE.TERTIARY_PHO_TERMINATION_DATE AS Tertiary_PHO_Termination_Date
,DATAHUB_PROVIDER_DETAIL_BASE.PROVIDER_START_DATE
,NULL AS Facility_Inception_Date
,DATAHUB_PROVIDER_DETAIL_BASE.ACTIVE_IND AS Provider_Active_Ind
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.LOCUM_TENENS_IND,'U') as Practitioner_Locum_Tenens_Ind
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.INVISIBLE_PROVIDER_IND,'U') AS Invisible_Provider_Ind
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.TEMPORARY_PROVIDER_IND,'U') AS Temporary_Provider_Ind
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.PA_MEDICAID_IND,'U') AS PA_Medicaid_Ind
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.PP_ACA_ENHANCED_PAY_IND,'U') AS PP_ACA_Enhanced_Pay_Ind
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.MALPRACTICE_COVERAGE_IND,'U') AS Has_Malpractice_Insurance_Ind
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.OWNERSHIP_STATUS_CODE, 0) AS Ownership_Status_Code
,IFNULL(DATAHUB_PROVIDER_DETAIL_BASE.OWNERSHIP_STATUS_DESC,'Unknown') AS Ownership_Status_Desc
,DATAHUB_PROVIDER_DETAIL_BASE.URI
,DATAHUB_PROVIDER_DETAIL_BASE.PROVIDER_ID AS SOURCE_PROVIDER_NBR
,DATAHUB_PROVIDER_DETAIL_BASE.HKEY AS SOURCE_ID
,'UPMCHP_DATAHUB' AS SOURCE_SYSTEM
,TO_BOOLEAN(IFF((DIM_PROVIDER_MATCHING_DATASOURCE.DIM_PROVIDER_KEY IS NOT NULL OR DIM_PROVIDER_CACTUS.DIM_PROVIDER_KEY IS NOT NULL), TRUE, FALSE)) AS HAS_MATCH_FROM_SQL_SERVER
,COALESCE(DIM_PROVIDER_CACTUS.DIM_PROVIDER_KEY, DIM_PROVIDER_MATCHING_DATASOURCE.DIM_PROVIDER_KEY) AS SQL_SERVER_DIM_PROVIDER_KEY

FROM RAWDATA.DATAHUB_PROVIDER_DETAIL_BASE

    --The look to ODS and DIM_PROVIDER is to get the proper provider id coming from the sql server (ods master version) of the providers
    --Intentially ignoring type-2 records and only going after the most current.
    LEFT OUTER JOIN DIMDATA.DIM_PROVIDER DIM_PROVIDER_MATCHING_DATASOURCE
        ON (DIM_PROVIDER_MATCHING_DATASOURCE.SOURCE_SYSTEM = 'SQLSERVER'
        AND DIM_PROVIDER_MATCHING_DATASOURCE.IS_CURRENTROW_FLAG = TRUE
        AND DIM_PROVIDER_MATCHING_DATASOURCE.IS_LOGICAL_DELETE_FLAG = FALSE
        AND DIM_PROVIDER_MATCHING_DATASOURCE.TPA_CLIENT_ID = DATAHUB_PROVIDER_DETAIL_BASE.TPA_CLIENT_ID
        AND DIM_PROVIDER_MATCHING_DATASOURCE.TPA_ID = DATAHUB_PROVIDER_DETAIL_BASE.TPA_ID
        AND DIM_PROVIDER_MATCHING_DATASOURCE.TPA_DIVISION_ID = DATAHUB_PROVIDER_DETAIL_BASE.TPA_DIV_ID
        AND DIM_PROVIDER_MATCHING_DATASOURCE.DATA_SOURCE_NAME = DATAHUB_PROVIDER_DETAIL_BASE.DATA_SOURCE_NAME
        AND DIM_PROVIDER_MATCHING_DATASOURCE.SOURCE_PROVIDER_NBR = DATAHUB_PROVIDER_DETAIL_BASE.PROVIDER_ID)

    --Specifically try and find the provider in the Cactus data coming from SQL Server
    --Cactus pretty much only holds MC400Upm credentialed provider and some MC400Dnt credentialed providers.
    --These are most all practitioners, not medical groups or facilites, so matching on type and lastname to ensure we get a good match
    LEFT OUTER JOIN DIMDATA.DIM_PROVIDER DIM_PROVIDER_CACTUS
        ON (DIM_PROVIDER_CACTUS.SOURCE_SYSTEM = 'SQLSERVER'
        AND DIM_PROVIDER_CACTUS.IS_CURRENTROW_FLAG = TRUE
        AND DIM_PROVIDER_CACTUS.IS_LOGICAL_DELETE_FLAG = FALSE
        AND DIM_PROVIDER_CACTUS.TPA_CLIENT_ID = DATAHUB_PROVIDER_DETAIL_BASE.TPA_CLIENT_ID
        AND DIM_PROVIDER_CACTUS.TPA_ID = DATAHUB_PROVIDER_DETAIL_BASE.TPA_ID
        AND DIM_PROVIDER_CACTUS.TPA_DIVISION_ID = DATAHUB_PROVIDER_DETAIL_BASE.TPA_DIV_ID
        AND DIM_PROVIDER_CACTUS.DATA_SOURCE_NAME = 'Cactus'
        AND DIM_PROVIDER_CACTUS.SOURCE_PROVIDER_NBR = DATAHUB_PROVIDER_DETAIL_BASE.PROVIDER_ID
        AND DIM_PROVIDER_CACTUS.PROVIDER_TYPE_DESC = DATAHUB_PROVIDER_DETAIL_BASE.PROVIDER_TYPE_NAME
        AND UPPER(DIM_PROVIDER_CACTUS.PRACTITIONER_LAST_NAME) = UPPER(DATAHUB_PROVIDER_DETAIL_BASE.LAST_NAME))

WHERE DATAHUB_PROVIDER_DETAIL_BASE.DATA_SOURCE_NAME <> 'ESI' --exclude pharmacy records
;