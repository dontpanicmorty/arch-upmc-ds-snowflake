CREATE OR REPLACE VIEW STAGEDATA.FACT_CLAIM_AUTHORIZATION_DETAIL_UPMCHP_DATAHUB_SELECT_VW
AS

WITH PROVIDER_LOOKUP_CTE
--using this to make to lookup to all the providers easier.
--It uses the stagedata view that builds the provider dimension so we can use all the same logic to see if we are finding a provider
--from SQL Server verses using one the has expicitaly added from UPMCHP_DATAHUB
AS
(

SELECT
DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.TPA_CLIENT_ID
,DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.TPA_ID
,DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.TPA_DIVISION_ID
,DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.DATA_SOURCE_NAME
,DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.SOURCE_PROVIDER_NBR AS PROVIDER_ID
,COALESCE(DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.SQL_SERVER_DIM_PROVIDER_KEY, DIM_PROVIDER.DIM_PROVIDER_KEY) AS DIM_PROVIDER_KEY
FROM STAGEDATA.DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW
    LEFT OUTER JOIN DIMDATA.DIM_PROVIDER
        ON (DIM_PROVIDER.TPA_CLIENT_ID = DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.TPA_CLIENT_ID
        AND DIM_PROVIDER.TPA_ID = DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.TPA_ID
        AND DIM_PROVIDER.TPA_DIVISION_ID = DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.TPA_DIVISION_ID
        AND DIM_PROVIDER.PROVIDER_ID = DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.PROVIDER_ID
        AND DIM_PROVIDER.IS_LOGICAL_DELETE_FLAG = 'FALSE')
)


SELECT

IFNULL(DIM_CLAIM_AUTHORIZATION_DETAIL.DIM_CLAIM_AUTHORIZATION_DETAIL_KEY,1) AS DIM_CLAIM_AUTHORIZATION_DETAIL_KEY,
IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY,1) AS DIM_TPA_HIERARCHY_KEY,
IFNULL(DIM_DATA_SOURCE.DIM_DATA_SOURCE_KEY,1) AS DIM_DATA_SOURCE_KEY,
IFNULL(DIM_CLAIM_AUTHORIZATION.DIM_CLAIM_AUTHORIZATION_KEY,1) AS DIM_CLAIM_AUTHORIZATION_KEY,
IFNULL(DIM_MEMBER.DIM_MEMBER_KEY,1) AS DIM_MEMBER_KEY,
IFNULL(DIM_PLAN.DIM_PLAN_KEY,1) AS DIM_PLAN_KEY,
IFNULL(SUBMITTING_PROVIDER.DIM_PROVIDER_KEY,1) AS DIM_SUBMITTING_PROVIDER_KEY,
IFNULL(RENDERING_PROVIDER.DIM_PROVIDER_KEY,1) AS DIM_RENDERING_PROVIDER_KEY,
IFNULL(DIM_CLAIM_PROCEDURE.DIM_CLAIM_PROCEDURE_KEY,1) AS DIM_CLAIM_PROCEDURE_KEY,
IFNULL(DIM_DATE_DAY_SERVICE_BEGIN.DIM_DATE_DAY_KEY, 1) AS DIM_SERVICE_BEGIN_DATE_KEY,
IFNULL(DIM_DATE_DAY_SERVICE_END.DIM_DATE_DAY_KEY, 1) AS DIM_SERVICE_END_DATE_KEY,
DATAHUB_CLAIM_AUTHORIZATION_BASE.AUTHORIZATION_NBR,
DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.AUTHORIZATION_LINE_NBR,
DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.SERVICE_BEGIN_DATE,
DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.SERVICE_END_DATE,
DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.AUTHORIZED_QTY,
DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.CONSUMED_QTY,
DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.DENIED_QTY,
DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.REQUESTED_QTY,
DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.ALLOWED_AMT,
DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.AUTHORIZED_AMT,
DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.AUTHORIZED_PER_UNIT_AMT,
DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.BALANCE_DUE_AMT,
DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.BILLED_AMT,
DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.COINSURANCE_AMT,
DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.COPAY_AMT,
DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.DEDUCTIBLE_APPLIED_AMT,
DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.PAID_AMT,
DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.PATIENT_PAY_APPLIED_AMT,
DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.PAYABLE_AMT,
DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.USUAL_AND_CUSTOMARY_AMT
FROM RAWDATA.DATAHUB_CLAIM_AUTHORIZATION_BASE
JOIN RAWDATA.DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE
    ON (DATAHUB_CLAIM_AUTHORIZATION_BASE.HUB_CLAIM_AUTHORIZATION_HKEY = DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.HUB_CLAIM_AUTHORIZATION_HKEY)
JOIN DIMDATA.DIM_TPA_HIERARCHY
    ON (DATAHUB_CLAIM_AUTHORIZATION_BASE.TPA_CLIENT_ID = DIM_TPA_HIERARCHY.TPA_CLIENT_ID
    AND DATAHUB_CLAIM_AUTHORIZATION_BASE.TPA_ID = DIM_TPA_HIERARCHY.TPA_ID
    AND DATAHUB_CLAIM_AUTHORIZATION_BASE.TPA_DIV_ID = DIM_TPA_HIERARCHY.TPA_DIV_ID
    )
JOIN DIMDATA.DIM_DATA_SOURCE
    ON (DATAHUB_CLAIM_AUTHORIZATION_BASE.DATA_SOURCE_NAME = DIM_DATA_SOURCE.DATA_SOURCE_NAME
    AND DIM_DATA_SOURCE.IS_LOGICAL_DELETE_FLAG = FALSE
    )
LEFT OUTER JOIN DIMDATA.DIM_CLAIM_AUTHORIZATION
    ON (DATAHUB_CLAIM_AUTHORIZATION_BASE.TPA_CLIENT_ID = DIM_CLAIM_AUTHORIZATION.TPA_CLIENT_ID
    AND DATAHUB_CLAIM_AUTHORIZATION_BASE.TPA_ID = DIM_CLAIM_AUTHORIZATION.TPA_ID
    AND DATAHUB_CLAIM_AUTHORIZATION_BASE.TPA_DIV_ID = DIM_CLAIM_AUTHORIZATION.TPA_DIV_ID
    AND DATAHUB_CLAIM_AUTHORIZATION_BASE.DATA_SOURCE_NAME = DIM_CLAIM_AUTHORIZATION.DATA_SOURCE_NAME
    AND DATAHUB_CLAIM_AUTHORIZATION_BASE.AUTHORIZATION_NBR = DIM_CLAIM_AUTHORIZATION.AUTHORIZATION_NBR
    AND DIM_CLAIM_AUTHORIZATION.IS_LOGICAL_DELETE_FLAG = FALSE
    )
LEFT OUTER JOIN DIMDATA.DIM_CLAIM_AUTHORIZATION_DETAIL
    ON (DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.TPA_CLIENT_ID = DIM_CLAIM_AUTHORIZATION_DETAIL.TPA_CLIENT_ID
    AND DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.TPA_ID = DIM_CLAIM_AUTHORIZATION_DETAIL.TPA_ID
    AND DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.TPA_DIV_ID = DIM_CLAIM_AUTHORIZATION_DETAIL.TPA_DIV_ID
    AND DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.DATA_SOURCE_NAME = DIM_CLAIM_AUTHORIZATION_DETAIL.DATA_SOURCE_NAME
    AND DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.AUTHORIZATION_NBR = DIM_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_NBR
    AND DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.AUTHORIZATION_LINE_NBR = DIM_CLAIM_AUTHORIZATION_DETAIL.AUTHORIZATION_LINE_NBR
    AND DIM_CLAIM_AUTHORIZATION_DETAIL.IS_LOGICAL_DELETE_FLAG = FALSE
    )
LEFT OUTER JOIN DIMDATA.DIM_PLAN
    ON (DATAHUB_CLAIM_AUTHORIZATION_BASE.TPA_CLIENT_ID = DIM_PLAN.TPA_CLIENT_ID
    AND DATAHUB_CLAIM_AUTHORIZATION_BASE.TPA_ID = DIM_PLAN.TPA_ID
    AND DATAHUB_CLAIM_AUTHORIZATION_BASE.TPA_DIV_ID = DIM_PLAN.TPA_DIV_ID
    AND DATAHUB_CLAIM_AUTHORIZATION_BASE.PLAN_CODE = DIM_PLAN.PLAN_CODE
    AND DATAHUB_CLAIM_AUTHORIZATION_BASE.PLAN_TYPE_CODE = DIM_PLAN.PLAN_TYPE_CODE
    )

LEFT OUTER JOIN DIMDATA.DIM_MEMBER
    ON (DATAHUB_CLAIM_AUTHORIZATION_BASE.TPA_CLIENT_ID = DIM_MEMBER.TPA_CLIENT_ID
    AND DATAHUB_CLAIM_AUTHORIZATION_BASE.TPA_ID = DIM_MEMBER.TPA_ID
    AND DATAHUB_CLAIM_AUTHORIZATION_BASE.TPA_DIV_ID = DIM_MEMBER.TPA_DIV_ID
    AND DATAHUB_CLAIM_AUTHORIZATION_BASE.MEMBER_NBR = DIM_MEMBER.MEMBER_NBR
    )

LEFT OUTER JOIN PROVIDER_LOOKUP_CTE SUBMITTING_PROVIDER
        ON (SUBMITTING_PROVIDER.TPA_ID = DATAHUB_CLAIM_AUTHORIZATION_BASE.TPA_ID
        AND SUBMITTING_PROVIDER.TPA_CLIENT_ID = DATAHUB_CLAIM_AUTHORIZATION_BASE.TPA_CLIENT_ID
        AND SUBMITTING_PROVIDER.TPA_DIVISION_ID = DATAHUB_CLAIM_AUTHORIZATION_BASE.TPA_DIV_ID
        AND SUBMITTING_PROVIDER.DATA_SOURCE_NAME = DATAHUB_CLAIM_AUTHORIZATION_BASE.DATA_SOURCE_NAME
        AND SUBMITTING_PROVIDER.PROVIDER_ID = DATAHUB_CLAIM_AUTHORIZATION_BASE.SUBMITTING_PROVIDER_ID)

LEFT OUTER JOIN PROVIDER_LOOKUP_CTE RENDERING_PROVIDER
        ON (RENDERING_PROVIDER.TPA_ID = DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.TPA_ID
        AND RENDERING_PROVIDER.TPA_CLIENT_ID = DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.TPA_CLIENT_ID
        AND RENDERING_PROVIDER.TPA_DIVISION_ID = DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.TPA_DIV_ID
        AND RENDERING_PROVIDER.DATA_SOURCE_NAME = DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.DATA_SOURCE_NAME
        AND RENDERING_PROVIDER.PROVIDER_ID = DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.RENDERING_PROVIDER_ID)

LEFT OUTER JOIN DIMDATA.DIM_CLAIM_PROCEDURE  
        ON (DIM_CLAIM_PROCEDURE.DIM_TPA_HIERARCHY_KEY = IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1)
        AND DIM_CLAIM_PROCEDURE.DATA_SOURCE_NAME = DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.DATA_SOURCE_NAME
        AND DIM_CLAIM_PROCEDURE.PROCEDURE_CODE = DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.PROCEDURE_CODE
        AND DIM_CLAIM_PROCEDURE.IS_LOGICAL_DELETE_FLAG = FALSE)
LEFT OUTER JOIN DIMDATA.DIM_DATE_DAY DIM_DATE_DAY_SERVICE_BEGIN
        ON (DIM_DATE_DAY_SERVICE_BEGIN.FULL_DATE = DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.SERVICE_BEGIN_DATE
        )
LEFT OUTER JOIN DIMDATA.DIM_DATE_DAY DIM_DATE_DAY_SERVICE_END
        ON (DIM_DATE_DAY_SERVICE_END.FULL_DATE = DATAHUB_CLAIM_AUTHORIZATION_DETAIL_BASE.SERVICE_END_DATE
        )
;