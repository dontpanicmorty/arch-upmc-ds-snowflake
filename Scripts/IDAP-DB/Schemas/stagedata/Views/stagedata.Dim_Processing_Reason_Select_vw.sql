CREATE OR REPLACE VIEW STAGEDATA.DIM_PROCESSING_REASON_SELECT_VW
AS

SELECT DISTINCT
IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1) AS DIM_TPA_HIERARCHY_KEY
,DATAHUB_CLAIM_DETAIL_PROCESSING_REASON_CODE.DATA_SOURCE_NAME
,DATAHUB_CLAIM_DETAIL_PROCESSING_REASON_CODE.CODE_POSITION
,DATAHUB_CLAIM_DETAIL_PROCESSING_REASON_CODE.REASON_CODE AS PROCESSING_REASON_CODE
,DATAHUB_CLAIM_DETAIL_PROCESSING_REASON_CODE.REASON_TYPE_CODE AS PROCESSING_REASON_TYPE_CODE
,DATAHUB_CLAIM_DETAIL_PROCESSING_REASON_CODE.CODE_DESC AS PROCESSING_REASON_DESC
,DATAHUB_CLAIM_DETAIL_PROCESSING_REASON_CODE.HIPAA_277_CODE
,DATAHUB_CLAIM_DETAIL_PROCESSING_REASON_CODE.HIPAA_835_CODE

FROM RAWDATA.DATAHUB_CLAIM_DETAIL_PROCESSING_REASON_CODE
    LEFT OUTER JOIN DIMDATA.DIM_TPA_HIERARCHY
        ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = DATAHUB_CLAIM_DETAIL_PROCESSING_REASON_CODE.TPA_CLIENT_ID
        AND DIM_TPA_HIERARCHY.TPA_ID = DATAHUB_CLAIM_DETAIL_PROCESSING_REASON_CODE.TPA_ID
        AND DIM_TPA_HIERARCHY.TPA_DIV_ID = DATAHUB_CLAIM_DETAIL_PROCESSING_REASON_CODE.TPA_DIV_ID)
;