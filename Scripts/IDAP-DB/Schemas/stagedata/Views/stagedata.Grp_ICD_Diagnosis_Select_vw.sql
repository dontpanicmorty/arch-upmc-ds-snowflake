CREATE OR REPLACE VIEW STAGEDATA.GRP_ICD_DIAGNOSIS_SELECT_VW
AS
SELECT
GRP_ICD_DIAGNOSIS.GRP_ICD_DIAGNOSIS_KEY
,IFNULL(DIM_ICD_DIAGNOSIS.DIM_ICD_DIAGNOSIS_KEY, 1) AS DIM_ICD_DIAGNOSIS_KEY
,ICD_DIAGNOSIS.CODE_POSITION AS ICD_POSITION_NBR
,ICD_DIAGNOSIS.POA_CODE AS POA_CODE
,ICD_DIAGNOSIS.CODE_QUALIFIER AS ICD_QUALIFIER_CODE
,CASE ICD_DIAGNOSIS.CODE_QUALIFIER 
    WHEN 'n/a' THEN 'n/a'
    ELSE ICD_QUALIFIER.TARGET_DESC
END AS ICD_QUALIFIER_DESC
,CASE WHEN (ICD_DIAGNOSIS.CODE_POSITION = 1)
    THEN 'Y' 
    ELSE 'N' 
END AS PRIMARY_DIAGNOSIS_IND
,ICD_DIAGNOSIS.CLAIM_HEADER_ICD_DIAGNOSIS_CODE_KEY
FROM STAGEDATA.CLAIM_HEADER_ICD_DIAGNOSIS_CODE ICD_DIAGNOSIS

    JOIN STAGEDATA.CLAIM_HEADER_ICD_DIAGNOSIS_CODE_GRP 
        ON (CLAIM_HEADER_ICD_DIAGNOSIS_CODE_GRP.CLAIM_HEADER_ICD_DIAGNOSIS_CODE_KEY = ICD_DIAGNOSIS.CLAIM_HEADER_ICD_DIAGNOSIS_CODE_KEY)
        
    JOIN STAGEDATA.GRP_ICD_DIAGNOSIS
        ON (GRP_ICD_DIAGNOSIS.CODE_VALUE = CLAIM_HEADER_ICD_DIAGNOSIS_CODE_GRP.CODE_VALUE)
        
    LEFT OUTER JOIN DIMDATA.DIM_TPA_HIERARCHY
            ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = ICD_DIAGNOSIS.TPA_CLIENT_ID
            AND DIM_TPA_HIERARCHY.TPA_ID = ICD_DIAGNOSIS.TPA_ID
            AND DIM_TPA_HIERARCHY.TPA_DIV_ID = ICD_DIAGNOSIS.TPA_DIV_ID)

    LEFT OUTER JOIN DIMDATA.DIM_ICD_DIAGNOSIS
        ON (DIM_ICD_DIAGNOSIS.DIM_TPA_HIERARCHY_KEY = IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1)
        AND DIM_ICD_DIAGNOSIS.DATA_SOURCE_NAME = ICD_DIAGNOSIS.DATA_SOURCE_NAME
        AND DIM_ICD_DIAGNOSIS.ICD_VERSION_NBR = ICD_DIAGNOSIS.CODE_VERSION
        AND DIM_ICD_DIAGNOSIS.ICD_DIAGNOSIS_CODE = ICD_DIAGNOSIS.CODE_VALUE)

    LEFT OUTER JOIN STAGEDATA.REFERENCE_DATA_SINGULAR_VW ICD_QUALIFIER
        ON (ICD_QUALIFIER.TARGET_REFERENCE_SET = 'icdQualifier'
        AND ICD_QUALIFIER.TPA_CLIENT_ID = ICD_DIAGNOSIS.TPA_CLIENT_ID
        AND ICD_QUALIFIER.TPA_ID = ICD_DIAGNOSIS.TPA_ID
        AND ICD_QUALIFIER.TPA_DIV_ID = ICD_DIAGNOSIS.TPA_DIV_ID
        AND ICD_QUALIFIER.TARGET_VALUE = ICD_DIAGNOSIS.CODE_QUALIFIER)
;