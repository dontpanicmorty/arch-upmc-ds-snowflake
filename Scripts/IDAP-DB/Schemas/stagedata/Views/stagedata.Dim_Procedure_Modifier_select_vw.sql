CREATE OR REPLACE VIEW STAGEDATA.DIM_PROCEDURE_MODIFIER_SELECT_VW
AS
SELECT DISTINCT
DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY AS DIM_TPA_HIERARCHY_KEY
,REFERENCE_DATA_SINGULAR_VW.DATA_SOURCE_NAME
,REFERENCE_DATA_SINGULAR_VW.TARGET_VALUE AS PROCEDURE_MODIFIER_CODE
,REFERENCE_DATA_SINGULAR_VW.TARGET_DESC AS PROCEDURE_MODIFIER_DESC

FROM STAGEDATA.REFERENCE_DATA_SINGULAR_VW REFERENCE_DATA_SINGULAR_VW
    JOIN (SELECT TPA_KEY, DATA_SOURCE_NAME, TARGET_VALUE, MAX(EFFECTIVE_START_DATE) AS EFFECTIVE_START_DATE
            FROM STAGEDATA.REFERENCE_DATA_SINGULAR_VW
            WHERE TARGET_REFERENCE_SET = 'procedureModifier'
            GROUP BY TPA_KEY, DATA_SOURCE_NAME, TARGET_VALUE) CURRENT_RECORD
        ON (CURRENT_RECORD.TPA_KEY = REFERENCE_DATA_SINGULAR_VW.TPA_KEY
        AND CURRENT_RECORD.DATA_SOURCE_NAME = REFERENCE_DATA_SINGULAR_VW.DATA_SOURCE_NAME
        AND CURRENT_RECORD.TARGET_VALUE = REFERENCE_DATA_SINGULAR_VW.TARGET_VALUE
        AND CURRENT_RECORD.EFFECTIVE_START_DATE = REFERENCE_DATA_SINGULAR_VW.EFFECTIVE_START_DATE)

    JOIN DIMDATA.DIM_TPA_HIERARCHY
        ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = REFERENCE_DATA_SINGULAR_VW.TPA_CLIENT_ID
        AND DIM_TPA_HIERARCHY.TPA_ID = REFERENCE_DATA_SINGULAR_VW.TPA_ID
        AND DIM_TPA_HIERARCHY.TPA_DIV_ID = REFERENCE_DATA_SINGULAR_VW.TPA_DIV_ID)
WHERE REFERENCE_DATA_SINGULAR_VW.TARGET_REFERENCE_SET = 'procedureModifier'
AND REFERENCE_DATA_SINGULAR_VW.DATA_SOURCE_NAME NOT IN
    (SELECT DISTINCT DATA_SOURCE_NAME FROM RAWDATA.DATAHUB_CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE)

UNION ALL

SELECT DISTINCT
DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY AS DIM_TPA_HIERARCHY_KEY
,DATAHUB_CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE.DATA_SOURCE_NAME
,DATAHUB_CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE.CODE_VALUE AS PROCEDURE_MODIFIER_CODE
,DATAHUB_CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE.CODE_DESC AS PROCEDURE_MODIFIER_DESC

FROM RAWDATA.DATAHUB_CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE
    JOIN DIMDATA.DIM_TPA_HIERARCHY
        ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = DATAHUB_CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE.TPA_CLIENT_ID
        AND DIM_TPA_HIERARCHY.TPA_ID = DATAHUB_CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE.TPA_ID
        AND DIM_TPA_HIERARCHY.TPA_DIV_ID = DATAHUB_CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE.TPA_DIV_ID)
;