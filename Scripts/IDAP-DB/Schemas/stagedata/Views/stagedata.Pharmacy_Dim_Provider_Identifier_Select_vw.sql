CREATE OR REPLACE VIEW STAGEDATA.PHARMACY_DIM_PROVIDER_IDENTIFIER_SELECT_VW
AS
SELECT
'N/A-UPMCHP_DATAHUB' AS MD5_VALUE_TEXT
,DIM_PROVIDER.DIM_PROVIDER_KEY
,IDENTIFIERS.VALUE:identifierName::string AS IDENTIFIER_NAME
,IDENTIFIERS.VALUE:identifierNbr::string AS IDENTIFIER_NBR
,DIM_PROVIDER.SOURCE_SYSTEM
FROM RAWDATA.DATAHUB_PHARMACY_DETAIL_BASE
    JOIN DIMDATA.DIM_PROVIDER
        ON (DIM_PROVIDER.SOURCE_SYSTEM = 'UPMCHP_DATAHUB'
        AND DIM_PROVIDER.TPA_CLIENT_ID = DATAHUB_PHARMACY_DETAIL_BASE.TPA_CLIENT_ID
        AND DIM_PROVIDER.TPA_ID = DATAHUB_PHARMACY_DETAIL_BASE.TPA_ID
        AND DIM_PROVIDER.TPA_DIVISION_ID = DATAHUB_PHARMACY_DETAIL_BASE.TPA_DIV_ID
        AND DIM_PROVIDER.DATA_SOURCE_NAME = DATAHUB_PHARMACY_DETAIL_BASE.DATA_SOURCE_NAME
        AND DIM_PROVIDER.SOURCE_PROVIDER_NBR = DATAHUB_PHARMACY_DETAIL_BASE.PROVIDER_ID)
, LATERAL FLATTEN(DATAHUB_PHARMACY_DETAIL_BASE.PHARMACY_IDENTIFIER_ARRAY) IDENTIFIERS

UNION ALL

SELECT
'N/A-UPMCHP_DATAHUB' AS MD5_VALUE_TEXT
,DIM_PROVIDER.DIM_PROVIDER_KEY
,IDENTIFIERS.VALUE:identifierName::string AS IDENTIFIER_NAME
,IDENTIFIERS.VALUE:identifierNbr::string AS IDENTIFIER_NBR
,DIM_PROVIDER.SOURCE_SYSTEM
FROM RAWDATA.DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE
    JOIN DIMDATA.DIM_PROVIDER
        ON (DIM_PROVIDER.SOURCE_SYSTEM = 'UPMCHP_DATAHUB'
        AND DIM_PROVIDER.TPA_CLIENT_ID = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.TPA_CLIENT_ID
        AND DIM_PROVIDER.TPA_ID = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.TPA_ID
        AND DIM_PROVIDER.TPA_DIVISION_ID = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.TPA_DIV_ID
        AND DIM_PROVIDER.DATA_SOURCE_NAME = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.DATA_SOURCE_NAME
        AND DIM_PROVIDER.SOURCE_PROVIDER_NBR = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.PROVIDER_ID)
, LATERAL FLATTEN(DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.PRESCRIBER_IDENTIFIER_ARRAY) IDENTIFIERS
;