CREATE OR REPLACE VIEW STAGEDATA.REFERENCE_DATA_SINGULAR_CURRENT_VW
AS
SELECT
RDS.*
FROM STAGEDATA.REFERENCE_DATA_SINGULAR_VW RDS
    JOIN (
        SELECT
        REFERENCE_DATA_SINGULAR_KEY
        ,ROW_NUMBER() OVER 
            (PARTITION BY 
                TPA_KEY, DATA_SOURCE_NAME, TARGET_REFERENCE_SET, SOURCE_VALUE, SOURCE_VERSION, LINE_OF_BUSINESS_CODE, LANGUAGE_NAME, EFFECTIVE_START_DATE 
            ORDER BY TPA_KEY, DATA_SOURCE_NAME, TARGET_REFERENCE_SET, SOURCE_VALUE, SOURCE_VERSION, LINE_OF_BUSINESS_CODE, LANGUAGE_NAME, EFFECTIVE_START_DATE, INSERT_DATETIME DESC
            ) AS RN
        FROM STAGEDATA.REFERENCE_DATA_SINGULAR_VW
        ) CURRENT_RECORD
    ON (CURRENT_RECORD.REFERENCE_DATA_SINGULAR_KEY = RDS.REFERENCE_DATA_SINGULAR_KEY
    AND CURRENT_RECORD.RN = 1)
;