CREATE OR REPLACE VIEW STAGEDATA.GRP_PROCEDURE_MODIFIER_SELECT_VW
AS
SELECT
GRP_PROCEDURE_MODIFIER.GRP_PROCEDURE_MODIFIER_KEY
,IFNULL(DIM_PROCEDURE_MODIFIER.DIM_PROCEDURE_MODIFIER_KEY,1) AS DIM_PROCEDURE_MODIFIER_KEY
,PROCEDURE_MODIFIER.CODE_POSITION AS PROCEDURE_MODIFIER_POSITION_NBR
,PROCEDURE_MODIFIER.CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE_KEY
FROM STAGEDATA.CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE PROCEDURE_MODIFIER
    JOIN STAGEDATA.CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE_GRP
        ON (CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE_GRP.CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE_KEY = PROCEDURE_MODIFIER.CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE_KEY)

    JOIN STAGEDATA.GRP_PROCEDURE_MODIFIER
        ON (GRP_PROCEDURE_MODIFIER.CODE_VALUE = CLAIM_DETAIL_PROCEDURE_MODIFIER_CODE_GRP.CODE_VALUE)

    LEFT OUTER JOIN DIMDATA.DIM_TPA_HIERARCHY
            ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = PROCEDURE_MODIFIER.TPA_CLIENT_ID
            AND DIM_TPA_HIERARCHY.TPA_ID = PROCEDURE_MODIFIER.TPA_ID
            AND DIM_TPA_HIERARCHY.TPA_DIV_ID = PROCEDURE_MODIFIER.TPA_DIV_ID)

    LEFT OUTER JOIN DIMDATA.DIM_PROCEDURE_MODIFIER
        ON (DIM_PROCEDURE_MODIFIER.DIM_TPA_HIERARCHY_KEY = IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1)
        AND DIM_PROCEDURE_MODIFIER.DATA_SOURCE_NAME = PROCEDURE_MODIFIER.DATA_SOURCE_NAME
        AND DIM_PROCEDURE_MODIFIER.PROCEDURE_MODIFIER_CODE = PROCEDURE_MODIFIER.CODE_VALUE)
;