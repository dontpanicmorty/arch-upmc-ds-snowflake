CREATE OR REPLACE VIEW STAGEDATA.BRIDGE_CLAIM_DETAIL_FINANCIAL_SERVICE_CATEGORY_SELECT_VW
AS
SELECT DISTINCT
DIM_CLAIM_DETAIL_KEY,
DIM_FINANCIAL_SERVICE_CATEGORY_KEY
FROM STAGEDATA.FSS_DECISION_DATA
JOIN DIMDATA.DIM_FINANCIAL_SERVICE_CATEGORY
    ON FSS_DECISION_DATA.SUBGROUP = DIM_FINANCIAL_SERVICE_CATEGORY.FINANCIAL_SERVICE_SUBGRP_CODE
    AND FSS_DECISION_DATA.DECISION_STEP = DIM_FINANCIAL_SERVICE_CATEGORY.FINANCIAL_SERVICE_DECISION_STEP
;