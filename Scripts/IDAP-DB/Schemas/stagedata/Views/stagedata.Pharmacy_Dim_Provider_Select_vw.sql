        AND DIM_PROVIDER_ESI.TPA_DIVISION_ID = DATAHUB_PHARMACY_DETAIL_BASE.TPA_DIV_ID
        AND DIM_PROVIDER_ESI.DATA_SOURCE_NAME = 'ESI'
        AND DIM_PROVIDER_ESI.SOURCE_PROVIDER_NBR = DATAHUB_PHARMACY_DETAIL_BASE.PROVIDER_ID
        AND DIM_PROVIDER_ESI.PROVIDER_TYPE_DESC = DATAHUB_PHARMACY_DETAIL_BASE.PROVIDER_TYPE_NAME
        AND UPPER(DIM_PROVIDER_ESI.PRACTITIONER_LAST_NAME) = UPPER(DATAHUB_PHARMACY_DETAIL_BASE.LAST_NAME))

UNION ALL

