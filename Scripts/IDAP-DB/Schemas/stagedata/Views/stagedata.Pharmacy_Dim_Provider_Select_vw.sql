CREATE OR REPLACE VIEW STAGEDATA.PHARMACY_DIM_PROVIDER_SELECT_VW 
AS
SELECT
'N/A-UPMCHP-DATAHUB' AS MD5_VALUE_TEXT
,TO_TIMESTAMP_TZ('1900-01-01') AS ROW_EFFECTIVE_DATETIME
,TO_TIMESTAMP_TZ('9999-12-31') AS ROW_EXPIRATION_DATETIME
,TRUE AS IS_CURRENTROW_FLAG
,DATAHUB_PHARMACY_DETAIL_BASE.DATA_SOURCE_NAME
,DATAHUB_PHARMACY_DETAIL_BASE.PROVIDER_ID
,DATAHUB_PHARMACY_DETAIL_BASE.TPA_CLIENT_ID
,DATAHUB_PHARMACY_DETAIL_BASE.TPA_ID
,DATAHUB_PHARMACY_DETAIL_BASE.TPA_DIV_ID AS TPA_DIVISION_ID
,CASE (DATAHUB_PHARMACY_DETAIL_BASE.PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN 1
    WHEN 'Facility' THEN 2
    WHEN 'Medical Group' THEN 3
    WHEN 'Pharmacy' THEN 4
    ELSE 0
END AS PROVIDER_TYPE_CODE
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.PROVIDER_TYPE_NAME, 'Unknown') AS PROVIDER_TYPE_DESC
,0 AS PROVIDER_ROLE_TYPE_CODE 
,'Unknown' AS PROVIDER_ROLE_TYPE_DESC
,DATAHUB_PHARMACY_DETAIL_BASE.PHARMACY_NAME AS PROVIDER_FULL_NAME
,CASE (PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.LAST_NAME,'')
    ELSE 'n/a'
END AS PRACTITIONER_LAST_NAME
,CASE (PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.FIRST_NAME,'')
    ELSE 'n/a'
END AS PRACTITIONER_FIRST_NAME
,CASE (PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.MIDDLE_NAME,'')
    ELSE 'n/a'
END AS PRACTITIONER_MIDDLE_NAME
,CASE (PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.MIDDLE_INITIAL_NAME,'')
    ELSE 'n/a'
END AS PRACTITIONER_MIDDLE_INITIAL
,CASE (PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.SUFFIX_NAME,'')
    ELSE 'n/a'
END AS PRACTITIONER_NAME_SUFFIX
,CASE (PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.GENDER_CODE,'U')
    ELSE 'n/a'
END AS PRACTITIONER_GENDER_CODE 
,CASE (PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.GENDER_NAME,'Unknown')
    ELSE 'n/a'
END AS PRACTITIONER_GENDER_NAME 
,DATAHUB_PHARMACY_DETAIL_BASE.DATE_OF_BIRTH AS PRACTITIONER_BIRTH_DATE
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.TAX_ID_NBR,'') AS MEDICAL_GROUP_TIN_NBR
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.UPIN_NBR,'') AS PRACTITIONER_UPIN_NBR
,CASE (PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.SOCIAL_SECURITY_NBR,'Unknown')
    ELSE 'n/a'
END AS PRACTITIONER_SSN_NBR
,CASE (PROVIDER_TYPE_NAME)
    WHEN 'Practitioner' THEN IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.DEGREE_TEXT,'Unknown')
    ELSE 'n/a'
END AS PRACTITIONER_DEGREE
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.EMAIL_ADDRESS,'Unknown') AS PROVIDER_EMAIL_ADDRESS
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.WEBSITE_URL,'Unknown') AS PROVIDER_WEBSITE_URL
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.PRIMARY_SPECIALTY_NAME,'Unknown') AS PRIMARY_SPECIALTY_NAME
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.PRIMARY_PHO_CODE, 0) AS PRIMARY_PHO_CODE
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.PRIMARY_PHO_NAME,'Unknown') AS PRIMARY_PHO_NAME
,DATAHUB_PHARMACY_DETAIL_BASE.PRIMARY_PHO_TERMINATION_DATE AS PRIMARY_PHO_TERMINATION_DATE
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.SECONDARY_PHO_CODE, 0) AS SECONDARY_PHO_CODE
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.SECONDARY_PHO_NAME,'Unknown') AS SECONDARY_PHO_NAME
,DATAHUB_PHARMACY_DETAIL_BASE.SECONDARY_PHO_TERMINATION_DATE AS SECONDARY_PHO_TERMINATION_DATE
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.TERTIARY_PHO_CODE,0) AS TERTIARY_PHO_CODE
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.TERTIARY_PHO_NAME,'Unknown') AS TERTIARY_PHO_NAME
,DATAHUB_PHARMACY_DETAIL_BASE.TERTIARY_PHO_TERMINATION_DATE AS TERTIARY_PHO_TERMINATION_DATE
,DATAHUB_PHARMACY_DETAIL_BASE.PROVIDER_START_DATE
,NULL AS FACILITY_INCEPTION_DATE
,DATAHUB_PHARMACY_DETAIL_BASE.ACTIVE_IND AS PROVIDER_ACTIVE_IND
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.LOCUM_TENENS_IND,'U') AS PRACTITIONER_LOCUM_TENENS_IND
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.INVISIBLE_PROVIDER_IND,'U') AS INVISIBLE_PROVIDER_IND
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.TEMPORARY_PROVIDER_IND,'U') AS TEMPORARY_PROVIDER_IND
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.PA_MEDICAID_IND,'U') AS PA_MEDICAID_IND
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.PP_ACA_ENHANCED_PAY_IND,'U') AS PP_ACA_ENHANCED_PAY_IND
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.MALPRACTICE_COVERAGE_IND,'U') AS HAS_MALPRACTICE_INSURANCE_IND
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.OWNERSHIP_STATUS_CODE, 0) AS OWNERSHIP_STATUS_CODE
,IFNULL(DATAHUB_PHARMACY_DETAIL_BASE.OWNERSHIP_STATUS_DESC,'Unknown') AS OWNERSHIP_STATUS_DESC
,DATAHUB_PHARMACY_DETAIL_BASE.URI
,DATAHUB_PHARMACY_DETAIL_BASE.PROVIDER_ID AS SOURCE_PROVIDER_NBR
,DATAHUB_PHARMACY_DETAIL_BASE.HUB_PROVIDER_HKEY AS SOURCE_ID
,'UPMCHP_DATAHUB' AS SOURCE_SYSTEM
,TO_BOOLEAN(IFF((DIM_PROVIDER_MATCHING_DATASOURCE.DIM_PROVIDER_KEY IS NOT NULL OR DIM_PROVIDER_ESI.DIM_PROVIDER_KEY IS NOT NULL), TRUE, FALSE)) AS HAS_MATCH_FROM_SQL_SERVER
,COALESCE(DIM_PROVIDER_ESI.DIM_PROVIDER_KEY, DIM_PROVIDER_MATCHING_DATASOURCE.DIM_PROVIDER_KEY) AS SQL_SERVER_DIM_PROVIDER_KEY

FROM RAWDATA.DATAHUB_PHARMACY_DETAIL_BASE

    LEFT OUTER JOIN DIMDATA.DIM_PROVIDER DIM_PROVIDER_MATCHING_DATASOURCE
        ON (DIM_PROVIDER_MATCHING_DATASOURCE.SOURCE_SYSTEM = 'SQLSERVER'
        AND DIM_PROVIDER_MATCHING_DATASOURCE.IS_CURRENTROW_FLAG = TRUE
        AND DIM_PROVIDER_MATCHING_DATASOURCE.IS_LOGICAL_DELETE_FLAG = FALSE
        AND DIM_PROVIDER_MATCHING_DATASOURCE.TPA_CLIENT_ID = DATAHUB_PHARMACY_DETAIL_BASE.TPA_CLIENT_ID
        AND DIM_PROVIDER_MATCHING_DATASOURCE.TPA_ID = DATAHUB_PHARMACY_DETAIL_BASE.TPA_ID
        AND DIM_PROVIDER_MATCHING_DATASOURCE.TPA_DIVISION_ID = DATAHUB_PHARMACY_DETAIL_BASE.TPA_DIV_ID
        AND DIM_PROVIDER_MATCHING_DATASOURCE.DATA_SOURCE_NAME = DATAHUB_PHARMACY_DETAIL_BASE.DATA_SOURCE_NAME
        AND DIM_PROVIDER_MATCHING_DATASOURCE.SOURCE_PROVIDER_NBR = DATAHUB_PHARMACY_DETAIL_BASE.PROVIDER_ID)

    LEFT OUTER JOIN DIMDATA.DIM_PROVIDER DIM_PROVIDER_ESI
        ON (DIM_PROVIDER_ESI.SOURCE_SYSTEM = 'SQLSERVER'
        AND DIM_PROVIDER_ESI.IS_CURRENTROW_FLAG = TRUE
        AND DIM_PROVIDER_ESI.IS_LOGICAL_DELETE_FLAG = FALSE
        AND DIM_PROVIDER_ESI.TPA_CLIENT_ID = DATAHUB_PHARMACY_DETAIL_BASE.TPA_CLIENT_ID
