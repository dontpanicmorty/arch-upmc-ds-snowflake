CREATE OR REPLACE VIEW STAGEDATA.DIM_PLACE_OF_SERVICE_SELECT_VW
AS
SELECT
IFNULL(TPA.DIM_TPA_HIERARCHY_KEY,1) AS DIM_TPA_HIERARCHY_KEY
,RDS_POS.SOURCE_VALUE AS PLACE_OF_SERVICE_CODE
,RDS_POS.TARGET_DESC AS PLACE_OF_SERVICE_DESC
,RDS_ST.SOURCE_VALUE AS SERVICE_TYPE_CODE
,RDS_ST.TARGET_DESC AS SERVICE_TYPE_DESC
,RDS_LC.SOURCE_VALUE AS LOCATION_CODE
,RDS_LC.TARGET_DESC AS LOCATION_DESC
FROM STAGEDATA.REFERENCE_DATA_SINGULAR_VW RDS_POS
    JOIN (SELECT TPA_KEY, DATA_SOURCE_NAME, SOURCE_VALUE, MAX(EFFECTIVE_START_DATE) AS EFFECTIVE_START_DATE
            FROM STAGEDATA.REFERENCE_DATA_SINGULAR_VW
            WHERE TARGET_REFERENCE_SET = 'placeOfService'
            GROUP BY TPA_KEY, DATA_SOURCE_NAME, SOURCE_VALUE) POS_CURRENT_RECORD
        ON (POS_CURRENT_RECORD.TPA_KEY = RDS_POS.TPA_KEY
        AND POS_CURRENT_RECORD.DATA_SOURCE_NAME = RDS_POS.DATA_SOURCE_NAME
        AND POS_CURRENT_RECORD.SOURCE_VALUE = RDS_POS.SOURCE_VALUE
        AND POS_CURRENT_RECORD.EFFECTIVE_START_DATE = RDS_POS.EFFECTIVE_START_DATE)

    LEFT OUTER JOIN DIMDATA.DIM_TPA_HIERARCHY TPA
        ON (TPA.TPA_CLIENT_ID = RDS_POS.TPA_CLIENT_ID
        AND TPA.TPA_ID = RDS_POS.TPA_ID
        AND TPA.TPA_DIV_ID = RDS_POS.TPA_DIV_ID)

    JOIN STAGEDATA.REFERENCE_DATA_SINGULAR_VW RDS_ST
        JOIN (SELECT TPA_KEY, DATA_SOURCE_NAME, SOURCE_VALUE, MAX(EFFECTIVE_START_DATE) AS EFFECTIVE_START_DATE
                FROM STAGEDATA.REFERENCE_DATA_SINGULAR_VW
                WHERE TARGET_REFERENCE_SET = 'serviceType'
                GROUP BY TPA_KEY, DATA_SOURCE_NAME, SOURCE_VALUE) ST_CURRENT_RECORD
            ON (ST_CURRENT_RECORD.TPA_KEY = RDS_ST.TPA_KEY
            AND ST_CURRENT_RECORD.DATA_SOURCE_NAME = RDS_ST.DATA_SOURCE_NAME
            AND ST_CURRENT_RECORD.SOURCE_VALUE = RDS_ST.SOURCE_VALUE
            AND ST_CURRENT_RECORD.EFFECTIVE_START_DATE = RDS_ST.EFFECTIVE_START_DATE)
        ON (RDS_ST.TARGET_REFERENCE_SET = 'serviceType'
        AND RDS_ST.DATA_SOURCE_NAME = 'all'
        AND RDS_ST.TPA_KEY = RDS_POS.TPA_KEY)

    JOIN STAGEDATA.REFERENCE_DATA_SINGULAR_VW RDS_LC
        JOIN (SELECT TPA_KEY, DATA_SOURCE_NAME, SOURCE_VALUE, MAX(EFFECTIVE_START_DATE) AS EFFECTIVE_START_DATE
                FROM STAGEDATA.REFERENCE_DATA_SINGULAR_VW
                WHERE TARGET_REFERENCE_SET = 'locationCode'
                GROUP BY TPA_KEY, DATA_SOURCE_NAME, SOURCE_VALUE) LC_CURRENT_RECORD
            ON (LC_CURRENT_RECORD.TPA_KEY = RDS_LC.TPA_KEY
            AND LC_CURRENT_RECORD.DATA_SOURCE_NAME = RDS_LC.DATA_SOURCE_NAME
            AND LC_CURRENT_RECORD.SOURCE_VALUE = RDS_LC.SOURCE_VALUE
            AND LC_CURRENT_RECORD.EFFECTIVE_START_DATE = RDS_LC.EFFECTIVE_START_DATE)
        ON (RDS_LC.TARGET_REFERENCE_SET = 'locationCode'
        AND RDS_LC.DATA_SOURCE_NAME = 'all'
        AND RDS_LC.TPA_KEY = RDS_POS.TPA_KEY)

WHERE RDS_POS.TARGET_REFERENCE_SET = 'placeOfService'
AND (TPA.TPA_CLIENT_ID, TPA.TPA_ID, TPA.TPA_DIV_ID, PLACE_OF_SERVICE_CODE, SERVICE_TYPE_CODE, LOCATION_CODE) NOT IN 
        (SELECT DISTINCT 
            DATAHUB_CLAIM_DETAIL_BASE.TPA_CLIENT_ID
            ,DATAHUB_CLAIM_DETAIL_BASE.TPA_ID
            ,DATAHUB_CLAIM_DETAIL_BASE.TPA_DIV_ID
            ,DATAHUB_CLAIM_HEADER_BASE.PLACE_OF_SERVICE_CODE
            ,DATAHUB_CLAIM_DETAIL_BASE.SERVICE_TYPE_CODE
            ,DATAHUB_CLAIM_DETAIL_BASE.LOCATION_CODE
        FROM RAWDATA.DATAHUB_CLAIM_DETAIL_BASE
            JOIN RAWDATA.DATAHUB_CLAIM_HEADER_BASE
                ON (DATAHUB_CLAIM_DETAIL_BASE.HUB_CLAIM_HKEY = DATAHUB_CLAIM_HEADER_BASE.HUB_CLAIM_HKEY)
        )

UNION ALL

SELECT DISTINCT 
IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY,1) AS DIM_TPA_HIERARCHY_KEY
,DATAHUB_CLAIM_HEADER_BASE.PLACE_OF_SERVICE_CODE
,DATAHUB_CLAIM_HEADER_BASE.PLACE_OF_SERVICE_DESC
,DATAHUB_CLAIM_DETAIL_BASE.SERVICE_TYPE_CODE 
,DATAHUB_CLAIM_DETAIL_BASE.SERVICE_TYPE_DESC
,DATAHUB_CLAIM_DETAIL_BASE.LOCATION_CODE
,DATAHUB_CLAIM_DETAIL_BASE.LOCATION_DESC
FROM RAWDATA.DATAHUB_CLAIM_DETAIL_BASE
    JOIN RAWDATA.DATAHUB_CLAIM_HEADER_BASE
        ON (DATAHUB_CLAIM_DETAIL_BASE.HUB_CLAIM_HKEY = DATAHUB_CLAIM_HEADER_BASE.HUB_CLAIM_HKEY)
    JOIN DIMDATA.DIM_TPA_HIERARCHY
        ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_CLIENT_ID
        AND DIM_TPA_HIERARCHY.TPA_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_ID
        AND DIM_TPA_HIERARCHY.TPA_DIV_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_DIV_ID)
;