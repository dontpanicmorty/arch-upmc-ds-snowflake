!set variable_substitution=true;
CREATE OR REPLACE VIEW STAGEDATA.FSS_CLAIMS_DATA_SELECT_VW(
	FACT_CLAIM_LINE_KEY,
 	FACT_CLAIM_LINE_LAST_UPDATED_DATETIME,
    DIM_CLAIM_HEADER_KEY,
    DIM_CLAIM_HEADER_LAST_UPDATED_DATETIME,
    DIM_CLAIM_DETAIL_KEY,
    DIM_CLAIM_DETAIL_LAST_UPDATED_DATETIME,
    CLAIM_NBR,
	CLAIM_LINE_NBR,
	CLAIM_SEQUENCE_NBR,
	PROCEDURE_ADJ_CODE,
	LOB_CODE,
	CPT4_CODE,
	REVENUE_CODE,
	ICD_DX_CODE,
	ICD_DX_VERSION,
	ICD_DX_GROUP,
	ICD_PROC_CODE,
	ICD_PROC_VERSION,
	BENEFIT_CATEGORY_CODE,
	LOCATION_CODE,
	SERVICE_TYPE,
	PLACE_OF_SERVICE_CODE,
	PROVIDER_TYPE_DESC,
	PROVIDER_TYPE,
	PROVIDER_SPECIALTY,
	HIAA_POS
) COMMENT='View of Data relevant to FSS Algorithm Processing'
 AS
SELECT 
  DISTINCT 
    FACT_CLAIM_LINE_KEY -- ClaimLineKey
    ,FACT_CLAIM_LINE.LAST_UPDATED_DATETIME AS FACT_CLAIM_LINE_LAST_UPDATED_DATETIME
    ,DIM_CLAIM_HEADER.DIM_CLAIM_HEADER_KEY --ClaimDetailKey
    ,DIM_CLAIM_HEADER.LAST_UPDATED_DATETIME AS DIM_CLAIM_HEADER_LAST_UPDATED_DATETIME
    ,DIM_CLAIM_DETAIL.DIM_CLAIM_DETAIL_KEY --ClaimDetailKey
    ,DIM_CLAIM_DETAIL.LAST_UPDATED_DATETIME AS DIM_CLAIM_DETAIL_LAST_UPDATED_DATETIME
    ,DIM_CLAIM_DETAIL.CLAIM_NBR --Matches in raw data to claimNbr
    ,DIM_CLAIM_DETAIL.CLAIM_LINE_NBR -- Matches in raw data to claimLineNbr
    ,DIM_CLAIM_DETAIL.CLAIM_SEQUENCE_NBR
    ,DIM_CLAIM_DETAIL.PROCEDURE_ADJ_CODE 
    ,DIM_PLAN.LOB_CODE
    ,DIM_CLAIM_PROCEDURE.PROCEDURE_CODE AS CPT4_CODE -- CPT/HCPCS Code
    ,DIM_REVENUE_PROCEDURE.REVENUE_CODE
    ,DIM_ICD_DIAGNOSIS.ICD_DIAGNOSIS_CODE AS ICD_DX_CODE -- ICD DX Code
    ,DIM_ICD_DIAGNOSIS.ICD_VERSION_NBR AS ICD_DX_VERSION
    ,DIM_ICD_DIAGNOSIS.ICD_DIAGNOSIS_GROUP_CODE AS ICD_DX_GROUP
    ,DIM_ICD_PROCEDURE.ICD_PROCEDURE_CODE AS ICD_PROC_CODE -- ICD Proc Code
    ,DIM_ICD_PROCEDURE.ICD_VERSION_NBR AS ICD_PROC_VERSION
    ,DIM_CLAIM_DETAIL.BENEFIT_CATEGORY_CODE AS BENEFIT_CATEGORY_CODE -- Benefit Category Code
    ,DIM_PLACE_OF_SERVICE.LOCATION_CODE AS LOCATION_CODE -- Location Type Code
    ,DIM_PLACE_OF_SERVICE.SERVICE_TYPE_CODE AS SERVICE_TYPE -- Service Type Code
    ,PLACE_OF_SERVICE_CODE -- Place of Service Code
    ,PROVIDER_TYPE_DESC
    ,CASE
        WHEN PROVIDER_TYPE_CODE = 1 THEN 'ID'
        WHEN PROVIDER_TYPE_CODE = 2 THEN 'FC'
        WHEN PROVIDER_TYPE_CODE = 3 THEN 'CL' -- Awaiting Feedback from Li if this mapping is okay.
        WHEN DIM_CLAIM_HEADER.CARE_TYPE_NAME = 'vision' THEN 'VN'
        ELSE 'UN'
    END AS PROVIDER_TYPE -- Provider Type
    ,DIM_CLAIM_HEADER.PROVIDER_SPECIALTY
    ,PLACE_OF_SERVICE_CODE AS HIAA_POS
FROM DIMDATA.FACT_CLAIM_LINE
LEFT JOIN DIMDATA.DIM_CLAIM_DETAIL
    ON DIM_CLAIM_DETAIL.DIM_CLAIM_DETAIL_KEY = FACT_CLAIM_LINE.DIM_CLAIM_DETAIL_KEY 
    AND DIM_CLAIM_DETAIL.IS_LOGICAL_DELETE_FLAG = FALSE 
LEFT JOIN DIMDATA.DIM_CLAIM_HEADER
    ON DIM_CLAIM_HEADER.DIM_CLAIM_HEADER_KEY = FACT_CLAIM_LINE.DIM_CLAIM_HEADER_KEY
    AND DIM_CLAIM_HEADER.IS_LOGICAL_DELETE_FLAG = FALSE
LEFT JOIN DIMDATA.DIM_CLAIM_PROCEDURE
    ON DIM_CLAIM_PROCEDURE.DIM_CLAIM_PROCEDURE_KEY = FACT_CLAIM_LINE.DIM_CLAIM_PROCEDURE_KEY
    AND DIM_CLAIM_PROCEDURE.IS_LOGICAL_DELETE_FLAG = FALSE
LEFT JOIN DIMDATA.GRP_ICD_DIAGNOSIS
    ON FACT_CLAIM_LINE.GRP_ICD_DIAGNOSIS_KEY = GRP_ICD_DIAGNOSIS.GRP_ICD_DIAGNOSIS_KEY 
    AND GRP_ICD_DIAGNOSIS.IS_LOGICAL_DELETE_FLAG = FALSE
LEFT JOIN DIMDATA.DIM_ICD_DIAGNOSIS
    ON DIM_ICD_DIAGNOSIS.DIM_ICD_DIAGNOSIS_KEY = GRP_ICD_DIAGNOSIS.DIM_ICD_DIAGNOSIS_KEY
    AND DIM_ICD_DIAGNOSIS.IS_LOGICAL_DELETE_FLAG = FALSE
LEFT JOIN DIMDATA.GRP_ICD_DIAGNOSIS_FLAT
    ON GRP_ICD_DIAGNOSIS.GRP_ICD_DIAGNOSIS_KEY = GRP_ICD_DIAGNOSIS_FLAT.GRP_ICD_DIAGNOSIS_KEY
    AND GRP_ICD_DIAGNOSIS_FLAT.IS_LOGICAL_DELETE_FLAG = FALSE
LEFT JOIN DIMDATA.GRP_ICD_PROCEDURE
    ON FACT_CLAIM_LINE.GRP_ICD_PROCEDURE_KEY = GRP_ICD_PROCEDURE.GRP_ICD_PROCEDURE_KEY
    AND GRP_ICD_PROCEDURE.IS_LOGICAL_DELETE_FLAG = FALSE
LEFT JOIN DIMDATA.DIM_ICD_PROCEDURE
    ON GRP_ICD_PROCEDURE.DIM_ICD_PROCEDURE_KEY = DIM_ICD_PROCEDURE.DIM_ICD_PROCEDURE_KEY
    AND DIM_ICD_PROCEDURE.IS_LOGICAL_DELETE_FLAG = FALSE
LEFT JOIN DIMDATA.DIM_PROVIDER 
    ON FACT_CLAIM_LINE.DIM_RENDERING_PROVIDER_KEY = DIM_PROVIDER.DIM_PROVIDER_KEY 
    AND DIM_PROVIDER.IS_LOGICAL_DELETE_FLAG = FALSE
LEFT JOIN DIMDATA.DIM_PLACE_OF_SERVICE
    ON DIM_PLACE_OF_SERVICE.DIM_PLACE_OF_SERVICE_KEY = FACT_CLAIM_LINE.DIM_PLACE_OF_SERVICE_KEY 
    AND DIM_PLACE_OF_SERVICE.IS_LOGICAL_DELETE_FLAG = FALSE
LEFT JOIN DIMDATA.DIM_REVENUE_PROCEDURE
    ON DIM_REVENUE_PROCEDURE.DIM_REVENUE_PROCEDURE_KEY = FACT_CLAIM_LINE.DIM_REVENUE_PROCEDURE_KEY
    AND DIM_REVENUE_PROCEDURE.IS_LOGICAL_DELETE_FLAG = FALSE
LEFT JOIN DIMDATA.DIM_PLAN
    ON FACT_CLAIM_LINE.DIM_PLAN_KEY = DIM_PLAN.DIM_PLAN_KEY
WHERE DIM_CLAIM_DETAIL.DATA_SOURCE_NAME = 'MC400Upm'
//AND DIM_ICD_DIAGNOSIS.ICD_DIAGNOSIS_CODE = GRP_ICD_DIAGNOSIS_FLAT.DIAGNOSIS_01 --only want to use primary icd_diagnosis_code value for each claim detail record
;
!set variable_substitution=false;