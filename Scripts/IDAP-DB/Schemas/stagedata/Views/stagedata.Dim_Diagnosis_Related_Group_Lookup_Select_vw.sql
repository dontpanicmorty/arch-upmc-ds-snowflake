CREATE OR REPLACE VIEW STAGEDATA.DIM_DIAGNOSIS_RELATED_GROUP_LOOKUP_SELECT_VW
COMMENT = 'View to create staging table that links a datahub claim header record to the proper drg code'
AS
SELECT
DATAHUB_CLAIM_HEADER_BASE.HUB_CLAIM_HKEY
,DATAHUB_CLAIM_HEADER_BASE.DIAGNOSIS_RELATED_GROUP_CODE
,DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS
,DATAHUB_CLAIM_HEADER_BASE.LINE_OF_BUSINESS_CODE
,DATAHUB_CLAIM_HEADER_BASE.GROUP_NBR
,DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE
,COALESCE(LOB_MA_CHC.DIM_DIAGNOSIS_RELATED_GROUP_KEY, LOB_CHIP_CM.DIM_DIAGNOSIS_RELATED_GROUP_KEY, LOB_MC.DIM_DIAGNOSIS_RELATED_GROUP_KEY, LOB_ALL.DIM_DIAGNOSIS_RELATED_GROUP_KEY) AS DIM_DIAGNOSIS_RELATED_GROUP_KEY
FROM RAWDATA.DATAHUB_CLAIM_HEADER_BASE
    LEFT OUTER JOIN
        (
        --LOB_MA_CHC
        SELECT DATAHUB_CLAIM_HEADER_BASE.HUB_CLAIM_HKEY, IFNULL(DIM_DIAGNOSIS_RELATED_GROUP_MS.DIM_DIAGNOSIS_RELATED_GROUP_KEY, DIM_DIAGNOSIS_RELATED_GROUP_APR.DIM_DIAGNOSIS_RELATED_GROUP_KEY) AS DIM_DIAGNOSIS_RELATED_GROUP_KEY
        FROM RAWDATA.DATAHUB_CLAIM_HEADER_BASE
                LEFT JOIN DIMDATA.DIM_DIAGNOSIS_RELATED_GROUP DIM_DIAGNOSIS_RELATED_GROUP_MS
                    ON ((DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS IS NULL OR DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS='0')
                    AND DIM_DIAGNOSIS_RELATED_GROUP_MS.EFFECTIVE_START_DATE <> TO_DATE('1950-01-01','YYYY-MM-DD')
                    AND DIM_DIAGNOSIS_RELATED_GROUP_MS.DIAGNOSIS_RELATED_GROUP_TYPE_CODE = 'MS'
                    AND DIM_DIAGNOSIS_RELATED_GROUP_MS.DIAGNOSIS_RELATED_GROUP_CODE = DATAHUB_CLAIM_HEADER_BASE.DIAGNOSIS_RELATED_GROUP_CODE
                    AND DIM_DIAGNOSIS_RELATED_GROUP_MS.EFFECTIVE_START_DATE <= DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE
                    AND DIM_DIAGNOSIS_RELATED_GROUP_MS.EFFECTIVE_END_DATE >= DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE
                    )                           
                
                LEFT JOIN DIMDATA.DIM_DIAGNOSIS_RELATED_GROUP DIM_DIAGNOSIS_RELATED_GROUP_APR
                    ON ((DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS IS NOT NULL AND DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS<>'0')
                    AND DIM_DIAGNOSIS_RELATED_GROUP_APR.EFFECTIVE_START_DATE <> TO_DATE('1950-01-01','YYYY-MM-DD')
                    AND DIM_DIAGNOSIS_RELATED_GROUP_APR.DIAGNOSIS_RELATED_GROUP_TYPE_CODE = 'APR'
                    AND DIM_DIAGNOSIS_RELATED_GROUP_APR.DIAGNOSIS_RELATED_GROUP_CODE = DATAHUB_CLAIM_HEADER_BASE.DIAGNOSIS_RELATED_GROUP_CODE
                    AND DIM_DIAGNOSIS_RELATED_GROUP_APR.SEVERITY_OF_ILLNESS_NBR = DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS
                    AND DIM_DIAGNOSIS_RELATED_GROUP_APR.EFFECTIVE_START_DATE <= DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE
                    AND DIM_DIAGNOSIS_RELATED_GROUP_APR.EFFECTIVE_END_DATE >= DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE
                    )

                WHERE DATAHUB_CLAIM_HEADER_BASE.LINE_OF_BUSINESS_CODE IN ('MA','CHC')

        ) LOB_MA_CHC
        ON (LOB_MA_CHC.HUB_CLAIM_HKEY = DATAHUB_CLAIM_HEADER_BASE.HUB_CLAIM_HKEY)

    LEFT OUTER JOIN
        (--LOB_CHIP_CM
            SELECT DATAHUB_CLAIM_HEADER_BASE.HUB_CLAIM_HKEY, IFNULL(DIM_DIAGNOSIS_RELATED_GROUP_MS.DIM_DIAGNOSIS_RELATED_GROUP_KEY, IFNULL(DIM_DIAGNOSIS_RELATED_GROUP_KIDS.DIM_DIAGNOSIS_RELATED_GROUP_KEY, DIM_DIAGNOSIS_RELATED_GROUP_NOT_KIDS.DIM_DIAGNOSIS_RELATED_GROUP_KEY)) AS DIM_DIAGNOSIS_RELATED_GROUP_KEY
            FROM RAWDATA.DATAHUB_CLAIM_HEADER_BASE
            
            LEFT JOIN DIMDATA.DIM_DIAGNOSIS_RELATED_GROUP DIM_DIAGNOSIS_RELATED_GROUP_MS
                    ON ((DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS IS NULL OR DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS='0')
                    AND DIM_DIAGNOSIS_RELATED_GROUP_MS.EFFECTIVE_START_DATE <> TO_DATE('1950-01-01','YYYY-MM-DD')
                    AND DIM_DIAGNOSIS_RELATED_GROUP_MS.DIAGNOSIS_RELATED_GROUP_TYPE_CODE = 'MS'
                    AND DIM_DIAGNOSIS_RELATED_GROUP_MS.DIAGNOSIS_RELATED_GROUP_CODE = DATAHUB_CLAIM_HEADER_BASE.DIAGNOSIS_RELATED_GROUP_CODE
                    AND DIM_DIAGNOSIS_RELATED_GROUP_MS.EFFECTIVE_START_DATE <= DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE
                    AND DIM_DIAGNOSIS_RELATED_GROUP_MS.EFFECTIVE_END_DATE >= DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE
                    )                           
                
            LEFT JOIN DIMDATA.DIM_DIAGNOSIS_RELATED_GROUP DIM_DIAGNOSIS_RELATED_GROUP_KIDS
                    ON ((DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS IS NOT NULL AND DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS<>'0')
                    AND DIM_DIAGNOSIS_RELATED_GROUP_KIDS.EFFECTIVE_START_DATE <> TO_DATE('1950-01-01','YYYY-MM-DD')
                    AND SUBSTRING(DATAHUB_CLAIM_HEADER_BASE.GROUP_NBR, 1, 4) = 'KIDS'
                    AND DIM_DIAGNOSIS_RELATED_GROUP_KIDS.DIAGNOSIS_RELATED_GROUP_TYPE_CODE = 'APR'
                    AND DIM_DIAGNOSIS_RELATED_GROUP_KIDS.DIAGNOSIS_RELATED_GROUP_CODE = DATAHUB_CLAIM_HEADER_BASE.DIAGNOSIS_RELATED_GROUP_CODE
                    AND DIM_DIAGNOSIS_RELATED_GROUP_KIDS.SEVERITY_OF_ILLNESS_NBR = DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS
                    AND DIM_DIAGNOSIS_RELATED_GROUP_KIDS.EFFECTIVE_START_DATE <= DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE
                    AND DIM_DIAGNOSIS_RELATED_GROUP_KIDS.EFFECTIVE_END_DATE >= DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE
                    )

            LEFT JOIN DIMDATA.DIM_DIAGNOSIS_RELATED_GROUP DIM_DIAGNOSIS_RELATED_GROUP_NOT_KIDS
                    ON ((DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS IS NOT NULL AND DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS<>'0')
                    AND DIM_DIAGNOSIS_RELATED_GROUP_NOT_KIDS.EFFECTIVE_START_DATE <> TO_DATE('1950-01-01','YYYY-MM-DD')
                    AND SUBSTRING(DATAHUB_CLAIM_HEADER_BASE.GROUP_NBR, 1, 4) <> 'KIDS'
                    AND DIM_DIAGNOSIS_RELATED_GROUP_NOT_KIDS.DIAGNOSIS_RELATED_GROUP_CODE = DATAHUB_CLAIM_HEADER_BASE.DIAGNOSIS_RELATED_GROUP_CODE
                    AND DIM_DIAGNOSIS_RELATED_GROUP_NOT_KIDS.SEVERITY_OF_ILLNESS_NBR = DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS
                    AND DIM_DIAGNOSIS_RELATED_GROUP_NOT_KIDS.EFFECTIVE_START_DATE <= DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE
                    AND DIM_DIAGNOSIS_RELATED_GROUP_NOT_KIDS.EFFECTIVE_END_DATE >= DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE
                    )                   
                
            WHERE DATAHUB_CLAIM_HEADER_BASE.LINE_OF_BUSINESS_CODE IN ('CHIP','CM')
            
        ) LOB_CHIP_CM
        ON (LOB_CHIP_CM.HUB_CLAIM_HKEY = DATAHUB_CLAIM_HEADER_BASE.HUB_CLAIM_HKEY)

    LEFT OUTER JOIN
        (
            SELECT DATAHUB_CLAIM_HEADER_BASE.HUB_CLAIM_HKEY, IFNULL(DIM_DIAGNOSIS_RELATED_GROUP_MS.DIM_DIAGNOSIS_RELATED_GROUP_KEY, DIM_DIAGNOSIS_RELATED_GROUP_APR.DIM_DIAGNOSIS_RELATED_GROUP_KEY) AS DIM_DIAGNOSIS_RELATED_GROUP_KEY
            FROM RAWDATA.DATAHUB_CLAIM_HEADER_BASE
            
                LEFT JOIN DIMDATA.DIM_DIAGNOSIS_RELATED_GROUP DIM_DIAGNOSIS_RELATED_GROUP_MS
                    ON ((DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS IS NULL OR DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS='0')
                    AND DIM_DIAGNOSIS_RELATED_GROUP_MS.EFFECTIVE_START_DATE <> TO_DATE('1950-01-01','YYYY-MM-DD')
                    AND DIM_DIAGNOSIS_RELATED_GROUP_MS.DIAGNOSIS_RELATED_GROUP_TYPE_CODE = 'MS'
                    AND DIM_DIAGNOSIS_RELATED_GROUP_MS.DIAGNOSIS_RELATED_GROUP_CODE = DATAHUB_CLAIM_HEADER_BASE.DIAGNOSIS_RELATED_GROUP_CODE
                    AND DIM_DIAGNOSIS_RELATED_GROUP_MS.EFFECTIVE_START_DATE <= DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE
                    AND DIM_DIAGNOSIS_RELATED_GROUP_MS.EFFECTIVE_END_DATE >= DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE
                    )                           
                
                LEFT JOIN DIMDATA.DIM_DIAGNOSIS_RELATED_GROUP DIM_DIAGNOSIS_RELATED_GROUP_APR
                    ON ((DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS IS NOT NULL AND DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS<>'0')
                    AND DIM_DIAGNOSIS_RELATED_GROUP_APR.EFFECTIVE_START_DATE <> TO_DATE('1950-01-01','YYYY-MM-DD')
                    AND DIM_DIAGNOSIS_RELATED_GROUP_APR.DIAGNOSIS_RELATED_GROUP_TYPE_CODE = 'APR'
                    AND DIM_DIAGNOSIS_RELATED_GROUP_APR.SEVERITY_OF_ILLNESS_NBR = DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS
                    AND DIM_DIAGNOSIS_RELATED_GROUP_APR.DIAGNOSIS_RELATED_GROUP_CODE = DATAHUB_CLAIM_HEADER_BASE.DIAGNOSIS_RELATED_GROUP_CODE
                    AND DIM_DIAGNOSIS_RELATED_GROUP_APR.EFFECTIVE_START_DATE <= DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE
                    AND DIM_DIAGNOSIS_RELATED_GROUP_APR.EFFECTIVE_END_DATE >= DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE
                    )   
                            
        WHERE DATAHUB_CLAIM_HEADER_BASE.LINE_OF_BUSINESS_CODE IN ('MC')

        ) LOB_MC
        ON (LOB_MC.HUB_CLAIM_HKEY = DATAHUB_CLAIM_HEADER_BASE.HUB_CLAIM_HKEY)

    LEFT OUTER JOIN DIMDATA.DIM_DIAGNOSIS_RELATED_GROUP LOB_ALL
        ON (LOB_ALL.EFFECTIVE_START_DATE = '1950-01-01'
        AND LOB_ALL.DIAGNOSIS_RELATED_GROUP_CODE = DATAHUB_CLAIM_HEADER_BASE.DIAGNOSIS_RELATED_GROUP_CODE
        AND LOB_ALL.SEVERITY_OF_ILLNESS_NBR = IFNULL(DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS, 0)
        AND LOB_ALL.EFFECTIVE_START_DATE <= DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE
        AND LOB_ALL.EFFECTIVE_END_DATE >= DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE)

WHERE DATAHUB_CLAIM_HEADER_BASE.DIAGNOSIS_RELATED_GROUP_CODE IS NOT NULL
;
