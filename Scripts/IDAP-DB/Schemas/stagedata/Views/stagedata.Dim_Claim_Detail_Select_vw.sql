CREATE OR REPLACE VIEW STAGEDATA.DIM_CLAIM_DETAIL_SELECT_VW
AS 
SELECT
    CLAIM_DETAIL_VW.TPA_CLIENT_ID
    ,CLAIM_DETAIL_VW.TPA_ID
    ,CLAIM_DETAIL_VW.TPA_DIV_ID
    ,CLAIM_DETAIL_VW.DATA_SOURCE_NAME
    ,CLAIM_DETAIL_VW.CLAIM_NBR
    ,CLAIM_DETAIL_VW.CLAIM_LINE_NBR
    ,IFNULL(CLAIM_DETAIL_VW.CLAIM_SEQUENCE_NBR, 'n/a') AS CLAIM_SEQUENCE_NBR
    ,IFNULL(CLAIM_DETAIL_VW.PROCEDURE_ADJ,'n/a') AS PROCEDURE_ADJ_CODE
    ,CONCAT(CLAIM_DETAIL_VW.TPA_CLIENT_ID,
            CLAIM_DETAIL_VW.TPA_ID,
            CLAIM_DETAIL_VW.TPA_DIV_ID,
            CLAIM_DETAIL_VW.DATA_SOURCE_NAME,
            CLAIM_DETAIL_VW.CLAIM_NBR
            ) AS DATA_HUB_UNIVERSAL_CLAIM_ID
    ,IFNULL(CLAIM_DETAIL_VW.PAY_STATUS_CODE,'n/a') AS CLAIM_PAYSTATUS_CODE
    ,IFNULL(CLAIM_PAYSTATUS_DESC.TARGET_DESC,'n/a') AS CLAIM_PAYSTATUS_DESC
    ,CLAIM_DETAIL_VW.CHECK_NBR
    ,CLAIM_DETAIL_VW.TRANSACTION_TYPE_CODE
    ,CLAIM_DETAIL_VW.TRANSACTION_TYPE_DESC
    ,IFNULL(CLAIM_DETAIL_VW.CLEAN_CLAIM_IND,'Unknown') AS CLEAN_CLAIM_IND
    ,IFNULL(CLAIM_DETAIL_VW.SERVICE_STATUS_CODE,'n/a') AS SERVICE_STATUS_CODE
    ,IFNULL(CLAIM_DETAIL_VW.SERVICE_STATUS_DESC,'n/a') AS SERVICE_STATUS_DESC
    ,CASE 
        WHEN UPPER(CLAIM_HEADER_VW.CARE_TYPE_NAME) = 'DENTAL' 
        THEN CLAIM_DETAIL_VW.TOOTH_ID ELSE 'n/a'
    END AS TOOTH_ID
    ,IFNULL(CLAIM_DETAIL_VW.TOOTH_SURFACE_ID,'n/a') AS TOOTH_SURFACE_ID
    ,IFNULL(CLAIM_DETAIL_VW.TOOTH_SURFACE_02,'n/a') AS TOOTH_SURFACE_02
    ,IFNULL(CLAIM_DETAIL_VW.TOOTH_SURFACE_03,'n/a') AS TOOTH_SURFACE_03
    ,IFNULL(CLAIM_DETAIL_VW.TOOTH_SURFACE_04,'n/a') AS TOOTH_SURFACE_04
    ,IFNULL(CLAIM_DETAIL_VW.TOOTH_SURFACE_05,'n/a') AS TOOTH_SURFACE_05
    ,IFNULL(CLAIM_DETAIL_VW.QUADRANT_ARCH,'n/a') AS QUADRANT_ARCH_ID
    ,CASE
        WHEN CLAIM_DETAIL_VW.QUADRANT_ARCH IS NULL THEN 'n/a'
        ELSE IFNULL(QUADRANT_ARCH_DESC.TARGET_DESC,'Unknown')
    END AS QUADRANT_ARCH_DESC
    ,NULL AS TOOTH_QUADRANT_CODE
    ,NULL AS TOOTH_QUADRANT_DESC
    ,NULL AS TOOTH_ARCH_CODE
    ,NULL AS TOOTH_ARCH_DESC
    ,IFNULL(TRIM(CLAIM_DETAIL_VW.BENEFIT_LEVEL_CODE),'n/a') AS BENEFIT_LEVEL_CODE
    ,CASE
        WHEN TRIM(CLAIM_DETAIL_VW.BENEFIT_LEVEL_CODE) IS NULL THEN 'n/a'
        ELSE IFNULL(BENEFIT_LEVEL_DESC.TARGET_DESC,'Unknown')
    END AS BENEFIT_LEVEL_DESC
    ,'n/a' AS BENEFIT_LEVEL_PAYMENT_TYPE_NAME
    ,IFNULL(CLAIM_DETAIL_VW.BENEFIT_CATEGORY_CODE,'n/a') AS BENEFIT_CATEGORY_CODE
    ,CASE
        WHEN CLAIM_DETAIL_VW.BENEFIT_CATEGORY_CODE IS NULL THEN 'n/a'
        ELSE IFNULL(BENEFIT_CATEGORY_DESC.TARGET_DESC,'Unknown')
    END AS BENEFIT_CATEGORY_DESC
    ,'MARKLOGIC' as SOURCE_SYSTEM
    ,TO_VARCHAR(CLAIM_DETAIL_VW.CLAIM_DETAIL_KEY) AS SOURCE_ID
    ,NULL AS AUTHORIZATION_NBR
    ,NULL AS AUTHORIZATION_LINE_NBR
    ,NULL AS CMS_CURRENT_ITERATION_FLAG

FROM STAGEDATA.CLAIM_DETAIL_VW
    JOIN STAGEDATA.CLAIM_HEADER_VW
        ON (CLAIM_HEADER_VW.UNIVERSAL_CLAIM_ID = CLAIM_DETAIL_VW.UNIVERSAL_CLAIM_ID)

    LEFT OUTER JOIN STAGEDATA.REFERENCE_DATA_SINGULAR_CURRENT_VW CLAIM_PAYSTATUS_DESC
        ON (CLAIM_PAYSTATUS_DESC.REFERENCE_KEY = CLAIM_DETAIL_VW.PAY_STATUS_DESC_KEY)

    LEFT OUTER JOIN STAGEDATA.REFERENCE_DATA_SINGULAR_CURRENT_VW QUADRANT_ARCH_DESC
        ON (QUADRANT_ARCH_DESC.TARGET_REFERENCE_SET = 'quadrantArchCode' 
        AND QUADRANT_ARCH_DESC.TPA_KEY = CLAIM_DETAIL_VW.TPA_KEY 
        AND QUADRANT_ARCH_DESC.DATA_SOURCE_NAME = CLAIM_DETAIL_VW.DATA_SOURCE_NAME 
        AND QUADRANT_ARCH_DESC.SOURCE_VALUE = CLAIM_DETAIL_VW.QUADRANT_ARCH)

    LEFT OUTER JOIN STAGEDATA.REFERENCE_DATA_SINGULAR_CURRENT_VW BENEFIT_LEVEL_DESC
        ON (BENEFIT_LEVEL_DESC.TARGET_REFERENCE_SET = 'benefitLevel' 
        AND BENEFIT_LEVEL_DESC.TPA_KEY = CLAIM_DETAIL_VW.TPA_KEY 
        AND BENEFIT_LEVEL_DESC.DATA_SOURCE_NAME = CLAIM_DETAIL_VW.DATA_SOURCE_NAME 
        AND BENEFIT_LEVEL_DESC.SOURCE_VALUE = CLAIM_DETAIL_VW.BENEFIT_LEVEL_CODE)

    LEFT OUTER JOIN STAGEDATA.REFERENCE_DATA_SINGULAR_CURRENT_VW BENEFIT_CATEGORY_DESC
        ON (BENEFIT_CATEGORY_DESC.TARGET_REFERENCE_SET = 'benefitCategory' 
        AND BENEFIT_CATEGORY_DESC.TPA_KEY = CLAIM_DETAIL_VW.TPA_KEY 
        AND BENEFIT_CATEGORY_DESC.DATA_SOURCE_NAME = CLAIM_DETAIL_VW.DATA_SOURCE_NAME 
        AND BENEFIT_CATEGORY_DESC.SOURCE_VALUE = CLAIM_DETAIL_VW.BENEFIT_CATEGORY_CODE)

WHERE CLAIM_DETAIL_VW.DATA_SOURCE_NAME NOT IN (SELECT DISTINCT DATA_SOURCE_NAME FROM RAWDATA.DATAHUB_CLAIM_HEADER_BASE
       )
       
        AND
        (
            claim_header_vw.CLAIM_TYPE_CODE NOT IN ('P','A') -- Filter out Pre-D claims, which shouldn't be with claims data.
            OR claim_header_vw.CLAIM_TYPE_CODE IS NULL -- This line needed because Claim_Type_Code coming from NVA is NULL, which isn't caught in the above line.
        )
------------------------------------
UNION ALL
------------------------------------

-- The records from UPMCHP_DATAHUB
SELECT
    DATAHUB_CLAIM_DETAIL_BASE.TPA_CLIENT_ID
    ,DATAHUB_CLAIM_DETAIL_BASE.TPA_ID
    ,DATAHUB_CLAIM_DETAIL_BASE.TPA_DIV_ID
    ,DATAHUB_CLAIM_DETAIL_BASE.DATA_SOURCE_NAME
    ,DATAHUB_CLAIM_DETAIL_BASE.CLAIM_NBR
    ,DATAHUB_CLAIM_DETAIL_BASE.CLAIM_LINE_NBR
    ,DATAHUB_CLAIM_DETAIL_BASE.CLAIM_LINE_SEQ_NBR AS CLAIM_SEQUENCE_NBR
    ,DATAHUB_CLAIM_DETAIL_BASE.CLAIM_LINE_PROCEDURE_ADJ_CODE AS PROCEDURE_ADJ_CODE
    ,CONCAT(DATAHUB_CLAIM_DETAIL_BASE.TPA_CLIENT_ID,
            DATAHUB_CLAIM_DETAIL_BASE.TPA_ID,
            DATAHUB_CLAIM_DETAIL_BASE.TPA_DIV_ID,
            DATAHUB_CLAIM_DETAIL_BASE.DATA_SOURCE_NAME,
            DATAHUB_CLAIM_DETAIL_BASE.CLAIM_NBR
            ) AS DATA_HUB_UNIVERSAL_CLAIM_ID
    ,IFNULL(DATAHUB_CLAIM_DETAIL_BASE.PAY_STATUS_CODE,'UNK') AS CLAIM_PAYSTATUS_CODE
    ,IFF(DATAHUB_CLAIM_DETAIL_BASE.PAY_STATUS_CODE IS NULL, 'Unknown', DATAHUB_CLAIM_DETAIL_BASE.PAY_STATUS_DESC) AS CLAIM_PAYSTATUS_DESC
    ,DATAHUB_CLAIM_DETAIL_BASE.CHECK_NUMBER AS CHECK_NBR
    ,DATAHUB_CLAIM_DETAIL_BASE.TRANSACTION_TYPE_CODE AS TRANSACTION_TYPE_CODE
    ,DATAHUB_CLAIM_DETAIL_BASE.TRANSACTION_TYPE_DESC AS TRANSACTION_TYPE_DESC
    ,IFNULL(DATAHUB_CLAIM_DETAIL_BASE.CLEAN_CLAIM_IND, 'U') AS CLEAN_CLAIM_IND
    ,IFNULL(DATAHUB_CLAIM_DETAIL_BASE.SERVICE_STATUS_CODE, 'UNK') AS SERVICE_STATUS_CODE
    ,IFF(DATAHUB_CLAIM_DETAIL_BASE.SERVICE_STATUS_CODE IS NULL, 'Unknown', DATAHUB_CLAIM_DETAIL_BASE.SERVICE_STATUS_DESC) AS SERVICE_STATUS_DESC
    ,IFF(UPPER(DATAHUB_CLAIM_DETAIL_BASE.CARE_TYPE_NAME) <> 'DENTAL', 'n/a', DATAHUB_CLAIM_DETAIL_BASE.TOOTH_ID) AS TOOTH_ID
    ,IFF(UPPER(DATAHUB_CLAIM_DETAIL_BASE.CARE_TYPE_NAME) <> 'DENTAL', 'n/a', DATAHUB_CLAIM_DETAIL_BASE.TOOTH_SURFACE_ARRAY[0]) AS TOOTH_SURFACE_ID
    ,IFF(UPPER(DATAHUB_CLAIM_DETAIL_BASE.CARE_TYPE_NAME) <> 'DENTAL', 'n/a', DATAHUB_CLAIM_DETAIL_BASE.TOOTH_SURFACE_ARRAY[1]) AS TOOTH_SURFACE_02
    ,IFF(UPPER(DATAHUB_CLAIM_DETAIL_BASE.CARE_TYPE_NAME) <> 'DENTAL', 'n/a', DATAHUB_CLAIM_DETAIL_BASE.TOOTH_SURFACE_ARRAY[2]) AS TOOTH_SURFACE_03
    ,IFF(UPPER(DATAHUB_CLAIM_DETAIL_BASE.CARE_TYPE_NAME) <> 'DENTAL', 'n/a', DATAHUB_CLAIM_DETAIL_BASE.TOOTH_SURFACE_ARRAY[3]) AS TOOTH_SURFACE_04
    ,IFF(UPPER(DATAHUB_CLAIM_DETAIL_BASE.CARE_TYPE_NAME) <> 'DENTAL', 'n/a', DATAHUB_CLAIM_DETAIL_BASE.TOOTH_SURFACE_ARRAY[4]) AS TOOTH_SURFACE_05
    ,'deprecated column' AS QUADRANT_ARCH_ID --this is 2 columns in the datahub.. legacy mc400 stuff
    ,'deprecated column' AS QUADRANT_ARCH_DESC --this is 2 columns in the datahub.. legacy mc400 stuff
    ,IFF(UPPER(DATAHUB_CLAIM_DETAIL_BASE.CARE_TYPE_NAME) <> 'DENTAL', 'n/a', DATAHUB_CLAIM_DETAIL_BASE.TOOTH_QUADRANT) AS TOOTH_QUADRANT_CODE
    ,IFF(UPPER(DATAHUB_CLAIM_DETAIL_BASE.CARE_TYPE_NAME) <> 'DENTAL', 'n/a', DATAHUB_CLAIM_DETAIL_BASE.TOOTH_QUADRANT_DESC) AS TOOTH_QUADRANT_DESC
    ,IFF(UPPER(DATAHUB_CLAIM_DETAIL_BASE.CARE_TYPE_NAME) <> 'DENTAL', 'n/a', DATAHUB_CLAIM_DETAIL_BASE.TOOTH_ARCH) AS TOOTH_ARCH_CODE
    ,IFF(UPPER(DATAHUB_CLAIM_DETAIL_BASE.CARE_TYPE_NAME) <> 'DENTAL', 'n/a', DATAHUB_CLAIM_DETAIL_BASE.TOOTH_ARCH_DESC) AS TOOTH_ARCH_DESC
    ,DATAHUB_CLAIM_DETAIL_BASE.BENEFIT_LEVEL_CODE
    ,DATAHUB_CLAIM_DETAIL_BASE.BENEFIT_LEVEL_DESC
    ,NULL AS BENEFIT_LEVEL_PAYMENT_TYPE_NAME --not in datahub yet, and NULL in dim currently
    ,DATAHUB_CLAIM_DETAIL_BASE.BENEFIT_CATEGORY_CODE
    ,DATAHUB_CLAIM_DETAIL_BASE.BENEFIT_CATEGORY_CODE_DESC AS BENEFIT_CATEGORY_DESC
    ,'UPMCHP_DATAHUB' AS SOURCE_SYSTEM
    ,DATAHUB_CLAIM_DETAIL_BASE.HUB_CLAIM_DETAIL_HKEY AS SOURCE_ID
    ,DATAHUB_CLAIM_DETAIL_BASE.AUTHORIZATION_NBR
    ,DATAHUB_CLAIM_DETAIL_BASE.AUTHORIZATION_LINE_NBR
    ,DATAHUB_CLAIM_DETAIL_BASE.CMS_CURRENT_ITERATION_FLAG
FROM RAWDATA.DATAHUB_CLAIM_DETAIL_BASE
    JOIN RAWDATA.DATAHUB_CLAIM_HEADER_BASE
    ON (DATAHUB_CLAIM_DETAIL_BASE.HUB_CLAIM_HKEY = DATAHUB_CLAIM_HEADER_BASE.HUB_CLAIM_HKEY)
WHERE DATAHUB_CLAIM_HEADER_BASE.IS_PREDETERMINATION_CLAIM_FLAG = FALSE -- Filter out Pre-D claims, which shouldn't be with claims data.
;