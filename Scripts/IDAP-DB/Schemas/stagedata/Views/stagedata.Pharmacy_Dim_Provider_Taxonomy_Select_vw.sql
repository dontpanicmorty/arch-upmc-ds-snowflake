CREATE OR REPLACE VIEW STAGEDATA.PHARMACY_DIM_PROVIDER_TAXONOMY_SELECT_VW
AS 
SELECT DISTINCT
PRIMARY_TAXONOMY_CODE AS TAXONOMY_CODE,
PRIMARY_TAXONOMY_TYPE AS TAXONOMY_TYPE,
PRIMARY_TAXONOMY_CLASS AS TAXONOMY_CLASS,
PRIMARY_TAXONOMY_SPECIALIZATION AS TAXONOMY_SPECIALIZATION
FROM RAWDATA.DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE
WHERE PRIMARY_TAXONOMY_CODE IS NOT NULL
AND (TAXONOMY_TYPE IS NOT NULL OR TAXONOMY_CLASS IS NOT NULL OR TAXONOMY_SPECIALIZATION IS NOT NULL)
;