CREATE OR REPLACE VIEW STAGEDATA.GRP_ICD_PROCEDURE_SELECT_VW
AS
SELECT
GRP_ICD_PROCEDURE.GRP_ICD_PROCEDURE_KEY
,IFNULL(DIM_ICD_PROCEDURE.DIM_ICD_PROCEDURE_KEY,1) AS DIM_ICD_PROCEDURE_KEY
,ICD_PROCEDURE.CODE_POSITION AS ICD_POSITION_NBR
,ICD_PROCEDURE.CODE_QUALIFIER AS ICD_QUALIFIER_CODE
,ICD_PROCEDURE.CODE_VERSION AS ICD_VERSION_NBR
,CASE ICD_PROCEDURE.CODE_QUALIFIER
    WHEN 'n/a' THEN 'n/a'
    ELSE ICD_QUALIFIER.TARGET_DESC
END AS ICD_QUALIFIER_DESC
,ICD_PROCEDURE.CLAIM_HEADER_ICD_PROCEDURE_CODE_KEY
FROM STAGEDATA.CLAIM_HEADER_ICD_PROCEDURE_CODE ICD_PROCEDURE

    JOIN STAGEDATA.CLAIM_HEADER_ICD_PROCEDURE_CODE_GRP 
        ON (CLAIM_HEADER_ICD_PROCEDURE_CODE_GRP.CLAIM_HEADER_ICD_PROCEDURE_CODE_KEY = ICD_PROCEDURE.CLAIM_HEADER_ICD_PROCEDURE_CODE_KEY)
        
    JOIN STAGEDATA.GRP_ICD_PROCEDURE
        ON (GRP_ICD_PROCEDURE.CODE_VALUE = CLAIM_HEADER_ICD_PROCEDURE_CODE_GRP.CODE_VALUE)

    LEFT OUTER JOIN DIMDATA.DIM_TPA_HIERARCHY
            ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = ICD_PROCEDURE.TPA_CLIENT_ID
            AND DIM_TPA_HIERARCHY.TPA_ID = ICD_PROCEDURE.TPA_ID
            AND DIM_TPA_HIERARCHY.TPA_DIV_ID = ICD_PROCEDURE.TPA_DIV_ID)

    LEFT OUTER JOIN DIMDATA.DIM_ICD_PROCEDURE
        ON (DIM_ICD_PROCEDURE.DIM_TPA_HIERARCHY_KEY = IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1)
        AND DIM_ICD_PROCEDURE.DATA_SOURCE_NAME = ICD_PROCEDURE.DATA_SOURCE_NAME
        AND DIM_ICD_PROCEDURE.ICD_VERSION_NBR = ICD_PROCEDURE.CODE_VERSION
        AND DIM_ICD_PROCEDURE.ICD_PROCEDURE_CODE = ICD_PROCEDURE.CODE_VALUE)

    LEFT OUTER JOIN STAGEDATA.REFERENCE_DATA_SINGULAR_VW ICD_QUALIFIER
        ON (ICD_QUALIFIER.TARGET_REFERENCE_SET = 'icdQualifier'
        AND ICD_QUALIFIER.TPA_CLIENT_ID = ICD_PROCEDURE.TPA_CLIENT_ID
        AND ICD_QUALIFIER.TPA_ID = ICD_PROCEDURE.TPA_ID
        AND ICD_QUALIFIER.TPA_DIV_ID = ICD_PROCEDURE.TPA_DIV_ID
        AND ICD_QUALIFIER.TARGET_VALUE = ICD_PROCEDURE.CODE_QUALIFIER)
;