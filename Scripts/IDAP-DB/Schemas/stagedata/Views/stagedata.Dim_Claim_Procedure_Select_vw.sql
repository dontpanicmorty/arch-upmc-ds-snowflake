CREATE OR REPLACE VIEW STAGEDATA.DIM_CLAIM_PROCEDURE_SELECT_VW
AS
SELECT DISTINCT
DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY AS DIM_TPA_HIERARCHY_KEY
,RDS.DATA_SOURCE_NAME AS DATA_SOURCE_NAME
,RDS.TARGET_VALUE AS PROCEDURE_CODE
,CASE WHEN LOWER(RDS.TARGET_VALUE) = 'needs mapped' --this was done becase of case-sensitive crap
    THEN 'needs mapped' 
    ELSE RDS.TARGET_DESC 
END AS PROCEDURE_CODE_SHORT_DESC
,CASE WHEN LOWER(RDS.TARGET_VALUE) = 'needs mapped'
    THEN 'needs mapped'
    ELSE IFNULL(RDS.TARGET_LONG_DESC,'undefined')
END AS PROCEDURE_CODE_LONG_DESC
,'undefined' AS PROCEDURE_CODE_SPANISH_DESC
FROM STAGEDATA.REFERENCE_DATA_SINGULAR_VW RDS
    JOIN (SELECT TARGET_REFERENCE_SET, TPA_KEY, DATA_SOURCE_NAME, TARGET_VALUE, EFFECTIVE_START_DATE, INSERT_DATETIME
            FROM (SELECT TARGET_REFERENCE_SET, TPA_KEY, DATA_SOURCE_NAME, TARGET_VALUE, EFFECTIVE_START_DATE, INSERT_DATETIME
                ,ROW_NUMBER() OVER (PARTITION BY TARGET_REFERENCE_SET, TPA_KEY, TARGET_VALUE ORDER BY DATA_SOURCE_NAME DESC, EFFECTIVE_START_DATE DESC, INSERT_DATETIME DESC) AS SOURCE_RANK
                FROM STAGEDATA.REFERENCE_DATA_SINGULAR_VW
                WHERE TARGET_REFERENCE_SET = 'procedureCode'
                )      
            WHERE SOURCE_RANK = 1 /*picking MC400Upm over Dnt as a hotfix until the procedureCode build is migrated away from markLogic*/
            ) CURRENT_RECORD
        ON (CURRENT_RECORD.TARGET_REFERENCE_SET = RDS.TARGET_REFERENCE_SET
        AND CURRENT_RECORD.TPA_KEY = RDS.TPA_KEY
        AND CURRENT_RECORD.DATA_SOURCE_NAME = RDS.DATA_SOURCE_NAME
        AND CURRENT_RECORD.TARGET_VALUE = RDS.TARGET_VALUE
        AND CURRENT_RECORD.EFFECTIVE_START_DATE = RDS.EFFECTIVE_START_DATE
        AND CURRENT_RECORD.INSERT_DATETIME = RDS.INSERT_DATETIME)

    JOIN DIMDATA.DIM_TPA_HIERARCHY
        ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = RDS.TPA_CLIENT_ID
        AND DIM_TPA_HIERARCHY.TPA_ID = RDS.TPA_ID
        AND DIM_TPA_HIERARCHY.TPA_DIV_ID = RDS.TPA_DIV_ID)

WHERE RDS.DATA_SOURCE_NAME NOT IN (SELECT DISTINCT DATA_SOURCE_NAME FROM RAWDATA.DATAHUB_CLAIM_DETAIL_BASE)

UNION ALL

SELECT DISTINCT
DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY AS DIM_TPA_HIERARCHY_KEY
,DATAHUB_CLAIM_DETAIL_BASE.DATA_SOURCE_NAME 
,DATAHUB_CLAIM_DETAIL_BASE.PROCEDURE_CODE
,DATAHUB_REFDATA_CLAIM_PROCEDURE_CODE.PROCEDURE_CODE_DESC
,DATAHUB_REFDATA_CLAIM_PROCEDURE_CODE.PROCEDURE_CODE_DESC_LONG AS PROCEDURE_CODE_LONG_DESC
,DATAHUB_REFDATA_CLAIM_PROCEDURE_CODE.PROCEDURE_CODE_SPANISH_DESC

FROM RAWDATA.DATAHUB_CLAIM_DETAIL_BASE
    JOIN RAWDATA.DATAHUB_REFDATA_CLAIM_PROCEDURE_CODE
        ON (DATAHUB_CLAIM_DETAIL_BASE.TPA_CLIENT_ID = DATAHUB_REFDATA_CLAIM_PROCEDURE_CODE.TPA_CLIENT_ID
        AND DATAHUB_CLAIM_DETAIL_BASE.TPA_ID = DATAHUB_REFDATA_CLAIM_PROCEDURE_CODE.TPA_ID
        AND DATAHUB_CLAIM_DETAIL_BASE.TPA_DIV_ID = DATAHUB_REFDATA_CLAIM_PROCEDURE_CODE.TPA_DIV_ID
        AND DATAHUB_CLAIM_DETAIL_BASE.DATA_SOURCE_NAME = DATAHUB_REFDATA_CLAIM_PROCEDURE_CODE.DATA_SOURCE_NAME
        AND DATAHUB_CLAIM_DETAIL_BASE.PROCEDURE_CODE = DATAHUB_REFDATA_CLAIM_PROCEDURE_CODE.PROCEDURE_CODE)
    JOIN DIMDATA.DIM_TPA_HIERARCHY
        ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_CLIENT_ID
        AND DIM_TPA_HIERARCHY.TPA_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_ID
        AND DIM_TPA_HIERARCHY.TPA_DIV_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_DIV_ID)
WHERE DATAHUB_CLAIM_DETAIL_BASE.PROCEDURE_CODE IS NOT NULL
;