CREATE OR REPLACE VIEW STAGEDATA.PHARMACY_DIM_PROVIDER_CONTACT_INFO_SELECT_VW 
AS
SELECT DISTINCT
'N/A-UPMCHP_DATAHUB' AS MD5_VALUE_TEXT
,DATAHUB_PHARMACY_DETAIL_BASE.PRIMARY_PHONE_NBR AS PROVIDER_PRIMARY_PHONE_NBR
,DATAHUB_PHARMACY_DETAIL_BASE.PRIMARY_PHONE_EXTENSION_NBR AS PROVIDER_PRIMARY_PHONE_EXTENSION_NBR
,DATAHUB_PHARMACY_DETAIL_BASE.PRIMARY_PHONE_NBR_FORMATTED AS PROVIDER_PRIMARY_PHONE_NBR_FORMATTED
,DATAHUB_PHARMACY_DETAIL_BASE.ALTERNATE_PHONE_NBR AS PROVIDER_ALTERNATE_PHONE_NBR
,DATAHUB_PHARMACY_DETAIL_BASE.ALTERNATE_PHONE_EXTENSION_NBR AS PROVIDER_ALTERNATE_PHONE_EXTENSION_NBR
,DATAHUB_PHARMACY_DETAIL_BASE.ALTERNATE_PHONE_NBR_FORMATTED AS PROVIDER_ALTERNATE_PHONE_NBR_FORMATTED
,DATAHUB_PHARMACY_DETAIL_BASE.FAX_NBR AS PROVIDER_FAX_NBR
,DATAHUB_PHARMACY_DETAIL_BASE.FAX_NBR_FORMATTED AS PROVIDER_FAX_NBR_FORMATTED
,DATAHUB_PHARMACY_DETAIL_BASE.INTERNATIONAL_PHONE_CODE AS PROVIDER_INTERNATIONAL_PHONE_CODE
,DATAHUB_PHARMACY_DETAIL_BASE.EMAIL_ADDRESS_TEXT AS PROVIDER_EMAIL_ADDRESS_TEXT
FROM RAWDATA.DATAHUB_PHARMACY_DETAIL_BASE
WHERE PROVIDER_PRIMARY_PHONE_NBR IS NOT NULL

UNION

SELECT DISTINCT
'N/A-UPMCHP_DATAHUB' AS MD5_VALUE_TEXT
,DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.MAILING_ADDRESS_PHONE_NBR AS PROVIDER_PRIMARY_PHONE_NBR
,DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.MAILING_ADDRESS_PHONE_EXTENSION_NBR AS PROVIDER_PRIMARY_PHONE_EXTENSION_NBR
,DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.MAILING_ADDRESS_PHONE_NBR_FORMATTED AS PROVIDER_PRIMARY_PHONE_NBR_FORMATTED
,'Unknown' AS PROVIDER_ALTERNATE_PHONE_NBR
,'Unknown' AS PROVIDER_ALTERNATE_PHONE_EXTENSION_NBR
,'Unknown' AS PROVIDER_ALTERNATE_PHONE_NBR_FORMATTED
,DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.MAILING_ADDRESS_FAX_NBR AS PROVIDER_FAX_NBR
,DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.MAILING_ADDRESS_FAX_NBR_FORMATTED AS PROVIDER_FAX_NBR_FORMATTED
,DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.INTERNATIONAL_PHONE_CODE AS PROVIDER_INTERNATIONAL_PHONE_CODE
,DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.EMAIL_ADDRESS_TEXT AS PROVIDER_EMAIL_ADDRESS_TEXT
FROM RAWDATA.DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE
WHERE MAILING_ADDRESS_PHONE_NBR IS NOT NULL

UNION

SELECT DISTINCT
'N/A-UPMCHP_DATAHUB' AS MD5_VALUE_TEXT
,DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.PRACTICE_ADDRESS_PHONE_NBR AS PROVIDER_PRIMARY_PHONE_NBR
,DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.PRACTICE_ADDRESS_PHONE_EXTENSION_NBR AS PROVIDER_PRIMARY_PHONE_EXTENSION_NBR
,DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.PRACTICE_ADDRESS_PHONE_NBR_FORMATTED AS PROVIDER_PRIMARY_PHONE_NBR_FORMATTED
,'Unknown' AS PROVIDER_ALTERNATE_PHONE_NBR
,'Unknown' AS PROVIDER_ALTERNATE_PHONE_EXTENSION_NBR
,'Unknown' AS PROVIDER_ALTERNATE_PHONE_NBR_FORMATTED
,DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.PRACTICE_ADDRESS_FAX_NBR AS PROVIDER_FAX_NBR
,DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.PRACTICE_ADDRESS_FAX_NBR_FORMATTED AS PROVIDER_FAX_NBR_FORMATTED
,DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.INTERNATIONAL_PHONE_CODE AS PROVIDER_INTERNATIONAL_PHONE_CODE
,DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.EMAIL_ADDRESS_TEXT AS PROVIDER_EMAIL_ADDRESS_TEXT
FROM RAWDATA.DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE
WHERE PRACTICE_ADDRESS_PHONE_NBR IS NOT NULL
;