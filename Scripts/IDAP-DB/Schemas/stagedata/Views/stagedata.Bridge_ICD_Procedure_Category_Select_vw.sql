CREATE OR REPLACE VIEW STAGEDATA.BRIDGE_ICD_PROCEDURE_CATEGORY_SELECT_VW
AS
SELECT DISTINCT
DIM_ICD_PROCEDURE.DIM_ICD_PROCEDURE_KEY
,DIM_ICD_CATEGORY.DIM_ICD_CATEGORY_KEY
FROM STAGEDATA.DIM_ICD_PROCEDURE_SELECT_VW
    JOIN DIMDATA.DIM_ICD_PROCEDURE
        ON (DIM_ICD_PROCEDURE.DIM_TPA_HIERARCHY_KEY = DIM_ICD_PROCEDURE_SELECT_VW.DIM_TPA_HIERARCHY_KEY
        AND DIM_ICD_PROCEDURE.DATA_SOURCE_NAME = DIM_ICD_PROCEDURE_SELECT_VW.DATA_SOURCE_NAME
        AND DIM_ICD_PROCEDURE.ICD_VERSION_NBR = DIM_ICD_PROCEDURE_SELECT_VW.ICD_VERSION_NBR
        AND DIM_ICD_PROCEDURE.ICD_PROCEDURE_CODE = DIM_ICD_PROCEDURE_SELECT_VW.ICD_PROCEDURE_CODE)
    ,LATERAL FLATTEN (mode => 'ARRAY', input => DIM_ICD_PROCEDURE_SELECT_VW.CHILD_IDS) CATEGORY
    JOIN STAGEDATA.DIM_ICD_CATEGORY_SELECT_VW
        ON (DIM_ICD_CATEGORY_SELECT_VW.REFERENCE_KEY = CATEGORY.VALUE::string)
    JOIN DIMDATA.DIM_ICD_CATEGORY
        ON (DIM_ICD_CATEGORY.DIM_TPA_HIERARCHY_KEY = DIM_ICD_CATEGORY_SELECT_VW.DIM_TPA_HIERARCHY_KEY
        AND DIM_ICD_CATEGORY.DATA_SOURCE_NAME = DIM_ICD_CATEGORY_SELECT_VW.DATA_SOURCE_NAME
        AND DIM_ICD_CATEGORY.ICD_VERSION_NBR = DIM_ICD_CATEGORY_SELECT_VW.ICD_VERSION_NBR
        AND DIM_ICD_CATEGORY.ICD_CATEGORY_CODE = DIM_ICD_CATEGORY_SELECT_VW.ICD_CATEGORY_CODE)
;

