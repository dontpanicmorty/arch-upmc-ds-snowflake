CREATE OR REPLACE VIEW STAGEDATA.DIM_PROCEDURE_CATEGORY_SELECT_VW
AS
SELECT
IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1) AS DIM_TPA_HIERARCHY_KEY
,RDS.DATA_SOURCE_NAME
,RDS.TARGET_VALUE AS PROCEDURE_CATEGORY_CODE
,RDS.TARGET_DESC AS PROCEDURE_CATEGORY_DESC
FROM STAGEDATA.REFERENCE_DATA_SINGULAR_VW RDS
JOIN (SELECT TPA_KEY, DATA_SOURCE_NAME, SOURCE_VERSION, TARGET_VALUE, MAX(EFFECTIVE_START_DATE) AS EFFECTIVE_START_DATE
        FROM STAGEDATA.REFERENCE_DATA_SINGULAR_VW
        WHERE TARGET_REFERENCE_SET = 'procedureCategory'
        GROUP BY TPA_KEY, DATA_SOURCE_NAME, SOURCE_VERSION, TARGET_VALUE) CURRENT_RECORD
    ON (CURRENT_RECORD.TPA_KEY = RDS.TPA_KEY
    AND CURRENT_RECORD.DATA_SOURCE_NAME = RDS.DATA_SOURCE_NAME
    AND EQUAL_NULL(CURRENT_RECORD.SOURCE_VERSION, RDS.SOURCE_VERSION)
    AND CURRENT_RECORD.TARGET_VALUE = RDS.TARGET_VALUE
    AND CURRENT_RECORD.EFFECTIVE_START_DATE = RDS.EFFECTIVE_START_DATE)

    LEFT OUTER JOIN DIMDATA.DIM_TPA_HIERARCHY
        ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = RDS.TPA_CLIENT_ID
        AND DIM_TPA_HIERARCHY.TPA_ID = RDS.TPA_ID
        AND DIM_TPA_HIERARCHY.TPA_DIV_ID = RDS.TPA_DIV_ID)
WHERE RDS.TARGET_REFERENCE_SET = 'procedureCategory'
AND RDS.DATA_SOURCE_NAME NOT IN
    (SELECT DISTINCT DATA_SOURCE_NAME FROM RAWDATA.DATAHUB_CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE)

UNION ALL

SELECT DISTINCT 
IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1) AS DIM_TPA_HIERARCHY_KEY
,DATAHUB_CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE.DATA_SOURCE_NAME
,DATAHUB_CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE.CATEGORY_CODE AS PROCEDURE_CATEGORY_CODE
,DATAHUB_CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE.CODE_DESC AS PROCEDURE_CATEGORY_DESC
FROM RAWDATA.DATAHUB_CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE
    LEFT OUTER JOIN DIMDATA.DIM_TPA_HIERARCHY
        ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = DATAHUB_CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE.TPA_CLIENT_ID
        AND DIM_TPA_HIERARCHY.TPA_ID = DATAHUB_CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE.TPA_ID
        AND DIM_TPA_HIERARCHY.TPA_DIV_ID = DATAHUB_CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE.TPA_DIV_ID)
;