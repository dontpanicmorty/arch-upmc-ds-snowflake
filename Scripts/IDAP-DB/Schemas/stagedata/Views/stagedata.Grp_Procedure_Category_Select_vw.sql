CREATE OR REPLACE VIEW STAGEDATA.GRP_PROCEDURE_CATEGORY_SELECT_VW
AS
SELECT
GRP_PROCEDURE_CATEGORY.GRP_PROCEDURE_CATEGORY_KEY
,IFNULL(DIM_PROCEDURE_CATEGORY.DIM_PROCEDURE_CATEGORY_KEY, 1) AS DIM_PROCEDURE_CATEGORY_KEY
,PROCEDURE_CATEGORY.CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE_KEY
FROM STAGEDATA.CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE PROCEDURE_CATEGORY
    JOIN STAGEDATA.CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE_GRP
        ON (CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE_GRP.CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE_KEY = PROCEDURE_CATEGORY.CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE_KEY)

    JOIN STAGEDATA.GRP_PROCEDURE_CATEGORY
        ON (GRP_PROCEDURE_CATEGORY.CODE_VALUE = CLAIM_DETAIL_PROCEDURE_CATEGORY_CODE_GRP.CODE_VALUE)

    LEFT OUTER JOIN DIMDATA.DIM_TPA_HIERARCHY
            ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = PROCEDURE_CATEGORY.TPA_CLIENT_ID
            AND DIM_TPA_HIERARCHY.TPA_ID = PROCEDURE_CATEGORY.TPA_ID
            AND DIM_TPA_HIERARCHY.TPA_DIV_ID = PROCEDURE_CATEGORY.TPA_DIV_ID)
            
    LEFT OUTER JOIN DIMDATA.DIM_PROCEDURE_CATEGORY
        ON (DIM_PROCEDURE_CATEGORY.DIM_TPA_HIERARCHY_KEY = IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1)
        AND DIM_PROCEDURE_CATEGORY.DATA_SOURCE_NAME = PROCEDURE_CATEGORY.DATA_SOURCE_NAME
        AND DIM_PROCEDURE_CATEGORY.PROCEDURE_CATEGORY_CODE = PROCEDURE_CATEGORY.CODE_VALUE)
;