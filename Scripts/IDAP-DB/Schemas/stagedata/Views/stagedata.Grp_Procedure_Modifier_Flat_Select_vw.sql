CREATE OR REPLACE VIEW STAGEDATA.GRP_PROCEDURE_MODIFIER_FLAT_SELECT_VW 
COMMENT='Pivots GRP_PROCEDURE_MODIFIER AND DIM_PROCEDURE_MODIFIER with modifier codes as columns instead of rows'
AS
SELECT GRP_PROCEDURE_MODIFIER_KEY,
LAST_UPDATED_DATETIME,
PROCEDURE_MODIFIER_01,
PROCEDURE_MODIFIER_02,
PROCEDURE_MODIFIER_03,
PROCEDURE_MODIFIER_04
FROM
(
SELECT GRP_PROCEDURE_MODIFIER_KEY
        ,MAX(GRP_PROCEDURE_MODIFIER.LAST_UPDATED_DATETIME) AS LAST_UPDATED_DATETIME
        ,DIM_PROCEDURE_MODIFIER.PROCEDURE_MODIFIER_CODE
        ,CONCAT('PROCEDURE_MODIFIER_', TO_CHAR(PROCEDURE_MODIFIER_POSITION_NBR)) AS MOD_COL
FROM DIMDATA.GRP_PROCEDURE_MODIFIER
    INNER JOIN DIMDATA.DIM_PROCEDURE_MODIFIER
        ON GRP_PROCEDURE_MODIFIER.DIM_PROCEDURE_MODIFIER_KEY = DIM_PROCEDURE_MODIFIER.DIM_PROCEDURE_MODIFIER_KEY
    WHERE GRP_PROCEDURE_MODIFIER.IS_LOGICAL_DELETE_FLAG = FALSE
    AND DIM_PROCEDURE_MODIFIER.IS_LOGICAL_DELETE_FLAG = FALSE
	GROUP BY GRP_PROCEDURE_MODIFIER_KEY
	    ,DIM_PROCEDURE_MODIFIER.PROCEDURE_MODIFIER_CODE
        ,CONCAT('PROCEDURE_MODIFIER_', TO_CHAR(PROCEDURE_MODIFIER_POSITION_NBR))    
) AS MOD_PREP
    PIVOT
    (MIN(PROCEDURE_MODIFIER_CODE) FOR MOD_COL IN (
    'PROCEDURE_MODIFIER_1',
    'PROCEDURE_MODIFIER_2',
    'PROCEDURE_MODIFIER_3',
    'PROCEDURE_MODIFIER_4')
    ) AS TBL (
        GRP_PROCEDURE_MODIFIER_KEY,
        LAST_UPDATED_DATETIME,
        PROCEDURE_MODIFIER_01,
        PROCEDURE_MODIFIER_02,
        PROCEDURE_MODIFIER_03,
        PROCEDURE_MODIFIER_04)
;