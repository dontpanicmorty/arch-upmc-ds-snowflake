CREATE OR REPLACE VIEW STAGEDATA.FACT_PHARMACY_CLAIM_LINE_SELECT_VW
AS
WITH PROVIDER_LOOKUP_CTE
--using this to make to lookup to all the providers easier.
--It uses the stagedata view that builds the provider dimension so we can use all the same logic to see if we are finding a provider
--from SQL Server verses using one the has explicitly added from UPMCHP_DATAHUB
AS
(
SELECT
PHARMACY_DIM_PROVIDER_SELECT_VW.TPA_CLIENT_ID
,PHARMACY_DIM_PROVIDER_SELECT_VW.TPA_ID
,PHARMACY_DIM_PROVIDER_SELECT_VW.TPA_DIVISION_ID
,PHARMACY_DIM_PROVIDER_SELECT_VW.DATA_SOURCE_NAME
,PHARMACY_DIM_PROVIDER_SELECT_VW.SOURCE_PROVIDER_NBR AS PROVIDER_ID
,COALESCE(PHARMACY_DIM_PROVIDER_SELECT_VW.SQL_SERVER_DIM_PROVIDER_KEY, DIM_PROVIDER.DIM_PROVIDER_KEY) AS DIM_PROVIDER_KEY
FROM STAGEDATA.PHARMACY_DIM_PROVIDER_SELECT_VW
    LEFT OUTER JOIN DIMDATA.DIM_PROVIDER
        ON (DIM_PROVIDER.TPA_CLIENT_ID = PHARMACY_DIM_PROVIDER_SELECT_VW.TPA_CLIENT_ID
        AND DIM_PROVIDER.TPA_ID = PHARMACY_DIM_PROVIDER_SELECT_VW.TPA_ID
        AND DIM_PROVIDER.TPA_DIVISION_ID = PHARMACY_DIM_PROVIDER_SELECT_VW.TPA_DIVISION_ID
        AND DIM_PROVIDER.PROVIDER_ID = PHARMACY_DIM_PROVIDER_SELECT_VW.PROVIDER_ID
        AND DIM_PROVIDER.IS_LOGICAL_DELETE_FLAG = 'FALSE')
)

SELECT
DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.CLAIM_NBR AS CLAIM_NBR
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.CLAIM_LINE_SEQ_NBR AS CLAIM_SEQUENCE_NBR 
,IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1) AS DIM_TPA_HIERARCHY_KEY
,IFNULL(DIM_DATA_SOURCE.DIM_DATA_SOURCE_KEY, 1) AS DIM_DATA_SOURCE_KEY
,IFNULL(DIM_PHARMACY_CLAIM_DETAIL.DIM_PHARMACY_CLAIM_DETAIL_KEY, 1) AS DIM_PHARMACY_CLAIM_DETAIL_KEY
,IFNULL(DIM_PHARMACY_CLAIM_HEADER.DIM_PHARMACY_CLAIM_HEADER_KEY, 1) AS DIM_PHARMACY_CLAIM_HEADER_KEY
,IFNULL(DIM_MEMBER.DIM_MEMBER_KEY, 1) AS DIM_MEMBER_KEY
,IFNULL(DIM_GROUP.DIM_GROUP_KEY, 1) AS DIM_GROUP_KEY
,IFNULL(DIM_SUB_GROUP.DIM_SUB_GROUP_KEY, 1) AS DIM_SUB_GROUP_KEY
,IFNULL(DIM_DRUG.DIM_DRUG_KEY, 1) AS DIM_DRUG_KEY
,IFNULL(DIM_MEMBER_DEMOGRAPHIC.DIM_MEMBER_DEMOGRAPHIC_KEY, 1) AS DIM_MEMBER_DEMOGRAPHIC_KEY
,IFNULL(DIM_RIDER.DIM_RIDER_KEY, 1) AS DIM_RIDER_KEY
,IFNULL(DIM_PLAN.DIM_PLAN_KEY, 1) AS DIM_PLAN_KEY
,IFNULL(DIM_ENROLLMENT_SPAN_LOOKUP.DIM_ENROLLMENT_SPAN_KEY, 1) AS DIM_ENROLLMENT_SPAN_KEY 
,IFNULL(DIM_PROVIDER_PHARMACY.DIM_PROVIDER_KEY, 1) AS DIM_PROVIDER_PHARMACY_KEY 
,IFNULL(DIM_PROVIDER_ADDRESS_PHARMACY.DIM_PROVIDER_ADDRESS_KEY, 1) AS DIM_PROVIDER_ADDRESS_PHARMACY_KEY 
,IFNULL(DIM_PROVIDER_CONTACT_INFO_PHARMACY.DIM_PROVIDER_CONTACT_INFO_KEY, 1) AS DIM_PROVIDER_CONTACT_INFO_PHARMACY_KEY 
,IFNULL(DIM_PROVIDER_IDENTIFIER_PHARMACY_NABP_NBR.DIM_PROVIDER_IDENTIFIER_KEY, 1) AS DIM_PROVIDER_IDENTIFIER_PHARMACY_NABP_NBR_KEY 
,IFNULL(DIM_PROVIDER_IDENTIFIER_PHARMACY_NPI.DIM_PROVIDER_IDENTIFIER_KEY, 1) AS DIM_PROVIDER_IDENTIFIER_PHARMACY_NPI_KEY 
,IFNULL(DIM_PROVIDER_PRESCRIBER.DIM_PROVIDER_KEY, 1) AS DIM_PROVIDER_PRESCRIBER_KEY 
,IFNULL(DIM_PROVIDER_ADDRESS_PRESCRIBER_MAILING.DIM_PROVIDER_ADDRESS_KEY, 1) AS DIM_PROVIDER_ADDRESS_PRESCRIBER_MAILING_KEY 
,IFNULL(DIM_PROVIDER_ADDRESS_PRESCRIBER_PRACTICE.DIM_PROVIDER_ADDRESS_KEY, 1) AS DIM_PROVIDER_ADDRESS_PRESCRIBER_PRACTICE_KEY 
,IFNULL(DIM_PROVIDER_CONTACT_INFO_PRESCRIBER_MAILING.DIM_PROVIDER_CONTACT_INFO_KEY, 1) AS DIM_PROVIDER_CONTACT_INFO_PRESCRIBER_MAILING_KEY 
,IFNULL(DIM_PROVIDER_CONTACT_INFO_PRESCRIBER_PRACTICE.DIM_PROVIDER_CONTACT_INFO_KEY, 1) AS DIM_PROVIDER_CONTACT_INFO_PRESCRIBER_PRACTICE_KEY 
,IFNULL(DIM_PROVIDER_IDENTIFIER_PRESCRIBER_NPI.DIM_PROVIDER_IDENTIFIER_KEY, 1) AS DIM_PROVIDER_IDENTIFIER_PRESCRIBER_NPI_KEY 
,IFNULL(DIM_PROVIDER_TAXONOMY_PRESCRIBER.DIM_PROVIDER_TAXONOMY_KEY, 1) AS DIM_PROVIDER_TAXONOMY_PRESCRIBER_KEY 
,IFF(DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.FILLED_DATE IS NULL, 2, IFNULL(DIM_DATE_DAY_FILLED.DIM_DATE_DAY_KEY, 1)) AS DIM_FILLED_DATE_KEY
,IFF(DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.PAYMENT_DATE IS NULL, 2, IFNULL(DIM_DATE_DAY_PAYMENT.DIM_DATE_DAY_KEY, 1)) AS DIM_PAYMENT_DATE_KEY
,IFF(DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.RECEIVED_DATE IS NULL, 2, IFNULL(DIM_DATE_DAY_RECEIVED.DIM_DATE_DAY_KEY, 1)) AS DIM_RECEIVED_DATE_KEY
,IFF(DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.PRESCRIPTION_WRITTEN_DATE IS NULL, 2, IFNULL(DIM_DATE_DAY_WRITTEN.DIM_DATE_DAY_KEY, 1)) AS DIM_PRESCRIPTION_WRITTEN_DATE_KEY
,IFF(DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.ADJUDICATION_DATE IS NULL, 2, IFNULL(DIM_ADJUDICATION_DATE.DIM_DATE_DAY_KEY, 1)) AS DIM_ADJUDICATION_DATE_KEY
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.REPORT_EFFECTIVE_DATE
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.FILLED_DATE
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.PAYMENT_DATE
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.RECEIVED_DATE
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.ADJUDICATION_DATE
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.PRESCRIPTION_WRITTEN_DATE
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.PHARMACY_CLAIM_CNT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.CHARGE_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.COPAY_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.DEDUCTIBLE_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.COINSURANCE_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.DAY_SUPPLY_CNT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.INGREDIENT_COST_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.SALES_TAX_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.DISPENSING_FEE_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.NET_CHECK_DUE_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.DRUG_METRIC_QTY
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.PRODUCT_SELECTION_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.BENEFIT_EXCEED_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.AWP_UNIT_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.UNIT_PRICE_ALLOWED_MAX_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.USUAL_CUSTOMARY_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.ADMINISTRATIVE_FEE_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.AWP_TOTAL_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.HRA_APPLIED_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.PRE_COB_CLAIM_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.COB_RECOVERY_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.DRUG_CALCULATED_DISCOUNT_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.DRUG_DISCOUNT_ELIGIBLE_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.HRA_SPENDING_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.HRA_SPENDING_AMT_UPDATE_DATE
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.HIA_SPENDING_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.HIA_SPENDING_AMT_UPDATE_DATE
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.TOTAL_SPENDING_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.OTHER_PAYOR_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.TROOP_APPLIED_AMT
,DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.MEMBER_PAID_AMT

FROM RAWDATA.DATAHUB_PHARMACY_CLAIM_HEADER_BASE

    JOIN RAWDATA.DATAHUB_PHARMACY_CLAIM_DETAIL_BASE
        ON (DATAHUB_PHARMACY_CLAIM_HEADER_BASE.HUB_CLAIM_HKEY = DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.HUB_CLAIM_HKEY)

    LEFT OUTER JOIN RAWDATA.DATAHUB_MEMBER_DETAIL_BASE
        ON (DATAHUB_PHARMACY_CLAIM_HEADER_BASE.HUB_MEMBER_HKEY = DATAHUB_MEMBER_DETAIL_BASE.HUB_MEMBER_HKEY)

    LEFT OUTER JOIN RAWDATA.DATAHUB_DRUG_DETAIL_BASE
        ON (DATAHUB_PHARMACY_CLAIM_HEADER_BASE.HUB_DRUG_HKEY = DATAHUB_DRUG_DETAIL_BASE.HUB_DRUG_HKEY)

    LEFT OUTER JOIN RAWDATA.DATAHUB_PHARMACY_DETAIL_BASE
        ON (DATAHUB_PHARMACY_CLAIM_HEADER_BASE.HUB_PROVIDER_PHARMACY_HKEY = DATAHUB_PHARMACY_DETAIL_BASE.HUB_PROVIDER_HKEY)

    LEFT OUTER JOIN RAWDATA.DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE
        ON (DATAHUB_PHARMACY_CLAIM_HEADER_BASE.HUB_PROVIDER_PRESCRIBER_HKEY = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.HUB_PROVIDER_HKEY)

    LEFT OUTER JOIN DIMDATA.DIM_TPA_HIERARCHY
        ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_CLIENT_ID
        AND DIM_TPA_HIERARCHY.TPA_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_ID
        AND DIM_TPA_HIERARCHY.TPA_DIV_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_DIV_ID)

    LEFT OUTER JOIN DIMDATA.DIM_DATA_SOURCE
        ON (DIM_DATA_SOURCE.DATA_SOURCE_NAME = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.DATA_SOURCE_NAME)
    
    LEFT OUTER JOIN DIMDATA.DIM_PHARMACY_CLAIM_HEADER
        ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_CLIENT_ID
        AND DIM_TPA_HIERARCHY.TPA_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_ID
        AND DIM_TPA_HIERARCHY.TPA_DIV_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_DIV_ID
        AND DIM_DATA_SOURCE.DATA_SOURCE_NAME = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.DATA_SOURCE_NAME
        AND DIM_PHARMACY_CLAIM_HEADER.CLAIM_NBR = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.CLAIM_NBR)

    LEFT OUTER JOIN DIMDATA.DIM_PHARMACY_CLAIM_DETAIL
        ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_CLIENT_ID
        AND DIM_TPA_HIERARCHY.TPA_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_ID
        AND DIM_TPA_HIERARCHY.TPA_DIV_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_DIV_ID
        AND DIM_DATA_SOURCE.DATA_SOURCE_NAME = DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.DATA_SOURCE_NAME
        AND DIM_PHARMACY_CLAIM_DETAIL.CLAIM_NBR = DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.CLAIM_NBR
        AND DIM_PHARMACY_CLAIM_DETAIL.CLAIM_LINE_NBR = DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.CLAIM_LINE_NBR
        AND DIM_PHARMACY_CLAIM_DETAIL.CLAIM_SEQUENCE_NBR = DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.CLAIM_LINE_SEQ_NBR
        AND DIM_PHARMACY_CLAIM_DETAIL.PROCEDURE_ADJ_CODE = DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.CLAIM_LINE_PROCEDURE_ADJ_CODE)

    LEFT OUTER JOIN DIMDATA.DIM_MEMBER 
        ON (DIM_MEMBER.TPA_CLIENT_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_CLIENT_ID
        AND DIM_MEMBER.TPA_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_ID
        AND DIM_MEMBER.TPA_DIV_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_DIV_ID
        AND DIM_MEMBER.MEMBER_NBR = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.MEMBER_NBR)

     LEFT OUTER JOIN DIMDATA.DIM_GROUP
        ON (DIM_GROUP.TPA_CLIENT_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_CLIENT_ID
        AND DIM_GROUP.TPA_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_ID
        AND DIM_GROUP.TPA_DIV_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_DIV_ID
        AND DIM_GROUP.GROUP_NBR = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.GROUP_NBR)

    LEFT OUTER JOIN DIMDATA.DIM_SUB_GROUP
        ON (DIM_SUB_GROUP.TPA_CLIENT_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_CLIENT_ID
        AND DIM_SUB_GROUP.TPA_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_ID
        AND DIM_SUB_GROUP.TPA_DIV_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_DIV_ID
        AND DIM_SUB_GROUP.GROUP_NBR = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.GROUP_NBR
        AND DIM_SUB_GROUP.SUB_GROUP_NBR = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.SUB_GROUP_NBR)        

    LEFT OUTER JOIN DIMDATA.DIM_PLAN
        ON (DIM_PLAN.TPA_CLIENT_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_CLIENT_ID
        AND DIM_PLAN.TPA_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_ID
        AND DIM_PLAN.TPA_DIV_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_DIV_ID
        AND DIM_PLAN.PLAN_CODE = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.PLAN_CODE
        AND DIM_PLAN.PLAN_TYPE_CODE = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.PLAN_TYPE_CODE)

    --made a special lookup table for enrollment spans to fix / account for bad membership data
    --this will and should get removed as the data gets corrected.
    LEFT OUTER JOIN STAGEDATA.DIM_ENROLLMENT_SPAN_LOOKUP
        ON (DIM_ENROLLMENT_SPAN_LOOKUP.TPA_CLIENT_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_CLIENT_ID
        AND DIM_ENROLLMENT_SPAN_LOOKUP.TPA_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_ID
        AND DIM_ENROLLMENT_SPAN_LOOKUP.TPA_DIV_ID = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.TPA_DIV_ID
        AND DIM_ENROLLMENT_SPAN_LOOKUP.MEMBER_NBR = DATAHUB_PHARMACY_CLAIM_HEADER_BASE.MEMBER_NBR
        AND DIM_ENROLLMENT_SPAN_LOOKUP.SUB_SOURCE_NAME = DATAHUB_MEMBER_DETAIL_BASE.MEMBER_TYPE_CODE
        AND DIM_ENROLLMENT_SPAN_LOOKUP.ELIGIBILITY_START_DATE <= DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.FILLED_DATE
        AND DIM_ENROLLMENT_SPAN_LOOKUP.ELIGIBILITY_END_DATE >= DATAHUB_PHARMACY_CLAIM_DETAIL_BASE.FILLED_DATE)

    LEFT OUTER JOIN DIMDATA.DIM_DRUG
        ON (DIM_DRUG.NDC_DRUG_CODE = DATAHUB_DRUG_DETAIL_BASE.NDC_CODE)      

LEFT OUTER JOIN PROVIDER_LOOKUP_CTE DIM_PROVIDER_PHARMACY
        ON (DIM_PROVIDER_PHARMACY.PROVIDER_ID = DATAHUB_PHARMACY_DETAIL_BASE.PROVIDER_ID
        AND DIM_PROVIDER_PHARMACY.TPA_CLIENT_ID = DATAHUB_PHARMACY_DETAIL_BASE.TPA_CLIENT_ID
        AND DIM_PROVIDER_PHARMACY.TPA_ID = DATAHUB_PHARMACY_DETAIL_BASE.TPA_ID
        AND DIM_PROVIDER_PHARMACY.TPA_DIVISION_ID = DATAHUB_PHARMACY_DETAIL_BASE.TPA_DIV_ID)

    LEFT OUTER JOIN DIMDATA.DIM_PROVIDER_ADDRESS DIM_PROVIDER_ADDRESS_PHARMACY
        ON (DIM_PROVIDER_ADDRESS_PHARMACY.PROVIDER_ADDRESS_TYPE_CODE = DATAHUB_PHARMACY_DETAIL_BASE.ADDRESS_TYPE_CODE
        AND DIM_PROVIDER_ADDRESS_PHARMACY.PROVIDER_OFFICE_ID = DATAHUB_PHARMACY_DETAIL_BASE.PROVIDER_ID
        AND DIM_PROVIDER_ADDRESS_PHARMACY.PROVIDER_OFFICE_NAME = DATAHUB_PHARMACY_DETAIL_BASE.PHARMACY_NAME
        AND DIM_PROVIDER_ADDRESS_PHARMACY.PROVIDER_ADDRESS_LINE1_TEXT = DATAHUB_PHARMACY_DETAIL_BASE.ADDRESS_LINE_1
        AND DIM_PROVIDER_ADDRESS_PHARMACY.PROVIDER_ADDRESS_LINE2_TEXT = DATAHUB_PHARMACY_DETAIL_BASE.ADDRESS_LINE_2
        AND DIM_PROVIDER_ADDRESS_PHARMACY.PROVIDER_CITY_NAME = DATAHUB_PHARMACY_DETAIL_BASE.ADDRESS_CITY
        AND DIM_PROVIDER_ADDRESS_PHARMACY.PROVIDER_STATE_ABBREV_NAME = DATAHUB_PHARMACY_DETAIL_BASE.ADDRESS_STATE_ABBREV_NAME
        AND DIM_PROVIDER_ADDRESS_PHARMACY.PROVIDER_ZIP_CODE_NBR = DATAHUB_PHARMACY_DETAIL_BASE.ADDRESS_ZIP_CODE
        AND DIM_PROVIDER_ADDRESS_PHARMACY.PROVIDER_COUNTRY_NAME = DATAHUB_PHARMACY_DETAIL_BASE.ADDRESS_COUNTRY_NAME)

    LEFT OUTER JOIN DIMDATA.DIM_PROVIDER_CONTACT_INFO DIM_PROVIDER_CONTACT_INFO_PHARMACY
        ON (DIM_PROVIDER_CONTACT_INFO_PHARMACY.PROVIDER_PRIMARY_PHONE_NBR = DATAHUB_PHARMACY_DETAIL_BASE.PRIMARY_PHONE_NBR
        AND DIM_PROVIDER_CONTACT_INFO_PHARMACY.PROVIDER_PRIMARY_PHONE_EXTENSION_NBR = DATAHUB_PHARMACY_DETAIL_BASE.PRIMARY_PHONE_EXTENSION_NBR
        AND DIM_PROVIDER_CONTACT_INFO_PHARMACY.PROVIDER_ALTERNATE_PHONE_NBR = DATAHUB_PHARMACY_DETAIL_BASE.ALTERNATE_PHONE_NBR
        AND DIM_PROVIDER_CONTACT_INFO_PHARMACY.PROVIDER_ALTERNATE_PHONE_EXTENSION_NBR = DATAHUB_PHARMACY_DETAIL_BASE.ALTERNATE_PHONE_EXTENSION_NBR
        AND DIM_PROVIDER_CONTACT_INFO_PHARMACY.PROVIDER_EMAIL_ADDRESS_TEXT = DATAHUB_PHARMACY_DETAIL_BASE.EMAIL_ADDRESS_TEXT
        AND DIM_PROVIDER_CONTACT_INFO_PHARMACY.PROVIDER_FAX_NBR = DATAHUB_PHARMACY_DETAIL_BASE.FAX_NBR
        AND DIM_PROVIDER_CONTACT_INFO_PHARMACY.IS_LOGICAL_DELETE_FLAG = FALSE)
        
    LEFT OUTER JOIN DIMDATA.DIM_PROVIDER_IDENTIFIER DIM_PROVIDER_IDENTIFIER_PHARMACY_NABP_NBR
        ON (DIM_PROVIDER_PHARMACY.DIM_PROVIDER_KEY = DIM_PROVIDER_IDENTIFIER_PHARMACY_NABP_NBR.DIM_PROVIDER_KEY
        AND DIM_PROVIDER_IDENTIFIER_PHARMACY_NABP_NBR.IS_LOGICAL_DELETE_FLAG = FALSE
        AND DIM_PROVIDER_IDENTIFIER_PHARMACY_NABP_NBR.IDENTIFIER_NAME = 'NABP Number')

    LEFT OUTER JOIN DIMDATA.DIM_PROVIDER_IDENTIFIER DIM_PROVIDER_IDENTIFIER_PHARMACY_NPI
        ON (DIM_PROVIDER_PHARMACY.DIM_PROVIDER_KEY = DIM_PROVIDER_IDENTIFIER_PHARMACY_NPI.DIM_PROVIDER_KEY
        AND DIM_PROVIDER_IDENTIFIER_PHARMACY_NPI.IS_LOGICAL_DELETE_FLAG = FALSE
        AND DIM_PROVIDER_IDENTIFIER_PHARMACY_NPI.IDENTIFIER_NAME = 'National Provider Identifier')

    LEFT OUTER JOIN PROVIDER_LOOKUP_CTE DIM_PROVIDER_PRESCRIBER
        ON (DIM_PROVIDER_PRESCRIBER.PROVIDER_ID = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.PROVIDER_ID
        AND DIM_PROVIDER_PRESCRIBER.TPA_CLIENT_ID = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.TPA_CLIENT_ID
        AND DIM_PROVIDER_PRESCRIBER.TPA_ID = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.TPA_ID
        AND DIM_PROVIDER_PRESCRIBER.TPA_DIVISION_ID = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.TPA_DIV_ID)

    LEFT OUTER JOIN DIMDATA.DIM_PROVIDER_ADDRESS DIM_PROVIDER_ADDRESS_PRESCRIBER_MAILING
        ON (DIM_PROVIDER_ADDRESS_PRESCRIBER_MAILING.PROVIDER_ADDRESS_TYPE_CODE = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.MAILING_ADDRESS_TYPE_CODE
        AND DIM_PROVIDER_ADDRESS_PRESCRIBER_MAILING.PROVIDER_OFFICE_ID = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.PROVIDER_ID
        AND DIM_PROVIDER_ADDRESS_PRESCRIBER_MAILING.PROVIDER_OFFICE_NAME = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.PRESCRIBER_NAME
        AND DIM_PROVIDER_ADDRESS_PRESCRIBER_MAILING.PROVIDER_ADDRESS_LINE1_TEXT = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.MAILING_ADDRESS_LINE_1
        AND DIM_PROVIDER_ADDRESS_PRESCRIBER_MAILING.PROVIDER_ADDRESS_LINE2_TEXT = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.MAILING_ADDRESS_LINE_2
        AND DIM_PROVIDER_ADDRESS_PRESCRIBER_MAILING.PROVIDER_CITY_NAME = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.MAILING_ADDRESS_CITY
        AND DIM_PROVIDER_ADDRESS_PRESCRIBER_MAILING.PROVIDER_STATE_ABBREV_NAME = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.MAILING_ADDRESS_STATE_ABBREV_NAME
        AND DIM_PROVIDER_ADDRESS_PRESCRIBER_MAILING.PROVIDER_ZIP_CODE_NBR = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.MAILING_ADDRESS_ZIP_CODE
        AND DIM_PROVIDER_ADDRESS_PRESCRIBER_MAILING.PROVIDER_COUNTRY_NAME = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.MAILING_ADDRESS_COUNTRY_NAME
        AND DIM_PROVIDER_ADDRESS_PRESCRIBER_MAILING.IS_LOGICAL_DELETE_FLAG = FALSE)           

    LEFT OUTER JOIN DIMDATA.DIM_PROVIDER_ADDRESS DIM_PROVIDER_ADDRESS_PRESCRIBER_PRACTICE
        ON (DIM_PROVIDER_ADDRESS_PRESCRIBER_PRACTICE.PROVIDER_ADDRESS_TYPE_CODE = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.PRACTICE_ADDRESS_TYPE_CODE
        AND DIM_PROVIDER_ADDRESS_PRESCRIBER_PRACTICE.PROVIDER_OFFICE_ID = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.PROVIDER_ID
        AND DIM_PROVIDER_ADDRESS_PRESCRIBER_PRACTICE.PROVIDER_OFFICE_NAME = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.PRESCRIBER_NAME
        AND DIM_PROVIDER_ADDRESS_PRESCRIBER_PRACTICE.PROVIDER_ADDRESS_LINE1_TEXT = DATAHUB_PHARMACY_PRESCRIBER_DETAIL_BASE.PRACTICE_ADDRESS_LINE_1
