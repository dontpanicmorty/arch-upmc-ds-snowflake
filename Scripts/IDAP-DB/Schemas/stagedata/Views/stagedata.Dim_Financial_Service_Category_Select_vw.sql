CREATE OR REPLACE VIEW STAGEDATA.DIM_FINANCIAL_SERVICE_CATEGORY_SELECT_VW
AS
SELECT
       FSS_DECISION_DATA.DECISION_STEP AS FINANCIAL_SERVICE_DECISION_STEP,
       FINANCIAL_SERVICE_CATEGORY.CONTROLLABLE_EXPENSE_CODE,
       FINANCIAL_SERVICE_CATEGORY.FINANCIAL_SERVICE_GROUP_CODE,
       FINANCIAL_SERVICE_CATEGORY.FINANCIAL_SERVICE_GROUP_DESC,
       FINANCIAL_SERVICE_CATEGORY.FINANCIAL_SERVICE_SUBGRP_CODE,
       FINANCIAL_SERVICE_CATEGORY.FINANCIAL_SERVICE_SUBGRP_DESC,
       FINANCIAL_SERVICE_CATEGORY.UNIT_MEASURE_CODE,
       FINANCIAL_SERVICE_CATEGORY.CLOSING_CATEGORY_DESC
FROM STAGEDATA.FSS_DECISION_DATA
INNER JOIN &{IDW}.EDW_RPT.FINANCIAL_SERVICE_CATEGORY
       ON FINANCIAL_SERVICE_CATEGORY.FINANCIAL_SERVICE_SUBGRP_CODE = FSS_DECISION_DATA.SUBGROUP
;
!set variable_substitution=false; 