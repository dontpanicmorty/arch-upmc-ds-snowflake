CREATE OR REPLACE VIEW STAGEDATA.DIM_DIAGNOSIS_RELATED_GROUP_SELECT_VW AS 
SELECT 
    CLAIM_DIAGNOSIS_RELATED_GROUP_HKEY,
    DIAGNOSIS_RELATED_GROUP_CODE,
    DIAGNOSIS_RELATED_GROUP_CODE_DESC,
    SEVERITY_OF_ILLNESS_NBR,
    DIAGNOSIS_RELATED_GROUP_TYPE_CODE,
    DIAGNOSIS_RELATED_GROUP_VERSION_NBR,
    DIAGNOSIS_RELATED_GROUP_CATEGORY_NAME,
    MDC_CODE,
    MDC_DESC,
    RELATIVE_VALUE_NBR,
    AVERAGE_LENGTH_OF_STAY_NBR,
    EFFECTIVE_START_DATE,
    EFFECTIVE_END_DATE
FROM RAWDATA.DATAHUB_CLAIM_DIAGNOSIS_RELATED_GROUP
UNION
SELECT DISTINCT 
NULL AS CLAIM_DIAGNOSIS_RELATED_GROUP_HKEY,
DATAHUB_CLAIM_HEADER_BASE.DIAGNOSIS_RELATED_GROUP_CODE,
'UNKNOWN' AS DIAGNOSIS_RELATED_GROUP_CODE_DESC,
COALESCE(DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS,0) AS SEVERITY_OF_ILLNESS_NBR,
IFF(COALESCE(DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS,0) = 0, 'MS', 'APR') AS DIAGNOSIS_RELATED_GROUP_TYPE_CODE,
0 AS DIAGNOSIS_RELATED_GROUP_VERSION_NBR,
'UNKNOWN' AS DIAGNOSIS_RELATED_GROUP_CATEGORY_NAME,
'UNKNOWN' AS MDC_CODE,
'UNKNOWN' AS MDC_DESC,
0 AS RELATIVE_VALUE_NBR,
0 AS AVERAGE_LENGTH_OF_STAY_NBR,
TO_DATE('1950-01-01','YYYY-MM-DD') AS EFFECTIVE_START_DATE,
TO_DATE('9999-12-31','YYYY-MM-DD') AS EFFECTIVE_END_DATE
FROM RAWDATA.DATAHUB_CLAIM_HEADER_BASE
LEFT JOIN RAWDATA.DATAHUB_CLAIM_DIAGNOSIS_RELATED_GROUP
    ON (DATAHUB_CLAIM_HEADER_BASE.DIAGNOSIS_RELATED_GROUP_CODE = DATAHUB_CLAIM_DIAGNOSIS_RELATED_GROUP.DIAGNOSIS_RELATED_GROUP_CODE
    AND DATAHUB_CLAIM_HEADER_BASE.SEVERITY_OF_ILLNESS = DATAHUB_CLAIM_DIAGNOSIS_RELATED_GROUP.SEVERITY_OF_ILLNESS_NBR
    AND DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE BETWEEN DATAHUB_CLAIM_DIAGNOSIS_RELATED_GROUP.EFFECTIVE_START_DATE AND DATAHUB_CLAIM_DIAGNOSIS_RELATED_GROUP.EFFECTIVE_END_DATE)
WHERE DATAHUB_CLAIM_HEADER_BASE.DIAGNOSIS_RELATED_GROUP_CODE IS NOT NULL
;