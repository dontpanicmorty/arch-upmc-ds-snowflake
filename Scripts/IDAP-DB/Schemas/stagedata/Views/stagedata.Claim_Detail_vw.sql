CREATE OR REPLACE VIEW STAGEDATA.CLAIM_DETAIL_VW
AS
SELECT
CLAIM_DETAIL_RAW_VW.CLAIM_DETAIL_KEY
,CLAIM_DETAIL_RAW_VW.URI
,CLAIM_DETAIL_RAW_VW.ACCOUNTS_PAYABLE_PAY_STATUS_CODE
,CLAIM_DETAIL_RAW_VW.ADJUDICATION_STATUS
,CLAIM_DETAIL_RAW_VW.ADJUSTMENT_REASONS
,CLAIM_DETAIL_RAW_VW.ALLOWED_AMT
,CLAIM_DETAIL_RAW_VW.APPROVED_AMT
,CLAIM_DETAIL_RAW_VW.BENEFIT_CATEGORY_CODE
,CLAIM_DETAIL_RAW_VW.BENEFIT_LEVEL_CODE
,CLAIM_DETAIL_RAW_VW.BUCKET_STATUS_FLAG
,CLAIM_DETAIL_RAW_VW.CHARGE_AMT
,CASE
    WHEN (CLAIM_DETAIL_RAW_VW.DATA_SOURCE_NAME = 'MC400Upm')
        THEN TRY_TO_DATE(TO_CHAR(MC400_DWOAO_APPERMANENTPAYMENT.CHECKDATE),'YYYYMMDD')
    ELSE CLAIM_DETAIL_RAW_VW.CHECK_DATE
END AS CHECK_DATE
,CASE
    WHEN (CLAIM_DETAIL_RAW_VW.DATA_SOURCE_NAME = 'MC400Upm')
        THEN MC400_DWOAO_APPERMANENTPAYMENT.CHECKNBR
    ELSE CLAIM_DETAIL_RAW_VW.CHECK_NBR
END AS CHECK_NBR
,CLAIM_DETAIL_RAW_VW.CLAIM_AMT_01
,CLAIM_DETAIL_RAW_VW.CLAIM_AMT_02
,CLAIM_DETAIL_RAW_VW.CLAIM_LINE_NBR
,CLAIM_DETAIL_RAW_VW.CLAIM_NBR
,CLAIM_DETAIL_RAW_VW.CLAIM_RECEIVED_DATE
,CLAIM_DETAIL_RAW_VW.CLAIM_SEQUENCE_NBR
,CLAIM_DETAIL_RAW_VW.CLAIM_TYPE_CODE
,CLAIM_DETAIL_RAW_VW.CLEAN_CLAIM_IND
,CLAIM_DETAIL_RAW_VW.CODE_REVIEW_ORIG_BILL_AMT
,CLAIM_DETAIL_RAW_VW.CODE_REVIEW_ORIG_NET_AMT
,CASE
    WHEN (CLAIM_DETAIL_RAW_VW.DATA_SOURCE_NAME = 'MC400Upm')
        THEN ZEROIFNULL(MC400_DWOAO_CLAIMSDETAIL.COINSURANCEAMT)
    ELSE CLAIM_DETAIL_RAW_VW.COINSURANCE_AMT
END AS COINSURANCE_AMT
,CLAIM_DETAIL_RAW_VW.COMPANY_CODE
,CASE
    WHEN (CLAIM_DETAIL_RAW_VW.DATA_SOURCE_NAME = 'MC400Upm')
        THEN ZEROIFNULL(MC400_DWOAO_CLAIMSDETAIL.COPAYAMT)
    ELSE CLAIM_DETAIL_RAW_VW.COPAY_AMT_01
END AS COPAY_AMT_01
,CLAIM_DETAIL_RAW_VW.COPAY_REASON_CODE
,CLAIM_DETAIL_RAW_VW.COPAY_REASON_DESC_KEY
,CLAIM_DETAIL_RAW_VW.DATA_SOURCE_NAME 
,CLAIM_DETAIL_RAW_VW.DEDUCTIBLE_AMT
,CLAIM_DETAIL_RAW_VW.DEDUCTIBLE_REASON_CODE
,CLAIM_DETAIL_RAW_VW.DEDUCTIBLE_REASON_DESC_KEY
,CLAIM_DETAIL_RAW_VW.ELIGIBILITY_MISC_STATUS_CODE
,CLAIM_DETAIL_RAW_VW.FORM_NBR
,CLAIM_DETAIL_RAW_VW.GL_DISTRIBUTION_CODE
,CLAIM_DETAIL_RAW_VW.IS_PROCESSING_COMPLETE
,CLAIM_DETAIL_RAW_VW.KEY_TO_SOURCE_FILE
,CLAIM_DETAIL_RAW_VW.LOCATION_CODE
,CLAIM_DETAIL_RAW_VW.MEMBER_AGE_NBR
,CLAIM_DETAIL_RAW_VW.MEMBER_NBR
,CLAIM_DETAIL_RAW_VW.MEMBER_NBR_TYPE
,CLAIM_DETAIL_RAW_VW.NOT_COVERED_AMT
,CLAIM_DETAIL_RAW_VW.NOT_COVERED_REASON_CODES
,CLAIM_DETAIL_RAW_VW.OIC_ALLOWED_AMT
,CLAIM_DETAIL_RAW_VW.OIC_PAID_AMT
,CLAIM_DETAIL_RAW_VW.OIC_RESERVED_PAID_AMT
,CLAIM_DETAIL_RAW_VW.PAID_AMT
,CLAIM_DETAIL_RAW_VW.PAY_FOR_PERFORMANCE_AMT
,CASE
    WHEN (CLAIM_DETAIL_RAW_VW.DATA_SOURCE_NAME = 'MC400Upm')
        THEN TRY_TO_DATE(TO_CHAR(MC400_DWOAO_APPERMANENTPAYMENT.CHECKDATE),'YYYYMMDD')
    ELSE CLAIM_DETAIL_RAW_VW.PAYMENT_DATE
END AS PAYMENT_DATE
,CASE
    WHEN (CLAIM_DETAIL_RAW_VW.DATA_SOURCE_NAME = 'MC400Upm')
        THEN IFNULL(MC400_DWOAO_APPERMANENTPAYMENT.STATUS,MC400_DWOAO_APWORK.STATUS)
    ELSE CLAIM_DETAIL_RAW_VW.PAY_STATUS_CODE
END AS PAY_STATUS_CODE
,CLAIM_DETAIL_RAW_VW.PAY_STATUS_DESC_KEY
,CLAIM_DETAIL_RAW_VW.PROCEDURE_ADJ
,CLAIM_DETAIL_RAW_VW.PROCEDURE_CATEGORIES
,CLAIM_DETAIL_RAW_VW.PROCEDURE_CODE
,CLAIM_DETAIL_RAW_VW.PROCEDURE_CODE_ENGLISH_DESC_KEY
,CLAIM_DETAIL_RAW_VW.PROCEDURE_MODIFIERS
,CLAIM_DETAIL_RAW_VW.PROCEDURE_QTY
,CLAIM_DETAIL_RAW_VW.QUADRANT_ARCH
,CASE WHEN (CLAIM_DETAIL_RAW_VW.DATA_SOURCE_NAME = 'MC400Upm')
    THEN CASE
        WHEN (CLAIM_DETAIL_RAW_VW.RENDERING_PROVIDER_ID IS NOT NULL)
            THEN CLAIM_DETAIL_RAW_VW.RENDERING_PROVIDER_ID
        WHEN (MC400_DWOAO_CLAIMS.CLAIMTYPE = 'I')
            THEN MC400_DWOAO_CLAIMS.FacilityPricingNbr
        WHEN (MC400_DWOAO_CLAIMS.CLAIMTYPE !='I')
            THEN MC400_DWOAO_CLAIMSDETAIL.PROVIDERNUMBERHCFA
        ELSE CLAIM_DETAIL_RAW_VW.RENDERING_PROVIDER_ID
    END
    ELSE CLAIM_DETAIL_RAW_VW.RENDERING_PROVIDER_ID
END AS RENDERING_PROVIDER_ID
,CASE WHEN (CLAIM_DETAIL_RAW_VW.DATA_SOURCE_NAME = 'MC400Upm')
    THEN CASE
        WHEN (CLAIM_DETAIL_RAW_VW.RENDERING_PROVIDER_DETAIL_KEY IS NOT NULL)
            THEN CLAIM_DETAIL_RAW_VW.RENDERING_PROVIDER_DETAIL_KEY
        WHEN (MC400_DWOAO_CLAIMS.CLAIMTYPE = 'I' AND FACILITY_PRICING_NBR.UNIVERSAL_PROVIDER_ID IS NOT NULL)
            THEN FACILITY_PRICING_NBR.UNIVERSAL_PROVIDER_ID
        WHEN (MC400_DWOAO_CLAIMS.CLAIMTYPE !='I' AND PROVIDER_NUMBER_HCFA.UNIVERSAL_PROVIDER_ID IS NOT NULL)
            THEN PROVIDER_NUMBER_HCFA.UNIVERSAL_PROVIDER_ID
        ELSE CLAIM_DETAIL_RAW_VW.RENDERING_PROVIDER_DETAIL_KEY
    END
    ELSE CLAIM_DETAIL_RAW_VW.RENDERING_PROVIDER_DETAIL_KEY
END AS RENDERING_PROVIDER_DETAIL_KEY
,CLAIM_DETAIL_RAW_VW.RENDERING_PROVIDER_SNAPSHOT
,CLAIM_DETAIL_RAW_VW.SERVICE_BEGIN_DATE
,CLAIM_DETAIL_RAW_VW.SERVICE_END_DATE
,CLAIM_DETAIL_RAW_VW.SERVICE_REASON_CODE
,CLAIM_DETAIL_RAW_VW.SERVICE_REASON_DESC_KEY
,CLAIM_DETAIL_RAW_VW.SERVICE_STATUS_CODE
,CLAIM_DETAIL_RAW_VW.SERVICE_STATUS_DESC
,CLAIM_DETAIL_RAW_VW.SERVICE_TYPE_CODE
,CLAIM_DETAIL_RAW_VW.SNAPSHOT_MAPPING_FINISHED
,CLAIM_DETAIL_RAW_VW.SOURCE_LAST_UPDATED_DATE
,CLAIM_DETAIL_RAW_VW.THIRD_PARTY_PAID_AMT
,CLAIM_DETAIL_RAW_VW.TOOTH_ID
,CLAIM_DETAIL_RAW_VW.TOOTH_SURFACE_ID
,CLAIM_DETAIL_RAW_VW.TOOTH_SURFACE_02
,CLAIM_DETAIL_RAW_VW.TOOTH_SURFACE_03
,CLAIM_DETAIL_RAW_VW.TOOTH_SURFACE_04
,CLAIM_DETAIL_RAW_VW.TOOTH_SURFACE_05
,CLAIM_DETAIL_RAW_VW.TPA_CLIENT_ID
,CLAIM_DETAIL_RAW_VW.TPA_DIV_ID
,CLAIM_DETAIL_RAW_VW.TPA_ID
,CLAIM_DETAIL_RAW_VW.TPA_KEY
,CLAIM_DETAIL_RAW_VW.TRANSACTION_TYPE_CODE
,CLAIM_DETAIL_RAW_VW.TRANSACTION_TYPE_DESC
,CLAIM_DETAIL_RAW_VW.UNIVERSAL_CLAIM_ID
,CLAIM_DETAIL_RAW_VW.WITHHOLD_AMT
,CLAIM_DETAIL_RAW_VW.MEMBER_LIABILITY
,CLAIM_DETAIL_RAW_VW.CLAIM_DAY_CNT
,CLAIM_DETAIL_RAW_VW.PAID_GROSS_AMT
,CLAIM_DETAIL_RAW_VW.SERVICE_CNT
,CLAIM_DETAIL_RAW_VW.DENIED_DAY_CNT
,CASE
    WHEN (CLAIM_DETAIL_RAW_VW.DATA_SOURCE_NAME = 'MC400Upm')
        THEN COALESCE(MC400_DWOAO_APPERMANENTPAYMENT_GL.GLAMOUNT,MC400_DWOAO_APWORK_GL.GLAMOUNT, 0)
    ELSE CLAIM_DETAIL_RAW_VW.INTEREST_DISCOUNT_AMT
END AS INTEREST_DISCOUNT_AMT
,CLAIM_DETAIL_RAW_VW.CLAIM_AMT_01_DESC
,CLAIM_DETAIL_RAW_VW.CLAIM_AMT_02_DESC
,CLAIM_DETAIL_RAW_VW.CLAIM_ENTRY_DATE
,CASE
    WHEN (CLAIM_DETAIL_RAW_VW.DATA_SOURCE_NAME = 'MC400Upm')
        THEN IFNULL(TRY_TO_DATE(TO_CHAR(MC400_DWOAO_APPERMANENTPAYMENT.POSTDATE),'YYYYMMDD'),TRY_TO_DATE(TO_CHAR(MC400_DWOAO_APWORK.POSTDATE),'YYYYMMDD'))
    ELSE CLAIM_DETAIL_RAW_VW.AP_POSTING_DATE
END AS AP_POSTING_DATE
,CLAIM_DETAIL_RAW_VW.ADD_DATE
,CLAIM_DETAIL_RAW_VW.REVENUE_CODE

FROM STAGEDATA.CLAIM_DETAIL_RAW_VW
    LEFT OUTER JOIN RAWDATA.MC400_DWOAO_CLAIMSDETAIL
        ON (MC400_DWOAO_CLAIMSDETAIL.TPACLIENT = CLAIM_DETAIL_RAW_VW.TPA_CLIENT_ID
        AND MC400_DWOAO_CLAIMSDETAIL.TPAIDOFCLIENT = CLAIM_DETAIL_RAW_VW.TPA_ID
        AND MC400_DWOAO_CLAIMSDETAIL.TPADIVISION = CLAIM_DETAIL_RAW_VW.TPA_DIV_ID
        AND MC400_DWOAO_CLAIMSDETAIL.DATA_SOURCE_NAME = CLAIM_DETAIL_RAW_VW.DATA_SOURCE_NAME
        AND MC400_DWOAO_CLAIMSDETAIL.CLAIMNBR = CLAIM_DETAIL_RAW_VW.CLAIM_NBR
        AND MC400_DWOAO_CLAIMSDETAIL.CLAIMLINENBR =  CLAIM_DETAIL_RAW_VW.CLAIM_LINE_NBR
        AND MC400_DWOAO_CLAIMSDETAIL.CLAIMSEQUENCE = CLAIM_DETAIL_RAW_VW.CLAIM_SEQUENCE_NBR
        AND MC400_DWOAO_CLAIMSDETAIL.PROCEDUREADJ = CLAIM_DETAIL_RAW_VW.PROCEDURE_ADJ)

    LEFT OUTER JOIN RAWDATA.MC400_DWOAO_CLAIMS
        ON (MC400_DWOAO_CLAIMSDETAIL.ADMITDATE = MC400_DWOAO_CLAIMS.ADMITDATE
        AND MC400_DWOAO_CLAIMSDETAIL.CLAIMTYPE = MC400_DWOAO_CLAIMS.CLAIMTYPE
        AND MC400_DWOAO_CLAIMSDETAIL.FORMNBR = MC400_DWOAO_CLAIMS.FORMNBR)

    LEFT OUTER JOIN RAWDATA.MC400_DWOAO_APPERMANENTPAYMENT
        ON (MC400_DWOAO_CLAIMSDETAIL.ROWID =  MC400_DWOAO_APPERMANENTPAYMENT.TABLEROWID
        AND MC400_DWOAO_CLAIMSDETAIL.CLAIMTYPE = MC400_DWOAO_APPERMANENTPAYMENT.FILETYPE)
    
    LEFT OUTER JOIN RAWDATA.MC400_DWOAO_APPERMANENTPAYMENT_GL
        ON (MC400_DWOAO_APPERMANENTPAYMENT.ROWID = MC400_DWOAO_APPERMANENTPAYMENT_GL.APPAYPROWID
        AND MC400_DWOAO_APPERMANENTPAYMENT.TPAROWID = MC400_DWOAO_APPERMANENTPAYMENT_GL.TPAROWID
        AND MC400_DWOAO_APPERMANENTPAYMENT_GL.GLTYPE = 'INT')
    
    LEFT OUTER JOIN RAWDATA.MC400_DWOAO_APWORK
        ON (MC400_DWOAO_CLAIMSDETAIL.CLAIMTYPE = MC400_DWOAO_APWORK.FILETYPE
        AND MC400_DWOAO_CLAIMSDETAIL.ROWID = CASE
                                                WHEN MC400_DWOAO_APWORK.FILETYPE = 'I'
                                                    THEN MC400_DWOAO_APWORK.HINSDPROWID
                                                ELSE MC400_DWOAO_APWORK.HENCDPROWID
                                            END
            )
    LEFT OUTER JOIN RAWDATA.MC400_DWOAO_APWORK_GL
        ON (MC400_DWOAO_APWORK.ROWID = MC400_DWOAO_APWORK_GL.APWORKPROWID
        AND MC400_DWOAO_APWORK.TPAROWID = MC400_DWOAO_APWORK_GL.TPAROWID
        AND MC400_DWOAO_APWORK_GL.GLTYPE = 'INT')

    LEFT OUTER JOIN STAGEDATA.PROVIDER_DETAIL_VW  FACILITY_PRICING_NBR
        ON (FACILITY_PRICING_NBR.TPA_CLIENT_ID = CLAIM_DETAIL_RAW_VW.TPA_CLIENT_ID
        AND FACILITY_PRICING_NBR.TPA_ID = CLAIM_DETAIL_RAW_VW.TPA_ID
        AND FACILITY_PRICING_NBR.TPA_DIV_ID = CLAIM_DETAIL_RAW_VW.TPA_DIV_ID 
        AND FACILITY_PRICING_NBR.DATA_SOURCE_NAME = CLAIM_DETAIL_RAW_VW.DATA_SOURCE_NAME  
        AND FACILITY_PRICING_NBR.SOURCE_PROVIDER_NBR = MC400_DWOAO_CLAIMS.FacilityPricingNbr)          

    LEFT OUTER JOIN STAGEDATA.PROVIDER_DETAIL_VW  PROVIDER_NUMBER_HCFA
        ON (PROVIDER_NUMBER_HCFA.TPA_CLIENT_ID = CLAIM_DETAIL_RAW_VW.TPA_CLIENT_ID
        AND PROVIDER_NUMBER_HCFA.TPA_ID = CLAIM_DETAIL_RAW_VW.TPA_ID
        AND PROVIDER_NUMBER_HCFA.TPA_DIV_ID = CLAIM_DETAIL_RAW_VW.TPA_DIV_ID 
        AND PROVIDER_NUMBER_HCFA.DATA_SOURCE_NAME = CLAIM_DETAIL_RAW_VW.DATA_SOURCE_NAME  
        AND PROVIDER_NUMBER_HCFA.SOURCE_PROVIDER_NBR = MC400_DWOAO_CLAIMSDETAIL.PROVIDERNUMBERHCFA)          
;