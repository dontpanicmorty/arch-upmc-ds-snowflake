CREATE OR REPLACE VIEW STAGEDATA.DIM_CLAIM_AUTHORIZATION_SELECT_VW
AS
SELECT
TPA_CLIENT_ID,
TPA_ID,
TPA_DIV_ID,
DATA_SOURCE_NAME,
AUTHORIZATION_NBR, --'Authorization Number from the source system'
CARE_TYPE_NAME, -- 'Defines the type of claim and can be used to filter between medical, dental, vision, pharmacy'
AUTHORIZATION_STATUS_DESC AS STATUS_DESC,
AUTHORIZATION_DETERMINATION_STATUS_DESC AS DETERMINATION_STATUS_DESC,
AUTHORIZATION_DETERMINATION_DATE AS DETERMINATION_DATE,
MEDICAL_GROUP_ADDRESS_LINE_1,
MEDICAL_GROUP_ADDRESS_LINE_2,
MEDICAL_GROUP_CITY,
MEDICAL_GROUP_STATE_ABBREV_NAME,
MEDICAL_GROUP_ZIP_CODE,
MEDICAL_GROUP_PRIMARY_PHONE_NBR
FROM RAWDATA.DATAHUB_CLAIM_AUTHORIZATION_BASE
;
