CREATE OR REPLACE VIEW STAGEDATA.FACT_APP_MOBILE_EVENT_SELECT_VW
AS
SELECT 
    IFNULL(DIM_APP_DEVICE_KEY, 1) AS DIM_APP_DEVICE_KEY,
    IFNULL(DIM_APP_EVENT_KEY, 1) AS DIM_APP_EVENT_KEY,
    IFNULL(DIM_MEMBER.DIM_MEMBER_KEY, 1) AS DIM_MEMBER_KEY,
    IFNULL(DIM_MEMBER_ADDRESS_PHYSICAL_VW.DIM_MEMBER_ADDRESS_PHYSICAL_KEY, 1) AS DIM_MEMBER_ADDRESS_PHYSICAL_KEY,
    IFNULL(FACT_AGG.DIM_PLAN_KEY, 1) AS DIM_PLAN_KEY,
    IFNULL(FACT_AGG.DIM_GROUP_KEY, 1) AS DIM_GROUP_KEY,
    IFNULL(FACT_AGG.DIM_SUB_GROUP_KEY, 1) AS DIM_SUB_GROUP_KEY,
    APIM_LOGS_MOBILE_VW.APIM_LOGS_KEY AS APIM_LOGS_KEY,
    IFNULL(APIM_LOGS_MOBILE_VW.SESSION_ID, 'Unknown') AS EVENT_SESSION_ID,
    TO_TIMESTAMP_TZ(APIM_LOGS_MOBILE_VW.EVENT_DATETIME) AS EVENT_DATETIME_UTC,
    TO_DATE(APIM_LOGS_MOBILE_VW.EVENT_DATETIME) AS EVENT_DATE,
    TO_TIME(APIM_LOGS_MOBILE_VW.EVENT_DATETIME) AS EVENT_TIME,
    IFNULL(APIM_LOGS_MOBILE_VW.RESPONSE_STATUS_CODE, 'UNK') AS EVENT_RESPONSE_STATUS_CODE,
    IFNULL(APIM_LOGS_MOBILE_VW.RESPONSE_STATUS_REASON, 'Unknown') AS EVENT_RESPONSE_STATUS_REASON,
    IFNULL(APIM_LOGS_MOBILE_VW.DEVICE_ID, 'Unknown') AS DEVICE_ID,
    IFNULL(APIM_LOGS_MOBILE_VW.DEVICE_LANGUAGE, 'UNK') AS DEVICE_LANGUAGE_CODE,
    IFNULL(APIM_LOGS_MOBILE_VW.DEVICE_APP_VERSION_NBR, 'Unknown') AS DEVICE_APP_VERSION_NBR
FROM STAGEDATA.APIM_LOGS_MOBILE_VW
    LEFT OUTER JOIN DIMDATA.DIM_APP_DEVICE
        ON (DIM_APP_DEVICE.DEVICE_OS_PLATFORM_NAME = APIM_LOGS_MOBILE_VW.DEVICE_PLATFORM
        AND DIM_APP_DEVICE.DEVICE_OS_VERSION_NBR = IFNULL(APIM_LOGS_MOBILE_VW.DEVICE_OPERATING_SYSTEM,'Unknown')
        AND DIM_APP_DEVICE.DEVICE_MODEL_NAME = IFNULL(APIM_LOGS_MOBILE_VW.DEVICE_MODEL_NAME, 'Unknown'))

    LEFT OUTER JOIN DIMDATA.DIM_APP_EVENT
        ON (DIM_APP_EVENT.EVENT_NAME = APIM_LOGS_MOBILE_VW.EVENT_NAME
        AND DIM_APP_EVENT.EVENT_VALUES = APIM_LOGS_MOBILE_VW.EVENT_VALUES)

    LEFT OUTER JOIN DIMDATA.DIM_MEMBER 
        ON (APIM_LOGS_MOBILE_VW.MEMBER_NBR = DIM_MEMBER.MEMBER_NBR
        AND IFNULL(APIM_LOGS_MOBILE_VW.TPA_CLIENT_ID,'000001') = DIM_MEMBER.TPA_CLIENT_ID
        AND IFNULL(APIM_LOGS_MOBILE_VW.TPA_ID,'000001') = DIM_MEMBER.TPA_ID
        AND IFNULL(APIM_LOGS_MOBILE_VW.TPA_DIV_ID, '0001') = DIM_MEMBER.TPA_DIV_ID)

    LEFT OUTER JOIN DIMDATA.DIM_MEMBER_ADDRESS_PHYSICAL_VW
        ON (DIM_MEMBER_ADDRESS_PHYSICAL_VW.DIM_MEMBER_KEY = DIM_MEMBER.DIM_MEMBER_KEY
        AND DIM_MEMBER_ADDRESS_PHYSICAL_VW.EFFECTIVE_START_DATE < DIM_MEMBER_ADDRESS_PHYSICAL_VW.EFFECTIVE_END_DATE
        AND TO_DATE(APIM_LOGS_MOBILE_VW.EVENT_DATETIME) BETWEEN DIM_MEMBER_ADDRESS_PHYSICAL_VW.EFFECTIVE_START_DATE AND DIM_MEMBER_ADDRESS_PHYSICAL_VW.EFFECTIVE_END_DATE)


    LEFT OUTER JOIN 
            (SELECT DISTINCT DIM_TPA_HIERARCHY_KEY,
                DIM_MEMBER_KEY,
                DIM_PLAN_KEY,
                DIM_SALES_CHANNEL_KEY,
                ELIGIBILITY_END_DATE,
                ENROLLMENT_DATE_KEY,
                RENEWAL_DATE_KEY,
                DIM_GROUP_KEY,
                DIM_SUB_GROUP_KEY,
                ELIGIBILITY_START_DATE as ELIGIBILITY_START_DATE_AGG,
                ELIGIBILITY_END_DATE as ELIGIBILITY_END_DATE_AGG,
                ENROLLMENT_DATE,
                RENEWAL_DATE
            FROM DIMDATA.FACT_ENROLLMENT
            WHERE DIM_PLAN_KEY <> '1'
            GROUP BY DIM_TPA_HIERARCHY_KEY,
                DIM_MEMBER_KEY,
                DIM_PLAN_KEY,
                DIM_SALES_CHANNEL_KEY,
                ELIGIBILITY_END_DATE,
                ENROLLMENT_DATE_KEY,
                RENEWAL_DATE_KEY,
                DIM_GROUP_KEY,
                DIM_SUB_GROUP_KEY,
                ELIGIBILITY_START_DATE,
                ELIGIBILITY_END_DATE,
                ENROLLMENT_DATE,
                RENEWAL_DATE
            ) FACT_AGG 
        ON (FACT_AGG.DIM_MEMBER_KEY = DIM_MEMBER.DIM_MEMBER_KEY
        AND CAST(APIM_LOGS_MOBILE_VW.EVENT_DATETIME AS DATE) BETWEEN FACT_AGG.ELIGIBILITY_START_DATE_AGG AND FACT_AGG.ELIGIBILITY_END_DATE_AGG
        )
;