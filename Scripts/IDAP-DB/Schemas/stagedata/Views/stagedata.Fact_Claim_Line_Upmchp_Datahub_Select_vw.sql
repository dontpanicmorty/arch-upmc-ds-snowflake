CREATE OR REPLACE VIEW STAGEDATA.FACT_CLAIM_LINE_UPMCHP_DATAHUB_SELECT_VW
AS

WITH PROVIDER_LOOKUP_CTE
--using this to make to lookup to all the providers easier.
--It uses the stagedata view that builds the provider dimension so we can use all the same logic to see if we are finding a provider
--from SQL Server verses using one the has expicitaly added from UPMCHP_DATAHUB
AS
(
SELECT
DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.TPA_CLIENT_ID
,DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.TPA_ID
,DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.TPA_DIVISION_ID
,DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.DATA_SOURCE_NAME
,DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.SOURCE_PROVIDER_NBR AS PROVIDER_ID
,COALESCE(DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.SQL_SERVER_DIM_PROVIDER_KEY, DIM_PROVIDER.DIM_PROVIDER_KEY) AS DIM_PROVIDER_KEY
FROM STAGEDATA.DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW
    LEFT OUTER JOIN DIMDATA.DIM_PROVIDER
        ON (DIM_PROVIDER.TPA_CLIENT_ID = DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.TPA_CLIENT_ID
        AND DIM_PROVIDER.TPA_ID = DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.TPA_ID
        AND DIM_PROVIDER.TPA_DIVISION_ID = DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.TPA_DIVISION_ID
        AND DIM_PROVIDER.PROVIDER_ID = DIM_PROVIDER_UPMCHP_DATAHUB_SELECT_VW.PROVIDER_ID
        AND DIM_PROVIDER.IS_LOGICAL_DELETE_FLAG = 'FALSE')
)

SELECT 
IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1) AS DIM_TPA_HIERARCHY_KEY
,IFNULL(DIM_DATA_SOURCE.DIM_DATA_SOURCE_KEY, 1) AS DIM_DATA_SOURCE_KEY
,DATAHUB_CLAIM_DETAIL_BASE.CLAIM_NBR
,DATAHUB_CLAIM_DETAIL_BASE.CLAIM_LINE_NBR
,IFNULL(DIM_CLAIM_HEADER.DIM_CLAIM_HEADER_KEY, 1) AS DIM_CLAIM_HEADER_KEY
,IFNULL(DIM_CLAIM_DETAIL.DIM_CLAIM_DETAIL_KEY, 1) AS DIM_CLAIM_DETAIL_KEY
,IFNULL(DIM_MEMBER.DIM_MEMBER_KEY, 1) AS DIM_MEMBER_KEY
,IFNULL(DIM_MEMBER_DEMOGRAPHIC.DIM_MEMBER_DEMOGRAPHIC_KEY, 1) AS DIM_MEMBER_DEMOGRAPHIC_KEY
,IFF(DATAHUB_CLAIM_HEADER_BASE.DIAGNOSIS_RELATED_GROUP_CODE IS NULL, 2, IFNULL(DIM_DIAGNOSIS_RELATED_GROUP_LOOKUP.DIM_DIAGNOSIS_RELATED_GROUP_KEY, 1)) AS DIM_DIAGNOSIS_RELATED_GROUP_KEY
,IFNULL(DIM_ENROLLMENT_SPAN_LOOKUP.DIM_ENROLLMENT_SPAN_KEY, 1) AS DIM_ENROLLMENT_SPAN_KEY
,IFNULL(DIM_GROUP.DIM_GROUP_KEY, 1) AS DIM_GROUP_KEY
,IFNULL(DIM_SUB_GROUP.DIM_SUB_GROUP_KEY,1) AS DIM_SUB_GROUP_KEY
,IFNULL(DIM_PLAN.DIM_PLAN_KEY,1) AS DIM_PLAN_KEY
,IFNULL(DIM_PLACE_OF_SERVICE.DIM_PLACE_OF_SERVICE_KEY, 1) AS DIM_PLACE_OF_SERVICE_KEY
,IFF(DATAHUB_CLAIM_DETAIL_BASE.PROCEDURE_CODE IS NULL, 2, IFNULL(DIM_CLAIM_PROCEDURE_CPT.DIM_CLAIM_PROCEDURE_KEY, 1)) AS DIM_CLAIM_PROCEDURE_KEY
,CASE
    WHEN IFNULL(DATAHUB_CLAIM_DETAIL_BASE.COPAY_AMT_01, 0) = 0 THEN 2
    ELSE IFNULL(DIM_COPAY_REASON_VW.DIM_COPAY_REASON_KEY, 1)
END AS DIM_COPAY_REASON_KEY
,CASE
    WHEN IFNULL(DATAHUB_CLAIM_DETAIL_BASE.COINSURANCE_AMOUNT, 0) = 0 THEN 2
    ELSE IFNULL(DIM_COINSURANCE_REASON_VW.DIM_COINSURANCE_REASON_KEY, 1)
END AS DIM_COINSURANCE_REASON_KEY
,CASE
    WHEN IFNULL(DATAHUB_CLAIM_DETAIL_BASE.DEDUCTIBLE_AMOUNT, 0 ) = 0 THEN 2
    ELSE IFNULL(DIM_DEDUCTIBLE_REASON_VW.DIM_DEDUCTIBLE_REASON_KEY, 1)
END AS DIM_DEDUCTIBLE_REASON_KEY 
,IFF(DATAHUB_CLAIM_DETAIL_BASE.ADJUSTMENT_REASON_ARRAY IS NULL, 2, IFNULL(GRP_ADJUSTMENT_REASON_LOOKUP.GRP_ADJUSTMENT_REASON_KEY, 1)) AS GRP_ADJUSTMENT_REASON_KEY
,IFF(DATAHUB_CLAIM_DETAIL_BASE.NOT_COVERED_REASON_ARRAY IS NULL, 2, IFNULL(GRP_NOT_COVERED_REASON_LOOKUP.GRP_NOT_COVERED_REASON_KEY, 1)) AS GRP_NOT_COVERED_REASON_KEY
,IFF(DATAHUB_CLAIM_DETAIL_BASE.SERVICE_REASON_ARRAY IS NULL, 2, IFNULL(GRP_SERVICE_REASON_LOOKUP.GRP_SERVICE_REASON_KEY, 1)) AS GRP_SERVICE_REASON_KEY
,IFF(DATAHUB_CLAIM_HEADER_BASE.RIDER_CODES IS NULL, 2, IFNULL(GRP_CLAIM_RIDER_LOOKUP.GRP_CLAIM_RIDER_KEY, 1)) AS GRP_CLAIM_RIDER_KEY
,IFF(
        (
            DATAHUB_CLAIM_DETAIL_BASE.PROCEDURE_MODIFIER_01 IS NULL
        AND DATAHUB_CLAIM_DETAIL_BASE.PROCEDURE_MODIFIER_02 IS NULL
        AND DATAHUB_CLAIM_DETAIL_BASE.PROCEDURE_MODIFIER_03 IS NULL
        AND DATAHUB_CLAIM_DETAIL_BASE.PROCEDURE_MODIFIER_04 IS NULL
        )
    , 2, IFNULL(GRP_PROCEDURE_MODIFIER_LOOKUP.GRP_PROCEDURE_MODIFIER_KEY, 1) 
    ) AS GRP_PROCEDURE_MODIFIER_KEY
,IFF(DATAHUB_CLAIM_DETAIL_BASE.PROCEDURE_CATEGORY_ARRAY IS NULL, 2, IFNULL(GRP_PROCEDURE_CATEGORY_LOOKUP.GRP_PROCEDURE_CATEGORY_KEY, 1)) AS GRP_PROCEDURE_CATEGORY_KEY
,IFF(DATAHUB_CLAIM_HEADER_BASE.ICD_DIAGNOSIS_CODES_ARRAY IS NULL, 2, IFNULL(GRP_ICD_DIAGNOSIS_LOOKUP.GRP_ICD_DIAGNOSIS_KEY, 1)) AS GRP_ICD_DIAGNOSIS_KEY
,IFNULL(GRP_ICD_PROCEDURE_LOOKUP.GRP_ICD_PROCEDURE_KEY, 2) AS GRP_ICD_PROCEDURE_KEY --NEEDS LOOKED AT FOR MC400UPM
,IFNULL(BILLING_PROVIDER.DIM_PROVIDER_KEY, 1) AS DIM_BILLING_PROVIDER_KEY
,IFF(DATAHUB_CLAIM_DETAIL_BASE.RENDERING_PROVIDER_ID IS NULL, 2, IFNULL(RENDERING_PROVIDER.DIM_PROVIDER_KEY, 1)) AS DIM_RENDERING_PROVIDER_KEY
,IFNULL(DIM_DATE_DAY_RECEIVED.DIM_DATE_DAY_KEY, 1) AS DIM_RECEIVED_DATE_KEY
,IFNULL(DIM_DATE_DAY_PAYMENT.DIM_DATE_DAY_KEY, 1) AS DIM_PAYMENT_DATE_KEY
,IFNULL(DIM_DATE_DAY_SERVICE_BEGIN.DIM_DATE_DAY_KEY, 1) AS DIM_SERVICE_BEGIN_DATE_KEY
,IFNULL(DIM_DATE_DAY_SERVICE_END.DIM_DATE_DAY_KEY, 1) AS DIM_SERVICE_END_DATE_KEY
,IFNULL(DIM_DATE_DAY_DISCHARGE_DATE.DIM_DATE_DAY_KEY, 1) AS DIM_DISCHARGE_DATE_KEY
,IFNULL(DIM_DATE_DAY_ADMIT_DATE.DIM_DATE_DAY_KEY, 1) AS DIM_ADMISSION_DATE_KEY
,IFNULL(IFNULL(DIM_MEMBER_ADDRESS_PHYSICAL_VW.DIM_MEMBER_ADDRESS_PHYSICAL_KEY, CURRENT_MEMBER_ADDRESS.DIM_MEMBER_ADDRESS_PHYSICAL_KEY), 1) AS DIM_MEMBER_ADDRESS_PHYSICAL_KEY
,IFF(DATAHUB_CLAIM_DETAIL_BASE.REVENUE_CODE IS NULL, 2, IFNULL(DIM_REVENUE_PROCEDURE.DIM_REVENUE_PROCEDURE_KEY, 1)) AS DIM_REVENUE_PROCEDURE_KEY
,DATAHUB_CLAIM_DETAIL_BASE.SERVICE_BEGIN_DATE AS SERVICE_BEGIN_DATE
,DATAHUB_CLAIM_DETAIL_BASE.SERVICE_END_DATE AS SERVICE_END_DATE
,DATAHUB_CLAIM_DETAIL_BASE.CLAIM_RECEIVED_DATE AS RECEIVED_DATE
,DATAHUB_CLAIM_DETAIL_BASE.PAYMENT_DATE AS PAYMENT_DATE
,DATAHUB_CLAIM_DETAIL_BASE.PROCEDURE_QUANTITY AS PROCEDURE_QTY
,DATAHUB_CLAIM_DETAIL_BASE.PAID_AMOUNT AS PAID_AMT
,DATAHUB_CLAIM_DETAIL_BASE.CHARGE_AMOUNT AS CHARGE_AMT
,DATAHUB_CLAIM_DETAIL_BASE.APPROVED_AMT AS APPROVED_AMT
,DATAHUB_CLAIM_DETAIL_BASE.NOT_COVERED_AMOUNT AS NOT_COVERED_AMT
,DATAHUB_CLAIM_DETAIL_BASE.COPAY_AMT_01 AS COPAY_AMT
,DATAHUB_CLAIM_DETAIL_BASE.DEDUCTIBLE_AMOUNT AS DEDUCTIBLE_AMT
,DATAHUB_CLAIM_DETAIL_BASE.COINSURANCE_AMOUNT AS COINSURANCE_AMT
,DATAHUB_CLAIM_DETAIL_BASE.ALLOWED_AMOUNT AS BENEFIT_ALLOW_AMT
,DATAHUB_CLAIM_DETAIL_BASE.THIRD_PARTY_PAID_AMOUNT AS THIRD_PARTY_PAID_AMT
,DATAHUB_CLAIM_HEADER_BASE.DISCHARGE_DATE AS DISCHARGE_DATE
,DATAHUB_CLAIM_HEADER_BASE.DISCHARGE_HOUR AS DISCHARGE_HOUR
,DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE AS ADMISSION_DATE
,DATAHUB_CLAIM_HEADER_BASE.ADMITTED_HOUR AS ADMISSION_HOUR
,DATAHUB_CLAIM_DETAIL_BASE.MEMBER_LIABILITY_AMT AS MEMBER_LIABILITY_AMT
,DATAHUB_CLAIM_DETAIL_BASE.CLAIM_DAY_CNT AS CLAIM_DAY_CNT
,IFF(DATAHUB_CLAIM_HEADER_BASE.REFERRING_PROVIDER_ID IS NULL, 2, IFNULL(REFERRING_PROVIDER.DIM_PROVIDER_KEY, 1)) AS DIM_REFERRING_PROVIDER_KEY
,DATAHUB_CLAIM_DETAIL_BASE.PAID_GROSS_AMOUNT AS PAID_GROSS_AMT
,DATAHUB_CLAIM_DETAIL_BASE.SERVICE_CNT AS SERVICE_CNT
,DATAHUB_CLAIM_DETAIL_BASE.DENIED_DAY_CNT AS DENIED_DAY_CNT
,IFF(DATAHUB_CLAIM_HEADER_BASE.ATTENDING_PHYSICIAN_ID IS NULL, 2, IFNULL(ATTENDING_PHYSICIAN.DIM_PROVIDER_KEY, 1)) AS DIM_ATTENDING_PHYSICIAN_KEY
,DATAHUB_CLAIM_DETAIL_BASE.INTEREST_DISCOUNT_AMOUNT AS INTEREST_DISCOUNT_AMT
,DATAHUB_CLAIM_DETAIL_BASE.THIRD_PARTY_ALLOWED_AMOUNT AS THIRD_PARTY_ALLOWED_AMT
,DATAHUB_CLAIM_DETAIL_BASE.PAY_FOR_PERFORMANCE_AMOUNT AS PAY_FOR_PERFORMANCE_AMT
,DATAHUB_CLAIM_DETAIL_BASE.HRA_APPLIED_AMT AS HRA_APPLIED_AMT
,DATAHUB_CLAIM_DETAIL_BASE.HIA_APPLIED_AMT AS HIA_APPLIED_AMT
,DATAHUB_CLAIM_HEADER_BASE.CLAIM_ENTRY_DATE AS CLAIM_ENTERED_DATE
,DATAHUB_CLAIM_DETAIL_BASE.WITHHOLD_AMOUNT AS WITHHOLD_AMT
,DATAHUB_CLAIM_DETAIL_BASE.AP_POSTING_DATE AS ACCOUNTS_PAYABLE_POSTING_DATE
,IFF(DATAHUB_CLAIM_DETAIL_BASE.ASSIGNED_PROVIDER_ID IS NULL, 2, IFNULL(ASSIGNED_PROVIDER.DIM_PROVIDER_KEY, 1)) AS DIM_ASSIGNED_PROVIDER_KEY
,DATAHUB_CLAIM_DETAIL_BASE.ADD_DATE AS SOURCE_SYSTEM_ADD_DATE
,DATAHUB_CLAIM_DETAIL_BASE.HUB_CLAIM_DETAIL_HKEY

FROM RAWDATA.DATAHUB_CLAIM_DETAIL_BASE

    JOIN RAWDATA.DATAHUB_CLAIM_HEADER_BASE
        ON (DATAHUB_CLAIM_HEADER_BASE.HUB_CLAIM_HKEY = DATAHUB_CLAIM_DETAIL_BASE.HUB_CLAIM_HKEY)

    LEFT JOIN RAWDATA.DATAHUB_MEMBER_DETAIL_BASE
        ON (DATAHUB_MEMBER_DETAIL_BASE.HUB_MEMBER_HKEY = DATAHUB_CLAIM_DETAIL_BASE.HUB_MEMBER_HKEY)

    LEFT OUTER JOIN DIMDATA.DIM_TPA_HIERARCHY
        ON DATAHUB_CLAIM_DETAIL_BASE.TPA_CLIENT_ID = DIM_TPA_HIERARCHY.TPA_CLIENT_ID
        AND DATAHUB_CLAIM_DETAIL_BASE.TPA_DIV_ID = DIM_TPA_HIERARCHY.TPA_DIV_ID
        AND DATAHUB_CLAIM_DETAIL_BASE.TPA_ID = DIM_TPA_HIERARCHY.TPA_ID

    LEFT OUTER JOIN DIMDATA.DIM_DATA_SOURCE
        ON (DIM_DATA_SOURCE.DATA_SOURCE_NAME = DATAHUB_CLAIM_DETAIL_BASE.DATA_SOURCE_NAME)

    LEFT OUTER JOIN DIMDATA.DIM_CLAIM_HEADER
        ON (DIM_CLAIM_HEADER.TPA_CLIENT_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_CLIENT_ID
        AND DIM_CLAIM_HEADER.TPA_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_ID
        AND DIM_CLAIM_HEADER.TPA_DIV_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_DIV_ID
        AND DIM_CLAIM_HEADER.DATA_SOURCE_NAME = DATAHUB_CLAIM_DETAIL_BASE.DATA_SOURCE_NAME
        AND DIM_CLAIM_HEADER.CLAIM_NBR = DATAHUB_CLAIM_DETAIL_BASE.CLAIM_NBR)

    LEFT OUTER JOIN DIMDATA.DIM_CLAIM_DETAIL
        ON (DIM_CLAIM_DETAIL.TPA_CLIENT_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_CLIENT_ID
        AND DIM_CLAIM_DETAIL.TPA_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_ID
        AND DIM_CLAIM_DETAIL.TPA_DIV_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_DIV_ID
        AND DIM_CLAIM_DETAIL.DATA_SOURCE_NAME = DATAHUB_CLAIM_DETAIL_BASE.DATA_SOURCE_NAME
        AND DIM_CLAIM_DETAIL.CLAIM_NBR = DATAHUB_CLAIM_DETAIL_BASE.CLAIM_NBR
        AND DIM_CLAIM_DETAIL.CLAIM_LINE_NBR = DATAHUB_CLAIM_DETAIL_BASE.CLAIM_LINE_NBR
        AND DIM_CLAIM_DETAIL.CLAIM_SEQUENCE_NBR = DATAHUB_CLAIM_DETAIL_BASE.CLAIM_LINE_SEQ_NBR
        AND DIM_CLAIM_DETAIL.PROCEDURE_ADJ_CODE = DATAHUB_CLAIM_DETAIL_BASE.CLAIM_LINE_PROCEDURE_ADJ_CODE)

    LEFT OUTER JOIN DIMDATA.DIM_MEMBER 
        ON (DIM_MEMBER.TPA_CLIENT_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_CLIENT_ID
        AND DIM_MEMBER.TPA_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_ID
        AND DIM_MEMBER.TPA_DIV_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_DIV_ID
        AND DIM_MEMBER.MEMBER_NBR = DATAHUB_CLAIM_DETAIL_BASE.MEMBER_NBR)

    LEFT OUTER JOIN DIMDATA.DIM_MEMBER_DEMOGRAPHIC
        ON (DIM_MEMBER_DEMOGRAPHIC.MEMBER_GENDER_CODE = DATAHUB_MEMBER_DETAIL_BASE.GENDER_CODE
        AND DIM_MEMBER_DEMOGRAPHIC.MEMBER_AGE = TRUNCATE(DATAHUB_CLAIM_DETAIL_BASE.MEMBER_AGE_NBR)) --remove decimals

    LEFT OUTER JOIN STAGEDATA.DIM_DIAGNOSIS_RELATED_GROUP_LOOKUP
        ON (DIM_DIAGNOSIS_RELATED_GROUP_LOOKUP.HUB_CLAIM_HKEY = DATAHUB_CLAIM_DETAIL_BASE.HUB_CLAIM_HKEY)

    --made a special lookup table for enrollment spans to fix / account for bad membership data
    --this will and should get removed as the data gets corrected.
    LEFT OUTER JOIN STAGEDATA.DIM_ENROLLMENT_SPAN_LOOKUP
        ON (DIM_ENROLLMENT_SPAN_LOOKUP.TPA_CLIENT_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_CLIENT_ID
        AND DIM_ENROLLMENT_SPAN_LOOKUP.TPA_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_ID
        AND DIM_ENROLLMENT_SPAN_LOOKUP.TPA_DIV_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_DIV_ID
        AND DIM_ENROLLMENT_SPAN_LOOKUP.MEMBER_NBR = DATAHUB_CLAIM_DETAIL_BASE.MEMBER_NBR
        AND DIM_ENROLLMENT_SPAN_LOOKUP.SUB_SOURCE_NAME = DATAHUB_MEMBER_DETAIL_BASE.MEMBER_TYPE_CODE
        AND DIM_ENROLLMENT_SPAN_LOOKUP.ELIGIBILITY_START_DATE <= DATAHUB_CLAIM_DETAIL_BASE.SERVICE_BEGIN_DATE
        AND DIM_ENROLLMENT_SPAN_LOOKUP.ELIGIBILITY_END_DATE >= DATAHUB_CLAIM_DETAIL_BASE.SERVICE_BEGIN_DATE)

    LEFT OUTER JOIN DIMDATA.DIM_GROUP
        ON (DIM_GROUP.TPA_CLIENT_ID = DATAHUB_CLAIM_HEADER_BASE.TPA_CLIENT_ID
        AND DIM_GROUP.TPA_ID = DATAHUB_CLAIM_HEADER_BASE.TPA_ID
        AND DIM_GROUP.TPA_DIV_ID = DATAHUB_CLAIM_HEADER_BASE.TPA_DIV_ID
        AND DIM_GROUP.GROUP_NBR = DATAHUB_CLAIM_HEADER_BASE.GROUP_NBR)

    LEFT OUTER JOIN DIMDATA.DIM_SUB_GROUP
        ON (DIM_SUB_GROUP.TPA_CLIENT_ID = DATAHUB_CLAIM_HEADER_BASE.TPA_CLIENT_ID
        AND DIM_SUB_GROUP.TPA_ID = DATAHUB_CLAIM_HEADER_BASE.TPA_ID
        AND DIM_SUB_GROUP.TPA_DIV_ID = DATAHUB_CLAIM_HEADER_BASE.TPA_DIV_ID
        AND DIM_SUB_GROUP.GROUP_NBR = DATAHUB_CLAIM_HEADER_BASE.GROUP_NBR
        AND DIM_SUB_GROUP.SUB_GROUP_NBR = DATAHUB_CLAIM_HEADER_BASE.SUB_GROUP_NBR)        

    LEFT OUTER JOIN DIMDATA.DIM_PLAN
        ON (DIM_PLAN.TPA_CLIENT_ID = DATAHUB_CLAIM_HEADER_BASE.TPA_CLIENT_ID
        AND DIM_PLAN.TPA_ID = DATAHUB_CLAIM_HEADER_BASE.TPA_ID
        AND DIM_PLAN.TPA_DIV_ID = DATAHUB_CLAIM_HEADER_BASE.TPA_DIV_ID
        AND DIM_PLAN.PLAN_CODE = DATAHUB_CLAIM_HEADER_BASE.PLAN_CODE
        AND DIM_PLAN.PLAN_TYPE_CODE = DATAHUB_CLAIM_HEADER_BASE.PLAN_TYPE_CODE)

    LEFT OUTER JOIN DIMDATA.DIM_PLACE_OF_SERVICE
        ON (DIM_PLACE_OF_SERVICE.DIM_TPA_HIERARCHY_KEY = IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1)
        AND DIM_PLACE_OF_SERVICE.PLACE_OF_SERVICE_CODE = DATAHUB_CLAIM_HEADER_BASE.PLACE_OF_SERVICE_CODE
        AND DIM_PLACE_OF_SERVICE.SERVICE_TYPE_CODE = DATAHUB_CLAIM_DETAIL_BASE.SERVICE_TYPE_CODE
        AND DIM_PLACE_OF_SERVICE.LOCATION_CODE = DATAHUB_CLAIM_DETAIL_BASE.LOCATION_CODE)

    LEFT OUTER JOIN DIMDATA.DIM_CLAIM_PROCEDURE  DIM_CLAIM_PROCEDURE_CPT
        ON (DIM_CLAIM_PROCEDURE_CPT.DIM_TPA_HIERARCHY_KEY = IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1)
        AND DIM_CLAIM_PROCEDURE_CPT.DATA_SOURCE_NAME = DATAHUB_CLAIM_DETAIL_BASE.DATA_SOURCE_NAME
        AND DIM_CLAIM_PROCEDURE_CPT.PROCEDURE_CODE = DATAHUB_CLAIM_DETAIL_BASE.PROCEDURE_CODE
        AND DIM_CLAIM_PROCEDURE_CPT.IS_LOGICAL_DELETE_FLAG = FALSE)

    LEFT OUTER JOIN DIMDATA.DIM_COPAY_REASON_VW
        ON (DIM_COPAY_REASON_VW.DIM_TPA_HIERARCHY_KEY = IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1)
        AND DIM_COPAY_REASON_VW.DATA_SOURCE_NAME = DATAHUB_CLAIM_DETAIL_BASE.DATA_SOURCE_NAME
        AND DIM_COPAY_REASON_VW.COPAY_REASON_CODE = DATAHUB_CLAIM_DETAIL_BASE.COPAY_REASON_CODE
        AND DIM_COPAY_REASON_VW.COPAY_REASON_CODE_POSITION = DATAHUB_CLAIM_DETAIL_BASE.COPAY_REASON_CODE_POSITION)

    LEFT OUTER JOIN DIMDATA.DIM_COINSURANCE_REASON_VW
        ON (DIM_COINSURANCE_REASON_VW.DIM_TPA_HIERARCHY_KEY = IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1)
        AND DIM_COINSURANCE_REASON_VW.DATA_SOURCE_NAME = DATAHUB_CLAIM_DETAIL_BASE.DATA_SOURCE_NAME
        AND DIM_COINSURANCE_REASON_VW.COINSURANCE_REASON_CODE = DATAHUB_CLAIM_DETAIL_BASE.COINSURANCE_REASON_CODE
        AND DIM_COINSURANCE_REASON_VW.COINSURANCE_REASON_CODE_POSITION = DATAHUB_CLAIM_DETAIL_BASE.COINSURANCE_REASON_CODE_POSITION)

    LEFT OUTER JOIN DIMDATA.DIM_DEDUCTIBLE_REASON_VW
        ON (DIM_DEDUCTIBLE_REASON_VW.DIM_TPA_HIERARCHY_KEY = IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1)
        AND DIM_DEDUCTIBLE_REASON_VW.DATA_SOURCE_NAME = DATAHUB_CLAIM_DETAIL_BASE.DATA_SOURCE_NAME
        AND DIM_DEDUCTIBLE_REASON_VW.DEDUCTIBLE_REASON_CODE = DATAHUB_CLAIM_DETAIL_BASE.DEDUCTIBLE_REASON_CODE
        AND DIM_DEDUCTIBLE_REASON_VW.DEDUCTIBLE_REASON_CODE_POSITION = DATAHUB_CLAIM_DETAIL_BASE.DEDUCTIBLE_REASON_CODE_POSITION)

    LEFT OUTER JOIN DIMDATA.DIM_REVENUE_PROCEDURE 
        ON (DIM_REVENUE_PROCEDURE.REVENUE_CODE = DATAHUB_CLAIM_DETAIL_BASE.REVENUE_CODE)

    LEFT OUTER JOIN STAGEDATA.GRP_ADJUSTMENT_REASON_LOOKUP
        ON (GRP_ADJUSTMENT_REASON_LOOKUP.HUB_CLAIM_DETAIL_HKEY = DATAHUB_CLAIM_DETAIL_BASE.HUB_CLAIM_DETAIL_HKEY)

    LEFT OUTER JOIN STAGEDATA.GRP_NOT_COVERED_REASON_LOOKUP
        ON (GRP_NOT_COVERED_REASON_LOOKUP.HUB_CLAIM_DETAIL_HKEY = DATAHUB_CLAIM_DETAIL_BASE.HUB_CLAIM_DETAIL_HKEY)

    LEFT OUTER JOIN STAGEDATA.GRP_SERVICE_REASON_LOOKUP
        ON (GRP_SERVICE_REASON_LOOKUP.HUB_CLAIM_DETAIL_HKEY = DATAHUB_CLAIM_DETAIL_BASE.HUB_CLAIM_DETAIL_HKEY)

    LEFT OUTER JOIN STAGEDATA.GRP_CLAIM_RIDER_LOOKUP
        ON (GRP_CLAIM_RIDER_LOOKUP.HUB_CLAIM_HKEY = DATAHUB_CLAIM_HEADER_BASE.HUB_CLAIM_HKEY)

   LEFT OUTER JOIN STAGEDATA.GRP_PROCEDURE_MODIFIER_LOOKUP
        ON (GRP_PROCEDURE_MODIFIER_LOOKUP.HUB_CLAIM_DETAIL_HKEY = DATAHUB_CLAIM_DETAIL_BASE.HUB_CLAIM_DETAIL_HKEY)

    LEFT OUTER JOIN STAGEDATA.GRP_PROCEDURE_CATEGORY_LOOKUP
        ON (GRP_PROCEDURE_CATEGORY_LOOKUP.HUB_CLAIM_DETAIL_HKEY = DATAHUB_CLAIM_DETAIL_BASE.HUB_CLAIM_DETAIL_HKEY)

    LEFT OUTER JOIN STAGEDATA.GRP_ICD_DIAGNOSIS_LOOKUP
        ON (GRP_ICD_DIAGNOSIS_LOOKUP.HUB_CLAIM_HKEY = DATAHUB_CLAIM_HEADER_BASE.HUB_CLAIM_HKEY)

    LEFT OUTER JOIN STAGEDATA.GRP_ICD_PROCEDURE_LOOKUP
        ON (GRP_ICD_PROCEDURE_LOOKUP.HUB_CLAIM_HKEY = DATAHUB_CLAIM_HEADER_BASE.HUB_CLAIM_HKEY)
   
--********************************************************
-- These provider joins might need addressed again when MC400UPM data, etc
--********************************************************
    LEFT OUTER JOIN PROVIDER_LOOKUP_CTE BILLING_PROVIDER
        ON (BILLING_PROVIDER.TPA_ID = DATAHUB_CLAIM_HEADER_BASE.TPA_ID
        AND BILLING_PROVIDER.TPA_CLIENT_ID = DATAHUB_CLAIM_HEADER_BASE.TPA_CLIENT_ID
        AND BILLING_PROVIDER.TPA_DIVISION_ID = DATAHUB_CLAIM_HEADER_BASE.TPA_DIV_ID
        AND BILLING_PROVIDER.DATA_SOURCE_NAME = DATAHUB_CLAIM_HEADER_BASE.DATA_SOURCE_NAME
        AND BILLING_PROVIDER.PROVIDER_ID = DATAHUB_CLAIM_HEADER_BASE.BILLING_PROVIDER_ID)

    LEFT OUTER JOIN PROVIDER_LOOKUP_CTE RENDERING_PROVIDER
        ON (RENDERING_PROVIDER.TPA_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_ID
        AND RENDERING_PROVIDER.TPA_CLIENT_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_CLIENT_ID
        AND RENDERING_PROVIDER.TPA_DIVISION_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_DIV_ID
        AND RENDERING_PROVIDER.DATA_SOURCE_NAME = DATAHUB_CLAIM_DETAIL_BASE.DATA_SOURCE_NAME
        AND RENDERING_PROVIDER.PROVIDER_ID = DATAHUB_CLAIM_DETAIL_BASE.RENDERING_PROVIDER_ID)

    LEFT OUTER JOIN PROVIDER_LOOKUP_CTE REFERRING_PROVIDER
        ON (REFERRING_PROVIDER.TPA_ID = DATAHUB_CLAIM_HEADER_BASE.TPA_ID
        AND REFERRING_PROVIDER.TPA_CLIENT_ID = DATAHUB_CLAIM_HEADER_BASE.TPA_CLIENT_ID
        AND REFERRING_PROVIDER.TPA_DIVISION_ID = DATAHUB_CLAIM_HEADER_BASE.TPA_DIV_ID
        AND REFERRING_PROVIDER.DATA_SOURCE_NAME = DATAHUB_CLAIM_HEADER_BASE.DATA_SOURCE_NAME
        AND REFERRING_PROVIDER.PROVIDER_ID = DATAHUB_CLAIM_HEADER_BASE.REFERRING_PROVIDER_ID)

    LEFT OUTER JOIN PROVIDER_LOOKUP_CTE ATTENDING_PHYSICIAN
        ON (ATTENDING_PHYSICIAN.TPA_CLIENT_ID = DATAHUB_CLAIM_HEADER_BASE.TPA_CLIENT_ID
        AND ATTENDING_PHYSICIAN.TPA_ID = DATAHUB_CLAIM_HEADER_BASE.TPA_ID
        AND ATTENDING_PHYSICIAN.TPA_DIVISION_ID = DATAHUB_CLAIM_HEADER_BASE.TPA_DIV_ID
        AND ATTENDING_PHYSICIAN.DATA_SOURCE_NAME = DATAHUB_CLAIM_HEADER_BASE.DATA_SOURCE_NAME
        AND ATTENDING_PHYSICIAN.PROVIDER_ID = DATAHUB_CLAIM_HEADER_BASE.ATTENDING_PHYSICIAN_ID)

    LEFT OUTER JOIN PROVIDER_LOOKUP_CTE ASSIGNED_PROVIDER
        ON (ASSIGNED_PROVIDER.TPA_CLIENT_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_CLIENT_ID
        AND ASSIGNED_PROVIDER.TPA_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_ID
        AND ASSIGNED_PROVIDER.TPA_DIVISION_ID = DATAHUB_CLAIM_DETAIL_BASE.TPA_DIV_ID
        AND ASSIGNED_PROVIDER.DATA_SOURCE_NAME = DATAHUB_CLAIM_DETAIL_BASE.DATA_SOURCE_NAME
        AND ASSIGNED_PROVIDER.PROVIDER_ID = DATAHUB_CLAIM_DETAIL_BASE.ASSIGNED_PROVIDER_ID)

    LEFT OUTER JOIN DIMDATA.DIM_DATE_DAY DIM_DATE_DAY_RECEIVED
        ON (DIM_DATE_DAY_RECEIVED.FULL_DATE = DATAHUB_CLAIM_DETAIL_BASE.CLAIM_RECEIVED_DATE)

    LEFT OUTER JOIN DIMDATA.DIM_DATE_DAY DIM_DATE_DAY_PAYMENT
        ON (DIM_DATE_DAY_PAYMENT.FULL_DATE = DATAHUB_CLAIM_DETAIL_BASE.PAYMENT_DATE)

    LEFT OUTER JOIN DIMDATA.DIM_DATE_DAY DIM_DATE_DAY_SERVICE_BEGIN
        ON (DIM_DATE_DAY_SERVICE_BEGIN.FULL_DATE = DATAHUB_CLAIM_DETAIL_BASE.SERVICE_BEGIN_DATE)

    LEFT OUTER JOIN DIMDATA.DIM_DATE_DAY DIM_DATE_DAY_SERVICE_END
        ON (DIM_DATE_DAY_SERVICE_END.FULL_DATE = DATAHUB_CLAIM_DETAIL_BASE.SERVICE_END_DATE)
    
    LEFT OUTER JOIN DIMDATA.DIM_DATE_DAY DIM_DATE_DAY_ADMIT_DATE
        ON (DIM_DATE_DAY_ADMIT_DATE.FULL_DATE = DATAHUB_CLAIM_HEADER_BASE.ADMITTED_DATE)

    LEFT OUTER JOIN DIMDATA.DIM_DATE_DAY DIM_DATE_DAY_DISCHARGE_DATE
        ON (DIM_DATE_DAY_DISCHARGE_DATE.FULL_DATE = DATAHUB_CLAIM_HEADER_BASE.DISCHARGE_DATE)

     LEFT OUTER JOIN DIMDATA.DIM_MEMBER_ADDRESS_PHYSICAL_VW
        ON (DIM_MEMBER_ADDRESS_PHYSICAL_VW.DIM_MEMBER_KEY = DIM_MEMBER.DIM_MEMBER_KEY
        AND DIM_MEMBER_ADDRESS_PHYSICAL_VW.EFFECTIVE_START_DATE <= DATAHUB_CLAIM_DETAIL_BASE.SERVICE_BEGIN_DATE
        AND DIM_MEMBER_ADDRESS_PHYSICAL_VW.EFFECTIVE_END_DATE >= DATAHUB_CLAIM_DETAIL_BASE.SERVICE_BEGIN_DATE
        AND DIM_MEMBER_ADDRESS_PHYSICAL_VW.EFFECTIVE_START_DATE < DIM_MEMBER_ADDRESS_PHYSICAL_VW.EFFECTIVE_END_DATE) -- remove same day data errors)

    LEFT OUTER JOIN (SELECT DIM_MEMBER_ADDRESS_PHYSICAL_VW.DIM_MEMBER_ADDRESS_PHYSICAL_KEY, DIM_MEMBER_ADDRESS_PHYSICAL_VW.DIM_MEMBER_KEY
                    FROM DIMDATA.DIM_MEMBER_ADDRESS_PHYSICAL_VW
                        JOIN (SELECT DIM_MEMBER_KEY, MAX(EFFECTIVE_START_DATE) AS EFFECTIVE_START_DATE_MAX
                                FROM DIMDATA.DIM_MEMBER_ADDRESS_PHYSICAL_VW
                                GROUP BY DIM_MEMBER_KEY
                            ) CURRENT_RECORD
                        ON (CURRENT_RECORD.DIM_MEMBER_KEY = DIM_MEMBER_ADDRESS_PHYSICAL_VW.DIM_MEMBER_KEY
                        AND CURRENT_RECORD.EFFECTIVE_START_DATE_MAX = DIM_MEMBER_ADDRESS_PHYSICAL_VW.EFFECTIVE_START_DATE
                        AND DIM_MEMBER_ADDRESS_PHYSICAL_VW.ACTIVE_IND = 'Y')
                     ) CURRENT_MEMBER_ADDRESS
        ON  (CURRENT_MEMBER_ADDRESS.DIM_MEMBER_KEY = DIM_MEMBER.DIM_MEMBER_KEY)

WHERE DATAHUB_CLAIM_HEADER_BASE.IS_PREDETERMINATION_CLAIM_FLAG = FALSE -- Filter out Pre-D claims, which shouldn't be with claims data.
