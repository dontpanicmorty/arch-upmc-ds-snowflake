CREATE OR REPLACE VIEW STAGEDATA.DIM_ICD_CATEGORY_SELECT_VW
AS
SELECT
IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1) AS DIM_TPA_HIERARCHY_KEY
,RDS.DATA_SOURCE_NAME
,IFNULL(RDS.SOURCE_VERSION,'Undefined') AS ICD_VERSION_NBR
,RDS.TARGET_VALUE AS ICD_CATEGORY_CODE
,RDS.TARGET_DESC AS ICD_CATEGORY_DESC
,RDS.REFERENCE_KEY
FROM STAGEDATA.REFERENCE_DATA_SINGULAR_VW RDS
    JOIN (SELECT TPA_KEY, DATA_SOURCE_NAME, SOURCE_VERSION, TARGET_VALUE, MAX(EFFECTIVE_START_DATE) AS EFFECTIVE_START_DATE
            FROM STAGEDATA.REFERENCE_DATA_SINGULAR_VW
            WHERE TARGET_REFERENCE_SET = 'icdCategory'
            GROUP BY TPA_KEY, DATA_SOURCE_NAME, SOURCE_VERSION, TARGET_VALUE) CURRENT_RECORD
        ON (CURRENT_RECORD.TPA_KEY = RDS.TPA_KEY
        AND CURRENT_RECORD.DATA_SOURCE_NAME = RDS.DATA_SOURCE_NAME
        AND EQUAL_NULL(CURRENT_RECORD.SOURCE_VERSION, RDS.SOURCE_VERSION)
        AND CURRENT_RECORD.TARGET_VALUE = RDS.TARGET_VALUE
        AND CURRENT_RECORD.EFFECTIVE_START_DATE = RDS.EFFECTIVE_START_DATE)

    LEFT OUTER JOIN DIMDATA.DIM_TPA_HIERARCHY
        ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = RDS.TPA_CLIENT_ID
        AND DIM_TPA_HIERARCHY.TPA_ID = RDS.TPA_ID
        AND DIM_TPA_HIERARCHY.TPA_DIV_ID = RDS.TPA_DIV_ID)
WHERE RDS.TARGET_REFERENCE_SET = 'icdCategory'
AND RDS.DATA_SOURCE_NAME NOT IN (SELECT DISTINCT DATA_SOURCE_NAME FROM RAWDATA.DATAHUB_REFDATA_CLAIM_ICD_DIAGNOSIS_CATEGORY)

UNION ALL

SELECT
IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1) AS DIM_TPA_HIERARCHY_KEY
,DATAHUB_REFDATA_CLAIM_ICD_DIAGNOSIS_CATEGORY.DATA_SOURCE_NAME
,'n/a' AS ICD_VERSION_NBR
,DATAHUB_REFDATA_CLAIM_ICD_DIAGNOSIS_CATEGORY.CODE AS ICD_CATEGORY_CODE
,DATAHUB_REFDATA_CLAIM_ICD_DIAGNOSIS_CATEGORY.CODE_DESC AS ICD_CATEGORY_DESC
,DATAHUB_REFDATA_CLAIM_ICD_DIAGNOSIS_CATEGORY.CODE AS REFERENCE_KEY
FROM RAWDATA.DATAHUB_REFDATA_CLAIM_ICD_DIAGNOSIS_CATEGORY
    LEFT OUTER JOIN DIMDATA.DIM_TPA_HIERARCHY
        ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = DATAHUB_REFDATA_CLAIM_ICD_DIAGNOSIS_CATEGORY.TPA_CLIENT_ID
        AND DIM_TPA_HIERARCHY.TPA_ID = DATAHUB_REFDATA_CLAIM_ICD_DIAGNOSIS_CATEGORY.TPA_ID
        AND DIM_TPA_HIERARCHY.TPA_DIV_ID = DATAHUB_REFDATA_CLAIM_ICD_DIAGNOSIS_CATEGORY.TPA_DIV_ID)
;
