CREATE OR REPLACE VIEW STAGEDATA.BRIDGE_APP_EVENT_PARAMETER_SELECT_VW
AS
SELECT
DIM_APP_EVENT.DIM_APP_EVENT_KEY
,IFNULL(DIM_APP_EVENT_PARAMETER.DIM_APP_EVENT_PARAMETER_KEY, 1) AS DIM_APP_EVENT_PARAMETER_KEY
FROM (SELECT DIM_APP_EVENT.DIM_APP_EVENT_KEY, EVENT_VALUES.value:key AS EVENT_PARAMETER_NAME, EVENT_VALUES.value:value AS EVENT_PARAMETER_VALUE
    FROM DIMDATA.DIM_APP_EVENT
    ,TABLE(FLATTEN(EVENT_VALUES)) EVENT_VALUES
    ) AS DIM_APP_EVENT
    LEFT OUTER JOIN DIMDATA.DIM_APP_EVENT_PARAMETER
        ON (DIM_APP_EVENT_PARAMETER.EVENT_PARAMETER_NAME = DIM_APP_EVENT.EVENT_PARAMETER_NAME
        AND DIM_APP_EVENT_PARAMETER.EVENT_PARAMETER_VALUE = DIM_APP_EVENT.EVENT_PARAMETER_VALUE)
;