CREATE OR REPLACE VIEW STAGEDATA.DIM_ICD_PROCEDURE_SELECT_VW
AS
SELECT DISTINCT
IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1) AS DIM_TPA_HIERARCHY_KEY
,DATAHUB_CLAIM_HEADER_ICD_PROCEDURE_CODE.DATA_SOURCE_NAME
,DATAHUB_CLAIM_HEADER_ICD_PROCEDURE_CODE.CODE_VERSION AS ICD_VERSION_NBR
,DATAHUB_CLAIM_HEADER_ICD_PROCEDURE_CODE.CODE_VALUE AS ICD_PROCEDURE_CODE
,DATAHUB_CLAIM_HEADER_ICD_PROCEDURE_CODE.CODE_DESC AS ICD_PROCEDURE_DESC
,NULL AS REFERENCE_KEY
,NULL AS URI
,DATAHUB_CLAIM_HEADER_ICD_PROCEDURE_CODE.ICD_PROCEDURE_CATEGORIES AS CHILD_IDS
FROM RAWDATA.DATAHUB_CLAIM_HEADER_ICD_PROCEDURE_CODE
    LEFT OUTER JOIN DIMDATA.DIM_TPA_HIERARCHY
        ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = DATAHUB_CLAIM_HEADER_ICD_PROCEDURE_CODE.TPA_CLIENT_ID
        AND DIM_TPA_HIERARCHY.TPA_ID = DATAHUB_CLAIM_HEADER_ICD_PROCEDURE_CODE.TPA_ID
        AND DIM_TPA_HIERARCHY.TPA_DIV_ID = DATAHUB_CLAIM_HEADER_ICD_PROCEDURE_CODE.TPA_DIV_ID)
;
