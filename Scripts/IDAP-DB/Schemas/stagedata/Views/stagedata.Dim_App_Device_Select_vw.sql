CREATE OR REPLACE VIEW STAGEDATA.DIM_APP_DEVICE_SELECT_VW
AS 
SELECT
APIM_LOGS_KEY
,PRODUCT AS APP_PRODUCT_NAME
,DEVICE_PLATFORM AS DEVICE_OS_PLATFORM_NAME
,IFNULL(DEVICE_OPERATING_SYSTEM,'Unknown') AS DEVICE_OS_VERSION_NBR
,IFNULL(DEVICE_MODEL_NAME,'Unknown') AS DEVICE_MODEL_NAME
FROM STAGEDATA.APIM_LOGS_MOBILE_VW
WHERE DEVICE_PLATFORM IS NOT NULL;