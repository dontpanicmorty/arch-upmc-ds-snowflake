CREATE OR REPLACE VIEW STAGEDATA.DIM_NOT_COVERED_REASON_SELECT_VW
AS
SELECT
IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1) AS DIM_TPA_HIERARCHY_KEY
,RDS.DATA_SOURCE_NAME
,RDS.TARGET_VALUE AS NOT_COVERED_REASON_CODE
,'Reason' AS NOT_COVERED_REASON_TYPE
,'All' AS LINE_OF_BUSINESS_CODE
,RDS.TARGET_DESC AS NOT_COVERED_REASON_DESC
,RDS.HIPAA_277_CODE
,RDS.HIPAA_835_CODE
FROM STAGEDATA.REFERENCE_DATA_SINGULAR_VW RDS
    JOIN (SELECT TARGET_REFERENCE_SET, TPA_KEY, DATA_SOURCE_NAME, TARGET_VALUE, MAX(EFFECTIVE_START_DATE) AS EFFECTIVE_START_DATE
        FROM STAGEDATA.REFERENCE_DATA_SINGULAR_VW
        WHERE TARGET_REFERENCE_SET ='notCoveredReason'
        GROUP BY TARGET_REFERENCE_SET, TPA_KEY, DATA_SOURCE_NAME, TARGET_VALUE) CURRENT_RECORD
        ON (CURRENT_RECORD.TARGET_REFERENCE_SET = RDS.TARGET_REFERENCE_SET
        AND CURRENT_RECORD.TPA_KEY = RDS.TPA_KEY
        AND CURRENT_RECORD.DATA_SOURCE_NAME = RDS.DATA_SOURCE_NAME
        AND CURRENT_RECORD.TARGET_VALUE = RDS.TARGET_VALUE
        AND CURRENT_RECORD.EFFECTIVE_START_DATE = RDS.EFFECTIVE_START_DATE)
    LEFT OUTER JOIN DIMDATA.DIM_TPA_HIERARCHY
        ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = RDS.TPA_CLIENT_ID
        AND DIM_TPA_HIERARCHY.TPA_ID = RDS.TPA_ID
        AND DIM_TPA_HIERARCHY.TPA_DIV_ID = RDS.TPA_DIV_ID)
WHERE RDS.TARGET_REFERENCE_SET = 'notCoveredReason'
AND RDS.DATA_SOURCE_NAME NOT IN (SELECT DISTINCT DATA_SOURCE_NAME FROM RAWDATA.DATAHUB_CLAIM_DETAIL_NOT_COVERED_REASON_CODE)

UNION ALL

SELECT DISTINCT
IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1) AS DIM_TPA_HIERARCHY_KEY
,DATAHUB_CLAIM_DETAIL_NOT_COVERED_REASON_CODE.DATA_SOURCE_NAME
,DATAHUB_CLAIM_DETAIL_NOT_COVERED_REASON_CODE.NOT_COVERED_REASON_CODE 
,DATAHUB_CLAIM_DETAIL_NOT_COVERED_REASON_CODE.NOT_COVERED_REASON_TYPE
,DATAHUB_CLAIM_DETAIL_NOT_COVERED_REASON_CODE.LINE_OF_BUSINESS_CODE
,DATAHUB_CLAIM_DETAIL_NOT_COVERED_REASON_CODE.NOT_COVERED_REASON_DESC
,DATAHUB_CLAIM_DETAIL_NOT_COVERED_REASON_CODE.HIPAA_277_CODE
,DATAHUB_CLAIM_DETAIL_NOT_COVERED_REASON_CODE.HIPAA_835_CODE
FROM RAWDATA.DATAHUB_CLAIM_DETAIL_NOT_COVERED_REASON_CODE
    LEFT OUTER JOIN DIMDATA.DIM_TPA_HIERARCHY
        ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = DATAHUB_CLAIM_DETAIL_NOT_COVERED_REASON_CODE.TPA_CLIENT_ID
        AND DIM_TPA_HIERARCHY.TPA_ID = DATAHUB_CLAIM_DETAIL_NOT_COVERED_REASON_CODE.TPA_ID
        AND DIM_TPA_HIERARCHY.TPA_DIV_ID = DATAHUB_CLAIM_DETAIL_NOT_COVERED_REASON_CODE.TPA_DIV_ID)

;
