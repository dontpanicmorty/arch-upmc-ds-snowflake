CREATE OR REPLACE VIEW STAGEDATA.GRP_NOT_COVERED_REASON_SELECT_VW
AS
SELECT
GRP_NOT_COVERED_REASON.GRP_NOT_COVERED_REASON_KEY
,IFNULL(DIM_NOT_COVERED_REASON.DIM_NOT_COVERED_REASON_KEY, 1) AS DIM_NOT_COVERED_REASON_KEY
,NOT_COVERED.CODE_POSITION AS NOT_COVERED_REASON_POSITION_NBR
,NOT_COVERED.CLAIM_DETAIL_NOT_COVERED_REASON_CODE_KEY
FROM STAGEDATA.CLAIM_DETAIL_NOT_COVERED_REASON_CODE NOT_COVERED
	JOIN STAGEDATA.CLAIM_DETAIL_NOT_COVERED_REASON_CODE_GRP
		ON (CLAIM_DETAIL_NOT_COVERED_REASON_CODE_GRP.CLAIM_DETAIL_NOT_COVERED_REASON_CODE_KEY = NOT_COVERED.CLAIM_DETAIL_NOT_COVERED_REASON_CODE_KEY) 

	JOIN STAGEDATA.GRP_NOT_COVERED_REASON
		ON (GRP_NOT_COVERED_REASON.CODE_VALUE = CLAIM_DETAIL_NOT_COVERED_REASON_CODE_GRP.CODE_VALUE)	

	LEFT OUTER JOIN DIMDATA.DIM_TPA_HIERARCHY
		ON (DIM_TPA_HIERARCHY.TPA_CLIENT_ID = NOT_COVERED.TPA_CLIENT_ID
		AND DIM_TPA_HIERARCHY.TPA_ID = NOT_COVERED.TPA_ID
		AND DIM_TPA_HIERARCHY.TPA_DIV_ID = NOT_COVERED.TPA_DIV_ID)

	LEFT OUTER JOIN DIMDATA.DIM_NOT_COVERED_REASON
		ON (DIM_NOT_COVERED_REASON.DIM_TPA_HIERARCHY_KEY = IFNULL(DIM_TPA_HIERARCHY.DIM_TPA_HIERARCHY_KEY, 1)
		AND DIM_NOT_COVERED_REASON.DATA_SOURCE_NAME = NOT_COVERED.DATA_SOURCE_NAME
		AND DIM_NOT_COVERED_REASON.NOT_COVERED_REASON_CODE = NOT_COVERED.CODE_VALUE
		AND DIM_NOT_COVERED_REASON.NOT_COVERED_REASON_TYPE = NOT_COVERED.CODE_TYPE
		AND DIM_NOT_COVERED_REASON.LINE_OF_BUSINESS_CODE = NOT_COVERED.LINE_OF_BUSINESS_CODE)
;