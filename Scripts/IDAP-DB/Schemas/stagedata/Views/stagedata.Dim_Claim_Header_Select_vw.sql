CREATE OR REPLACE VIEW STAGEDATA.DIM_CLAIM_HEADER_SELECT_VW
AS
--Claims from data sources not in UPMCHP_DATAHUB
SELECT
    CLAIM_HEADER_VW.TPA_CLIENT_ID
    ,CLAIM_HEADER_VW.TPA_ID
    ,CLAIM_HEADER_VW.TPA_DIV_ID
    ,CLAIM_HEADER_VW.DATA_SOURCE_NAME
    ,CLAIM_HEADER_VW.CLAIM_NBR
    ,CONCAT(CLAIM_HEADER_VW.TPA_CLIENT_ID,
            CLAIM_HEADER_VW.TPA_ID,
            CLAIM_HEADER_VW.TPA_DIV_ID,
            CLAIM_HEADER_VW.DATA_SOURCE_NAME,
            CLAIM_HEADER_VW.CLAIM_NBR
            ) AS DATA_HUB_UNIVERSAL_CLAIM_ID
    ,CLAIM_HEADER_VW.CARE_TYPE_NAME
    ,CASE 
         WHEN CLAIM_DETAIL_PAID_AMT.TOTAL_PAID_AMT >= 200000 THEN 'Y'
         ELSE 'N'
     END AS SHOCK_CLAIM_IND
    ,CLAIM_HEADER_VW.PROVIDER_ACCT_NBR
    ,CLAIM_HEADER_VW.IPA_CODE AS CLAIM_IPA_CODE
    ,CLAIM_HEADER_VW.ELECTRONIC_CLAIM_TYPE_CODE
    ,CLAIM_TYPE_CODE.TARGET_DESC AS ELECTRONIC_CLAIM_TYPE_DESC
    ,CLAIM_HEADER_VW.BILL_TYPE_CODE
    ,BILL_TYPE.TARGET_DESC AS BILL_TYPE_DESC
    ,CLAIM_HEADER_VW.BILLING_PROVIDER_VENDOR_NBR AS BILLING_PROVIDER_VENDOR_NBR
    ,CLAIM_HEADER_VW.UB92_DISCHARGE_STATUS_CODE AS DISCHARGE_STATUS_CODE
    ,IFNULL(DISCHARGE_STATUS_DESC.TARGET_DESC,'n/a') AS DISCHARGE_STATUS_DESC
    ,CLAIM_HEADER_VW.UB92_ADMISSION_SOURCE_CODE AS ADMISSION_SOURCE_CODE
    ,IFNULL(ADMISSION_SOURCE_DESC.TARGET_DESC,'n/a') AS ADMISSION_SOURCE_DESC
    ,CLAIM_HEADER_VW.UB92_ADMISSION_TYPE_CODE AS ADMISSION_TYPE_CODE
    ,IFNULL(ADMISSION_TYPE_CODE.TARGET_DESC,'n/a') AS ADMISSION_TYPE_DESC
    ,CLAIM_HEADER_VW.BILLING_PROVIDER_PARTICIPATING_STATUS_CODE AS CLAIM_BILL_PROVIDER_PAR_STATUS_CODE
    ,CONCAT(CLAIM_BILL_PROVIDER_PAR_STATUS_CODE, CLAIM_IPA_CODE) AS BILLING_PROVIDER_STATUS_CODE
    ,IFNULL(CLAIM_HEADER_VW.PRICING_ZIP_SOURCE,'n/a') AS PRICE_ZIP_SOURCE_IND
    ,IFNULL(CLAIM_HEADER_VW.PAID_PRES_ZIPCODE,'n/a') AS SERVICE_ZIP_CODE
    ,IFNULL(EDI_837_FACILITY_NPI_NBR,'Unknown') AS EDI_837_FACILITY_NPI_NBR
    ,IFNULL(EDI_837_FACILITY_NAME,'Unknown') AS EDI_837_FACILITY_NAME
    ,IFNULL(EDI_837_FACILITY_TELEPHONE_NBR,'Unknown') AS EDI_837_FACILITY_TELEPHONE_NBR
    ,IFNULL(EDI_837_FACILITY_ADDRESS_LINE_1_TEXT,'Unknown') AS EDI_837_FACILITY_ADDRESS_LINE_1_TEXT
    ,IFNULL(EDI_837_FACILITY_ADDRESS_LINE_2_TEXT,'Unknown') AS EDI_837_FACILITY_ADDRESS_LINE_2_TEXT
    ,IFNULL(EDI_837_FACILITY_STATE_ABBREV_NAME,'Unknown') AS EDI_837_FACILITY_STATE_ABBREV_NAME
    ,IFNULL(EDI_837_FACILITY_ZIP_CODE_NBR,'Unknown') AS EDI_837_FACILITY_ZIP_CODE_NBR
    ,IFNULL(EDI_837_FACILITY_OTHER_ID,'Unknown') AS EDI_837_FACILITY_OTHER_ID
    ,CLAIM_HEADER_VW.DISCHARGE_DATE AS DISCHARGE_DATE
    ,CLAIM_HEADER_VW.DISCHARGE_HOUR AS DISCHARGE_HOUR
    ,CLAIM_HEADER_VW.ADMIT_DATE AS ADMISSION_DATE
    ,CLAIM_HEADER_VW.ADMIT_HOUR AS ADMISSION_HOUR
    ,IFNULL(CLAIM_HEADER_VW.DIAGNOSIS_RELATED_GROUP_CODE,'n/a') AS DIAGNOSIS_RELATED_GROUP_CODE
    ,CASE 
        WHEN CLAIM_HEADER_VW.DIAGNOSIS_RELATED_GROUP_CODE IS NULL THEN 'n/a'
        ELSE CLAIM_HEADER_VW.DATA_HUB_UNIVERSAL_DRG_ID 
    END AS DATA_HUB_UNIVERSAL_DRG_ID
    ,CLAIM_HEADER_VW.SEVERITY_OF_ILLNESS AS SEVERITY_OF_ILLNESS
    ,CLAIM_HEADER_VW.MICROFILM_NBR AS MICROFILM_NBR
    ,CLAIM_HEADER_VW.CLAIM_TYPE_CODE AS CLAIM_TYPE_CODE
    ,NULL AS ORIGINAL_CLAIM_ID
    ,NULL AS MULTISOURCE_CLAIM_IND
    ,NULL AS PROVIDER_SPECIALTY
    ,NULL AS PAID_STATUS_FOR_CMS
    ,'MARKLOGIC' AS SOURCE_SYSTEM
    ,TO_VARCHAR(CLAIM_HEADER_VW.CLAIM_HEADER_KEY) AS SOURCE_ID
FROM STAGEDATA.CLAIM_HEADER_VW

    LEFT OUTER JOIN STAGEDATA.REFERENCE_DATA_SINGULAR_CURRENT_VW CLAIM_TYPE_CODE
        ON (CLAIM_TYPE_CODE.TARGET_REFERENCE_SET = 'claimTypeCode'
        AND CLAIM_TYPE_CODE.DATA_SOURCE_NAME = CLAIM_HEADER_VW.DATA_SOURCE_NAME
        AND CLAIM_TYPE_CODE.SOURCE_VALUE = CLAIM_HEADER_VW.ELECTRONIC_CLAIM_TYPE_CODE)

    LEFT OUTER JOIN STAGEDATA.REFERENCE_DATA_SINGULAR_CURRENT_VW BILL_TYPE
        ON (BILL_TYPE.TARGET_REFERENCE_SET = 'ub92BillType'
        AND BILL_TYPE.REFERENCE_KEY =  CLAIM_HEADER_VW.BILL_TYPE_DESC_KEY
        AND BILL_TYPE.SOURCE_VALUE = CLAIM_HEADER_VW.BILL_TYPE_CODE)

    LEFT OUTER JOIN STAGEDATA.REFERENCE_DATA_SINGULAR_VW DISCHARGE_STATUS_DESC
        ON (DISCHARGE_STATUS_DESC.TARGET_REFERENCE_SET = 'ub92DischargeStatus'
        AND DISCHARGE_STATUS_DESC.REFERENCE_KEY = CLAIM_HEADER_VW.UB92_DISCHARGE_STATUS_DESC_KEY)

    LEFT OUTER JOIN STAGEDATA.REFERENCE_DATA_SINGULAR_VW ADMISSION_SOURCE_DESC
        ON (ADMISSION_SOURCE_DESC.TARGET_REFERENCE_SET IN ('ub92AdmissionSource1','ub92AdmissionSource2')
        AND ADMISSION_SOURCE_DESC.REFERENCE_KEY = CLAIM_HEADER_VW.UB92_ADMISSION_SOURCE_DESC_KEY)

    LEFT OUTER JOIN STAGEDATA.REFERENCE_DATA_SINGULAR_VW ADMISSION_TYPE_CODE
        ON (ADMISSION_TYPE_CODE.TARGET_REFERENCE_SET = 'ub92AdmissionType'
        AND ADMISSION_TYPE_CODE.REFERENCE_KEY = CLAIM_HEADER_VW.UB92_ADMISSION_TYPE_DESC_KEY)
    
    LEFT OUTER JOIN 
    	    (
            SELECT TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_NBR, IFNULL(SUM(PAID_AMT), 0) AS TOTAL_PAID_AMT
            FROM STAGEDATA.CLAIM_DETAIL_RAW_VW --Used RAW view on purpose for performance and there is no modifications in non-RAW View
            GROUP BY TPA_CLIENT_ID, TPA_ID, TPA_DIV_ID, DATA_SOURCE_NAME, CLAIM_NBR
            ) CLAIM_DETAIL_PAID_AMT
        ON (CLAIM_DETAIL_PAID_AMT.TPA_CLIENT_ID = CLAIM_HEADER_VW.TPA_CLIENT_ID
            AND CLAIM_DETAIL_PAID_AMT.TPA_ID = CLAIM_HEADER_VW.TPA_ID
            AND CLAIM_DETAIL_PAID_AMT.TPA_DIV_ID = CLAIM_HEADER_VW.TPA_DIV_ID
            AND CLAIM_DETAIL_PAID_AMT.DATA_SOURCE_NAME = CLAIM_HEADER_VW.DATA_SOURCE_NAME
            AND CLAIM_DETAIL_PAID_AMT.CLAIM_NBR = CLAIM_HEADER_VW.CLAIM_NBR)

--Non-Skygen claims from ML whose data sources have not yet been migrated to the DATAHUB
WHERE CLAIM_HEADER_VW.DATA_SOURCE_NAME NOT IN (SELECT DISTINCT DATA_SOURCE_NAME FROM RAWDATA.DATAHUB_CLAIM_DETAIL_BASE)
        AND
        (
            claim_header_vw.CLAIM_TYPE_CODE NOT IN ('P','A') -- Filter out Pre-D claims, which shouldn't be with claims data.
            OR claim_header_vw.CLAIM_TYPE_CODE IS NULL -- This line needed because Claim_Type_Code coming from NVA is NULL, which isn't caught in the above line.
        )
-------------------------------------------------------
UNION ALL 

-------------------------------------------------------
-- The claims from UPMCHP_DATAHUB
-------------------------------------------------------

SELECT
    TPA_CLIENT_ID
    ,TPA_ID
    ,TPA_DIV_ID
    ,DATA_SOURCE_NAME
    ,CLAIM_NBR
    ,CONCAT(TPA_CLIENT_ID,TPA_ID,TPA_DIV_ID,DATA_SOURCE_NAME,CLAIM_NBR) AS DATA_HUB_UNIVERSAL_CLAIM_ID
    ,CARE_TYPE_NAME
    ,SHOCK_CLAIM_IND
    ,PATIENT_ACCOUNT_NUMBER AS PROVIDER_ACCT_NBR
    ,IPA_CODE AS CLAIM_IPA_CODE
    ,ELECTRONIC_CLAIM_TYPE_CODE
    ,ELECTRONIC_CLAIM_TYPE_DESC
    ,IFF(UPPER(CARE_TYPE_NAME) <> 'MEDICAL', 'n/a', BILLING_TYPE_CODE) AS BILL_TYPE_CODE
    ,IFF(UPPER(CARE_TYPE_NAME) <> 'MEDICAL', 'n/a', BILLING_TYPE_DESC) AS BILL_TYPE_DESC
    ,BILLING_PROVIDER_VENDOR_NBR
    ,IFF(UPPER(CARE_TYPE_NAME) <> 'MEDICAL', 'n/a', DISCHARGE_STATUS_CODE) AS DISCHARGE_STATUS_CODE
    ,IFF(UPPER(CARE_TYPE_NAME) <> 'MEDICAL', 'n/a', DISCHARGE_STATUS_DESC) AS DISCHARGE_STATUS_DESC
    ,IFF(UPPER(CARE_TYPE_NAME) <> 'MEDICAL', 'n/a', ADMISSION_SOURCE_CODE) AS ADMISSION_SOURCE_CODE
    ,IFF(UPPER(CARE_TYPE_NAME) <> 'MEDICAL', 'n/a', ADMISSION_SOURCE_DESC) AS ADMISSION_SOURCE_DESC
    ,IFF(UPPER(CARE_TYPE_NAME) <> 'MEDICAL', 'n/a', ADMISSION_TYPE_CODE) AS ADMISSION_TYPE_CODE
    ,IFF(UPPER(CARE_TYPE_NAME) <> 'MEDICAL', 'n/a', ADMISSION_TYPE_DESC) AS ADMISSION_TYPE_DESC
    ,BILLING_PROVIDER_PARTICIPATING_STATUS_CODE AS CLAIM_BILL_PROVIDER_PAR_STATUS_CODE
    ,CONCAT(CLAIM_BILL_PROVIDER_PAR_STATUS_CODE, CLAIM_IPA_CODE) AS BILLING_PROVIDER_STATUS_CODE
    ,IFF(UPPER(CARE_TYPE_NAME) <> 'MEDICAL', 'n/a', PRICING_ZIP_SOURCE) AS PRICE_ZIP_SOURCE_IND
    ,IFF(UPPER(CARE_TYPE_NAME) <> 'MEDICAL', 'n/a', SERVICE_ZIP_CODE) AS SERVICE_ZIP_CODE
    ,IFF(UPPER(CARE_TYPE_NAME) <> 'MEDICAL', 'n/a', EDI_837_FACILITY_NPI_NBR) AS EDI_837_FACILITY_NPI_NBR
    ,IFF(UPPER(CARE_TYPE_NAME) <> 'MEDICAL', 'n/a', EDI_837_FACILITY_NAME) AS EDI_837_FACILITY_NAME
    ,IFF(UPPER(CARE_TYPE_NAME) <> 'MEDICAL', 'n/a', EDI_837_FACILITY_TELEPHONE_NBR) AS EDI_837_FACILITY_TELEPHONE_NBR
    ,IFF(UPPER(CARE_TYPE_NAME) <> 'MEDICAL', 'n/a', EDI_837_FACILITY_ADDRESS_LINE_1_TEXT) AS EDI_837_FACILITY_ADDRESS_LINE_1_TEXT
    ,IFF(UPPER(CARE_TYPE_NAME) <> 'MEDICAL', 'n/a', EDI_837_FACILITY_ADDRESS_LINE_2_TEXT) AS EDI_837_FACILITY_ADDRESS_LINE_2_TEXT
    ,IFF(UPPER(CARE_TYPE_NAME) <> 'MEDICAL', 'n/a', EDI_837_FACILITY_STATE_ABBREV_NAME) AS EDI_837_FACILITY_STATE_ABBREV_NAME
    ,IFF(UPPER(CARE_TYPE_NAME) <> 'MEDICAL', 'n/a', EDI_837_FACILITY_ZIP_CODE_NBR) AS EDI_837_FACILITY_ZIP_CODE_NBR
    ,IFF(UPPER(CARE_TYPE_NAME) <> 'MEDICAL', 'n/a', EDI_837_FACILITY_OTHER_ID) AS EDI_837_FACILITY_OTHER_ID
    ,DISCHARGE_DATE AS DISCHARGE_DATE
    ,DISCHARGE_HOUR AS DISCHARGE_HOUR
    ,ADMITTED_DATE AS ADMISSION_DATE
    ,ADMITTED_HOUR AS ADMISSION_HOUR
    ,NULL AS DIAGNOSIS_RELATED_GROUP_CODE -- this is not a column in DIM_CLAIM_HEADER
    ,NULL AS DATA_HUB_UNIVERSAL_DRG_ID -- This only applies to stuff from Marklogic
    ,IFF(UPPER(CARE_TYPE_NAME) <> 'MEDICAL', 'n/a', SEVERITY_OF_ILLNESS) AS SEVERITY_OF_ILLNESS
    ,MICROFILM_NBR AS MICROFILM_NBR
    ,CLAIM_TYPE_CODE
    ,ORIGINAL_CLAIM_ID
    ,MULTISOURCE_CLAIM_IND
    ,PROVIDER_SPECIALTY
    ,PAID_STATUS_FOR_CMS
    ,'UPMCHP_DATAHUB' as SOURCE_SYSTEM
    ,HUB_CLAIM_HKEY AS SOURCE_ID
FROM RAWDATA.DATAHUB_CLAIM_HEADER_BASE
WHERE IS_PREDETERMINATION_CLAIM_FLAG = FALSE -- Filter out Pre-D claims, which shouldn't be with claims data.
;