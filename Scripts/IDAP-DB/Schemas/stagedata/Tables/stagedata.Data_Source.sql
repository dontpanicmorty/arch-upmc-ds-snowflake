CREATE OR REPLACE TABLE STAGEDATA.DATA_SOURCE
(
  DATA_SOURCE_KEY NUMBER(38,0) NOT NULL,
  URI VARCHAR NOT NULL,
  JSON_DATA VARIANT NOT NULL,
  INSERT_DATETIME TIMESTAMP_TZ(9) NOT NULL,
  LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) NOT NULL,
  CONSTRAINT PK_DATA_SOURCE PRIMARY KEY (DATA_SOURCE_KEY),
  CONSTRAINT UK_DATA_SOURCE UNIQUE (URI)
) COMMENT='Landing area for data coming from IDAP MarkLogic in JSON form'
;