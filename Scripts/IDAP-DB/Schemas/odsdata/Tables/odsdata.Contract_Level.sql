CREATE OR REPLACE TABLE
	ODSDATA.CONTRACT_LEVEL (
		CONTRACT_LEVEL_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
