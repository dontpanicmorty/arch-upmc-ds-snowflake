	ODSDATA.INSTITUTION_ADDRESS_REL (
		INSTITUTION_ADDRESS_REL_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
		INSTITUTION_KEY NUMBER(38,0) NOT NULL,
		ADDRESS_KEY NUMBER(38,0) NOT NULL,
		ADDRESS_USAGE_TYPE_KEY NUMBER(38,0) NOT NULL,
