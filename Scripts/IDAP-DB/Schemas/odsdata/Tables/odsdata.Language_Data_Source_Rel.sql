CREATE OR REPLACE TABLE
	ODSDATA.LANGUAGE_DATA_SOURCE_REL (
		LANGUAGE_DATA_SOURCE_REL_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
		DATA_SOURCE_KEY NUMBER(38,0) NOT NULL,
		LANGUAGE_KEY NUMBER(38,0) NOT NULL,
		LANGUAGE_SOURCE_NAME VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT FK_LANGUAGE_DATA_SOURCE_REL_DATA_SOURCE FOREIGN KEY (DATA_SOURCE_KEY) REFERENCES ODSDATA.DATA_SOURCE (DATA_SOURCE_KEY),
		CONSTRAINT FK_LANGUAGE_DATA_SOURCE_REL_LANGUAGE FOREIGN KEY (LANGUAGE_KEY) REFERENCES ODSDATA.LANGUAGE (LANGUAGE_KEY),
		CONSTRAINT PK_LANGUAGE_DATA_SOURCE_REL PRIMARY KEY (LANGUAGE_DATA_SOURCE_REL_KEY),
		CONSTRAINT UK_LANGUAGE_DATA_SOURCE_REL UNIQUE (DATA_SOURCE_KEY, LANGUAGE_KEY, LANGUAGE_SOURCE_NAME)
	)COMMENT='Relates source Language values to standard values in Language'
