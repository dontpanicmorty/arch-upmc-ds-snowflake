CREATE OR REPLACE TABLE
	ODSDATA.EMR_SYSTEM (
		EMR_SYSTEM_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
		EMR_SYSTEM_NAME VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_EMR_SYSTEM PRIMARY KEY (EMR_SYSTEM_KEY),
		CONSTRAINT UK_EMR_SYSTEM UNIQUE (EMR_SYSTEM_NAME)
	)COMMENT='Standardized list of Eletronic Medical Record systems'
;