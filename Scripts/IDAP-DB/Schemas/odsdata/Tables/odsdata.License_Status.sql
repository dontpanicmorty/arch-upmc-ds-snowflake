CREATE OR REPLACE TABLE
	ODSDATA.LICENSE_STATUS (
		LICENSE_STATUS_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
		LICENSE_STATUS_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_LICENSE_STATUS PRIMARY KEY (LICENSE_STATUS_KEY),
		CONSTRAINT UK_LICENSE_STATUS UNIQUE (LICENSE_STATUS_DESC)
	)COMMENT='The status of any type of license.'
;