CREATE OR REPLACE TABLE
	ODSDATA.TIME (
		TIME_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
		HOUR_NBR NUMBER(38,0) NOT NULL,
		MINUTE_NBR NUMBER(38,0) NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_TIME PRIMARY KEY (TIME_KEY),
		CONSTRAINT UK_TIME UNIQUE (HOUR_NBR, MINUTE_NBR)
	)COMMENT='Contains a list of allowable times of the day in hours and minutes'
;