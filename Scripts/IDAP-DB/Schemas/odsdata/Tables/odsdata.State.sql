CREATE OR REPLACE TABLE
	ODSDATA.STATE (
		STATE_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
		STATE_FULL_NAME VARCHAR NOT NULL,
		COUNTRY_KEY NUMBER(38,0) NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		STATE_ABBREVIATION_NAME CHAR(2) NOT NULL,
		CONSTRAINT FK_STATE_COUNTRY FOREIGN KEY (COUNTRY_KEY) REFERENCES ODSDATA.COUNTRY (COUNTRY_KEY),
		CONSTRAINT PK_STATE PRIMARY KEY (STATE_KEY),
		CONSTRAINT UK_STATE UNIQUE (STATE_FULL_NAME, COUNTRY_KEY)
	)COMMENT='Contains a list of distinct states and their respoective countries.'
;