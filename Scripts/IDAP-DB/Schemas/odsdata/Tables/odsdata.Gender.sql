CREATE OR REPLACE TABLE
	ODSDATA.GENDER (
		GENDER_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
		GENDER_NAME VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		GENDER_CODE CHAR(1),
		CONSTRAINT PK_GENDER PRIMARY KEY (GENDER_KEY),
		CONSTRAINT UK_GENDER UNIQUE (GENDER_NAME)
	)COMMENT='A list of gender codes and corresponding decriptions'
;