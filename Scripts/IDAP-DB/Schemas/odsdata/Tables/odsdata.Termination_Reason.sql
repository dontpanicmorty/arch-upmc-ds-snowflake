CREATE OR REPLACE TABLE
	ODSDATA.TERMINATION_REASON (
		TERMINATION_REASON_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
		TERMINATION_REASON_DESC VARCHAR NOT NULL,
		TERMINATION_TYPE_KEY NUMBER(38,0) NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT FK_TERMINATION_REASON_TERMINATION_TYPE FOREIGN KEY (TERMINATION_TYPE_KEY) REFERENCES ODSDATA.TERMINATION_TYPE (TERMINATION_TYPE_KEY),
		CONSTRAINT PK_TERMINATION_REASON PRIMARY KEY (TERMINATION_REASON_KEY),
		CONSTRAINT UK_TERMINATION_REASON UNIQUE (TERMINATION_REASON_DESC, TERMINATION_TYPE_KEY)
	)COMMENT='The reason for a type of termination.'
