CREATE OR REPLACE TABLE
	ODSDATA.DEGREE (
		DEGREE_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
		DEGREE_NAME VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_DEGREE PRIMARY KEY (DEGREE_KEY),
		CONSTRAINT UK_DEGREE UNIQUE (DEGREE_NAME)
	)COMMENT='The type of Degree recieved during education.'
;