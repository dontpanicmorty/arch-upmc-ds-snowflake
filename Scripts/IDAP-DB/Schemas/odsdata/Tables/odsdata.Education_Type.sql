CREATE OR REPLACE TABLE
	ODSDATA.EDUCATION_TYPE (
		EDUCATION_TYPE_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
		EDUCATION_TYPE_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_EDUCATION_TYPE PRIMARY KEY (EDUCATION_TYPE_KEY),
		CONSTRAINT UK_EDUCATION_TYPE UNIQUE (EDUCATION_TYPE_DESC)
	)COMMENT='The type of Education recieved. Examples: Medical School, Residency, Internship'
;