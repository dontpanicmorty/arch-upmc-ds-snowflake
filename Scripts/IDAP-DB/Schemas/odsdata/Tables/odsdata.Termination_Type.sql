CREATE OR REPLACE TABLE
	ODSDATA.TERMINATION_TYPE (
		TERMINATION_TYPE_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
		TERMINATION_TYPE_DESC VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_TERMINATION_TYPE PRIMARY KEY (TERMINATION_TYPE_KEY),
		CONSTRAINT UK_TERMINATION_TYPE UNIQUE (TERMINATION_TYPE_DESC)
