CREATE OR REPLACE TABLE
	ODSDATA.SPECIALTY (
		SPECIALTY_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
		TPA_HIERARCHY_KEY NUMBER(38,0) NOT NULL,
		SPECIALTY_NAME VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		LIMITED_SERVICE_AREA_IND CHAR(1) NOT NULL,
		SPECIALTY_DIRECTORY_NAME VARCHAR,
		CONSTRAINT FK_SPECIALTY_TPA_HIERARCHY FOREIGN KEY (TPA_HIERARCHY_KEY) REFERENCES ODSDATA.TPA_HIERARCHY (TPA_HIERARCHY_KEY),
		CONSTRAINT PK_SPECIALTY PRIMARY KEY (SPECIALTY_KEY),
		CONSTRAINT UK_SPECIALTY UNIQUE (TPA_HIERARCHY_KEY, SPECIALTY_NAME)
	)COMMENT='Specialty is a specific branch of medicine or function that a Provider can be skilled at. Each Speciality has SpecialtyCategory associated with it.'
