CREATE OR REPLACE TABLE
	ODSDATA.PHARMACY_TYPE (
		PHARMACY_TYPE_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
		PHARMACY_TYPE_NAME VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
