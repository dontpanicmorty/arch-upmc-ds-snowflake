CREATE OR REPLACE TABLE
	ODSDATA.LANGUAGE (
		LANGUAGE_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
		LANGUAGE_NAME VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		CONSTRAINT PK_LANGUAGE PRIMARY KEY (LANGUAGE_KEY),
		CONSTRAINT UK_LANGUAGE UNIQUE (LANGUAGE_NAME)
	)COMMENT='A list of language codes that can be used in a variety of ways.'
;