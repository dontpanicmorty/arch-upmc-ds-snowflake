CREATE OR REPLACE TABLE
	ODSDATA.PRACTITIONER (
		PRACTITIONER_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		UPIN_NBR CHAR(8),
		FULL_NAME VARCHAR NOT NULL,
		LAST_NAME VARCHAR NOT NULL,
		FIRST_NAME VARCHAR NOT NULL,
		MIDDLE_NAME VARCHAR,
		MIDDLE_INITIAL_NAME CHAR(1),
		SUFFIX_NAME VARCHAR,
		DEGREE_TEXT VARCHAR,
		SOCIAL_SECURITY_NBR CHAR(9),
		BIRTH_DATE DATE,
		GENDER_KEY NUMBER(38,0) NOT NULL,
		LOCUM_TENENS_IND CHAR(1) NOT NULL,
		INVISIBLE_PROVIDER_IND CHAR(1) NOT NULL,
		TEMPORARY_PROVIDER_IND CHAR(1) NOT NULL,
		PROVIDER_MAL_PRACTICE_COVERAGE_IND CHAR(1) NOT NULL,
		LGBTQIA_CULTURAL_COMPETENCY_IND CHAR(1),
		CONSTRAINT FK_PRACTITIONER_GENDER FOREIGN KEY (GENDER_KEY) REFERENCES ODSDATA.GENDER (GENDER_KEY),
		CONSTRAINT FK_PRACTITIONER_PROVIDER FOREIGN KEY (PRACTITIONER_KEY) REFERENCES ODSDATA.PROVIDER (PROVIDER_KEY),
		CONSTRAINT PK_PRACTITIONER PRIMARY KEY (PRACTITIONER_KEY),
		CONSTRAINT UK_PRACTITIONER UNIQUE (PRACTITIONER_KEY)
	)COMMENT='A Practitioner is a subtype of Provider. The ProviderKey  from the Provider table is role named to PractitionerKey in the Practitioner table. Attributes of a Practitioner are applicable only to a person.'
;