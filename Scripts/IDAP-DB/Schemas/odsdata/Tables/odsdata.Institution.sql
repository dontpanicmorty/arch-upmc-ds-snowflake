CREATE OR REPLACE TABLE
	ODSDATA.INSTITUTION (
		INSTITUTION_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
		INSTITUTION_SOURCE_NBR VARCHAR NOT NULL,
		DATA_SOURCE_KEY NUMBER(38,0) NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		INSTITUTION_NAME VARCHAR NOT NULL,
		PROVIDER_KEY NUMBER(38,0),
		INSTITUTION_NOTES_TEXT VARCHAR,
		CONSTRAINT FK_INSTITUTION_DATA_SOURCE FOREIGN KEY (DATA_SOURCE_KEY) REFERENCES ODSDATA.DATA_SOURCE (DATA_SOURCE_KEY),
		CONSTRAINT FK_INSTITUTION_PROVIDER FOREIGN KEY (PROVIDER_KEY) REFERENCES ODSDATA.PROVIDER (PROVIDER_KEY),
		CONSTRAINT PK_INSTITUTION PRIMARY KEY (INSTITUTION_KEY),
		CONSTRAINT UK_INSTITUTION UNIQUE (INSTITUTION_SOURCE_NBR, DATA_SOURCE_KEY)
	)COMMENT='An Institution is any organization (such as a hospital or school) that UPMC maintains information about. Some Institutions are also stored as Providers and can be linked using the ProviderKey.'
;