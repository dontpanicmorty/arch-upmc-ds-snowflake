CREATE OR REPLACE TABLE
	ODSDATA.COUNTRY (
		COUNTRY_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
		COUNTRY_NAME VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		ISO2A_NAME CHAR(2),
		ISO3A_NAME CHAR(3),
		ISO3N_NAME CHAR(3),
		INTERNATIONAL_PHONE_CODE VARCHAR,
		CONSTRAINT PK_COUNTRY PRIMARY KEY (COUNTRY_KEY),
		CONSTRAINT UK_COUNTRY UNIQUE (COUNTRY_NAME)
	)COMMENT='Contains a list of distinct countries, along with their ISO codes.'
;