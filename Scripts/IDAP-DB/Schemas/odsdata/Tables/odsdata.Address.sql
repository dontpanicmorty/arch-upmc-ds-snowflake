CREATE OR REPLACE TABLE
	ODSDATA.ADDRESS (
		ADDRESS_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
		ADDRESS_LINE1_TEXT VARCHAR NOT NULL,
		ADDRESS_LINE2_TEXT VARCHAR,
		CITY_NAME VARCHAR,
		STATE_KEY NUMBER(38,0),
		COUNTY_NAME VARCHAR,
		COUNTRY_KEY NUMBER(38,0),
		ZIP_CODE_NBR VARCHAR NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		LATITUDE_NBR DECIMAL(10,6),
		LONGITUDE_NBR DECIMAL(10,6),
		VERIFIED_ADDRESS_LINE1_TEXT VARCHAR,
		VERIFIED_ADDRESS_LINE2_TEXT VARCHAR,
		VERIFIED_CITY_NAME VARCHAR,
		VERIFIED_STATE_KEY NUMBER(38,0),
		VERIFIED_COUNTY_NAME VARCHAR,
		VERIFIED_COUNTRY_KEY NUMBER(38,0),
		VERIFIED_ZIP_CODE5_NBR CHAR(5),
		VERIFIED_ZIP_CODE9_NBR CHAR(9),
		VERIFIED_LATITUDE_NBR DECIMAL(10,6),
		VERIFIED_LONGITUDE_NBR DECIMAL(10,6),
		MAILABILITY_RESULT_PCT DECIMAL(10,2),
		GEOCODING_STATUS_TEXT VARCHAR,
		CONSTRAINT FK_ADDRESS_COUNTRY FOREIGN KEY (COUNTRY_KEY) REFERENCES ODSDATA.COUNTRY (COUNTRY_KEY),
		CONSTRAINT FK_ADDRESS_STATE FOREIGN KEY (STATE_KEY) REFERENCES ODSDATA.STATE (STATE_KEY),
		CONSTRAINT PK_ADDRESS PRIMARY KEY (ADDRESS_KEY),
		CONSTRAINT UK_ADDRESS UNIQUE (ADDRESS_LINE1_TEXT, ADDRESS_LINE2_TEXT, CITY_NAME, STATE_KEY, COUNTY_NAME, COUNTRY_KEY, ZIP_CODE_NBR)
	)COMMENT='List of unique addresses'
	;