CREATE OR REPLACE TABLE
	ODSDATA.FACILITY (
		FACILITY_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
		LAST_UPDATED_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
		FACILITY_NAME VARCHAR NOT NULL,
		INCEPTION_DATE DATE,
		INVISIBLE_PROVIDER_IND CHAR(1) NOT NULL,
		TEMPORARY_PROVIDER_IND CHAR(1) NOT NULL,
		PROVIDER_MAL_PRACTICE_COVERAGE_IND CHAR(1) NOT NULL,
		CONSTRAINT FK_FACILITY_PROVIDER FOREIGN KEY (FACILITY_KEY) REFERENCES ODSDATA.PROVIDER (PROVIDER_KEY),
		CONSTRAINT PK_FACILITY PRIMARY KEY (FACILITY_KEY),
		CONSTRAINT UK_FACILITY UNIQUE (FACILITY_KEY)
	)COMMENT='A Facility is a place or building that provides medical services. This is a subtype of Provider. The ProviderKey from Provider is role named to FacilityKey in the Facility table. '
;