SpecialtyCategoryDataSourceRel.$1::NUMBER(38,0) AS SPECIALTY_CATEGORY_DATA_SOURCE_REL_KEY
,SpecialtyCategoryDataSourceRel.$2::NUMBER(38,0) AS DATA_SOURCE_KEY
,SpecialtyCategoryDataSourceRel.$3::NUMBER(38,0) AS SPECIALTY_CATEGORY_KEY
,SpecialtyCategoryDataSourceRel.$4::VARCHAR AS SPECIALTY_CATEGORY_SOURCE_NAME
,SpecialtyCategoryDataSourceRel.$5::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/SpecialtyCategoryDataSourceRel.txt
