COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
InstitutionFunctionDataSourceRel.$1::NUMBER(38,0) AS INSTITUTION_FUNCTION_DATA_SOURCE_REL_KEY
,InstitutionFunctionDataSourceRel.$2::NUMBER(38,0) AS DATA_SOURCE_KEY
,InstitutionFunctionDataSourceRel.$3::NUMBER(38,0) AS INSTITUTION_FUNCTION_KEY
,InstitutionFunctionDataSourceRel.$4::VARCHAR AS IINSTITUTION_FUNCTION_SOURCE_DESC
,InstitutionFunctionDataSourceRel.$5::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/InstitutionFunctionDataSourceRel.txt
