CREATE OR REPLACE VIEW ODSDATA.TERMINATION_REASON_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
TerminationReason.$1::NUMBER(38,0) AS TERMINATION_REASON_KEY
,TerminationReason.$2::VARCHAR AS TERMINATION_REASON_DESC
,TerminationReason.$3::NUMBER(38,0) AS TERMINATION_TYPE_KEY
,TerminationReason.$4::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/TerminationReason.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')TerminationReason
;
