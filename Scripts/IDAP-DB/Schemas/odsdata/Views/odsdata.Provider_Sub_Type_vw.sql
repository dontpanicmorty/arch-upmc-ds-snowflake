CREATE OR REPLACE VIEW ODSDATA.PROVIDER_SUB_TYPE_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
ProviderSubType.$1::NUMBER(38,0) AS PROVIDER_SUB_TYPE_KEY
,ProviderSubType.$2::VARCHAR AS PROVIDER_SUB_TYPE_DESC
,ProviderSubType.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/ProviderSubType.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')ProviderSubType
;
