CREATE OR REPLACE VIEW ODSDATA.LANGUAGE_SUPPORT_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
LanguageSupport.$1::NUMBER(38,0) AS LANGUAGE_SUPPORT_KEY
,LanguageSupport.$2::VARCHAR AS LANGUAGE_SUPPORT_TYPE
,LanguageSupport.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/LanguageSupport.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')LanguageSupport
;
