CREATE OR REPLACE VIEW ODSDATA.SERVICE_AREA_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
ServiceArea.$1::NUMBER(38,0) AS SERVICE_AREA_KEY
,ServiceArea.$2::NUMBER(38,0) AS STATE_KEY
,ServiceArea.$3::VARCHAR AS SERVICE_AREA_TEXT
,ServiceArea.$4::VARCHAR AS COUNTY_NAME
,ServiceArea.$5::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/ServiceArea.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')ServiceArea
;
