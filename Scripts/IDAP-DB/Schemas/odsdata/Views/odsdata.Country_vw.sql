CREATE OR REPLACE VIEW ODSDATA.COUNTRY_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
Country.$1::NUMBER(38,0) AS COUNTRY_KEY
,Country.$2::VARCHAR AS COUNTRY_NAME
,Country.$3::DATETIME AS LAST_UPDATED_DATETIME
,Country.$5::VARCHAR AS ISO2A_Name
,Country.$6::VARCHAR AS ISO3A_Name
,Country.$7::VARCHAR AS ISO3N_Name
,Country.$8::VARCHAR AS INTERNATIONAL_PHONE_CODE
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/Country.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')Country
;