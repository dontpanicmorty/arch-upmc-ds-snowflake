CREATE OR REPLACE VIEW ODSDATA.INSTITUTION_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
Institution.$1::NUMBER(38,0) AS INSTITUTION_KEY
,Institution.$2::VARCHAR AS INSTITUTION_SOURCE_NBR
,Institution.$3::NUMBER(38,0) AS DATA_SOURCE_KEY
,Institution.$4::DATETIME AS LAST_UPDATED_DATETIME
,Institution.$5::DATETIME AS INSERT_DATETIME
,Institution.$6::VARCHAR AS INSTITUTION_NAME
,Institution.$7::NUMBER(38,0) AS PROVIDER_KEY
,Institution.$8::VARCHAR AS INSTITUTION__NOTES_TEXT
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/Institution.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')Institution
;
