CREATE OR REPLACE VIEW ODSDATA.PROVIDER_REL_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
ProviderRel.$1::NUMBER(38,0) AS PROVIDER_REL_KEY
,ProviderRel.$2::NUMBER(38,0) AS PARENT_PROVIDER_KEY
,ProviderRel.$3::NUMBER(38,0) AS CHILD_PROVIDER_KEY
,ProviderRel.$4::NUMBER(38,0) AS PROVIDER_REL_TYPE_KEY
,ProviderRel.$5::DATETIME AS LAST_UPDATED_DATETIME
,ProviderRel.$6::DATETIME AS INSERT_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/ProviderRel.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')ProviderRel
;
