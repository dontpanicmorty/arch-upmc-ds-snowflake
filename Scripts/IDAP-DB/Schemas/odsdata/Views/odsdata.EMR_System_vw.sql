CREATE OR REPLACE VIEW ODSDATA.EMR_SYSTEM_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
EMRSystem.$1::NUMBER(38,0) AS EMR_SYSTEM_KEY
,EMRSystem.$2::VARCHAR AS EMR_SYSTEM_NAME
,EMRSystem.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/EMRSystem.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')EMRSystem
;
