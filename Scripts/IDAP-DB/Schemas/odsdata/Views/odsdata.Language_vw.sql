CREATE OR REPLACE VIEW ODSDATA.LANGUAGE_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
Language.$1::NUMBER(38,0) AS LANGUAGE_KEY
,Language.$2::VARCHAR AS LANGUAGE_NAME
,Language.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/Language.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')Language
;
