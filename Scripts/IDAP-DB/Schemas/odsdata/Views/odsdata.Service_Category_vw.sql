CREATE OR REPLACE VIEW ODSDATA.SERVICE_CATEGORY_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
ServiceCategory.$1::NUMBER(38,0) AS SERVICE_CATEGORY_KEY
,ServiceCategory.$2::VARCHAR AS SERVICE_CATEGORY_NAME
,ServiceCategory.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/ServiceCategory.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')ServiceCategory
;
