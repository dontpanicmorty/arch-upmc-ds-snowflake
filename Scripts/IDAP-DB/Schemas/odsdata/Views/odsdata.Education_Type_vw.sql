CREATE OR REPLACE VIEW ODSDATA.EDUCATION_TYPE_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
EducationType.$1::NUMBER(38,0) AS EDUCATION_TYPE_KEY
,EducationType.$2::VARCHAR AS EDUCATION_TYPE_DESC
,EducationType.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/EducationType.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')EducationType
;
