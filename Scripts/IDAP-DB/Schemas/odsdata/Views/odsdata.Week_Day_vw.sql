CREATE OR REPLACE VIEW ODSDATA.WEEK_DAY_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
WeekDay.$1::NUMBER(38,0) AS WEEK_DAY_KEY
,WeekDay.$2::VARCHAR AS WEEK_DAY_NAME
,WeekDay.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/WeekDay.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')WeekDay
;
