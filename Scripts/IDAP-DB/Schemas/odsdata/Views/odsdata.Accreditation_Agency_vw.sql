CREATE OR REPLACE VIEW ODSDATA.ACCREDITATION_AGENCY_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
AccreditationAgency.$1::NUMBER(38,0) AS ACCREDITATION_AGENCY_KEY
,AccreditationAgency.$2::VARCHAR AS ACCREDITATION_AGENCY_NAME
,AccreditationAgency.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/AccreditationAgency.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT') AccreditationAgency
;