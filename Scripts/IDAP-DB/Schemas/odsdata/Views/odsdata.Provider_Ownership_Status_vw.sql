CREATE OR REPLACE VIEW ODSDATA.PROVIDER_OWNERSHIP_STATUS_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
ProviderOwnershipStatus.$1::NUMBER(38,0) AS PROVIDER_OWNERSHIP_STATUS_KEY
,ProviderOwnershipStatus.$2::VARCHAR AS PROVIDER_OWNERSHIP_STATUS_DESC
,ProviderOwnershipStatus.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/ProviderOwnershipStatus.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')ProviderOwnershipStatus
;
