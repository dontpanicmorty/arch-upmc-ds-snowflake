CREATE OR REPLACE VIEW ODSDATA.CONTRACT_LEVEL_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
ContractLevel.$1::NUMBER(38,0) AS CONTRACT_LEVEL_KEY
,ContractLevel.$2::VARCHAR AS CONTRACT_LEVEL_CODE
,ContractLevel.$3::DATETIME AS LAST_UPDATED_DATETIME
,ContractLevel.$5::VARCHAR AS CONTRACT_LEVEL_DESC
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/ContractLevel.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')ContractLevel
;