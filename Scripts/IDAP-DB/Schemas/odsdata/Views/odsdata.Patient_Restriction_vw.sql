CREATE OR REPLACE VIEW ODSDATA.PATIENT_RESTRICTION_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
PatientRestriction.$1::NUMBER(38,0) AS PATIENT_RESTRICTION_KEY
,PatientRestriction.$2::NUMBER(38,0) AS MIN_AGE_NBR
,PatientRestriction.$3::NUMBER(38,0) AS MAX_AGE_NBR
,PatientRestriction.$4::NUMBER(38,0) AS GENDER_KEY
,PatientRestriction.$5::VARCHAR AS EXISTING_PATIENTS_ONLY_IND
,PatientRestriction.$6::VARCHAR AS SPECIAL_RESTRICTION_DESC
,PatientRestriction.$7::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/PatientRestriction.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')PatientRestriction
;
