CREATE OR REPLACE VIEW ODSDATA.INSTITUTION_ADDRESS_REL_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
InstitutionAddressRel.$1::NUMBER(38,0) AS INSTITUTION_ADDRESS_REL_KEY
,InstitutionAddressRel.$2::NUMBER(38,0) AS INSTITUTION_KEY
,InstitutionAddressRel.$3::NUMBER(38,0) AS ADDRESS_KEY
,InstitutionAddressRel.$4::NUMBER(38,0) AS ADDRESS_USAGE_TYPE_KEY
,InstitutionAddressRel.$5::DATETIME AS LAST_UPDATED_DATETIME
,InstitutionAddressRel.$6::DATETIME AS INSERT_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/InstitutionAddressRel.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')InstitutionAddressRel
;
