CREATE OR REPLACE VIEW ODSDATA.PROVIDER_REL_TYPE_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
ProviderRelType.$1::NUMBER(38,0) AS PROVIDER_REL_TYPE_KEY
,ProviderRelType.$2::VARCHAR AS PROVIDER_REL_TYPE_DESC
,ProviderRelType.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/ProviderRelType.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')ProviderRelType
;
