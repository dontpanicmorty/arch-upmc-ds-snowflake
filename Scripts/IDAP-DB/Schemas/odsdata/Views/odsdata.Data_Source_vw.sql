CREATE OR REPLACE VIEW ODSDATA.DATA_SOURCE_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
DataSource.$1::NUMBER(38,0) AS DATA_SOURCE_KEY
,DataSource.$2::VARCHAR AS DATA_SOURCE_NAME
,DataSource.$3::DATETIME AS LAST_UPDATED_DATETIME
,DataSource.$5::VARCHAR AS ADDRESS_SPECIFIC_CONTRACT_IND
,DataSource.$6::VARCHAR AS INCLUDE_SOURCE_IN_IDAP
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/DataSource.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')DataSource
;