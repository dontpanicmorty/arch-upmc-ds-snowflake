CREATE OR REPLACE VIEW ODSDATA.LANGUAGE_DATA_SOURCE_REL_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
LanguageDataSourceRel.$1::NUMBER(38,0) AS LANGUAGE_DATA_SOURCE_REL_KEY
,LanguageDataSourceRel.$2::NUMBER(38,0) AS DATA_SOURCE_KEY
,LanguageDataSourceRel.$3::NUMBER(38,0) AS LANGUAGE_KEY
,LanguageDataSourceRel.$4::VARCHAR AS LANGUAGE_SOURCE_NAME
,LanguageDataSourceRel.$5::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/LanguageDataSourceRel.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')LanguageDataSourceRel
;
