SpecialtyLineOfBusinessRel.$1::NUMBER(38,0) AS SPECIALTY_LINE_OF_BUSINESS_REL_KEY
,SpecialtyLineOfBusinessRel.$2::NUMBER(38,0) AS SPECIALTY_KEY
,SpecialtyLineOfBusinessRel.$3::NUMBER(38,0) AS LINE_OF_BUSINESS_KEY
,SpecialtyLineOfBusinessRel.$4::DATETIME AS LAST_UPDATED_DATETIME
,SpecialtyLineOfBusinessRel.$5::DATETIME AS INSERT_DATETIME
