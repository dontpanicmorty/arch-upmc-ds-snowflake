CREATE OR REPLACE VIEW ODSDATA.LICENSE_TYPE_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
LicenseType.$1::NUMBER(38,0) AS LICENSE_TYPE_KEY
,LicenseType.$2::VARCHAR AS LICENSE_TYPE_DESC
,LicenseType.$3::DATETIME AS LAST_UPDATED_DATETIME
,LicenseType.$5::VARCHAR AS LICENSE_TYPE_CODE
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/LicenseType.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')LicenseType
;
