CREATE OR REPLACE VIEW ODSDATA.STATE_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
State.$1::NUMBER(38,0) AS STATE_KEY
,State.$2::VARCHAR AS STATE_FULL_NAME
,State.$3::NUMBER(38,0) AS COUNTRY_KEY
,State.$4::DATETIME AS LAST_UPDATED_DATETIME
,State.$6::VARCHAR AS STATE_ABBREVIATION_NAME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/State.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')State
;
