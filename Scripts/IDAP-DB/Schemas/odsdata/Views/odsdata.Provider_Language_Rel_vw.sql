CREATE OR REPLACE VIEW ODSDATA.PROVIDER_LANGUAGE_REL_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
ProviderLanguageRel.$1::NUMBER(38,0) AS PROVIDER_LANGUAGE_REL_KEY
,ProviderLanguageRel.$2::NUMBER(38,0) AS PROVIDER_KEY
,ProviderLanguageRel.$3::NUMBER(38,0) AS LANGUAGE_KEY
,ProviderLanguageRel.$4::DATETIME AS LAST_UPDATED_DATETIME
,ProviderLanguageRel.$5::DATETIME AS INSERT_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/ProviderLanguageRel.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')ProviderLanguageRel
;
