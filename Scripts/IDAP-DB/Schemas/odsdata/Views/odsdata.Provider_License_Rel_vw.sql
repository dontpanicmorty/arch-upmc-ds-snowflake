CREATE OR REPLACE VIEW ODSDATA.PROVIDER_LICENSE_REL_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
ProviderLicenseRel.$1::NUMBER(38,0) AS PROVIDER_LICENSE_REL_KEY
,ProviderLicenseRel.$2::NUMBER(38,0) AS PROVIDER_KEY
,ProviderLicenseRel.$3::NUMBER(38,0) AS LICENSE_TYPE_KEY
,ProviderLicenseRel.$4::VARCHAR AS LICENSE_NBR
,ProviderLicenseRel.$5::NUMBER(38,0) AS LICENSE_STATUS_KEY
,ProviderLicenseRel.$6::NUMBER(38,0) AS STATE_KEY
,ProviderLicenseRel.$7::DATETIME AS LAST_UPDATED_DATETIME
,ProviderLicenseRel.$8::DATETIME AS INSERT_DATETIME
,ProviderLicenseRel.$9::DATE AS AWARDED_DATE
,ProviderLicenseRel.$10::DATE AS LICENSE_EXPIRATION_DATE
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/ProviderLicenseRel.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')ProviderLicenseRel
;
