CREATE OR REPLACE VIEW ODSDATA.BOARD_CERTIFICATION_STATUS_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
BoardCertificationStatus.$1::NUMBER(38,0) AS BOARD_CERTIFICATION_STATUS_KEY
,BoardCertificationStatus.$2::VARCHAR AS BOARD_CERTIFICATION_STATUS_DESC
,BoardCertificationStatus.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/BoardCertificationStatus.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')BoardCertificationStatus
;
