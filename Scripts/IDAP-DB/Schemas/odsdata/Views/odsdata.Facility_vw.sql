CREATE OR REPLACE VIEW ODSDATA.FACILITY_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
Facility.$1::NUMBER(38,0) AS FACILITY_KEY
,Facility.$2::DATETIME AS LAST_UPDATED_DATETIME
,Facility.$3::DATETIME AS INSERT_DATETIME
,Facility.$4::VARCHAR AS FACILITY_NAME
,Facility.$5::DATE AS INCEPTION_DATE
,Facility.$6::VARCHAR AS INVISIBLE_PROVIDER_IND
,Facility.$7::VARCHAR AS TEMPORARY_PROVIDER_IND
,Facility.$8::VARCHAR AS PROVIDER_MAL_PRACTICE_COVERAGE_IND
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/Facility.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')Facility
;
