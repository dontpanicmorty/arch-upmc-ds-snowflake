CREATE OR REPLACE VIEW ODSDATA.PROVIDER_CONTRACT_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
ProviderContract.$1::NUMBER(38,0) AS PROVIDER_CONTRACT_KEY
,ProviderContract.$2::NUMBER(38,0) AS PROVIDER_KEY
,ProviderContract.$3::NUMBER(38,0) AS PRODUCT_KEY
,ProviderContract.$4::NUMBER(38,0) AS PRODUCT_TYPE_KEY
,ProviderContract.$5::NUMBER(38,0) AS CONTRACT_LEVEL_KEY
,ProviderContract.$6::DATE AS CONTRACT_START_DATE
,ProviderContract.$7::DATETIME AS LAST_UPDATED_DATETIME
,ProviderContract.$8::DATETIME AS INSERT_DATETIME
,ProviderContract.$9::DATE AS CONTRACT_TERMINATION_DATE
,ProviderContract.$10::NUMBER(38,0) AS CONTRACT_TERMINATION_REASON_KEY
,ProviderContract.$11::VARCHAR AS ACTIVE_IND
,ProviderContract.$12::NUMBER(38,0) AS PROVIDER_ROLE_TYPE_KEY
,ProviderContract.$13::NUMBER(38,0) AS PATIENT_RESTRICTION_KEY
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/ProviderContract.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')ProviderContract
;
