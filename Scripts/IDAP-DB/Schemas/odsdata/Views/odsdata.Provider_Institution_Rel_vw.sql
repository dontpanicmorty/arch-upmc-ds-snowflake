COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
ProviderInstitutionRel.$1::NUMBER(38,0) AS PROVIDER_INSTITUTION_REL_KEY
,ProviderInstitutionRel.$2::NUMBER(38,0) AS PROVIDER_KEY
,ProviderInstitutionRel.$3::NUMBER(38,0) AS INSTITUTION_KEY
,ProviderInstitutionRel.$4::NUMBER(38,0) AS PROVIDER_AFFILIATION_TYPE_KEY
,ProviderInstitutionRel.$5::DATE AS PROVIDER_AFFILIATION_START_DATE
,ProviderInstitutionRel.$6::DATETIME AS LAST_UPDATED_DATETIME
,ProviderInstitutionRel.$7::DATETIME AS INSERT_DATETIME
,ProviderInstitutionRel.$8::DATE AS PROVIDER_AFFILIATION_END_DATE
,ProviderInstitutionRel.$9::VARCHAR AS ACTIVE_IND
,ProviderInstitutionRel.$10::VARCHAR AS PROVIDER_AFFILIATION_GATEWAY_TEXT
,ProviderInstitutionRel.$11::NUMBER(38,0) AS PROVIDER_AFFILIATION_GATEWAY_TYPE_KEY
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/ProviderInstitutionRel.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')ProviderInstitutionRel
;
