CREATE OR REPLACE VIEW ODSDATA.MEDICAL_GROUP_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
MedicalGroup.$1::NUMBER(38,0) AS MEDICAL_GROUP_KEY
,MedicalGroup.$2::DATETIME AS LAST_UPDATED_DATETIME
,MedicalGroup.$3::DATETIME AS INSERT_DATETIME
,MedicalGroup.$4::VARCHAR AS MEDICAL_GROUP_NAME
,MedicalGroup.$5::VARCHAR AS TIN_NBR
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/MedicalGroup.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')MedicalGroup
;
