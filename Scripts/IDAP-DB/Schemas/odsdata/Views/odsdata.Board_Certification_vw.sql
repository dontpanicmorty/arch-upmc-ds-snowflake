CREATE OR REPLACE VIEW ODSDATA.BOARD_CERTIFICATION_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
BoardCertification.$1::NUMBER(38,0) AS BOARD_CERTIFICATION_KEY
,BoardCertification.$2::VARCHAR AS BOARD_CERTIFICATION_NAME
,BoardCertification.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/BoardCertification.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')BoardCertification
;