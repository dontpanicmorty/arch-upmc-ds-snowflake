CREATE OR REPLACE VIEW ODSDATA.PRODUCT_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
Product.$1::NUMBER(38,0) AS PRODUCT_KEY
,Product.$2::VARCHAR AS PRODUCT_NAME
,Product.$3::DATETIME AS LAST_UPDATED_DATETIME
,Product.$5::NUMBER(38,0) AS TPA_HIERARCHY_KEY
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/Product.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')Product
;