CREATE OR REPLACE VIEW ODSDATA.ADDRESS_USAGE_TYPE_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
AddressUsageType.$1::NUMBER(38,0) AS ADDRESS_USAGE_TYPE_KEY
,AddressUsageType.$2::VARCHAR AS ADDRESS_USAGE_TYPE_DESC
,AddressUsageType.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/AddressUsageType.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')AddressUsageType
;