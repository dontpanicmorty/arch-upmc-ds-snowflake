CREATE OR REPLACE VIEW ODSDATA.LINE_OF_BUSINESS_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
LineOfBusiness.$1::NUMBER(38,0) AS LINE_OF_BUSINESS_KEY
,LineOfBusiness.$2::VARCHAR AS LINE_OF_BUSINESS_NAME
,LineOfBusiness.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/LineOfBusiness.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')LineOfBusiness
;
