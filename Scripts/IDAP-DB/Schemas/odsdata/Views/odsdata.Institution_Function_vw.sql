CREATE OR REPLACE VIEW ODSDATA.INSTITUTION_FUNCTION_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
InstitutionFunction.$1::NUMBER(38,0) AS INSTITUTION_FUNCTION_KEY
,InstitutionFunction.$2::VARCHAR AS INSTITUTION_FUNCTION_DESC
,InstitutionFunction.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/InstitutionFunction.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')InstitutionFunction
;
