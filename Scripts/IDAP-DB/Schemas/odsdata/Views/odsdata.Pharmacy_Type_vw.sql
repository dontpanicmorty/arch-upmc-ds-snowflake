CREATE OR REPLACE VIEW ODSDATA.PHARMACY_TYPE_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
PharmacyType.$1::NUMBER(38,0) AS PHARMACY_TYPE_KEY
,PharmacyType.$2::VARCHAR AS PHARMACY_TYPE_NAME
,PharmacyType.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/PharmacyType.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')PharmacyType
;
