CREATE OR REPLACE VIEW ODSDATA.TPA_HIERARCHY_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
TPAHierarchy.$1::NUMBER(38,0) AS TPA_HIERARCHY_KEY
,TPAHierarchy.$2::VARCHAR AS CLIENT_ID
,TPAHierarchy.$3::VARCHAR AS TPA_ID
,TPAHierarchy.$4::VARCHAR AS TPA_DIV_ID
,TPAHierarchy.$5::DATETIME AS LAST_UPDATED_DATETIME
,TPAHierarchy.$7::VARCHAR AS TPA_DESC
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/TPAHierarchy.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')TPAHierarchy
;
