CREATE OR REPLACE VIEW ODSDATA.EDUCATIONAL_DEPARTMENT_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
EducationalDepartment.$1::NUMBER(38,0) AS EDUCATIONAL_DEPARTMENT_KEY
,EducationalDepartment.$2::VARCHAR AS EDUCATIONAL_DEPARTMENT_NAME
,EducationalDepartment.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/EducationalDepartment.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')EducationalDepartment
;
