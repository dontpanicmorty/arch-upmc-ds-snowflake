CREATE OR REPLACE VIEW ODSDATA.CARE_TYPE_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
CareType.$1::NUMBER(38,0) AS CARE_TYPE_KEY
,CareType.$2::VARCHAR AS CARE_TYPE_DESC
,CareType.$3::DATETIME AS LAST_UPDATED_DATETIME
,CareType.$5::VARCHAR AS TELE_HEALTH_IND
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/CareType.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')CareType
;
