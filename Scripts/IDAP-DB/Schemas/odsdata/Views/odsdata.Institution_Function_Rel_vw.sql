CREATE OR REPLACE VIEW ODSDATA.INSTITUTION_FUNCTION_REL_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
InstitutionFunctionRel.$1::NUMBER(38,0) AS INSTITUTION_FUNCTION_REL_KEY
,InstitutionFunctionRel.$2::NUMBER(38,0) AS INSTITUTION_KEY
,InstitutionFunctionRel.$3::NUMBER(38,0) AS INSTITUTION_FUNCTION_KEY
,InstitutionFunctionRel.$4::DATETIME AS LAST_UPDATED_DATETIME
,InstitutionFunctionRel.$5::DATETIME AS INSERT_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/InstitutionFunctionRel.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')InstitutionFunctionRel
;
