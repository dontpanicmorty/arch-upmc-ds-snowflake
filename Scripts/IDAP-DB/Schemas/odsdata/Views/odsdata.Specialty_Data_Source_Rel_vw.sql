CREATE OR REPLACE VIEW ODSDATA.SPECIALTY_DATA_SOURCE_REL_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
SpecialtyDataSourceRel.$1::NUMBER(38,0) AS SPECIALTY_DATA_SOURCE_REL
,SpecialtyDataSourceRel.$2::NUMBER(38,0) AS DATA_SOURCE_KEY
,SpecialtyDataSourceRel.$3::NUMBER(38,0) AS SPECIALTY_KEY
,SpecialtyDataSourceRel.$4::VARCHAR AS SPECIALTY_SOURCE_DESC
,SpecialtyDataSourceRel.$5::DATETIME AS LAST_UPDATED_DATETIME
,SpecialtyDataSourceRel.$7::VARCHAR AS LIMITED_SERVICE_AREA_IND
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/SpecialtyDataSourceRel.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')SpecialtyDataSourceRel
;
