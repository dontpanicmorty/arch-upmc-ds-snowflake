CREATE OR REPLACE VIEW ODSDATA.EMR_SYSTEM_DATA_SOURCE_REL_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
EMRSystemDataSourceRel.$1::NUMBER(38,0) AS EMR_SYSTEM_DATA_SOURCE_REL_KEY
,EMRSystemDataSourceRel.$2::NUMBER(38,0) AS DATA_SOURCE_KEY
,EMRSystemDataSourceRel.$3::NUMBER(38,0) AS EMR_SYSTEM_KEY
,EMRSystemDataSourceRel.$4::VARCHAR AS EMR_SYSTEM_SOUCRE_NAME
,EMRSystemDataSourceRel.$5::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/EMRSystemDataSourceRel.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')EMRSystemDataSourceRel
;
