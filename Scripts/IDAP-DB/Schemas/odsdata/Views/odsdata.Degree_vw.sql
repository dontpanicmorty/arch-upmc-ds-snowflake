CREATE OR REPLACE VIEW ODSDATA.DEGREE_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
Degree.$1::NUMBER(38,0) AS DEGREE_KEY
,Degree.$2::VARCHAR AS DEGREE_NAME
,Degree.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/Degree.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')Degree
;
