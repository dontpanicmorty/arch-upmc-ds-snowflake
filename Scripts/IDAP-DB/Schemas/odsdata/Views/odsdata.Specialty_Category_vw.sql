CREATE OR REPLACE VIEW ODSDATA.SPECIALTY_CATEGORY_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
SpecialtyCategory.$1::NUMBER(38,0) AS SPECIALTY_CATEGORY_KEY
,SpecialtyCategory.$2::VARCHAR AS SPECIALTY_CATEGORY_NAME
,SpecialtyCategory.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/SpecialtyCategory.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')SpecialtyCategory
;
