CREATE OR REPLACE VIEW ODSDATA.SERVICE_CATEGORY_DATA_SOURCE_REL_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
ServiceCategoryDataSourceRel.$1::NUMBER(38,0) AS SERVICE_CATEGORY_DATA_SOURCE_REL_KEY
,ServiceCategoryDataSourceRel.$2::NUMBER(38,0) AS DATA_SOURCE_KEY
,ServiceCategoryDataSourceRel.$3::NUMBER(38,0) AS SERVICE_CATEGORY_KEY
,ServiceCategoryDataSourceRel.$4::VARCHAR AS SERVICE_CATEGORY_SOURCE_NAME
,ServiceCategoryDataSourceRel.$5::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/ServiceCategoryDataSourceRel.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')ServiceCategoryDataSourceRel
;
