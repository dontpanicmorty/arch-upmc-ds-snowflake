CREATE OR REPLACE VIEW ODSDATA.SCHEDULE_TYPE_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
ScheduleType.$1::NUMBER(38,0) AS SCHEDULE_TYPE_KEY
,ScheduleType.$2::VARCHAR AS SCHEDULE_TYPE_DESC
,ScheduleType.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/ScheduleType.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')ScheduleType
;
