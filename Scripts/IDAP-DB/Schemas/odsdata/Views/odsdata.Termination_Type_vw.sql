CREATE OR REPLACE VIEW ODSDATA.TERMINATION_TYPE_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
TerminationType.$1::NUMBER(38,0) AS TERMINATION_TYPE_KEY
,TerminationType.$2::VARCHAR AS TERMINATION_TYPE_DESC
,TerminationType.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/TerminationType.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')TerminationType
;
