COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
LanguageSupportDataSourceRel.$1::NUMBER(38,0) AS LANGUAGE_SUPPORT_DATA_SOURCE_REL_KEY
,LanguageSupportDataSourceRel.$2::NUMBER(38,0) AS DATA_SOURCE_KEY
,LanguageSupportDataSourceRel.$3::NUMBER(38,0) AS LANGUAGE_SUPPORT_KEY
,LanguageSupportDataSourceRel.$4::VARCHAR AS LANGUAGE_SUPPORT_TYPE_NAME
,LanguageSupportDataSourceRel.$5::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/LanguageSupportDataSourceRel.txt
