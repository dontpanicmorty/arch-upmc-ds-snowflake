CREATE OR REPLACE VIEW ODSDATA.DEGREE_DATA_SOURCE_REL_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
DegreeDataSourceRel.$1::NUMBER(38,0) AS DEGREE_DATA_SOURCE_REL_KEY
,DegreeDataSourceRel.$2::NUMBER(38,0) AS DATA_SOURCE_KEY
,DegreeDataSourceRel.$3::NUMBER(38,0) AS DEGREE_KEY
,DegreeDataSourceRel.$4::VARCHAR AS DEGREE_SOURCE_NAME
,DegreeDataSourceRel.$5::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/DegreeDataSourceRel.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')DegreeDataSourceRel
;
