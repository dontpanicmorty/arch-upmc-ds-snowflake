CREATE OR REPLACE VIEW ODSDATA.SPECIALTY_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
Specialty.$1::NUMBER(38,0) AS SPECIALTY_KEY
,Specialty.$2::NUMBER(38,0) AS TPA_HIERARCHY_KEY
,Specialty.$3::VARCHAR AS SPECIALTY_NAME
,Specialty.$4::DATETIME AS LAST_UPDATED_DATETIME
,Specialty.$6::VARCHAR AS LIMITED_SERVICE_AREA_IND
,Specialty.$7::VARCHAR AS SPECIALTY_DIRECTORY_NAME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/Specialty.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')Specialty
;
