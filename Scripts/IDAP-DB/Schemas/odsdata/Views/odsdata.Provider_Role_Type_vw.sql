CREATE OR REPLACE VIEW ODSDATA.PROVIDER_ROLE_TYPE_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
ProviderRoleType.$1::NUMBER(38,0) AS PROVIDER_ROLE_TYPE_KEY
,ProviderRoleType.$2::VARCHAR AS PROVIDER_ROLE_TYPE_DESC
,ProviderRoleType.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/ProviderRoleType.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')ProviderRoleType
;
