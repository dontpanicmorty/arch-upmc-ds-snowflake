CREATE OR REPLACE VIEW ODSDATA.SCHEDULE_HOLD_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
ScheduleHold.$1::NUMBER(38,0) AS PROVIDER_ADDRESS_KEY
,ScheduleHold.$2::VARCHAR AS WEEK_DAY_NAME
,ScheduleHold.$3::VARCHAR AS SCHEDULED_HOURS_TEXT
,ScheduleHold.$4::NUMBER(38,0) AS OPEN_HOUR_NBR
,ScheduleHold.$5::NUMBER(38,0) AS OPEN_MINUTE_NBR
,ScheduleHold.$6::NUMBER(38,0) AS CLOSE_HOUR_NBR
,ScheduleHold.$7::NUMBER(38,0) AS CLOSE_MINUTE_NBR
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/ScheduleHold.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')ScheduleHold
;
