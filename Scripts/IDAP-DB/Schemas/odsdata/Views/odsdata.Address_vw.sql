CREATE OR REPLACE VIEW ODSDATA.ADDRESS_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
Address.$1::NUMBER(38,0) AS ADDRESS_KEY
,Address.$2::VARCHAR AS ADDRESS_LINE1_TEXT
,Address.$3::VARCHAR AS ADDRESS_LINE2_TEXT
,Address.$4::VARCHAR AS CITY_NAME
,Address.$5::NUMBER(38,0) AS STATE_KEY
,Address.$6::VARCHAR AS COUNTY_NAME
,Address.$7::NUMBER(38,0) AS COUNTRY_KEY
,Address.$8::VARCHAR AS ZIP_CODE_NBR
,Address.$9::DATETIME AS LAST_UPDATED_DATETIME
,Address.$10::DATETIME AS INSERT_DATETIME
,Address.$11::NUMBER(10,6) AS LATITUDE_NBR
,Address.$12::NUMBER(10,6) AS LONGITUDE_NBR
,Address.$13::VARCHAR AS VERIFIED_ADDRESS_LINE1_TEXT
,Address.$14::VARCHAR AS VERIFIED_ADDRESS_LINE2_TEXT
,Address.$15::VARCHAR AS VERIFIED_CITY_NAME
,Address.$16::NUMBER(38,0) AS VERIFIED_STATE_KEY
,Address.$17::VARCHAR AS VERIFIED_COUNTY_NAME
,Address.$18::NUMBER(38,0) AS VERIFIED_COUNTRY_KEY
,Address.$19::VARCHAR AS VERIFIED_ZIP_CODE5_NBR
,Address.$20::VARCHAR AS VERIFIED_ZIP_CODE9_NBR
,Address.$21::NUMBER(10,6) AS VERIFIED_LATITUDE_NBR
,Address.$22::NUMBER(10,6) AS VERIFIED_LONGITUDE_NBR
,Address.$23::NUMBER(10,2) AS MAILABILITY_RESULT_PCT
,Address.$24::VARCHAR AS GEOCODING_STATUS_TEXT
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/Address.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')Address
;
