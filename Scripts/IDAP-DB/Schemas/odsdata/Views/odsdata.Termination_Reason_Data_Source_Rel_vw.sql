CREATE OR REPLACE VIEW ODSDATA.TERMINATION_REASON_DATA_SOURCE_REL_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
TerminationReasonDataSourceRel.$1::NUMBER(38,0) AS TERMINATION_REASON_DATA_SOURCE_REL_KEY
,TerminationReasonDataSourceRel.$2::NUMBER(38,0) AS DATA_SOURCE_KEY
,TerminationReasonDataSourceRel.$3::NUMBER(38,0) AS TERMINATION_REASON_KEY
,TerminationReasonDataSourceRel.$4::VARCHAR AS TERMINATION_REASON_SOURCE_DESC
,TerminationReasonDataSourceRel.$5::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/TerminationReasonDataSourceRel.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')TerminationReasonDataSourceRel
;
