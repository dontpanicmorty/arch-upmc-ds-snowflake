CREATE OR REPLACE VIEW ODSDATA.PRODUCT_TYPE_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
ProductType.$1::NUMBER(38,0) AS PRODUCT_TYPE_KEY
,ProductType.$2::VARCHAR AS PRODUCT_TYPE_NAME
,ProductType.$3::DATETIME AS LAST_UPDATED_DATETIME
,ProductType.$5::NUMBER(38,0) AS TPA_HIERARCHY_KEY
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/ProductType.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')ProductType
;
