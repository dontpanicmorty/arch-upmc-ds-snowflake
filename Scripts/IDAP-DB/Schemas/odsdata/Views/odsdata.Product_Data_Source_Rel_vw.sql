CREATE OR REPLACE VIEW ODSDATA.PRODUCT_DATA_SOURCE_REL_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
ProductDataSourceRel.$1::NUMBER(38,0) AS PRODUCT_DATA_SOURCE_REL_KEY
,ProductDataSourceRel.$2::NUMBER(38,0) AS DATA_SOURCE_KEY
,ProductDataSourceRel.$3::NUMBER(38,0) AS PRODUCT_KEY
,ProductDataSourceRel.$4::VARCHAR AS PRODUCT_SOURCE_NAME
,ProductDataSourceRel.$5::DATETIME AS LAST_UPDATED_DATETIME
,ProductDataSourceRel.$7::NUMBER(38,0) AS TPA_HIERARCHY_KEY
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/ProductDataSourceRel.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')ProductDataSourceRel
;
