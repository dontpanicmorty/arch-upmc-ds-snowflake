CREATE OR REPLACE VIEW ODSDATA.LICENSE_STATUS_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
LicenseStatus.$1::NUMBER(38,0) AS LICENSE_STATUS_KEY
,LicenseStatus.$2::VARCHAR AS LICENSE_STATUS_DESC
,LicenseStatus.$3::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/LicenseStatus.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')LicenseStatus
;
