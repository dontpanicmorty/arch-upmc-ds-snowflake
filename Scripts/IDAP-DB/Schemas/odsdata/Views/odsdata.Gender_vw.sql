CREATE OR REPLACE VIEW ODSDATA.GENDER_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
Gender.$1::NUMBER(38,0) AS GENDER_KEY
,Gender.$2::VARCHAR AS GENDER_NAME
,Gender.$3::DATETIME AS LAST_UPDATED_DATETIME
,Gender.$5::VARCHAR AS GENDER_CODE
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/Gender.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')Gender
;
