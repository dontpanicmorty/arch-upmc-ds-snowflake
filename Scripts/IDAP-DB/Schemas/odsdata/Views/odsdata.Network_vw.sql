CREATE OR REPLACE VIEW ODSDATA.NETWORK_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
Network.$1::NUMBER(38,0) AS NETWORK_KEY
,Network.$2::NUMBER(38,0) AS PRODUCT_TYPE_KEY
,Network.$3::NUMBER(38,0) AS PRODUCT_KEY
,Network.$4::DATETIME AS LAST_UPDATED_DATETIME
,Network.$6::NUMBER(38,0) AS CARE_TYPE_KEY
,Network.$7::VARCHAR AS CONTRACT_MODEL_TEXT
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/Network.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')Network
;
