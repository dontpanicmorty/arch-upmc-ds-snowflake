CREATE OR REPLACE VIEW ODSDATA.PHARMACY_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
Pharmacy.$1::NUMBER(38,0) AS PHARMACY_KEY
,Pharmacy.$2::DATETIME AS LAST_UPDATED_DATETIME
,Pharmacy.$3::DATETIME AS INSERT_DATETIME
,Pharmacy.$4::VARCHAR AS PHARMACY_NAME
,Pharmacy.$5::VARCHAR AS DRIVE_THROUGH_IND
,Pharmacy.$6::VARCHAR AS DELIVERY_SERVICE_IND
,Pharmacy.$7::VARCHAR AS PREFERRED_PHARMACY_IND
,Pharmacy.$8::VARCHAR AS NY_ADA_ATTESTATION_IND
,Pharmacy.$9::VARCHAR AS OPEN_24_HOURS_PHARMACY_IND
,Pharmacy.$10::VARCHAR AS CHAIN_PHARMACY_IND
,Pharmacy.$11::VARCHAR AS INDEPENDENT_PHARMACY_IND
,Pharmacy.$12::VARCHAR AS PSAO_IND
,Pharmacy.$13::VARCHAR AS PHARMACY_CHAIN_NAME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/Pharmacy.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')Pharmacy
;
