CREATE OR REPLACE VIEW ODSDATA.TIME_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
Time.$1::NUMBER(38,0) AS TIME_KEY
,Time.$2::NUMBER(38,0) AS HOUR_NBR
,Time.$3::NUMBER(38,0) AS MINUTE_NBR
,Time.$4::DATETIME AS LAST_UPDATED_DATETIME
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/Time.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_FILE_FORMAT')Time
;
