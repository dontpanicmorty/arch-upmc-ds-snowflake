CREATE OR REPLACE VIEW ODSDATA.PRACTITIONER_VW
COMMENT = 'Replicated from Azure SQL DB'
AS
SELECT
Practitioner.$1::NUMBER(38,0) AS PRACTITIONER_KEY
,Practitioner.$2::DATETIME AS LAST_UPDATED_DATETIME
,Practitioner.$3::DATETIME AS INSERT_DATETIME
,Practitioner.$4::VARCHAR AS UPIN_NBR
,Practitioner.$5::VARCHAR AS FULL_NAME
,Practitioner.$6::VARCHAR AS LAST_NAME
,Practitioner.$7::VARCHAR AS FIRST_NAME
,Practitioner.$8::VARCHAR AS MIDDLE_NAME
,Practitioner.$9::VARCHAR AS MIDDLE_INITIAL_NAME
,Practitioner.$10::VARCHAR AS SUFFIX_NAME
,Practitioner.$11::VARCHAR AS DEGREE_TEXT
,Practitioner.$12::VARCHAR AS SOCIAL_SECURITY_NBR
,Practitioner.$13::DATE AS BIRTH_DATE
,Practitioner.$14::NUMBER(38,0) AS GENDER_KEY
,Practitioner.$15::VARCHAR AS LOCUM_TENENS_IND
,Practitioner.$16::VARCHAR AS INVISIBLE_PROVIDER_IND
,Practitioner.$17::VARCHAR AS TEMPORARY_PROVIDER_IND
,Practitioner.$18::VARCHAR AS PROVIDER_MAL_PRACTICE_COVERAGE_IND
,Practitioner.$19::VARCHAR AS LGBTQIA_CULTURAL_COMPETENCEY_IND
FROM @ODSDATA.HPDSDATALAKE_IDAPSQL/providerods/Practitioner.txt
(FILE_FORMAT => 'ODSDATA.PROVIDER_ODS_PRACTITIONER_FILE_FORMAT')Practitioner
;
