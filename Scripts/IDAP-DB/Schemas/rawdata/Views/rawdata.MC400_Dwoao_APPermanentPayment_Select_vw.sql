CREATE OR REPLACE VIEW RAWDATA.MC400_DWOAO_APPERMANENTPAYMENT_SELECT_VW
AS
SELECT
AMOUNT 
,CHECKNBR 
,CHECKDATE
,IFF(FILETYPE = 'H', 'I' , FILETYPE) AS FILETYPE
,POSTDATE
,ROWID
,SYSGENID
,STATUS 
,TABLEROWID 
,VENDORNO
,TPAROWID
FROM &{MC400}.DWOAO.APPERMANENTPAYMENT
QUALIFY DENSE_RANK() OVER(PARTITION BY TABLEROWID, FILETYPE ORDER BY SYSGENID) = 1
;
