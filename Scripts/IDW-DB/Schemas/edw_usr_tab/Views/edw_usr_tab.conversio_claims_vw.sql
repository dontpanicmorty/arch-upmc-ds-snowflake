CREATE OR REPLACE VIEW EDW_USR_TAB.CONVERSIO_CLAIMS_VW
AS
 SELECT C.MEMBER_ID,
   C.MEMBER_FIRST_NAME,
   C.MEMBER_LAST_NAME,
   C.MEMBER_DOB,
   C.FILL_ID,
   C.RX_SEQ,
   C.RX_NUMBER,
   C.FILL_START_DATE,
   C.DAYS_SUPPLY,
   C.QUANTITY,
   C.QUANTITY_UNITS,
   C.HCPCS_CODE,
   C.PRIMARY_MODIFIER,
   C.PRODUCT_SKU,
   C.PRODUCT_DESCRIPTION,
   C.THERAPEUTIC_CLASS,
   C.PRESCRIBER_NPI,
   C.PHARMACY_NPI,
   P.PROVIDER_NAME,
   C.STATUS,
   C.FILENAME AS FILE_NAME,
   C.INSERT_DATETIME AS LOAD_DATE
 FROM  &{IDAP_LAKE}.CLAIM.CONVERSIO_CLAIMS C
 LEFT JOIN &{IDW_LAKE}.EDW_RPT.PHARMACY_CLAIM_NPI P
ON C.PRESCRIBER_NPI=P.PRESCRIBER_NPI
;

