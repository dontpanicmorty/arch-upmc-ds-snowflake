CREATE OR REPLACE VIEW MEMBER_COMMUNICATIONS.TBL_MP_SMS_RESPONSE_VW (
	COMMUNICATION_ID,
	AUDIENCE,
	MESSAGE_TIMESTAMP,
	MESSAGE_CONTENT,
	EVENT_MEASURE_NAME,
	MEASURE_VALUE,
	MEASURE_VALUE_UNIQUE,
	MSG_SEQNUM,
	URL,
	SSC,
	CTS
	)
	COMMENT = 'This is the view that reads the Marketing SMS communication response from blob storage to IDAP_LAKE.'
AS (SELECT $1:COMMUNICATION_ID::VARCHAR,
		$1:AUDIENCE::VARCHAR,
		$1:MESSAGE_TIMESTAMP::VARCHAR,
		$1:MESSAGE_CONTENT::VARCHAR,
		$1:EVENT_MEASURE_NAME::VARCHAR,
		$1:MEASURE_VALUE::NUMBER,
		$1:MEASURE_VALUE_UNIQUE::NUMBER,
		$1:MSG_SEQNUM::NUMBER,
		$1:URL::VARCHAR,
		$1:SSC::VARCHAR,
		$1:CTS::TIMESTAMP_NTZ
FROM @UTIL.HPDSDATALAKE_DBEXTRACT_IDAP_LAKE/mktodsdb/dbo/tbl_mp_sms_response_vw/
(FILE_FORMAT => 'UTIL.DB_EXTRACT_PARQUET_FILE_FORMAT')
    )
;