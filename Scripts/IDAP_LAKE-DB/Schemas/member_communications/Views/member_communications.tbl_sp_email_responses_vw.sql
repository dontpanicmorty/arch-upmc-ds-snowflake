CREATE OR REPLACE VIEW MEMBER_COMMUNICATIONS.TBL_SP_EMAIL_RESPONSE_VW (
    COMMUNICATION_ID, 
    EMAIL_SUBJECT_LINE,
    CLICK_LINK_NAME,
    EVENT_DATE,
    EVENT_MEASURE_NAME,
    EVENT_MEASURE_VALUE,
    SSC,
    CTS
    )
    COMMENT = 'This view pulls the table from blob storage into the IDAP_LAKE view for the Marketing Email Repsonses.'
AS (
SELECT  $1:COMMUNICATION_ID::VARCHAR,
        $1:EMAIL_SUBJECT_LINE::VARCHAR,
        $1:CLICK_LINK_NAME::VARCHAR,
        $1:EVENT_DATE::TIMESTAMP_NTZ,
        $1:EVENT_MEASURE_NAME::VARCHAR,
        $1:EVENT_MEASURE_VALUE::NUMBER,
        $1:SSC::VARCHAR,
        $1:CTS::TIMESTAMP_NTZ
FROM    @UTIL.HPDSDATALAKE_DBEXTRACT_IDAP_LAKE/mktodsdb/dbo/tbl_sp_email_response_vw/ 
        (FILE_FORMAT => 'UTIL.DB_EXTRACT_PARQUET_FILE_FORMAT')
    )
;