CREATE OR REPLACE VIEW DHS.OIM_DETAIL_VW AS
SELECT
    FILENAME,
    INSERT_DATETIME,
    SSN,
    CATEGORY_CODE,
    STATUS_CODE,
    START_DATE,
    END_DATE,
    REDETERMINATION_DATE
FROM DHS.OIM_DETAIL_CURRENT_VW
UNION ALL
SELECT
    FILENAME,
    INSERT_DATETIME,
    SSN,
    CATEGORY_CODE,
    STATUS_CODE,
    START_DATE,
    END_DATE,
    REDETERMINATION_DATE
FROM DHS.OIM_DETAIL_HISTORY;