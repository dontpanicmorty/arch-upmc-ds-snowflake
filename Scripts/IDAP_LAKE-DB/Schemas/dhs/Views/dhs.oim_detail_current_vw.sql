CREATE OR REPLACE VIEW DHS.OIM_DETAIL_CURRENT_VW AS
SELECT
    FILENAME                            AS FILENAME,
    FILE_LAST_MODIFIED_DATETIME         AS INSERT_DATETIME,
    SUBSTR(RECORD, 2, 9)                AS SSN,
    TRIM(SUBSTR(RECORD, 11, 3))         AS CATEGORY_CODE,
    SUBSTR(RECORD, 14, 2)               AS STATUS_CODE,
    SUBSTR(RECORD, 16, 7)               AS START_DATE,
    SUBSTR(RECORD, 23, 7)               AS END_DATE,
    SUBSTR(RECORD, 30, 7)               AS REDETERMINATION_DATE
FROM DHS.OIM_HEADER_AND_DETAIL_STAGE
WHERE SUBSTR(RECORD, 1, 1) = '2';