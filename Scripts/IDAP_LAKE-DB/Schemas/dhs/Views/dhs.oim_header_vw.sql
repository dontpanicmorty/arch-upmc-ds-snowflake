CREATE OR REPLACE VIEW DHS.OIM_HEADER_VW AS
SELECT
    FILENAME,
    INSERT_DATETIME,
    SSN,
    LAST_NAME,
    FIRST_NAME,
    MIDDLE_NAME,
    DOB
FROM DHS.OIM_HEADER_CURRENT_VW
UNION ALL
SELECT
    FILENAME,
    INSERT_DATETIME,
    SSN,
    LAST_NAME,
    FIRST_NAME,
    MIDDLE_NAME,
    DOB
FROM DHS.OIM_HEADER_HISTORY;