CREATE OR REPLACE VIEW DHS.MEDICAID_PEND_ENROLL_VW AS
SELECT
    SUBSTR(RECORD,  1, 10)      AS RECIP_INDIV_NO,
    SUBSTR(RECORD, 11,  2)      AS COUNTY,
    SUBSTR(RECORD, 13,  2)      AS CURRENT_PLAN_CODE,
    SUBSTR(RECORD, 15,  1)      AS OTHER_INS_IND,
    SUBSTR(RECORD, 16,  1)      AS PREGNANT_IND,
    TO_DATE(NULLIF(SUBSTR(RECORD, 17, 8), '        '), 'MMDDYYYY') AS DELIVERY_DATE,
    SUBSTR(RECORD, 25,  6)      AS SPEC_MED_NEED_1,
    SUBSTR(RECORD, 31, 200)     AS SPEC_NEED_NOTES,
    SUBSTR(RECORD,231, 10)      AS MEDICARE_NO,
    SUBSTR(RECORD,241,  3)      AS OTHER_INS_COVER_NO_1,
    SUBSTR(RECORD,244, 20)      AS OTHER_INS_POLICY_NO_1,
    SUBSTR(RECORD,264,  3)      AS OTHER_INS_COVER_NO_2,
    SUBSTR(RECORD,267, 20)      AS OTHER_INS_POLICY_NO_2,
    SUBSTR(RECORD,287, 15)      AS PLAN_PRVDR_NO,
    SUBSTR(RECORD,302,  2)      AS PRVDR_TYPE,
    SUBSTR(RECORD,304, 61)      AS PRVDR_NAME,
    SUBSTR(RECORD,365,200)      AS PCP_NOTES,
    SUBSTR(RECORD,565, 10)      AS CASE_PHONE_NO,
    SUBSTR(RECORD,575, 10)      AS ALT_CASE_PHONE,
    SUBSTR(RECORD,585, 27)      AS CASE_ADDR1,
    SUBSTR(RECORD,612, 26)      AS CASE_ADDR2,
    SUBSTR(RECORD,638, 16)      AS CASE_CITY,
    SUBSTR(RECORD,654,  2)      AS CASE_STATE,
    SUBSTR(RECORD,656,  5)      AS CASE_ZIP,
    SUBSTR(RECORD,661,  4)      AS CASE_ZIP_EXT,
    SUBSTR(RECORD,665,  2)      AS LANG_CODE,
    FILENAME                    AS FILE_NAME,
    FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM DHS.MEDICAID_PEND_ENROLL
WHERE SUBSTR(RECORD,  1, 7) <> 'TRAILER';