CREATE OR REPLACE VIEW DHS.OIM_HEADER_CURRENT_VW AS
SELECT
    FILENAME                            AS FILENAME,
    FILE_LAST_MODIFIED_DATETIME         AS INSERT_DATETIME,
    SUBSTR(RECORD, 2, 9)                AS SSN,
    SUBSTR(RECORD, 11, 14)              AS LAST_NAME,
    SUBSTR(RECORD, 25, 11)              AS FIRST_NAME,
    SUBSTR(RECORD, 36, 4)               AS MIDDLE_NAME,
    SUBSTR(RECORD, 40, 7)               AS DOB
FROM DHS.OIM_HEADER_AND_DETAIL_STAGE
WHERE SUBSTR(RECORD, 1, 1) = '1';