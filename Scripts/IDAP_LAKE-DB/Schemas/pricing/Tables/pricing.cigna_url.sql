CREATE OR REPLACE TABLE PRICING.CIGNA_URL (
  FILENAME VARCHAR,
  INSERT_DATETIME TIMESTAMP_TZ(9),
  URL VARCHAR,
  CIGNA_URL_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
  CONSTRAINT PK_CIGNA_URL PRIMARY KEY (CIGNA_URL_KEY),
  CONSTRAINT UK_CIGNA_URL UNIQUE (URL)
)
COMMENT = 'URLs provided by Cigna that need to be included as an in-network file for us. Delivered monthly.'
