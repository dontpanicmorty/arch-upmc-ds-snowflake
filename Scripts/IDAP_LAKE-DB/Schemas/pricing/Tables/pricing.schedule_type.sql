CREATE OR REPLACE TABLE PRICING.SCHEDULE_TYPE (
  FILENAME VARCHAR,
  INSERT_DATETIME TIMESTAMP_TZ(9),
  PROVIDER_TYPE VARCHAR,
  SCHEDULE_TYPE VARCHAR,
  SCHEDULE_DETAIL VARCHAR,
  BILLING_CLASS VARCHAR,
  SCHEDULE_TYPE_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
