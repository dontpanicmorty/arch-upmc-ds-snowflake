CREATE OR REPLACE TABLE PRICING.LOCATION (
  FILENAME VARCHAR,
  INSERT_DATETIME TIMESTAMP_TZ(9),
  ID VARCHAR,
  LOCATION VARCHAR,
  PLACE_OF_SERVICE VARCHAR,
  LOCATION_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
  CONSTRAINT PK_LOCATION PRIMARY KEY (LOCATION_KEY),
  CONSTRAINT UK_LOCATION UNIQUE (LOCATION, PLACE_OF_SERVICE)
)
COMMENT = 'Location/place-of-service spreadsheets provided by business (Mateo Cummings) for CMS_PRICING.'
;