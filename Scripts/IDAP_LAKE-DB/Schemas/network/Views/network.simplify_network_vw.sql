create or replace view NETWORK.SIMPLIFY_NETWORK_VW(
	DOCUMENT_ID,
	SIMPLIFY_PLAN_PACKAGE_KEY,
	COVERAGE_DISPLAY_NAME,
	COVERAGE_NAME,
	NETWORK_NAME,
	NETWORK_TIER,
	PROV_NETWORK_TIER,
	PROV_PROVIDER_NETWORK_NAME
) COMMENT='Parses out Network column from JSON leaving nested arrays still as arrays so its one row per documentID/SimplifyPlanPackageKey'
 as 


(  

SELECT  C.Document_ID,
C.SIMPLIFY_PLAN_PACKAGE_KEY,
C.COVERAGE_DISPLAY_NAME,
C.COVERAGE_NAME,
N.NETWORK_NAME,
N.NETWORK_TIER,
p.PROV_NETWORK_TIER,
P.PROV_PROVIDER_NETWORK_NAME

    
FROM
     (SELECT DISTINCT V.Document_ID
     ,V.SIMPLIFY_PLAN_PACKAGE_KEY
    ,value:CoverageDisplayName::String AS COVERAGE_DISPLAY_NAME
    ,value:CoverageName::string AS COVERAGE_NAME
FROM NETWORK.SIMPLIFY_PLAN_PACKAGE_VW V
,lateral flatten( input => NETWORK:CoverageLevelList) ) C


  INNER JOIN

   (SELECT DISTINCT V.Document_ID
     ,V.SIMPLIFY_PLAN_PACKAGE_KEY
    ,value:NetworkName::String AS NETWORK_NAME
    ,value:NetworkTier::string AS NETWORK_TIER
FROM NETWORK.SIMPLIFY_PLAN_PACKAGE_VW V
    ,lateral flatten( input => NETWORK:NetworkTierList) ) N ON 
        C.SIMPLIFY_PLAN_PACKAGE_KEY=N.SIMPLIFY_PLAN_PACKAGE_KEY
        AND C.DOCUMENT_ID=N.DOCUMENT_ID


INNER JOIN

   (SELECT DISTINCT V.Document_ID
     ,V.SIMPLIFY_PLAN_PACKAGE_KEY
    ,value:NetworkTier::String AS PROV_NETWORK_TIER
    ,value:ProviderNetworkName::string AS PROV_PROVIDER_NETWORK_NAME
FROM NETWORK.SIMPLIFY_PLAN_PACKAGE_VW V
    ,lateral flatten( input => NETWORK:ProviderNetworkMap:ProviderNetworkList) ) P ON 
        C.SIMPLIFY_PLAN_PACKAGE_KEY=P.SIMPLIFY_PLAN_PACKAGE_KEY
        AND C.DOCUMENT_ID=P.DOCUMENT_ID


INNER JOIN
    NETWORK.SIMPLIFY_PLAN_PACKAGE_CURRENT_ROW_VW CR ON 
        C.SIMPLIFY_PLAN_PACKAGE_KEY = CR.SIMPLIFY_PLAN_PACKAGE_KEY
  
)
;