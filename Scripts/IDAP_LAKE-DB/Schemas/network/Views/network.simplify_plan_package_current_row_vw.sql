CREATE OR REPLACE MATERIALIZED VIEW NETWORK.SIMPLIFY_PLAN_PACKAGE_CURRENT_ROW_VW
COMMENT='Returns the most current INSERT_DATETIME per FormInstanceID / DOCUMENT_ID'
AS
SELECT 
JSON_DATA:Result.Data.FormInstanceID::number AS DOCUMENT_ID
,MAX(SIMPLIFY_PLAN_PACKAGE_KEY) AS SIMPLIFY_PLAN_PACKAGE_KEY
,MAX(INSERT_DATETIME) AS INSERT_DATETIME
FROM NETWORK.SIMPLIFY_PLAN_PACKAGE
GROUP BY JSON_DATA:Result.Data.FormInstanceID::number
;