CREATE OR REPLACE VIEW NETWORK.SIMPLIFY_PRODUCT_RULES_VW
COMMENT = 'Parses out Product_Rules column from JSON leaving nested arrays still as arrays so its one row per documentID/SimplifyPlanPackageKey'
AS 

(  

SELECT  C.Document_ID
    ,C.SIMPLIFY_PLAN_PACKAGE_KEY
    ,COC_FILENAME
    ,MEDICAL_ROC_FILENAME
    ,MEDICAL_SOB_FILENAME
    ,PEDI_DENTAL_SOB_FILENAME
    ,PEDI_VISION_ROC_FILENAME
    ,PEDI_VISION_SOB_FILENAME
    ,PEDIATRIC_DENTAL_COI_FILENAME
    ,PEDIATRIC_DENTAL_ROC_FILENAME
    ,PEDIATRIC_VISION_COI_FILENAME
    ,SBC_FILENAME
    ,FUNDING_ARRANGEMENT
    ,IS_PCP_REQUIRED
    ,LEGAL_ENTITY
    ,LINE_OF_BUSINESS
    ,MARKET_SEGMENT
    ,MARKETING_PORTFOLIO
    ,MEDICAL_PID_FORM_NUMBER
    ,NEW_RENEWAL_PLAN
    ,PLAN_EFFECTIVE_DATE
    ,PLAN_NAME
    ,PLAN_NAME_ON_ID_CARD
    ,PLAN_SUBTYPE
    ,POLICY_FORM_NUMBER
    ,PRODUCT_ID
    ,TYPE_OF_PLAN

FROM
--Getting MedicalDocumentFiles section
     (SELECT DISTINCT V.Document_ID
        ,V.SIMPLIFY_PLAN_PACKAGE_KEY
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'MedicalDocumentFileNames.COCFileName' ) AS COC_FILENAME
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'MedicalDocumentFileNames.MedicalROCFileName' )  AS MEDICAL_ROC_FILENAME
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'MedicalDocumentFileNames.MedicalSOBFileName' ) AS MEDICAL_SOB_FILENAME
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'MedicalDocumentFileNames.PediDentalSOBFileName' ) AS PEDI_DENTAL_SOB_FILENAME
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'MedicalDocumentFileNames.PediVisionROCFileName' ) AS PEDI_VISION_ROC_FILENAME
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'MedicalDocumentFileNames.PediVisionSOBFileName' ) AS PEDI_VISION_SOB_FILENAME
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'MedicalDocumentFileNames.PediatricDentalCOIFileName' ) AS PEDIATRIC_DENTAL_COI_FILENAME
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'MedicalDocumentFileNames.PediatricDentalROCFileName' ) AS PEDIATRIC_DENTAL_ROC_FILENAME
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'MedicalDocumentFileNames.PediatricVisionCOIFileName' ) AS PEDIATRIC_VISION_COI_FILENAME
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'MedicalDocumentFileNames.SBCFileName' ) AS SBC_FILENAME
      FROM IDAP_LAKE.NETWORK.SIMPLIFY_PLAN_PACKAGE_VW V
     ) C

INNER JOIN
--Getting PlanInformation section
    (SELECT DISTINCT V.Document_ID
        ,V.SIMPLIFY_PLAN_PACKAGE_KEY
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'PlanInformation.FundingArrangement' ) AS FUNDING_ARRANGEMENT
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'PlanInformation.IsPCPRequired' ) AS IS_PCP_REQUIRED
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'PlanInformation.LegalEntity' ) AS LEGAL_ENTITY
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'PlanInformation.LineofBusiness' ) AS LINE_OF_BUSINESS
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'PlanInformation.MarketSegment' ) AS MARKET_SEGMENT
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'PlanInformation.MarketingPortfolio' ) AS MARKETING_PORTFOLIO
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'PlanInformation.MedicalPIDFormNumber' ) AS MEDICAL_PID_FORM_NUMBER
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'PlanInformation.NewRenewalPlan' ) AS NEW_RENEWAL_PLAN
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'PlanInformation.PlanEffectiveDate' ) AS PLAN_EFFECTIVE_DATE
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'PlanInformation.PlanName' ) AS PLAN_NAME
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'PlanInformation.PlanNameonIDCard' ) AS PLAN_NAME_ON_ID_CARD
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'PlanInformation.PlanSubtype' ) AS PLAN_SUBTYPE
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'PlanInformation.PolicyFormNumber' ) AS POLICY_FORM_NUMBER
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'PlanInformation.ProductID' ) AS PRODUCT_ID
        ,JSON_EXTRACT_PATH_TEXT( V.PRODUCTRULES , 'PlanInformation.TypeofPlan' ) AS TYPE_OF_PLAN
      FROM IDAP_LAKE.NETWORK.SIMPLIFY_PLAN_PACKAGE_VW V
    ) D ON 
        C.SIMPLIFY_PLAN_PACKAGE_KEY = D.SIMPLIFY_PLAN_PACKAGE_KEY
        AND C.DOCUMENT_ID=D.DOCUMENT_ID

  INNER JOIN IDAP_LAKE.NETWORK.SIMPLIFY_PLAN_PACKAGE_CURRENT_ROW_VW CR ON 
    C.SIMPLIFY_PLAN_PACKAGE_KEY = CR.SIMPLIFY_PLAN_PACKAGE_KEY
)
;
