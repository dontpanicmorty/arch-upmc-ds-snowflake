CREATE OR REPLACE TABLE APPLICATION_EVENTS.SMS_MESSAGE_LOGS (
    SMS_MESSAGE_LOGS_KEY NUMBER(38, 0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
    FILENAME VARCHAR NOT NULL,
    FILE_ROW_NUMBER NUMBER(38, 0) NOT NULL,
    LOAD_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    EVENT_ENQUEUED_UTC_TIME TIMESTAMP_TZ(9) NOT NULL,
    EVENT_PROCESSED_UTC_TIME TIMESTAMP_TZ(9) NOT NULL,
    OPERATION VARCHAR NOT NULL,
    PARTITION_ID VARCHAR NOT NULL,
    TABLE_NAME VARCHAR NOT NULL,
    JSON_DATA VARIANT NOT NULL,
    CONSTRAINT PK_SMS_MESSAGE_LOGS PRIMARY KEY (SMS_MESSAGE_LOGS_KEY),
    CONSTRAINT UK_SMS_MESSAGE_LOGS UNIQUE (FILENAME, FILE_ROW_NUMBER)
) COMMENT = 'Stream analytics application logged sms data from Consumer Tech.';