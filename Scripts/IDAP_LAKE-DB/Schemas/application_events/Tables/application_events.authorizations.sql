CREATE OR REPLACE TABLE APPLICATION_EVENTS.AUTHORIZATIONS (
    AUTHORIZATIONS_KEY NUMBER(38, 0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
    FILENAME VARCHAR(16777216) NOT NULL,
	FILE_ROW_NUMBER NUMBER(38,0) NOT NULL,
	LOAD_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    ID VARCHAR NULL,
    COSMOS_LAST_UPDATED TIMESTAMP_TZ(9) NULL,
    SOURCE_LAST_UPDATED TIMESTAMP_TZ(9) NULL,
    MEMBER_ID VARCHAR NULL,
    JSON_DATA VARIANT NOT NULL,
    CONSTRAINT PK_AUTHORIZATIONS PRIMARY KEY (AUTHORIZATIONS_KEY),
    CONSTRAINT UK_AUTHORIZATIONS UNIQUE (FILENAME, FILE_ROW_NUMBER)
)