CREATE OR REPLACE TABLE APPLICATION_EVENTS.APIM_LOGS
    (
        APIM_LOGS_KEY NUMBER(38, 0) NOT NULL AUTOINCREMENT ORDER START 1 INCREMENT 1,
        FILENAME VARCHAR NOT NULL,
        FILE_ROW_NUMBER NUMBER(38, 0) NOT NULL,
        LOAD_DATETIME TIMESTAMP_TZ(9),
        EVENT_DATETIME_UTC TIMESTAMP_TZ(9),
        PRODUCT VARCHAR,
        API_NAME VARCHAR NOT NULL,
        REQUEST_URL VARCHAR NOT NULL,
        JSON_DATA VARIANT NOT NULL,
        CONSTRAINT PK_APIM_LOGS PRIMARY KEY (APIM_LOGS_KEY),
        CONSTRAINT UK_APIM_LOGS UNIQUE (FILENAME, FILE_ROW_NUMBER)
    ) 
    COMMENT = 'Stream analytics application logged event data from Consumer Tech.';