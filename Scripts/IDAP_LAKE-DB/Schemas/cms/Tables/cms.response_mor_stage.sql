CREATE OR REPLACE TABLE CMS.RESPONSE_MOR_STAGE 
(
    FILENAME VARCHAR,
    FILE_LAST_MODIFIED_DATETIME TIMESTAMP_TZ(9),
    LAST_UPDATED_DATETIME TIMESTAMP_TZ(9),
    ROW_NUMBER NUMBER,
    RECORD_TYPE VARCHAR,
    FILE_PREFIX VARCHAR,
    FILE_TYPE VARCHAR,
    FILE_DATE VARCHAR,
    FILE_TIME VARCHAR,
    RECORD VARCHAR,
    constraint PK_RESPONSE_MOR_STAGE primary key (FILENAME, ROW_NUMBER)
)
COMMENT = 'Staging table for MOR response files from CMS' 
;