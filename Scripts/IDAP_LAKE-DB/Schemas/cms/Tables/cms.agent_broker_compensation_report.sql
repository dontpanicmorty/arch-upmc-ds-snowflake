CREATE OR REPLACE TABLE CMS.AGENT_BROKER_COMPENSATION_REPORT
(
    FILENAME VARCHAR,
    FILE_LAST_MODIFIED_DATETIME TIMESTAMP_TZ(9),
    ROW_NUMBER NUMBER,
    RECORD VARCHAR,
