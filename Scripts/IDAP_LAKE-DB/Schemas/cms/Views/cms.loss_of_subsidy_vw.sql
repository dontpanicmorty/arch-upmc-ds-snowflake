CREATE OR REPLACE VIEW CMS.LOSS_OF_SUBSIDY_VW AS
SELECT
  SUBSTRING(RECORD, 1, 12)    AS BENEFICIARY_ID,
  SUBSTRING(RECORD, 13, 12)   AS SURNAME,
  SUBSTRING(RECORD, 25, 7)    AS FIRST_NAME,
  SUBSTRING(RECORD, 32, 1)    AS MIDDLE_INITIAL,
  SUBSTRING(RECORD, 33, 1)    AS SEX_CODE,
  SUBSTRING(RECORD, 34, 8)    AS DATE_OF_BIRTH,
  SUBSTRING(RECORD, 42, 1)    AS FILLER_1,
  SUBSTRING(RECORD, 43, 5)    AS CONTRACT_NUMBER,
  SUBSTRING(RECORD, 48, 2)    AS STATE_CODE,
  SUBSTRING(RECORD, 50, 3)    AS COUNTY_CODE,
  SUBSTRING(RECORD, 53, 4)    AS FILLER_2,
  SUBSTRING(RECORD, 57, 3)    AS TRC,
  SUBSTRING(RECORD, 60, 2)    AS TRANSACTION_CODE,
  SUBSTRING(RECORD, 62, 1)    AS FILLER_3,
  SUBSTRING(RECORD, 63, 8)    AS EFFECTIVE_DATE,
  SUBSTRING(RECORD, 71, 1)    AS FILLER_4,
  SUBSTRING(RECORD, 72, 3)    AS PBP_ID,
  SUBSTRING(RECORD, 75, 1)    AS FILLER_5,
  SUBSTRING(RECORD, 76, 8)    AS TRANSACTION_DATE,
  SUBSTRING(RECORD, 84, 1)    AS FILLER_6,
  SUBSTRING(RECORD, 85, 8)    AS LOW_INCOME_SUBSIDY_END_DATE,
  SUBSTRING(RECORD, 93, 42)   AS FILLER_7,
  SUBSTRING(RECORD, 135, 3)   AS SEGMENT_NUMBER,
  SUBSTRING(RECORD, 138, 97)  AS FILLER_8,
  SUBSTRING(RECORD, 235, 3)   AS PART_D_LIPS_LEVEL,
  SUBSTRING(RECORD, 238, 1)   AS LOW_INCOME_COPAY_CATEGORY,
  SUBSTRING(RECORD, 239, 124) AS FILLER_9,
  SUBSTRING(RECORD, 363, 1)   AS LIS_SOURCE_CODE,
  SUBSTRING(RECORD, 364, 137) AS FILLER_10,
  FILENAME                    AS FILE_NAME,
  FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.LOSS_OF_SUBSIDY;