CREATE OR REPLACE VIEW CMS.COB_OHI_ANNUAL_SUMMARY_HEADER_VW AS
SELECT
  SUBSTRING(RECORD, 1, 16)  AS FILLER_1,
  SUBSTRING(RECORD, 23, 34) AS REPORT_NAME,
  SUBSTRING(RECORD, 61, 20) AS FILLER_2,
  FILENAME                  AS FILE_NAME,
  FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.COB_OHI_ANNUAL_SUMMARY
WHERE SUBSTRING(RECORD, 23, 34) = 'Annual COB-OHI Summary File Report';