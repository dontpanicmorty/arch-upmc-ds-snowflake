CREATE OR REPLACE VIEW CMS.MONTHLY_PREMIUM_WITHHOLDING_REPORT_TRAILER_VW AS
SELECT
    SUBSTRING(RECORD,  1,  2) AS RECORD_TYPE,
    SUBSTRING(RECORD,  3,  5) AS MCO_CONTRACT_NUMBER,
    SUBSTRING(RECORD,  8,  3) AS PLAN_BENEFIT_PACKAGE_ID,
    SUBSTRING(RECORD, 11,  3) AS PLAN_SEGMENT_ID,
    SUBSTRING(RECORD, 14, 14) AS TOTAL_PART_C_PREMIUMS_COLLECTED,
    SUBSTRING(RECORD, 28, 14) AS TOTAL_PART_D_PREMIUMS_COLLECTED,
    SUBSTRING(RECORD, 42, 14) AS TOTAL_PART_D_LEPS_COLLECTED,
    SUBSTRING(RECORD, 56, 14) AS TOTAL_PREMIUMS_COLLECTED,
    SUBSTRING(RECORD, 70, 96) AS FILLER,
    FILENAME,
	FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.MONTHLY_PREMIUM_WITHHOLDING_REPORT
WHERE TRIM(SUBSTRING(RECORD,  1,  2)) NOT IN ('H','D');