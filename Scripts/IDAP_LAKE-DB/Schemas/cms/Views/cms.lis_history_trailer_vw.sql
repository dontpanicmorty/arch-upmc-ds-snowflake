CREATE OR REPLACE VIEW CMS.LIS_HISTORY_TRAILER_VW AS
SELECT
    SUBSTRING(RECORD, 1,   1)   AS RECORD_TYPE,
    SUBSTRING(RECORD, 2,   5)   AS MCO_CONTRACT_NUMBER,
    SUBSTRING(RECORD, 7,   8)   AS TOTALS,
    SUBSTRING(RECORD, 15, 151)  AS FILLER,
	FILENAME,
	FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.LIS_HISTORY
 WHERE SUBSTRING(RECORD, 1, 1) = 'T';