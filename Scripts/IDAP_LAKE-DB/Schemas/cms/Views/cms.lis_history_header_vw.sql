CREATE OR REPLACE VIEW CMS.LIS_HISTORY_HEADER_VW AS
SELECT
    SUBSTRING(RECORD, 1, 1)   AS RECORD_TYPE,
    SUBSTRING(RECORD, 2, 5)   AS MCO_CONTRACT_NUMBER,
    SUBSTRING(RECORD, 7, 8)   AS DATA_FILE_DATE,
    SUBSTRING(RECORD, 15, 6)  AS CALENDAR_MONTH,
    SUBSTRING(RECORD, 21, 145) AS FILLER,
	FILENAME,
	FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.LIS_HISTORY
 WHERE SUBSTRING(RECORD, 1, 1) = 'H';