CREATE OR REPLACE VIEW CMS.PARTD_EXCLUSION_WARNING_PEXBT_CURRENT_VW AS
SELECT
    FILENAME                                                            AS FILENAME,
    FILE_LAST_MODIFIED_DATETIME                                         AS INSERT_DATETIME,
    SUBSTR(RECORD,1,5)                                                  AS RECORD_ID,
    TRY_TO_DATE(NULLIF(TRIM(SUBSTR(RECORD, 6, 8)),''),'YYYYMMDD')       AS DDPS_SYSTEM_DATE,
    SUBSTR(RECORD,14,6)                                                 AS DDPS_SYSTEM_TIME,
    SUBSTR(RECORD,20,5)                                                 AS FILE_ID,
    SUBSTR(RECORD,25,4)                                                 AS RECON_BENEFIT_YEAR,
    SUBSTR(RECORD,29,4)                                                 AS RECON_NUM,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,33,14)) AS NUMBER(14,2))       AS TOTAL_LICS_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,47,14)) AS NUMBER(14,2))       AS TOTAL_GDCB_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,61,14)) AS NUMBER(14,2))       AS TOTAL_GDCA_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,75,14)) AS NUMBER(14,2))       AS TOTAL_CPP_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,89,14)) AS NUMBER(14,2))       AS TOTAL_EST_REMUN_AT_POS_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,103,14)) AS NUMBER(14,2))      AS TOTAL_NPP_AMT,
    TRY_TO_NUMBER(SUBSTR(RECORD,117,7))                                 AS TOTAL_PDE_COUNT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,124,14)) AS NUMBER(14,2))      AS TOTAL_GAP_DISC_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,138,14)) AS NUMBER(14,2))      AS TOTAL_MANUFAC_DISC_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,152,14)) AS NUMBER(14,2))      AS TOTAL_SELEC_DRUG_SUB_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,166,14)) AS NUMBER(14,2))      AS TOTAL_PHARM_PRICE_CONCESS_AT_POS 
FROM CMS.PARTD_EXCLUSION_WARNING_STAGE
WHERE SUBSTR(RECORD,1,5) = 'PEXBT';