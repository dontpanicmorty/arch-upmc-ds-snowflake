CREATE OR REPLACE VIEW CMS.COB_OHI_ANNUAL_SUMMARY_SUBHEADER_VW AS
SELECT
  SUBSTRING(RECORD, 1, 34)  AS FILLER_1,
  SUBSTRING(RECORD, 35, 10) AS REPORT_CREATION_DATE,
  SUBSTRING(RECORD, 47, 34) AS FILLER_2,
  FILENAME                  AS FILE_NAME,
  FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.COB_OHI_ANNUAL_SUMMARY
WHERE SUBSTRING(RECORD, 1, 34) = '                                  ';