CREATE OR REPLACE VIEW CMS.MEDICARE_ADVANTAGE_MEDICAID_STATUS_TRAILER_VW AS
SELECT
    SUBSTRING(RECORD,  1,  1) AS RECORD_TYPE,
    SUBSTRING(RECORD,  2,  5) AS CONTRACT_NUMBER,
    SUBSTRING(RECORD,  7,  7) AS RECORD_COUNT,
    SUBSTRING(RECORD, 14,  7) AS BENEFICIARY_RECORD_COUNT,
    SUBSTRING(RECORD, 21, 55) AS FILLER,
    FILENAME,
	FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.MEDICARE_ADVANTAGE_MEDICAID_STATUS
WHERE SUBSTRING(RECORD,  1,  1) = '4';