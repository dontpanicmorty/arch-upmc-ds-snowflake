CREATE OR REPLACE VIEW CMS.BATCH_COMPLETION_STATUS_SUMMARY_COUNTS_VW AS
WITH counts AS (
    SELECT
        FILENAME,
        FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE,
        ROW_NUMBER,
        SUBSTRING(RECORD, 1, 2)     AS COUNT_TYPE,
        RECORD                      AS LINE
    FROM CMS.BATCH_COMPLETION_STATUS_SUMMARY
    WHERE SUBSTRING(RECORD, 1, 1) = 'C'
),
parsed AS (
    SELECT
        FILENAME,
        LOAD_DATE,
        COUNT_TYPE,

        CASE WHEN COUNT_TYPE = 'C1' THEN
            TRIM(SPLIT_PART(LINE, '=', 2))
        END AS C1_TRAN_CNTS1,

        CASE WHEN COUNT_TYPE = 'C2' THEN
            TRIM(SPLIT_PART(LINE, '=', 2))
        END AS C2_TRAN_CNTS2,

        CASE WHEN COUNT_TYPE = 'C3' THEN
            TRIM(SPLIT_PART(LINE, '=', 2))
        END AS C3_TRAN_CNTS3,

        CASE WHEN COUNT_TYPE = 'C4' THEN
            TRIM(SPLIT_PART(LINE, '=', 2))
        END AS C4_TRAN_CNTS4,

        CASE WHEN COUNT_TYPE = 'C5' THEN
            TRIM(SPLIT_PART(LINE, '=', 2))
        END AS C5_TRAN_CNTS5,

        CASE WHEN COUNT_TYPE = 'C6' THEN
            TRIM(SPLIT_PART(LINE, '=', 2))
        END AS C6_TRAN_CNTS6
    
    FROM counts
)
SELECT 
    FILENAME,
    LOAD_DATE,
    MAX(C1_TRAN_CNTS1)     AS C1_TRAN_CNTS1,
    MAX(C2_TRAN_CNTS2)     AS C2_TRAN_CNTS2,
    MAX(C3_TRAN_CNTS3)     AS C3_TRAN_CNTS3,
    MAX(C4_TRAN_CNTS4)     AS C4_TRAN_CNTS4,
    MAX(C5_TRAN_CNTS5)     AS C5_TRAN_CNTS5,
    MAX(C6_TRAN_CNTS6)     AS C6_TRAN_CNTS6
FROM parsed
GROUP BY FILENAME, LOAD_DATE;
