CREATE OR REPLACE VIEW CMS.MEDICARE_ADVANTAGE_MEDICAID_STATUS_DETAIL_VW AS
SELECT
    SUBSTRING(RECORD,  1,  1) AS RECORD_TYPE,
    SUBSTRING(RECORD,  2,  5) AS CONTRACT_NUMBER,
    SUBSTRING(RECORD,  7,  8) AS MEDICAID_START_DATE,
    SUBSTRING(RECORD, 15,  8) AS MEDICAID_END_DATE,
    SUBSTRING(RECORD, 23,  1) AS MEDICAID_FULL_PARTIAL_NON_DUAL,
    SUBSTRING(RECORD, 24,  2) AS DUAL_STATUS_CODE,
    SUBSTRING(RECORD, 26, 12) AS RECORD_ADD_TIMESTAMP,
    SUBSTRING(RECORD, 38, 12) AS RECORD_UPDATE_TIMESTAMP,
    SUBSTRING(RECORD, 50,  1) AS MEDICAID_RECORD_TYPE,
    SUBSTRING(RECORD, 51, 25) AS FILLER,
    FILENAME,
	FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.MEDICARE_ADVANTAGE_MEDICAID_STATUS
WHERE SUBSTRING(RECORD,  1,  1) = '3';