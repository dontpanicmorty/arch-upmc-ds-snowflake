CREATE OR REPLACE VIEW CMS.MEDICARE_ADVANTAGE_MEDICAID_STATUS_IDENTIFICATION_VW AS
SELECT
    SUBSTRING(RECORD,  1,  1) AS RECORD_TYPE,
    SUBSTRING(RECORD,  2,  5) AS CONTRACT_NUMBER,
    SUBSTRING(RECORD,  7, 12) AS BENEFICIARY_ID,
    SUBSTRING(RECORD, 19, 12) AS LAST_NAME,
    SUBSTRING(RECORD, 31,  7) AS FIRST_NAME,
    SUBSTRING(RECORD, 38,  1) AS MIDDLE_INITIAL,
    SUBSTRING(RECORD, 39,  8) AS DOB,
    SUBSTRING(RECORD, 47,  1) AS SEX,
    SUBSTRING(RECORD, 48, 28) AS FILLER,
    FILENAME,
	FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.MEDICARE_ADVANTAGE_MEDICAID_STATUS
WHERE SUBSTRING(RECORD,  1,  1) = '2';