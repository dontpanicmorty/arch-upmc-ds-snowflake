CREATE OR REPLACE VIEW CMS.MONTHLY_NORX_DETAIL_VW AS
SELECT
    SUBSTRING(RECORD, 1, 3)     AS RECORD_TYPE,
    SUBSTRING(RECORD, 4, 5)     AS FILLER_1,
    SUBSTRING(RECORD, 9, 12)    AS HICN_OR_RRB,
    SUBSTRING(RECORD, 21, 9)    AS SSN,
    SUBSTRING(RECORD, 30, 11)   AS MBI,
    SUBSTRING(RECORD, 41, 49)   AS FILLER_2,
    SUBSTRING(RECORD, 90, 5)    AS CONTRACT_NUMBER,
    SUBSTRING(RECORD, 95, 3)    AS PBP,
    SUBSTRING(RECORD, 98, 71)   AS FILLER_3,
    SUBSTRING(RECORD, 169, 8)   AS FILE_CREATION_DATE,
    SUBSTRING(RECORD, 177, 574) AS FILLER_4,
	FILENAME,
	FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.MONTHLY_NORX
WHERE SUBSTRING(RECORD, 1, 3) = 'NRX';