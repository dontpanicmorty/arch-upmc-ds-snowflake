CREATE OR REPLACE VIEW CMS.MAO_001_DETAIL_VW (
    FILENAME,   
    FILE_TYPE,
    ROW_NUMBER,
    RECORD_TYPE,
    REPORT_ID, 
    MEDICARE_ADVANTAGE,
    PLAN_ENCOUNTER_ID,
    ENCOUNTER_ICN,
    ENCOUNTER_LINE_NUMBER,
    DUPLICATE_PLAN_ENCOUNTER_ID,
    DUPLICATE_ENCOUNTER_ICN,
    DUPLICATE_ENCOUNTER_LINE_NUMBER,
    MEDICARE_BENEFICIARY_IDENTIFIERM,
    DATE_OF_SERVICE,
    ERROR_CODE
)as
SELECT 
    FILENAME,
    FILE_TYPE,
    ROW_NUMBER,
    RECORD_TYPE,
    SUBSTR(RECORD, 3, 7) as REPORT_ID,
    SUBSTR(RECORD, 11, 5)AS MEDICARE_ADVANTAGE,
    SUBSTR(RECORD, 17, 20) AS PLAN_ENCOUNTER_ID,
    SUBSTR(RECORD, 38, 19)AS ENCOUNTER_ICN,
    SUBSTR(RECORD, 58, 3)AS ENCOUNTER_LINE_NUMBER,
    SUBSTR(RECORD, 62, 20)AS DUPLICATE_PLAN_ENCOUNTER_ID,
    SUBSTR(RECORD, 83, 19)AS DUPLICATE_ENCOUNTER_ICN,
    SUBSTR(RECORD, 103, 3)AS DUPLICATE_ENCOUNTER_LINE_NUMBER,
    SUBSTR(RECORD, 107, 12)AS MEDICARE_BENEFICIARY_IDENTIFIER,
    SUBSTR(RECORD, 120, 8)AS DATE_OF_SERVICE,
    SUBSTR(RECORD, 129, 5)AS ERROR_CODE
from CMS.RESPONSE_MAO_001_STAGE
WHERE RECORD_TYPE = '1'
;