CREATE OR REPLACE VIEW CMS.MONTHLY_PREMIUM_WITHHOLDING_REPORT_DETAIL_VW AS
SELECT
    SUBSTRING(RECORD,  1,  2) AS RECORD_TYPE,
    SUBSTRING(RECORD,  3,  5) AS MCO_CONTRACT_NUMBER,
    SUBSTRING(RECORD,  8,  3) AS PLAN_BENEFIT_PACKAGE_ID,
    SUBSTRING(RECORD, 11,  3) AS PLAN_SEGMENT_ID,
    SUBSTRING(RECORD, 14, 12) AS BENEFICIARY_ID,
    SUBSTRING(RECORD, 26,  7) AS SURNAME,
    SUBSTRING(RECORD, 33,  1) AS FIRST_INITIAL,
    SUBSTRING(RECORD, 34,  1) AS SEX,
    SUBSTRING(RECORD, 35,  8) AS DATE_OF_BIRTH,
    SUBSTRING(RECORD, 43,  3) AS PPO,
    SUBSTRING(RECORD, 46,  1) AS FILLER_1,
    SUBSTRING(RECORD, 47,  8) AS PREMIUM_PERIOD_START_DATE,
    SUBSTRING(RECORD, 55,  8) AS PREMIUM_PERIOD_END_DATE,
    SUBSTRING(RECORD, 63,  2) AS NUMBER_OF_MONTHS_IN_PREMIUM_PERIOD,
    SUBSTRING(RECORD, 65,  8) AS PART_C_PREMIUMS_COLLECTED,
    SUBSTRING(RECORD, 73,  8) AS PART_D_PREMIUMS_COLLECTED,
    SUBSTRING(RECORD, 81,  8) AS PART_D_LATE_ENROLLMENT_PENALTIES_COLLECTED,
    SUBSTRING(RECORD, 89, 10) AS CLEANUP_ID,
    SUBSTRING(RECORD, 99, 67) AS FILLER_2,
    FILENAME,
	FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.MONTHLY_PREMIUM_WITHHOLDING_REPORT
WHERE TRIM(SUBSTRING(RECORD,  1,  2)) = 'D';