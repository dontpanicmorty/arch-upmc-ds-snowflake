CREATE OR REPLACE VIEW CMS.LIS_HISTORY_DETAIL_VW AS
SELECT
    SUBSTRING(RECORD, 1,   1)  AS RECORD_TYPE,
    SUBSTRING(RECORD, 2,   5)  AS MCO_CONTRACT_NUMBER,
    SUBSTRING(RECORD, 7,   3)  AS PBP_NUMBER,
    SUBSTRING(RECORD, 10, 12)  AS BENEFICIARY_ID,
    SUBSTRING(RECORD, 22, 12)  AS SURNAME,
    SUBSTRING(RECORD, 34,  7)  AS FIRST_NAME,
    SUBSTRING(RECORD, 41,  1)  AS MIDDLE_INITIAL,
    SUBSTRING(RECORD, 42,  1)  AS SEX,
    SUBSTRING(RECORD, 43,  8)  AS DATE_OF_BIRTH,
    SUBSTRING(RECORD, 51,  8)  AS LOW_INCOME_PERIOD_START_DATE,
    SUBSTRING(RECORD, 59,  8)  AS LOW_INCOME_PERIOD_END_DATE,
    SUBSTRING(RECORD, 67,  3)  AS LIPS_PERCENTAGE,
    SUBSTRING(RECORD, 70,  8)  AS PREMIUM_LIS_AMOUNT,
    SUBSTRING(RECORD, 78,  1)  AS LOW_INCOME_CO_PAY_LEVEL_ID,
    SUBSTRING(RECORD, 79,  1)  AS BENEFICIARY_SOURCE_OF_SUBSIDY_CODE,
    SUBSTRING(RECORD, 80,  1)  AS LIS_ACTIVITY_FLAG,
    SUBSTRING(RECORD, 81,  8)  AS PBP_START_DATE,
    SUBSTRING(RECORD, 89,  8)  AS NET_PART_D_PREMIUM_AMOUNT,
    SUBSTRING(RECORD, 97,  4)  AS CONTRACT_YEAR,
    SUBSTRING(RECORD, 101, 1)  AS INSTITUTIONAL_STATUS_INDICATOR,
    SUBSTRING(RECORD, 102, 8)  AS PBP_ENROLLMENT_TERMINATION_DATE,
    SUBSTRING(RECORD, 110, 56) AS FILLER,
	FILENAME,
	FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.LIS_HISTORY
 WHERE SUBSTRING(RECORD, 1, 1) = 'D';