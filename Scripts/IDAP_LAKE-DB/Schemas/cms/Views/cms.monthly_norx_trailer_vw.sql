CREATE OR REPLACE VIEW CMS.MONTHLY_NORX_TRAILER_VW AS
SELECT
    SUBSTRING(RECORD, 1, 8)    AS FILE_ID_NAME,
    SUBSTRING(RECORD, 9, 8)    AS SENDING_ENTITY,
    SUBSTRING(RECORD, 17, 8)   AS FILE_CREATION_DATE,
    SUBSTRING(RECORD, 25, 9)   AS FILLER_1,
    SUBSTRING(RECORD, 34, 7)   AS FILE_RECORD_COUNT,
    SUBSTRING(RECORD, 41, 710) AS FILLER_2,
	FILENAME,
	FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.MONTHLY_NORX
WHERE SUBSTRING(RECORD, 1, 8) = 'CMSNRX0T';