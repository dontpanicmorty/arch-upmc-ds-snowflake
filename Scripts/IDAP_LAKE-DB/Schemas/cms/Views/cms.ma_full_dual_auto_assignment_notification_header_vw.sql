CREATE OR REPLACE VIEW CMS.MA_FULL_DUAL_AUTO_ASSIGNMENT_NOTIFICATION_HEADER_VW AS
SELECT
    SUBSTRING(RECORD, 1, 8)    AS FILE_ID_NAME,
    SUBSTRING(RECORD, 9, 8)    AS SENDING_ENTITY,
    SUBSTRING(RECORD, 17, 8)   AS FILE_CREATION_DATE,
    SUBSTRING(RECORD, 25, 9)   AS FILE_CONTROL_NUMBER,
    SUBSTRING(RECORD, 34, 67)  AS FILLER,
	FILENAME,
	FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.MA_FULL_DUAL_AUTO_ASSIGNMENT_NOTIFICATION
WHERE SUBSTRING(RECORD, 1, 8) = 'MMAADUAH';