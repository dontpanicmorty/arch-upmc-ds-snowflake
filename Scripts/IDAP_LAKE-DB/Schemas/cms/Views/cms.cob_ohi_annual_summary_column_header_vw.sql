CREATE OR REPLACE VIEW CMS.COB_OHI_ANNUAL_SUMMARY_COLUMN_HEADER_VW AS
SELECT
  SUBSTRING(RECORD, 1, 11)  AS CONTRACT_ID_COLUMN_HEADING,
  SUBSTRING(RECORD, 12, 5)  AS FILLER_1,
  SUBSTRING(RECORD, 17, 9)  AS FILE_NAME_COLUMN_HEADING,
  SUBSTRING(RECORD, 26, 40) AS FILLER_2,
  SUBSTRING(RECORD, 66, 10) AS FILE_COUNT_COLUMN_HEADING,
  SUBSTRING(RECORD, 76, 5)  AS FILLER_3,
  FILENAME                  AS FILE_NAME,
  FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.COB_OHI_ANNUAL_SUMMARY
WHERE SUBSTRING(RECORD, 1, 11) = 'Contract ID';