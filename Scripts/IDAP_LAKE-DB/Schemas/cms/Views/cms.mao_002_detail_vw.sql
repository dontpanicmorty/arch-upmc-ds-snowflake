CREATE OR REPLACE VIEW CMS.MAO_002_DETAIL_VW (
    FILENAME,
    FILE_TYPE,
    ROW_NUMBER,
    RECORD_TYPE,
    REPORT_ID,
    MEDICARE_ADVANTAGE_CONTRACT_ID,
    PLAN_ENCOUNTER_ID,
    ENCOUNTER_ICN,
    ENCOUNTER_LINE_NUMBER,
    ENCOUNTER_STATUS,
    ERROR_CODE,
    ERROR_DESCRIPTION
) AS
SELECT
    FILENAME,
    FILE_TYPE,
    ROW_NUMBER,
    RECORD_TYPE,
    SUBSTR(RECORD, 3, 7) as REPORT_ID,
    SUBSTR(RECORD, 11, 5) as MEDICARE_ADVANTAGE_CONTRACT_ID,
    SUBSTR(RECORD, 17, 38) as PLAN_ENCOUNTER_ID,
    SUBSTR(RECORD, 56, 13) as ENCOUNTER_ICN,
    SUBSTR(RECORD, 101, 3) as ENCOUNTER_LINE_NUMBER,
    SUBSTR(RECORD, 105, 8) as ENCOUNTER_STATUS,
    SUBSTR(RECORD, 114, 5) as ERROR_CODE,
    SUBSTR(RECORD, 120, 40) as ERROR_DESCRIPTION
FROM CMS.RESPONSE_MAO_002_STAGE
WHERE RECORD_TYPE = '1'
;