CREATE OR REPLACE VIEW CMS.MAO_001_TRAILER_VW (
    FILENAME,
    FILE_TYPE,
    ROW_NUMBER,
    RECORD_TYPE,
    REPORT_ID,
    DUPLICATE_ENCOUNTER_LINES_REJECTED,
    ENCOUNTER_LINES_SUBMITTED,
    ENCOUNTER_RECORDS_SUBMITTED
)as
SELECT 
    FILENAME,
    FILE_TYPE,
    ROW_NUMBER,
    RECORD_TYPE,
    SUBSTR(RECORD, 3, 7) as REPORT_ID,
    SUBSTR(RECORD, 11, 8)AS DUPLICATE_ENCOUNTER_LINES_REJECTED,
    SUBSTR(RECORD, 20, 8) AS ENCOUNTER_LINES_SUBMITTED,
    SUBSTR(RECORD, 29, 8)AS ENCOUNTER_RECORDS_SUBMITTED
FROM CMS.RESPONSE_MAO_001_STAGE
WHERE RECORD_TYPE = '9'