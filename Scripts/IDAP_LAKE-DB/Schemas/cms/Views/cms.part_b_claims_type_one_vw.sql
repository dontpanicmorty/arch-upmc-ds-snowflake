CREATE OR REPLACE VIEW CMS.PART_B_CLAIMS_TYPE_ONE_VW AS
SELECT
  SUBSTRING(RECORD, 1,   5)  AS CONTRACT_NUMBER,
  SUBSTRING(RECORD, 6,   1)  AS RECORD_TYPE,
  SUBSTRING(RECORD, 7,  12)  AS BENEFICIARY_ID,
  SUBSTRING(RECORD, 19,  8)  AS PERIOD_FROM_DATE,
  SUBSTRING(RECORD, 27,  8)  AS PERIOD_TO_DATE,
  SUBSTRING(RECORD, 35,  8)  AS DATE_OF_BIRTH,
  SUBSTRING(RECORD, 43,  6)  AS SURNAME_6,
  SUBSTRING(RECORD, 49,  1)  AS FIRST_INITIAL,
  SUBSTRING(RECORD, 50,  1)  AS MIDDLE_INITIAL,
  SUBSTRING(RECORD, 51, 11)  AS REIMBURSEMENT_AMOUNT,
  SUBSTRING(RECORD, 62, 11)  AS TOTAL_ALLOWED_CHARGES,
  SUBSTRING(RECORD, 73,  6)  AS REPORT_DATE,
  SUBSTRING(RECORD, 79,  5)  AS CONTRACTOR_ID,
  SUBSTRING(RECORD, 84, 10)  AS PROVIDER_ID,
  SUBSTRING(RECORD, 94, 15)  AS INTERNAL_CONTROL_NUMBER,
  SUBSTRING(RECORD, 109, 11) AS PROVIDER_PAYMENT_AMOUNT,
  SUBSTRING(RECORD, 120, 11) AS BENEFICIARY_PAYMENT_AMOUNT,
  SUBSTRING(RECORD, 131, 57) AS FILLER,
  FILENAME,
  FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
  FROM CMS.PART_B_CLAIMS
  WHERE SUBSTRING(RECORD, 6,   1) IN ('6', '7');