CREATE OR REPLACE VIEW CMS.PARTD_EXCLUSION_WARNING_PEXCT_CURRENT_VW AS
SELECT
    FILENAME                                                            AS FILENAME,
    FILE_LAST_MODIFIED_DATETIME                                         AS INSERT_DATETIME,
    SUBSTR(RECORD,1,5)                                                  AS RECORD_ID,
    TRY_TO_NUMBER(SUBSTR(RECORD,6,7))                                   AS SEQUENCE_NUMBER,
    TRY_TO_DATE(NULLIF(TRIM(SUBSTR(RECORD, 13, 8)),''),'YYYYMMDD')      AS DDPS_SYSTEM_DATE,
    SUBSTR(RECORD,21,6)                                                 AS DDPS_SYSTEM_TIME,
    SUBSTR(RECORD,27,5)                                                 AS FILE_ID,
    SUBSTR(RECORD,32,5)                                                 AS CONTRACT_ID,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,37,14)) AS NUMBER(14,2))       AS TOTAL_LICS_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,51,14)) AS NUMBER(14,2))       AS TOTAL_GDCB_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,65,14)) AS NUMBER(14,2))       AS TOTAL_GDCA_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,79,14)) AS NUMBER(14,2))       AS TOTAL_CPP_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,93,14)) AS NUMBER(14,2))       AS TOTAL_EST_REMUN_AT_POS_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,107,14)) AS NUMBER(14,2))      AS TOTAL_NPP_AMT,
    TRY_TO_NUMBER(SUBSTR(RECORD,121,7))                                 AS TOTAL_PBP_COUNT,
    TRY_TO_NUMBER(SUBSTR(RECORD,128,9))                                 AS TOTAL_PDE_COUNT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,137,14)) AS NUMBER(14,2))      AS TOTAL_GAP_DISC_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,151,14)) AS NUMBER(14,2))      AS TOTAL_MANUFAC_DISC_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,165,14)) AS NUMBER(14,2))      AS TOTAL_SELEC_DRUG_SUB_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,179,14)) AS NUMBER(14,2))      AS TOTAL_PHARM_PRICE_CONCESS_AT_POS  
FROM CMS.PARTD_EXCLUSION_WARNING_STAGE
WHERE SUBSTR(RECORD,1,5) = 'PEXCT';