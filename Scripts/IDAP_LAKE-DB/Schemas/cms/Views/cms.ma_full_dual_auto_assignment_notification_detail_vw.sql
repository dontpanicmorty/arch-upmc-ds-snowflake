CREATE OR REPLACE VIEW CMS.MA_FULL_DUAL_AUTO_ASSIGNMENT_NOTIFICATION_DETAIL_VW AS
SELECT
    SUBSTRING(RECORD, 1, 5)    AS CONTRACT_NUMBER,
    SUBSTRING(RECORD, 6, 8)    AS RUN_DATE,
    SUBSTRING(RECORD, 14, 6)   AS FILLER_1,
    SUBSTRING(RECORD, 20, 12)  AS BENEFICIARY_ID,
    SUBSTRING(RECORD, 32, 12)  AS SURNAME,
    SUBSTRING(RECORD, 44, 1)   AS FIRST_INITIAL,
    SUBSTRING(RECORD, 45, 1)   AS SEX_CODE,
    SUBSTRING(RECORD, 46, 8)   AS DATE_OF_BIRTH,
    SUBSTRING(RECORD, 54, 11)  AS MBI,
    SUBSTRING(RECORD, 65, 36)  AS FILLER_2,
	FILENAME,
	FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.MA_FULL_DUAL_AUTO_ASSIGNMENT_NOTIFICATION
WHERE SUBSTRING(RECORD, 1, 8) NOT IN ('MMAADUAH', 'MMAADUAT');