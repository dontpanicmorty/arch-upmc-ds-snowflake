CREATE OR REPLACE VIEW CMS.MAO_004_HEADER_VW
AS
SELECT
    RESPONSE_MAO_004_STAGE.FILENAME
    ,RESPONSE_MAO_004_STAGE.FILE_TYPE
    ,RESPONSE_MAO_004_STAGE.ROW_NUMBER
    ,RESPONSE_MAO_004_STAGE.REPORT_TYPE
    ,RESPONSE_MAO_004_STAGE.RECORD_TYPE as RECORD_TYPE_CODE
    
    ,SUBSTR(RESPONSE_MAO_004_STAGE.RECORD,3,7) AS REPORT_ID
    ,SUBSTR(RESPONSE_MAO_004_STAGE.RECORD,11,5) AS MEDICARE_ADVANTAGE_CONTRACT_ID
    ,SUBSTR(RESPONSE_MAO_004_STAGE.RECORD,17,8) AS REPORT_DATE
    ,SUBSTR(RESPONSE_MAO_004_STAGE.RECORD,26,53) AS REPORT_DESCRIPTION
    ,SUBSTR(RESPONSE_MAO_004_STAGE.RECORD,111,4) AS SUBMISSION_FILE_TYPE
    ,SUBSTR(RESPONSE_MAO_004_STAGE.RECORD,116,1) AS PHASE
    ,SUBSTR(RESPONSE_MAO_004_STAGE.RECORD,118,1) AS VERSION

    ,RESPONSE_MAO_004_STAGE.FILE_PREFIX
    ,RESPONSE_MAO_004_STAGE.FILE_DATE
    ,RESPONSE_MAO_004_STAGE.FILE_TIME
    ,RESPONSE_MAO_004_STAGE.FILE_LAST_MODIFIED_DATETIME
    ,RESPONSE_MAO_004_STAGE.LAST_UPDATED_DATETIME
    ,RESPONSE_MAO_004_STAGE.RECORD AS RAW_RECORD_TEXT
FROM
    CMS.RESPONSE_MAO_004_STAGE RESPONSE_MAO_004_STAGE
WHERE
    RECORD_TYPE = '0'
;