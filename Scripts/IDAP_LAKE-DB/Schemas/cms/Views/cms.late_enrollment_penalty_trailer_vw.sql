CREATE OR REPLACE VIEW CMS.LATE_ENROLLMENT_PENALTY_TRAILER_VW AS
SELECT
    SUBSTRING(RECORD,  1,  3) AS RECORD_TYPE,
    SUBSTRING(RECORD,  4,  4) AS CONTRACT_NUMBER,
    SUBSTRING(RECORD,  9,  3) AS PBP_NUMBER,
    SUBSTRING(RECORD,  12,  3) AS SEGMENT_NUMBER,
    SUBSTRING(RECORD,  15,  14) AS TOTAL_LEP_AMOUNT,
    SUBSTRING(RECORD,  29,  14) AS RECORD_COUNT,
    SUBSTRING(RECORD,  43,  123) AS FILLER,
	FILENAME,
	FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.LATE_ENROLLMENT_PENALTY
WHERE TRIM(SUBSTRING(RECORD,  1,  3)) NOT IN ('PD', 'AD', 'HD', 'H');