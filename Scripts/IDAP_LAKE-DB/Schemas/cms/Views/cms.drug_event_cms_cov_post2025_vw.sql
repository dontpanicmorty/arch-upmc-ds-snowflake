    TRY_TO_NUMBER(SUBSTR(RECORD, 334, 12))                                          AS NET_NUM_NON_CAT_PDES,
    TRY_TO_NUMBER(SUBSTR(RECORD, 346, 12))                                          AS NET_NUM_NON_STAND_FORMAT_PDES,
    TRY_TO_NUMBER(SUBSTR(RECORD, 358, 12))                                          AS NET_NUM_OON_PDES,
    NULLIF(TRIM(SUBSTR(RECORD, 424, 144)),'')                                       AS FILLER,
    FILE_LAST_MODIFIED_DATETIME                                                     AS INSERT_DATETIME,
    FILENAME                                                                        AS FILENAME,
    CMS.FXN_OVERPUNCH(TRIM(SUBSTR(RECORD, 370, 14)))                                AS NET_EST_REMUN_POST_AMT,
    CMS.FXN_OVERPUNCH(TRIM(SUBSTR(RECORD, 384, 14)))                                AS NET_VAC_ADMIN_FEE,
    CMS.FXN_OVERPUNCH(TRIM(SUBSTR(RECORD, 398, 14)))                                AS NET_RPT_GAP_DISC,
    TRY_TO_NUMBER(SUBSTR(RECORD, 412, 12))                                          AS NET_NUMBER_RPT_GAP_DISC_PDES
FROM CMS.DRUG_EVENT_DDPS_COV_STAGE
