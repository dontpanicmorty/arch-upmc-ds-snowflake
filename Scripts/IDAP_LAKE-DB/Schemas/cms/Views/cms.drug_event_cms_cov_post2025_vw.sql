    TRY_TO_NUMBER(SUBSTR(RECORD, 286, 12))                                          AS NUM_ADJUSTED_PDES,
    TRY_TO_NUMBER(SUBSTR(RECORD, 298, 12))                                          AS NUM_DELETION_PDES,
