    CMS.FXN_OVERPUNCH(TRIM(SUBSTR(RECORD, 106, 14)))                                AS NET_DISPENSE_FEE,
    CMS.FXN_OVERPUNCH(TRIM(SUBSTR(RECORD, 120, 14)))                                AS NET_SALES_TAX,
    CMS.FXN_OVERPUNCH(TRIM(SUBSTR(RECORD, 134, 14)))                                AS NET_GDCB,
    CMS.FXN_OVERPUNCH(TRIM(SUBSTR(RECORD, 148, 14)))                                AS NET_GDCA,
    CMS.FXN_OVERPUNCH(TRIM(SUBSTR(RECORD, 162, 14)))                                AS NET_TOTAL_GROSS_DRUG_COST,
    CMS.FXN_OVERPUNCH(TRIM(SUBSTR(RECORD, 176, 14)))                                AS NET_PATIENT_PAY_AMOUNT,
    CMS.FXN_OVERPUNCH(TRIM(SUBSTR(RECORD, 190, 14)))                                AS NET_OTHER_TROOP_AMOUNT,
    CMS.FXN_OVERPUNCH(TRIM(SUBSTR(RECORD, 204, 14)))                                AS NET_LICS_AMOUNT,
    CMS.FXN_OVERPUNCH(TRIM(SUBSTR(RECORD, 218, 14)))                                AS NET_TROOP_AMOUNT,
