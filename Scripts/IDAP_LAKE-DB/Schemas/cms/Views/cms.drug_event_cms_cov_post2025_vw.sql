    TRIM(SUBSTR(RECORD, 32, 20))                                                    AS LAST_SUBMITTED_HICN,
    TRIM(SUBSTR(RECORD, 52, 20))                                                    AS LAST_SUBMITTED_CARDHOLDER_ID,
