CREATE OR REPLACE VIEW CMS.MEDICARE_ADVANTAGE_MEDICAID_STATUS_HEADER_VW AS
SELECT
    SUBSTRING(RECORD,  1,  1) AS RECORD_TYPE,              
    SUBSTRING(RECORD,  2,  5) AS CONTRACT_NUMBER,          
    SUBSTRING(RECORD,  7,  4) AS START_YEAR,               
    SUBSTRING(RECORD, 11,  4) AS END_YEAR,                 
    SUBSTRING(RECORD, 15,  8) AS FILE_GENERATION_DATE,     
    SUBSTRING(RECORD, 23, 53) AS FILLER,
    FILENAME,
	FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.MEDICARE_ADVANTAGE_MEDICAID_STATUS
WHERE SUBSTRING(RECORD,  1,  1) = '1';