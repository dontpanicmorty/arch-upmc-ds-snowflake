CREATE OR REPLACE VIEW CMS.MONTHLY_MEDICARE_SECONDARY_PAYER_PART_C_HEADER_VW AS
SELECT
    SUBSTRING(RECORD,  1,   8) AS HEADER_CODE,
    SUBSTRING(RECORD,  9,   4) AS SENDING_ENTITY,
    SUBSTRING(RECORD, 13,   8) AS FILE_CREATION_DATE,
    SUBSTRING(RECORD, 21, 680) AS FILLER,
    FILENAME,
    FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.MONTHLY_MEDICARE_SECONDARY_PAYER_PART_C
WHERE SUBSTRING(RECORD,  1,   8) = 'CMSMSPDH';