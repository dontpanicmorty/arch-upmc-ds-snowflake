CREATE OR REPLACE VIEW CMS.COB_OHI_ANNUAL_SUMMARY_TOTAL_VW AS
SELECT
  SUBSTRING(RECORD, 1, 5)   AS CONTRACT_ID,
  SUBSTRING(RECORD, 6, 11)  AS FILLER_1,
  SUBSTRING(RECORD, 17, 16) AS TOTAL_FILE_COUNT_LABEL,
  SUBSTRING(RECORD, 33, 33) AS FILLER_2,
  SUBSTRING(RECORD, 66, 5)  AS FILE_COUNT,
  SUBSTRING(RECORD, 71, 10) AS FILLER_3,
  FILENAME                  AS FILE_NAME,
  FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.COB_OHI_ANNUAL_SUMMARY
WHERE SUBSTRING(RECORD, 17, 16) = 'TOTAL FILE COUNT';