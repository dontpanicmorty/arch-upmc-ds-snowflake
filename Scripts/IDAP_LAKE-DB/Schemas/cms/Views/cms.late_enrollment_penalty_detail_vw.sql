CREATE OR REPLACE VIEW CMS.LATE_ENROLLMENT_PENALTY_DETAIL_VW AS
SELECT
    SUBSTRING(RECORD,  1,  3) AS RECORD_TYPE,
    SUBSTRING(RECORD,  4,  5) AS CONTRACT_NUMBER,
    SUBSTRING(RECORD,  9,  3) AS PBP_NUMBER,
    SUBSTRING(RECORD, 12,  3) AS PLAN_SEGMENT_NUMBER,
    SUBSTRING(RECORD, 15, 12) AS BENEFICIARY_ID,
    SUBSTRING(RECORD, 27,  7) AS SURNAME,
    SUBSTRING(RECORD, 34,  1) AS FIRST_INITIAL,
    SUBSTRING(RECORD, 35,  1) AS SEX,
    SUBSTRING(RECORD, 36,  8) AS DOB,
    SUBSTRING(RECORD, 44,  1) AS FILLER_1,
    SUBSTRING(RECORD, 45,  8) AS PREMIUM_ADJUSTMENT_HARM_PERIOD_START_DATE,
    SUBSTRING(RECORD, 53,  8) AS PREMIUM_ADJUSTMENT_HARM_PERIOD_END_DATE,
    SUBSTRING(RECORD, 61,  2) AS NUMBER_OF_MONTHS_IN_PREMIUM_ADJUSTMENT_PERIOD,
    SUBSTRING(RECORD, 63,  2) AS NUMBER_OF_MONTHS_UNCOVERED,
    SUBSTRING(RECORD, 66,  8) AS LEP_AMOUNT_FOR_DIRECT_BILLED_MEMBERS,
    SUBSTRING(RECORD, 74, 10) AS CLEANUP_ID,
    SUBSTRING(RECORD, 84, 82) AS FILLER_2,
	FILENAME,
	FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.LATE_ENROLLMENT_PENALTY
WHERE TRIM(SUBSTRING(RECORD,  1,  3)) IN ('PD', 'AD', 'HD');