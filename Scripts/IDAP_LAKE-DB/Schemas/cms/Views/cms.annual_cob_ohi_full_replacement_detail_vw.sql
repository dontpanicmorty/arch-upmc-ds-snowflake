CREATE OR REPLACE VIEW CMS.ANNUAL_COB_OHI_FULL_REPLACEMENT_DETAIL_VW AS
SELECT
  SUBSTRING(RECORD, 1, 3)   AS RECORD_TYPE,
  SUBSTRING(RECORD, 4, 12)  AS BENEFICIARY_ID,
  SUBSTRING(RECORD, 16, 9)  AS SSN,
  SUBSTRING(RECORD, 25, 8)  AS DOB,
  SUBSTRING(RECORD, 33, 1)  AS SEX_CODE,
  SUBSTRING(RECORD, 34, 5)  AS CONTRACT_NUMBER,
  SUBSTRING(RECORD, 39, 3)  AS PBP_NUMBER,
  SUBSTRING(RECORD, 42, 1)  AS ACTION_TYPE,
  SUBSTRING(RECORD, 43, 20) AS PART_D_RX_ID,
  SUBSTRING(RECORD, 63, 15) AS PART_D_RX_GROUP,
  SUBSTRING(RECORD, 78, 6)  AS PART_D_RX_BIN,
  SUBSTRING(RECORD, 84, 10) AS PART_D_RX_PCN,
  SUBSTRING(RECORD, 94, 8)  AS PART_D_EFFECTIVE_DATE,
  SUBSTRING(RECORD, 102, 8) AS PART_D_TERMINATION_DATE,
  SUBSTRING(RECORD, 110, 991) AS DATE_TIMESTAMP,
  FILENAME,
  FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE,
FROM CMS.ANNUAL_COB_OHI_FULL_REPLACEMENT
WHERE SUBSTRING(RECORD, 1, 3) = 'DTL';