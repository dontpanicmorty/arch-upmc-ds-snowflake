CREATE OR REPLACE VIEW CMS.MAO_002_TRAILER_VW (
    FILENAME,
    FILE_TYPE,
    ROW_NUMBER,
    RECORD_TYPE,
    REPORT_ID,
    TOTAL_PROCESSING_ERRORS,
    TOTAL_LINES_ACCEPTED,
    TOTAL_LINES_REJECTED,
    TOTAL_LINES_SUBMITTED,
    TOTAL_RECORDS_ACCEPTED,
    TOTAL_RECORDS_REJECTED,
    TOTAL_RECORDS_SUBMITTED
) AS    
SELECT
    FILENAME,
    FILE_TYPE,
    ROW_NUMBER,
    RECORD_TYPE,
    SUBSTR(RECORD, 3, 7) as REPORT_ID,
    SUBSTR(RECORD, 11, 8) as TOTAL_PROCESSING_ERRORS,
    SUBSTR(RECORD, 20, 8) as TOTAL_LINES_ACCEPTED,
    SUBSTR(RECORD, 29, 8) as TOTAL_LINES_REJECTED,
    SUBSTR(RECORD, 38, 8) as TOTAL_LINES_SUBMITTED,
    SUBSTR(RECORD, 47, 8) as TOTAL_RECORDS_ACCEPTED,
    SUBSTR(RECORD, 56, 8) as TOTAL_RECORDS_REJECTED,
    SUBSTR(RECORD, 65, 8) as TOTAL_RECORDS_SUBMITTED,
FROM CMS.RESPONSE_MAO_002_STAGE
WHERE RECORD_TYPE = '9'
;