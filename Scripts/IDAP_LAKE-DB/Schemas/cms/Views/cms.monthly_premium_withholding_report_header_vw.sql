CREATE OR REPLACE VIEW CMS.MONTHLY_PREMIUM_WITHHOLDING_REPORT_HEADER_VW AS
SELECT
    SUBSTRING(RECORD,  1,  2) AS RECORD_TYPE,
    SUBSTRING(RECORD,  3,  5) AS MCO_CONTRACT_NUMBER,
    SUBSTRING(RECORD,  8,  8) AS PAYMENT_DATE,
    SUBSTRING(RECORD, 16,  8) AS REPORT_DATE,
    SUBSTRING(RECORD, 24, 142) AS FILLER,
    FILENAME,
	FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.MONTHLY_PREMIUM_WITHHOLDING_REPORT
WHERE TRIM(SUBSTRING(RECORD,  1,  2)) = 'H';