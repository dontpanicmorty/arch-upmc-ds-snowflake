CREATE OR REPLACE VIEW CMS.BATCH_COMPLETION_STATUS_SUMMARY_FAILED_DETAIL_VW AS
SELECT
    SUBSTRING(RECORD, 1, 2) AS RECORD_TYPE_IDENTIFIER,
    SUBSTRING(RECORD, 3, 1) AS FILLER_1,
    SUBSTRING(RECORD, 4, 600) AS FAILED_INPUT_TRANSACTION_RECORD_TEXT,
    SUBSTRING(RECORD, 604, 5) AS FILLER_2,
    SUBSTRING(RECORD, 609, 3) AS FIRST_TRC,
    SUBSTRING(RECORD, 612, 3) AS SECOND_TRC,
    SUBSTRING(RECORD, 615, 3) AS THIRD_TRC,
    SUBSTRING(RECORD, 618, 3) AS FOURTH_TRC,
    SUBSTRING(RECORD, 621, 3) AS FIFTH_TRC,
    FILENAME,
    FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.BATCH_COMPLETION_STATUS_SUMMARY
WHERE TRIM(SUBSTRING(RECORD, 1, 2)) IN ('F');