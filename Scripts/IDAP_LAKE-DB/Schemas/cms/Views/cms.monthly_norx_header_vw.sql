CREATE OR REPLACE VIEW CMS.MONTHLY_NORX_HEADER_VW AS
SELECT
    SUBSTRING(RECORD, 1, 8)    AS FILE_ID_NAME,
    SUBSTRING(RECORD, 9, 8)    AS SENDING_ENTITY,
    SUBSTRING(RECORD, 17, 8)   AS FILE_CREATION_DATE,
	SUBSTRING(RECORD, 25, 9)   AS FILE_CONTROL_NUMBER,
    SUBSTRING(RECORD, 34, 717) AS FILLER,
	FILENAME,
	FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.MONTHLY_NORX
WHERE SUBSTRING(RECORD, 1, 8) = 'CMSNRX0H';