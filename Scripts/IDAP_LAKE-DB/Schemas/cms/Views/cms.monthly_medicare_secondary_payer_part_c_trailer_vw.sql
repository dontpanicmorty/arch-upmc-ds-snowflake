CREATE OR REPLACE VIEW CMS.MONTHLY_MEDICARE_SECONDARY_PAYER_PART_C_TRAILER_VW AS
SELECT
    SUBSTRING(RECORD,   1,  8) AS TRAILER_CODE,
    SUBSTRING(RECORD,   9,  4) AS SENDING_ENTITY,
    SUBSTRING(RECORD,  13,  8) AS FILE_CREATION_DATE,
    SUBSTRING(RECORD,  21,  8) AS TOTAL_PRM_COUNT,
    SUBSTRING(RECORD,  29,  8) AS TOTAL_RECORDS_COUNT,
    SUBSTRING(RECORD,  37, 664) AS FILLER,
    FILENAME,
    FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.MONTHLY_MEDICARE_SECONDARY_PAYER_PART_C
WHERE SUBSTRING(RECORD,   1,  8) = 'CMSMSPDT';