CREATE OR REPLACE VIEW CMS.MOR_RXHCC_TRAILER_VW AS
SELECT
    S.FILENAME,
    S.FILE_TYPE,
    S.ROW_NUMBER,
    T.RECORD_TYPE_CODE,     
    T.RECORD_TYPE_DESC,

    /* Trailer fields per Part D layout (PY2017–PY2026) */
    SUBSTR(S.RECORD,  2, 5) AS CONTRACT_NUMBER,      -- pos 2-6
    SUBSTR(S.RECORD,  7, 9) AS TOTAL_RECORD_COUNT,   -- pos 7-15 (inclusive of header + trailer)

    /* Standard file metadata (match your existing views) */
    S.FILE_PREFIX,
    S.FILE_DATE,
    S.FILE_TIME,
    S.FILE_LAST_MODIFIED_DATETIME,
    S.LAST_UPDATED_DATETIME,
    S.RECORD AS RAW_RECORD_TEXT
FROM
    CMS.RESPONSE_MOR_STAGE S
    INNER JOIN CMS.RESPONSE_MOR_TYPES T
        ON T.RECORD_TYPE_CODE = S.RECORD_TYPE
       AND T.FILE_TYPE        = S.FILE_TYPE
WHERE
      T.REPORT_SEGMENT_VIEW_NAME = 'MOR_RXHCC_TRAILER_VW'
  AND S.FILE_TYPE   = 'PTDMODD'   -- Part D MOR data file
  AND S.RECORD_TYPE = '3';        -- Trailer