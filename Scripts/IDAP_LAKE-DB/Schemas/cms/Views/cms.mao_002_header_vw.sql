CREATE OR REPLACE VIEW CMS.MAO_002_HEADER_VW(
    FILENAME,
    FILE_TYPE,
    ROW_NUMBER,
    RECORD_TYPE,
    REPORT_ID,
    REPORT_DATE,
    TRANSACTION_DATE,
    REPORT_DESCRIPTION,
    SUBMISSION_INTERCHANGE_NUMBER,
    RECORD_TYPE_CODE,
    SUBMISSION_FILE_TYPE
) as
SELECT 
    FILENAME, 
    FILE_TYPE,
    ROW_NUMBER,
    RECORD_TYPE,
    SUBSTR(RECORD, 3, 7) as REPORT_ID,
    SUBSTR(RECORD, 11, 8) as REPORT_DATE,
    SUBSTR(RECORD, 20, 8) as TRANSACTION_DATE,
    SUBSTR(RECORD, 29, 39) as REPORT_DESCRIPTION,
    SUBSTR(RECORD, 75, 30) as SUBMISSION_INTERCHANGE_NUMBER,
    SUBSTR(RECORD, 106, 3) as RECORD_TYPE_CODE,
    SUBSTR(RECORD, 110, 3) as SUBMISSION_FILE_TYPE
FROM CMS.RESPONSE_MAO_002_STAGE
WHERE RECORD_TYPE = '0'
;