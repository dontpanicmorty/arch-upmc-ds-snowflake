CREATE OR REPLACE VIEW CMS.PARTD_EXCLUSION_WARNING_PEXDT_CURRENT_VW AS
SELECT
    FILENAME                                                            AS FILENAME,
    FILE_LAST_MODIFIED_DATETIME                                         AS INSERT_DATETIME,
    SUBSTR(RECORD,1,5)                                                  AS RECORD_ID,
    TRY_TO_NUMBER(SUBSTR(RECORD,6,7))                                   AS SEQUENCE_NUMBER,
    TRIM(SUBSTR(RECORD,13,20))                                          AS CURRENT_CMS_HICN,
    TRIM(SUBSTR(RECORD,33,20))                                          AS CARD_HOLDER_ID,
    SUBSTR(RECORD,53,40)                                                AS CLAIM_CONTROL_NUM,
    SUBSTR(RECORD,93,12)                                                AS PRESC_SERVICE_REF_NUM,
    TRY_TO_DATE(NULLIF(TRIM(SUBSTR(RECORD, 105, 8)),''),'YYYYMMDD')     AS DATE_OF_SERVICE,
    SUBSTR(RECORD,113,2)                                                AS FILL_NUM,
    SUBSTR(RECORD,116,2)                                                AS SERVICE_PROV_ID_QUAL,
    SUBSTR(RECORD,118,15)                                               AS SERVICE_PROV_ID,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,133,14)) AS NUMBER(14,2))      AS LICS_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,147,14)) AS NUMBER(14,2))      AS GDCB_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,161,14)) AS NUMBER(14,2))      AS GDCA_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,175,14)) AS NUMBER(14,2))      AS CPP_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,189,14)) AS NUMBER(14,2))      AS EST_REMUN_AT_POS_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,203,14)) AS NUMBER(14,2))      AS NPP_AMT,
    SUBSTR(RECORD,217,1)                                                AS P2P_INDICATOR,
    TRIM(SUBSTR(RECORD,218,100))                                        AS EXCLUDE_REASON,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,318,14)) AS NUMBER(14,2))      AS GAP_DISC_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,332,14)) AS NUMBER(14,2))      AS MANUFAC_DISC_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,346,14)) AS NUMBER(14,2))      AS SELEC_DRUG_SUB_AMT,
    CAST(CMS.FXN_OVERPUNCH(SUBSTR(RECORD,360,14)) AS NUMBER(14,2))      AS PHARM_PRICE_CONCESS_AT_POS
FROM CMS.PARTD_EXCLUSION_WARNING_STAGE
WHERE SUBSTR(RECORD,1,5) = 'PEXDT';