CREATE OR REPLACE VIEW CMS.AGENT_BROKER_COMPENSATION_REPORT_DETAIL_VW AS
SELECT
  SUBSTRING(RECORD, 1, 1)   AS RECORD_TYPE,
  SUBSTRING(RECORD, 2, 5)   AS CONTRACT_NUMBER,
  SUBSTRING(RECORD, 7, 3)   AS PBP,
  SUBSTRING(RECORD, 10, 12) AS BENEFICIARY_ID,
  SUBSTRING(RECORD, 22, 12) AS LAST_NAME,
  SUBSTRING(RECORD, 34, 7)  AS FIRST_NAME,
  SUBSTRING(RECORD, 41, 1)  AS MIDDLE_INITIAL,
  SUBSTRING(RECORD, 42, 8)  AS DOB,
  SUBSTRING(RECORD, 50, 1)  AS SEX,
  SUBSTRING(RECORD, 51, 8)  AS APPLICATION_DATE,
  SUBSTRING(RECORD, 59, 8)  AS ENROLLMENT_EFFECTIVE_START_DATE,
  SUBSTRING(RECORD, 67, 1)  AS COMPENSATION_TYPE_AS_OF_ENROLLMENT_EFFECTIVE_DATE,
  SUBSTRING(RECORD, 68, 8)  AS REPORT_GENERATION_DATE,
  SUBSTRING(RECORD, 76, 3)  AS CYCLE_YEAR_AS_OF_REPORT_GENERATION_DATE,
  SUBSTRING(RECORD, 79, 3)  AS COMPENSATION_PAYMENT_YEAR,
  SUBSTRING(RECORD, 82, 7)  AS PRIOR_PLAN_TYPE,
  SUBSTRING(RECORD, 89, 2)  AS CORRECTION_INDICATOR,
  SUBSTRING(RECORD, 91, 60) AS FILLER_1,
  FILENAME                  AS FILE_NAME,
  FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.AGENT_BROKER_COMPENSATION_REPORT
WHERE SUBSTRING(RECORD, 1, 1) = '1';