CREATE OR REPLACE VIEW CMS.BATCH_COMPLETION_STATUS_SUMMARY_PROCESSING_VW AS
WITH processing AS (
    SELECT
        FILENAME,
        FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE,
        ROW_NUMBER,
        SUBSTRING(RECORD, 1, 2)     AS PROCESSING_TYPE,
        RECORD                      AS LINE
    FROM CMS.BATCH_COMPLETION_STATUS_SUMMARY
    WHERE SUBSTRING(RECORD, 1, 1) = 'P'
),
parsed AS (
    SELECT
        FILENAME,
        LOAD_DATE,
        PROCESSING_TYPE,

        CASE WHEN PROCESSING_TYPE = 'P1' THEN
            TRIM(SPLIT_PART(LINE, '=', 2))
        END AS P1_TOTAL_TRANSACTIONS_PROCESSED,

        CASE WHEN PROCESSING_TYPE = 'P2' THEN
            TRIM(SPLIT_PART(LINE, '=', 2))
        END AS P2_TOTAL_ACCEPTED_TRANSACTIONS,

        CASE WHEN PROCESSING_TYPE = 'P3' THEN
            TRIM(SPLIT_PART(LINE, '=', 2))
        END AS P3_TOTAL_REJECTED_TRANSACTIONS,

        CASE WHEN PROCESSING_TYPE = 'P4' THEN
            TRIM(SPLIT_PART(LINE, '=', 2))
        END AS P4_TOTAL_FAILED_TRANSACTIONS
    
    FROM processing
)
SELECT 
    FILENAME,
    LOAD_DATE,
    MAX(P1_TOTAL_TRANSACTIONS_PROCESSED)   AS P1_TOTAL_TRANSACTIONS_PROCESSED,
    MAX(P2_TOTAL_ACCEPTED_TRANSACTIONS)    AS P2_ACCEPTED_TRANSACTIONS,
    MAX(P3_TOTAL_REJECTED_TRANSACTIONS)    AS P3_TOTAL_REJECTED_TRANSACTIONS,
    MAX(P4_TOTAL_FAILED_TRANSACTIONS)      AS P4_TOTAL_FAILED_TRANSACTIONS
FROM parsed
GROUP BY FILENAME, LOAD_DATE;