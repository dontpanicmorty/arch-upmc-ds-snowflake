CREATE OR REPLACE VIEW CMS.MOR_HCC_TRAILER_VW AS
SELECT
    RESPONSE_MOR_STAGE.FILENAME
    ,RESPONSE_MOR_STAGE.FILE_TYPE
    ,RESPONSE_MOR_STAGE.ROW_NUMBER
    ,RESPONSE_MOR_TYPES.RECORD_TYPE_CODE
    ,RESPONSE_MOR_TYPES.RECORD_TYPE_DESC
    
    ,SUBSTR(RESPONSE_MOR_STAGE.RECORD,2,5) AS CONTRACT_NUMBER
    ,SUBSTR(RESPONSE_MOR_STAGE.RECORD,7,9) AS TOTAL_RECORD_COUNT
    
    ,RESPONSE_MOR_STAGE.FILE_PREFIX
    ,RESPONSE_MOR_STAGE.FILE_DATE
    ,RESPONSE_MOR_STAGE.FILE_TIME
    ,RESPONSE_MOR_STAGE.FILE_LAST_MODIFIED_DATETIME
    ,RESPONSE_MOR_STAGE.LAST_UPDATED_DATETIME
    ,RESPONSE_MOR_STAGE.RECORD AS RAW_RECORD_TEXT    
FROM
    CMS.RESPONSE_MOR_STAGE RESPONSE_MOR_STAGE
    INNER JOIN CMS.RESPONSE_MOR_TYPES RESPONSE_MOR_TYPES 
        ON RESPONSE_MOR_TYPES.RECORD_TYPE_CODE = RESPONSE_MOR_STAGE.RECORD_TYPE
            AND RESPONSE_MOR_TYPES.FILE_TYPE = RESPONSE_MOR_STAGE.FILE_TYPE
WHERE
    RESPONSE_MOR_TYPES.REPORT_SEGMENT_VIEW_NAME = 'MOR_HCC_TRAILER_VW'
;