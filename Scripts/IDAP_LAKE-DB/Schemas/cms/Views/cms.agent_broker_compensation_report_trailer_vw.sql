CREATE OR REPLACE VIEW CMS.AGENT_BROKER_COMPENSATION_REPORT_TRAILER_VW AS
SELECT
  SUBSTRING(RECORD, 1, 1)    AS RECORD_TYPE,
  SUBSTRING(RECORD, 2, 5)    AS CONTRACT_NUMBER,
  SUBSTRING(RECORD, 7, 8)    AS DETAIL_RECORD_COUNT,
  SUBSTRING(RECORD, 15, 136) AS FILLER_1,
  FILENAME                   AS FILE_NAME,
  FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.AGENT_BROKER_COMPENSATION_REPORT
WHERE SUBSTRING(RECORD, 1, 1) = '2';