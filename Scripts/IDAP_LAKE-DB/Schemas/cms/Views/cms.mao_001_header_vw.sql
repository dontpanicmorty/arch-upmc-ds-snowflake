CREATE OR REPLACE VIEW CMS.MAO_001_HEADER_VW (
    FILENAME,
    FILE_TYPE,
    ROW_NUMBER,
    RECORD_TYPE,
    REPORT_ID,
    REPORT_DATE,
    TRANSACTION_DATE,
    REPORT_DESCRIPTION,
    SUBMISSION_INTERCHANGE_NUMBER,
    RECORD_TYPE_CODE,
    SUBMISSION_FILE_TYPE
)as 
SELECT 
    FILENAME,
    FILE_TYPE,
    ROW_NUMBER,
    RECORD_TYPE,
    SUBSTR(RECORD, 3, 7) as REPORT_ID,
    SUBSTR(RECORD, 11, 8)AS REPORT_DATE,
    SUBSTR(RECORD, 20, 8) AS TRANSACTION_DATE,
    SUBSTR(RECORD, 29, 39)AS REPORT_DESCRIPTION,
    SUBSTR(RECORD, 75, 30)AS SUBMISSION_INTERCHANGE_NUMBER,
    SUBSTR(RECORD, 106, 3)AS RECORD_TYPE_CODE,
    SUBSTR(RECORD, 110, 4)AS SUBMISSION_FILE_TYPE
from CMS.RESPONSE_MAO_001_STAGE
WHERE RECORD_TYPE = '0'
;