CREATE OR REPLACE VIEW CMS.COB_OHI_ANNUAL_SUMMARY_DETAIL_VW AS
SELECT
  SUBSTRING(RECORD, 1, 5)   AS CONTRACT_ID,
  SUBSTRING(RECORD, 6, 11)  AS FILLER_1,
  SUBSTRING(RECORD, 17, 44) AS FILE_NAME_IN_RECORD,
  SUBSTRING(RECORD, 61, 9)  AS FILLER_2,
  SUBSTRING(RECORD, 70, 1)  AS FILE_COUNT,
  SUBSTRING(RECORD, 71, 10) AS FILLER_3,
  FILENAME                  AS FILE_NAME,
  FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.COB_OHI_ANNUAL_SUMMARY
WHERE SUBSTRING(RECORD, 1, 5)  NOT IN('     ', 'Contr' );;