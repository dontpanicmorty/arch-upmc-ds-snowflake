CREATE OR REPLACE VIEW CMS.LIS_PART_D_PREMIUM_VW AS
SELECT
    SUBSTRING(RECORD, 1, 12)    AS BENEFICIARY_ID,
    SUBSTRING(RECORD, 13, 5)    AS CONTRACT_NUMBER,
    SUBSTRING(RECORD, 18, 3)    AS PBP_NUMBER,
    SUBSTRING(RECORD, 21, 3)    AS SEGMENT_NUMBER,
    SUBSTRING(RECORD, 24, 8)    AS RUN_DATE,
    SUBSTRING(RECORD, 32, 8)    AS SUBSIDY_START_DATE,
    SUBSTRING(RECORD, 40, 8)    AS SUBSIDY_END_DATE,
    SUBSTRING(RECORD, 48, 3)    AS PART_D_PREMIUM_SUBSIDY_PERCENTAGE,
    SUBSTRING(RECORD, 51, 1)    AS LOW_INCOME_CO_PAYMENT_LEVEL_ID,
    SUBSTRING(RECORD, 52, 8)    AS BENEFICIARY_ENROLLMENT_EFFECTIVE_DATE,
    SUBSTRING(RECORD, 60, 8)    AS BENEFICIARY_ENROLLMENT_END_DATE,
    SUBSTRING(RECORD, 68, 8)    AS PART_C_PREMIUM_AMOUNT,
    SUBSTRING(RECORD, 76, 8)    AS PART_D_PREMIUM_AMOUNT,
    SUBSTRING(RECORD, 84, 8)    AS PART_D_LATE_ENROLLMENT_PENALTY_AMOUNT,
    SUBSTRING(RECORD, 92, 8)    AS LIS_SUBSIDY_AMOUNT,
    SUBSTRING(RECORD, 100, 8)   AS LIS_PENALTY_SUBSIDY_AMOUNT,
    SUBSTRING(RECORD, 108, 8)   AS PART_D_PENALTY_WAIVED_AMOUNT,
    SUBSTRING(RECORD, 116, 8)   AS TOTAL_PREMIUM_AMOUNT,
    SUBSTRING(RECORD, 124, 8)   AS DE_MINIMIS_DIFFERENTIAL_AMOUNT,
    SUBSTRING(RECORD, 132, 147) AS FILLER,
	FILENAME,
	FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.LIS_PART_D_PREMIUM;