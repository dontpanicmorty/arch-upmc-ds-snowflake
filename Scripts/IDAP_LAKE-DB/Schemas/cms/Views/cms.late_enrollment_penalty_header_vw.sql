CREATE OR REPLACE VIEW CMS.LATE_ENROLLMENT_PENALTY_HEADER_VW AS
SELECT
    SUBSTRING(RECORD,  1,  3) AS RECORD_TYPE,
    SUBSTRING(RECORD,  4,  4) AS CONTRACT_NUMBER,
    SUBSTRING(RECORD,  9,  8) AS PAYMENT_ADJUSTMENT_DATE,
    SUBSTRING(RECORD,  17,  8) AS DATA_FILE_DATE,
    SUBSTRING(RECORD,  25,  141) AS FILLER,
	FILENAME,
	FILE_LAST_MODIFIED_DATETIME AS LOAD_DATE
FROM CMS.LATE_ENROLLMENT_PENALTY
WHERE TRIM(SUBSTRING(RECORD,  1,  3)) = 'H';