CREATE OR REPLACE TABLE CLAIM.CHIP_NEWSERHIST_REVENUE
(
 CHIP_NEWSERHIST_REVENUE_KEY NUMBER(38,0) NOT NULL autoincrement start 1 increment 1 order,  
 PROMISE_ICN_NUM				    VARCHAR,
 DETAIL_NUM					    VARCHAR,
 REVENUE_CODE					    VARCHAR,
 FILENAME				VARCHAR NOT NULL,
 INSERT_DATETIME TIMESTAMP_TZ(9) NOT NULL DEFAULT CURRENT_TIMESTAMP(),
 constraint PK_CHIP_NEWSERHIST_REVENUE primary key (CHIP_NEWSERHIST_REVENUE_KEY), 
 constraint UK_CHIP_NEWSERHIST_REVENUE unique (CHIP_NEWSERHIST_REVENUE_KEY, FILENAME, INSERT_DATETIME)  
)
COMMENT='CHIP History File RevenueCode'
;
