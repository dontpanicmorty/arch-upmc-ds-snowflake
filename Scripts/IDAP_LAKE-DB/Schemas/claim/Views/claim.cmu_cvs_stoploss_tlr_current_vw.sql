CREATE OR REPLACE VIEW CLAIM.CMU_CVS_STOPLOSS_TLR_CURRENT_VW AS
SELECT
    FILENAME,
    FILE_LAST_MODIFIED_DATETIME AS INSERT_DATETIME,
    LOADED_FILE_ROW_NUMBER,
    SUBSTR(RECORD,1,2) AS RECORD_TYPE,
    SUBSTR(RECORD,3,10) AS TOT_REC_CNT,
    CMS.FXN_OVERPUNCH(SUBSTR(RECORD,13,12)) AS TOT_NET_DUE_AMT
FROM CLAIM.CMU_CVS_STOPLOSS_STAGE
WHERE SUBSTR(RECORD,1,2) = 'PT';