CREATE OR REPLACE VIEW CLAIM.STAGE_NADAC_PRICING_VW
COMMENT='Select view adding row effective/expiration dates for National Average Drug Acquisition Cost data from Medicaid.gov'
AS
SELECT 
     NDC_DESCRIPTION
    ,NDC 
    ,NADAC_PER_UNIT
    ,EFFECTIVE_DATE 
    ,PRICING_UNIT 
    ,PHARMACY_TYPE_INDICATOR 
    ,OTC
    ,EXPLANATION_CODE 
    ,CLASSIFICATION_FOR_RATE_SETTING 
    ,CORRESPONDING_GENERIC_DRUG_NADAC_PER_UNIT 
    ,CORRESPONDING_GENERIC_DRUG_EFFECTIVE_DATE 
    ,AS_OF_DATE
    ,YEAR(AS_OF_DATE) as NADAC_YEAR
    ,AS_OF_DATE as ROW_EFFECTIVE_DATE
    ,CASE WHEN LEAD(AS_OF_DATE) over (PARTITION BY NDC ORDER BY AS_OF_DATE) IS NULL THEN LAST_DAY(AS_OF_DATE,YEAR)
        ELSE DATEADD(DAY,-1,LEAD(AS_OF_DATE) over (PARTITION BY NDC ORDER BY AS_OF_DATE)) END as ROW_EXPIRATION_DATE    
    ,LOAD_DATETIME
    ,SOURCE_FILE_NAME
FROM 
    CLAIM.STAGE_MEDICAID_NADAC
;