CREATE OR REPLACE VIEW CLAIM.COTIVITI_PPM_DATA_HDR_VW
AS
SELECT	SUBSTR(RECORD, 1, 5) AS STREAM_ID,
		SUBSTR(RECORD, 6, 1) AS FILE_TYPE,
		SUBSTR(RECORD, 7, 5) AS INVOICE_KEY,
		TO_DATE(SUBSTR(RECORD, 12, 8), 'YYYYMMDD') AS PRODUCED_DATE,
		SUBSTR(RECORD, 20, 10) AS RECORD_COUNT,
		SUBSTR(RECORD, 30, 483) AS FILLER, 
        FILENAME AS FILE_NAME,
        INSERT_DATETIME AS LOAD_DATE
FROM    CLAIM.COTIVITI_PPM_DATA_STG 
WHERE   ROW_NUMBER = 1
;