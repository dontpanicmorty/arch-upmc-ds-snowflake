!set variable_substitution=true;
CREATE OR REPLACE VIEW CLAIM.ESI_SPE384_NEW_GCN_CODES_VW
COMMENT = 'New GCN codes from most recent ESI SPE384 File that have not yet been added to GCN list'
AS
SELECT DISTINCT REPLACE(ESI_SPE384_CURRENT_VW.GCN_NBR, '"', '') AS GCN_CODE,
                REPLACE(ESI_SPE384_CURRENT_VW.GENERIC_DRUG_NAME, '"', '') AS DRUG_NAME_GENERIC,
                REPLACE(ESI_SPE384_CURRENT_VW.BRAND_NAME, '"', '') AS DRUG_NAME_BRAND,
                REPLACE(ESI_SPE384_CURRENT_VW.LABEL_TEXT, '"', '') AS DRUG_LABEL_NAME
FROM CLAIM.ESI_SPE384_CURRENT_VW
WHERE NOT EXISTS (
                    SELECT GCN_CODE FROM &{UPMCHP_DATAHUB}.RAWDATA.IDAPLAKE_REFERENCEDATA_ESI_SPECIALTY_DRUG_INDICATOR_VW WHERE GCN_CODE = REPLACE(ESI_SPE384_CURRENT_VW.GCN_NBR, '"', '')
                    UNION ALL
                    SELECT GCN_CODE FROM &{UPMCHP_DATAHUB}.RAWDATA.IDAPLAKE_REFERENCEDATA_ESI_SPECIALTY_DRUG_INDICATOR_EXCLUSIONS_VW WHERE GCN_CODE = REPLACE(ESI_SPE384_CURRENT_VW.GCN_NBR, '"', '')
                 );

!set variable_substitution=false;