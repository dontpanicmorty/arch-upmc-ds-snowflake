CREATE OR REPLACE VIEW CLAIM.WEX_DATA_FINAL_VW
AS
SELECT
METADATA$FILENAME AS FILENAME
,METADATA$FILE_ROW_NUMBER AS FILE_ROW_NUMBER
,METADATA$FILE_LAST_MODIFIED AS FILE_LAST_MODIFIED
,$1 AS RECORD_TYPE
,$2 AS TRANSACTION_TYPE
,$3 AS MODE_OF_TRANSACTION
,$4 AS MODE_OF_TRANSACTION_DESC
,$5 AS TRANSACTION_ID
,$6 AS CLAIM_ID
,$7 AS EXTERNAL_TRANSACTION_ID
,$8 AS DATE_OF_SERVICE
,$9 AS RECEIPT_DATE
,$10 AS DETERMINATION_DATE
,$11 AS RECORD_CREATE_TIMESTAMP
,$12 AS CARRIER_MBR_ID
,$13 AS ENROLL_ID
,$14 AS TRANSACTION_STATUS
,$15 AS SUBMITTED_AMT
,$16 AS PAID_AMT
,$17 AS DENIED_AMT
,$18 AS MERCHANT_NUMBER
,$19 AS MERCHANT_NAME
,$20 AS SERVICE_DESC
,$21 AS DENIAL_CODE
,$22 AS DENIAL_DESCRIPTION
,$23 AS WEX_PLAN_ID
,$24 AS WEX_PLAN_NAME
,$25 AS PAYEE_NAME
,$26 AS DIVISION_FIELD
,$27 AS EMPLOYER_EMPLOYEE_ID
,$28 AS GROUP_CODE
,$29 AS ITEM_TYPE
FROM '@UTIL.HPDSDATALAKE_IDAPLAKE/claim/wex/'
    (FILE_FORMAT =>  CLAIM.WEX_DATA_FINAL_FILE_FORMAT )
;