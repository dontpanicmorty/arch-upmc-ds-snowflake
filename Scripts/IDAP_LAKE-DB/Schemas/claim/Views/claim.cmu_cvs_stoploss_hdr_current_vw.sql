SELECT
    FILENAME,
    FILE_LAST_MODIFIED_DATETIME AS INSERT_DATETIME,
    LOADED_FILE_ROW_NUMBER,
    SUBSTR(RECORD,1,2) AS RECORD_TYPE,
    SUBSTR(RECORD,3,2) AS VERS_NBR,
    SUBSTR(RECORD,5,24) AS SEND_ENT_ID,
    SUBSTR(RECORD,29,7) AS BATCH_NBR,
    TRY_TO_DATE(NULLIF(SUBSTR(RECORD,36,8),'00000000'),'YYYYMMDD') AS CREATION_DATE,
    SUBSTR(RECORD,44,4) AS CREATION_TIME,
    SUBSTR(RECORD,48,24) AS REC_ID,
    TRY_TO_DATE(NULLIF(SUBSTR(RECORD,72,8),'00000000'),'YYYYMMDD') AS REPORT_PER_ST_DATE,
    TRY_TO_DATE(NULLIF(SUBSTR(RECORD,80,8),'00000000'),'YYYYMMDD') AS REPORT_PER_END_DATE,
    SUBSTR(RECORD,88,1) AS FILE_TYPE,
    SUBSTR(RECORD,89,1) AS TRANS_ACT,
    SUBSTR(RECORD,90,2) AS SUB_NBR
FROM CLAIM.CMU_CVS_STOPLOSS_STAGE
WHERE SUBSTR(RECORD,1,2) = 'PA';