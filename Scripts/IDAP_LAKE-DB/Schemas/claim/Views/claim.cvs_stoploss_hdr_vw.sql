CREATE OR REPLACE VIEW CLAIM.CVS_STOPLOSS_HDR_VW AS
SELECT
    FILENAME,
    INSERT_DATETIME,
    LOADED_FILE_ROW_NUMBER,
    RECORD_TYPE,
    VERSION_NBR,
    SEND_ENT_ID,
    BATCH_NBR,
    CREATION_DATE,
    CREATION_TIME,
    RECEIVER_ID,
    REPORT_PER_ST_DATE,
    REPORT_PER_END_DATE,
    FILE_TYPE,
    TRANS_ACTION,
    SUBMISSION_NBR
FROM CLAIM.CVS_STOPLOSS_HDR_CURRENT_VW
UNION ALL
SELECT
    FILENAME,
    INSERT_DATETIME,
    NULL AS LOADED_FILE_ROW_NUMBER,
    RECORD_TYPE,
    VERSION_NBR,
    SEND_ENT_ID,
    BATCH_NBR,
    CREATION_DATE,
    CREATION_TIME,
    RECEIVER_ID,
    REPORT_PER_ST_DATE,
    REPORT_PER_END_DATE,
    FILE_TYPE,
    TRANS_ACTION,
    SUBMISSION_NBR
FROM CLAIM.CVS_STOPLOSS_HDR_HISTORY;