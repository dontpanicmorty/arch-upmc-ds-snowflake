CREATE OR REPLACE VIEW CLAIM.SPANISH_NOT_COVERED_REASON_VW(
	FILENAME,
	FILE_LAST_MODIFIED,
	FILE_ROW_NUMBER,
	NCRCODE,
	ENGLISHDESC,
	ENGLISHCMSDESC,
	SPANISHDESC,
	SPANISHCMSDESC,
    CLAIMSSOURCE,
    MEMBERPAY,
    PLANTYPE
) COMMENT='File converted to csv and manually dropped into /referencedata/claim/spanish_ncrc/ for use in the view.' 
as
SELECT  METADATA$FILENAME AS FILENAME,
        METADATA$FILE_LAST_MODIFIED AS FILE_LAST_MODIFIED,
        METADATA$FILE_ROW_NUMBER AS FILE_ROW_NUMBER,
        $1 AS 	NCRCODE,
        $2 AS	ENGLISHDESC,
        $3 AS	ENGLISHCMSDESC,
        $4 AS	SPANISHDESC,
        $5 AS	SPANISHCMSDESC,
        $6 AS   CLAIMSSOURCE,
        $7 AS   MEMBERPAY,
        $8 AS   PLANTYPE
FROM    @UTIL.HPDSDATALAKE_IDAPLAKE/referencedata/claim/spanish_ncrc/
        (FILE_FORMAT =>  'CLAIM.SPANISH_NOT_COVERED_REASON_FILE_FORMAT' )
;