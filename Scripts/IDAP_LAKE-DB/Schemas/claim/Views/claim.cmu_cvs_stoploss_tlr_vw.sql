SELECT
    FILENAME,
    INSERT_DATETIME,
    LOADED_FILE_ROW_NUMBER,
    RECORD_TYPE,
    TOT_REC_CNT,
    TOT_NET_DUE_AMT
FROM CLAIM.CMU_CVS_STOPLOSS_TLR_CURRENT_VW
