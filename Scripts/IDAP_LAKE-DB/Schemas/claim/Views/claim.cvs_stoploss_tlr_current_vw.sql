CREATE OR REPLACE VIEW CLAIM.CVS_STOPLOSS_TLR_CURRENT_VW AS
SELECT
    FILENAME,
    FILE_LAST_MODIFIED_DATETIME                                                         AS INSERT_DATETIME,
    LOADED_FILE_ROW_NUMBER,
    RECORD_TYPE,
    TRIM(SUBSTR(RECORD, 3, 10))                                                         AS TOT_RECORD_CT,
    CAST(CLAIM.FXN_SQLLDR_ZONED_TO_NUMBER(SUBSTR(RECORD, 13, 12), 2) AS NUMBER(12,2))   AS TOT_AMT_DUE
FROM CLAIM.CVS_STOPLOSS_STAGE
WHERE RECORD_TYPE = 'PT';