CREATE OR REPLACE VIEW CLAIM.CVS_STOPLOSS_TLR_VW AS
SELECT
    FILENAME,
    INSERT_DATETIME,
    LOADED_FILE_ROW_NUMBER,
    RECORD_TYPE,
    TOT_RECORD_CT,
    TOT_AMT_DUE
FROM CLAIM.CVS_STOPLOSS_TLR_CURRENT_VW
UNION ALL
SELECT
    FILENAME,
    INSERT_DATETIME,
    NULL AS LOADED_FILE_ROW_NUMBER,
    RECORD_TYPE,
    TOT_RECORD_CT,
    TOT_AMT_DUE
FROM CLAIM.CVS_STOPLOSS_TLR_HISTORY;