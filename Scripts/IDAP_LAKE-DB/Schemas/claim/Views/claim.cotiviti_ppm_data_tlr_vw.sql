CREATE OR REPLACE VIEW CLAIM.COTIVITI_PPM_DATA_TLR_VW
AS
SELECT  SUBSTR(RECORD,	1	,	7	) AS TRAILER_CONSTANT,
        SUBSTR(RECORD,	8	,	10	) AS RECORD_COUNT,
        TO_TIMESTAMP(SUBSTR(RECORD,	18	,	12	), 'yyyymmddhhmi') AS PRODUCED_DATE,
        SUBSTR(RECORD,	30	,	483	) AS FILLER,
        FILENAME AS FILE_NAME,
        INSERT_DATETIME AS LOAD_DATE
FROM    CLAIM.COTIVITI_PPM_DATA_STG 
WHERE   SUBSTR(RECORD, 1, 7) = 'TRAILER'
;