!set variable_substitution=true;
CREATE OR REPLACE VIEW CLAIM.PHARMACY_HRA_HIA_AUDIT_VW
COMMENT = 'Report showing original and updated HRA and HIA spend amount values'
AS
SELECT  FACT_PHARMACY_CLAIM_LINE.FACT_PHARMACY_CLAIM_LINE_KEY,
        SAT_CLAIM_LINE_PHARMACY.ORIGINAL_HIA_SPENDING_AMT,
        SAT_CLAIM_LINE_PHARMACY.UPDATED_HIA_SPENDING_AMT,
        SAT_CLAIM_LINE_PHARMACY.HIA_SPENDING_AMT_UPDATE_DATE,
        SAT_CLAIM_LINE_PHARMACY.ORIGINAL_HRA_SPENDING_AMT,
        SAT_CLAIM_LINE_PHARMACY.UPDATED_HRA_SPENDING_AMT,
        SAT_CLAIM_LINE_PHARMACY.HRA_SPENDING_AMT_UPDATE_DATE
FROM &{UPMCHP_DATAHUB}.HUBDATA.HUB_CLAIM_DETAIL
JOIN &{UPMCHP_DATAHUB}.HUBDATA.EFF_SAT_CLAIM_LINE
    ON (HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = EFF_SAT_CLAIM_LINE.HUB_CLAIM_DETAIL_HKEY
    AND EFF_SAT_CLAIM_LINE.IS_CURRENT_ROW_FLAG = TRUE
    AND EFF_SAT_CLAIM_LINE.DELETED_DATETIME > CURRENT_TIMESTAMP())
JOIN &{UPMCHP_DATAHUB}.HUBDATA.SAT_CLAIM_LINE_PHARMACY
    ON (HUB_CLAIM_DETAIL.HUB_CLAIM_DETAIL_HKEY = SAT_CLAIM_LINE_PHARMACY.HUB_CLAIM_DETAIL_HKEY
    AND SAT_CLAIM_LINE_PHARMACY.IS_CURRENT_ROW_FLAG = TRUE)
JOIN &{IDAP}.DIMDATA.DIM_PHARMACY_CLAIM_DETAIL
    ON (HUB_CLAIM_DETAIL.TPA_CLIENT_ID = DIM_PHARMACY_CLAIM_DETAIL.TPA_CLIENT_ID
    AND HUB_CLAIM_DETAIL.TPA_ID = DIM_PHARMACY_CLAIM_DETAIL.TPA_ID
    AND HUB_CLAIM_DETAIL.TPA_DIV_ID = DIM_PHARMACY_CLAIM_DETAIL.TPA_DIV_ID
    AND HUB_CLAIM_DETAIL.DATA_SOURCE_NAME = DIM_PHARMACY_CLAIM_DETAIL.DATA_SOURCE_NAME
    AND HUB_CLAIM_DETAIL.CLAIM_NBR = DIM_PHARMACY_CLAIM_DETAIL.CLAIM_NBR
    AND HUB_CLAIM_DETAIL.CLAIM_LINE_NBR = DIM_PHARMACY_CLAIM_DETAIL.CLAIM_LINE_NBR
    AND HUB_CLAIM_DETAIL.CLAIM_LINE_SEQ_NBR = DIM_PHARMACY_CLAIM_DETAIL.CLAIM_SEQUENCE_NBR
    AND HUB_CLAIM_DETAIL.CLAIM_LINE_PROCEDURE_ADJ_CODE = DIM_PHARMACY_CLAIM_DETAIL.PROCEDURE_ADJ_CODE
    AND DIM_PHARMACY_CLAIM_DETAIL.IS_LOGICAL_DELETE_FLAG = FALSE)
JOIN &{IDAP}.DIMDATA.FACT_PHARMACY_CLAIM_LINE
    ON (DIM_PHARMACY_CLAIM_DETAIL.DIM_PHARMACY_CLAIM_DETAIL_KEY = FACT_PHARMACY_CLAIM_LINE.DIM_PHARMACY_CLAIM_DETAIL_KEY)
WHERE (UPDATED_HIA_SPENDING_AMT IS NOT NULL OR UPDATED_HRA_SPENDING_AMT IS NOT NULL) --only return records that have had an update in one or both of these fields: HIA_SPENDING_AMT, HRA_SPENDING_AMT
;