CREATE OR REPLACE VIEW MEMBER.INSPIRA_SUBSCRIBER_FSA_DETAIL_RECORD_VW AS
SELECT
SPLIT_PART(RECORD, '|', 1) AS RECORD_INDICATOR_CODE ,
SPLIT_PART(RECORD, '|', 2) AS EMPLOYER_ID ,
SPLIT_PART(RECORD, '|', 3) AS MEMBER_NUMBER ,
SPLIT_PART(RECORD, '|', 4) AS MEMBER_SSN ,
SPLIT_PART(RECORD, '|', 5) AS SERVICE_START_DATE ,
SPLIT_PART(RECORD, '|', 6) AS SERVICE_END_DATE,
NULLIF(TRIM(SPLIT_PART(RECORD, '|', 7)), '') AS TERM_INDICATOR,
FILENAME,
LAST_UPDATED_DATETIME
FROM MEMBER.INSPIRA_SUBSCRIBER_FSA
WHERE RECORD_TYPE = 'DTR';