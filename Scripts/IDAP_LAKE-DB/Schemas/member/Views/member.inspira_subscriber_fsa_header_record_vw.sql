CREATE OR REPLACE VIEW MEMBER.INSPIRA_SUBSCRIBER_FSA_HEADER_RECORD_VW AS
SELECT
SPLIT_PART(RECORD, '|', 1) AS RECORD_INDICATOR_CODE,
SPLIT_PART(RECORD, '|', 2) AS CARRIER_NAME,
SPLIT_PART(RECORD, '|', 3) AS FILE_DATE_CREATED,
SPLIT_PART(RECORD, '|', 4) AS FILE_TIME_CREATED,
SPLIT_PART(RECORD, '|', 5) AS FILE_LAYOUT_TYPE,
FILENAME,
LAST_UPDATED_DATETIME
FROM MEMBER.INSPIRA_SUBSCRIBER_FSA
WHERE RECORD_TYPE = 'HDR';