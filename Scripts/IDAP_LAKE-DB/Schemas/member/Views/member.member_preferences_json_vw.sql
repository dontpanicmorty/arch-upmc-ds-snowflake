CREATE OR REPLACE VIEW MEMBER.MEMBER_PREFERENCES_JSON_VW
COMMENT = 'Returns the current loaded record in raw table format'
AS
SELECT
MEMBER_PREFERENCES_KEY
,MEMBER_PREFERENCES.FILENAME
,MEMBER_PREFERENCES.FILE_ROW_NBR
,MEMBER_PREFERENCES.INSERT_DATETIME
,MEMBER_PREFERENCES.JSON_DATA
,MEMBER_PREFERENCES.JSON_ID
,MEMBER_PREFERENCES.JSON_LAST_UPDATED_DATE
FROM MEMBER.MEMBER_PREFERENCES
    JOIN MEMBER.MEMBER_PREFERENCES_CURRENT_ROW_VW
        ON (MEMBER_PREFERENCES_CURRENT_ROW_VW.JSON_ID = MEMBER_PREFERENCES.JSON_ID
        AND MEMBER_PREFERENCES_CURRENT_ROW_VW.INSERT_DATETIME = MEMBER_PREFERENCES.INSERT_DATETIME
        AND MEMBER_PREFERENCES_CURRENT_ROW_VW.FILENAME = MEMBER_PREFERENCES.FILENAME)
;