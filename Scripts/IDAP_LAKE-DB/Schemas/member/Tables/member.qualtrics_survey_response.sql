CREATE OR REPLACE TABLE MEMBER.QUALTRICS_SURVEY_RESPONSE (
    SURVEY_RESPONSE_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
    FILENAME VARCHAR,
    INSERT_DATETIME TIMESTAMP_TZ(9),
    JSON_DATA VARIANT,
    CONSTRAINT PK_SURVEY_RESPONSE PRIMARY KEY (SURVEY_RESPONSE_KEY),
    CONSTRAINT UK_SURVEY_RESPONSE UNIQUE (FILENAME, INSERT_DATETIME)
)
COMMENT = "Survey responses from Qualtrics for linking to members. All response formats are condensed into one table, regardless of which question IDs are used in each given survey."
