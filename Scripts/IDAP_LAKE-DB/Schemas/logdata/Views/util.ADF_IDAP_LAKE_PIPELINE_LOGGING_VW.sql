!set variable_substitution=true;
CREATE VIEW logdata.ADF_IDAP_LAKE_PIPELINE_LOGGING_VW AS
SELECT	METADATA$FILENAME AS FILENAME,
		$1 AS DATAFACTORY_NAME,
		$2 AS PIPELINE_NAME,
		$3 AS RUN_ID,
		$4 AS TRIGGER_TYPE,
		$5 AS TRIGGER_ID,
		$6 AS TRIGGER_NAME,
		$7 AS TRIGGER_TIME,
		$8 AS TARGET_LOCATION,
		$9 AS DATA_COPIED,
		$10 AS DATA_READ,
		$11 AS ERRORS,
		$12 AS THROUGHPUT,
		$13 AS EFFECTIVE_INTEGRATION_RUNTIME,
		$14 AS SOURCE_TYPE,
		$15 AS SINK_TYPE,
		$16 AS EXECUTION_STATUS,
		$17 AS COPY_ACTIVITY_START_TIME,
		$18 AS COPY_ACTIVITY_END_TIME,
		$19 AS COPY_ACTIVITY_QUEUING_DURATION_SECONDS,
		$20 AS COPY_ACTIVITY_TRANSFER_DURATION_SECONDS,
		$21 AS ADF_FILE_COPY_CONTROL_KEY
FROM 	@UTIL.HPDSDATALAKE_IDAPLAKE/logdata/adf/
		(file_format => 'util.ADF_LOGGING_FILE_FORMAT')
WHERE   SPLIT_PART(FILENAME, '/', 4) >= TO_CHAR(CURRENT_DATE() -7, 'YYYYMMDD')

!set variable_substitution=false;
