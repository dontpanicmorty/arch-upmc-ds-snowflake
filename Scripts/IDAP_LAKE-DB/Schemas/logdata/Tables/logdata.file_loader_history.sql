CREATE OR REPLACE TABLE LOGDATA.FILE_LOADER_HISTORY (
  FILE_LOADER_HISTORY_KEY NUMBER(38,0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL,
  FILE_LOADER_CONTROL_KEY NUMBER(38,0) NOT NULL,
  INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP(), 
  FILENAME VARCHAR, 
  LOAD_STATUS VARCHAR, 
  ERROR_MESSAGE VARCHAR, 
  ROW_CNT INTEGER,
  CONSTRAINT PK_FILE_LOADER_HISTORY PRIMARY KEY (FILE_LOADER_HISTORY_KEY),
  CONSTRAINT UK_FILE_LOADER_HISTORY UNIQUE (FILE_LOADER_CONTROL_KEY, INSERT_DATETIME, FILENAME),
  CONSTRAINT FK_FILELOADERHISTORY_FILELOADERCONTROL FOREIGN KEY (FILE_LOADER_CONTROL_KEY) REFERENCES UTIL.FILE_LOADER_CONTROL(FILE_LOADER_CONTROL_KEY)
)
COMMENT = 'Log table to track loading flat files into IDAP_LAKE.'
;