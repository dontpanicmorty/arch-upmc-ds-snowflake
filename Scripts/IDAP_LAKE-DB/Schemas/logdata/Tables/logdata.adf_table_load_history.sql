CREATE OR REPLACE TABLE LOGDATA.ADF_TABLE_LOAD_HISTORY
    (
        RUN_ID VARCHAR NOT NULL,
        ADF_CONTROL_KEY VARCHAR NOT NULL,
        NAME VARCHAR NOT NULL,
        TYPE VARCHAR NOT NULL,
        START_TIME TIMESTAMP_TZ(9) NOT NULL,
        END_TIME TIMESTAMP_TZ(9) NULL,
        INSERT_COUNT NUMBER(38,0) NULL,
        RESULT_TEXT VARCHAR NULL,
        SQL_STATEMENT VARCHAR NOT NULL,
        ERROR_CODE VARCHAR NULL,
        ERROR_STATE VARCHAR NULL,
        ERROR_MESSAGE VARCHAR NULL,
        ERROR_STACK_TRACE_TEXT VARCHAR NULL
    ) COMMENT='Tracks all DML operations and any associated errors';