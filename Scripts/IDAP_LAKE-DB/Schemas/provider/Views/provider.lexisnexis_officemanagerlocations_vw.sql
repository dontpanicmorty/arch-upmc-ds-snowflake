CREATE OR REPLACE VIEW PROVIDER.LEXISNEXIS_OFFICEMANAGERLOCATIONS_VW
AS
SELECT 
	METADATA$FILE_LAST_MODIFIED AS LOAD_TIME,
	METADATA$FILENAME AS FILENAME,
	$1 AS PRACTICE_NAME, 
	$2 AS ADDRESS_LINE_1, 
	$3 AS ADDRESS_LINE_2, 
	$4 AS CITY, 
	$5 AS STATE, 
	$6 AS ZIP, 
	$7 AS PHONE, 
	$8 AS FAX, 
	$9 AS SECURE_FAX, 
	$10 AS PROVIDER_SUN_HOURS, 
	$11 AS PROVIDER_MON_HOURS, 
	$12 AS PROVIDER_TUES_HOURS, 
	$13 AS PROVIDER_WEDS_HOURS, 
	$14 AS PROVIDER_THURS_HOURS, 
	$15 AS PROVIDER_FRI_HOURS, 
	$16 AS PROVIDER_SAT_HOURS, 
	$17 AS UPDATED_DATE, 
	$18 AS UPDATED_BY, 
	$19 AS PAYER_ADDRESS_ID, 
	$20 AS SECONDARY_RANGE_VERIFIED, 
	$21 AS TAX_ID
FROM @UTIL.HPDSDATALAKE_IDAPLAKE/provider/lexisnexis (file_format => PROVIDER.LEXIS_NEXIS_FILE_FORMAT)
WHERE FILENAME LIKE '%0000010000010001-provider-LexisNexis__OfficeManagerLocations_%.txt%'
;