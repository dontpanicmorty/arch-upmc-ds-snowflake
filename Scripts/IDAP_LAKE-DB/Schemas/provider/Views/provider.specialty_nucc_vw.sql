CREATE OR REPLACE VIEW PROVIDER.SPECIALTY_NUCC_VW
COMMENT='Specialty Taxonomy Spreadsheet provided by business (Liz Venturino)'
AS
WITH LATEST_FILE AS (
	SELECT
		METADATA$FILENAME AS FILENAME,
		METADATA$FILE_LAST_MODIFIED AS DATE_UPDATED
	FROM
		@UTIL.HPDSDATALAKE_IDAPLAKE/provider/specialty_nucc/
	QUALIFY
		ROW_NUMBER() OVER (ORDER BY DATE_UPDATED DESC) = 1
),
DATA AS (
	SELECT
		METADATA$FILENAME AS FILENAME,
		METADATA$FILE_LAST_MODIFIED AS DATE_UPDATED,
		$1 AS DATA_SOURCE,
		$2 AS SPECIALTY_RAW,
		$3 AS SPECIALTY_REVIEW,
		$4 AS SPECIALTY_KEY,
		$5 AS SPECIALTY,
		$6 AS SPECIALTY_DIRECTORY,
		$7 AS PROVIDER_TAXONOMY_CODE,
		$8 AS PROVIDER_TAXONOMY,
		$9 AS NOTES,
		$10 AS MEDICARE_SPECIALTY_CODE,
		$11 AS MEDICARE_PROVIDER_SUPPLIER_TYPE_DESCRIPTION,
	FROM
		@UTIL.HPDSDATALAKE_IDAPLAKE/provider/specialty_nucc/
		(FILE_FORMAT => 'PROVIDER.TSV_FILE_FORMAT')
	WHERE
		METADATA$FILENAME = (SELECT FILENAME FROM LATEST_FILE)
)
SELECT *
FROM (
	SELECT
		DATA_SOURCE,
		SPECIALTY_RAW,
		SPECIALTY_REVIEW,
		SPECIALTY_KEY,
		SPECIALTY,
		SPECIALTY_DIRECTORY,
		PROVIDER_TAXONOMY_CODE,
		PROVIDER_TAXONOMY,
		NOTES,
		MEDICARE_SPECIALTY_CODE,
		MEDICARE_PROVIDER_SUPPLIER_TYPE_DESCRIPTION,
		DATE_UPDATED,
		FILENAME,
		ROW_NUMBER() OVER (PARTITION BY SPECIALTY_KEY ORDER BY DATE_UPDATED DESC) AS RN
	FROM
		DATA
)
WHERE
	RN = 1
;