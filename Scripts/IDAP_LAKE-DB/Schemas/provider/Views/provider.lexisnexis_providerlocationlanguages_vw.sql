CREATE OR REPLACE VIEW PROVIDER.LEXISNEXIS_PROVIDERLOCATIONLANGUAGES_VW
AS
SELECT 
	METADATA$FILE_LAST_MODIFIED AS LOAD_TIME,
	METADATA$FILENAME AS FILENAME,
	$1 AS PAYER_PROVIDER_ID, 
	$2 AS PAYER_ADDRESS_ID, 
	$3 AS ATTESTED_ENTITY_UNIQUE_ID, 
	$4 AS LNPID, 
	$5 AS LOCATION_LANGUAGE, 
	$6 AS LOCATION_LANGUAGE_VERIFIED, 
	$7 AS USER_DEF_01, 
	$8 AS USER_DEF_02, 
	$9 AS USER_DEF_03, 
	$10 AS USER_DEF_04, 
	$11 AS USER_DEF_05, 
	$12 AS USER_DEF_06, 
	$13 AS USER_DEF_07, 
	$14 AS USER_DEF_08, 
	$15 AS USER_DEF_09, 
	$16 AS USER_DEF_10, 
	$17 AS STATUS, 
	$18 AS ATTESTED_DATE, 
	$19 AS APL_TOTAL_PRACTICE_ENTITY_ID, 
	$20 AS SECONDARY_RANGE_VERIFIED
FROM @UTIL.HPDSDATALAKE_IDAPLAKE/provider/lexisnexis (file_format => PROVIDER.LEXIS_NEXIS_FILE_FORMAT)
WHERE FILENAME LIKE '%0000010000010001-provider-LexisNexis__ProviderLocationLanguages_%.txt%'
;