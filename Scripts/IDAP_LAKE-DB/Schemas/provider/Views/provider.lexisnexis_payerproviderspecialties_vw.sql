CREATE OR REPLACE VIEW PROVIDER.LEXISNEXIS_PAYERPROVIDERSPECIALTIES_VW
AS
SELECT 
	METADATA$FILE_LAST_MODIFIED AS LOAD_TIME,
	METADATA$FILENAME AS FILENAME,
	$1 AS PAYER_PROVIDER_ID, 
	$2 AS ATTESTED_ENTITY_UNIQUE_ID, 
	$3 AS LNPID, 
	$4 AS TAXONOMY_CODE, 
	$5 AS TAXONOMY_CODE_VERIFIED, 
	$6 AS IS_PRIMARY, 
	$7 AS IS_PRIMARY_VERIFIED, 
	$8 AS IS_BOARD_CERTIFIED, 
	$9 AS IS_BOARD_CERTIFIED_VERIFIED, 
	$10 AS USER_DEF_01, 
	$11 AS USER_DEF_02, 
	$12 AS USER_DEF_03, 
	$13 AS USER_DEF_04, 
	$14 AS USER_DEF_05, 
	$15 AS USER_DEF_06, 
	$16 AS USER_DEF_07, 
	$17 AS USER_DEF_08, 
	$18 AS USER_DEF_09, 
	$19 AS USER_DEF_10, 
	$20 AS STATUS, 
	$21 AS ATTESTED_DATE
FROM @UTIL.HPDSDATALAKE_IDAPLAKE/provider/lexisnexis (file_format => PROVIDER.LEXIS_NEXIS_FILE_FORMAT)
WHERE FILENAME LIKE '%0000010000010001-provider-LexisNexis__PayerProviderSpecialties_%.txt%'
;