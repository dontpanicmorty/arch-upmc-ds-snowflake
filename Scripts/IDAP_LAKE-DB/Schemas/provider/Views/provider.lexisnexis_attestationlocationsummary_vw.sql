CREATE OR REPLACE VIEW PROVIDER.LEXISNEXIS_ATTESTATIONLOCATIONSUMMARY_VW
AS
SELECT 
	METADATA$FILE_LAST_MODIFIED AS LOAD_TIME,
	METADATA$FILENAME AS FILENAME,
	$1 AS PAYER_PROVIDER_ID, 
	$2 AS PROVIDER_NPI_ID, 
	$3 AS ENTITY_UNIQUE_ID, 
	$4 AS LNPID, 
	$5 AS PAYER_ADDRESSID, 
	$6 AS SECONDARY_RANGE_VERIFIED, 
	$7 AS ADDRESS_LINE_1_VERIFIED, 
	$8 AS ADDRESS_LINE_2_VERIFIED, 
	$9 AS CITY_VERIFIED, 
	$10 AS STATE_VERIFIED, 
	$11 AS ZIP_VERIFIED, 
	$12 AS PHONE_VERIFIED, 
	$13 AS FAX_VERIFIED, 
	$14 AS ATTESTED_DATE, 
	$15 AS USER_ATTESTED, 
	$16 AS METHOD, 
	$17 AS CONTACT_TITLE, 
	$18 AS CONTACT_NAME, 
	$19 AS CONTACT_EMAIL, 
	$20 AS CONTACT_PHONE, 
	$21 AS TOTAL_PRACTICE_ENTITY_ID
FROM @UTIL.HPDSDATALAKE_IDAPLAKE/provider/lexisnexis (file_format => PROVIDER.LEXIS_NEXIS_FILE_FORMAT)
WHERE FILENAME LIKE '%0000010000010001-provider-LexisNexis__AttestationLocationSummary_%.txt%'
;