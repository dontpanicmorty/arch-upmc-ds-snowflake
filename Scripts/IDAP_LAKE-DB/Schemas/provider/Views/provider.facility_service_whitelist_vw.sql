CREATE OR REPLACE VIEW PROVIDER.FACILITY_SERVICE_WHITELIST_VW
COMMENT='Facility Service Whitelist Spreadsheet provided by business'
AS
WITH LATEST_FILE AS (
	SELECT
		METADATA$FILENAME AS FILENAME,
		METADATA$FILE_LAST_MODIFIED AS DATE_UPDATED
	FROM
		@UTIL.HPDSDATALAKE_IDAPLAKE/provider/facility_service_whitelist/
	QUALIFY
		ROW_NUMBER() OVER (ORDER BY DATE_UPDATED DESC) = 1
),
DATA AS (
	SELECT
		METADATA$FILENAME AS FILENAME,
		METADATA$FILE_LAST_MODIFIED AS DATE_UPDATED,
		$1 AS TIN,
		$2 AS PROVIDER_NAME,
		$3 AS PROVIDER_LOCATION_KEY,
		$4 AS F1,
		$5 AS F2,
		$6 AS F3,
		$7 AS F4,
		$8 AS F5,
		$9 AS F6,
		$10 AS F7,
		$11 AS F8,
		$12 AS F9,
		$13 AS F10,
		$14 AS F11,
		$15 AS F12,
		$16 AS F13,
		$17 AS F14,
		$18 AS F15,
		$19 AS F16,
		$20 AS F17,
		$21 AS F18,
		$22 AS F19,
		$23 AS F20,
		$24 AS F21,
		$25 AS F22,
		$26 AS F23,
		$27 AS F24,
		$28 AS F25
	FROM
		@UTIL.HPDSDATALAKE_IDAPLAKE/provider/facility_service_whitelist/
		(FILE_FORMAT => 'PROVIDER.TSV_FILE_FORMAT')
	WHERE
		METADATA$FILENAME = (SELECT FILENAME FROM LATEST_FILE)
)
SELECT *
FROM (
	SELECT
		TIN,
		PROVIDER_NAME,
		PROVIDER_LOCATION_KEY,
		F1,
		F2,
		F3,
		F4,
		F5,
		F6,
		F7,
		F8,
		F9,
		F10,
		F11,
		F12,
		F13,
		F14,
		F15,
		F16,
		F17,
		F18,
		F19,
		F20,
		F21,
		F22,
		F23,
		F24,
		F25,
		DATE_UPDATED,
		FILENAME,
		ROW_NUMBER() OVER (PARTITION BY PROVIDER_LOCATION_KEY ORDER BY DATE_UPDATED DESC) AS RN
	FROM
		DATA
)
WHERE
	RN = 1
;
