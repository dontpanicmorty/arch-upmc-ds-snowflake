CREATE OR REPLACE VIEW PROVIDER.PRV414_VW AS (
	WITH HEADER AS
	(SELECT 
	  SUBSTRING(RECORD,1,1) RECORDTYPE,
	  TRIM(SUBSTRING(RECORD,2,9)) PROMISEPROV,
	  TRIM(SUBSTRING(RECORD,11,4)) SERVICELOC,
	  TRIM(SUBSTRING(RECORD,15,8)) BEGINDATE,
	  TRIM(SUBSTRING(RECORD,23,8)) ENDDATE,
	  TRIM(SUBSTRING(RECORD,31,50)) PROVNAME,
	  TRIM(SUBSTRING(RECORD,81,9)) IRSSSN,
	  TRIM(SUBSTRING(RECORD,90,1)) IRSSSNIND,
	  TRIM(SUBSTRING(RECORD,91,10)) MEDICARE,
	  TRIM(SUBSTRING(RECORD,101,2)) COUNTY,
	  TRIM(SUBSTRING(RECORD,103,30)) ADDR_1,
	  TRIM(SUBSTRING(RECORD,133,30)) ADDR_2,
	  TRIM(SUBSTRING(RECORD,163,18)) CITY,
	  TRIM(SUBSTRING(RECORD,181,2)) STATE,
	  TRIM(SUBSTRING(RECORD,183,5)) ZIP,
	  TRIM(SUBSTRING(RECORD,188,4)) ZIPEXT,
	  TRIM(SUBSTRING(RECORD,192,10)) PHONE,
	  TRIM(SUBSTRING(RECORD,202,9)) DEA,
	  TRIM(SUBSTRING(RECORD,211,6)) UPIN,
	  TRIM(SUBSTRING(RECORD,217,10)) MAMISID,
	  '' PROVTYPE,
	  '' SPECCODE,
	  '' SPECCODEBEGIN,
	  '' SPECCODEEND,
	  '' LICENSE,
	  '' LICENSEEND,
	  '' PRACTYPE,
	  '' MEDICALDEG,
	  '' STATUSCODE
	  FROM PROVIDER.PRV414_RAW
	  WHERE SUBSTRING(RECORD,1,1) = '1'
	),

	DETAIL AS
	(SELECT
	  SUBSTRING(RECORD,1,1) RECORDTYPE,
	  TRIM(SUBSTRING(RECORD,2,9)) PROMISEPROV,
	  TRIM(SUBSTRING(RECORD,11,4)) SERVICELOC,
	  '' BEGINDATE,
	  '' ENDDATE,
	  '' PROVNAME,
	  '' IRSSSN,
	  '' IRSSSNIND,
	  '' MEDICARE,
	  '' COUNTY,
	  '' ADDR_1,
	  '' ADDR_2,
	  '' CITY,
	  '' STATE,
	  '' ZIP,
	  '' ZIPEXT,
	  '' PHONE,
	  '' DEA,
	  '' UPIN,
	  '' MAMISID,
	  TRIM(SUBSTRING(RECORD,15,2)) PROVTYPE,
	  TRIM(SUBSTRING(RECORD,17,3)) SPECCODE,
	  TRIM(SUBSTRING(RECORD,20,8)) SPECCODEBEGIN,
	  TRIM(SUBSTRING(RECORD,28,8)) SPECCODEEND,
	  TRIM(SUBSTRING(RECORD,36,10)) LICENSE,
	  TRIM(SUBSTRING(RECORD,46,8)) LICENSEEND,
	  TRIM(SUBSTRING(RECORD,54,1)) PRACTYPE,
	  TRIM(SUBSTRING(RECORD,55,3)) MEDICALDEG,
	  TRIM(SUBSTRING(RECORD,58,1)) STATUSCODE
	  FROM PROVIDER.PRV414_RAW
	  WHERE SUBSTRING(RECORD,1,1) = '2'
	)

	SELECT HEADER.PROMISEPROV,
	HEADER.SERVICELOC,
	HEADER.BEGINDATE,
	HEADER.ENDDATE,
	HEADER.PROVNAME,
	HEADER.IRSSSN,
	HEADER.IRSSSNIND,
	HEADER.MEDICARE,
	HEADER.COUNTY,
	HEADER.ADDR_1,
	HEADER.ADDR_2,
	HEADER.CITY,
	HEADER.STATE,
	HEADER.ZIP,
	HEADER.ZIPEXT,
	HEADER.PHONE,
	HEADER.DEA,
	HEADER.UPIN,
	HEADER.MAMISID,
	COALESCE(DETAIL.PROVTYPE,'') AS PROVTYPE,
	COALESCE(DETAIL.SPECCODE,'') AS SPECCODE,
	COALESCE(DETAIL.SPECCODEBEGIN,'') AS SPECCODEBEGIN,
	COALESCE(DETAIL.SPECCODEEND,'') AS SPECCODEEND,
	COALESCE(DETAIL.LICENSE,'') AS LICENSE,
	COALESCE(DETAIL.LICENSEEND,'') AS LICENSEEND,
	COALESCE(DETAIL.PRACTYPE,'') AS PRACTYPE,
	COALESCE(DETAIL.MEDICALDEG,'') AS MEDICALDEG,
	DETAIL.STATUSCODE

	FROM DETAIL
	INNER JOIN HEADER
	ON HEADER.PROMISEPROV = DETAIL.PROMISEPROV
	AND HEADER.SERVICELOC = DETAIL.SERVICELOC
);
