CREATE OR REPLACE VIEW PROVIDER.AFFILIATIONS_NON_PARTICIPANT_VW
COMMENT = 'stores all provider affiliations including for non-participant providers'
AS
SELECT
	METADATA$FILE_LAST_MODIFIED AS LOAD_TIME,
	METADATA$FILENAME AS FILENAME,
	$1 AS PROVIDER_KEY,
	$2 AS FACILITY_NAME,
	$3 AS ADMIT_HOSP_OWNED_STATUS,
	$4 AS FACILITY_PROVIDER_KEY,
	$5 AS PROVIDER_ADDRESS_RELATIONSHIP_KEY,
	$6 AS PROVIDER_DIRECTORY_H2_PRODUCT_NAME,
	$7 AS PROVIDER_DIRECTORY_H2_SUB_PRODUCT_NAME,
	$8 AS PROVIDER_DIRECTORY_H2_SUB_PRODUCT_KEY,
	$9 AS H2_ENTITY_NAME ,
	$10 AS PRODUCT_KEY ,
	$11 AS PRODUCT_TYPE_KEY ,
	$12 AS PROVIDER_DIRECTORY_NETWORK_ID ,
	$13 AS LEVELED_SUB_PRODUCT_INDICATOR ,
	$14 AS CONTRACT_LEVEL_CODE
FROM @util.HPDSDATALAKE_DBEXTRACT_IDAP_LAKE/providerdirectory/dbo (file_format => UTIL.DB_EXTRACT_FILE_FORMAT)
WHERE FILENAME LIKE '%PROVIDERAFFILIATIONS_NONPAR.TXT';