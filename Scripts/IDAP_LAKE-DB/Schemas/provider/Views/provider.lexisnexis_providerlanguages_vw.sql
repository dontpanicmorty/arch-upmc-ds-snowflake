CREATE OR REPLACE VIEW PROVIDER.LEXISNEXIS_PROVIDERLANGUAGES_VW
AS
SELECT 
	METADATA$FILE_LAST_MODIFIED AS LOAD_TIME,
	METADATA$FILENAME AS FILENAME,
	$1 AS PAYER_PROVIDER_ID, 
	$2 AS ATTESTED_ENTITY_UNIQUE_ID, 
	$3 AS LNPID, 
	$4 AS PROVIDER_LANGUAGE, 
	$5 AS PROVIDER_LANGUAGE_VERIFIED, 
	$6 AS USER_DEF_01, 
	$7 AS USER_DEF_02, 
	$8 AS USER_DEF_03, 
	$9 AS USER_DEF_04, 
	$10 AS USER_DEF_05, 
	$11 AS USER_DEF_06, 
	$12 AS USER_DEF_07, 
	$13 AS USER_DEF_08, 
	$14 AS USER_DEF_09, 
	$15 AS USER_DEF_10, 
	$16 AS STATUS, 
	$17 AS ATTESTED_DATE
FROM @UTIL.HPDSDATALAKE_IDAPLAKE/provider/lexisnexis (file_format => PROVIDER.LEXIS_NEXIS_FILE_FORMAT)
WHERE FILENAME LIKE '%0000010000010001-provider-LexisNexis__ProviderLanguages_%.txt%'
;