CREATE OR REPLACE VIEW PROVIDER.LEXISNEXIS_ATTESTATIONSUMMARY_VW
AS
SELECT 
	METADATA$FILE_LAST_MODIFIED AS LOAD_TIME,
	METADATA$FILENAME AS FILENAME,
	$1 AS PAYER_PROVIDER_ID, 
	$2 AS PROVIDER_NPI_ID, 
	$3 AS ENTITY_UNIQUE_ID, 
	$4 AS LNPID, 
	$5 AS ATTESTED_DATE, 
	$6 AS USER_ATTESTED, 
	$7 AS METHOD, 
	$8 AS CONTACT_TITLE, 
	$9 AS CONTACT_NAME, 
	$10 AS CONTACT_EMAIL, 
	$11 AS CONTACT_PHONE
FROM @UTIL.HPDSDATALAKE_IDAPLAKE/provider/lexisnexis (file_format => PROVIDER.LEXIS_NEXIS_FILE_FORMAT)
WHERE FILENAME LIKE '%0000010000010001-provider-LexisNexis__AttestationSummary_%.txt%'
;