CREATE OR REPLACE VIEW PROVIDER.FACILITY_WHITELIST_CODE_KEY_VW
COMMENT='File provided by business'
AS
WITH LATEST_FILE AS (
    SELECT
        METADATA$FILENAME AS FILENAME,
        METADATA$FILE_LAST_MODIFIED AS DATE_UPDATED
    FROM
        @UTIL.HPDSDATALAKE_IDAPLAKE/provider/facility_whitelist_code_key/
    QUALIFY
        ROW_NUMBER() OVER (ORDER BY DATE_UPDATED DESC) = 1
),
DATA AS (
    SELECT
        METADATA$FILENAME AS FILENAME,
        METADATA$FILE_LAST_MODIFIED AS DATE_UPDATED,
        $1 AS MAPPED_KEY,
        $2 AS ENCOUNTER_ID,
        $3 AS SOURCE_ENCOUNTER_NAME,
        $4 AS DISPLAY_NAME,
        $5 AS OOP_POS,
        $6 AS KEY
    FROM
        @UTIL.HPDSDATALAKE_IDAPLAKE/provider/facility_whitelist_code_key/
        (FILE_FORMAT => 'PROVIDER.TSV_FILE_FORMAT')
)
SELECT *
FROM (
    SELECT
        MAPPED_KEY,
        ENCOUNTER_ID,
        SOURCE_ENCOUNTER_NAME,
        DISPLAY_NAME,
        OOP_POS,
        KEY,
        DATE_UPDATED,
        FILENAME,
        ROW_NUMBER() OVER (PARTITION BY KEY ORDER BY DATE_UPDATED DESC) AS RN
    FROM
        DATA
)
WHERE
    RN = 1
;
