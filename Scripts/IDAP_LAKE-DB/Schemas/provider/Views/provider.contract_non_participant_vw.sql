CREATE OR REPLACE VIEW PROVIDER.CONTRACT_NON_PARTICIPANT_VW
COMMENT = 'all contracts including non-participant providers'
AS
SELECT
    METADATA$FILE_LAST_MODIFIED AS LOAD_TIME,
	METADATA$FILENAME AS FILENAME,
	$1 AS PROVIDER_ADDRESS_RELATIONSHIP_KEY,
	$2 AS PRODUCT_KEY,
	$3 AS PRODUCT_NAME,
	$4 AS PRODUCT_TYPE_KEY,
	$5 AS PRODUCT_TYPE_NAME,
	$6 AS CONTRACT_LEVEL_CODE,
	$7 AS ACTIVE_INDICATOR,
	$8 AS PROVIDER_CONTRACT_ROLE_TYPE,
	$9 AS ACCEPTING_NEW_PATIENTS_INDICATOR,
	$10 AS PROVIDER_DIRECTORY_RESTRICTION_DESCRIPTION,
	$11 AS RESTRICTION_RANK_NUMBER,
	$12 AS H2_ENTITY_NAME,
	$13 AS CARE_TYPE_NAME,
	$14 AS COVERAGE_TYPE_NAME,
	$15 AS LEVELED_SUB_PRODUCT_INDICATOR,
	$16 AS CONTRACT_MODEL_NAME,
	$17 AS ALTERNATE_NETWORK_NAME,
	$18 AS PROVIDER_DIRECTORY_H2_PRODUCT_NAME,
	$19 AS PROVIDER_DIRECTORY_H2_PRODUCT_KEY,
	$20 AS PROVIDER_DIRECTORY_H2_SUB_PRODUCT_NAME,
	$21 AS PROVIDER_DIRECTORY_H2_SUB_PRODUCT_KEY,
	$22 AS PROVIDER_DIRECTORY_NETWORK_ID
FROM @util.HPDSDATALAKE_DBEXTRACT_IDAP_LAKE/providerdirectory/dbo (file_format => UTIL.DB_EXTRACT_FILE_FORMAT)
WHERE FILENAME LIKE '%PROVIDERSCONTRACT_NONPAR.TXT';