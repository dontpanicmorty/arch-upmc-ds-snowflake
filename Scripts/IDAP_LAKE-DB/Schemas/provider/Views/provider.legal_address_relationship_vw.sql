CREATE OR REPLACE VIEW PROVIDER.LEGAL_ADDRESS_RELATIONSHIP_VW
COMMENT = 'Stores Legal/Billing info for provider addresses'
AS
SELECT
	METADATA$FILE_LAST_MODIFIED AS LOAD_TIME,
	METADATA$FILENAME AS FILENAME,
	$1 AS LEGAL_ADDRESS_RELATIONSHIP_KEY,
	$2 AS PROVIDER_KEY,
	$3 AS LEGAL_KEY,
	$4 AS LEGAL_OFFICE_NAME,
	$5 AS LEGAL_ADDRESS1,
	$6 AS LEGAL_ADDRESS2,
	$7 AS LEGAL_CITY,
	$8 AS LEGAL_STATE,
	$9 AS LEGAL_ZIP
FROM @util.HPDSDATALAKE_DBEXTRACT_IDAP_LAKE/providerods/dbo (file_format => UTIL.DB_EXTRACT_FILE_FORMAT)
WHERE FILENAME LIKE '%LEGALADDRESSREL.TXT';
