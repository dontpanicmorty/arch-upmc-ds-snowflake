!set variable_substitution=true;
create or replace view MARKETING.MEMBER_MATCHING_SOURCE_VW(
	MASTER_MEMBER_ID,
	AGE,
	FIRST_NAME,
	LAST_NAME,
	MIDDLE_INITIAL,
	MMI_STATUS,
	VERIFIED_ADDRESSLINE1_TEXT,
	VERIFIED_ADDRESSLINE2_TEXT,
	ZIP
) COMMENT='Member view with data format as source for matching'
 as
SELECT 
    MASTER_MEMBER_ID,
    AGE,
    FIRST_NAME,
    LAST_NAME,
    MIDDLE_INITIAL,
    MMI_STATUS,
    VERIFIED_ADDRESSLINE1_TEXT,
    VERIFIED_ADDRESSLINE2_TEXT,
    ZIP
FROM (
    SELECT
        INDIVIDUAL_VW.MASTER_MEMBER_ID AS MASTER_MEMBER_ID,
        INDIVIDUAL_VW.AGE AS AGE,
        UPPER(TRIM(INDIVIDUAL_VW.FIRST_NAME)) AS FIRST_NAME,
        UPPER(TRIM(INDIVIDUAL_VW.LAST_NAME)) AS LAST_NAME,
        LEFT(UPPER(TRIM(COALESCE(INDIVIDUAL_VW.MIDDLE_INITIAL, ''))), 1) AS MIDDLE_INITIAL,
        INDIVIDUAL_VW.MEMBERSHIP_STATUS AS MMI_STATUS,
        UPPER(TRIM(COALESCE(DIM_MEMBER_ADDRESS.VERIFIED_ADDRESSLINE1_TEXT, ''))) AS VERIFIED_ADDRESSLINE1_TEXT,
        UPPER(TRIM(COALESCE(DIM_MEMBER_ADDRESS.VERIFIED_ADDRESSLINE2_TEXT, ''))) AS VERIFIED_ADDRESSLINE2_TEXT,
        TRIM(COALESCE(DIM_MEMBER_ADDRESS.VERIFIED_ZIPCODE5_NBR, '')) AS ZIP
    FROM MARKETING_EDS.INDIVIDUAL_VW
    LEFT JOIN &{IDAP}.DIMDATA.DIM_MEMBER_ADDRESS
        ON INDIVIDUAL_VW.ADDRESS_KEY = DIM_MEMBER_ADDRESS.DIM_MEMBER_ADDRESS_KEY
    WHERE INDIVIDUAL_VW.FIRST_NAME IS NOT NULL
    AND INDIVIDUAL_VW.LAST_NAME IS NOT NULL
    AND TRIM(INDIVIDUAL_VW.FIRST_NAME) != ''
    AND TRIM(INDIVIDUAL_VW.LAST_NAME) != ''
)
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY MASTER_MEMBER_ID
    ORDER BY MASTER_MEMBER_ID
) = 1
;

!set variable_substitution=false;