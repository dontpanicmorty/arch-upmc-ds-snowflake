create or replace view MARKETING.ACXIOM_MEMBER_MATCHING_LEVEL_2_SELECT_VW(
	ACXIOM_PERSON_ID,
	MASTER_MEMBER_ID,
	MATCH_TYPE_ID,
	MATCH_TYPE_NAME,
	MMI_STATUS
) as
WITH MEMBER_MATCHING_SOURCE_VW AS (SELECT * FROM MARKETING.MEMBER_MATCHING_SOURCE_VW)
SELECT
DISTINCT
    ACXIOM_MATCHING_SOURCE_VW.ACXIOM_PERSON_ID,
    COALESCE(ACTIVE.MASTER_MEMBER_ID, FUTURE.MASTER_MEMBER_ID, INACTIVE.MASTER_MEMBER_ID) AS MASTER_MEMBER_ID,
    2 AS MATCH_TYPE_ID,
    CASE
        WHEN COUNT(DISTINCT COALESCE(ACTIVE.MASTER_MEMBER_ID, FUTURE.MASTER_MEMBER_ID, INACTIVE.MASTER_MEMBER_ID)) OVER (PARTITION BY ACXIOM_MATCHING_SOURCE_VW.ACXIOM_PERSON_ID) > 1 OR COUNT(DISTINCT ACXIOM_MATCHING_SOURCE_VW.ACXIOM_PERSON_ID) OVER (PARTITION BY COALESCE(ACTIVE.MASTER_MEMBER_ID, FUTURE.MASTER_MEMBER_ID, INACTIVE.MASTER_MEMBER_ID)) > 1 THEN 'MULTIPLE'
        ELSE 'CLEAN'
    END AS MATCH_TYPE_NAME,
    COALESCE(ACTIVE.MMI_STATUS, FUTURE.MMI_STATUS, INACTIVE.MMI_STATUS) AS MMI_STATUS
FROM MARKETING.ACXIOM_MATCHING_SOURCE_VW
LEFT JOIN (SELECT * FROM MEMBER_MATCHING_SOURCE_VW WHERE UPPER(MMI_STATUS) = 'ACTIVE') AS ACTIVE ON 1 = 1
    AND ACXIOM_MATCHING_SOURCE_VW.FIRST_NAME = ACTIVE.FIRST_NAME
    AND ACXIOM_MATCHING_SOURCE_VW.MIDDLE_INITIAL = ACTIVE.MIDDLE_INITIAL
    AND ACXIOM_MATCHING_SOURCE_VW.LAST_NAME = ACTIVE.LAST_NAME
    AND ACXIOM_MATCHING_SOURCE_VW.DELIVERY_LINE_1_SMARTY = ACTIVE.VERIFIED_ADDRESSLINE1_TEXT
    AND ACXIOM_MATCHING_SOURCE_VW.DELIVERY_LINE_2_SMARTY = ACTIVE.VERIFIED_ADDRESSLINE2_TEXT
    AND ACXIOM_MATCHING_SOURCE_VW.ZIP = ACTIVE.ZIP
LEFT JOIN (SELECT * FROM MEMBER_MATCHING_SOURCE_VW WHERE UPPER(MMI_STATUS) = 'FUTURE') AS FUTURE ON 1 = 1
    AND ACXIOM_MATCHING_SOURCE_VW.FIRST_NAME = FUTURE.FIRST_NAME
    AND ACXIOM_MATCHING_SOURCE_VW.MIDDLE_INITIAL = FUTURE.MIDDLE_INITIAL
    AND ACXIOM_MATCHING_SOURCE_VW.LAST_NAME = FUTURE.LAST_NAME
    AND ACXIOM_MATCHING_SOURCE_VW.DELIVERY_LINE_1_SMARTY = FUTURE.VERIFIED_ADDRESSLINE1_TEXT
    AND ACXIOM_MATCHING_SOURCE_VW.DELIVERY_LINE_2_SMARTY = FUTURE.VERIFIED_ADDRESSLINE2_TEXT
    AND ACXIOM_MATCHING_SOURCE_VW.ZIP = FUTURE.ZIP
LEFT JOIN (SELECT * FROM MEMBER_MATCHING_SOURCE_VW WHERE UPPER(MMI_STATUS) = 'INACTIVE') AS INACTIVE ON 1 = 1
    AND ACXIOM_MATCHING_SOURCE_VW.FIRST_NAME = INACTIVE.FIRST_NAME
    AND ACXIOM_MATCHING_SOURCE_VW.MIDDLE_INITIAL = INACTIVE.MIDDLE_INITIAL
    AND ACXIOM_MATCHING_SOURCE_VW.LAST_NAME = INACTIVE.LAST_NAME
    AND ACXIOM_MATCHING_SOURCE_VW.DELIVERY_LINE_1_SMARTY = INACTIVE.VERIFIED_ADDRESSLINE1_TEXT
    AND ACXIOM_MATCHING_SOURCE_VW.DELIVERY_LINE_2_SMARTY = INACTIVE.VERIFIED_ADDRESSLINE2_TEXT
    AND ACXIOM_MATCHING_SOURCE_VW.ZIP = INACTIVE.ZIP
WHERE 1 = 1
    AND COALESCE(ACTIVE.MASTER_MEMBER_ID, FUTURE.MASTER_MEMBER_ID, INACTIVE.MASTER_MEMBER_ID) IS NOT NULL
;