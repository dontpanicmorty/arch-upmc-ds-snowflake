create or replace view MARKETING.ACXIOM_MEMBER_MATCHING_LEVEL_13_UNMATCHED_SELECT_VW(
	ACXIOM_PERSON_ID,
	MASTER_MEMBER_ID,
	MMI_STATUS,
	MATCH_TYPE_ID,
	MATCH_TYPE_NAME
) as
SELECT 
    ACXIOM_MATCHING_SOURCE_VW.ACXIOM_PERSON_ID
