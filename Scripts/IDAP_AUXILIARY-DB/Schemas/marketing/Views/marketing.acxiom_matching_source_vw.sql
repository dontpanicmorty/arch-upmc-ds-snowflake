!set variable_substitution=true;
create or replace view MARKETING.ACXIOM_MATCHING_SOURCE_VW(
	ACXIOM_PERSON_ID,
	AGE,
	FIRST_NAME,
	LAST_NAME,
	MIDDLE_INITIAL,
	DELIVERY_LINE_1_SMARTY,
	DELIVERY_LINE_2_SMARTY,
	ZIP
) COMMENT='Acxiom view with data format as source for matching'
 as
SELECT
    ACXIOM_PERSON_ID,
    AGE,
    FIRST_NAME,
    LAST_NAME,
    MIDDLE_INITIAL,
    DELIVERY_LINE_1_SMARTY,
    DELIVERY_LINE_2_SMARTY,
    ZIP
FROM (
    SELECT
        FORMATTED_PROSPECTS_18_65.ENTITY_REALID_PERSON_ID AS ACXIOM_PERSON_ID,
        TO_NUMBER(
            NULLIF(
                REGEXP_REPLACE(
                    FORMATTED_PROSPECTS_18_65."Age in One-Year Increments - Person",
                    '[^0-9]',
                    ''
                ),
                ''
            )
        ) AS AGE,
        UPPER(TRIM(FORMATTED_PROSPECTS_18_65.INPUT_FIRST_NAME_3131)) AS FIRST_NAME,
        UPPER(TRIM(FORMATTED_PROSPECTS_18_65.INPUT_LAST_NAME_3131)) AS LAST_NAME,
        UPPER(TRIM(COALESCE(FORMATTED_PROSPECTS_18_65.INPUT_MIDDLE_INITIAL_3131, ''))) AS MIDDLE_INITIAL,
        UPPER(TRIM(COALESCE(PROSPECT_ADDRESS.DELIVERY_LINE_1_SMARTY, ''))) AS DELIVERY_LINE_1_SMARTY,
        UPPER(TRIM(COALESCE(PROSPECT_ADDRESS.DELIVERY_LINE_2_SMARTY, ''))) AS DELIVERY_LINE_2_SMARTY,
        TRIM(COALESCE(PROSPECT_ADDRESS.ZIPCODE_SMARTY, '')) AS ZIP
    FROM &{IDAP_LAKE}.ACXIOMDB.FORMATTED_PROSPECTS_18_65
    LEFT JOIN &{IDAP_LAKE}.MARKETING_PROSPECTS.PROSPECT_ADDRESS
        ON FORMATTED_PROSPECTS_18_65.ENTITY_REALID_PLACE_ID = PROSPECT_ADDRESS.ENTITY_REALID_PLACE_ID

    UNION ALL

    SELECT
        FORMATTED_PROSPECTS_66_PLUS.ENTITY_REALID_PERSON_ID AS ACXIOM_PERSON_ID,
        TO_NUMBER(
            NULLIF(
                REGEXP_REPLACE(
                    FORMATTED_PROSPECTS_66_PLUS."Age in One-Year Increments - Person",
                    '[^0-9]',
                    ''
                ),
                ''
            )
        ) AS AGE,
        UPPER(TRIM(FORMATTED_PROSPECTS_66_PLUS.INPUT_FIRST_NAME_3131)) AS FIRST_NAME,
        UPPER(TRIM(FORMATTED_PROSPECTS_66_PLUS.INPUT_LAST_NAME_3131)) AS LAST_NAME,
        UPPER(TRIM(COALESCE(FORMATTED_PROSPECTS_66_PLUS.INPUT_MIDDLE_INITIAL_3131, ''))) AS MIDDLE_INITIAL,
        UPPER(TRIM(COALESCE(PROSPECT_ADDRESS.DELIVERY_LINE_1_SMARTY, ''))) AS DELIVERY_LINE_1_SMARTY,
        UPPER(TRIM(COALESCE(PROSPECT_ADDRESS.DELIVERY_LINE_2_SMARTY, ''))) AS DELIVERY_LINE_2_SMARTY,
        TRIM(COALESCE(PROSPECT_ADDRESS.ZIPCODE_SMARTY, '')) AS ZIP
    FROM &{IDAP_LAKE}.ACXIOMDB.FORMATTED_PROSPECTS_66_PLUS
    LEFT JOIN &{IDAP_LAKE}.MARKETING_PROSPECTS.PROSPECT_ADDRESS
        ON FORMATTED_PROSPECTS_66_PLUS.ENTITY_REALID_PLACE_ID = PROSPECT_ADDRESS.ENTITY_REALID_PLACE_ID
)
WHERE FIRST_NAME IS NOT NULL
  AND LAST_NAME IS NOT NULL
  AND TRIM(FIRST_NAME) != ''
  AND TRIM(LAST_NAME) != ''
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY ACXIOM_PERSON_ID
    ORDER BY ACXIOM_PERSON_ID
) = 1
;
!set variable_substitution=false;