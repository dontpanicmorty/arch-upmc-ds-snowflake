CREATE OR REPLACE VIEW PROVIDER_ATTESTATION.LEXIS_NEXIS_CACTUS_PRACTICE_LOCATION_HOURS_VW
(
  PAYER_PROVIDER_ID
, PROVIDER_NAME
, ANCILARY_PROVIDER_IND
, ADDRESS_ID
, PAYER_ADDRESS_ID
, PRACTICE_NAME
, PROVIDER_CATEGORY
, PHYSICIAN_HOSPITAL_ORGANIZATION
, TAX_ID_NBR
, UPMC_OWNERSHIP_DESC
, CHANGE_TYPE
, AREA_AFFECTED
, CHANGE_REQUIRED
, OLD_VALUE
, NEW_VALUE
, ATTESTED_USER
, ATTESTED_DATE
, ATTESTED_PHONE_NBR
, ATTESTED_EMAIL
, PHYSICIAN_ACCOUNT_EXECUTIVE
, PCP_OFFICE_IND
, DUAL_CREDENTIALED_IND
, CREATED_ON
, SPECIALTY_NAME
, SOURCE_FILE_NAME
, OLD_NEW_PERCENT_MATCH
, ADDITIONAL_PRACTICE_RESTRICTIONS_VERIFIED
, CHANGE_TYPE_CLASSIFICATION
) 
 COMMENT = 'LEXIS NEXIS CACTUS PRACTICE LEVEL LOCATION HOURS VIEW' AS 
 (SELECT E.PAYER_PROVIDER_ID
     , E.PROVIDERNAME
     , E.ANCILLARY_PROVIDER_IND
     , E.ADDRESS_ID
     , E.PAYER_ADDRESSID
     , E.PRACTICE_NAME
     , E.USER_DEF_01
     , E.USER_DEF_02
     , E.TAX_ID
     , E.UPMC_OWNERSHIP_DESC
     , E.CHANGE_TYPE
     , E.AREA_AFFECTED
     , E.CHANGE_REQUIRED
     , E.OLD_VALUE
     , E.NEW_VALUE
     , E.ATTESTED_USER
     , E.ATTESTED_DATE
     , E.CONTACT_PHONE
     , E.CONTACT_EMAIL 
     , E.PHYSICIAN_ACCOUNT_EXECUTIVE
     , E.PCP_OFFICE_IND
     , E.DUALCREDENTIALEDIND
     , E.LOAD_TIME
     , E.SPECIALTY_NAME
     , E.FILENAME
     , E.OLD_NEW_PERCENT_MATCH,
     E.ADDITIONAL_PRACTICE_RESTRICTIONS_VERIFIED,
     CASE 
      WHEN COUNT(DISTINCT E.OLD_VALUE) OVER(PARTITION BY E.ADDRESS_ID) IN (0,1) AND COUNT(DISTINCT E.NEW_VALUE) OVER(PARTITION BY E.ADDRESS_ID) IN (0,1) THEN 
        CASE WHEN ROW_NUMBER() OVER(PARTITION BY E.ADDRESS_ID ORDER BY E.ADDRESS_ID) = 1 THEN 'Accepted' 
          ELSE 'Consolidated' 
        END ELSE 'Needs Reviewed'
     END AS CHANGETYPECLASSIFICATION
 FROM (SELECT DISTINCT B.PAYER_PROVIDER_ID
        , COALESCE(NAME_PREFIX,'') || ' ' || COALESCE(FIRST_NAME,'') || ' ' || COALESCE(MIDDLE_NAME,'') || ' ' || COALESCE(LAST_NAME,'') || ' ' || COALESCE(NAME_SUFFIX,'') || ' ' || COALESCE(PROF_SUFFIX,'') AS PROVIDERNAME
        , PA.ANCILLARY_PROVIDER_IND
        , B.USER_DEF_06 AS ADDRESS_ID
        , B.PAYER_ADDRESSID
        , CASE WHEN B.PRACTICE_NAME = '' OR B.PRACTICE_NAME IS NULL THEN B.PRACTICE_NAME_VERIFIED ELSE B.PRACTICE_NAME END AS PRACTICE_NAME
        , B.USER_DEF_01
        , B.USER_DEF_02
        , CASE WHEN D.TAX_ID = '' OR D.TAX_ID IS NULL THEN D.TAX_ID_VERIFIED ELSE D.TAX_ID END AS TAX_ID
        , PA.PROVIDER_OWNERSHIP_STATUS_SOURCE_DESC AS UPMC_OWNERSHIP_DESC
        , 'U - Update' AS CHANGE_TYPE
        , 'Practice Location Hours' as AREA_AFFECTED
        , 'Suppress Provider' AS CHANGE_REQUIRED
        , CASE 
            WHEN PROVIDER_MON_HOURS IS NULL THEN NULL 
            ELSE 'Provider Mon Hours: '||COALESCE(B.PROVIDER_MON_HOURS,'') ||' ' 
          END || 
          CASE 
            WHEN PROVIDER_TUES_HOURS IS NULL THEN NULL 
            ELSE 'Provider Tues Hours: '||COALESCE(B.PROVIDER_TUES_HOURS,'') || ' ' 
          END ||
          CASE 
            WHEN PROVIDER_WEDS_HOURS IS NULL THEN NULL 
            ELSE 'Provider Wed Hours: '||COALESCE(B.PROVIDER_WEDS_HOURS,'') ||' ' 
          END ||
          CASE 
            WHEN PROVIDER_THURS_HOURS IS NULL 
            THEN NULL ELSE 'Provider Thurs Hours: '||COALESCE(B.PROVIDER_THURS_HOURS,'') ||' ' 
          END ||
          CASE 
            WHEN PROVIDER_FRI_HOURS IS NULL THEN NULL 
            ELSE 'Provider Fri Hours: '||COALESCE(B.PROVIDER_FRI_HOURS ,'') ||' ' 
          END ||
          CASE 
            WHEN PROVIDER_SAT_HOURS IS NULL THEN NULL 
            ELSE 'Provider Sat Hours: '||COALESCE(B.PROVIDER_SAT_HOURS,'') ||' ' 
          END ||
          CASE 
            WHEN PROVIDER_SUN_HOURS IS NULL THEN NULL 
            ELSE 'Provider Sun Hours: '||COALESCE(B.PROVIDER_SUN_HOURS ,'')
          END AS OLD_VALUE,
          CASE 
            WHEN PROVIDER_MON_HOURS_VERIFIED IS NULL THEN '' 
            WHEN PROVIDER_MON_HOURS_VERIFIED = 'Not Available' THEN '' 
            ELSE 'Provider Mon Hours Verified: '||COALESCE(B.PROVIDER_MON_HOURS_VERIFIED,'')||' ' 
          END ||
          CASE WHEN PROVIDER_TUES_HOURS_VERIFIED IS NULL THEN '' 
              WHEN PROVIDER_TUES_HOURS_VERIFIED = 'Not Available' THEN '' 
              ELSE 'Provider Tues Hours Verified: '||COALESCE(B.PROVIDER_TUES_HOURS_VERIFIED,'') || ' ' 
          END||
          CASE WHEN PROVIDER_WEDS_HOURS_VERIFIED IS NULL THEN '' 
              WHEN PROVIDER_WEDS_HOURS_VERIFIED = 'Not Available' THEN '' 
              ELSE 'Provider Wed Hours Verified: '||COALESCE(b.Provider_Weds_Hours_Verified,'') ||' ' 
          END||
          CASE WHEN PROVIDER_THURS_HOURS_VERIFIED IS NULL THEN '' 
              WHEN PROVIDER_THURS_HOURS_VERIFIED = 'NOT Available' THEN '' 
              ELSE 'Provider Thurs Hours Verified: '||COALESCE(B.PROVIDER_THURS_HOURS_VERIFIED,'') ||' ' 
          END||
          CASE WHEN PROVIDER_FRI_HOURS_VERIFIED IS NULL THEN '' 
              WHEN PROVIDER_FRI_HOURS_VERIFIED = 'Not Available' THEN '' 
              ELSE 'Provider Fri Hours Verified: '||COALESCE(B.PROVIDER_FRI_HOURS_VERIFIED,'') ||' ' 
          END ||
          CASE WHEN PROVIDER_SAT_HOURS_VERIFIED IS NULL THEN '' 
              WHEN PROVIDER_SAT_HOURS_VERIFIED = 'Not Available' THEN '' 
              ELSE 'Provider Sat Hours Verified: '||COALESCE(B.PROVIDER_SAT_HOURS_VERIFIED,'') ||' ' 
          END ||
          CASE WHEN PROVIDER_SUN_HOURS_VERIFIED IS NULL THEN '' 
              WHEN PROVIDER_SUN_HOURS_VERIFIED = 'Not Available' THEN '' 
              ELSE 'Provider Sun Hours Verified: '||COALESCE(B.PROVIDER_SUN_HOURS_VERIFIED,'')
          END AS NEW_VALUE
        , G.CONTACT_NAME AS ATTESTED_USER
        , DATE(G.ATTESTED_DATE) AS ATTESTED_DATE
        , G.CONTACT_PHONE
        , G.CONTACT_EMAIL 
        , SA.PAE AS PHYSICIAN_ACCOUNT_EXECUTIVE
        , CASE WHEN PA.MA_SUPER_PCP_IND = 'Y' THEN 'Y' ELSE 'N' END AS PCP_OFFICE_IND
        , CASE WHEN PA.MA_SUPER_PCP_IND = 'Y' THEN 'Y' ELSE 'N' END AS DUALCREDENTIALEDIND
        , B.LOAD_TIME
        , CASE WHEN PA.PRIMARY_SPECIALTY_IND = 'Y' THEN  PA.SPECIALTY_NAME ELSE 'No Primary' END AS SPECIALTY_NAME
        , B.FILENAME
        , NULL AS OLD_NEW_PERCENT_MATCH
        , B.ADDITIONAL_PRACTICE_RESTRICTIONS_VERIFIED
FROM (
    SELECT PAYER_PROVIDER_ID
    , STATUS
    , ATTESTED_ENTITY_UNIQUE_ID
    , PAYER_ADDRESSID
    , (CASE 
        WHEN PROVIDER_MON_HOURS_VERIFIED IS NULL THEN 0 
        WHEN PROVIDER_MON_HOURS_VERIFIED = 'Not Available' THEN 0 
        ELSE TIMEDIFF(MINUTE, TRY_TO_TIME(REGEXP_SUBSTR(PROVIDER_MON_HOURS_VERIFIED, '(\\d{1,2}:\\d{2})')), TRY_TO_TIME(REGEXP_SUBSTR(PROVIDER_MON_HOURS_VERIFIED, '\\d{2}:\\d{2}$'))) /60 
       END + 
       CASE 
        WHEN PROVIDER_TUES_HOURS_VERIFIED IS NULL THEN 0 
        WHEN PROVIDER_TUES_HOURS_VERIFIED = 'Not Available' THEN 0 
        ELSE TIMEDIFF(MINUTE, TRY_TO_TIME(REGEXP_SUBSTR(PROVIDER_TUES_HOURS_VERIFIED, '(\\d{1,2}:\\d{2})')), TRY_TO_TIME(REGEXP_SUBSTR(PROVIDER_TUES_HOURS_VERIFIED, '\\d{2}:\\d{2}$'))) /60 
      END +
      CASE 
        WHEN PROVIDER_WEDS_HOURS_VERIFIED IS NULL THEN 0 
        WHEN PROVIDER_WEDS_HOURS_VERIFIED = 'Not Available' THEN 0 
        ELSE TIMEDIFF(MINUTE, TRY_TO_TIME(REGEXP_SUBSTR(PROVIDER_WEDS_HOURS_VERIFIED, '(\\d{1,2}:\\d{2})')), TRY_TO_TIME(REGEXP_SUBSTR(PROVIDER_WEDS_HOURS_VERIFIED, '\\d{2}:\\d{2}$'))) /60 
      END +
      CASE 
        WHEN PROVIDER_THURS_HOURS_VERIFIED IS NULL THEN 0 
        WHEN PROVIDER_THURS_HOURS_VERIFIED = 'Not Available' THEN 0 
        ELSE TIMEDIFF(MINUTE, TRY_TO_TIME(REGEXP_SUBSTR(PROVIDER_THURS_HOURS_VERIFIED, '(\\d{1,2}:\\d{2})')), TRY_TO_TIME(REGEXP_SUBSTR(PROVIDER_THURS_HOURS_VERIFIED, '\\d{2}:\\d{2}$'))) /60 
      END +
      CASE 
        WHEN PROVIDER_FRI_HOURS_VERIFIED IS NULL THEN 0 
        WHEN PROVIDER_FRI_HOURS_VERIFIED = 'Not Available' THEN 0 
        ELSE TIMEDIFF(MINUTE, TRY_TO_TIME(REGEXP_SUBSTR(PROVIDER_FRI_HOURS_VERIFIED, '(\\d{1,2}:\\d{2})')), TRY_TO_TIME(REGEXP_SUBSTR(PROVIDER_FRI_HOURS_VERIFIED, '\\d{2}:\\d{2}$'))) /60 
      END +
      CASE 
        WHEN PROVIDER_SAT_HOURS_VERIFIED IS NULL THEN 0 
        WHEN PROVIDER_SAT_HOURS_VERIFIED = 'Not Available' THEN 0 
        ELSE TIMEDIFF(MINUTE, TRY_TO_TIME(REGEXP_SUBSTR(PROVIDER_SAT_HOURS_VERIFIED, '(\\d{1,2}:\\d{2})')), TRY_TO_TIME(REGEXP_SUBSTR(PROVIDER_SAT_HOURS_VERIFIED, '\\d{2}:\\d{2}$'))) /60 
      END +
      CASE 
		WHEN PROVIDER_SUN_HOURS_VERIFIED IS NULL THEN 0 
		WHEN PROVIDER_SUN_HOURS_VERIFIED = 'Not Available' THEN 0 
		ELSE TIMEDIFF(MINUTE, TRY_TO_TIME(REGEXP_SUBSTR(PROVIDER_SUN_HOURS_VERIFIED, '(\\d{1,2}:\\d{2})')), TRY_TO_TIME(REGEXP_SUBSTR(PROVIDER_SUN_HOURS_VERIFIED, '\\d{2}:\\d{2}$'))) /60 
      END) AS NUMBER_OF_HOURS
    FROM &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PRACTICELOCATIONS_VW
    WHERE STATUS ='U' 
    AND COALESCE(PROVIDER_MON_HOURS_VERIFIED,'')||COALESCE(PROVIDER_TUES_HOURS_VERIFIED,'')||COALESCE(PROVIDER_WEDS_HOURS_VERIFIED,'')||COALESCE(PROVIDER_THURS_HOURS_VERIFIED,'')||COALESCE(PROVIDER_FRI_HOURS_VERIFIED,'')||COALESCE(PROVIDER_SAT_HOURS_VERIFIED,'')||COALESCE(PROVIDER_SUN_HOURS_VERIFIED,'')<> COALESCE(PROVIDER_MON_HOURS,'')||COALESCE(PROVIDER_TUES_HOURS,'')||COALESCE(PROVIDER_WEDS_HOURS,'')||COALESCE(PROVIDER_THURS_HOURS,'')||COALESCE(PROVIDER_FRI_HOURS,'')||COALESCE(PROVIDER_SAT_HOURS,'')||COALESCE(PROVIDER_SUN_HOURS,'') 
    AND COALESCE(PROVIDER_MON_HOURS_VERIFIED,'')||COALESCE(PROVIDER_TUES_HOURS_VERIFIED,'')||COALESCE(PROVIDER_WEDS_HOURS_VERIFIED,'')||COALESCE(PROVIDER_THURS_HOURS_VERIFIED,'')||COALESCE(PROVIDER_FRI_HOURS_VERIFIED,'')||COALESCE(PROVIDER_SAT_HOURS_VERIFIED,'')||COALESCE(PROVIDER_SUN_HOURS_VERIFIED,'') IS NOT NULL
    GROUP BY PAYER_PROVIDER_ID
            , PROVIDER_MON_HOURS_VERIFIED
            , PROVIDER_TUES_HOURS_VERIFIED
            , PROVIDER_WEDS_HOURS_VERIFIED
            , PROVIDER_THURS_HOURS_VERIFIED
            , PROVIDER_FRI_HOURS_VERIFIED
            , PROVIDER_SAT_HOURS_VERIFIED
            , PROVIDER_SUN_HOURS_VERIFIED
            , ATTESTED_ENTITY_UNIQUE_ID
            , PAYER_ADDRESSID
            , STATUS
    ) a
    INNER JOIN &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PRACTICELOCATIONS_VW B
        ON A.ATTESTED_ENTITY_UNIQUE_ID = B.ATTESTED_ENTITY_UNIQUE_ID
        AND A.PAYER_ADDRESSID = B.PAYER_ADDRESSID
    INNER JOIN &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PROVIDERINFO_VW C
        ON B.ATTESTED_ENTITY_UNIQUE_ID = C.ATTESTED_ENTITY_UNIQUE_ID
    JOIN PROVIDER_ATTESTATION.LKP_LEXIS_NEXIS_CACTUS_PROVIDER_DETAIL_SELECT_VW PD 
        ON C.PAYER_PROVIDER_ID = PD.SOURCE_PROVIDER_NBR
    LEFT JOIN  (SELECT * , ROW_NUMBER() OVER(PARTITION BY UNIVERSAL_PROVIDER_ID, OFFICE_ID ORDER BY ANCILLARY_PROVIDER_IND DESC,PROVIDER_ADDRESS_START_DATE DESC) AS ROW_NBR FROM PROVIDER_ATTESTATION.LKP_LEXIS_NEXIS_CACTUS_PROVIDER_ADDRESS_SELECT_VW) PA 
        ON PD.UNIVERSAL_PROVIDER_ID = PA.UNIVERSAL_PROVIDER_ID AND PA.OFFICE_ID = B.USER_DEF_06
    LEFT JOIN &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PAYERPROVIDERLOCATIONGROUPS_VW D
        ON B.ATTESTED_ENTITY_UNIQUE_ID = D.ATTESTED_ENTITY_UNIQUE_ID
        AND B.TOTAL_PRACTICE_ENTITY_ID = D.APL_TOTAL_PRACTICE_ENTITY_ID
        AND B.ATTESTED_DATE = D.ATTESTED_DATE
    INNER JOIN &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_ATTESTATIONLOCATIONSUMMARY_VW G
        ON B.ATTESTED_ENTITY_UNIQUE_ID = G.ENTITY_UNIQUE_ID
        AND B.TOTAL_PRACTICE_ENTITY_ID = G.TOTAL_PRACTICE_ENTITY_ID
        AND B.ATTESTED_DATE = G.ATTESTED_DATE
        AND ((B.STATUS <> 'A' AND B.USER_DEF_06 = D.USER_DEF_06)
        OR (B.STATUS = 'A' AND NVL(B.USER_DEF_06,'9999999') = NVL(D.USER_DEF_06,'9999999')))
    LEFT JOIN &{IDW}.SACA.STAFF_ASSIGN_VW SA ON SA.OFFICEID = B.USER_DEF_06 
    WHERE SUBSTR(B.FILENAME, LENGTH(B.FILENAME) - 11, 8) = (
    SELECT MAX(SUBSTR(FILENAME, LENGTH(FILENAME) - 11, 8)) FROM &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PRACTICELOCATIONS_VW) AND 
    (UPPER(B.USER_DEF_02) IN ( 'HEALTH PLAN DIRECT CREDENTIAL', 'SKYGEN') OR UPPER(B.USER_DEF_02) IS NULL ) 
    AND PA.ROW_NBR = 1  
    AND A.NUMBER_OF_HOURS < 8  
    AND (TRIM(NEW_VALUE) NOT LIKE '')) E);
