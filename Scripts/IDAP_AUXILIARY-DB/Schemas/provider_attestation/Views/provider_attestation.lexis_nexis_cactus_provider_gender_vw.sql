!set variable_substitution=true;
CREATE OR REPLACE VIEW PROVIDER_ATTESTATION.LEXIS_NEXIS_CACTUS_PROVIDER_GENDER_VW
(
  PAYER_PROVIDER_ID
, PROVIDER_NAME
, ANCILARY_PROVIDER_IND
, PROVIDER_CATEGORY
, PHYSICIAN_HOSPITAL_ORGANIZATION
, OLD_VALUE
, NEW_VALUE
, ATTESTED_USER
, ATTESTED_DATE
, ATTESATED_PHONE
, ATTESTED_EMAIL
, CREATED_ON
, SOURCE_FILE_NAME
, CHANGE_TYPE
, AREA_AFFECTED
, CHANGE_REQUIRED
, CHANGE_TYPE_CASSIFICATION)
COMMENT = 'LEXIS NEXIS CACTUS PROVIDER LEVEL GENDER VIEW' 
AS
(
    SELECT DISTINCT PROV.PAYER_PROVIDER_ID
        , COALESCE(NAME_PREFIX,'') || ' ' || COALESCE(FIRST_NAME,'') || ' ' || COALESCE(MIDDLE_NAME,'') || ' ' || COALESCE(LAST_NAME,'') || ' ' || COALESCE(NAME_SUFFIX,'') || ' ' || COALESCE(PROF_SUFFIX,'') AS NAME
        , PA.ANCILLARY_PROVIDER_IND
        , PROV.USER_DEF_01 AS PROVIDER_CATEGORY
        , PROV.USER_DEF_02 AS PHYSICIAN_HOSPITAL_ORGANIZATION
        , PROV.GENDER AS OLD_VALUE
        , PROV.GENDER_VERIFIED AS NEW_VALUE
        , ATS.CONTACT_NAME AS ATTESTED_USER
        , DATE(ATS.ATTESTED_DATE)AS ATTESTED_DATE
        , ATS.CONTACT_PHONE
        , ATS.CONTACT_EMAIL
        , PROV.LOAD_TIME
        , PROV.FILENAME
        , CASE WHEN PROV.STATUS = 'U' THEN 'U - UPDATE' END AS CHANGETYPE
        , 'GENDER' AS AREAAFFECTED
        , CASE WHEN PROV.STATUS = 'U' THEN 'GENDER CHANGE' END AS CHANGEREQUIRED
        , CASE WHEN OLD_VALUE = 'M' AND NEW_VALUE = 'F' THEN 'NEEDS REVIEWED' 
               WHEN OLD_VALUE = 'F' AND NEW_VALUE = 'M' THEN 'NEEDS REVIEWED'
               WHEN OLD_VALUE = 'U' AND NEW_VALUE IN ('F','M') THEN 'ACCEPTED'
               WHEN OLD_VALUE IS NULL AND NEW_VALUE IN ('F','M') THEN 'ACCEPTED'
               WHEN OLD_VALUE IS NULL AND NEW_VALUE = 'U' THEN 'REJECTED'
               WHEN OLD_VALUE IN ('M','F') AND  NEW_VALUE = 'U' THEN 'REJECTED'
               WHEN OLD_VALUE IN ('M','F') AND  NEW_VALUE IN (NULL,'') THEN 'REJECTED' END AS CHANGETYPECASSIFICATION
    FROM &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PROVIDERINFO_VW PROV
    JOIN PROVIDER_ATTESTATION.LKP_LEXIS_NEXIS_CACTUS_PROVIDER_DETAIL_SELECT_VW PD 
      ON PROV.PAYER_PROVIDER_ID = PD.SOURCE_PROVIDER_NBR
    LEFT JOIN  (SELECT *, ROW_NUMBER() OVER(PARTITION BY UNIVERSAL_PROVIDER_ID ORDER BY ANCILLARY_PROVIDER_IND DESC, PROVIDER_ADDRESS_START_DATE DESC) AS ROW_NBR FROM PROVIDER_ATTESTATION.LKP_LEXIS_NEXIS_CACTUS_PROVIDER_ADDRESS_SELECT_VW) PA 
      ON PD.UNIVERSAL_PROVIDER_ID = PA.UNIVERSAL_PROVIDER_ID 
    INNER JOIN &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_ATTESTATIONSUMMARY_VW ATS 
      ON PROV.ATTESTED_ENTITY_UNIQUE_ID = ATS.ENTITY_UNIQUE_ID AND PROV.ATTESTED_DATE = ATS.ATTESTED_DATE
    WHERE SUBSTR(PROV.FILENAME, LENGTH(PROV.FILENAME) - 11, 8) = (
            SELECT MAX(SUBSTR(FILENAME, LENGTH(FILENAME) - 11, 8)) FROM &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PROVIDERINFO_VW) AND
            PA.ROW_NBR = 1 
        AND (UPPER(PROV.USER_DEF_02) IN ('HEALTH PLAN DIRECT CREDENTIAL', 'SKYGEN') OR PROV.USER_DEF_02 IS NULL)             
        AND PROV.STATUS IN ('U') 
        AND ((UPPER (GENDER_VERIFIED) <> NVL2 (UPPER (GENDER), UPPER (GENDER), ' ') AND GENDER_VERIFIED IS NOT NULL)));

!set variable_substitution=false;