CREATE OR REPLACE VIEW PROVIDER_ATTESTATION.LEXIS_NEXIS_CACTUS_PRACTICE_LOCATION_VW
(
  PAYER_PROVIDER_ID
, PROVIDER_NAME
, ANCILARY_PROVIDER_IND
, ADDRESS_ID
, PAYER_ADDRESS_ID
, PRACTICE_NAME
, PROVIDER_CATEGORY
, PHYSICIAN_HOSPITAL_ORGANIZATION
, TAX_ID_NBR
, UPMC_OWNERSHIP_DESC
, CHANGE_TYPE
, AREA_AFFECTED
, CHANGE_REQUIRED
, OLD_VALUE
, NEW_VALUE
, PRACTICE_NAME_CACTUS
, ADDRESS_LINE1_CACTUS
, ADDRESS_LINE2_CACTUS
, CITY_NAME_CACTUS
, STATE_ABBREVIATION_CACTUS
, ZIP_CODE_CACTUS
, PRIMARY_PHONE_NBR_CACTUS
, ALTERNATE_PHONE_NBR_CACTUS
, ATTESTED_USER
, ATTESTED_DATE
, ATTESTED_PHONE_NBR
, ATTESTED_EMAIL
, PHYSICIAN_ACCOUNT_EXECUTIVE
, PCP_OFFICE_IND
, DUAL_CREDENTIALED_IND
, CREATED_ON
, SPECIALTY_NAME
, SOURCE_FILE_NAME
, OLD_NEW_PERCENT_MATCH
, CHANGE_TYPE_CLASSIFICATION
) 
 COMMENT = 'LEXIS NEXIS CACTUS PRACTICE LEVEL LOCATION VIEW' AS 
 (SELECT DISTINCT B.PAYER_PROVIDER_ID
        , COALESCE(NAME_PREFIX,'') || ' ' || COALESCE(FIRST_NAME,'') || ' ' || COALESCE(MIDDLE_NAME,'') || ' ' || COALESCE(LAST_NAME,'') || ' ' || COALESCE(NAME_SUFFIX,'') || ' ' || COALESCE(PROF_SUFFIX,'') AS PROVIDER_NAME
        , CASE WHEN PA.OFFICE_ID = B.USER_DEF_06 THEN 
PA.ANCILLARY_PROVIDER_IND ELSE 'N' END AS ANCILLARY_PROVIDER_IND
        , B.USER_DEF_06 AS ADDRESS_ID
        , B.PAYER_ADDRESSID
        , CASE WHEN B.PRACTICE_NAME = '' OR B.PRACTICE_NAME IS NULL THEN translate(B.PRACTICE_NAME_VERIFIED,',-.','') ELSE translate(B.PRACTICE_NAME,',-.','') END AS PRACTICE_NAME
        , B.USER_DEF_01
        , B.USER_DEF_02
        , CASE WHEN D.TAX_ID = '' OR D.TAX_ID IS NULL THEN D.TAX_ID_VERIFIED ELSE D.TAX_ID END AS TAX_ID
        , PA.PROVIDER_OWNERSHIP_STATUS_SOURCE_DESC AS UPMCOWNERSHIPDESC
        , CASE WHEN B.STATUS = 'A' THEN 'A - Add' 
               WHEN B.STATUS = 'D' THEN 'D - Delete'
               ELSE 'U - Update' 
          END AS CHANGE_TYPE
        , 'Practice Location' as AREA_AFFECTED
        , CASE 
                WHEN B.STATUS = 'A' THEN 'Add Practice Location' 
                WHEN B.STATUS  = 'D' THEN 'Delete Practice Location' 
                ELSE 'Update Practice Location (City, State or Zip only)' 
          END AS CHANGE_REQUIRED
        , CASE 
                WHEN B.STATUS = 'D' THEN 'Group Name: '|| COALESCE(D.GROUP_NAME,'') ||' NPI: '|| COALESCE(D.ORG_NPI_ID,'') || ' TAX ID: '|| COALESCE(D.TAX_ID,'') || ' Address: ' || COALESCE(B.Primary_Address,'')|| ' ' ||COALESCE(B.Secondary_Address,'')|| ' ' ||B.City|| ' ' ||B.State|| ' ' ||B.Zip|| ' Phone: ' ||COALESCE(B.PHONE,'')|| ' Fax: ' ||COALESCE(B.FAX,'') 
                WHEN B.STATUS= 'A' THEN NULL
                ELSE COALESCE(B.PRIMARY_ADDRESS,'')||' ' ||COALESCE(B.SECONDARY_ADDRESS,'')|| ' ' ||COALESCE(B.CITY,'')|| ' ' ||COALESCE(B.STATE,'')|| ' ' ||COALESCE(B.ZIP,'') 
          END AS OLD_VALUE
        , CASE 
                WHEN B.STATUS = 'A' THEN 'Group Name: '||COALESCE(D.GROUP_NAME_VERIFIED,'')||' NPI: '||COALESCE(D.ORG_NPI_ID_VERIFIED,'')||' TAX ID: '||COALESCE(D.TAX_ID_VERIFIED,'')||' Address: '||COALESCE(PRIMARY_ADDRESS_VERIFIED,'')||' '||COALESCE(SECONDARY_ADDRESS_VERIFIED,'')||' '||COALESCE(B.CITY_VERIFIED,'')||' '||COALESCE(B.STATE_VERIFIED,'')||' '||COALESCE(B.ZIP_VERIFIED,'')||' Phone: '||COALESCE(B.PHONE_VERIFIED,'')||' Fax: '||COALESCE(B.FAX_VERIFIED,'')||' Accepts Medicaid: '||COALESCE(b.ACCEPTS_MEDICAID_VERIFIED,'')||' Accessibility Options: '||(CASE WHEN COALESCE(UPPER(B.ACCESSIBILITY_OPTIONS_VERIFIED),'') LIKE '%MEETS ADA ACCESSIBILITY%' THEN COALESCE(B.ACCESSIBILITY_OPTIONS_VERIFIED,'') ELSE '' END)  
                WHEN B.STATUS = 'D' THEN NULL 
                ELSE COALESCE(PRIMARY_ADDRESS_VERIFIED,'')||' '||COALESCE(SECONDARY_ADDRESS_VERIFIED,'')||' '||COALESCE(B.CITY_VERIFIED,'')||' '||COALESCE(B.STATE_VERIFIED,'')||' '||COALESCE(B.ZIP_VERIFIED ,'')
          END AS NEW_VALUE
        , PA.OFFICE_NAME
        , PA.ADDRESS_LINE1
        , PA.ADDRESS_LINE2
        , PA.CITY_NAME
        , PA.STATE_ABBREVIATION
        , PA.ZIP_CODE
        , PA.PRIMARY_PHONE_NBR
        , PA.ALTERNATE_PHONE_NBR
        , G.CONTACT_NAME AS ATTESTED_USER
        , DATE(G.ATTESTED_DATE) AS ATTESTED_DATE
        , G.CONTACT_PHONE
        , G.CONTACT_EMAIL 
        , SA.PAE AS PHYSICIAN_ACCOUNT_EXECUTIVE
        , CASE WHEN PA.MA_SUPER_PCP_IND = 'Y' THEN 'Y' ELSE 'N' END AS PCP_OFFICE_IND
        , CASE WHEN PA.MA_SUPER_PCP_IND = 'Y' THEN 'Y' ELSE 'N' END AS DUALCREDENTIALEDIND
        , C.LOAD_TIME
        , CASE WHEN PA.PRIMARY_SPECIALTY_IND = 'Y' THEN  PA.SPECIALTY_NAME ELSE 'NO PRIMARY' END AS SPECIALTY_NAME
        , C.FILENAME
        , JAROWINKLER_SIMILARITY(OLD_VALUE, NEW_VALUE) AS OLD_NEW_PERCENTAGE_MATCH 
        , 'NEEDS REVIEWED' AS CHANGE_TYPE_CLASSIFICATION
    FROM &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PRACTICELOCATIONS_VW  B
    INNER JOIN &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PROVIDERINFO_VW C
        ON B.ATTESTED_ENTITY_UNIQUE_ID = C.ATTESTED_ENTITY_UNIQUE_ID
    JOIN PROVIDER_ATTESTATION.LKP_LEXIS_NEXIS_CACTUS_PROVIDER_DETAIL_SELECT_VW PD 
        ON C.PAYER_PROVIDER_ID = PD.SOURCE_PROVIDER_NBR
    FULL OUTER JOIN  (SELECT * , ROW_NUMBER() OVER(PARTITION BY UNIVERSAL_PROVIDER_ID, OFFICE_ID ORDER BY ANCILLARY_PROVIDER_IND DESC,PROVIDER_ADDRESS_START_DATE DESC) AS ROW_NBR FROM PROVIDER_ATTESTATION.LKP_LEXIS_NEXIS_CACTUS_PROVIDER_ADDRESS_SELECT_VW) PA 
        ON PD.UNIVERSAL_PROVIDER_ID = PA.UNIVERSAL_PROVIDER_ID AND PA.OFFICE_ID = COALESCE(B.USER_DEF_06,'')
    LEFT JOIN &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PAYERPROVIDERLOCATIONGROUPS_VW  D
        ON B.ATTESTED_ENTITY_UNIQUE_ID = D.ATTESTED_ENTITY_UNIQUE_ID
        AND B.TOTAL_PRACTICE_ENTITY_ID = D.APL_TOTAL_PRACTICE_ENTITY_ID
        AND B.ATTESTED_DATE = D.ATTESTED_DATE
        AND ((B.STATUS <> 'A' AND B.USER_DEF_06 = D.USER_DEF_06)
        OR (B.STATUS = 'A' AND NVL(B.USER_DEF_06,'9999999') = NVL(D.USER_DEF_06,'9999999')))
    INNER JOIN &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_ATTESTATIONLOCATIONSUMMARY_VW G
        ON B.ATTESTED_ENTITY_UNIQUE_ID = G.ENTITY_UNIQUE_ID
        AND B.TOTAL_PRACTICE_ENTITY_ID = G.TOTAL_PRACTICE_ENTITY_ID
        AND B.ATTESTED_DATE = G.ATTESTED_DATE
    LEFT JOIN &{IDW}.SACA.STAFF_ASSIGN_VW SA ON SA.OFFICEID = B.USER_DEF_06
        WHERE COALESCE(B.ATTESTED_ENTITY_UNIQUE_ID,'')||COALESCE(B.PAYER_ADDRESSID,'')  NOT IN (
            SELECT DISTINCT COALESCE(A.ATTESTED_ENTITY_UNIQUE_ID,'')||COALESCE(A.PAYER_ADDRESSID,'')
            FROM &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PRACTICELOCATIONS_VW A
                WHERE A.STATUS IN ('D','A')
            GROUP BY ATTESTED_ENTITY_UNIQUE_ID, PAYER_ADDRESSID 
            HAVING COUNT(DISTINCT STATUS)=2)
   AND SUBSTR(B.FILENAME, LENGTH(B.FILENAME) - 11, 8) = (
        SELECT MAX(SUBSTR(FILENAME, LENGTH(FILENAME) - 11, 8)) FROM &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PRACTICELOCATIONS_VW)
   AND (UPPER(C.USER_DEF_02) IN ('HEALTH PLAN DIRECT CREDENTIAL', 'SKYGEN') OR UPPER(C.USER_DEF_02) IS NULL) 
   AND COALESCE(TO_VARCHAR(PA.ROW_NBR),'') IN ('1','') 
   AND (B.STATUS IN ('A','D')    
        OR (B.STATUS = 'U' AND UPPER(SOUNDEX(COALESCE(B.CITY,'')))||SOUNDEX(UPPER(COALESCE(B.STATE,'')))||UPPER(COALESCE(B.ZIP,'')) <> UPPER(SOUNDEX(COALESCE(B.CITY_VERIFIED,'')))||SOUNDEX(UPPER(COALESCE(B.STATE_VERIFIED,'')))||UPPER(SUBSTR(COALESCE(B.ZIP_VERIFIED,''),1,5))))); 
!set variable_substitution=false;