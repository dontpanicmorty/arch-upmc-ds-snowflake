!set variable_substitution=true;
CREATE OR REPLACE VIEW PROVIDER_ATTESTATION.LKP_LEXIS_NEXIS_CACTUS_PROVIDER_DETAIL_SELECT_VW(
  UNIVERSAL_PROVIDER_ID
, SOURCE_PROVIDER_NBR
, PROVIDER_KEY
, DATA_SOURCE_NAME
) COMMENT = 'LOOK UP VIEW FOR LEXIS NEXIS CACTUS PROVIDER DETAIL CREATED USING PROVIDER ODS DATA'
AS (
	SELECT DISTINCT CONCAT(PROV.TPA_HIERARCHY_KEY, DS.DATA_SOURCE_NAME, PROV.SOURCE_PROVIDER_NBR) AS UNIVERSAL_PROVIDER_ID
		, PROV.SOURCE_PROVIDER_NBR
		, PROVIDER_KEY
		, DS.DATA_SOURCE_NAME
	FROM &{IDAP}.ODSDATA.PROVIDER_VW PROV 
	JOIN &{IDAP}.ODSDATA.DATA_SOURCE_VW DS ON PROV.DATA_SOURCE_KEY = DS.DATA_SOURCE_KEY AND UPPER(DATA_SOURCE_NAME) = 'CACTUS'
	); 
!set variable_substitution=false;