CREATE OR REPLACE VIEW PROVIDER_ATTESTATION.LEXIS_NEXIS_CACTUS_PROVIDER_STATUS_VW
(
 PAYER_PROVIDER_ID
,PROVIDER_NAME
,ANCILARY_PROVIDER_IND
,PROVIDER_CATEGORY
,PHYSICIAN_HOSPITAL_ORGANIZATION
,OLD_VALUE
,NEW_VALUE
,ATTESTED_USER
,ATTESTED_DATE
,ATTESTED_PHONE_NBR
,ATTESTED_EMAIL
,CREATED_ON
,SOURCE_FILE_NAME
,CHANGE_TYPE
,AREA_AFFECTED
,CHANGE_REQUIRED
,CHANGE_TYPE_CLASSIFICATION)  
COMMENT = 'LEXIS NEXIS CACTUS PROVIDER LEVEL STATUS VIEW' 
AS (
    SELECT DISTINCT PROV.PAYER_PROVIDER_ID
		,COALESCE(NAME_PREFIX,'') || ' ' || COALESCE(FIRST_NAME,'') || ' ' || COALESCE(MIDDLE_NAME,'') || ' ' || 		COALESCE(LAST_NAME,'') || ' ' || COALESCE(NAME_SUFFIX,'') || ' ' || COALESCE(PROF_SUFFIX,'')
		,PA.ANCILLARY_PROVIDER_IND
		,PROV.USER_DEF_01 AS PROVIDERCATEGORY
		,PROV.USER_DEF_02 AS PHYSICIANHOSPITALORGANIZATION
		,PROVIDER_STATUS
		,PROVIDER_STATUS_VERIFIED
		,B.CONTACT_NAME
		,DATE(B.ATTESTED_DATE)
		,B.CONTACT_PHONE
		,B.CONTACT_EMAIL
		,PROV.LOAD_TIME
		,PROV.FILENAME
		,CASE WHEN PROVIDER_STATUS_VERIFIED = 'D' THEN 'D - Deceased' 
			WHEN PROVIDER_STATUS_VERIFIED = 'R1' THEN 'R1 - Retired'
			WHEN PROVIDER_STATUS_VERIFIED = 'O' THEN 'O - On Leave' end AS CHANGE_TYPE
		,'Provider Status' AS AREA_AFFECTED
		,CASE WHEN PROVIDER_STATUS_VERIFIED = 'D' THEN 'Investigate Deceased' 
			WHEN PROVIDER_STATUS_VERIFIED = 'R1' THEN 'Investigate Retired'
			WHEN PROVIDER_STATUS_VERIFIED = 'O' THEN 'Investigate On Leave' END AS CHANGE_REQUIRED
		,'Needs Reviewed' AS CHANGE_TYPE_CLASSIFICATION
		FROM &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PROVIDERINFO_VW PROV
		JOIN PROVIDER_ATTESTATION.LKP_LEXIS_NEXIS_CACTUS_PROVIDER_DETAIL_SELECT_VW PD 
			ON PROV.PAYER_PROVIDER_ID = PD.SOURCE_PROVIDER_NBR
		LEFT JOIN (SELECT * , ROW_NUMBER() OVER(PARTITION BY UNIVERSAL_PROVIDER_ID ORDER BY	ANCILLARY_PROVIDER_IND DESC,PROVIDER_ADDRESS_START_DATE DESC) AS ROW_NBR FROM PROVIDER_ATTESTATION.LKP_LEXIS_NEXIS_CACTUS_PROVIDER_ADDRESS_SELECT_VW) PA 
			ON PD.UNIVERSAL_PROVIDER_ID = PA.UNIVERSAL_PROVIDER_ID 
		INNER JOIN &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_ATTESTATIONSUMMARY_VW B
			ON PROV.ATTESTED_ENTITY_UNIQUE_ID = B.ENTITY_UNIQUE_ID
			AND PROV.ATTESTED_DATE = B.ATTESTED_DATE
		WHERE SUBSTR(PROV.FILENAME, LENGTH(PROV.FILENAME) - 11, 8) = (
            SELECT MAX(SUBSTR(FILENAME, LENGTH(FILENAME) - 11, 8)) FROM &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PROVIDERINFO_VW) 
            AND PA.ROW_NBR = 1 AND (UPPER(PROV.USER_DEF_02) IN ('HEALTH PLAN DIRECT CREDENTIAL', 'SKYGEN') OR PROV.USER_DEF_02 IS NULL) AND PROVIDER_STATUS_VERIFIED IN ('D','R1','O'));

