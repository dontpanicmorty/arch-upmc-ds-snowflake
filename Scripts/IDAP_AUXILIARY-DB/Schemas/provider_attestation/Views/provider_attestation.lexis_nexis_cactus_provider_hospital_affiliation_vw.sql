CREATE OR REPLACE VIEW PROVIDER_ATTESTATION.LEXIS_NEXIS_CACTUS_PROVIDER_HOSPITAL_AFFILIATION_VW
(
  PAYER_PROVIDER_ID
, PROVIDER_NAME
, ANCILLARY_PROVIDER_IND
, PROVIDER_CATEGORY
, PHYSICIAN_HOSPITAL_ORGANIZATION
, OLD_VALUE
, NEW_VALUE
, ATTESTED_USER
, ATTESTED_DATE
, CONTACT_PHONE
, CONTACT_EMAIL
, CREATED_ON
, SOURCE_FILE_NAME
, OLD_NEW_PERCENT_MATCH
, CHANGE_TYPE
, AREA_AFFECTED
, CHANGE_REQUIRED
, CHANGE_TYPE_CLASSIFICATION
, PHYSICIAN_ACCOUNT_EXECUTIVE
, MULTIPLE_RECORDS_IND
)  
COMMENT = 'LEXIS NEXIS CACTUS HOSPITAL PROVIDER LEVEL AFFLIATION VIEW' AS
(SELECT PAYER_PROVIDER_ID
    , HA.PROVIDERNAME
    , HA.ANCILLARY_PROVIDER_IND
    , HA.USER_DEF_01
    , HA.USER_DEF_02
    , HA.OLD_VALUE
    , HA.NEW_VALUE
    , HA.CONTACT_NAME
    , DATE (HA.ATTESTED_DATE) AS ATTESTED_DATE
    , HA.CONTACT_PHONE
    , HA.CONTACT_EMAIL
    , HA.LOAD_TIME
    , HA.FILENAME
    , NULL AS OLD_NEW_PERCENT_MATCH
    , CHANGE_TYPE
    , AREA_AFFECTED
    , CHANGE_REQUIRED
    , CHANGE_TYPE_CLASSIFICATION
    , PHYSICIAN_ACCOUNT_EXECUTIVE
    , CASE WHEN COUNT(*) OVER (PARTITION BY HA.PAYER_PROVIDER_ID) > 1 THEN 'Y'
           ELSE 'N' END AS MULTIPLE_RECORDS_IND
    FROM 
        (SELECT AFF.*
        , ROW_NUMBER() OVER (PARTITION BY AFF.PAYER_PROVIDER_ID ORDER BY AFF.PAYER_PROVIDER_ID) AS PAYER_PROVIDER_ID_COUNT FROM
            (SELECT DISTINCT PROV.PAYER_PROVIDER_ID
                , COALESCE(NAME_PREFIX,'') || ' ' || COALESCE(FIRST_NAME,'') || ' ' || COALESCE(MIDDLE_NAME,'') || ' ' || COALESCE(LAST_NAME,'') || ' ' || COALESCE(NAME_SUFFIX,'') || ' ' || COALESCE(PROF_SUFFIX,'') AS PROVIDERNAME
                , PA.ANCILLARY_PROVIDER_IND
                , PROV.USER_DEF_01
                , PROV.USER_DEF_02
                , COALESCE(c.HOSPITAL_NAME,'') || ' ' || COALESCE(c.City,'') || ' ' || COALESCE(c.STATE,'') AS OLD_VALUE
                , CASE WHEN C.STATUS = 'D'
                     THEN NULL
                     ELSE COALESCE(c.HOSPITAL_NAME_VERIFIED,'') || ' ' || COALESCE(c.CITY_VERIFIED,'') || ' ' || COALESCE(c.STATE_VERIFIED,'') END AS NEW_VALUE
                 , REPLACE(B.CONTACT_NAME,'  ',' ') as CONTACT_NAME
                 , DATE (B.ATTESTED_DATE) AS ATTESTED_DATE
                 , B.CONTACT_PHONE
                 , B.CONTACT_EMAIL
                 , PROV.LOAD_TIME
                 , PROV.FILENAME
                 , CASE
                        WHEN C.STATUS = 'A' THEN 'A - Add Hospital Affiliation'
                        WHEN c.STATUS = 'U' THEN 'U - Update Hospital Affiliation'
                        WHEN c.STATUS = 'D' THEN 'D - Delete Hospital Affiliation'
                   END AS CHANGE_TYPE,
                 'Hospital Affiliation' AS AREA_AFFECTED
                 , CASE
                     WHEN c.STATUS = 'A' THEN 'Add Hospital Affiliation'
                     WHEN C.STATUS = 'U' THEN 'Update Hospital Affiliation'
                     WHEN C.STATUS = 'D' THEN 'Delete Hospital Affiliation'
                     ELSE 'Unknown'
                 END AS CHANGE_REQUIRED
                 , CASE 
                     WHEN PA.ANCILLARY_PROVIDER_IND = 'N' THEN 'Rejected'
                     ELSE 'Needs Reviewed' END AS CHANGE_TYPE_CLASSIFICATION
                 , CASE 
                     WHEN COUNT(DISTINCT SA.PAE) =1 THEN MAX(SA.PAE)
                     WHEN COUNT(DISTINCT SA.PAE) > 1 THEN 'multiple'
                     ELSE 'No PAE Listed' END AS PHYSICIAN_ACCOUNT_EXECUTIVE
                         
      FROM &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PROVIDERINFO_VW PROV
      LEFT JOIN (SELECT *, ROW_NUMBER() OVER(PARTITION BY UNIVERSAL_PROVIDER_ID ORDER BY ANCILLARY_PROVIDER_IND DESC,PROVIDER_ADDRESS_START_DATE DESC) AS ROW_NBR FROM PROVIDER_ATTESTATION.LKP_LEXIS_NEXIS_CACTUS_PROVIDER_ADDRESS_SELECT_VW) PA 
        ON PROV.PAYER_PROVIDER_ID = PA.SOURCE_PROVIDER_NBR
      JOIN &{IDAP}.ODSDATA.PROVIDER_VW P 
        ON PROV.PAYER_PROVIDER_ID = P.SOURCE_PROVIDER_NBR
      LEFT JOIN &{IDAP}.ODSDATA.MEDICAL_GROUP_VW MG 
        ON MG.MEDICAL_GROUP_KEY = P.PROVIDER_KEY
      LEFT JOIN &{IDW}.SACA.STAFF_ASSIGN_VW SA 
        ON SA.OFFICEID = PA.OFFICE_ID
      INNER JOIN &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PAYERPROVIDERHOSPITALAFFILIATION_VW C
        ON PROV.ATTESTED_ENTITY_UNIQUE_ID = C.ATTESTED_ENTITY_UNIQUE_ID AND PROV.ATTESTED_DATE = C.ATTESTED_DATE
      INNER JOIN &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_ATTESTATIONSUMMARY_VW B
        ON PROV.ATTESTED_ENTITY_UNIQUE_ID = B.ENTITY_UNIQUE_ID AND PROV.ATTESTED_DATE = B.ATTESTED_DATE
      WHERE SUBSTR(PROV.FILENAME, LENGTH(PROV.FILENAME) - 11, 8) = (
            SELECT MAX(SUBSTR(FILENAME, LENGTH(FILENAME) - 11, 8)) FROM &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PROVIDERINFO_VW) 
            AND (UPPER(PROV.USER_DEF_02) IN ('HEALTH PLAN DIRECT CREDENTIAL', 'SKYGEN') OR PROV.USER_DEF_02 IS NULL) 
        AND ((C.STATUS IN ('A', 'U')
        AND UPPER (HOSPITAL_NAME_VERIFIED) <> NVL2 (UPPER (HOSPITAL_NAME),UPPER (HOSPITAL_NAME), ' '))
        OR C.STATUS = 'D')  
        AND PA.ROW_NBR = 1 GROUP BY PROV.PAYER_PROVIDER_ID, NAME_PREFIX, FIRST_NAME, MIDDLE_NAME,LAST_NAME, NAME_SUFFIX, PROF_SUFFIX, ANCILLARY_PROVIDER_IND, PROV.USER_DEF_01, PROV.USER_DEF_02,C.STATUS, B.CONTACT_NAME, B.ATTESTED_DATE, B.CONTACT_PHONE, B.CONTACT_EMAIL, PROV.LOAD_TIME, PROV.FILENAME, C.HOSPITAL_NAME, C.CITY, C.STATE, C.HOSPITAL_NAME_VERIFIED, C.CITY_VERIFIED, C.STATE_VERIFIED, MG.MEDICAL_GROUP_NAME ) AFF ) HA ORDER BY HA.PAYER_PROVIDER_ID, HA.PAYER_PROVIDER_ID_COUNT);
!set variable_substitution=false;