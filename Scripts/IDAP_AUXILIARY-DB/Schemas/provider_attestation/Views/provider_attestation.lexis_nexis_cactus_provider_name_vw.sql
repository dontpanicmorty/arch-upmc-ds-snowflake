CREATE OR REPLACE VIEW PROVIDER_ATTESTATION.LEXIS_NEXIS_CACTUS_PROVIDER_NAME_VW
( PAYER_PROVIDER_ID
, PROVIDER_NAME
, ANCILLARY_PROVIDER_IND
, NAME_PREFIX
, FIRST_NAME
, MIDDLE_NAME
, LAST_NAME
, NAME_SUFFIX
, PROF_SUFFIX
, NAME_PREFIX_VERIFIED
, FIRST_NAME_VERIFIED
, MIDDLE_NAME_VERIFIED
, LAST_NAME_VERIFIED
, NAME_SUFFIX_VERIFIED
, PROF_SUFFIX_VERIFIED
, PROVIDER_CATEGORY
, PHYSICIAN_HOSPITAL_ORGANIZATION
, OLD_VALUE
, NEW_VALUE
, ATTESTED_USER
, ATTESTED_DATE
, ATTESTED_PHONE_NBR
, ATTESTED_EMAIL
, CREATED_ON
, SOURCE_FILE_NAME
, CHANGE_TYPE
, AREA_AFFECTED
, CHENGE_REQUIRED
, CHANGE_TYPE_CLASSIFICATION) 
COMMENT = 'LEXIS NEXIS CACTUS PROVIDER LEVEL NAME VIEW'
AS (SELECT DISTINCT PROV.PAYER_PROVIDER_ID
,                 COALESCE(NAME_PREFIX,'') || ' ' || COALESCE(FIRST_NAME,'') || ' ' || COALESCE(MIDDLE_NAME,'') || ' ' || COALESCE(LAST_NAME,'') || ' ' || COALESCE(NAME_SUFFIX,'') || ' ' || COALESCE(PROF_SUFFIX,'') AS PROVIDERNAME
                , PA.ANCILLARY_PROVIDER_IND
                , NAME_PREFIX 
                , FIRST_NAME
                , MIDDLE_NAME
                , LAST_NAME
                , NAME_SUFFIX
                , PROF_SUFFIX
                , NAME_PREFIX_VERIFIED
                , FIRST_NAME_VERIFIED
                , MIDDLE_NAME_VERIFIED
                , LAST_NAME_VERIFIED
                , NAME_SUFFIX_VERIFIED
                , PROF_SUFFIX_VERIFIED
                , PROV.USER_DEF_01 AS PROVIDERCATEGORY
                , USER_DEF_02 AS PHYSICIANHOSPITALORGANIZATION
                , COALESCE(NAME_PREFIX,'') || ' ' || COALESCE(FIRST_NAME,'') || ' ' || COALESCE(MIDDLE_NAME,'') || ' ' || COALESCE(LAST_NAME,'') || ' ' || COALESCE(NAME_SUFFIX,'') || ' ' || COALESCE(PROF_SUFFIX,'') AS OLD_VALUE
                , COALESCE(NAME_PREFIX_VERIFIED,'') || ' ' || COALESCE(FIRST_NAME_VERIFIED,'') || ' ' || COALESCE(MIDDLE_NAME_VERIFIED,'') || ' ' || COALESCE(LAST_NAME_VERIFIED,'') || ' ' || COALESCE(NAME_SUFFIX_VERIFIED,'') || ' ' || COALESCE(PROF_SUFFIX_VERIFIED,'') AS NEW_VALUE
                , B.CONTACT_NAME
                , DATE(B.ATTESTED_DATE)
                , B.CONTACT_PHONE
                , B.CONTACT_EMAIL
                , PROV.LOAD_TIME
                , PROV.FILENAME
                , CASE WHEN PROV.STATUS = 'U' THEN 'U - UPDATE' END AS CHANGE_TYPE
                , 'NAME' AS AREA_AFFECTED
                , CASE WHEN PROV.STATUS = 'U' THEN 'NAME CHANGE' END AS CHANGE_REQUIRED
                , CASE WHEN TRANSLATE(UPPER(COALESCE(MIDDLE_NAME,'')),'.','') = TRANSLATE(UPPER(COALESCE(MIDDLE_NAME_VERIFIED,'')),'.','') 
                            AND UPPER(COALESCE(NAME_PREFIX,'')) = UPPER(COALESCE(NAME_PREFIX_VERIFIED,'')) 
                            AND UPPER(COALESCE(FIRST_NAME,'')) = UPPER(COALESCE(FIRST_NAME_VERIFIED,''))
                            AND UPPER(COALESCE(LAST_NAME,'')) = UPPER(COALESCE(LAST_NAME_VERIFIED,''))
                            AND UPPER(COALESCE(NAME_SUFFIX,'')) = UPPER(COALESCE(NAME_SUFFIX_VERIFIED,''))
                            AND TRANSLATE(UPPER(COALESCE(PROF_SUFFIX,'')),',','') = TRANSLATE(UPPER(COALESCE(PROF_SUFFIX_VERIFIED,'')),',','') 
                       THEN 'Rejected'
                       WHEN (NAME_PREFIX IS NULL AND UPPER(COALESCE(NAME_PREFIX_VERIFIED,'')) = 'DR')
                            AND TRANSLATE(UPPER(COALESCE(MIDDLE_NAME,'')),'.','') = TRANSLATE(UPPER(COALESCE(MIDDLE_NAME_VERIFIED,'')),'.','') 
                            AND UPPER(COALESCE(FIRST_NAME,'')) = UPPER(COALESCE(FIRST_NAME_VERIFIED,''))
                            AND UPPER(COALESCE(LAST_NAME,'')) = UPPER(COALESCE(LAST_NAME_VERIFIED,''))
                            AND UPPER(COALESCE(NAME_SUFFIX,'')) = UPPER(COALESCE(NAME_SUFFIX_VERIFIED,''))
                            AND TRANSLATE(UPPER(COALESCE(PROF_SUFFIX,'')),',','') = TRANSLATE(UPPER(COALESCE(PROF_SUFFIX_VERIFIED,'')),',','') 
                      THEN 'Rejected'
                      WHEN TRANSLATE(UPPER(OLD_VALUE),'[0-9]#$&&!_.,\'- ','[0-9]') = TRANSLATE(UPPER(NEW_VALUE),'[0-9]#$&&!_.,\'- ','[0-9]') 
                      THEN 'Rejected'
                      WHEN NAME_PREFIX_VERIFIED IS NOT NULL AND UPPER(COALESCE(NAME_PREFIX,'')) <> UPPER(COALESCE(NAME_PREFIX_VERIFIED,''))
                            AND UPPER(COALESCE(FIRST_NAME,'')) = UPPER(COALESCE(FIRST_NAME_VERIFIED,''))
                            AND UPPER(COALESCE(MIDDLE_NAME,'')) = UPPER(COALESCE(MIDDLE_NAME_VERIFIED,''))
                            AND UPPER(COALESCE(LAST_NAME,'')) = UPPER(COALESCE(LAST_NAME_VERIFIED,''))
                            AND UPPER(COALESCE(NAME_SUFFIX,'')) = UPPER(COALESCE(NAME_SUFFIX_VERIFIED,''))
                            AND UPPER(COALESCE(PROF_SUFFIX,'')) = UPPER(COALESCE(PROF_SUFFIX_VERIFIED,'')) 
                      THEN 'Rejected'
	                  WHEN FIRST_NAME_VERIFIED IS NOT NULL AND UPPER(COALESCE(FIRST_NAME,'')) <>  UPPER(COALESCE(FIRST_NAME,'')) 
                      THEN 'Needs Reviewed'
	                  WHEN MIDDLE_NAME IS NULL AND MIDDLE_NAME_VERIFIED IS NOT NULL 
                      THEN 'Accepted'
	                  WHEN TRANSLATE(UPPER(COALESCE(MIDDLE_NAME,'')),'[0-9]#$&&!_.,\'- ','[0-9]') <> TRANSLATE(UPPER(COALESCE(MIDDLE_NAME_VERIFIED,'')),'[0-9]#$&&!_.,\'- ','[0-9]') 
                      THEN 'Accepted'	
                      WHEN LAST_NAME_VERIFIED IS NOT NULL AND LAST_NAME <>  LAST_NAME_VERIFIED 
                      THEN 'Needs Reviewed'
	                  WHEN NAME_SUFFIX_VERIFIED IS NOT NULL AND UPPER(COALESCE(NAME_SUFFIX,'')) <>  UPPER(COALESCE(NAME_SUFFIX_VERIFIED,'')) 
                      THEN 'Needs Reviewed'
	                  WHEN PROF_SUFFIX_VERIFIED IS NOT NULL AND UPPER(COALESCE(PROF_SUFFIX,'')) <>  UPPER(COALESCE(PROF_SUFFIX_VERIFIED,'')) 
                      THEN 'Needs Reviewed'
	                  ELSE 'Needs Reviewed'
                 END AS CHANGE_TYPE_CLASSIFICATION                    
    FROM &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PROVIDERINFO_VW PROV
    JOIN PROVIDER_ATTESTATION.LKP_LEXIS_NEXIS_CACTUS_PROVIDER_DETAIL_SELECT_VW PD 
        ON PROV.PAYER_PROVIDER_ID = PD.SOURCE_PROVIDER_NBR
    LEFT JOIN  (SELECT * , ROW_NUMBER() OVER(PARTITION BY UNIVERSAL_PROVIDER_ID ORDER BY ANCILLARY_PROVIDER_IND DESC,PROVIDER_ADDRESS_START_DATE DESC) AS ROW_NBR FROM PROVIDER_ATTESTATION.LKP_LEXIS_NEXIS_CACTUS_PROVIDER_ADDRESS_SELECT_VW) PA 
        ON PD.UNIVERSAL_PROVIDER_ID = PA.UNIVERSAL_PROVIDER_ID 
    INNER JOIN &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_ATTESTATIONSUMMARY_VW B
        ON PROV.ATTESTED_ENTITY_UNIQUE_ID = B.ENTITY_UNIQUE_ID
            AND PROV.ATTESTED_DATE = B.ATTESTED_DATE
    WHERE SUBSTR(PROV.FILENAME, LENGTH(PROV.FILENAME) - 11, 8) = (
            SELECT MAX(SUBSTR(FILENAME, LENGTH(FILENAME) - 11, 8)) FROM &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PROVIDERINFO_VW) 
            AND PROV.STATUS IN ('U') AND (UPPER(PROV.USER_DEF_02) IN ('HEALTH PLAN DIRECT CREDENTIAL', 'SKYGEN') OR PROV.USER_DEF_02 IS NULL)
    AND PA.ROW_NBR = 1 
    AND ((UPPER ( (NAME_PREFIX_VERIFIED)) <> 
           NVL2 (UPPER (NAME_PREFIX),UPPER (NAME_PREFIX),' ')
            AND NAME_PREFIX_VERIFIED IS NOT NULL)
                                                    
            OR (UPPER ( (FIRST_NAME_VERIFIED)) <>
                    NVL2 (UPPER (FIRST_NAME),UPPER (FIRST_NAME),' ')
                AND FIRST_NAME_VERIFIED IS NOT NULL )
                          
            OR (UPPER (TRANSLATE(MIDDLE_NAME_VERIFIED, '.','')) <>
                    NVL2 ((TRANSLATE (MIDDLE_NAME, '.','')),UPPER (TRANSLATE (MIDDLE_NAME, '.','')),' ')
                AND MIDDLE_NAME_VERIFIED IS NOT NULL)
                          
            OR ( UPPER ((LAST_NAME_VERIFIED)) <>
                        NVL2 (UPPER (LAST_NAME),UPPER (LAST_NAME),' ')
                AND LAST_NAME_VERIFIED IS NOT NULL)
                          
            OR (UPPER ((NAME_SUFFIX_VERIFIED)) <>
                    NVL2 (UPPER (NAME_SUFFIX),UPPER (NAME_SUFFIX),' ')
                          AND NAME_SUFFIX_VERIFIED IS NOT NULL)
                          
            OR (UPPER ((PROF_SUFFIX_VERIFIED)) <>
                              NVL2 (UPPER (PROF_SUFFIX),UPPER (PROF_SUFFIX),' ')
                          AND PROF_SUFFIX_VERIFIED IS NOT NULL)));  
