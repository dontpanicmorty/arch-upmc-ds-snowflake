CREATE OR REPLACE VIEW PROVIDER_ATTESTATION.LKP_LEXIS_NEXIS_CACTUS_PROVIDER_ADDRESS_SELECT_VW(
  UNIVERSAL_PROVIDER_ID
, SOURCE_PROVIDER_NBR
, PROVIDER_ADDRESS_ACTIVE_IND
, DATA_SOURCE_NAME
, PROVIDER_OWNERSHIP_STATUS_SOURCE_DESC
, SPECIALTY_NAME
, PRIMARY_SPECIALTY_IND
, PROVIDER_ADDRESS_START_DATE
, ANCILLARY_PROVIDER_IND
, OFFICE_ID
, OFFICE_NAME
, ADDRESS_LINE1
, ADDRESS_LINE2
, CITY_NAME
, STATE_ABBREVIATION
, ZIP_CODE
, PRIMARY_PHONE_NBR
, ALTERNATE_PHONE_NBR
, MA_SUPER_PCP_IND)
COMMENT = 'LOOK UP VIEW FOR LEXIS NEXIS CACTUS PROVIDER ADDRESS CREATED USING PROVIDER ODS DATA'
AS 
(SELECT DISTINCT CONCAT(PROV.TPA_HIERARCHY_KEY, DS.DATA_SOURCE_NAME, PROV.SOURCE_PROVIDER_NBR) AS UNIVERSAL_PROVIDER_ID
    , PROV.SOURCE_PROVIDER_NBR
    , PROVIDER_ADDRESS_ACTIVE_IND
    , DS.DATA_SOURCE_NAME
    , C.PROVIDER_OWNERSHIP_STATUS_SOURCE_DESC
    , SPEC.SPECIALTY_NAME
    , PROV_ADD_SPEC.PRIMARY_SPECIALTY_IND
    , PROV_ADD.PROVIDER_ADDRESS_START_DATE
    , CASE WHEN UPPER(SPEC.SPECIALTY_NAME) IN 
        ('ACUPUNCTURE',
            'AUDIOLOGY',
            'CHIROPRACTIC MEDICINE',
            'OCCUPATIONAL THERAPY',
            'PEDIATRIC PHYSICAL THERAPY',
            'PHYSICAL THERAPY',
            'SPEECH THERAPY',
            'VACCINE SERVICES')  AND PROVIDER_ADDRESS_ACTIVE_IND = 'Y' 
        THEN 'Y' ELSE 'N' END AS ANCILLARY_PROVIDER_IND
    , PROV_ADD.OFFICE_ID
    , PROV_ADD.OFFICE_NAME
    , ADD.ADDRESS_LINE2_TEXT
    , ADD.ADDRESS_LINE1_TEXT
    , ADD.CITY_NAME
    , S.STATE_ABBREVIATION_NAME  
    , ADD.ZIP_CODE_NBR
    , PROV_ADD.PRIMARY_PHONE_NBR
    , PROV_ADD.ALTERNATE_PHONE_NBR
    , PROV_ADD.MA_SUPER_PCP_IND
FROM &{IDAP}.ODSDATA.PROVIDER_VW PROV 
JOIN &{IDAP}.ODSDATA.PROVIDER_ADDRESS_REL_VW PROV_ADD ON PROV.PROVIDER_KEY = PROV_ADD.PROVIDER_KEY 
JOIN &{IDAP}.ODSDATA.ADDRESS_VW ADD ON ADD.ADDRESS_KEY = PROV_ADD.ADDRESS_KEY 
JOIN &{IDAP}.ODSDATA.STATE_VW S ON S.STATE_KEY= ADD.STATE_KEY
JOIN &{IDAP}.ODSDATA.PROVIDER_OWNERSHIP_STATUS_DATA_SOURCE_REL_VW C ON PROV_ADD.PROVIDER_OWNERSHIP_STATUS_KEY = C.PROVIDER_OWNERSHIP_STATUS_KEY AND PROV.DATA_SOURCE_KEY = C.DATA_SOURCE_KEY
JOIN &{IDAP}.ODSDATA.DATA_SOURCE_VW DS ON PROV.DATA_SOURCE_KEY = DS.DATA_SOURCE_KEY
LEFT JOIN &{IDAP}.ODSDATA.PROVIDER_ADDRESS_SPECIALTY_REL_VW PROV_ADD_SPEC ON PROV_ADD_SPEC.PROVIDER_ADDRESS_REL_KEY = PROV_ADD.PROVIDER_ADDRESS_REL_KEY 
LEFT JOIN &{IDAP}.ODSDATA.SPECIALTY_VW SPEC ON SPEC.SPECIALTY_KEY = PROV_ADD_SPEC.SPECIALTY_KEY);
!set variable_substitution=false;