CREATE OR REPLACE VIEW PROVIDER_ATTESTATION.LEXIS_NEXIS_CACTUS_PRACTICE_NAME_VW
( PAYER_PROVIDER_ID
, PROVIDER_NAME
, ANCILLARY_PROVIDER_IND
, ADDRESS_ID
, PAYER_ADDRESS_ID
, PRACTICE_NAME
, PROVIDER_CATEGORY
, PHYSICIAN_HOSPITAL_ORGANIZATION
, TAX_ID_NBR
, UPMC_OWNERSHIP_DESC
, CHANGE_TYPE
, AREA_AFFECTED
, CHENGE_REQUIRED
, OLD_VALUE
, NEW_VALUE
, PRACTICE_NAME_CACTUS
, ADDRESS_LINE1_CACTUS
, ADDRESS_LINE2_CACTUS
, CITY_NAME_CACTUS
, STATE_ABBREVIATION_CACTUS
, ZIP_CODE_CACTUS
, PRIMARY_PHONE_NBR_CACTUS
, ALTERNATE_PHONE_NBR_CACTUS
, ATTESTED_USER
, ATTESTED_DATE
, ATTESTED_PHN_NBR
, ATTESTED_EMAIL
, PHYSICIAN_ACCOUNT_EXECUTIVE
, PCP_OFFICE_IND
, DUAL_CREDENTIALED_IND
, CREATED_ON
, SPECIALTY_NAME
, SOURCE_FILE_NAME
, OLD_NEW_PERCENT_MATCH
, CHANGE_TYPE_CLASSIFICATION) AS 
    (SELECT E.PAYER_PROVIDER_ID
    , E.PROVIDER_NAME
    , E.ANCILLARY_PROVIDER_IND
    , E.ADDRESS_ID
    , E.PAYER_ADDRESSID
    , E.PRACTICE_NAME 
    , E.USER_DEF_01
    , E.USER_DEF_02
    , E.TAX_ID
    , E.UPMC_OWNERSHIP_DESC
    , E.CHANGE_TYPE
    , E.AREA_AFFECTED
    , E.CHANGE_REQUIRED
    , E.OLD_VALUE
    , E.NEW_VALUE
    , E.OFFICE_NAME
    , E.ADDRESS_LINE1
    , E.ADDRESS_LINE2
    , E.CITY_NAME
    , E.STATE_ABBREVIATION
    , E.ZIP_CODE
    , E.PRIMARY_PHONE_NBR
    , E.ALTERNATE_PHONE_NBR
    , E.ATTESTED_USER
    , E.ATTESTED_DATE
    , E.CONTACT_PHONE
    , E.CONTACT_EMAIL 
    , E.PHYSICIAN_ACCOUNT_EXECUTIVE
    , E.PCP_OFFICE_IND
    , E.DUALCREDENTIALEDIND
    , E.LOAD_TIME
    , E.SPECIALTY_NAME
    , E.FILENAME
    , E.OLD_NEW_PERCENT_MATCH
    , CASE WHEN TRANSLATE(UPPER(E.OLD_VALUE),'[0-9]#$&&!_.,\'- ','[0-9]') = TRANSLATE(UPPER(E.NEW_VALUE),'[0-9]#$&&!_.,\'- ','[0-9]') THEN 'Rejected'
           WHEN COUNT(DISTINCT E.OLD_VALUE) OVER(PARTITION BY E.ADDRESS_ID) IN (0,1) AND COUNT(DISTINCT E.NEW_VALUE) OVER(PARTITION BY E.ADDRESS_ID) IN (0,1) THEN CASE WHEN ROW_NUMBER() OVER(PARTITION BY E.ADDRESS_ID ORDER BY E.ADDRESS_ID) = 1 THEN 'Accepted' ELSE 'Consolidated' END
          ELSE 'Needs Reviewed' END AS CHANGETYPECLASSIFICATION
	FROM (SELECT DISTINCT B.PAYER_PROVIDER_ID
                    , COALESCE(NAME_PREFIX,'') || ' ' || COALESCE(FIRST_NAME,'') || ' ' || COALESCE(MIDDLE_NAME,'') || ' ' || COALESCE(LAST_NAME,'') || ' ' || COALESCE(NAME_SUFFIX,'') || ' ' || COALESCE(PROF_SUFFIX,'') AS PROVIDER_NAME
                    , PA.ANCILLARY_PROVIDER_IND
                    , B.USER_DEF_06 AS ADDRESS_ID
                    , B.PAYER_ADDRESSID
                    , CASE WHEN B.PRACTICE_NAME = '' OR B.PRACTICE_NAME IS NULL THEN B.PRACTICE_NAME_VERIFIED ELSE B.PRACTICE_NAME END AS PRACTICE_NAME
                    , B.USER_DEF_01
                    , B.USER_DEF_02
                    , CASE WHEN D.TAX_ID = '' OR D.TAX_ID IS NULL THEN D.TAX_ID_VERIFIED ELSE D.TAX_ID END AS TAX_ID
                    , PA.PROVIDER_OWNERSHIP_STATUS_SOURCE_DESC AS UPMC_OWNERSHIP_DESC
                    , 'U - Update' as CHANGE_TYPE
                    , 'Practice Location Practice Name' as AREA_AFFECTED
                    , 'Update Practice Name' as CHANGE_REQUIRED
                    , B.PRACTICE_NAME AS OLD_VALUE
                    , B.PRACTICE_NAME_VERIFIED AS NEW_VALUE
                    , PA.OFFICE_NAME
                    , PA.ADDRESS_LINE1
                    , PA.ADDRESS_LINE2
                    , PA.CITY_NAME
                    , PA.STATE_ABBREVIATION
                    , PA.ZIP_CODE
                    , PA.PRIMARY_PHONE_NBR
                    , PA.ALTERNATE_PHONE_NBR
                    , G.CONTACT_NAME AS ATTESTED_USER
                    , DATE(G.ATTESTED_DATE) AS ATTESTED_DATE
                    , G.CONTACT_PHONE
                    , G.CONTACT_EMAIL 
                    , SA.PAE AS PHYSICIAN_ACCOUNT_EXECUTIVE
                    , CASE WHEN PA.MA_SUPER_PCP_IND = 'Y' THEN 'Y' ELSE 'N' END AS PCP_OFFICE_IND
                    , CASE WHEN PA.MA_SUPER_PCP_IND = 'Y' THEN 'Y' ELSE 'N' END AS DUALCREDENTIALEDIND
                    , B.LOAD_TIME
                    , CASE WHEN PA.PRIMARY_SPECIALTY_IND = 'Y' THEN  PA.SPECIALTY_NAME ELSE 'No Primary' END AS SPECIALTY_NAME
                    , B.FILENAME
                    , NULL AS OLD_NEW_PERCENT_MATCH
    FROM &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PRACTICELOCATIONS_VW B
    INNER JOIN &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PROVIDERINFO_VW C
        ON B.ATTESTED_ENTITY_UNIQUE_ID = C.ATTESTED_ENTITY_UNIQUE_ID
    JOIN PROVIDER_ATTESTATION.LKP_LEXIS_NEXIS_CACTUS_PROVIDER_DETAIL_SELECT_VW PD 
        ON C.PAYER_PROVIDER_ID = PD.SOURCE_PROVIDER_NBR
    LEFT JOIN  (SELECT * , ROW_NUMBER() OVER(PARTITION BY UNIVERSAL_PROVIDER_ID, OFFICE_ID ORDER BY ANCILLARY_PROVIDER_IND DESC,PROVIDER_ADDRESS_START_DATE DESC) AS ROW_NBR FROM PROVIDER_ATTESTATION.LKP_LEXIS_NEXIS_CACTUS_PROVIDER_ADDRESS_SELECT_VW) PA 
        ON PD.UNIVERSAL_PROVIDER_ID = PA.UNIVERSAL_PROVIDER_ID AND PA.OFFICE_ID = B.USER_DEF_06
    LEFT JOIN &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PAYERPROVIDERLOCATIONGROUPS_VW D
        ON B.ATTESTED_ENTITY_UNIQUE_ID = D.ATTESTED_ENTITY_UNIQUE_ID
        AND B.TOTAL_PRACTICE_ENTITY_ID = D.APL_TOTAL_PRACTICE_ENTITY_ID
        AND B.ATTESTED_DATE = D.ATTESTED_DATE
        AND ((B.STATUS <> 'A' AND B.USER_DEF_06 = D.USER_DEF_06)
        OR (B.STATUS = 'A' AND NVL(B.USER_DEF_06,'9999999') = NVL(D.USER_DEF_06,'9999999')))
    INNER JOIN &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_ATTESTATIONLOCATIONSUMMARY_VW G
        ON B.ATTESTED_ENTITY_UNIQUE_ID = G.ENTITY_UNIQUE_ID
        AND B.TOTAL_PRACTICE_ENTITY_ID = G.TOTAL_PRACTICE_ENTITY_ID
        AND B.ATTESTED_DATE = G.ATTESTED_DATE
    LEFT JOIN &{IDW}.SACA.STAFF_ASSIGN_VW SA ON SA.OFFICEID = B.USER_DEF_06    
    WHERE  COALESCE(B.ATTESTED_ENTITY_UNIQUE_ID,'')||COALESCE(B.PAYER_ADDRESSID,'')  NOT IN (
        SELECT DISTINCT COALESCE(A.ATTESTED_ENTITY_UNIQUE_ID,'')||COALESCE(A.PAYER_ADDRESSID,'')
        FROM &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PRACTICELOCATIONS_VW A
        WHERE A.STATUS IN ('D','A') GROUP BY ATTESTED_ENTITY_UNIQUE_ID, PAYER_ADDRESSID 
        HAVING COUNT(DISTINCT STATUS)=2) 
    AND SUBSTR(B.FILENAME, LENGTH(B.FILENAME) - 11, 8) = (
    SELECT MAX(SUBSTR(FILENAME, LENGTH(FILENAME) - 11, 8)) FROM &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PRACTICELOCATIONS_VW)
    AND (UPPER(C.USER_DEF_02) IN ( 'HEALTH PLAN DIRECT CREDENTIAL', 'SKYGEN') OR UPPER(C.USER_DEF_02) IS NULL) 
    AND PA.ROW_NBR =1 
    AND (B.STATUS IN ('U')
    AND TRANSLATE(UPPER(OLD_VALUE),'[0-9].','[0-9]') <> TRANSLATE(UPPER(NEW_VALUE),'[0-9].','[0-9]') AND NEW_VALUE IS NOT NULL)) E);
!set variable_substitution=false;