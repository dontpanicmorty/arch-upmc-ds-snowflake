!set variable_substitution=true;
CREATE OR REPLACE VIEW PROVIDER_ATTESTATION.LEXIS_NEXIS_CACTUS_PROVIDER_LANGUAGE_VW
(
  PAYER_PROVIDER_ID
, PROVIDER_NAME
, ANCILARY_PROVIDER_IND
, PROVIDER_CATEGORY 
, PHYSICIAN_HOSPITAL_ORGANIZATION
, OLD_VALUE
, NEW_VALUE
, ATTESTED_USER
, ATTESTED_DATE
, CONTACT_PHONE
, CONTACT_EMAIL
, CREATED_ON
, SOURCE_FILE_NAME
, CHANGE_TYPE
, AREA_AFFECTED
, CHANGE_REQUIRED
, CHANGE_TYPE_CLASSIFICATION
)
COMMENT= 'LEXIS NEXIS CACTUS PROVIDER LEVEL LANGUAGE VIEW'
AS
    (SELECT DISTINCT PROV.PAYER_PROVIDER_ID,COALESCE(NAME_PREFIX,'') || ' ' || COALESCE(FIRST_NAME,'') || ' ' || COALESCE(MIDDLE_NAME,'') || ' ' || COALESCE(LAST_NAME,'') || ' ' || COALESCE(NAME_SUFFIX,'') || ' ' || COALESCE(PROF_SUFFIX,'') AS PROVIDERNAME
    , PA.ANCILLARY_PROVIDER_IND
    , PROV.USER_DEF_01
    , PROV.USER_DEF_02
    , CASE WHEN C.STATUS= 'A' THEN NULL ELSE C.PROVIDER_LANGUAGE END AS OLD_VALUE
    , CASE WHEN C.STATUS = 'D' THEN NULL ELSE C.PROVIDER_LANGUAGE_VERIFIED END AS NEW_VALUE
    , B.CONTACT_NAME
    , DATE(B.ATTESTED_DATE) AS ATTESTED_DATE
    , B.CONTACT_PHONE
    , B.CONTACT_EMAIL
    , PROV.LOAD_TIME
    , PROV.FILENAME
    , CASE WHEN C.STATUS = 'A' then 'A - Add Provider Language'
    WHEN C.STATUS = 'D' THEN 'D - Delete Provider Language' END AS CHANGE_TYPE
    ,'Provider Language' as AREA_AFFECTED
    , CASE WHEN C.STATUS = 'A' THEN 'Add Provider Language'
    WHEN C.STATUS = 'D' THEN 'Delete Provider Language' END AS CHANGE_REQUIRED,
    'Accepted' as CHANGE_TYPE_CLASSIFICATION
    FROM &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PROVIDERINFO_VW PROV
    JOIN PROVIDER_ATTESTATION.LKP_LEXIS_NEXIS_CACTUS_PROVIDER_DETAIL_SELECT_VW PD 
        ON PROV.PAYER_PROVIDER_ID = PD.SOURCE_PROVIDER_NBR
    LEFT JOIN  (SELECT * , ROW_NUMBER() OVER(PARTITION BY UNIVERSAL_PROVIDER_ID ORDER BY ANCILLARY_PROVIDER_IND DESC,PROVIDER_ADDRESS_START_DATE DESC) AS ROW_NBR FROM PROVIDER_ATTESTATION.LKP_LEXIS_NEXIS_CACTUS_PROVIDER_ADDRESS_SELECT_VW) PA 
        ON PROV.PAYER_PROVIDER_ID = PA.SOURCE_PROVIDER_NBR
    INNER JOIN &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PROVIDERLANGUAGES_VW C
        ON PROV.ATTESTED_ENTITY_UNIQUE_ID = C.ATTESTED_ENTITY_UNIQUE_ID
        AND PROV.ATTESTED_DATE = C.ATTESTED_DATE
    INNER JOIN &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_ATTESTATIONSUMMARY_VW B
        ON PROV.ATTESTED_ENTITY_UNIQUE_ID = B.ENTITY_UNIQUE_ID
        AND PROV.ATTESTED_DATE = B.ATTESTED_DATE
    WHERE SUBSTR(PROV.FILENAME, LENGTH(PROV.FILENAME) - 11, 8) = (
            SELECT MAX(SUBSTR(FILENAME, LENGTH(FILENAME) - 11, 8)) FROM &{IDAP_LAKE}.PROVIDER.LEXISNEXIS_PROVIDERINFO_VW) 
            AND (UPPER(PROV.USER_DEF_02) IN ('HEALTH PLAN DIRECT CREDENTIAL', 'SKYGEN') OR PROV.USER_DEF_02 IS NULL)
        AND PA.ROW_NBR = 1
        AND C.STATUS IN ('A', 'D')
        AND (C.PROVIDER_LANGUAGE_VERIFIED) <> 'ENGLISH');
!set variable_substitution=false;