create or replace VIEW GREENBACK.PLAN_DESIGN_EXTRACT_UPMC_OUTBOUND_VW 
COMMENT = 'UPMC to GBH Plan Design Extract'
AS
SELECT 
    TO_CHAR(PLAN_EFFECTIVE_DATE, 'MM/DD/YYYY') AS PLAN_EFFECTIVE_DATE,
    TO_CHAR(PLAN_TERM_DATE, 'MM/DD/YYYY') AS PLAN_TERM_DATE,
	PLAN_ID,
	FORMULARY_ID,
    MAX_EMBEDDED_DED_AMOUNT,
	MAX_FAMILY_DEDUCTIBLE,
	MAX_INDIVIDUAL_DEDUCTIBLE,
	MAX_EMBEDDED_OOP_AMOUNT,
	MAX_FAMILY_OOP_AMOUNT,
    MAX_INDIVIDUAL_OOP_AMOUNT,
	SUB_FAM_IND,
	FORMULARY_TIER,
	NETWORK_NAME,
	-- Ensure IS_DEDUCTIBLE_REQUIRED is always populated with Yes/No; default null or blank source values to 'No' 
	COALESCE(NULLIF(TRIM(IS_DEDUCTIBLE_REQUIRED), ''), 'No') AS IS_DEDUCTIBLE_REQUIRED,
	COPAY,
	COINSURANCE,
	COINSURANCE_MINIMUM_COST,
	COINSURANCE_MAXIMUM_COST,
	ANNUAL_COINSURANCE_CAP
    FROM GREENBACK.PLAN_DESIGN_EXTRACT_UPMC_OUTBOUND
    WHERE IS_LOGICAL_DELETE_FLAG=FALSE;