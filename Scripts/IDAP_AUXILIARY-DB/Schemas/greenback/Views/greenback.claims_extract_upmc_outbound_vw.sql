CREATE OR REPLACE VIEW GREENBACK.CLAIMS_EXTRACT_UPMC_OUTBOUND_VW
COMMENT = 'WEEKLY ESI F14 CLAIM FILE TO GBH'
 AS
SELECT DISTINCT
    --CLIENT_ID_LKP BASED ON COMPANY_CODE, PLAN_TYPE, CORP_ID, ESI_PLAN_TYPE
    CASE
        WHEN DWOAO_GROUPS.ESIPLANOVERRIDE <> '' THEN DWOAO_GROUPS.ESIPLANOVERRIDE
        -- 0000 (G223) 
        WHEN RX_PLAN.CORPORATION_ID = 'G223' AND DIM_RIDER.COMPANY_CODE = 'A' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('P') THEN '0000'
        -- 0115 (S036) 
        WHEN RX_PLAN.CORPORATION_ID = 'S036' AND DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('N','O') THEN '0115'
        -- 0116 (AON1) 
        WHEN RX_PLAN.CORPORATION_ID = 'AON1' AND DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('P') THEN '0116'
        -- 0118 (F275)
        WHEN RX_PLAN.CORPORATION_ID = 'F275' AND DIM_RIDER.COMPANY_CODE = 'P' AND LEFT(LEFT(RX_PLAN.PRODUCT_CODE, 1), 1) IN ('2','H') THEN '0118'
        WHEN RX_PLAN.CORPORATION_ID = 'F275' AND DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(LEFT(RX_PLAN.PRODUCT_CODE, 1), 1) IN ('3','5','E','H','N','O','P') THEN '0118'
        WHEN RX_PLAN.CORPORATION_ID = 'F275' AND DIM_RIDER.COMPANY_CODE = 'N' AND LEFT(LEFT(RX_PLAN.PRODUCT_CODE, 1), 1) IN ('E','H','P') THEN '0118'
        WHEN RX_PLAN.CORPORATION_ID = 'F275' AND DIM_RIDER.COMPANY_CODE = 'C' AND LEFT(LEFT(RX_PLAN.PRODUCT_CODE, 1), 1) IN ('H','J') THEN '0118'
        WHEN RX_PLAN.CORPORATION_ID = 'F275' AND DIM_RIDER.COMPANY_CODE = 'A' AND LEFT(LEFT(RX_PLAN.PRODUCT_CODE, 1), 1) IN ('W') THEN '0118'
        -- 0119 (PB35)
        WHEN RX_PLAN.CORPORATION_ID = 'PB35' AND DIM_RIDER.COMPANY_CODE = 'P' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('H') THEN '0119'
        WHEN RX_PLAN.CORPORATION_ID = 'PB35' AND DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('P') THEN '0119'
        -- 0131 (OEXC)
        WHEN RX_PLAN.CORPORATION_ID = 'OEXC' AND DIM_RIDER.COMPANY_CODE = 'C' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('I') THEN '0131'
        WHEN RX_PLAN.CORPORATION_ID = 'OEXC' AND DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('I','N','O') THEN '0131'
        WHEN RX_PLAN.CORPORATION_ID = 'OEXC' AND DIM_RIDER.COMPANY_CODE = 'P' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('I') THEN '0131'
        --0160 (EXCH)
        WHEN RX_PLAN.CORPORATION_ID = 'EXCH' AND DIM_RIDER.COMPANY_CODE = 'C' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('I','X') THEN '0160'
        WHEN RX_PLAN.CORPORATION_ID = 'EXCH' AND DIM_RIDER.COMPANY_CODE = 'N' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('I','X') THEN '0160'
        WHEN RX_PLAN.CORPORATION_ID = 'EXCH' AND DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('I','N','O') THEN '0160'
        WHEN RX_PLAN.CORPORATION_ID = 'EXCH' AND DIM_RIDER.COMPANY_CODE = 'P' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('I','X') THEN '0160'
        --0170 (SHOP)
        WHEN RX_PLAN.CORPORATION_ID = 'SHOP' AND DIM_RIDER.COMPANY_CODE = 'B' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('3','5') THEN '0170'
        WHEN RX_PLAN.CORPORATION_ID = 'SHOP' AND DIM_RIDER.COMPANY_CODE = 'C' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('3','I') THEN '0170'
        WHEN RX_PLAN.CORPORATION_ID = 'SHOP' AND DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('3','5','E','H','I','P') THEN '0170'
        WHEN RX_PLAN.CORPORATION_ID = 'SHOP' AND DIM_RIDER.COMPANY_CODE = 'N' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('E','P') THEN '0170'
        WHEN RX_PLAN.CORPORATION_ID = 'SHOP' AND DIM_RIDER.COMPANY_CODE = 'P' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('H') THEN '0170'
        --0171 (SHOP)
        WHEN RX_PLAN.CORPORATION_ID = 'SHOP' AND DIM_RIDER.COMPANY_CODE = 'C' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('E','H','J') THEN '0171'
        -- CORP_ID = 'ANY'
        -- 0100
        WHEN DIM_RIDER.COMPANY_CODE = 'C' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('2','J') THEN '0100'
        WHEN DIM_RIDER.COMPANY_CODE = 'P' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('2')     THEN '0100'
        WHEN DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('3','5','E','H','N','O','P') THEN '0100'
        WHEN DIM_RIDER.COMPANY_CODE = 'N' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('E','H','P') THEN '0100'
        WHEN DIM_RIDER.COMPANY_CODE = 'A' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('W')     THEN '0100'
        -- 0110
        WHEN DIM_RIDER.COMPANY_CODE = 'C' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('H')     THEN '0110'
        WHEN DIM_RIDER.COMPANY_CODE = 'P' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('H')     THEN '0110'
        -- 0115
        WHEN DIM_RIDER.COMPANY_CODE = 'B' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('I')     THEN '0115'
        WHEN DIM_RIDER.COMPANY_CODE = 'C' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('I','X') THEN '0115'
        WHEN DIM_RIDER.COMPANY_CODE = 'N' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('I')     THEN '0115'
        WHEN DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('I')     THEN '0115'
        WHEN DIM_RIDER.COMPANY_CODE = 'P' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('I','N','X') THEN '0115'
        -- 0121
        WHEN DIM_RIDER.COMPANY_CODE = 'A' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('3','5','E','H','P','Z') THEN '0121'
        -- 0132
        WHEN DIM_RIDER.COMPANY_CODE = 'B' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('3','5','P') THEN '0132'
        -- 0140
        WHEN DIM_RIDER.COMPANY_CODE = 'N' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('Y')     THEN '0140'
        -- 0150
        WHEN DIM_RIDER.COMPANY_CODE = 'A' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('Y')     THEN '0150'
        WHEN DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('Y')     THEN '0150'
        -- 0220
        WHEN DIM_RIDER.COMPANY_CODE = 'M' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('B')     THEN '0220'
        -- 0300
        WHEN DIM_RIDER.COMPANY_CODE = 'C' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('K')     THEN '0300'
        WHEN DIM_RIDER.COMPANY_CODE = 'P' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('K')     THEN '0300'
        -- 0400
        WHEN DIM_RIDER.COMPANY_CODE = 'B' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('Q','S') THEN '0400'
        -- 0630
        WHEN DIM_RIDER.COMPANY_CODE = 'M' AND LEFT(RX_PLAN.PRODUCT_CODE, 1) IN ('C')     THEN '0630'
        ELSE NULL
    END AS CLIENT_ID,
    TRIM(ESI.CARDHOLDER_ID_NUMBER) AS MEMBER_ID,--Removing white spaces
    ESI.CLAIM_ID AS RX_SOURCE_CLAIM_ID,

    -- Lookup to get the Claim status based on the TRANSACTION_TYPE_CODE
    CASE
        WHEN ESI.TRANSACTION_TYPE_CODE = 31 THEN 'P'
        WHEN ESI.TRANSACTION_TYPE_CODE = 32 THEN 'X'
        WHEN ESI.TRANSACTION_TYPE_CODE = 36 THEN 'P'
        WHEN ESI.TRANSACTION_TYPE_CODE = 37 THEN 'X'
        WHEN ESI.TRANSACTION_TYPE_CODE = 42 THEN 'X'
        ELSE ''
    END AS CLM_STATUS,
        
    CAST(ESI.ADJUDICATION_DATE AS DATE) AS CLAIM_PAID_DATE,
    CAST(ESI.DATE_FILLED AS DATE) AS CLAIM_FILL_DATE,
    ESI.NDC_NUMBER AS NDC,
    TRUNCATE(TO_CHAR(ESI.COPAY_TIER_LEVEL_NUMBER*100)) as Tier,
    ESI.METRIC_QUANTITY AS QUANTITY,
    ESI.DAY_SUPPLY AS DAYS_SUPPLY,
    (ESI.AMOUNT_BILLED + ESI.ADMIN_FEE) AS PLAN_COST,
    ESI.CO_PAY_AMOUNT AS MEMBER_COST,
    (ESI.AMOUNT_BILLED + ESI.ADMIN_FEE) + ESI.CO_PAY_AMOUNT AS TOTAL_COST,
    ESI.PRESCRIBER_IDENTIFIER AS PRESCRIBER_NPI,
    ESI.PHARMACY_IDENTIFIER AS PHARMACY_NPI 
     FROM IDW.EDW_USR_TAB.ESI_CLAIM_RECORD_F14_VW AS ESI
    LEFT OUTER JOIN MC400.DWOAO.GROUPS AS DWOAO_GROUPS
    ON SUBSTR(TRIM(ESI.GROUP_NUMBER), -9,6)= DWOAO_GROUPS.GROUPNBR
    INNER JOIN IDW.EDW_RPT.PHARMACY_UNRESOLVED AS UNRESOLVED
    ON ESI.CLAIM_ID = UNRESOLVED.ADJUSTMENT_CLAIM_ID
    INNER JOIN IDW.EDW_RPT.PHARMACY_FACT AS RX_FACT
    ON UNRESOLVED.PHARMACY_UNRESOLVED_KEY = RX_FACT.PHARMACY_UNRESOLVED_KEY
    INNER JOIN IDW.EDW_RPT.RIDER AS RIDER
    ON RX_FACT.RIDER_KEY = RIDER.RIDER_KEY
    INNER JOIN IDAP.DIMDATA.DIM_RIDER_VW AS DIM_RIDER
    ON SUBSTR(RIDER.DIVISION_ID,1,6) = DIM_RIDER.GROUP_NBR
    AND SUBSTR(RIDER.DIVISION_ID,7,3) = DIM_RIDER.SUB_GROUP_NBR
    AND DIM_RIDER.TPA_CLIENT_ID = '000001' 
    AND DIM_RIDER.TPA_ID = '000001'
    AND DIM_RIDER.TPA_DIV_ID = '0001'
    AND RIDER.RIDER_TYPE = DIM_RIDER.RIDER_TYPE_CODE
    AND RIDER.RIDER_EFFECTIVE_DATE = DIM_RIDER.RIDER_EFFECTIVE_DATE
    INNER JOIN IDW.EDW_RPT.PLAN AS RX_PLAN
    ON RX_FACT.PLAN_KEY = RX_PLAN.PLAN_KEY
    WHERE 
      ESI.ESI_BILLING_DATE = (SELECT MAX(ESI_BILLING_DATE)
       FROM
       IDW.EDW_USR_TAB.ESI_CLAIM_RECORD_F14_VW)
    AND
    SUBSTR(TRIM(ESI.GROUP_NUMBER),-9) NOT LIKE 'MA%' 
    AND 
    SUBSTR(TRIM(ESI.GROUP_NUMBER),-9) NOT LIKE 'MC%'
    AND
    (SUBSTR(ESI.GROUP_NUMBER,1,3) <>'MS0'
    AND 
    SUBSTR(TRIM(ESI.GROUP_NUMBER),-1,1) <> 'G')
    AND
    SUBSTR(TRIM(ESI.CLAIM_ID),1,1) <> 'G'
    AND 
    SUBSTR(TRIM(ESI.GROUP_NUMBER),-9) NOT LIKE 'KIDS%' -- Exclude CHIP
    -- Exclude Groups -> FEHB, PSHB, Go Health and any groups which uses Value Choice Formulary
        AND RX_PLAN.CORPORATION_ID NOT IN ('F275','PB35','5A02', 'C633','DS94','O267','CZ35')
        AND RX_PLAN.BUSINESS_INSURED_TYPE = 'FULLY INSURED';