CREATE OR REPLACE VIEW GREENBACK.ELIGIBILITY_EXTRACT_UPMC_OUTBOUND_VW
COMMENT = 'UPMC to GBH Eligibility Extract'
AS

-- Deduplicate business-level enrollment records and retain the latest subgroup
WITH ELIGIBILITY_ENROLLMENT_BASE AS (
    SELECT
        FACT_ENROLLMENT.DIM_MEMBER_KEY,
        FACT_ENROLLMENT.DIM_ENROLLMENT_SPAN_KEY,
        FACT_ENROLLMENT.DIM_PLAN_KEY,
        FACT_ENROLLMENT.DIM_RIDER_KEY,
        FACT_ENROLLMENT.DIM_GROUP_KEY,
        FACT_ENROLLMENT.DIM_SUB_GROUP_KEY,
        FACT_ENROLLMENT.LAST_UPDATED_DATETIME,
        FACT_ENROLLMENT.INSERT_DATETIME,

        DIM_MEMBER.MEMBER_NBR,
        DIM_MEMBER.PERSON_NBR,
        TO_DATE(DIM_ENROLLMENT_SPAN.ELIGIBILITY_START_DATE) AS COV_START_DT,
        TO_DATE(DIM_ENROLLMENT_SPAN.ELIGIBILITY_END_DATE) AS COV_END_DT,
        DIM_RIDER.RIDER_CODE AS PLAN_ID,
        DIM_GROUP.GROUP_NBR,

        -- Rank duplicate business-level enrollment rows to keep the most recently updated subgroup record
        ROW_NUMBER() OVER (
            PARTITION BY
                DIM_MEMBER.MEMBER_NBR,
                DIM_MEMBER.PERSON_NBR,
                DIM_MEMBER.MEMBER_BIRTH_DATE,
                TO_DATE(DIM_ENROLLMENT_SPAN.ELIGIBILITY_START_DATE),
                TO_DATE(DIM_ENROLLMENT_SPAN.ELIGIBILITY_END_DATE),
                DIM_RIDER.RIDER_CODE,
                DIM_GROUP.GROUP_NBR
            ORDER BY
                FACT_ENROLLMENT.LAST_UPDATED_DATETIME DESC,
                FACT_ENROLLMENT.INSERT_DATETIME DESC,
                FACT_ENROLLMENT.DIM_SUB_GROUP_KEY DESC
        ) AS RN
    FROM IDAP.DIMDATA.FACT_ENROLLMENT_VW AS FACT_ENROLLMENT

    INNER JOIN IDAP.DIMDATA.DIM_MEMBER AS DIM_MEMBER
        ON FACT_ENROLLMENT.DIM_MEMBER_KEY = DIM_MEMBER.DIM_MEMBER_KEY

    INNER JOIN IDAP.DIMDATA.DIM_ENROLLMENT_SPAN_VW AS DIM_ENROLLMENT_SPAN
        ON DIM_ENROLLMENT_SPAN.DIM_ENROLLMENT_SPAN_KEY = FACT_ENROLLMENT.DIM_ENROLLMENT_SPAN_KEY

    INNER JOIN IDAP.DIMDATA.DIM_PLAN_VW AS DIM_PLAN
        ON DIM_PLAN.DIM_PLAN_KEY = FACT_ENROLLMENT.DIM_PLAN_KEY

    INNER JOIN IDAP.DIMDATA.DIM_RIDER_VW AS DIM_RIDER
        ON DIM_RIDER.DIM_RIDER_KEY = FACT_ENROLLMENT.DIM_RIDER_KEY
       AND DIM_RIDER.RIDER_TYPE_CODE = 'RX'

    INNER JOIN IDAP.DIMDATA.DIM_GROUP_VW AS DIM_GROUP
        ON FACT_ENROLLMENT.DIM_GROUP_KEY = DIM_GROUP.DIM_GROUP_KEY

    INNER JOIN IDAP.DIMDATA.DIM_SUB_GROUP_VW AS DIM_SUB_GROUP
        ON DIM_SUB_GROUP.DIM_SUB_GROUP_KEY = FACT_ENROLLMENT.DIM_SUB_GROUP_KEY
       AND DIM_SUB_GROUP.GROUP_NBR = DIM_GROUP.GROUP_NBR

    WHERE
        DIM_ENROLLMENT_SPAN.ELIGIBILITY_START_DATE <= CURRENT_DATE()
        AND DIM_ENROLLMENT_SPAN.ELIGIBILITY_END_DATE > CURRENT_DATE()
        AND DIM_ENROLLMENT_SPAN.ELIGIBILITY_START_DATE <> DIM_ENROLLMENT_SPAN.ELIGIBILITY_END_DATE
        AND DIM_ENROLLMENT_SPAN.SUB_SOURCE_NAME = 'MEDICAL UPMC'
        AND FACT_ENROLLMENT.DIM_ENROLLMENT_SPAN_KEY <> '4002'
        AND DIM_PLAN.LOB_CODE = 'CM'
        AND DIM_PLAN.FUNDING_TYPE_DESC = 'FULLY INSURED'
        AND DIM_PLAN.TPA_DIV_ID = '0001'
        AND DIM_GROUP.CORPORATE_ID NOT IN ('F275', 'PB35', '5A02', 'C633', 'DS94', 'O267', 'CZ35')
        AND DIM_ENROLLMENT_SPAN.IS_LOGICAL_DELETE_FLAG = FALSE

        AND NOT EXISTS (
            SELECT 1
            FROM MC400.DWOAO.POLICYHOLDERCOB AS PL
            INNER JOIN MC400.DWOAO.MEMBERCOB AS COB
                ON COB.SUBSCRIBERNUMBER = PL.SUBSCRIBERNUMBER
               AND COB.PERSONNBR = PL.PERSONNBR
               AND COB.POLICYADDTIME = PL.POLICYADDTIME
            WHERE PL.SUBSCRIBERNUMBER = LEFT(DIM_MEMBER.MEMBER_NBR, LENGTH(DIM_MEMBER.MEMBER_NBR) - 2)
              AND PL.PERSONNBR = DIM_MEMBER.PERSON_NBR
              AND COB.COBPROVISION = 'S'
              AND PL.POLICYEFFDATE <> PL.POLICYTERMDATE
              AND TRY_TO_DATE(TO_VARCHAR(PL.POLICYEFFDATE), 'YYYYMMDD') <= CURRENT_DATE()
              AND (
                    TRY_TO_DATE(TO_VARCHAR(PL.POLICYTERMDATE), 'YYYYMMDD') > CURRENT_DATE()
                    OR PL.POLICYTERMDATE = 99999999
                  )
        )
),

ELIGIBILITY_ENROLLMENT_LATEST AS (
    SELECT *
    FROM ELIGIBILITY_ENROLLMENT_BASE
    WHERE RN = 1
)

SELECT DISTINCT
    DIM_MEMBER.MEMBER_NBR AS MEMBER_ID, -- A unique number assigned to each family member under the subscriber's insurance contract
    DIM_MEMBER.PERSON_NBR AS PERSON_CODE, -- A unique counter within each contract used to distinguish each member covered by the contract or who was ever covered

    -- CCID Fix: Remove leading non-numeric characters (e.g., hidden LF / 0x0A)
    NULLIF(
        REGEXP_REPLACE(TRIM(DWOAO_ELIGIBILITYHISTORY.CONSUMERCONNECTID), '^[^0-9]+', ''),
        ''
    ) AS ALT_MBR_ID,

    DIM_MEMBER.MEMBER_FIRST_NAME AS MBR_FIRST_NAME,
    NULLIF(TRIM(DIM_MEMBER.MEMBER_MIDDLE_NAME), 'UNKNOWN') AS MBR_MIDDLE_NAME,
    NULLIF(TRIM(DIM_MEMBER.MEMBER_LAST_NAME), 'UNKNOWN') AS MBR_LAST_NAME,
    DIM_MEMBER.GENDER_CODE AS GENDER, -- U, F, M
    DIM_MEMBER.MEMBER_BIRTH_DATE AS DT_OF_BIRTH, -- YYYY-MM-DD

    DIM_MEMBER_ADDRESS.MEMBER_ADDRESSLINE1_TEXT AS MBR_ADDR_LINE_1,
    DIM_MEMBER_ADDRESS.MEMBER_ADDRESSLINE2_TEXT AS MBR_ADDR_LINE_2,
    DIM_MEMBER_ADDRESS.MEMBER_CITY_NAME AS CITY,
    DIM_MEMBER_ADDRESS.MEMBER_FIPS_STATE_CODE AS STATE,
    DIM_MEMBER_ADDRESS.VERIFIED_ZIPCODE5_NBR AS ZIP_CD,

    -- Standardize phone numbers: keep digits only
    REGEXP_REPLACE(MEMBER_PREFERENCE.MOBILE_PHONE_NUMBER, '[^0-9]', '') AS MOBILE_PHONE,
    REGEXP_REPLACE(MEMBER_PREFERENCE.HOME_PHONE_NUMBER, '[^0-9]', '') AS HOME_PHONE,

    MEMBER_PREFERENCE.EMAIL_ADDRESS AS PRIMARY_EMAIL_ADDR,
    NULL AS SECARY_EMAIL_ADDR, -- Currently we do not have a separate field for secondary email address
    DIM_MEMBER.SUBSCRIBER_RELATIONSHIP_CODE AS RELAT_CD,
    TO_DATE(DIM_ENROLLMENT_SPAN.ELIGIBILITY_START_DATE) AS COV_START_DT,
    TO_DATE(DIM_ENROLLMENT_SPAN.ELIGIBILITY_END_DATE) AS COV_END_DT,
    DIM_RIDER.RIDER_CODE AS PLAN_ID, -- Where RIDER_TYPE_CODE = 'RX'
    DIM_RIDER.RIDER_DESC AS PLAN_NAME,
    CONCAT(DIM_GROUP.CORPORATE_ID, DIM_GROUP.GROUP_NBR, DIM_SUB_GROUP.SUB_GROUP_NBR) AS GROUP_ID,
    NULLIF(TRIM(DIM_GROUP.GROUP_NAME), 'Unknown') AS GROUP_NAME,
    DIM_SUB_GROUP.SUB_GROUP_NBR AS SUB_GROUP_ID,
    NULLIF(TRIM(DIM_SUB_GROUP.SUB_GROUP_NAME), 'Unknown') AS SUB_GROUP_NAME,

    -- CLIENT_ID_LKP BASED ON COMPANY_CODE, PLAN_TYPE, CORP_ID, ESI_PLAN_TYPE
    CASE
        WHEN DWOAO_GROUPS.ESIPLANOVERRIDE <> '' THEN DWOAO_GROUPS.ESIPLANOVERRIDE

        -- 0000 (G223)
        WHEN DIM_GROUP.CORPORATE_ID = 'G223' AND DIM_RIDER.COMPANY_CODE = 'A' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('P') THEN '0000'

        -- 0115 (S036)
        WHEN DIM_GROUP.CORPORATE_ID = 'S036' AND DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('N', 'O') THEN '0115'

        -- 0116 (AON1)
        WHEN DIM_GROUP.CORPORATE_ID = 'AON1' AND DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('P') THEN '0116'

        -- 0118 (F275)
        WHEN DIM_GROUP.CORPORATE_ID = 'F275' AND DIM_RIDER.COMPANY_CODE = 'P' AND LEFT(LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1), 1) IN ('2', 'H') THEN '0118'
        WHEN DIM_GROUP.CORPORATE_ID = 'F275' AND DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1), 1) IN ('3', '5', 'E', 'H', 'N', 'O', 'P') THEN '0118'
        WHEN DIM_GROUP.CORPORATE_ID = 'F275' AND DIM_RIDER.COMPANY_CODE = 'N' AND LEFT(LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1), 1) IN ('E', 'H', 'P') THEN '0118'
        WHEN DIM_GROUP.CORPORATE_ID = 'F275' AND DIM_RIDER.COMPANY_CODE = 'C' AND LEFT(LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1), 1) IN ('H', 'J') THEN '0118'
        WHEN DIM_GROUP.CORPORATE_ID = 'F275' AND DIM_RIDER.COMPANY_CODE = 'A' AND LEFT(LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1), 1) IN ('W') THEN '0118'

        -- 0119 (PB35)
        WHEN DIM_GROUP.CORPORATE_ID = 'PB35' AND DIM_RIDER.COMPANY_CODE = 'P' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('H') THEN '0119'
        WHEN DIM_GROUP.CORPORATE_ID = 'PB35' AND DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('P') THEN '0119'

        -- 0131 (OEXC)
        WHEN DIM_GROUP.CORPORATE_ID = 'OEXC' AND DIM_RIDER.COMPANY_CODE = 'C' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('I') THEN '0131'
        WHEN DIM_GROUP.CORPORATE_ID = 'OEXC' AND DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('I', 'N', 'O') THEN '0131'
        WHEN DIM_GROUP.CORPORATE_ID = 'OEXC' AND DIM_RIDER.COMPANY_CODE = 'P' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('I') THEN '0131'

        -- 0160 (EXCH)
        WHEN DIM_GROUP.CORPORATE_ID = 'EXCH' AND DIM_RIDER.COMPANY_CODE = 'C' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('I', 'X') THEN '0160'
        WHEN DIM_GROUP.CORPORATE_ID = 'EXCH' AND DIM_RIDER.COMPANY_CODE = 'N' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('I', 'X') THEN '0160'
        WHEN DIM_GROUP.CORPORATE_ID = 'EXCH' AND DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('I', 'N', 'O') THEN '0160'
        WHEN DIM_GROUP.CORPORATE_ID = 'EXCH' AND DIM_RIDER.COMPANY_CODE = 'P' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('I', 'X') THEN '0160'

        -- 0170 (SHOP)
        WHEN DIM_GROUP.CORPORATE_ID = 'SHOP' AND DIM_RIDER.COMPANY_CODE = 'B' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('3', '5') THEN '0170'
        WHEN DIM_GROUP.CORPORATE_ID = 'SHOP' AND DIM_RIDER.COMPANY_CODE = 'C' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('3', 'I') THEN '0170'
        WHEN DIM_GROUP.CORPORATE_ID = 'SHOP' AND DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('3', '5', 'E', 'H', 'I', 'P') THEN '0170'
        WHEN DIM_GROUP.CORPORATE_ID = 'SHOP' AND DIM_RIDER.COMPANY_CODE = 'N' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('E', 'P') THEN '0170'
        WHEN DIM_GROUP.CORPORATE_ID = 'SHOP' AND DIM_RIDER.COMPANY_CODE = 'P' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('H') THEN '0170'

        -- 0171 (SHOP)
        WHEN DIM_GROUP.CORPORATE_ID = 'SHOP' AND DIM_RIDER.COMPANY_CODE = 'C' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('E', 'H', 'J') THEN '0171'

        -- CORP_ID = 'ANY'
        -- 0100
        WHEN DIM_RIDER.COMPANY_CODE = 'C' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('2', 'J') THEN '0100'
        WHEN DIM_RIDER.COMPANY_CODE = 'P' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('2') THEN '0100'
        WHEN DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('3', '5', 'E', 'H', 'N', 'O', 'P') THEN '0100'
        WHEN DIM_RIDER.COMPANY_CODE = 'N' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('E', 'H', 'P') THEN '0100'
        WHEN DIM_RIDER.COMPANY_CODE = 'A' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('W') THEN '0100'

        -- 0110
        WHEN DIM_RIDER.COMPANY_CODE = 'C' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('H') THEN '0110'
        WHEN DIM_RIDER.COMPANY_CODE = 'P' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('H') THEN '0110'

        -- 0115
        WHEN DIM_RIDER.COMPANY_CODE = 'B' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('I') THEN '0115'
        WHEN DIM_RIDER.COMPANY_CODE = 'C' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('I', 'X') THEN '0115'
        WHEN DIM_RIDER.COMPANY_CODE = 'N' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('I') THEN '0115'
        WHEN DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('I') THEN '0115'
        WHEN DIM_RIDER.COMPANY_CODE = 'P' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('I', 'N', 'X') THEN '0115'

        -- 0121
        WHEN DIM_RIDER.COMPANY_CODE = 'A' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('3', '5', 'E', 'H', 'P', 'Z') THEN '0121'

        -- 0132
        WHEN DIM_RIDER.COMPANY_CODE = 'B' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('3', '5', 'P') THEN '0132'

        -- 0140
        WHEN DIM_RIDER.COMPANY_CODE = 'N' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('Y') THEN '0140'

        -- 0150
        WHEN DIM_RIDER.COMPANY_CODE = 'A' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('Y') THEN '0150'
        WHEN DIM_RIDER.COMPANY_CODE = 'O' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('Y') THEN '0150'

        -- 0220
        WHEN DIM_RIDER.COMPANY_CODE = 'M' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('B') THEN '0220'

        -- 0300
        WHEN DIM_RIDER.COMPANY_CODE = 'C' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('K') THEN '0300'
        WHEN DIM_RIDER.COMPANY_CODE = 'P' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('K') THEN '0300'

        -- 0400
        WHEN DIM_RIDER.COMPANY_CODE = 'B' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('Q', 'S') THEN '0400'

        -- 0630
        WHEN DIM_RIDER.COMPANY_CODE = 'M' AND LEFT(DIM_PLAN.PLAN_TYPE_CODE, 1) IN ('C') THEN '0630'

        ELSE NULL
    END AS CLIENT_ID

FROM ELIGIBILITY_ENROLLMENT_LATEST AS FACT_ENROLLMENT

-- DIM_MEMBER -- Sourcing from the base table as the view has restricted data
INNER JOIN IDAP.DIMDATA.DIM_MEMBER AS DIM_MEMBER
    ON FACT_ENROLLMENT.DIM_MEMBER_KEY = DIM_MEMBER.DIM_MEMBER_KEY

-- DIM_MEMBER_ADDRESS
-- Picks one address per member by prioritizing active records first (if present),
-- otherwise falls back to any record, then ranks address type: H6 > Mailing > Physical
LEFT JOIN (
    SELECT *
    FROM IDAP.DIMDATA.DIM_MEMBER_ADDRESS_VW
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY DIM_MEMBER_KEY
        ORDER BY
            CASE
                WHEN ACTIVE_IND = 'Y' THEN 1
                ELSE 2
            END,
            CASE
                WHEN MEMBER_ADDRESS_TYPE = 'H6' THEN 1
                WHEN MEMBER_ADDRESS_TYPE = 'Mailing' THEN 2
                WHEN MEMBER_ADDRESS_TYPE = 'Physical' THEN 3
                ELSE 4
            END
    ) = 1
) AS DIM_MEMBER_ADDRESS
    ON DIM_MEMBER.DIM_MEMBER_KEY = DIM_MEMBER_ADDRESS.DIM_MEMBER_KEY

-- DIM_ENROLLMENT_SPAN
INNER JOIN IDAP.DIMDATA.DIM_ENROLLMENT_SPAN_VW AS DIM_ENROLLMENT_SPAN
    ON DIM_ENROLLMENT_SPAN.DIM_ENROLLMENT_SPAN_KEY = FACT_ENROLLMENT.DIM_ENROLLMENT_SPAN_KEY

-- DIM_PLAN
INNER JOIN IDAP.DIMDATA.DIM_PLAN_VW AS DIM_PLAN
    ON DIM_PLAN.DIM_PLAN_KEY = FACT_ENROLLMENT.DIM_PLAN_KEY

-- DIM_RIDER -- Business confirmed that this should be RX RIDER assigned to this group
INNER JOIN IDAP.DIMDATA.DIM_RIDER_VW AS DIM_RIDER
    ON DIM_RIDER.DIM_RIDER_KEY = FACT_ENROLLMENT.DIM_RIDER_KEY
   AND DIM_RIDER.RIDER_TYPE_CODE = 'RX'

-- DIM_GROUP
INNER JOIN IDAP.DIMDATA.DIM_GROUP_VW AS DIM_GROUP
    ON FACT_ENROLLMENT.DIM_GROUP_KEY = DIM_GROUP.DIM_GROUP_KEY

-- DIM_SUB_GROUP
INNER JOIN IDAP.DIMDATA.DIM_SUB_GROUP_VW AS DIM_SUB_GROUP
    ON DIM_SUB_GROUP.DIM_SUB_GROUP_KEY = FACT_ENROLLMENT.DIM_SUB_GROUP_KEY
   AND DIM_SUB_GROUP.GROUP_NBR = DIM_GROUP.GROUP_NBR

-- COMMUNICATION FROM IDAP_LAKE
LEFT JOIN (
    SELECT
        MEMBER_ID,
        TPA_CLIENT,
        TPA_ID,
        TPA_DIV,
        MOBILE_PHONE_NUMBER,
        HOME_PHONE_NUMBER,
        EMAIL_ADDRESS,
        SOURCE_LAST_UPDATED_DATE
    FROM IDAP_LAKE.MEMBER.MEMBER_PREFERENCES_VW
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY MEMBER_ID, TPA_CLIENT, TPA_ID, TPA_DIV
        ORDER BY SOURCE_LAST_UPDATED_DATE DESC
    ) = 1
) AS MEMBER_PREFERENCE
    ON MEMBER_PREFERENCE.MEMBER_ID = DIM_MEMBER.MEMBER_NBR
   AND MEMBER_PREFERENCE.TPA_CLIENT = DIM_MEMBER.TPA_CLIENT_ID
   AND MEMBER_PREFERENCE.TPA_ID = DIM_MEMBER.TPA_ID
   AND MEMBER_PREFERENCE.TPA_DIV = DIM_MEMBER.TPA_DIV_ID

-- CCID FROM DWOAO
LEFT JOIN MC400.DWOAO.ELIGIBILITYHISTORY AS DWOAO_ELIGIBILITYHISTORY
    ON DWOAO_ELIGIBILITYHISTORY.TPACLIENT = DIM_ENROLLMENT_SPAN.TPA_CLIENT_ID
   AND DWOAO_ELIGIBILITYHISTORY.TPADIVISION = DIM_ENROLLMENT_SPAN.TPA_DIV_ID
   AND DWOAO_ELIGIBILITYHISTORY.TPAIDOFCLIENT = DIM_ENROLLMENT_SPAN.TPA_ID
   AND DWOAO_ELIGIBILITYHISTORY.MEMBERNBR = DIM_ENROLLMENT_SPAN.MEMBER_NBR
   AND TO_TIMESTAMP_NTZ(TO_VARCHAR(DWOAO_ELIGIBILITYHISTORY.ELIGIBILITYSTARTDATE), 'YYYYMMDD') = DIM_ENROLLMENT_SPAN.ELIGIBILITY_START_DATE

-- ESI_PLAN_OVERRIDE from DWOAO.GROUPS
LEFT JOIN MC400.DWOAO.GROUPS AS DWOAO_GROUPS
    ON DWOAO_GROUPS.TPACLIENT = DIM_GROUP.TPA_CLIENT_ID
   AND DWOAO_GROUPS.TPADIVISION = DIM_GROUP.TPA_DIV_ID
   AND DWOAO_GROUPS.TPAIDOFCLIENT = DIM_GROUP.TPA_ID
   AND DWOAO_GROUPS.GROUPNBR = DIM_GROUP.GROUP_NBR
;
