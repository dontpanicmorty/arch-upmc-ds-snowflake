CREATE OR REPLACE VIEW EPIC_EXTRACT.SNU_FINAL_ACTIVE_MEMBER_VW AS
WITH MEMBERDEMOGRAPHICS AS (
    SELECT 
        MD.MEMBER_NBR
        ,MD.MASTER_MEMBER_ID
        ,MD.MEMBER_FULL_NAME
        ,MD.MEMBER_LAST_NAME
        ,MD.MEMBER_FIRST_NAME
        ,MD.MEMBER_MIDDLE_NAME
        ,MD.MEMBER_BIRTH_DATE
        ,MD.MEMBER_AGE
        ,MD.GENDER_CODE
        ,MD.RECIPIENT_ID
        ,ROW_NUMBER() OVER (
            PARTITION BY MD.MASTER_MEMBER_ID
            ORDER BY  MD.MEMBER_NBR
        ) AS RN
   FROM &{IDAP}.DIMDATA.DIM_MEMBER_VW MD
   INNER JOIN &{IDAP}.DIMDATA.FACT_ENROLLMENT_VW E
                ON E.DIM_MEMBER_KEY = MD.DIM_MEMBER_KEY
            WHERE MD.TPA_DIV_ID = '0001' 
                    AND (E.ELIGIBILITY_END_DATE IS NULL
                         OR E.ELIGIBILITY_END_DATE = '9999-12-31'
                         OR E.ELIGIBILITY_END_DATE >= LAST_DAY(CURRENT_DATE(), 'YEAR'))
)
 
SELECT 
         D.MASTER_MEMBER_ID
        ,D.MEMBER_FULL_NAME
        ,D.MEMBER_FIRST_NAME
        ,D.MEMBER_LAST_NAME
        ,CASE 
               WHEN D.MEMBER_MIDDLE_NAME = 'UNKNOWN' THEN NULL
                ELSE D.MEMBER_MIDDLE_NAME
         END AS MEMBER_MIDDLE_NAME
        ,D.GENDER_CODE
        ,TO_VARCHAR(D.MEMBER_BIRTH_DATE, 'YYYYMMDD') AS MEMBER_BIRTH_DATE
        ,COALESCE(NULLIF(TRIM(SUBSTR(A.SPEC_MED_NEED_1,1,2)), ''),'0') AS SN1
        ,COALESCE(NULLIF(TRIM(SUBSTR(A.SPEC_MED_NEED_1,3,2)), ''),'0') AS SN2
        ,COALESCE(NULLIF(TRIM(SUBSTR(A.SPEC_MED_NEED_1,5,2)), ''),'0') AS SN3
        ,NULLIF(TRIM(SPEC_NEED_NOTES), '') AS NOTE
        ,TO_VARCHAR(A.LOAD_DATE, 'YYYYMMDDHH24MISS') AS LOAD_DATE
FROM &{IDAP_LAKE}.DHS.MEDICAID_PEND_ENROLL_VW A
INNER JOIN MEMBERDEMOGRAPHICS D
        ON A.RECIP_INDIV_NO = D.RECIPIENT_ID
WHERE D.RN = 1  
ORDER BY MASTER_MEMBER_ID
;

