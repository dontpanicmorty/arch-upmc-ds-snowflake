!set variable_substitution=true;

CREATE OR REPLACE VIEW MARKETING_EDS.DNV_MEMBER_RIDER_VW
COMMENT = 'VIEW FOR MARKETING ENGAGEMENT DATA SOURCE OF THE DENTAL VISION MEMBER AND RIDER COMBINATIONS'
(
	DNV_MEMBER_KEY,
	DNV_MEMBER_RIDER_KEY,
	DNV_MBR_LOAD_DATE
)
AS
SELECT
SQL.DNV_MEMBER_KEY AS DNV_MEMBER_KEY,
SQL.DIM_RIDER_KEY AS DNV_MEMBER_RIDER_KEY,
SQL.INSERT_DATETIME AS DNV_MBR_LOAD_DATE
FROM
(
SELECT 
 DNV_MEMBERS_VW.DNV_MEMBER_KEY,
 DIM_RIDER.RIDER_CODE,
 DIM_RIDER.RIDER_TYPE_CODE AS RIDER_TYPE_CODE,
 FACT_ENROLLMENT.DIM_RIDER_KEY,
 ROW_NUMBER() OVER(PARTITION BY DNV_MEMBERS_VW.DNV_MEMBER_KEY, DIM_RIDER.RIDER_CODE ORDER BY FACT_ENROLLMENT.ELIGIBILITY_START_DATE DESC ) AS SEQNUM,
 FACT_ENROLLMENT.ELIGIBILITY_START_DATE,
 FACT_ENROLLMENT.ELIGIBILITY_END_DATE,
 FACT_ENROLLMENT.INSERT_DATETIME
FROM MARKETING_EDS.DNV_MEMBERS_VW 
        LEFT JOIN &{IDAP}.DIMDATA.FACT_ENROLLMENT
            ON FACT_ENROLLMENT.DIM_MEMBER_KEY = DNV_MEMBERS_VW.DNV_MEMBER_KEY
        INNER JOIN &{IDAP}.DIMDATA.DIM_ELIGIBILITY_TYPE
            ON DIM_ELIGIBILITY_TYPE.DIM_ELIGIBILITY_TYPE_KEY = FACT_ENROLLMENT.DIM_ELIGIBILITY_TYPE_KEY
        INNER JOIN &{IDAP}.DIMDATA.DIM_RIDER
            ON FACT_ENROLLMENT.DIM_RIDER_KEY = DIM_RIDER.DIM_RIDER_KEY
WHERE DIM_ELIGIBILITY_TYPE.ELIGIBILITY_TYPE_NAME = 'RIDER'
 AND FACT_ENROLLMENT.ELIGIBILITY_START_DATE <> FACT_ENROLLMENT.ELIGIBILITY_END_DATE
 AND FACT_ENROLLMENT.ELIGIBILITY_END_DATE >= SYSDATE()
) SQL
WHERE SQL.SEQNUM = 1
;

