CREATE OR REPLACE VIEW MARKETING_EDS.MARKETING_DNV_PLAN_VW(
	DNV_PLAN_KEY,
	DNV_DIVISION_KEY,
	PLAN_NBR,
	PLAN_DESC,
	PLAN_TYPE,
	PRODUCT_CODE,
	PRODUCT_DESC,
	BUSINESS_INSURED_TYPE,
	LINE_OF_BUSINESS,
	DNV_PLAN_LOAD_DATE,
	DNV_PLAN_UPDATE_DATE
) COMMENT='Plan information for dental/vision members'
 as
SELECT
    CAST(LPAD(SPLIT_PART(DNV_PLAN_KEY, '-', 1), 12, '0') ||  
        LPAD(SPLIT_PART(DNV_PLAN_KEY, '-', 2), 12, '0') ||  
        LPAD(SPLIT_PART(DNV_PLAN_KEY, '-', 3), 12, '0') AS NUMBER(38,0))::NUMBER(38,0) AS DNV_PLAN_KEY,
    CAST(LPAD(SPLIT_PART(DNV_DIVISION_KEY, '-', 1), 12, '0') ||  
            LPAD(SPLIT_PART(DNV_DIVISION_KEY, '-', 2), 12, '0') AS NUMBER(38,0))::NUMBER(38,0) AS DNV_DIVISION_KEY,
    PLAN_NBR::VARCHAR(5),
    PLAN_DESC::VARCHAR(50),
    PLAN_TYPE::VARCHAR(250),
    PRODUCT_CODE::VARCHAR(10),
    PRODUCT_DESC::VARCHAR(30),
    BUSINESS_INSURED_TYPE::VARCHAR(20),
    CASE
        WHEN LINE_OF_BUSINESS = 'WL' THEN 'W'
        ELSE LINE_OF_BUSINESS
    END::VARCHAR(10) AS LINE_OF_BUSINESS,
    DNV_PLAN_LOAD_DATE::DATETIME,
    DNV_PLAN_UPDATE_DATE::DATETIME
FROM MARKETING_EDS.DNV_PLAN_VW;