CREATE OR REPLACE VIEW MARKETING_EDS.ENGAGEMENT_MEMBER_CONDITIONS_VW(
	INDIVIDUAL_KEY,
	CONDITON_KEY,
	MEMBER_CONDITIONS_LOAD_DATE
) COMMENT='Member Conditions for Marketing Automation'
 as 
select MBR.INDIVIDUAL_KEY::VARCHAR(12) AS INDIVIDUAL_KEY,
    TBL_MEMBER_ATTRIBUTES.ATTRIBUTE_KEY::NUMBER(38,0) AS CONDITON_KEY,
     TBL_MEMBER_ATTRIBUTES.ATTRIBUTE_DATE::TIMESTAMP_NTZ(9) AS MEMBER_CONDITIONS_LOAD_DATE
from DEPT_MKTG.MKT_ODSDB.TBL_MEMBER_ATTRIBUTES TBL_MEMBER_ATTRIBUTES
INNER JOIN DEPT_MKTG.MKT_ODSDB.REF_MEMBER_ATTRIBUTES REF_MEMBER_ATTRIBUTES
ON TBL_MEMBER_ATTRIBUTES.ATTRIBUTE_KEY = REF_MEMBER_ATTRIBUTES.ATTRIBUTE_KEY
INNER JOIN MARKETING_EDS.ENGAGEMENT_MEMBERS_VW MBR
ON TBL_MEMBER_ATTRIBUTES.MEMBER_NBR = MBR.MEMBER_NBR
AND REF_MEMBER_ATTRIBUTES.ATTRIBUTE_CATEGORY = 'CONDITIONS'
;