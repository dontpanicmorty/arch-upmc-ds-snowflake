!set variable_substitution=true;

create or replace view MARKETING_EDS.DNV_MEMBERS_VW(
	DNV_MEMBER_KEY,
	INDIVIDUAL_KEY,
	DNV_MEMBER_NBR,
	DNV_CONTRACT_NBR,
	RELATIONSHIP_CODE,
	RELATIONSHIP_DESC,
	NEW_START_DATE,
	TERM_DATE,
	RENEW_START_DATE,
	ENROLLMENT_DATE,
	DNV_FLAG,
	MEMBER_NBR,
	DNV_MEMBER_LOAD_DATE,
	DNV_MEMBER_UPDATE_DATE,
	FACT_ENROLLMENT_KEY_DE,
	FACT_ENROLLMENT_KEY_VI,
	DIM_RIDER_KEY_DE,
	DIM_RIDER_KEY_VI,
	MMI_RECORD_SEQ,
	FIRST_MEMBERSHIP_DATE
) COMMENT='VIEW FOR MARKETING ENGAGEMENT SOURCE OF DENTAL AND VISION MEMBERS'
 as
SELECT DIM_MEMBER.DIM_MEMBER_KEY  AS DNV_MEMBER_KEY,
        NVL(DIM_MEMBER.MASTER_MEMBER_ID, SQ4.MASTER_MEMBER_ID)  AS INDIVIDUAL_KEY,
        DIM_MEMBER.MEMBER_NBR AS DNV_MEMBER_NBR,
        DIM_MEMBER.SUBSCRIBER_NBR AS DNV_CONTRACT_NBR,
        DIM_MEMBER.SUBSCRIBER_RELATIONSHIP_CODE AS RELATIONSHIP_CODE,
        DIM_MEMBER.SUBSCRIBER_RELATIONSHIP_DESC AS RELATIONSHIP_DESC,
        NSDV.NEW_START_DATE,
        NVL(NVL(CURRENT_MEMBERSHIP.TERM_DATE, FUTURE_MEMBERSHIP.TERM_DATE), INACTIVE_MEMBERSHIP.TERM_DATE) AS TERM_DATE,
        NVL(NVL(CURRENT_MEMBERSHIP.RENEW_START_DATE, FUTURE_MEMBERSHIP.RENEW_START_DATE), INACTIVE_MEMBERSHIP.RENEW_START_DATE) AS RENEW_START_DATE,
        NVL(NVL(CURRENT_MEMBERSHIP.ENROLLMENT_DATE, FUTURE_MEMBERSHIP.ENROLLMENT_DATE), INACTIVE_MEMBERSHIP.ENROLLMENT_DATE) AS ENROLLMENT_DATE,
        CASE WHEN NVL(NVL(CURRENT_MEMBERSHIP.DNV_FLAG, FUTURE_MEMBERSHIP.DNV_FLAG), INACTIVE_MEMBERSHIP.DNV_FLAG) = 'DV' THEN 'B' ELSE NVL(NVL(CURRENT_MEMBERSHIP.DNV_FLAG, FUTURE_MEMBERSHIP.DNV_FLAG), INACTIVE_MEMBERSHIP.DNV_FLAG) END AS DNV_FLAG,
        SQ4.MEMBER_NBR AS MEMBER_NBR,
        DIM_MEMBER.MEMBER_ADDED_DATE AS DNV_MEMBER_LOAD_DATE,
        DIM_MEMBER.LAST_UPDATED_DATETIME AS DNV_MEMBER_UPDATE_DATE,
        CASE WHEN CURRENT_MEMBERSHIP.DIM_MEMBER_KEY IS NOT NULL THEN CURRENT_MEMBERSHIP.FACT_ENROLLMENT_KEY_DE WHEN FUTURE_MEMBERSHIP.DIM_MEMBER_KEY IS NOT NULL THEN FUTURE_MEMBERSHIP.FACT_ENROLLMENT_KEY_DE WHEN INACTIVE_MEMBERSHIP.DIM_MEMBER_KEY IS NOT NULL THEN INACTIVE_MEMBERSHIP.FACT_ENROLLMENT_KEY_DE END AS FACT_ENROLLMENT_KEY_DE,
CASE WHEN CURRENT_MEMBERSHIP.DIM_MEMBER_KEY IS NOT NULL THEN CURRENT_MEMBERSHIP.FACT_ENROLLMENT_KEY_VI WHEN FUTURE_MEMBERSHIP.DIM_MEMBER_KEY IS NOT NULL THEN FUTURE_MEMBERSHIP.FACT_ENROLLMENT_KEY_VI WHEN INACTIVE_MEMBERSHIP.DIM_MEMBER_KEY IS NOT NULL THEN INACTIVE_MEMBERSHIP.FACT_ENROLLMENT_KEY_VI END AS FACT_ENROLLMENT_KEY_VI,
CASE WHEN CURRENT_MEMBERSHIP.DIM_MEMBER_KEY IS NOT NULL THEN CURRENT_MEMBERSHIP.DIM_RIDER_KEY_DE WHEN FUTURE_MEMBERSHIP.DIM_MEMBER_KEY IS NOT NULL THEN FUTURE_MEMBERSHIP.DIM_RIDER_KEY_DE WHEN INACTIVE_MEMBERSHIP.DIM_MEMBER_KEY IS NOT NULL THEN INACTIVE_MEMBERSHIP.DIM_RIDER_KEY_DE END AS DIM_RIDER_KEY_DE,
CASE WHEN CURRENT_MEMBERSHIP.DIM_MEMBER_KEY IS NOT NULL THEN CURRENT_MEMBERSHIP.DIM_RIDER_KEY_VI WHEN FUTURE_MEMBERSHIP.DIM_MEMBER_KEY IS NOT NULL THEN FUTURE_MEMBERSHIP.DIM_RIDER_KEY_VI WHEN INACTIVE_MEMBERSHIP.DIM_MEMBER_KEY IS NOT NULL THEN INACTIVE_MEMBERSHIP.DIM_RIDER_KEY_VI END AS DIM_RIDER_KEY_VI,
        ROW_NUMBER() OVER (PARTITION BY NVL(DIM_MEMBER.MASTER_MEMBER_ID,SQ4.MASTER_MEMBER_ID)
                            ORDER BY NVL(NVL(CURRENT_MEMBERSHIP.MEMBERSHIP_STATUS, FUTURE_MEMBERSHIP.MEMBERSHIP_STATUS), INACTIVE_MEMBERSHIP.MEMBERSHIP_STATUS) ASC, NVL(NVL(CURRENT_MEMBERSHIP.ENROLLMENT_DATE, FUTURE_MEMBERSHIP.ENROLLMENT_DATE), INACTIVE_MEMBERSHIP.ENROLLMENT_DATE) DESC, DIM_MEMBER.MEMBER_ADDED_DATE DESC) AS MMI_RECORD_SEQ,
        MIN(NVL(NVL(CURRENT_MEMBERSHIP.ENROLLMENT_DATE, FUTURE_MEMBERSHIP.ENROLLMENT_DATE), INACTIVE_MEMBERSHIP.ENROLLMENT_DATE)) OVER (PARTITION BY NVL(DIM_MEMBER.MASTER_MEMBER_ID,SQ4.MASTER_MEMBER_ID)) AS  FIRST_MEMBERSHIP_DATE
FROM &{IDAP}.DIMDATA.DIM_MEMBER AS DIM_MEMBER 
LEFT JOIN (SELECT SQ1.DIM_MEMBER_KEY,  
                    MAX(CASE WHEN SQ1.SEQNUM = 1 THEN SQ1.ELIGIBILITY_END_DATE ELSE NULL END)  AS TERM_DATE,
                    MAX(CASE WHEN SQ1.SEQNUM = 1 THEN TO_DATE(SQ1.CURRENT_GROUP_END_DATE) ELSE NULL END) AS RENEW_START_DATE,  
                    MAX(CASE WHEN SQ1.SEQNUM = 1 THEN SQ1.eligibility_start_date ELSE NULL END)  AS ENROLLMENT_DATE,
                    MAX(CASE WHEN SQ1.SEQNUM = 1 AND SQ1.RIDER_TYPE_CODE = 'DE' THEN SQ1.FACT_ENROLLMENT_KEY ELSE NULL END)  AS FACT_ENROLLMENT_KEY_DE,
                    MAX(CASE WHEN SQ1.SEQNUM = 1 AND SQ1.RIDER_TYPE_CODE = 'VI' THEN SQ1.FACT_ENROLLMENT_KEY ELSE NULL END)  AS FACT_ENROLLMENT_KEY_VI,
                    MAX(CASE WHEN SQ1.SEQNUM = 1 AND SQ1.RIDER_TYPE_CODE = 'DE' THEN SQ1.DIM_RIDER_KEY ELSE NULL END)  AS DIM_RIDER_KEY_DE,
                    MAX(CASE WHEN SQ1.SEQNUM = 1 AND SQ1.RIDER_TYPE_CODE = 'VI' THEN SQ1.DIM_RIDER_KEY ELSE NULL END)  AS DIM_RIDER_KEY_VI,
                    CONCAT(MAX(CASE WHEN SQ1.SEQNUM = 1 AND SQ1.RIDER_TYPE_CODE = 'DE' THEN 'D' ELSE ''  END),
                              MAX(CASE WHEN SQ1.SEQNUM = 1 AND SQ1.RIDER_TYPE_CODE = 'VI' THEN 'V' ELSE ''  END)) AS DNV_FLAG, 
                              'ACTIVE' AS MEMBERSHIP_STATUS
            FROM (SELECT DIM_MEMBER.DIM_MEMBER_KEY, FACT_ENROLLMENT.FACT_ENROLLMENT_KEY,FACT_ENROLLMENT.ELIGIBILITY_START_DATE, FACT_ENROLLMENT.ELIGIBILITY_END_DATE, DATEADD(day, +1, TO_DATE(DIM_GROUP.CURRENT_GROUP_END_DATE)) AS CURRENT_GROUP_END_DATE, DIM_RIDER.RIDER_TYPE_CODE, FACT_ENROLLMENT.DIM_RIDER_KEY, 
                    ROW_NUMBER() OVER (PARTITION BY DIM_MEMBER.DIM_MEMBER_KEY, DIM_RIDER.RIDER_TYPE_CODE ORDER BY FACT_ENROLLMENT.ELIGIBILITY_START_DATE DESC, FACT_ENROLLMENT.FACT_ENROLLMENT_KEY ASC) AS SEQNUM,
                    FROM  &{IDAP}.DIMDATA.DIM_MEMBER DIM_MEMBER
                        INNER JOIN &{IDAP}.DIMDATA.FACT_ENROLLMENT FACT_ENROLLMENT
                            ON DIM_MEMBER.DIM_MEMBER_KEY = FACT_ENROLLMENT.DIM_MEMBER_KEY
                        INNER JOIN &{IDAP}.DIMDATA.DIM_GROUP AS DIM_GROUP 
                            ON DIM_GROUP.DIM_GROUP_KEY = FACT_ENROLLMENT.DIM_GROUP_KEY 
                        INNER JOIN &{IDAP}.DIMDATA.DIM_ELIGIBILITY_TYPE AS DIM_ELIGIBILITY_TYPE 
                            ON FACT_ENROLLMENT.DIM_ELIGIBILITY_TYPE_KEY = DIM_ELIGIBILITY_TYPE.DIM_ELIGIBILITY_TYPE_KEY
                        LEFT JOIN &{IDAP}.DIMDATA.DIM_RIDER DIM_RIDER
                            ON FACT_ENROLLMENT.DIM_RIDER_KEY = DIM_RIDER.DIM_RIDER_KEY
                    WHERE DIM_ELIGIBILITY_TYPE.ELIGIBILITY_TYPE_NAME = 'RIDER'
                    AND DIM_MEMBER.SUB_SOURCE_NAME = 'DENTAL UPMC'
                    AND FACT_ENROLLMENT.ELIGIBILITY_START_DATE <>  FACT_ENROLLMENT.ELIGIBILITY_END_DATE
                    AND FACT_ENROLLMENT.ELIGIBILITY_START_DATE <= SYSDATE()
                    AND FACT_ENROLLMENT.ELIGIBILITY_END_DATE >= SYSDATE()
                    ) SQ1
            GROUP BY SQ1.DIM_MEMBER_KEY
            ) CURRENT_MEMBERSHIP
ON DIM_MEMBER.DIM_MEMBER_KEY = CURRENT_MEMBERSHIP.DIM_MEMBER_KEY   
LEFT JOIN (SELECT SQ1.DIM_MEMBER_KEY,  
                    MAX(CASE WHEN SQ1.SEQNUM = 1 THEN SQ1.ELIGIBILITY_END_DATE ELSE NULL END)  AS TERM_DATE,
                    MAX(CASE WHEN SQ1.SEQNUM = 1 THEN TO_DATE(SQ1.CURRENT_GROUP_END_DATE) ELSE NULL END) AS RENEW_START_DATE,  
                    MAX(CASE WHEN SQ1.SEQNUM = 1 THEN SQ1.eligibility_start_date ELSE NULL END)  AS ENROLLMENT_DATE,
                    MAX(CASE WHEN SQ1.SEQNUM = 1 AND SQ1.RIDER_TYPE_CODE = 'DE' THEN SQ1.FACT_ENROLLMENT_KEY ELSE NULL END)  AS FACT_ENROLLMENT_KEY_DE,
                    MAX(CASE WHEN SQ1.SEQNUM = 1 AND SQ1.RIDER_TYPE_CODE = 'VI' THEN SQ1.FACT_ENROLLMENT_KEY ELSE NULL END)  AS FACT_ENROLLMENT_KEY_VI,
                    MAX(CASE WHEN SQ1.SEQNUM = 1 AND SQ1.RIDER_TYPE_CODE = 'DE' THEN SQ1.DIM_RIDER_KEY ELSE NULL END)  AS DIM_RIDER_KEY_DE,
                    MAX(CASE WHEN SQ1.SEQNUM = 1 AND SQ1.RIDER_TYPE_CODE = 'VI' THEN SQ1.DIM_RIDER_KEY ELSE NULL END)  AS DIM_RIDER_KEY_VI,
                    CONCAT(MAX(CASE WHEN SQ1.SEQNUM = 1 AND SQ1.RIDER_TYPE_CODE = 'DE' THEN 'D' ELSE ''  END),
                           MAX(CASE WHEN SQ1.SEQNUM = 1 AND SQ1.RIDER_TYPE_CODE = 'VI' THEN 'V' ELSE ''  END)) AS DNV_FLAG,
                    'FUTURE' AS MEMBERSHIP_STATUS          
            FROM (SELECT DIM_MEMBER.DIM_MEMBER_KEY, FACT_ENROLLMENT.FACT_ENROLLMENT_KEY,FACT_ENROLLMENT.ELIGIBILITY_START_DATE, FACT_ENROLLMENT.ELIGIBILITY_END_DATE, DATEADD(day, +1, TO_DATE(DIM_GROUP.CURRENT_GROUP_END_DATE)) AS CURRENT_GROUP_END_DATE, DIM_RIDER.RIDER_TYPE_CODE, FACT_ENROLLMENT.DIM_RIDER_KEY, 
                            ROW_NUMBER() OVER (PARTITION BY DIM_MEMBER.DIM_MEMBER_KEY, DIM_RIDER.RIDER_TYPE_CODE ORDER BY FACT_ENROLLMENT.ELIGIBILITY_START_DATE ASC, FACT_ENROLLMENT.FACT_ENROLLMENT_KEY ASC) AS SEQNUM,
                    FROM  &{IDAP}.DIMDATA.DIM_MEMBER DIM_MEMBER
                    INNER JOIN &{IDAP}.DIMDATA.FACT_ENROLLMENT FACT_ENROLLMENT
                        ON DIM_MEMBER.DIM_MEMBER_KEY = FACT_ENROLLMENT.DIM_MEMBER_KEY
                    INNER JOIN &{IDAP}.DIMDATA.DIM_GROUP AS DIM_GROUP 
                            ON DIM_GROUP.DIM_GROUP_KEY = FACT_ENROLLMENT.DIM_GROUP_KEY 
                    INNER JOIN &{IDAP}.DIMDATA.DIM_ELIGIBILITY_TYPE AS DIM_ELIGIBILITY_TYPE 
                        ON FACT_ENROLLMENT.DIM_ELIGIBILITY_TYPE_KEY = DIM_ELIGIBILITY_TYPE.DIM_ELIGIBILITY_TYPE_KEY
                    LEFT JOIN &{IDAP}.DIMDATA.DIM_RIDER DIM_RIDER
                        ON FACT_ENROLLMENT.dim_rider_key = DIM_RIDER.DIM_RIDER_KEY
                    WHERE DIM_ELIGIBILITY_TYPE.ELIGIBILITY_TYPE_NAME = 'RIDER'
                    AND DIM_MEMBER.SUB_SOURCE_NAME = 'DENTAL UPMC'
                    AND FACT_ENROLLMENT.ELIGIBILITY_START_DATE <>  FACT_ENROLLMENT.ELIGIBILITY_END_DATE
                    AND FACT_ENROLLMENT.ELIGIBILITY_START_DATE > SYSDATE()
                   ) SQ1
            GROUP BY SQ1.DIM_MEMBER_KEY
            ) FUTURE_MEMBERSHIP
ON DIM_MEMBER.DIM_MEMBER_KEY = FUTURE_MEMBERSHIP.DIM_MEMBER_KEY
LEFT JOIN (SELECT SQ1.DIM_MEMBER_KEY,  
                    MAX(CASE WHEN SQ1.SEQNUM = 1 THEN SQ1.ELIGIBILITY_END_DATE ELSE NULL END)  AS TERM_DATE,
                    MAX(CASE WHEN SQ1.SEQNUM = 1 THEN TO_DATE(SQ1.CURRENT_GROUP_END_DATE) ELSE NULL END) AS RENEW_START_DATE,  
                    MAX(CASE WHEN SQ1.SEQNUM = 1 THEN SQ1.eligibility_start_date ELSE NULL END)  AS ENROLLMENT_DATE,
                    MAX(CASE WHEN SQ1.SEQNUM = 1 AND SQ1.RIDER_TYPE_CODE = 'DE' THEN SQ1.FACT_ENROLLMENT_KEY ELSE NULL END)  AS FACT_ENROLLMENT_KEY_DE,
                    MAX(CASE WHEN SQ1.SEQNUM = 1 AND SQ1.RIDER_TYPE_CODE = 'VI' THEN SQ1.FACT_ENROLLMENT_KEY ELSE NULL END)  AS FACT_ENROLLMENT_KEY_VI,
                    MAX(CASE WHEN SQ1.SEQNUM = 1 AND SQ1.RIDER_TYPE_CODE = 'DE' THEN SQ1.DIM_RIDER_KEY ELSE NULL END)  AS DIM_RIDER_KEY_DE,
                    MAX(CASE WHEN SQ1.SEQNUM = 1 AND SQ1.RIDER_TYPE_CODE = 'VI' THEN SQ1.DIM_RIDER_KEY ELSE NULL END)  AS DIM_RIDER_KEY_VI,
                    CONCAT(MAX(CASE WHEN SQ1.SEQNUM = 1 AND SQ1.RIDER_TYPE_CODE = 'DE' THEN 'D' ELSE ''  END),
                           MAX(CASE WHEN SQ1.SEQNUM = 1 AND SQ1.RIDER_TYPE_CODE = 'VI' THEN 'V' ELSE ''  END)) AS DNV_FLAG,
                    'INACTIVE' AS MEMBERSHIP_STATUS          
            FROM (SELECT DIM_MEMBER.DIM_MEMBER_KEY, FACT_ENROLLMENT.FACT_ENROLLMENT_KEY,FACT_ENROLLMENT.ELIGIBILITY_START_DATE, FACT_ENROLLMENT.ELIGIBILITY_END_DATE, DATEADD(day, +1, TO_DATE(DIM_GROUP.CURRENT_GROUP_END_DATE)) AS CURRENT_GROUP_END_DATE, DIM_RIDER.RIDER_TYPE_CODE, FACT_ENROLLMENT.DIM_RIDER_KEY, 
                            ROW_NUMBER() OVER (PARTITION BY DIM_MEMBER.DIM_MEMBER_KEY, DIM_RIDER.RIDER_TYPE_CODE ORDER BY FACT_ENROLLMENT.ELIGIBILITY_START_DATE DESC, FACT_ENROLLMENT.FACT_ENROLLMENT_KEY ASC) AS SEQNUM,
                    FROM  &{IDAP}.DIMDATA.DIM_MEMBER DIM_MEMBER
                    INNER JOIN &{IDAP}.DIMDATA.FACT_ENROLLMENT FACT_ENROLLMENT
                        ON DIM_MEMBER.DIM_MEMBER_KEY = FACT_ENROLLMENT.DIM_MEMBER_KEY
                    INNER JOIN &{IDAP}.DIMDATA.DIM_GROUP AS DIM_GROUP 
                            ON DIM_GROUP.DIM_GROUP_KEY = FACT_ENROLLMENT.DIM_GROUP_KEY 
                    INNER JOIN &{IDAP}.DIMDATA.DIM_ELIGIBILITY_TYPE AS DIM_ELIGIBILITY_TYPE 
                        ON FACT_ENROLLMENT.DIM_ELIGIBILITY_TYPE_KEY = DIM_ELIGIBILITY_TYPE.DIM_ELIGIBILITY_TYPE_KEY
                    LEFT JOIN &{IDAP}.DIMDATA.DIM_RIDER DIM_RIDER
                        ON FACT_ENROLLMENT.dim_rider_key = DIM_RIDER.DIM_RIDER_KEY
                    WHERE DIM_ELIGIBILITY_TYPE.ELIGIBILITY_TYPE_NAME = 'RIDER'
                    AND DIM_MEMBER.SUB_SOURCE_NAME = 'DENTAL UPMC'
                    AND FACT_ENROLLMENT.ELIGIBILITY_START_DATE <>  FACT_ENROLLMENT.ELIGIBILITY_END_DATE
                    AND FACT_ENROLLMENT.ELIGIBILITY_START_DATE < SYSDATE()
                    AND FACT_ENROLLMENT.ELIGIBILITY_END_DATE < SYSDATE()
                   ) SQ1
            GROUP BY SQ1.DIM_MEMBER_KEY
            ) INACTIVE_MEMBERSHIP
ON DIM_MEMBER.DIM_MEMBER_KEY = INACTIVE_MEMBERSHIP.DIM_MEMBER_KEY
LEFT JOIN (SELECT DISTINCT DIM_MEMBER.MEMBER_NBR AS DNV_MEMBER_NBR, DIM_MEMBER.MASTER_MEMBER_ID, SEM.MEMBER_NBR ,
                        ROW_NUMBER() OVER (PARTITION BY DIM_MEMBER.DIM_MEMBER_KEY ORDER BY DIM_MEMBER.MASTER_MEMBER_ID ) AS SEQNUM
            FROM &{IDAP}.DIMDATA.DIM_MEMBER DIM_MEMBER
            LEFT JOIN MARKETING_EDS.MEMBERS_VW SEM
            ON DIM_MEMBER.MASTER_MEMBER_ID = SEM.INDIVIDUAL_KEY
            AND SEM.MMI_RECORD_SEQ = 1
            WHERE MASTER_MEMBER_ID is not null
            AND DIM_MEMBER.SUB_SOURCE_NAME = 'DENTAL UPMC'
            AND DIM_MEMBER.TPA_CLIENT_ID = '000001'
            AND DIM_MEMBER.TPA_DIV_ID = '0002'
            AND DIM_MEMBER.TPA_ID = '000001'
            ) SQ4
ON DIM_MEMBER.MEMBER_NBR = SQ4.DNV_MEMBER_NBR         
AND SQ4.SEQNUM = 1
LEFT JOIN DEPT_MKTG.MKT_ODSDB.NEW_START_DATE_VW AS NSDV
ON DIM_MEMBER.MEMBER_NBR = NSDV.MEMBER_NBR
WHERE DIM_MEMBER.SUB_SOURCE_NAME = 'DENTAL UPMC'
AND DIM_MEMBER.TPA_CLIENT_ID = '000001'
AND DIM_MEMBER.TPA_DIV_ID = '0002'
AND DIM_MEMBER.TPA_ID = '000001'
AND DIM_MEMBER.MASTER_MEMBER_ID IS NOT NULL
AND NVL(NVL(CURRENT_MEMBERSHIP.ENROLLMENT_DATE, FUTURE_MEMBERSHIP.ENROLLMENT_DATE), INACTIVE_MEMBERSHIP.ENROLLMENT_DATE) IS NOT NULL
;

