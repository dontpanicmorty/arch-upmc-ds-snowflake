
CREATE OR REPLACE VIEW MARKETING_EDS.MARKETING_DNV_MEMBER_PLAN_VW(
	DNV_MEMBER_KEY,
	DNV_PLAN_KEY,
	DNV_MBRPLAN_LOAD_DATE
) COMMENT='Links IDAP_AUXILIARY.MARKETING_EDS.MARKETING_DNV_MEMBERS_VW to IDAP_AUXILIARY.MARKETING_EDS.MARKETING_DNV_PLAN_VW'
 AS
SELECT
    DNV_MEMBER_KEY,
    CAST(LPAD(SPLIT_PART(DNV_PLAN_KEY, '-', 1), 12, '0') ||  
        LPAD(SPLIT_PART(DNV_PLAN_KEY, '-', 2), 12, '0') ||  
        LPAD(SPLIT_PART(DNV_PLAN_KEY, '-', 3), 12, '0') AS NUMBER(38,0))::NUMBER(38,0) AS DNV_PLAN_KEY,
    DNV_MBRPLAN_LOAD_DATE::DATETIME
FROM MARKETING_EDS.DNV_MEMBER_PLAN_VW;