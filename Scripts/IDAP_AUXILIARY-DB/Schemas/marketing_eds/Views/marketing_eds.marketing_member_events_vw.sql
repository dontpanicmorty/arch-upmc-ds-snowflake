CREATE OR REPLACE VIEW MARKETING_EDS.MARKETING_MEMBER_EVENTS_VW(
	MEMBER_KEY,
	EVENT_TYPE_KEY,
	EVENT_TYPE,
	COUNT,
	FIRST_OCCURANCE,
	LAST_OCCURANCE,
	RANGE_START_DATE,
	RANGE_END_DATE,
	LOAD_DATE,
	UPDATE_DATE,
	DELETE_DATE
) COMMENT='Member Events for Marketing Automation'
 AS
SELECT ENGAGEMENT_MEMBERS.MEMBER_KEY::NUMBER(38,0) AS MEMBER_KEY,
    TBL_MEMBER_ATTRIBUTES.ATTRIBUTE_KEY::NUMBER(38,0) AS EVENT_TYPE_KEY,
    'COUNT'::VARCHAR(10) AS EVENT_TYPE,
    1::NUMBER(38,4) AS COUNT,
    MIN(TBL_MEMBER_ATTRIBUTES.ATTRIBUTE_DATE) OVER (PARTITION BY TBL_MEMBER_ATTRIBUTES.MASTER_MEMBER_ID, TBL_MEMBER_ATTRIBUTES.ATTRIBUTE_KEY)::TIMESTAMP_NTZ(9) AS FIRST_OCCURANCE,
    MAX(TBL_MEMBER_ATTRIBUTES.ATTRIBUTE_DATE) OVER (PARTITION BY TBL_MEMBER_ATTRIBUTES.MASTER_MEMBER_ID,TBL_MEMBER_ATTRIBUTES.ATTRIBUTE_KEY)::TIMESTAMP_NTZ(9) AS LAST_OCCURANCE,
    TBL_MEMBER_ATTRIBUTES.ATTRIBUTE_DATE::TIMESTAMP_NTZ(9) AS RANGE_START_DATE,
    TBL_MEMBER_ATTRIBUTES.ATTRIBUTE_DATE::TIMESTAMP_NTZ(9) AS RANGE_END_DATE,
    TBL_MEMBER_ATTRIBUTES.LOAD_DATE::TIMESTAMP_NTZ(9) AS  LOAD_DATE,
    TBL_MEMBER_ATTRIBUTES.LOAD_DATE::TIMESTAMP_NTZ(9) AS UPDATE_DATE,
    NULL::TIMESTAMP_NTZ(9) AS DELETE_DATE
from DEPT_MKTG.MKT_ODSDB.TBL_MEMBER_ATTRIBUTES TBL_MEMBER_ATTRIBUTES
INNER JOIN DEPT_MKTG.MKT_ODSDB.REF_MEMBER_ATTRIBUTES REF_MEMBER_ATTRIBUTES
ON TBL_MEMBER_ATTRIBUTES.ATTRIBUTE_KEY = REF_MEMBER_ATTRIBUTES.ATTRIBUTE_KEY
INNER JOIN MARKETING_EDS.ENGAGEMENT_MEMBERS_VW ENGAGEMENT_MEMBERS
ON TBL_MEMBER_ATTRIBUTES.MEMBER_NBR = ENGAGEMENT_MEMBERS.MEMBER_NBR
AND REF_MEMBER_ATTRIBUTES.ATTRIBUTE_CATEGORY = 'EVENTS'
;