!set variable_substitution=true;

CREATE OR REPLACE VIEW MARKETING_EDS.MEMBER_PLAN_VW
COMMENT = 'VIEW FOR MARKETING ENGAGEMENT DATA SOURCE FOR  MEMBER AND PLAN COMBINATIONS'
(
	MEMBER_KEY,
	PLAN_KEY,
	LOAD_DATE
)
AS
SELECT  MEMBERS_VW.MEMBER_KEY, 
        CONCAT(FACT_ENROLLMENT.DIM_PLAN_KEY ,'-', FACT_ENROLLMENT.DIM_GROUP_KEY,'-', FACT_ENROLLMENT.DIM_SUB_GROUP_KEY) AS PLAN_KEY,
        FACT_ENROLLMENT.INSERT_DATETIME AS LOAD_DATE
FROM MARKETING_EDS.MEMBERS_VW
LEFT JOIN &{IDAP}.DIMDATA.FACT_ENROLLMENT
    ON MEMBERS_VW.FACT_ENROLLMENT_KEY = FACT_ENROLLMENT.FACT_ENROLLMENT_KEY
;

!set variable_substitution=false;