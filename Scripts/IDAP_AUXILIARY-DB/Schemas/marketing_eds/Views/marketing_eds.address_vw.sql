CREATE OR REPLACE view MARKETING_EDS.ADDRESS_VW
COMMENT = 'VIEW FOR MARKETING ENGAGEMENT DATA SOURCE FOR ADDRESS'
(
	ADDRESS_KEY,
	ADDRESS_TYPE,
	ADDRESS_LINE_1,
	ADDRESS_LINE_2,
	CITY,
	STATE,
	ZIP,
	ZIP_EXT,
	COUNTY,
	COUNTRY,
	PHONE,
	FAX,
	REGION_CODE,
	LATITUDE,
	LONGITUDE,
	LOAD_DATE,
	UPDATE_DATE,
	HOUSEHOLD_ID_ADR
)
AS
SELECT DIM_MEMBER_ADDRESS.DIM_MEMBER_ADDRESS_KEY AS ADDRESS_KEY,
        DIM_MEMBER_ADDRESS.MEMBER_ADDRESS_TYPE AS ADDRESS_TYPE,
        DIM_MEMBER_ADDRESS.MEMBER_ADDRESSLINE1_TEXT AS ADDRESS_LINE_1,
        DIM_MEMBER_ADDRESS.MEMBER_ADDRESSLINE2_TEXT AS ADDRESS_LINE_2,
        DIM_MEMBER_ADDRESS.MEMBER_CITY_NAME AS CITY,
        DIM_MEMBER_ADDRESS.MEMBER_STATE_ABBREVIATION_NAME AS STATE,
        SUBSTR(DIM_MEMBER_ADDRESS.MEMBER_ZIP_CODE_NBR,1,5) AS ZIP,
        SUBSTR(DIM_MEMBER_ADDRESS.MEMBER_ZIP_CODE_NBR,6,4) AS ZIP_EXT,
        DIM_MEMBER_ADDRESS.MEMBER_COUNTY_DESC AS COUNTY,
        'US' AS COUNTRY,
        MEMBERS.MEMBERHOMEPHONENBR AS PHONE,
        MEMBERS.FAXNBR AS FAX,
        NULL AS REGION_CODE,
        DIM_MEMBER_ADDRESS.MEMBER_LATITUDE_NBR AS LATITUDE,
        DIM_MEMBER_ADDRESS.MEMBER_LONGITUDE_NBR AS LONGITUDE,
        DIM_MEMBER_ADDRESS.INSERT_DATETIME AS LOAD_DATE,
        DIM_MEMBER_ADDRESS.LAST_UPDATED_DATETIME AS UPDATE_DATE,
        NVL(HH.HOUSEHOLD_ID_ADR, UPPER(CONCAT(NVL(DIM_MEMBER_ADDRESS.MEMBER_ADDRESSLINE1_TEXT,''),NVL(DIM_MEMBER_ADDRESS.MEMBER_ADDRESSLINE2_TEXT,''), NVL(DIM_MEMBER_ADDRESS.MEMBER_CITY_NAME,''), NVL(SUBSTR(DIM_MEMBER_ADDRESS.MEMBER_ZIP_CODE_NBR,1,5),''))) ) AS HOUSEHOLD_ID_ADR
        FROM &{IDAP}.DIMDATA.DIM_MEMBER_ADDRESS DIM_MEMBER_ADDRESS
INNER JOIN MARKETING_EDS.INDIVIDUAL_VW
    ON DIM_MEMBER_ADDRESS.DIM_MEMBER_ADDRESS_KEY = INDIVIDUAL_VW.ADDRESS_KEY 
LEFT JOIN &{IDAP}.DIMDATA.DIM_MEMBER DIM_MEMBER
    ON DIM_MEMBER.DIM_MEMBER_KEY = INDIVIDUAL_VW.DIM_MEMBER_KEY
LEFT JOIN   &{MC400}.DWOAO.MEMBERS MEMBERS
    ON MEMBERS.MEMBERNBR = DIM_MEMBER.MEMBER_NBR
LEFT JOIN (SELECT HH.MASTER_MEMBER_ID, MAX(HH.HOUSEHOLD_ID)  AS HOUSEHOLD_ID_ADR
            FROM &{IDW}.ADL_PROD.INFO_HOUSEHOLD_ID HH
            INNER JOIN (select MASTER_MEMBER_ID, MAX(YYYYMM) AS YYYYMM_MAX from &{IDW}.ADL_PROD.INFO_HOUSEHOLD_ID GROUP BY MASTER_MEMBER_ID) HHM
            ON HH.MASTER_MEMBER_ID = HHM.MASTER_MEMBER_ID
            AND HH.YYYYMM = HHM.YYYYMM_MAX
            GROUP BY HH.MASTER_MEMBER_ID
            ) HH
ON INDIVIDUAL_VW.INDIVIDUAL_KEY = HH.MASTER_MEMBER_ID             
;

!set variable_substitution=false;