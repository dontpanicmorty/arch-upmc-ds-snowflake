CREATE OR REPLACE VIEW MARKETING_EDS.ENGAGEMENT_REF_ZIPCODES_VW(
	CITY,
	STATE,
	COUNTY,
	ZIPCLASS,
	ZIPCODE,
	LATITUDE,
	LONGITUDE
) COMMENT='ZIP code reference table: state/county and latitude/longitude'
 AS 
select 
CITY::VARCHAR(50) AS CITY,
 STATE::VARCHAR(50) AS STATE,	
 COUNTY::VARCHAR(50) AS COUNTY,	
 ZIPCLASS::VARCHAR(50) AS ZIPCLASS,
 ZIPCODE::VARCHAR(10) AS ZIPCODE,
 LATITUDE::NUMBER(38,12) AS LATITUDE,
 LONGITUDE::NUMBER(38,12) AS LONGITUDE
from DEPT_MKTG.MKT_ODSDB.REF_ZIPCODES;