CREATE OR REPLACE VIEW MARKETING_EDS.ENGAGEMENT_MEDICAL_HOME_PCP_VW(
	MEMBER_NBR,
	SELECTED_OFFICE_NAME,
	SELECTED_PHONE_NBR,
	SELECTED_PROVIDER_NAME,
	IMPUTED_OFFICE_NAME,
	IMPUTED_PHONE_NBR,
	IMPUTED_PROVIDER_NAME,
	LOAD_DATE,
	UPDATE_DATE,
	EXTENDER_FLAG,
	MATCH_STRENGTH,
	RDATE,
	SELECTION_TYPE,
	OFFICE_NAME,
	PROVIDER_NAME,
	PHONE_NBR,
	PROVIDER_SELECTION_DATE,
	RANGE_END_DATE
) COMMENT='Office and provider data from Oracle: EDW_USR_TAB.MEDICAL_HOME'
 AS
select  MEMBER_NBR ::Varchar(22) AS  MEMBER_NBR ,
 SELECTED_OFFICE_NAME ::Varchar(510) AS  SELECTED_OFFICE_NAME ,
 SELECTED_PHONE_NBR ::Varchar(20) AS  SELECTED_PHONE_NBR ,
 SELECTED_PROVIDER_NAME ::Varchar(510) AS  SELECTED_PROVIDER_NAME ,
 IMPUTED_OFFICE_NAME ::Varchar(510) AS  IMPUTED_OFFICE_NAME ,
 IMPUTED_PHONE_NBR ::Varchar(20) AS  IMPUTED_PHONE_NBR ,
 IMPUTED_PROVIDER_NAME ::Varchar(510) AS  IMPUTED_PROVIDER_NAME ,
 LOAD_DATE ::DATETIME AS  LOAD_DATE ,
 UPDATE_DATE ::DATETIME AS  UPDATE_DATE ,
 EXTENDER_FLAG ::Varchar(16) AS  EXTENDER_FLAG ,
 MATCH_STRENGTH ::Varchar(2) AS  MATCH_STRENGTH ,
 RDATE ::DATETIME AS  RDATE ,
 SELECTION_TYPE ::Varchar(13) AS  SELECTION_TYPE ,
 OFFICE_NAME ::Varchar(510) AS  OFFICE_NAME ,
 PROVIDER_NAME ::Varchar(510) AS  PROVIDER_NAME ,
 PHONE_NBR ::Varchar(20) AS  PHONE_NBR ,
 PROVIDER_SELECTION_DATE ::DATETIME AS  PROVIDER_SELECTION_DATE ,
 RANGE_END_DATE::DATETIME AS  RANGE_END_DATE
 from IDW.ENGAGEMENT.ETL_STGEDW_MEDICAL_HOME_PCP;