CREATE OR REPLACE VIEW MARKETING_EDS.MARKETING_DNV_MEMBERS_VW(
	DNV_MEMBER_KEY,
	INDIVIDUAL_KEY,
	DNV_MEMBER_NBR,
	DNV_CONTRACT_NBR,
	RELATIONSHIP_CODE,
	RELATIONSHIP_DESC,
	NEW_START_DATE,
	TERM_DATE,
	RENEW_START_DATE,
	ENROLLMENT_DATE,
	DNV_FLAG,
	MEMBER_NBR,
	DNV_MEMBER_LOAD_DATE,
	DNV_MEMBER_UPDATE_DATE
) COMMENT='Dental/vision members and their start/term dates'
 as
SELECT
    DNV_MEMBER_KEY,
    CAST(INDIVIDUAL_KEY AS INTEGER)::INTEGER AS INDIVIDUAL_KEY, 
    DNV_MEMBER_NBR::VARCHAR(11),
    DNV_CONTRACT_NBR::VARCHAR(9),
    CASE WHEN RELATIONSHIP_CODE IN ('AD','CD','DB','DE','DS','FC','MD','N1','N2','N3','NB','OD','PD','SD','WD') THEN 'D'
            ELSE CASE WHEN RELATIONSHIP_CODE IN ('MP','SB','ST') THEN 'E'
            ELSE CASE WHEN RELATIONSHIP_CODE IN ('SP','SX') THEN 'S'
            ELSE CASE WHEN RELATIONSHIP_CODE IN ('DP') THEN 'P'
            ELSE 'E' END END END END ::VARCHAR(2) AS RELATIONSHIP_CODE,
    UPPER(LEFT(CONCAT(RELATIONSHIP_CODE,'-', RELATIONSHIP_DESC) ,20))::VARCHAR(20) AS RELATIONSHIP_DESC,
    NEW_START_DATE::DATETIME,
    TERM_DATE::DATETIME,
    RENEW_START_DATE::DATETIME,
    ENROLLMENT_DATE::DATETIME,
    DNV_FLAG::VARCHAR(1),
    MEMBER_NBR::VARCHAR(11),
    DNV_MEMBER_LOAD_DATE::DATETIME,
    DNV_MEMBER_UPDATE_DATE::DATETIME
FROM MARKETING_EDS.DNV_MEMBERS_VW;