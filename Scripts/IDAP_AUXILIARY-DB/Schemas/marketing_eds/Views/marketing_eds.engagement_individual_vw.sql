create or replace view MARKETING_EDS.ENGAGEMENT_INDIVIDUAL_VW(
	INDIVIDUAL_KEY,
	INDIVIDUAL_ID,
	HOUSEHOLD_KEY,
	ADDRESS_KEY,
	MEMBERSHIP_STATUS,
	MASTER_MEMBER_ID,
	TITLE,
	INDIVIDUAL_FIRST_NAME,
	MIDDLE_INITIAL,
	INDIVIDUAL_LAST_NAME,
	SUFFIX,
	GENDER,
	BIRTH_DATE,
	AGE,
	DECEASED_DATE,
	PREFERRED_CONTACT_METHOD_CODE,
	PREFERRED_CONTACT_METHOD_DESC,
	EMAIL_ADDRESS,
	ALTERNATE_PHONE,
	FIRST_MEMBERSHIP_DATE,
	DO_NOT_CONTACT_INDICATOR,
	INDIVIDUAL_LOAD_DATE,
	INDIVIDUAL_UPDATE_DATE
) COMMENT='Individual-level information (i.e. name/gender/age) for members and prospects'
 as
SELECT
    INDIVIDUAL_KEY::NUMERIC(38,0),  
    INDIVIDUAL_ID::VARCHAR(20),
    HOUSEHOLD_KEY::NUMBER(38,0),
    ADDRESS_KEY::NUMERIC(38,0),                         
    MEMBERSHIP_STATUS::VARCHAR(20),
    MASTER_MEMBER_ID::VARCHAR(12),
    NULLIF(TRIM(TITLE), '')::VARCHAR(10) AS TITLE,
    INITCAP(NULLIF(TRIM(FIRST_NAME), ''))::VARCHAR(25) AS INDIVIDUAL_FIRST_NAME,
    NULLIF(TRIM(LEFT(MIDDLE_INITIAL, 1)), '')::VARCHAR(1) AS MIDDLE_INITIAL,
    INITCAP(NULLIF(TRIM(LAST_NAME), ''))::VARCHAR(35) AS INDIVIDUAL_LAST_NAME,
    NULLIF(TRIM(SUFFIX), '')::VARCHAR(9) AS SUFFIX,
    GENDER::VARCHAR(1),
    BIRTH_DATE::VARCHAR(10),
    FLOOR(DATEDIFF(DAY, BIRTH_DATE, CURRENT_TIMESTAMP)/365.25)::NUMBER(5,2) AS AGE,
    NULLIF(DECEASED_DATE, '9999-12-31')::DATETIME AS DECEASED_DATE,
    PREFERRED_CONTACT_METHOD_CODE::VARCHAR(5),
    PREFERRED_CONTACT_METHOD_DESC::VARCHAR(35),
    NVL(NULLIF(TRIM(EMAIL_ADDRESS), ''), 'UNKNOWN')::VARCHAR(100) AS EMAIL_ADDRESS,
    NVL(NULLIF(TRIM(ALTERNATE_PHONE), ''), 'UNKNOWN')::VARCHAR(20) AS ALTERNATE_PHONE,
    FIRST_MEMBERSHIP_DATE::DATETIME,
    DO_NOT_CONTACT_IND::VARCHAR(1) AS DO_NOT_CONTACT_INDICATOR,
    LOAD_DATE::DATETIME AS INDIVIDUAL_LOAD_DATE,
    UPDATE_DATE::DATETIME AS INDIVIDUAL_UPDATE_DATE
FROM MARKETING_EDS.INDIVIDUAL_VW;