CREATE OR REPLACE VIEW MARKETING_EDS.ENGAGEMENT_EXTATTR_TYPES_VW(
	EXTATTR_TYPE_KEY,
	EXTATTR_TYPE_CODE,
	EXTATTR_DESC,
	EXTATTR_TYPE_LOAD_DATE,
	EXTATTR_TYPE_UPDATE_DATE
) COMMENT='Individual External Attribute Codes for Marketing Automation'
 AS
SELECT ATTRIBUTE_KEY::NUMBER(38,0) AS EXTATTR_TYPE_KEY, 
       ATTRIBUTE_NAME::VARCHAR(100) AS EXTATTR_TYPE_CODE, 
       ATTRIBUTE_DESC::VARCHAR(500) AS EXTATTR_DESC, 
       LOAD_DATE::TIMESTAMP_NTZ(9) AS EXTATTR_TYPE_LOAD_DATE, 
       LOAD_DATE::TIMESTAMP_NTZ(9) AS EXTATTR_TYPE_UPDATE_DATE 
from DEPT_MKTG.MKT_ODSDB.REF_MEMBER_ATTRIBUTES
WHERE ATTRIBUTE_CATEGORY = 'EXT ATTRIBUTES';