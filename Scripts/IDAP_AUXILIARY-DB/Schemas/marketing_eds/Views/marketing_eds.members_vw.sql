!set variable_substitution=true;

create or replace view MARKETING_EDS.MEMBERS_VW(
	MEMBER_KEY,
	INDIVIDUAL_KEY,
	MEMBER_NBR,
	CONTRACT_NBR,
	RELATIONSHIP_CODE,
	RELATIONSHIP_DESC,
	NEW_START_DATE,
	TERM_DATE,
	RENEW_START_DATE,
	ENROLLMENT_DATE,
	MEMBERS_LOAD_DATE,
	MEMBERS_UPDATE_DATE,
	FACT_ENROLLMENT_KEY,
	MMI_RECORD_SEQ,
	FIRST_MEMBERSHIP_DATE
) COMMENT='VIEW FOR MARKETING ENGAGEMENT DATA SOURCE OF MEMBERS'
 as
SELECT
    DIM_MEMBER.DIM_MEMBER_KEY AS MEMBER_KEY,
    DIM_MEMBER.MASTER_MEMBER_ID AS INDIVIDUAL_KEY,
    DIM_MEMBER.MEMBER_NBR,
    DIM_MEMBER.SUBSCRIBER_NBR AS CONTRACT_NBR,
    DIM_MEMBER.SUBSCRIBER_RELATIONSHIP_CODE AS RELATIONSHIP_CODE,
    DIM_MEMBER.SUBSCRIBER_RELATIONSHIP_DESC AS RELATIONSHIP_DESC,
    NSDV.NEW_START_DATE,
    NVL(NVL(CURRENT_MEMBERSHIP.TERM_DATE,FUTURE_MEMBERSHIP.TERM_DATE), INACTIVE_MEMBERSHIP.TERM_DATE) AS TERM_DATE,
    NVL(NVL(CURRENT_MEMBERSHIP.RENEW_START_DATE, FUTURE_MEMBERSHIP.RENEW_START_DATE), INACTIVE_MEMBERSHIP.RENEW_START_DATE) AS RENEW_START_DATE,  
    NVL(NVL(CURRENT_MEMBERSHIP.ENROLLMENT_DATE, FUTURE_MEMBERSHIP.ENROLLMENT_DATE), INACTIVE_MEMBERSHIP.ENROLLMENT_DATE) AS ENROLLMENT_DATE,
    DIM_MEMBER.MEMBER_ADDED_DATE AS MEMBERS_LOAD_DATE,
    TO_DATE(DIM_MEMBER.LAST_UPDATED_DATETIME) AS MEMBERS_UPDATE_DATE,
    NVL(NVL(CURRENT_MEMBERSHIP.fact_enrollment_key, FUTURE_MEMBERSHIP.FACT_ENROLLMENT_KEY), INACTIVE_MEMBERSHIP.FACT_ENROLLMENT_KEY) AS FACT_ENROLLMENT_KEY,
    ROW_NUMBER() OVER (PARTITION BY DIM_MEMBER.MASTER_MEMBER_ID  
                            ORDER BY NVL(NVL(CURRENT_MEMBERSHIP.MEMBERSHIP_STATUS, FUTURE_MEMBERSHIP.MEMBERSHIP_STATUS), INACTIVE_MEMBERSHIP.MEMBERSHIP_STATUS) ASC, COALESCE(CURRENT_MEMBERSHIP.ENROLLMENT_DATE, FUTURE_MEMBERSHIP.ENROLLMENT_DATE, INACTIVE_MEMBERSHIP.ENROLLMENT_DATE) DESC,   DIM_MEMBER.MEMBER_ADDED_DATE DESC, DIM_MEMBER.SUBSCRIBER_RELATIONSHIP_DESC DESC) AS MMI_RECORD_SEQ,
    MIN(NVL(NVL(CURRENT_MEMBERSHIP.ENROLLMENT_DATE, FUTURE_MEMBERSHIP.ENROLLMENT_DATE), INACTIVE_MEMBERSHIP.ENROLLMENT_DATE)) OVER (PARTITION BY DIM_MEMBER.MASTER_MEMBER_ID) AS  FIRST_MEMBERSHIP_DATE
FROM &{IDAP}.DIMDATA.DIM_MEMBER AS DIM_MEMBER 
LEFT JOIN (SELECT SQ1.DIM_MEMBER_KEY, 
                MAX(CASE WHEN SQ1.SEQNUM = 1 THEN SQ1.ELIGIBILITY_END_DATE ELSE NULL END)  AS TERM_DATE,
                MAX(CASE WHEN SQ1.SEQNUM = 1 THEN TO_DATE(SQ1.CURRENT_GROUP_END_DATE) ELSE NULL END) AS RENEW_START_DATE,  
                MAX(CASE WHEN SQ1.SEQNUM = 1 THEN SQ1.ELIGIBILITY_START_DATE ELSE NULL END)  AS ENROLLMENT_DATE,
                MAX(CASE WHEN SQ1.SEQNUM = 1 THEN SQ1.FACT_ENROLLMENT_KEY ELSE NULL END)  AS FACT_ENROLLMENT_KEY,
                'ACTIVE' AS MEMBERSHIP_STATUS,
            FROM (SELECT DIM_MEMBER.DIM_MEMBER_KEY, FACT_ENROLLMENT.FACT_ENROLLMENT_KEY,FACT_ENROLLMENT.ELIGIBILITY_START_DATE, FACT_ENROLLMENT.ELIGIBILITY_END_DATE, DATEADD(day, +1, TO_DATE(DIM_GROUP.CURRENT_GROUP_END_DATE)) AS CURRENT_GROUP_END_DATE, DIM_MEMBER.SUBSCRIBER_RELATIONSHIP_CODE, 
			ROW_NUMBER() OVER (PARTITION BY DIM_MEMBER.DIM_MEMBER_KEY ORDER BY FACT_ENROLLMENT.ELIGIBILITY_START_DATE DESC, FACT_ENROLLMENT.LAST_UPDATED_DATETIME DESC, SUBSCRIBER_RELATIONSHIP_DESC DESC) AS SEQNUM
                    FROM  &{IDAP}.DIMDATA.DIM_MEMBER DIM_MEMBER
                        INNER JOIN &{IDAP}.DIMDATA.FACT_ENROLLMENT FACT_ENROLLMENT
                            ON DIM_MEMBER.DIM_MEMBER_KEY = FACT_ENROLLMENT.DIM_MEMBER_KEY
                        INNER JOIN &{IDAP}.DIMDATA.DIM_GROUP AS DIM_GROUP 
                            ON DIM_GROUP.DIM_GROUP_KEY = FACT_ENROLLMENT.DIM_GROUP_KEY
                        INNER JOIN &{IDAP}.DIMDATA.DIM_ELIGIBILITY_TYPE AS DIM_ELIGIBILITY_TYPE 
                            ON FACT_ENROLLMENT.DIM_ELIGIBILITY_TYPE_KEY = DIM_ELIGIBILITY_TYPE.DIM_ELIGIBILITY_TYPE_KEY
                    WHERE DIM_ELIGIBILITY_TYPE.ELIGIBILITY_TYPE_NAME = 'MAIN'
                    AND DIM_MEMBER.TPA_CLIENT_ID = '000001'
                    AND DIM_MEMBER.TPA_DIV_ID = '0001'
                    AND DIM_MEMBER.TPA_ID = '000001'
                    and DIM_MEMBER.sub_source_name = 'MEDICAL UPMC'
                    and FACT_ENROLLMENT.ELIGIBILITY_START_DATE <>  FACT_ENROLLMENT.ELIGIBILITY_END_DATE
                    and FACT_ENROLLMENT.ELIGIBILITY_START_DATE <= SYSDATE()
                    and FACT_ENROLLMENT.ELIGIBILITY_END_DATE >= SYSDATE()
) SQ1
            GROUP BY SQ1.DIM_MEMBER_KEY
            ) CURRENT_MEMBERSHIP
ON DIM_MEMBER.DIM_MEMBER_KEY = CURRENT_MEMBERSHIP.DIM_MEMBER_KEY            
LEFT JOIN (SELECT SQ1.DIM_MEMBER_KEY, 
            MAX(CASE WHEN SQ1.SEQNUM = 1 THEN SQ1.ELIGIBILITY_END_DATE ELSE NULL END)  AS TERM_DATE,
            MAX(CASE WHEN SQ1.SEQNUM = 1 THEN TO_DATE(SQ1.CURRENT_GROUP_END_DATE) ELSE NULL END) AS RENEW_START_DATE,  
            MAX(CASE WHEN SQ1.SEQNUM = 1 THEN SQ1.ELIGIBILITY_START_DATE ELSE NULL END)  AS ENROLLMENT_DATE,
            MAX(CASE WHEN SQ1.SEQNUM = 1 THEN SQ1.FACT_ENROLLMENT_KEY ELSE NULL END)  AS fact_enrollment_key,
            'FUTURE' AS MEMBERSHIP_STATUS,
        FROM (SELECT DIM_MEMBER.DIM_MEMBER_KEY, FACT_ENROLLMENT.FACT_ENROLLMENT_KEY,FACT_ENROLLMENT.ELIGIBILITY_START_DATE, FACT_ENROLLMENT.ELIGIBILITY_END_DATE, DATEADD(day, +1, TO_DATE(DIM_GROUP.CURRENT_GROUP_END_DATE)) AS CURRENT_GROUP_END_DATE, DIM_MEMBER.SUBSCRIBER_RELATIONSHIP_CODE, 
			ROW_NUMBER() OVER (PARTITION BY DIM_MEMBER.DIM_MEMBER_KEY ORDER BY FACT_ENROLLMENT.ELIGIBILITY_START_DATE ASC, FACT_ENROLLMENT.LAST_UPDATED_DATETIME DESC, SUBSCRIBER_RELATIONSHIP_DESC DESC) AS SEQNUM
                FROM  &{IDAP}.DIMDATA.DIM_MEMBER DIM_MEMBER
                    INNER JOIN &{IDAP}.DIMDATA.FACT_ENROLLMENT FACT_ENROLLMENT
                        ON DIM_MEMBER.DIM_MEMBER_KEY = FACT_ENROLLMENT.DIM_MEMBER_KEY
                    INNER JOIN &{IDAP}.DIMDATA.DIM_GROUP AS DIM_GROUP
                        ON DIM_GROUP.DIM_GROUP_KEY = FACT_ENROLLMENT.DIM_GROUP_KEY
                    INNER JOIN &{IDAP}.DIMDATA.DIM_ELIGIBILITY_TYPE AS DIM_ELIGIBILITY_TYPE 
                        ON FACT_ENROLLMENT.DIM_ELIGIBILITY_TYPE_KEY = DIM_ELIGIBILITY_TYPE.DIM_ELIGIBILITY_TYPE_KEY
                where DIM_ELIGIBILITY_TYPE.ELIGIBILITY_TYPE_NAME = 'MAIN'
                AND DIM_MEMBER.TPA_CLIENT_ID = '000001'
                AND DIM_MEMBER.TPA_DIV_ID = '0001'
                AND DIM_MEMBER.TPA_ID = '000001'
                and DIM_MEMBER.SUB_SOURCE_NAME = 'MEDICAL UPMC'
                and FACT_ENROLLMENT.ELIGIBILITY_START_DATE <>  FACT_ENROLLMENT.eligibility_end_date
                and FACT_ENROLLMENT.ELIGIBILITY_START_DATE > SYSDATE()
                ) SQ1
            GROUP BY SQ1.DIM_MEMBER_KEY) FUTURE_MEMBERSHIP
ON DIM_MEMBER.DIM_MEMBER_KEY = FUTURE_MEMBERSHIP.DIM_MEMBER_KEY
LEFT JOIN (SELECT SQ1.DIM_MEMBER_KEY, 
                MAX(CASE WHEN SQ1.SEQNUM = 1 THEN SQ1.ELIGIBILITY_END_DATE ELSE NULL END)  AS TERM_DATE,
                MAX(CASE WHEN SQ1.SEQNUM = 1 THEN TO_DATE(SQ1.CURRENT_GROUP_END_DATE) ELSE NULL END) AS RENEW_START_DATE,  
                MAX(CASE WHEN SQ1.SEQNUM = 1 THEN SQ1.ELIGIBILITY_START_DATE ELSE NULL END)  AS ENROLLMENT_DATE,
                MAX(CASE WHEN SQ1.SEQNUM = 1 THEN SQ1.FACT_ENROLLMENT_KEY ELSE NULL END)  AS FACT_ENROLLMENT_KEY,
                'INACTIVE' AS MEMBERSHIP_STATUS,
            FROM (SELECT DIM_MEMBER.DIM_MEMBER_KEY, FACT_ENROLLMENT.FACT_ENROLLMENT_KEY,FACT_ENROLLMENT.ELIGIBILITY_START_DATE, FACT_ENROLLMENT.ELIGIBILITY_END_DATE, DATEADD(day, +1, TO_DATE(DIM_GROUP.CURRENT_GROUP_END_DATE)) AS CURRENT_GROUP_END_DATE, DIM_MEMBER.SUBSCRIBER_RELATIONSHIP_CODE, 
			ROW_NUMBER() OVER (PARTITION BY DIM_MEMBER.DIM_MEMBER_KEY ORDER BY FACT_ENROLLMENT.ELIGIBILITY_START_DATE DESC, FACT_ENROLLMENT.LAST_UPDATED_DATETIME DESC, SUBSCRIBER_RELATIONSHIP_DESC DESC) AS SEQNUM
                    FROM  &{IDAP}.DIMDATA.DIM_MEMBER DIM_MEMBER
                        INNER JOIN &{IDAP}.DIMDATA.FACT_ENROLLMENT FACT_ENROLLMENT
                            ON DIM_MEMBER.DIM_MEMBER_KEY = FACT_ENROLLMENT.DIM_MEMBER_KEY
                        INNER JOIN &{IDAP}.DIMDATA.DIM_GROUP AS DIM_GROUP 
                            ON DIM_GROUP.DIM_GROUP_KEY = FACT_ENROLLMENT.DIM_GROUP_KEY
                        INNER JOIN &{IDAP}.DIMDATA.DIM_ELIGIBILITY_TYPE AS DIM_ELIGIBILITY_TYPE 
                            ON FACT_ENROLLMENT.DIM_ELIGIBILITY_TYPE_KEY = DIM_ELIGIBILITY_TYPE.DIM_ELIGIBILITY_TYPE_KEY
                    WHERE DIM_ELIGIBILITY_TYPE.ELIGIBILITY_TYPE_NAME = 'MAIN'
                    AND DIM_MEMBER.TPA_CLIENT_ID = '000001'
                    AND DIM_MEMBER.TPA_DIV_ID = '0001'
                    AND DIM_MEMBER.TPA_ID = '000001'
                    and DIM_MEMBER.SUB_SOURCE_NAME = 'MEDICAL UPMC'
                    and FACT_ENROLLMENT.ELIGIBILITY_START_DATE <>  FACT_ENROLLMENT.ELIGIBILITY_END_DATE
                    and FACT_ENROLLMENT.ELIGIBILITY_START_DATE < SYSDATE()
                    and FACT_ENROLLMENT.ELIGIBILITY_END_DATE < SYSDATE()
) SQ1
            GROUP BY SQ1.DIM_MEMBER_KEY
            ) INACTIVE_MEMBERSHIP
ON DIM_MEMBER.DIM_MEMBER_KEY = INACTIVE_MEMBERSHIP.DIM_MEMBER_KEY
LEFT JOIN DEPT_MKTG.MKT_ODSDB.NEW_START_DATE_VW AS NSDV
ON DIM_MEMBER.MEMBER_NBR = NSDV.MEMBER_NBR
WHERE DIM_MEMBER.TPA_CLIENT_ID = '000001'
AND DIM_MEMBER.TPA_DIV_ID = '0001'
AND DIM_MEMBER.TPA_ID = '000001'
AND DIM_MEMBER.SUB_SOURCE_NAME = 'MEDICAL UPMC'
AND DIM_MEMBER.MASTER_MEMBER_ID IS NOT NULL
AND COALESCE(CURRENT_MEMBERSHIP.ENROLLMENT_DATE, FUTURE_MEMBERSHIP.ENROLLMENT_DATE, INACTIVE_MEMBERSHIP.ENROLLMENT_DATE) IS NOT NULL
;

!set variable_substitution=false;