!set variable_substitution=true;

CREATE OR REPLACE VIEW MARKETING_EDS.DNV_DIVISION_VW
COMMENT = 'VIEW FOR MARKETING ENGAGEMENT DATA SOURCE FOR DENTAL AND VISION DIVISIONS'
(
	DNV_DIVISION_KEY,
	DIVISION_ID,
	DIVISION_DESC,
	CORPORATION_ID,
	CORPORATION_NAME,
	GROUP_ID,
	GROUP_DESC,
	DNV_DIVISION_LOAD_DATE,
	DNV_DIVISION_UPDATE_DATE,
	DIM_GROUP_KEY,
	DIM_SUB_GROUP_KEY
) 
AS
SELECT  CONCAT(DIM_GROUP.DIM_GROUP_KEY,'-', DIM_SUB_GROUP.DIM_SUB_GROUP_KEY) AS DNV_DIVISION_KEY,
        DIM_SUB_GROUP.DIVISION_ID AS DIVISION_ID, 
        DIM_SUB_GROUP.SUB_GROUP_NAME  AS DIVISION_DESC, 
        DIM_GROUP.CORPORATE_ID  AS CORPORATION_ID, 
        CORP_NAME_LKP.CORPORATION_NAME AS CORPORATION_NAME, 
        DIM_GROUP.GROUP_NBR  AS GROUP_ID, 
        DIM_GROUP.GROUP_NAME  AS GROUP_DESC, 
        DIM_SUB_GROUP.INSERT_DATETIME AS DNV_DIVISION_LOAD_DATE, 
        DIM_SUB_GROUP.LAST_UPDATED_DATETIME AS DNV_DIVISION_UPDATE_DATE,
        DIM_GROUP.DIM_GROUP_KEY, DIM_SUB_GROUP.DIM_SUB_GROUP_KEY
FROM &{IDAP}.DIMDATA.DIM_SUB_GROUP AS DIM_SUB_GROUP
INNER JOIN &{IDAP}.DIMDATA.DIM_GROUP AS DIM_GROUP  
    ON DIM_SUB_GROUP.GROUP_NBR = DIM_GROUP.GROUP_NBR
LEFT JOIN &{IDW}.STAGING.CORP_NAME_LKP CORP_NAME_LKP
    ON DIM_GROUP.CORPORATE_ID = CORP_NAME_LKP.CORPORATION_ID
WHERE DIM_SUB_GROUP.TPA_CLIENT_ID = '000001'
AND DIM_SUB_GROUP.TPA_DIV_ID = '0002'
AND DIM_SUB_GROUP.TPA_ID = '000001'
AND DIM_GROUP.TPA_CLIENT_ID = '000001'
AND DIM_GROUP.TPA_DIV_ID = '0002'
AND DIM_GROUP.TPA_ID = '000001'
;

!set variable_substitution=false;