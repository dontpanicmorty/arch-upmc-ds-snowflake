CREATE OR REPLACE VIEW MARKETING_EDS.ENGAGEMENT_PLAN_VW(
	PLAN_KEY,
	DIVISION_KEY,
	PLAN_NBR,
	PLAN_DESC,
	PLAN_TYPE,
	PRODUCT_CODE,
	PRODUCT_DESC,
	HEALTHY_U_INDICATOR,
	BUSINESS_INSURED_TYPE,
	LINE_OF_BUSINESS,
	PLAN_LOAD_DATE,
	PLAN_UPDATE_DATE
) COMMENT='Plan information for medical members'
 AS
SELECT
    CAST(LPAD(SPLIT_PART(PLAN_KEY, '-', 1), 12, '0') ||  
    LPAD(SPLIT_PART(PLAN_KEY, '-', 2), 12, '0') ||  
    LPAD(SPLIT_PART(PLAN_KEY, '-', 3), 12, '0') AS NUMBER(38,0))::NUMBER(38,0) AS PLAN_KEY,
    CAST(LPAD(SPLIT_PART(DIVISION_KEY, '-', 1), 12, '0') ||  
            LPAD(SPLIT_PART(DIVISION_KEY, '-', 2), 12, '0') AS NUMBER(38,0))::NUMBER(38,0) AS DIVISION_KEY ,
    PLAN_NBR::VARCHAR(5),
    PLAN_DESC::VARCHAR(50),
    PLAN_TYPE::VARCHAR(250),
    PRODUCT_CODE::VARCHAR(10),
    PRODUCT_DESC::VARCHAR(30),
    HEALTHY_U::VARCHAR(2) AS HEALTHY_U_INDICATOR,
    BUSINESS_INSURED_TYPE::VARCHAR(20),
    CASE
        WHEN LINE_OF_BUSINESS = 'WL' THEN 'W'
        ELSE LINE_OF_BUSINESS
    END::VARCHAR(10) AS LINE_OF_BUSINESS,
    LOAD_DATE::DATETIME AS PLAN_LOAD_DATE,
    UPDATE_DATE::DATETIME AS PLAN_UPDATE_DATE
FROM MARKETING_EDS.PLAN_VW;