!set variable_substitution=true;

CREATE OR REPLACE VIEW MARKETING_EDS.MEMBER_RIDER_VW
(
    MEMBER_NBR,
	RIDER_CODE,
	RIDER_TYPE,
	SEQNUM,
	DIM_RIDER_KEY,
	FACT_ENROLLMENT_KEY,
	ELIGIBILITY_START_DATE,
	ELIGIBILITY_END_DATE
) COMMENT='VIEW FOR MARKETING ENGAGEMENT DATA SOURCE OF MEMBER AND RIDER COMBINATIONS'
 AS
SELECT * 
FROM (SELECT MEMBERS_VW.MEMBER_NBR, DIM_RIDER.RIDER_CODE, DIM_RIDER.RIDER_TYPE_CODE AS RIDER_TYPE,  
                    ROW_NUMBER() OVER (PARTITION BY MEMBERS_VW.MEMBER_KEY, DIM_RIDER.RIDER_CODE ORDER BY FACT_ENROLLMENT.ELIGIBILITY_START_DATE DESC) AS SEQNUM,
                    FACT_ENROLLMENT.DIM_RIDER_KEY, FACT_ENROLLMENT.FACT_ENROLLMENT_KEY,FACT_ENROLLMENT.ELIGIBILITY_START_DATE, FACT_ENROLLMENT.ELIGIBILITY_END_DATE
        FROM  MARKETING_EDS.MEMBERS_VW MEMBERS_VW
            INNER JOIN &{IDAP}.DIMDATA.FACT_ENROLLMENT FACT_ENROLLMENT
                ON MEMBERS_VW.MEMBER_KEY = FACT_ENROLLMENT.DIM_MEMBER_KEY 
            INNER JOIN &{IDAP}.DIMDATA.DIM_ELIGIBILITY_TYPE AS DIM_ELIGIBILITY_TYPE
                ON FACT_ENROLLMENT.DIM_ELIGIBILITY_TYPE_KEY = DIM_ELIGIBILITY_TYPE.DIM_ELIGIBILITY_TYPE_KEY
            INNER JOIN &{IDAP}.DIMDATA.DIM_RIDER DIM_RIDER
            ON FACT_ENROLLMENT.DIM_RIDER_KEY = DIM_RIDER.DIM_RIDER_KEY
        where DIM_ELIGIBILITY_TYPE.ELIGIBILITY_TYPE_NAME = 'RIDER'
        and FACT_ENROLLMENT.ELIGIBILITY_START_DATE <>  FACT_ENROLLMENT.ELIGIBILITY_END_DATE
        and FACT_ENROLLMENT.ELIGIBILITY_END_DATE >= SYSDATE()
        ) SQ1
WHERE SQ1.SEQNUM = 1
;

!set variable_substitution=false;