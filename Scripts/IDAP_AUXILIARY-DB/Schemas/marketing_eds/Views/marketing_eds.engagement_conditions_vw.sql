create or replace view MARKETING_EDS.ENGAGEMENT_CONDITIONS_VW(
	CONDITION_KEY,
	CONDITION_CODE,
	CONDITION_SOURCE,
	CONDITION_DESC,
	CONDITION_LOAD_DATE,
	CONDITION_UPDATE_DATE
) COMMENT='Member Condition Codes for Marketing Automation'
 as
select  ATTRIBUTE_KEY::NUMBER(38,0) AS CONDITION_KEY, 
        ATTRIBUTE_NAME::VARCHAR(100) AS CONDITION_CODE, 
        SSC::VARCHAR(100) AS CONDITION_SOURCE, 
        ATTRIBUTE_DESC::VARCHAR(500) AS CONDITION_DESC, 
        LOAD_DATE::TIMESTAMP_NTZ(9) AS CONDITION_LOAD_DATE, 
        LOAD_DATE::TIMESTAMP_NTZ(9) AS CONDITION_UPDATE_DATE 
from DEPT_MKTG.MKT_ODSDB.REF_MEMBER_ATTRIBUTES
WHERE ATTRIBUTE_CATEGORY = 'CONDITIONS'
;