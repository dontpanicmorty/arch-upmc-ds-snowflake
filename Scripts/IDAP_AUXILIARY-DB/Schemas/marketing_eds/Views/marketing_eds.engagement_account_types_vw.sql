create or replace view MARKETING_EDS.ENGAGEMENT_ACCOUNT_TYPES_VW(
	ACCOUNT_TYPE_KEY,
	ACCOUNT_TYPE,
	ACCOUNT_DESC,
	EVENT_SOURCE,
	ACCOUNT_TYPE_LOAD_DATE,
	ACCOUNT_TYPE_UPDATE_DATE
) COMMENT='Member Account Types for Marketing Automation'
 as
select  ATTRIBUTE_KEY::NUMBER(38,0) AS ACCOUNT_TYPE_KEY, 
        ATTRIBUTE_NAME::VARCHAR(100) AS ACCOUNT_TYPE, 
        ATTRIBUTE_DESC::VARCHAR(500) AS ACCOUNT_DESC, 
        SSC::VARCHAR(100) AS EVENT_SOURCE, 
        LOAD_DATE::TIMESTAMP_NTZ(9) AS ACCOUNT_TYPE_LOAD_DATE, 
        LOAD_DATE::TIMESTAMP_NTZ(9) AS ACCOUNT_TYPE_UPDATE_DATE 
from DEPT_MKTG.MKT_ODSDB.REF_MEMBER_ATTRIBUTES
WHERE ATTRIBUTE_CATEGORY = 'ACCOUNT'
;