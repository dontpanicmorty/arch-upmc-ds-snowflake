create or replace view MARKETING_EDS.MARKETING_DNV_MEMBER_RIDER_VW(
	DNV_MEMBER_KEY,
	DNV_RIDER_KEY,
	DNVMBR_LOAD_DATE
) COMMENT='Links IDAP_AUXILIARY.MARKETING_EDS.MARKETING_DNV_MEMBERS_VW to IDAP_AUXILIARY.MARKETING_EDS.MARKETING_DNV_RIDERS_VW'
 as
SELECT
    DNV_MEMBER_KEY,
    DNV_MEMBER_RIDER_KEY AS DNV_RIDER_KEY,
    DNV_MBR_LOAD_DATE::DATETIME AS DNVMBR_LOAD_DATE
FROM MARKETING_EDS.DNV_MEMBER_RIDER_VW;
