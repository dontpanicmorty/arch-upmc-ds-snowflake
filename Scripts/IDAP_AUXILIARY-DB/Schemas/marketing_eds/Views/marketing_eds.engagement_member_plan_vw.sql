create or replace view MARKETING_EDS.ENGAGEMENT_MEMBER_PLAN_VW(
	MEMBER_KEY,
	PLAN_KEY,
	MEMBER_PLAN_LOAD_DATE
) COMMENT='Links IDAP_AUXILIARY.MARKETING_EDS.ENGAGEMENT_MEMBERS_VW to IDAP_AUXILIARY.MARKETING_EDS.ENGAGEMENT_PLAN_VW'
 as
SELECT
    MEMBER_KEY,
    CAST(LPAD(SPLIT_PART(PLAN_KEY, '-', 1), 12, '0') ||  
    LPAD(SPLIT_PART(PLAN_KEY, '-', 2), 12, '0') ||  
    LPAD(SPLIT_PART(PLAN_KEY, '-', 3), 12, '0') AS NUMBER(38,0))::NUMBER(38,0) AS PLAN_KEY,
    LOAD_DATE::DATETIME AS MEMBER_PLAN_LOAD_DATE
FROM MARKETING_EDS.MEMBER_PLAN_VW;