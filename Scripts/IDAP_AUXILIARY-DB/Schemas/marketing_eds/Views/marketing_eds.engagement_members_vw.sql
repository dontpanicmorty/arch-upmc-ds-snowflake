CREATE OR REPLACE VIEW MARKETING_EDS.ENGAGEMENT_MEMBERS_VW(
	MEMBER_KEY,
	INDIVIDUAL_KEY,
	MEMBER_NBR,
	CONTRACT_NBR,
	RELATIONSHIP_CODE,
	RELATIONSHIP_DESC,
	NEW_START_DATE,
	TERM_DATE,
	RENEW_START_DATE,
	ENROLLMENT_DATE,
	MEMBERS_LOAD_DATE,
	MEMBERS_UPDATE_DATE
) COMMENT='Medical members and their start/term dates'
 AS
SELECT
    MEMBER_KEY::NUMBER(38,0),
    INDIVIDUAL_KEY::NUMBER(38,0),
    MEMBER_NBR::VARCHAR(11),
    CONTRACT_NBR::VARCHAR(9),
    CASE WHEN RELATIONSHIP_CODE IN ('AD','CD','DB','DE','DS','FC','MD','N1','N2','N3','NB','OD','PD','SD','WD') THEN 'D'
            ELSE CASE WHEN RELATIONSHIP_CODE IN ('MP','SB','ST') THEN 'E'
            ELSE CASE WHEN RELATIONSHIP_CODE IN ('SP','SX') THEN 'S'
            ELSE CASE WHEN RELATIONSHIP_CODE IN ('DP') THEN 'P'
            ELSE 'E' END END END END ::VARCHAR(2) AS RELATIONSHIP_CODE,
    UPPER(LEFT(CONCAT(RELATIONSHIP_CODE,'-', RELATIONSHIP_DESC) ,20))::VARCHAR(20) AS RELATIONSHIP_DESC,
    NEW_START_DATE::DATETIME,
    TERM_DATE::DATETIME,
    RENEW_START_DATE::DATETIME,
    ENROLLMENT_DATE::DATETIME,
    MEMBERS_LOAD_DATE::DATETIME,
    MEMBERS_UPDATE_DATE::DATETIME
FROM MARKETING_EDS.MEMBERS_VW
UNION ALL
SELECT
    -1::NUMBER(38,0) AS MEMBER_KEY,
    -1::NUMBER(38,0) AS INDIVIDUAL_KEY,
    '00000000000'::VARCHAR(11) AS MEMBER_NBR,
    '000000000'::VARCHAR(9) AS CONTRACT_NBR,
    'E'::VARCHAR(2) AS RELATIONSHIP_CODE,
    'SB-SUBSCRIBER'::VARCHAR(20) AS RELATIONSHIP_DESC,
    CURRENT_DATE::DATETIME AS NEW_START_DATE,
    '9999-12-31'::DATETIME AS TERM_DATE,
    CURRENT_DATE::DATETIME AS RENEW_START_DATE,
    CURRENT_DATE::DATETIME AS ENROLLMENT_DATE,
    CURRENT_DATE::DATETIME AS MEMBERS_LOAD_DATE,
    CURRENT_DATE::DATETIME AS MEMBERS_UPDATE_DATE
;