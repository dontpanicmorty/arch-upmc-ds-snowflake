CREATE OR REPLACE VIEW MARKETING_EDS.MARKETING_DNV_DIVISION_VW(
	DNV_DIVISION_KEY,
	DIVISION_ID,
	DIVISION_DESC,
	CORPORATION_ID,
	CORPORATION_NAME,
	GROUP_ID,
	GROUP_DESC,
	DNV_DIVISION_LOAD_DATE,
	DNV_DIVISION_UPDATE_DATE
) COMMENT='Division information for dental/vision members'
 AS
SELECT
     CAST(LPAD(SPLIT_PART(DNV_DIVISION_KEY, '-', 1), 12, '0') ||  
            LPAD(SPLIT_PART(DNV_DIVISION_KEY, '-', 2), 12, '0') AS NUMBER(38,0))::NUMBER(38,0) AS DNV_DIVISION_KEY,
    DIVISION_ID::VARCHAR(10),
    DIVISION_DESC::VARCHAR(40),
    CORPORATION_ID::VARCHAR(4),
    CORPORATION_NAME::VARCHAR(250),
    GROUP_ID::VARCHAR(6),
    GROUP_DESC::VARCHAR(30),
    DNV_DIVISION_LOAD_DATE::DATETIME,
    DNV_DIVISION_UPDATE_DATE::DATETIME
FROM MARKETING_EDS.DNV_DIVISION_VW;