!set variable_substitution=true;
create or replace view MARKETING_EDS.HOUSEHOLD_SOURCE_VW(
    INDIVIDUAL_KEY,
    CONTRACT_NBR,
    MAIDRESPPARTY,
    ADDRESSLASTNAME,
    ADDRESS,
    MMI_STATUS,
    LINE_OF_BUSINESS,
    ADDRESS_CNT
) as
WITH IND AS (
    SELECT
        INDIVIDUAL_KEY,
        ADDRESS_KEY,
        MEMBERSHIP_STATUS,
        INDIVIDUAL_LAST_NAME
    FROM MARKETING_EDS.ENGAGEMENT_INDIVIDUAL_VW
    WHERE MEMBERSHIP_STATUS = 'ACTIVE'
),
ADR AS (
    SELECT
        ADDRESS_KEY,
        HOUSEHOLD_ID_ADR
    FROM MARKETING_EDS.ADDRESS_VW
),
MEDICAL AS (
    SELECT
        IND.INDIVIDUAL_KEY,
        NULLIF(TRIM(ENGAGEMENT_MEMBERS_VW.CONTRACT_NBR), '') AS CONTRACT_NBR,
        NULLIF(TRIM(DIM_MEMBER.MEDICAID_ID) || '-' || TRIM(DIM_MEMBER.RESPONSIBLE_PARTY_NAME), '-') AS MAIDRESPPARTY,
        NULLIF(TRIM(ADR.HOUSEHOLD_ID_ADR) || '-' || TRIM(IND.INDIVIDUAL_LAST_NAME), '-') AS ADDRESSLASTNAME,
        NULLIF(TRIM(ADR.HOUSEHOLD_ID_ADR), '') AS ADDRESS,
        NULLIF(TRIM(IND.MEMBERSHIP_STATUS), '') AS MMI_STATUS,
        NULLIF(TRIM(ENGAGEMENT_PLAN_VW.LINE_OF_BUSINESS), '') AS LINE_OF_BUSINESS
    FROM IND
    INNER JOIN MARKETING_EDS.ENGAGEMENT_MEMBERS_VW
        ON IND.INDIVIDUAL_KEY = ENGAGEMENT_MEMBERS_VW.INDIVIDUAL_KEY
        AND ENGAGEMENT_MEMBERS_VW.ENROLLMENT_DATE <= SYSDATE()
        AND ENGAGEMENT_MEMBERS_VW.TERM_DATE >= SYSDATE()
    LEFT JOIN ADR
        ON IND.ADDRESS_KEY = ADR.ADDRESS_KEY
    LEFT JOIN &{IDAP}.DIMDATA.DIM_MEMBER
        ON ENGAGEMENT_MEMBERS_VW.MEMBER_NBR = DIM_MEMBER.MEMBER_NBR
    LEFT JOIN MARKETING_EDS.ENGAGEMENT_MEMBER_PLAN_VW
        ON ENGAGEMENT_MEMBERS_VW.MEMBER_KEY = ENGAGEMENT_MEMBER_PLAN_VW.MEMBER_KEY
    LEFT JOIN MARKETING_EDS.ENGAGEMENT_PLAN_VW
        ON ENGAGEMENT_MEMBER_PLAN_VW.PLAN_KEY = ENGAGEMENT_PLAN_VW.PLAN_KEY
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY IND.INDIVIDUAL_KEY
        ORDER BY 
        ENGAGEMENT_MEMBER_PLAN_VW.MEMBER_PLAN_LOAD_DATE DESC NULLS LAST,
        ENGAGEMENT_MEMBERS_VW.MEMBER_NBR DESC NULLS LAST
    ) = 1
),
DNV AS (
    SELECT
        IND.INDIVIDUAL_KEY,
        NULLIF(TRIM(MARKETING_DNV_MEMBERS_VW.DNV_CONTRACT_NBR), '') AS CONTRACT_NBR,
        NULLIF(TRIM(DIM_MEMBER.MEDICAID_ID) || '-' || TRIM(DIM_MEMBER.RESPONSIBLE_PARTY_NAME), '-') AS MAIDRESPPARTY,
        NULLIF(TRIM(ADR.HOUSEHOLD_ID_ADR) || '-' || TRIM(IND.INDIVIDUAL_LAST_NAME), '-') AS ADDRESSLASTNAME,
        NULLIF(TRIM(ADR.HOUSEHOLD_ID_ADR), '') AS ADDRESS,
        NULLIF(TRIM(IND.MEMBERSHIP_STATUS), '') AS MMI_STATUS,
        NULLIF(TRIM(MARKETING_DNV_PLAN_VW.LINE_OF_BUSINESS), '') AS LINE_OF_BUSINESS
    FROM IND
    INNER JOIN MARKETING_EDS.MARKETING_DNV_MEMBERS_VW
        ON IND.INDIVIDUAL_KEY = MARKETING_DNV_MEMBERS_VW.INDIVIDUAL_KEY
        AND MARKETING_DNV_MEMBERS_VW.ENROLLMENT_DATE <= SYSDATE()
        AND MARKETING_DNV_MEMBERS_VW.TERM_DATE >= SYSDATE()
    LEFT JOIN ADR
        ON IND.ADDRESS_KEY = ADR.ADDRESS_KEY
    LEFT JOIN &{IDAP}.DIMDATA.DIM_MEMBER
        ON MARKETING_DNV_MEMBERS_VW.DNV_MEMBER_NBR = DIM_MEMBER.MEMBER_NBR
    LEFT JOIN MARKETING_EDS.MARKETING_DNV_MEMBER_PLAN_VW
        ON MARKETING_DNV_MEMBERS_VW.DNV_MEMBER_KEY = MARKETING_DNV_MEMBER_PLAN_VW.DNV_MEMBER_KEY
    LEFT JOIN MARKETING_EDS.MARKETING_DNV_PLAN_VW
        ON MARKETING_DNV_MEMBER_PLAN_VW.DNV_PLAN_KEY = MARKETING_DNV_PLAN_VW.DNV_PLAN_KEY
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY IND.INDIVIDUAL_KEY
        ORDER BY 
        MARKETING_DNV_MEMBER_PLAN_VW.DNV_MBRPLAN_LOAD_DATE DESC NULLS LAST,
        MARKETING_DNV_MEMBERS_VW.DNV_MEMBER_NBR DESC NULLS LAST
    ) = 1
)
SELECT
    COALESCE(MEDICAL.INDIVIDUAL_KEY, DNV.INDIVIDUAL_KEY) AS INDIVIDUAL_KEY,
    COALESCE(MEDICAL.CONTRACT_NBR, DNV.CONTRACT_NBR) AS CONTRACT_NBR,
    COALESCE(MEDICAL.MAIDRESPPARTY, DNV.MAIDRESPPARTY) AS MAIDRESPPARTY,
    COALESCE(MEDICAL.ADDRESSLASTNAME, DNV.ADDRESSLASTNAME) AS ADDRESSLASTNAME,
    COALESCE(MEDICAL.ADDRESS, DNV.ADDRESS) AS ADDRESS,
    COALESCE(MEDICAL.MMI_STATUS, DNV.MMI_STATUS) AS MMI_STATUS,
    COALESCE(MEDICAL.LINE_OF_BUSINESS, DNV.LINE_OF_BUSINESS) AS LINE_OF_BUSINESS,
    COUNT(DISTINCT COALESCE(MEDICAL.INDIVIDUAL_KEY, DNV.INDIVIDUAL_KEY)) OVER (PARTITION BY COALESCE(MEDICAL.ADDRESS, DNV.ADDRESS)) AS ADDRESS_CNT
FROM MEDICAL
FULL JOIN DNV
    ON MEDICAL.INDIVIDUAL_KEY = DNV.INDIVIDUAL_KEY
;
!set variable_substitution=false;