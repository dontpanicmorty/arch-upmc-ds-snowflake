CREATE OR REPLACE view MARKETING_EDS.ENGAGEMENT_DIVISION_VW(
	DIVISION_KEY,
	DIVISION_ID,
	DIVISION_DESC,
	CORPORATION_ID,
	CORPORATION_NAME,
	GROUP_ID,
	GROUP_DESC,
	DIVISION_LOAD_DATE,
	DIVISION_UPDATE_DATE
) COMMENT='Division information for medical members'
 AS
SELECT
    CAST(LPAD(SPLIT_PART(DIVISION_KEY, '-', 1), 12, '0') ||  
            LPAD(SPLIT_PART(DIVISION_KEY, '-', 2), 12, '0') AS NUMBER(38,0))::NUMBER(38,0) AS DIVISION_KEY,
    DIVISION_ID::VARCHAR(10),
    DIVISION_DESC::VARCHAR(40),
    CORPORATION_ID::VARCHAR(4),
    CORPORATION_NAME::VARCHAR(250),
    GROUP_ID::VARCHAR(6),
    GROUP_DESC::VARCHAR(30),
    LOAD_DATE::DATETIME AS DIVISION_LOAD_DATE,
    UPDATE_DATE::DATETIME AS DIVISION_UPDATE_DATE
FROM MARKETING_EDS.DIVISION_VW;