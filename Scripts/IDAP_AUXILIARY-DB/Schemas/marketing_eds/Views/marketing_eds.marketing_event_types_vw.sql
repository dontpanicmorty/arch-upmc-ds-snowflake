CREATE OR REPLACE VIEW MARKETING_EDS.MARKETING_EVENT_TYPES_VW(
	EVENT_TYPE_KEY,
	EVENT_TYPE_CODE,
	EVENT_TYPE_DESCRIPTION,
	EVENT_SOURCE,
	EVENT_TYPE,
	EVENT_TYPE_LOAD_DATE,
	EVENT_TYPE_UPDATE_DATE
) COMMENT='Member Event Type Codes for Marketing Automation'
 AS
select  ATTRIBUTE_KEY::NUMBER(38,0) AS EVENT_TYPE_KEY, 
        ATTRIBUTE_NAME::VARCHAR(100) AS EVENT_TYPE_CODE, 
        ATTRIBUTE_DESC::VARCHAR(500) AS EVENT_TYPE_DESCRIPTION, 
        SSC::VARCHAR(100) AS EVENT_SOURCE, 
        'COUNT'::VARCHAR(10) AS EVENT_TYPE, 
        LOAD_DATE::TIMESTAMP_NTZ(9) AS EVENT_TYPE_LOAD_DATE, 
        LOAD_DATE::TIMESTAMP_NTZ(9) AS EVENT_TYPE_UPDATE_DATE 
from DEPT_MKTG.MKT_ODSDB.REF_MEMBER_ATTRIBUTES
WHERE ATTRIBUTE_CATEGORY = 'EVENTS'
;