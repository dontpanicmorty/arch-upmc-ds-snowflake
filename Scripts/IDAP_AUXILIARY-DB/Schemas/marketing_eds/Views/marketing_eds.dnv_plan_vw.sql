CREATE OR REPLACE VIEW MARKETING_EDS.DNV_PLAN_VW
COMMENT= 'VIEW FOR MARKETING ENGAGEMENT DATA SOURCE OF DENTAL AND VISION PLANS'
(
	DNV_PLAN_KEY,
	DNV_DIVISION_KEY,
	PLAN_NBR,
	PLAN_DESC,
	PLAN_TYPE,
	PRODUCT_CODE,
	PRODUCT_DESC,
	HEALTHY_U,
	BUSINESS_INSURED_TYPE,
	LINE_OF_BUSINESS,
	DNV_PLAN_LOAD_DATE,
	DNV_PLAN_UPDATE_DATE,
	DIM_PLAN_KEY
)
AS
SELECT  ARRAY_TO_STRING(
        ARRAY_CONSTRUCT_COMPACT(
            DIM_PLAN.DIM_PLAN_KEY
            ,TMP_DIM_DIVISION.DIM_GROUP_KEY
            ,TMP_DIM_DIVISION.DIM_SUB_GROUP_KEY
        )
        ,'-'
    ) AS DNV_PLAN_KEY, 
        IFNULL(TMP_DIM_DIVISION.DNV_DIVISION_KEY,'-1') AS DNV_DIVISION_KEY, 
        DIM_PLAN.PLAN_CODE AS PLAN_NBR, 
        DIM_PLAN.PLAN_DESC AS PLAN_DESC, 
        DIM_PLAN.PLAN_CATEGORY_NAME  AS PLAN_TYPE, 
        DIM_PLAN.PLAN_TYPE_CODE AS PRODUCT_CODE, 
        DIM_PLAN.LOB_PLAN_TYPE_DESC AS PRODUCT_DESC, 
        DIM_PLAN.HEALTHY_U_IND AS HEALTHY_U, 
        DIM_PLAN.FUNDING_TYPE_DESC AS BUSINESS_INSURED_TYPE, 
        DIM_PLAN.LOB_CODE AS LINE_OF_BUSINESS, 
        DIM_PLAN.INSERT_DATETIME AS DNV_PLAN_LOAD_DATE, 
        DIM_PLAN.LAST_UPDATED_DATETIME AS DNV_PLAN_UPDATE_DATE, 
        DIM_PLAN.DIM_PLAN_KEY        
FROM &{IDAP}.DIMDATA.DIM_PLAN AS DIM_PLAN
LEFT JOIN (SELECT DISTINCT DIM_PLAN_KEY, DIM_GROUP_KEY, DIM_SUB_GROUP_KEY, CONCAT(DIM_GROUP_KEY, '-', DIM_SUB_GROUP_KEY) AS DNV_DIVISION_KEY  FROM &{IDAP}.DIMDATA.FACT_ENROLLMENT) TMP_DIM_DIVISION
ON DIM_PLAN.DIM_PLAN_KEY = TMP_DIM_DIVISION.dim_plan_key
WHERE 1 = 1
AND DIM_PLAN.TPA_CLIENT_ID = '000001'
AND DIM_PLAN.TPA_DIV_ID = '0002'
AND DIM_PLAN.TPA_ID = '000001'
;

!set variable_substitution=false;

