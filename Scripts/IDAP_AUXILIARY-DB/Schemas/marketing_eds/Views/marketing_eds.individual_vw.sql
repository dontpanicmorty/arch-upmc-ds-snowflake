CREATE OR REPLACE VIEW MARKETING_EDS.INDIVIDUAL_VW(
              INDIVIDUAL_KEY,
              INDIVIDUAL_ID,
              HOUSEHOLD_KEY,
              ADDRESS_KEY,
              MEMBERSHIP_STATUS,
              MASTER_MEMBER_ID,
              TITLE,
              FIRST_NAME,
              MIDDLE_INITIAL,
              LAST_NAME,
              SUFFIX,
              GENDER,
              BIRTH_DATE,
              AGE,
              DECEASED_DATE,
              PREFERRED_CONTACT_METHOD_CODE,
              PREFERRED_CONTACT_METHOD_DESC,
              EMAIL_ADDRESS,
              ALTERNATE_PHONE,
              FIRST_MEMBERSHIP_DATE,
              DO_NOT_CONTACT_IND,
              LOAD_DATE,
              UPDATE_DATE,
              MEMBER_PREFERENCES_KEY,
              DIM_MEMBER_KEY
) COMMENT='VIEW FOR MARKETING ENGAGEMENT DATA SOURCE OF INDIVIDUALS'
AS
WITH
MEMBERS AS
(
    SELECT 
        MEMBERS_VW.INDIVIDUAL_KEY,
        'MEDICAL' AS RECORD_SOURCE,
        MEMBERS_VW.MEMBERS_LOAD_DATE AS LOAD_DATE,
        MEMBERS_VW.MEMBERS_UPDATE_DATE AS UPDATE_DATE,
        MEMBERS_VW.MEMBER_KEY AS DIM_MEMBER_KEY,
        MEMBERS_VW.FIRST_MEMBERSHIP_DATE,
        MEMBERS_VW.MEMBER_NBR,
        'MEDICAL' AS SUBSCRIPTION_TYPE,
        CASE 
            WHEN MEMBERS_VW.ENROLLMENT_DATE <= SYSDATE() 
             AND MEMBERS_VW.TERM_DATE >= SYSDATE() THEN 'ACTIVE'
            WHEN MEMBERS_VW.ENROLLMENT_DATE > SYSDATE() 
             AND MEMBERS_VW.TERM_DATE > SYSDATE() THEN 'FUTURE'
            ELSE 'INACTIVE'
        END AS MEMBERSHIP_STATUS
    FROM MARKETING_EDS.MEMBERS_VW
    WHERE MEMBERS_VW.INDIVIDUAL_KEY IS NOT NULL
      AND MEMBERS_VW.MMI_RECORD_SEQ = 1

    UNION

    SELECT 
        DNV_MEMBERS_VW.INDIVIDUAL_KEY,
        'DNV' AS RECORD_SOURCE,
        DNV_MEMBERS_VW.DNV_MEMBER_LOAD_DATE AS LOAD_DATE,
        DNV_MEMBERS_VW.DNV_MEMBER_UPDATE_DATE AS UPDATE_DATE,
        DNV_MEMBERS_VW.DNV_MEMBER_KEY AS DIM_MEMBER_KEY,
        DNV_MEMBERS_VW.FIRST_MEMBERSHIP_DATE,
        DNV_MEMBERS_VW.DNV_MEMBER_NBR AS MEMBER_NBR,
        'DNV' AS SUBSCRIPTION_TYPE,
        CASE 
            WHEN DNV_MEMBERS_VW.ENROLLMENT_DATE <= SYSDATE() 
             AND DNV_MEMBERS_VW.TERM_DATE >= SYSDATE() THEN 'ACTIVE'
            WHEN DNV_MEMBERS_VW.ENROLLMENT_DATE > SYSDATE() 
             AND DNV_MEMBERS_VW.TERM_DATE > SYSDATE() THEN 'FUTURE'
            ELSE 'INACTIVE'
        END AS MEMBERSHIP_STATUS
    FROM MARKETING_EDS.DNV_MEMBERS_VW
    WHERE DNV_MEMBERS_VW.INDIVIDUAL_KEY IS NOT NULL
      AND DNV_MEMBERS_VW.INDIVIDUAL_KEY NOT IN 
            (SELECT MEMBERS_VW.INDIVIDUAL_KEY FROM MARKETING_EDS.MEMBERS_VW)
      AND DNV_MEMBERS_VW.MMI_RECORD_SEQ = 1
),
MEMBER_PREFERENCES AS
(
    SELECT
        MEMBER_PREFERENCES_VW.MEMBER_PREFERENCES_KEY,
        MEMBER_PREFERENCES_VW.SUBSCRIPTION_TYPE,
        MEMBER_PREFERENCES_VW.MEMBER_ID AS MEMBER_NBR,
        MEMBER_PREFERENCES_VW.EMAIL_ADDRESS,
        MEMBER_PREFERENCES_VW.HOME_PHONE_NUMBER,
        MEMBER_PREFERENCES_VW.MOBILE_PHONE_NUMBER,
        MEMBER_PREFERENCES_VW.COMMUNICATION_PREFERENCES_ALTERNATE_FORMAT_CODE,
        NVL(
            MEMBER_PREFERENCES_VW.COMMUNICATION_PREFERENCES_ALTERNATE_FORMAT_CODE,
            SUBSCRIBERPROFILE.BESTMETHODOFCONTACTCODE
        ) AS PREFERRED_CONTACT_METHOD_CODE,
        GENERICCODES.DESCRIPTION AS PREFERRED_CONTACT_METHOD_DESC,
        CASE 
            WHEN NVL(
                    MEMBER_PREFERENCES_VW.COMMUNICATION_PREFERENCES_ALTERNATE_FORMAT_CODE,
                    NULLIF(SUBSCRIBERPROFILE.BESTMETHODOFCONTACTCODE, '')
                 ) IN ('PMC06','PMC07','PMC09')
            THEN 'A' ELSE 'N'
        END AS DO_NOT_CONTACT,
        ROW_NUMBER() OVER (
            PARTITION BY MEMBER_PREFERENCES_VW.MEMBER_ID 
            ORDER BY MEMBER_PREFERENCES_VW.MEMBER_ID, 
                     MEMBER_PREFERENCES_VW.SOURCE_LAST_UPDATED_DATE DESC
        ) AS MEMBER_PREF_SEQ
    FROM &{IDAP_LAKE}.MEMBER.MEMBER_PREFERENCES_VW
    LEFT JOIN &{MC400}.DWOAO.SUBSCRIBERPROFILE
        ON MEMBER_PREFERENCES_VW.MEMBER_ID = 
           CONCAT(SUBSCRIBERPROFILE.SUBSCRIBER, SUBSCRIBERPROFILE.PERSONNUMBER)
    LEFT JOIN &{MC400}.DWOAO.GENERICCODES
        ON GENERICCODES.CODEVALUE = NVL(
                MEMBER_PREFERENCES_VW.COMMUNICATION_PREFERENCES_ALTERNATE_FORMAT_CODE,
                SUBSCRIBERPROFILE.BESTMETHODOFCONTACTCODE
           )
       AND GENERICCODES.CODEFIELD = 'SPPMC'
    WHERE 
        CASE 
            WHEN MEMBER_PREFERENCES_VW.SUBSCRIPTION_TYPE = 'Dental' 
             AND MEMBER_PREFERENCES_VW.TPA_DIV = '0002' THEN 1
            WHEN MEMBER_PREFERENCES_VW.SUBSCRIPTION_TYPE = 'Medical' 
             AND MEMBER_PREFERENCES_VW.TPA_DIV = '0001' THEN 1
            ELSE 0
        END = 1
)
SELECT
    MEMBERS.INDIVIDUAL_KEY AS INDIVIDUAL_KEY,
    MEMBERS.INDIVIDUAL_KEY AS INDIVIDUAL_ID,
    HOUSEHOLD_BRIDGE.HOUSEHOLD_KEY AS HOUSEHOLD_KEY,
    DIM_MEMBER_ADDRESS.DIM_MEMBER_ADDRESS_KEY AS ADDRESS_KEY,
    MEMBERS.MEMBERSHIP_STATUS,
    MEMBERS.INDIVIDUAL_KEY AS MASTER_MEMBER_ID,
    DWOAO_MEMBERS.MEMBERSTITLE AS TITLE,
    DIM_MEMBER.MEMBER_FIRST_NAME AS FIRST_NAME,
    CASE 
        WHEN DIM_MEMBER.MEMBER_MIDDLE_NAME = 'UNKNOWN' THEN '' 
        ELSE DIM_MEMBER.MEMBER_MIDDLE_NAME 
    END AS MIDDLE_INITIAL,
    DIM_MEMBER.MEMBER_LAST_NAME AS LAST_NAME,
    DWOAO_MEMBERS.MEMBERSSUFFIX AS SUFFIX,
    DIM_MEMBER.GENDER_CODE AS GENDER,
    DIM_MEMBER.MEMBER_BIRTH_DATE AS BIRTH_DATE,
    DATEDIFF(YEAR, DIM_MEMBER.MEMBER_BIRTH_DATE, CURRENT_TIMESTAMP) AS AGE,
    DIM_MEMBER.MEMBER_DEATH_DATE AS DECEASED_DATE,
    MEMBER_PREFERENCES.PREFERRED_CONTACT_METHOD_CODE,
    MEMBER_PREFERENCES.PREFERRED_CONTACT_METHOD_DESC,
    MEMBER_PREFERENCES.EMAIL_ADDRESS AS EMAIL_ADDRESS,
    NVL(MEMBER_PREFERENCES.MOBILE_PHONE_NUMBER, MEMBER_PREFERENCES.HOME_PHONE_NUMBER) AS ALTERNATE_PHONE,
    MEMBERS.FIRST_MEMBERSHIP_DATE,
    MEMBER_PREFERENCES.DO_NOT_CONTACT AS DO_NOT_CONTACT_IND,
    MEMBERS.LOAD_DATE,
    MEMBERS.UPDATE_DATE,
    MEMBER_PREFERENCES.MEMBER_PREFERENCES_KEY,
    MEMBERS.DIM_MEMBER_KEY
FROM MEMBERS
LEFT JOIN &{IDAP}.DIMDATA.DIM_MEMBER
    ON MEMBERS.DIM_MEMBER_KEY = DIM_MEMBER.DIM_MEMBER_KEY
LEFT JOIN &{IDAP}.DIMDATA.DIM_MEMBER_ADDRESS
    ON MEMBERS.DIM_MEMBER_KEY = DIM_MEMBER_ADDRESS.DIM_MEMBER_KEY
   AND DIM_MEMBER_ADDRESS.MEMBER_ADDRESS_TYPE = 'Physical'
   AND DIM_MEMBER_ADDRESS.ACTIVE_IND = 'Y'
   AND DIM_MEMBER_ADDRESS.EFFECTIVE_END_DATE >= SYSDATE()
LEFT JOIN &{MC400}.DWOAO.MEMBERS DWOAO_MEMBERS
    ON DWOAO_MEMBERS.MEMBERNBR = DIM_MEMBER.MEMBER_NBR
LEFT JOIN  MEMBER_PREFERENCES
    ON MEMBERS.MEMBER_NBR = MEMBER_PREFERENCES.MEMBER_NBR
LEFT JOIN MARKETING_EDS.HOUSEHOLD_BRIDGE
    ON MEMBERS.INDIVIDUAL_KEY = HOUSEHOLD_BRIDGE.INDIVIDUAL_KEY
;

!set variable_substitution=false;
