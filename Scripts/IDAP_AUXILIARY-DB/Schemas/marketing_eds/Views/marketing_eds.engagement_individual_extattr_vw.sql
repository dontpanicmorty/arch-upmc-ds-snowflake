CREATE OR REPLACE VIEW MARKETING_EDS.ENGAGEMENT_INDIVIDUAL_EXTATTR_VW(
	INDIVIDUAL_ID,
	MEMBER_NBR,
	MMI,
	EXTATTR_TYPE_KEY,
	EXTATTR_VALUE,
	STATUS,
	LOAD_DATE,
	UPDATE_DATE
) COMMENT='Individual External Attributes for Marketing Automation'
 AS
SELECT ENGAGEMENT_MEMBER.INDIVIDUAL_KEY::VARCHAR(20) AS INDIVIDUAL_ID,
        ENGAGEMENT_MEMBER.MEMBER_NBR::VARCHAR(12) AS MEMBER_NBR,
        ENGAGEMENT_MEMBER.INDIVIDUAL_KEY::VARCHAR(12) AS MMI,
        TBL_MEMBER_ATTRIBUTES.ATTRIBUTE_KEY::NUMBER(38,0)  AS EXTATTR_TYPE_KEY,
        TBL_MEMBER_ATTRIBUTES.ATTRIBUTE_VALUE::VARCHAR(100) AS EXTATTR_VALUE,
        'ACTIVE' AS STATUS,
        TBL_MEMBER_ATTRIBUTES.ATTRIBUTE_DATE::TIMESTAMP_NTZ(9)  AS  LOAD_DATE,
        TBL_MEMBER_ATTRIBUTES.LOAD_DATE::TIMESTAMP_NTZ(9) AS UPDATE_DATE
from DEPT_MKTG.MKT_ODSDB.TBL_MEMBER_ATTRIBUTES TBL_MEMBER_ATTRIBUTES
INNER JOIN DEPT_MKTG.MKT_ODSDB.REF_MEMBER_ATTRIBUTES REF_MEMBER_ATTRIBUTES
ON TBL_MEMBER_ATTRIBUTES.ATTRIBUTE_KEY = REF_MEMBER_ATTRIBUTES.ATTRIBUTE_KEY
INNER JOIN MARKETING_EDS.ENGAGEMENT_MEMBERS_VW ENGAGEMENT_MEMBER
ON TBL_MEMBER_ATTRIBUTES.MEMBER_NBR = ENGAGEMENT_MEMBER.MEMBER_NBR
AND REF_MEMBER_ATTRIBUTES.ATTRIBUTE_CATEGORY = 'EXT ATTRIBUTES'
;