CREATE OR REPLACE VIEW MARKETING_EDS.ENGAGEMENT_ACCOUNTS_VW(
	INDIVIDUAL_KEY,
	ACCOUNT_TYPE_KEY,
	ACCOUNT_ID,
	ACCOUNT_STATUS,
	ACCOUNT_START_DATE,
	ACCOUNT_TERM_DATE,
	ACCOUNT_LOAD_DATE,
	ACCOUNT_UPDATE_DATE
) COMMENT='Member Accounts for Marketing Automation'
 as 
select ENGAGEMENT_MEMBER.INDIVIDUAL_KEY::VARCHAR(12) AS INDIVIDUAL_KEY, 
       TBL_MEMBER_ATTRIBUTES.ATTRIBUTE_KEY::NUMBER(38,0) AS ACCOUNT_TYPE_KEY, 
       ENGAGEMENT_MEMBER.MEMBER_NBR::VARCHAR(100) AS ACCOUNT_ID, 
        'ACTIVE'::VARCHAR(20) AS ACCOUNT_STATUS, 
        TBL_MEMBER_ATTRIBUTES.ATTRIBUTE_DATE::TIMESTAMP_NTZ(9) AS ACCOUNT_START_DATE, 
        NULL::TIMESTAMP_NTZ(9) AS ACCOUNT_TERM_DATE, 
        TBL_MEMBER_ATTRIBUTES.LOAD_DATE::TIMESTAMP_NTZ(9) AS ACCOUNT_LOAD_DATE, 
        TBL_MEMBER_ATTRIBUTES.LOAD_DATE::TIMESTAMP_NTZ(9) AS ACCOUNT_UPDATE_DATE
FROM DEPT_MKTG.MKT_ODSDB.TBL_MEMBER_ATTRIBUTES TBL_MEMBER_ATTRIBUTES
INNER JOIN DEPT_MKTG.MKT_ODSDB.REF_MEMBER_ATTRIBUTES REF_MEMBER_ATTRIBUTES
ON TBL_MEMBER_ATTRIBUTES.ATTRIBUTE_KEY = REF_MEMBER_ATTRIBUTES.ATTRIBUTE_KEY
INNER JOIN MARKETING_EDS.ENGAGEMENT_MEMBERS_VW ENGAGEMENT_MEMBER
ON TBL_MEMBER_ATTRIBUTES.MEMBER_NBR = ENGAGEMENT_MEMBER.MEMBER_NBR
AND REF_MEMBER_ATTRIBUTES.ATTRIBUTE_CATEGORY = 'ACCOUNT'
;
