CREATE OR REPLACE VIEW MARKETING_EDS.DNV_MEMBER_PLAN_VW
COMMENT = 'VIEW FOR MARKETING ENGAGEMENT OF THE DENTAL AND VISION COMBINATIONS OF MEMBER PLANS'
(
	DNV_MEMBER_KEY,
	DNV_PLAN_KEY,
	DNV_MBRPLAN_LOAD_DATE
)
AS
SELECT  DNV_MEMBERS.DNV_MEMBER_KEY, 
        NVL(CONCAT(FACT_ENROLLMENT_DE.DIM_PLAN_KEY ,'-', FACT_ENROLLMENT_DE.DIM_GROUP_KEY,'-', FACT_ENROLLMENT_DE.DIM_SUB_GROUP_KEY),
            CONCAT(FACT_ENROLLMENT_VI.DIM_PLAN_KEY ,'-', FACT_ENROLLMENT_VI.DIM_GROUP_KEY,'-', FACT_ENROLLMENT_VI.DIM_SUB_GROUP_KEY)) AS DNV_PLAN_KEY,
        NVL(FACT_ENROLLMENT_DE.INSERT_DATETIME, FACT_ENROLLMENT_VI.INSERT_DATETIME) AS DNV_MBRPLAN_LOAD_DATE
FROM MARKETING_EDS.DNV_MEMBERS_VW DNV_MEMBERS
LEFT JOIN &{IDAP}.DIMDATA.FACT_ENROLLMENT FACT_ENROLLMENT_DE
ON DNV_MEMBERS.FACT_ENROLLMENT_KEY_DE = FACT_ENROLLMENT_DE.FACT_ENROLLMENT_KEY
LEFT JOIN &{IDAP}.DIMDATA.FACT_ENROLLMENT FACT_ENROLLMENT_VI
ON DNV_MEMBERS.FACT_ENROLLMENT_KEY_VI = FACT_ENROLLMENT_VI.FACT_ENROLLMENT_KEY
;


!set variable_substitution=false;