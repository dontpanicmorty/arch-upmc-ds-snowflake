!set variable_substitution=true;

CREATE OR REPLACE VIEW MARKETING_EDS.MEMBER_RIDER_DNV_VW
(
	MEMBER_NBR,
	RIDER_CODE,
	RIDER_TYPE,
	SEQNUM,
	DIM_RIDER_KEY,
	FACT_ENROLLMENT_KEY,
	ELIGIBILITY_START_DATE,
	ELIGIBILITY_END_DATE
) COMMENT='VIEW FOR MARKETING ENGAGEMENT OF THE MEMBER AND RIDER TYPE COMBINATIONS FOR DENTAL AND VISION MEMBERS'
 as
SELECT * 
FROM (SELECT 
      DNV_MEMBERS_VW.MEMBER_NBR, 
      DIM_RIDER.RIDER_CODE, 
      DIM_RIDER.RIDER_TYPE_CODE AS RIDER_TYPE,  
      ROW_NUMBER() OVER (PARTITION BY DNV_MEMBERS_VW.DNV_MEMBER_KEY, DIM_RIDER.RIDER_CODE 
      ORDER BY 
      FACT_ENROLLMENT.eligibility_start_date DESC) AS SEQNUM,
      FACT_ENROLLMENT.DIM_RIDER_KEY,     
      FACT_ENROLLMENT.fact_enrollment_key,
      FACT_ENROLLMENT.eligibility_start_date, 
      FACT_ENROLLMENT.ELIGIBILITY_END_DATE
      FROM  MARKETING_EDS.DNV_MEMBERS_VW AS DNV_MEMBERS_VW
      INNER JOIN &{IDAP}.DIMDATA.FACT_ENROLLMENT  AS FACT_ENROLLMENT
            ON DNV_MEMBERS_VW.DNV_MEMBER_KEY = FACT_ENROLLMENT.DIM_MEMBER_KEY 
      INNER JOIN &{IDAP}.DIMDATA.DIM_ELIGIBILITY_TYPE AS DIM_ELIGIBILITY_TYPE 
            ON FACT_ENROLLMENT.DIM_ELIGIBILITY_TYPE_KEY = DIM_ELIGIBILITY_TYPE.DIM_ELIGIBILITY_TYPE_KEY
      INNER JOIN &{IDAP}.DIMDATA.DIM_RIDER AS DIM_RIDER
           ON FACT_ENROLLMENT.dim_rider_key = DIM_RIDER.DIM_RIDER_KEY
      WHERE DIM_ELIGIBILITY_TYPE.ELIGIBILITY_TYPE_NAME = 'RIDER'
      AND FACT_ENROLLMENT.eligibility_start_date <>  FACT_ENROLLMENT.eligibility_end_date
      AND FACT_ENROLLMENT.eligibility_end_date >= SYSDATE()
      AND DNV_MEMBERS_VW.MEMBER_NBR IS NOT NULL
        ) SQ1
WHERE SQ1.SEQNUM = 1;


