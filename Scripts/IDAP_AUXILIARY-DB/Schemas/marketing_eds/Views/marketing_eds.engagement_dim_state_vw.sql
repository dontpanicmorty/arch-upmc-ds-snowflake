create or replace view MARKETING_EDS.ENGAGEMENT_DIM_STATE_VW(
	STATE,
	STATE_NAME,
	STATE_TYPE,
	STATE_RPTGRP_01,
	STATE_RPTGRP_02
) COMMENT='State reference table: names and abbreviations'
 as
select  
 STATE::VARCHAR(2) AS STATE,
 STATE_NAME::VARCHAR(50) AS STATE_NAME,
 STATE_TYPE::VARCHAR(100) AS STATE_TYPE,	
 STATE_RPTGRP_01::VARCHAR(20) AS STATE_RPTGRP_01,
 STATE_RPTGRP_02::VARCHAR(20) AS STATE_RPTGRP_02
from DEPT_MKTG.MKT_ODSDB.REF_STATE
;