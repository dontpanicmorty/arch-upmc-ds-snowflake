CREATE OR REPLACE VIEW MARKETING_EDS.ENGAGEMENT_ADDRESS_VW(
	ADDRESS_KEY,
	ADDRESS_TYPE,
	ADDRESS_LINE_1,
	ADDRESS_LINE_2,
	CITY,
	STATE,
	ZIP,
	ZIP_EXT,
	COUNTY,
	COUNTRY,
	PHONE,
	FAX,
	REGION_CODE,
	LATITUDE,
	LONGITUDE,
	ADDRESS_LOAD_DATE,
	ADDRESS_UPDATE_DATE,
	STATE_NAME
) COMMENT='Address information for members and prospects'
 as
SELECT
    ADDRESS.ADDRESS_KEY,
    ADDRESS.ADDRESS_TYPE::VARCHAR(20),
    NULLIF(TRIM(REPLACE(REPLACE(ADDRESS.ADDRESS_LINE_1, ',', ' '), '"', ' ')), '')::VARCHAR(100) AS ADDRESS_LINE_1,
    NULLIF(TRIM(REPLACE(REPLACE(ADDRESS.ADDRESS_LINE_2, ',', ' '), '"', ' ')), '')::VARCHAR(100) AS ADDRESS_LINE_2,
    NULLIF(TRIM(ADDRESS.CITY), '')::VARCHAR(50) AS CITY,
    NULLIF(TRIM(ADDRESS.STATE), '')::VARCHAR(2) AS STATE,
    NULLIF(TRIM(ADDRESS.ZIP), '')::VARCHAR(11) AS ZIP,
    NULLIF(TRIM(ADDRESS.ZIP_EXT), '')::VARCHAR(4) AS ZIP_EXT,
    NULLIF(TRIM(ADDRESS.COUNTY), '')::VARCHAR(250) AS COUNTY,
    NULLIF(TRIM(ADDRESS.COUNTRY), '')::VARCHAR(50) AS COUNTRY, 
    NULLIF(TRIM(ADDRESS.PHONE), '')::VARCHAR(25) AS PHONE, 
    NULLIF(TRIM(ADDRESS.FAX), '')::VARCHAR(25) AS FAX,
    ADDRESS.REGION_CODE::VARCHAR(20),
    ADDRESS.LATITUDE::NUMBER(38,9),
    ADDRESS.LONGITUDE::NUMBER(38,9),
    ADDRESS.LOAD_DATE::DATETIME AS ADDRESS_LOAD_DATE,
    ADDRESS.UPDATE_DATE::DATETIME AS ADDRESS_UPDATE_DATE,
    REF_STATE.STATE_NAME::VARCHAR(50)
FROM MARKETING_EDS.ADDRESS_VW AS ADDRESS
LEFT JOIN DEPT_MKTG.MKT_ODSDB.REF_STATE AS REF_STATE 
    ON ADDRESS.STATE = REF_STATE.STATE
;