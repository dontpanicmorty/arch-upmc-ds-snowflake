CREATE OR REPLACE VIEW MARKETING_EDS.DNV_RIDER_VW
COMMENT= 'VIEW FOR MARKETING ENGAGEMENT DATA SOURCE OF DENTAL AND VISION RIDER CODES'
(
	DNV_RIDER_KEY,
	DNV_RIDER_CODE,
	DNV_RIDER_DESC,
	DNV_RIDER_LOAD_DATE,
	DNV_RIDER_UPDATE_DATE
)
AS
SELECT DIM_RIDER.DIM_RIDER_KEY AS DNV_RIDER_KEY, 
        DIM_RIDER.RIDER_CODE AS DNV_RIDER_CODE,
        DIM_RIDER.RIDER_DESC AS DNV_RIDER_DESC, 
        DIM_RIDER.INSERT_DATETIME AS DNV_RIDER_LOAD_DATE, 
        DIM_RIDER.LAST_UPDATED_DATETIME AS DNV_RIDER_UPDATE_DATE
FROM &{IDAP}.DIMDATA.DIM_RIDER
WHERE DIM_RIDER.TPA_CLIENT_ID = '000001'
AND DIM_RIDER.TPA_DIV_ID = '0002'
AND DIM_RIDER.TPA_ID = '000001'
;

!set variable_substitution=false;