CREATE OR REPLACE VIEW MARKETING_EDS.MARKETING_DNV_RIDERS_VW(
	DNV_RIDER_KEY,
	DNV_RIDER_CODE,
	DNV_RIDER_DESC,
	DNV_RIDER_LOAD_DATE,
	DNV_RIDER_UPDATE_DATE
) COMMENT='Dental/vision rider codes'
 as
SELECT
    DNV_RIDER_KEY::NUMBER(38,0),
    DNV_RIDER_CODE::VARCHAR(10), --Not matching current of varchar(2)
    DNV_RIDER_DESC::VARCHAR(50),
    DNV_RIDER_LOAD_DATE::DATETIME,
    DNV_RIDER_UPDATE_DATE::DATETIME
FROM MARKETING_EDS.DNV_RIDER_VW;