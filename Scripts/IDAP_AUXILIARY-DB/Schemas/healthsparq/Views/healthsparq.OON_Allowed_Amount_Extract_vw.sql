!set variable_substitution=true;

CREATE OR REPLACE VIEW HEALTHSPARQ.OON_ALLOWED_AMOUNT_EXTRACT_VW 
AS

WITH

POS_KEY AS(
SELECT DISTINCT  
     LISTAGG(DISTINCT PLACE_OF_SERVICE,'') WITHIN GROUP (ORDER BY PLACE_OF_SERVICE) OVER () AS POS_COLLECTION_KEY
FROM &{IDAP_LAKE}.PRICING.LOCATION
)

SELECT
    'A' AS UPDATE_TYPE,
    'UPMC_I' AS INSURER_CODE,
    'ALL' AS PRODUCT_CODE,
    BILLING_CODE.BILLING_CODE_TYPE_NAME AS BILLING_CODE_TYPE,
    BILLING_CODE.BILLING_CODE_TYPE_VERSION_TEXT AS BILLING_CODE_TYPE_VER,
    HEALTHSPARQ_SHOPPABLE_SERVICES.PROCEDURE_CODE AS BILLING_CODE,
    (SELECT POS_COLLECTION_KEY FROM POS_KEY) AS POS_COLLECTION_KEY,
    'amount' as ALLOWED_AMOUNT_TYPE,
    DWOAO_USUALCUSTOMARYREASONABLE.PERCENTILECATPRICE80 AS ALLOWED_AMOUNT,
    DWOAO_USUALCUSTOMARYREASONABLE.GEOGRAPHICAREA AS CLIENT_REGION_KEY,
    DWOAO_USUALCUSTOMARYREASONABLE.MODIFIER AS MODIFIER,
    'professional' AS BILLING_CLASS
FROM &{CMS_PRICING_HEALTHSPARQ}.EXTRACTDATA.BILLING_CODE
INNER JOIN &{CMS_PRICING_HEALTHSPARQ}.STAGEDATA.BILLING_CODE_INTERNAL_VW ON
    EXTRACTDATA.BILLING_CODE.BILLING_CODE = BILLING_CODE_INTERNAL_VW.BILLING_CODE and
    CURRENT_DATE >=  CAST(BILLING_CODE_INTERNAL_VW.START_DATE AS DATE)AND
    CURRENT_DATE <= CAST(BILLING_CODE_INTERNAL_VW.END_DATE AS DATE) and
    EXTRACTDATA.BILLING_CODE.BILLING_CODE_TYPE_VERSION_TEXT = BILLING_CODE_INTERNAL_VW.BILLING_CODE_TYPE_VERSION_TEXT
JOIN &{IDAP_LAKE}.PRICING.HEALTHSPARQ_SHOPPABLE_SERVICES
    ON HEALTHSPARQ_SHOPPABLE_SERVICES.PROCEDURE_CODE = BILLING_CODE.BILLING_CODE
JOIN &{CMS_PRICING_HEALTHSPARQ}.RAWDATA.DWOAO_USUALCUSTOMARYREASONABLE
    ON DWOAO_USUALCUSTOMARYREASONABLE.PROCEDUECODE = HEALTHSPARQ_SHOPPABLE_SERVICES.PROCEDURE_CODE
JOIN &{IDAP_LAKE}.PRICING.HEALTHSPARQ_ISSUER_REGIONS
    ON HEALTHSPARQ_ISSUER_REGIONS.CLIENT_REGION_KEY = DWOAO_USUALCUSTOMARYREASONABLE.GEOGRAPHICAREA 

UNION

SELECT
    'A' AS UPDATE_TYPE,
    'UPMC_I' AS INSURER_CODE,
    'ALL' AS PRODUCT_CODE,
    BILLING_CODE.BILLING_CODE_TYPE_NAME AS BILLING_CODE_TYPE,
    BILLING_CODE.BILLING_CODE_TYPE_VERSION_TEXT AS BILLING_CODE_TYPE_VER,
    HEALTHSPARQ_SHOPPABLE_SERVICES.PROCEDURE_CODE AS BILLING_CODE,
    NULL AS POS_COLLECTION_KEY,
    'amount' as ALLOWED_AMOUNT_TYPE,
    DWOAO_USUALCUSTOMARYREASONABLE.PERCENTILECATPRICE80 AS ALLOWED_AMOUNT,
    DWOAO_USUALCUSTOMARYREASONABLE.GEOGRAPHICAREA AS CLIENT_REGION_KEY,
    DWOAO_USUALCUSTOMARYREASONABLE.MODIFIER AS MODIFIER,
    'institutional' AS BILLING_CLASS
FROM &{CMS_PRICING_HEALTHSPARQ}.EXTRACTDATA.BILLING_CODE
INNER JOIN &{CMS_PRICING_HEALTHSPARQ}.STAGEDATA.BILLING_CODE_INTERNAL_VW ON
    EXTRACTDATA.BILLING_CODE.BILLING_CODE = BILLING_CODE_INTERNAL_VW.BILLING_CODE and
    CURRENT_DATE >=  CAST(BILLING_CODE_INTERNAL_VW.START_DATE AS DATE)AND
    CURRENT_DATE <= CAST(BILLING_CODE_INTERNAL_VW.END_DATE AS DATE) and
    EXTRACTDATA.BILLING_CODE.BILLING_CODE_TYPE_VERSION_TEXT = BILLING_CODE_INTERNAL_VW.BILLING_CODE_TYPE_VERSION_TEXT
JOIN &{IDAP_LAKE}.PRICING.HEALTHSPARQ_SHOPPABLE_SERVICES
    ON HEALTHSPARQ_SHOPPABLE_SERVICES.PROCEDURE_CODE = BILLING_CODE.BILLING_CODE
JOIN &{CMS_PRICING_HEALTHSPARQ}.RAWDATA.DWOAO_USUALCUSTOMARYREASONABLE
    ON DWOAO_USUALCUSTOMARYREASONABLE.PROCEDUECODE = HEALTHSPARQ_SHOPPABLE_SERVICES.PROCEDURE_CODE
JOIN &{IDAP_LAKE}.PRICING.HEALTHSPARQ_ISSUER_REGIONS
    ON HEALTHSPARQ_ISSUER_REGIONS.CLIENT_REGION_KEY = DWOAO_USUALCUSTOMARYREASONABLE.GEOGRAPHICAREA

UNION

SELECT
    UPDATE_TYPE,
    INSURER_CODE,
    PRODUCT_CODE,
    BILLING_CODE_TYPE,
    BILLING_CODE_TYPE_VER,
    BILLING_CODE,
    POS_COLLECTION_KEY,
    ALLOWED_AMOUNT_TYPE,
    ALLOWED_AMOUNT,
    CLIENT_REGION_KEY,
    MODIFIER,
    BILLING_CLASS

FROM &{IDAP_LAKE}.PRICING.HEALTHSPARQ_OON_INPATIENT_ALLOWED_AMOUNT
;
 
