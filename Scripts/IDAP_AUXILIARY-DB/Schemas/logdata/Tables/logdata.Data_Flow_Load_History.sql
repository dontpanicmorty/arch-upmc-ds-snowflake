CREATE OR REPLACE TABLE LOGDATA.DATA_FLOW_LOAD_HISTORY
(
    RUN_ID VARCHAR NOT NULL COMMENT 'GUID from ADF runtime'
    ,LOG_ENTRY_TIMESTAMP TIMESTAMP_TZ NOT NULL DEFAULT CONVERT_TIMEZONE('UTC',CURRENT_TIMESTAMP())
    ,DATA_DOMAIN_NAME VARCHAR NULL
    ,DATA_FLOW_NAME VARCHAR NULL
    ,STEP_ORDER_NUMBER INT NULL COMMENT 'NULL indicates a data flow level log entry'
    ,STEP_PROCEDURE_NAME VARCHAR NULL COMMENT 'NULL indicates a data flow level log entry'
    ,EXECUTION_USERNAME VARCHAR NOT NULL DEFAULT CURRENT_USER()
    ,EXECUTION_START_TIME TIMESTAMP_TZ NOT NULL
    ,EXECUTION_END_TIME TIMESTAMP_TZ NULL
    ,EXECUTION_STATUS VARCHAR NOT NULL COMMENT 'Starting, Succeeded, Skipped, or Error'
    ,ERROR_CODE VARCHAR NULL
    ,ERROR_STATE VARCHAR NULL
    ,ERROR_MESSAGE VARCHAR NULL
    ,ERROR_STACK_TRACE_TEXT VARCHAR NULL

    ,CONSTRAINT PK_DATA_FLOW_LOAD_HISTORY PRIMARY KEY (RUN_ID, DATA_FLOW_NAME, LOG_ENTRY_TIMESTAMP)
) COMMENT= 'Log data for flows driven by UTIL.DATA_FLOW_CONTROL_TABLE entries'
;