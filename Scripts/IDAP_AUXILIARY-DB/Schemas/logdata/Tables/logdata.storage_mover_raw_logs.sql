    LEVEL STRING AS (VALUE:c2::STRING),
    OPERATION_NAME STRING AS (VALUE:c3::STRING),
    OPERATION_ITEM STRING AS (VALUE:c4::STRING),
    MESSAGE STRING AS (VALUE:c5::STRING),
