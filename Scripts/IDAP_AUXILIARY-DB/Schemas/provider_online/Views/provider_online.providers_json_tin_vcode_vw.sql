CREATE OR REPLACE VIEW PROVIDER_ONLINE.PROVIDERS_JSON_TIN_VCODE_VW 
(
	TAX_IDENTIFICATION_NUMBER, 
	PROVDIRJSONTXT
) COMMENT = 'Assembles the JSON for many vcodes for one tin' 
AS
WITH
	TIN_VCODE_SETUP AS (
		SELECT DISTINCT
			P.TAX_ID_NUMBER AS TINID,
			P.CLIENT_ID AS TPACLIENT,
			P.TPA_ID AS TPAID,
			P.TPA_DIV_ID AS TPADIV,
			LEGALNAME,
			LEGALADDRESS1,
			LEGALADDRESS2,
			LEGALCITY,
			LEGALSTATE,
			LEGALZIP,
			ARRAY_AGG(
				DISTINCT OBJECT_CONSTRUCT(
					'billingProviderId', P.VCODE,
					'billingProviderClaimTypeCode',	VCODE_BILLING_SUBQUERY.BILLING_PROVIDER_CLAIM_TYPE,
					'billingProviderName', VCODE_BILLING_SUBQUERY.OFFICE_NAME,
					'billingProviderAddress1', VCODE_BILLING_SUBQUERY.ADDRESSLINE1_TEXT,
					'billingProviderAddress2', VCODE_BILLING_SUBQUERY.ADDRESSLINE2_TEXT,
					'billingProviderCity', VCODE_BILLING_SUBQUERY.CITY_NAME,
					'billingProviderState', VCODE_BILLING_SUBQUERY.STATE_ABBREVIATION_NAME,
					'billingProviderZip', VCODE_BILLING_SUBQUERY.ZIP_CODE_NUMBER
				)
			) AS VCODES
		FROM
			PROVIDER_ONLINE.DIRECTORY_NON_PARTICIPANT P
			INNER JOIN (
				SELECT DISTINCT
					PROVIDER_NUMBER,
					BILLING_PROVIDER_CLAIM_TYPE,
					LEGAL_ADDRESS_RELATIONSHIP_KEY,
					OFFICE_NAME,
					ADDRESSLINE1_TEXT,
					ADDRESSLINE2_TEXT,
					CITY_NAME,
					STATE_ABBREVIATION_NAME,
					ZIP_CODE_NUMBER
				FROM
					PROVIDER_ONLINE.DIRECTORY_NON_PARTICIPANT P
				WHERE
					DATA_SOURCE_NAME = 'MC400Upm'
					AND PROVIDER_SUB_TYPE_DESCRIPTION = 'Medical Group'
					AND BILLING_PROVIDER_CLAIM_TYPE IS NOT NULL
			) VCODE_BILLING_SUBQUERY ON P.VCODE = VCODE_BILLING_SUBQUERY.PROVIDER_NUMBER
			INNER JOIN (
				SELECT
					L.LEGAL_ADDRESS_RELATIONSHIP_KEY,
					TRIM(L.LEGAL_OFFICE_NAME) AS LEGALNAME,
					TRIM(L.LEGAL_ADDRESS1) AS LEGALADDRESS1,
					IFF(TRIM(L.LEGAL_ADDRESS2) = '', NULL, TRIM(L.LEGAL_ADDRESS2)) AS LEGALADDRESS2,
					TRIM(L.LEGAL_CITY) AS LEGALCITY,
					TRIM(L.LEGAL_STATE) AS LEGALSTATE,
					TRIM(L.LEGAL_ZIP) AS LEGALZIP
				FROM
					PROVIDER_ONLINE.LEGAL_ADDRESS_RELATIONSHIP L
			) AS L ON VCODE_BILLING_SUBQUERY.LEGAL_ADDRESS_RELATIONSHIP_KEY = L.LEGAL_ADDRESS_RELATIONSHIP_KEY
		WHERE
			P.NETWORK_ID IS NOT NULL
			AND P.VCODE IS NOT NULL
		GROUP BY
			P.TAX_ID_NUMBER,
			P.CLIENT_ID,
			P.TPA_ID,
			P.TPA_DIV_ID,
			LEGALNAME,
			LEGALADDRESS1,
			LEGALADDRESS2,
			LEGALCITY,
			LEGALSTATE,
			LEGALZIP
	)
SELECT
	TINID AS TAX_IDENTIFICATION_NUMBER,
	OBJECT_CONSTRUCT(
		'tinid', CONCAT(TINID, TPACLIENT, TPAID, TPADIV),
		'documentType', 'TIN_VCodes',
		'tpaClient', TPACLIENT,
		'tpaId', TPAID,
		'tpaDiv', TPADIV,
		'lastUpdated', CURRENT_TIMESTAMP,
		'lastUpdated_int', TO_CHAR(CURRENT_TIMESTAMP, 'YYYYMMDD')::INT,
		'legalName', LEGALNAME,
		'legalAddress1', LEGALADDRESS1,
		'legalAddress2', LEGALADDRESS2,
		'legalCity', LEGALCITY,
		'legalState', LEGALSTATE,
		'legalZip', LEGALZIP,
		'vCodes', VCODES
	) AS PROVDIRJSONTXT
FROM
	TIN_VCODE_SETUP;