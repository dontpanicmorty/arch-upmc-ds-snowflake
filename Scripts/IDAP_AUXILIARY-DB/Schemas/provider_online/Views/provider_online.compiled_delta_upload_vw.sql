CREATE OR REPLACE VIEW PROVIDER_ONLINE.COMPILED_DELTA_UPLOAD_VW 
(
    ID, 
    NETWORK_ID, 
    PROVIDER_KEY, 
    PROVDIRJSONTXT
) COMMENT = 'Add together upserts and deletes for provideronline' AS
--CACTUS PRACS and FACILITIES
SELECT
    P.ID AS ID,
    P.NETWORK_ID AS NETWORK_ID,
    P.PROVIDER_KEY AS PROVIDER_KEY,
    PROVDIRJSONTXT 
FROM PROVIDER_ONLINE.PROVIDERS_JSON_SELECT_CACTUS_VW P
    INNER JOIN PROVIDER_ONLINE.DIRECTORY_NON_PARTICIPANT_PREVIOUS PREV 
    ON P.ID = PREV.ID
    AND P.NETWORK_ID = PREV.NETWORK_ID
    AND P.PROVIDER_KEY = PREV.PROVIDER_KEY
WHERE
    PREV.LAST_AUDIT_ACTION IN ('INSERT', 'UPDATE')
    AND PREV.PROVIDER_DIRECTORY_JSON_CURRENT_MD5 != COALESCE(PREV.PROVIDER_DIRECTORY_JSON_PREVIOUS_MD5, '123abc')
UNION ALL
--MC400 PRACS AND FACILITIES
SELECT
    P.ID AS ID,
    P.NETWORK_ID AS NETWORK_ID,
    P.PROVIDER_KEY AS PROVIDER_KEY,
    PROVDIRJSONTXT 
FROM PROVIDER_ONLINE.PROVIDERS_JSON_SELECT_MC400_VW P
    INNER JOIN PROVIDER_ONLINE.DIRECTORY_NON_PARTICIPANT_PREVIOUS PREV 
    ON P.ID = PREV.ID
    AND P.NETWORK_ID = PREV.NETWORK_ID
    AND P.PROVIDER_KEY = PREV.PROVIDER_KEY
WHERE
    PREV.LAST_AUDIT_ACTION IN ('INSERT', 'UPDATE')
    AND PREV.PROVIDER_DIRECTORY_JSON_CURRENT_MD5 != COALESCE(PREV.PROVIDER_DIRECTORY_JSON_PREVIOUS_MD5, '123abc')
UNION ALL
--CACTUS MED GROUPS
SELECT
    P.ID AS ID,
    P.NETWORK_ID AS NETWORK_ID,
    P.PROVIDER_KEY AS PROVIDER_KEY,
    PROVDIRJSONTXT 
FROM PROVIDER_ONLINE.PROVIDERS_JSON_SELECT_MEDGROUP_CACTUS_VW P
    INNER JOIN PROVIDER_ONLINE.DIRECTORY_NON_PARTICIPANT_PREVIOUS PREV 
    ON P.ID = PREV.ID
    AND P.NETWORK_ID = PREV.NETWORK_ID
    AND P.PROVIDER_KEY = PREV.PROVIDER_KEY
WHERE
    PREV.LAST_AUDIT_ACTION IN ('INSERT', 'UPDATE')
    AND PREV.PROVIDER_DIRECTORY_JSON_CURRENT_MD5 != COALESCE(PREV.PROVIDER_DIRECTORY_JSON_PREVIOUS_MD5, '123abc')
UNION ALL
--MC400 MED GROUPS
SELECT
    P.ID AS ID,
    P.NETWORK_ID AS NETWORK_ID,
    P.PROVIDER_KEY AS PROVIDER_KEY,
    PROVDIRJSONTXT 
FROM PROVIDER_ONLINE.PROVIDERS_JSON_SELECT_MEDGROUP_MC400_VW P
    INNER JOIN PROVIDER_ONLINE.DIRECTORY_NON_PARTICIPANT_PREVIOUS PREV 
    ON P.ID = PREV.ID
    AND P.NETWORK_ID = PREV.NETWORK_ID
    AND P.PROVIDER_KEY = PREV.PROVIDER_KEY
WHERE
    PREV.LAST_AUDIT_ACTION IN ('INSERT', 'UPDATE')
    AND PREV.PROVIDER_DIRECTORY_JSON_CURRENT_MD5 != COALESCE(PREV.PROVIDER_DIRECTORY_JSON_PREVIOUS_MD5, '123abc')
UNION ALL
-- SOFT DELETES
SELECT DISTINCT
    ID,
    NETWORK_ID,
    PROVIDER_KEY,
    OBJECT_CONSTRUCT(
        'id',
        ID,
        'providerKey',
        PROVIDER_KEY,
        'networkId',
        NETWORK_ID,
        'isLogicalDelete',
        1
    ) AS PROVDIRJSONTXT
FROM
    PROVIDER_ONLINE.DIRECTORY_NON_PARTICIPANT_PREVIOUS
WHERE
    NETWORK_ID IS NOT NULL
    AND LAST_AUDIT_ACTION = 'DELETE';