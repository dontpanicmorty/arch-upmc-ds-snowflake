CREATE OR REPLACE VIEW HEALTHSPARQ_2.PLAN_DETAILS_EXTRACT_VW
AS
SELECT
    'UPMC_I' AS INSURER_CODE,
    'UPMC' AS CLIENT_BRAND_CODE,
     PRICING_FILE_SEGMENT_VW.PRICING_FILE_KEY AS PLAN_COLLECTION_KEY,
     NULL AS REPORTING_ENTITY_NAME,
     NULL AS REPORTING_ENTITY_TYPE,
     'I' AS MRF_TYPE,
     PRICING.HEALTHSPARQ_PRODUCT_CODE_CROSSWALK.PRODUCT_CODE,
     NULL AS PLAN_ID,
     NULL AS PLAN_ID_TYPE,
     NULL AS PLAN_NAME,
     NULL AS PLAN_MARKET_TYPE,
     NULL AS PAYER_OR_ISSUER_NAME,
     NULL AS PLAN_ISSUER_NAME,
     NULL AS PLAN_SPONSOR_NAME,
        FROM &{IDAP_LAKE}.PRICING.HEALTHSPARQ_PRODUCT_CODE_CROSSWALK  
        JOIN &{CMS_PRICING_2_HEALTHSPARQ}.EXTRACTDATA.PRICING_FILE_SEGMENT_VW
        ON 
        HEALTHSPARQ_PRODUCT_CODE_CROSSWALK.SEGMENT = PRICING_FILE_SEGMENT_VW.SEGMENT
        AND 
        HEALTHSPARQ_PRODUCT_CODE_CROSSWALK.PROVIDER_SET = PRICING_FILE_SEGMENT_VW.PROVIDER_SET
;
 
!set variable_substitution=false;