CREATE OR REPLACE VIEW HEALTHSPARQ_2.CONTROL_FILE_EXTRACT_VW AS

SELECT VW.FILENAME,
    VW.CNT,
    FILE_VERSION AS VERSION,
    VW.FORMAT
FROM (
    SELECT HEALTHSPARQ_2.FXN_MAKE_FILENAME(
            'LEASED_NETWORKS_MAPPING', 
            &{CMS_PRICING_2_HEALTHSPARQ}.EXTRACTDATA.FXN_GET_CURRENT_TIC_DATE()
        ) AS FILENAME,
        COUNT(*) AS CNT,
        'TXT' AS FORMAT
    FROM HEALTHSPARQ_2.EXTERNAL_MRF_MAPPING_EXTRACT_VW
) VW
INNER JOIN HEALTHSPARQ_2.FILE_VERSIONS ON FILE_NAME = 'LEASED_NETWORKS_MAPPING'

UNION

SELECT VW.FILENAME,
    VW.CNT,
    FILE_VERSION AS VERSION,
    VW.FORMAT
FROM (
    -- Intentionally lower-case per Healthsparq's specs
    SELECT HEALTHSPARQ_2.FXN_MAKE_FILENAME(
            'OON_Region_XWalk', 
            &{CMS_PRICING_2_HEALTHSPARQ}.EXTRACTDATA.FXN_GET_CURRENT_TIC_DATE()
        ) AS FILENAME,
        COUNT(*) AS CNT,
        'TXT' AS FORMAT
    FROM HEALTHSPARQ_2.REGION_CROSSWALK_EXTRACT_VW
) VW
INNER JOIN HEALTHSPARQ_2.FILE_VERSIONS ON FILE_NAME = 'OON_Region_XWalk'

UNION

SELECT VW.FILENAME,
    VW.CNT,
    FILE_VERSION AS VERSION,
    VW.FORMAT
FROM (
    SELECT HEALTHSPARQ_2.FXN_MAKE_FILENAME(
            'OUTOFNETWORK_ALLOWED_AMOUNT', 
            &{CMS_PRICING_2_HEALTHSPARQ}.EXTRACTDATA.FXN_GET_CURRENT_TIC_DATE()
        ) AS FILENAME,
        COUNT(*) AS CNT,
        'TXT' AS FORMAT
    FROM HEALTHSPARQ_2.OON_ALLOWED_AMOUNT_EXTRACT_VW
) VW
INNER JOIN HEALTHSPARQ_2.FILE_VERSIONS ON FILE_NAME = 'OUTOFNETWORK_ALLOWED_AMOUNT'

UNION

SELECT VW.FILENAME,
    VW.CNT,
    FILE_VERSION AS VERSION,
    VW.FORMAT
FROM (
    SELECT HEALTHSPARQ_2.FXN_MAKE_FILENAME(
            'PLAN_DETAILS', 
            &{CMS_PRICING_2_HEALTHSPARQ}.EXTRACTDATA.FXN_GET_CURRENT_TIC_DATE()
        ) AS FILENAME,
        COUNT(*) AS CNT,
        'TXT' AS FORMAT
    FROM HEALTHSPARQ_2.PLAN_DETAILS_EXTRACT_VW
) VW
INNER JOIN HEALTHSPARQ_2.FILE_VERSIONS ON FILE_NAME = 'PLAN_DETAILS'

UNION

SELECT VW.FILENAME,
    VW.CNT,
    FILE_VERSION AS VERSION,
    VW.FORMAT
FROM (
    SELECT HEALTHSPARQ_2.FXN_MAKE_FILENAME(
            'POS_MAPPING', 
            &{CMS_PRICING_2_HEALTHSPARQ}.EXTRACTDATA.FXN_GET_CURRENT_TIC_DATE()
        ) AS FILENAME,
        COUNT(*) AS CNT,
        'TXT' AS FORMAT
    FROM HEALTHSPARQ_2.POS_MAPPING_EXTRACT_VW
) VW
INNER JOIN HEALTHSPARQ_2.FILE_VERSIONS ON FILE_NAME = 'POS_MAPPING'

UNION

SELECT 
    CONCAT(SPLIT(
        &{CMS_PRICING_2_HEALTHSPARQ}.EXTRACTDATA.FXN_MAKE_URL_PATH(FILE_TYPE_NAME, PRICING_FILE_KEY), 
        'in-network-rates/'
    )[1], '.zip') AS FILENAME,
    1 AS CNT,
    VERSION,
    'JSON' AS FORMAT
FROM &{CMS_PRICING_2_HEALTHSPARQ}.EXTRACTDATA.IN_NETWORK_FILE_BASE_SELECT_VW

