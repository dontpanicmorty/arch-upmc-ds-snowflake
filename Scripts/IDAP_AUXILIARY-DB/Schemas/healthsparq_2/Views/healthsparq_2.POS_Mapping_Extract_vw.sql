!set variable_substitution=true;

CREATE OR REPLACE VIEW HEALTHSPARQ_2.POS_MAPPING_EXTRACT_VW
AS
SELECT 'UPMC_I' AS INSURER_CODE,
        LISTAGG(DISTINCT PLACE_OF_SERVICE,'') WITHIN GROUP (ORDER BY PLACE_OF_SERVICE) OVER () AS POS_COLLECTION_KEY,
        PLACE_OF_SERVICE AS PLACE_OF_SERVICE_CODE
FROM &{IDAP_LAKE}.PRICING.LOCATION

UNION

SELECT 'UPMC_I' AS INSURER_CODE, 
        ARRAY_TO_STRING(PLACE_OF_SERVICE_CODES,'') 
        POS_COLLECTION_KEY, 
        POS_CODES.VALUE::STRING AS PLACE_OF_SERVICE_CODE
FROM &{CMS_PRICING_2_HEALTHSPARQ}.EXTRACTDATA.NEGOTIATED_PRICE,
     LATERAL FLATTEN(INPUT => PLACE_OF_SERVICE_CODES) POS_CODES
;
 
!set variable_substitution=false;