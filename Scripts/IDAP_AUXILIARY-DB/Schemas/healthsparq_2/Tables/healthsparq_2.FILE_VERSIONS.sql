CREATE OR REPLACE TABLE HEALTHSPARQ_2.FILE_VERSIONS (
	FILE_VERSIONS_KEY NUMBER(38, 0) AUTOINCREMENT ORDER START 1 INCREMENT 1 NOT NULL UNIQUE,
	INSERT_DATETIME TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
	FILE_NAME VARCHAR NOT NULL,
	FILE_VERSION VARCHAR NOT NULL,
	CONSTRAINT PK_FILE_VERSIONS PRIMARY KEY (FILE_VERSIONS_KEY),
	CONSTRAINT UK_FILE_VERSIONS UNIQUE (FILE_NAME, FILE_VERSION)
) COMMENT = 'Holds versions for files exported in the control file that do not reference their own versions.';