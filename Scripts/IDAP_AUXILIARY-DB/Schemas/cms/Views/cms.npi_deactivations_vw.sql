CREATE OR REPLACE VIEW CMS.NPI_DEACTIVATIONS_VW AS
SELECT
    NPI,
    ENTITY_TYPE_CODE,
    PROVIDER_ORG_NAME,
    PROVIDER_LAST_NAME,
    PROVIDER_FIRST_NAME,
    PROVIDER_ENUMERATION_DATE,
    NPI_DEACTIVATION_DATE,
    NPI_REACTIVATION_DATE,
    LAST_UPDATED_DATETIME AS LOAD_DATE
FROM &{IDAP_LAKE}.CMS.NPI;

