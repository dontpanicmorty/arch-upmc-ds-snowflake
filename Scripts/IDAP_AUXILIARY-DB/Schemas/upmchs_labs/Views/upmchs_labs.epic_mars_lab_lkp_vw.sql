CREATE OR REPLACE VIEW UPMCHS_LABS.EPIC_MARS_LAB_LKP_VW AS
WITH
    MARS_EPIC_RAW_FILE_TEMP_load AS (
        SELECT DISTINCT
            UPPER(PAT_LAST_NAME || ', ' || PAT_FIRST_NAME || ' ' || PAT_MIDDLE_NAME) AS FULL_NAME,
            PAT_MRN_ID AS MRN,
            HSP_ACCOUNT_ID AS ACCT_NBR,
            COMP_ANL_INST_TM,
            ENTERPRISE_IBM_INITIATE_EMPI_ID_5000 AS ENTERPRISE_IBM_INITIATE_EMPI_ID
        FROM &{IDAP_LAKE}.LAB.EPIC_MARS
    ),
    IDAP_EMPI_DAILY_GLOBAL_temp AS (
        SELECT DISTINCT
            HEALTHPLAN_ID,
            DOB,
            EMPI_ID
        FROM &{IDAP_LAKE}.MEMBER.EMPI_DAILY_GLOBAL
    ),
    ELIGIBILITYHISTORY_TEMP AS (
        SELECT DISTINCT
            COVERAGEGROUPCODE,
            TO_DATE(ELIGIBILITYHISTORY.ELIGIBILITYSTARTDATE::STRING, 'YYYYMMDD') STARTDATE,
            CASE
                WHEN ELIGIBILITYENDDATE = 0 THEN DATE '9999-12-31'
                ELSE TO_DATE(ELIGIBILITYHISTORY.ELIGIBILITYENDDATE::STRING, 'YYYYMMDD')
            END ENDDATE,            
            MEMBERNBR
        FROM &{MC400}.DWOAO.ELIGIBILITYHISTORY
    ),
    MEMBERS_TEMP AS (
        SELECT DISTINCT
            MEMBERNBR,
            MEMBERSOCIALSECURITY
        FROM &{MC400}.DWOAO.MEMBERS
    )

SELECT
    A.FULL_NAME,
    A.DOB,
    A.MRN,
    A.GROUP_NUMBER,
    A.MEMBER_NBR,
    A.ACCT_NBR,
    A.SSN
FROM (
    SELECT
        MARS_EPIC_RAW_FILE_TEMP_load.FULL_NAME,
        IDAP_EMPI_DAILY_GLOBAL_temp.DOB AS DOB,
        MARS_EPIC_RAW_FILE_TEMP_load.MRN,
        ELIGIBILITYHISTORY_TEMP.COVERAGEGROUPCODE AS GROUP_NUMBER,
        IDAP_EMPI_DAILY_GLOBAL_temp.HEALTHPLAN_ID AS MEMBER_NBR,
        MARS_EPIC_RAW_FILE_TEMP_load.ACCT_NBR,
        MEMBERS_TEMP.MEMBERSOCIALSECURITY AS SSN,
        ROW_NUMBER() OVER(
            PARTITION BY
                IDAP_EMPI_DAILY_GLOBAL_temp.HEALTHPLAN_ID,
                MARS_EPIC_RAW_FILE_TEMP_load.ACCT_NBR
            ORDER BY
                ELIGIBILITYHISTORY_TEMP.ENDDATE DESC
        ) AS RANK
    FROM MARS_EPIC_RAW_FILE_TEMP_load
        LEFT JOIN IDAP_EMPI_DAILY_GLOBAL_temp
              ON MARS_EPIC_RAW_FILE_TEMP_load.ENTERPRISE_IBM_INITIATE_EMPI_ID = IDAP_EMPI_DAILY_GLOBAL_temp.EMPI_ID
        LEFT JOIN ELIGIBILITYHISTORY_TEMP
            ON IDAP_EMPI_DAILY_GLOBAL_temp.HEALTHPLAN_ID = ELIGIBILITYHISTORY_TEMP.MEMBERNBR
        LEFT JOIN MEMBERS_TEMP 
            ON ELIGIBILITYHISTORY_TEMP.MEMBERNBR = MEMBERS_TEMP.MEMBERNBR
     WHERE CAST(MARS_EPIC_RAW_FILE_TEMP_load.COMP_ANL_INST_TM AS DATE)
           BETWEEN ELIGIBILITYHISTORY_TEMP.STARTDATE AND ELIGIBILITYHISTORY_TEMP.ENDDATE 
    ) A
WHERE A.RANK = 1
ORDER BY A.FULL_NAME;

