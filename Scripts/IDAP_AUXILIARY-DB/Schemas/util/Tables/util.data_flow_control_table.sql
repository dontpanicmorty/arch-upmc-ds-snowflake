CREATE OR REPLACE TABLE UTIL.DATA_FLOW_CONTROL_TABLE
(
    DATA_FLOW_NAME VARCHAR NOT NULL
    ,DATA_DOMAIN_NAME VARCHAR NOT NULL COMMENT 'Should generally match the schema name in IDAP_AUXILIARY'
    ,DS_FLOW_OWNER VARCHAR NOT NULL COMMENT 'This is the DS team that supports this flow'
    ,STEP_ORDER_NUMBER INT NOT NULL COMMENT 'Execution order of the steps.  Unique per DATA_FLOW_NAME'
    ,STEP_PROCEDURE_NAME VARCHAR NOT NULL
    ,IS_ACTIVE VARCHAR(1) NOT NULL DEFAULT 'Y'
    ,INSERTED_DATETIME TIMESTAMP_TZ NOT NULL DEFAULT CONVERT_TIMEZONE('UTC',CURRENT_TIMESTAMP())
    ,LAST_UPDATED_DATETIME TIMESTAMP_TZ

    ,CONSTRAINT PK_DATA_FLOW_CONTROL_TABLE PRIMARY KEY (DATA_FLOW_NAME, STEP_ORDER_NUMBER)    
) COMMENT= 'Control table for multi-step data flows in IDAP_AUXILIARY'
;