
CREATE OR REPLACE VIEW QUALITY.CCD_ASSESSMENTS_VW(
	SECTION_TITLE,
	FILENAME,
	MRN,
	TEMPLATE_OID,
	ASSESSMENT_CODE,
	ASSESSMENT_CODE_SYSTEM,
	ASSESSMENT_CODE_SYSTEM_NAME,
	ASSESSMENT_DISPLAY_NAME,
	ASSESSMENT_DATE,
	CODE,
	DESCRIPTION,
	PROVIDER,
	ROW_NUM,
	TS_LAST_MODIFY,
	SCAN_TIME
) as
SELECT X.SECTION_TITLE
      ,X.FILENAME
      ,X.MRN
      ,GET(XMLGET(XMLGET(X.XML,'section'),'templateId'),'@root')::STRING AS TEMPLATE_OID
      ,GET(XMLGET(XMLGET(X.XML,'section'),'code'),'@code')::STRING AS ASSESSMENT_CODE
      ,GET(XMLGET(XMLGET(X.XML,'section'),'code'),'@codeSystem')::STRING AS ASSESSMENT_CODE_SYSTEM
      ,GET(XMLGET(XMLGET(X.XML,'section'),'code'),'@codeSystemName')::STRING as ASSESSMENT_CODE_SYSTEM_NAME        
      ,GET(XMLGET(XMLGET(X.XML,'section'),'code'),'@displayName')::STRING AS ASSESSMENT_DISPLAY_NAME     
      ,XMLGET( F.VALUE, 'td'):"$"::STRING AS ASSESSMENT_DATE
      ,NVL(XMLGET( F.VALUE, 'td',1):"$"::STRING,'NA)') AS CODE
      ,NVL(XMLGET( F.VALUE, 'td',2):"$"::STRING, 'NA') AS DESCRIPTION      
      ,NVL(XMLGET( F.VALUE, 'td',3):"$"::STRING,'NA') AS PROVIDER
      ,ROW_NUM
      ,TS_LAST_MODIFY
	  ,SCAN_TIME
FROM QUALITY.SECTION_XML X
   ,LATERAL FLATTEN(to_array(XMLGET(XMLGET(XMLGET(XMLGET(X.XML, 'section'),'text'),'table'),'tbody'):"$")) F
    WHERE SECTION_TITLE = 'Assessments'
AND F.VALUE LIKE '%tr%'
AND ASSESSMENT_DATE IS NOT NULL;
