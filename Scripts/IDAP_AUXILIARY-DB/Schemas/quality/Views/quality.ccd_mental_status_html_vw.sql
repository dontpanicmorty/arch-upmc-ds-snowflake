CREATE OR REPLACE VIEW QUALITY.CCD_MENTAL_STATUS_HTML_VW(
	SECTION_TITLE,
	FILENAME,
	MRN,
	TEMPLATE_ROOT,
	TEMPLATE_EXTENSION,
	SECTION_CODE,
	SECTION_NAME,
	SECTION_CODE_SYSTEM,
	SECTION_CODE_SYSTEM_NAME,
	NO_DATA,
	MENTAL_STATUS_DATE,
	MENTAL_STATUS_ASSESSMENT,
	MENTAL_STATUS_VALUE,
	MENTAL_STATUS_REF_RANGE,
	MENTAL_STATUS_INTERPRETAION,
	DESCRIPTION
) as
SELECT X.SECTION_TITLE
      ,X.FILENAME
      ,X.MRN
      ,GET(XMLGET(XMLGET(X.XML,'section'),'templateId'),'@root')::STRING AS TEMPLATE_ROOT
      ,GET(XMLGET(XMLGET(X.XML,'section'),'templateId'),'@extension')::STRING AS TEMPLATE_EXTENSION
      ,GET(XMLGET(XMLGET(X.XML,'section'),'code'),'@code')::STRING AS SECTION_CODE
      ,GET(XMLGET(XMLGET(X.XML,'section'),'code'),'@displayName')::STRING AS SECTION_NAME
      ,GET(XMLGET(XMLGET(X.XML,'section'),'code'),'@codeSystem')::STRING AS SECTION_CODE_SYSTEM                  
      ,GET(XMLGET(XMLGET(X.XML,'section'),'code'),'@codeSystemName')::STRING as SECTION_CODE_SYSTEM_NAME
      ,NULL AS NO_DATA            
      ,XMLGET( F.VALUE, 'td'):"$"::STRING AS MENTAL_STATUS_DATE
      ,XMLGET( F.VALUE, 'td',1):"$"::STRING AS MENTAL_STATUS_ASSESSMENT
      ,XMLGET( F.VALUE, 'td',2):"$"::STRING AS MENTAL_STATUS_VALUE
      ,XMLGET( F.VALUE, 'td',3):"$"::STRING AS MENTAL_STATUS_REF_RANGE
      ,XMLGET( F.VALUE, 'td',4):"$"::STRING AS MENTAL_STATUS_INTERPRETATION      
      ,'Description' AS DESCRIPTION      
FROM QUALITY.SECTION_XML X
    ,LATERAL FLATTEN(XMLGET(XMLGET(XMLGET(XMLGET(X.XML, 'section'),'text'),'table'),'tbody'):"$") F
WHERE SECTION_TITLE in ( 'Mental Status', 'MENTAL STATUS')
AND F.VALUE LIKE '%tr%'
AND MENTAL_STATUS_DATE IS NOT NULL;
