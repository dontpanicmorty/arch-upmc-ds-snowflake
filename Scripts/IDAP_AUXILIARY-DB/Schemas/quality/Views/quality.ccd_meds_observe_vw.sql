CREATE OR REPLACE VIEW QUALITY.CCD_MEDS_OBSERVE_VW(
	FILENAME,
	MRN,
	ENTRY_ID_EXT,
	ICD10_SYSTEM_NAME,
	ICD10_CODE,
	ICD10_DISPLAY_NAME,
	ICD10_CODE_SYSTEM
) as
SELECT
     X.FILENAME
    ,X.MRN
    ,get(XMLGET(XMLGET(ENTRY.VALUE,'substanceAdministration'),'id'),'@extension')::VARCHAR AS ENTRY_ID_EXT
    ,MAX(CASE WHEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR = 'ICD-10-CM' THEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR ELSE NULL END) AS ICD10_SYSTEM_NAME 
    ,MAX(CASE WHEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR = 'ICD-10-CM' THEN TRANSLATION.VALUE:"@code"::VARCHAR ELSE NULL END) AS ICD10_CODE
    ,MAX(CASE WHEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR = 'ICD-10-CM' THEN TRANSLATION.VALUE:"@displayName"::VARCHAR ELSE NULL END) AS ICD10_DISPLAY_NAME
    ,MAX(CASE WHEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR = 'ICD-10-CM' THEN TRANSLATION.VALUE:"@codeSystem"::VARCHAR ELSE NULL END) AS ICD10_CODE_SYSTEM
FROM
     QUALITY.SECTION_XML X
    ,LATERAL FLATTEN(X.xml) SECTION
    ,LATERAL FLATTEN(SECTION.VALUE:"$"::ARRAY) ENTRY
    ,LATERAL FLATTEN(ENTRY.VALUE:"$"::ARRAY) SUBSTANCE_ADMINISTRATION
    ,LATERAL FLATTEN(SUBSTANCE_ADMINISTRATION.VALUE:"$"::ARRAY) ENTRY_RELATIONSHIP
    ,LATERAL FLATTEN(ENTRY_RELATIONSHIP.VALUE:"$"::ARRAY) OBSERVATION
    ,LATERAL FLATTEN(OBSERVATION.VALUE:"$"::ARRAY) VALUE
    ,LATERAL FLATTEN(VALUE.VALUE:"$"::ARRAY) TRANSLATION
WHERE
    X.SECTION_TITLE = 'Medications'
    -- AND X.FILENAME = '5810784.xml'
    AND GET(SECTION.VALUE, '@') = 'section'
    AND GET(ENTRY.VALUE, '@') = 'entry'
    AND GET(SUBSTANCE_ADMINISTRATION.VALUE, '@') = 'substanceAdministration'
    AND GET(ENTRY_RELATIONSHIP.VALUE, '@') = 'entryRelationship'    
    AND GET(OBSERVATION.VALUE, '@') = 'observation'
    AND GET(VALUE.VALUE, '@') = 'value'
    AND GET(TRANSLATION.VALUE, '@') = 'translation'
GROUP BY 
    X.FILENAME
   ,X.MRN
   ,ENTRY.VALUE;

