    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'ACT' THEN (GET(XMLGET(XMLGET(ER_CHILD.VALUE,'text'),'reference'),'@value')::STRING) ELSE NULL END) AS ACT_REF_VALUE
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'ACT' THEN (GET(XMLGET(ER_CHILD.VALUE,'statusCode'),'@code')::STRING) ELSE NULL END) AS ACT_STATUS_CODE
    -- REFR REFR REFR
    ,MAX(CASE WHEN ENTRY_RELATIONSHIP.VALUE:"@typeCode"::VARCHAR = 'REFR' THEN ENTRY_RELATIONSHIP.VALUE:"@typeCode"::VARCHAR ELSE NULL END) AS ER_TYPE_REFR
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN ER_CHILD.VALUE:"@classCode"::VARCHAR ELSE NULL END) AS SPLY_CLASS_CODE        
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN ER_CHILD.VALUE:"@moodCode"::VARCHAR ELSE NULL END) AS SPLY_MOOD_CODE    
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(ER_CHILD.VALUE,'templateId'),'@root')::STRING) ELSE NULL END) AS SPLY_TEMPL_ROOT    
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(ER_CHILD.VALUE,'templateId'),'@extension')::STRING) ELSE NULL END) AS SPLY_TEMPL_EXT
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(ER_CHILD.VALUE,'id'),'@root')::STRING) ELSE NULL END) AS SPLY_ID_ROOT
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(ER_CHILD.VALUE,'id'),'@extension')::STRING) ELSE NULL END) AS SPLY_ID_EXT
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(ER_CHILD.VALUE,'statusCode'),'@code')::STRING) ELSE NULL END) AS SPLY_STATUS_CODE
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(ER_CHILD.VALUE,'effectiveTime'),'@xsi:type')::STRING) ELSE NULL END) AS SPLY_EFF_TIME_TYPE
