    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' 
         THEN (GET(XMLGET(ER_CHILD.VALUE,'repeatNumber'),'@value')::STRING) ELSE NULL END) AS SPLY_REPEAT_NUMBER
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(ER_CHILD.VALUE,'quantity'),'@value')::STRING) ELSE NULL END) AS SPLY_QTY_VALUE
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(ER_CHILD.VALUE,'quantity'),'@unit')::STRING) ELSE NULL END) AS SPLY_QTY_UNIT
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' 
         THEN (GET(XMLGET(XMLGET(ER_CHILD.VALUE,'product'),'manufacturedProduct'),'@classCode')::STRING) ELSE NULL END) AS SPLY_MP_CLASS_CODE
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' 
         THEN (GET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,'product'),'manufacturedProduct'),'templateId'),'@root')::STRING) ELSE NULL END) AS SPLY_MP_TEMPLATE_ROOT
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,'product'),
              'manufacturedProduct'),'templateId'),'@extension')::STRING) ELSE NULL END) AS SPLY_MP_TEMPLATE_EXT
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,'product'),
                                      'manufacturedProduct'),'manufacturedMaterial'),'code'),'@nullFlavor')::STRING) ELSE NULL END) AS SPLY_MMAT_CODE_NULL              
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,'product'),
                                      'manufacturedProduct'),'manufacturedMaterial'),'code'),'@code')::STRING) ELSE NULL END) AS SPLY_MMAT_CODE
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,'product'),
                                      'manufacturedProduct'),'manufacturedMaterial'),'code'),'@displayName')::STRING) ELSE NULL END) AS SPLY_MMAT_DISPLAY_NAME
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,'product'),
                                      'manufacturedProduct'),'manufacturedMaterial'),'code'),'@codeSystem')::STRING) ELSE NULL END) AS SPLY_MMAT_CODE_SYSTEM
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,'product'),
                                      'manufacturedProduct'),'manufacturedMaterial'),'code'),'@codeSystemName')::STRING) ELSE NULL END) AS SPLY_MMAT_CODE_SYSTEM_NAME
    -- TRANSLATION SECTION - ANOTHER VIEW (VW) TO BE INCLUDED
    --
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(XMLGET(ER_CHILD.VALUE,'author'),
                                      'time'),'@value')::STRING) ELSE NULL END) AS SPLY_AUTHOR_TIME
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,'author'),
                                      'assignedAuthor'),'id'),'@root')::STRING) ELSE NULL END) AS SPLY_AUTHOR_ID_ROOT
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,'author'),
                                      'assignedAuthor'),'id'),'@extension')::STRING) ELSE NULL END) AS SPLY_AUTHOR_ID_EXT    
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,'author'),
                                      'assignedAuthor'),'addr'),'@use')::STRING) ELSE NULL END) AS SPLY_AUTHOR_ADDR_USE                                      
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (XMLGET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,'author'),
                                      'assignedAuthor'),'addr'),'streetAddressLine'):"$"::STRING) ELSE NULL END) AS SPLY_AUTHOR_ADDR_STREET
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (XMLGET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,'author'),
                                      'assignedAuthor'),'addr'),'city'):"$"::STRING) ELSE NULL END) AS SPLY_AUTHOR_ADDR_CITY
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (XMLGET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,'author'),
                                      'assignedAuthor'),'addr'),'state'):"$"::STRING) ELSE NULL END) AS SPLY_AUTHOR_ADDR_STATE
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (XMLGET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,'author'),
                                      'assignedAuthor'),'addr'),'postalCode'):"$"::STRING) ELSE NULL END) AS SPLY_AUTHOR_ADDR_ZIP
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (XMLGET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,'author'),'assignedAuthor'),'addr'),'country'):"$"::STRING) ELSE NULL END) AS SPLY_AUTHOR_ADDR_COUNTRY
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,   'author'),'assignedAuthor'),'telecom'),'@use')::STRING) ELSE NULL END) AS SPLY_AUTHOR_PHONE_USE
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' THEN (GET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,'author'),
                                      'assignedAuthor'),'telecom'),'@value')::STRING) ELSE NULL END) AS SPLY_AUTHOR_PHONE_NUM 
    ,MAX (  CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'SPLY' 
                 THEN CONCAT ( 
                               (XMLGET(XMLGET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,'author'),'assignedAuthor'),'assignedPerson'),'name'), 'family'):"$"::STRING ), ', ',
                               (XMLGET(XMLGET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,'author'),'assignedAuthor'),'assignedPerson'),'name'), 'given'):"$"::STRING ), ' ',
                               (XMLGET(XMLGET(XMLGET(XMLGET(XMLGET(ER_CHILD.VALUE,'author'),'assignedAuthor'),'assignedPerson'),'name'), 'suffix'):"$"::STRING )
            ) 
                 ELSE NULL END ) AS AA_ASSIGNED_PERSION_NAME
    ,ROW_NUM AS XML_ROW_NUMBER
    ,TS_LAST_MODIFY AS XML_TS_LAST_MODIFY
    ,SCAN_TIME AS XML_TS_SCAN_TIME
FROM
    QUALITY.SECTION_XML X
    ,LATERAL FLATTEN(X.xml) SECTION
    ,LATERAL FLATTEN(SECTION.VALUE:"$"::ARRAY) ENTRY
    ,LATERAL FLATTEN(ENTRY.VALUE:"$"::ARRAY) SUBSTANCE_ADMINISTRATION
    ,LATERAL FLATTEN(SUBSTANCE_ADMINISTRATION.VALUE:"$"::ARRAY) CONSUMABLE
    ,LATERAL FLATTEN(SUBSTANCE_ADMINISTRATION.VALUE:"$"::ARRAY) AUTHOR
    ,LATERAL FLATTEN(SUBSTANCE_ADMINISTRATION.VALUE:"$"::ARRAY) ENTRY_RELATIONSHIP
    ,LATERAL FLATTEN(ENTRY_RELATIONSHIP.VALUE:"$"::ARRAY) ER_CHILD    
WHERE
    x.SECTION_TITLE = 'Medications'    
    AND GET(SECTION.VALUE, '@') = 'section'
    AND GET(ENTRY.VALUE, '@') = 'entry'
    AND GET(SUBSTANCE_ADMINISTRATION.VALUE, '@') = 'substanceAdministration'
    AND GET(CONSUMABLE.VALUE, '@') = 'consumable'    
    AND GET(AUTHOR.VALUE, '@') = 'author'    
    AND GET(ENTRY_RELATIONSHIP.VALUE, '@') = 'entryRelationship'
    AND GET(ER_CHILD.VALUE, '@') in ( 'observation', 'act', 'supply' )
--    AND X.FILENAME = '5810784.xml'
group by
     X.SECTION_TITLE
    ,X.MRN
    ,X.FILENAME
    ,SUB_ADMIN_ID_ROOT
    ,ENTRY_ID_EXT    
    ,X.ROW_NUM
    ,X.TS_LAST_MODIFY
    ,X.SCAN_TIME    
    ,SECTION.VALUE
    ,ENTRY.VALUE
    ,SUBSTANCE_ADMINISTRATION.VALUE
    ,CONSUMABLE.VALUE
    ,AUTHOR.VALUE;
