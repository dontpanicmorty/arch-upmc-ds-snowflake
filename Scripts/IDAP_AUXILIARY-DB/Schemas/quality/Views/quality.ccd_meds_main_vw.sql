    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'OBS' THEN GET(XMLGET(ER_CHILD.VALUE, 'id'),'@root')::VARCHAR ELSE NULL END) AS OBS_ID_ROOT
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'OBS' THEN GET(XMLGET(ER_CHILD.VALUE, 'id'),'@extension')::VARCHAR ELSE NULL END) AS OBS_ID_EXT
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'OBS' THEN GET(XMLGET(ER_CHILD.VALUE, 'code'),'@code')::VARCHAR ELSE NULL END) AS OBS_CODE
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'OBS' THEN GET(XMLGET(ER_CHILD.VALUE, 'code'),'@displayName')::VARCHAR ELSE NULL END) AS OBS_CODE_DISPLAY_NAME
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'OBS' THEN GET(XMLGET(ER_CHILD.VALUE, 'code'),'@codeSystem')::VARCHAR ELSE NULL END) AS OBS_CODE_SYSTEM
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'OBS' THEN GET(XMLGET(ER_CHILD.VALUE, 'code'),'@codeSystemName')::VARCHAR ELSE NULL END) AS OBS_CODE_SYSTEM_NAME
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'OBS' THEN GET(XMLGET(ER_CHILD.VALUE, 'statusCode'),'@code')::VARCHAR ELSE NULL END) AS OBS_STATUS_CODE
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'OBS' THEN GET(XMLGET(ER_CHILD.VALUE, 'effectiveTime'),'@nullFlavor')::VARCHAR ELSE NULL END) AS OBS_EFF_TIME_NULL
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'OBS' THEN GET(XMLGET(ER_CHILD.VALUE, 'value'),'@xsi:type')::VARCHAR ELSE NULL END) AS OBS_VALUE_TYPE
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'OBS' THEN GET(XMLGET(ER_CHILD.VALUE, 'value'),'@nullFlavor')::VARCHAR ELSE NULL END) AS OBS_VALUE_NULL
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'OBS' THEN GET(XMLGET(ER_CHILD.VALUE, 'value'),'@codeSystem')::VARCHAR ELSE NULL END) AS OBS_VALUE_CODE_SYSTEM
    --
    -- TRANSLATIONS - ICD10 TO BE INCLUDED
    --
    -- SUBJ SUBJ SUBJ
    ,MAX(CASE WHEN ENTRY_RELATIONSHIP.VALUE:"@typeCode"::VARCHAR = 'SUBJ' THEN ENTRY_RELATIONSHIP.VALUE:"@typeCode"::VARCHAR ELSE NULL END) AS ER_TYPE_SUBJ
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'ACT' THEN ER_CHILD.VALUE:"@classCode"::VARCHAR ELSE NULL END) AS ACT_CLASS_CODE
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'ACT' THEN ER_CHILD.VALUE:"@moodCode"::VARCHAR ELSE NULL END) AS ACT_MOOD_CODE
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'ACT' THEN (GET(XMLGET(ER_CHILD.VALUE,'templateId'),'@root')::STRING) ELSE NULL END) AS ACT_TEMPLATE_ROOT
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'ACT' THEN (GET(XMLGET(ER_CHILD.VALUE,'templateId'),'@extension')::STRING) ELSE NULL END) AS  ACT_TEMPLATE_EXTENSION
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'ACT' THEN (GET(XMLGET(ER_CHILD.VALUE,'code'),'@code')::STRING) ELSE NULL END) AS ACT_CODE
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'ACT' THEN (GET(XMLGET(ER_CHILD.VALUE,'code'),'@displayName')::STRING) ELSE NULL END) AS ACT_DISPLAY_NAME
    ,MAX(CASE WHEN ER_CHILD.VALUE:"@classCode"::VARCHAR = 'ACT' THEN (GET(XMLGET(ER_CHILD.VALUE,'code'),'@codeSystem')::STRING) ELSE NULL END) AS  ACT_CODE_SYSTEM
