    ,get(XMLGET( SUBSTANCE_ADMINISTRATION.VALUE,'effectiveTime',1),'@xsi:type')::VARCHAR AS EFFECTIVE_TIME2_TYPE            
    ,get(XMLGET( SUBSTANCE_ADMINISTRATION.VALUE,'effectiveTime',1),'@operator')::VARCHAR AS EFFECTIVE_TIME2_OP 
    ,get(XMLGET(XMLGET( SUBSTANCE_ADMINISTRATION.VALUE,'effectiveTime',1),'low'),'@nullFlavor')::VARCHAR AS EFFECTIVE_TIME2_LOW_NULL
