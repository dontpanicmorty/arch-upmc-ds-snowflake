     WHEN XMLGET(XMLGET(XMLGET(XMLGET( AUTHOR.VALUE, 'assignedAuthor'),'assignedPerson'), 'name'),'family'):"$"::STRING IS NULL
     THEN XMLGET(XMLGET(XMLGET( AUTHOR.VALUE, 'assignedAuthor'),'assignedPerson'),'name'):"$"::STRING 
     ELSE 
          CONCAT(
            nvl(XMLGET(XMLGET(XMLGET(XMLGET( AUTHOR.VALUE, 'assignedAuthor'),'assignedPerson'), 'name'),'family'):"$"::STRING,''), ', ',
	        nvl(XMLGET(XMLGET(XMLGET(XMLGET( AUTHOR.VALUE, 'assignedAuthor'),'assignedPerson'),'name'),'given', 0):"$"::STRING,''), ' ',
            nvl(XMLGET(XMLGET(XMLGET(XMLGET( AUTHOR.VALUE, 'assignedAuthor'),'assignedPerson'),'name'),'given', 1):"$"::STRING,''), ' ',
