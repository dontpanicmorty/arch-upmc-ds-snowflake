SELECT 
     X.SECTION_TITLE
    ,X.FILENAME
    ,X.MRN       
    ,get(XMLGET( SECTION.VALUE,'templateId'),'@root')::VARCHAR AS TEMPLATE_ID
    ,get(XMLGET( SECTION.VALUE,'templateId'),'@extension')::VARCHAR AS TEMPLATE_EXT
    ,get(XMLGET( SECTION.VALUE,'code'),'@code')::VARCHAR AS  MED_CODE
