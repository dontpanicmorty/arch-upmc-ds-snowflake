CREATE OR REPLACE VIEW QUALITY.CCD_MEDS_SUPPLY_VW(
	FILENAME,
	MRN,
	ENTRY_ID_EXT,
	MP_CLASS_CODE,
	MM_CODE,
	GPI_SYSTEM_NAME,
	GPI_CODE,
	GPI_DISPLAY_NAME,
	GPI_CODE_SYSTEM,
	NDC_CODE_SYSTEM_NAME,
	NDC_CODE,
	NDC_DISPLAY_NAME,
	NDC_CODE_SYSTEM
) as
SELECT
     x.FILENAME
    ,x.MRN
    ,get(XMLGET(XMLGET(ENTRY.VALUE,'substanceAdministration'),'id'),'@extension')::VARCHAR AS ENTRY_ID_EXT
    ,get(MANUFACTURED_PRODUCT.VALUE,'@classCode')::VARCHAR AS MP_CLASS_CODE
    ,get(XMLGET(MANUFACTURED_MATERIAL.VALUE,'code'),'@code')::VARCHAR AS MM_CODE

    ,MAX(CASE WHEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR = 'Medispan GPI' THEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR ELSE NULL END) AS GPI_SYSTEM_NAME 
    ,MAX(CASE WHEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR = 'Medispan GPI' THEN TRANSLATION.VALUE:"@code"::VARCHAR ELSE NULL END) AS GPI_CODE
    ,MAX(CASE WHEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR = 'Medispan GPI' THEN TRANSLATION.VALUE:"@displayName"::VARCHAR ELSE NULL END) AS GPI_DISPLAY_NAME
    ,MAX(CASE WHEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR = 'Medispan GPI' THEN TRANSLATION.VALUE:"@codeSystem"::VARCHAR ELSE NULL END) AS GPI_CODE_SYSTEM
        
    ,MAX(CASE WHEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR = 'National Drug Codes' THEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR ELSE NULL END) AS NDC_CODE_SYSTEM_NAME
    ,MAX(CASE WHEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR = 'National Drug Codes' THEN TRANSLATION.VALUE:"@code"::VARCHAR ELSE NULL END) AS NDC_CODE
    ,MAX(CASE WHEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR = 'National Drug Codes' THEN TRANSLATION.VALUE:"@displayName"::VARCHAR ELSE NULL END) AS NDC_DISPLAY_NAME
    ,MAX(CASE WHEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR = 'National Drug Codes' THEN TRANSLATION.VALUE:"@codeSystem"::VARCHAR ELSE NULL END) AS NDC_CODE_SYSTEM    

FROM
    QUALITY.SECTION_XML X
    ,LATERAL FLATTEN(X.xml) SECTION
    ,LATERAL FLATTEN(SECTION.VALUE:"$"::ARRAY) ENTRY
    ,LATERAL FLATTEN(ENTRY.VALUE:"$"::ARRAY) SUBSTANCE_ADMINISTRATION
    ,LATERAL FLATTEN(SUBSTANCE_ADMINISTRATION.VALUE:"$"::ARRAY) ENTRY_RELATIONSHIP
    ,LATERAL FLATTEN(ENTRY_RELATIONSHIP.VALUE:"$"::ARRAY) SUPPLY
    ,LATERAL FLATTEN(SUPPLY.VALUE:"$"::ARRAY) PRODUCT
    ,LATERAL FLATTEN(PRODUCT.VALUE:"$"::ARRAY) MANUFACTURED_PRODUCT
    ,LATERAL FLATTEN(MANUFACTURED_PRODUCT.VALUE:"$"::ARRAY) MANUFACTURED_MATERIAL
    ,LATERAL FLATTEN(MANUFACTURED_MATERIAL.VALUE:"$"::ARRAY) CODE
    ,LATERAL FLATTEN(CODE.VALUE:"$"::ARRAY) TRANSLATION
WHERE
    x.SECTION_TITLE = 'Medications'
    -- AND X.FILENAME = '5810784.xml'
    AND GET(SECTION.VALUE, '@') = 'section'
    AND GET(ENTRY.VALUE, '@') = 'entry'
    AND GET(SUBSTANCE_ADMINISTRATION.VALUE, '@') = 'substanceAdministration'
    AND GET(ENTRY_RELATIONSHIP.VALUE, '@') = 'entryRelationship'    
    AND GET(SUPPLY.VALUE, '@') = 'supply'        
    AND GET(PRODUCT.VALUE, '@') = 'product'
    AND GET(MANUFACTURED_PRODUCT.VALUE, '@') = 'manufacturedProduct'
    AND GET(MANUFACTURED_MATERIAL.VALUE, '@') = 'manufacturedMaterial'
    AND GET(CODE.VALUE, '@') = 'code'
    AND GET(TRANSLATION.VALUE, '@') = 'translation'
group by
    x.FILENAME
    ,x.MRN
   ,ENTRY.VALUE
   ,MANUFACTURED_PRODUCT.VALUE
   ,MANUFACTURED_MATERIAL.VALUE;

