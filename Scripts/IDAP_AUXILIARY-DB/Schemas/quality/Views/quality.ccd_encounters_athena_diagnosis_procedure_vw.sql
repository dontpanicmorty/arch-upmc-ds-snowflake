CREATE OR REPLACE VIEW QUALITY.CCD_ENCOUNTERS_ATHENA_DIAGNOSIS_PROCEDURE_VW(
	FILENAME,
	SECTION_TITLE,
	DIAGNOSIS_PROCEDURE_HKEY,
	MRN,
	ENCOUNTER_ID_EXTENSION,
	DIAGNOSIS_PROCEDURE_ID_EXTENSION,
	DIAGNOSIS_PROCEDURE_LEVEL,
	DIAGNOSIS_PROCEDURE_TYPE_CODE,
	DIAGNOSIS_PROCEDURE_CLASS_CODE,
	DIAGNOSIS_PROCEDURE_MOOD_CODE,
	TEMPLATE_ID_EXTENSION,
	TEMPLATE_ID_ROOT,
	TEMPLATE_ID_ROOT2,
	DIAGNOSIS_PROCEDURE_ID_ASSIGN_AUTHORITY_NAME,
	DIAGNOSIS_PROCEDURE_ID_ROOT,
	DIAGNOSIS_PROCEDURE_CODE,
	DIAGNOSIS_PROCEDURE_CODE_SYSTEM,
	DIAGNOSIS_PROCEDURE_CODE_SYSTEM_NAME,
	DIAGNOSIS_PROCEDURE_CODE_DISPLAY_NAME,
	DIAGNOSIS_PROCEDURE_TRANSLATE_CODE,
	DIAGNOSIS_PROCEDURE_TRANSLATE_CODE_SYSTEM,
	DIAGNOSIS_PROCEDURE_TRANSLATE_CODE_SYSTEM_NAME,
	DIAGNOSIS_PROCEDURE_TRANSLATE_DISPLAY_NAME,
	STATUS_CODE,
	EFFECTIVE_TIME_TYPE,
	EFFECTIVE_DATE_LOW,
	EFFECTIVE_DATE_HIGH,
	DIAGNOSIS_PROCEDURE_VALUE_CODE,
	DIAGNOSIS_PROCEDURE_VALUE_CODE_SYSTEM,
	DIAGNOSIS_PROCEDURE_VALUE_CODE_SYSTEM_NAME,
	DIAGNOSIS_PROCEDURE_VALUE_TYPE,
	VALUE_TEXT_ORIGINAL,
	TRANSLATE_ICD_10,
	TRANSLATE_ICD_10_CODE_SYSTEM,
	TRANSLATE_ICD_9,
	TRANSLATE_ICD_9_CODE_SYSTEM,
	TRANSLATE_MEL,
	TRANSLATE_MEL_CODE_SYSTEM,
	XML_ROW_NUM,
	TS_LAST_MODIFY,
	SCAN_TIME
) as 
SELECT
          FILENAME
         ,SECTION_TITLE
         ,IDAP_AUXILIARY_DEV.UTIL.FXN_ARRAY_HASH( [FILENAME, MRN, SECTION_TITLE, ENCOUNTER_ID_EXTENSION, DIAGNOSIS_PROCEDURE_ID_EXTENSION]) AS DIAGNOSIS_PROCEDURE_HKEY         
         ,MRN
         ,ENCOUNTER_ID_EXTENSION
         ,DIAGNOSIS_PROCEDURE_ID_EXTENSION
         ,DIAGNOSIS_PROCEDURE_LEVEL
         ,DIAGNOSIS_PROCEDURE_TYPE_CODE
         ,DIAGNOSIS_PROCEDURE_CLASS_CODE
         ,DIAGNOSIS_PROCEDURE_MOOD_CODE         
         ,TEMPLATE_ID_EXTENSION
         ,TEMPLATE_ID_ROOT
         ,TEMPLATE_ID_ROOT2
         ,DIAGNOSIS_PROCEDURE_ID_ASSIGN_AUTHORITY_NAME
         ,DIAGNOSIS_PROCEDURE_ID_ROOT         
         ,DIAGNOSIS_PROCEDURE_CODE
         ,DIAGNOSIS_PROCEDURE_CODE_SYSTEM
         ,DIAGNOSIS_PROCEDURE_CODE_SYSTEM_NAME         
         ,DIAGNOSIS_PROCEDURE_CODE_DISPLAY_NAME
         ,DIAGNOSIS_PROCEDURE_TRANSLATE_CODE
         ,DIAGNOSIS_PROCEDURE_TRANSLATE_CODE_SYSTEM
         ,DIAGNOSIS_PROCEDURE_TRANSLATE_CODE_SYSTEM_NAME
         ,DIAGNOSIS_PROCEDURE_TRANSLATE_DISPLAY_NAME
         ,STATUS_CODE
         ,EFFECTIVE_TIME_TYPE
         ,EFFECTIVE_DATE_LOW
         ,EFFECTIVE_DATE_HIGH
         ,DIAGNOSIS_PROCEDURE_VALUE_CODE
         ,DIAGNOSIS_PROCEDURE_VALUE_CODE_SYSTEM
         ,DIAGNOSIS_PROCEDURE_VALUE_CODE_SYSTEM_NAME  
         ,DIAGNOSIS_PROCEDURE_VALUE_TYPE
         ,VALUE_TEXT_ORIGINAL
         ,TRANSLATE_ICD_10
         ,TRANSLATE_ICD_10_CODE_SYSTEM
         ,TRANSLATE_ICD_9         
         ,TRANSLATE_ICD_9_CODE_SYSTEM         
         ,TRANSLATE_MEL        
         ,TRANSLATE_MEL_CODE_SYSTEM
         ,XML_ROW_NUM
         ,TS_LAST_MODIFY
	     ,SCAN_TIME
FROM (
      SELECT
           X.FILENAME
          ,X.SECTION_TITLE
          ,X.MRN AS MRN
          ,GET(XMLGET(encounter.VALUE,'id'),'@extension')::STRING AS ENCOUNTER_ID_EXTENSION
          ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP.VALUE,'act'),'id'),'@extension')::STRING AS DIAGNOSIS_PROCEDURE_ID_EXTENSION
          ,1 as DIAGNOSIS_PROCEDURE_LEVEL
         ,GET(ENTRY_RELATIONSHIP.VALUE,'@typeCode')::STRING AS DIAGNOSIS_PROCEDURE_TYPE_CODE
         ,GET(XMLGET(ENTRY_RELATIONSHIP.VALUE,'act'),'@classCode')::STRING AS DIAGNOSIS_PROCEDURE_CLASS_CODE
         ,GET(XMLGET(ENTRY_RELATIONSHIP.VALUE,'act'),'@moodCode')::STRING AS DIAGNOSIS_PROCEDURE_MOOD_CODE         
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP.VALUE,'act'),'templateId'),'@extension')::STRING AS TEMPLATE_ID_EXTENSION
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP.VALUE,'act'),'templateId'),'@root')::STRING AS TEMPLATE_ID_ROOT
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP.VALUE,'act'),'templateId',1),'@root')::STRING AS TEMPLATE_ID_ROOT2
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP.VALUE,'act'),'id'),'@assigningAuthorityName')::STRING AS DIAGNOSIS_PROCEDURE_ID_ASSIGN_AUTHORITY_NAME
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP.VALUE,'act'),'id'),'@root')::STRING AS DIAGNOSIS_PROCEDURE_ID_ROOT         
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP.VALUE,'act'),'code'),'@code')::STRING AS DIAGNOSIS_PROCEDURE_CODE
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP.VALUE,'act'),'code'),'@codeSystem')::STRING AS DIAGNOSIS_PROCEDURE_CODE_SYSTEM
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP.VALUE,'act'),'code'),'@codeSystemName')::STRING AS DIAGNOSIS_PROCEDURE_CODE_SYSTEM_NAME         
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP.VALUE,'act'),'code'),'@displayName')::STRING AS DIAGNOSIS_PROCEDURE_CODE_DISPLAY_NAME
         ,NULL AS DIAGNOSIS_PROCEDURE_TRANSLATE_CODE
         ,NULL AS DIAGNOSIS_PROCEDURE_TRANSLATE_CODE_SYSTEM
         ,NULL AS DIAGNOSIS_PROCEDURE_TRANSLATE_CODE_SYSTEM_NAME
         ,NULL AS DIAGNOSIS_PROCEDURE_TRANSLATE_DISPLAY_NAME
         ,NULL AS STATUS_CODE
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP.VALUE,'act'),'effectiveTime'),'@xsi:type')::STRING AS EFFECTIVE_TIME_TYPE
         --,GET(XMLGET(XMLGET(XMLGET(ENTRY_RELATIONSHIP.VALUE,'act'),'effectiveTime'),'low'),'@value')::STRING AS EFFECTIVE_TIME_VALUE
         ,GET(XMLGET(XMLGET(XMLGET(ENTRY_RELATIONSHIP.VALUE,'observation'),'effectiveTime'),'low'),'@value')::STRING AS EFFECTIVE_DATE_LOW
         ,GET(XMLGET(XMLGET(XMLGET(ENTRY_RELATIONSHIP.VALUE,'observation'),'effectiveTime'),'high'),'@value')::STRING AS EFFECTIVE_DATE_HIGH
          --
         ,NULL AS DIAGNOSIS_PROCEDURE_VALUE_CODE
         ,NULL AS DIAGNOSIS_PROCEDURE_VALUE_CODE_SYSTEM
         ,NULL AS DIAGNOSIS_PROCEDURE_VALUE_CODE_SYSTEM_NAME  
         ,NULL AS DIAGNOSIS_PROCEDURE_VALUE_TYPE
         ,NULL AS VALUE_TEXT_ORIGINAL
         ,NULL AS TRANSLATE_ICD_10
         ,NULL AS TRANSLATE_ICD_10_CODE_SYSTEM
         ,NULL AS TRANSLATE_ICD_9         
         ,NULL AS TRANSLATE_ICD_9_CODE_SYSTEM         
         ,NULL AS TRANSLATE_MEL        
         ,NULL AS TRANSLATE_MEL_CODE_SYSTEM
         ,ROW_NUM AS XML_ROW_NUM
         ,TS_LAST_MODIFY
	     ,SCAN_TIME
     FROM QUALITY.SECTION_XML X
             ,LATERAL FLATTEN(X.xml) SECTION     
             ,LATERAL FLATTEN(SECTION.VALUE:"$"::ARRAY) ENTRY
             ,LATERAL FLATTEN(entry.VALUE:"$"::ARRAY) ENCOUNTER
             ,LATERAL FLATTEN(encounter.VALUE:"$"::ARRAY) ENTRY_RELATIONSHIP
     WHERE X.SECTION_TITLE = 'ENCOUNTERS'
           AND GET(SECTION.VALUE, '@') = 'section'
           AND GET(ENTRY.VALUE, '@') = 'entry'
           AND GET(encounter.VALUE, '@') = 'encounter'
           AND GET(entry_relationship.value, '@') = 'entryRelationship'
           -- AND FILENAME = '14607350.xml' --'14599554r2.xml'
UNION ALL
     SELECT
          X.FILENAME
         ,X.SECTION_TITLE
         ,X.MRN AS MRN
         ,GET(XMLGET(encounter.VALUE,'id'),'@extension')::STRING AS ENCOUNTER_ID_EXTENSION
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'id'),'@extension')::STRING AS DIAGNOSIS_PROCEDURE_ID_EXTENSION
         ,2 as DIAGNOSIS_PROCEDURE_LEVEL
         ,GET(ENTRY_RELATIONSHIP_2.VALUE,'@typeCode')::STRING AS DIAGNOSIS_PROCEDURE_TYPE_CODE
         ,GET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'@classCode')::STRING AS DIAGNOSIS_PROCEDURE_CLASS_CODE
         ,GET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'@moodCode')::STRING AS DIAGNOSIS_PROCEDURE_MOOD_CODE
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'templateId'),'@extension')::STRING AS TEMPLATE_ID_EXTENSION
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'templateId'),'@root')::STRING AS TEMPLATE_ID_ROOT
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'templateId',1),'@root')::STRING AS TEMPLATE_ID_ROOT2        
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'id'),'@assigningAuthorityName')::STRING AS DIAGNOSIS_PROCEDURE_ID_ASSIGN_AUTHORITY_NAME
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'id'),'@root')::STRING AS DIAGNOSIS_PROCEDURE_ID_ROOT         
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'code'),'@code')::STRING AS DIAGNOSIS_PROCEDURE_CODE
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'code'),'@codeSystem')::STRING AS DIAGNOSIS_PROCEDURE_CODE_SYSTEM
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'code'),'@codeSystemName')::STRING AS DIAGNOSIS_PROCEDURE_CODE_SYSTEM_NAME
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'code'),'@displayName')::STRING AS DIAGNOSIS_PROCEDURE_CODE_DISPLAY_NAME
         ,GET(XMLGET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'code'),'translation'),'@code')::STRING AS DIAGNOSIS_PROCEDURE_TRANSLATE_CODE
         ,GET(XMLGET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'code'),'translation'),'@codeSystem')::STRING AS DIAGNOSIS_PROCEDURE_TRANSLATE_CODE_SYSTEM
         ,GET(XMLGET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'code'),'translation'),'@codeSystemName')::STRING AS DIAGNOSIS_PROCEDURE_TRANSLATE_CODE_SYSTEM_NAME
         ,GET(XMLGET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'code'),'translation'),'@displayName')::STRING AS DIAGNOSIS_PROCEDURE_TRANSLATE_DISPLAY_NAME
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'statusCode'),'@code')::STRING AS STATUS_CODE
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'effectiveTime'),'@xsi:type')::STRING AS EFFECTIVE_TIME_TYPE
--         ,GET(XMLGET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'effectiveTime'),'low'),'@value')::STRING AS EFFECTIVE_TIME_VALUE
         ,GET(XMLGET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'effectiveTime'),'low'),'@value')::STRING AS EFFECTIVE_DATE_LOW
         ,GET(XMLGET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'effectiveTime'),'high'),'@value')::STRING AS EFFECTIVE_DATE_HIGH
          --
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'value'),'@code')::STRING AS DIAGNOSIS_PROCEDURE_VALUE_CODE
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'value'),'@codeSystem')::STRING AS DIAGNOSIS_PROCEDURE_VALUE_CODE_SYSTEM
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'value'),'@codeSystemName')::STRING AS DIAGNOSIS_PROCEDURE_VALUE_CODE_SYSTEM_NAME  
         ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'value'),'@xsi:type')::STRING AS DIAGNOSIS_PROCEDURE_VALUE_TYPE
         ,XMLGET(XMLGET(XMLGET(ENTRY_RELATIONSHIP_2.VALUE,'observation'),'value'),'originalText'):"$"::STRING AS VALUE_TEXT_ORIGINAL
         ,MAX(CASE WHEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR = 'ICD-10-US' THEN TRANSLATION.VALUE:"@code"::VARCHAR ELSE NULL END) AS TRANSLATE_ICD_10
         ,MAX(CASE WHEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR = 'ICD-10-US' THEN TRANSLATION.VALUE:"@codeSystem"::VARCHAR ELSE NULL END) AS TRANSLATE_ICD_10_CODE_SYSTEM
         --,MAX(CASE WHEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR = 'ICD-9 (USA)' THEN TRANSLATION.VALUE:"@code"::VARCHAR ELSE NULL END) AS TRANSLATE_ICD_9
         ,MAX(CASE WHEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR = 'ICD-9 (USA)' THEN quality.fxn_extract_value( translation.value, 'code=')::VARCHAR ELSE NULL END) AS TRANSLATE_ICD_9         
         ,MAX(CASE WHEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR = 'ICD-9 (USA)' THEN TRANSLATION.VALUE:"@codeSystem"::VARCHAR ELSE NULL END) AS TRANSLATE_ICD_9_CODE_SYSTEM         
         ,MAX(CASE WHEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR = 'MEL' THEN TRANSLATION.VALUE:"@code"::VARCHAR ELSE NULL END) AS TRANSLATE_MEL
         ,MAX(CASE WHEN TRANSLATION.VALUE:"@codeSystemName"::VARCHAR = 'MEL' THEN TRANSLATION.VALUE:"@codeSystem"::VARCHAR ELSE NULL END) AS TRANSLATE_MEL_CODE_SYSTEM
         ,ROW_NUM AS XML_ROW_NUM
         ,TS_LAST_MODIFY
	     ,SCAN_TIME
     FROM QUALITY.SECTION_XML X
             ,LATERAL FLATTEN(X.xml) SECTION     
             ,LATERAL FLATTEN(SECTION.VALUE:"$"::ARRAY) ENTRY
             ,LATERAL FLATTEN(entry.VALUE:"$"::ARRAY) ENCOUNTER
             ,LATERAL FLATTEN(encounter.VALUE:"$"::ARRAY) ENTRY_RELATIONSHIP
             ,LATERAL FLATTEN(entry_relationship.VALUE:"$"::ARRAY) ACT       
             ,LATERAL FLATTEN(act.VALUE:"$"::ARRAY) ENTRY_RELATIONSHIP_2             
             ,LATERAL FLATTEN(entry_relationship_2.VALUE:"$"::ARRAY) OBSERVATION             
             ,LATERAL FLATTEN(observation.VALUE:"$"::ARRAY) VALUE
             ,LATERAL FLATTEN(value.VALUE:"$"::ARRAY) TRANSLATION             
     WHERE X.SECTION_TITLE = 'ENCOUNTERS'
           AND GET(SECTION.VALUE, '@') = 'section'
           AND GET(ENTRY.VALUE, '@') = 'entry'
           AND GET(encounter.VALUE, '@') = 'encounter'
           AND GET(entry_relationship.value, '@') = 'entryRelationship'
           AND GET(act.value, '@') = 'act'           
           AND GET(entry_relationship_2.value, '@') = 'entryRelationship'           
           AND GET(observation.value, '@') = 'observation'
           AND GET(value.value, '@') = 'value'           
           AND GET(translation.value, '@') = 'translation'          
     GROUP BY           
          X.FILENAME
         ,X.SECTION_TITLE
         ,X.MRN
         ,ENCOUNTER.VALUE
         ,ENTRY_RELATIONSHIP_2.VALUE
         ,XML_ROW_NUM
         ,TS_LAST_MODIFY
         ,SCAN_TIME
);