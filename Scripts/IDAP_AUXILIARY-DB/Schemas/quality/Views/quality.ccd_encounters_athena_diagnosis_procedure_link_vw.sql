CREATE OR REPLACE VIEW QUALITY.CCD_ENCOUNTERS_ATHENA_DIAGNOSIS_PROCEDURE_LINK_VW(
	FILENAME,
	SECTION_TITLE,
	ENCOUNTER_HKEY,
	DIAGNOSIS_PROCEDURE_HKEY,
	MRN,
	ENCOUNTER_ID_EXTENSION,
	DIAGNOSIS_PROCEDURE_ID_EXTENSION,
	XML_ROW_NUM,
	TS_LAST_MODIFY,
	SCAN_TIME
) AS SELECT
          FILENAME
         ,SECTION_TITLE
         ,IDAP_AUXILIARY_DEV.UTIL.FXN_ARRAY_HASH( [FILENAME, MRN, SECTION_TITLE, ENCOUNTER_ID_EXTENSION]) AS ENCOUNTER_HKEY         
         ,IDAP_AUXILIARY_DEV.UTIL.FXN_ARRAY_HASH( [FILENAME, MRN, SECTION_TITLE, ENCOUNTER_ID_EXTENSION, DIAGNOSIS_PROCEDURE_ID_EXTENSION ]) AS DIAGNOSIS_PROCEDURE_HKEY         
         ,MRN
         ,ENCOUNTER_ID_EXTENSION
         ,DIAGNOSIS_PROCEDURE_ID_EXTENSION
         ,XML_ROW_NUM
         ,TS_LAST_MODIFY
         ,SCAN_TIME
FROM (
      SELECT
           X.FILENAME
          ,X.SECTION_TITLE
          ,X.MRN AS MRN
          ,GET(XMLGET(encounter.VALUE,'id'),'@extension')::STRING AS ENCOUNTER_ID_EXTENSION
          ,GET(XMLGET(XMLGET(ENTRY_RELATIONSHIP.VALUE,'act'),'id'),'@extension')::STRING AS DIAGNOSIS_PROCEDURE_ID_EXTENSION
          ,ROW_NUM AS XML_ROW_NUM
          ,TS_LAST_MODIFY
          ,SCAN_TIME
      FROM QUALITY.SECTION_XML X
             ,LATERAL FLATTEN(X.xml) SECTION     
             ,LATERAL FLATTEN(SECTION.VALUE:"$"::ARRAY) ENTRY
             ,LATERAL FLATTEN(entry.VALUE:"$"::ARRAY) ENCOUNTER
             ,LATERAL FLATTEN(encounter.VALUE:"$"::ARRAY) ENTRY_RELATIONSHIP
     WHERE X.SECTION_TITLE = 'ENCOUNTERS'
           AND GET(SECTION.VALUE, '@') = 'section'
           AND GET(ENTRY.VALUE, '@') = 'entry'
           AND GET(encounter.VALUE, '@') = 'encounter'
           AND GET(entry_relationship.value, '@') = 'entryRelationship'
);