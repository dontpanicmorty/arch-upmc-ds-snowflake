
CREATE OR REPLACE TABLE QUALITY.SECTION_XML (
	MRN VARCHAR(100) NOT NULL,
	SECTION_TITLE VARCHAR(100) NOT NULL,
	XML VARIANT,
	CS_TRANSACTION_ID NUMBER(38,0),
	FILENAME VARCHAR(100) NOT NULL,
	ROW_NUM NUMBER(38,0),
	TS_LAST_MODIFY TIMESTAMP_NTZ(9),
	SCAN_TIME TIMESTAMP_NTZ(9),
	constraint SECTION_XML_PK primary key (MRN, SECTION_TITLE, FILENAME)
)COMMENT='Table to contain single sections of ClearSense XML data'
;
