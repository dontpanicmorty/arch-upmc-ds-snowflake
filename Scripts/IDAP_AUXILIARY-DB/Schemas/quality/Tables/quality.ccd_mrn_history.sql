
CREATE OR REPLACE TABLE QUALITY.CCD_MRN_HISTORY (
	MRN VARCHAR(50) NOT NULL,
	CS_TRANSACTION_ID NUMBER(38,0),
	XML_FILENAME VARCHAR(500) NOT NULL,
	ZIP_FILENAME VARCHAR(500),
	SUBSCRIBER_ID_UPMC VARCHAR(30),
	IS_ACTIVE VARCHAR(1),
	DATE_ADDED VARCHAR(30) NOT NULL,
	DATE_REMOVED VARCHAR(30),
	DATE_PROCESSED VARCHAR(30),
	constraint CCD_MRN_HISTORY_PK primary key (MRN, XML_FILENAME, DATE_ADDED)
)COMMENT='History of MRN values and  respective dates Added/Deleted from CCD ClearSense Tables'
;
