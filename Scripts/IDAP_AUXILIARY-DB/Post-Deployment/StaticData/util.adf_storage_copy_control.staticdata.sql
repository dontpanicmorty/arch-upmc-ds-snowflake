	ADF_STORAGE_COPY_CONTROL_KEY VARCHAR NULL,
    INSERT_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    UPDATE_DATETIME TIMESTAMP_TZ(9) NOT NULL,
    IS_ACTIVE BOOLEAN NOT NULL,
    SOURCE_FILE_PATH VARCHAR NOT NULL,
    SOURCE_FILENAME_PATTERN VARCHAR NOT NULL,
    IS_TARGET_ADLS_FLAG BOOLEAN NOT NULL,
    IS_TARGET_UNZIPPED_FLAG BOOLEAN NOT NULL,
    IS_TARGET_PATH_DATED_FLAG BOOLEAN NOT NULL,
    IS_RETAIN_TARGET_ZIP_NAME BOOLEAN NOT NULL,
    TARGET_ACCOUNT_NAME VARCHAR NOT NULL,
    TARGET_CONTAINER_NAME VARCHAR NOT NULL,
    TARGET_FILE_PATH VARCHAR NOT NULL,
    CONSTRAINT UK_ADF_STORAGE_COPY_CONTROL UNIQUE (SOURCE_FILE_PATH, SOURCE_FILENAME_PATTERN, TARGET_ACCOUNT_NAME, TARGET_FILE_PATH) 
);

-- 2: Populate the table variable with data
