!set variable_substitution=true;
INSERT INTO UTIL.TMP_ADF_STORAGE_COPY_CONTROL (IS_ACTIVE, INSERT_DATETIME, UPDATE_DATETIME, SOURCE_FILE_PATH, SOURCE_FILENAME_PATTERN, IS_TARGET_ADLS_FLAG, IS_TARGET_UNZIPPED_FLAG, IS_TARGET_PATH_DATED_FLAG, IS_RETAIN_TARGET_ZIP_NAME, TARGET_ACCOUNT_NAME, TARGET_CONTAINER_NAME, TARGET_FILE_PATH)
    VALUES
