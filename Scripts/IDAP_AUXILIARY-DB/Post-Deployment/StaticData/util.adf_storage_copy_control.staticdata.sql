(TRUE, '2026-05-01 09:00:00.000 -0400', CURRENT_TIMESTAMP(), 'Application Services/Application Services(Custom)/&{smileXDriveEnv}/', 'CCD_*txt', FALSE, FALSE, TRUE, FALSE, '&{smilestorageaccount}', 'cda-documents', 'raw/clearsenseccd/')
;
!set variable_substitution=false;

-- 3: Update the File Copy Control Key for all records
UPDATE UTIL.TMP_ADF_STORAGE_COPY_CONTROL
SET ADF_STORAGE_COPY_CONTROL_KEY = UTIL.FXN_ARRAY_HASH([SOURCE_FILE_PATH, SOURCE_FILENAME_PATTERN, TARGET_ACCOUNT_NAME, TARGET_FILE_PATH])
;

-- 4: Check for Duplicates
--Check for bad data in the temp table before merging
EXECUTE IMMEDIATE $$
DECLARE
  dup_primary_key_exception EXCEPTION (-20001, 'DUPLICATE Primary Keys Detected.');
  dup_unique_key_exception EXCEPTION (-20002, 'DUPLICATE Unique Keys Detected.');
  dup_count INTEGER;
BEGIN
    SELECT COUNT(1) INTO :dup_count 
        FROM(SELECT ADF_STORAGE_COPY_CONTROL_KEY, COUNT(1) FROM UTIL.TMP_ADF_STORAGE_COPY_CONTROL GROUP BY ADF_STORAGE_COPY_CONTROL_KEY HAVING COUNT(1) > 1);
    IF (dup_count > 0) THEN
    RAISE dup_primary_key_exception;
	END IF;

    SELECT COUNT(1) INTO :dup_count 
        FROM(SELECT SOURCE_FILENAME_PATTERN,TARGET_FILE_PATH, COUNT(1) FROM UTIL.TMP_ADF_STORAGE_COPY_CONTROL GROUP BY SOURCE_FILENAME_PATTERN, TARGET_FILE_PATH HAVING COUNT(1) > 1);
    IF (dup_count > 0) THEN
    RAISE dup_unique_key_exception;
	END IF;
END;
$$;

-- 5: Check for invalid unzip / retain unzip combination
EXECUTE IMMEDIATE $$
DECLARE
  invalid_unzip_state EXCEPTION (-20003, 'Invalid unzip/retain flag combination detected.');
  bad_count INTEGER;
BEGIN
    SELECT COUNT(1) INTO :bad_count
    FROM UTIL.TMP_ADF_STORAGE_COPY_CONTROL
    WHERE IS_TARGET_UNZIPPED_FLAG = FALSE
      AND IS_RETAIN_TARGET_ZIP_NAME = TRUE;

    IF (bad_count > 0) THEN
        RAISE invalid_unzip_state;
    END IF;
END;
$$;


-- 6: merge new and updated records
MERGE INTO UTIL.ADF_STORAGE_COPY_CONTROL AS TGT
USING (SELECT ADF_STORAGE_COPY_CONTROL_KEY, IS_ACTIVE, INSERT_DATETIME, UPDATE_DATETIME, SOURCE_FILE_PATH, SOURCE_FILENAME_PATTERN, IS_TARGET_ADLS_FLAG, IS_TARGET_UNZIPPED_FLAG, IS_TARGET_PATH_DATED_FLAG, IS_RETAIN_TARGET_ZIP_NAME, TARGET_ACCOUNT_NAME, TARGET_CONTAINER_NAME, TARGET_FILE_PATH
    FROM UTIL.TMP_ADF_STORAGE_COPY_CONTROL
	MINUS 
	SELECT ADF_STORAGE_COPY_CONTROL_KEY, IS_ACTIVE, INSERT_DATETIME, UPDATE_DATETIME, SOURCE_FILE_PATH, SOURCE_FILENAME_PATTERN, IS_TARGET_ADLS_FLAG, IS_TARGET_UNZIPPED_FLAG, IS_TARGET_PATH_DATED_FLAG, IS_RETAIN_TARGET_ZIP_NAME, TARGET_ACCOUNT_NAME, TARGET_CONTAINER_NAME, TARGET_FILE_PATH
    FROM UTIL.ADF_STORAGE_COPY_CONTROL
	) AS SRC

ON (TGT.SOURCE_FILENAME_PATTERN = SRC.SOURCE_FILENAME_PATTERN
AND TGT.TARGET_FILE_PATH = SRC.TARGET_FILE_PATH)

WHEN MATCHED
THEN UPDATE
    SET TGT.ADF_STORAGE_COPY_CONTROL_KEY = SRC.ADF_STORAGE_COPY_CONTROL_KEY,
    TGT.INSERT_DATETIME = SRC.INSERT_DATETIME,
    TGT.UPDATE_DATETIME = CURRENT_TIMESTAMP(),
    TGT.IS_ACTIVE = SRC.IS_ACTIVE,
    TGT.SOURCE_FILE_PATH = SRC.SOURCE_FILE_PATH,
    TGT.SOURCE_FILENAME_PATTERN = SRC.SOURCE_FILENAME_PATTERN,
    TGT.IS_TARGET_ADLS_FLAG = SRC.IS_TARGET_ADLS_FLAG,
    TGT.IS_TARGET_UNZIPPED_FLAG = SRC.IS_TARGET_UNZIPPED_FLAG,
    TGT.IS_TARGET_PATH_DATED_FLAG = SRC.IS_TARGET_PATH_DATED_FLAG,
    TGT.IS_RETAIN_TARGET_ZIP_NAME = SRC.IS_RETAIN_TARGET_ZIP_NAME,
    TGT.TARGET_ACCOUNT_NAME = SRC.TARGET_ACCOUNT_NAME,
    TGT.TARGET_CONTAINER_NAME = SRC.TARGET_CONTAINER_NAME,
    TGT.TARGET_FILE_PATH = SRC.TARGET_FILE_PATH

WHEN NOT MATCHED
THEN INSERT
    (ADF_STORAGE_COPY_CONTROL_KEY, IS_ACTIVE, INSERT_DATETIME, UPDATE_DATETIME, SOURCE_FILE_PATH, SOURCE_FILENAME_PATTERN, IS_TARGET_ADLS_FLAG, IS_TARGET_UNZIPPED_FLAG, IS_TARGET_PATH_DATED_FLAG, IS_RETAIN_TARGET_ZIP_NAME, TARGET_ACCOUNT_NAME, TARGET_CONTAINER_NAME, TARGET_FILE_PATH)
VALUES
    (SRC.ADF_STORAGE_COPY_CONTROL_KEY, SRC.IS_ACTIVE, SRC.INSERT_DATETIME, SRC.UPDATE_DATETIME, SRC.SOURCE_FILE_PATH, SRC.SOURCE_FILENAME_PATTERN, SRC.IS_TARGET_ADLS_FLAG, SRC.IS_TARGET_UNZIPPED_FLAG, SRC.IS_TARGET_PATH_DATED_FLAG, SRC.IS_RETAIN_TARGET_ZIP_NAME, SRC.TARGET_ACCOUNT_NAME, SRC.TARGET_CONTAINER_NAME, SRC.TARGET_FILE_PATH)
;

-- 7: Delete obsolete records
DELETE FROM UTIL.ADF_STORAGE_COPY_CONTROL TGT
USING
(SELECT SOURCE_FILENAME_PATTERN, TARGET_FILE_PATH
	FROM UTIL.ADF_STORAGE_COPY_CONTROL
	MINUS 
	SELECT SOURCE_FILENAME_PATTERN, TARGET_FILE_PATH
	FROM UTIL.tmp_ADF_STORAGE_COPY_CONTROL
	) SRC
WHERE TGT.SOURCE_FILENAME_PATTERN = SRC.SOURCE_FILENAME_PATTERN
AND TGT.TARGET_FILE_PATH = SRC.TARGET_FILE_PATH
;

SELECT 'Finished updating static data table UTIL.ADF_STORAGE_COPY_CONTROL';