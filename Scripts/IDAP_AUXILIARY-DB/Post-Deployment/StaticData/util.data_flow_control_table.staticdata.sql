-- 3: Upsert new data with targeted delete

MERGE INTO UTIL.DATA_FLOW_CONTROL_TABLE AS TGT
USING (SELECT DATA_FLOW_NAME,DATA_DOMAIN_NAME,DS_FLOW_OWNER,STEP_ORDER_NUMBER,STEP_PROCEDURE_NAME,IS_ACTIVE
	FROM  UTIL.tmp_DATA_FLOW_CONTROL_TABLE
	MINUS 
	SELECT DATA_FLOW_NAME,DATA_DOMAIN_NAME,DS_FLOW_OWNER,STEP_ORDER_NUMBER,STEP_PROCEDURE_NAME,IS_ACTIVE
	FROM UTIL.DATA_FLOW_CONTROL_TABLE
	) AS SRC

ON TGT.DATA_FLOW_NAME = SRC.DATA_FLOW_NAME
	AND TGT.STEP_ORDER_NUMBER = SRC.STEP_ORDER_NUMBER

WHEN MATCHED 
THEN UPDATE SET 
	TGT.STEP_PROCEDURE_NAME = SRC.STEP_PROCEDURE_NAME
	,TGT.DATA_DOMAIN_NAME = SRC.DATA_DOMAIN_NAME
	,TGT.DS_FLOW_OWNER = SRC.DS_FLOW_OWNER
	,TGT.IS_ACTIVE = SRC.IS_ACTIVE
	,TGT.LAST_UPDATED_DATETIME = CONVERT_TIMEZONE('UTC',CURRENT_TIMESTAMP())
WHEN NOT MATCHED 
THEN INSERT
(
    DATA_FLOW_NAME
    ,DATA_DOMAIN_NAME
    ,DS_FLOW_OWNER
    ,STEP_ORDER_NUMBER
    ,STEP_PROCEDURE_NAME
    ,IS_ACTIVE
)
VALUES
(
    DATA_FLOW_NAME
    ,DATA_DOMAIN_NAME
    ,DS_FLOW_OWNER
    ,STEP_ORDER_NUMBER
    ,STEP_PROCEDURE_NAME
    ,IS_ACTIVE
)
;
	
--Remove any extra data flow steps

DELETE FROM UTIL.DATA_FLOW_CONTROL_TABLE TGT
USING (
	SELECT lkp.DATA_FLOW_NAME, lkp.STEP_ORDER_NUMBER
	FROM UTIL.DATA_FLOW_CONTROL_TABLE lkp
    WHERE
        EXISTS (
            SELECT DATA_FLOW_NAME 
            FROM UTIL.tmp_DATA_FLOW_CONTROL_TABLE tmp
            WHERE tmp.DATA_FLOW_NAME = lkp.DATA_FLOW_NAME
        )
        AND STEP_ORDER_NUMBER NOT IN (
            SELECT STEP_ORDER_NUMBER 
            FROM UTIL.tmp_DATA_FLOW_CONTROL_TABLE tmp
            WHERE tmp.DATA_FLOW_NAME = lkp.DATA_FLOW_NAME
        )
) AS SRC
WHERE
	TGT.DATA_FLOW_NAME = SRC.DATA_FLOW_NAME
	AND TGT.STEP_ORDER_NUMBER = SRC.STEP_ORDER_NUMBER
;

