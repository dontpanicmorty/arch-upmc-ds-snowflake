-- 4: Check for Duplicates
--Check for bad data in the temp table before merging
EXECUTE IMMEDIATE $$
DECLARE
  dup_primary_key_exception EXCEPTION (-20001, 'DUPLICATE Primary Keys Detected.');
  dup_unique_key_exception EXCEPTION (-20002, 'DUPLICATE Unique Keys Detected.');
  dup_count INTEGER;
BEGIN
    SELECT COUNT(1) INTO :dup_count 
        FROM(SELECT ADF_EPIC_COPY_CONTROL_KEY, COUNT(1) FROM UTIL.TMP_ADF_EPIC_EXPORT_COPY_CONTROL GROUP BY ADF_EPIC_COPY_CONTROL_KEY HAVING COUNT(1) > 1);
    IF (dup_count > 0) THEN
    RAISE dup_primary_key_exception;
	END IF;

    SELECT COUNT(1) INTO :dup_count 
        FROM(SELECT SOURCE_DATABASE_NAME, SOURCE_SCHEMA_NAME, SOURCE_VIEW_NAME, COUNT(1) FROM UTIL.TMP_ADF_EPIC_EXPORT_COPY_CONTROL GROUP BY SOURCE_DATABASE_NAME, SOURCE_SCHEMA_NAME, SOURCE_VIEW_NAME HAVING COUNT(1) > 1);
    IF (dup_count > 0) THEN
    RAISE dup_unique_key_exception;
	END IF;
END;
$$;
