module.exports = {
  IN_NETWORK_RATES_FILES: () => `SELECT PRICING_FILE_KEY, 
  EXTRACTDATA.FXN_MAKE_URL_PATH(FILE_TYPE_NAME, PRICING_FILE_KEY) AS URL
FROM EXTRACTDATA.PRICING_FILE
LEFT JOIN EXTRACTDATA.REPORTING_ENTITY ON
    PRICING_FILE.REPORTING_ENTITY_KEY = REPORTING_ENTITY.REPORTING_ENTITY_KEY
WHERE REPORTING_ENTITY_NAME = 'UPMC Health Plan'
    AND FILE_TYPE_NAME = 'in-network-rates';`,

  IN_NETWORK_BASE: (WHERE_CLAUSE) => `SELECT IN_NETWORK_JSON
FROM EXTRACTDATA.IN_NETWORK_BASE_JSON_VW ${WHERE_CLAUSE};`,

  IN_NETWORK_FILE_BASE_SELECT_VW: (WHERE_CLAUSE) => `SELECT * 
FROM EXTRACTDATA.IN_NETWORK_FILE_BASE_SELECT_VW ${WHERE_CLAUSE};`,

  GET_TIC_DATE: () =>
    `SELECT EXTRACTDATA.FXN_GET_CURRENT_TIC_DATE() AS TIC_DATE;`
};
